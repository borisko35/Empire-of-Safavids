-- ============================================================
-- 031_guest_accounts.sql — гостевой вход
-- ============================================================
-- Зачем: без возможности войти «просто так» большая часть новых
-- игроков отваливается на форме регистрации. Гостевой аккаунт
-- создаётся в один клик, игра доступна сразу, а позже его можно
-- «присвоить» (задать email и пароль) — прогресс сохраняется,
-- потому что user_id не меняется.
--
-- Отличие от обычного аккаунта: is_guest = TRUE. По нему:
--   — показываем в интерфейсе предложение сохранить аккаунт;
--   — считаем отдельно в аналитике (конверсия гость → игрок);
--   — чистим неактивных гостей скриптом обслуживания.
--
-- email и password_hash остаются NOT NULL: для гостя подставляется
-- синтетическая почта (guest_<uuid>@guest.invalid, .invalid по RFC 2606
-- нельзя зарегистрировать) и хэш случайного пароля. Так не нужно
-- менять ограничения существующей таблицы, а войти в гостя по
-- паролю невозможно.

ALTER TABLE users ADD COLUMN IF NOT EXISTS is_guest   BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS claimed_at TIMESTAMPTZ;

-- Чистка гостей ищет неприсвоенные аккаунты
CREATE INDEX IF NOT EXISTS idx_users_is_guest ON users(is_guest);

-- Кто ещё не присвоил аккаунт: для подсказки в интерфейсе
CREATE INDEX IF NOT EXISTS idx_users_guest_pending ON users(is_guest, last_login_at)
  WHERE is_guest = TRUE;
