-- Миграция 068: Герат как восьмой регион
--
-- ЧТО БЫЛО. Таблица region_visits (миграция 056) ограничена списком из
-- семи регионов:
--
--   region IN ('tabriz', 'isfahan', 'shiraz', 'caucasus',
--              'mesopotamia', 'khorasan', 'persian_gulf')
--
-- Перечислить регион в коде мало: СУБД отвергла бы вставку в region_visits
-- и CharacterService.recordRegionVisit проглотила бы ошибку (она
-- специально не поднимает исключение, чтобы сбой отметки не ронял
-- путешествие). Итог выглядел бы исправно, а молча перестал бы работать
-- целый механизм: ни достижение «посетить регион», ни история путешествий.
--
-- ПОЧЕМУ ЭТО ОПАСНЕЕ, КАЖЕТСЯ. Ошибка здесь не видна: она не бросает
-- исключение наверх, она гасит запись целиком. Именно такие молчащие
-- поломки и вылавливались в этой серии - список ограничений выглядел
-- законченным, потому что перечислял все известные регионы.
--
-- ЧТО ДЕЛАЕМ. Переносим ограничение на все восемь регионов. Число
-- регионов теперь живёт здесь и в enum Region, и сверяется проверкой
-- migrations.test.ts - чтобы следующий регион нельзя было добавить в коде
-- и забыть про базу.
--
-- Про NULL и про NOT VALID: ограничение было NOT VALID, и остаётся таковым.
-- Это осознанно: в нём нет смысла валидировать старые строки, а NOT VALID
-- не мешает вставлять новые. Проверка ниже всё равно требует, чтобы
-- ограничение было, и чтобы в нём был Герат.
BEGIN;

ALTER TABLE region_visits DROP CONSTRAINT IF EXISTS region_visits_region_check;

ALTER TABLE region_visits ADD CONSTRAINT region_visits_region_check CHECK (
  region IN ('tabriz', 'isfahan', 'shiraz', 'caucasus', 'mesopotamia', 'khorasan', 'persian_gulf', 'herat')
) NOT VALID;

COMMIT;
