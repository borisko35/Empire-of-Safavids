-- ============================================================
-- Миграция 055: выдача награды за переход по рекламной ссылке
-- ============================================================
-- ЗАЧЕМ. На объявлении сайта висела ссылка «получи бонус в 100 очков
-- игрока», и кода, который что-то начислял, не было нигде: игрок уходил
-- на рекламную сеть, сайт получал деньги, игрок не получал ничего.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ СЧЁТЧИК В LEADERBOARD. Счётчики в
-- leaderboard копятся сложением и не убывают: они отвечают на вопрос
-- «сколько раз случилось». Здесь вопрос обратный - «выдавалось ли уже», и
-- ответ обязан быть навсегда одним: повторная выдача - это чистый убыток
-- сайта. Счётчик, который можно увеличить, для этого не годится, а
-- флаг в персонаже означал бы третье место учёта.
--
-- reward_key, а не одна колонка на персонажа: ссылок может быть несколько
-- (разные партнёрки, разные акции), и «выдано по ссылке такой-то» -
-- разные факты. Первичный ключ по паре и запрет дубля - на уровне базы,
-- а не проверки в коде.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции.
CREATE TABLE IF NOT EXISTS reward_claims (
  character_id UUID NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  reward_key   VARCHAR(50) NOT NULL,
  gold         INT NOT NULL DEFAULT 0,
  claimed_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (character_id, reward_key)
);

-- Сумма неотрицательна: отрицательная «награда» была бы не наградой, а
-- списанием под видом подарка.
ALTER TABLE reward_claims
  DROP CONSTRAINT IF EXISTS reward_claims_gold_nonneg;

ALTER TABLE reward_claims
  ADD CONSTRAINT reward_claims_gold_nonneg CHECK (gold >= 0);
