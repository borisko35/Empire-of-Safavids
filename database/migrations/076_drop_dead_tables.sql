-- Удаление четырёх таблиц, в которые никто не пишет и из которых никто не читает.
--
-- Зачем. Каждая объявлена миграцией, и все четыре простояли пустыми. Читая
-- схему, легко решить, что механизм существует: «dungeon_boss_progress» звучит
-- как прогресс боссов, «party_progress» — как партийный счёт. На деле прогресс
-- боссов живёт в памяти процесса (DungeonService), а партийного счёта нет
-- никакого.
--
-- Проверено перед сносом: ни одного упоминания ни в одном .ts и .sql всей
-- разработки, кроме самих миграций о создании. Цифры не выдуманы.
--
-- Пятая таблица из того же разбора, `inventory`, сюда не вошла: её уже удалила
-- миграция 007 (`DROP TABLE IF EXISTS inventory;`). Повторный снос был бы
-- шумом.
--
-- ПОЧЕМУ ИМЕННО DROP, А НЕ «ОСТАВИТЬ НА ВСЯКИЙ СЛУЧАЙ». Пустая таблица не
-- хранит ничего, но она мешает: миграции проходят, в схеме виден механизм,
-- и следующий читатель тратит на него время. Если механика понадобится, её
-- создадут заново — вместе с кодом, который будет её писать.
--
-- CASCADE не используется намеренно: внешних ключей НА эти таблицы нет
-- (они ссылаются сами), а CASCADE способен утащить за собой чужое.
DROP TABLE IF EXISTS dungeon_boss_progress;
DROP TABLE IF EXISTS party_progress;
DROP TABLE IF EXISTS item_enchants;
DROP TABLE IF EXISTS login_history;
