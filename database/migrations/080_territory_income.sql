-- ============================================================
-- Миграция 080: доход с территорий
-- ============================================================
-- ЗАЧЕМ. Вид бонуса `gold_income` был объявлен в данных территорий с
-- самого начала и отключён с записанным объяснением: «нужен таймер и
-- правило начисления, которых нет». Таймер появился в §184.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ COUNT-НА ТИКЕ. Срок начисления должен
-- переживать перезапуск сервера. Счётчик тиков обнуляется при старте, и
-- после выкатки гильдия, державшая территорию неделю, получила бы весь
-- доход разом — или не получила бы ничего до конца периода, в зависимости
-- от того, как счётчик встанет. Отметка времени лежит в базе рядом с
-- территорией и говорит прямо: «столько ещё не выплачено».
--
-- DEFAULT NOW() — не формальность. Четыре строки уже лежат в таблице без
-- этой колонки, и без умолчания ALTER TABLE поставил бы им NULL: сравнение
-- NULL с временем даёт NULL, а «выплатить, где начислено ИСТИННО» молча
-- пропустило бы все четыре.
--
-- UPDATE: guild_territories идёт сама по себе, ей ничего не нужно.
ALTER TABLE guild_territories
  ADD COLUMN IF NOT EXISTS last_income_at TIMESTAMPTZ NOT NULL DEFAULT NOW();