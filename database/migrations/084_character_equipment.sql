-- 084: стартовая экипировка Сефевидов на characters
-- ═══════════════════════════════════════════════════════════════════
--
-- КОД ЕХАЛ БЕЗ МИГРАЦИИ. Коммит c4d93b23 («feat: safavid 3D equipment»,
-- 2 ноября 2026) научил CharacterService.createCharacter писать
-- стартовую экипировку в колонку characters.equipment, но SQL-файл
-- для колонки создан не был. На проде с того момента, как код доехал
-- до боя (7 ноября), POST /api/characters падал у ВСЕХ с
-- 42703: column "equipment" of relation "characters" does not exist —
-- ни один новый игрок не мог создать персонажа. Клиент показывал это
-- как «Не удалось создать персонажа. Попробуйте другое имя», поэтому
-- владелец искал причину в имени.
--
-- ТИП — JSONB, а не TEXT: чтение идёт через SELECT * без
-- JSON.parse (parseJsonFields разбирает только stats и position),
-- то есть наружу должен выходить готовый объект слотов
-- { robe, turban, coat, mail, helmet, weapon }.
-- Запись — JSON.stringify(...) параметром: строка с JSON
-- неявно приводится к jsonb на стороне Postgres.
--
-- NOT NULL DEFAULT '{}': у персонажей, созданных до этой колонки,
-- стартовой экипировки не было — пустой объект честно это выражает
-- и избавляет мир от NULL-проверок на чтении.

ALTER TABLE characters
  ADD COLUMN IF NOT EXISTS equipment JSONB NOT NULL DEFAULT '{}'::jsonb;
