-- ============================================================
-- Зоны внутри регионов: колонка zone в characters
-- ============================================================
-- Каждый регион разделён на зоны с прямоугольными границами.
-- Зона определяет уровень опасности, набор монстров и квестов.
-- Колонка хранит id зоны (например, "tabriz_center").
--
-- ПРИМЕЧАНИЕ. Значения намеренно НЕ заполняются здесь.
--
-- Первая версия этой миграции пыталась проставить зону всем существующим
-- персонажам одним UPDATE с подзапросом, и он падал: подзапрос был назван
-- z, и внутри него тоже была таблица z — Postgres считал ссылку z.id
-- неоднозначной ("column reference id is ambiguous").
--
-- Заполнять нечем и незачем. Зону определяет сервер при движении игрока
-- (GameSocketHandler.handlePlayerMove), и у каждого персонажа она проставится
-- сама в первые секунды после входа. Писать в миграции 21 прямоугольник
-- вторым списком означало бы держать в двух местах то, что обязано совпадать:
-- поправь одну границу здесь — и зоны на проде разойдутся с кодом.
ALTER TABLE characters ADD COLUMN IF NOT EXISTS zone VARCHAR(50);

CREATE INDEX IF NOT EXISTS idx_characters_zone ON characters(zone);
