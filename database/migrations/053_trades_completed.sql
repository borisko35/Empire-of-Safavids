-- ============================================================
-- Миграция 053: счётчик выполненных торговых контрактов
-- ============================================================
-- ЗАЧЕМ. У достижения «Торговец Шёлкового Пути» написано «выполнить 10
-- торговых контрактов», и условия не было: счётчика не существовало.
-- Контракты же работают - TradeService.deliver сдаёт груз и платит.
--
-- Почему счётчик в leaderboard, а не в trade_caravans. Там уже лежит
-- строка на каждый караван со статусом delivered, но достижения смотрят
-- условие по закрытому списку COUNTER_COLUMN, и третья таблица учёта была
-- бы местом, где счётчик забывают внести.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции.
ALTER TABLE leaderboard
  ADD COLUMN IF NOT EXISTS trades_completed INT NOT NULL DEFAULT 0;

-- Неотрицателен. Потолок 10000 - грубый предохранитель от двойного
-- начисления, а не предел игры: при десяти контрактах на достижение
-- игрок делает сотни, и потолок ровно в 1000 сделал бы достижение
-- недостижимым навсегда при любой ошибке с повтором.
ALTER TABLE leaderboard
  DROP CONSTRAINT IF EXISTS leaderboard_trades_completed_range;

ALTER TABLE leaderboard
  ADD CONSTRAINT leaderboard_trades_completed_range
  CHECK (trades_completed >= 0 AND trades_completed <= 10000);
