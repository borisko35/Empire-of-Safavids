-- ============================================================
-- 027 — Караваны: контракт и реальный таймер в пути
-- ============================================================
-- Таблица trade_caravans была заведена ещё в 016, но не использовалась:
-- контракты хранились в Redis, а груз при приёме просто списывался
-- из сумки. Из-за этого груз пропадал навсегда, если игрок закрывал
-- панель и забывал про контракт.
--
-- Теперь караван — строка в БД: id контракта, груз и время в пути.
-- eta_minutes из той же таблицы стал настоящим таймером — сдать груз
-- можно только после прихода, и cargo возвращается игроку.

ALTER TABLE trade_caravans ADD COLUMN IF NOT EXISTS contract_id VARCHAR(100);

CREATE INDEX IF NOT EXISTS idx_trade_caravans_owner
  ON trade_caravans (owner_id, status);

-- Контракты, созданные до 027: id в БД не было, а в Redis — только id.
-- Их восстановить нечем, поэтому помечаем отменёнными, чтобы игрок
-- не видел вечно «активный» контракт и мог взять новый.
UPDATE trade_caravans SET status = 'cancelled', completed_at = NOW()
  WHERE contract_id IS NULL AND status = 'active';
