-- Миграция 054: счётчик убийств мировых боссов
-- ============================================================
-- ЗАЧЕМ. У достижения «Убийца Боссов» написано «убить первого мирового
-- босса», и я записал в коде и в дорожной карте, что такой системы в игре
-- нет. Это было неправдой, и неправда была моей: поиск вёлся по двум
-- файлам (data/dungeons.ts и systems/DungeonService.ts), а вывод делался
-- по всему проекту.
--
-- Система на месте и работает: WorldEventSystem создаётся в GameLoop,
-- init/start/loadSchedule вызываются, спавны Симурга и Рустама заданы в
-- SpawnSystem, победы пишутся в world_boss_kills (миграция 002, колонка
-- character_id добавлена миграцией 041), зал славы их читает.
--
-- ПОЧЕМУ СЧЁТЧИК В LEADERBOARD, А НЕ ЧТЕНИЕ ИЗ world_boss_kills.
-- Таблица хранит по строке на победу и копит top_damage, но условия
-- достижений смотрят по закрытому списку COUNTER_COLUMN. Собственный
-- запрос из достижения означал бы, что правило «откуда берётся число»
-- живёт в двух местах: в списке и в маршруте.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции.
ALTER TABLE leaderboard
  ADD COLUMN IF NOT EXISTS world_boss_kills INT NOT NULL DEFAULT 0;

-- Неотрицателен: победа не отнимается. Потолок 1000 - грубый
-- предохранитель от двойного начисления. Боссы переспавниваются раз в
-- неделю и в две недели, и за год игры их не убить больше сотни, поэтому
-- 1000 - запас, а не предел.
ALTER TABLE leaderboard
  DROP CONSTRAINT IF EXISTS leaderboard_world_boss_kills_range;

ALTER TABLE leaderboard
  ADD CONSTRAINT leaderboard_world_boss_kills_range
  CHECK (world_boss_kills >= 0 AND world_boss_kills <= 1000);
