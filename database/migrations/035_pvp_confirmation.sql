-- Подтверждение результата PvP — Empire of Safavids
-- ============================================================
-- ТУТ БЫЛА ДЫРА. Маршрут /api/game/pvp/complete принимал winner_id прямо
-- из тела запроса и никем не проверял его: можно было отправить свой
-- characterId (его проверял requireCharacterOwnership) и победителем
-- назвать ЛЮБОГО персонажа. Рейтинг накручивался себе и снимался с чужого,
-- а топ-10 показывается прямо на сайте.
--
-- Теперь исход боя объявляют оба, и сервер ждёт обоих:
--   p1_confirmed / p2_confirmed — что назвал каждый из игроков;
--   settle_after — до какого момента ждём второго.
--
-- Три исхода:
--   1) оба назвали одного — победа ему, рейтинг пересчитывается;
--   2) один не ответил за settle_after — победа отвесившему, молчаливый
--      считается проигравшим (иначе можно было бы выиграть, просто не
--      отвечая);
--   3) оба ответили и назвали разных — ничья, рейтинг не трогаем.
--      Иначе врать было бы выгодно, а это и есть накрутка.

ALTER TABLE pvp_arena ADD COLUMN IF NOT EXISTS p1_confirmed UUID;
ALTER TABLE pvp_arena ADD COLUMN IF NOT EXISTS p2_confirmed UUID;
ALTER TABLE pvp_arena ADD COLUMN IF NOT EXISTS settle_after  TIMESTAMPTZ;

