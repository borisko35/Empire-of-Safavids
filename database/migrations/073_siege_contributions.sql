-- ============================================================
-- Миграция 073: вклад участников в осаду
-- ============================================================
-- ЗАЧЕМ. «Вся гильдия участвует в осаде крепости» — но урон
-- считался только суммарный: guild_sieges.damage растёт, а кто
-- именно растил — нигде не лежит. Игрок, добившийий десяток
-- монстров в регионе осады, не мог ни увидеть свой вклад, ни
-- доказать его; гильдия не видела, кто воевал, а кто смотрел.
--
-- ЧТО ЗДЕСЬ. Одна строка на (осада, персонаж): сколько урона
-- нанёс этот участник этой осаде. Персонаж может участвовать в
-- разных осадах, а в одной осаде — только один раз, поэтому
-- ключ составной и UPDATE идёт на сложение.
--
-- Почему не колонка в guild_sieges. Там был бы урон последнего
-- участника, а не каждого: осада — это коллектив, и таблица
-- без участников это «осада была», а не «осада была нашей».
--
-- CASCADE: осада закрылась — её можно чистить вместе со строкой,
-- персонаж удалён — его вклад не нужен. Без CASCADE строки
-- копились бы вечно и читались бы только этой осадой.
CREATE TABLE IF NOT EXISTS siege_contributions (
  siege_id      UUID NOT NULL REFERENCES guild_sieges(id) ON DELETE CASCADE,
  character_id  UUID NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  -- Сколько урона по крепости нанёс этот персонаж. Складывается:
  -- один участник бьёт крепость много раз за осаду.
  damage        INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (siege_id, character_id),
  CONSTRAINT siege_contributions_damage_nonnegative CHECK (damage >= 0)
);

-- Рейтинг вклада читается для живой осады: сначала те, кто
-- вложил больше. Частичный индекс не годится — осада одна, а
-- сортировка нужна и для открытых, и для закрытых (история).
CREATE INDEX IF NOT EXISTS siege_contributions_rank_idx
  ON siege_contributions (siege_id, damage DESC);

