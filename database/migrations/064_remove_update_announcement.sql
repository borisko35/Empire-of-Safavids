-- ============================================================
-- Миграция 064: снятие объявления об обновлении 1 октября
-- ============================================================
-- ЗАЧЕМ. Объявление о большом обновлении было нужно ровно до 1 октября.
-- После этой даты навсегда оставленная страница с обратным отсчётом
-- вводит новых посетителей в заблуждение: счётчик превращается в надпись
-- «Обновление началось» и перестаёт что-либо значить. Решение владельца:
-- снять.
--
-- ЧТО ДЕЛАЕТ. Убирает из ленты новостей тот пункт, который вёл на
-- /update.html. Остальные десять пунктов - обычная хроника игры, они
-- остаются.
--
-- ПОЧЕМУ МИГРАЦИЯ, А НЕ РУЧНОЙ UPDATE. Ручная правка продовой базы
-- остаётся только на проде: на любой другой машине, на откате и при
-- развёртывании с нуля объявление вернётся, и картина будет зависеть от
-- того, кто и когда заходил в базу.
--
-- ЗАЩИТА ОТ ПОВТОРОГО ЗАПУСКА. Фильтр выбирает по ссылке, поэтому хоть
-- десять раз применённая миграция не упадёт на «nothing to delete».
--
-- БЕЗ СОБСТВЕННЫХ BEGIN/COMMIT. Их оборачивает migrate.ts: он открывает
-- транзакцию, выполняет файл и откатывает при ошибке. Собственные
-- BEGIN/COMMIT внутри миграции закрывают его транзакцию раньше времени,
-- и его ROLLBACK откатывает уже не то.

UPDATE site_content
SET value = jsonb_set(
      value,
      '{items}',
      COALESCE(
        (
          SELECT jsonb_agg(item)
          FROM jsonb_array_elements(value->'items') AS item
          WHERE COALESCE(item->>'link', '') <> '/update.html'
        ),
        '[]'::jsonb
      ),
      false
    ),
    updated_at = NOW()
WHERE key = 'news'
  AND EXISTS (
    SELECT 1
    FROM jsonb_array_elements(value->'items') AS item
    WHERE COALESCE(item->>'link', '') = '/update.html'
  );
