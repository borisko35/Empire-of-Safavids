-- ============================================================
-- 077_xsolla_login_link.sql — вход через Xsolla
-- ============================================================
-- Зачем: Xsolla Login даёт своего пользователя со своим id, и без связи
-- с users игры этот id не к чему прикрепить: обмен кода вернул бы токен
-- Xsolla, но игра продолжала бы спрашивать почту.
--
-- ПОЧЕМУ НЕ КОЛОНКА В users. Первая версия этой миграции добавляла
-- users.xsolla_id. Это повторяет решение, от которого в 032 осознанно
-- отказались (см. шапку 032_oauth_identities.sql). Причины те же:
--   — у одного человека бывает несколько входов (Xsolla + Google + VK +
--     гостевой) при ОДНОМ user_id;
--   — колонка позволила бы только один Xsolla на аккаунт, а таблица —
--     сколько угодно, и каждый в свой ряд.
-- Поэтому здесь НЕ колонок, а только явное разрешение переиспользовать
-- user_identities под нового провайдера.
--
-- 'xsolla' короче VARCHAR(20) — сама колонка менять не нужно.
-- PRIMARY KEY (provider, provider_id) уже гарантирует, что один аккаунт
-- Xsolla не принадлежит двум игрокам, и он же индексом для поиска
-- (см. запрос OAuthService: WHERE provider = $1 AND provider_id = $2).
-- Новых индексов не требуется.

-- Контроль на будущее: таблица обязана существовать. Если её переименуют
-- или удалят, миграция упадёт здесь, а не тихо в рантайме.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_tables WHERE tablename = 'user_identities') THEN
    RAISE EXCEPTION 'user_identities не найдена: сперва примените 032_oauth_identities.sql';
  END IF;
END $$;

COMMENT ON COLUMN user_identities.provider IS
  'Провайдер входа: google | vk | xsolla. Новый провайдер = новая миграция, ставящая компонент.';
