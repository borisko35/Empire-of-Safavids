-- Миграция 066: осады территорий гильдий
-- ============================================================
-- ЗАЧЕМ. Четыре территории объявлены в data/guilds.ts с очками захвата,
-- очками защиты и расписанием осады, таблица guild_territories создана
-- миграцией 002 и засеяна этими четырьмя id. Но читать её не читал никто,
-- а уведомление siege_starting было объявлено в NotificationService и
-- не отправлялось ни разу. То есть осады не было ни в данных, ни в коде:
-- игрокам обещали штурм выходных, которого не существовало.
--
-- ЧТО ЗДЕСЬ. Только состояние осады, а не результат: кто, когда и чем
-- закончил. Сама логика - в systems/SiegeSystem.ts.
--
-- Почему отдельная таблица, а не колонки в guild_territories: там лежит
-- НАСТОЯЩИЙ владелец и текущая прочность (её читать будут бонусы), а
-- здесь - ПОПЫТКИ. Без истории нельзя ответить на вопрос «кто держит
-- Дворцовый квартал и сколько раз его отбивали», а территория без
-- истории - это объявление, а не владение.
--
-- Строка создаётся за полчаса до начала (это и есть напоминание), а
-- ended_at проставляется в конце. Незакрытая строка - это осада,
-- которая идёт сейчас или должна была идти: так осада переживает
-- перезапуск сервера, не потеряв ни факта начала, ни накопленного урона.
CREATE TABLE IF NOT EXISTS guild_sieges (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  territory_id      VARCHAR(50) NOT NULL,
  -- Когда осада должна была начаться. Пишется заранее, за полчаса.
  started_at        TIMESTAMPTZ NOT NULL,
  ended_at          TIMESTAMPTZ,
  -- Владелец на момент начала: кто оборонял.
  defender_guild_id UUID REFERENCES guilds(id) ON DELETE SET NULL,
  -- Кто в итоге прорвался. Заполняется при захвате, не раньше.
  attacker_guild_id UUID REFERENCES guilds(id) ON DELETE SET NULL,
  outcome           VARCHAR(16) NOT NULL DEFAULT 'scheduled',
  -- Накопленный урон по крепости. Пишется на каждом ударе: без этого
  -- после падения сервера нельзя понять, сколько было вложено.
  damage            INTEGER NOT NULL DEFAULT 0,
  reminder_sent_at  TIMESTAMPTZ,
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT guild_sieges_outcome_range
    CHECK (outcome IN ('scheduled', 'in_progress', 'defended', 'captured')),
  -- Урон неотрицателен, а outcome закрыт списком выше. Без этого
  -- опечатка в outcome тихо создала бы третье состояние, о котором
  -- никто в коде не думает, и осада навсегда осталась бы «идущей».
  CONSTRAINT guild_sieges_damage_nonnegative CHECK (damage >= 0)
);

-- Незакрытые осады: их читает tick при старте сервера. Частичный индекс
-- работает быстрее общего, потому что закрытых строк будет на порядок
-- больше незакрытых.
--
-- ИМЕННО УНИКАЛЬНЫЙ, и это не украшение, а запрет дубля. Тик идёт каждые
-- полминуты и входит в код начала осады каждый раз; без уникальности он
-- вставлял бы новую строку на каждый тик, и к концу осады их было бы
-- больше сотни, а «одна открытая осада на территорию» была бы fiction.
-- ON CONFLICT (territory_id) WHERE ended_at IS NULL в SiegeSystem опирается
-- именно на этот индекс: текст условия обязан совпадать с его предикатом.
CREATE UNIQUE INDEX IF NOT EXISTS guild_sieges_open_idx
  ON guild_sieges (territory_id) WHERE ended_at IS NULL;

-- История: «кто и когда держал территорию». Обратный порядок - это
-- порядок, в котором её читают.
CREATE INDEX IF NOT EXISTS guild_sieges_history_idx
  ON guild_sieges (started_at DESC);

-- ПРОЧНОСТЬ. defense_hp в guild_territories объявлен как 100000, а
-- очки защиты в data/guilds.ts - от 5000 (базар) до 60000 (порт). Это
-- расхождение не трогаем: значение 100000 никто не читает, а SiegeSystem
-- выставляет настоящие очки защиты при начале осады. Пока осады не было,
-- поле было просто числом по умолчанию.

