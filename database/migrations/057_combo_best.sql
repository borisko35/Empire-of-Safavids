-- ============================================================
-- Миграция 057: достигнутое комбо
-- ============================================================
-- ЗАЧЕМ. Достижение «Мастер Комбо» обещает «комбо из 5 ударов», и условия
-- не было: счётчика не существовало. Цепочка ударов считалась в памяти и
-- никуда не записывалась.
--
-- ПОЧЕМУ НЕ СЧЁТЧИК-СУММА, А ПОРОГ. Цепочка - это длина ОДНОЙ серии подряд,
-- а не сумма ударов. Сложение дало бы «две серии по три удара = шесть», и
-- «комбо из 5» закрыл бы тот, кто прыгал с места на место. Правило другое:
-- здесь пишется достижение ПРОЙДЕННОГО ПОРОГА, и оно пишется один раз.
--
-- ПОЧЕМУ ИМЯ combo_best, А НЕ combo_5. Колонка означает «длинная серия
-- была», и её правят через GREATEST, а не сложением: повторное достижение
-- порога не должно превращать её в 10.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции.
ALTER TABLE leaderboard
  ADD COLUMN IF NOT EXISTS combo_best INT NOT NULL DEFAULT 0;

-- Потолок 100. Длиннее 100 ударов подряд цепочка не набирает: окно 4 секунды,
-- и быстрее 25 ударов в секунду никто не кликает. Число оставлено с
-- запасом, чтобы не обрезать настоящий рекорд из-за округления.
ALTER TABLE leaderboard
  DROP CONSTRAINT IF EXISTS leaderboard_combo_best_range;

ALTER TABLE leaderboard
  ADD CONSTRAINT leaderboard_combo_best_range
  CHECK (combo_best >= 0 AND combo_best <= 100);
