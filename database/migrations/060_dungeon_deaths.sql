-- ============================================================
-- Миграция 060: смерти в подземельях переживают перезапуск сервера
-- ============================================================
-- ЗАЧЕМ. Достижение «пройти подземелье без единой смерти» считает смерти в
-- памяти сессии. Память умирает вместе с сервером: сессия, восстановленная
-- после перезапуска, начинала счёт с нуля. То есть заход, в котором игрок
-- умер ДО рестарта, засчитывался как безсмертный - достижение выдавалось за
-- то, чего не было.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В dungeon_sessions. Сессия может
-- иметь нескольких участников, и у каждого своё число смертей. Колонка в
-- сессии была бы числом только лидера - а счётчик достижения тоже
-- достаётся лидеру, значит для ОДНОГО персонажа хватило бы. Но участники
-- подземелья заходят по приглашению, и их смерти тоже могут понадобиться:
-- когда правило достижения перестанет быть «кто прошёл», а станет «кто
-- прошёл без потерь» для всех, данные уже будут на месте.
--
-- ПОЧЕМУ deaths, А НЕ ФЛАГ. Умер, поднялся, умер снова - и заход уже не
-- безсмертный. Один флаг «умер ли» этого не различит.
--
-- ON DELETE CASCADE от сессии: сессия удалена - её смерти больше не имеют
-- смысла. Хранить их после закрытия сессии незачем, и иначе таблица росла
-- бы бесконечно.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой
-- файл роняет сайт целиком на этапе миграции.
CREATE TABLE IF NOT EXISTS dungeon_deaths (
  session_id   UUID NOT NULL REFERENCES dungeon_sessions(id) ON DELETE CASCADE,
  character_id UUID NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  deaths       INTEGER NOT NULL DEFAULT 0,
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (session_id, character_id),
  CHECK (deaths >= 0)
);

-- Поиск идёт по персонажу: «сколько смертей у этого игрока в этой сессии».
CREATE INDEX IF NOT EXISTS idx_dungeon_deaths_character
  ON dungeon_deaths (character_id);
