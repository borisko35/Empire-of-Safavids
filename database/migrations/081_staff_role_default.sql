-- ============================================================
-- Миграция 081: роль staff выдавалась каждому аккаунту
-- ============================================================
-- ЗАЧЕМ. Миграция 013 добавила колонку так:
--
--   ALTER TABLE users ADD COLUMN admin_role VARCHAR(20) NOT NULL DEFAULT 'gm';
--
-- Значение по умолчанию стояло 'gm' — а 'gm' входит в SITE_STAFF_ROLES
-- (server/src/middleware/adminCheck.ts). Проверка siteStaffCheck идёт по
-- роли ОДНОЙ, флаг is_admin ей не нужен:
--
--   const byRole = SITE_STAFF_ROLES.has(row?.admin_role ?? '');
--   if (!row || (!row.is_admin && !byRole)) → 403
--
-- Значит каждый аккаунт, созданный после 013, получал admin_role='gm'
-- автоматически и проходил проверку персонала. На боевом сервере это
-- было 37 аккаунтов из 37, включая 31 гостя.
--
-- ЧТО БЫЛО ОТКРЫТО ГОСТЮ:
--   PUT  /api/site/content/news          переписать новости сайта
--   PUT  /api/site/content/announcement  переписать заявление на главной
--   PUT  /api/site/content/maintenance   включить режим техработ
--   модерация форума: закрыть, закрепить и удалить темы
--   разбор жалоб (feedback)
-- Ключи перечислены в ALLOWED_KEYS (server/src/routes/site.ts).
--
-- КАК ПРАВИТЬ. Роль по умолчанию убираем совсем, а «не сотрудник»
-- означает NULL. Смысл такой: роль нельзя получить вместе с аккаунтом,
-- её можно только выдать осознанно. Пустое значение и роль 'user' были бы
-- хуже: любой будущий список ролей легко забыл бы про 'user', а NULL
-- проверяется единственным правилом — роль есть, значит её выдали.
--
-- ЧТО НЕ ТРОГАЕМ. is_admin остаётся как был: настоящие права проверяются
-- по нему одному (adminCheck смотрит только на is_admin). Роли
-- сотрудников is_admin=TRUE сохраняются — миграция их не задевает.

ALTER TABLE users ALTER COLUMN admin_role DROP DEFAULT;
ALTER TABLE users ALTER COLUMN admin_role DROP NOT NULL;

-- Роль 'gm' была у всех, кто когда-либо зарегистрировался или зашёл
-- гостем. Снимаем её у всех, у кого нет флага администратора.
UPDATE users SET admin_role = NULL WHERE is_admin IS NOT TRUE;

-- Учётная запись владельца: флаг администратора и роль owner.
-- Без is_admin=TRUE панель администратора показывает «нет доступа»,
-- а /api/admin/* отвечает 403, потому что adminCheck смотрит только
-- на этот флаг. Роль owner кладём по почте, а не по логину: логины
-- меняли, почта в этом проекте идентифицирует владельца устойчиво.
UPDATE users
   SET is_admin = TRUE, admin_role = 'owner'
 WHERE lower(email) IN ('fariz_allahverdiyev1990@bk.ru',
                        'borisglebov595@gmail.com');