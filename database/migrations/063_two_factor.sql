-- ============================================================
-- Миграция 063: двухфакторная аутентификация
-- ============================================================
-- ЗАЧЕМ. Вход защищался только паролем. Утечка одного пароля - это вход в
-- чужой аккаунт: пароль можно переиспользовать с другого сайта, подобрать по
-- словарю или купить. Второй фактор - код из телефона, который нельзя увести
-- вместе с паролем.
--
-- СЕКРЕТ ЛЕЖИТ ЗАШИФРОВАННЫМ. Это принципиально. TOTP по RFC 6238
-- устроен так, что сервер ОБЯЗАН уметь посчитать код сам: симметричный
-- алгоритм, ключ общий с телефоном. Значит секрет, который можно прочитать
-- из базы, - это все коды за все тридцать секунд вперёд. Поэтому секрет
-- шифруется, и шифр - AES-256-GCM, а не XOR и не base64.
--
-- Почему нельзя только хэш, как у пароля: пароль проверяется перебором
-- на сервере, а здесь сервер обязан ВЫЧИСЛИТЬ код по секрету. Хэш от
-- секрета не годится - из него код не получить.
--
-- last_used_step - ЗАЩИТА ОТ ПОВТОРА. Код действует своё окно в тридцать
-- секунд, и всё это время его можно слать подряд. Без этого поля код,
-- подсмотренный через плечо или найденный в чужом журнале, сработал бы
-- много раз подряд. Хранится номер шага последнего принятого кода, и
-- следующий обязан быть строго больше.
--
-- recovery - коды восстановления на случай, когда телефон потерян. Хранятся
-- ХЭШАМИ с солью, а не текстом: база - место, где утечка наиболее вероятна.
-- salt один на аккаунт, hash по одному на код, списком jsonb.
--
-- confirmed_at заполняется только после того, как игрок доказал, что его
-- телефон показывает тот же код, что и сервер. Без этого подтверждения
-- включённый, но не подтверждённый 2FA заблокировал бы вход навсегда - и
-- исправлять это можно было бы только правкой базы.
--
-- Строгая целостность: primary key на user_id, внешний ключ на users с
-- удалением каскадом. Аккаунт удалён - секрет удалён, без исключения.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой
-- файл роняет сайт целиком на этапе миграции.
CREATE TABLE IF NOT EXISTS user_2fa (
  user_id         UUID        PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  -- Секрет в base32, но зашифрованный. Именно в base32, потому что в таком
  -- виде его показывает и вводит телефон.
  secret_encrypted TEXT       NOT NULL,
  -- enabled, а confirmed_at IS NOT NULL: включён, но не подтверждён - это
  -- разные состояния, и второе опаснее для игрока, чем первое.
  enabled          BOOLEAN     NOT NULL DEFAULT FALSE,
  confirmed_at     TIMESTAMPTZ,
  recovery_hash    JSONB       NOT NULL DEFAULT '[]'::jsonb,
  recovery_salt    TEXT,
  -- Номер последнего принятого шага. 0 = кодов ещё не было.
  last_used_step   BIGINT      NOT NULL DEFAULT 0,
  -- Счётчик неудачных попыток кода. Отдельный от парольного: игрок может
  -- верно помнить пароль и ошибаться в коде, и обесценивать его за это
  -- нельзя. Защита от перебора шестизначного кода - отдельная.
  failed_attempts  INTEGER     NOT NULL DEFAULT 0,
  locked_until     TIMESTAMPTZ,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

