-- ============================================================
-- Миграция 049: счётчик собранных стихотворений
-- ============================================================
-- ЗАЧЕМ. У достижения «Поэт Шираза» написано «выполнить все поэтические
-- задания», и счётчика не было нигде - как и маршрута, который вообще
-- что-то начисляет за стихи. Награды в данных были (50, 150 и 500 золота
-- по сложности), но до кошелька не доходили: игра заканчивалась, и всё.
--
-- Почему счётчик в leaderboard, а не отдельная таблица. Там уже копятся
-- monsters_killed, pvp_wins, quests_completed, playtime_seconds и parries
-- из миграции 046. Шестое место учёта в другой таблице означало бы, что
-- счётчик надо не забыть в двух местах: и здесь, и в списке, по
-- которому достижения смотрят условие.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции.
ALTER TABLE leaderboard
  ADD COLUMN IF NOT EXISTS poetry_completed INT NOT NULL DEFAULT 0;

-- Счётчик неотрицателен и неотъемлем от числа стихов: больше, чем стихов
-- есть, собрать нельзя. Верхняя граница ловит ошибку, при которой
-- достижение выдалось бы само по себе.
ALTER TABLE leaderboard
  DROP CONSTRAINT IF EXISTS leaderboard_poetry_completed_range;

ALTER TABLE leaderboard
  ADD CONSTRAINT leaderboard_poetry_completed_range
  CHECK (poetry_completed >= 0 AND poetry_completed <= 1000);
