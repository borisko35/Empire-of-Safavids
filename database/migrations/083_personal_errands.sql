-- ============================================================
-- Миграция 083: личные поручения
-- ============================================================
-- ЗАЧЕМ. Слой наблюдений (§365) отвечает на вопрос «что игрок делает
-- чаще», но сам по себе ничего не предлагает — инфраструктура без
-- потребителя. Личное поручение — первый настоящий потребитель профиля:
-- НПС, привязанный к верхнему делу персонажа, даёт задание, прогресс
-- которого считается тем же счётчиком наблюдений.
--
-- ЧТО ЗДЕСЬ. Одна строка на персонажа — активное поручение. У персонажа
-- ровно одно личное поручение одновременно: это персональный сюжет, а не
-- вторая колонка ежедневных задач.
--
-- Почему base_count, а не прогресс. Прогресс считается ЛЕНИВО: разница
-- между текущим счётчиком наблюдений и базой на момент принятия. Никаких
-- новых крючков в бой не добавляется — наблюдение (§365) уже считает
-- каждое дело, поручение лишь читает разницу. Кэш прогресса в строке
-- мгновенно разошёлся бы с наблюдением.
--
-- Почему строка удаляется при выдаче награды. История поручений — будущая
-- работа (лента «что ты делал»); хранить выполненное поручение в таблице
-- активных значило бы городить статусы ради данных, которых никто не читает.
CREATE TABLE IF NOT EXISTS personal_errands (
  character_id UUID PRIMARY KEY REFERENCES characters(id) ON DELETE CASCADE,
  -- Какое дело наблюдается: тот же kind, что в player_observations (082).
  kind         TEXT NOT NULL,
  -- Сколько дел нужно сверх базы. Числа берутся из шаблона поручений,
  -- поэтому CHECK только на здравый смысл.
  target       INTEGER NOT NULL CHECK (target > 0),
  -- Счётчик наблюдений на момент принятия: прогресс = текущий - база.
  base_count   INTEGER NOT NULL CHECK (base_count >= 0),
  accepted_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

