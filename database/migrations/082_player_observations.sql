-- ============================================================
-- Миграция 082: слой наблюдений за привычками игрока
-- ============================================================
-- ЗАЧЕМ. Третий пункт списка владельца (личные квесты) требует «слоя
-- наблюдений: что игрок делает чаще, и на этом основании — предложение».
-- Сейчас мир не помнит ничего долговременного о манере игры: задачи дня
-- живут сутки и стираются, репутация помнит только шесть фракционных
-- действий. Наблюдение — это то, что останется: сколько раз персонаж
-- сделал каждое из шести канонических дел.
--
-- ЧТО ЗДЕСЬ. Одна строка на (персонаж, вид деятельности) со счётчиком.
-- Ключ составной: у персонажа ровно одна строка на вид, UPDATE идёт на
-- сложение — как в siege_contributions (073).
--
-- Почему таблица, а не Redis или память процесса. Наблюдение — память
-- мира о привычках, фундамент личных квестов: кэш, умирающий на рестарте,
-- значил бы «мир забывает тебя каждый перезапуск». Караванная обида (361)
-- уже установила правило: память мира живёт в данных события.
--
-- Почему счётчик, а не журнал событий. Наблюдение отвечает на вопрос
-- «что игрок делает чаще», а не «когда именно он это сделал». Журнал
-- рос бы на каждое убийство монстра — это тысячи строк на персонажа ради
-- суммы, которая и есть счётчик.
CREATE TABLE IF NOT EXISTS player_observations (
  character_id UUID NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  -- Вид деятельности: monsterKill, dungeonClear, questDone, pvpWin,
  -- auctionSale, tradeDone — те же шесть, что растят репутацию: у канона
  -- «что случилось» ровно один источник (ReputationGrants).
  kind         TEXT NOT NULL,
  count        INTEGER NOT NULL DEFAULT 0,
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (character_id, kind),
  CONSTRAINT player_observations_count_nonnegative CHECK (count >= 0)
);

-- Профиль читается целиком (шесть строк) при открытии панели задач,
-- сортировка по счёту нужна, чтобы верхняя строка была «чаще всего».
CREATE INDEX IF NOT EXISTS player_observations_top_idx
  ON player_observations (character_id, count DESC);

