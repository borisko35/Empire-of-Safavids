-- ============================================================
-- Миграция 046: счётчик парирований
-- ============================================================
-- ЗАЧЕМ. У достижения «Идеальный Блок» было написано «выполнить 10
-- идеальных блоков», но парирование появилось только сейчас, а счётчика
-- парирований не существовало нигде. Поле perfect_blocks, на которое
-- указывала дорожная карта, - фантом: миграция 016 объявляла его в
-- `CREATE TABLE IF NOT EXISTS combat_logs`, но таблицу к тому моменту уже
-- создала миграция 001, поэтому весь 016-й блок про combat_logs был
-- пустым. Колонки perfect_blocks в базе не было и никогда не было.
--
-- ГДЕ ЖИВЁТ СЧЁТЧИК. В таблице leaderboard: там уже копятся настоящие
-- счётчики (monsters_killed, pvp_wins, quests_completed), и они
-- накапливаются сложением в момент события, а не затираются тиком.
-- Отдельная таблица ради одного числа была бы второй системой учёта
-- с тем же смыслом.
--
-- CHECK на неотрицательное: счётчик, ушедший в минус из-за ошибки
-- вычитания, выглядел бы как «-3 парирования» и тихо ломал бы все
-- достижения, которые на него смотрят.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции. Это уже стоило простоя.
ALTER TABLE leaderboard
  ADD COLUMN IF NOT EXISTS parries BIGINT NOT NULL DEFAULT 0;

-- Разумный предел. Парирование засчитывается один раз на удар, и больше
-- 10 миллионов за одну игру не набирает никто: значение извне не приходит,
-- но верхняя граница делает опечатку в коде заметной сразу, а не через
-- месяц в виде достижения, которое выдалось само.
ALTER TABLE leaderboard
  DROP CONSTRAINT IF EXISTS leaderboard_parries_nonnegative;

ALTER TABLE leaderboard
  ADD CONSTRAINT leaderboard_parries_nonnegative CHECK (parries >= 0 AND parries <= 10000000);
