-- ============================================================
-- Миграция 058: у guild_skills не было updated_at
-- ============================================================
-- ЗАЧЕМ. Покупка г��льдейского навыка падала с
--   column "updated_at" of relation "guild_skills" does not exist
-- а золото к этому моменту УЖЕ БЫЛО СПИСАНО из казны. Проверка на бою
-- потеряла 6000 золота, купив несуществующий навык.
--
-- ПОЧЕМУ КОЛОНКИ НЕ БЫЛО. Миграция 050 объявляет:
--     CREATE TABLE IF NOT EXISTS guild_skills (..., updated_at TIMESTAMPTZ ...)
-- Но guild_skills была создана РАНЬШЕ, без updated_at, и IF NOT EXISTS
-- молча пропустил новое определение. Ограничения из следующих ALTER
-- добавились, а колонка - нет. IF NOT EXISTS прячет расхождение схемы:
-- миграция отчитывается об успехе, а таблица не соответствует тексту.
--
-- ЭТО ЖЕ БЫЛО С ДРУГИМ ФАЙЛОМ. Для guilds миграция 042 добавляла
-- недостающие territory, gold, emblem, created_at, updated_at - то есть
-- та же болезнь уже была и лечилась точечно. Здесь она повторилась на
-- соседней таблице, потому что никто не сверял текст миграций с
-- фактической схемой.
--
-- Добавление колонки, а не удаление updated_at из кода. Колонка нужна,
-- чтобы видеть, когда навык куплен; в остальных таблицах гильдий она
-- есть. Плюс NOW() для старых строк: иначе дата была бы 1970 года.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой
-- файл роняет сайт целиком на этапе миграции.
ALTER TABLE guild_skills
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
