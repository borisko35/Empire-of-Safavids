-- Состояние захода, которое переживает перезапуск сервера.
--
-- Зачем. Вход в подземелье держится в памяти процесса, и при старте
-- restoreActiveSessions собирает сессию заново из базы. Смерти он уже
-- читает из таблицы (dungeon_deaths), а сундуки и убитых боссов — нет:
-- там стояло openedChests: new Set() и killedBossIds: new Set(), а
-- spawnSessionMonsters/spawnSessionChests заново создавали всех монстров
-- и все сундуки.
--
-- Что из этого выходило. Игрок вскрывал сундуки, убивал босса, и тут
-- сервер перезапускался — а это происходит на каждой выкатке, то есть
-- раз в несколько коммитов. Заход возвращался целиком: сундуки пустые,
-- босс жив. Повторное вскрытие платило золото и опыт заново, босс
-- убивался заново, и complete() считал заход выполненным второй раз.
-- Награда за заход не задваивалась (loot_claimed_at, миграция 071), но
-- сундуки и добыча с монстров — задваивались, и бесконечно.
--
-- Формат. JSONB-массив строк, а не отдельная таблица: состояние нужно
-- целиком при чтении и не нужно искать по нему. Проверка «есть ли уже»
-- делается тем же оператором `?`, поэтому гонка двух вскрытий
-- разрешается базой.
ALTER TABLE dungeon_sessions
  ADD COLUMN IF NOT EXISTS opened_chests JSONB NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS killed_boss_ids JSONB NOT NULL DEFAULT '[]'::jsonb;

-- Восстановление захода читает эти столбцы целиком по primary key,
-- отдельного индекса не нужно.
COMMENT ON COLUMN dungeon_sessions.opened_chests IS
  'Идентификаторы вскрытых сундуков захода. Не пустой после перезапуска, иначе заход становится фармом.';
COMMENT ON COLUMN dungeon_sessions.killed_boss_ids IS
  'Идентификаторы убитых боссов захода. Сбрасывать при восстановлении нельзя: босс воскреснет.';