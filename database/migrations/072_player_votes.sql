-- ============================================================
-- Миграция 072: голосование на browsermmorpg.com
-- ============================================================
-- ЗАЧЕМ. Голосование на рейтинговом сайте даёт игровую награду, но без
-- записи в базе оно неотличимо от клика: игрок нажал кнопку, а игра об этом
-- не узнала. Награду нельзя было ни выдать, ни проверить, ни ограничить по
-- времени — то есть обещание «проголосуй и получи» было обещанием ни на чём.
--
-- ЧТО ЗДЕСЬ. Одна строка на персонажа: когда голос отдан и сколько наград
-- получено. Кулдаун — 12 часов, как принято на рейтинговых сайтах; раньше
-- награду не даём, но и не молчим: возвращаем, через сколько можно снова.
--
-- Почему одна строкка, а не история голосов. История нужна для статистики,
-- а не для награды; её можно добавить позже, не трогая эту таблицу. Пока
-- важно одно: голос учтён и награда выдана ровно один раз.
CREATE TABLE IF NOT EXISTS player_votes (
  character_id   UUID PRIMARY KEY REFERENCES characters(id) ON DELETE CASCADE,
  -- Когда отдан последний голос. По нему считается кулдаун.
  voted_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Сколько наград за голоса получил персонаж. Нужно для статистики и для
  -- проверки, что награда не выдавалась дважды за один голос.
  rewards_claimed INTEGER NOT NULL DEFAULT 0,
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Кулдаун неотрицателен: отрицательный означал бы, что голос можно повторить
  -- раньше, чем он отдан, — это дыра, а не настройка.
  CONSTRAINT player_votes_rewards_nonnegative CHECK (rewards_claimed >= 0)
);

-- Кто и когда голосовал: читается панелью и статистикой. Обратный порядок —
-- порядок, в котором её читают: сначала свежие.
CREATE INDEX IF NOT EXISTS player_votes_voted_at_idx
  ON player_votes (voted_at DESC);

