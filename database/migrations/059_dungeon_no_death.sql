-- ============================================================
-- Миграция 059: подземелье, пройденное без единой смерти
-- ============================================================
-- ЗАЧЕМ. Достижение «без смертей» обещало «пройти подземелье, не умерши
-- ни разу», и условия не было: смерти нигде не считались. Счётчик
-- отсутствовал, и достижение не выдавалось никому.
--
-- ПОЧЕМУ СЧЁТЧИК, А НЕ СОСТОЯНИЕ. «Без единой смерти» - это про
-- КАЖДЫЙ отдельный заход, а не про накопительный итог. Считать
-- накопительно нельзя: пять заходов по одной смерти - это пять смертей,
-- и achievement «ни разу не умер» закрывать не должен. Поэтому счётчик
-- наращивается по одному разу за ЗАСЧИТАННЫЙ заход без смертей, а не за
-- каждую смерть.
--
-- Потолок 10000 заведомо избыточен: счётчик показывает не число
-- прохождений, а сколько раз игрок обошёлся без потерь, и за 10000 таких
-- заходов игрок не доживёт. Число поставлено с запасом, чтобы не
-- обрезать настоящий счёт при округлении.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой
-- файл роняет сайт целиком на этапе миграции.
ALTER TABLE leaderboard
  ADD COLUMN IF NOT EXISTS dungeons_no_death INT NOT NULL DEFAULT 0;

ALTER TABLE leaderboard
  DROP CONSTRAINT IF EXISTS leaderboard_dungeons_no_death_range;

ALTER TABLE leaderboard
  ADD CONSTRAINT leaderboard_dungeons_no_death_range
  CHECK (dungeons_no_death >= 0 AND dungeons_no_death <= 10000);
