-- Признак «добыча за заход уже выдана».
--
-- Зачем. complete() вызывается по добитому боссу, а вызвать его можно
-- дважды: две вкладки, двойной клик, гонка двух заходов. Без этого
-- признака каждый вызов выдавал бы опыт, золото и предметы заново.
--
-- Забирается одним UPDATE с условием «признак ещё пуст», а не чтением
-- и последующей записью: две одновременные победы читали бы «пусто»
-- обе и обе выдали бы добычу.
--
-- NULL означает «ещё не выдавали». Часовой пояс считает база.
ALTER TABLE dungeon_sessions
  ADD COLUMN IF NOT EXISTS loot_claimed_at TIMESTAMPTZ;

-- Раздача идёт по участникам захода, а по заходу искать нужно часто:
-- идёт лимит попыток.
CREATE INDEX IF NOT EXISTS idx_dungeon_sessions_dungeon_started
  ON dungeon_sessions(dungeon_id, started_at);
