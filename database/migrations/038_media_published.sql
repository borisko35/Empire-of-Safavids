-- ============================================================
-- Публикация загруженных материалов на сайте — Empire of Safavids
-- ============================================================
-- Панель загрузки сама по себе ни на что не влияла: сотрудник заливал
-- снимок, получал ссылку, и дальше её надо было вручную вписать в
-- страницу сайта и пересобрать. Страницы сайта — обычные html-файлы,
-- которые кладутся в образ при сборке, поэтому «добавить скриншот»
-- означало «позвать разработчика».
--
-- Три новых поля:
--   is_public    — показывать ли файл в галерее на сайте. По умолчанию
--                  НЕТ: залитый файл может быть черновиком, и он не
--                  должен появляться на главной странице до решения
--                  сотрудника.
--   caption      — подпись под файлом в галерее. Пишет сотрудник, а не
--                  берётся из имени файла: имя прислано человеком и
--                  часто нечитаемое.
--   published_at — когда включили публикацию. По нему галерея
--                  сортируется, и в панели видно, что старше.
--
-- Частичный индекс: галерея читает только опубликованное, и ей не
-- нужно сканировать черновики.

ALTER TABLE media_files
  ADD COLUMN IF NOT EXISTS is_public    BOOLEAN     NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS caption      VARCHAR(200),
  ADD COLUMN IF NOT EXISTS published_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS idx_media_files_public
  ON media_files (published_at DESC)
  WHERE is_public;
