-- Миграция 069: Герат в ограничении, который реально действует
--
-- ЧТО СЛОМАЛОСЬ. Миграция 068 добавила ограничение с восемью регионами, но
-- не убрала старое, с семью. Она делала:
--
ALTER TABLE region_visits DROP CONSTRAINT IF EXISTS region_visits_region_check;
--
-- а настоящее имя старого ограничения - region_visits_region_known (его
-- создаёт миграция 056). Имя не совпало, IF EXISTS молча ничего не сделал, и
-- второе ограничение было ДОБАВЛЕНО рядом со старым. Два CHECK на одном
-- столбце действуют как пересечение, то есть действовал более строгий - тот,
-- что на семь регионов.
--
-- ПРОВЕРЕНО НА ЖИВОЙ БАЗЕ, А НЕ ПО ИМЕНАМ. Вставка отметки о посещении
-- Герата падала:
--
--   ERROR: new row for relation "region_visits" violates check constraint
--          "region_visits_region_known"
--
-- Сравнение: isfahan вставлялся молча. То есть отметка о посещении Герата
-- не доходила до базы.
--
-- ПОЧЕМУ ЭТО БЫЛО ТИХО. CharacterService.recordRegionVisit специально не
-- поднимает исключение, чтобы сбой отметки не ронял путешествие игрока.
-- Ошибка гасилась, путешествие работало, а «посетить Герат» и «посетить
-- все восемь регионов» были недостижимы навсегда - и выглядело это как
-- обычная игра.
--
-- ЧТО ДЕЛАЕМ. Сносятся ОБА ограничения на регион и добавляется одно,
-- перечисляющее восемь. Старое имя выбрано не наугад: оно взято из
-- миграции 056, которая его создаёт, - и теперь проверка сверяет эти два
-- имени, чтобы такое расхождение не повторилось.
--
-- Про NOT VALID: оставлено, как было. В нём нет смысла валидировать старые
-- строки, а NOT VALID не мешает вставлять новые. Но теперь ограничение
-- единственное, и перечисление в нём - полный список регионов.
BEGIN;

ALTER TABLE region_visits DROP CONSTRAINT IF EXISTS region_visits_region_known;

ALTER TABLE region_visits DROP CONSTRAINT IF EXISTS region_visits_region_check;

ALTER TABLE region_visits ADD CONSTRAINT region_visits_region_known CHECK (
  region IN ('tabriz', 'isfahan', 'shiraz', 'caucasus', 'mesopotamia', 'khorasan', 'persian_gulf', 'herat')
) NOT VALID;

COMMIT;
