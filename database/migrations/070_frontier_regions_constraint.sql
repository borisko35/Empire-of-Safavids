-- Миграция 070: дальние края в ограничении, которое реально действует
--
-- ЧТО СДЕЛАНО В КОДЕ. Решение владельца: за x = ±2350 край стал девятым и
-- десятым регионами. До этого все 24 зоны были полосами ВО ВСЮ ШИРИНУ мира:
-- у каждой стояло x1: -3175, x2: 3175, различался только север-юг. Замер это
-- показал буквально - на любой широте встречалась ровно одна зона, и игрок,
-- ушедший от Исфахана на восток, проходил 3141 единицу и оставался в зоне
-- «Центр Исфахана. Безопасная зона для новичков» с монстрами первого уровня.
-- Расширение мира в семь раз по площади растянуло «зону новичка» на все
-- 6350 единиц ширины.
--
-- ПОЧЕМУ ЭТО МИГРАЦИЯ, А НЕ ПРАВКА ПРЕДЫДУЩЕЙ. Ограничение перечисляет
-- регионы списком, и новых в нём не было. Проверка regionVisits сверяет
-- список в CHECK с enum Region и роняет сборку при расхождении - то есть
-- несовпадение поймали бы ДО выкатки. Но сама СУБД ошибку отдаёт тихо:
-- CharacterService.recordRegionVisit специально не поднимает исключение,
-- чтобы сбой отметки не ронял путешествие игрока. Ошибка гасилась,
-- путешествие работало, а «посетить все регионы» было недостижимо.
-- Именно так уже терялся Герат - см. 068 и 069.
--
-- ПОЧЕМУ СНОСЯТСЯ ОБА ОГРАНИЧЕНИЯ, А ДОБАВЛЯЕТСЯ ОДНО. Миграция 068 сносила
-- не то имя (region_visits_region_check вместо настоящего
-- region_visits_region_known) и потому надоложила второе ограничение рядом со
-- старым. Два CHECK на одном столбце действуют как пересечение, то есть
-- действует более строгий - тот, что на семь регионов. Здесь оба сносятся и
-- добавляется одно, перечисляющее десять. Имя взято не наугад: его создаёт
-- миграция 056, и теперь проверка сверяет эти два имени.
--
-- Про NOT VALID: оставлено, как было. Старые строки валидировать незачем, а
-- NOT VALID не мешает вставлять новые. Ограничение единственное, и перечень
-- в нём - полный список регионов.
--
-- Порядок: сначала сносятся старые, потом добавляется новое. Обратный
-- порядок оставил бы на миллисекунду старое ограничение поверх нового, и
-- вставка в этот промежуток упала бы.
BEGIN;

ALTER TABLE region_visits DROP CONSTRAINT IF EXISTS region_visits_region_known;

ALTER TABLE region_visits DROP CONSTRAINT IF EXISTS region_visits_region_check;

ALTER TABLE region_visits ADD CONSTRAINT region_visits_region_known CHECK (
  region IN ('tabriz', 'isfahan', 'shiraz', 'caucasus', 'mesopotamia', 'khorasan',
             'persian_gulf', 'herat', 'east_frontier', 'west_frontier')
) NOT VALID;

COMMIT;