-- ============================================================
-- Миграция 061: базовое здоровье отдельно от бонуса гильдии
-- ============================================================
-- ЗАЧЕМ. max_hp - сохранённая колонка, которая НАКАПЛИВАЕТСЯ прибавлением:
-- при создании 100 + выносливость*10, при левеле max_hp = max_hp + прирост.
-- Поэтому бонус гильдии (навык guild_hp_boost, +100 HP за уровень) нельзя
-- просто прибавить: при выходе из гильдии его нечем снять - под ним нет
-- базы.
--
-- base_max_hp - это то же здоровье БЕЗ бонуса. По нему считается бонус,
-- и он же переживает смену состава гильдии.
--
-- ВАЖНО. Снаряжение в max_hp НЕ входит: формула считается из BASE_STATS
-- класса, снаряжение живёт отдельно и применяется к защите. Запись в
-- ROADMAP обещала «пересчёт при каждом изменении снаряжения» - этого
-- делать не нужно, потому что снаряжение в формулу не входит вовсе.
--
-- Заполнение для существующих персонажей: base_max_hp = max_hp. Это
-- верно - бонуса гильдии пока не существует, и текущее значение является
-- базой.
--
-- ШАГ ПЕРВЫЙ ИЗ ДВУХ. Эта миграция только заводит колонку и ведёт её
-- параллельно с max_hp. Поведение игры НЕ меняется: обе колонки растут
-- одинаково. Бонус гильдии подключается следующим шагом.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой
-- файл роняет сайт целиком на этапе миграции.
ALTER TABLE characters
  ADD COLUMN IF NOT EXISTS base_max_hp INTEGER;

UPDATE characters
  SET base_max_hp = max_hp
  WHERE base_max_hp IS NULL;

-- После заполнения колонка обязательна: NULL означал бы «неизвестно», а
-- вычисление max_hp из него дало бы NULL вместо числа.
ALTER TABLE characters
  ALTER COLUMN base_max_hp SET DEFAULT 100;

ALTER TABLE characters
  ALTER COLUMN base_max_hp SET NOT NULL;
