-- Стартовый регион персонажа: 'tabriz' → 'isfahan'
--
-- ЧТО БЫЛО. Колонка characters.region была объявлена с умолчанием
-- 'tabriz' (миграция 001), и createCharacter писал region = Region.TABRIZ,
-- а точку старта ставил в (0,0) — это Исфахан по REGION_SPAWNS.
--
-- Чем это оборачивалось. Персонаж 1-го уровня рождался на площади столицы,
-- а сервер считал его в Тебризе, где требуется 20 уровень. Требование
-- уровня переставало быть затвором: новичок рождался по ту сторону ворот.
-- Отсюда монстры, комнаты сокетов, чат и квесты ключились на Тебриц, а
-- игрок стоял в Исфахане, и в углу экрана горело «Тебриз». А запись
-- region_visites сразу помечала Тебриз посещённым, и «посетить Тебриз»
-- засчитывалось, никуда не сходив.
--
-- ЧТО МЕНЯЕТСЯ. Умолчание приводится в соответствие с реальным стартом.
-- Само объявление колонки в миграции 001 не трогаем: её давно накатили на
-- боевой сервер, и правка там ничего бы не изменила. Правят уже применённые
-- базы - именно для этого миграция и нужна.
--
-- Про APPLICATION не через миграцию: INSERT идёт из createCharacter и
-- передаёт region явно, поэтому умолчание для создания персонажа и не
-- работало. Оно влияло на любой вставки без region, и на 056_region_visits,
-- где проверка «characters.region = 'tabriz'» считалась ловушкой.
ALTER TABLE characters ALTER COLUMN region SET DEFAULT 'isfahan';
