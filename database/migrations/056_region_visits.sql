-- ============================================================
-- Миграция 056: посещённые регионы
-- ============================================================
-- ЗАЧЕМ. Два достижения («Посетить Тебриз», «Посетить все 7 регионов») не
-- имели условия, потому что проверить их было нечем.
--
-- Почему нельзя было проверить по characters.region. У нового персонажа
-- регион по умолчанию ровно в 'tabriz' (миграция 001). Проверка
-- region = 'tabriz' была бы верной с момента регистрации, и «Посетить
-- Тебриз» выдавалось бы бесплатно, никто никуда не сходив. То же самое с
-- «все 7 регионов»: из одного столбца «где персонаж сейчас» это не
-- выводится - там лежит только текущий регион, а не история.
--
-- ДОПИСКА ПОЗДНЕЕ. Умолчание 'tabriz' оказалось муляжом, а не замыслом: к
-- моменту создания персонажа точку старта перенесли в Исфахан (0,0), а регион
-- остался 'tabriz' - персонаж рождался на площади столицы, числясь в Тебризе.
-- Умолчание исправлено миграцией 067_start_region_isfahan.
-- Таблица region_visits при этом остаётся нужной, и причина другая: в
-- characters.region лежит ТЕКУЩИЙ регион, а не пройденный путь. Сходивший в
-- Тебриз и вернувшийся домой неотличим от никуда не ходившего.
--
-- ПОЧЕМУ СТРОКА, А НЕ СЧЁТЧИК. «Посещённые регионы» - это множество, и
-- множество нельзя хранить числом: после семи регионов число перестаёт
-- расти, а новый регион появиться не может. Счётчик «посещений» в
-- leaderboard считал бы переходы, а не освоенные регионы, и «посетить все
-- 7» выдалось бы тому, кто семь раз прыгал между двумя городами.
--
-- Таблица маленькая: одна строка на пару (персонаж, регион), максимум 7.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции.
CREATE TABLE IF NOT EXISTS region_visits (
  character_id   UUID NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  region         VARCHAR(30) NOT NULL,
  first_visited_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  visits_count   INT NOT NULL DEFAULT 1,
  -- Одна строка на регион: повторные приходы не плодят строки, иначе
  -- «посетить все 7» превратилось бы в «совершить 50 переходов».
  PRIMARY KEY (character_id, region)
);

-- Счётчик приходов неотрицателен и не меньше единицы: строка означает
-- «здесь был», и ноль приходов в ней противоречил бы её собственному
-- существованию.
ALTER TABLE region_visits
  DROP CONSTRAINT IF EXISTS region_visits_count_range;

ALTER TABLE region_visits
  ADD CONSTRAINT region_visits_count_range CHECK (visits_count >= 1);

-- Регион ограничен списком из game.types.ts. Опечатка в имени не создала
-- бы строку, которую потом прочитать нечем, - она была бы отвергнута.
ALTER TABLE region_visits
  DROP CONSTRAINT IF EXISTS region_visits_region_known;

ALTER TABLE region_visits
  ADD CONSTRAINT region_visits_region_known CHECK (
    region IN ('tabriz', 'isfahan', 'shiraz', 'caucasus', 'mesopotamia', 'khorasan', 'persian_gulf')
  );

-- ДОБАВЛЕНИЕ СУЩЕСТВУЮЩИХ. Персонаж стоит в своём регионе, значит он там
-- и был: иначе достижение «Посетить Тебриз» оказалось бы недостижимым
-- для всех, кто ни разу не путешествовал, хотя Тебриз - стартовый город.
INSERT INTO region_visits (character_id, region)
SELECT id, region FROM characters
ON CONFLICT (character_id, region) DO NOTHING;
