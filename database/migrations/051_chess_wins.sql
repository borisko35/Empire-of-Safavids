-- ============================================================
-- Миграция 051: счётчик побед в шахматах
-- ============================================================
-- ЗАЧЕМ. У достижения «Шахматный Гений» написано «выиграть 10 шахматных
-- партий», и условия не было вовсе: счётчика побед не существовало ни в
-- одной таблице. Это был один из 12 пунктов со словами «пока не
-- считается» - достижение существовало, а измерить его было нечем.
--
-- Почему счётчик в leaderboard, а не отдельная таблица. Там уже копятся
-- monsters_killed, pvp_wins, quests_completed, poetry_completed, parries и
-- playtime_seconds из миграций 046 и 049. Седьмое место учёта в другой
-- таблице означало бы, что счётчик надо не забыть в двух местах: и здесь,
-- и в списке COUNTER_COLUMN, по которому достижения смотрят условие.
--
-- Комментарии строго '--': в .sql-файле '//' не комментарий, и такой файл
-- роняет сайт целиком на этапе миграции.
ALTER TABLE leaderboard
  ADD COLUMN IF NOT EXISTS chess_wins INT NOT NULL DEFAULT 0;

-- Счётчик неотрицателен: победа не может быть отнята. Верхняя граница
-- ловит ошибку, при которой одна партия засчиталась бы дважды - при
-- ставке до 5000 и выплате вдвое выиграть 10 000 партий нельзя, и такая
-- цифра означала бы, что счётчик пишется не по одному разу на партию.
ALTER TABLE leaderboard
  DROP CONSTRAINT IF EXISTS leaderboard_chess_wins_range;

ALTER TABLE leaderboard
  ADD CONSTRAINT leaderboard_chess_wins_range
  CHECK (chess_wins >= 0 AND chess_wins <= 10000);
