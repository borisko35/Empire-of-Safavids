-- ============================================================
-- Миграция 065: два старых пункта ленты новостей
-- ============================================================
-- ЗАЧЕМ. В ленте оставались два пункта, обещавшие обновление:
--   - «⚔️ ГРЯДЁТ ВЕЛИКОЕ ОБНОВЛЕНИЕ В EMPIRE OF SAFAVIDS! ⚔️» со
--     списком из пятнадцати грядущих новшеств (новые локации, мини-игры,
--     кат-сцены, переработка меню);
--   - «Новое обновление в игре!» с перечнем того, что уже выпустили
--     (Склад и Банк Гильдии, караваны, NPC-попутчики, исправления города).
-- Оба остались от события, которого больше нет. Первое обещает то, чего
-- не случилось в таком виде, второе перечисляет выигранное - но так
-- громко, что читается как свежее обновление, а не как хроника. Решение
-- владельца: убрать оба.
--
-- ЧТО ДЕЛАЕТ. Убирает эти два пункта. Восемь остаются - обычная хроника
-- игры: сервер открыт, умные NPC, домен с HTTPS, карта мира и прочее.
--
-- ПОЧЕМУ ПО ТЕКСТУ, А НЕ ПО НОМЕРУ. Пункты не имеют ни id, ни даты, ни
-- ссылки - только заголовок. Отбирать их по номеру нельзя: после любой
-- правки ленты номера седут, и миграция удалит не то. Заголовок хотя бы
-- уникален в ленте и переживает перестановку.
--
-- Повторный запуск безопасен: отбирается по тексту, а не по позиции.
--
-- БЕЗ СОБСТВЕННЫХ BEGIN/COMMIT - см. пояснение в миграции 064.
--
-- Копия текстов оставлена в docs/archive/news-removed-2026-10-01.md.

UPDATE site_content
SET value = jsonb_set(
      value,
      '{items}',
      COALESCE(
        (
          SELECT jsonb_agg(item)
          FROM jsonb_array_elements(value->'items') AS item
          WHERE btrim(COALESCE(item->'title'->>'ru', '')) NOT IN (
                  '⚔️ ГРЯДЁТ ВЕЛИКОЕ ОБНОВЛЕНИЕ В EMPIRE OF SAFAVIDS! ⚔️',
                  'Новое обновление в игре!'
                )
            -- Пустой заголовок оставляем: иначе миграция, применённая к
            -- ленте с неразобранными записями, молча вычистила бы их все.
            AND COALESCE(item->'title'->>'ru', '') <> ''
        ),
        '[]'::jsonb
      ),
      false
    ),
    updated_at = NOW()
WHERE key = 'news'
  AND EXISTS (
    SELECT 1
    FROM jsonb_array_elements(value->'items') AS item
    WHERE btrim(COALESCE(item->'title'->>'ru', '')) IN (
            '⚔️ ГРЯДЁТ ВЕЛИКОЕ ОБНОВЛЕНИЕ В EMPIRE OF SAFAVIDS! ⚔️',
            'Новое обновление в игре!'
          )
  );
