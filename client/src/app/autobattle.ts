// ============================================================
// Автобой — Empire of Safavids
// ============================================================
// Цикл боя без нажатий: игрок сам решает, включить его или нет.
//
// ВЫБОР ИГРОКА ОБЯЗАТЕЛ, и это не украшение. Автобой без переключателя
// лишает игрока контроля над собственным боем, а в PvP-зоне это способ умереть
// не глядя. Плюс к тому его надо уметь выключить на середине: если автобой
// нельзя остановить, им нельзя пользоваться.
//
// ПОЧЕМУ ЦИКЛ НА КЛИЕНТЕ, А НЕ НА СЕРВЕРЕ. Серверные проверки боя не меняются
// ни на строчку: тот же combat:action, те же античит, та же проверка дальности
// и отката. Если бы сервер бил сам, появился бы второй путь начисления урона
// - тот самый класс поломки, который в этом проекте уже случался (счётчик
// убийств в рейтинге писался через placeholder и падал молча на втором
// событии). Автобой на клиенте физически не может нанести урон в обход
// серверных правил.
//
// ЧТО АВТОБОЙ НЕ ДЕЛАЕТ И НЕ БУДЕТ ДЕЛАТЬ:
//   * не бьёт игроков. Цель выбирается только из монстров, в том числе в
//     PvP-зонах - ноPvP для автобоя просто отключается (см. можноВPvP);
//   * не обходит кулдаун: пауза между ударами не короче серверного отката;
//   * не ест ресурсы «в обход» проверок - мана и стамина тратятся тем же
//     путём, что и при клике.
//
// ГРАНИЦА, КОТОРУЮ СТОИТ ЗНАТЬ. Автобой не ходит по миру за новыми целями:
// он бьёт монстра, до которого игрок дошёл. Навигатор квестовой цели
// (refreshNavTarget) ставится игроком вручную или идёт от активного квеста,
// но САМ автобой по нему не идёт - это был бы отдельный кусок работы с
// коллизиями и границами мира, и его не стоит делать молча.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ ИМПОРТОВ. Ни window, ни deathScreen: модуль решает, а не
// рисует, и не знает про экраны. Побочный плют - его можно импортировать из
// серверных проверок: у серверного tsconfig нет DOM-библиотеки, и любой
// window здесь ломал бы сборку проверок на ровном месте. Состояние «мёртв»
// и таймер приходят снаружи, от мира.

/** Пауза между ударами автобоя, мс. Не короче серверного отката (380 мс). */
export const ПАУЗА_УДАРА_МС = 700;

/**
 * Дальность, с которой автобой начинает бить, метры.
 *
 * Шире, чем у замаха (26 м): игрок не смотрит в сторону монстра, он вообще
 * может в это время читать задания. Но не «вся карта» - иначе автобой бьёт
 * через полкомнаты и выглядит как чит.
 */
export const ДАЛЬНОСТЬ_БОЯ = 18;

/** Что автобойу нужно от мира, чтобы решить, кого бить. */
export interface МирДляАвтобоя {
  monsters: Map<string, { instanceId: string; pos: { x: number; z: number }; deadAt?: number }>;
  /** Позиция игрока. */
  me: { pos: { x: number; z: number } } | null;
  /** Регион игрока - по нему решается, можно ли бить в этой зоне. */
  region: string;
}

/**
 * Регионы, где автобой обязан молчать.
 *
 * Соответствует PVP_ZONES на сервере (systems/KarmaSystem.ts): safe - можно,
 * contested и pvp - нельзя. В PvP-зоне автобой выключается сам и говорит
 * об этом один раз: молча выключиться игрок не заметит и решит, что игра
 * зависла.
 *
 * Список продублирован здесь намеренно. Импортировать серверный файл в
 * клиент нельзя - это затащило бы в сборку базу и логгер, а shared не должен
 * знать про карму. Расхождение списков ловит проверка: она читает оба файла
 * и требует, чтобы PvP-регионы совпадали.
 */
export const АВТОБОЙ_МОЛЧИТ: readonly string[] = ['caucasus', 'mesopotamia', 'khorasan', 'persian_gulf'];

/** Можно ли в этом регионе бить автоматически. */
export function можноВРегионе(region: string): boolean {
  return !АВТОБОЙ_МОЛЧИТ.includes(region);
}

/**
 * Ближайший живой монстр в пределах досягаемости.
 *
 * null, а не «первый попавшийся»: иначе автобой бил бы через всю карту
 * ближайшим по списку, а не тем, до кого игрок реально дошёл.
 */
export function выбратьЦель(мир: МирДляАвтобоя): string | null {
  if (мир.me === null) return null;
  let лучшая: string | null = null;
  // Сравнение ВКЛЮЧИТЕЛЬНОЕ, а не строгое. Строгое отбрасывало бы монстра,
  // стоящего ровно в ДАЛЬНОСТЬ_БОЯ метрах: он в досягаемости, а выбираться
  // не хотел. Нашлась это проверкой, а не чтением - граница видна только
  // на одном значении, и опечатка в знаке стоила бы «автобой не бьёт вплотную».
  let лучшаяДистанция = ДАЛЬНОСТЬ_БОЯ;
  for (const монстр of мир.monsters.values()) {
    if (монстр.deadAt) continue;
    const d = Math.hypot(монстр.pos.x - мир.me.pos.x, монстр.pos.z - мир.me.pos.z);
    if (d <= лучшаяДистанция) {
      лучшаяДистанция = d;
      лучшая = монстр.instanceId;
    }
  }
  return лучшая;
}

/** Почему автобой не бьёт. null - бьёт. */
export type ПричинаМолчания = 'выключен' | 'мертв' | 'pvp' | 'нет_цели';

export interface РешениеАвтобоя {
  /** Что делать на этом такте. */
  бить: string | null;
  /** Почему не бьём, если не бьём. */
  причина: ПричинаМолчания | null;
  /** Правда ли, что он молчит из-за PvP-зоны. */
  изЗаPvP: boolean;
}

/**
 * Один такт решения.
 *
 * Вынесено чистой функцией, чтобы правило проверялось без браузера: всё
 * решение - это «можно ли в этой зоне» плюс «есть ли кто рядом», и оба
 * условия обязаны быть видны в проверке поимённо.
 */
export function решить(
  мир: МирДляАвтобоя,
  включён: boolean,
  мёртв: boolean,
): РешениеАвтобоя {
  if (!включён) return { бить: null, причина: 'выключен', изЗаPvP: false };
  if (мёртв) return { бить: null, причина: 'мертв', изЗаPvP: false };
  if (!можноВРегионе(мир.region)) {
    return { бить: null, причина: 'pvp', изЗаPvP: true };
  }
  const цель = выбратьЦель(мир);
  if (цель === null) return { бить: null, причина: 'нет_цели', изЗаPvP: false };
  return { бить: цель, причина: null, изЗаPvP: false };
}

export type Автобой = {
  /** Включён ли. Игрок решает сам, и это хранится у него. */
  включён: boolean;
  /** Идёт ли сейчас такт. */
  работает: boolean;
  /** Игрок жаловался на PvP-молчание - второй раз не говорим. */
  сказалПроPvP: boolean;
};

export function создатьАвтобой(включён: boolean): Автобой {
  return { включён, работает: false, сказалПроPvP: false };
}

/**
 * Запустить цикл.
 *
 * Такт НЕ вызывает сам себя через setInterval, а берёт таймер извне: так его
 * можно проверить, не заводя настоящих часов. Плюс это же позволяет
 * останавливать и запускать такт по событию, а не по расписанию.
 */
export function запустить(
  ав: Автобой,
  мир: () => МирДляАвтобоя,
  мёртв: () => boolean,
  ударить: (цель: string) => void,
  такт: () => void,
): () => void {
  ав.работает = true;
  let таймер: ReturnType<typeof setTimeout> | null = null;
  const шаг = (): void => {
    if (!ав.работает) return;
    try {
      const решение = решить(мир(), ав.включён, мёртв());
      if (решение.изЗаPvP && !ав.сказалПроPvP) {
        ав.сказалПроPvP = true;
        такт();
      }
      if (решение.бить !== null) ударить(решение.бить);
    } catch {
      // Такт автобоя не имеет права ронять игровой цикл: ошибка здесь
      // должна останавливать авто, а не игру.
      ав.работает = false;
      return;
    }
    таймер = setTimeout(шаг, ПАУЗА_УДАРА_МС);
  };
  таймер = setTimeout(шаг, ПАУЗА_УДАРА_МС);
  return () => {
    if (таймер !== null) clearTimeout(таймер);
    таймер = null;
  };
}

/** Остановить цикл. */
export function остановить(ав: Автобой): void {
  ав.работает = false;
}
