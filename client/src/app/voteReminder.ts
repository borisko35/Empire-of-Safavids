// Напоминание проголосовать на BrowserMMORPG.
//
// ЗАЧЕМ. Голос на рейтинговом сайте поднимает игру в списке, а награда за него —
// причина возвращаться. Но награда обещана на сайте, а просят голос раз в 12 часов,
// и без напоминания игрок просто забывает: сайт открыл, проголосил, в игру вернулся —
// а награду не забрал, потому что на сайте её надо забрать отдельно.
//
// ЧТО ЗДЕСЬ. Раз в 10 минут клиент спрашивает сервер «можно ли голосовать».
// Сервер знает кулдаун и не врёт — клиенту не нужно угадывать. Когда голосовать
// можно, приходит тост с напоминанием забрать награду на сайте.
//
// ПОЧЕМУ НЕ КАЖДЫЕ 10 МИНУТ. Кулдаун 12 часов, и если напоминать всё это время,
// игрок научится пропускать тост глазами — а вместе с ним пропускает и сам факт,
// что награда есть. Поэтому напоминаем один раз на окно кулдауна и замолкаем.
import { toast } from './hud';

const ПРОВЕРКА_МС = 10 * 60 * 1000;

let таймер: ReturnType<typeof setInterval> | null = null;
/** Уже напомнили про это окно кулдауна — чтобы не долбить каждые 10 минут. */
let напомнили = false;

async function проверить(): Promise<void> {
  const token = localStorage.getItem('eos_token');
  if (!token) return;
  try {
    const res = await fetch('/api/game/vote/status', {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!res.ok) return;
    const статус = (await res.json()) as { canVote?: boolean };
    if (статус.canVote !== true) {
      // Кулдаун ещё идёт — сбрасываем флаг, чтобы напомнить, когда истечёт.
      напомнили = false;
      return;
    }
    if (напомнили) return;
    напомнили = true;
    toast('Проголосуй на BrowserMMORPG — награда 500 золота в игре', 'info');
  } catch {
    // Сеть недоступна — напоминание не приходит. Молчать здесь правильно: игрок и так
    // видит, что игра не в сети.
  }
}

export function startVoteReminder(): void {
  if (таймер !== null) return;
  void проверить();
  таймер = setInterval(() => void проверить(), ПРОВЕРКА_МС);
}