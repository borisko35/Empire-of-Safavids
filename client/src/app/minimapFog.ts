// Туман войны для мини-карты и большой карты.
//
// ЧТО ЭТО. Память о том, где игрок был. В эскизе владельца туман был заглушкой —
// просто чёрная полупрозрачная плоскость поверх карты: она ничего не помнила и
// ничего не скрывала, а выглядела как туман. Настоящий туман здесь такой:
//   - видел сейчас  — круг вокруг игрока, обычная яркость;
//   - бывал раньше   — видно, но это память;
//   - не был         — чёрное.
//
// ГДЕ ПОМНИТСЯ — РЕШЕНИЕ. Память о мире лежит в localStorage браузера, по
// ключу на персонажа. Почему не база: ради такой памяти нужна миграция схемы и
// новая колонка, а это целый шаг выкатки ради того, что игрок и так не увидит.
// Честное ограничение: знание карты не переносится между браузерами и устройствами.
// Если понадобится — память переезжает в characters одной миграцией, а сам
// расклад остаётся прежним: биты и клетки не знают, где они лежат.
//
// РАЗМЕР. Мир — WORLD_HALF 3175 в каждую сторону. При клетке 32 мировые единицы
// получается 199 клеток по стороне, 39601 бит — меньше 5 КБ на персонажа. Хранить
// список посещённых клеток нельзя: он рос бы линейно и к концу игры занимал
// больше, чем сам битовый массив.
//
// ПОЧЕМУ КЛЕТКА 32, А НЕ МЕЛЬЧЕ. Мелкая клетка честнее на вид, но память растёт
// как квадрат, а рисовать маску приходится на каждый пиксель. 32 единицы — это
// примерно два экрана мельком: карта открывается чуть раньше, чем игрок дошёл, и
// это скорее приятно, чем обидно.
import { WORLD_HALF } from './game3d/terrain';

/** Сторона клетки памяти в мировых единицах */
export const FOG_CELL = 32;

/** На сколько клеток вокруг игрока открывается. 9 клеток — 288 единиц. */
export const FOG_REVEAL_CELLS = 9;

/** Сторона сетки клеток: мир от -WORLD_HALF до +WORLD_HALF */
export const FOG_GRID = Math.ceil((WORLD_HALF * 2) / FOG_CELL);

/** Байт на битовый массив памяти */
const БАЙТОВ = Math.ceil((FOG_GRID * FOG_GRID) / 8);

/** Клетка мира по координате, с зажимом в границы карты */
export function fogCell(мировая: number): number {
  const клетка = Math.floor((мировая + WORLD_HALF) / FOG_CELL);
  return клетка < 0 ? 0 : клетка >= FOG_GRID ? FOG_GRID - 1 : клетка;
}

/**
 * Флаги модуля.
 *
 * Собраны в объект, а не в три отдельные переменные — не для красоты: проверка
 * исполняет настоящие функции этого файла и подставляет их как ЗНАЧЕНИЯ, а не
 * как живые связи. Присваивание к переменной снаружи не видно, и проверка не
 * смогла бы убедиться, что память помечена флаги.слойй и что пора записать её на
 * диск. Через объект видно всё.
 */
const флаги = {
  /** Перерисовать слой мини-карты: память изменилась после его отрисовки */
  слой: false,
  /**
   * Перерисовать маску большой карты.
   *
   * Свой флаг, а не общий со слоем: слой мини-карты снимает свой флаг при
   * перерисовке, и общий флаг обманул бы обе карты — большая решила бы, что ей
   * нечего показывать, и нарисовала старую память.
   */
  маска: true,
  /** Записать память на диск при ближайшей возможности */
  запись: false,
};

/** Память: по биту на клетку. Бит = 1 — игрок здесь был. */
let память = new Uint8Array(БАЙТОВ);
let персонаж = '';

function индекс(ix: number, iz: number): number {
  return iz * FOG_GRID + ix;
}

/** Открыта ли клетка */
export function fogSeen(ix: number, iz: number): boolean {
  if (ix < 0 || iz < 0 || ix >= FOG_GRID || iz >= FOG_GRID) return false;
  const бит = индекс(ix, iz);
  return (память[бит >>> 3] & (1 << (бит & 7))) !== 0;
}

function открыть(ix: number, iz: number): boolean {
  const бит = индекс(ix, iz);
  const байт = бит >>> 3;
  const маска = 1 << (бит & 7);
  if ((память[байт] & маска) !== 0) return false;
  память[байт] |= маска;
  return true;
}

// ── Сохранение ────────────────────────────────────────────────────────────

const КЛЮЧ = (id: string): string => `eos_fog_v1_${id}`;

/** Биты в строку: каждый байт — один символ, дальше base64 ради хранилища */
function упаковать(данные: Uint8Array): string {
  let строка = '';
  for (let i = 0; i < данные.length; i++) строка += String.fromCharCode(данные[i]);
  return btoa(строка);
}

/** Развернуть обратно. Мусор на входе — не повод ломать игру: память просто пустая. */
function распаковать(текст: string, куда: Uint8Array): boolean {
  try {
    const сырой = atob(текст);
    const байты = new Uint8Array(сырой.length);
    for (let i = 0; i < сырой.length; i++) байты[i] = сырой.charCodeAt(i);
    куда.set(байты.subarray(0, Math.min(байты.length, куда.length)));
    return true;
  } catch {
    return false;
  }
}

/**
 * Загрузить память персонажа.
 *
 * Смена персонажа пересоздаёт массив: иначе карта нового героя начиналась бы с
 * картой предыдущего.
 */
export function loadFog(characterId: string): void {
  if (персонаж === characterId) return;
  персонаж = characterId;
  память = new Uint8Array(БАЙТОВ);
  флаги.слой = true;
  if (!characterId) return;
  try {
    распаковать(localStorage.getItem(КЛЮЧ(characterId)) ?? '', память);
  } catch {
    // Приватный режим или переполненное хранилище: играем с пустой картой.
  }
}

function сохранить(): void {
  if (!персонаж) return;
  try {
    localStorage.setItem(КЛЮЧ(персонаж), упаковать(память));
    флаги.запись = false;
  } catch {
    // Хранилище недоступно: память живёт до конца вкладки, и это не поломка.
  }
}

/** Записать, если память менялась. Вызывать нечасто — писать дорого. */
export function flushFog(): void {
  if (флаги.запись) сохранить();
}

// ── Открытие местности ────────────────────────────────────────────────────

/**
 * Отметить всё, что игрок видит вокруг себя.
 *
 * Круг, а не квадрат: за углом ничего не видно, и открывать «за углом» нечестно.
 */
export function revealAround(worldX: number, worldZ: number): boolean {
  const cx = fogCell(worldX);
  const cz = fogCell(worldZ);
  let открылось = 0;
  for (let dz = -FOG_REVEAL_CELLS; dz <= FOG_REVEAL_CELLS; dz++) {
    for (let dx = -FOG_REVEAL_CELLS; dx <= FOG_REVEAL_CELLS; dx++) {
      if (dx * dx + dz * dz > FOG_REVEAL_CELLS * FOG_REVEAL_CELLS) continue;
      const ix = cx + dx;
      const iz = cz + dz;
      if (ix < 0 || iz < 0 || ix >= FOG_GRID || iz >= FOG_GRID) continue;
      if (открыть(ix, iz)) открылось++;
    }
  }
  if (открылось > 0) {
    флаги.слой = true;
    // У большой карты свой флаг. Общий с мини-картой обманывал бы обе карты:
    // слой мини-карты снимает флаги.слойсть при перерисовке, и большая карта после
    // этого решает, что показывать нечего, то есть рисует старую память.
    флаги.маска = true;
    флаги.запись = true;
  }
  return открылось > 0;
}

/** Слой тумана изменился и его надо перерисовать */
export function fogDirty(): boolean {
  return флаги.слой;
}

export function fogClearDirty(): void {
  флаги.слой = false;
}

/** Сколько памяти занято — для проверок и для отладки */
export function fogSeenRatio(): number {
  let занято = 0;
  for (let i = 0; i < память.length; i++) {
    let bits = память[i];
    while (bits) {
      занято += bits & 1;
      bits >>= 1;
    }
  }
  return занято / (FOG_GRID * FOG_GRID);
}

// ── Слой тумана для мини-карты ────────────────────────────────────────────

let слой: HTMLCanvasElement | null = null;
let слойOrigin = { x: 0, z: 0 };
let слойExtent = 0;
let слойPx = 0;

/**
 * Чёрная маска на видимую часть карты.
 *
 * Маска рисуется в мировых координатах и кладётся в тот же поворот, что и рельеф,
 * поэтому туман поворачивается вместе с картой и совпадает с биомами. Одно
 * изображение на пиксель: без зазоров, в отличие от россыпи прямоугольников.
 *
 * Кэш перерисовывается при смене центра или размера, и после каждого открытия
 * местности — иначе карта показала бы старую память и «забывала» новую.
 */
export function fogLayerFor(originX: number, originZ: number, extent: number, sizePx: number): HTMLCanvasElement | null {
  const перерисовать =
    !слой || слойPx !== sizePx || слойExtent !== extent ||
    слойOrigin.x !== originX || слойOrigin.z !== originZ || флаги.слой;
  if (!перерисовать) return слой;

  const cvs = слой ?? document.createElement('canvas');
  cvs.width = sizePx;
  cvs.height = sizePx;
  const ctx = cvs.getContext('2d');
  if (!ctx) return null;

  const img = ctx.createImageData(sizePx, sizePx);
  const data = img.data;
  const клеткаВПикселях = extent / sizePx;
  for (let py = 0; py < sizePx; py++) {
    const wz = originZ + py * клеткаВПикселях;
    const iz = fogCell(wz);
    for (let px = 0; px < sizePx; px++) {
      const wx = originX + px * клеткаВПикселях;
      const i = (py * sizePx + px) * 4;
      if (fogSeen(fogCell(wx), iz)) {
        data[i + 3] = 0;              // видели — карта видна как обычно
        continue;
      }
      data[i] = 0; data[i + 1] = 0; data[i + 2] = 0;
      data[i + 3] = 235;              // не были — чёрное
    }
  }
  ctx.putImageData(img, 0, 0);

  слой = cvs;
  слойOrigin = { x: originX, z: originZ };
  слойExtent = extent;
  слойPx = sizePx;
  флаги.слой = false;
  return cvs;
}

// ── Маска тумана для большой карты ────────────────────────────────────────

let мироваяМаска: HTMLCanvasElement | null = null;

/**
 * Маска на весь мир: по 4 пикселя на клетку.
 *
 * Большая карта показывает весь мир сразу, поэтому маска на всё здание памяти
 * строится один раз и потом дорисовывается по мере открытия. Пересобирать её
 * целиком на каждое движение нельзя: это миллион пикселей каждые несколько
 * секунд.
 */
export function worldFogMask(): HTMLCanvasElement | null {
  // Большая карта перерисовывается каждые полторы секунды, а память меняется
  // куда реже. Без этой проверки на каждый кадр обходились бы 39601 клетка и
  // тысячи прямоугольников, а память бы ещё и выглядела бы «моргающей».
  if (мироваяМаска && !флаги.маска) return мироваяМаска;

  const сторона = FOG_GRID * 4;
  if (!мироваяМаска) {
    мироваяМаска = document.createElement('canvas');
    мироваяМаска.width = сторона;
    мироваяМаска.height = сторона;
  }
  const ctx = мироваяМаска.getContext('2d');
  if (!ctx) return null;
  // Стартуем полностью чёрным: не был — значит чёрное.
  ctx.globalCompositeOperation = 'source-over';
  ctx.fillStyle = 'rgba(0, 0, 0, 0.92)';
  ctx.fillRect(0, 0, сторона, сторона);
  // Стираем чёрное там, где игрок был.
  ctx.globalCompositeOperation = 'destination-out';
  for (let iz = 0; iz < FOG_GRID; iz++) {
    let подряд = -1;
    for (let ix = 0; ix <= FOG_GRID; ix++) {
      const видна = ix < FOG_GRID && fogSeen(ix, iz);
      if (видна) {
        if (подряд < 0) подряд = ix;
        continue;
      }
      if (подряд >= 0) {
        ctx.clearRect(подряд * 4, iz * 4, (ix - подряд) * 4, 4);
        подряд = -1;
      }
    }
  }
  ctx.globalCompositeOperation = 'source-over';
  флаги.маска = false;
  return мироваяМаска;
}