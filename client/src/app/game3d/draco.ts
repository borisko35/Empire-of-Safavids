// ============================================================
// Один декодер Draco на весь клиент
// ============================================================
//
// ЗАЧЕМ. DRACOLoader — не тонкая обёртка над декодером: он поднимает
// РАБОЧИЕ ПОТОКИ (по умолчанию до четырёх) и держит их живыми, пока жив
// сам. До этой правки каждый загрузчик создавал свой DRACOLoader:
// `loadDecorModel` — на каждую модель декора (177 файлов), интерьеры — на
// трон, кафедру и камень, realRig и animalModels — по одному на модуль.
//
// ЧТО ИЗ ЭТОГО ВЫШЛО (§330). Платаны не появлялись в мире: ни кроны, ни
// ошибки. `декорВещь('platan-1')` вызывался, модель грузилась, а обещание
// не сбывалось никогда — ни успехом, ни `null`. Замер на стенде показал,
// что тот же файл обычным GLTFLoader разбирается и рисуется. Причина —
// потолок рабочих потоков: после пары сотен своих декодеров браузер
// перестаёт поднимать новые, и разбор Draco просто не начинается.
// Ошибки нет, потому что никто её не бросает: поток не создан — колбэк
// не позван.
//
// ПОЧЕМУ ОДИН НА ВСЕХ. DRACOLoader умеет параллельные разборы: у него
// внутри пул задач и очередь, а не «один файл за раз». Общий декодер —
// это не очередь из моделей, а те же четыре потока на весь клиент.
//
// ПОЧЕМУ НЕ ВЫГРУЖАЕМ. Декодер живёт столько же, сколько страница: мир
// грузится один раз за вход, а вход бывает повторным (смерть → выбор
// персонажа → снова мир). Выгружать и поднимать его заново — значит
// снова платить за инициализацию WASM на входе в мир.

import { DRACOLoader } from 'three/examples/jsm/loaders/DRACOLoader.js';

/** Где лежат decoder'ы (public/draco). */
const DRACO_BASE = '/game/draco/';

let общий: DRACOLoader | null = null;

/**
 * Декодер Draco на весь клиент. Создаётся при первом обращении.
 *
 * Возвращается один и тот же объект: загрузчики разных модулей делят его
 * пул потоков. Повторный `setDecoderPath` безвреден.
 */
export function декодерDraco(): DRACOLoader {
  if (!общий) {
    общий = new DRACOLoader();
    общий.setDecoderPath(DRACO_BASE);
  }
  return общий;
}
