// Пыльные вихри в пустыне (§257).
//
// ЧТО БЫЛО. Пустыня вокруг Исфахана — песок и ветер, и ничего, что шевелилось
// само по себе. Песчаная буря есть (погода), а вихрей нет: в мире, где ветер
// поднимает пыль, вихрь — самое естественное, что может случиться с песком.
//
// ЧТО ТЕПЕРЬ. Три вихря, которые бродят по песку рядом с игроком: столб из
// клубов, который поднимается, закручивается и медленно идёт по земле. Живёт
// вихрь полминуты, потом рассеивается и на его месте появляется новый —
// в другом месте.
import * as THREE from 'three';
import { createPuffs, type Puffs } from './puffs';
import { CITY } from './terrain';

/** Сколько вихрей в мире одновременно. */
const ВИХРЕЙ = 3;
/**
 * Радиус, в котором вихрь появляется у игрока, метры.
 *
 * БЫЛО 150–420: вихрь был далеко, и игрок его не видел вовсе — на кадре пусто.
 * Теперь 60–260: столб песка виден с дороги, но не мешает идти.
 */
const БЛИЗКО = 60;
const ДАЛЕКО = 260;
/** Сколько живёт вихрь, секунд. */
const ЖИЗНЬ = 26;

interface Вихрь {
  пыль: Puffs;
  x: number;
  z: number;
  vx: number;
  vz: number;
  угол: number;
  осталось: number;
  таймер: number;
  высота: number;
}

export interface DustDevilsHandle {
  update(dt: number, now: number, px: number, pz: number): void;
  dispose(): void;
}

export function createDustDevils(scene: THREE.Scene): DustDevilsHandle {
  const вихри: Вихрь[] = [];

  const новыйПыль = (): Puffs => createPuffs(scene, {
    количество: 24,
    // Песок в воздухе ТЕМНЕЕ песка на земле: он в тени самого столба. Светлый
    // клуб на светлом песке не читался вовсе — вихря не было видно.
    цвет: 0xac9c79,
    размер: 1.4,
    рост: 3.2,
    жизнь: 2.8,
    подъём: 1.9,
    разброс: 0.9,
    непрозрачность: 0.66,
    затухание: 1.4,
    вращение: 1.6,
  });

  const появиться = (px: number, pz: number): Вихрь => {
    // Вихрь появляется по песку, не на стене города и не в воде.
    const угол = Math.random() * Math.PI * 2;
    const дальность = БЛИЗКО + Math.random() * (ДАЛЕКО - БЛИЗКО);
    let x = px + Math.cos(угол) * дальность;
    let z = pz + Math.sin(угол) * дальность;
    // За стенами города вихря быть не должно: песок там мощёный, и вихрь
    // среди домов читается как дым из трубы.
    const отГорода = Math.hypot(x - CITY.x, z - CITY.z);
    if (отГорода < CITY.radius + 40) {
      const к = (CITY.radius + 40) / Math.max(отГорода, 1);
      x = CITY.x + (x - CITY.x) * к;
      z = CITY.z + (z - CITY.z) * к;
    }
    const курс = Math.random() * Math.PI * 2;
    return {
      пыль: новыйПыль(),
      x,
      z,
      vx: Math.cos(курс) * 1.6,
      vz: Math.sin(курс) * 1.6,
      угол: 0,
      осталось: ЖИЗНЬ,
      таймер: 0,
      высота: 0,
    };
  };

  for (let i = 0; i < ВИХРЕЙ; i++) вихри.push(появиться(CITY.x, CITY.z));

  function update(dt: number, _now: number, px: number, pz: number): void {
    for (const в of вихри) {
      в.осталось -= dt;
      в.высота = Math.min(1, (ЖИЗНЬ - в.осталось) / 6) * 7;
      // Вихрь идёт по песку и слегка поворачивает.
      в.x += в.vx * dt;
      в.z += в.vz * dt;
      в.угол += dt * 2.4;
      if (Math.hypot(в.x - px, в.z - pz) < 25 || Math.hypot(в.x - px, в.z - pz) > 420) {
        // Слишком близко (мешает идти) или слишком далеко (не видно) — вихрь
        // рассыпается и начинается новый, в другом месте.
        в.пыль.dispose();
        Object.assign(в, появиться(px, pz));
        continue;
      }
      // Клубы выходят из основания столба по кругу и поднимаются.
      в.таймер += dt;
      if (в.таймер >= 0.07) {
        в.таймер = 0;
        const радиус = 1.1 + в.высота * 0.18;
        const a = в.угол * 2.2;
        в.пыль.всплеск(
          в.x + Math.cos(a) * радиус,
          в.высота * 0.15 + Math.random() * 0.4,
          в.z + Math.sin(a) * радиус,
        );
      }
      в.пыль.update(dt);
    }
  }

  function dispose(): void {
    for (const в of вихри) в.пыль.dispose();
  }

  return { update, dispose };
}
