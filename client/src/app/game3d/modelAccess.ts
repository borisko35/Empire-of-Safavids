// библиотеки Adobe Mixamo. Условия Mixamo игры разрешают прямо, а раздачу
// исходных файлов — нет (разбор: THIRD_PARTY.md). Пока `/game/models/`
// отдавался кому угодно, любой мог скачать `walking.glb` отдельным файлом
// по прямому адресу — то есть ровно то, что условия запрещают, и без
// всякого входа.
//
// Теперь nginx перед отдачей файла спрашивает сервер «вошёл ли игрок»
// (auth_request на `/api/auth/gate`), а сервер отвечает по тому же токену,
// что и весь остальной API. Модуль здесь ровно для одной вещи: положить
// этот токен в запрос файла.
//
// ПОЧЕМУ ЗАГОЛОВОК, А НЕ ПЕЧЕНЬКА. Сессия живёт в localStorage под ключом
// `eos_token` и уходит на сервер заголовком `Authorization` — так её шлют
// api.ts и media.ts. Печенек у игры нет вовсе, и заводить их только ради
// моделей значило бы держать два разных понятия «вошёл».
//
// ПОЧЕМУ ЗАГОЛОВОК СТАВИТСЯ ПЕРЕД КАЖДОЙ ЗАГРУЗКОЙ, А НЕ ОДИН РАЗ.
// Загрузчики кешируются по модулю (realRig держит один общий на всю игру),
// а игрок может выйти и войти другим аккаунтом, не перезагружая страницу:
// logoutLocal() в main.ts именно так и делает. Загрузчик, у которого
// заголовок выставлен один раз при создании, остался бы с чужим токеном —
// и модели молча перестали бы грузиться у всех после смены аккаунта.
// Поэтому сВходом() зовётся ровно там, где начинается загрузка.
//
// ЕСЛИ ТОКЕНА НЕТ, ЗАГОЛОВКА ТОЖЕ НЕТ: сервер ответит 401, файла не будет,
// и вызывающие (у всех них есть откат на процедурный силуэт) нарисуют
// палочки. Так и должно быть: модели закрыты, а не «открыты, если не
// заметили».

import type { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';

/** Ключ токена в localStorage — тот же, что у api.ts и state.ts. */
const КЛЮЧ_ТОКЕНА = 'eos_token';

/** Заголовок запроса файла. Пустой объект — если игрок ещё не вошёл. */
export function заголовокВхода(): Record<string, string> {
  const token = localStorage.getItem(КЛЮЧ_ТОКЕНА) ?? '';
  return token ? { Authorization: `Bearer ${token}` } : {};
}

/**
 * Поставить загрузчику текущий заголовок входа и вернуть его же.
 *
 * Возвращается сам загрузчик, чтобы вызов читался одной строкой:
 * `сВходом(l).load(...)` — и чтобы не было способа поставить заголовок и
 * забыть про сам вызов.
 */
export function сВходом(загрузчик: GLTFLoader): GLTFLoader {
  загрузчик.setRequestHeader(заголовокВхода());
  return загрузчик;
}
