// Рябь от дождя в лужах (§285).
//
// ЧТО БЫЛО. Лужи на площади и в пригороде (§264, §269) стояли гладкими
// зеркалами: вода в луже никогда не двигалась. Дождь шёл, капли падали, земля
// темнела — а вода в луже оставалась мёртвой. По стоячей воде читается, что
// дождя нет.
//
// ЧТО ТЕПЕРЬ. В луже идут круги от капель: каждый круг расходится, слабеет и
// гаснет. Кругов много, и они идут непрерывно, пока дождь идёт, — вода
// выглядит живой.
//
// ПОЧЕМУ ПУЛ, А НЕ МЕШ НА КАЖДУЮ КАПЛЮ. Капли в дождь идут сотнями в секунду.
// Создавать и удалять меши на каждую каплю — значит мусорить в куче. Поэтому
// кольца берутся из пула: свободное кольцо просто переезжает под новую
// каплю.
import * as THREE from 'three';
import { лужиГорода } from './terrain';

export interface PuddleRipplesHandle {
  update(dt: number, rain: number, wet: number, px: number, pz: number): void;
  dispose(): void;
}

/** Сколько колец в пуле. */
const КОЛЕЦ = 56;
/** Как часто в луже появляется новый круг, секунды. */
const ТАКТ = 0.045;
/** Сколько живёт круг, секунды. */
const ЖИЗНЬ = 0.85;
/** Насколько круг вырастает, метры. */
const РОСТ = 1.15;

export function createPuddleRipples(scene: THREE.Scene): PuddleRipplesHandle {
  // Кольцо: тонкое, радиусом в единицу — размер задаётся масштабом.
  const геометрия = new THREE.RingGeometry(0.62, 1, 24);
  // Мягкий гребень: настоящий круг от капли не рисуется краской, а блестит
  // узкой полоской. Резкое кольцо выглядело бы нарисованным.
  const канва = document.createElement('canvas');
  канва.width = 64;
  канва.height = 64;
  const г = канва.getContext('2d');
  if (г) {
    // Градиент по радиусу. Ступени градиента — в долях его радиуса, а кольцо
    // в UV лежит между 0.62 и 1.0 (внутренний радиус кольца — 0.62 от
    // внешнего). Гребень должен приходиться на эту полосу.
    const градиент = г.createRadialGradient(32, 32, 1, 32, 32, 31);
    градиент.addColorStop(0, 'rgba(255,255,255,0)');
    градиент.addColorStop(0.6, 'rgba(255,255,255,0)');
    градиент.addColorStop(0.8, 'rgba(255,255,255,0.85)');
    градиент.addColorStop(0.91, 'rgba(255,255,255,0.35)');
    градиент.addColorStop(1, 'rgba(255,255,255,0)');
    г.fillStyle = градиент;
    г.fillRect(0, 0, 64, 64);
  }
  const текстура = new THREE.CanvasTexture(канва);
  текстура.colorSpace = THREE.SRGBColorSpace;
  const материал = new THREE.MeshBasicMaterial({
    map: текстура,
    color: 0xbdd2e0,
    transparent: true,
    opacity: 0,
    depthWrite: false,
    side: THREE.DoubleSide,
  });

  interface Кольцо {
    меш: THREE.Mesh;
    /** Сколько кольцу осталось жить, секунды. */
    осталось: number;
  }
  const кольца: Кольцо[] = [];
  for (let i = 0; i < КОЛЕЦ; i++) {
    const меш = new THREE.Mesh(геометрия, материал);
    меш.rotation.x = -Math.PI / 2;
    меш.visible = false;
    меш.renderOrder = 3;
    scene.add(меш);
    кольца.push({ меш, осталось: 0 });
  }

  let такт = 0;

  function update(dt: number, rain: number, wet: number, px: number, pz: number): void {
    // Круги идут, пока идёт дождь и лужи стоят. Без воды и без дождя колец
    // на площади не было бы видно, а лужи сухи — это другое.
    const идёт = rain > 0.05 && wet > 0.35 && лужиГорода.length > 0;

    if (идёт) {
      такт += dt;
      while (такт >= ТАКТ) {
        такт -= ТАКТ;
        // Свободное кольцо.
        const к = кольца.find((x) => x.осталось <= 0);
        if (!к) break;
        // Капля падает в лужу рядом с игроком: вдали от игрока её и не видно,
        // а лужи там всё равно есть.
        let лужа = лужиГорода[0];
        for (let попытка = 0; попытка < 5; попытка++) {
          const индекс = Math.floor(hashЛужи(попытка + 1, такт) * лужиГорода.length) % лужиГорода.length;
          лужа = лужиГорода[индекс];
          if (Math.hypot(лужа.x - px, лужа.z - pz) < 70) break;
        }
        // Круг появляется не в центре лужи, а в случайной точке внутри неё.
        const угол = hashЛужи(такт, лужа.x) * Math.PI * 2;
        const доля = hashЛужи(лужа.z, такт) * 0.7;
        const r = лужа.r * доля;
        к.меш.position.set(
          лужа.x + Math.cos(угол) * r,
          лужа.y + 0.012,
          лужа.z + Math.sin(угол) * r,
        );
        к.меш.scale.set(0.12, 0.12, 1);
        к.меш.visible = true;
        к.осталось = ЖИЗНЬ;
      }
    }

    // Круги расходятся и гаснут.
    for (const к of кольца) {
      if (к.осталось <= 0) continue;
      к.осталось -= dt;
      if (к.осталось <= 0) { к.меш.visible = false; continue; }
      const доля = 1 - к.осталось / ЖИЗНЬ;
      const размер = 0.12 + доля * РОСТ;
      к.меш.scale.set(размер, размер, 1);
    }
    // Прозрачность — общая для всех колец: они идут рядом, и разной прозрачности
    // у круга от капли нет.
    материал.opacity = идёт ? 0.34 * Math.min(1, rain) : 0;
  }

  function dispose(): void {
    геометрия.dispose();
    текстура.dispose();
    материал.dispose();
    for (const к of кольца) scene.remove(к.меш);
  }

  return { update, dispose };
}

/**
 * Псевдослучайное число по двум числам — без Math.random, чтобы мир собирался
 * одинаково при каждом запуске (правило детерминизма).
 */
function hashЛужи(a: number, b: number): number {
  const s = Math.sin(a * 127.1 + b * 311.7) * 43758.5453;
  return s - Math.floor(s);
}
