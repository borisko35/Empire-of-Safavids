/**
 * Потолок видимого размера спрайта.
 *
 * ЗАЧЕМ ФАЙЛ. У THREE.Sprite по умолчанию включён sizeAttenuation, и такой
 * спрайт не просто удаляется с расстоянием — он РАСТУТ при приближении к
 * камере, без верхней границы. Надписи в игре сделаны спрайтами мирового
 * размера (имя NPC, знак «!», метка путника, реплика горожанина), и ни у
 * одной из них не было ограничения. Стоило подойти вплотную — и надпись
 * занимала треть экрана поверх мира. Владелец прислал такой скриншот:
 * «Стражник Фарид» во всю ширину, поверх стены.
 *
 * ПОЧЕМУ НЕ «ПОПИКСЕЛИ НА КАЖДЫЙ СПРАЙТ СВОЙ ПОРОГ». Потолок считается не
 * в метрах, а в кажущемся размере: у спрайта размера h на расстоянии d
 * видимая величина равна h / d («сколько он занял бы в мире, будь он в
 * метре от камеры»). Один и тот же потолок MAX_APPARENT даёт для каждой
 * надписи СВОЙ порог в метрах, и пороги эти нельзя перепутать между собой.
 *
 * При MAX_APPARENT = 0.25 получается:
 *   имя NPC 0.78 м → гаснет ближе 3.1 м
 *   знак «!» 0.85 м → гаснет ближе 3.4 м
 *   реплика 1.0 м  → гаснет ближе 4.0 м
 *   метка 0.5 м    → гаснет ближе 2.0 м
 */
export const MAX_APPARENT = 0.25;

/**
 * Ближе какого расстояния спрайт мирового размера `worldSize` гаснет.
 * @param worldSize высота спрайта в мировых единицах (как задана в scale)
 */
export function minDistance(worldSize: number): number {
  return worldSize / MAX_APPARENT;
}

/**
 * Виден ли спрайт мирового размера `worldSize` на расстоянии `d`.
 * Чистая функция: проверяется в тестах без сцены и без three.
 */
export function spriteVisible(worldSize: number, d: number): boolean {
  return d >= minDistance(worldSize);
}