// Птицы над пустыней и городом (§259).
//
// ЧТО БЫЛО. Небо было пустым: в мире, где есть верблюды, коровы, пыльные
// вихри и ветер, который качает зелень, не летает ни одна птица. Небо
// читалось как фон, а не как воздух.
//
// ЧТО ТЕПЕРЬ. Стая: вожатый с двенадцатью птицами по бокам и позади. Стая
// облетает игрока по широкой дуге, крылья бьют вразнобой (у каждой птицы своя
// фаза), и птицы иногда проходят совсем близко над головой.
//
// ТЕНИ СТАИ (§284). Птицы летели, а под ними земля была чистой: стая читалась
// только в небе, а на мостовой её не было видно. Теперь под птицей тянется
// тень — она сдвинута от птицы в сторону, противоположную солнцу, и в полдень
// короткая, а на закате длинная.
import * as THREE from 'three';
import { LAKE, CITY, groundHeight, hash2 } from './terrain';

export interface BirdsHandle {
  update(dt: number, now: number, px: number, pz: number, ночь?: number, солнце?: THREE.Vector3): void;
  dispose(): void;
}

/** Сколько птиц в стае. */
const ПТИЦ = 13;
/**
 * Размах крыльев, метры. Крупная птица: вдалеке обычная ворона — точка, а на
 * кадре такая стая не читалась вовсе.
 */
const РАЗМАХ = 2;
/** Высота полёта над землёй, метры. */
const ВЫСОТА = 30;
/** Уровень крыш города: сюда стая опускается над городом (§279). */
const ВЫСОТА_КРОВ = 9;
/** Радиус облёта вокруг игрока, метры. */
const РАДИУС = 78;
/** Радиус тени птицы у земли, метры (§284). */
const ТЕНЬ_РАДИУС = 1.4;
/**
 * Как часто тень примеряется к земле (§284).
 *
 * Земля меряется дорого: высота рельефа считается через шум, и тринадцать
 * птиц, меряющих землю каждый кадр, съели бы кадр целиком. Поэтому высота
 * снимается раз в несколько кадров и сглаживается — тень от этого не
 * дёргается, а кадр стоит копейки.
 */
const ТЕНЬ_ШАГ = 8;

interface Птица {
  группа: THREE.Group;
  крылоЛ: THREE.Mesh;
  крылоП: THREE.Mesh;
  /** Смещение в строю: назад и в стороны. */
  dx: number;
  dz: number;
  /** Своя фаза взмахов. */
  фаза: number;
  /** Тень птицы на земле (§284). */
  тень: THREE.Mesh;
  /** Высота земли под тенью — меряется не каждый кадр. */
  теньВысота: number;
  /** Сглаженная высота тени: к ней тень подтягивается. */
  теньY: number;
}

/** Мягкое пятно: тень птицы не бывает резкой (§284). */
function теньТекстура(): THREE.Texture {
  const канва = document.createElement('canvas');
  канва.width = 64;
  канва.height = 64;
  const г = канва.getContext('2d');
  if (г) {
    const градиент = г.createRadialGradient(32, 32, 1, 32, 32, 31);
    градиент.addColorStop(0, 'rgba(0,0,0,0.85)');
    градиент.addColorStop(0.55, 'rgba(0,0,0,0.4)');
    градиент.addColorStop(1, 'rgba(0,0,0,0)');
    г.fillStyle = градиент;
    г.fillRect(0, 0, 64, 64);
  }
  const текстура = new THREE.CanvasTexture(канва);
  текстура.colorSpace = THREE.SRGBColorSpace;
  return текстура;
}

export function createBirds(scene: THREE.Scene): BirdsHandle {
  const материал = new THREE.MeshStandardMaterial({
    color: 0x2e2a26,
    roughness: 0.9,
    side: THREE.DoubleSide,
  });
  const группаСтаи = new THREE.Group();
  scene.add(группаСтаи);

  // Тени птиц (§284): у каждой птицы своё мягкое пятно на земле.
  const теньМатериал = new THREE.MeshBasicMaterial({
    map: теньТекстура(),
    transparent: true,
    depthWrite: false,
    opacity: 0,
    color: 0x241c14,
  });
  const теньГео = new THREE.PlaneGeometry(1, 1);

  const птицы: Птица[] = [];
  for (let i = 0; i < ПТИЦ; i++) {
    const группа = new THREE.Group();
    const тело = new THREE.Mesh(new THREE.BoxGeometry(0.1, 0.08, 0.34), материал);
    группа.add(тело);
    // Крылья: тонкие пластины, поставленные под углом, — силуэт «галочки».
    const крылоЛ = new THREE.Mesh(new THREE.BoxGeometry(РАЗМАХ * 0.5, 0.02, 0.16), материал);
    крылоЛ.position.set(-РАЗМАХ * 0.25, 0.02, 0);
    крылоЛ.rotation.z = 0.22;
    const крылоП = new THREE.Mesh(new THREE.BoxGeometry(РАЗМАХ * 0.5, 0.02, 0.16), материал);
    крылоП.position.set(РАЗМАХ * 0.25, 0.02, 0);
    крылоП.rotation.z = -0.22;
    группа.add(крылоЛ, крылоП);
    // Тень под птицей (§284): лежит на земле, развёрнута по ветру полёта.
    const тень = new THREE.Mesh(теньГео, теньМатериал);
    тень.rotation.order = 'YXZ';
    тень.visible = false;
    scene.add(тень);
    // Строй: клином назад от вожатого.
    const ряд = i === 0 ? 0 : Math.ceil(i / 2);
    const сторона = i % 2 === 0 ? -1 : 1;
    const dx = i === 0 ? 0 : сторона * ряд * 1.5;
    const dz = i === 0 ? 0 : -ряд * 1.9;
    группаСтаи.add(группа);
    // Фаза взмахов — по хэшу, а не по случайному числу: мир должен собираться
    // одинаково при каждом запуске (§284, правка детерминизма §259).
    птицы.push({ группа, крылоЛ, крылоП, dx, dz, фаза: hash2(i, 17) * 6.28, тень, теньВысота: 0, теньY: 0 });
  }

  // Центр стаи ходит по кругу вокруг игрока и медленно поворачивает.
  let угол = 0;
  let направление = 1;
  let центрX = 0;
  let центрZ = 0;
  let начато = false;
  // На какой высоте летит стая сейчас (§273): над водой она садится.
  let высота = ВЫСОТА;

  function update(dt: number, now: number, px: number, pz: number, ночь = 0, солнце?: THREE.Vector3): void {
    if (!начато) {
      центрX = px + РАДИУС;
      центрZ = pz;
      начато = true;
    }
    // Стая облетает игрока и не подходит слишком близко.
    // Радиус дышит: то издали, то совсем близко над головой — стая живая.
    угол += dt * 0.085 * направление;
    const радиус = РАДИУС + Math.sin(угол * 0.7) * 28;
    const цельX = px + Math.cos(угол) * радиус;
    const цельZ = pz + Math.sin(угол) * радиус;
    центрX += (цельX - центрX) * Math.min(1, dt * 0.9);
    центрZ += (цельZ - центрZ) * Math.min(1, dt * 0.9);
    // Угол поворота стаи: туда, куда она летит.
    const курс = Math.atan2(центрZ - pz, центрX - px) + Math.PI / 2;
    const взмах = Math.sin(now * 2.4) * 0.5;

    // ПТИЦЫ САДЯТСЯ НА ВОДУ (§273). Пока стая летала всегда в воздухе, озеро
    // у порта было пустым: вода без птиц читается как зеркало, а не как место,
    // где что-то живёт. Когда стая подлетает к озеру, она опускается на воду,
    // сидит какое-то время и снова взлетает.
    const уОзера = Math.hypot(центрX - LAKE.x, центрZ - LAKE.z) < 150;
    // ПТИЦЫ СЕДАЮТ НА КРЫШИ (§279). Стая облетает игрока, и над городом
    // часть её опускается до уровня крыш: с высоты птица кажется точкой, а
    // сидящая на куполе — деталью города.
    const надГородом = Math.hypot(центрX - CITY.x, центрZ - CITY.z) < 95;
    const цельY = уОзера ? LAKE.level + 0.22 : надГородом ? ВЫСОТА_КРОВ : ВЫСОТА;
    высота += (цельY - высота) * Math.min(1, dt * 0.5);
    // 0 — летит, 1 — сидит (на воде или на крыше).
    const сидит = Math.max(0, Math.min(1, (ВЫСОТА - высота) / 8));

    // Тени стаи на земле (§284).
    //
    // Тень есть только при солнце: ночью птиц над землёй не видно, и тень
    // была бы пятном без причины. Солнце низко — тень длинная и слабая, в
    // полдень — короткая и плотная.
    const день = Math.max(0, Math.min(1, 1 - ночь));
    const солнцеY = солнце ? Math.max(0.12, солнце.y) : 1;
    const солнцеX = солнце ? солнце.x : 0;
    const солнцеZ = солнце ? солнце.z : 0;
    теньМатериал.opacity = день * (0.16 + 0.46 * Math.min(1, солнцеY));
    let кадр = 0;

    for (const п of птицы) {
      // Птица стоит в строю: смещение поворачивается вместе со стаей.
      const поворот = курс;
      const cs = Math.cos(поворот);
      const sn = Math.sin(поворот);
      const wx = центрX + п.dx * cs - п.dz * sn;
      const wz = центрZ + п.dx * sn + п.dz * cs;
      const wy = высота + Math.sin(now * 0.7 + п.фаза) * 2.2 * (1 - сидит) + (п.dz < 0 ? 1.5 : 0);
      п.группа.position.set(wx, wy, wz);
      п.группа.rotation.y = -курс + Math.PI / 2;
      // Крылья бьют вразнобой: у каждой птицы своя фаза и свой размах. А когда
      // птица сидит на воде — крылья сложены, и бой затихает.
      const бой = (Math.sin(now * 7.5 + п.фаза) * 0.55 + взмах) * (1 - сидит);
      п.крылоЛ.rotation.z = 0.22 - бой;
      п.крылоП.rotation.z = -0.22 + бой;

      // Тень под птицей (§284). Сдвинута от птицы в сторону, противоположную
      // солнцу: чем ниже солнце, тем дальше тень уходит от самой птицы.
      const надЗемлёй = Math.max(0, wy - п.теньВысота);
      const отступ = Math.min(80, надЗемлёй / солнцеY);
      const sx = wx - солнцеX * отступ;
      const sz = wz - солнцеZ * отступ;
      // Земля меряется не каждый кадр (дорого), а сглаживается — тень не
      // дёргается на неровной земле.
      кадр++;
      if (кадр % ТЕНЬ_ШАГ === 0) п.теньВысота = groundHeight(sx, sz);
      п.теньY += (п.теньВысота - п.теньY) * Math.min(1, dt * 4);
      п.тень.position.set(sx, п.теньY + 0.05, sz);
      // Тень шире, чем птица: крылья дают вытянутое пятно поперёк полёта.
      // С высотой тень не растёт много — расплывается, а не увеличивается.
      const радиус = ТЕНЬ_РАДИУС * (1 + надЗемлёй * 0.012);
      п.тень.scale.set(радиус * 2.3, радиус * 1.1, 1);
      п.тень.rotation.set(-Math.PI / 2, -курс + Math.PI / 2, 0);
      // Сидящей птице тень на земле не нужна: она на воде или на крыше.
      п.тень.visible = теньМатериал.opacity > 0.01 && надЗемлёй > 2 && сидит < 0.5;
    }
  }

  function dispose(): void {
    материал.dispose();
    теньМатериал.dispose();
    теньГео.dispose();
    for (const п of птицы) scene.remove(п.тень);
    группаСтаи.traverse(o => {
      if (o instanceof THREE.Mesh) o.geometry.dispose();
    });
    scene.remove(группаСтаи);
  }

  return { update, dispose };
}
