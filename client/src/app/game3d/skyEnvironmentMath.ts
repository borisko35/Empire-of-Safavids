/** Виды погоды. Определение живёт здесь же — см. объяснение выше. */
export type WeatherKind = 'clear' | 'cloudy' | 'rain' | 'storm' | 'fog' | 'sandstorm' | 'snow' | 'wind';
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ РЕНДЕРИНГА. Проверять числа нужно числами: читаемость
// силуэтов и отсутствие пересветов — это про яркости в карте, а не про вызовы
// WebGL. Клиент не имеет своего тест-раннера, поэтому проверить этот модуль
// набором нельзя, а пробник на `tsx` — можно. Значит всё, что считается,
// живёт здесь, без единого импорта three, а `skyEnvironment.ts` только
// раскладывает результат по текстурам.
//
// ЧТО ЭТО ТАКОЕ. Эквиректангулярная HDR-карта в линейном свете: значения
// больше единицы (солнце), рядом с единицей (небо) и меньше (песок в тени).
// Дальше её крутит PMREMGenerator — и свет мира начинает считаться от неба, а
// не от чисел, написанных руками в кадре.
//
// ПОЧЕМУ НЕ ФАЙЛ. HDRI/EXR в проекте нет ни одного, и в `.gitignore` сказано
// про бинарные ассеты прямо: «самих файлов нет в проекте». Окружение,
// собранное из данных, работает везде и не занимает в репозитории ни байта.

/** Стиль неба и света. Один стиль на игру, но структура — на все регионы. */
export interface SkyStyle {
  /** Название стиля — попадёт в лог и в отчёт стенда. */
  readonly name: string;
  /** Цвет зенита (в зените, вверх). Линейный свет, 0..1+. */
  readonly zenith: readonly [number, number, number];
  /** Цвет горизонта. */
  readonly horizon: readonly [number, number, number];
  /** Цвет песка: то, что светит снизу. */
  readonly ground: readonly [number, number, number];
  /**
   * Подсвет неба вокруг солнца, в единицах яркости неба.
   *
   * ОТДЕЛЬНО от ядра солнца — это и была ошибка. Одно число на «насколько
   * ярко солнце» означало, что и ядро, и подсвет неба получают одну и ту же
   * амплитуду: ядру это нужно, подсвету — нет, и подсвет уводил полдень в
   * 3.6 единицы при тонмаппинге ACES, то есть в белое пятно.
   */
  readonly sunGlow: number;
  /** Яркость ядра солнца. Сотни единиц — солнце и должно быть слепящим. */
  readonly sunCore: number;
  /** Подсвет неба вокруг луны. */
  readonly moonGlow: number;
  /** Яркость ядра луны. */
  readonly moonCore: number;
  /** Насыщенность солнечного пятна (тёплее — меньше). */
  readonly sunTint: readonly [number, number, number];
  /** Насыщенность лунного пятна. */
  readonly moonTint: readonly [number, number, number];
  /** Цвет пасмурного неба: к нему всё сводится в дождь и бурю. */
  readonly overcastTint: readonly [number, number, number];
  /** Насколько сильно пыль поднимает горизонт вверх, 0..1. */
  readonly haze: number;
}

