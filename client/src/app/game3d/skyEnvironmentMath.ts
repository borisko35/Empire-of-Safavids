/** Параметры момента: где солнце, какая погода, какая ночь. */
export interface SkyState {
  /** Направление на солнце, нормализованное. */
  readonly sun: readonly [number, number, number];
  /** Направление на луну — противоположное солнцу. */
  readonly moon: readonly [number, number, number];
  /** Высота солнца: >0 днём. Дублирует sun[1], но читается прямо. */
  readonly sunHeight: number;
  /** 0 — день, 1 — глухая ночь. */
  readonly night: number;
  /** 0 — ясно, 1 — плотная облачность. */
  readonly overcast: number;
  /** Текущая погода (rain/storm/snow/fog/...). Необязательно: старые вызовы
   *  могут его не передавать, и всё работает как раньше. */
  readonly weather?: WeatherKind;
}

export interface EquirectMap {
  readonly width: number;
  readonly height: number;
  /** RGB, линейный свет, значения больше 1 — это HDR. */
  readonly data: Float32Array;
}

const DEFAULT_WIDTH = 256;
const DEFAULT_HEIGHT = 128;

/**
 * Величина дизеринга в линейном свете.
 *
 * Меньше шага квантования: карта линейная, экран восьмибитный, и без помехи
 * плавный градиент в узком диапазоне после ACES превращается в лесенку.
 * Помеха обязана быть постоянной — см. комментарий у пикселя.
 */
const ДИЗЕРИНГ = 0.005;

const clamp01 = (x: number): number => (x < 0 ? 0 : x > 1 ? 1 : x);
const smoothstep = (a: number, b: number, x: number): number => {
  const t = clamp01((x - a) / (b - a || 1e-6));
  return t * t * (3 - 2 * t);
};

/**
 * Собрать эквиректангулярную карту неба.
 *
 * Раскладка: u — азимут (0…1 на полный оборот), v — высота, сверху вниз.
 * Половина снизу — земля, и она не чёрная: на неё светит небо, и именно этот
 * отсвет снизу держит силуэты читаемыми.
 */
export function buildEquirect(
  style: SkyStyle,
  state: SkyState,
  width = DEFAULT_WIDTH,
  height = DEFAULT_HEIGHT,
): EquirectMap {
  const data = new Float32Array(width * height * 3);
  const [zx, zy, zz] = style.zenith;
  const [hx, hy, hz] = style.horizon;
  const [gx, gy, gz] = style.ground;
  const [sx, sy, sz] = style.sunTint;
  const [mx, my, mz] = style.moonTint;
  const [ox, oy, oz] = style.overcastTint;
  const [sunX, sunY, sunZ] = state.sun;
  const [moonX, moonY, moonZ] = state.moon;

  // Ночью небо не просто темнее: оно холоднее. Тёплое ночное небо читается
  // как «свет включили», а не как небо.
  const ночнойСдвиг = state.night;
  const зенит: [number, number, number] = [
    zx * (1 - ночнойСдвиг * 0.72) + 0.008 * ночнойСдвиг,
    zy * (1 - ночнойСдвиг * 0.80) + 0.012 * ночнойСдвиг,
    zz * (1 - ночнойСдвиг * 0.55) + 0.030 * ночнойСдвиг,
  ];
  const горизонт: [number, number, number] = [
    hx * (1 - ночнойСдвиг * 0.86) + 0.010 * ночнойСдвиг,
    hy * (1 - ночнойСдвиг * 0.88) + 0.014 * ночнойСдвиг,
    hz * (1 - ночнойСдвиг * 0.78) + 0.030 * ночнойСдвиг,
  ];
  const земля: [number, number, number] = [
    gx * (1 - ночнойСдвиг * 0.88) + 0.006 * ночнойСдвиг,
    gy * (1 - ночнойСдвиг * 0.90) + 0.007 * ночнойСдвиг,
    gz * (1 - ночнойСдвиг * 0.84) + 0.014 * ночнойСдвиг,
  ];

  const пасмурность = clamp01(state.overcast);
  // Солнце под горизонтом — пятна быть не должно, иначе ночью небо светится
  // там, где солнца нет.
  const солнцеЖивёт = state.sunHeight > -0.12 ? 1 - пасмурность * 0.92 : 0;
  const лунаЖивёт = state.moon[1] > -0.1 ? (1 - пасмурность * 0.9) * 0.9 : 0;

  for (let y = 0; y < height; y++) {
    // v сверху вниз: 0 — зенит, 1 — надир.
    const theta = (0.5 - y / (height - 1)) * Math.PI; // +π/2 сверху
    const sinT = Math.sin(theta);
    const cosT = Math.cos(theta);
    for (let x = 0; x < width; x++) {
      const phi = (x / width - 0.5) * Math.PI * 2;
      const dx = cosT * Math.sin(phi);
      const dz = cosT * Math.cos(phi);
      const dy = sinT;

      let r: number;
      let g: number;
      let b: number;

      // Стык неба и земли. Раньше цвет прыгал здесь с горизонта на песок, и
      // после тонмаппинга это читалось как проведённая черта поперёк неба.
      // В переходной зоне оба цвета смешиваются, и границы не видно.
      const ШИРИНА_СТЫКА = 0.10;
      const вСтыке = 1 - smoothstep(0, ШИРИНА_СТЫКА, Math.abs(dy));
      let земляR = 0, земляG = 0, земляB = 0;

      if (dy >= 0) {
        // Небо. Подъём к зениту — плавный, и горизонт остаётся светлее
        // зенита: так оно и выглядит над пустыней.
        const t = smoothstep(0, 0.55 + style.haze, dy);
        r = горизонт[0] + (зенит[0] - горизонт[0]) * t;
        g = горизонт[1] + (зенит[1] - горизонт[1]) * t;
        b = горизонт[2] + (зенит[2] - горизонт[2]) * t;
      } else {
        // Земля. У самого горизонта светлее: песок ловит небо.
        const под = -dy;
        const отсвет = 0.45 + 0.55 * (1 - smoothstep(0, 0.5, под));
        r = земля[0] * отсвет;
        g = земля[1] * отсвет;
        b = земля[2] * отсвет;
      }

      // Пыль у горизонта: поднимает яркость и размывает границу неба и земли.
      if (style.haze > 0) {
        const близко = 1 - smoothstep(0, 0.28, Math.abs(dy));
        const пыль = близко * style.haze * 0.35;
        r += (горизонт[0] - r) * пыль;
        g += (горизонт[1] - g) * пыль;
        b += (горизонт[2] - b) * пыль;
      }

      // Стык: смешивание неба с землёй в узкой зоне вокруг горизонта.
      if (вСтыке > 0) {
        const под = Math.max(0, -dy);
        const отсвет = 0.45 + 0.55 * (1 - smoothstep(0, 0.5, под));
        земляR = земля[0] * отсвет;
        земляG = земля[1] * отсвет;
        земляB = земля[2] * отсвет;
        r += (земляR - r) * вСтыке;
        g += (земляG - g) * вСтыке;
        b += (земляB - b) * вСтыке;
      }

      if (солнцеЖивёт > 0) {
        const d = dx * sunX + dy * sunY + dz * sunZ;
        if (d > 0) {
          // Два лепестка: широкий даёт мягкий подсвет неба, узкий — яркое
          // ядро. Один лепесток даёт либо плоское небо, либо слепящее пятно.
          const подсвет = Math.pow(d, 10) * style.sunGlow * солнцеЖивёт;
          const ядро = Math.pow(d, 900) * style.sunCore * солнцеЖивёт;
          r += sx * (подсвет + ядро);
          g += sy * (подсвет + ядро);
          b += sz * (подсвет + ядро);
        }
      }

      if (лунаЖивёт > 0) {
        const d = dx * moonX + dy * moonY + dz * moonZ;
        if (d > 0) {
          const подсвет = Math.pow(d, 60) * style.moonGlow * лунаЖивёт;
          const ядро = Math.pow(d, 700) * style.moonCore * лунаЖивёт;
          r += mx * (подсвет + ядро);
          g += my * (подсвет + ядро);
          b += mz * (подсвет + ядро);
        }
      }

      // Звёзды на ночном небе: 슬abeе точки, видны только когда солнце ниже горизонта
      const звёздыЖивут = state.sunHeight < -0.05 ? 1 - пасмурность * 0.9 : 0;
      if (звёздыЖивут > 0) {
        // Две звёздные полосы: Млечный Путь и разрозненные точки
        const звёздныйШум = Math.sin(x * 137) * Math.cos(y * 97) * 0.5 + 0.5;
        const звёзды = звёздныйШум * звёздныйШум * звёздныйШум; // контрастнее
        if (звёзды > 0.86) {
          const яркость = (звёзды - 0.86) / 0.14 * звёздыЖивут * 0.06;
          r += яркость;
          g += яркость * 0.95;
          b += яркость * 1.05;
        }
      }

      if (пасмурность > 0) {
        const k = пасмурность * 0.75;
        r += (ox - r) * k;
        g += (oy - g) * k;
        b += (oz - b) * k;
      }

      // Дизеринг против полос. Помеха детерминированная: по координатам
      // пикселя, а не случайная. Случайная менялась бы при каждой пересборке
      // карты, и на небе мерцало бы — хуже, чем полосы.
      //
      // Величина меньше шага квантования в линейном свете, поэтому на освещение
      // не влияет: пробник печатает те же числа и остаётся зелёным.
      const шум = (((x * 73856093) ^ (y * 19349663)) & 1023) / 1023 - 0.5;
      const помеха = шум * ДИЗЕРИНГ;

      const i = (y * width + x) * 3;
      data[i] = r + помеха;
      data[i + 1] = g + помеха;
      data[i + 2] = b + помеха;
    }
  }
  return { width, height, data };
}

/**
 * Упаковка карты в RGBA для `THREE.DataTexture`.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ И ПОЧЕМУ СТРОКИ ПЕРЕВЁРНУТЫ.
 *
 * `buildEquirect` пишет карту сверху вниз: строка 0 — зенит, последняя —
 * надир. Так её читает человек и так её считает `equirectStats`.
 *
 * Но видеокарта читает эквиректангулярную текстуру иначе. Three.js берёт
 * направление и считает `v = 0.5 + asin(y) / π`: вверх (y = 1) — это v = 1,
 * вниз (y = −1) — это v = 0. У `DataTexture` `flipY` не применяется (это не
 * картинка из файла), поэтому v = 0 — это ПЕРВАЯ строка массива. Значит
 * карту нужно отдать перевёрнутой: строка 0 данных — надир, последняя —
 * зенит.
 *
 * ЧТО БЫЛО СЛОМАНО (§221). Функция раньше копировала строки как есть, и
 * небо рисовалось вверх ногами: в кадре над головой стояла «земля» карты —
 * ровное тёплое полотно без градиента, а свет неба (PMREM) приходил снизу,
 * от песка. Полдень выглядел как пасмурный вечер, и ни один цвет неба не
 * доходил до экрана.
 *
 * Проверяется числами: `skyEnvironment.test.ts` строит карту 2×2 с синим
 * верхом и коричневым низом и требует, чтобы в RGBA первой шла коричневая
 * строка.
 */
export function equirectToRgba(map: EquirectMap): Float32Array {
  const { data, width, height } = map;
  const out = new Float32Array(width * height * 4);
  const строка = width * 3;
  for (let y = 0; y < height; y++) {
    // y — строка карты (0 = зенит), а в текстуре ей достаётся строка
    // height − 1 − y (0 = надир).
    const отсюда = y * строка;
    const туда = (height - 1 - y) * width * 4;
    for (let x = 0; x < width; x++) {
      const i = отсюда + x * 3;
      const j = туда + x * 4;
      out[j] = data[i];
      out[j + 1] = data[i + 1];
      out[j + 2] = data[i + 2];
      out[j + 3] = 1;
    }
  }
  return out;
}

/** Сводка по карте — для проверок и для отчёта стенда. */
export interface EquirectStats {
  /** Средняя яркость верхней полусферы (небо). */
  sky: number;
  /** Средняя яркость нижней полусферы (песок). */
  ground: number;
  /** Максимум — это солнечное ядро. */
  peak: number;
  /** 99.5-й процентиль: «небо без солнца», то есть кадр без пересвета. */
  skyHigh: number;
  /** Насколько небо темнее максимума: солнце осталось пятном, а не заливкой. */
  peakRatio: number;
}

export function equirectStats(map: EquirectMap): EquirectStats {
  let sumSky = 0;
  let nSky = 0;
  let sumGround = 0;
  let nGround = 0;
  let peak = 0;
  const luminances: number[] = [];

  for (let y = 0; y < map.height; y++) {
    const isSky = y < map.height / 2;
    for (let x = 0; x < map.width; x++) {
      const i = (y * map.width + x) * 3;
      const lum = 0.2126 * map.data[i] + 0.7152 * map.data[i + 1] + 0.0722 * map.data[i + 2];
      if (lum > peak) peak = lum;
      luminances.push(lum);
      if (isSky) { sumSky += lum; nSky++; } else { sumGround += lum; nGround++; }
    }
  }

  luminances.sort((a, b) => a - b);
  const p = (q: number): number => luminances[Math.min(luminances.length - 1, Math.floor(luminances.length * q))] ?? 0;

  const sky = sumSky / Math.max(1, nSky);
  const ground = sumGround / Math.max(1, nGround);
  const skyHigh = p(0.995);
  return { sky, ground, peak, skyHigh, peakRatio: peak / Math.max(1e-6, skyHigh) };
}