//
// ЧТО ЗДЕСЬ НЕ РЕШАЕТСЯ. Почему именно эти четыре здания. Здание выбрано по смыслу: дом
// письма — медресе, виночервей — корчма, небо и хлеб — обсерватория, люди — аукционный дом.
// Это моё решение, а не измерение; владелец может переставить.
//
// ГДЕ ВИСЯТ. Только на городских домах: их строит один код (buildTownBuildings), и положение
// стены известно точно. У караван-сарая, крепости и мечети экстерьеры строятся каждый
// отдельно, и координаты их стен надо сначала измерить.

import * as THREE from 'three';

export interface Inscription {
  /** Короткое имя для проверок и отладки. Латиницей: так его ищут в коде. */
  id: string;
  /** Здание, у двери которого стоит стела. */
  buildingId: string;
  /** Строки надписи, по одной на бейт. Персидский, без огласовки. */
  lines: string[];
  /** Поэт и произведение латиницей. Не украшение: проверка требует это поле, чтобы
   *  текст не появился в мире без указания, откуда он. */
  source: string;
  /** Перевод строк латиницей, по одной на строку. Нужен не для красоты: если на
   *  машине игрока нет гарнитуры с персидскими буквами, браузер нарисует вместо
   *  букв пустые прямоугольники, и каменная плита окажется без надписи. Тогда
   *  вместо персидского рисуется этот перевод. Пустой плиты быть не должно. */
  translit: string[];
}

