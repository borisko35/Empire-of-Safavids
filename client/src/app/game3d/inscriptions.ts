// Шрифт. Персидский требует арабской гарнитуры: если её нет, браузер нарисует
// пустые прямоугольники, и это будет выглядеть как поломка. Поэтому перечисляем
// четыре распространённые гарнитуры и только в самом конце - generic
// sans-serif, который точно есть, но персидские буквы в нём есть не везде.
const ГАРНИТУРЫ = '"Noto Naskh Arabic", "Amiri", "Scheherazade New", "Segoe UI", Tahoma, sans-serif';

/** Надпись здания, если оно есть в списке. */
export function inscriptionFor(buildingId: string): Inscription | undefined {
  return INSCRIPTIONS.find((i) => i.buildingId === buildingId);
}

// ── Геометрия стелы ────────────────────────────────────────────
//
// Всё в локальных координатах группы города (buildTownBuildings): стены дома
// шириной 8 и глубиной 6, то есть фасад лежит на z = +3.
//
// СТЕЛА ПОСТАВЛЕНА ПОДОКОННИКОМ. Окно слева от двери занимает локальные
// y от 2.0 до 3.2. Стела ниже: её верх на отметке 1.9, то есть на 0.1 ниже
// подоконника. Ставить выше нельзя - стела закрыла бы окно, и это видно с улицы.
//
// ШИРИНА ОТ ДВЕРИ. Дверь шириной 2.2 занимает x от -1.1 до 1.1. Стела шириной 1.1
// стоит по центру x = -2.9, то есть занимает от -3.45 до -2.35, и до края двери
// не достаёт. Окно при этом закрывает: его x от -3.6 до -2.2, но стела ниже
// подоконника, поэтому перекрытия в проекции нет.

export const STELE = {
  /** Высота ствола над землёй. Верх на 1.9 - ниже подоконника 2.0. */
  height: 1.9,
  /** Ширина ствола. */
  width: 1.1,
  /** Толщина ствола: стела каменная, не фанерка. */
  depth: 0.24,
  /** Центр ствола по высоте, то есть половина высоты. */
  centerY: 0.95,
  /** Положение стелы у фасада. x = -2.9 - под окном и левее двери. */
  offsetX: -2.9,
  offsetY: 0,
  /** Отступ от стены. Фасад на z = +3, стела чуть впереди, чтобы читалась. */
  offsetZ: 3.3,
  /** Ширина полосы с надписью на лицевой стороне. */
  faceWidth: 0.9,
  /** Высота полосы с надписью. */
  faceHeight: 1.5,
} as const;

/**
 * Холст с резьбой по камню.
 *
 * Буквы не нарисованы, а вырезаны: под ними тень, иначе надпись читается как
 * надпись, а как камень - нет. Поэтому рисуем тёмные буквы и тут же под ними
 * светлую подложку со смещением вниз на два пикселя: тень от нижнего края
 * резьбы и есть весь эффект.
 */
export function inscriptionFace(ins: Inscription): THREE.Mesh {
  const ШИР = 512;
  const ВЫС = 850;
  const c = document.createElement('canvas');
  c.width = ШИР;
  c.height = ВЫС;
  const g = c.getContext('2d')!;

  // Камень: тёплый известняк, чуть темнее стены дома, чтобы стела читалась
  // отдельным предметом, а не частью фасада.
  g.fillStyle = '#b8a184';
  g.fillRect(0, 0, ШИР, ВЫС);

  // Ржаные пятна по всей плоскости: стела стоит на улице не первый год.
  // Круп и число пятен заданы прямо здесь: это отделка, а не механика, и
  // измерять её нечем.
  let зерно = 20251004;
  const случайное = () => {
    зерно = (зерно * 1103515245 + 12345) & 0x7fffffff;
    return зерно / 0x7fffffff;
  };
  for (let i = 0; i < 900; i++) {
    const x = случайное() * ШИР;
    const y = случайное() * ВЫС;
    const r = 1 + случайное() * 5;
    g.fillStyle = случайное() > 0.5 ? 'rgba(120, 96, 68, 0.10)' : 'rgba(226, 212, 186, 0.10)';
    g.beginPath();
    g.arc(x, y, r, 0, Math.PI * 2);
    g.fill();
  }

  // Врезанная рамка: тонкая линия, утопленная в камень.
  g.strokeStyle = 'rgba(88, 68, 46, 0.75)';
  g.lineWidth = 5;
  g.strokeRect(24, 24, ШИР - 48, ВЫС - 48);

  // Шрифт и начертание заданы константой ГАРНИТУРЫ на уровне модуля.
  const кегль = 78;
  g.textAlign = 'center';
  g.textBaseline = 'middle';

  // Чем рисуем. Сначала персидский, потом латиницу: на машине без арабской
  // гарнитуры плита не должна остаться пустой.
  const попытки: { строки: readonly string[]; rtl: boolean; кегль: number }[] = [
    { строки: ins.lines, rtl: true, кегль },
    { строки: ins.translit, rtl: false, кегль: 52 },
  ];

  let букв = 0;
  for (const попытка of попытки) {
    букв = написатьСтроки(g, попытка.строки, попытка.кегль, ШИР, ВЫС, попытка.rtl);
    if (букв > 0) break;
    // Полотно затираем перед следующей попыткой, иначе вторая ляжет поверх
    // первой и на камне окажутся обе строки сразу.
    g.fillStyle = '#b8a184';
    g.fillRect(0, 0, ШИР, ВЫС);
    g.strokeStyle = 'rgba(88, 68, 46, 0.75)';
    g.lineWidth = 5;
    g.strokeRect(24, 24, ШИР - 48, ВЫС - 48);
  }

  // Если букв всё равно ноль, на камне пусто. Такой случай на обычной системе
  // не бывает, но пустая плита читается как ошибка сборки, и молчать об этом
  // нельзя: это видно игроку.

  const текстура = new THREE.CanvasTexture(c);
  const m = new THREE.Mesh(
    new THREE.PlaneGeometry(STELE.faceWidth, STELE.faceHeight),
    new THREE.MeshStandardMaterial({ map: текстура, roughness: 0.95 }),
  );
  // Лицевая сторона смотрит в +Z, как и фасад дома.
  m.position.set(0, STELE.centerY, STELE.depth / 2 + 0.005);
  return m;
}

/**
 * Пишет строки по центру полосы и возвращает, сколько букв легло на камень.
 *
 * Считать надо именно буквы, а не вызовы fillText: браузер отрабатывает
 * fillText без ошибки и тогда, когда букв в гарнитуре нет - он рисует
 * прямоугольники. Считать нечего, поэтому сравниваем, сколько символов
 * нарисовалось темнее фона.
 */
function написатьСтроки(
  g: CanvasRenderingContext2D,
  строки: readonly string[],
  кегль: number,
  ширина: number,
  высота: number,
  rtl: boolean,
): number {
  const ПРЕДЕЛ = ширина - 100;
  const всего = строки.length;
  g.direction = rtl ? 'rtl' : 'ltr';
  строки.forEach((строка, i) => {
    const y = высота / 2 + (i - (всего - 1) / 2) * (кегль + 54);

    // Подгонка по ширине: персидская строка бывает длиннее полосы, и тогда её
    // надо уменьшить, а не обрезать. Обрезанная надпись читается как ошибка,
    // уменьшенная - как длинная строка.
    g.font = `bold ${кегль}px ${ГАРНИТУРЫ}`;
    const ширинаСтроки = g.measureText(строка).width;
    const масштаб = ширинаСтроки > ПРЕДЕЛ ? ПРЕДЕЛ / ширинаСтроки : 1;

    g.save();
    g.translate(ширина / 2, y);
    g.scale(масштаб, 1);
    g.font = `bold ${Math.round(кегль * масштаб)}px ${ГАРНИТУРЫ}`;

    // Светлая подложка со смещением вниз: нижний край резьбы ловит свет.
    g.fillStyle = 'rgba(236, 224, 200, 0.85)';
    g.fillText(строка, 0, 4);
    // Сама резьба тёмная: это тень в выемке.
    g.fillStyle = '#43331f';
    g.fillText(строка, 0, 0);
    g.restore();
  });
  return посчитатьБуквы(g, ширина, высота);
}

/**
 * Сколько тёмных пикселей осталось на полотне сверх рамки и пятен.
 *
 * Порог 400 выбран не на глаз по числу, а по смыслу: одна строка персидского
 * текста на 78 кегля даёт тысячи тёмных пикселей, а полотна без букв - около
 * сотни от рамки и крапин. Разрыв двукратный, поэтому порог берётся с запасом
 * и не срабатывает на пустом полотне.
 */
function посчитатьБуквы(
  g: CanvasRenderingContext2D,
  ширина: number,
  высота: number,
): number {
  const данные = g.getImageData(0, 0, ширина, высота).data;
  let тёмных = 0;
  for (let i = 0; i < данные.length; i += 4) {
    // Резьба #43331f: тёмная и оранжевая. Камень #b8a184: светлее и желтее.
    if (данные[i] < 130 && данные[i + 1] < 110 && данные[i + 2] < 80) тёмных++;
  }
  return тёмных;
}