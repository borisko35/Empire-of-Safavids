/** Метров на один повтор карты нормалей. Тот же порядок, что и у карты смещения. */
const ПЛИТКА_НОРМАЛЕЙ_М = 6;

interface Замер {
  тело: WaterBody;
  амплитуда: number;
  гребнейНа100м: number;
  максНаклон: number;
  худшаяОктаваМ: number;
  вершинНаХудшую: number;
  вершинНаОктаву: { длина: number; вершин: number }[];
}

function замерить(тело: WaterBody, t: number): Замер {
  const поле: WaveField = WAVE_FIELDS[тело];
  const сетка = WATER_GRIDS[тело];

  // Идём вдоль направления САМОЙ КОРОТКОЙ вершинной октавы: по нему мелкая
  // рябь видна лучше всего, а крупная зыбь её не забивает.
  const мелкая = корочеВсехВершиннаяОктава(поле);
  if (!мелкая) throw new Error(`у поля «${поле.name}» нет ни одной вершинной октавы`);
  const d = Math.hypot(мелкая.dirX, мелкая.dirZ) || 1;
  const ux = мелкая.dirX / d;
  const uz = мелкая.dirZ / d;

  let максНаклон = 0;
  let гребней = 0;
  let предыдущая = 0;

  const ШАГ = 0.05; // 20 замеров на метр
  const ПРОБЕГ = 120; // метров вдоль ряби

  for (let s = 0; s <= ПРОБЕГ / ШАГ; s++) {
    const x = ux * s * ШАГ;
    const z = uz * s * ШАГ;
    // Считаем только то, что реально несёт сетка: мелочь приходит картой
    // нормалей и в вершинах её нет.
    const h = waveHeight(поле, x, z, t, 1, 'mesh');
    if (s > 0 && предыдущая < 0 && h >= 0) гребней++;
    предыдущая = h;

    if (s % 20 === 0) {
      const n = waveNormal(поле, x, z, t, 0.5, 1, 'mesh');
      const наклон = Math.acos(Math.min(1, Math.max(-1, n[1]))) * 180 / Math.PI;
      if (наклон > максНаклон) максНаклон = наклон;
    }
  }

  const вершины = поле.octaves
    .filter((o) => o.carriedBy === 'mesh')
    .map((o) => ({ длина: o.wavelength, вершин: вершинНаВолну(o.wavelength, сетка.step) }));

  const худшая = вершины.reduce((a, b) => (b.вершин < a.вершин ? b : a));

  return {
    тело,
    амплитуда: поле.octaves
      .filter((o) => o.carriedBy === 'mesh')
      .reduce((s, o) => s + o.amplitude, 0) * поле.scale,
    гребнейНа100м: (гребней / ПРОБЕГ) * 100,
    максНаклон,
    худшаяОктаваМ: худшая.длина,
    вершинНаХудшую: худшая.вершин,
    вершинНаОктаву: вершины,
  };
}

