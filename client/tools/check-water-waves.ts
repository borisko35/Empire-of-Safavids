// ── Проверки ────────────────────────────────────────────────────────

const ошибки: string[] = [];

for (const з of замеры) {
  const имя = WAVE_FIELDS[з.тело].name;

  if (з.гребнейНа100м < 1) {
    ошибки.push(
      `${имя}: ${з.гребнейНа100м.toFixed(2)} гребня на 100 м - поверхность читается `
      + 'как наклонная плита, а не как вода',
    );
  }

  if (з.максНаклон < 3) {
    ошибки.push(`${имя}: макс наклон ${з.максНаклон.toFixed(1)}° - гладь стеклянная, ряби нет`);
  }

  for (const октава of з.вершинНаОктаву) {
    if (октава.вершин < 3) {
      ошибки.push(
        `${имя}: волна ${октава.длина.toFixed(1)} м получает ${октава.вершин.toFixed(1)} `
        + `вершины сетки при шаге ${WATER_GRIDS[з.тело].step} м - меньше трёх, `
        + 'и вершинное смещение её не рисует',
      );
    }
  }

  // Мелочь помечена как detail: приходит картой нормалей. Если она длиннее
  // плитки этой карты, глаз её не различит, и она просто тратит амплитуду.
  const поле = WAVE_FIELDS[з.тело];
  for (const о of поле.octaves) {
    if (о.carriedBy !== 'detail') continue;
    if (о.wavelength > ПЛИТКА_НОРМАЛЕЙ_М * 3) {
      ошибки.push(
        `${имя}: мелкая октава ${о.wavelength.toFixed(1)} м длиннее плитки карты `
        + `нормалей (${ПЛИТКА_НОРМАЛЕЙ_М} м) более чем втрое - её не видно`,
      );
    }
  }
}

// ── Проверки сетки ─────────────────────────────────────────────────
//
// ГЛАВНАЯ ЗАЩИТА ОТ ВОЗВРАТА. Сетка из четырёх вершин на 6.3 километра - это
// ровно то, чем море было 15.10.2026 (PlaneGeometry(..., 1, 1)). Никакой
// разговор про «волны в метрах» её не поймал бы: числа про волны останутся
// правильными, а рисовать будет нечем. Поэтому проверяется сама сетка.
if (xsCount < 40 || zs.length < 20) {
  ошибки.push(
    `сетка моря ${xsCount}x${zs.length}: вершин слишком мало - вершинному `
    + 'смещению негде звучаться (было 2x2 на 6.3 км)',
  );
}

if (seaTris > 60_000) {
  ошибки.push(
    `сетка моря стоит ${seaTris} треугольников - это уже не вода, а асфальт. `
    + `Шаг ${SEA_GRID.step} м и рост x${SEA_GRID.growth} раздувают её быстрее нужного`,
  );
}

if (seaTris < 5_000) {
  ошибки.push(`сетка моря всего ${seaTris} треугольников: волны на горизонте не будет`);
}

// Шаг, в который сетка превращается там, где вершинное смещение ещё не погасло.
const шагУГасания = stepAt(210, SEA_GRID.step, SEA_GRID.growth);
const худшаяВершинная = корочеВсехВершиннаяОктава(WAVE_FIELDS.sea);
if (худшаяВершинная && шагУГасания > худшаяВершинная.wavelength) {
  ошибки.push(
    `вершинное смещение гаснет на 210 м, а шаг сетки там уже ${шагУГасанию.toFixed(0)} м `
    + `- длиннее волны ${худшаяВершинная.wavelength} м. Гасить надо раньше`,
  );
}

if (ошибки.length) {
  console.log('');
  console.log('ПРОВАЛЕНО:');
  for (const о of ошибки) console.log('  - ' + о);
  process.exit(1);
}

