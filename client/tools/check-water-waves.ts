// Проверка волн числами, до всякого рендеринга.
//
// ЗАЧЕМ. «Волны читаются как волны» - измеримое утверждение, а не вкусовое.
// До 15.10.2026 шейдер брал длину волны от uv (0..1 на каждое тело), и «9
// метров» на озере означали 2720 метров: озеро целиком помещалось в одну волну
// и выглядело медленно кренящейся плитой, а море было плоскостью 1x1 вообще
// без волн. Ни один глаз не описал бы это точнее, чем эти числа.
//
// ГЛАВНЫЕ ПРИЗНАКИ. Волна читается, если:
//   1. гребней укладывается в 100 м больше одного (иначе это наклон плиты),
//   2. склон гребня крутой (иначе поверхность стеклянная),
//   3. на КАЖДУЮ вершинную октаву приходится не меньше трёх вершин сетки
//      (иначе волна физически некуда рисовать - это и был случай моря
//      из четырёх вершин),
//   4. мелочь, помеченная в таблице как detail, короче плитки карты нормалей
//      более чем втрое (иначе она неразличима и глаз её не видит).
//
// ПОРОГИ НЕ ВЫДУМАНЫ: сначала печатаются измеренные значения, потом
// сравнение. Всё считается теми же формулами, что и в шейдере, потому что GLSL
// генерируется из той же таблицы октав.
//
// ЗАПУСК: из client/ ->  npx tsx tools/check-water-waves.ts
