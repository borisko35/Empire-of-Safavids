// Проверка формата UUID.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Колонки с типом UUID отвечают Postgres ошибкой
// приведения типа, а не пустым результатом: если во входных данных вместо
// идентификатора прилетит мусор, маршрут ответит 500 там, где человек всего
// лишь опечатался. Проверка нужна на входе, и нужна одинаковая везде, где
// идентификатор приходит от клиента.
//
// Первая копия этого регулярного выражения появилась в маршруте журнала
// боёв. Вторая копия через полгода отличалась бы от первой на один
// символ — и ровно в том месте, где проверка перестала бы работать.
const UUID_RE = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/;

/** Строка ровно в формате UUID, без каких-либо оговорок. */
export function isUuid(value: unknown): value is string {
  return typeof value === 'string' && UUID_RE.test(value);
}
