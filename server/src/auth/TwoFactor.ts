// Двухфакторная аутентификация по времени (TOTP, RFC 6238).
//
// Модуль ЧИСТЫЙ: ни базы, ни окружения, ни времени извне. Всё время
// передаётся аргументом. Это не украшение: TOTP - это арифметика, которую
// легко испортить, и проверить её на настоящих векторах из RFC можно
// только если функция не прячется за базой и часами.
//
// ПОЧЕМУ SHA-1, А НЕ SHA-256. RFC 6238 определяет HMAC-SHA-1 как
// ОБЯЗАТЕЛЬНЫЙ, потому что им все приложения-аутентификаторы. Сломать
// SHA-1 можно, но нельзя сломать совместимость с телефоном игрока, а это
// здесь важнее: приложение, которое игрок поставил, должно работать.
//
// ПРОВЕРКА НА НАСТОЯЩИХ ВЕКТОРАХ. Ниже используются значения из
// приложения A1 стандарта RFC 6238 (секрет "12345678901234567890",
// HMAC-SHA-1). Если сдвинуть период, смещение окна, разрядность или
// порядок байтов, векторы перестанут совпадать - и проверка это заметит.

import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto';

/** Алфавит base32 по RFC 4648, без знака «=». */
const BASE32 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

/** Стандартный период: 30 секунд. */
export const ПЕРИОД = 30;

/** Стандартная разрядность: 6 цифр. */
export const ЦИФРЫ = 6;

/** Сколько шагов в окно в каждую сторону. */
export const ОКНО = 1;

/**
 * Перевести байты в base32.
 *
 * Своя реализация вместо Buffer: base32 нужен как ТЕКСТ в ссылке otpauth и в
 * поле, которое игрок вводит руками. Нулевой байт должен давать 'A', а не
 * 'AA' - иначе секрет расползается по длине.
 */
export function вBase32(байты: Uint8Array): string {
  let вывод = '';
  let буфер = 0;
  let битов = 0;
  for (const байт of байты) {
    буфер = (буфер << 8) | байт;
    битов += 8;
    while (битов >= 5) {
      вывод += BASE32[(буфер >>> (битов - 5)) & 31];
      битов -= 5;
    }
  }
  if (битов > 0) вывод += BASE32[(буфер << (5 - битов)) & 31];
  return вывод;
}

/**
 * Разобрать base32 обратно в байты.
 *
 * Мусор на входе не роняет: секрет мог прийти из поля, которое игрок
 * переписал. Возвращается пустой массив, и проверка кода его отвергнет -
 * с понятным отказом, а не с исключением посреди входа.
 */
export function изBase32(текст: string): Uint8Array {
  const чистый = String(текст ?? '').toUpperCase().replace(/[^A-Z2-7]/g, '');
  const байты: number[] = [];
  let буфер = 0;
  let битов = 0;
  for (const символ of чистый) {
    const значение = BASE32.indexOf(символ);
    if (значение < 0) continue;
    буфер = (буфер << 5) | значение;
    битов += 5;
    if (битов >= 8) {
      байты.push((буфер >>> (битов - 8)) & 255);
      битов -= 8;
    }
  }
  return Uint8Array.from(байты);
}

/** Случайный секрет. 20 байт - длина по умолчанию в RFC 4226. */
export function новыйСекрет(длина = 20): string {
  return вBase32(randomBytes(Math.max(10, Math.min(64, длина))));
}

/** Номер шага для момента времени. Время в секундах, НЕ в миллисекундах. */
export function шаг(время: number, период = ПЕРИОД): number {
  return Math.floor(время / (период > 0 ? период : ПЕРИОД));
}

/**
 * Код для конкретного шага.
 *
 * Динамическое усечение по RFC 4226: младший бит последнего байта задаёт
 * смещение, из четырёх байт начиная с него собирается число, старший бит
 * первого сбрасывается (иначе код мог бы стать восьмизначным), и остаток
 * от деления на 10^цифры даёт код.
 */
export function кодШага(секрет: string, номер: number, цифр = ЦИФРЫ): string {
  const ключ = изBase32(секрет);
  if (ключ.length === 0) return '';
  const счётчик = Buffer.alloc(8);
  // 64-битный счётчик, старшим байтом вперёд: так требует RFC.
  счётчик.writeBigUInt64BE(BigInt(Math.floor(номер)));
  const mac = createHmac('sha1', ключ).update(счётчик).digest();
  const смещение = mac[mac.length - 1] & 0x0f;
  const значение = ((mac[смещение] & 0x7f) << 24)
    | ((mac[смещение + 1] & 0xff) << 16)
    | ((mac[смещение + 2] & 0xff) << 8)
    | (mac[смещение + 3] & 0xff);
  return (значение % 10 ** цифр).toString().padStart(цифр, '0');
}

/** Код для момента времени. Удобная обёртка для тестов и отладки. */
export function кодНа(секрет: string, времяMs: number, цифр = ЦИФРЫ): string {
  return кодШага(секрет, шаг(Math.floor(времяMs / 1000)), цифр);
}

/**
 * Сравнение кодов за постоянное время.
 *
 * Обычное === сравнивает посимвольно и замолкает на первом различии, а по
 * времени ответа можно подбирать код по одному разряду за попытку. Здесь
 * сравнение всегда одинаковой длины.
 */
function равноПоВремени(a: string, b: string): boolean {
  const x = Buffer.from(String(a));
  const y = Buffer.from(String(b));
  // Разная длина - заведомо не равно, но длины сравниваются константно.
  if (x.length !== y.length) return false;
  if (x.length === 0) return false;
  return timingSafeEqual(x, y);
}

export interface РезультатПроверки {
  ok: boolean;
  /** Шаг, которому соответствует принятый код. 0 - код не принят. */
  step: number;
  /** Почему отказ. Пустая строка - код принят. */
  reason: string;
}

/**
 * Проверить код.
 *
 * ОКНО. Принимаются коды соседних шагов, потому что часы телефона и часы
 * сервера расходятся. По умолчанию ±1 шаг - это 30 секунд в каждую
 * сторону.
 *
 * ПОВТОР КОДА. Если step меньше последнего принятого, код считается
 * повторным и не принимается. Без этого код, подсмотренный через плечо или
 * перехваченный в журнале, можно было бы отправлять повторно до конца
 * своего окна - то есть подряд секунд тридцать.
 */
export function проверитьКод(
  секрет: string,
  код: string,
  времяMs: number,
  окно = ОКНО,
  последнийШаг = 0,
  цифр = ЦИФРЫ,
): РезультатПроверки {
  const введённый = String(код ?? '').trim();
  // Не выкидываем код, а смотрим на его длину: код с мусором внутри той же
  // длины всё равно не пройдёт, но не пройдёт ЗА СРАВНЕНИЕ, а не заранее.
  if (введённый.length !== цифр || !/^\d+$/.test(введённый)) {
    return { ok: false, step: 0, reason: 'two_factor_invalid' };
  }
  if (изBase32(секрет).length === 0) {
    return { ok: false, step: 0, reason: 'two_factor_no_secret' };
  }

  const текущий = шаг(Math.floor(времяMs / 1000));
  const радиус = Number.isFinite(окно) && окно > 0 ? Math.floor(окно) : 0;

  for (let смещение = -радиус; смещение <= радиус; смещение++) {
    const номер = текущий + смещение;
    if (номер < 0) continue;
    if (равноПоВремени(кодШага(секрет, номер, цифр), введённый)) {
      if (последнийШаг > 0 && номер <= последнийШаг) {
        return { ok: false, step: 0, reason: 'two_factor_replayed' };
      }
      return { ok: true, step: номер, reason: '' };
    }
  }
  return { ok: false, step: 0, reason: 'two_factor_invalid' };
}

/**
 * Ссылка otpauth:// для сканирования телефоном.
 *
 * issuer обязателен: без него в приложении рядом лежат коды других
 * сайтов, и игрок не сможет отличить, какой из них его.
 */
export function ссылкаOtpauth(секрет: string, аккаунт: string, издатель: string): string {
  const метка = encodeURIComponent(`${издатель}:${аккаунт}`);
  return `otpauth://totp/${метка}?secret=${секрет}&issuer=${encodeURIComponent(издатель)}&algorithm=SHA1&digits=${ЦИФРЫ}&period=${ПЕРИОД}`;
}

/** Коды восстановления: одноразовые, заменяют телефон. */
export function новыеКодыВосстановления(сколько = 10): string[] {
  const n = Number.isFinite(сколько) && сколько > 0 ? Math.floor(сколько) : 10;
  return Array.from({ length: n }, () => randomBytes(5).toString('hex').toUpperCase());
}

/**
 * Хэш кода восстановления.
 *
 * sha256, а не bcrypt: код восстановления - это 80 бит случайных данных,
 * им нельзя подбирать по словарю, а bcrypt на семи цифрах всё равно
 * тормозит. Соль добавляется, чтобы два одинаковых кода у разных игроков
 * давали разные хэши.
 */
export function хэшКодаВосстановления(код: string, соль: string): string {
  return createHmac('sha256', String(соль)).update(String(код).trim().toUpperCase()).digest('hex');
}
