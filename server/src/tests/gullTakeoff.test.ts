// Чайки слетают с причала.
//
// ЧТО БЫЛО (22 октября 2026, §278). Чайки стояли столбом: пройти мимо них —
// значит пройти мимо каменных фигур. Живая птица от человека улетает.
//
// ЧТО ТЕПЕРЬ. Чайка взлетает, когда игрок подходит ближе пяти метров, уходит в
// сторону, ждёт и возвращается на место.
//
// ГЛАВНОЕ ПРАВИЛО, РОДИВШЕЕСЯ ИЗ ОШИБКИ §275. Тогда у чаек было задано
// положение ДЕТАЛЕЙ (тело, хвост, клюв), а положение самой группы — нет, и все
// чайки стояли в центре порта. Проверка смотрела на записанные места и была
// зелёной. Поэтому теперь проверяется и записанное место, и то, что группа
// действительно стоит в этом месте.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Чайки слетают с причала', () => {
  it('у чайки задано положение группы, а не только деталей', () => {
    // Именно этого не хватало в §275: детали стояли на своих местах, а группа
    // — в нуле, и все чайки стояли в центре порта.
    должен(
      /чайка\.position\.set\(lx, земля, lz\);/.test(ТЕРРЕЙН),
      'у чайки не задано положение группы: она стоит не там, где записано',
    );
    // И детали — относительно группы.
    должен(/тело\.position\.y = 0\.78;/.test(ТЕРРЕЙН), 'тело чайки стоит не на группе');
    // Записанное место совпадает с положением группы.
    должен(
      /x: PORT\.x \+ lx,\s*z: PORT\.z \+ lz,\s*группа: чайка,\s*base: чайка\.position\.clone\(\),/.test(ТЕРРЕЙН),
      'записанное место чайки не совпадает с её положением',
    );
  });

  it('чайка взлетает, когда игрок подходит, и возвращается', () => {
    должен(
      /if \(ч\.состояние === 0 && близко\) \{/.test(МИР),
      'чайка не взлетает, когда игрок подходит',
    );
    // Близко — пять метров.
    должен(
      /const близко = Math\.hypot\(ч\.x - me\.pos\.x, ч\.z - me\.pos\.z\) < 5;/.test(МИР),
      'чайка взлетает слишком далеко от игрока',
    );
    // Улетела — ждёт и возвращается.
    должен(/if \(ч\.состояние === 2\) \{[\s\S]{0,200}?ч\.состояние = 3;/.test(МИР),
      'улетевшая чайка не возвращается');
    // Сторона взлёта — по детерминированному генератору, а не случайно.
    должен(/const к = hash2\(Math\.round\(ч\.x\), Math\.round\(ч\.z\)\);/.test(МИР),
      'сторона взлёта считается случайно: после перезагрузки чайка улетит иначе');
  });
});
