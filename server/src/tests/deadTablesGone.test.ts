// Мёртвые таблицы: в схеме есть механизмы, которых никто не пишет и не читает.
//
// ЧТО БЫЛО. Четыре таблицы, созданные миграциями и простоявшие пустыми:
//   - dungeon_boss_progress — звучит как прогресс боссов;
//   - party_progress — звучит как партийный счёт;
//   - item_enchants — звучит как зачарования;
//   - login_history — звучит как журнал входов.
// На деле прогресс боссов живёт в памяти процесса (DungeonService), партийного
// счёта нет никакого, зачарований нет, журнал входов не ведется.
//
// Пятая, `inventory`, сюда не вошла: её уже удалила миграция 007. Повторный
// снос был бы шумом.
//
// ЧТО ЗАЩИЩАЕТСЯ. Не «в миграции есть DROP», а то, что таблицы не всплыли
// заново: проверка ищет их упоминания во всём коде разработки. Если кто-то
// начнёт писать в party_progress, он должен это сделать осознанно — с миграцией
// о создании и с кодом, который пишет.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

/** Все .ts и .sql разработки, кроме миграций о создании и тестов. */
function файлыРазработки(): { путь: string; текст: string }[] {
  const результат: { путь: string; текст: string }[] = [];
  const корни = ['server/src', 'client/src', 'shared', 'tools', 'database'];
  const обход = (каталог: string): void => {
    for (const запись of readdirSync(join(корень, каталог), { withFileTypes: true })) {
      if (запись.name === 'node_modules') continue;
      const путь = join(каталог, запись.name);
      if (запись.isDirectory()) { обход(путь); continue; }
      if (!/\.(ts|sql)$/.test(запись.name)) continue;
      // Сами миграции исключены: в них таблицы объявлены или снесены, и
      // проверка «в коде нет упоминаний» иначе падала бы на них.
      if (/[\\/]migrations[\\/]/.test(путь)) continue;
      // Тесты исключены: они про эти таблицы и говорят.
      if (/\.test\.ts$/.test(запись.name)) continue;
      результат.push({ путь, текст: readFileSync(join(корень, путь), 'utf-8') });
    }
  };
  for (const кореньКаталога of корни) {
    try { обход(кореньКаталога); } catch { /* каталога нет - не наше дело */ }
  }
  return результат;
}

const файлы = файлыРазработки();

/** Таблицы, снесённые миграцией 076. */
const МЁРТВЫЕ = ['dungeon_boss_progress', 'party_progress', 'item_enchants', 'login_history'];

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/** Миграция без комментариев: только выполняемые операторы.
 *
 *  Убирать нужно обязательно. Проверка «в миграции нет CASCADE» читала прозу и
 *  падала на собственном же объяснении, почему CASCADE не использован. Это та же
 *  болезнь, от которой в проекте сделан stripCode для ts.
 */
function sqlБезКомментариев(миграция: string): string {
  return миграция
    .split(/\r?\n/)
    .map((с) => с.replace(/--.*$/, ''))
    .join('\n');
}

describe('Мёртвые таблицы: снесены и не всплыли', () => {
  it('миграция сносит все четыре', () => {
    const миграция = sqlБезКомментариев(readFileSync(
      join(корень, 'database/migrations/076_drop_dead_tables.sql'),
      'utf-8'
    ));
    for (const таблица of МЁРТВЫЕ) {
      must(
        new RegExp(`DROP TABLE IF EXISTS ${таблица};`).test(миграция),
        `миграция не сносит ${таблица}`,
      );
    }
  });

  it('CASCADE не используется', () => {
    // Внешних ключей НА эти таблицы нет - они ссылаются сами. CASCADE способен
    // утащить за собой чужое, а на пустых таблицах он не даёт ничего.
    const миграция = sqlБезКомментариев(readFileSync(
      join(корень, 'database/migrations/076_drop_dead_tables.sql'),
      'utf-8'
    ));
    must(!/CASCADE/.test(миграция), 'в миграции есть CASCADE: он может утащить чужое');
  });

  it('в коде разработки их нет', () => {
    // Сердце проверки. Пока таблица не упоминается, снос безопасен; как только
    // кто-то начнёт в неё писать, проверка обязана заставить его завести
    // миграцию о создании.
    const ожившими: string[] = [];
    for (const { путь, текст } of файлы) {
      const безКомментариев = текст
        .split(/\r?\n/)
        .filter((с) => !/^\s*(?:\/\/|\*|--|\/\*)/.test(с))
        .join('\n');
      for (const таблица of МЁРТВЫЕ) {
        if (new RegExp(`\\b${таблица}\\b`).test(безКомментариев)) ожившими.push(`${путь}: ${таблица}`);
      }
    }
    expect({ ожившими }).toEqual({ ожившими: [] });
  });

  it('обход разработки не пустой', () => {
    // Иначе предыдущая проверка проходила бы на пустом множестве: «нет
    // упоминаний» потому, что смотреть негде.
    must(файлы.length > 200, `файлов разработки набрано ${файлы.length}: обход не работает`);
  });

  it('inventory уже снесена раньше и здесь не фигурирует', () => {
    // Миграция 007 сделала это. Повторный снос - шум.
    const миграция = sqlБезКомментариев(readFileSync(
      join(корень, 'database/migrations/076_drop_dead_tables.sql'),
      'utf-8'
    ));
    must(!/\binventory\b/.test(миграция), 'миграция снова сносит inventory - это уже сделала 007');
  });
});