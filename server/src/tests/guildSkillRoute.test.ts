// Покупка навыка гильдии вообще достижима из игры.
//
// ЧТО БЫЛО. GuildService.upgradeSkill был написан целиком - проверял
// право, считал цену, не давал в долг, сбрасывал кэш - и НЕ ВЫЗЫВАЛСЯ
// НИГДЕ. Маршрута не было. Навык нельзя было купить никаким способом, и
// панель гильдии ничего не показывала бы про покупку.
//
// ПОЧЕМУ ПРОВЕРКА ЧИТАЕТ ИСХОДНИК, А НЕ ДЕРЁТ ЗАПРОС. Проверка живым
// запросом потребовала бы гильдию с казнами, офицером и золотом, а
// главное - она прошла бы и БЕЗ маршрута, если бы проверяла только ответ
// сервиса. Маршрут - это строчка в файле, и единственная честная проверка
// его существования - спросить файл.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

describe('Маршрут покупки навыка существует', () => {
  const роуты = читать('server/src/routes/guilds.ts');

  it('объявлен POST /skills/upgrade', () => {
    // Без этой строки upgradeSkill недостижим из игры, сколько угодно
    // качественного кода в сервисе.
    expect({ есть: /router\.post\('\/skills\/upgrade'/.test(роуты) })
      .toEqual({ есть: true });
  });

  it('за маршрутом стоит вызов upgradeSkill', () => {
    // Отдельная проверка от объявления: маршрут может быть объявлен и
    // ничего не вызывать - это уже другой мёртвый код.
    const блок = роуты.slice(
      роуты.indexOf("router.post('/skills/upgrade'"),
      роуты.indexOf('/*', роуты.indexOf("router.post('/skills/upgrade'") + 10));
    expect({
      зовёт: /guilds\.upgradeSkill\(/.test(роуты),
      передаёт_гильдию: /upgradeSkill\(data\.guild\.id, characterId, skillId, levels\)/.test(роуты),
      блок_не_пустой: блок.length > 0,
    }).toEqual({ зовёт: true, передаёт_гильдию: true, блок_не_пустой: true });
  });

  it('вход идёт через ownCharacterId, а не через тело запроса', () => {
    // Иначе можно было бы купить навык от чужого персонажа: подставив
    // characterId в тело, игрок тратил бы казну чужой гильдии.
    const блок = роуты.slice(
      роуты.indexOf("router.post('/skills/upgrade'"),
      роуты.indexOf("router.post('/skills/upgrade'") + 900);
    expect({
      своя_персоналка: /const characterId = await ownCharacterId\(req\)/.test(блок),
      тело_игнорируется: !/req\.body\.characterId\b/.test(блок),
    }).toEqual({ своя_персоналка: true, тело_игнорируется: true });
  });

  it('гильдия берётся по персонажу, а не из тела запроса', () => {
    // Иначе можно было бы указать любую гильдию и тратить её казну.
    const блок = роуты.slice(
      роуты.indexOf("router.post('/skills/upgrade'"),
      роуты.indexOf("router.post('/skills/upgrade'") + 900);
    expect({
      по_персонажу: /guilds\.getGuildByCharacter\(characterId\)/.test(блок),
      тело_игнорируется: !/req\.body\.guildId\b/.test(блок),
    }).toEqual({ по_персонажу: true, тело_игнорируется: true });
  });
});

describe('Ошибки сервиса не теряются', () => {
  const роуты = читать('server/src/routes/guilds.ts');

  it('клиенту отдаётся код ошибки, а не 400 на всё', () => {
    // «Нет права» и «нет золота» — разные ситуации для игрока, и клиент
    // обязан их различать. Схлопывание в один 400 означало бы, что
    // игроку показывают «не хватает золота», когда на самом деле у него
    // нет права качать навык.
    const блок = роуты.slice(
      роуты.indexOf("router.post('/skills/upgrade'"),
      роуты.indexOf("router.post('/skills/upgrade'") + 1600);
    expect({
      запрет_403: /SKILLS_FORBIDDEN: 403/.test(блок),
      не_член_403: /NOT_A_MEMBER: 403/.test(блок),
      неизвестный_404: /SKILL_UNKNOWN: 404/.test(блок),
      пустой_котёл_400: /NOT_ENOUGH_GUILD_GOLD: 400/.test(блок),
      // Навык без точки применения - недоработка сервера, не вина игрока.
      недоработка_409: /SKILL_UNAVAILABLE: 409/.test(блок),
      статус_из_карты: /res\.status\(статус\[code\] \?\? 400\)/.test(блок),
    }).toEqual({
      запрет_403: true, не_член_403: true, неизвестный_404: true,
      пустой_котёл_400: true, недоработка_409: true, статус_из_карты: true,
    });
  });
});

describe('Мёртвых методов гильдии не осталось', () => {
  it('upgradeSkill вызывается не только из сервиса', () => {
    // Общий класс поломки этого репозитория: метод написан, маршрута
    // нет. Такое уже было с depositItem и с рекордом комбо до этого.
    // Проверка ищет вызов ВНЕ файла сервиса.
    const сервис = читать('server/src/services/GuildService.ts');
    const роуты = читать('server/src/routes/guilds.ts');
    expect({
      в_роутере: /upgradeSkill\(/.test(роуты),
      объявление_одно: (сервис.match(/async upgradeSkill\(/g) ?? []).length === 1,
    }).toEqual({ в_роутере: true, объявление_одно: true });
  });
});

describe('Комментарий не может съесть маршрут', () => {
  // ЭТО ПОЛУЧИЛОСЬ НА САМОМ ДЕЛЕ. В комментарии к новому маршруту стояло
  // "named'ы" - с апострофом. stripComments сначала маскирует строковые
  // литералы и только потом снимает комментарии, поэтому апостроф открыл
  // "строку", которая тянулась до следующей настоящей кавычки. Вместе с
  // ней исчезли router.post('/deposit-item') и router.post('/withdraw-item'),
  // и их собственные проверки покраснели - но выглядело это как поломка
  // склада, а не как ошибка в комментарии.
  //
  // Проверка читает файл тем же способом, каким его читают все остальные,
  // и требует, чтобы ВСЕ объявленные маршруты дожили до конца. Тогда
  // поломка выдаёт себя именем исчезнувшего маршрута, а не загадочным
  // падением половины набора.
  it('все 13 объявленных маршрутов переживают stripComments', () => {
    const сырой = читать('server/src/routes/guilds.ts');
    const очищенный = stripComments(сырой);

    // Список зафиксирован руками. Новый маршрут обязан сломать эту
    // проверку, иначе она ничего не сторожит: забытый '/skills/upgrade'
    // сделал бы её зелёной ровно тогда, когда он нужен.
    const ожидаем = [
      '/', '/bank', '/create', '/deposit-gold', '/deposit-item', '/join',
      '/kick', '/leave', '/members', '/rank', '/search', '/skills/upgrade',
      '/withdraw-item',
    ].sort();

    const выжили = ожидаем.filter(путь => очищенный.includes('router.') && очищенный.includes("'" + путь + "'"));
    expect({ объявлено: ожидаем.length, выжило: выжили.length, выжившие: выжили })
      .toEqual({ объявлено: 13, выжило: 13, выжившие: ожидаем });
  });

  it('ни в одном комментарии файла нет апострофа', () => {
    // Прямой запрет на причину. Апостроф в комментарии - не пунктуация,
    // а способ отключить любую проверку, читающую этот файл.
    const строки = читать('server/src/routes/guilds.ts').split('\n');
    let вБлоке = false;
    const виновники: string[] = [];
    for (const строка of строки) {
      if (/\/\*/.test(строка)) вБлоке = true;
      const тело = строка.replace(/\/\/.*$/, '');
      if (тело.includes("'") && (вБлоке || /\/\//.test(строка))) виновники.push(строка.trim().slice(0, 70));
      if (вБлоке && /\*\//.test(строка)) вБлоке = false;
    }
    expect({ виновники }).toEqual({ виновники: [] });
  });
});
