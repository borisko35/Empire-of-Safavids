// Проклятие Шеиха: страх, который действительно мешает.
//
// ЧТО ЗАМЕР ПОКАЗАЛ. Вид эффекта fear был объявлен и в типах, и в ограничении
// базы, монстры его навешивали — и он НИГДЕ НЕ ПРОВЕРЯЛСЯ. На игрока не влиял
// ничего: только иконка. Проклятие, сделанное «просто страхом», было бы
// пустышкой.
//
// ПОЧЕМУ НЕ НОВЫЙ ВИД. Новый вид «сквернение» потребовал бы миграции на снятие
// CHECK, новой логики спадания и ветки в игровом цикле — работа вчетверо больше
// при том же результате для игрока.
//
// ГРАНИЦА НАКАЗАНИЯ. В страхе нельзя бить и колдовать, но можно защищаться и
// бежать: иначе игрок был бы беспомощен, и это уже не наказание.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = код('server/src/systems/DungeonService.ts');
const дебаффы = код('server/src/services/DebuffService.ts');
const сокет = код('server/src/socket/GameSocketHandler.ts');
const ошибки = читать('shared/combatErrors.ts');

describe('Страх влияет на игрока, а не только на иконку', () => {
  it('есть быстрый запрос «боится ли персонаж»', () => {
    must(/async isAfraid\(characterId: string\)/.test(дебаффы), 'метода isAfraid нет');
    must(
      /kind = 'fear' AND expires_at > NOW\(\)/.test(дебаффы),
      'запрос не смотрит вид эффекта и не смотрит срок: просроченный страх держал бы игрока'
    );
  });

  it('запрос гасится, а не роняет бой', () => {
    must(/\.catch\(\(\) => null\)/.test(дебаффы), 'падение запроса не гасится');
  });

  it('в бою страх запрещает атаку, но не защиту', () => {
    must(/await this\.debuffs\.isAfraid\(socket\.characterId\)/.test(сокет), 'страх не проверяется в бою');
    must(
      /вСтрахе\s*&&\s*action\.actionType !== 'dodge'\s*&&\s*action\.actionType !== 'block'/.test(сокет),
      'страх блокирует и защиту, или не блокирует атаку: наказание должно оставлять защиту и бег'
    );
    must(/code: 'afraid'/.test(сокет), 'игроку не отправляется причина отказа');
  });

  it('код отказа известен клиенту и переведён', () => {
    must(/\| 'afraid'/.test(ошибки), 'код afraid не объявлен среди причин отказа');
    must(/afraid: 'world\.combat_error_afraid'/.test(ошибки), 'на код нет ключа перевода');
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`));
      must(
        typeof словарь.world?.combat_error_afraid === 'string' &&
          словарь.world.combat_error_afraid.length > 0,
        `в ${язык}.json нет текста world.combat_error_afraid`
      );
    }
  });
});

describe('Проклятие накрывает весь заход', () => {
  it('навешивается и при завершении захода, и при досрочном выходе', () => {
    // Два вызова с this. — complete и leave. Объявление метода идёт без this.,
    // поэтому в счётчик оно не попадает.
    const вызовы = сервис.split('this.curseSheikhRun(').length - 1;
    must(вызовы === 2, `вызовов curseSheikhRun ${вызовы}: ждём ровно два — complete и leave`);
    must(
      /this\.curseSheikhRun\(участники, session\.id\)/.test(сервис),
      'при завершении захода страх не навешивается'
    );
    must(
      /this\.curseSheikhRun\(\[\.\.\.сессия\.members\], сессия\.id\)/.test(сервис),
      'при досрочном выходе страх не навешивается'
    );
  });

  it('состав берётся до удаления человека из members', () => {
    // Иначе проклятие накрыло бы только того, кто выходит, а не весь заход.
    const начало = сервис.indexOf('async leave(');
    const тело = сервис.slice(начало, начало + 900);
    const вызов = тело.indexOf('this.curseSheikhRun([...сессия.members]');
    const удаление = тело.indexOf('this.sessions.get(sessionId)?.members.delete');
    must(вызов > 0, 'в leave нет навешивания проклятия');
    must(
      удаление < 0 || вызов < удаление,
      'состав захода снимается уже после удаления человека: проклятие накроет не весь заход'
    );
  });

  it('страх не достаётся тем, кто был в завершённом заходе', () => {
    // Завершённый заход уже наложил проклятие в complete. Повторное
    // навешивание при выходе продлило бы срок вдвое.
    must(
      /if \(сессия && !сессия\.completedAt\)/.test(сервис),
      'при выходе страх навешивается даже из завершённого захода: срок удвоится'
    );
  });

  it('вид эффекта и срок заданы явно', () => {
    must(/kind: 'fear'/.test(сервис), 'проклятие навешивается не тем видом');
    must(
      /durationMs: 5 \* 60 \* 1000/.test(сервис),
      'срок проклятия не задан явно: при гробнице с одним входом в сутки это решает всё'
    );
    must(/debuffId: 'sheikh_curse'/.test(сервис), 'у проклятия нет своего идентификатора');
  });

  it('проклятие не падает вместе с заходом', () => {
    // Ищется в теле наложения, а не где угодно в сервисе: catch с таким же
    // текстом есть и в других местах, и проверка цепляла их.
    const начало = сервис.indexOf('private async curseSheikhRun(');
    must(начало > 0, 'метод наложения проклятия не найден');
    const конец = сервис.indexOf('private async claimLoot(', начало);
    const тело = сервис.slice(начало, конец > начало ? конец : начало + 1500);
    must(
      /\.catch\(\(e: unknown\) =>/.test(тело),
      'падение навешивания не гасится: прохождение будет испорчено'
    );
    must(/logger\.warn/.test(тело), 'падение навешивания проходит молча');
  });

  it('источник помечен заходом, а не монстром', () => {
    must(
      /dungeon:\$\{sessionId\}/.test(сервис),
      'источник проклятия не помечен заходом: в журнале эффектов будет пусто'
    );
  });
});

describe('Страх был видом, который ничего не делал', () => {
  it('в системе эффектов он и раньше был объявлен, но не проверялся', () => {
    // Это зафиксировано, чтобы правка «страх запрещает атаку» не выглядела
    // новой механикой: вид существовал, работало только отображение.
    const миграция = читать('database/migrations/047_monster_effects.sql');
    must(
      /kind IN \('stun', 'slow', 'bleed', 'poison', 'fear'\)/.test(миграция),
      'вид fear исчез из ограничения базы: проверка опиралась бы несуществующий набор'
    );
  });

  it('в клиенте fear уже умеет показываться', () => {
    const клиент = читать('client/src/app/debuffs.ts');
    must(/case 'fear'/.test(клиент), 'клиент не умеет показывать fear');
  });

  it('урон от страха не начисляется: его и не должно быть', () => {
    // Урон со временем есть только у bleed и poison, это запрещено
    // ограничением базы. Страх должен быть страхом, а не тиком.
    must(/tickDamage: 0/.test(сервис), 'проклятие наносит урон тиками');
    must(/magnitude: 0/.test(сервис), 'проклятие замедляет или усиливает без нужды');
  });
});
