// Награда за задание выдаётся ровно один раз - и это держит БАЗА.
//
// ПОЧЕМУ ЧИТАЕМ ИСХОДНИК, А НЕ ВЫЗЫВАЕМ СЕРВИС. Проверка «вызвать claim
// дважды» на подставной базе ничего не доказывает: подставная база сама
// решит, что вернуть. Единственное доказательство - условие в самом
// UPDATE и транзакция вокруг него. Их и проверяем здесь, а настоящее
// поведение гоняется на живом сервере.
//
// ПРАВИЛО ДНЯ. Ни одна проверка этого файла не может стать зелёной на
// сломанном коде: у каждой есть разбор, почему именно этот кусок текста
// и есть защита.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const сервис = читать('server/src/services/GuildMissionService.ts');
const миграция = читать('database/migrations/062_guild_missions.sql');

describe('Награда не выдаётся дважды', () => {
  it('перевод статуса ограничен текущим статусом', () => {
    // ГЛАВНАЯ ЗАЩИТА. Второй претендент на награду шлёт тот же UPDATE, но
    // строка уже claimed, условие status = 'active' не находит ничего, и
    // rowCount = 0. Без этого условия UPDATE отработал бы по любой строке
    // и заплатил дважды.
    const перевод = /UPDATE guild_missions([\s\S]*?)WHERE id = \$1 AND status = 'active'/.exec(сервис);
    expect({
      есть_условие: перевод?.[1] !== undefined,
      // Ставит именно claimed, а не active: иначе повторный забор проходил бы.
      ставит_claimed: /SET status = 'claimed'/.test(перевод?.[1] ?? ''),
      // Откат задаётся в той же строке - иначе задание можно было бы
      // начать снова сразу после получения награды.
      ставит_откат: /available_at = \$3/.test(перевод?.[1] ?? ''),
    }).toEqual({ есть_условие: true, ставит_claimed: true, ставит_откат: true });
  });

  it('нулевой результат перевода отменяет всю выдачу', () => {
    // Порядок «выдать, потом проверить» не защищает: награда ушла бы уже.
    const блок = сервис.slice(сервис.indexOf('async claim('));
    expect({
      проверяет_rowCount: /перевод\.rowCount === 0/.test(блок),
      бросает: /throw new Error\('MISSION_ALREADY_CLAIMED'\)/.test(блок),
      // Награда в гильде начисляется ПОСЛЕ перевода статуса. Наоборот -
      // опыт с золотом начислились бы даже тому, кто перевод проиграл.
      награда_после: блок.indexOf('UPDATE guilds SET experience')
        > блок.indexOf('перевод.rowCount === 0'),
    }).toEqual({ проверяет_rowCount: true, бросает: true, награда_после: true });
  });

  it('отказ ловится по коду, а не по тексту ошибки', () => {
    // Я бросаю Error с кодом и ловлю его, сверяя код. Сверять текст
    // сообщения - хрупко: перевод слова в этом же файле или правка
    // формулировки тихо ломает защиту, и вторая выдача проходит.
    const блок = сервис.slice(сервис.indexOf('async claim('));
    const сравнения = блок.match(/сообщение === 'MISSION_ALREADY_CLAIMED'/g) ?? [];
    const бросит = /throw new Error\('MISSION_ALREADY_CLAIMED'\)/.test(блок);
    expect({
      бросит_с_кодом: бросит,
      сверяет_код: сравнения.length > 0,
      // Сверка должна быть РОВНО одна. Две означали бы, что путь отказа
      // продублирован и при изменении кода легко починить одну и забыть
      // про другую.
      сверок: сравнения.length,
    }).toEqual({ бросит_с_кодом: true, сверяет_код: true, сверок: 1 });
  });

  it('выдача идёт в одной транзакции с самим переводом статуса', () => {
    // Транзакция здесь - не украшение. Без неё перевод статуса и
    // прибавление опыта с золотом расходятся при любой ошибке второго:
    // отметка «получено» есть, а награды нет.
    const блок = сервис.slice(сервис.indexOf('async claim('));
    const транзакция = блок.indexOf('this.db.transaction');
    const перевод = блок.indexOf('UPDATE guild_missions');
    const опыт = блок.indexOf('UPDATE guilds SET experience');
    expect({
      есть_транзакция: транзакция > 0,
      перевод_внутри: перевод > транзакция,
      награда_внутри: опыт > транзакция,
    }).toEqual({ есть_транзакция: true, перевод_внутри: true, награда_внутри: true });
  });
});

describe('Прогресс не накапливается выше нужды', () => {
  it('сверху прижат required', () => {
    // Без этого игрок, убивший 300 разбойников, при следующем взятии
    // задания сразу получал бы «выполнено» - а задание обещало 100.
    expect({
      при_вставке: /VALUES \(\$1, \$2, \$3, LEAST\(\$4::int, \$5::int\)\)/.test(сервис),
      при_прибавлении: /DO UPDATE SET progress = LEAST\(/.test(сервис),
      required_как_параметр: /Number\(цель\.required\) \|\| 0/.test(сервис),
    }).toEqual({ при_вставке: true, при_прибавлении: true, required_как_параметр: true });
  });

  it('тип потолка задан явно - второй случай за день', () => {
    // ЖИВОЙ ПРОГОН: column "progress" is of type integer but expression is
    // of type text. LEAST - функция с переменным числом аргументов, и
    // Postgres выводит тип неизвестных параметров как text. Потолок не
    // влезал в колонку, и запись прогресса не происходила ВООБЩЕ: задание
    // было невыполнимо, ни убийства, ни сбор, ни данж не засчитывались.
    //
    // ВТОРОЙ ЗА СЕГОДНЯ ТОТ ЖЕ КЛАСС. Первым был $2::numeric в
    // recalcMaxHp. Общая причина: Postgres выводит тип сам, и выведенный
    // тип не совпадает с колонкой. Лечится только явным приведением.
    //
    // Проверка ловит именно ОТСУТСТВИЕ приведения, а не наличие LEAST:
    // иначе она осталась бы зелёной на LEAST($4, $5).
    const потолок = /LEAST\(([^)]*)\)/g;
    const все = [...сервис.matchAll(потолок)].map(m => m[1]);
    // Ищем параметр БЕЗ приведения: $4::int - приведённый, $4 - нет.
    // Проверка на «есть ли вообще $» была бы всегдашней правдой и ничего
    // бы не ловила: $4::int тоже содержит знак доллара.
    const безПриведения = (текст: string): string[] =>
      [...текст.matchAll(/\$(\d+)(?!::)/g)].map(m => m[0]);
    expect({
      потолков_найдено: все.length,
      без_приведения: все.flatMap(безПриведения),
    }).toEqual({ потолков_найдено: 2, без_приведения: [] });
  });

  it('ошибка записи прогресса пишется с кодом, а не пустотой', () => {
    // В логе было «прогресс не записан: » - ПУСТОЙ текст. Причина есть,
    // но по одному message её не видно, и поломку пришлось искать
    // отдельным скриптом. Код Postgres в сообщении полезен.
    const блок = сервис.slice(сервис.indexOf('async addProgress('), сервис.indexOf('async onKill('));
    expect({
      печатает_код: /ошибка\.code/.test(блок),
      подстраховка: /без сообщения/.test(блок),
    }).toEqual({ печатает_код: true, подстраховка: true });
  });

  it('повторное взятие обнуляет прошлый прогресс', () => {
    // Иначе 90 убийств из прошлой попытки засчитались бы сразу.
    const блок = сервис.slice(сервис.indexOf('async start('), сервис.indexOf('async addProgress('));
    expect({ чистит: /DELETE FROM guild_mission_progress WHERE mission_row = \$1/.test(блок) })
      .toEqual({ чистит: true });
  });

  it('ошибка записи прогресса не поднимается', () => {
    // addItems и убийство монстра - горячие точки. Исключение от гильдейского
    // задания там останавливало бы бой и выдачу предметов.
    const блок = сервис.slice(сервис.indexOf('async addProgress('), сервис.indexOf('async onKill('));
    expect({
      ловится: /catch \(e\) \{/.test(блок) && /logger\.warn/.test(блок),
      нет_throw: !/throw /.test(блок),
    }).toEqual({ ловится: true, нет_throw: true });
  });
});

describe('Схема держит два защитных свойства', () => {
  it('уникальность пары (гильдия, задание) объявлена в базе', () => {
    // Без неё можно было бы завести две строки на одно задание, и
    // награда выдалась бы дважды через две разные строки.
    expect({ уникальна: /UNIQUE \(guild_id, mission_id\)/.test(миграция) })
      .toEqual({ уникальна: true });
  });

  it('character_id НЕ входит в первичный ключ', () => {
    // ПЕРВАЯ ОШИБКА ЭТОЙ МИГРАЦИИ, ПОЙМАННАЯ ДО ЗАПУСКА. PRIMARY KEY в
    // Postgres объявляет все свои колонки NOT NULL. А character_id здесь
    // nullable по смыслу: NULL - «прогресс общий, гильдейский», как у цели
    // «собрать 500 шёлка». С первичным ключом такая миграция просто не
    // применилась бы, и на бою это выглядело бы как «миграция прошла, а
    // таблицы нет».
    expect({
      без_первичного_ключа: !/PRIMARY KEY \(mission_row/.test(миграция),
      колонка_nullable: /character_id\s+UUID\s+REFERENCES/.test(миграция),
    }).toEqual({ без_первичного_ключа: true, колонка_nullable: true });
  });

  it('уникальный индекс учитывает NULL через COALESCE', () => {
    // NULL в уникальном индексе не сравнивается с NULL: две строки с
    // character_id = NULL прошли бы незамеченными, и общий прогресс
    // накопился бы дважды.
    expect({
      coalesce_в_индексе: /COALESCE\(character_id, '00000000-0000-0000-0000-000000000000'::uuid\)/
        .test(миграция),
      индекс_уникальный: /CREATE UNIQUE INDEX IF NOT EXISTS idx_guild_mission_progress_key/.test(миграция),
    }).toEqual({ coalesce_в_индексе: true, индекс_уникальный: true });
  });

  it('комментарии только в стиле SQL', () => {
    // В .sql-файле '//' не комментарий. Такой файл роняет сайт целиком на
    // этапе миграции - не одну таблицу, а всё.
    expect({
      нет_двойных_слэшей: !/^\s*\/\//m.test(миграция),
      комментарии_есть: /^--/m.test(миграция),
    }).toEqual({ нет_двойных_слэшей: true, комментарии_есть: true });
  });
});

