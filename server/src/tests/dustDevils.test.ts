// Пыльные вихри в пустыне.
//
// ЧТО БЫЛО (21 октября 2026, §257). Пустыня вокруг Исфахана — песок и ветер,
// и ничего, что шевелилось само по себе. Песчаная буря есть (погода), а
// вихрей нет: в мире, где ветер поднимает пыль, вихрь — самое естественное,
// что может случиться с песком.
//
// ЧТО ТЕПЕРЬ. Три вихря бродят по песку рядом с игроком: столб из клубов,
// который поднимается, закручивается и медленно идёт по земле.
//
// ЧТО ПРОВЕРЯЕТСЯ. Вихри создаются и живут (дрейф, закрутка, клубы из
// основания); за стенами города их нет — песок там мощёный; и движок их
// обновляет и вычищает.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ВИХРИ = читать('client/src/app/game3d/dustDevil.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Пыльные вихри', () => {
  it('вихри бродят по песку и закручиваются', () => {
    должен(/export function createDustDevils/.test(ВИХРИ), 'нет модуля вихрей');
    должен(/const ВИХРЕЙ = 3;/.test(ВИХРИ), 'вихрей не три');
    // Столб: клубы выходят из основания по кругу и поднимаются.
    должен(
      /в\.пыль\.всплеск\(\s*в\.x \+ Math\.cos\(a\) \* радиус,[\s\S]{0,200}?в\.пыль\.update\(dt\)/.test(ВИХРИ),
      'клубы вихря не выходят из основания столба',
    );
    // Вихрь идёт по земле.
    должен(/в\.x \+= в\.vx \* dt;/.test(ВИХРИ), 'вихрь не двигается по песку');
    должен(/в\.угол \+= dt \* 2\.4;/.test(ВИХРИ), 'вихрь не закручивается');
  });

  it('за стенами города вихрей нет', () => {
    должен(
      /const отГорода = Math\.hypot\(x - CITY\.x, z - CITY\.z\);[\s\S]{0,400}?CITY\.radius \+ 40/.test(ВИХРИ),
      'вихрь может появиться внутри города: песок там мощёный',
    );
  });

  it('вихрь рассыпается, когда он слишком близко или слишком далеко', () => {
    должен(
      /Math\.hypot\(в\.x - px, в\.z - pz\) < 25[\s\S]{0,300}?в\.пыль\.dispose\(\)/.test(ВИХРИ),
      'вихрь не возрождается рядом с игроком',
    );
  });

  it('движок создаёт вихри, обновляет и вычищает', () => {
    должен(/this\.вихри = createDustDevils\(this\.scene\);/.test(МИР), 'движок не создаёт вихри');
    должен(
      /this\.вихри\.update\(dt, now, me\.pos\.x, me\.pos\.z\);/.test(МИР),
      'вихри не обновляются: столбы песка стоят на месте',
    );
    должен(/this\.вихри\?\.dispose\(\);/.test(МИР), 'вихри не вычищаются');
  });
});
