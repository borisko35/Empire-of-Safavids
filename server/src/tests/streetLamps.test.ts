// Фонари вдоль проспектов: ночью город не должен выключаться.
//
// ЧТО БЫЛО (21 октября 2026, §245). На весь город шесть фонарей (пять
// городских и четыре квартальных), а проспектов четыре и улиц десятки.
// Ночью город выключался целиком: тёмная плита, тёмные дома.
//
// ЧТО ТЕПЕРЬ. По два фонаря на проспект, попеременно по сторонам, и у каждого
// — источник света в фонаре.
//
// ЧТО ПРОВЕРЯЕТСЯ. Фонари стоят ВДОЛЬ проспекта (а не в центре площади) и
// каждый даёт свет: без источника фонарь — просто палка с чашей.
//
// ПРО ГРАНИЦУ ПРОВЕРКИ. Строки фонарей на проспектах и в пригороде
// совпадают слово в слово, поэтому проверка смотрит ТОЛЬКО свой раздел кода:
// иначе ломка «убери свет у фонарей проспекта» молча правила фонари
// пригорода, а сторож этого не замечал.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

function свойРаздел(начало: string, конец: string): string {
  // Ищем по ИСХОДНИКУ: метки разделов — это комментарии, а в очищенном коде
  // их нет.
  const от = ТЕРРЕЙН.indexOf(начало);
  должен(от >= 0, `в коде нет раздела «${начало}»`);
  const до = ТЕРРЕЙН.indexOf(конец, от);
  должен(до > от, `в коде нет раздела «${конец}» после «${начало}»`);
  return ТЕРРЕЙН.slice(от, до).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const ПРОСПЕКТЫ = свойРаздел('── Фонари вдоль проспекта (§245) ──', '── Ворота квартала (§235) ──');

describe('Фонари вдоль проспектов', () => {
  it('фонари стоят вдоль проспекта, по обе стороны', () => {
    должен(
      /const lx = \(q\.x \/ len\) \* d \+ nx \* сторона \* 3\.4;/.test(ПРОСПЕКТЫ),
      'фонари не стоят вдоль проспекта',
    );
    // По одному с каждой стороны: через один.
    должен(
      /const сторона = i % 2 \? 1 : -1;/.test(ПРОСПЕКТЫ),
      'фонари не чередуются по сторонам',
    );
  });

  it('каждый фонарь даёт свет', () => {
    // Фонарь без источника — палка с золотой чашей.
    должен(
      /lights\.push\(\{ x: CITY\.x \+ lx, z: CITY\.z \+ lz, y: city\.position\.y \+ земля \+ 3\.55 \}\)/.test(
        ПРОСПЕКТЫ,
      ),
      'фонари на проспектах не получают источников света',
    );
    // И стоят по настоящей земле.
    должен(
      /const земля = groundHeight\(CITY\.x \+ lx, CITY\.z \+ lz\) - city\.position\.y;/.test(ПРОСПЕКТЫ),
      'фонари стоят на зашитой высоте',
    );
  });
});
