// Растительность и ткань носят текстуры, а не стоят голым цветом.
//
// ЧТО ЗДЕСЬ ВСКРЫТО ЗАМЕРОМ. Камень, песок и дерево имели albedo, карту
// нормалей и карту шероховатости, а крона, стволы, кустарник и ткань стояли
// плоским цветом с roughness: 1. Разница видна с ходу: крона читалась как
// вырезанная из цветного картона, ствол — как палка, парус — как заливка.
// Плоская поверхность не даёт того, за что глаз цепляется на кустах и
// кронах, — претензионной детали и собственной тени от неё.
//
// Проверка читает исходник, а не запускает canvas: текстуры строятся в
// браузере, и поднять их в node нельзя. Как и в других проверках качества
// картинки, единственное что тут можно сломать — вернуть плоский материал
// или оторвать текстуру от материала, и оба случая видны в тексте.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const текстуры = stripComments(читать('client/src/app/game3d/textures.ts'));
const рельеф = stripComments(читать('client/src/app/game3d/terrain.ts'));

/** Тело конструктора материала по его имени в MAT. */
function материал(имя: string): string {
  const начало = рельеф.indexOf(`\n  ${имя}: new THREE.MeshStandardMaterial(`);
  must(начало !== -1, `материал ${имя} не найден`);
  const скобка = рельеф.indexOf('(', начало);
  let глубина = 0;
  let конец = скобка;
  for (let i = скобка; i < рельеф.length; i++) {
    if (рельеф[i] === '(') глубина++;
    else if (рельеф[i] === ')') {
      глубина--;
      if (глубина === 0) { конец = i; break; }
    }
  }
  return рельеф.slice(скобка, конец);
}

describe('Растительность и ткань носят текстуры', () => {
  it('текстуры листвы, коры и ткани написаны', () => {
    for (const имя of [
      'foliageTexture', 'foliageNormalTexture',
      'barkTexture', 'barkNormalTexture',
      'clothTexture',
    ]) {
      must(new RegExp(`export function ${имя}\\s*\\(`).test(текстуры),
        `в textures.ts нет функции ${имя} — материал вернётся к плоскому цвету`);
    }
  });

  it('у листвы, кустарника и пальмового листа есть albedo и нормали', () => {
    // Поверхность без нормалей не даёт детали: цвет меняет тон, наклон
    // даёт объём. Без normalMap крона остаётся плоской заливкой, сколько
    // бы детальной ни была текстура цвета.
    for (const имя of ['foliage', 'foliageDark', 'foliageLight', 'brush', 'palmLeaf']) {
      const m = материал(имя);
      must(/map:\s*foliageTexture\(/.test(m), `${имя}: нет карты цвета — крона плоская`);
      must(/normalMap:\s*foliageNormalTexture\(/.test(m), `${имя}: нет карты нормалей`);
    }
  });

  it('у стволов есть кора с нормалями, а не доски', () => {
    for (const имя of ['trunk', 'palmTrunk']) {
      const m = материал(имя);
      must(/map:\s*barkTexture\(/.test(m), `${имя}: нет карты коры`);
      must(/normalMap:\s*barkNormalTexture\(/.test(m), `${имя}: нет карты нормалей коры`);
      must(!/woodTexture\(/.test(m),
        `${имя}: стоит woodTexture — это доски, на стволе они читаются как обои в полоску`);
    }
  });

  it('у ткани есть переплетение нитей', () => {
    for (const имя of ['clothRed', 'clothTeal', 'clothPurple', 'white']) {
      must(/map:\s*clothTexture\(/.test(материал(имя)), `${имя}: ткань без текстуры`);
    }
  });

  it('цвет текстуры совпадает с цветом материала', () => {
    // Текстура приходит в multiply к color. Расхождение тянет материал в
    // чужой оттенок: ткань, задуманная бирюзовой, становилась синей. Такое
    // случилось при написании и было замечено здесь, а не на игре.
    for (const имя of ['foliage', 'foliageDark', 'foliageLight', 'brush', 'palmLeaf', 'trunk', 'palmTrunk', 'clothRed', 'clothTeal', 'clothPurple', 'white']) {
      const m = материал(имя);
      const цвет = /color:\s*0x([0-9a-fA-F]{6})/.exec(m);
      const текстура = /(?:foliageTexture|barkTexture|clothTexture)\(\s*'#([0-9a-fA-F]{6})'/.exec(m);
      must(цвет !== null, `${имя}: не найден color`);
      must(текстура !== null, `${имя}: не найден базовый цвет текстуры`);
      const материалЦвет = `${цвет[1]!.toLowerCase()}`;
      const текстураЦвет = `${текстура[1]!.toLowerCase()}`;
      must(материалЦвет === текстураЦвет,
        `${имя}: color 0x${материалЦвет}, а текстура #${текстураЦвет} — материал уедет в чужой оттенок`);
    }
  });

  it('сила нормалей у листвы и коры не выкручена в полную', () => {
    // Полная сила превращает крона в шум из чешуек: глаз ловит рельеф там,
    // где должна читаться масса листвы. У камня стоит 1.2, у дерева 0.8 —
    // у зелени должно быть не больше.
    for (const имя of ['foliage', 'foliageDark', 'foliageLight', 'brush', 'palmLeaf']) {
      const m = материал(имя);
      const масштаб = /normalScale:\s*new THREE\.Vector2\(([\d.]+)/.exec(m);
      must(масштаб !== null, `${имя}: не задан normalScale`);
      const сила = Number(масштаб[1]);
      must(сила > 0 && сила <= 0.9, `${имя}: сила нормалей ${сила} — крона рассыплется в чешуйки`);
    }
  });

  it('текстуры стыкуются сами с собой по краям', () => {
    // Лист и волокно рисуются девятью сдвигами, иначе по периметру текстуры
    // видна прямая рамка. Проверяется по коду: число сдвигов в теле функции
    // должно быть не меньше девяти.
    for (const имя of ['foliageTexture', 'foliageNormalTexture']) {
      const начало = текстуры.indexOf(`export function ${имя}`);
      const тело = текстуры.slice(начало, начало + 2600);
      const сдвигов = (тело.match(/\[-size, -size\]/g) ?? []).length;
      must(сдвигов >= 1,
        `${имя}: нет рисования со сдвигами на все восемь сторон — по краям будет рамка`);
    }
  });

  it('у снега есть текстура с кристаллами и нормалями', () => {
    // Снег — один из самых заметных материалов в горных районах. Плоский белый
    // цвет с roughness: 1 читался как белая бумага, а не снежный покров.
    // Текстура снега даёт мелкие кристаллы и неровности.
    const m = материал('snow');
    must(/map:\s*snowTexture\(/.test(m), 'snow: нет карты цвета');
    must(/normalMap:\s*snowNormalTexture\(/.test(m), 'snow: нет карты нормалей');
  });

  it('цвет текстуры снега совпадает с цветом материала', () => {
    // Та же проверка, что и для листвы и ткани: текстура приходит в multiply
    // к color, и расхождение дало бы чужой оттенок.
    const m = материал('snow');
    const цвет = /color:\s*0x([0-9a-fA-F]{6})/.exec(m);
    const текстура = /snowTexture\(\s*'#([0-9a-fA-F]{6})'/.exec(m);
    must(цвет !== null, 'snow: не найден color');
    must(текстура !== null, 'snow: не найден базовый цвет текстуры');
    must(цвет[1]!.toLowerCase() === текстура[1]!.toLowerCase(),
      `snow: color 0x${цвет[1]}, а текстура #${текстура[1]} — материал уедет в чужой оттенок`);
  });

  it('у снега шероховатость не единица', () => {
    // Снег не идеально матовый: кристаллы льда дают лёгкий блеск. roughness: 1
    // гасит весь блик, и снег читается как бумага.
    const m = материал('snow');
    const шерох = /roughness:\s*([\d.]+)/.exec(m);
    must(шерох !== null, 'snow: не задана roughness');
    const значение = Number(шерох[1]);
    must(значение < 1, `snow: roughness ${значение} — блик от кристаллов снега пропадёт`);
  });

  it('у рамы окна есть текстура дерева с нормалями', () => {
    // Рама окна — один из самых заметных элементов в городской среде.
    // Плоский светлый цвет читался как пластиковая полоса, а не дерево.
    const m = материал('windowFrame');
    must(/map:\s*windowFrameTexture\(/.test(m), 'windowFrame: нет карты цвета');
    must(/normalMap:\s*windowFrameNormalTexture\(/.test(m), 'windowFrame: нет карты нормалей');
  });

  it('цвет текстуры рамы окна совпадает с цветом материала', () => {
    const m = материал('windowFrame');
    const цвет = /color:\s*0x([0-9a-fA-F]{6})/.exec(m);
    const текстура = /windowFrameTexture\(\s*'#([0-9a-fA-F]{6})'/.exec(m);
    must(цвет !== null, 'windowFrame: не найден color');
    must(текстура !== null, 'windowFrame: не найден базовый цвет текстуры');
    must(цвет[1]!.toLowerCase() === текстура[1]!.toLowerCase(),
      `windowFrame: color 0x${цвет[1]}, а текстура #${текстура[1]} — материал уедет в чужой оттенок`);
  });

  it('у цветка есть текстура лепестков с нормалями', () => {
    // Цветок — простой белый материал с roughness: 1. Лепестки имеют
    // тонкие прожилки и полупрозрачные края, которые ловят свет.
    const m = материал('flower');
    must(/map:\s*flowerTexture\(/.test(m), 'flower: нет карты цвета');
    must(/normalMap:\s*flowerNormalTexture\(/.test(m), 'flower: нет карты нормалей');
  });

  it('цвет текстуры цветка совпадает с цветом материала', () => {
    const m = материал('flower');
    const цвет = /color:\s*0x([0-9a-fA-F]{6})/.exec(m);
    const текстура = /flowerTexture\(\s*'#([0-9a-fA-F]{6})'/.exec(m);
    must(цвет !== null, 'flower: не найден color');
    must(текстура !== null, 'flower: не найден базовый цвет текстуры');
    must(цвет[1]!.toLowerCase() === текстура[1]!.toLowerCase(),
      `flower: color 0x${цвет[1]}, а текстура #${текстура[1]} — материал уедет в чужой оттенок`);
  });

  it('у цветка шероховатость не единица', () => {
    // Лепестки полупрозрачны и ловят свет. roughness: 1 гасит блик.
    const m = материал('flower');
    const шерох = /roughness:\s*([\d.]+)/.exec(m);
    must(шерох !== null, 'flower: не задана roughness');
    const значение = Number(шерох[1]);
    must(значение < 1, `flower: roughness ${значение} — блик от лепестков пропадёт`);
  });
});