// Разметка, на которую ссылается клиентский код, лежит в ОТСЛЕЖИВАЕМЫХ
// файлах.
//
// ЗАЧЕМ. Панель второго фактора рисуется в $('#twofa-box'). Я внёс коробку в
// client/web/game/index.html - а это BUILD-ВЫХОД, он в .gitignore и
// пересоздаётся при каждой сборке из client/src/app/index.html. Правка не
// попала бы в репозиторий, и на проде панель исчезла бы молча: настройки
// остались бы, кнопка включения 2FA пропала бы, и это выглядело бы как
// «2FA не работает».
//
// Проверка не ищет коробку вообще - она сверяет ТРИ вещи:
//   1. клиентский код ссылается на идентификатор;
//   2. этот идентификатор есть в ОТСЛЕЖИВАЕМОЙ разметке;
//   3. его нет в файлах, которые git не видит.
//
// Третий пункт главный: без него правка в сборку прошла бы молча, и ошибка
// повторилась бы при следующем обновлении.
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

describe('Разметка второй фактора', () => {
  it('клиентский код ссылается на коробку, которая есть в разметке', () => {
    const панель = читать('client/src/app/panels.ts');
    const разметка = читать('client/src/app/index.html');
    must(/\$?\('twofa-box'\)/.test(панель) || /twofa-box/.test(панель),
      'клиентский код больше не ссылается на twofa-box');
    expect({ коробка_в_разметке: /id="twofa-box"/.test(разметка) })
      .toEqual({ коробка_в_разметке: true });
  });

  it('заголовок переводится, а не зашит по-русски', () => {
    // Остальные заголовки панели настроек переводятся через data-i18n.
    // Этот - тоже, иначе на азербайджанском в панели появится русская
    // строка рядом с переведёнными соседями.
    const разметка = читать('client/src/app/index.html');
    expect({ переводится: /data-i18n="twofa\.title"/.test(разметка) })
      .toEqual({ переводится: true });
  });

  it('правка не попала в игнорируемую сборку', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. В сборку смотреть нельзя - она всё равно
    // пересоздаётся; вопрос в том, не осталась ли там правка, которая
    // создаёт расхождение между источником и выходом.
    const сборка = 'client/web/game/index.html';
    if (!existsSync(join(корень, сборка))) {
      // Сборки нет - значит, вопрос не возник. Локально её может не быть.
      return;
    }
    const отслеживается = (() => {
      try {
        execFileSync('git', ['ls-files', '--error-unmatch', сборка], {
          cwd: корень, stdio: 'pipe',
        });
        return true;
      } catch { return false; }
    })();
    expect({ файл_под_контролем_git: отслеживается })
      .toEqual({ файл_под_контролем_git: false });
  });
});
