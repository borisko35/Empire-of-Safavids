// Абордаж: заход можно НАЧАТЬ (§191).
//
// До этой правки механика существовала целиком и была покрыта 36 проверками,
// а начать её было нечем: resolveBoardFight, boardLoot и pvpCargoLoss
// вызывались только из своих тестов. Маршрут отдавал список целей — и на этом
// всё заканчивалось.
//
// Проверяется не «метод есть», а три вещи, которые ломаются тихо:
//   1. сервер берёт цель ПОИСКОМ, а не из пакета;
//   2. PvE не получает вторую награду поверх обычного пути убийства;
//   3. оба режима доходят до ответа — симметрия, за которую стоит держаться.
import { readFileSync } from 'node:fs';
import * as ts from 'typescript';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';
import { resolveBoardFight, boardLoot, pvpCargoLoss } from '../systems/BoardingFight';
import { boardSelfRejected, boardReward } from '../systems/Boarding';
import type { BoardTarget } from '../systems/BoardingTypes';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

/**
 * Подписки socket.on, лежащие внутри тела другой подписки.
 *
 * Спросить у ПАРСЕРА, а не у глаз: вид подписки ничего не говорит о её форме.
 * Отступ врёт в обе стороны — подписка в цикле стоит глубже, а вложенная может
 * стоять на том же отступе, что и внешняя. Подсчёт скобок тоже врёт: он ломается
 * о скобки внутри строк и шаблонных подстановок.
 */
function вложенныхПодписок(код: string): string[] {
  const файл = ts.createSourceFile('world.ts', код, ts.ScriptTarget.Latest, true);
  const плохие: string[] = [];
  const обход = (узел: ts.Node, внутри: boolean): void => {
    let здесь = внутри;
    if (
      ts.isCallExpression(узел)
      && ts.isPropertyAccessExpression(узел.expression)
      && узел.expression.name.text === 'on'
      && ts.isIdentifier(узел.expression.expression)
      && узел.expression.expression.text === 'socket'
    ) {
      if (здесь) {
        const первый = узел.arguments[0];
        плохие.push(первый && ts.isStringLiteralLike(первый) ? первый.text : '(без литерала)');
      }
      здесь = true;
    }
    ts.forEachChild(узел, (дитя) => обход(дитя, здесь));
  };
  обход(файл, false);
  return плохие;
}

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СОКЕТ = код('server/src/socket/GameSocketHandler.ts');
const ПОИСК = код('server/src/systems/BoardingSearch.ts');

/**
 * Тело метода по имени, до закрывающей скобки.
 *
 * Срез «следующие N символов» не годится: метод длиннее среза проверяет
 * воздух и остаётся зелёным. Скобки идут до самого конца метода, сколько бы он
 * ни вырос.
 */
function тело(источник: string, имя: string): string {
  const начало = источник.indexOf(' ' + имя + '(');
  if (начало < 0) return '';
  const открывающая = источник.indexOf('{', начало);
  if (открывающая < 0) return '';
  let глубина = 0;
  for (let i = открывающая; i < источник.length; i++) {
    if (источник[i] === '{') глубина++;
    else if (источник[i] === '}') {
      глубина--;
      if (глубина === 0) return источник.slice(начало, i + 1);
    }
  }
  return '';
}

describe('Абордаж: заход можно начать (§191)', () => {
  it('сокет слушает событие начала захода', () => {
    must(/socket\.on\(SOCKET_EVENTS\.BOARDING_START/.test(СОКЕТ),
      'сокет не слушает boarding:start: кнопка есть, а нажать нечем');
    must(/handleBoardingStart/.test(СОКЕТ), 'обработчик начала захода не вызывается');
    must(/BOARDING_RESULT/.test(СОКЕТ), 'исход захода никуда не отправляется');
  });

  it('цель берётся ПОИСКОМ, а не из пакета', () => {
    // Главное правило. Если сервер доверяет присланным полям, игрок шлёт
    // { level: 1, x: 0, z: 0 } и абордажит рейд без боя. Правило, написанное
    // в BoardingTargets, было бы пустым текстом.
    must(/найтиЦелиАбордажа\(/.test(СОКЕТ),
      'заход не ищет цели: бой идёт с тем, что прислал клиент');
    must(/поиск\.targets\.find\(/.test(СОКЕТ),
      'цель ищется не в найденном списке, а где-то ещё');
    // В пакете читаются ТОЛЬКО идентификатор и режим.
    must(!/data\.(level|x|z|region)\b/.test(СОКЕТ),
      'обработчик читает уровень, позицию или регион из пакета: клиент может солгать');
  });

  it('подписка лежит на верхнем уровне, а не внутри другой подписки', () => {
    // §191, вторая редакция. Обработчик boarding:result был вставлен сразу
    // после строки `socket.on('combat:error', …)`, то есть ВНУТРИ её тела.
    // Компилятор доволен, бандл собран, строка события в нём есть — и подписка
    // не создаётся никогда, потому что не наступает ошибка боя.
    //
    // Проверка общая для всех событий, а не только абордажа: подписка внутри
    // подписки — всегда ошибка, и всегда молчаливая.
    const строки = читать('client/src/app/world.ts').split('\n');
    const начало = строки.findIndex((l) => l.startsWith('function wireSocket'));
    must(начало >= 0, 'wireSocket не найден на клиенте');

    must(вложенныхПодписок(читать('client/src/app/world.ts')).length === 0,
      'подписка socket.on лежит внутри тела другой подписки: она не создастся, '
      + 'пока внешняя не сработает. Компилятор такое пропускает, бандл собирается, '
      + 'и строка события в нём есть — а подписки нет.');
  });

  it('PvE не получает вторую награду поверх обычного пути убийства', () => {
    // Вторая награда разошлась бы с первой: сегодня совпали бы, завтра одну
    // из них поправили, а другую нет.
    const блок = тело(СОКЕТ, 'абордажМонстра');
    must(блок.length > 0, 'ветки PvE нет');
    must(/rewardMonsterKill/.test(блок),
      'PvE не идёт обычным путём убийства: опыт, репутация и бонусы потеряны');
    must(!/boardLoot\(/.test(блок),
      'в PvE золото считается ещё раз через boardLoot: две награды разойдутся');
  });

  it('PvP считает добычу и отнимает треть груза', () => {
    const блок = тело(СОКЕТ, 'абордажИгрока');
    must(блок.length > 0, 'ветки PvP нет');
    must(/boardLoot\(/.test(блок), 'добыча PvP не считается boardLoot');
    must(/pvpCargoLoss\(/.test(блок),
      'проигравший не теряет треть груза — решение владельца из §191 не выполнено');
    must(/removeItems/.test(блок) && /addItems/.test(блок),
      'груз не переносится: победитель ничего не забирает');
  });

  it('оба режима доходят до ответа', () => {
    // Симметрия — свойство, записанное в самом Boarding.ts: «новая возможность
    // обязана появиться в обоих режимах». Один ответ — половинчатость.
    const отправок = (СОКЕТ.match(/SOCKET_EVENTS\.BOARDING_RESULT/g) ?? []).length;
    must(отправок >= 4,
      `исход отправляется в ${отправок} местах, а нужно минимум четыре: `
      + 'отказ, PvE, PvP жертве и PvP атакующему');
  });

  it('силы берутся из боевых формул, а не из своих', () => {
    must(/getBaseDamageFor/.test(СОКЕТ), 'сила удара считается не боевой формулой');
    must(/getDefenseFor/.test(СОКЕТ),
      'защита считается не боевой формулой: своя копия разойдётся с обычным боем');
    must(/monsterAsCharacter/.test(СОКЕТ),
      'монстр не приводится к персонажу: для него пришлось бы писать вторую формулу');
  });

  it('маршрут и сокет идут через ОДИН поиск целей', () => {
    must(/найтиЦелиАбордажа\(/.test(код('server/src/routes/game.ts')),
      'маршрут собирает цели сам: картина для показа и для боя разойдутся');
    must((ПОИСК.match(/boardTargets\(/g) ?? []).length === 1,
      'в общем поиске несколько вызовов boardTargets: правила разошлись');
  });

  it('поведение ядра: симметрия режимов и потеря груза', () => {
    // Не читаем исходник, а считаем: правила должны работать, а не выглядеть
    // рабочими.
    const силы = {
      attack: 100, defense: 10, hp: 500, targetAttack: 100, targetHp: 300,
      level: 40, targetLevel: 40,
    };
    const победа = resolveBoardFight(силы);
    must(победа.won === true, `при равных силах победил не атакующий: ${JSON.stringify(победа)}`);

    // Награда PvP выше PvE в BOARD_PVP_REWARD_MULT раз — иначе риск не окупает.
    must(boardReward(100, 'pvp') > boardReward(100, 'pve'),
      'награда PvP не выше PvE: абордаж чужой лодки не стоил бы риска');

    // Треть груза, а не весь и не пусто.
    const груз = ['a', 'b', 'c', 'd', 'e', 'f'];
    const потеряно = pvpCargoLoss(груз);
    must(потеряно.length > 0 && потеряно.length < груз.length,
      `проигравший теряет ${потеряно.length} из ${груз.length}: это не часть`);
    must(pvpCargoLoss([]).length === 0, 'пустой груз дал потерю: игрок без вещей теряет нечего');

    // Свою лодку абордажировать нельзя.
    const своя: BoardTarget = {
      id: 'c-1', nameRu: 'Своя', mode: 'pvp', level: 40,
      region: 'isfahan' as BoardTarget['region'], x: 0, z: 0,
    };
    must(boardSelfRejected(своя, 'c-1') === true, 'абордаж самой себя разрешён');
    must(boardSelfRejected(своя, 'c-2') === false, 'чужую лодку абордажировать нельзя');

    // Проигравший не получает добычу.
    const добыча = boardLoot({ won: false, hpLeft: 12, targetHpLeft: 40 }, {
      mode: 'pvp', baseGold: 500, targetItems: ['x'], attackerItems: [],
    });
    must(добыча.gold === 0 && добыча.items.length === 0,
      'проигравший получил добычу: заход без риска выгоднее победы');
  });
});
