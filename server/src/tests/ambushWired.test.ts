// Сторож засады на караван (Шёлковый путь, ROADMAP §179).
//
// ЗАЧЕМ ПРОВЕРКИ ИМЕННО ТАКИЕ. Засада держится на четырёх вещах, каждая из
// которых молча ломает механику целиком:
//
//   1. Гонорар списывается ДО подъёма конвоя. Обратный порядок дарит
//      бесплатную засаду: конвой убит, а золото не списали, потому что
//      что-то упало при выдаче.
//   2. Конвой объявляется в Redis вручную. Спавн по точке идёт мимо
//      SpawnSystem и сам ничего не пишет, а без объявления конвой не
//      существует ни для кого, включая нападавшего.
//   3. Добыча собирается при гибели ПОСЛЕДНЕГО эскорта. Каждый убитый
//      монстр в регионе иначе выдавал бы груз.
//   4. UNIQUE на караван, а не на нападавшего: иначе толпа собирает конвой
//      за минуту и делит добычу.
//
// ПОЧЕМУ НЕ ПОВЕДЕНЧЕСКАЯ ПРОВЕРКА ЗАСАДЫ. Поведенчески она требует двух
// персонажей, золотого, живого конвоя и его убийства — то есть стенда. Такой
// стенд здесь и нужен, но он пишется отдельно (tools/), и засада проверяется
// им на живом сервере. Этот сторож держит связность: чтобы засада развалилась
// молча, пришлось бы выкинуть больше, чем здесь проверяется.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function читать(...путь: string[]): string {
  return readFileSync(join(корень, ...путь), 'utf-8');
}

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const СЕРВИС = читать('server', 'src', 'services', 'AmbushService.ts');
const ДАННЫЕ = читать('server', 'src', 'data', 'ambushes.ts');
const РОУТ = читать('server', 'src', 'routes', 'game.ts');
const СОКЕТ = читать('server', 'src', 'socket', 'GameSocketHandler.ts');
const МИГРАЦИЯ = читать('database', 'migrations', '079_caravan_ambushes.sql');
const ПАНЕЛЬ = читать('client', 'src', 'app', 'panels.ts');
const API = читать('client', 'src', 'app', 'api.ts');

describe('Засада на караван связана целиком', () => {
  it('все части прочитаны', () => {
    const источники = { СЕРВИС, ДАННЫЕ, РОУТ, СОКЕТ, МИГРАЦИЯ, ПАНЕЛЬ, API };
    for (const [имя, текст] of Object.entries(источники)) {
      должен(текст.length > 100, `${имя} не прочитан или подозрительно мал: проверка ослепла`);
    }
  });

  it('гонорар списывается в транзакции ДО подъёма конвоя', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Обратный порядок дарил бы бесплатную засаду.
    должен(
      /this\.db\.transaction/.test(СЕРВИС),
      'гонорар и запись засады не в одной транзакции: можно заплатить и не начать',
    );
    const транзакция = СЕРВИС.indexOf('this.db.transaction');
    const спавн = СЕРВИС.indexOf('ai.spawnMonster');
    должен(спавн > 0, 'не нашёл подъём конвоя');
    должен(
      транзакция < спавн,
      'конвой поднимается раньше, чем списан гонорар: при падении подъёма засада была бы бесплатной',
    );
  });

  it('условие списания в самом UPDATE', () => {
    // Проверка выше успевает устареть: между ней и списанием золото может
    // уйти на что-то ещё — например, на покупку того же караула (§178).
    должен(
      /WHERE id = \$1 AND gold >= \$2/.test(СЕРВИС),
      'списание гонорара не защищено условием в самом UPDATE: золото может уйти в минус',
    );
  });

  it('конвой объявляется вручную', () => {
    // Спавн по точке идёт мимо SpawnSystem. Без публикации в Redis конвой
    // не существует ни для кого, и нападавший увидит пустоту вместо боя.
    должен(
      /:spawn`/.test(СЕРВИС),
      'конвой не объявляется в Redis: нападающий его не увидит',
    );
  });

  it('точка засады берётся из данных, а не от клиента', () => {
    // Иначе игрок поднял бы засаду у себя на крыше и никого не встретил.
    должен(
      /ambushPoint\(герой\.region\)/.test(СЕРВИС),
      'точка засады берётся не из данных региона',
    );
    должен(
      !/body\.position|req\.body\.\s*position/.test(СЕРВИС),
      'сервис читает точку из тела запроса: клиент может поставить засаду куда угодно',
    );
  });

  it('засада ровно одна на караван', () => {
    должен(
      /idx_caravan_ambushes_once/.test(МИГРАЦИЯ),
      'нет уникального индекса на караван: толпа соберёт конвой за минуту',
    );
    // И проверка в коде: индекс защищает от гонки, но не от «уже засадили»,
    // прочитанного раньше.
    должен(
      /caravan_already_ambushed/.test(СЕРВИС),
      'сервис не отказывает, если караван уже засадили',
    );
  });

  it('добыча собирается по гибели эскорта, а не любого монстра', () => {
    // Обратная ссылка instanceId -> засада. Без неё каждый убитый разбойник
    // в регионе выдавал бы груз чужого каравана.
    должен(
      /ambush:escort:/.test(СЕРВИС),
      'нет обратной ссылки от эскорта к засаде: любой убитый монстр выдаст груз',
    );
    const смерть = СОКЕТ.indexOf('эскортУбит');
    const награда = СОКЕТ.indexOf('rewardMonsterKill');
    должен(смерть > 0 && награда > 0, 'не нашёл ни вызов засады, ни награду за монстра');
    должен(
      смерть > награда,
      'добыча с каравана приходит раньше обычной награды за монстра: засада стала бы заменой охоте',
    );
  });

  it('закрыть засаду можно один раз', () => {
    // Между чтением засады и её закрытием проходит время, и второй удар
    // мог бы собрать добычу дважды.
    должен(
      /AND outcome = 'in_progress' RETURNING id/.test(СЕРВИС),
      'засада закрывается безусловно: добычу можно собрать дважды',
    );
  });

  it('выигрыш приходит игроку отдельным пакетом', () => {
    должен(
      /socket\.emit\('ambush:won'/.test(СОКЕТ),
      'о выигрыше не сообщают: игрок убьёт конвой и не поймёт, куда делся груз',
    );
  });

  it('конвой подбирается под уровень, а не один и тот же всегда', () => {
    // Пятидесятиуровневый караван на восьмиуровневом разбойнике — это «засада
    // невозможна», и идея молча умирает на первом же дешёвом контракте.
    const доли = [...ДАННЫЕ.matchAll(/contractId: '([^']+)'/g)].map((m) => m[1]);
    должен(доли.length >= 4, `засад описано ${доли.length}, ожидалось не меньше четырёх`);
    const монстры = [...ДАННЫЕ.matchAll(/monsterId: '([^']+)'/g)].map((m) => m[1]);
    const разные = new Set(монстры);
    должен(
      разные.size >= 3,
      `в конвоях всего ${разные.size} видов врагов: засады не отличаются друг от друга`,
    );
  });

  it('владелец каравана не может засадить самого себя', () => {
    // Иначе один аккаунт с двумя персонажами кормит сам себя.
    должен(
      /ownerId === characterId|ownerId === characterId\)/.test(СЕРВИС),
      'нет запрета на засаду на собственный караван',
    );
  });
});

describe('Дорога видна игроку', () => {
  it('маршруты дороги и засады зарегистрированы', () => {
    должен(
      /gameRouter\.get\('\/trade\/road'/.test(РОУТ),
      'маршрута списка дороги нет: игрок не видит, кого можно засадить',
    );
    должен(
      /gameRouter\.post\('\/trade\/ambush'/.test(РОУТ),
      'маршрута засады нет: кнопка зовёт адрес, которого нет',
    );
  });

  it('у обоих маршрутов проверяется владение персонажем', () => {
    const дороги = РОУТ.indexOf("'/trade/road'");
    const засады = РОУТ.indexOf("'/trade/ambush'");
    должен(дороги > 0 && засады > 0, 'не нашёл ни один из маршрутов');
    const участок = РОУТ.slice(Math.max(0, дороги), засады + 400);
    должен(
      /userId !== req\.userId|requireCharacterOwnership/.test(участок),
      'у маршрутов засады нет проверки владения: чужим караваном можно панель набить',
    );
  });

  it('панель рисует дорогу и кнопку засады', () => {
    должен(
      /api\.tradeRoad\(/.test(ПАНЕЛЬ),
      'панель торговли не спрашивает дорогу',
    );
    должен(
      /api\.tradeAmbush\(/.test(ПАНЕЛЬ),
      'у панели нет кнопки засады: дорога показана, а напасть нельзя',
    );
    // Кнопка гасится сама, а не только после отказа сервера: игрок должен
    // видеть, что караван уже засадили, ещё до попытки.
    должен(
      /кнопка\.disabled = караван\.ambushed/.test(ПАНЕЛЬ),
      'кнопка не гасится по уже начатой засаде: игрок будет жать и получать отказ',
    );
  });

  it('поломка дороги не убирает торговлю', () => {
    // Засада — необязательная часть панели. Её отказ не должен уносить
    // контракты, которые и без неё работают.
    const начало = ПАНЕЛЬ.indexOf('const дорожные = await api.tradeRoad');
    должен(начало > 0, 'не нашёл блок дороги в панели');
    const блок = ПАНЕЛЬ.slice(начало, начало + 4000);
    должен(
      /catch\s*\{[\s\S]{0,200}дорога недоступна/.test(блок),
      'блок дороги не ловит отказ: поломка засады уберёт всю торговлю',
    );
  });

  it('методы API ходят на те же адреса, что и маршруты', () => {
    должен(/\/api\/game\/trade\/road\?characterId=/.test(API), 'метод tradeRoad ходит не на /trade/road');
    должен(/'\/api\/game\/trade\/ambush'/.test(API), 'метод tradeAmbush ходит не на /trade/ambush');
  });
});