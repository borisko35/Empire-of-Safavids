// Пределы itch.io взяты из их документации, а не из памяти.
//
// Источник: https://itch.io/docs/creators/html5, раздел «ZIP file
// requirements». Площадка называет ровно эти числа:
//
//   - не больше 1000 файлов после распаковки;
//   - длина имени вместе с путём не больше 240 символов;
//   - суммарный распакованный размер не больше 500 МБ;
//   - один файл не больше 200 МБ;
//   - только ZIP: rar, tar.gz и 7z не принимаются;
//   - index.html обязан лежать в корне;
//   - имена регистрозависимы и кодируются в UTF-8;
//   - пути относительные: абсолютные уводят запрос за пределы проекта.
//
// Отдельно itch.io называет две ловушки, обе проверяются: доступ к пути,
// который не указывает на файл, возвращает 403, а не 404; и ссылка на файл
// с другим регистром падает в ERR_ABORTED 403, хотя на Windows и macOS
// грузится.
//
// Проверка НЕ сверяется с живой документацией. И не должна: иначе она падала
// бы в день, когда у itch.io лёг сайт, и заблокировала бы сборку ни за что.
// Числа зафиксированы здесь - если площадка поменяет требование, правка
// видна сразу.
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Связка в пределах, которые itch.io называет своими', () => {
  it('пределы в сборщике совпадают с опубликованными', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Пределы взяты из документации площадки, и
    // их правка без правки здесь - это расхождение с тем, что на самом деле
    // требует itch.io.
    const код = читать('tools/build-itch-bundle.js');
    // Пределы записаны выражением, а не числом: `всего: 500 * 1024 * 1024`.
    // Первая версия регулярки брала только `500`, делила на 1048576 и
    // получала 0.0004 МБ - то есть проверка проходила, ни разу не сверив
    // настоящий предел. Захватывается всё выражение и вычисляется.
    const взятьБайты = (имя: string): number => {
      const m = new RegExp(имя + ':\\s*([\\d\\s*]+)').exec(код);
      must(m, 'предел ' + имя + ' не найден в сборщике');
      // Только цифры, пробелы и звёздочки: никакого исполнения кода из
      // своего же исходника.
      const выражение = m[1].replace(/\s+/g, '');
      must(/^[\d*]+$/.test(выражение), 'предел ' + имя + ' записан не как число: ' + m[1]);
      return выражение.split('*').reduce((a, ч) => a * Number(ч), 1);
    };
    expect({
      файлов: взятьБайты('файлов'),
      путь: взятьБайты('путь'),
      всего_мб: взятьБайты('всего') / 1048576,
      файл_мб: взятьБайты('файл') / 1048576,
    }).toEqual({ файлов: 1000, путь: 240, всего_мб: 500, файл_мб: 200 });
  });

  it('регистр имён проверяется: itch.io регистрозависим, Windows - нет', () => {
    // Локально файл грузится в любом регистре, на площадке падает с
    // ERR_ABORTED 403. Именно это itch.io называет в списке ловушек.
    const код = читать('tools/build-itch-bundle.js');
    expect({
      проверяет_регистр: /TOCHNYM registrom/.test(код),
      // И ищет имя в архиве, а не на своём диске: на своём оно всегда есть.
      сверяет_с_архивом: /пред\.список/.test(код),
    }).toEqual({ проверяет_регистр: true, сверяет_с_архивом: true });
  });

  it('нарушение предела останавливает сборку, а не печатается в конце', () => {
    // Проверка пределов стоит ДО запросов по адресам. Если связка не влезает,
    // незачем поднимать сервер и стучаться по файлам, которых на площадке
    // тоже не будет.
    const код = читать('tools/build-itch-bundle.js');
    // Ищется ВЫЗОВ, а не объявление. Строка «проверитьПределы(папка)» есть и
    // в теле функции, и в месте вызова; бралась первая, то есть объявление,
    // которое стоит раньше всего. Поломка «подменить вызов на заглушку» при
    // этом проходила: объявление оставалось на месте, а сравнение «раньше
    // запроса» выполнялось само по себе. Тот же класс, что был с проверкой
    // «функция существует».
    const пред = код.indexOf('= проверитьПределы(папка)');
    const зап = код.indexOf("взять('/index.html')");
    must(пред > 0, 'вызов проверки пределов не найден');
    must(зап > 0, 'запрос index.html не найден');
    // И нарушение увеличивает счётчик, а не просто печатается.
    const влияет = /NET\s+predel/.test(код) && /плохо\+\+/.test(
      код.slice(код.indexOf('NET  predel'), код.indexOf('NET  predel') + 200));
    expect({
      пределы_раньше_запросов: пред < зап,
      нарушение_учитывается: влияет,
    }).toEqual({ пределы_раньше_запросов: true, нарушение_учитывается: true });
  });

  it('связка влезает в пределы с большим запасом', () => {
    // Считается по тому, что реально лежит в папке сборки. Папки может не
    // быть - её собирают на VPS, и на своей машине её нет. Тогда проверка
    // говорит об этом прямо, а не радостно рапортует «пределы соблюдены».
    const папка = join(корень, 'tools/itch-bundle');
    if (!existsSync(папка)) {
      // Папки нет - это не «всё хорошо» и не «плохо», это «не из чего
      // считать». Отмечаем явно.
      expect({ папка_собрана: false, причина: 'запустите tools/build-itch-bundle.js' })
        .toEqual({ папка_собрана: false, причина: 'запустите tools/build-itch-bundle.js' });
      return;
    }
    const список = файлыПод(папка);
    const всего = список.reduce((a, п) => a + statSync(join(папка, п)).size, 0);
    expect({
      есть_index: список.includes('index.html'),
      файлов_под_пределом: список.length <= 1000,
      всего_мб_под_пределом: Math.round(всего / 1048576) <= 500,
      есть_licenziya: список.includes('LICENSE'),
    }).toEqual({
      есть_index: true, файлов_под_пределом: true,
      всего_мб_под_пределом: true, есть_licenziya: true,
    });
  });
});

function файлыПод(кореньПапки: string, относный = ''): string[] {
  const выход: string[] = [];
  for (const имя of readdirSync(кореньПапки)) {
    const полный = join(кореньПапки, имя);
    const путь = относный ? относный + '/' + имя : имя;
    if (statSync(полный).isDirectory()) выход.push(...файлыПод(полный, путь));
    else выход.push(путь);
  }
  return выход;
}
