// Погода как потребитель: visibilityMod читается, остальные четыре - нет.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ. В weatherEffects.test.ts стоял заголовок, который
// утверждал, что все пять модификаторов WEATHER_EFFECTS "НИ ОДИН не
// читался". Это было правдой, пока мёртвое поле просто лежало. Шаг 2 стелса
// дал visibilityMod настоящего потребителя - правило скрытности в
// shared/stealth.ts сокращает им обзор стража, и в песчаную бурю он падает
// с 20 до 6 единиц.
//
// ПОЧЕМУ ПРОВЕРКА ТАК СТРОГА К ЗАГОЛОВКУ. Заголовок проверки - это
// утверждение, которому поверит следующий человек. Если он говорит "поле не
// читается", а поле читается, следующий либо удалит рабочее правило как
// "оставшееся от мёртвого поля", либо не станет чинить остальные четыре. Поэтому
// проверка требует, чтобы в заголовке ровно и честно говорилось: одно поле
// читается, четыре - нет. И она сначала доказывает, что умеет ловить ложь на
// старой формулировке, иначе она такая же пустая, как те заголовки, которые
// читает.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { WEATHER_EFFECTS } from '../systems/WorldTimeSystem';
import { GUARD_POSTS, effectiveSight, spottedBy, GUARD_SIGHT } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const стража = GUARD_POSTS[0];

describe('Погода и стелс: кто из модификаторов погоды действительно жив', () => {

  // Обход дерева объявлен на уровне описания, потому что на список файлов
  // ссылаются три проверки ниже: сверка шапки, закрепление потребителей и
  // сквозная сверка «сколько полей живо».
  //
  // Свой обход вместо readdirSync({recursive}): первая версия строила путь
  // через join(корень, "server/src", "..", f) и падала с ENOENT - проверка
  // упала не из-за кода, а из-за собственной навигации.
  function собрать(dir: string, найдено: string[] = []): string[] {
    for (const запись of readdirSync(join(корень, dir), { withFileTypes: true })) {
      if (запись.name === 'node_modules' || запись.name === 'dist') continue;
      const путь = `${dir}/${запись.name}`;
      if (запись.isDirectory()) {
        if (путь.endsWith('server/src/tests')) continue; // проверки сами не потребители
        собрать(путь, найдено);
      } else if (запись.name.endsWith('.ts')) {
        найдено.push(путь);
      }
    }
    return найдено;
  }

  const репозиторий = [...собрать("server/src"), ...собрать("client/src"), ...собрать("shared")];
  // Ненулевая исходная точка: если обход ничего не нашёл, все проверки ниже
  // прошли бы вхолостую, потому что фильтр по пустому массиву всегда пуст.
  must(
    репозиторий.length > 50,
    `обход нашёл всего ${репозиторий.length} файлов: проверки прошли бы вхолостую`
  );
  it('visibilityMod реально сокращает обзор стража', () => {
    // Это главное: поле не просто "читается кем-то", а меняет игру.
    must(WEATHER_EFFECTS.clear.visibilityMod === 1.0, 'в ясную погоду обзор должен быть полным');
    const вБурю = effectiveSight(стража, { visibility: WEATHER_EFFECTS.sandstorm.visibilityMod });
    must(
      вБурю < GUARD_SIGHT,
      `в песчаную бурю обзор ${вБурю} не меньше обычного ${GUARD_SIGHT}: правило не работает`
    );
    // И это меняет исход обнаружения, а не только число в отчёте.
    const игрок = { x: стража.x + 8, z: стража.z };
    must(
      spottedBy(игрок, [стража], { visibility: 1.0 }) !== null,
      'в ясную погоду на 8 единицах должен быть замечен'
    );
    // песчаная буря: обзор 6, значит 8 - уже не видит
    must(
      spottedBy(игрок, [стража], { visibility: WEATHER_EFFECTS.sandstorm.visibilityMod }) === null,
      'в песчаную бурю на 8 единицах не должен быть замечен: погода не влияет на обнаружение'
    );
  });

  it('заголовок weatherEffects.test.ts не врёт про visibilityMod', () => {
    const шапка = читать('server/src/tests/weatherEffects.test.ts').slice(0, 1600);
    must(шапка.length > 200, 'заголовок не прочитан, проверка прошла бы вхолостую');

    // 1. В шапке сказано, что visibilityMod теперь читается. Тире между именем
    //    поля и словом «читает» допускается: в шапке оно есть, и регулярка
    //    без него искала бы мимо живого текста.
    must(
      /visibilityMod\s*[-–—]?\s*читает/.test(шапка),
      'в шапке weatherEffects.test.ts нет утверждения, что visibilityMod читается: ' +
        'шапка продолжает врать, что поле мертвое, хотя правило скрытности его читает'
    );
    // 2. И назван единственный по-настоящему мёртвый модификатор. Раньше здесь
    //    стояло требование «остальные четыре не читаются» - оно само было
    //    неверным: expMod, spawnMod и specialMobs читались и до шага 2.
    must(
      /speedMod\s+-\s+единственный по-настоящему мёртвый/.test(шапка),
      'в шапке не назван единственный мёртвый модификатор speedMod'
    );
    // И сказано, почему шапка врала раньше - иначе история повторится.
    must(
      /читател[ия]|точечн/.test(шапка),
      'в шапке нет объяснения, почему прежнее утверждение «НИ ОДИН не читался» было неверным'
    );
    // 3. Старая формулировка осталась, но ТОЛЬКО в разделе "ЧТО БЫЛО", а
    //    сегодняшнее состояние описано рядом. Раздел называется "ЧТО НА САМОМ
    //    ДЕЛЕ": слово "СТАЛО" сюда не подходит, потому что рядом стоит
    //    разбор того, что утверждение врало и до шага 2.
    const было = шапка.indexOf('ЧТО БЫЛО');
    const есть = шапка.indexOf('ЧТО НА САМОМ ДЕЛЕ');
    must(было >= 0, 'в шапке нет раздела ЧТО БЫЛО, куда должно уйти старое утверждение');
    must(есть > было, 'в шапке нет раздела ЧТО НА САМОМ ДЕЛЕ после ЧТО БЫЛО');
    const староеУтверждение = /specialMobs\)\s*-\s*и НИ ОДИН не/.test(шапка);
    must(староеУтверждение, 'старое утверждение пропало совсем: его надо оставить как прошлое');
  });

  // Обход дерева объявлен здесь, чтобы им пользовались все проверки ниже:
  // и заголовок, и список потребителей.

  it('проверка умеет ловить ложь: на старой шапке она обязана упасть', () => {
    // Без этого утверждения выше - украшение. Если подменить шапку на ту,
    // что была до шага 2, проверка обязана это заметить. Делаем ровно так,
    // на копии текста, ничего не портя на диске.
    const стараяШапка = [
      '// ЧТО БЫЛО. WEATHER_EFFECTS объявлял пять модификаторов',
      '// (visibilityMod, speedMod, expMod, spawnMod, specialMobs) - и НИ ОДИН не',
      '// читался.',
    ].join('\n');

    const видитНовое = /visibilityMod\s+читает/.test(стараяШапка);
    must(
      !видитНовое,
      'проверка не отличает старую ложную шапку от новой: она всегда зелёная и ничего не ловит'
    );
  });

  it('состояние всех пяти модификаторов закреплено по живому коду', () => {
    // Что было измерено поиском по всем .ts вне tests:
    //   spawnMod      -> SpawnSystem.ts
    //   specialMobs   -> SpawnSystem.ts
    //   expMod        -> weatherExpMultiplier() -> CharacterService
    //   visibilityMod -> GameSocketHandler (правило скрытности)
    //   speedMod      -> никого: единственный мёртвый
    // Список закреплён, чтобы шапка снова не разъехалась с кодом.
    const читатели = (поле: string): string[] =>
      репозиторий.filter((f) =>
        читать(f)
          .split('\n')
          .some((l) => l.includes(`.${поле}`))
      );

    must(
      читатели('spawnMod').some((f) => f.endsWith('SpawnSystem.ts')),
      'spawnMod перестал читаться: шапка говорит, что SpawnSystem его использует'
    );
    must(
      читатели('specialMobs').some((f) => f.endsWith('SpawnSystem.ts')),
      'specialMobs перестал читаться: шапка говорит, что SpawnSystem его использует'
    );
    must(
      читатели('expMod').some((f) => f.endsWith('WorldTimeSystem.ts')),
      'expMod перестал читаться через weatherExpMultiplier()'
    );
    must(
      читатели('visibilityMod').some((f) => f.endsWith('GameSocketHandler.ts')),
      'visibilityMod перестал читаться правилом скрытности'
    );
    // А вот speedMod обязан остаться мёртвым. Если кто-то его подключит,
    // проверка упадёт - и это правильно: значит, пора чинить шапку.
    must(
      читатели('speedMod').length === 0,
      `speedMod кто-то прочитал (${читатели('speedMod').slice(0, 3).join(', ')}): ` +
        'шапка называет его единственным мёртвым, её надо привести в соответствие'
    );
  });

  it('заголовок называет speedMod единственным мёртвым', () => {
    const шапка = читать('server/src/tests/weatherEffects.test.ts').slice(0, 2200);
    must(
      /speedMod\s+-\s+единственный по-настоящему мёртвый/.test(шапка),
      'в шапке нет вывода, что мёртв только speedMod: четыре живых поля ' +
        'и одно мёртвое перепутаны, и это повторится снова'
    );
  });

  it('ни один модификатор не объявлен мёртвым по ошибке', () => {
    // Сквозная сверка: сколько полей реально читается.
    const поля = ['visibilityMod', 'speedMod', 'expMod', 'spawnMod', 'specialMobs'] as const;
    const живые = поля.filter((п) =>
      репозиторий.some((f) =>
        читать(f)
          .split('\n')
          .some((l) => l.includes(`.${п}`))
      )
    );
    must(
      живые.length === 4,
      `найдено живых модификаторов: ${живые.length} (${живые.join(', ')}), а ожидалось 4. ` +
        'Значит, либо кто-то подключил пятый, либо шапка снова разъехалась.'
    );
  });
});
