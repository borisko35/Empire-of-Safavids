// Уведомление о завершении захода получают все участники, и каждый видит свою
// долю.
//
// ЧТО БЫЛО ИЗМЕРЕНО. DungeonService.complete() делит добычу и начисляет её всем
// участникам захода, а отчёт DungeonCompleteInfo возвращает один. Сокет-обработчик
// отправлял его ОДНОМУ: тому, чей сокет пришёл с ударом, то есть убийце босса.
// Итог: опыт, золото и предметы получали все, а уведомление об этом - один.
// Участник, который присоединился к заходу, видел свои числа без объяснения,
// откуда они взялись.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ:
//   1. отчёт содержит долю каждого участника, а не одну общую;
//   2. доля совпадает с тем, что реально ушло на сервер;
//   3. событие уходит каждому участнику, у кого есть сокет;
//   4. участник без сокета (вышел) пропускается молча, а не роняет рассылку;
//   5. никто не остаётся без уведомления: список участников и список долей
//      совпадают.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const безКомментариев = (исходник: string): string =>
  исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = читать('server/src/systems/DungeonService.ts');
const сокет = читать('server/src/socket/GameSocketHandler.ts');
const сервисКод = безКомментариев(сервис);
const сокетКод = безКомментариев(сокет);

describe('Отчёт о заходе: в нём есть доля каждого', () => {
  it('отчёт объявляет доли участников', () => {
    must(
      /shares:\s*\{ characterId: string; gold: number; experience: number; items: string\[\] \}\[\]/.test(сервис),
      'в DungeonCompleteInfo нет долей участников: сообщать придётся одну общую сумму'
    );
  });

  it('доли собираются из тех же данных, что и раздача', () => {
    // Доля в отчёте и доля, ушедшая на сервер, - одно и то же число. Считать
    // заново по другой формуле означало бы показывать игроку не то, что он
    // получил: с остатком золота лидеру это расходится сразу.
    must(
      /shares:\s*получили\.map/.test(сервисКод),
      'доли в отчёте считаются отдельно от раздачи: игрок увидит не свою долю'
    );
    must(
      /characterId:\s*доля\.characterId/.test(сервисКод) && /gold:\s*доля\.gold/.test(сервисКод),
      'в отчёте нет ни персонажа, ни золота из доли'
    );
    must(
      /items:\s*доля\.items/.test(сервисКод),
      'в отчёте нет предметов доли: игрок увидит весь список захода вместо своего'
    );
  });

  it('круг раздачи остаётся прежним: предмет достаётся по порядку входа', () => {
    // Правка не должна была сломать раздачу: сундуки и предметы по-прежнему
    // идут по кругу, и каждый предмет достаётся ровно одному.
    must(
      /items: добыча\.filter\(\(_, i\) => i % народу === порядок\)/.test(сервисКод),
      'раздача по кругу входа сломана'
    );
    must(
      /const получили = участники\.map/.test(сервисКод),
      'раздача перестала считаться по участникам'
    );
  });
});

describe('Уведомление о заходе: достаёт каждого', () => {
  it('событие уходит по сокету каждого участника, а не только убийцы', () => {
    must(
      !/socket\.emit\(SERVER_EVENTS\.DUNGEON_COMPLETED/.test(сокетКод),
      'уведомление по-прежнему уходит только в сокет того, кто ударил босса: ' +
        'остальные участники получают награду молча'
    );
    must(
      /for \(const доля of dungeonDone\.shares\)/.test(сокетКод),
      'рассылка уведомления идёт не по долям, а одним сокетом'
    );
    must(
      /this\.activePlayers\.get\(доля\.characterId\)/.test(сокетКод),
      'сокет участника ищется не по его персонажу'
    );
    must(
      /сокетУчастника\.emit\(SERVER_EVENTS\.DUNGEON_COMPLETED/.test(сокетКод),
      'уведомление отправляется не в сокет участника'
    );
  });

  it('каждому уходит его доля, а не весь заход', () => {
    must(
      /\.\.\.dungeonDone,\s*\n\s*gold: доля\.gold,\s*\n\s*items: доля\.items,/.test(сокетКод),
      'в уведомлении не подставлена доля участника: все увидят весь список захода'
    );
  });

  it('участник без сокета пропускается молча', () => {
    // Вышел из захода - уведомление ему некуда слать. Это не ошибка, и падать
    // на этом нельзя: рассылка идёт в горячем месте боя.
    must(
      /if \(!сокетУчастника\) continue;/.test(сокетКод),
      'рассылка падает на участнике без сокета вместо того, чтобы его пропустить'
    );
  });

  it('задача дня по-прежнему засчитывается убийце', () => {
    // Правка не должна была задеть счётчик: он идёт по тому, кто ударил.
    must(
      /dailyTasks\.updateProgress\(attacker\.id, 'dungeon', 'any'\)/.test(сокетКод),
      'задача дня по подземелью больше не засчитывается'
    );
  });

  it('клиент умеет показать чужую долю', () => {
    // Клиент читает поля из события. Новых полей он не добавлял: показывается
    // ровно то, что сервер прислал, поэтому проверяем, что приём на месте и
    // не выкидывает список предметов.
    const клиент = читать('client/src/app/world.ts');
    must(
      /socket\.on\(SERVER_EVENTS\.DUNGEON_COMPLETED/.test(клиент),
      'клиент не слушает завершение захода'
    );
    must(
      /for \(const id of d\?\.items \?\? \[\]\)/.test(клиент),
      'клиент не показывает список предметов из уведомления'
    );
  });
});
