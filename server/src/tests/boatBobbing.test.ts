// Лодки качаются на волнах.
//
// ЧТО БЫЛО (22 октября 2026, §277). Лодки у причала стояли на воде как на
// полу: вода под ними ходила, а сами они нет, и порт с лодками читался как
// складской двор.
//
// ЧТО ТЕПЕРЬ. Лодка качается вместе с водой: по вертикали и слегка в
// сторону, и у каждой своя фаза.
//
// ЧТО ПРОВЕРЯЕТСЯ. Лодки записаны списком (движку нужен доступ), и движок
// действительно их качает — от основания, а не от нуля.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Лодки качаются на волнах', () => {
  it('лодки записаны списком с основанием и фазой', () => {
    должен(
      /export const лодкиУПира: \{ группа: THREE\.Group; y: number; фаза: number \}\[\] = \[\];/.test(ТЕРРЕЙН),
      'нет списка лодок',
    );
    // Фаза — по детерминированному генератору: после перезагрузки страницы
    // лодка должна качаться так же, а не иначе.
    должен(
      /лодкиУПира\.push\(\{ группа: boat, y: LAKE\.level \+ 0\.35, фаза: hash2\(7, 3\) \* 6\.28 \}\);/.test(ТЕРРЕЙН),
      'лодка не записана или её фаза считается случайно',
    );
  });

  it('движок качает лодки от основания', () => {
    должен(
      /л\.группа\.position\.y = л\.y \+ Math\.sin\(now \* 0\.85 \+ л\.фаза\) \* 0\.09;/.test(МИР),
      'лодка не качается по вертикали от своего основания',
    );
    должен(/л\.группа\.rotation\.z = Math\.sin\(now \* 0\.62 \+ л\.фаза\) \* 0\.035;/.test(МИР),
      'лодка не качается в сторону');
  });
});
