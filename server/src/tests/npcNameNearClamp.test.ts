// Надписи в мире не разрастаются во весь экран
//
// ЗАЧЕМ ФАЙЛ. Владелец прислал скриншот: «Стражник Фарид» во всю ширину
// экрана поверх мира. Выглядело как поломка шрифта, хотя шрифт был ни при
// чём. Причина общая для всех надписей игры.
//
// ПРИЧИНА. Надписи сделаны THREE.Sprite мирового размера
// (scale.set(...)), а у спрайтов sizeAttenuation по умолчанию включён.
// Такой спрайт не просто удаляется с расстоянием — он РАСТУТ при
// приближении к камере, без верхней границы. Подойдя вплотную к стражнику,
// игрок получал его имя на треть экрана.
//
// ГЛАВНОЕ В ЭТОМ ФАЙЛЕ. Один отказ нашлся сразу в ЧЕТЫРЁХ местах, и
// худшее из них ломалось дважды. Поэтому проверка идёт по каждому месту
// отдельно: починить одно и объявить «готово» тут не выйдет.
//
//   1. имя NPC               — размер 0.78, d >= 3.1 м
//   2. знак «!» квестодателя — размер 0.85, d >= 3.4 м
//   3. реплика горожанина    — размер 1.0,  d >= 4.0 м, depthTest: false
//   4. метка путника         — размер 0.5,  d >= 2.0 м
//
// РЕПЛИКА ЛОМАЛАСЬ ХУЖЕ ВСЕХ. У неё sort() по расстоянию, так что ближайший
// пузырь всегда первый и рисуется всегда; плюс depthTest: false — рисуется
// поверх всего, включая модель игрока. То есть худший случай совпадал с
// худшим: именно тот пузырь, который разрастался, и был единственным
// гарантированно видимым.
//
// ЧТО ПРОВЕРЯЕТСЯ. Потолок как математика (без three и без сцены — правило
// должно быть чистой функцией), затем подключение в каждом из четырёх мест
// и то, что мировые размеры из scale.set никуда не «разъехались».
import { readFileSync } from 'fs';
import { join } from 'path';

import { MAX_APPARENT, minDistance, spriteVisible } from '../../../client/src/app/game3d/spriteClamp';

const root = join(__dirname, '..', '..', '..');
const read = (p: string): string => readFileSync(join(root, p), 'utf8');

function must(cond: boolean, why: string): void {
  if (!cond) throw new Error(why);
}

describe('Потолок видимого размера спрайта', () => {
  it('видимый размер не зависит от того, какой спрайт', () => {
    // Смысл правила: «сколько места надпись занимает на экране» ограничено
    // для всех одинаково, а порог в метрах у каждой свой.
    // Здесь кажущийся размер для всех один и тот же — 0.25.
    for (const worldSize of [0.5, 0.78, 0.85, 1.0]) {
      const порог = minDistance(worldSize);
      must(Math.abs(worldSize / порог - MAX_APPARENT) < 1e-9,
        `у размера ${worldSize} на своём пороге кажущийся размер не равен потолку`);
    }
  });

  it('чем крупнее спрайт, тем дальше он гаснет', () => {
    // Реплика (1.0) крупнее имени (0.78) и должна гаснуть дальше. Если бы
    // пороги не зависели от размера, правило перестало бы иметь смысл.
    must(minDistance(1.0) > minDistance(0.78),
      'порог не зависит от размера спрайта — крупная надпись гаснет раньше мелкой');
  });

  it('в упор не видно, издалека видно', () => {
    // Границу берём из самого правила, а не выписываем числом. Порог для
    // 0.78 равен 3.12 м: прикидка «3.1» в проверке дала бы красный тест
    // на правильном коде — и «починка» теста сдвинула бы сам порог в
    // игре ради того, чтобы зелёное совпало с прикидкой.
    const порог = minDistance(0.78);
    must(spriteVisible(0.78, порог) === true, 'на своём пороге надпись должна ещё быть видна');
    must(spriteVisible(0.78, порог * 0.99) === false, 'чуть ближе порога надпись должна гаснуть');
    must(spriteVisible(0.78, 0) === false, 'в упор надпись видна — это и есть поломка');
    must(spriteVisible(0.78, 40) === true, 'вдали надпись должна быть видна');
  });

  it('порог не ноль', () => {
    // Если бы потолок был Infinity или MAX_APPARENT стремился к нулю,
    // minDistance дал бы 0 и правило выключилось бы молча.
    must(Number.isFinite(minDistance(1.0)) && minDistance(1.0) > 1,
      `порог ${minDistance(1.0)} не похож на порог в метрах`);
  });
});

describe('Все четыре надписи под потолком', () => {
  const npc = read('client/src/app/game3d/npc.ts');
  const civilians = read('client/src/app/game3d/civilians.ts');
  const roadTraffic = read('client/src/app/game3d/roadTraffic.ts');
  const world3d = read('client/src/app/game3d/world3d.ts');

  it('1. имя NPC гасится по камере', () => {
    must(/n\.sprite\.visible = spriteVisible\(n\.worldSize, d\)/.test(npc),
      'имя NPC не гасится по потолку');
    must(/Math\.hypot\(n\.x - камера\.x, n\.y - камера\.y, n\.z - камера\.z\)/.test(npc),
      'расстояние считается не от камеры — имя будет гаснуть не там');
    must(/update\(dt: number, now: number, камера\?: THREE\.Vector3\): void/.test(npc),
      'сигнатура update не приняла камеру');
    must(/this\.npcs\.update\(dt, now, this\.camera\.position\)/.test(world3d),
      'вызов из world3d не передаёт камеру: гасить не с чем сравнивать');
  });

  it('2. знак «!» квестодателя гасится наравне с именем', () => {
    // Знак «!» — тот же спрайт мирового размера. Когда чинили гигантское
    // имя, его легко было пропустить: он не тронут визуально в первом
    // скриншоте, но подойдя к квестодателю, разрастался так же.
    must(/names\.push\(\{ sprite: marker, worldSize: 0\.85,/.test(npc),
      'знак «!» не внесён в список надписей — он остаётся без потолка');
    must(/names\.push\(\{ sprite: name, worldSize: 0\.78,/.test(npc),
      'имя NPC не внесено в список надписей');
  });

  it('3. реплика горожанина гасится', () => {
    // Здесь ловушка: сортировка по расстоянию ставит ближайший пузырь
    // первым, поэтому одного «прячем дальние» тут недостаточно — раньше
    // дальние и не прятались, а ближний был виден ВСЕГДА.
    must(/spriteVisible\(BUBBLE_WORLD_SIZE, Math\.sqrt\(dist2\(c\)\)\)/.test(civilians),
      'реплика горожанина не гасится по потолку');
    must(/const BUBBLE_WORLD_SIZE = 1\.0;/.test(civilians),
      'нет константы размера пузыря');
  });

  it('4. метка путника гасится', () => {
    must(/spriteVisible\(WALKER_MARKER_SIZE, Math\.hypot\(p\.x - px, p\.z - pz\)\)/.test(roadTraffic),
      'метка путника не гасится по потолку');
    must(/const WALKER_MARKER_SIZE = 0\.5;/.test(roadTraffic),
      'нет константы размера метки путника');
  });

  it('мировые размеры из scale.set не разъехались с константами', () => {
    // Потолок считается от высоты в scale.set. Если высоту подправят на глаз
    // и забудут про константу, порог молча поедет: либо надпись начнёт
    // гаснуть слишком рано, либо снова разрастётся. Поэтому проверяем
    // именно пару «scale.set ↔ константа» в обоих местах.
    must(/sp\.scale\.set\(2\.6, BUBBLE_WORLD_SIZE, 1\)/.test(civilians),
      'scale пузыря больше не берёт BUBBLE_WORLD_SIZE');
    must(/sp\.scale\.set\(WALKER_MARKER_SIZE, WALKER_MARKER_SIZE, 1\)/.test(roadTraffic),
      'scale метки путника больше не берёт WALKER_MARKER_SIZE');
    must(/sprite\.scale\.set\(worldW, 0\.78, 1\)/.test(npc),
      'высота имени NPC в scale.set изменилась — 0.78 в names.push должен совпадать');
    must(/sprite\.scale\.set\(0\.85, 0\.85, 1\)/.test(npc),
      'высота знака «!» в scale.set изменилась — 0.85 в names.push должен совпадать');
  });

  it('без камеры имена не гаснут', () => {
    // Отдельные пробники сцены зовут update без камеры. Если тогда имена
    // гаснут, пробник рисует город без единой надписи — и это выглядит
    // как поломка, хотя правило сработало верно.
    must(/if \(камера\) \{/.test(npc),
      'гашение выполняется без проверки, есть ли камера');
  });

  it('все четыре места тянут одно правило, а не копию формулы', () => {
    // Копия формулы в четвёртом месте = баг в пятом. Проверяем импорты.
    for (const [файл, код] of [
      ['npc.ts', npc], ['civilians.ts', civilians], ['roadTraffic.ts', roadTraffic],
    ] as const) {
      must(/import \{ spriteVisible \} from '\.\/spriteClamp';/.test(код),
        `${файл} не берёт общее правило spriteClamp`);
    }
  });
});