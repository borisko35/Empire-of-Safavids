// Трейлер должен вставать не только на нашем домене.
//
// ЗАЧЕМ ФАЙЛ. Страница самодостаточна: внешних стилей и скриптов у неё нет
// вовсе, весь вид внутри одного файла. Именно поэтому её можно выложить куда
// угодно одним куском - на itch.io, в iframe, в Discord, хоть на флешку.
//
// Абсолютные пути это ломают. '/assets/bg-history.png' на нашем домене
// работает СЛУЧАЙНО: страница лежит в корне, и корень совпадает с началом
// сайта. Откроешь по адресу с подкаталогом - https://vlas.itch.io/empire/ -
// и браузер пойдёт за https://vlas.itch.io/assets/bg-history.png, то есть
// мимо. Пять сцен из семи пусты, и снаружи это выглядит как «игра
// сломалась».
//
// Вторая ловушка, на которую легко наступить при правке: og:image и
// twitter:image обязаны остаться АБСОЛЮТНЫМИ. Скрапер, собирающий карточку
// для Discord, Telegram или Reddit, запрашивает их со своего сервера и не
// знает, откуда пришла страница. Относительный путь там не работает нигде,
// и «сделаем всё относительным разом» тихо убирает превью из соцсетей.
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const путьТрейлера = join(корень, 'client/web/trailer.html');
const трейлер = readFileSync(путьТрейлера, 'utf-8');
const каталогСтраницы = dirname(путьТрейлера);

/**
 * must объявлен как asserts - иначе он не сужает типы, и компилятор
 * требует проверки на null после каждого вызова. Это уже записано в проекте
 * как ловушка, и на неё наступили второй раз: без asserts сборка падала с
 * TS18047 на четырёх местах, хотя проверка рядом стояла и падала бы в нужный
 * момент сама.
 */
function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Все значения img: из сцен - и полные пути, и имена из SHOTS. */
function сцены(): { полный: string; имя: string }[] {
  const шоты = /const SHOTS = '([^']*)'/.exec(трейлер);
  must(шоты, 'на странице нет const SHOTS — проверка не знает, где искать кадры из SHOTS');
  const префикс = шоты[1];
  return [...трейлер.matchAll(/img: [^,\n]*?['`]([^'`]*\.png)['`]/g)].map(m => {
    const имя = m[1];
    return { имя, полный: имя.includes('/') ? имя : префикс + имя };
  });
}

describe('Трейлер встанет не только на нашем домене', () => {
  it('ни один кадр не задан путём от корня', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА.
    const отКорня = сцены()
      .filter(s => s.полный.startsWith('/'))
      .map(s => s.полный);
    expect({ от_корня: [...new Set(отКорня)] }).toEqual({ от_корня: [] });
  });

  it('все кадры лежат рядом со страницей и существуют', () => {
    // Относительный путь, которого нет, - это тот же самый пропавший файл,
    // только найти его труднее: снаружи он выглядит как «страница не
    // загрузилась».
    const уехали: Record<string, string> = {};
    const нетФайла: Record<string, string> = {};
    const все = сцены();
    for (const s of все) {
      if (!s.полный.startsWith('assets/')) { уехали[s.полный] = 'не под assets/'; continue; }
      const файл = join(каталогСтраницы, s.полный);
      if (!existsSync(файл)) { нетФайла[s.полный] = 'нет файла'; continue; }
      if (statSync(файл).size < 20_000) нетФайла[s.полный] = 'пустой или обрезан';
    }
    // Страховка от молчания: ноль сцен выглядит как «всё в порядке», если
    // не с чем сравнить. Регулярка уже сбивалась дважды - то на строках
    // SHOTS + '...', то на полных путях, молча пропуская кадры.
    must(все.length > 0, 'не нашлось ни одной сцены — возможно, сменился формат записи');
    expect({ сцен_найдено: все.length, уехали, нет_файла: нетФайла })
      .toEqual({ сцен_найдено: 21, уехали: {}, нет_файла: {} });
  });

  it('картинка превью осталась абсолютной', () => {
    // og:image и twitter:image относительными быть НЕ МОГУТ. Скрапер
    // Discord, Telegram и Reddit запрашивает их со своей машины. Убрать
    // слеши «для единообразия» — значит тихо убрать превью из всех трёх
    // соцсетей сразу.
    const og = /og:image" content="([^"]+)"/.exec(трейлер);
    const tw = /twitter:image" content="([^"]+)"/.exec(трейлер);
    must(og && tw, 'нет og:image или twitter:image — превью не соберётся');
    expect({
      og_https: /^https:\/\//.test(og[1]),
      twitter_https: /^https:\/\//.test(tw[1]),
      // И обе указывают на существующий файл: превью, ссылающееся в пустоту,
      // выглядит как «ссылка плохая», а не как «картинка потерялась».
      og_файл_есть: existsSync(join(корень, 'client/web',
        new URL(og[1]).pathname.replace(/^\//, ''))),
      twitter_файл_есть: existsSync(join(корень, 'client/web',
        new URL(tw[1]).pathname.replace(/^\//, ''))),
    }).toEqual({
      og_https: true, twitter_https: true, og_файл_есть: true, twitter_файл_есть: true,
    });
  });

  it('страница остаётся самодостаточной: ни одного внешнего стиля и скрипта', () => {
    // Смысл всей затеи - один файл, который куда угодно загружается. Как
    // только появляется <link rel="stylesheet">, страница перестаёт быть
    // переносимой, и относительные пути кадров перестают иметь смысл.
    //
    // Считаются ТОЛЬКО то, что реально грузится. Первая версия брала все
    // <link href> подряд и ловила rel="canonical" - который по правилам
    // обязан быть абсолютным, ведёт на наш же домен и не грузит ничего.
    // Проверка требовала сделать относительным URL, который относительным
    // быть не может: это сломало бы канонический адрес страницы.
    const внешние = [
      ...[...трейлер.matchAll(/<link\b[^>]*\brel="stylesheet"[^>]*>/g)]
        .map(m => /href="([^"]+)"/.exec(m[0])?.[1] ?? '?'),
      ...[...трейлер.matchAll(/<script\b[^>]*\bsrc="([^"]+)"/g)].map(m => m[1]),
      // И отдельно: <link> без rel не считаем, но если он вдруг окажется
      // не-каноническим и не-иконкой, это повод посмотреть.
      ...[...трейлер.matchAll(/<link\b[^>]*>/g)]
        .map(m => m[0])
        .filter(тег => !/rel="(canonical|icon|apple-touch-icon)"/.test(тег))
        .map(() => 'проверьте этот link руками'),
    ].filter(Boolean);
    expect({ внешние_файлы: внешние }).toEqual({ внешние_файлы: [] });
  });

  it('живая проверка из подкаталога лежит в репозитории и запускается', () => {
    // Проверка поднимает настоящий http-сервер, раскладывает страницу в
    // /itchdemo/ и запрашивает кадры так, как это сделал бы браузер. Без
    // неё всё вышесказанное остаётся рассуждением.
    const инструмент = join(корень, 'tools/check-trailer-subdir.js');
    must(existsSync(инструмент), 'нет tools/check-trailer-subdir.js');
    const код = readFileSync(инструмент, 'utf-8');
    expect({
      // Именно new URL, а не склейка строк. Склейка чинится файловой
      // системой: '/itchdemo/' + '/assets/x' превращается в
      // '/itchdemo/assets/x', проверка рапортует «OK», и поломанная
      // страница проходит. На этом уже поймали один раз.
      разрешает_как_браузер: /new URL\(имя/.test(код),
      // И требует ровно шесть уникальных кадров - иначе пропуск снова
      // станет безголосым.
      требует_шесть: /ОЖИДАЕМО_КАДРОВ = 6/.test(код),
      // И запрещает выход за пределы витрины.
      следит_за_выходом: /вВитрине/.test(код),
    }).toEqual({ разрешает_как_браузер: true, требует_шесть: true, следит_за_выходом: true });
  });

  it('временная витрина инструмента не попадёт в репозиторий', () => {
    const игнор = readFileSync(join(корень, '.gitignore'), 'utf-8');
    expect({
      папка_в_игноре: /tools\/trailer-subdir-site\//.test(игнор),
    }).toEqual({ папка_в_игноре: true });
  });
});
