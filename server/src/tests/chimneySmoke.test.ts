// Дым из печных труб.
//
// ЧТО БЫЛО (21 октября 2026, §266). В городе есть печные трубы, но они не
// дымят: город из жары выглядел выключенным — над крышами ни дыма, ни пара.
//
// ЧТО ТЕПЕРЬ. Из труб идёт дым: редкими клубами, каждый из своей трубы, и
// только у тех труб, что не дальше девяноста метров от игрока.
//
// ЧТО ПРОВЕРЯЕТСЯ. Трубы запоминаются при постройке города; дым идёт из них
// по списку; дальние трубы не дымят (их дым ушёл бы в туман, а стоил бы кадр).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Дым из печных труб', () => {
  it('трубы запоминаются при постройке города', () => {
    должен(/export const дымныеТрубы: \{ x: number; y: number; z: number \}\[\] = \[\];/.test(ТЕРРЕЙН),
      'нет списка дымных труб');
    должен(
      /if \(п\.труба\) \{[\s\S]{0,700}?дымныеТрубы\.push\(\{/.test(ТЕРРЕЙН),
      'трубы не запоминаются: дым идти неоткуда',
    );
    // Мировые координаты: труба стоит в городе, а список должен быть в мире.
    должен(/x: CITY\.x \+ п\.x \+ п\.w \* 0\.3,/.test(ТЕРРЕЙН), 'трубы запоминаются не в мировых координатах');
  });

  it('дым идёт из случайной трубы и не из дальних', () => {
    должен(
      /const труба = дымныеТрубы\[Math\.floor\(Math\.random\(\) \* дымныеТрубы\.length\)\];/.test(МИР),
      'дым идёт не из случайной трубы: из одной идёт сильнее, чем из других',
    );
    должен(
      /if \(Math\.hypot\(труба\.x - me\.pos\.x, труба\.z - me\.pos\.z\) < 90\)/.test(МИР),
      'дальние трубы тоже дымят: дым уходит в туман, а стоит кадра',
    );
    должен(/this\.дымТруб\.всплеск\(труба\.x, труба\.y, труба\.z\);/.test(МИР), 'клуб дыма не появляется');
    должен(/this\.дымТруб\.update\(dt\);/.test(МИР), 'дым не обновляется');
  });

  it('дым вычищается вместе с миром', () => {
    должен(/this\.дымТруб\?\.dispose\(\);/.test(МИР), 'дым не вычищается');
  });
});
