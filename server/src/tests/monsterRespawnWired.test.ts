// Респавн: два конкурирующих понятия, одно из которых было выдумкой.
//
// ЧТО БЫЛО. Срок воскресения жил в двух местах:
//   - MonsterDefinition.respawnTime — заполнен у 41 монстра, от 30 секунд до
//     двух недель, и НЕ ЧИТАЛСЯ НИГДЕ;
//   - SpawnPoint.respawnTime — обязательное поле, задано у всех 53 точек.
// То есть чтобы изменить срок появления монстра, надо было найти и править
// каждую его точку, а значение прямо на монстре ничего не значило.
//
// ЧЕСТНАЯ ОГОВОРКА. Сверка показала, что 26 точек из 53 отличаются от
// монстра намеренно — иногда вдесятеро (моб_rain_spirit: монстр 600, точка
// 120). Это правка под конкретный лагерь, а не дубль. Поэтому монстр сделан
// ЗНАЧЕНИЕМ ПО УМОЛЧАНИЮ, а не единственным источником. Проверка требует
// и того и другого и не утверждает, что поведение изменилось сегодня: все
// точки задают срок сами, и монстр пока служит только тот, кто его не задал.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const монстры = читать('server/src/data/monsters.ts');
const спавн = код('server/src/systems/SpawnSystem.ts');

describe('Респавн: поле монстра больше не выдумка', () => {
  it('у монстров срок действительно заполнен', () => {
    // Без этой проверки тест был бы страховкой от воображаемой проблемы.
    const значений = (монстры.match(/respawnTime:/g) ?? []).length;
    must(значений >= 30, `respawnTime есть у ${значений} монстров - чинить нечего`);
  });

  it('спавн читает срок монстра', () => {
    must(
      /определение\?\.respawnTime/.test(спавн) || /MONSTERS_DATABASE\[sp\.monsterId\]\?\.respawnTime/.test(спавн),
      'спавн не читает срок монстра: поле по-прежнему мёртвое',
    );
  });

  it('срок точки - исключение, а не обязательный дубль', () => {
    must(/respawnTime\?: number/.test(спавн), 'срок точки всё ещё обязателен');
    must(
      /sp\.respawnTime \?\?/.test(спавн),
      'срок точки не является исключением: значение монстра им перекрыто всегда',
    );
  });

  it('есть запас, если не задано ни там, ни там', () => {
    // Иначе респавн ломал бы молча: undefined в арифметике даёт NaN, а
    // `elapsed >= NaN` ложно навсегда — монстр не появлялся бы уже никогда.
    must(/ЗАПАС_РЕСПАВНА/.test(спавн), 'запаса нет');
    must(
      /ЗАПАС_РЕСПАВНА =\s*3600/.test(спавн),
      'запас не равен часу: без причины взятое другое число запутает того, кто будет настраивать',
    );
  });
});

describe('Респавн: точки сохраняют свою правку', () => {
  it('точки со своим сроком остались', () => {
    // Обратная сторона: свести всё к одному монстру значило бы стереть
    // настройку лагерей. Сверка показала 26 отличающихся точек - например
    // mob_rain_spirit: монстр 600, точка 120. Это правка, а не дубль.
    const точек = (спавн.match(/respawnTime:/g) ?? []).length;
    must(точек >= 40, `точек со своим сроком ${точек}: настройка лагерей потерялась`);
  });
});