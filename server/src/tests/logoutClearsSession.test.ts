// Выход из аккаунта обязан отозвать сессию, а не только нарисовать экран входа.
//
// ЧТО БЫЛО. Выход был в двух местах, и места вели себя по-разному:
//
//   - из меню мира (world.ts): запрос уходит, затем logoutLocal() зовёт
//     clearAuth() и показывает экран входа. Правильно.
//   - с экрана персонажей (screens/chars.ts): запрос уходит и СРАЗУ зовётся
//     `location.reload()`.
//
// У второго пути две поломки, и обе невидимы.
//
//   1. `location.reload()` срывает запрос на полпути. Отзыв токена на сервере
//      (`authService.logout(token, userId)`) не доходит, и сессия остаётся живой
//      после того, как игрок вышел.
//   2. `clearAuth()` здесь не звали вовсе, поэтому `eos_token` остаётся в
//      localStorage, и после перезагрузки приложение читает его заново. Выход
//      выглядит как «ничего не сделал».
//
// ПОЧЕМУ ЭТО ТИХО. И то и другое выглядит правильно: экран входа на месте, ошибок
// нет. Ровно этот класс поломок закрыл напоминание о голосовании (§149) — там
// тост не появлялся, а запрос уходил с 400. Здесь «успешный» выход, который
// ничего не отзывает.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

// asserts, а не просто void: без него TypeScript не сужает тип после проверки,
// и каждое обращение к результату регулярки требовало бы повторной проверки.
// Так объявлено в остальных наборах проекта.
function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Код без комментариев: пояснение о поломке стоит рядом с местом поломки, и без
// вырезания оно попало бы в проверку. Тот же класс ошибки, что в §142 и §149.
function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const ЭКРАН = код(читать('client/src/app/screens/chars.ts'));
const МИР = код(читать('client/src/app/world.ts'));
const ГЛАВНАЯ = код(читать('client/src/app/main.ts'));
const СОСТОЯНИЕ = код(читать('client/src/app/state.ts'));

/**
 * Тело обработчика выхода — по балансу скобок, а не регуляркой.
 *
 * ПОЧЕМУ НЕ РЕГУЛЯРКА. Тело содержит `.catch(() => {})`, и ленивая регулярка
 * вида `\{[\s\S]{0,400}?\}\s*\)` обрывалась ровно на нём — на первом `})` подряд.
 * В обрезанном тексте не оказывалось `logoutLocal`, и проверка порядка падала на
 * правильном коде. Баланс скобок берёт всё тело целиком.
 */
function обработчикВыхода(текст: string): string {
  const начало = текст.indexOf("$('btn-logout').addEventListener");
  должен(начало >= 0, 'обработчик выхода на экране персонажей не найден: проверка ослепла');
  let глубина = 0;
  let началоТела = -1;
  for (let i = начало; i < текст.length; i++) {
    if (текст[i] === '{') {
      if (глубина === 0) началоТела = i;
      глубина++;
    } else if (текст[i] === '}') {
      глубина--;
      if (глубина === 0 && началоТела >= 0) return текст.slice(началоТела, i + 1);
    }
  }
  throw new Error('обработчик выхода не закрыт: код переехал, проверка ослепла');
}

describe('Выход из аккаунта', () => {
  it('ни один выход не реализован перезагрузкой страницы', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. reload() здесь был единственной причиной обеих
    // поломок: он обрывает запрос и обнуляет возможность почистить сессию.
    // Проверяется по телу обработчика, а не по всему файлу: перезагрузка может
    // быть законной где-то ещё, не внутри выхода из аккаунта.
    const выход = обработчикВыхода(ЭКРАН);
    должен(
      !/location\.reload\s*\(/.test(выход),
      'выход с экрана персонажей снова делает location.reload(): запрос отзыва срывается, ' +
        'локальная сессия не чистится',
    );
  });

  it('оба выхода ведут себя одинаково', () => {
    // Расхождение между местами и было поломкой: одно чистило сессию, другое
    // нет. Проверяется не текстом, а наличием одного и того же приёма в обоих.
    должен(
      /api\.logout\s*\(/.test(ЭКРАН),
      'выход с экрана персонажей не зовёт api.logout(): сессия живёт на сервере',
    );
    должен(
      /api\.logout\s*\(/.test(МИР),
      'выход из мира перестал звать api.logout()',
    );
    for (const [имя, текст] of [['экрана персонажей', ЭКРАН], ['меню мира', МИР]] as const) {
      должен(
        /logoutLocal\s*\(/.test(текст),
        `выход из ${имя} не зовёт logoutLocal(): локальный токен остаётся в localStorage`,
      );
    }
  });

  it('logoutLocal действительно чистит токен', () => {
    // Проверяется конец цепочки, а не только её начало: если logoutLocal вдруг
    // перестанет звать clearAuth, предыдущая проверка останется зелёной.
    должен(
      /export function logoutLocal\s*\(\s*\)\s*:\s*void\s*\{\s*clearAuth\s*\(\s*\)/.test(ГЛАВНАЯ),
      'logoutLocal больше не чистит локальную сессию в первую очередь',
    );
    должен(
      /localStorage\.removeItem\(\s*'eos_token'\s*\)/.test(СОСТОЯНИЕ),
      'clearAuth больше не убирает токен из localStorage: выход перестал быть выходом',
    );
  });

  it('отказ сервера не отменяет локальный выход', () => {
    // Запрос может не дойти. Если из-за этого игрок остаётся в аккаунте, то при
    // первом же обрыве связи «выход» перестаёт работать — а это ровно то, что
    // делает его незаметно ненадёжным. Локальная чистка обязана быть безусловной.
    const выход = обработчикВыхода(ЭКРАН);
    const позицияЗапроса = выход.indexOf('api.logout');
    const позицияЧистки = выход.indexOf('logoutLocal');
    должен(
      позицияЗапроса > 0 && позицияЧистки > позицияЗапроса,
      'локальная чистка должна идти после отправки запроса, но не внутри его ожидания',
    );
    должен(
      !/await\s+api\.logout\s*\(/.test(выход[0]),
      'выход ждёт ответа сервера перед чисткой: обрыв связи оставит игрока в аккаунте',
    );
  });
});