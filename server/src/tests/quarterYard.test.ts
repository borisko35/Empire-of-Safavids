// Жилой квартал: двор между домами.
//
// ЧТО БЫЛО (21 октября 2026, §240). Семь домов стояли кольцом и смотрели
// в центр, а внутри кольца было пусто: ни дорожек, ни колодца, ни зелени.
//
// ЧТО ТЕПЕРЬ (§326). Дорожки от колодца к каждому дому; сам колодец —
// готовая GLB-модель (Quaternius): каменное кольцо с крышей и воротом.
// Процедурный колодец из семи примитивов удалён.
//
// ЧТО ПРОВЕРЯЕТСЯ. Модель колодца лежит в манифесте; во дворе стоит decorВещь
// 'well'; дорожки идут к домам; между домами зелень.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
  animals?: { file: string; name: string; bytes: number }[];
};
const вМанифесте = (раздел: 'decor' | 'animals', имя: string): boolean =>
  (МАНИФЕСТ[раздел] ?? []).some((д) => д.name === имя);

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Двор жилого квартала', () => {
  it('в середине кольца домов стоит готовый колодец', () => {
    должен(вМанифесте('decor', 'well'), 'well.glb нет в манифесте: колодец не доедет');
    должен(
      /decorВещь\(city, 'well', центрX, центрZ, \{ размер: [\d.]+, y: [\d.]+, ry: [\d.]+ \}\);/.test(код),
      'в середине жилого квартала нет колодца: двор пустой',
    );
    // И коллайдер у колодца остался: сквозь него не проходят.
    должен(/addCollider\(CITY\.x \+ центрX, CITY\.z \+ центрZ, 1\.3\);/.test(код),
      'у колодца нет коллайдера');
    // Процедурных колец больше нет.
    должен(!/CylinderGeometry\(1\.1, 1\.2, 0\.9, 12\)/.test(код), 'колодец снова из примитивов');
  });

  it('от колодца к каждому дому идёт дорожка', () => {
    должен(
      /const дорожка = new THREE\.Mesh\(new THREE\.BoxGeometry\(2\.2, 0\.12, длина\), streetMat\)/.test(код),
      'дорожек от колодца к домам нет: двор пустой',
    );
    должен(/дорожка\.rotation\.y = Math\.atan2\(ux, uz\)/.test(код), 'дорожка повёрнута не к дому');
    должен(
      /куст\(city, центрX \+ \(a\[0\] \+ b\[0\]\) \/ 2, центрZ \+ \(a\[1\] \+ b\[1\]\) \/ 2, 0\.3, 1\.0\)/.test(код),
      'между домами нет зелени',
    );
  });
});
