// Жилой квартал: двор между домами.
//
// ЧТО БЫЛО (21 октября 2026, §240). Семь домов стояли кольцом и смотрели
// в центр, а внутри кольца было пусто: ни дорожек, ни колодца, ни зелени.
// Двор без хозяйства читается как пустырь между домами.
//
// ЧТО ТЕПЕРЬ. Дорожки от колодца к каждому дому, сам колодец с валом и
// ведром, и кусты в промежутках между домами.
//
// ЧТО ПРОВЕРЯЕТСЯ. Двор есть в середине кольца, дорожки идут к домам, а
// колодец настоящий (каменное кольцо, стойки, вал, ведро).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Двор жилого квартала', () => {
  it('в середине кольца домов стоит колодец', () => {
    должен(
      /const колодец = new THREE\.Mesh\(new THREE\.CylinderGeometry\(1\.1, 1\.2, 0\.9, 12\), MAT\.sandstone\)/.test(
        код,
      ),
      'в середине жилого квартала нет колодца: двор пустой',
    );
    // Настоящий колодец: стойки, перекладина, вал и ведро.
    должен(/const вал = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.12, 0\.12, 1\.8, 8\), MAT\.wood\)/.test(код),
      'у колодца нет вала: это просто каменное кольцо');
    должен(/const ведро = new THREE\.Mesh/.test(код), 'у колодца нет ведра');
  });

  it('от колодца к каждому дому идёт дорожка', () => {
    должен(
      /const дорожка = new THREE\.Mesh\(new THREE\.BoxGeometry\(2\.2, 0\.12, длина\), streetMat\)/.test(код),
      'дорожек от колодца к домам нет: двор пустой',
    );
    // Дорожка идёт по направлению к дому, а не вбок.
    должен(/дорожка\.rotation\.y = Math\.atan2\(ux, uz\)/.test(код), 'дорожка повёрнута не к дому');
    // И кусты в промежутках между домами.
    должен(
      /куст\(city, центрX \+ \(a\[0\] \+ b\[0\]\) \/ 2, центрZ \+ \(a\[1\] \+ b\[1\]\) \/ 2, 0\.3, 1\.0\)/.test(
        код,
      ),
      'между домами нет зелени',
    );
  });
});
