// У каждого региона есть город, и он стоит там, где надо.
//
// ЧТО БЫЛО. Регионов на карте семь, а построенных поселений шесть, причём
// четыре из них стояли в регионе Исфахана: столица, лагерь, караван-сарай
// и ещё один лагерь. То есть в шести регионах — Тебризе, Ширазе, Кавказе,
// Месопотамии, Хорасане и заливе — не было НИ ОДНОГО здания, и игрок,
// выбравший такой регион, возрождался на своём якоре в пустом поле.
//
// ПОЧЕМУ ЭТО МОЛЧАЛО. Ни одна проверка не смотрела на поселения вообще:
// cityPlacement не существовало. В��рые города на месте стояли, пустые
// регионы выглядели как «ещё не построенная часть карты», а не как поломка.
//
// ЧТО ПРОВЕРЯЕМ. Для каждого региона, кроме Исфахана, город обязан:
//   - существовать и стоять в зоне своего региона;
//   - стоять на суше (иначе игрок возрождается в воде);
//   - совпадать с якорем региона (иначе возрождение — в стороне от города);
//   - иметь ровную землю под домами, иначе постройки висят и тонут.
//
// ЧТО УМЕЕТСЯ СЧИТАТЬСЯ. Данные городов читаются из ИСХОДНИКА terrain.ts
// регуляркой, а не импортом: файл требует document и canvas, в Node не
// импортируется, а серверный tsconfig вообще не включает DOM и не
// покрывает каталог client. Положение берётся из текста объявления:
// дублировать числа в проверке — значит завести вторую копию, которая
// разойдётся.
//
// ЧЕГО ПРОВЕРКА НЕ ДЕЛАЕТ. Она не мерит высоту земли под городами.
// terrainHeight живёт в файле, который нельзя импортировать из серверной
// проверки, а копия функции в проверке измеряла бы саму себя. Поэтому
// здесь проверяется, что РОВНЯЛКА ОБЪЯВЛЕНА для всех городов и с
// достаточным радиусом, а фактическая ровность измерена один раз
// инструментом и записана в сообщении коммита: размах высот под домами
// равен нулю во всех шести городах.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { getZoneAt, ZONES, REGION_SPAWNS } from '../../../shared/constants';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

interface Город {
  region: string;
  x: number;
  z: number;
  radius: number;
  level: number;
  kind: string;
  nameRu: string;
}

/**
 * Города читаются из исходника terrain.ts. Импорт невозможен: файл на
 * верхнем уровне строит текстуры через document.createElement('canvas'),
 * и в Node падает. Копия чисел в проверке разошлась бы с оригиналом при
 * первой же правке — а проверка обязана ловить расхождение, а не прятать
 * его.
 */
function города(): Город[] {
  const исходник = readFileSync(join(корень, 'client/src/app/game3d/terrain.ts'), 'utf-8');
  const re = /\{\s*region:\s*'([a-z_]+)',\s*x:\s*(-?\d+),\s*z:\s*(-?\d+),\s*radius:\s*(\d+),\s*level:\s*(-?[\d.]+),\s*kind:\s*'([a-z]+)',\s*nameRu:\s*'([^']+)'/g;
  const найдено: Город[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(исходник)) !== null) {
    найдено.push({
      region: m[1],
      x: Number(m[2]),
      z: Number(m[3]),
      radius: Number(m[4]),
      level: Number(m[5]),
      kind: m[6],
      nameRu: m[7],
    });
  }
  return найдено;
}

/** Размах высот под городами здесь не меряется — см. пояснение в шапке. */

const ГОРОДА = города();
const РЕГИОНЫ = [...new Set(ZONES.map((з) => з.region))];

describe('Города регионов: у каждого региона есть свой', () => {
  it('каждый город виден на карте мира', () => {
    // ЧТО БЫЛО. Карта рисовала поселения из захардкоженного списка из
    // шести записей — тех, что строит buildSettlements. Шесть городов
    // регионов в список не попали, и игрок видел на карте пустоту там, где
    // стоит город. Это молчало: список выглядел полным, потому что на
    // карте было что показать.
    //
    // ЧТО ПРОВЕРЯЕМ. Список поселений на карте выводится из REGION_TOWNS,
    // а не повторяет его руками. Тогда новый город появляется на карте
    // сам, и забыть его уже нельзя.
    const hud = readFileSync(join(корень, 'client/src/app/hud.ts'), 'utf-8');
    must(
      /import\s*\{[^}]*REGION_TOWNS[^}]*\}\s*from\s*'\.\/game3d\/terrain'/.test(hud),
      'hud.ts не импортирует REGION_TOWNS — города регионов не попадут на карту',
    );
    must(
      /REGION_TOWNS\.map\(/s.test(hud),
      'Список поселений карты не строится из REGION_TOWNS. Значит, новый город на карте не появится, пока кто-то не вспомнит про него.',
    );
    must(
      /\.\.\.ГОРОДА_РЕГИОНОВ_НА_КАРТЕ/.test(hud),
      'Города регионов вычисляются, но не добавлены в список поселений карты',
    );
    // Подпись города берётся из словаря регионов, а не из nameRu в
    // данных: nameRu всегда по-русски, и игрок с английским интерфейсом
    // увидел бы «Хорасан» вместо «Khorasan».
    must(
      /nameKey:\s*`regions\.\$\{t\.region\}`/.test(hud),
      'Подпись города на карте берётся не из словаря regions.* — у игрока с другим языком будет русское название',
    );
  });

  it('на карте есть границы регионов и их названия', () => {
    // Границ не было вовсе, и игрок не мог понять, где кончается один
    // регион и начинается другой. Регионы - горизонтальные полосы, и
    // полосы считаются из ZONES, а не пишутся числами: рукописные границы
    // разошлись бы с зонами молча, как уже разошлись координаты якорей.
    const hud = readFileSync(join(корень, 'client/src/app/hud.ts'), 'utf-8');
    must(
      /import\s*\{[^}]*ZONES[^}]*\}\s*from\s*'\.\.\/\.\.\/\.\.\/shared\/constants'/.test(hud),
      'hud.ts не импортирует ZONES — границы регионов посчитать не из чего',
    );
    must(
      /ПОЛОСЫ_РЕГИОНОВ/.test(hud),
      'На карте нет полос регионов: границы и названия не рисуются',
    );
    must(
      /setLineDash/.test(hud),
      'Границы регионов не рисуются пунктиром — сплошная линия читалась бы как дорога',
    );
    must(
      /t\(`regions\.\$\{полоса\.region\}`\)/.test(hud),
      'Название региона на карте берётся не из словаря regions.*',
    );
    // У каждого региона должно быть название в словаре — иначе на карте
    // появится путь ключа вместо подписи.
    const отсутствуют: string[] = [];
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(readFileSync(join(корень, `shared/locales/${язык}.json`), 'utf-8')) as Record<string, Record<string, string>>;
      for (const регион of РЕГИОНЫ) {
        if (typeof словарь.regions?.[регион] !== 'string') {
          отсутствуют.push(`${язык}: regions.${регион}`);
        }
      }
    }
    must(
      отсутствуют.length === 0,
      `в словарях нет названий регионов для карты:\n  ${отсутствуют.join('\n  ')}`,
    );
  });

  it('города вообще прочитались из исходника', () => {
    // Проверка на саму себя. Пустой список означал бы, что регулярка
    // устарела, и ВСЕ проверки ниже прошли бы вхолостую, сообщив «все
    // регионы обслужены», хотя не проверен ни один.
    must(
      ГОРОДА.length >= 6,
      `Прочитано ${ГОРОДА.length} городов, а их не меньше шести. Регулярка не ловит формат объявления, и проверки ниже молчали бы вхолостую.`,
    );
  });

  it('у каждого региона, кроме Исфахана, есть город', () => {
    // Исфахан исключён не по прихоти: там уже стоит столица, отдельная
    // постройка на 500 строк, и второй город рядом с ней был бы дублем.
    const безГорода = РЕГИОНЫ.filter(
      (р) => р !== 'isfahan' && !ГОРОДА.some((г) => г.region === р),
    );
    must(
      безГорода.length === 0,
      `в этих регионах нет города, и игрок возрождается в пустом поле: ${безГорода.join(', ')}`,
    );
  });

  it('каждый город стоит в зоне своего региона', () => {
    const неверные: string[] = [];
    for (const г of ГОРОДА) {
      const зона = getZoneAt(г.x, г.z);
      if (зона === null) {
        неверные.push(`${г.region}: (${г.x}, ${г.z}) вне всякой зоны`);
      } else if (зона.region !== г.region) {
        неверные.push(`${г.region}: (${г.x}, ${г.z}) в зоне ${зона.id} региона ${зона.region}`);
      }
    }
    must(
      неверные.length === 0,
      `города стоят не в своих регионах:\n  ${неверные.join('\n  ')}`,
    );
  });

  it('ни один город не стоит в воде', () => {
    // Возрождение берёт якорь региона, а не город: якорь проверяет
    // spawnPlacement. Здесь про другое — здание в воде означает, что
    // под ним пустота и стены висят в воде.
    const вВоде: string[] = [];
    for (const г of ГОРОДА) {
      if (isWater(г.x, г.z)) вВоде.push(`${г.region}: (${г.x}, ${г.z})`);
    }
    must(вВоде.length === 0, `города стоят в воде:\n  ${вВоде.join('\n  ')}`);
  });

  it('город стоит на якоре своего региона', () => {
    // Иначе возрождение в городе означает «в городе, но в двухстах
    // метрах от него»: игрок выходит у ворот в поле.
    const сдвинутые: string[] = [];
    for (const г of ГОРОДА) {
      const якорь = REGION_SPAWNS[г.region];
      must(якорь, `у региона ${г.region} нет якоря в REGION_SPAWNS`);
      const сдвиг = Math.hypot(г.x - якорь.x, г.z - якорь.z);
      if (сдвиг > 2) {
        сдвинутые.push(`${г.region}: город (${г.x}, ${г.z}), якорь (${якорь.x}, ${якорь.z}) — ${Math.round(сдвиг)}`);
      }
    }
    must(
      сдвинутые.length === 0,
      `города разошлись с якорями возрождения:\n  ${сдвинутые.join('\n  ')}`,
    );
  });

  it('земля под городами ровняется, и радиуса хватает на дома', () => {
    // Ровнялка не проверяется измерением, а проверяется объявлением:
    // terrain.ts нельзя импортировать из серверной проверки. Требуется
    // ровно две вещи — цикл по городам и радиус, вдвое больший
    // городского.
    //
    // ПОЧЕМУ ИМЕННО ВДВОЕ. flatten() держит ровную землю только в
    // центральных 55% СВОЕГО радиуса, а дома стоят на 86% городского
    // плюс их собственная ширина. При равных радиусах дома попали бы в
    // зону смешивания и стояли на разной высоте: часть висела бы, часть
    // была бы вкопана. Поэтому ровняем на 2*R, и ровная зона до 1.1*R
    // покрывает все постройки с запасом.
    const исходник = readFileSync(join(корень, 'client/src/app/game3d/terrain.ts'), 'utf-8');
    const цикл = /for \(const t of REGION_TOWNS\) h = flatten\(h, x, z, t\.x, t\.z, ([^,]+), t\.level\)/.exec(исходник);
    must(
      цикл,
      'В terrainHeight нет ровнялки по городам регионов. Без неё дома стоят на невыровненной земле: часть висит, часть вкопана.',
    );
    must(
      цикл![1].includes('radius * 2'),
      `Ровнялка городов идёт на «${цикл![1].trim()}», а нужно на radius * 2: flatten держит ровную землю только в центральных 55% своего радиуса, а дома стоят на 86% городского.`,
    );
    // Постройки не должны вылезать за ровную зону
    const слишкомШирокие = ГОРОДА.filter((г) => г.radius > 1.1 * (г.radius * 2 * 0.55));
    must(
      слишкомШирокие.length === 0,
      `у этих городов постройки выходят за ровную зону:\n  ${слишкомШирокие.map((г) => г.region).join('\n  ')}`,
    );
  });

  it('города не налезают друг на друга', () => {
    // Два города в 200 метрах друг от друга — нормально, а вот в
    // ста — это одна стена на двоих и торговая площадь в обоих.
    const пересечения: string[] = [];
    for (let i = 0; i < ГОРОДА.length; i++) {
      for (let j = i + 1; j < ГОРОДА.length; j++) {
        const a = ГОРОДА[i];
        const b = ГОРОДА[j];
        const d = Math.hypot(a.x - b.x, a.z - b.z);
        if (d < (a.radius + b.radius) * 1.2) {
          пересечения.push(`${a.region} и ${b.region}: расстояние ${Math.round(d)}`);
        }
      }
    }
    must(
      пересечения.length === 0,
      `города пересекаются:\n  ${пересечения.join('\n  ')}`,
    );
  });

  it('у каждого города есть названный персонаж региона', () => {
    // Всё, что делает город узнаваемым, — это памятник в середине.
    // Шесть одинаковых поселков читаются как один, скопированный шесть
    // раз, сколько бы домов их ни было.
    const виды = new Set(ГОРОДА.map((г) => г.kind));
    must(
      виды.size === ГОРОДА.length,
      `у ${ГОРОДА.length} городов только ${виды.size} видов: ${[...виды].join(', ')}. Каждый регион обязан отличаться силуэтом.`,
    );
    const безИмени = ГОРОДА.filter((г) => !г.nameRu || г.nameRu.length < 2);
    must(
      безИмени.length === 0,
      `у этих городов не записано имя: ${безИмени.map((г) => г.region).join(', ')}`,
    );
  });
});
