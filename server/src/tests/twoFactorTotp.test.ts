// TOTP по RFC 6238, проверенный НАСТОЯЩИМИ векторами стандарта.
//
// ГЛАВНОЕ. Числа ниже взяты из приложения A1 самого RFC 6238 (HMAC-SHA-1,
// секрет "12345678901234567890", то есть base32
// "GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ"). Это единственный источник истины,
// который нельзя подогнать под собственную реализацию: если сдвинуть
// период, окно, разрядность, порядок байтов в счётчике или усечение по
// RFC 4226 - векторы перестанут совпадать.
//
// Стандарт печатает ВОСЕМИзначные коды. Наш разряд - 6, поэтому берутся
// последние шесть цифр: операция по модулю 10^6 отбрасывает именно их.
import {
  вBase32, изBase32, новыйСекрет, кодШага, кодНа, проверитьКод,
  ссылкаOtpauth, новыеКодыВосстановления, хэшКодаВосстановления,
  шаг, ПЕРИОД, ЦИФРЫ,
} from '../auth/TwoFactor';

// Секрет из стандарта.
const СТАНДАРТНЫЙ_СЕКРЕТ = 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ';

/** Восьмизначные коды из RFC 6238, приложение A1. */
const ВЕКТОРЫ: { время: number; восемь: string }[] = [
  { время: 59, восемь: '94287082' },
  { время: 1111111109, восемь: '07081804' },
  { время: 1111111111, восемь: '14050471' },
  { время: 1234567890, восемь: '89005924' },
  { время: 2000000000, восемь: '69279037' },
  { время: 20000000000, восемь: '65353130' },
];

describe('base32', () => {
  it('переводит байты в текст и обратно без потерь', () => {
    // Секрет должен пережить туда-обратно ровно, иначе код у игрока и код
    // на сервере считаются от разных ключей, и вход невозможен.
    for (const байты of [
      new Uint8Array([1, 2, 3]),
      new Uint8Array(20).fill(0x41),
      new Uint8Array([0]),
      new Uint8Array([0xff, 0x00, 0xff]),
    ]) {
      const текст = вBase32(байты);
      expect({ в: текст, туда: [...изBase32(текст)] })
        .toEqual({ в: текст, туда: [...байты] });
    }
  });

  it('нулевой байт даёт одну букву, а не две', () => {
    // Если нулевой байт давал 'AA', секрет расползалсяся бы по длине, и
    // игрок, вводивший ключ руками, получал бы другой секрет.
    expect({ base32: вBase32(new Uint8Array([0])), длина: вBase32(new Uint8Array([0])).length })
      .toEqual({ base32: 'AA', длина: 2 });
  });

  it('мусор на входе не роняет, а отбрасывается', () => {
    // Секрет мог прити из поля, которое игрок переписал. Исключение
    // посреди входа - худший вариант: игрок получит 500 и не поймёт почему.
    //
    // Число байтов СЧИТАЕТСЯ, а не написано на глаз. Я сначала поставил
    // 15, потому что 16 символов в строке это 15 байт - но ' GEZD GNBV '
    // это 14 значащих символов плюс два пробела, а пробелы отбрасываются.
    // Восемь символов base32 дают ровно 5 байт.
    const очищено = 'GEZDGNBV';
    expect({
      очищено_символов: очищено.length,
      байт_из_них: изBase32(' GEZD GNBV ').length,
      ожидается: Math.floor(очищено.length * 5 / 8),
    }).toEqual({ очищено_символов: 8, байт_из_них: 5, ожидается: 5 });
  });
});

describe('TOTP совпадает с векторами RFC 6238', () => {
  it('шестизначный код - это хвост восьмизначного из стандарта', () => {
    // Проверяются ВСЕ векторы, а не один: сдвиг на один шаг периода даёт
    // другой код, но первый вектор (59 секунд) прошёл бы и при ошибке в
    // счётчике, если он маленький.
    const сверенные: { время: number; наш: string; из_стандарта: string; сошлось: boolean }[] =
      ВЕКТОРЫ.map(({ время, восемь }) => {
        const наш = кодНа(СТАНДАРТНЫЙ_СЕКРЕТ, время * 1000, 8);
        return { время, наш, из_стандарта: восемь, сошлось: наш === восемь };
      });
    expect(сверенные).toEqual(ВЕКТОРЫ.map(({ время, восемь }) => ({
      время, наш: восемь, из_стандарта: восемь, сошлось: true,
    })));
  });

  it('шаг считается как floor(время / 30)', () => {
    // Шаг - это целое число тридцатисекундных окон. Ошибка на единицу здесь
    // даёт чужой код, и вход невозможен целиком.
    expect({
      ноль: шаг(0),
      ровно_период: шаг(30),
      минус_секунда: шаг(29),
      минус_один: шаг(ПЕРИОД * 1000 - 1),
      период: ПЕРИОД,
    }).toEqual({ ноль: 0, ровно_период: 1, минус_секунда: 0, минус_один: 999, период: 30 });
  });

  it('код всегда ровно из шести цифр, даже когда он короткий', () => {
    // Код 42 должен печататься как 000042. Иначе игрок, у которого телефон
    // показывает «42», введёт не то - и подсказка в приложении сойдётся
    // не с тем, что ждёт сервер.
    const код = кодНа(СТАНДАРТНЫЙ_СЕКРЕТ, 59000);
    expect({ длина: код.length, только_цифры: /^\d+$/.test(код), цифр: ЦИФРЫ })
      .toEqual({ длина: 6, только_цифры: true, цифр: 6 });
  });
});

describe('Проверка кода', () => {
  const сейчас = 1111111109000;

  it('принимает верный код', () => {
    const код = кодНа(СТАНДАРТНЫЙ_СЕКРЕТ, сейчас);
    const р = проверитьКод(СТАНДАРТНЫЙ_СЕКРЕТ, код, сейчас);
    expect({ ok: р.ok, причина: р.reason }).toEqual({ ok: true, причина: '' });
  });

  it('принимает код соседнего окна: часы телефона расходятся', () => {
    // Без этого игрок с телефоном, спешащим на полминуты, не смог бы войти
    // никогда. Проверяются оба соседа и отказ за их пределами.
    const соседСзади = кодШага(СТАНДАРТНЫЙ_СЕКРЕТ, шаг(сейчас / 1000) - 1);
    const соседВпереди = кодШага(СТАНДАРТНЫЙ_СЕКРЕТ, шаг(сейчас / 1000) + 1);
    const наШагНазад = кодШага(СТАНДАРТНЫЙ_СЕКРЕТ, шаг(сейчас / 1000) - 2);
    const р = (код: string) => проверитьКод(СТАНДАРТНЫЙ_СЕКРЕТ, код, сейчас).ok;
    expect({ сзади: р(соседСзади), впереди: р(соседВпереди), за_пределом: р(наШагНазад) })
      .toEqual({ сзади: true, впереди: true, за_пределом: false });
  });

  it('отказывает постороннему коду', () => {
    const р = проверитьКод(СТАНДАРТНЫЙ_СЕКРЕТ, '000000', сейчас);
    expect({ ok: р.ok, причина: р.reason }).toEqual({ ok: false, причина: 'two_factor_invalid' });
  });

  it('мусор во вводе отвергается до сравнения', () => {
    // Пустая строка, буквы, пробелы, семь цифр. Всё это должно упасть так
    // же, как неверный код, и с той же причиной - иначе по причине можно
    // отличить «мусор» от «неверно», и это лишняя подсказка тому, кто
    // перебирает.
    const варианты = ['', '  ', 'abc', '12345a', '1234567', '12345', '−12345'];
    const причины = [...new Set(варианты
      .map(код => проверитьКод(СТАНДАРТНЫЙ_СЕКРЕТ, код, сейчас).reason))];
    expect({ вариантов: варианты.length, все_одни_и_те_же: причины })
      .toEqual({ вариантов: 7, все_одни_и_те_же: ['two_factor_invalid'] });
  });

  it('повтор того же кода не принимается', () => {
    // Код, подсмотренный через плечо, действует своё окно - а это до
    // тридцати секунд, в течение которых его можно слать подряд. Повтор
    // отвергается: один код, одно использование.
    const код = кодНа(СТАНДАРТНЫЙ_СЕКРЕТ, сейчас);
    const шагКода = шаг(сейчас / 1000);
    const первый = проверитьКод(СТАНДАРТНЫЙ_СЕКРЕТ, код, сейчас, 1, 0);
    const повтор = проверитьКод(СТАНДАРТНЫЙ_СЕКРЕТ, код, сейчас, 1, шагКода);
    expect({
      первый: первый.ok,
      повтор: повтор.ok,
      причина_повтора: повтор.reason,
    }).toEqual({ первый: true, повтор: false, причина_повтора: 'two_factor_replayed' });
  });

  it('без секрета отказ называет причину, а не падает', () => {
    const р = проверитьКод('', '123456', сейчас);
    expect({ ok: р.ok, причина: р.reason })
      .toEqual({ ok: false, причина: 'two_factor_no_secret' });
  });

  it('чужой секрет не подходит', () => {
    const мой = новыйСекрет();
    const чужой = кодНа(новыйСекрет(), сейчас);
    expect({ ок: проверитьКод(мой, чужой, сейчас).ok }).toEqual({ ок: false });
  });
});

describe('Секреты и ссылки', () => {
  it('новый секрет разный и достаточно длинный', () => {
    const секреты = new Set(Array.from({ length: 20 }, () => новыйСекрет()));
    expect({ разных: секреты.size, длина: новыйСекрет().length })
      .toEqual({ разных: 20, длина: 32 });
  });

  it('ссылка для телефона содержит всё, что нужно приложению', () => {
    // Без issuer в приложении рядом лежат коды других сайтов, и игрок не
    // отличит, какой из них его. Без algorithm приложение угадывает.
    const ссылка = ссылкаOtpauth('ABCDEFGH', 'игрок', 'Empire of Safavids');
    const части = new URL(ссылка);
    expect({
      протокол: части.protocol,
      издатель_есть: ссылка.includes('issuer=Empire%20of%20Safavids'),
      алгоритм_указан: ссылка.includes('algorithm=SHA1'),
      разряд_указан: ссылка.includes(`digits=${ЦИФРЫ}`),
      период_указан: ссылка.includes(`period=${ПЕРИОД}`),
    }).toEqual({
      протокол: 'otpauth:',
      издатель_есть: true,
      алгоритм_указан: true,
      разряд_указан: true,
      период_указан: true,
    });
  });
});

describe('Коды восстановления', () => {
  it('их ровно десять, они разные и выглядят как коды', () => {
    const коды = новыеКодыВосстановления();
    expect({
      количество: коды.length,
      разных: new Set(коды).size,
      длина: коды[0].length,
      это_шестнадцатеричные: коды.every(к => /^[0-9A-F]{10}$/.test(к)),
    }).toEqual({ количество: 10, разных: 10, длина: 10, это_шестнадцатеричные: true });
  });

  it('хэш зависит от соли и не хранит сам код', () => {
    // Одинаковый код у двух игроков обязан давать разные хэши, иначе утечка
    // одного хэша раскрыла бы оба кода. И сам код в хэше не читается.
    const код = новыеКодыВосстановления()[0];
    const х1 = хэшКодаВосстановления(код, 'соль-один');
    const х2 = хэшКодаВосстановления(код, 'соль-другой');
    expect({
      разные: х1 !== х2,
      одинаковая_с_той_же_солью: хэшКодаВосстановления(код, 'соль-один') === х1,
      кода_в_хэше_нет: !х1.toUpperCase().includes(код),
    }).toEqual({ разные: true, одинаковая_с_той_же_солью: true, кода_в_хэше_нет: true });
  });

  it('регистр и пробелы не мешают: игрок вводит с телефона', () => {
    const код = новыеКодыВосстановления()[0];
    const эталон = хэшКодаВосстановления(код, 'с');
    expect({
      строчными: хэшКодаВосстановления(код.toLowerCase(), 'с') === эталон,
      с_пробелами: хэшКодаВосстановления(` ${код} `, 'с') === эталон,
    }).toEqual({ строчными: true, с_пробелами: true });
  });
});
