// Настоящий посох мистика: шестой пакет из Assets.
//
// Процедурный посох (палка со сферой) заменяется готовой моделью с текстурой.
// Подмена позже построения: сначала процедурный (мгновенно), потом модель
// (когда доедет); нет файла — остаётся процедурный. Мистик теперь с видимым
// посохом и в игре, и в превью: прятали процедурный, настоящий показывают.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РИГ = читать('client/src/app/game3d/realRig.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  weapons?: { file: string; name: string; bytes: number }[];
};

describe('Посох: готовая модель вместо процедурной', () => {
  it('файл в источнике сборки и совпадает с манифестом', () => {
    must(
      МАНИФЕСТ.weapons !== undefined && МАНИФЕСТ.weapons.length >= 1,
      'в манифесте нет раздела weapons: файл посоха никто не сверяет с диском'
    );
    for (const запись of МАНИФЕСТ.weapons!) {
      const путь = join(корень, 'client/src/app/public', запись.file);
      must(existsSync(путь), `нет файла оружия ${запись.file}: мистик останется с палкой`);
      must(
        statSync(путь).size === запись.bytes,
        `${запись.file}: на диске ${statSync(путь).size}, в манифесте ${запись.bytes}`
      );
    }
  });

  it('модель сжата и лёгкая', () => {
    const путь = join(корень, 'client/src/app/public/models/weapons/staff.glb');
    must(existsSync(путь), 'файла посоха нет: проверять нечего');
    const buf = readFileSync(путь);
    const json = JSON.parse(buf.slice(20, 20 + buf.readUInt32LE(12)).toString('utf-8')) as {
      extensionsUsed?: string[];
    };
    must(
      (json.extensionsUsed ?? []).includes('KHR_draco_mesh_compression'),
      'посох без Draco: оружие весит как сырое'
    );
    must(buf.length < 2 * 1024 * 1024, `посох весит ${(buf.length / 1048576).toFixed(1)} МБ: многовато для палки`);
  });

  it('подмена идёт поверх процедурного, а не вместо', () => {
    // Процедурный строится мгновенно, модель доезжает позже. Если строить
    // только модель, рука останется пустой на время загрузки.
    must(
      /this\.оружие = buildWeapon\(this\.видОружия\);/.test(РИГ),
      'процедурное оружие не строится сразу: рука пуста, пока едет модель'
    );
    must(
      /if \(this\.видОружия === 'staff'\) void this\.заменитьПосох\(\);/.test(РИГ),
      'подмена посоха не вызывается: модель лежит, а в руке палка'
    );
    must(
      /загрузитьСцену\('weapons\/staff'\)/.test(РИГ),
      'посох грузится не из weapons/staff: путь разъедется с манифестом молча'
    );
  });

  it('модель нормализуется под процедурный габарит', () => {
    // Посох 2 м в человеческий рост не встанет: габарит процедурного —
    // низ −0.3, высота 1.6. Без нормализации модель либо дылда, либо обрубок.
    must(/ПОСОХ_ВЫСОТА = 1\.6;/.test(РИГ), 'нет высоты посоха: модель встанет как есть');
    must(/ПОСОХ_НИЗ = -0\.3;/.test(РИГ), 'нет низа посоха: рукоять не под кистью');
    must(
      /модель\.scale\.setScalar\(k\);/.test(РИГ),
      'модель не масштабируется: двухметровый посох в руке как есть'
    );
    must(
      /const k = ПОСОХ_ВЫСОТА \/ высота;/.test(РИГ),
      'масштаб считается не от габарита модели: формула сломана, посох дылда или обрубок'
    );
    must(
      /свет\.position\.y = ПОСОХ_НИЗ \+ ПОСОХ_ВЫСОТА;/.test(РИГ),
      'свет навершия потерян при подмене: шар без свечения мёртвый'
    );
  });

  it('подмена отменяется, если вид сменили или риг разобрали', () => {
    // Модель едет секунды; за это время игрок сменит оружие или выйдет.
    // Без проверки в руке окажется чужой посох или посох у разобранного рига.
    must(
      /if \(!сцена \|\| !рука \|\| this\.видОружия !== 'staff'\) return;/.test(РИГ),
      'подмена не проверяет вид и руку: опоздавшая модель встанет куда попало'
    );
  });

  it('игра ставит вид по классу и показывает посох мистика', () => {
    // Раньше все ходили с мечами, а мистик — вообще без оружия. Оба пути
    // выдачи (создание рига и синхронизация) обязаны ставить вид.
    const выдачи = (МИР.match(/setWeaponKind\??\.?\(CLASS_WEAPON\[/g) || []).length;
    must(
      выдачи === 2,
      `вид оружия ставится ${выдачи} раз из 2 путей выдачи: где-то снова меч у всех`
    );
    must(
      !/equipWeapon\(p\.charClass !== 'sufi_mystic'\)/.test(МИР) &&
        !/equipWeapon\(charClass !== 'sufi_mystic'\)/.test(МИР),
      'мистик снова без оружия: настоящий посох никто не увидит'
    );
    must(
      /CLASS_WEAPON/.test(МИР) && /from '\.\/realRig'/.test(МИР),
      'мир не берёт карту оружия из realRig: вид задаётся неизвестно откуда'
    );
  });
});
