// Декор из готовых моделей: акведук деревни.
//
// Первый пакет из папки Assets: разрушенная аркада из пяти сегментов к
// востоку от лесной деревни (строка списка владельца требует у деревни
// акведуки). Конвейер: FBX из архива → Blender (децимация 3.7 млн → 66к,
// Draco, JPEG) → public/models/decor → сцена с коллайдерами.
//
// ЧТО ПРОВЕРЯЕТСЯ. Файл лежит в источнике сборки и совпадает с манифестом;
// сцена его грузит (путь, Draco, коллайдеры); аркада стоит у деревни, на
// суше, вне домов; сегментов несколько (аркада, а не камень).
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
};

function деревня(): { x: number; z: number } {
  const м = /export const VILLAGE = \{ x: (-?\d+), z: (-?\d+), radius: (\d+)/.exec(ТЕРРЕЙН);
  must(м !== null, 'не нашли VILLAGE в terrain.ts: деревня переехала, проверка слепа');
  return { x: Number(м![1]), z: Number(м![2]) };
}

describe('Акведук деревни: модель на месте и в сцене', () => {
  it('файл декора в источнике сборки и совпадает с манифестом', () => {
    must(
      МАНИФЕСТ.decor !== undefined && МАНИФЕСТ.decor.length >= 1,
      'в манифесте нет раздела decor: файл декора никто не сверяет с диском',
    );
    for (const запись of МАНИФЕСТ.decor!) {
      const путь = join(корень, 'client/src/app/public', запись.file);
      must(existsSync(путь), `нет файла декора ${запись.file}: сцена останется без аркады`);
      must(
        statSync(путь).size === запись.bytes,
        `${запись.file}: на диске ${statSync(путь).size}, в манифесте ${запись.bytes}`
      );
    }
  });

  it('модель сжата и лёгкая, а не сырой FBX', () => {
    // 3.7 млн треугольников исходника в веб тащить нельзя: децимация и Draco.
    const путь = join(корень, 'client/src/app/public/models/decor/aqueduct-seg.glb');
    must(existsSync(путь), 'файла акведука нет: проверять нечего');
    const buf = readFileSync(путь);
    const json = JSON.parse(buf.slice(20, 20 + buf.readUInt32LE(12)).toString('utf-8')) as {
      extensionsUsed?: string[];
    };
    must(
      (json.extensionsUsed ?? []).includes('KHR_draco_mesh_compression'),
      'акведук без Draco: геометрия весит как сырая'
    );
    must(
      buf.length < 10 * 1024 * 1024,
      `акведук весит ${(buf.length / 1048576).toFixed(1)} МБ: в веб столько не возят`
    );
  });

  it('сцена грузит акведук с Draco и коллайдерами', () => {
    must(
      /const AQUEDUCT_MODEL = 'decor\/aqueduct-seg\.glb';/.test(ТЕРРЕЙН),
      'модель акведука не подключена к сцене: файл лежит, а аркады нет'
    );
    must(
      /new DRACOLoader\(\)/.test(ТЕРРЕЙН) && /setDecoderPath\('\/game\/draco\/'\)/.test(ТЕРРЕЙН),
      'загрузчик декора без Draco: сжатая геометрия не разберётся'
    );
    must(
      /export function buildAqueduct\(scene: THREE\.Scene\): void/.test(ТЕРРЕЙН),
      'нет построителя акведука: сегментам негде вставать'
    );
    must(
      /addCollider\(px, pz, 0\.9\);/.test(ТЕРРЕЙН),
      'у сегментов нет коллайдеров: сквозь аркаду ходят пешком'
    );
    must(
      /buildAqueduct\(this\.scene\);/.test(читать('client/src/app/game3d/world3d.ts')),
      'построитель не вызван из мира: код есть, а аркады нет'
    );
  });

  it('аркада стоит у деревни, на суше и вне домов', () => {
    // Площадка мерялась: восток, сухо, размах 0.2–0.3. Проверка повторяет
    // замер по тем же функциям воды, а не по памяти автора.
    const д = деревня();
    const м = /export const AQUEDUCT = \{ x: VILLAGE\.x \+ (\d+), z: VILLAGE\.z ([+-]) (\d+), count: (\d+), step: ([\d.]+) \};/.exec(
      ТЕРРЕЙН
    );
    must(м !== null, 'константа AQUEDUCT не найдена: аркада едет неизвестно куда');
    const dx = Number(м![1]);
    const dz = (м![2] === '-' ? -1 : 1) * Number(м![3]);
    const count = Number(м![4]);
    const step = Number(м![5]);
    must(count >= 3, `сегментов ${count}: один камень — не аркада`);
    for (let i = 0; i < count; i++) {
      const px = д.x + dx + (i - (count - 1) / 2) * step;
      const pz = д.z + dz;
      must(
        !isWater(px, pz),
        `сегмент ${i} в (${px}, ${pz}) стоит в воде: аркада утонула`
      );
      const отДеревни = Math.hypot(px - д.x, pz - д.z);
      must(
        отДеревни >= 14 && отДеревни <= 40,
        `сегмент ${i} в ${Math.round(отДеревни)} от центра деревни: внутри домов (кольцо 10) или в чистом поле`
      );
    }
  });
});


describe('Шатёр и кузница: модели на месте и в сцене', () => {
  // Третий и четвёртый пакеты из Assets. Файлы и манифест покрывает общий
  // цикл выше (все записи decor) — здесь только привязка к местам.
  it('построители вызывают общий загрузчик, а не копии', () => {
    // Копии загрузчика расходились бы молча: путь, Draco, fallback.
    must(
      /export function loadDecorModel\(path: string\)/.test(ТЕРРЕЙН),
      'нет общего загрузчика декора: каждая модель тащит свою копию'
    );
    for (const вызов of ['buildTradeTent', 'buildVillageForge']) {
      const начало = ТЕРРЕЙН.indexOf(`export function ${вызов}(`);
      // Тело функции — до её закрывающей скобки, а не N символов: иначе
      // проверка залезла бы в следующую функцию и нашла чужой вызов.
      // Первая версия так и делала — ломка её не ломала.
      // Перенос строки — через регулярку: в файле \r\n, и '\n}\n' не найдётся.
      const хвост = ТЕРРЕЙН.slice(начало);
      const конецОтн = хвост.search(/\r?\n\}\r?\n/);
      const тело = конецОтн > 0 ? хвост.slice(0, конецОтн) : '';
      must(
        /placeDecor\(scene, 'decor\//.test(тело),
        `${вызов} ставит модель мимо общего загрузчика`
      );
    }
    // Сам placeDecor обязан идти через общий загрузчик, а не грузить напрямую:
    // иначе первая же копия пути разъедется молча.
    must(
      /function placeDecor\([\s\S]{0,600}?loadDecorModel\(path\)/.test(ТЕРРЕЙН),
      'placeDecor грузит модель напрямую: общий загрузчик обходится'
    );
    must(
      /buildTradeTent\(this\.scene\);/.test(читать('client/src/app/game3d/world3d.ts')) &&
        /buildVillageForge\(this\.scene\);/.test(читать('client/src/app/game3d/world3d.ts')),
      'построители не вызваны из мира: код есть, а шатра и кузницы нет'
    );
  });

  it('шатёр в базарном квартале, кузница в деревне, обе на суше', () => {
    const д = деревня();
    const город = /export const CITY = \{ x: (\d+), z: (\d+)/.exec(ТЕРРЕЙН);
    must(город !== null, 'не нашли CITY: столица переехала, проверка слепа');
    const сх = Number(город![1]);
    const сz = Number(город![2]);
    const шатёр = /export const TRADE_TENT = \{ x: CITY\.x \+ (\d+), z: CITY\.z, lift: ([\d.]+), ry: ([-\d.]+) \};/.exec(
      ТЕРРЕЙН
    );
    must(шатёр !== null, 'константа шатра не найдена: шатёр едет неизвестно куда');
    // Базарный квартал (84, 0, r = 13) в координатах столицы: шатёр обязан
    // быть внутри квартала, а не в чистом поле.
    const шx = сх + Number(шатёр![1]);
    must(
      Math.hypot(шx - (сх + 84), сz - сz) <= 13,
      `шатёр в (${шx}, ${сz}): вне базарного квартала`
    );
    must(!isWater(шx, сz), 'шатёр стоит в воде');
    const кузница = /export const VILLAGE_FORGE = \{ x: VILLAGE\.x, z: VILLAGE\.z ([+-]) (\d+), lift: ([\d.]+), ry: ([-\d.]+) \};/.exec(
      ТЕРРЕЙН
    );
    must(кузница !== null, 'константа кузницы не найдена');
    const кz = д.z + (кузница![1] === '-' ? -1 : 1) * Number(кузница![2]);
    must(!isWater(д.x, кz), 'кузница стоит в воде');
    const отДеревни = Math.abs(кz - д.z);
    must(
      отДеревни >= 12 && отДеревни <= 30,
      `кузница в ${Math.round(отДеревни)} от центра деревни: внутри домов или в чистом поле`
    );
  });

  it('подъём над землёй задан из габаритов, а не на глаз', () => {
    // Обе модели отцентрены (низ −0.91/−0.95): ставить на groundHeight
    // значило бы вкопать по пояс. Подъём обязан равняться глубине низа.
    must(
      /lift: 0\.91/.test(ТЕРРЕЙН),
      'подъём шатра не 0.91: низ модели на −0.91, шатёр вкопан или висит'
    );
    must(
      /lift: 0\.95/.test(ТЕРРЕЙН),
      'подъём кузницы не 0.95: низ модели на −0.95'
    );
  });
});


describe('Руина ворот: арка поперёк дороги', () => {
  // Пятый пакет из Assets. Файл и манифест покрывает общий цикл выше.
  it('арка стоит на дороге к воротам, а не в воротах', () => {
    // Рабочие створки в самих воротах трогать нельзя: у руины механики нет.
    // Дистанция CITY.radius + 35 от центра: ворота на radius, руина снаружи.
    must(
      /const dist = CITY\.radius \+ 35;/.test(ТЕРРЕЙН),
      'дистанция руины не от радиуса города: арка уедет в поле или в ворота'
    );
    const город = /export const CITY = \{ x: (\d+), z: (\d+), radius: (\d+) \};/.exec(ТЕРРЕЙН);
    must(город !== null, 'не нашли CITY: столица переехала, проверка слепа');
    const сх = Number(город![1]);
    const сz = Number(город![2]);
    const радиус = Number(город![3]);
    const a = Math.atan2(-сz, -сх);
    const x = сх + Math.cos(a) * (радиус + 35);
    const z = сz + Math.sin(a) * (радиус + 35);
    must(!isWater(x, z), `руина в (${x.toFixed(0)}, ${z.toFixed(0)}) стоит в воде`);
    // До городских ворот ~35: не затыкает створки (проём ворот ±9.5).
    const ворота = /export const GATE = \(\(\) => \{[\s\S]{0,200}?CITY\.radius/.test(ТЕРРЕЙН);
    must(ворота, 'якорь GATE потерян: руину не от чего отмерять');
  });

  it('проём смотрит вдоль дороги, коллайдеры только на устоях', () => {
    // Проём вдоль локальной Z (проверено рендером): ось ложится на радиус.
    must(
      /ry: Math\.atan2\(Math\.cos\(a\), Math\.sin\(a\)\),/.test(ТЕРРЕЙН),
      'поворот арки не кладёт проём на дорогу: дорога упрётся в стену'
    );
    must(
      /const бок = 3\.0;/.test(ТЕРРЕЙН),
      'разнос устоев не задан числом: проход могут замуровать молча'
    );
    // Середина свободна: коллайдер по центру означал бы стену вместо арки.
    const тело = ТЕРРЕЙН.slice(ТЕРРЕЙН.indexOf('export function buildRuinGate('));
    const хвост = тело.slice(0, тело.search(/\r?\n\}\r?\n/));
    const вСередине = /addCollider\(x, z,/.test(хвост);
    must(!вСередине, 'коллайдер по центру проёма: арка непроходная, это стена');
    must(
      /addCollider\(x \+ dx, z \+ dz, 1\.5\);/.test(хвост) && /addCollider\(x - dx, z - dz, 1\.5\);/.test(хвост),
      'устоев нет по бокам: сквозь боковины ходят пешком'
    );
  });

  it('масштаб из размера обломка, а не на глаз', () => {
    // Модель метрового обломка (0.98): масштаб 8 даёт арку 7.8 × 5.9.
    // Масштаб 1 оставил бы садовую арку по колено.
    must(/scale: 8,/.test(ТЕРРЕЙН), 'масштаб арки не 8: обломок встанет как есть');
    must(
      /buildRuinGate\(this\.scene\);/.test(читать('client/src/app/game3d/world3d.ts')),
      'построитель не вызван из мира: код есть, а арки нет'
    );
  });
});
