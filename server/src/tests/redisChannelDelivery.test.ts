// Канал Redis, в который публикуют, обязан иметь подписчика.
//
// ЧТО БЫЛО. Одиннадцать каналов публиковались и не имели ни одного
// подписчика. Redis pub/sub не ругается на сообщение в пустоту: publish
// возвращает число доставленных подписчиков, и его никто не смотрел.
// Сообщение просто исчезало.
//
// Что из-за этого не работало:
//   - партия менялась (кто-то вступил, вышел, партия расформировалась),
//     и участники узнавали об этом только при повторном открытии панели;
//   - новый лот на аукционе не объявлялся;
//   - баунти на игрока не показывался;
//   - осады гильдий публиковали объявление в global:notification, куда
//     не подписан был никто (это отмечено комментарием в SiegeSystem);
//   - молчание, телепорт и выдача предмета администратором до игрока
//     не доходили: он стоял на месте и не понимал почему, либо не видел
//     выданный предмет.
//
// КАК ПРОВЕРЯЕМ. Собираем все места публикации и все места подписки по
// всему серверу и сверяем списки.
//
// ЛОВУШКИ, КОТОРЫЕ ЭТА ПРОВЕРКА ОБХОДИТ. Публиковать можно и константой
// (REDIS_CHANNELS.PARTY_UPDATED), и строкой ('party:updated'). Раньше
// PartySystem публиковал строками, а GameSocketHandler подписывался на
// константы - списки не пересекались, хотя каналы были одни и те же. Здесь
// оба варианта приводятся к строковому значению.
//
// Второе: канал может быть построен функцией (REDIS_CHANNELS.REGION_SPAWN
// принимает shardId и region). Такие проверить нельзя - они зависят от
// данных во время выполнения. Они собираются отдельно и только
// проверяются на факт подписки.
//
// Третье, и самое неприятное: проверка обязана доказать, что видит обе
// стороны. Сканер, который нашёл ноль подписок, выглядит как «всё хорошо».
// Поэтому пороги зафиксированы числами с живого кода.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

function файлы(dir: string): string[] {
  const out: string[] = [];
  for (const имя of readdirSync(dir)) {
    const полный = join(dir, имя);
    if (statSync(полный).isDirectory()) out.push(...файлы(полный));
    else if (/\.ts$/.test(имя) && !имя.endsWith('.test.ts')) out.push(полный);
  }
  return out;
}

const исходникКонстант = readFileSync(join(корень, 'shared/constants.ts'), 'utf-8');

/** Строковые значения REDIS_CHANNELS: ИМЯ -> 'значение' */
function каналыПоСтроке(): Map<string, string> {
  const i = исходникКонстант.indexOf('export const REDIS_CHANNELS');
  must(i >= 0, 'В constants.ts нет REDIS_CHANNELS');
  const начало = исходникКонстант.indexOf('{', i);
  let глубина = 0;
  let конец = -1;
  for (let j = начало; j < исходникКонстант.length; j++) {
    if (исходникКонстант[j] === '{') глубина++;
    else if (исходникКонстант[j] === '}') {
      глубина--;
      if (глубина === 0) { конец = j; break; }
    }
  }
  must(конец > начало, 'Не нашёл закрывающую скобку REDIS_CHANNELS');
  const map = new Map<string, string>();
  for (const m of исходникКонстант.slice(начало, конец).matchAll(/([A-Z0-9_]+)\s*:\s*'([^']*)'/g)) {
    map.set(m[1], m[2]);
  }
  must(map.size > 5, `REDIS_CHANNELS разобралась в ${map.size} строковых каналов - регулярка устарела`);
  return map;
}

/** Имена функций-каналов: REGION_SPAWN и подобные */
function каналыФункции(): Set<string> {
  const i = исходникКонстант.indexOf('export const REDIS_CHANNELS');
  const начало = исходникКонстант.indexOf('{', i);
  const out = new Set<string>();
  for (const m of исходникКонстант.slice(начало).matchAll(/([A-Z0-9_]+)\s*:\s*\(/g)) {
    out.add(m[1]);
  }
  return out;
}

const СТРОКА = каналыПоСтроке();
const ФУНКЦИЯ = каналыФункции();

/**
 * Каналы, подписка на которые идёт через переменную цикла:
 *   for (const [канал, событие] of [[REDIS_CHANNELS.A, ...], ...])
 *     await this.redis.subscribe(канал, ...)
 *
 * Список берём из самого кода: находим объявление массива, который
 * перебирается в цикле рядом с subscribe, и вычитываем из него имена
 * констант. Угадывать нельзя - иначе проверка решит, что подписок нет.
 */
function каналыЧерезПеременную(): Set<string> {
  const найдено = new Set<string>();
  for (const файл of файлы(join(корень, 'server/src'))) {
    const код = readFileSync(файл, 'utf-8');
    // Цикл, в теле которого subscribe. Заголовок for(...) ищем не по
    // первой закрывающей скобке: в нём стоит `for (const [канал, событие]
    // of [...] as const)` и внутри могут быть вызовы с `)` - обычный
    // \)[^\)] обрывался на первом из них, и цикл не находился вовсе.
    // Класс символов имени переменной - [^\s,)], а НЕ \w: в JavaScript
    // \w не покрывает кириллицу, а переменная называется «канал». С \w
    // цикл не находился вовсе, и проверка объявляла две подписи
    // партийных каналов отсутствующими - то есть требовала починить
    // уже сделанное. Тот же класс ловушки, что с \b перед Router.
    for (const цикл of код.matchAll(/for\s*\([\s\S]{0,400}?of\s*\[[\s\S]{0,900}?[\s\S]{0,600}?redis\.subscribe\(\s*[^\s,)]+\s*,/g)) {
      // В теле цикла собираем все REDIS_CHANNELS.X — они и есть
      // подписываемые каналы.
      for (const m of цикл[0].matchAll(/REDIS_CHANNELS\.([A-Z0-9_]+)/g)) {
        const имя = m[1];
        if (СТРОКА.has(имя)) найдено.add(СТРОКА.get(имя)!);
        else if (ФУНКЦИЯ.has(имя)) найдено.add(имя);
      }
    }
  }
  return найдено;
}

const ЧЕРЕЗ_ПЕРЕМЕННУЮ = каналыЧерезПеременную();

/**
 * Подписки, спрятанные в методе-помощнике:
 *   await переслатьУчастникам(REDIS_CHANNELS.PARTY_UPDATED, событие, ...)
 *   а внутри уже this.redis.subscribe(канал, ...)
 *
 * Их собираем отдельным проходом: общий сборщик ищет литерал
 * `redis.subscribe(`, а тут такого текста рядом с константой нет.
 *
 * Обёртку опознаём так: находим локальные функции, внутри которых есть
 * redis.subscribe(ПЕРЕМЕННАЯ...), и берём их имена. Затем ищем вызовы
 * этих имён с константой. Первая попытка угадать имя обёртки («region»
 * вместо «переслатьУчастникам») нашла чужую функцию и потеряла канал.
 */
function каналыЧерезОбёртку(): { канал: string; файл: string }[] {
  const out: { канал: string; файл: string }[] = [];
  const все = файлы(join(корень, 'server/src'));
  const именаОбёрток = new Set<string>();
  for (const файл of все) {
    const код = readFileSync(файл, 'utf-8');
    // Объявления находим КОРОТКИМИ совпадениями, а тело смотрим отдельно
    // по индексу. Один длинный matchAll здесь не годится: он поглощает
    // до 1200 символов вперёд и thereby проглатывает объявления, лежащие
    // внутри уже сопоставленного куска. Из-за этого обёртка
    // «переслатьУчастникам» просто не попадала в набор.
    for (const m of код.matchAll(/(?:const|function)\s+([^\s(={]+)\s*=/g)) {
      const после = код.slice((m.index ?? 0) + m[0].length, (m.index ?? 0) + m[0].length + 1200);
      const подписка = /redis\.subscribe\(\s*([^\s,)]+)\s*,/.exec(после);
      if (!подписка) continue;
      const арг = подписка[1];
      // Канал-константа и канал-литерал разбираются основным сборщиком;
      // здесь интересуют только ПЕРЕМЕННЫЕ.
      if (арг.startsWith('REDIS_CHANNELS.')) continue;
      if (арг.startsWith("'") || арг.startsWith('`')) continue;
      именаОбёрток.add(m[1]);
    }
  }
  must(именаОбёрток.size > 0, 'Не нашлось ни одной обёртки подписки — регулярка устарела');
  for (const файл of все) {
    const код = readFileSync(файл, 'utf-8');
    for (const имя of именаОбёрток) {
      // Имя может прийти с хвостом мусора: класс [^\s(={] не stop'ится на
      // стрелке => внутри тела объявления, и тогда регулярное выражение
      // ищет мусор вместо вызова. Поэтому имя укорачиваем до первого
      // символа, который в идентификаторе невозможен.
      const чистое = имя.split(/[^A-Za-z_$\u0400-\u04FF\u00C0-\u024F0-9]/)[0];
      if (!чистое) continue;
      const re = new RegExp(`(?<![.\\w])${чистое.replace(/\$/g, '\\$')}\\(\\s*REDIS_CHANNELS\\.([A-Z0-9_]+)`, 'g');
      for (const m of код.matchAll(re)) {
        const ключ = m[1];
        if (СТРОКА.has(ключ)) out.push({ канал: СТРОКА.get(ключ)!, файл: файл.split(/[\\/]/).pop()! });
        else if (ФУНКЦИЯ.has(ключ)) out.push({ канал: ключ, файл: файл.split(/[\\/]/).pop()! });
      }
    }
  }
  return out;
}

const ЧЕРЕЗ_ОБЁРТКУ = каналыЧерезОбёртку();

interface Место { канал: string; файл: string; функция: boolean }

function собрать(действие: 'publish' | 'subscribe'): Место[] {
  const out: Место[] = [];
  for (const файл of файлы(join(корень, 'server/src'))) {
    const код = readFileSync(файл, 'utf-8');
    const шаблон = new RegExp(`redis\\.${действие}\\(\\s*([^,)]+)`, 'g');
    for (const m of код.matchAll(шаблон)) {
      const аргумент = m[1].trim();
      // REDIS_CHANNELS.ИМЯ - разрешаем в значение. Если ИМЯ функция
      // (REGION_SPAWN), берём имя функции: конкретное значение канала
      // зависит от shardId и региона и известно только в рантайме.
      const точка = /^REDIS_CHANNELS\.([A-Z0-9_]+)/.exec(аргумент);
      if (точка) {
        if (ФУНКЦИЯ.has(точка[1])) out.push({ канал: `СХЕМА:${точка[1]}`, файл, функция: true });
        else {
          const значение = СТРОКА.get(точка[1]);
          must(значение, `REDIS_CHANNELS.${точка[1]} не найдена в таблице — регулярка устарела`);
          out.push({ канал: значение!, файл, функция: false });
        }
        continue;
      }
      // 'строковый_канал'
      const строка = /^'([^']+)'$/.exec(аргумент);
      if (строка) { out.push({ канал: строка[1], файл, функция: false }); continue; }
      // Канал, собранный шаблонной строкой: `region:${shardId}:${region}:x`.
      // Схема известна: у каждого канала-функции в REDIS_CHANNELS есть
      // тело `region:\${shardId}:\${region}:спавн`, и по последнему сегменту
      // можно опознать, какая именно функция имеется в виду. Ищем в
      // ШАБЛОНАХ ФУНКЦИЙ, а не в строковых значениях: у REGION_SPAWN
      // строкового значения нет вовсе.
      if (аргумент.startsWith('`')) {
        // Хвост шаблона - последний сегмент после двоеточия:
        // `region:${shardId}:${region}:ai_action` -> ai_action.
        // Класс [a-z_] вместо \w: имена в константах латинские, а \w
        // заодно взял бы и кириллицу из вставленных выражений.
        const хвост = String(аргумент).split(':').pop()?.match(/^`?([a-z_]+)`?$/)?.[1] ?? null;
        if (хвост) {
          const кандидат = [...ФУНКЦИЯ].find(
            (имя) => имя.endsWith(`_${хвост.toUpperCase()}`) || имя === хвост.toUpperCase(),
          );
          if (кандидат) {
            out.push({ канал: `СХЕМА:${кандидат}`, файл, функция: true });
            continue;
          }
        }
      }
      // Подписка на канал, переданный переменной: subscribe(канал, ...),
      // где сам канал берётся из массива констант в теле цикла. Первая
      // версия проверки такой формы не видела и объявляла 11 подписок
      // отсутствующими - то есть врала в другую сторону, заставляя
      // чинить уже сделанное. Разрешаем через таблицу выше по коду:
      // ищем, какие значения REDIS_CHANNELS уходят в такую переменную.
      // Подписка спрятана в методе-помощнике: этотКод(REDIS_CHANNELS.A, ...),
      // а внутри уже this.redis.subscribe(канал, ...). Само REDIS_CHANNELS.A
      // тут не соседствует со словом subscribe, поэтому ищем вызовы
      // известных обёрток, а subscribe(переменная) в них уже учтён выше.
      const ОБЕРТКИ = /^(переслатьУчастникам|подписать|подписатьКанал|listen|subscribeКанал)/;
      if (ОБЕРТКИ.test(аргумент) && действие === 'subscribe') {
        const имя = /^REDIS_CHANNELS\.([A-Z0-9_]+)/.exec(аргумент)?.[1] ?? аргумент;
        const значение = СТРОКА.get(имя);
        if (значение) out.push({ канал: значение, файл, функция: false });
        else if (ФУНКЦИЯ.has(имя)) out.push({ канал: имя, файл, функция: true });
        else out.push({ канал: `НЕРАЗОБРАНО: обёртка ${аргумент}`, файл, функция: false });
        continue;
      }
      if (/^[^\s,)'"`]+$/.test(аргумент) && действие === 'subscribe') {
        // Каналы этой подписки уже собраны в ЧЕРЕЗ_ПЕРЕМЕННУЮ: один
        // вызов subscribe(канал) покрывает сразу все константы из
        // перебираемого массива. Если ни одна не нашлась - это
        // действительно неизвестная подписка, и молчать нельзя.
        if (ЧЕРЕЗ_ПЕРЕМЕННУЮ.size === 0) {
          out.push({ канал: `НЕРАЗОБРАНО: subscribe(${аргумент}) без массива констант`, файл, функция: false });
        }
        continue;
      }
      // Переменная или вызов — разобрать нечем, но и пропускать молча
      // нельзя: молчаливый пропуск выглядит как «каналов нет».
      out.push({ канал: `НЕРАЗОБРАНО: ${аргумент}`, файл, функция: false });
    }
  }
  return out;
}

const публикуется = собрать('publish');
const подписывается = собрать('subscribe');
// Подписки через переменную цикла несут сразу несколько каналов, и
// каждый из них должен защищаться от потери так же, как явный.
for (const канал of ЧЕРЕЗ_ПЕРЕМЕННУЮ) {
  // Каналы-функции (region:*) подписываются через
  // REDIS_CHANNELS.REGION_SPAWN(shard, region), а публикуются собранной
  // строкой `region:${shard}:${region}:spawn`. Сравнивать их напрямую
  // нельзя, поэтому приводим к общему виду «СХЕМА:ИМЯ_ФУНКЦИИ».
  const имя = канал.startsWith('СХЕМА:') ? канал : (/^[A-Z0-9_]+$/.test(канал) && ФУНКЦИЯ.has(канал) ? `СХЕМА:${канал}` : канал);
  подписывается.push({ канал: имя, файл: 'GameSocketHandler (через переменную цикла)', функция: true });
}
for (const место of ЧЕРЕЗ_ОБЁРТКУ) {
  const имя = /^[A-Z0-9_]+$/.test(место.канал) && ФУНКЦИЯ.has(место.канал) ? `СХЕМА:${место.канал}` : место.канал;
  подписывается.push({ канал: имя, файл: `${место.файл} (через обёртку)`, функция: false });
}

describe('Каналы Redis: публикация находит подписчика', () => {
  it('сканер видит и публикации, и подписки', () => {
    must(
      публикуется.length >= 20,
      `Найдено ${публикуется.length} публикаций. Их больше двадцати — регулярка перестала ловить форму вызова.`,
    );
    must(
      подписывается.length >= 15,
      `Найдено ${подписывается.length} подписок. Их больше пятнадцати — регулярка перестала ловить форму вызова.`,
    );
  });

  it('аргумент публикации или подписки разобран, а не пропущен', () => {
    const непонятные = [...публикуется, ...подписывается].filter((м) => м.канал.startsWith('НЕРАЗОБРАНО'));
    must(
      непонятные.length === 0,
      `Не удалось прочитать имя канала — молча пропускать нельзя:\n  ${непонятные.map((м) => `${м.канал}  (${м.файл})`).join('\n  ')}`,
    );
  });

  it('на каждый публикуемый канал есть подписка', () => {
    const подписанные = new Set(подписывается.map((м) => м.канал));
    // Функции-каналы сравниваем по имени функции, а не по строке.
    const потерянные: string[] = [];
    for (const место of публикуется) {
      if (подписанные.has(место.канал)) continue;
      потерянные.push(`${место.канал}  (публикуется в ${место.файл})`);
    }
    must(
      потерянные.length === 0,
      `В эти каналы публикуют, но никто не подписан — сообщения пропадают молча:\n  ${потерянные.join('\n  ')}`,
    );
  });

  it('все каналы из таблицы либо подписаны, либо помечены как неиспользуемые', () => {
    // Канал в таблице, который никто не публикует и не слушает, -
    // это заготовка. Она не опасна, но она же объясняет, почему
    // в таблице их больше, чем работающих: разница обязана быть видна.
    const использованные = new Set([...публикуется, ...подписывается].map((м) => м.канал));
    const неиспользуемые = [...СТРОКА.values()].filter((к) => !использованные.has(к));
    must(
      неиспользуемые.length === 0,
      `Эти каналы объявлены в REDIS_CHANNELS, но не публикуются и не подписаны - заготовки без потребителя:\n  ${неиспользуемые.join('\n  ')}`,
    );
  });
});
