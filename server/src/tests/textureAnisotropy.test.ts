// Анизотропия: землю видно вдоль, и она не должна быть мутной.
//
// ЧТО БЫЛО. В toTexture стояло зашитое anisotropy = 4. Землю игрок видит
// под скользящим углом — почти вдоль, — и с четвёркой она превращается в
// мыльную муть именно там, куда смотрит. На типичной видеокарте доступно
// 16, а узнать точное число может только рендер.
//
// ЧТО ПРОВЕРЯЕТСЯ. Значение не зашито, берётся у рендера и ставится ДО
// создания текстур. Порядок важен: buildTerrain создаёт текстуры, и
// вызов после него ничего бы не изменил — текстуры уже родились с четвёркой.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ТЕКСТУРЫ = читать('client/src/app/game3d/textures.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Анизотропия текстур', () => {
  it('четвёрка не зашита в создание текстуры', () => {
    должен(
      !/tex\.anisotropy\s*=\s*4\b/.test(ТЕКСТУРЫ),
      'в toTexture снова зашита четвёрка: земля будет мутной под скользящим углом',
    );
    // Значение приходит извне, а не считается на месте.
    должен(
      /tex\.anisotropy\s*=\s*МАКС_АНИЗОТРОПИЯ/.test(ТЕКСТУРЫ),
      'anisotropy не берётся из возможностей рендера',
    );
  });

  it('есть способ сообщить текстурам возможности железа', () => {
    должен(
      /export function setTextureAnisotropy\(/.test(ТЕКСТУРЫ),
      'нет setTextureAnisotropy: текстуры нечем рассказать о возможностях',
    );
    // Мусор вроде нуля или отрицательного не должен пройти.
    должен(
      /Math\.max\(1/.test(ТЕКСТУРЫ),
      'setTextureAnisotropy не страхует нижнюю границу: ноль оставит текстуры без фильтрации',
    );
  });

  it('рендер ставит анизотропию ДО создания текстур мира', () => {
    // Это главная проверка. Порядок в мире: рендер, анизотропия, buildTerrain.
    // Вызов после buildTerrain не дал бы ничего: текстуры уже созданы.
    const позицияРендера = МИР.indexOf('new THREE.WebGLRenderer');
    const позицияАнизотропии = МИР.indexOf('setTextureAnisotropy(this.renderer.capabilities');
    const позицияТекстур = МИР.indexOf('buildTerrain(this.scene)');
    должен(позицияРендера > 0, 'в world3d не найден рендер');
    должен(позицияАнизотропии > 0, 'world3d не вызывает setTextureAnisotropy: текстуры останутся на четвёрке');
    должен(позицияТекстур > 0, 'в world3d не найден buildTerrain');
    должен(
      позицияАнизотропии > позицияРендера && позицияАнизотропии < позицияТекстур,
      'порядок неверен: анизотропия должна ставиться после создания рендера и ДО buildTerrain',
    );
    // И значение спрашивается у рендера, а не выдумывается.
    должен(
      /setTextureAnisotropy\(this\.renderer\.capabilities\.getMaxAnisotropy\(\)\)/.test(МИР),
      'анизотропия не спрашивается у рендера: число снова зашито или угадано',
    );
  });
});
