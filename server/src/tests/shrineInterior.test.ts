// Зороастрийское святилище: дверь одна и та же, руины действительно руины.
//
// ЧТО ЗАЩИЩАЕТ. Святилище — первое подземелье, построенное как живая постройка.
// Осмотр кода показал: из задания владельца («полуразрушенные стены, рельефы»)
// не было построено ничего. Значит проверка должна защитить не только от
// «двери в воде», но и от главной беды здесь — **от того, что руины окажутся
// целыми**. Святое здание без разрушений — это просто ещё один зал.
//
// ЧТО ПРОВЕРЯЕМ ПО-НАСТОЯЩЕМУ.
//   1. Место двери сухое — водой замерено настоящим waterMask.
//   2. Слот и дверь совпадают на клиенте и сервере, все 16 построек держат слоты.
//   3. Разрушения настоящие: пролом в стене, обломки у основания, рельефы в нишах.
//   4. Алтарь с огнём: зороастрийский культ держится на священном пламени.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';
import { waterMask } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

describe('Святилище: место подобрано измерением', () => {
  it('дверь стоит на сухой земле', () => {
    const def = INTERIORS.shrine;
    must(def !== undefined, 'на сервере нет записи shrine: дверь есть, а войти некуда');
    const влажность = waterMask(def.doorX, def.doorZ);
    must(
      влажность === 0,
      `у двери святилища (${def.doorX}, ${def.doorZ}) влажность ${влажность.toFixed(4)}, ` +
        'а должно быть 0.0000: стена встанет в воду'
    );
  });

  it('проверка места не пустая: вода остаётся водой', () => {
    must(waterMask(-420, -160) > 0.9, 'озеро перестало быть водой: маска считается неверно');
    must(waterMask(620, 300) > 0.9, 'пруд перестал быть водой: маска считается неверно');
  });

  it('дверь не стоит на отпавших северных точках', () => {
    // При замере весь север дал 1.0000 — это озеро: (1250,-1250), (700,-1250),
    // (-700,-1300). Если бы дверь оказалась там, святилище стояло бы в воде.
    const def = INTERIORS.shrine!;
    must(
      def.doorZ > 0,
      `дверь святилища на z=${def.doorZ}, а север карты занят озером (1.0000 на всём севере)`
    );
  });

  it('святилище стоит далеко от города, а не в чужом дворе', () => {
    const def = INTERIORS.shrine!;
    // От таможни (-900, 800) и от любой городской постройки.
    must(
      Math.hypot(def.doorX + 900, def.doorZ - 800) > 500,
      `святилище в ${Math.hypot(def.doorX + 900, def.doorZ - 800).toFixed(0)} от таможни: ` +
        'слишком близко, две постройки слиплись'
    );
  });
});

describe('Святилище: слот и дверь совпадают на клиенте и на сервере', () => {
  it('святилище держит пятнадцатый слот на обеих сторонах', () => {
    const ключи = Object.keys(INTERIORS);
    const слотСервер = ключи.indexOf('shrine');
    must(слотСервер === 15, `святилище на слоте ${слотСервер} из ${ключи.length}, а обязана быть пятнадцатой`);
    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    must(
      записи.indexOf('shrine') === слотСервер,
      `на клиенте святилище на слоте ${записи.indexOf('shrine')}, а на сервере ${слотСервер}`
    );
  });

  it('шестнадцать построек держат свои слоты', () => {
    const ключи = Object.keys(INTERIORS);
    const ждём: [string, number, number][] = [
      ['stable', 0, 4000],
      ['barracks', 1, 4044],
      ['workshop', 2, 4088],
      ['tavern', 3, 4132],
      ['observatory', 4, 4176],
      ['science', 5, 4220],
      ['arena', 6, 4264],
      ['auction_house', 7, 4308],
      ['circus', 8, 4352],
      ['caravanserai', 9, 4396],
      ['fortress', 10, 4440],
      ['palace', 11, 4484],
      ['mosque', 12, 4528],
      ['weaver', 13, 4572],
      ['customs', 14, 4616],
      ['shrine', 15, 4660],
    ];
    for (const [id, слот, комната] of ждём) {
      must(ключи[слот] === id, `на слоте ${слот} стоит ${ключи[слот]}, а ожидался ${id}`);
      must(
        INTERIORS[id as keyof typeof INTERIORS]!.roomCx === комната,
        `у ${id} roomCx ${INTERIORS[id as keyof typeof INTERIORS]!.roomCx}, а слот ${слот} даёт ${комната}`
      );
    }
  });

  it('координаты двери совпадают на клиенте и на сервере', () => {
    const def = INTERIORS.shrine!;
    const своя = /id: 'shrine', kind: 'shrine',[\s\S]{0,140}?dx: (-?\d+), dz: (-?\d+)/.exec(клиент);
    must(своя !== null, 'у святилища на клиенте нет абсолютной двери');
    must(
      Number(своя![1]) === def.doorX && Number(своя![2]) === def.doorZ,
      `клиент рисует дверь в (${своя![1]}, ${своя![2]}), а сервер ждёт (${def.doorX}, ${def.doorZ})`
    );
  });

  it('комната не налезает на соседние', () => {
    const def = INTERIORS.shrine!;
    const чужие = Object.values(INTERIORS).filter((д) => д.id !== 'shrine');
    const тесные = чужие.filter((д) =>
      Math.abs(д.roomCx - def.roomCx) < 32 && Math.abs(д.roomCz - def.roomCz) < 32
    );
    must(тесные.length === 0, `комната налезает на: ${тесные.map((д) => д.id).join(', ')}`);
  });

  it('граница кармана покрывает новую комнату целиком', () => {
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+), z0: (-?\d+), z1: (\d+) \}/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    must(
      Number(прямоугольник![2]) >= INTERIORS.shrine!.roomCx + INTERIORS.shrine!.roomHalf,
      `правый край кармана ${прямоугольник![2]}, а правый край комнаты ` +
        `${INTERIORS.shrine!.roomCx + INTERIORS.shrine!.roomHalf}: под комнатой нет земли`
    );
  });
});

describe('Святилище: разрушения настоящие, а не только заявлены', () => {
  it('функция обстановки заведена и вызывается', () => {
    must(/function furnishShrine\(/.test(клиент), 'функции обстановки святилища нет');
    must(/shrine: furnishShrine,/.test(клиент), 'святилище не прописан в выборе обстановки');
    must(
      /'shrine'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 800) ?? ''),
      'в типе BuildingKind нет святилища'
    );
  });

  it('стена разрушена проломом, а не сплошной', () => {
    const начало = клиент.indexOf('function furnishShrine(');
    must(начало > 0, 'функция обстановки святилища не найдена');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);

    // Две части стены вместо одной: между ними и есть пролом.
    must(тело.includes('box(7, 3.2, 0.7, M.stone, cx - 7'), 'левая часть стены разрушенной стены нет');
    must(тело.includes('box(4.4, 2.2, 0.7, M.stone, cx + 7.8'), 'правая часть стены разрушенной стены нет');
    // Правая часть ниже левой — стена просела. Если бы высоты совпали, это была бы
    // просто стена с дверью, а не руина.
    const левая = /box\(7, 3\.2/.exec(тело);
    const правая = /box\(4\.4, 2\.2/.exec(тело);
    must(левая !== null && правая !== null, 'геометрия стены не найдена');
  });

  it('обломки лежат куском и повёрнуты, а не стоят рядом', () => {
    const начало = клиент.indexOf('function furnishShrine(');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);
    must(/\[-7, -7, 0\.4\], \[-5\.6, -8\.2, 1\.1\]/.test(тело), 'обломков нет или они не разбросаны');
    must(/r\.rotation\.y = rot;/.test(тело), 'обломки стоят ровно: стена не рушилась, её сложили');
    must(/const r = box\(2\.2, 0\.9, 1\.6, M\.stone/.test(тело), 'обломки не того размера');
  });

  it('рельефы в нишах есть и видны отличием от стены', () => {
    const начало = клиент.indexOf('function furnishShrine(');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);
    // Ниша тёмная, рельеф золотой и выходит из неё — иначе рельеф не разглядеть.
    must(/box\(0\.6, 3\.6, 3\.2, M\.dark, px/.test(тело), 'ниш нет: рельеф висит в воздухе');
    must(/box\(0\.35, 2\.6, 2\.2, M\.gold, px/.test(тело), 'рельефов нет или они не отличаются от стены');
    must(тело.split('for (const side of [-1, 1])').length - 1 >= 2, 'боковые ряды должны быть ровно двумя');
  });

  it('алтарь с огнём: священное пламя держит весь культ', () => {
    const начало = клиент.indexOf('function furnishShrine(');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);
    must(тело.includes('box(4.4, 1.2, 2.2, M.stone, cx, FLOOR_Y + 0.6, cz - 7)'), 'алтаря нет');
    must(тело.includes('cyl(0.5, 0.9, 0.5, M.gold, cx, FLOOR_Y + 1.75, cz - 7'), 'чаши для огня нет');
    // Пламя: два конуса разного размера.
    must(/cyl\(0\.75, 1\.3, 0\.75, M\.red/.test(тело), 'пламени нет');
    must(/cyl\(0\.45, 1\.9, 0\.45, M\.gold/.test(тело), 'внутреннего огня нет: пламя однородное');
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.shrine === 'string' && словарь.buildings.shrine.length > 0,
        `в ${код}.json нет названия buildings.shrine`
      );
    }
  });
});

describe('Святилище: подземелья не выдают себя за построенные', () => {
  it('ни одного файла карты подземелий нет', () => {
    // Записи подземелий есть, и это вводит в заблуждение: выглядит как
    // «уже построено». Файлов карт на диске нет ни одного, и mapPath не
    // читает никто — значит в такую комнату нельзя дойти.
    const каталоги = ['maps', 'server/maps', 'client/public/maps'];
    let найдено = 0;
    for (const dir of каталоги) {
      // Каталога нет — это и есть ожидаемое состояние, ловить тут нечего.
      const файлы = читатьСписок(dir);
      найдено += файлы.filter((f) => f.endsWith('.umap')).length;
    }
    must(найдено === 0, `файлов карт подземелий: ${найдено}: если они появились, подземелья надо проверить заново`);
  });

  it('mapPath не читается кодом — запись подземелья недостижима', () => {
    const файлы: string[] = [];
    const walk = (dir: string, depth = 0) => {
      if (depth > 6) return;
      for (const e of читатьСписокРасширенно(dir)) {
        const p = dir + '/' + e.name;
        // Тесты исключены осознанно. Проверка ищет ЧТЕНИЕ поля, а в тестах
        // слово mapPath встречается внутри регулярных выражений — то есть это
        // упоминание, а не обращение к полю. Без исключения проверка находила
        // саму себя и падала на собственном шаблоне.
        if (p.includes('src/tests')) continue;
        if (e.isDirectory()) walk(p, depth + 1);
        else if (/\.ts$/.test(e.name)) файлы.push(p);
      }
    };
    walk('server/src');
    walk('client/src');
    let читатели = 0;
    for (const f of файлы) {
      const строки = читать(f).split(/\r?\n/);
      // ПОСТРОЧНО, а не по файлу. Первая версия проверки делала так:
      // если в файле есть хоть одно объявление `mapPath:` — пропускала файл
      // целиком. Значит чтение в том же файле, где и объявление, она заметить
      // не могла, и ломка (добавить чтение в dungeons.ts) оставалась зелёной.
      // Объявление поля и обращение к нему стоят в разных строках — значит и
      // проверять надо по строкам.
      for (let i = 0; i < строки.length; i++) {
        const строка = строки[i];
        if (/^\s*(\/\/|\*|\/\*)/.test(строка)) continue; // комментарий — не код
        if (/mapPath\s*:\s*['"]/.test(строка)) continue; // объявление поля
        if (/\.mapPath\b|\bmapPath\s*\]/.test(строка)) {
          читатели++;
          console.error('    mapPath читает: ' + f + ':' + (i + 1) + ' → ' + строка.trim().slice(0, 70));
        }
      }
    }
    must(читатели === 0, `mapPath читают в ${читатели} местах: подземелья могут оказаться достижимыми`);
  });
});

// Склейка корень + dir БЕЗ РАЗДЕЛИТЕЛЯ даёт путь вида
// "D:\...\Empire of Sefevidsserver/src". readdirSync на таком пути падает,
// catch возвращает пустой список, обход не находит НИ ОДНОГО файла — и
// проверка «mapPath не читается» проходит всегда, ничего не проверяя.
// Это холостой ноль: ровно тот дефект, который за серию находили шесть раз,
// и на этот раз я внёс его сам.
//
// Правило: пути собираются через join, а не склейкой.
function читатьСписок(dir: string): string[] {
  try {
    return readdirSync(join(корень, dir));
  } catch (e) {
    return [];
  }
}

function читатьСписокРасширенно(dir: string): { name: string; isDirectory(): boolean }[] {
  try {
    return readdirSync(join(корень, dir), { withFileTypes: true });
  } catch (e) {
    return [];
  }
}