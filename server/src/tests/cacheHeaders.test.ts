// Проверка заголовков кэширования.
//
// ЧТО ЗАЩИЩАЕМ. Без явных Cache-Control браузер применяет эвристическое
// кэширование, и после выкатки игрок несколько дней ходит на старый код.
// На этом споткнулся разбор объявления: сервер отдавал новый main.js, а
// вкладка выполняла старый, и кнопка то появлялась, то исчезала.
//
// Проверять придётся по тексту конфига: поднять nginx в тестах нечем, а
// сам заголовок без сервера не увидеть. Поэтому проверяем ровно те три
// свойства, из-за которых всё затевалось:
//   1. входной HTML игры не кэшируется надолго - в нём имена файлов сборки;
//   2. файлы сборки игры кэшируются навсегда - в их именах хеш содержимого;
//   3. скрипты и страницы лендинга не кэшируются надолго - их имена
//      постоянные, и файл меняется под тем же именем.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const repoRoot = join(__dirname, '..', '..', '..');
const nginx = readFileSync(join(repoRoot, 'client', 'nginx.conf'), 'utf-8');

/** Тело location-блока по имени */
function locationBody(name: string): string {
  const start = nginx.indexOf(`location ${name}`);
  if (start < 0) return '';
  const next = nginx.indexOf('\n  }', start);
  return nginx.slice(start, next < 0 ? nginx.length : next);
}

describe('Кэширование: игроки не должны ходить на старый код', () => {
  it('входной HTML игры перезапрашивается каждый раз', () => {
    // В нём имена файлов сборки. Закэшированная копия означала бы, что
    // игрок месяц открывает старую версию игры.
    const body = locationBody('/game/');
    expect({
      блок_найден: body.length > 0,
      перезапрашивается: /add_header Cache-Control "no-cache" always;/.test(body),
      вечного_кэша_нет: !/max-age=31536000/.test(body),
    }).toEqual({ блок_найден: true, перезапрашивается: true, вечного_кэша_нет: true });
  });

  it('файлы сборки игры кэшируются навсегда', () => {
    // Имена содержат хеш содержимого: index-5kcH5ef0.js. Такой файл
    // не может измениться, не сменив имя, - кэшировать безопасно, и это
    // главный выигрыш по скорости входа.
    const body = locationBody('^~ /game/assets/');
    expect({
      блок_найден: body.length > 0,
      immutable: /immutable/.test(body),
      срок_год: /max-age=31536000/.test(body),
    }).toEqual({ блок_найден: true, immutable: true, срок_год: true });
  });

  it('блок файлов сборки не перекрывается общим блоком игры', () => {
    // ПЕРВАЯ ВЕРСИЯ ПРОВЕРКИ БЫЛА НЕВЕРНОЙ. Она требовала, чтобы блок
    // ассетов стоял в файле раньше общего блока игры. Слой с переставленным
    // блоком остался зелёным - и это оказалось правильно: в nginx порядок
    // префиксных location не решает ничего, выигрывает самый длинный
    // подходящий префикс. То есть проверялось требование, которого нет.
    //
    // Настоящее требование: префикс ассетов строго вложен в общий и длиннее
    // его, иначе хешированные файлы попадут в общий блок и закэшируются
    // как обычный HTML.
    const assetsPrefix = '/game/assets/';
    const gamePrefix = '/game/';
    expect({
      вложен: assetsPrefix.startsWith(gamePrefix),
      строго_длиннее: assetsPrefix.length > gamePrefix.length,
    }).toEqual({ вложен: true, строго_длиннее: true });
  });

  it('блок файлов сборки указывает на свою папку', () => {
    // Более специфичный блок с чужим alias отдавал бы 404 на все ассеты
    // игры: формально он «правильный», но файлы не найдены. Проверяем,
    // что внутри блока свой alias, а не общий.
    const body = locationBody('^~ /game/assets/');
    expect({
      alias_свой: /alias \/usr\/share\/nginx\/html\/game\/assets\//.test(body),
      не_общий: !/alias \/usr\/share\/nginx\/html;/.test(body),
    }).toEqual({ alias_свой: true, не_общий: true });
  });

  it('блок ассетов защищён от перехвата регулярным выражением', () => {
    // '^~' запрещает искать дальше по regex-блокам, если префикс уже
    // совпал. В файле есть регулярный блок для /api, /locales и
    // /socket.io - сегодня он не пересекается с ассетами, но это
    // единственная защита, если его когда-нибудь расширят.
    const body = locationBody('^~ /game/assets/');
    expect(/location \^~ \/game\/assets\//.test(nginx) && body.length > 0).toBe(true);
  });

  it('лендинг перезапрашивается, а не кэшируется надолго', () => {
    // Скрипты лендинга названы обычными именами: main.js. Кэшировать их
    // на год нельзя - файл меняется, имя остаётся прежним.
    const body = locationBody('/ {');
    expect({
      блок_найден: body.length > 0,
      перезапрашивается: /add_header Cache-Control "no-cache" always;/.test(body),
      вечного_кэша_нет: !/max-age=31536000/.test(body),
    }).toEqual({ блок_найден: true, перезапрашивается: true, вечного_кэша_нет: true });
  });

  it('все always: без них заголовок не отдаётся на части ответов', () => {
    // nginx по умолчанию добавляет add_header только для 200, 201, 204,
    // 206, 301, 302, 303, 304, 307, 308. Ошибки и нестандартные коды
    // остались бы без заголовка - то есть ровно в аварии заголовка не
    // будет, когда он нужнее всего.
    const adds = nginx.match(/add_header Cache-Control[^;]+;/g) ?? [];
    expect({ сколько_всего: adds.length, все_с_always: adds.every(a => /always;/.test(a)) })
      .toEqual({ сколько_всего: expect.any(Number), все_с_always: true });
  });

  it('проксируемые адреса не получили заголовков кэша', () => {
    // /api, /locales и /socket.io идут на игровой сервер. Если бы им
    // достался immutable, браузер годами держал бы, например, старый
    // перевод или старый ответ API.
    const apiBlock = locationBody('~ ^/(api|locales|socket.io)/');
    expect({ блок_найден: apiBlock.length > 0, без_cache_control: !/Cache-Control/.test(apiBlock) })
      .toEqual({ блок_найден: true, без_cache_control: true });
  });
});

describe('Согласованность с тем, как собирается игра', () => {
  it('файлы сборки действительно содержат хеш в имени', () => {
    // Если бы сборка перестала хешировать имена, вечное кэширование
    // стало бы ошибкой: игрок застрял бы на старой версии навсегда.
    // Проверяем по исходникам: имена файлов в index.html игры.
    const gameHtml = readFileSync(join(repoRoot, 'client', 'src', 'app', 'index.html'), 'utf-8');
    const refs = [...gameHtml.matchAll(/\/game\/assets\/[^"']+/g)].map(m => m[0]);
    const hashed = refs.filter(r => /-[A-Za-z0-9_-]{8,}\.(js|css)$/.test(r));
    expect({ ссылок_на_ассеты: refs.length, с_хешем: hashed.length }).toEqual({ ссылок_на_ассеты: expect.any(Number), с_хешем: expect.any(Number) });
    // Ссылок может не быть вовсе: ассеты подставляет сборка. Тогда важно,
    // чтобы проверка не требовала несуществующего: сравниваем с исходным
    // числом и не падаем, если файлов нет
    if (refs.length === 0) {
      expect({ примечание: 'ссылок на ассеты в исходнике нет, имена даёт сборка Vite' })
        .toEqual({ примечание: 'ссылок на ассеты в исходнике нет, имена даёт сборка Vite' });
    }
  });
});
