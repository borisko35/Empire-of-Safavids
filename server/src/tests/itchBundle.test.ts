      // караванов на дороге и подъём засады.
      // 223 → 224 при §215: в пояснении modelAccess.ts назван адрес проверки
      // входа (`/api/auth/gate`). Счётчик считает все вхождения `/api/`,
      // включая пояснения, — его известная неточность. Настоящих вызовов
