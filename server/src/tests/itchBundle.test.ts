// Связка для itch.io: что именно мы выкладываем и почему не игру.
//
// ЗАЧЕМ ФАЙЛ. Проверено по исходникам: игра делает 203 обращения к /api/ и
// разговаривает по Socket.IO, всё по своему адресу. itch.io отдаёт
// статические файлы, сервера там нет. Значит выложить игру на itch.io нельзя
// - витрина будет страницей со ссылкой на наш сайт, а выкладывать оттуда
// можно страницу трейлера.
//
// Это утверждение проверяется кодом, а не держится на слове. Если когда-нибудь
// игра заработает без сервера, проверка покраснеет и скажет: перечитай, что
// мы собираемся выкладывать. Обратное тоже верно - если число обращений
// упадёт до нуля из-за правки, значит вывод «на itch.io нужен трейлер, а не
// игра» стал неверен.
//
// ЧТО ЗДЕЛАНО ДЛЯ ПУБЛИКАЦИИ. Сборщик tools/build-itch-bundle.js собирает
// папку, запаковывает и ДВАЖДЫ проверяет настоящим сервером: сначала
// распакованную папку, потом сам архив после распаковки. Проверка папки
// ничего не говорит об архиве: Compress-Archive кладёт файлы по своим
// путям, и index.html может лечь не в корень.
import { readFileSync, existsSync } from 'node:fs';
import { readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Рекурсивно читает все .ts исходники клиента. */
function исходники(папка: string): { код: string; файлов: number } {
  let код = '';
  let файлов = 0;
  for (const имя of readdirSync(папка)) {
    const путь = join(папка, имя);
    if (statSync(путь).isDirectory()) {
      const вложенные = исходники(путь);
      код += вложенные.код;
      файлов += вложенные.файлов;
      continue;
    }
    if (!имя.endsWith('.ts')) continue;
    код += readFileSync(путь, 'utf-8') + '\n';
    файлов++;
  }
  return { код, файлов };
}

describe('Что мы выкладываем на itch.io', () => {
  it('игра требует сервера — значит выкладывать её туда нельзя', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Если обращения к /api/ исчезнут, вывод
    // «витрина ведёт на наш сайт, выкладываем трейлер» станет неверен.
    const клиент = исходники(join(корень, 'client/src'));
    const обращений = (клиент.код.match(/\/api\//g) || []).length;
    const сокет = /socket\.io/.test(клиент.код);
    must(клиент.файлов > 20, 'прочитано подозрительно мало файлов клиента');
    expect({
      файлов_прочитано: клиент.файлов,
      обращений_к_api: обращений,
      socket_io_есть: сокет,
    }).toEqual({
      // Растёт с каждым новым модулем клиента: 46 → 47 при появлении
      // autobattle.ts, 47 → 48 при появлении minimapFog.ts (туман войны),
  // 48 → 49 при появлении realRig.ts (настоящие модели персонажей),
      // 205 → 206 при добавлении запроса заданий крафта (craftingJobs): без него
      // изготовленную вещь было не забрать после сброса браузера.
      // 50 → 51 при появлении classPreview.ts (живые 3D-превью классов),
      // 51 → 52 при появлении townfolk.ts (жители городов на настоящих моделях).
      // Число зафиксировано руками намеренно - иначе файл,
      // случайно выпавший из обхода, никто бы не заметил.
      файлов_прочитано: 53,
      обращений_к_api: 209,
      socket_io_есть: true,
    });
  });

  it('в черновике сказано то же самое, а не «выкладываем игру»', () => {
    // Черновик раздаётся владельцу как инструкция. Если в нём написано, что
    // игра выкладывается на itch.io, человек загрузит то, что не запустится.
    const черновик = читать('tools/itch-reddit-draft.md');
    must(черновик.length > 1000, 'черновик пуст или не найден');
    // Считаются ВСЕ упоминания ограничения, а не любое одно совпадение. Первая
    // версия спрашивала /статическ|сервера там нет/ - и поломка, убирающая одну
    // фразу, проходила: в абзаце оставались другие. Значит заявление держалось
    // на одной фразе из трёх, и выброс любой одной ничего не менял бы.
    const проСтатику = (черновик.match(/отдаёт \*\*статические файлы\*\*/g) || []).length
      + (черновик.match(/Сервера там нет и не появится/g) || []).length
      + (черновик.match(/живого сервера/g) || []).length;
    expect({
      // Упоминание того, что сервера на площадке нет, - трижды в разных
      // местах, чтобы случайно не вычеркнули одним предложением.
      упоминаний_об_ограничении: проСтатику,
      // И что выкладывается трейлер, а не игра.
      грузим_трейлер: /itch-bundle\.zip[^\n]*трейлер/i.test(черновик),
      прямо_сказано_что_не_игру: /\*\*НЕ игра\*\*/.test(черновик),
    }).toEqual({
      упоминаний_об_ограничении: 3,
      грузим_трейлер: true,
      прямо_сказано_что_не_игру: true,
    });
  });
});

describe('Связка, которую грузят на площадку', () => {
  it('сборщик лежит в репозитории и проверяет и папку, и архив', () => {
    const сборщик = join(корень, 'tools/build-itch-bundle.js');
    must(existsSync(сборщик), 'нет tools/build-itch-bundle.js');
    const код = читать('tools/build-itch-bundle.js');
    expect({
      // Распаковка и второй прогон: без этого проверяется папка, а грузится
      // архив, и разница между ними не видна.
      распаковывает: /Expand-Archive/.test(код),
      гоняет_дважды: /САМ АРХИВ, РАСПАКОВАН/.test(код),
      // index.html обязан быть в корне архива.
      следит_за_корнем: /index\.html не в корне архива/.test(код),
      // Адреса разрешаются как в браузере, а не склейкой строк.
      разрешает_как_браузер: /new URL\(имя/.test(код),
      // И сверяется САМО число кадров, а не наличие константы. Первая версия
      // проверяла /ОЖИДАЕМО_КАДРОВ/ - то есть только факт объявления. Поломка
      // «поставим 99 вместо 6» прошла насквозь: константа на месте, проверка
      // довольна, а сверять не с чем. Проверка, которая не может покраснеть,
      // хуже отсутствующей.
      сверяет_число: /ОЖИДАЕМО_КАДРОВ = 6\b/.test(код),
    }).toEqual({
      распаковывает: true, гоняет_дважды: true, следит_за_корнем: true,
      разрешает_как_браузер: true, сверяет_число: true,
    });
  });

  it('архив и папка сборки не попадут в репозиторий', () => {
    const игнор = читать('.gitignore');
    expect({
      папка_витрины: /tools\/itch-bundle\//.test(игнор),
      распаковка: /tools\/itch-unpack\//.test(игнор),
      // Архив закрыт общим правилом *.zip - иначе в коммит попадёт файл на
      // два мегабайта, который каждый раз меняется при пересборке.
      архив: /^\*\.zip$/m.test(игнор),
    }).toEqual({ папка_витрины: true, распаковка: true, архив: true });
  });

  it('связка берёт трейлер с сайта, а не свою копию', () => {
    // Своя копия трейлера в связке разъехалась бы с сайтом, и витрина
    // показывала бы кадры, которых на сайте уже нет. Первая версия сборщика
    // копировала файл и правила его; теперь файл один.
    const код = читать('tools/build-itch-bundle.js');
    expect({
      берёт_из_клиента: /client\/web\/trailer\.html/.test(код),
      копирует_без_правок: /\.copyFileSync|writeFileSync\(path\.join\(папка, 'index\.html'\), исходник\)/.test(код),
    }).toEqual({ берёт_из_клиента: true, копирует_без_правок: true });
  });

  it('в связку едет лицензия, и на странице есть ссылка на неё', () => {
    // Связка едет на чужую площадку. GPL-3.0 требует передавать текст
    // лицензии вместе с программой: ссылка на /LICENSE без самого файла -
    // это ссылка в пустоту, и на itch.io это заметят.
    const код = читать('tools/build-itch-bundle.js');
    const тянет = /copyFileSync\(path\.join\(корень, 'client\/web\/LICENSE'\)/.test(код);
    const проверяет = /ссылка на LICENSE есть на странице/.test(код);
    expect({ тянет_лицензию: тянет, проверяет_ссылку: проверяет })
      .toEqual({ тянет_лицензию: true, проверяет_ссылку: true });
  });
});
