// Кнопка присоединения: клиент видит открытые заходы и может вступить.
//
// ЧТО ЗАЩИЩАЕТ. Групповой заход был мёртв: сервер умел join, а игрок не мог им
// воспользоваться — кнопки не было, и клиент не знал, к какому заходу идти.
// Проверка требует и список заходов, и кнопку, и вызов — по одному слову
// «join» она ничего не проверяла бы, потому что join в коде много.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = код('server/src/systems/DungeonService.ts');
const маршруты = код('server/src/routes/game.ts');
const апи = код('client/src/app/api.ts');
const панель = код('client/src/app/panels.ts');

describe('Кнопка присоединения: сервер отдаёт список', () => {
  it('метод списка есть и возвращает по заданному данжу', () => {
    must(/listOpenSessions\(dungeonId: string\)/.test(сервис), 'метода списка заходов нет');
    must(
      /сессия\.dungeonId === dungeonId/.test(сервис),
      'список не фильтруется по данжу: игрок увидит чужие заходы'
    );
  });

  it('завершённые заходы в список не попадают', () => {
    must(
      /!сессия\.completedAt/.test(сервис),
      'завершённые заходы попадут в список: кнопка предложит войти в закрытый заход'
    );
  });

  it('без описания данжа список пуст, а не ошибка', () => {
    must(/if \(!def\) return \[\];/.test(сервис), 'несуществующий данж не обработан');
  });

  it('лидер и состав группы игроку не отдаются', () => {
    // Лишние данные: список работает и без них.
    const начало = сервис.indexOf('listOpenSessions(');
    const тело = сервис.slice(начало, начало + 1100);
    must(!/leaderId|leader:/.test(тело), 'список отдаёт лидера: это лишние данные');
    must(
      /sessionId: сессия\.id/.test(тело) && /members: сессия\.members\.size/.test(тело),
      'в списке нет идентификатора и числа участников — кнопке нечего показать'
    );
  });

  it('маршрут списка есть и он защищён', () => {
    must(маршруты.includes("'/dungeons/:dungeonId/sessions'"), 'маршрута списка заходов нет');
    // Блок — до следующего объявления маршрута, а не окном в символах. Окно
    // однажды захватило secureMiddleware из соседнего маршрута, и проверка
    // осталась зелёной на маршруте без защиты.
    const начало = маршруты.indexOf("'/dungeons/:dungeonId/sessions'");
    const конец = маршруты.indexOf('gameRouter.', начало + 10);
    const блок = маршруты.slice(начало, конец > начало ? конец : начало + 400);
    must(блок.includes('secureMiddleware'), 'список заходов открыт всем подряд');
    must(/listOpenSessions\(req\.params\.dungeonId\)/.test(маршруты), 'маршрут не вызывает список');
  });
});

describe('Кнопка присоединения: клиент умеет ею пользоваться', () => {
  it('вызов списка и вызов присоединения объявлены', () => {
    must(/dungeonSessions: \(dungeonId: string\)/.test(апи), 'вызова списка заходов нет на клиенте');
    must(
      /dungeonJoin: \(dungeonId: string, sessionId: string, characterId: string\)/.test(апи),
      'вызова присоединения нет на клиенте'
    );
  });

  it('вызов присоединения идёт по правильному адресу и несёт идентификатор захода', () => {
    must(/\/api\/game\/dungeons\/\$\{dungeonId\}\/join/.test(апи), 'адрес присоединения не тот');
    must(/JSON\.stringify\(\{ characterId, sessionId \}\)/.test(апи), 'идентификатор захода не уходит на сервер');
  });

  it('панель берёт список и рисует кнопку', () => {
    must(/api\.dungeonSessions\(d\.id\)/.test(панель), 'панель не берёт список заходов');
    must(/api\.dungeonJoin\(d\.id, заход\.sessionId, cid\(\)\)/.test(панель), 'кнопка не вызывает присоединение');
    must(/actionButton\(t\('panels\.join_run'\)/.test(панель), 'кнопки «вступить» нет');
  });

  it('список берётся на каждый данж, а не один раз', () => {
    // Один вызов на весь список показал бы заходы первого данжа всем.
    const вызовы = панель.match(/api\.dungeonSessions\(/g) ?? [];
    must(вызовы.length === 1, `вызовов списка заходов ${вызовы.length}: один список показал бы заходы всем`);
    must(/api\.dungeonSessions\(d\.id\)/.test(панель), 'список берётся не по данжу');
  });

  it('кнопка не рисуется, когда игрок уже в заходе', () => {
    // Человек внутри данжа не должен видеть «вступить».
    // Точная последовательность, а не «где-то рядом есть if (!status.active)»:
// такой поиск попадал на соседний if от кнопки входа и проходил на маршруте,
    // где кнопка присоединения рисуется всем.
    must(
      /if \(!status\.active\) \{\s*const открытые = await api\.dungeonSessions\(d\.id\)/.test(панель),
      'кнопка присоединения рисуется без проверки, что игрок ещё не в заходе'
    );
  });

  it('список переживает недоступность и не ломает панель', () => {
    must(
      /api\.dungeonSessions\(d\.id\)\.catch\(/.test(панель),
      'падение списка заходов уронит панель данжей целиком'
    );
  });

  it('тексты кнопки переведены во всех трёх языках', () => {
    for (const кодЯзыка of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${кодЯзыка}.json`));
      for (const ключ of ['join_run', 'joined_run', 'run_open']) {
        must(
          typeof словарь.panels?.[ключ] === 'string' && словарь.panels[ключ].length > 0,
          `в ${кодЯзыка}.json нет текста panels.${ключ}`
        );
      }
    }
  });
});

describe('Кнопка присоединения: маршруты обеспечены вызовом', () => {
  it('присоединение больше не числится маршрутом без вызова', () => {
    // Проверка apiSurface следит за этим списком; когда кнопка появилась,
    // маршрут должен был из списка уйти. Здесь фиксируем, что он ушёл.
    const список = читать('server/src/tests/apiSurface.test.ts');
    must(
      !/'POST \/api\/game\/dungeons\/:\/join'/.test(список),
      'маршрут присоединения всё ещё записан как «без клиентского вызова»: клиент его вызывает'
    );
  });
});
