// Живые последствия, кусок 3 (§361): караванщики помнят грабителя.
//
// ЗА ЧТО БОРЕТСЯ. Грабёж караванов (Шёлковый путь) существовал как механика
// и как выгода: поднял засаду, забрал груз, пришёл принять новый контракт —
// и караванщики радовались клиенту. Мир не помнил ничего: атака на караван
// не имела последствий для самой торговли.
//
// ЧТО ТЕПЕРЬ. Засада публична: конвой поднят у всех на глазах, и запись
// caravan_ambushes стоит в базе в момент поднятия. Свежая запись — и
// контракт не принимается с честным кодом caravan_grudge, а клиент называет
// причину, а не «что-то сломалось». Удачной засада быть не обязана:
// попытка уже испортила доверие.
//
// ПОЧЕМУ ИСТОЧНИК — ТАБЛИЦА, А НЕ НОВАЯ КАРТА. AmbushService уже пишет
// caravan_ambushes в момент атаки. Своя «карта обид» в TradeService была бы
// второй истиной: караванщики помнили бы не то, что случилось, а то, что
// запомнилось. Правило этого проекта: память мира живёт в данных события.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = читать('server/src/systems/TradeService.ts');
const клиент = читать('client/src/app/panels.ts');

describe('Караванная обида: правило в accept', () => {
  it('приём контракта проверяет свежие засады', () => {
    must(/помнятГрабителя\(characterId\)\) return \{ ok: false, code: 'caravan_grudge' \};/.test(сервис),
      'accept не проверяет обиду: грабитель получает контракт как ни в чём не бывало');
  });

  it('проверка читает таблицу засад по нападавшему в окне времени', () => {
    must(/FROM caravan_ambushes\s*\n?\s*WHERE ambusher_id = \$1 AND started_at > NOW\(\) - make_interval\(mins => \$2\)/.test(сервис),
      'обида берётся не из caravan_ambushes: память мира разошлась с событием');
    must(!/new Map|cache/i.test(сервис.slice(сервис.indexOf('помнятГрабителя'), сервис.indexOf('async accept'))),
      'обида кэшируется в памяти процесса: рестарт — и караванщики всё забыли');
  });

  it('длительность обиды в рамках: связно, но не вечна', () => {
    const число = /CARAVAN_GRUDGE_MINUTES = (\d+);/.exec(сервис);
    must(число !== null, 'константы обиды нет: число вшито в запрос');
    const минуты = Number(число![1]);
    must(минуты >= 10 && минуты <= 120,
      `обида ${минуты} минут вне рамок: игрок не свяжет отказ с засадой или наказание дольше памяти мира`);
  });

  it('проверка стоит до создания каравана: отказ не создаёт груз', () => {
    const grudge = сервис.indexOf('помнятГрабителя(characterId)');
    const insert = сервис.indexOf('INSERT INTO trade_caravans', grudge);
    must(grudge >= 0 && insert > grudge, 'обида проверяется после INSERT: отказ роняет караван посреди записи');
  });
});

describe('Клиент называет причину', () => {
  it('grudge — своя строка, а не общий отказ', () => {
    must(/code\.includes\('grudge'\)\) toast\(t\('panels\.trade_err_grudge'\)/.test(клиент),
      'клиент не отличает обиду от прочих отказов: игрок думает, что игра сломалась');
  });
});
