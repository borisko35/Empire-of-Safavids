// Рыбаки и сети на порту.
//
// ЧТО БЫЛО (21 октября 2026, §274). На порту есть рыбак, лодки и озеро, а
// промысла не видно: берег пустой, и порт читался как место, где лодки стоят
// просто так.
//
// ЧТО ТЕПЕРЬ. У кромки воды стоят сети (жерди и полотнище с ячейками) и куча
// улова, и рядом с каждой сетью стоит рыбак.
//
// ГЛАВНОЕ ПРАВИЛО. Рыбак стоит У СВОЕЙ СЕТИ. Сети ставятся в terrain.ts, места
// записываются в список, и NPC проверяются по нему: если сеть сдвинется, рыбак
// поедет за ней.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const NPC = читать('client/src/app/game3d/npc.ts');

/** Порт — начало отсчёта NPC (те же числа, что в terrain.ts). */
const PORT_X = -225;
const PORT_Z = -150;

/** Места сетей — как в terrain.ts. */
function сети(): { x: number; z: number }[] {
  const места: { x: number; z: number }[] = [];
  for (const [nx, nz] of [[-247, -146], [-249, -157]] as const) {
    места.push({ x: nx + 0.9, z: nz + 0.3 });
  }
  return места;
}

describe('Рыбаки и сети на порту', () => {
  it('сети стоят у кромки воды, с уловом', () => {
    должен(/export const сетиРыбаков: \{ x: number; z: number \}\[\] = \[\];/.test(ТЕРРЕЙН),
      'нет списка мест сетей');
    // Жердь, полотнище и куча улова.
    должен(/const жердь = new THREE\.Mesh\(new THREE\.CylinderGeometry/.test(ТЕРРЕЙН),
      'у сети нет жерди');
    должен(/const полотно = new THREE\.Mesh\(new THREE\.PlaneGeometry\(2\.8, 2\.2\), MAT\.net\);/.test(ТЕРРЕЙН),
      'у сети нет полотнища с ячейками');
    должен(/const куча = new THREE\.Mesh\(new THREE\.ConeGeometry/.test(ТЕРРЕЙН),
      'у сети нет улова');
    // Место сети записывается — по нему потом ставятся рыбаки.
    должен(/сетиРыбаков\.push\(\{ x: nx \+ 0\.9, z: nz \+ 0\.3 \}\);/.test(ТЕРРЕЙН),
      'место сети не записывается: рыбак поедет не туда');
  });

  it('рыбак стоит у своей сети', () => {
    const места = сети();
    места.forEach((сеть, i) => {
      const вход = new RegExp(
        `id: 'npc_fisherman_net_${i}'[\\s\\S]{0,220}?dx: (-?[\\d.]+), dz: (-?[\\d.]+)`,
      ).exec(NPC);
      должен(вход, `нет рыбака у сети ${i}`);
      // Порт — начало отсчёта NPC: смещение относительно него.
      const wx = PORT_X + Number(вход![1]);
      const wz = PORT_Z + Number(вход![2]);
      const d = Math.hypot(wx - сеть.x, wz - сеть.z);
      должен(d < 1.5, `рыбак ${i} стоит в ${d.toFixed(1)} м от своей сети, а не рядом`);
    });
  });
});
