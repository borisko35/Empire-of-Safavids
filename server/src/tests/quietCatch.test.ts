// Молчание должно быть сказано вслух.
//
// ЧТО ЗДЕСЬ. `.catch(() => {})` — это отказ, который никто не увидит: ни
// игрок, ни консоль, ни тот, кто потом будет искать причину. К §153 в коде
// оставалось шесть таких мест, и ни у одного не было записано, чем молчание
// оправдано.
//
// ЧТО ПОМЕНЯЛСЯ. Пять из шести молчаний убраны: там отказ — это потеря, а не
// фон, и он теперь печатается в консоль. Игроку по-прежнему ничего не
// показывается, но поломка видна тому, кто её ищет.
//
//   • выход из аккаунта (world.ts, chars.ts) — сервер не отозвал токен;
//   • отметка «прочитано» без награды (panels.ts) — письмо появится заново;
//   • пропуск сцены (cutscene.ts) — сцена вернётся позже;
//   • предшаг диалога (world.ts) — не сеть, а то, что вне внутреннего try.
//
// Шестое осталось молчать, и это правильно: `vid.play()` по наведению (media.ts)
// блокируется браузером без настоящего жеста, то есть отказ приходит на каждое
// наведение и на тех машинах, где всё работает как задумано. Логировать его —
// значит засорять консоль именно там, где поломки нет.
//
// ПОЧЕМУ МАРКЕР `QUIET:`, А НЕ ФРАЗА ПО-РУССКИ. Регулярка по русскому тексту
// разъезжается переносом строки, и проверка начинает искать не там: это уже
// шестой раз, когда проверка по фразе оказалась хрупче проверки по коду
// (§142, §152, §153, §154, §157). ASCII-маркер переносом не разъезжается.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Кириллица в причинах иероглифами не печатается, но на условие это не влияет.
function должно(условие: unknown, причина: string): void {
  должен(условие, причина);
}

type Файл = { путь: string; строки: string[] };

function читатьКлиентскиеФайлы(): Файл[] {
  const кореньКлиента = join(корень, 'client', 'src');
  const найдено: Файл[] = [];
  const обойти = (папка: string): void => {
    for (const имя of readdirSync(папка)) {
      const полный = join(папка, имя);
      if (statSync(полный).isDirectory()) {
        обойти(полный);
        continue;
      }
      if (!имя.endsWith('.ts')) continue;
      найдено.push({
        путь: полный.slice(кореньКлиента.length + 1).replace(/\\/g, '/'),
        строки: readFileSync(полный, 'utf-8').split('\n'),
      });
    }
  };
  обойти(кореньКлиента);
  return найдено;
}

const ФАЙЛЫ = читатьКлиентскиеФайлы();

/** Голое `.catch(…)`, в котором ничего не происходит и ничего не пишется. */
const ГОЛОЕ = /\.catch\(\s*\(\s*[A-Za-zа-яА-Я_]*\s*\)\s*=>\s*\{\s*\}\s*\)/;

/** Код строки без комментария: иначе поиск цепляет упоминания в пояснениях. */
function безКомментария(строка: string): string {
  const i = строка.indexOf('//');
  return i < 0 ? строка : строка.slice(0, i);
}

describe('Молчание сказано вслух', () => {
  it('обход клиента не ослеп', () => {
    должно(
      ФАЙЛЫ.length > 20,
      'обход клиента нашёл подозрительно мало файлов: проверка ослепла',
    );
  });

  it('голое .catch без записанной причины не вернулось', () => {
    const виновники: string[] = [];
    for (const ф of ФАЙЛЫ) {
      for (let i = 0; i < ф.строки.length; i++) {
        if (!ГОЛОЕ.test(безКомментария(ф.строки[i]))) continue;
        // причина ищется в СЫРОМ тексте: маркер живёт в комментарии, а
        // проверка кода комментарии вырезает
        const окно = ф.строки.slice(Math.max(0, i - 6), i + 1).join('\n');
        if (/QUIET:/.test(окно)) continue;
        виновники.push(`${ф.путь}:${i + 1}`);
      }
    }
    должно(
      виновники.length === 0,
      `молчание без причины: ${виновники.join(', ')}. ` +
        'Либо рядом пишется QUIET: с объяснением, почему отказ не нужен игроку, ' +
        'либо отказ печатается в консоль (требование §153)',
    );
  });

  it('причина молчания названа, а не оставлена на выдумку', () => {
    // Единственное оставшееся молчание — видео по наведению. Если его уберут
    // совсем, а причина останется в карте, читатель решит, что место забыли.
    const медиа = ФАЙЛЫ.find((ф) => ф.путь.endsWith('media.ts'));
    должно(медиа !== undefined, 'файл media.ts не найден: проверка ослепла');
    должно(
      медиа!.строки.some((s) => /QUIET:/.test(s)),
      'в media.ts нет маркера QUIET:, а молчание в нём осталось: причина не записана',
    );
    // Построчно, а не по всему файлу сразу: безКомментария() режет по ПЕРВОМУ
    // же `//`, и на многострочном тексте это отбрасывало всё после шапки —
    // проверка искала уже не там. Здесь это стоило одного падения.
    const естьМесто = медиа!.строки.some((s) => /vid\.play\(\)\.catch/.test(безКомментария(s)));
    должно(
      естьМесто,
      'в media.ts больше нет vid.play().catch(...): снятие молчания должно идти вместе с причиной',
    );
  });

  it('причина записана рядом с местом молчания', () => {
    // ASCII-маркер, а не русская фраза: фраза разъезжается переносом строки.
    const медиа = ФАЙЛЫ.find((ф) => ф.путь.endsWith('media.ts'))!;
    const строка = медиа.строки.findIndex((s) => /vid\.play\(\)\.catch/.test(безКомментария(s)));
    должно(строка >= 0, 'молчание в media.ts не найдено — проверка ослепла');
    // Маркер обязан быть ВЫШЕ, и рядом, а не в шапке файла: причина читается
    // вместе с местом, иначе её найдёт только тот, кто уже знает ответ.
    const выше = медиа.строки.slice(Math.max(0, строка - 6), строка).join('\n');
    должно(
      /QUIET:/.test(выше),
      'маркер QUIET: должен стоять непосредственно над местом молчания, а не в другой части файла',
    );
  });
});