// Рейд «Падение Багдадской Цитадели» — первый рейд в игре.
//
// ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. Рейд отличается от обычного подземелья тремя
// вещами, и каждая из них易 ломается тихо:
//
// 1. Число игроков. Рейд на 20 человек, и заход на 5 — это не рейд, а
//    обычное подземелье с громким названием.
// 2. Финал у везиря. Имя босса в данных и имя в описании того же босса
//    обязаны совпадать: описание «Босс данча "Багдадская Цитадель"»
//    лежало в monsters.ts с момента своего появления, хотя такого данжа
//    не существовало. Описание врало до постройки.
// 3. Сундуки на геометрии. Вскрытие идёт по координатам из данных, а
//    сундук рисуется по координатам из геометрии. Расхождение — сундук
//    в воздухе, и игрок его не найдёт.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

const ДАННЫЕ = читать('server/src/data/dungeons.ts');
const МОНСТРЫ = читать('server/src/data/monsters.ts');
const КЛИЕНТ = читать('client/src/app/game3d/interiors.ts');
const ИНТЕРЬЕРЫ = читать('server/src/data/interiors.ts');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/**
 * Вырезать кусок исходника или упасть.
 *
 * Отдельная функция, а не must(кусок) + кусок!: TypeScript не сужает тип
 * по утверждению о ПЕРЕМЕННОЙ, и проверка либо не собралась бы, либо
 * молча проверяла бы пустую строку — то есть проходила бы на сломанном
 * коде. Ровно так уже было с потерянным guard'ом в main.ts.
 */
function вырезать(код: string, регулярка: RegExp, причина: string): string {
  const найдено = регулярка.exec(код)?.[0];
  must(найдено, причина);
  return найдено as string;
}

describe('Рейд «Падение Багдадской Цитадели»', () => {
  it('подземелье объявлено и помечено как рейд', () => {
    must(
      /'dungeon_baghdad_citadel':\s*\{/.test(ДАННЫЕ),
      'рейд не объявлен в DUNGEONS_DATABASE',
    );
    must(
      /id:\s*'dungeon_baghdad_citadel',[\s\S]{0,900}?isRaid:\s*true/.test(ДАННЫЕ),
      'рейд не помечен isRaid — панель не отличит его от обычного подземелья',
    );
  });

  it('на двадцать человек, а не на пять', () => {
    must(
      /id:\s*'dungeon_baghdad_citadel',[\s\S]{0,900}?maxPlayers:\s*20/.test(ДАННЫЕ),
      'maxPlayers рейда не 20 — это не рейд',
    );
    must(
      /id:\s*'dungeon_baghdad_citadel',[\s\S]{0,900}?minPlayers:\s*10/.test(ДАННЫЕ),
      'minPlayers рейда не 10: заход вчетвером не считается штурмом',
    );
  });

  it('описание босса наконец правдиво', () => {
    // Описание лежало в данных до того, как цитадель существовала, и врало.
    // Теперь подземелье есть, и проверка не даст описанию снова уехать.
    const блок = вырезать(МОНСТРЫ, /'boss_ottoman_pasha':\s*\{[\s\S]*?\n  \}/, 'босса везиря нет в monsters.ts');
    must(
      /description:[^\n]*Багдадская Цитадель/.test(блок),
      'описание везиря больше не называет Багдадскую Цитадель — ' +
        'либо цитадели нет, либо описание описывает другое подземелье',
    );
    // И цитадель правда стала подземельем с этим боссом.
    must(
      /bossId:\s*'boss_ottoman_pasha'/.test(ДАННЫЕ),
      'везирь не объявлен боссом ни одного подземелья — описание снова врёт',
    );
  });

  it('четыре комнаты, и финал помечен как боссовой', () => {
    const блок = вырезать(ДАННЫЕ, /'dungeon_baghdad_citadel':\s*\{[\s\S]*?\r?\n  \},/, 'не вырезался блок рейда');
    const комнаты = [...блок.matchAll(/id:\s*'room_baghdad_[a-z]+'/g)].map(m => m[0]);
    expect({ комнат: комнаты.length }).toEqual({ комнат: 4 });
    must(
      /isBossRoom:\s*true,\s*\n\s*bossId:\s*'boss_ottoman_pasha'/.test(блок),
      'в рейде нет боссовой комнаты с везирем',
    );
  });

  it('сундуки нарисованы там же, где вскрываются', () => {
    // Координаты в данных и в геометрии обязаны совпадать: вскрытие идёт
    // по данным, а рисуется по геометрии.
    const блокДанных = вырезать(ДАННЫЕ, /'dungeon_baghdad_citadel':\s*\{[\s\S]*?\r?\n  \},/, 'не вырезался блок рейда');
    const изДанных = [...блокДанных.matchAll(/chestPositions:\s*\[([^\]]*)\]/g)]
      .flatMap(m => [...m[1].matchAll(/x:\s*(-?[\d.]+),\s*z:\s*(-?[\d.]+)/g)].map(p => [p[1], p[2]]));
    const всего = изДанных.length;
    expect({ сундуков_в_данных: всего }).toEqual({ сундуков_в_данных: 12 });

    // Каждая пара из данных обязана найтись в функции обстановки цитадели.
    const функция = вырезать(КЛИЕНТ, /function furnishBaghdadCitadel[\s\S]*?\n\}/, 'нет функции furnishBaghdadCitadel — сундуки не нарисованы');
    // Знак перед cx необязателен: точка на оси комнаты пишется просто
    // [cx, cz + 6.4], и без «?» такая пара выпадала из разбора — проверка
    // рапортовала бы о пропаже сундука, который нарисован.
    const изГеометрии = [...функция.matchAll(/cx(?:\s*([+-])\s*([\d.]+))?\s*,\s*cz\s*([+-])\s*([\d.]+)/g)]
      .map(m => [
        String(m[2] === undefined ? 0 : Number(m[2]) * (m[1] === '-' ? -1 : 1)),
        String(Number(m[4]) * (m[3] === '-' ? -1 : 1)),
      ]);
    const есть = изГеометрии.map(p => p.join(','));
    const потеряны = изДанных
      .map(p => p.join(','))
      .filter(p => !есть.includes(p));
    expect({ потеряны }).toEqual({ потеряны: [] });
  });

  it('интерьер на своём слоте, а дверь — в мире', () => {
    must(
      /baghdad_citadel:\s*\{[\s\S]{0,240}?roomCx:\s*4968/.test(ИНТЕРЬЕРЫ),
      'интерьер цитадели не на своём слоте: слот 22 = 4000 + 22*44 = 4968',
    );
    must(
      /baghdad_citadel:\s*\{[\s\S]{0,240}?doorX:\s*200,\s*doorZ:\s*-392/.test(ИНТЕРЬЕРЫ),
      'дверь цитаели не в мире или не у спавна паши (200, −380)',
    );
    // Вход подземелья обязан совпадать с комнатой своего интерьера,
    // иначе монстры появятся в пустом месте.
    must(
      /id:\s*'dungeon_baghdad_citadel',[\s\S]{0,700}?entryX:\s*4968/.test(ДАННЫЕ),
      'вход в рейд не совпадает с комнатой своего интерьера',
    );
  });

  it('граница кармана накрывает новую комнату', () => {
    const граница = /POCKET_RECT\s*=\s*\{[^}]*x1:\s*(\d+)/.exec(КЛИЕНТ)?.[1];
    must(граница, 'не найдена правая граница кармана');
    // Комната слота 22 занимает 4968 ± 16.
    expect({ граница: Number(граница), минимум: 4968 + 16 })
      .toEqual({ граница: Math.max(Number(граница), 4984), минимум: 4984 });
  });

  it('функция обстановки заведена, вызывается и есть в типе', () => {
    must(
      /baghdad_citadel: furnishBaghdadCitadel/.test(КЛИЕНТ),
      'furnishBaghdadCitadel не подключена к карте обстановки',
    );
    must(
      /'baghdad_citadel'/.test(КЛИЕНТ.split('function furnishBaghdadCitadel')[0].split('export type BuildingKind')[1] ?? ''),
      "baghdad_citadel нет в типе BuildingKind — запись SPOTS не пройдёт типизацию",
    );
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`)) as {
        buildings: Record<string, string>;
      };
      must(
        словарь.buildings.baghdad_citadel,
        `в ${код}.json нет buildings.baghdad_citadel — здание покажется пустым именем`,
      );
    }
  });
});
