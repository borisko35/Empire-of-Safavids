// Жители новых мест города.
//
// ЧТО БЫЛО (21 октября 2026, §244). Сквер (§239), двор жилого квартала (§240),
// пригород (§241) и сад с прудом (§242) стояли пустыми: без людей место
// читается как декорация, а не как место, где кто-то живёт.
//
// ЧТО ТЕПЕРЬ. По одному жителю в каждом новом месте: цветочница в сквере,
// водоносчица у колодца, мастер в пригороде, садовник у пруда.
//
// ЧТО ПРОВЕРЯЕТСЯ. Все четверо на месте и стоят ТАМ, где их место: смещение
// считается от города, и если кто-то сдвинет сквер или пруд, житель должен
// поехать вместе с ними.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const NPC = читать('client/src/app/game3d/npc.ts');

describe('Жители новых мест города', () => {
  it('у каждого нового места есть свой житель', () => {
    for (const [id, имя] of [
      ['npc_flower_woman', 'Цветочница Мадина'],
      ['npc_well_woman', 'Водоносчица Багира'],
      ['npc_suburb_master', 'Мастер Лейла'],
      ['npc_gardener', 'Садовник Рустем'],
    ] as const) {
      должен(NPC.includes(`id: '${id}'`), `нет жителя ${имя} (${id})`);
      должен(NPC.includes(`nameRu: '${имя}'`), `нет имени ${имя}`);
    }
  });

  it('жители стоят в своих местах', () => {
    // Сквер (местные −12, 4) — цветочница рядом с кустами.
    должен(
      /id: 'npc_flower_woman'[\s\S]{0,220}?dx: -8\.5, dz: 6\.5/.test(NPC),
      'цветочница не в сквере',
    );
    // Колодец в середине кольца домов (59.4, 59.4).
    должен(
      /id: 'npc_well_woman'[\s\S]{0,220}?dx: 56\.5, dz: 62\.5/.test(NPC),
      'водоносчица не у колодца',
    );
    // Пригород: мастерская (120, 111).
    должен(
      /id: 'npc_suburb_master'[\s\S]{0,220}?dx: 120, dz: 114/.test(NPC),
      'мастер не в пригороде',
    );
    // Сад с прудом (−31.5, 77.9).
    должен(
      /id: 'npc_gardener'[\s\S]{0,220}?dx: -27, dz: 81/.test(NPC),
      'садовник не у пруда',
    );
  });
});
