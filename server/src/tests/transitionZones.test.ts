// Переходные зоны: расписание работает и покрывает время без дыр.
//
// ЧЕСТНОЕ ИМЕ. Это расписание, а не сама механика событий. Замер до начала:
// в проекте НЕТ метода появления NPC — ни spawnNpc, ни таймера с интервалом
// в минутах, ни «появления по мировому времени». Есть только postPosition,
// который двигает живого стража по маршруту: это движение, а не событие.
//
// ПОЧЕМУ БЕЗ СЛУЧАЙНОСТИ. Детерминированного генератора в проекте нет вообще:
// ноль seededRandom, ноль mulberry32, ноль Math.random в shared/. Правило
// обязано считаться одинаково на клиенте и сервере.
//
// ГЛАВНОЕ. Расписание легко сделать так, что оно почти всегда пустое: три
// события, каждое видно 25–50% цикла, — и тропа молчит половину времени.
// Проверка ниже меряет, сколько времени цикла тропа занята, и требует, чтобы
// это было осмысленно, а не «иногда что-то происходит».
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  TRANSITION_PERIOD_MS,
  TRANSITION_EVENTS,
  transitionEventsNow,
  anyTransitionNow,
} from '../../../shared/stealth';
import { GUARD_POSTS } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Переходные зоны: расписание считается, а не выдумывается', () => {
  it('событий три, и они разные', () => {
    must(TRANSITION_EVENTS.length === 3, `событий ${TRANSITION_EVENTS.length}, а должно быть 3`);
    const виды = new Set(TRANSITION_EVENTS.map((e) => e.kind));
    must(виды.size === 3, `видов ${виды.size}: события слились в одно`);
  });

  it('интервал в середине диапазона владельца 15–30 минут', () => {
    const минуты = TRANSITION_PERIOD_MS / 60000;
    must(
      минуты >= 15 && минуты <= 30,
      `интервал ${минуты} минут вне диапазона 15–30 из задания владельца`
    );
  });

  it('события не появляются одновременно', () => {
    // Три события в один момент — значит на тропе разом патруль, караван и
    // банда, и «раз в 15–30 минут» перестаёт быть правдой.
    const фазы = new Set(TRANSITION_EVENTS.map((e) => e.phase));
    must(фазы.size === 3, `фаз ${фазы.size} на три события: события накладываются`);
    for (const f of фазы) {
      must(f >= 0 && f < 1, `фаза ${f} вне цикла`);
    }
  });

  it('в начале цикла тропа занята, а не пуста', () => {
    // Самая частая поломка расписания: все фазы сдвинуты так, что на нуле
    // мирового времени ничего не происходит.
    must(anyTransitionNow(0), 'в момент ноль на тропе никого: расписание начинается с пустоты');
  });

  it('тропа занята осмысленную долю времени, а не почти всегда', () => {
    // Меряем долю занятого времени на длинном цикле мелкими шагами.
    const шагов = 3000;
    const шаг = TRANSITION_PERIOD_MS / шагов;
    let занято = 0;
    for (let i = 0; i < шагов; i++) {
      if (anyTransitionNow(i * шаг)) занято++;
    }
    const доля = занято / шагов;
    must(
      доля > 0.5,
      `тропа занята только ${(доля * 100).toFixed(0)}% времени: ` +
        'расписание почти всегда пустое, и игрок ничего не встречает'
    );
    must(
      доля < 1,
      `тропа занята ${(доля * 100).toFixed(0)}% времени: события не уходят вовсе, ` +
        'а «раз в 15–30 минут» означает и появление, и исчезновение'
    );
  });

  it('через полный цикл каждое событие появляется хотя бы раз', () => {
    const увидели = new Set<string>();
    const шагов = 600;
    const шаг = TRANSITION_PERIOD_MS / шагов;
    for (let i = 0; i < шагов; i++) {
      for (const s of transitionEventsNow(i * шаг)) увидели.add(s.kind);
    }
    for (const e of TRANSITION_EVENTS) {
      must(
        увидели.has(e.kind),
        `${e.kind} не появился ни разу за цикл: его фаза и окно присутствия не пересекаются`
      );
    }
  });
});

describe('Переходные зоны: событие присутствует и движется', () => {
  it('событие, когда оно есть, находится на тропе и имеет прогресс', () => {
    const найдено = transitionEventsNow(0);
    must(найдено.length > 0, 'в момент ноль ничего нет');
    for (const s of найдено) {
      must(s.x !== null && s.z !== null, `${s.kind} присутствует, но без координат`);
      must(s.progress !== null, `${s.kind} присутствует, но без прогресса`);
      must(
        s.progress! >= 0 && s.progress! <= 1,
        `${s.kind}: прогресс ${s.progress} вне 0..1, событие ушло за конец тропы`
      );
    }
  });

  it('караван не замечает игрока, банда замечает дальше стражи', () => {
    const караван = TRANSITION_EVENTS.find((e) => e.kind === 'caravan')!;
    const банда = TRANSITION_EVENTS.find((e) => e.kind === 'band')!;
    const стража = TRANSITION_EVENTS.find((e) => e.kind === 'patrol')!;
    must(караван !== undefined && банда !== undefined && стража !== undefined, 'не все три события описаны');
    must(караван.sight === 0, `у каравана обзор ${караван.sight}: он мирный, стелс перед ним бессмыслен`);
    must(
      банда.sight > стража.sight,
      `у банды обзор ${банда.sight}, у патруля ${стража.sight}: банда ищет добычу и должна видеть дальше`
    );
  });

  it('тропа начинается у ворот, а не в поле', () => {
    // Начало отрезка совпадает с точкой схода маршрута привратника (52,26) или
    // с воротами (60,32): обе точки измерены в правиле сторожевых постов.
    const ворота = GUARD_POSTS.find((п) => п.id === 'npc_guard_gate');
    must(ворота !== undefined, 'поста npc_guard_gate нет');
    for (const e of TRANSITION_EVENTS) {
      const уВорот = Math.hypot(e.fromX - ворота!.x, e.fromZ - ворота!.z) <= 10;
      must(
        уВорот,
        `${e.kind} начинается в (${e.fromX}, ${e.fromZ}), это в ${Math.hypot(
          e.fromX - ворота!.x,
          e.fromZ - ворота!.z
        ).toFixed(0)} от ворот: тропа ушла из города в поле`
      );
    }
  });
});

describe('Переходные зоны: правило честное, а не обещающее', () => {
  it('расписание действительно привязано к времени, а не к Math.random', () => {
    const правило = читать('shared/stealth.ts');
    const начало = правило.indexOf('ПЕРЕХОДНЫЕ ЗОНЫ');
    must(начало > 0, 'секция расписания не найдена');
    // КОММЕНТАРИИ ВЫРЕЗАЮТСЯ. Первая версия проверки искала Math.random прямо
    // по тексту секции и находила его В КОММЕНТАРИИ, где написано «ноль
    // Math.random в shared/». Это тот же урок, что и с минаретом (слово в
    // комментарии выдавало себя за геометрию) и с кузницей (отсутствие слова
    // выдавало себя за отсутствие дела). Ищем по коду, а не по тексту.
    const код = правило
      .slice(начало)
      .split(/\r?\n/)
      .filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l))
      .join('\n');
    must(
      !/Math\.random/.test(код),
      'в коде расписания есть Math.random: клиент и сервер разойдутся'
    );
    // Детерминированного генератора в проекте нет вообще — это и есть причина.
    const весьКод = правило
      .split(/\r?\n/)
      .filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l))
      .join('\n');
    must(!/Math\.random/.test(весьКод), 'в коде shared/stealth.ts появился Math.random');
  });

  it('расписание стоит в shared, а не на одной стороне', () => {
    const клиент = читать('client/tsconfig.json');
    must(/stealth\.ts/.test(клиент), "клиент не включает shared/stealth.ts: он не увидит расписание");
  });

  it('интервал не молчит про свою природу: это выбор, а не измерение', () => {
    // Проверка ищет пометку В ПРЯМОЙ ДОКУМЕНТАЦИИ ОБЪЯВЛЕНИЯ, а не в широком
    // окне перед ним. Первая версия брала 400 символов и находила слово
    // «ВЫБОР» в соседнем комментарии про фазу — то есть проходила, даже если
    // пометку у самого интервала снести. Ломка это вскрыла.
    const строки = читать('shared/stealth.ts').split(/\r?\n/);
    const строка = строки.findIndex((l) => l.includes('export const TRANSITION_PERIOD_MS'));
    must(строка > 0, 'интервал не найден');
    // Собираем комментарий над объявлением: идём вверх, пока идут строки с
    // «*» или «//».
    const над: string[] = [];
    for (let i = строка - 1; i >= 0; i--) {
      const s = строки[i].trim();
      if (s.startsWith('*') || s.startsWith('//') || s === '' || s.endsWith('*/')) {
        над.unshift(s);
        if (s.endsWith('*/')) break;
        continue;
      }
      break;
    }
    const пометка = над.join(' ');
    must(
      /ВЫБОР|не измерение/i.test(пометка),
      `рядом с интервалом нет пометки, что это выбор: он выглядит как измерение. Комментарий: «${пометка}»`
    );
  });

  it('появления NPC в проекте по-прежнему нет — и это признано', () => {
    // Расписание без появления — половина механики. Проверка фиксирует
    // честное состояние: если появление появится, её придётся переписать,
    // и это лучше, чем молча выдавать расписание за готовую механику.
    const сервер = читать('server/src/socket/GameSocketHandler.ts');
    const естьПоявление = /spawnNpc|spawnNPC/.test(сервер);
    must(
      !естьПоявление,
      'появление NPC в обработчике уже есть: расписание перестало быть половиной механики — обнови эту проверку и документ'
    );
  });
});