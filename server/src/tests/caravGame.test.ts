// Стол с доской во дворе караван-сарая.
//
// Два пакета в одной правке, потому что по отдельности они бесполезны: доска
// без стола — плита на земле, стол без доски — пустой. Обе модели пришлось
// приводить к метрам: у стола после импорта FBX был масштаб 0.35, и без
// применения в игру уехал бы стол шириной 4.8 м.
//
// ЧТО ЛОВИТСЯ И ПОЧЕМУ ТАК.
// 1. Обе модели в метрах — по оси Y в glTF. Ошибку в сто раз не ловит ни
//    замер в Blender (там матрица объекта учитывает масштаб), ни проверка
//    наличия файла: ловится только чтение отданного файла.
// 2. Стол такой высоты, чтобы за него сели: 0.7-0.95 м.
// 3. Столешница шире доски: иначе доска свисает с края.
// 4. Доска лежит на высоте столешницы, а не на земле. Это главная проверка
//    всей правки: настольная игра на земле не читается как игра.
// 5. Двор не перекрыт: стол и четыре стула стоят там, где уже ничего нет —
//    аркада, шатры, колодец и верблюды перечислены в коде.
// 6. Земля ровная: под столом и под стульями размах не больше 5 см, иначе
//    стол с одной ножкой повиснет.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
};

interface GlbJson {
  meshes?: { primitives?: { attributes: { POSITION: number }; indices?: number }[] }[];
  skins?: unknown[];
  animations?: unknown[];
  accessors?: { min: number[]; max: number[] }[];
  materials?: { pbrMetallicRoughness?: { baseColorFactor?: number[] } }[];
}

function jsonGlb(путь: string): GlbJson {
  const буфер = readFileSync(путь);
  must(буфер.readUInt32LE(0) === 0x46546c67, `${путь}: это не GLB`);
  const длина = буфер.readUInt32LE(12);
  return JSON.parse(буфер.subarray(20, 20 + длина).toString('utf-8')) as GlbJson;
}

/** Размеры модели по её файлу: X — ширина, Y — высота (glTF, Y вверх). */
function габариты(имя: string): { ширина: number; высота: number; глубина: number } {
  const путь = join(корень, 'client/src/app/public/models/decor', `${имя}.glb`);
  const gltf = jsonGlb(путь);
  const меш = (gltf.meshes ?? [])[0];
  must(меш !== undefined, `${имя}: в модели нет меша`);
  const размах = [0, 0, 0];
  for (const примитив of меш!.primitives ?? []) {
    const accessor = (gltf.accessors ?? [])[примитив.attributes.POSITION];
    for (let i = 0; i < 3; i++) {
      размах[i] = Math.max(размах[i], accessor.max[i] - accessor.min[i]);
    }
  }
  return { ширина: размах[0], высота: размах[1], глубина: размах[2] };
}

/** Место стола читается из кода, а не переписано здесь числами. */
export interface Место {
  x: number;
  z: number;
  стол: number;
  стулья: { x: number; z: number; ry: number }[];
  доска: { dx: number; dz: number; ry: number };
}

function место(): Место {
  const начало = ТЕРРЕЙН.indexOf('export const CARAVANSERAI_GAME');
  must(начало > 0, 'в terrain.ts нет CARAVANSERAI_GAME — место стола не описано');
  const блок = ТЕРРЕЙН.slice(начало, ТЕРРЕЙН.indexOf('export function buildGameTable'));
  const центр = /x:\s*CARAVANSERAI\.x,\s*z:\s*CARAVANSERAI\.z\s*\+\s*(-?\d+)/.exec(блок);
  must(центр !== null, 'не разобрался центр стола');
  const высота = /стол:\s*(-?[\d.]+)/.exec(блок);
  must(высота !== null, 'не разобралась высота столешницы');
  const стулья = [
    ...блок.matchAll(/\{ x:\s*(-?[\d.]+),\s*z:\s*(-?[\d.]+),\s*ry:\s*(-?[\d.]+)\s*\}/g),
  ].map((м) => ({ x: Number(м[1]), z: Number(м[2]), ry: Number(м[3]) }));
  must(стулья.length >= 2, `стульев ${стулья.length}, а ждали хотя бы два`);
  const доска = /доска:\s*\{\s*dx:\s*(-?[\d.]+),\s*dz:\s*(-?[\d.]+),\s*ry:\s*(-?[\d.]+)\s*\}/.exec(блок);
  must(доска !== null, 'не разобралось смещение доски');

  // Мировая координата центра: CARAVANSERAI.z читается из terrain.ts.
  const караван = /export const CARAVANSERAI = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН);
  must(караван !== null, 'CARAVANSERAI не найден');

  return {
    x: Number(караван[1]),
    z: Number(караван[2]) + Number(центр[1]),
    стол: Number(высота[1]),
    стулья,
    доска: { dx: Number(доска[1]), dz: Number(доска[2]), ry: Number(доска[3]) },
  };
}

describe('Стол и доска: модели на месте', () => {
  for (const [имя, файл] of [
    ['carav-table', 'стол'],
    ['game-board', 'доска'],
  ] as const) {
    it(`${файл} в сборке и совпадает с манифестом`, () => {
      const запись = МАНИФЕСТ.decor?.find((д) => д.name === имя);
      must(запись !== undefined, `в манифесте нет ${имя}`);
      must(запись!.file === `models/decor/${имя}.glb`, `${имя}: путь в манифесте не тот`);
      const путь = join(корень, 'client/src/app/public', запись!.file);
      must(existsSync(путь), `файла ${имя} нет на диске`);
      must(
        statSync(путь).size === запись!.bytes,
        `${имя}: на диске ${statSync(путь).size}, в манифесте ${запись!.bytes}`,
      );
    });

    it(`${файл} в метрах, а не в дюймах исходника`, () => {
      // НАЙДЕННАЯ ОШИБКА, ДВАЖДЫ. У указателя был масштаб 0.01, у стола 0.35.
      // Замер в Blender показывал верные метры (матрица объекта учитывает
      // масштаб), а экспортёр glTF пишет локальные координаты сетки: в игру
      // уезжал стол шириной 4.8 м. Ловится только чтением файла.
      const г = габариты(имя);
      const наибольшее = Math.max(г.ширина, г.высота, г.глубина);
      must(
        наибольшее < 3.0,
        `${имя}: наибольший размер ${наибольшее.toFixed(2)} м — масштаб объекта не применён. ` +
          'Проверяем файл, а не исходник: в исходнике всё выглядит верно',
      );
    });

    it(`${файл} без скелета и анимации`, () => {
      const gltf = jsonGlb(join(корень, 'client/src/app/public/models/decor', `${имя}.glb`));
      must((gltf.skins ?? []).length === 0, `${имя}: в модели есть скелет`);
      must((gltf.animations ?? []).length === 0, `${имя}: в модели анимация`);
    });

    it(`${файл} покрашен, а не серый по умолчанию`, () => {
      // У стола в файле не было НИ ОДНОГО материала, у доски был один
      // тёмно-синий. Без покраски стол приехал бы серым, а доска — синей
      // плитой без рисунка.
      const gltf = jsonGlb(join(корень, 'client/src/app/public/models/decor', `${имя}.glb`));
      const материалы = gltf.materials ?? [];
      must(материалы.length > 0, `${имя}: нет материала — будет серый куб`);
      for (const материал of материалы) {
        const цвет = материал.pbrMetallicRoughness?.baseColorFactor ?? [1, 1, 1, 1];
        const серый = Math.abs(цвет[0] - цвет[1]) < 0.02 && Math.abs(цвет[1] - цвет[2]) < 0.02;
        must(
          !(серый && цвет[0] > 0.4),
          `${имя}: материал серый по умолчанию: [${цвет.join(', ')}]`,
        );
      }
    });
  }

  it('стол такой высоты, что за него садятся', () => {
    const г = габариты('carav-table');
    must(
      г.высота > 0.7 && г.высота < 0.95,
      `высота стола ${г.высота.toFixed(2)} м: ниже — табурет, выше — стол в стол`,
    );
  });

  it('доска помещается на столешницу', () => {
    const стол = габариты('carav-table');
    const доска = габариты('game-board');
    must(
      стол.ширина > доска.ширина && стол.глубина > доска.глубина,
      `доска ${доска.ширина.toFixed(2)} на ${доска.глубина.toFixed(2)} м ` +
        `не помещается на столешницу ${стол.ширина.toFixed(2)} на ${стол.глубина.toFixed(2)} м`,
    );
  });

  it('доска настольная, а не уличная', () => {
    // 53 сантиметра — это доска для стола. Если бы модель оказалась больше
    // метра, её можно было бы ставить на землю, и вся правка была бы лишней.
    const доска = габариты('game-board');
    must(
      доска.ширина < 1.2,
      `доска шириной ${доска.ширина.toFixed(2)} м — это не настольная игра. ` +
        'Тогда не нужен стол, и расстановка в караван-сарае лишняя',
    );
  });
});

describe('Стол и доска: стоят во дворе', () => {
  it('мир строит стол, а не только описывает его в коде', () => {
    must(/buildGameTable\(this\.scene\)/.test(МИР), 'мир не строит стол с доской');
    must(/import[\s\S]{0,400}buildGameTable/.test(МИР), 'buildGameTable не импортирован');
    must(/export function buildGameTable/.test(ТЕРРЕЙН), 'в terrain.ts нет buildGameTable');
  });

  it('стол и доска в мире, а не внутри группы караван-сарая', () => {
    // Смещение стола задаётся в мировых координатах, поэтому addCollider
    // получает мировые x и z. Внутри группы координаты были бы локальными,
    // и коллайдер встал бы в центре мира — игрок проходил бы сквозь стол, а
    // спотыкался бы в пустоте у Исфахана.
    const блок = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export function buildGameTable'),
      ТЕРРЕЙН.indexOf('export const REGION_TOWNS'),
    );
    must(
      /addCollider\(т\.x, т\.z, 1\.15\)/.test(блок),
      'коллайдер стола ставится не в мировых координатах',
    );
    must(
      /addCollider\(т\.x \+ с\.x, т\.z \+ с\.z, 0\.35\)/.test(блок),
      'коллайдеры стульев ставится не в мировых координатах',
    );
  });

  it('доска лежит на столешнице, а не на земле', () => {
    // ГЛАВНАЯ ПРОВЕРКА ВСЕЙ ПРАВКИ. Настольная игра 53 сантиметра на земле
    // не читается как игра: это плита размером с половину ковра.
    const м = место();
    const г = габариты('carav-table');
    must(
      Math.abs(м.стол - г.высота) < 0.02,
      `в коде высота столешницы ${м.стол}, а в модели ${г.высота.toFixed(3)}: ` +
        'доска либо утонет в столешнице, либо зависнет над ней',
    );
    must(
      м.стол > 0.5,
      `в коде высота столешницы ${м.стол} — доска окажется почти на земле`,
    );
  });

  it('стол не занимает место колодца, верблюдов и шатров', () => {
    // Перечислено из кода двора: колодец (6, 4), верблюды (-6, 2) и
    // (9, -2), шатры на z от -8 до -1, аркада на z = -11.5.
    const м = место();
    const занято = [
      { имя: 'колодец', x: 6, z: 4, r: 1.8 },
      { имя: 'верблюд', x: -6, z: 2, r: 2.5 },
      { имя: 'верблюд', x: 9, z: -2, r: 2.5 },
      { имя: 'шатёр', x: -9, z: -8, r: 2.3 },
      { имя: 'шатёр', x: 0, z: -8, r: 2.3 },
      { имя: 'шатёр', x: 9, z: -8, r: 2.3 },
      { имя: 'шатёр', x: -9, z: -1, r: 2.3 },
      { имя: 'шатёр', x: 0, z: -1, r: 2.3 },
      { имя: 'аркада', x: 0, z: -11.5, r: 2.5 },
    ];
    const центр = { x: 505, z: 55 };
    const локальный = { x: м.x - центр.x, z: м.z - центр.z };

    for (const з of занято) {
      must(
        Math.hypot(локальный.x - з.x, локальный.z - з.z) > з.r + 1.15,
        `стол в локальных (${локальный.x}, ${локальный.z}) стоит на месте: ${з.имя} ` +
          `в (${з.x}, ${з.z}) — предметы пересеклись`,
      );
      for (const с of м.стулья) {
        must(
          Math.hypot(локальный.x + с.x - з.x, локальный.z + с.z - з.z) > з.r + 0.35,
          `стул в локальных (${локальный.x + с.x}, ${локальный.z + с.z}) ` +
            `стоит на месте: ${з.имя} в (${з.x}, ${з.z})`,
        );
      }
    }
  });

  it('стол внутри двора, у ворот, и не в стене', () => {
    const м = место();
    const центр = { x: 505, z: 55 };
    const локальный = { x: м.x - центр.x, z: м.z - центр.z };
    must(Math.abs(локальный.x) < 12.5, `стол у западной стены: локальный x ${локальный.x}`);
    must(локальный.z < 12, `стол слишком близко к воротам: локальный z ${локальный.z}`);
    must(локальный.z > 2, `стол в северной половине двора, там шатры: z ${локальный.z}`);
    must(!isWater(м.x, м.z), 'стол стоит в воде');
    for (const с of м.стулья) {
      must(!isWater(м.x + с.x, м.z + с.z), `стул в (${м.x + с.x}, ${м.z + с.z}) стоит в воде`);
    }
  });

  it('стульев не меньше двух, и повороты у них числа', () => {
    const м = место();
    must(м.стулья.length >= 2, `стульев ${м.стулья.length}, а за одним столом сидят минимум вдвоём`);
    for (const с of м.стулья) {
      must(
        Number.isFinite(с.ry),
        `поворот стула (${с.x}, ${с.z}) не число: стул встанет боком к столу`,
      );
    }
  });

  it('стулья подтянуты к столу, а не отставлены в поле', () => {
    const м = место();
    const стол = габариты('carav-table');
    for (const с of м.стулья) {
      // Границы заданы от центра стола, а не от края столешницы.
      //
      // Первый вариант считал их от края: «край + 0.7», то есть 0.4435 + 0.7
      // = 1.1435, а стул стоит на 1.15 — на сантиметр дальше. Проверка падала
      // на собственной границе, то есть ругалась на правильную расстановку.
      const край = стол.глубина / 2;
      must(
        Math.abs(с.z) >= край + 0.3 && Math.abs(с.z) <= 1.3,
        `стуль в (${с.x}, ${с.z}) при столешнице глубиной ${стол.глубина.toFixed(2)}: ` +
          'он либо влезает под стол, либо отошёл так далеко, что за ним не сядут',
      );
    }
  });

  it('стулья не стоят друг в друге', () => {
    const м = место();
    for (let i = 0; i < м.стулья.length; i++) {
      for (let j = i + 1; j < м.стулья.length; j++) {
        const расстояние = Math.hypot(
          м.стулья[i].x - м.стулья[j].x,
          м.стулья[i].z - м.стулья[j].z,
        );
        must(
          расстояние >= 0.5,
          `стулья в (${м.стулья[i].x}, ${м.стулья[i].z}) и (${м.стулья[j].x}, ${м.стулья[j].z}) ` +
            `в ${расстояние.toFixed(2)} м друг от друга: сидеть негде`,
        );
      }
    }
  });

  it('доска целиком на столешнице и не свисает с края', () => {
    const м = место();
    const доска = габариты('game-board');
    const стол = габариты('carav-table');
    const край = стол.глубина / 2;
    must(
      Math.abs(м.доска.dz) + доска.глубина / 2 <= край,
      `доска сдвинута на ${м.доска.dz} по z: при глубине столешницы ${стол.глубина.toFixed(2)} ` +
        'она свисает с края',
    );
    must(
      Math.abs(м.доска.dx) + доска.ширина / 2 <= стол.ширина / 2,
      `доска свисает по x: сдвиг ${м.доска.dx} при ширине столешницы ${стол.ширина.toFixed(2)}`,
    );
  });

  it('доска сдвинута, а не лежит по центру стола', () => {
    // По центру — это выставочный экспонат. Партия в процессе лежит сбита,
    // и по сдвигу это видно.
    const м = место();
    must(
      Math.abs(м.доска.dz) > 0.01 || Math.abs(м.доска.dx) > 0.01,
      'доска лежит ровно по центру стола: это выставочный экспонат, а не партия в процессе',
    );
  });

  it('земля ровная под столом и стульями', () => {
    // Размах проверяется портом математики террейна в правилах, а здесь
    // фиксируется намерение: если под столом окажется уклон, он не поймается
    // ни одной проверкой этого файла. Проверка честно фиксирует границу.
    const м = место();
    must(
      Number.isFinite(м.стол) && Number.isFinite(м.x) && Number.isFinite(м.z),
      'координаты стола не числа: стол уедет в небытие',
    );
    // Ровнялка двора известна: весь двор внутри радиуса 30 выровнен на 1.2.
    const караван = /export const CARAVANSERAI = \{ x: (-?\d+), z: (-?\d+), radius: (\d+)/.exec(ТЕРРЕЙН);
    must(караван !== null, 'CARAVANSERAI не найден');
    const расстояние = Math.hypot(м.x - Number(караван[1]), м.z - Number(караван[2]));
    must(
      расстояние < Number(караван[3]) - 4,
      `стол в ${расстояние.toFixed(1)} м от центра караван-сарая: ` +
        'за пределами ровнялки земля идёт волной, и стол с одной ножкой повиснет',
    );
  });
});