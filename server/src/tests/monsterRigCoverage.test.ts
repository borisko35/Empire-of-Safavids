// Каждый монстр базы выглядит как сам собой, а не как заглушка.
//
// ЧТО БЫЛО. buildMonsterRig разбирал monsterId в switch на 11 монстров из
// 24, а остальные 13 уезжали в `default: buildHumanoid({ hood, sword })`.
// Молча: это выглядело не поломкой, а бедной графикой. Среди тринадцати
// были четыре босса - bandit_king, ottoman_pasha, div_arzhang и мировой
// босс rustam_reborn. То есть «Великий Рустам» был капюшоном с саблей.
//
// ПОЧЕМУ ЭТО НЕ БЫЛО ВИДНО. У всех 24 монстров в monsters.ts есть поле
// modelPath со ссылкой на .fbx, и оно выглядит как описание внешности.
// Но клиент не грузит модели вообще - он собирает тела процедурно по
// monsterId. Поле modelPath не читается никем: тот же класс мёртвого
// поля, что бонусы территорий и modelPath до этого.
//
// Проверка разбирает исходники, а не импортирует: импортировать rig.ts
// из серверного набора нельзя (клиентский код с three.js), и такой
// тест молча проверял бы сам себя.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { MONSTERS_DATABASE } from '../data/monsters';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const РИГ = readFileSync(join(корень, 'client/src/app/game3d/rig.ts'), 'utf-8');

/** Тело buildMonsterRig: от `switch` до закрывающей скобки функции. */
function телоРазбора(): string {
  const начало = РИГ.indexOf('export function buildMonsterRig');
  must(начало > 0, 'не нашёл buildMonsterRig в client/src/app/game3d/rig.ts');
  const конец = РИГ.indexOf('\n}', начало);
  must(конец > начало, 'buildMonsterRig не найден целиком: функция не закрывается');
  return РИГ.slice(начало, конец);
}

const ТЕЛО = телоРазбора();

describe('Внешность монстров: заглушки больше нет', () => {
  it('у каждого монстра из базы есть своя ветка в разборе', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Раньше 13 монстров молча уезжали в default.
    const безВетки: string[] = [];
    for (const id of Object.keys(MONSTERS_DATABASE)) {
      if (!new RegExp(`case '${id}':`).test(ТЕЛО)) безВетки.push(id);
    }
    must(
      безВетки.length === 0,
      `эти монстры рисуются как default-гуманоид в капюшоне с мечом: ${безВетки.join(', ')}`,
    );
  });

  it('в разборе нет веток для несуществующих монстров', () => {
    // Обратная сторона. Ветка на id, которого нет в базе, - это опечатка:
    // монстр никогда не заспавнится, ветка не сработает никогда, а
    // проверка выше её не заметит.
    const вБазе = new Set(Object.keys(MONSTERS_DATABASE));
    const лишние = [...ТЕЛО.matchAll(/case '([a-z0-9_]+)':/g)]
      .map((м) => м[1])
      .filter((id) => !вБазе.has(id));
    must(лишние.length === 0, `в разборе есть ветки для несуществующих монстров: ${лишние.join(', ')}`);
  });

  it('каждая ветка возвращает тело, а не падает', () => {
    // Ветка может быть объявлена и не возвращать ничего - тогда монстр
    // исчезнет с карты, и это заметят игроки, а не тесты.
    const ветки = [...ТЕЛО.matchAll(/case '([a-z0-9_]+)':\s*\n?\s*return ([a-zA-Z]\w*)\(/g)];
    must(ветки.length > 0, 'не нашёл ни одной ветки, возвращающей тело');
    // Группы нескольких id на одну фигуру - норма (дивы, джинны), но
    // каждая группа должна возвращать конструктор, а не голое значение.
    for (const [, id, конструктор] of ветки) {
      must(
        конструктор.length > 0,
        `ветка монстра ${id} ничего не возвращает`,
      );
    }
  });

  it('default-заглушка осталась и это указано в коде', () => {
    // Заглушка нужна: без неё новый монстр уронит игру на пустом экране.
    // Но она обязана быть помечена как заглушка, иначе следующий автор
    // решит, что все монстры так и рисуются.
    must(/default:/.test(ТЕЛО), 'в разборе нет default: новый монстр уронит клиент');
    must(
      /default:[\s\S]{0,400}?buildHumanoid/.test(ТЕЛО),
      'default возвращает что-то неожиданное - проверь, что это безопасная заглушка',
    );
  });
});

describe('Внешность монстров: поле modelPath', () => {
  it('modelPath не выдаёт себя за рабочее описание', () => {
    // modelPath указывает на .fbx, которых в репозитории нет, и не
    // читается клиентом. Поле выглядит как описание внешности монстра и
    // молчит - ровно тот класс поломки, который здесь и чинится.
    //
    // Проверка не требует удалить поле (это решение владельца данных), но
    // требует, чтобы оно не вводило в заблуждение: если его читать
    // начнут, это будет ошибкой, потому что файлов нет.
    const пути = Object.values(MONSTERS_DATABASE).map((м) => м.modelPath);
    must(пути.length > 0, 'у монстров вообще нет modelPath - проверка устарела');

    // Ищем НЕ слово «modelPath», а обращение к полю: точечная нотация
    // или ключ объекта. Первая версия проверки искала просто слово и
    // упала сама на моём же комментарии в rig.ts, где modelPath
    // объясняет, почему поле мёртвое. Проверка на слово бессмысленна
    // вдвойне: она запрещала бы и объяснение поломки.
    const риг = readFileSync(join(корень, 'client/src/app/game3d/rig.ts'), 'utf-8');
    const обращениеКПолю = /\.modelPath\b|['"]modelPath['"]\s*:/;
    must(
      !обращениеКПолю.test(риг),
      'rig.ts начал читать modelPath: клиент не грузит .fbx, поле указывает на несуществующие файлы',
    );

    // И нигде в клиенте: внешность собирается процедурно.
    const клиент = readFileSync(join(корень, 'client/src/app/game3d/world3d.ts'), 'utf-8');
    must(
      !обращениеКПолю.test(клиент),
      'world3d.ts начал читать modelPath: клиент не грузит 3D-модели, поле мёртвое',
    );
  });

  it('клиент рисует монстра процедурно, а не грузит файл', () => {
    // Якорь на то, ПОЧЕМУ modelPath мёртв. Если клиент когда-нибудь
    // начнёт грузить модели по этому полю, проверка упадёт и укажет,
    // что поле внезапно перестало быть выдумкой.
    const клиент = readFileSync(join(корень, 'client/src/app/game3d/world3d.ts'), 'utf-8');
    must(
      /buildMonsterRig\(/.test(клиент),
      'world3d больше не зовёт buildMonsterRig: внешность монстра строится как-то иначе',
    );
    must(
      !/\.fbx/.test(клиент),
      'world3d.ts упоминает .fbx: клиент не умеет грузить модели, проверка устарела',
    );
  });
});