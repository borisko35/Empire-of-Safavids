// Тени: кромка не должна быть ступенькой, и свет должен следовать за игроком.
//
// ЧТО БЫЛО. Две вещи, обе роняли реалистичность кадра.
//
// 1. Кромка тени была ЖЁСТКОЙ (PCFShadowMap): алиасинг ступенькой по краю
//    читается глазом сразу. Причина — комментарий «мягкие тени вырезаны из
//    Three.js». Он был правдой когда-то, а в three 0.186 константа на месте
//    (const PCFSoftShadowMap = 2, проверено чтением установленной копии).
//    Устаревшая запись стоила проекту мягких теней.
//
// 2. Когда тени выключены (уровень low), тип так и оставался мягким: шейдеры
//    считали выборку вхолостую — свет тень не бросает, а платят за неё.
//
// ЧТО ПРОВЕРЯЕТСЯ. Тип тени мягкий, при выключении — дешёвый, константа
// существует в подключенной three, и теневой свет следует за игроком (иначе
// вне квадрата 92x92 метра тени просто исчезают).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/world3d.ts');
const НАСТРОЙКИ = читать('client/src/app/settings.ts');

describe('Качество теней', () => {
  it('кромка тени мягкая, а не ступенькой', () => {
    // VSM, а не PCFSoft. Про PCFSoft: константа в three осталась, а
    // реализации нет — рендер тихо берёт PCFShadowMap. Ошибка была моя,
    // стоила выката и раздела §134.
    должен(
      /this\.renderer\.shadowMap\.type\s*=\s*THREE\.VSMShadowMap/.test(МИР),
      'в world3d не VSMShadowMap: кромка тени ступенькой, как в игре 2003 года',
    );
    // И не жёсткий режим, и не удалённый тип.
    должен(
      !/shadowMap\.type\s*=\s*THREE\.BasicShadowMap/.test(МИР),
      'основной тип теней стал BasicShadowMap: тени пропадут вовсе',
    );
    должен(
      !/shadowMap\.type\s*=\s*THREE\.PCFSoftShadowMap/.test(МИР),
      'включён тип, которого рендер не знает: кадр молча откатится на жёсткие тени',
    );
  });

  it('при выключенных тенях тип дешёвый', () => {
    // Свет тень не бросает, а мягкая выборка всё равно считается в шейдере.
    //
    // ПРОВЕРКА НА ПРИСВАИВАНИЕ, А НЕ НА УПОМИНАНИЕ. Первая версия искала
    // /нужныйТип|p.shadows...BasicShadowMap/ — и проходила по одному
    // только наличию имени нужныйТип. Ломка «убрать тернарник» её не
    // ломала: имя осталось, а проверка молчала. Так она бы и сторожила
    // ничего.
    должен(
      /p\.shadows\s*\?\s*THREE\.\w+ShadowMap\s*:\s*THREE\.BasicShadowMap/.test(МИР),
      'выключение теней не даёт дешёвый тип: шейдеры считают мягкую выборку вхолостую',
    );
    // И тип должен реально применяться, а не считаться впустую.
    должен(
      /shadowMap\.type\s*=\s*нужныйТип|нужныйТип[\s\S]{0,40}shadowMap\.type/.test(МИР),
      'тип тени считается в переменную и забывается: он не доходит до рендера',
    );
  });

  it('константа VSMShadowMap реализована в подключенной three', () => {
    // Проверять в вакууме бессмысленно: имя должно быть в той версии,
    // которая стоит у клиента. three ставится клиенту, серверный jest его
    // не видит — читаем клиентскую копию.
    const пакет = JSON.parse(читать('client/node_modules/three/package.json')) as { version?: string };
    должен(/^\d+\.\d+\.\d+$/.test(пакет.version ?? ''), 'версия three не читается');
    const рендер = читать('client/node_modules/three/build/three.module.js');
    // Имя в экспортах — это ещё не реализация (см. §134 про PCFSoft).
    должен(
      /SHADOWMAP_TYPE_VSM/.test(рендер),
      `VSM не реализован в three ${пакет.version}: мягкой кромки не будет`,
    );
  });

  it('теневой свет следует за игроком', () => {
    // Камера тени — квадрат +/-46 метров вокруг цели источника. Если цель
    // остаётся в начале координат, вне этого квадрата тени просто исчезают.
    // Владелец играет в городе, который заведомо больше 92 метров.
    должен(
      /this\.sun\.position\.set\(/.test(МИР),
      'источник теней не двигается: он светит из застывшей точки',
    );
    должен(
      /this\.sun\.target\.position\.set\(/.test(МИР),
      'цель источника теней не двигается за игроком: вне квадрата 92x92 тени пропадут',
    );
    // И цель обязана быть в сцене: без add(target) Three.js ею пренебрегает.
    должен(
      /this\.scene\.add\(this\.sun,\s*this\.sun\.target\)/.test(МИР),
      'цель источника не добавлена в сцену: свет смотрит не туда, куда думает код',
    );
  });

  it('из настроек ушло ложное «мягкие тени вырезаны»', () => {
    // Не эстетика: именно эта запись объясняла, почему включены жёсткие.
    // Возвратив её, следующий человек «починит» всё обратно.
    должен(
      !/вырезаны/.test(НАСТРОЙКИ),
      'в settings.ts вернулось «мягкие тени вырезаны»: следующему это объяснит включить жёсткие',
    );
  });
});
