// Туториал не должен ломать игру — и не ломал.
//
// ЧТО БЫЛО. initTutorial читал data.progress.completed без всякой осторожности.
// Ответ приходит по сети, значит может прийти чем угодно: сломанным, пустым,
// с 200-м кодом и телом не-JSON (тогда клиентский req вернёт {}). В любом из
// этих случаев игра падала с TypeError "Cannot read properties of undefined",
// который не говорил ни о чём.
//
// Смысл try/catch был в том, чтобы туториал НЕ ЛОМАЛ игру. Ломал он как раз.
//
// ЧТО ПРОВЕРЯЕТСЯ. Поле читается с проверкой, и отсутствие поля — это тихий
// выход из функции, а не падение. Плюс: серверная часть обязана отдавать поле
// ВСЕГДА, потому что клиент на неё завязан.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const КЛИЕНТ = читать('client/src/app/tutorial.ts');
const МАРШРУТ = читать('server/src/routes/tutorial.ts');
const СЕРВИС = читать('server/src/services/TutorialService.ts');

describe('Туториал не ломает игру', () => {
  it('поле progress читается только ПОСЛЕ проверки', () => {
    // Запрещать само чтение нельзя: после защиты data.progress.completed —
    // законное обращение. Запрещать надо ПОРЯДОК: сначала проверка, потом
    // чтение. Раньше чтение шло первым, и на неожиданном ответе игра падала.
    const защита = КЛИЕНТ.search(/!\s*data\.progress/);
    const чтение = КЛИЕНТ.search(/if\s*\(\s*data\.progress\.completed/);
    должен(защита > 0, 'нет проверки на отсутствие progress');
    должен(чтение > 0, 'в коде нет обращения к progress.completed вовсе — проверка потеряла смысл');
    должен(
      защита < чтение,
      'progress читается ДО проверки: при отсутствии поля игра упадёт, как и падала',
    );
  });

  it('отсутствие поля — тихий выход, а не падение', () => {
    // Ветка обязана вернуться: иначе выполнение падает в showStep с
    // currentStep === undefined.
    должен(
      /!\s*data\.progress[\s\S]{0,400}return;/.test(КЛИЕНТ),
      'при отсутствии progress нет раннего выхода: код пойдёт дальше и сломается',
    );
  });

  it('сервер отдаёт progress ВСЕГДА', () => {
    // Клиент завязан на это поле, и JSON.stringify ВЫБРАСЫВАЕТ ключ со
    // значением undefined: ответ без ключа доходит до клиента как объект
    // без progress. Поэтому поле обязано быть, всегда.
    должен(
      /res\.json\(\{\s*progress,/.test(МАРШРУТ),
      'маршрут перестал отдавать progress: клиент получит объект без этого ключа',
    );
    // И getProgress обязан возвращать объект даже без строки в базе.
    должен(
      /row\s*\?\s*\{[^}]*\}\s*:\s*\{\s*step:\s*0,\s*completed:\s*false\s*\}/.test(СЕРВИС),
      'getProgress без строки в базе возвращает не объект: progress уедет в JSON как undefined',
    );
  });
});