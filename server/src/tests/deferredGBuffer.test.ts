// Отложенный G-buffer не должен остаться в игре молча выключенным.
//
// ЧТО ЗДЕСЬ ЛОВИТСЯ. Отложенный рендер ломается тихо: если материал не
// прошит, его каналы G-buffer остаются пустыми, и AO на этом объекте не
// считается - а картинка остаётся почти такой же. Тот же класс поломки мы
// уже ловили с программой three: когда материал без патча делит ключ кэша с
// материалом с патчем, three переиспользует чужую программу, и каналы пусты
// без единой ошибки.
//
// ПОЧЕМУ ПРОВЕРКИ ТЕКСТОВЫЕ, А ЧИСЛОВЫЕ - В БРАУЗЕРЕ. Считать G-buffer
// можно только с живым WebGL2. Это делает client/src/app/deferred-harness.ts:
// он строит сцену, прогоняет настоящий DeferredPass, читает пиксели каналов
// обратно и печатает числа (нормали единичной длины, альбедо, AO). Без
// браузера числа не получить, поэтому здесь сторож на структуру, а числа —
// на стенде.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const прочитать = (...путь: string[]): string =>
  readFileSync(join(корень, ...путь), 'utf8').replace(/\r\n/g, '\n');

/** Код без комментариев: иначе проверка находит собственное объяснение поломки. */
const код = (...путь: string[]): string =>
  прочитать(...путь)
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/^\s*\/\/.*$/gm, ' ')
    .replace(/\/\/.*$/gm, ' ');

const ОТЛОЖЕННЫЕ = ['deferred'];
const МИР = ['client', 'src', 'app', 'game3d', ...ОТЛОЖЕННЫЕ];
const МИР3D = ['client', 'src', 'app', 'game3d'];
const ФАЙЛ = {
  gbuffer: 'gbuffer.ts',
  ao: 'gbufferAo.ts',
  pass: 'deferredPass.ts',
} as const;

describe('Отложенный G-buffer включён и прошит', () => {
  const gbuffer = код(...МИР, ФАЙЛ.gbuffer);
  const pass = код(...МИР, ФАЙЛ.pass);
  const world3d = код(...МИР3D, 'world3d.ts');

  it('в мире стоит отложенный проход, а не RenderPass', () => {
    must(
      /import \{ DeferredPass \} from '\.\/deferred\/deferredPass'/.test(world3d),
      'world3d не импортирует DeferredPass: отложенный путь не включён',
    );
    must(
      !/RenderPass/.test(world3d),
      'RenderPass снова в цепочке вместе с отложенным проходом: сцена будет '
      + 'рисоваться дважды, а AO ляжет поверх освещённого цвета',
    );
    must(
      !/SSAOPass/.test(world3d),
      'SSAOPass вернулся: он снова рисует сцену вторым проходом ради нормалей, '
      + 'которые теперь и так есть в G-buffer, и AO ляжет дважды',
    );
  });

  it('материалы прошиваются и получают отдельный ключ программы', () => {
    must(
      /patchScene\(/.test(pass),
      'отложенный проход не прошивает сцену: каналы G-buffer останутся пустыми',
    );
    must(
      /КЛЮЧ_ПРОГРАММЫ = 'eos-gbuffer-ao'/.test(gbuffer),
      'у прошитого материала нет своего ключа программы: three возьмёт чужую '
      + 'программу, каналы G-buffer не заполнятся, и это будет выглядеть как '
      + 'просто «нет AO»',
    );
    // Ключ составляется из своего и чужого: у макро-слоя площади свой ключ, и
    // если его потерять, материал получит программу без макро-слоя.
    must(
      /КЛЮЧ_ПРОГРАММЫ\}\|\$\{чужойКлюч\}/.test(gbuffer),
      'ключ программы прошитого материала затирает чужой ключ: материал с '
      + 'макро-слоем тихо потеряет свой патч',
    );
    // Значение ключа обязано читаться ДО подмены onBeforeCompile: по умолчанию
    // three строит его из текста этого обработчика, и после подмены в ключ
    // уедет весь наш патч.
    must(
      /const чужойКлюч = typeof расширяемый\.customProgramCacheKey === 'function'/.test(gbuffer)
      && /расширяемый\.customProgramCacheKey\.call\(material\)/.test(gbuffer),
      'чужой ключ программы читается после подмены onBeforeCompile: three '
      + 'положит в ключ текст нашего патча вместо ключа материала',
    );
  });

  it('мир прошивается после постройки, а не в конструкторе прохода', () => {
    // Проход создаётся в начале сборки мира, когда сцена ещё пуста. Прошивка
    // оттуда даёт отчёт «0 из 0», и каналы G-buffer остаются пустыми у ВСЕГО
    // мира: AO умножает свет по нулевой нормали, отражения не знают, что
    // отражать. Замер на живом мире: 1119 материалов в сцене, 0 прошито.
    const iСборка = world3d.indexOf('this.collectSsrReflectors();');
    const iПрошивка = world3d.indexOf('this.patchWorldMaterials(true)');
    must(iПрошивка > 0, 'после постройки мира нет прошивки G-buffer');
    must(
      iСборка > 0 && iПрошивка > iСборка,
      'прошивка стоит раньше конца постройки мира: сцена ещё пуста, и каналы '
      + 'G-buffer останутся пустыми у всех материалов',
    );
  });

  it('материалы, пришедшие позже, тоже прошиваются', () => {
    // Персонаж, монстры, лошади и караваны грузятся моделями уже после
    // постройки мира. Без повторной прошивки они навсегда остаются без
    // каналов — без AO и без участия в отражениях.
    const iПовтор = world3d.indexOf('this.patchWorldMaterials(false)');
    const iРендер = world3d.indexOf('this.composer.render()');
    must(iПовтор > 0, 'новые материалы не прошиваются повторно');
    must(
      iПовтор < iРендер,
      'повторная прошивка стоит после отрисовки кадра: новые материалы '
      + 'попадут в G-buffer только со следующего кадра, а не с этого',
    );
  });

  it('прошивка не выбрасывает чужой патч материала', () => {
    // Прошивка ПОДМЕНЯЛА onBeforeCompile, и макро-слой площади (textures.ts,
    // addMacroLayer) пропадал молча. Пока сцена не прошивалась вовсе, потерю
    // никто не видел; с работающей прошивкой она стала бы заметной.
    must(
      /прежнийКомпилятор/.test(gbuffer),
      'прошивка не сохраняет прежний onBeforeCompile материала',
    );
    must(
      /прежнийКомпилятор\.call\(material, shader, renderer\)/.test(gbuffer),
      'прежний обработчик сохранён, но не вызывается: чужой патч шейдера '
      + '(макро-слой, свечение) не попадёт в программу',
    );
  });

  it('проход умеет прошивать сцену повторно', () => {
    must(
      /patch\(scene: THREE\.Object3D = this\.scene\): PatchReport/.test(pass),
      'у отложенного прохода нет метода повторной прошивки',
    );
    must(
      /patchScene\(scene, this\.gbuffer\.aoTexture, this\.aoInvRes\)/.test(pass),
      'повторная прошивка не передаёт актуальный инверс разрешения AO: после '
      + 'ресайза поздно прошитые материалы читали бы AO не по тем координатам',
    );
  });

  it('каналы объявлены по location, а не в общий вывод', () => {
    for (const канал of ['gAlbedoRough', 'gNormalMetal', 'gEmissiveMask']) {
      must(
        new RegExp(`layout\\(location = \\d\\) out vec4 ${канал}`).test(gbuffer),
        `нет объявления канала ${канал} по location: без него значение не уйдёт `
        + 'ни в одно вложение, и канал останется пустым',
      );
    }
    must(
      /layout\(location = 1\)/.test(gbuffer) && /layout\(location = 3\)/.test(gbuffer),
      'каналы не разведены по вложениям: все в одну цель попадет последний',
    );
  });

  it('запись каналов стоит там, где посчитаны нужные величины', () => {
    // roughnessFactor и metalnessFactor появляются в шейдере three только
    // после своих include'ов; если писать раньше, компилятор не найдёт имени.
    const iЗапись = gbuffer.indexOf('gAlbedoRough = vec4(diffuseColor.rgb, roughnessFactor)');
    must(iЗапись > 0, 'в шейдере нет записи альбедо и шероховатости');
    must(
      /#include <opaque_fragment>/.test(gbuffer),
      'запись каналов потеряла привязку к opaque_fragment: сдвиг вставил её '
      + 'не туда, и величины окажутся вне области видимости',
    );
  });

  it('AO применяется к рассеянному свету, а не к готовому цвету', () => {
    must(
      /reflectedLight\.indirectDiffuse \*= eosAo/.test(gbuffer),
      'AO не умножает indirectDiffuse: он применён не в том месте, и картинка '
      + 'либо останется как была, либо станет грязной в тенях',
    );
  });

  it('инверс разрешения AO берётся от полного кадра', () => {
    // От инверса полуразмерной карты UV уезжает вдвое за единицу, и AO
    // читается с обёрткой: по краям кадра появляется мусор.
    must(
      /new THREE\.Vector2\(1 \/ Math\.max\(1, width\), 1 \/ Math\.max\(1, height\)\)/.test(pass),
      'в deferredPass AO задан инверс не того размера: он должен быть от '
      + 'полного кадра, потому что gl_FragCoord идёт в его пикселях',
    );
    must(
      /setSize\(width: number, height: number\)/.test(pass)
      && /updateAoInverseResolution/.test(pass),
      'при смене размера окна инверс разрешения не обновляется: после ресайза '
      + 'AO читается не по тем координатам',
    );
  });
  it('unpatched materials still declare all G-buffer outputs', () => {
    must(
      /gAlbedoRough = vec4\(0\.0\)/.test(gbuffer),
      'fallback must write gAlbedoRough placeholder vec4(0.0)',
    );
    must(
      /gNormalMetal = vec4\(0\.5, 0\.5, 1\.0, 0\.0\)/.test(gbuffer),
      'fallback must write gNormalMetal placeholder flat normal',
    );
    must(
      /gEmissiveMask = vec4\(0\.0\)/.test(gbuffer),
      'fallback must write gEmissiveMask placeholder vec4(0.0)',
    );
  });
});

describe('Отложенность объявлена честно', () => {
  const ao = код(...МИР, ФАЙЛ.ao);
  const pass = код(...МИР, ФАЙЛ.pass);

  it('идентификаторы в GLSL — только латиница', () => {
    // Первая версия AO-шейдера была на русских именах переменных и не
    // скомпилировалась: синтаксическая ошибка в строке 95, а на экране —
    // просто чёрный AO. Спецификация GLSL ES допускает не-ASCII не везде.
    for (const [имя, текст] of [
      ['AO', ao],
      ['deferredPass', pass],
    ] as const) {
      const тело = текст.slice(текст.indexOf('precision highp'));
      const кириллица = [...new Set(
        тело.match(/(?:^|[^\w.])([A-Za-z_][А-Яа-яЁё][\wА-Яа-яЁё]*)/g) ?? [],
      )].map((s) => s.trim());
      must(
        кириллица.length === 0,
        `в GLSL файла ${имя} кириллица в идентификаторах: ${кириллица.join(', ')}`,
      );
    }
  });

  it('свойство three с фоном записано, чтобы его не «починили» снова', () => {
    // При фоне-цвете three затирает фреймбуфер через glClear, а тот бьёт по
    // всем вложениям: на небе в канале нормалей лежит цвет фона. Первая
    // попытка вылечить это проходом с drawBuffers не удалась (чтение depth
    // при привязанном depth-текстуре - обратная связь, discard не срабатывал,
    // и квадрат обнулял альбедо всей сцены). Если это не записать, правку
    // попробуют снова.
    must(
      /glClear/.test(прочитать(...МИР, ФАЙЛ.pass)),
      'в deferredPass.ts больше нет описания того, что three затирает все '
      + 'вложения фоном. Без записи это свойство откроют заново и попробуют '
      + 'вылечить проходом, который уже пробовали и который ломает G-buffer',
    );
  });

  it('AO пропускает небо по глубине', () => {
    must(
      /if \(d >= 0\.9999/.test(ao),
      'AO не отбрасывает небо по глубине: он будет считать по мусорному '
      + 'каналу нормалей, который на небе содержит цвет фона',
    );
  });
});