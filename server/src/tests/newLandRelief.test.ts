// Новая земля получила рельеф.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ПРАВКИ. По суше мира:
//   весь мир                   размах  77.3 м, СКО 18.8, выше 20 м 27.2%
//   старый мир (|x|,|z|<=1200) размах  20.5 м, СКО  2.5, выше 20 м  0.0%
//   Герат, радиус 300           размах  18.4 м, СКО  3.0, выше 20 м  0.0%
//   окно 400x400 у Герата      размах  12.4 м
//
// ЧТО БЫЛО НЕ ТАК. Размах мира в 77 метров создавался не рельефом, а кольцом
// гор у самого края карты: edge > 0.72 поднимает землю на 55 метров. Внутри
// мира, включая страну Герата, земля была ровной столешницей с шумом в три
// метра. Расширение мира в семь раз по площади добавило игроку 4400 единиц
// пути по пустому столу.
//
// ЧТО СТАЛО. Страна Герата: СКО 3.0 -> 6.0, окно игрока 12.4 -> 23.6
// метра, максимум 14.7 -> 22.8. Ровное поле 55.3% -> 53.0% суши.
//
// ГЛАВНОЕ ПРАВИЛО, КОТОРОЕ ЗАЩИЩЕНО ПЕРВЫМ ЖЕ УТВЕРЖДЕНИЕМ. Внутри старого
// мира рельеф обязан быть строго нулём - там всё расставлено руками: города,
// дороги, лесная деревня, форт, караван-сарай. Если новый рельеф до туда
// доберётся, он поднимет под ними землю, и поставленное вручную встанет
// неровно или вообще уйдёт под воду. Маска идёт по метрике Чебышёва
// (max по модулю), потому что старый мир был квадратом 2400x2400, а круг от
// центра срезал бы углы и тронул города.
//
// ПРОВЕРКА ВЫЧИСЛЯЕТ ФУНКЦИЮ, А НЕ ИЩЕТ ЕЁ ТЕКСТ. Функции вырезаются из
// terrain.ts, проходят через компилятор и выполняются.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import * as ts from 'typescript';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРАЙН = читать('client/src/app/game3d/terrain.ts');

// Возвращается Record<string, unknown>, а не набор функций: модуль содержит и
// функции, и константы. Первая версия объявила тип «всё - функция», из-за чего
// константа СТАРЫЙ_МИР получила тип функции, а сравнение числа с ней роняло
// компиляцию вместо того, чтобы проверять код.
function вычислить(имена: string[], константы: string[]): Record<string, unknown> {
  const куски: string[] = [];
  for (const имя of константы) {
    // Константа берётся ИЗ ИСХОДНИКА, а не из проверки. Если бы проверка
    // держала свою копию числа 1200, то правка константы в коде прошла бы
    // мимо неё: рельеф поехал бы внутрь старого мира, а проверка радостно
    // подтвердила бы, что всё в порядке, потому что мерила не тот край.
    const строка = ТЕРРАЙН.split(/\r?\n/).find((s) => s.includes(`const ${имя} =`));
    must(строка !== undefined, `не нашёл константу ${имя} в terrain.ts - проверка мерит не тот код`);
    must(/^export const /.test(строка), `строка константы ${имя} не начинается с export - вид исходника изменился`);
    куски.push(строка.replace('export ', '').trim());
  }
  for (const имя of имена) {
    const начало = ТЕРРАЙН.search(new RegExp(`(^|\\n)(export )?function ${имя}\\s*\\(`));
    must(начало >= 0, `не нашёл функцию ${имя} в terrain.ts - проверка мерит не тот код`);
    const конец = ТЕРРАЙН.indexOf('\n}', начало);
    must(конец > начало, `функция ${имя} не закрылась - вид исходника изменился`);
    куски.push(ТЕРРАЙН.slice(начало, конец + 2).replace('export ', ''));
  }
  const js = ts.transpileModule(куски.join('\n'), {
    compilerOptions: { target: ts.ScriptTarget.ES2020 },
  }).outputText;
  must(js.length > 0, 'компилятор вернул пустой код - проверка ничего не сможет посчитать');
  return new Function(`${js}; return { ${[...константы, ...имена].join(', ')} };`)() as Record<string, unknown>;
}

// landformRelief зависит только от vnoise и clamp01, обе чистые. Граница
// старого мира тянется из исходника вместе с ними. smoothstep нужен самому
// vnoise: без него вычисление падало с ReferenceError, то есть проверка не
// работала ни разу вместо того, чтобы проверять.
const модуль = вычислить(
  ['fract', 'hash2', 'smoothstep', 'clamp01', 'vnoise', 'landformRelief'],
  ['СТАРЫЙ_МИР'],
);
const рельеф = модуль.landformRelief as (x: number, z: number) => number;
const СТАРЫЙ_МИР = модуль.СТАРЫЙ_МИР as number;

const WORLD_HALF = 3175;

describe('У новой земли есть рельеф', () => {
  it('граница старого мира взята из кода, а не из проверки', () => {
    // Отдельным шагом, чтобы падало по имени при попытке «просто выкинуть»
    // проверку на константу.
    must(СТАРЫЙ_МИР === 1200,
      `в коде граница старого мира ${СТАРЫЙ_МИР}, а проверка считала под 1200 - ` +
      'край ручной земли поехал бы, и проверка об этом не узнала бы');
  });
  it('внутри старого мира рельеф строго ноль', () => {
    // Старый мир сделан руками. Рельеф, дошедший до него, поднимет землю под
    // городами, дорогами и фортом. Ноль проверяется на всём квадрате, включая
    // углы: круг от центра углы бы срезал, и проверка это не заметила бы.
    let ненулевых = 0, всего = 0;
    let худшая: [number, number, number] = [0, 0, 0];
    for (let x = -СТАРЫЙ_МИР; x <= СТАРЫЙ_МИР; x += 40) {
      for (let z = -СТАРЫЙ_МИР; z <= СТАРЫЙ_МИР; z += 40) {
        всего++;
        const v = рельеф(x, z);
        if (v !== 0) { ненулевых++; if (Math.abs(v) > Math.abs(худшая[2])) худшая = [x, z, v]; }
      }
    }
    must(всего > 100, `проверка прошла вхолостую: всего ${всего} точек старого мира`);
    must(ненулевых === 0,
      `рельеф добрался в старый мир: ${ненулевых} из ${всего} точек не ноль, ` +
      `например (${худшая[0]}, ${худшая[1]}) = ${худшая[2].toFixed(2)} - под поставленными вручную городами земля встанет неровно`);
  });

  it('рельеф настоящий, а не намёк: в стране Герата видно перепад', () => {
    // Исходное состояние измерено: СКО 3.0, окно 400x400 размах 12.4 метра.
    // Проверка идёт по окну игрока, а не по всему миру: игрок не видит мир
    // целиком, он видит кусок. Если в окне перепада нет, рельеф не читается.
    let мин = Infinity, макс = -Infinity;
    for (let x = -900; x <= -500; x += 20) {
      for (let z = 2050; z <= 2450; z += 20) {
        const v = рельеф(x, z);
        мин = Math.min(мин, v); макс = Math.max(макс, v);
      }
    }
    must(макс > мин, 'в окне игрока у Герата рельеф не меняется - страна стоит столбом');
    must((макс - мин) > 10,
      `перепад рельефа в окне игрока у Герата всего ${(макс - мин).toFixed(1)} м ` +
      '(было 12.4 без рельефа, цель - больше 20): глазом разницу не увидеть');
    must(Math.abs(макс) > 15 || Math.abs(мин) > 15,
      `рельеф у Герата слишком мал: от ${мин.toFixed(1)} до ${макс.toFixed(1)} - это шум, а не земля`);
  });

  it('рельеф не выходит за разумные пределы', () => {
    // Рельеф складывается с краем мира (+55) и хребтом (+26..60). Если он
    // сам начнёт давать сотни метров, игрок получит стены и провалы.
    let макс = 0;
    for (let x = -WORLD_HALF; x <= WORLD_HALF; x += 50) {
      for (let z = -WORLD_HALF; z <= WORLD_HALF; z += 50) {
        макс = Math.max(макс, Math.abs(рельеф(x, z)));
      }
    }
    must(макс > 0, 'рельеф нигде не проявился - функция возвращает нуль и толку от неё нет');
    must(макс < 40, `рельеф поднимается на ${макс.toFixed(1)} м - в сумме с краем мира это стена`);
  });

  it('рельеф добавлен в землю, а не лежит мёртвым', () => {
    // Функция может быть написана и не вызвана. Проверяем вызов в
    // terrainHeight, а не существование функции.
    const код = ТЕРРАЙН.replace(/\/\/[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
    must(/h \+= landformRelief\(x, z\)/.test(код),
      'landformRelief не прибавляется к высоте - функция есть, а толку от неё ноль');
  });

  it('рельеф ложится под край мира и хребет, а не поверх', () => {
    // ПОРЯДОК РЕШАЕТ ВСЁ. Если рельеф прибавить после дна водоёмов и после
    // площадок городов, он поднимет берег залива выше уровня моря и высунет
    // холмы сквозь воду: залив превратится в грязь, а игрок будет ходить по
    // плёнке воды над склоном. Поэтому рельеф идёт сразу после базового
    // шума, а всё остальное - после него.
    const код = ТЕРРАЙН.replace(/\/\/[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
    const вызов = код.indexOf('h += landformRelief(x, z)');
    must(вызов > 0, 'не нашёл вызов рельефа в terrainHeight');
    const край = код.indexOf('const edge = Math.max');
    const хребет = код.indexOf('const ridge = ridgeMask(x, z)');
    const дно = код.indexOf('const bed = sm >= w');
    must(край > вызов, 'рельеф прибавляется после края мира - поднимет берег залива');
    must(хребет > вызов, 'рельеф прибавляется после хребта - поменяет береговую линию');
    must(дно > вызов, 'рельеф прибавляется после дна водоёмов - вода окажется над землёй');
  });

  it('край старого мира назван числом, а не спрятан в маске', () => {
    // Граница 1200 = половина старого мира 2400x2400. Если её написать в
    // маске молча, через год никто не поймёт, почему рельеф начинается там.
    must(/СТАРЫЙ_МИР = 1200/.test(ТЕРРАЙН),
      'нет именованной границы старого мира - непонятно, где кончается ручная земля');
  });
});