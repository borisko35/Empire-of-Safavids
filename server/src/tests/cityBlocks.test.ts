// Жилые улицы Исфахана: кварталы, а не россыпь коробок (§328).
//
// ЧТО БЫЛО. Сорок четыре дома ставились случайными точками по городу с
// зазором в три метра. На аэроснимке (замер §328) город читался россыпью
// отдельных коробок на песке: между домами пустырь, улиц нет, кварталов нет,
// и даже готовые фасады не помогали — дома не стояли лицами друг к другу.
//
// ЧТО ТЕПЕРЬ. Восемь переулков лучами от площади до стены, по обе стороны —
// дома лицом на улицу, а промежутки закрыты дувалами с воротами. Улица с
// двумя сплошными стенами по бокам и есть квартал.
//
// ЧТО ПРОВЕРЯЕТСЯ. Случайная россыпь не вернулась; дома строятся общим
// brickHouse и смотрят на переулок; между домами стоит дувал; мостовая
// переулка — с метрическим UV (иначе плитка растягивается в доски); у дома
// есть зубчатый парапет, глиняная кровля и арочный портал.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

/** Тело функции по имени: от объявления до закрывающей скобки на нуле. */
function тело(имя: string): string {
  const начало = код.indexOf(`function ${имя}(`);
  должен(начало >= 0, `в коде нет функции ${имя}`);
  const конец = код.indexOf('\n}\n', начало);
  должен(конец > начало, `у функции ${имя} не найден конец`);
  return код.slice(начало, конец);
}

describe('Жилые улицы', () => {
  it('случайная россыпь домов не вернулась', () => {
    должен(!/for \(let i = 0; i < 44; i\+\+\) \{\n\s*const a = rng\(\)/.test(код),
      'дома снова ставятся сорока четырьмя случайными точками: улиц нет');
    должен(/жилыеУлицы\(city, placed\);/.test(код),
      'жилые улицы не строятся: город остался россыпью');
  });

  it('дом стоит лицом к переулку, а не куда повернётся', () => {
    const улицы = тело('жилыеУлицы');
    должен(/brickHouse\(city, cx, cz, w, h, \{/.test(улицы),
      'дома улицы строятся не общим brickHouse: фасад разъедется');
    // Локальный +z дома смотрит на ось переулка.
    должен(/const rotY = Math\.atan2\(-сторона \* px, -сторона \* pz\);/.test(улицы),
      'дом не разворачивается фасадом к переулку');
    должен(/if \(занято\.some\(\(p\) => Math\.hypot\(p\.x - cx, p\.z - cz\) < p\.r \+ r \+ 2\.0\)\) continue;/.test(улицы),
      'дом ставится без проверки занятых мест: встанет в мечеть или в проспект');
  });

  it('между домами стоит дувал с воротами', () => {
    const улицы = тело('жилыеУлицы');
    должен(/дувал\(/.test(улицы), 'промежутки между домами не закрыты: улица без стен');
    const стена = тело('дувал');
    должен(/BoxGeometry\(0\.36, 2\.3, длина\)/.test(стена), 'дувал не построен стеной');
    должен(/if \(жребий > 0\.3 && длина > 1\.6\)/.test(стена),
      'ворота стоят в каждом промежутке: ряд одинаковых калиток');
  });

  it('ворота — это столбы, перекладина и полотно, а не полотно само по себе (§331)', () => {
    const стена = тело('дувал');
    должен(/BoxGeometry\(0\.26, 2\.05, 0\.26\)/.test(стена),
      'у ворот нет столбов: доска ворот торчит из стены сама по себе');
    должен(/BoxGeometry\(0\.3, 0\.26, 1\.84\)/.test(стена),
      'у ворот нет перекладины: проём не закрыт сверху');
    должен(/const полотно = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.12, 1\.9, 1\.3\), MAT\.wood\);\n\s*полотно\.position\.set\(лицо\(0\.02\), 0\.95, 0\);/.test(стена),
      'полотно снова в толще стены: доску ворот не видно, ворота не читаются');
  });

  it('глухой дувал — рёбра и ниша с полкой, а не сплошная полоса (§331)', () => {
    const стена = тело('дувал');
    должен(/BoxGeometry\(0\.14, 2\.1, 0\.5\)/.test(стена),
      'на глухом дувале нет рёбер-контрфорсов: стена снова сплошной пласт');
    должен(/BoxGeometry\(0\.03, 0\.6, 0\.44\)/.test(стена) && /BoxGeometry\(0\.24, 0\.07, 0\.52\)/.test(стена),
      'нет ниши с полкой-сакрой: забор не отличить от складской стены');
    должен(/слитьПоМатериалам\(g\)/.test(стена),
      'детали дувала не слиты: восемь мешей на каждую стену квартала');
  });

  it('мостовая переулка не растянута в доски', () => {
    const улицы = тело('жилыеУлицы');
    должен(/metricBoxUV\(new THREE\.BoxGeometry\(ШИРИНА, 0\.1, длина\)/.test(улицы),
      'мостовая переулка без метрического UV: плитка растянется на всю длину');
    должен(/MAT\.streetLane/.test(улицы),
      'мостовая переулка берёт материал с repeat 3: рисунок повторится трижды');
    должен(/streetLane: new THREE\.MeshStandardMaterial/.test(код),
      'нет материала мостовой с repeat 1');
  });
});

describe('Фасад дома', () => {  it('парапет зубчатый, и зубцы слиты в одну геометрию', () => {
    const обвес = тело('домОбвес');
    должен(/зубцыПарапета\(w, d, h \+ пh\)/.test(обвес),
      'у дома снова гладкий парапет: силуэт — ободок коробки');
    const зубцы = тело('зубцыПарапета');
    должен(/mergeGeometries\(части, false\)/.test(зубцы),
      'зубцы не слиты: тридцать вызовов отрисовки на дом');
  });

  it('у дома глиняная кровля, а не верх бокса', () => {
    const дом = тело('brickHouse');
    должен(/MAT\.houseRoof/.test(дом), 'кровля дома — верх самого бокса: с высоты белые квадраты');
    должен(/houseRoof: surfaceMaterial\('sand_01'/.test(код), 'нет материала глиняной кровли');
  });

  it('вход — рама со стрельчатой аркой, а не буква П с торусом', () => {
    const вход = тело('входДом');
    должен(/pishtaqGeometry\(1\.98, 3\.34, 1\.3, 2\.62, 0\.22\)/.test(вход),
      'вход дома не пиштак: у персидского входа арка, а не перекладина');
    должен(!/TorusGeometry/.test(вход), 'торус-полукруг вернулся на место арки');
  });

  it('окно со ставнями и подоконником, слитое по материалам', () => {
    const окно = тело('окноСоСтавнями');
    должен(/windowPane\(cx, cy, faceZ, rotY, W, H\)/.test(окно),
      'окно со ставнями перестало быть окном города');
    должен(/подоконник/.test(окно), 'у окна нет подоконника: тени под проёмом нет');
    должен(/створка/.test(окно), 'у окна нет ставен: проём снова пятно');
    должен(/return слитьПоМатериалам\(g\);/.test(окно),
      'окно не слито по материалам: двенадцать мешей на проём');
  });
});

describe('Глубина квартала и зелень (§329)', () => {
  it('за первым рядом стоит второй дом во дворе', () => {
    const улицы = тело('жилыеУлицы');
    должен(/const отступ2 = ФАСАД \+ d \+ 4\.6 \+ d2 \/ 2;/.test(улицы),
      'второго ряда нет: за улицей пусто, квартал читается полосой');
    должен(/rotY: rotY \+ Math\.PI/.test(улицы),
      'второй дом смотрит на улицу, а не во двор');
  });

  it('кладка парапета темнее штукатурки', () => {
    должен(/parapet: surfaceMaterial\('sandstone_blocks_04'/.test(код),
      'парапет снова из светлого камня: крыши обведены белым пунктиром с высоты');
    должен(/const меш = new THREE\.Mesh\(гео, MAT\.parapet\);/.test(код),
      'зубцы не перешли на тёмную кладку');
  });

  it('между лучами переулков стоят дворы, а не песок (§332)', () => {
    const улицы = тело('жилыеУлицы');
    должен(/const всеУглы = \[\.\.\.УГЛЫ, УГЛЫ\[0\] \+ Math\.PI \* 2\];/.test(улицы),
      'нет обхода круга лучей: последняя пара не закрывается');
    должен(/for \(let i = 0; i < всеУглы\.length - 1; i\+\+\) \{/.test(улицы),
      'дворы не перебирают пары соседних лучей');
    должен(/for \(let радиус = 30; радиус < CITY\.radius - 26; радиус \+= 15\) \{/.test(улицы),
      'дворы не ставятся вдоль середины лучей');
    должен(/brickHouse\(city, cx, cz, w, h \* 0\.92, \{/.test(улицы),
      'двор без домов: квартал между улицами пустел бы ровно как и песок');
    должен(/rotY: Math\.atan2\(-сторонаДома \* px, -сторонаДома \* pz\),/.test(улицы),
      'двор не знает, куда смотреть дом: обращаются друг на друга');
  });
});