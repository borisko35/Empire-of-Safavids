// Жилые улицы Исфахана: кварталы, а не россыпь коробок (§328).
//
// ЧТО БЫЛО. Сорок четыре дома ставились случайными точками по городу с
// зазором в три метра. На аэроснимке (замер §328) город читался россыпью
// отдельных коробок на песке: между домами пустырь, улиц нет, кварталов нет,
// и даже готовые фасады не помогали — дома не стояли лицами друг к другу.
//
// ЧТО ТЕПЕРЬ. Восемь переулков лучами от площади до стены, по обе стороны —
// дома лицом на улицу, а промежутки закрыты дувалами с воротами. Улица с
// двумя сплошными стенами по бокам и есть квартал.
//
// ЧТО ПРОВЕРЯЕТСЯ. Случайная россыпь не вернулась; дома строятся общим
// brickHouse и смотрят на переулок; между домами стоит дувал; мостовая
// переулка — с метрическим UV (иначе плитка растягивается в доски); у дома
// есть зубчатый парапет, глиняная кровля и арочный портал.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

function должны(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

/** Тело функции по имени: от объявления до закрывающей скобки на нуле. */
function тело(имя: string): string {
  const начало = код.indexOf(`function ${имя}(`);
  должен(начало >= 0, `в коде нет функции ${имя}`);
  const конец = код.indexOf('\n}\n', начало);
  должен(конец > начало, `у функции ${имя} не найден конец`);
  return код.slice(начало, конец);
}

describe('Жилые улицы', () => {
  it('случайная россыпь домов не вернулась', () => {
    должны(!/for \(let i = 0; i < 44; i\+\+\) \{\n\s*const a = rng\(\)/.test(код),
      'дома снова ставятся сорока четырьмя случайными точками: улиц нет');
    должны(/жилыеУлицы\(city, placed\);/.test(код),
      'жилые улицы не строятся: город остался россыпью');
  });

  it('дом стоит лицом к переулку, а не куда повернётся', () => {
    const улицы = тело('жилыеУлицы');
    должны(/brickHouse\(city, cx, cz, w, h, \{/.test(улицы),
      'дома улицы строятся не общим brickHouse: фасад разъедется');
    должны(/const rotY = Math\.atan2\(-сторона \* px, -сторона \* pz\);/.test(улицы),
      'дом не разворачивается фасадом к переулку');
    должны(/if \(занято\.some\(\(p\) => Math\.hypot\(p\.x - cx, p\.z - cz\) < p\.r \+ r \+ 2\.0\)\) continue;/.test(улицы),
      'дом ставится без проверки занятых мест: встанет в мечеть или в проспект');
  });

  it('между домами стоит дувал с воротами', () => {
    const улицы = тело('жилыеУлицы');
    должны(/дувал\(/.test(улицы), 'промежутки между домами не закрыты: улица без стен');
    const стена = тело('дувал');
    должны(/BoxGeometry\(0\.36, 2\.3, длина\)/.test(стена), 'дувал не построен стеной');
    должны(/if \(жребий > 0\.3 && длина > 1\.6\)/.test(стена),
      'ворота стоят в каждом промежутке: ряд одинаковых калиток');
  });

  it('ворота — это столбы, перекладина и полотно, а не полотно само по себе (§331)', () => {
    const стена = тело('дувал');
    должны(/BoxGeometry\(0\.26, 2\.05, 0\.26\)/.test(стена),
      'у ворот нет столбов: доска ворот торчит из стены сама по себе');
    должны(/BoxGeometry\(0\.3, 0\.26, 1\.84\)/.test(стена),
      'у ворот нет перекладины: проём не закрыт сверху');
    должны(/const полотно = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.12, 1\.9, 1\.3\), MAT\.wood\);\n\s*полотно\.position\.set\(лицо\(0\.02\), 0\.95, 0\);/.test(стена),
      'полотно снова в толще стены: доску ворот не видно, ворота не читаются');
  });

  it('глухой дувал — рёбра и ниша с полкой, а не сплошная полоса (§331)', () => {
    const стена = тело('дувал');
    должны(/BoxGeometry\(0\.14, 2\.1, 0\.5\)/.test(стена),
      'на глухом дувале нет рёбер-контрфорсов: стена снова сплошной пласт');
    должны(/BoxGeometry\(0\.03, 0\.6, 0\.44\)/.test(стена) && /BoxGeometry\(0\.24, 0\.07, 0\.52\)/.test(стена),
      'нет ниши с полкой-сакрой: забор не отличить от складской стены');
    должны(/слитьПоМатериалам\(g\)/.test(стена),
      'детали дувала не слиты: восемь мешей на каждую стену квартала');
  });

  it('мостовая переулка не растянута в доски', () => {
    const улицы = тело('жилыеУлицы');
    должны(/metricBoxUV\(new THREE\.BoxGeometry\(ШИРИНА, 0\.1, длина\)/.test(улицы),
      'мостовая переулка без метрического UV: плитка растянется на всю длину');
    должны(/MAT\.streetLane/.test(улицы),
      'мостовая переулка берёт материал с repeat 3: рисунок повторится трижды');
    должны(/streetLane: new THREE\.MeshStandardMaterial/.test(код),
      'нет материала мостовой с repeat 1');
  });
});

describe('Фасад дома (GLB, §336)', () => {
  it('brickHouse использует GLB-модель персидского дома', () => {
    const дом = тело('brickHouse');
    должны(/loadDecorModel`models\/decor\/\$\{modelName}\.glb`/.test(дом),
      'brickHouse не загружает persian-house GLB');
    должны(/metricBoxUV\(new THREE\.BoxGeometry\(w, h, d\)/.test(дом),
      'нет плейсхолдера: дом не отобразится до загрузки GLB');
    должны(/scaleX = w \/ baseW/.test(дом) || /scaleY = h \//.test(дом),
      'нет масштабирования модели под целевые размеры');
  });

  it('у дома глиняная кровля (материал в GLB)', () => {
    const дом = тело('brickHouse');
    должны(!/new THREE\.BoxGeometry\(w - 0\.45, 0\.09, d - 0\.45\)/.test(дом),
      'кровля не должна быть отдельным боксом: она в GLB');
  });

  it('вход — пиштак (встроен в GLB)', () => {
    должны(!/function входДом\(/.test(код),
      'старый входДом не должен использоваться: вход в GLB');
  });

  it('окна встроены в GLB', () => {
    должны(!/function окноСоСтавнями\(/.test(код),
      'старые окна не должны использоваться: они в GLB');
  });
});

describe('Глубина квартала и зелень (§329)', () => {
  it('за первым рядом стоит второй дом во дворе', () => {
    const улицы = тело('жилыеУлицы');
    должны(/const отступ2 = ФАСАД \+ d \+ 4\.6 \+ d2 \/ 2;/.test(улицы),
      'второго ряда нет: за улицей пусто, квартал читается полосой');
    должны(/rotY: rotY \+ Math\.PI/.test(улицы),
      'второй дом смотрит на улицу, а не во двор');
  });

  it('кладка парапета темнее штукатурки (встроена в GLB)', () => {
    const ТЕРРЕЙН2 = читать('client/src/app/game3d/terrain.ts');
    if (!ТЕРРЕЙН2.includes('loadDecorModel(`models/decor/${modelName}.glb`)')) {
      throw new Error('brickHouse не загружает persian-house GLB: парапет в модели');
    }
    if (/const меш = new THREE\.Mesh\(гео, MAT\.parapet\);/.test(код)) {
      throw new Error('парапет не должен быть процедурным: он в GLB-модели');
    }
  });

  it('между лучами переулков стоят дворы, а не песок (§332)', () => {
    const улицы = тело('жилыеУлицы');
    должны(/const всеУглы = \[\.\.\.УГЛЫ, УГЛЫ\[0\] \+ Math\.PI \* 2\];/.test(улицы),
      'нет обхода круга лучей: последняя пара не закрывается');
    должны(/for \(let i = 0; i < всеУглы\.length - 1; i\+\+\) \{/.test(улицы),
      'дворы не перебирают пары соседних лучей');
    должны(/for \(let радиус = 30; радиус < CITY\.radius - 26; радиус \+= 15\) \{/.test(улицы),
      'дворы не ставятся вдоль середины лучей');
    должны(/brickHouse\(city, cx, cz, w, h \* 0\.92, \{/.test(улицы),
      'двор без домов: квартал между улицами пустел бы ровно как и песок');
    должны(/rotY: Math\.atan2\(-сторонаДома \* px, -сторонаДома \* pz\),/.test(улицы),
      'двор не знает, куда смотреть дом: обращаются друг на друга');
  });
});