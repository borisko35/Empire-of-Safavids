describe('Эффекты действительно применяются в бою, а не только описаны', () => {
  it('цикл боя применяет эффект из данных монстра', () => {
    // Главная проверка всего обновления. Раньше в GameLoop не было ни
    // одного упоминания effect - и не было самого эффекта.
    expect({
      спрашивает_план: /debuffPlan\(this\.monsterSkill\(atk\)\)/.test(цикл),
      пишет_в_базу: /this\.debuffService\.apply\(target\.id, план, atk\.instanceId\)/.test(цикл),
    }).toEqual({ спрашивает_план: true, пишет_в_базу: true });
  });

  it('уклонение отменяет и эффект', () => {
    // Иначе монстр отравлял бы игрока, стоявшего вне досягаемости:
    // удара не было, а яд есть.
    expect(/!isDodged \? debuffPlan/.test(цикл)).toEqual(true);
  });

  it('оглушение запрещает удары на сервере', () => {
    // Проверка на сервере, а не в панели: панель можно не открыть.
    expect({
      спрашивает: /this\.debuffs\.isStunned\(socket\.characterId\)/.test(обработчик),
      отказывает: /code: 'stunned'/.test(обработчик),
    }).toEqual({ спрашивает: true, отказывает: true });
  });

  it('проверка оглушения идёт до проверки частоты пакетов', () => {
    // Иначе игрок под оглушением слал бы пакеты и получал отказ про
    // спам вместо отказа про оглушение - ошибка врёт о причине.
    // Сравниваем ВНУТРИ handleCombatAction, а не по всему файлу: в файле
    // есть другой вызов validatePacketRate (на входе на арену, строкой
    // раньше), и первая версия проверки попала в него. Порядок был
    // верным, а из файла это доказать нельзя.
    const начало = обработчик.indexOf('private async handleCombatAction');
    const тело = обработчик.slice(начало, обработчик.indexOf('\n  private ', начало + 10));
    const оглушение = тело.indexOf("code: 'stunned'");
    const частота = тело.indexOf('validatePacketRate');
    expect({
      оглушение_есть: оглушение > 0,
      частота_есть: частота > 0,
      раньше: оглушение < частота,
    }).toEqual({ оглушение_есть: true, частота_есть: true, раньше: true });
  });

  it('урон со временем тикает по таймеру, а не только в момент удара', () => {
    // Ищем ВЫЗОВ, а не имя метода. Первая версия проверки искала
    // `tickDebuffs()` по всему файлу, и удаление вызова из tick() было
    // незаметно: определение метода оставалось на месте, а набор
    // оставался зелёным. Слой «урон со временем не тикает» это и поймал.
    const начало = цикл.indexOf('private tick(): void');
    expect({ начало_найдено: начало > 0 }).toEqual({ начало_найдено: true });
    const тело = цикл.slice(начало, цикл.indexOf('\n  private ', начало + 10));
    expect({
      вызывается: /this\.tickDebuffs\(\)/.test(тело),
      начисляет_урон: /applyDamage\(id, итог\.damage\)/.test(цикл),
    }).toEqual({ вызывается: true, начисляет_урон: true });
  });

  it('эффект продлевается, а не копится', () => {
    // Десять укусов за минуту должны дать одну рану, а не десять.
    // Иначе монстр становился бы тем сильнее, чем чаще бьёт, - а он и
    // так бьёт по кулдауну.
    //
    // Проверяем, что срок ПРОДЛЕВАЕТСЯ, а не просто что есть DO UPDATE.
    // Первая версия проверяла наличие конструкции, и поломка
    // `expires_at = character_debuffs.expires_at` - то есть эффект
    // перестаёт продлеваться вовсе - её проходила.
    const блок = сервис.slice(сервис.indexOf('ON CONFLICT'), сервис.indexOf('} catch', сервис.indexOf('ON CONFLICT')));
    expect({
      есть_конфликт: /ON CONFLICT \(character_id, debuff_id\) DO UPDATE SET/.test(блок),
      продлевает: /expires_at = EXCLUDED\.expires_at/.test(блок),
    }).toEqual({ есть_конфликт: true, продлевает: true });
  });

  it('продление не сбрасывает накопленный урон', () => {
    // last_tick_at не двигается при продлении: иначе рана, продлённая
    // вторым укусом, никогда бы не накопила урона за всё время.
    const блок = сервис.slice(сервис.indexOf('ON CONFLICT'), сервис.indexOf('} catch', сервис.indexOf('ON CONFLICT')));
    expect({
      двигает_только_срок: /expires_at = EXCLUDED\.expires_at/.test(блок),
      не_двигает_тик: !/last_tick_at = EXCLUDED/.test(блок),
    }).toEqual({ двигает_только_срок: true, не_двигает_тик: true });
  });

  it('ошибка базы не превращает удар в ошибку', () => {
    // Эффект - украшение удара. База мигнула: игрок получает урон без
    // отравления, и это переживаемо.
    expect(/catch \(err\)[\s\S]{0,200}logger\.warn\('\[Debuff\] не применён/.test(сервис))
      .toEqual(true);
  });

  it('клиент показывает эффекты и не даёт бить под оглушением', () => {
    const клиент = читать('client/src/app/world.ts');
    expect({
      слушает_тик: /combat:debuff_tick/.test(клиент),
      запрещает_атаку: /isStunnedNow\(\)/.test(клиент),
      чистит_при_выходе: /clearDebuffs\(\)/.test(клиент),
    }).toEqual({ слушает_тик: true, запрещает_атаку: true, чистит_при_выходе: true });
  });
});

