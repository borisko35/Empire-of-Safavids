// Эффекты монстров перестали быть надписями в данных: stun, slow, bleed,
// poison и fear применяются к игроку.
//
// ЧТО БЫЛО. У одиннадцати способностей монстров были объявлены `effect`
// и `effectDuration`, и не читался ни один. Монстр бил числом и забывал
// про то, что у него написано: «Землетрясение» с остановкой на 5 секунд
// выглядело как обычный удар. Панель достижений при этом показывала
// счётчик парирований, а игрок под «Тараном» продолжал бить.
//
// ЗДЕСЬ ТРИ ПРОВЕРКИ ПОДРЯД, И ЭТО НЕ ПЕдантиЗМ. Каждая отвечает на свой
// вопрос, и ни одна не проходит «по построению».
