// Второй фактор: защита, которую нельзя обойти.
//
// ПРАВИЛО. Каждая проверка здесь называет способ поломки, который ловит.
// Проверка, которая может стать зелёной на неверном коде, хуже отсутствующей.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  зашифровать, расшифровать, ключШифрования, ЛИМИТ_ПОПЫТОК, БЛОКИРОВКА_МИНУТ,
} from '../services/TwoFactorService';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const сервис = читать('server/src/services/TwoFactorService.ts');
const вход = читать('server/src/services/AuthService.ts');
const миграция = читать('database/migrations/063_two_factor.sql');

// asserts, а не просто проверка. Без asserts TypeScript не сужает тип после
// вызова, и пришлось бы писать `ключ!` - то есть утверждать не-null вручную в
// каждом месте. Ручное утверждение здесь обесценило бы саму проверку:
// проверка падает с внятным текстом, а `!` молча продолжает работу с null.
function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Секрет не лежит в базе открытым', () => {
  it('ключ выводится из окружения, а не хранится рядом с секретом', () => {
    // Поломка: положить ключ рядом с шифротекстом, «чтобы было проще
    // расшифровать». Тогда украденная база раскрывается целиком.
    expect({
      из_окружения: /process\.env/.test(сервис),
      нет_константы_в_коде: !/=\s*['"][0-9a-f]{32,}['"]/i.test(сервис),
    }).toEqual({ из_окружения: true, нет_константы_в_коде: true });
  });

  it('шифр с аутентификацией, а не просто кодирование', () => {
    // AES-GCM даёт проверку целостности: подмена шифротекста в базе
    // обнаруживается, а не приводит к тихому порче секрета. ECB и XOR
    // такой проверки не имеют.
    expect({
      gcm: /aes-256-gcm/.test(сервис),
      тег_проверяется: /setAuthTag/.test(сервис),
      // Случайный IV обязателен: с постоянным IV одинаковые секреты
      // шифровались бы в одинаковый текст, и по базе можно было бы судить,
      // у кого секреты совпадают.
      iv_случаен: /randomBytes\(12\)/.test(сервис),
    }).toEqual({ gcm: true, тег_проверяется: true, iv_случаен: true });
  });

  it('шифрование и расшифровка идут друг в друга', () => {
    // Проверка на настоящих байтах, а не на виде исходника. Смена шифра или
    // формата хранения без смены расшифровки поймалась бы здесь.
    const ключ = ключШифрования({ JWT_SECRET: 'kljuch-dlya-proverki-2fa' });
    must(ключ, 'ключ не вывелся из JWT_SECRET - проверять нечего');
    const секрет = 'GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ';
    const шифр = зашифровать(секрет, ключ);
    expect({
      расшифровался: расшифровать(шифр, ключ) === секрет,
      // Текст не должен читаться прямо в шифре.
      секрета_в_шифре_нет: !шифр.includes(секрет.slice(0, 8)),
      // Два шифра одного секрета различаются: иначе по базе видно, у кого
      // секреты совпадают.
      шифры_разные: зашифровать(секрет, ключ) !== шифр,
    }).toEqual({ расшифровался: true, секрета_в_шифре_нет: true, шифры_разные: true });
  });

  it('чужой ключ и мусор не дают секрет', () => {
    // Подмена ключа или битая запись обязаны дать null, а не «какой-нибудь»
    // секрет: из которого вычислялись бы неверные коды и игрок был бы
    // заперт снаружи со своим телефоном.
    const возможныйМой = ключШифрования({ JWT_SECRET: 'moy' });
    const возможныйЧужой = ключШифрования({ JWT_SECRET: 'chuzhoy' });
    // null утверждается в тесте про пустое окружение. Здесь берём непустой
    // ключ: must() без asserts не сужает тип, и TypeScript справедливо не
    // даст передать null в функцию, которая ключа ждёт.
    must(возможныйМой && возможныйЧужой, 'ключи не вывелись');
    const мой: Buffer = возможныйМой;
    const чужой: Buffer = возможныйЧужой;
    const шифр = зашифровать('ABCDEFGH', мой);
    expect({
      чужим_не_расшифровать: расшифровать(шифр, чужой) === null,
      мусор_не_расшифровать: расшифровать('не-шифр', мой) === null,
      пусто_не_расшифровать: расшифровать('', мой) === null,
    }).toEqual({ чужим_не_расшифровать: true, мусор_не_расшифровать: true, пусто_не_расшифровать: true });
  });

  it('без ключа в окружении 2FA не включается молча', () => {
    // Пустое окружение обязано дать null, а не ключ из нулей: ключ из нулей
    // шифровал бы «всем сразу», и защита была бы иллюзией.
    expect({
      пусто: ключШифрования({}) === null,
      пробелы: ключШифрования({ JWT_SECRET: '   ' }) === null,
      // Явный ключ важнее общего секрета, если его задали.
      явный_важнее: ключШифрования({ JWT_SECRET: 'a', TWOFA_ENCRYPTION_KEY: 'b' })?.length === 32,
    }).toEqual({ пусто: true, пробелы: true, явный_важнее: true });
  });
});

describe('Код нельзя использовать дважды', () => {
  it('шаг последнего принятого кода обновляется и проверяется в базе', () => {
    // Поломка: не хранить last_used_step. Код действует своё окно в тридцать
    // секунд, и всё это время его можно слать подряд - то есть подсмотренный
    // код превращается в ключ на полминуты.
    // Проверяется САМ ЗАПРОС, а не весь файл. По всему файлу эта же
    // строка есть в комментарии над запросом, и поломка проходила зелёной:
    // регулярка находила собственный комментарий.
    const запрос = /SET last_used_step = [\s\S]*?`,/.exec(сервис)?.[0] ?? '';
    must(запрос, 'в сервисе нет UPDATE с last_used_step - проверять нечего');
    expect({
      колонка_есть: /last_used_step\s+BIGINT/.test(миграция),
      пишется: /SET last_used_step = \$2/.test(запрос),
      // Условие в WHERE - защита от гонки: две параллельные попытки с одним
      // кодом дадут одну запись, а не две.
      с_условием: /last_used_step < \$2/.test(запрос),
    }).toEqual({ колонка_есть: true, пишется: true, с_условием: true });
  });

  it('код восстановления помечается использованным в том же запросе', () => {
    // Порядок «проверил, потом пометил» не защищает: две гонки помечали бы
    // один код дважды. Условие used = false в самом UPDATE - это защита.
    expect({
      условие_в_sql: /used'\) = 'false'/.test(сервис),
      возвращает_строку: /RETURNING 1/.test(сервис),
    }).toEqual({ условие_в_sql: true, возвращает_строку: true });
  });

  it('блокировка перебора считается отдельно от пароля', () => {
    // Поломка: обесценивать 2FA за неудачный код тем же счётчиком, что и
    // пароль, или вовсе не считать. Шестизначный код перебирается за часы,
    // значит нужен отдельный лимит.
    expect({
      колонка: /failed_attempts\s+INTEGER/.test(миграция),
      лимит_константа: /ЛИМИТ_ПОПЫТОК = \d+/.test(сервис),
      // Запрос на снятие блокировки по коду идёт в ту же таблицу.
      // Якорь на самом шаблоне: префикса locked_until в нём нет, он стоит
      // левее, в другой строке запроса.
      блокировка_пишется: /NOW\(\) \+ INTERVAL/.test(сервис),
      лимит_разумный: ЛИМИТ_ПОПЫТОК > 0 && ЛИМИТ_ПОПЫТОК <= 10,
      минут_разумно: БЛОКИРОВКА_МИНУТ > 0 && БЛОКИРОВКА_МИНУТ <= 60,
    }).toEqual({
      колонка: true, лимит_константа: true, блокировка_пишется: true,
      лимит_разумный: true, минут_разумно: true,
    });
  });
});

describe('Второй фактор стоит до выдачи сессии', () => {
  it('сессия не создаётся, пока код не принят', () => {
    // ГЛАВНАЯ ПРОВЕРКА ВСЕГО 2FA. Если бы код проверялся ПОСЛЕ
    // createSession, игрок получил бы рабочий токен и отказку на экране:
    // токен остался бы в браузере, обошёл бы интерфейс и был бы пригоден, пока
    // не истечёт. «Вход защищён вторым фактором» означало бы, что защиты нет.
    const блок = вход.slice(вход.indexOf('async login('));
    const проверка = блок.indexOf('двухФактор.проверитьКод');
    const сессия = блок.indexOf('this.createSession(');
    must(проверка > 0, 'в login нет проверки кода - второй фактор не подключён');
    must(сессия > 0, 'в login нет createSession - проверка не о том');
    expect({ проверка_раньше_сессии: проверка < сессия })
      .toEqual({ проверка_раньше_сессии: true });
  });

  it('неверный код бросает наружу, а не возвращает пустую сессию', () => {
    const блок = вход.slice(вход.indexOf('async login('));
    expect({
      бросает: /throw this\.authError\(результат\.code/.test(блок),
      // Отдельная причина «нужен код», а не «неверные данные»: игрок должен
      // понять, что пароль подошёл. Иначе он начнёт подбирать пароль.
      отдельная_причина: /two_factor_required/.test(блок),
    }).toEqual({ бросает: true, отдельная_причина: true });
  });

  it('аккаунт без второго фактора входит как раньше', () => {
    // Регрессия: включение 2FA у одного игрока не должно ломать вход у
    // всех остальных. Проверка идёт по флагу enabled, а не по наличию
    // строки в таблице - иначе игрок, начавший включение и не закончивший,
    // оказался бы заперт.
    const блок = вход.slice(вход.indexOf('async login('));
    expect({
      спрашивает_флаг: /FROM user_2fa WHERE user_id = \$1 AND enabled = TRUE/.test(блок),
      не_по_наличию_строки: !/FROM user_2fa WHERE user_id = \$1(?! AND)/.test(блок),
    }).toEqual({ спрашивает_флаг: true, не_по_наличию_строки: true });
  });
});

describe('Включение и выключение', () => {
  it('выданный, но не подтверждённый фактор не действует', () => {
    // Поломка: enabled = true сразу при выдаче. Игрок, закрывший вкладку на
    // втором шаге, остался бы с включённой защитой и без входа - а починить
    // это можно было бы только правкой базы.
    expect({
      выдача_без_enabled: /FALSE, NULL, \$3::jsonb/.test(сервис),
      включает_подтверждение: /UPDATE user_2fa SET enabled = TRUE, confirmed_at = NOW\(\)/.test(сервис),
    }).toEqual({ выдача_без_enabled: true, включает_подтверждение: true });
  });

  it('выключение требует верного кода и стирает секрет', () => {
    // Поломка: выключение без кода. Тогда достаточно украсть сессию, чтобы
    // снять защиту с чужого аккаунта - второй фактор защищал бы от угона
    // пароля и не защищал бы от угона сессии.
    expect({
      // Внутри самого сервиса вызов идёт через this, а не через поле
      // двухФактор - это поле в AuthService, другого файла.
      требует_код: /this\.проверитьКод\(userId, код\)/.test(
        сервис.slice(сервис.indexOf('async выключить('), сервис.indexOf('async перевыпуститьКоды('))),
      // УДАЛЕНИЕ, а не обнуление: обнуление оставило бы шифротекст, который
      // расшифровывается старым ключом.
      удаляет: /DELETE FROM user_2fa WHERE user_id = \$1/.test(сервис),
      не_обнуляет: !/UPDATE user_2fa SET enabled = FALSE[^;]*\n\s*WHERE/.test(сервис),
    }).toEqual({ требует_код: true, удаляет: true, не_обнуляет: true });
  });

  it('коды восстановления не хранятся текстом', () => {
    // База - место наиболее вероятной утечки. Открытые коды восстановления в
    // ней означали бы, что утечка базы отменяет второй фактор целиком.
    expect({
      jsonb_колонка: /recovery_hash\s+JSONB/.test(миграция),
      хэш_с_солью: /хэшКодаВосстановления\(к, соль\)/.test(сервис),
    }).toEqual({ jsonb_колонка: true, хэш_с_солью: true });
  });

  it('комментарии миграции только в стиле SQL', () => {
    // В .sql-файле '//' не комментарий. Такой файл роняет сайт целиком на
    // этапе миграции - не одну таблицу, а всё.
    expect({
      нет_двойных_слэшей: !/^\s*\/\//m.test(миграция),
      комментарии_есть: /^--/m.test(миграция),
    }).toEqual({ нет_двойных_слэшей: true, комментарии_есть: true });
  });
});
