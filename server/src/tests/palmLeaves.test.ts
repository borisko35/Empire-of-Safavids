// Листья пальмы: плоский лист не ловит свет с изнанки.
//
// ЧТО БЫЛО (21 октября 2026, §234). Лист пальмы — плоская грань, и солнце
// светит ей в спину: изнанка не получала света вовсе. Замер в кадре по
// экранным координатам самих листьев давал #020b01 — почти чёрный силуэт на
// фоне неба, и пальма читалась чёрной звездой из листьев.
//
// ЧТО ТЕПЕРЬ. У материала листа слабое свечение: изнанка поднимается до
// тёмно-зелёного (#223c20 вместо #020b01) и лист читается листом.
//
// ЧТО ПРОВЕРЯЕТСЯ. Свечение есть, оно слабое и тёмное: при ярком оно
// превратилось бы в ночную зеленую лампу.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Листья пальмы', () => {
  it('у листа есть слабое свечение: изнанка не чёрная', () => {
    const мат = /palmLeaf:\s*new THREE\.MeshStandardMaterial\(\{([\s\S]*?)\}\),/.exec(код);
    должен(мат, 'не найден материал листа пальмы');
    const тело = мат![1];
    должен(
      /emissive:\s*0x[0-9a-f]{6}/.test(тело),
      'у листа нет свечения: плоский лист на фоне неба читается чёрной дырой',
    );
    // Свечение тёмное: зелёный канал не выше 0x40, иначе ночью лист светится.
    const цвет = /emissive:\s*0x([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})/.exec(тело);
    должен(цвет, 'не разобрался цвет свечения листа');
    const зелёный = parseInt(цвет![2], 16);
    должен(зелёный <= 0x40, `зелёный канал свечения 0x${зелёный.toString(16)}: лист будет светиться ночью`);
    // И слабое по силе.
    const сила = /emissiveIntensity:\s*([\d.]+)/.exec(тело);
    должен(сила, 'у листа нет силы свечения');
    должен(
      Number(сила![1]) <= 1,
      `сила свечения листа ${сила![1]}: это уже лампа, а не лист`,
    );
  });
});
