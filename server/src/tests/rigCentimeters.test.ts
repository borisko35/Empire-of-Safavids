// Модели приезжают в сантиметрах, и подгонка обязана это учитывать.
//
// ЧТО БЫЛО. Корневой узел сцены (Armature) несёт scale 0.01 — модели
// экспортированы из Blender в сантиметрах. Подгонка мерила габарит как есть,
// three.js честно учёл 0.01, высота пришла в сотых метра, k вылетел за
// MAX_SCALE, и размер НЕ трогали. Фигура оставалась ростом 0,0365 м.
//
// Замер на живых моделях: геометрия стража 3,6501, мировая высота 0,0365,
// k = 52 при MAX_SCALE = 5.
//
// ЧТО СДЕЛАНО. Корень приводится к единице ДО замера. Тогда высота приходит
// в метрах (3,65), k = 0,52 — внутри диапазона, и нормализация применяется.
//
// ЧТО ПРОВЕРЯЕТСЯ. Порядок действий (это главное: привести корень после
// замера бессмысленно) и сама арифметика на настоящих числах моделей.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const РИГ = читать('client/src/app/game3d/realRig.ts');

/** Числа, снятые с настоящих .glb на живом сайте (см. §139-140). */
const МОДЕЛИ = [
  { имя: 'guard-qizilbash', геометрия: 3.6501, корень: 0.01 },
  { имя: 'market-vendor', геометрия: 1.7102, корень: 0.01 },
];
const TARGET = 1.9;
const MIN_SCALE = 0.2;
const MAX_SCALE = 5;

describe('Подгонка понимает сантиметры', () => {
  it('корень приводится к единице ДО замера габарита', () => {
    // Порядок, а не наличие: привести корень ПОСЛЕ замера не даёт ничего,
    // потому что k уже посчитан по сантиметрам.
    const нормализация = РИГ.indexOf('multiplyScalar(1 / корень)');
    const замер = РИГ.indexOf('new THREE.Box3().setFromObject(сцена)');
    должен(нормализация > 0, 'корень сцены не приводится к единице: модель остаётся в сантиметрах');
    должен(замер > 0, 'замер габарита не читается');
    должен(
      нормализация < замер,
      'корень приводится ПОСЛЕ замера: k уже посчитан по сантиметрам и нормализация не сработает',
    );
  });

  it('после приведения корень действительно даёт нормальный коэффициент', () => {
    // Арифметика на настоящих числах, а не «должно получиться».
    for (const м of МОДЕЛИ) {
      const мироваяБыло = м.геометрия * м.корень;
      const kБыло = TARGET / мироваяБыло;
      должен(
        kБыло > MAX_SCALE,
        `${м.имя}: ожидали, что ДО правки коэффициент вылетал за пределы, а получили ${kБыло.toFixed(2)}`,
      );
      const мироваяСтало = м.геометрия; // корень приведён к 1
      const kСтало = TARGET / мироваяСтало;
      должен(
        kСтало >= MIN_SCALE && kСтало <= MAX_SCALE,
        `${м.имя}: после приведения коэффициент ${kСтало.toFixed(2)} всё ещё вне [${MIN_SCALE}, ${MAX_SCALE}] — правка не помогла`,
      );
    }
  });

  it('масштаб вешается на детей, а сцена остаётся единицей', () => {
    // Если взвесить саму сцену, всё дерево растянулось бы дважды: и через
    // масштаб сцены, и через масштаб корня внутри неё.
    должен(
      /for \(const узел of сцена\.children\)\s*узел\.scale\.multiplyScalar/.test(РИГ),
      'масштаб вешается не на детей сцены: дерево растянется дважды',
    );
    должен(
      !/сцена\.scale\.multiplyScalar/.test(РИГ),
      'масштаб взвешен на саму сцену — получится двойное растяжение',
    );
  });

  it('после приведения мировые матрицы пересчитаны', () => {
    // Замер сразу после смены scale без updateMatrixWorld читает старые
    // матрицы и снова получает сантиметры.
    должен(
      /multiplyScalar\(1 \/ корень\)[\s\S]{0,200}updateMatrixWorld/.test(РИГ),
      'после смены масштаба мировые матрицы не пересчитаны: замер увидит старые',
    );
  });

  it('предупреждение больше не врёт про масштаб корня', () => {
    // Старая формулировка объясняла отказ «масштабом корня в файле» — но
    // корень теперь приводится ДО замера, и такая причина исключена.
    //
    // Проверяется САМ ВЫЗОВ console.warn, а не весь файл: та же фраза
    // осталась в комментарии над корневойМасштаб, и проверка на весь файл
    // падала бы на комментарии. Это пятый случай за серию (secret, корейский
    // символ, «мягкие тени вырезаны», #include, теперь этот).
    // Ищем ИМЕННО это предупреждение: в файле есть и другие console.warn
    // («gltf loader unavailable»), и ленивая регулярка брала первое.
    const вызов = /console\.warn\([\s\S]{0,400}?не трогаю размер[\s\S]{0,400}?\);/.exec(РИГ);
    должен(вызов, 'предупреждение «не трогаю размер» не читается');
    должен(
      !/масштаб корня в файле/.test(вызов![0]),
      'предупреждение всё ещё ссылается на масштаб корня: причина уже устранена',
    );
    // И оно обязано говорить, где искать на самом деле.
    должен(
      /Корень уже приведён к единице/.test(вызов![0]),
      'предупреждение не сообщает, что корень уже приведён: причина отказа осталась загадкой',
    );
  });
});