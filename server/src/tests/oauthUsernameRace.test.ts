// Гонка за именем при входе через соцсеть.
//
// ЗАЧЕМ ФАЙЛ. Имя игрока в OAuthService берётся из профиля провайдера — то
// есть это ЧУЖОЙ ТЕКСТ, написанный кем угодно. Два разных человека вполне
// могут называться одинаково: «Иван» в Google встречается тысячи раз.
//
// Код брал имя так: спросить у базы «есть ли уже такое?» — и если нет,
// вставить. Проверка «спросить, потом вставить» не защищает: между вопросом
// и вставкой в промежуток влезает второй вход с тем же именем, и его INSERT
// падает с 23505. Исключение уходило в общий обработчик, игрок получал 500
// вместо входа, и виноват был не в чём: он честно вошёл через Google.
//
// Правильный порядок — сначала пробовать вставить, и если база сказала
// «занято», брать следующее имя. Проверка эти файлы и сторожит.
//
// ЧТО ТУТ ПРОВЕРЯЕТСЯ. Четыре утверждения:
//   1. Обработчик 23505 вообще есть и стоит именно на вставке пользователя.
//   2. Он НЕ глотает посторонние ошибки: обрыв связи с базой обязан уйти
//      наверх, иначе игрок получит «занято имя» вместо правды о поломке.
//   3. Следующий кандидат обязательно НОВЫЙ (передаётся счётчик skip):
//      вернуть то же занятое имя — значит повторить тот же отказ.
//   4. Аварийное имя тоже не возвращается «как есть» без суффикса.
import { readFileSync } from 'fs';
import { join } from 'path';

const root = join(__dirname, '..', '..', '..');
const read = (p: string): string => readFileSync(join(root, p), 'utf8');

describe('OAuth: имя из чужого профиля', () => {
  const svc = read('server/src/services/OAuthService.ts');

  it('отказ базы о занятом имени ловится и вход продолжается', () => {
    must(svc.includes("code !== '23505'"), 'обработчика 23505 нет — гонка за имя вернётся');
    must(/if \(\(err as \{ code\?: string \}\)\.code !== '23505' \|\| attempt === 4\) throw err;/
      .test(svc), 'посторонняя ошибка не пробрасывается — поломка базы станет «занятым ником»');
  });

  it('попытки повторяются, а не одна', () => {
    must(/let username = await this\.pickUsername\(profile\);/.test(svc),
      'имя подбирается один раз и вставляется без повторов');
    must(/for \(let attempt = 0; attempt < 5; attempt\+\+\)/.test(svc),
      'нет повторных попыток вставки — гонка не пройдёт');
  });

  it('следующий кандидат новый, а не тот же самый', () => {
    must(/username = await this\.pickUsername\(profile, attempt \+ 1\);/.test(svc),
      'после отказа подбирается то же имя — вторая попытка упадёт так же');
    must(/private async pickUsername\(profile: OAuthProfile, skip = 0\)/.test(svc),
      'у pickUsername нет счётчика пропуска');
    must(/for \(let i = skip; i < skip \+ 12; i\+\+\)/.test(svc),
      'цикл подбора начинается не с skip — проверка не двинется вперёд');
  });

  it('аварийное имя тоже помечено суффиксом', () => {
    must(/return `Player_\$\{profile\.providerId\.slice\(0, 8\)\}_\$\{Math\.floor/.test(svc),
      'аварийное имя не имеет суффикса: последняя попытка упрётся в тот же отказ');
    must(!/return `Player_\$\{profile\.providerId\.slice\(0, 8\)\}`;/.test(svc),
      'осталось старое аварийное имя без суффикса');
  });

  it('пароль считается один раз, а не на каждую попытку', () => {
    must(/const passwordHash = await bcrypt\.hash\(uuidv4\(\) \+ uuidv4\(\), 12\);/.test(svc),
      'пароль считается заново на каждой попытке — это десятки лишних секунд хэширования');
  });
});

function must(cond: boolean, why: string): void {
  if (!cond) throw new Error(why);
}