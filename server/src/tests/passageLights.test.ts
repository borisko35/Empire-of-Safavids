// Свет в проёмах: там, где темнота не от ночи.
//
// ЧТО БЫЛО (21 октября 2026, §226). Два места читались чёрными провалами:
//   • ворота дворца — крытая галерея за проёмом стены: перекрытие начинается
//     в 3.2 м, проход проходимый, но днём внутри темно, и снаружи это чёрный
//     прямоугольник;
//   • вход в гробницу — на столбах стояли золотые фонари, а СВЕТА от них не
//     было: геометрия есть, источника нет.
//
// ЧТО ТЕПЕРЬ. У ворот дворца стоят факелы (тот же decor/torch.glb, что у
// караван-сарая), у гробницы горят фонари. И главное: эти источники горят
// ПОСТОЯННО, а не по ночному правилу — проход закрыт от солнца, и днём в
// нём темно так же, как ночью.
//
// ЧТО ПРОВЕРЯЕТСЯ. Чтобы свет не «погас» при переносе в общий список
// уличных факелов: там яркость днём падает до 0.35 от ночной.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
// Проверки идут по коду без комментариев: иначе сторож ловит собственное
// пояснение правки.
const кодТ = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
const кодМ = МИР.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Свет в проёмах', () => {
  it('у ворот дворца стоят факелы', () => {
    должен(
      /export const ПРОЁМНЫЕ_ФАКЕЛЫ = \[/.test(кодТ),
      'нет списка факелов в проёмах',
    );
    // Огонь должен стоять ПОД сводом, то есть внутри ворот, а не перед ними.
    должен(
      /PALACE\.x - 2\.6, z: PALACE\.z \+ GATE_Z - 1\.7/.test(кодТ),
      'факелы в воротах дворца поставлены не под сводом: проход останется тёмным',
    );
    должен(
      /export function buildPassageTorches/.test(кодТ) &&
        /placeDecor\(scene, 'decor\/torch\.glb', т\.x, т\.z, -ТОРЧ_УТОПЛЕН/.test(кодТ),
      'факелы в проёмах не ставятся той же моделью, что у караван-сарая',
    );
  });

  it('фонари гробницы записаны и получают свет', () => {
    должен(
      /export const ФОНАРИ_ГРОБНИЦЫ =/.test(кодТ),
      'фонари гробницы не записаны: их позиции должны быть у источников',
    );
    должен(
      /TOMB\.x \+ s \* \(TOMB_GEO\.door\.w \/ 2 \+ 1\.6\)/.test(кодТ),
      'фонари гробницы поставлены не по краям входа',
    );
    должен(
      /for \(const фонарь of ФОНАРИ_ГРОБНИЦЫ\)/.test(кодМ),
      'фонари гробницы не получают источников света: золотые фонари не светят',
    );
  });

  it('свет в проёмах горит постоянно, а не только ночью', () => {
    // Уличный факел днём горит в четверть силы (0.35 + night * 0.65). В проёме
    // солнце не светит: если такие источники попадут в общий список torches,
    // днём проём снова станет чёрным.
    должен(/private lamps: \{ light: THREE\.PointLight; base: number \}\[\] = \[\];/.test(кодМ),
      'нет отдельного списка постоянных источников: свет в проёмах будет гаснуть днём');
    должен(
      /for \(const l of this\.lamps\) \{\s*l\.light\.intensity = l\.base;/.test(кодМ),
      'постоянные источники не зажигаются на всю силу',
    );
    // И в проёмах, и у фонарей — именно постоянные, а не уличные.
    должен(
      /this\.lamps\.push\(\{ light, base: ТОРЧ_СВЕТ_ЯРКОСТЬ \* 2 \}\)/.test(кодМ),
      'факелы в проёмах попали в список уличных: днём проём останется тёмным',
    );
    должен(/this\.lamps\.push\(\{ light, base: 2\.6 \}\)/.test(кодМ),
      'фонари гробницы не записаны в постоянные источники');
  });
});
