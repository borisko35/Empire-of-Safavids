// Слоты комнат: клиент и сервер обязаны идти в одном порядке.
//
// ЧТО ТУТ ПОЛОЖЕНО ПОД НОЖ. Слот комнаты на клиенте считается по индексу в
// массиве SPOTS: roomCx = POCKET_X + i * ROOM_DX. На сервере слот зашит числом
// в каждой записи INTERIORS. Совпадают они только потому, что оба списка
// идут в одном порядке, и НИЧЕГО этого не проверяет.
//
// КАК ЭТО ВЫГЛЯДЕТ, ЕСЛИ СЛОМАЕТСЯ. Кто-то вставит новый интерьер третьим в
// массив SPOTS, потому что «логично поставить рядом с похожим». Клиент
// раздвинет слоты: всё, что ниже, сдвинется на 44 единицы. Серверные числа
// при этом не изменятся, потому что они написаны вручную. Итог: клиентская
// комната казармы окажется там, где сервер считает комнатой мастерской. Игрок
// войдёт в одну дверь и окажется в другой комнате, а сервер решит, что он
// влетел в стену или вышел за пределы.
//
// ПОЧЕМУ ЭТО ТИХО. Каждая проверка по отдельности осталась бы верной: у каждой
// комнаты есть корректный номер, у каждой двери есть корректные координаты,
// пересечений нет. Ломается только СООТВЕТСТВИЕ двух списков, и до сих пор его
// никто не сверял. Это не «ошибка в данных», это «данные с двух сторон
// разошлись» - самый дорогой вид поломки, потому что виден только на живом
// игроке.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

/** Записи SPOTS в порядке файла, с их объявленными координатами.
 *
 *  ПОЧЕМУ НЕ ОДНОЙ РЕГУЛЯРКОЙ. Первая версия брала запись так:
 *  `\{ id: '([a-z_]+)', kind: '[a-z_]+'[^\n]*?(?:(lx|lz|dx|dz): (-?[\d.]+))?[^\n]*\}`
 *  и группа координат там была НЕОБЯЗАТЕЛЬНОЙ. Движок при первом же
 *  положении успевал пройти без неё, `[^\n]*` съедал остаток строки, и
 *  координаты терялись: проверка «дверь считается от столицы» рапортовала,
 *  что от столицы не считается вообще ничего. Ноль из-за того, что группа
 *  схлопнулась, выглядел как поломка кода, которой нет.
 *  Теперь запись вырезается целиком, а поля ищутся внутри неё поимённо.
 */
function записиКлиента(): { id: string; lx?: number; lz?: number; dx?: number; dz?: number }[] {
  const блок = /const SPOTS:[\s\S]*?\n\};/.exec(клиент)?.[0] ?? '';
  must(блок.length > 0, 'не нашёл массив SPOTS в interiors.ts - вид файла изменился');
  const поле = (запись: string, имя: string): number | undefined => {
    const m = new RegExp(`\\b${имя}: (-?[\\d.]+)`).exec(запись);
    return m ? Number(m[1]) : undefined;
  };
  return [...блок.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'[^\n]*?\}/g)].map((м) => ({
    id: м[1],
    lx: поле(м[0], 'lx'),
    lz: поле(м[0], 'lz'),
    dx: поле(м[0], 'dx'),
    dz: поле(м[0], 'dz'),
  }));
}

/** Слоты клиента ровно так, как их считает сам код. */
function слотыКлиента(): { id: string; roomCx: number }[] {
  const POCKET_X = Number(/export const POCKET_X = (-?\d+)/.exec(клиент)?.[1]);
  const ROOM_DX = Number(/const ROOM_DX = (\d+)/.exec(клиент)?.[1]);
  must(Number.isFinite(POCKET_X) && Number.isFinite(ROOM_DX),
    'не нашёл POCKET_X или ROOM_DX в interiors.ts - клиентский расчёт слота изменился');
  return записиКлиента().map((з, i) => ({ id: з.id, roomCx: POCKET_X + i * ROOM_DX }));
}

describe('Слоты комнат совпадают у сервера и клиента', () => {
  it('клиент и сервер перечисляют интерьеры в одном порядке', () => {
    // Порядок и есть весь механизм. Пока списки идут одинаково, слоты совпадают.
    const уКлиента = записиКлиента().map((з) => з.id);
    const уСервера = Object.keys(INTERIORS);
    const разница = уКлиента.filter((id, i) => уСервера[i] !== id);
    must(разница.length === 0,
      `на позициях [${разница.map((id, i) => `${i}: клиент ${id} / сервер ${уСервера[уКлиента.indexOf(id)]}`).join(', ')}] ` +
      'порядок разошёлся. Вставка нового интерьера в середину списка сдвинет ' +
      'все последующие комнаты на клиенте, а серверные номера останутся прежними');
  });

  it('слот каждой комнаты, посчитанный клиентом, равен номеру на сервере', () => {
    // Прямая сверка чисел. Это ровно то расхождение, из-за которого игрок
    // оказывается не в той комнате.
    const клиентские = слотыКлиента();
    const расхождения = клиентские
      .map((к) => ({ ...к, серверный: INTERIORS[к.id]?.roomCx }))
      .filter((к) => к.серверный !== к.roomCx);
    must(расхождения.length === 0,
      `клиент посчитал слоты иначе, чем записано на сервере:\n  ` +
      расхождения.map((к) => `${к.id}: клиент ${к.roomCx}, сервер ${к.серверный}`).join('\n  '));
  });

  it('число интерьеров у обеих сторон одно', () => {
    // Разное число - это предыдущий сдвиг в чистом виде: одна сторона уже
    // знает про новый интерьер, другая ещё нет.
    const уКлиента = записиКлиента().length;
    const уСервера = Object.keys(INTERIORS).length;
    must(уКлиента === уСервера,
      `клиент знает ${уКлиента} интерьеров, сервер ${уСервера} - списки разной длины`);
  });

  it('комнаты не налезают друг на друга ни на одной стороне', () => {
    // Соседние слоты разнесены на ROOM_DX = 44 при половине комнаты 16, то
    // есть между центрами остаётся 12 единиц зазора. Меньше - комнаты
    // перекрываются, и игрок, войдя в одну, видит пол другой.
    const ROOM_DX = Number(/const ROOM_DX = (\d+)/.exec(клиент)?.[1]);
    const roomHalf = Object.values(INTERIORS)[0]?.roomHalf ?? 16;
    const минЗазор = ROOM_DX - roomHalf * 2;
    must(минЗазор >= 8,
      `между центрами соседних комнат остаётся ${минЗазор} единиц при шаге ${ROOM_DX} ` +
      `и половине комнаты ${roomHalf} - комнаты стоят слишком тесно`);
    const слоты = слотыКлиента().map((к) => к.roomCx).sort((a, b) => a - b);
    for (let i = 1; i < слоты.length; i++) {
      must(слоты[i] - слоты[i - 1] >= roomHalf * 2,
        `слоты ${слоты[i - 1]} и ${слоты[i]} перекрываются: между ними ${слоты[i] - слоты[i - 1]}, ` +
        `а комната шириной ${roomHalf * 2}`);
    }
  });

  it('дверь каждой комнаты стоит в том городе, которому она принадлежит', () => {
    // Обратная сторона. Дверь столичной записи считается от CITY.x, и если
    // потеряется CITY, запись уедет в начало координат - тихо и с минусом на
    // 34 единицы, то есть в Аравию, через полкарты.
    //
    // ДОПУСК 0.5, А НЕ ТОЧНОЕ РАВЕНСТВО, И ЭТО НЕ ПОПУСК ПОПРОСТО. Номера на
    // сервере переписаны руками из клиентского расчёта, и при переносе они
    // округляются. Замер показал реальный дрейф: стойла - клиент считает
    // (15.4, -43.5), сервер записал (15.4, -43.6). Разница 0.1 - это
    // округление, а не расхождение. Допуск в 0.5 ловит округление и не
    // пропускает настоящий разъезд: если CITY потеряется, запись уедет на
    // десятки единиц, и проверка это увидит.
    const ДОПУСК = 0.5;
    const террейн = читать('client/src/app/game3d/terrain.ts');
    const город = /export const CITY = \{ x: (-?\d+), z: (-?\d+)/.exec(террейн);
    must(город !== null, 'не нашёл координаты столицы CITY в terrain.ts - расчёт дверей изменился');
    const [ГОРОД_X, ГОРОД_Z] = [Number(город[1]), Number(город[2])];

    const уСтолицы = записиКлиента().filter((з) => з.lx !== undefined && з.lz !== undefined);
    must(уСтолицы.length > 0, 'ни одной двери не считается от столицы - CITY перестал участвовать в расчёте');

    const разъезды: string[] = [];
    let худший = 0;
    for (const з of уСтолицы) {
      const def = INTERIORS[з.id];
      must(def !== undefined, `запись клиента ${з.id} отсутствует на сервере`);
      const ожидаемыйX = ГОРОД_X + з.lx!;
      const ожидаемыйZ = ГОРОД_Z + з.lz!;
      const снос = Math.max(Math.abs(def.doorX - ожидаемыйX), Math.abs(def.doorZ - ожидаемыйZ));
      if (снос > худший) худший = снос;
      if (снос > ДОПУСК) {
        разъезды.push(`${з.id}: клиент (${ожидаемыйX.toFixed(1)}, ${ожидаемыйZ.toFixed(1)}), ` +
          `сервер (${def.doorX}, ${def.doorZ}) - расхождение ${снос.toFixed(1)}`);
      }
    }
    must(разъезды.length === 0,
      `двери разошлись со столицей сильнее, чем на округление ${ДОПУСК}:\n  ${разъезды.join('\n  ')}\n` +
      `(худшее расхождение ${худший.toFixed(1)})`);
  });
});