// Заход в подземелье переживал перезапуск сервера как фарм.
//
// ЧТО БЫЛО. Состав захода держится в памяти процесса, и при старте
// restoreActiveSessions собирает сессию заново из базы. Смерти он читал из
// таблицы dungeon_deaths, а сундуки и убитых боссов — нет: стояло
// `openedChests: new Set()` и `killedBossIds: new Set()`, а
// spawnSessionMonsters/spawnSessionChests создавали всех монстров и все
// сундуки заново.
//
// ЧТО ИЗ ЭТОГО ВЫХОДИЛО. Игрок вскрывал сундуки, убивал босса — и тут
// сервер перезапускался. А он перезапускается на каждой выкатке, то есть
// раз в несколько коммитов. Заход возвращался целиком: сундуки пустые, босс
// жив. Золото и опыт платились повторно, сколько угодно раз. Награда за
// заход не задваивалась (loot_claimed_at, миграция 071) — а сундуки и добыча
// с босса задваивались.
//
// ЛОВУШКА, КОТОРУЮ ЕДВА НЕ ПОВТОРИЛ. killedBossIds хранит instanceId —
// идентификатор ЭКЗЕМПЛЯРА, который создаётся заново при каждом спавне.
// Сохранив его в базу, мы получили бы заход, который после перезапуска
// никогда не завершится: условие «все обязательные боссы убиты» сверяло бы
// новые instanceId со старым списком. Поэтому в базу пишется идентификатор
// ОПРЕДЕЛЕНИЯ (monsterId), а убитый босс при восстановлении не спавнится вовсе.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = код('server/src/systems/DungeonService.ts');
const МИГРАЦИИ = 'database/migrations';
const миграция = код(`${МИГРАЦИИ}/074_dungeon_run_state.sql`);

describe('Перезапуск сервера: заход не становится фармом', () => {
  it('состояние захода есть в базе, а не только в памяти', () => {
    for (const столбец of ['opened_chests', 'killed_boss_ids']) {
      must(
        new RegExp(`ADD COLUMN IF NOT EXISTS ${столбец}\\b`).test(миграция),
        `в миграции нет столбца ${столбец}`,
      );
    }
    // JSONB-массив, а не отдельная таблица: состояние читается целиком при
    // восстановлении захода и по нему не ищут.
    must(/JSONB NOT NULL DEFAULT '\[\]'::jsonb/.test(миграция), 'столбцы не JSONB-массивы');
  });

  it('столбцы читаются при восстановлении', () => {
    must(
      /opened_chests:\s*string\[\]\s*\|\s*null; killed_boss_ids:\s*string\[\]\s*\|\s*null/.test(сервис),
      'восстановление не запрашивает состояние захода',
    );
    must(/COALESCE\(s\.opened_chests/.test(сервис), 'opened_chests читается как есть, без COALESCE');
  });

  it('восстановленный заход берёт сундуки и боссов из базы', () => {
    must(
      /openedChests: new Set\(row\.opened_chests \?\? \[\]\)/.test(сервис),
      'открытые сундуки не читаются из базы — они все снова станут закрытыми',
    );
    must(
      /killedBossDefs: new Set\(row\.killed_boss_ids \?\? \[\]\)/.test(сервис),
      'убитые боссы не читаются из базы — они воскреснут',
    );
  });

  it('сундук отмечается в базе атомарно, а не в памяти', () => {
    const начало = сервис.indexOf('async openChest(');
    must(начало > 0, 'openChest не найден');
    const тело = сервис.slice(начало, начало + 3000);
    must(
      /UPDATE dungeon_sessions[\s\S]{0,120}SET opened_chests/.test(тело),
      'сундук не отмечается в базе: после перезапуска он откроется заново',
    );
    // Условие «ещё не вскрыт» обязано быть в самом UPDATE. SELECT и последующая
    // запись проигрывают гонку двумя вкладками — это ровно тот случай, ради
    // которого claimLoot сделан одним UPDATE.
    must(
      /AND NOT \(opened_chests \? \$2\)[\s\S]{0,80}RETURNING/.test(тело),
      'отметка сундука не защищена условием в самом UPDATE: две вкладки заплатят дважды',
    );
    must(
      /return \{ ok: false, code: 'already_opened'/.test(тело),
      'проигравший гонку не получает отказ: он получает выплату за чужой сундук',
    );
  });

  it('босс пишется по определению, а не по экземпляру', () => {
    must(
      /private async recordBossKilled\(/.test(сервис),
      'убийство босса не пишется в базу',
    );
    must(
      /getContext\(instanceId\)\?\.monsterId/.test(сервис),
      'босс пишется по instanceId: он меняется при каждом спавне и не переживёт перезапуск',
    );
    must(
      /SET killed_boss_ids = killed_boss_ids \|\| to_jsonb/.test(сервис),
      'убитый босс не дописывается в состояние захода',
    );
  });

  it('убитый до перезапуска босс не спавнится заново', () => {
    const начало = сервис.indexOf('private spawnSessionMonsters(');
    must(начало > 0, 'spawnSessionMonsters не найдена');
    const тело = сервис.slice(начало, начало + 2000);
    must(
      /session\.killedBossDefs\.has\(room\.bossId\)[\s\S]{0,80}continue;/.test(тело),
      'босс, убитый до перезапуска, воскресает при восстановлении',
    );
  });

  it('поле, переживающее перезапуск, не перепутано с полем экземпляров', () => {
    // Восстановление обязано очищать killedBossIds: новые instanceId не
    // совпадают со старыми, и оставленные старые сделали бы заход
    // незавершаемым навсегда.
    const начало = сервис.indexOf('async restoreActiveSessions(');
    const тело = сервис.slice(начало, начало + 3000);
    must(
      /killedBossIds: new Set\(\)/.test(тело),
      'killedBossIds восстанавливается из базы — он хранит instanceId, они не переживают перезапуск',
    );
  });

  it('все выходы захода пишутся в базу', () => {
    // Обратная сторона: если забыть любой из них, заход снова станет фармом.
    must(/opened_chests/.test(сервис), 'состояние сундуков нигде не пишется');
    must(/killed_boss_ids/.test(сервис), 'состояние боссов нигде не пишется');
  });
});