// Откат повторного квеста: объявленное в данных ожидание работает.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ЭТОЙ ПРОВЕРКИ. Поле repeatCooldown объявлено у всех
// двадцати одного повторяемого квеста — значения от 24 до 336 часов, в среднем
// 55 — и не читалось НИГДЕ. Единственная проверка в accept() была
// `!def.repeatable`: повторяемый квест можно было взять снова сразу после
// выполнения, сколько угодно раз. То есть квест с откатом в две недели
// переделывался немедленно и снова давал награду.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ:
//   1. каждый повторяемый квест объявляет откат, и откат разумный;
//   2. отсчёт идёт в часах, как в данных, и переводится в миллисекунды;
//   3. граница включена со стороны игрока: ровно в момент истечения можно взять,
//     на миллисекунду раньше - ещё нет;
//   4. пустое время выполнения или нулевой откат не блокируют квест навсегда;
//   5. сервер проверяет откат и отказывает отдельным кодом, у которого есть
//      перевод во всех трёх словарях.
//
// ПОЧЕМУ ПРОВЕРКА СЧИТАЕТ, А НЕ ИЩЕТ СТРОКУ. Поиск repeatCooldown доказал бы,
// что слово есть. Здесь считаются миллисекунды на настоящих значениях из данных.
import {
  HOUR_MS, repeatBlocked, repeatReadyAt,
} from '../services/QuestService';
import { QUESTS_DATABASE } from '../data/quests';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const повторяемые = Object.values(QUESTS_DATABASE).filter((квест) => квест.repeatable);
const всеКвесты = Object.values(QUESTS_DATABASE);

describe('Откат повторного квеста: данные', () => {
  it('повторяемые квесты в базе есть', () => {
    must(
      повторяемые.length >= 10,
      `повторяемых квестов ${повторяемые.length}: проверка считает не тот случай`
    );
    must(
      всеКвесты.length > повторяемые.length,
      'все квесты повторяемые: проверка не отличает повторяемые от обычных'
    );
  });

  it('у каждого повторяемого квеста объявлен откат', () => {
    const безОтката = повторяемые.filter((к) => !к.repeatCooldown);
    must(
      безОтката.length === 0,
      `повторяемых квестов без отката: ${безОтката.length} ` +
        `(${безОтката.slice(0, 5).map((к) => к.id).join(', ')}) - их можно переделывать без паузы`
    );
  });

  it('откаты из данных — целые часы и не меньше суток', () => {
    for (const к of повторяемые) {
      const часы = к.repeatCooldown!;
      must(
        Number.isInteger(часы),
        `${к.id}: откат ${часы} — не целое число часов, а данные объявлены числами`
      );
      must(
        часы >= 24,
        `${к.id}: откат ${часы} ч меньше суток. Меньше суток - это не откат, а формальность: ` +
          'квест-минутку можно переделать до истощения, и никакого отката не выходит'
      );
      must(
        часы <= 24 * 30,
        `${к.id}: откат ${часы} ч больше месяца: квест недоступен почти навсегда`
      );
    }
  });
});

describe('Откат повторного квеста: считается правильно', () => {
  const сейчас = 1_800_000_000_000;
  const выполнен = сейчас - 3_600_000; // час назад

  it('час в данных переводится в миллисекунды', () => {
    must(HOUR_MS === 3_600_000, `в часе ${HOUR_MS} мс вместо 3 600 000`);
    must(
      repeatReadyAt(выполнен, 24) === выполнен + 24 * HOUR_MS,
      'сутки откату считаются не как 24 часа'
    );
    must(
      repeatReadyAt(выполнен, 336) === выполнен + 336 * HOUR_MS,
      '336 часов (две недели) считаются неверно'
    );
  });

  it('минуту назад повтор запрещён, а через сутки разрешён', () => {
    must(
      repeatBlocked(выполнен, 24, сейчас),
      'квест с откатом в сутки можно взять через минуту после выполнения'
    );
    const завтра = repeatReadyAt(выполнен, 24);
    must(
      !repeatBlocked(выполнен, 24, завтра),
      'ровно в момент истечения отката квест всё ещё запрещён: граница не включена'
    );
    must(
      repeatBlocked(выполнен, 24, завтра - 1),
      'за миллисекунду до истечения отката повтор разрешён: граница сдвинута'
    );
  });

  it('пустое время выполнения не блокирует навсегда', () => {
    // Неровные данные не должны превращать квест в вечную стену: игрок иначе
    // не поймёт, почему задание больше не выдаётся.
    for (const пусто of [0, -1, Number.NaN, Number.POSITIVE_INFINITY]) {
      must(
        !repeatBlocked(пусто, 24, сейчас),
        `при пустом времени выполнения ${пусто} повтор заблокирован: квест недоступен навсегда`
      );
    }
  });

  it('квест без отката повторяется сразу', () => {
    for (const без of [undefined, 0, -5]) {
      must(
        !repeatBlocked(выполнен, без, сейчас),
        `откат ${без} блокирует повтор, хотя такого отката в данных нет`
      );
    }
  });

  it('короткий откат действительно короче длинного', () => {
    // Проверка на данных: чем больше откат, тем позже повтор. На настоящем
    // значении из базы, а не на выдуманном.
    const квестыСОткатом = повторяемые
      .filter((к) => к.repeatCooldown)
      .sort((а, б) => а.repeatCooldown! - б.repeatCooldown!);
    must(
      квестыСОткатом.length >= 3,
      `квестов с откатом ${квестыСОткатом.length}: проверка сравнивает нечего`
    );
    const первый = квестыСОткатом[0];
    const последний = квестыСОткатом[квестыСОткатом.length - 1];
    must(
      repeatReadyAt(выполнен, первый.repeatCooldown!) < repeatReadyAt(выполнен, последний.repeatCooldown!),
      `откат ${первый.id} (${первый.repeatCooldown} ч) заканчивается не раньше ` +
        `${последний.id} (${последний.repeatCooldown} ч): короткий откат ждёт дольше длинного`
    );
  });
});

describe('Откат повторного квеста: сервер его держит', () => {
  const сервис = читать('server/src/services/QuestService.ts');

  it('отказ имеет отдельный код', () => {
    must(
      /'quest_repeat_cooldown'/.test(сервис),
      'у отказа нет отдельного кода: игрок увидит «квест уже выполнен», хотя выполнен он был вчера'
    );
  });

  it('проверка стоит в пути приёма квеста', () => {
    must(
      /repeatBlocked\(выполнен, def\.repeatCooldown\)/.test(сервис),
      'откат не проверяется при приёме квеста: поле снова мёртвое'
    );
    must(
      /if \(repeatBlocked[\s\S]{0,120}quest_repeat_cooldown/.test(сервис),
      'откат проверяется, но отказ возвращается не тем кодом'
    );
  });

  it('проверка только для повторяемых и только после выполнения', () => {
    // Обычный выполненный квест и раньше должен быть недоступен - это другой
    // отказ. Проверка отката не должна менять его смысл.
    must(
      /if \(!def\.repeatable\) return \{ ok: false, code: 'quest_already_completed' \};/.test(сервис),
      'обычный выполненный квест больше не отказывает отдельным кодом'
    );
    must(
      /if \(existing\?\.status === 'completed'\) \{/.test(сервис),
      'откат проверяется не только для выполненных квестов'
    );
  });

  it('время выполнения берётся из состояния квеста', () => {
    must(
      /existing\.completedAt/.test(сервис),
      'откат считается не от времени выполнения, а от чего-то другого'
    );
  });

  it('у кода отказа есть перевод во всех трёх словарях', () => {
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`));
      const текст = (словарь.errors || {})['quest_repeat_cooldown'];
      must(
        typeof текст === 'string' && текст.length > 0,
        `${язык}: нет перевода quest_repeat_cooldown - игрок прочитает путь ключа вместо текста`
      );
    }
  });
});
