// Экстерьер кавказского форпоста: крепость с воротами, решёткой, стенами.
//
// ЗАМЕР: дверь и выход ровно -2.4000, отклонение 0.0000; перепад голого
// комплекса 0.002 м; ось чиста на 60 м; подход к двери свободен. Сухо: 0 мокрых
// точек.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

function блокФорпоста(): string {
  const начало = ТЕРРЕЙН.indexOf('  // ── Кавказский форпост');
  must(начало > 0, 'нет блока кавказского форпоста');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', начало);
  must(конец > начало, 'конец блока не найден');
  return ТЕРРЕЙН.slice(начало, конец);
}

describe('Кавказский форпост: площадка', () => {
  it('стоит на месте записи интерьера', () => {
    must(/id: 'caucasus_fort',[^}]*dx: -880, dz: 520/.test(ИНТЕРЬЕРЫ), 'запись изменилась');
    must(/export const CAUCASUS_FORT = \{ x: -880, z: 520,/.test(ТЕРРЕЙН), 'константа не там');
  });

  it('ровнялка стоит ПОСЛЕ ровнялки залива', () => {
    const код = ТЕРРЕЙН.slice(ТЕРРЕЙН.indexOf('export function terrainHeight'), ТЕРРЕЙН.indexOf('const TERRAIN_SEG'))
      .split('\n').filter((s) => !/^\s*(\/\/|\*|\/\*)/.test(s)).join('\n');
    must(код.indexOf('CAUCASUS_FORT.x') > код.indexOf('-820'), 'ровнялка не после залива');
  });

  it('уровень близок к медиане -2.40', () => {
    const m = /export const CAUCASUS_FORT = \{ x: -880, z: 520, radius: \d+, level: (-?[\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'уровень не объявлен');
    const уровень = Number(m![1]);
    must(уровень >= -2.8 && уровень <= -2.0, `уровень ${уровень} далёк от медианы`);
  });

  it('запас ровной части достаточен', () => {
    const m = /export const CAUCASUS_FORT = \{ x: -880, z: 520, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус не объявлен');
    const ровная = Number(m![1]) * 0.55;
    // Полудиагональ считается по ВСЕМУ комплексу: двор 12 м плюс ворота и
    // стены. Раньше считалась только двор, и ломка «радиус 44» проходила насквозь.
    must(ровная - Math.hypot(24 / 2 + 3, 12 + 6 + 3) >= 2, 'запас мал');
  });

  it('сухо', () => {
    must(!isWater(-880, 520), 'под форпостом вода');
  });
});

describe('Кавказский форпост: дверь и подход', () => {
  it('дверь кликабельная и ведёт в интерьер форпоста', () => {
    const блок = блокФорпоста();
    must(/doorBuilding: 'caucasus_fort'/.test(блок), 'нет doorBuilding');
    must(/doorAction: 'enter'/.test(блок), 'дверь не ведёт внутрь');
    must(/doorName: t\('buildings\.caucasus_fort'\)/.test(блок), 'не то название');
  });

  it('ворота с решёткой', () => {
    const блок = блокФорпоста();
    must(/ворота/.test(блок), 'нет ворот');
    must(/решётка/.test(блок), 'нет решётки');
    must(/прут/.test(блок), 'прутья решётки не построены');
  });

  it('в проёме двери заглушка', () => {
    must(/КАВКАЗ_ЗАГЛУШКА/.test(ТЕРРЕЙН), 'нет заглушки');
  });
});

describe('Кавказский форпост: двор', () => {
  it('стена с зубцами по бокам', () => {
    const блок = блокФорпоста();
    must(/стена/.test(блок), 'нет стены');
    must(/зубец/.test(блок), 'зубцы не построены');
  });

  it('сторожевые посты с факелами', () => {
    const блок = блокФорпоста();
    must(/факел/.test(блок), 'нет факелов');
  });
});