// Базовое здоровье заведено и стоит на своём месте.
//
// ЧТО ЗАЧЕМ. max_hp накапливается прибавлением, поэтому бонус гильдии
// (+100 HP за уровень навыка) нельзя просто прибавить: при выходе из
// гильдии его нечем снять. Нужна база под ним - base_max_hp.
//
// ЭТО ШАГ ПЕРВЫЙ ИЗ ДВУХ. Пока обе колонки растут в ногу и равны друг
// другу, поведение игры НЕ меняется. Бонус подключается следующим шагом.
//
// ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Значение для колонки должно стоять на позиции
// своего плейсхолдера. Я поставил base_max_hp десятой в списке колонок и
// значение добавил в КОНЕЦ массива - на позицию 20. Тогда $10 получил бы
// character.mana: число манны вместо здоровья.
//
// Это молчаливая порча данных. Ни ошибка компиляции, ни ошибка базы: у
// обоих полей INTEGER. Поймано чтением, а не прогоном - и поэтому проверка
// на это обязана быть здесь, а не только в голове.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const сервис = читать('server/src/services/CharacterService.ts');
const левелинг = читать('server/src/systems/LevelingSystem.ts');
const миграция = читать('database/migrations/061_base_max_hp.sql');

describe('Колонка заведена', () => {
  it('base_max_hp добавлена и заполнена', () => {
    expect({
      добавление: /ADD COLUMN IF NOT EXISTS base_max_hp INTEGER/.test(миграция),
      // Заполнение обязательно: NULL означал бы «неизвестно», и вычисление
      // max_hp из него дало бы NULL вместо числа.
      заполнение: /SET base_max_hp = max_hp\s*\n\s*WHERE base_max_hp IS NULL/.test(миграция),
      not_null: /ALTER COLUMN base_max_hp SET NOT NULL/.test(миграция),
    }).toEqual({ добавление: true, заполнение: true, not_null: true });
  });
});

describe('Значение стоит на позиции своего плейсхолдера', () => {
  // Разбираем INSERT механически: количество колонок, старший плейсхолдер и
  // число значений обязаны совпадать. Считать через запятую нельзя -
  // внутри JSON.stringify(character.position) запятые тоже есть, и наивный
  // подсчёт давал 24 против 20 и пугал без причины.
  const insert = /INSERT INTO characters\s*\(([\s\S]*?)\)\s*VALUES \(([\s\S]*?)\)`/.exec(сервис);
  const колонки = (insert?.[1] ?? '').split(',').map(c => c.trim()).filter(Boolean);
  const плейсхолдеры = [...(insert?.[2] ?? '').matchAll(/\$(\d+)/g)].map(m => Number(m[1]));
  // Комментарии ВЫРЕЗАЮТСЯ: мой комментарий содержит запятую, и она
  // считалась разделителем - тот же класс, что и нарезка комментария в аудите
  // схемы.
  const массив = (/character\.id, character\.userId[\s\S]*?\n      \]/.exec(сервис)?.[0] ?? '')
    .replace(/\/\/[^\n]*/g, ' ');
  // Значения делятся по запятой на верхнем уровне: скобки не учитываются.
  // Висячая запятая перед ] - синтаксис массива, а не разделитель.
  // Без срезания хвоста 20 значений давали 21.
  const безХвоста = массив.replace(/\s*\]\s*$/, '').replace(/,\s*$/, '');
  let глубина = 0, штук = 1;
  for (const символ of безХвоста) {
    if (символ === '(' || символ === '[') глубина++;
    else if (символ === ')' || символ === ']') глубина--;
    else if (символ === ',' && глубина === 0) штук++;
  }

  it('колонок, плейсхолдеров и значений поровну', () => {
    expect({
      колонок: колонки.length,
      плейсхолдеров: плейсхолдеры.length,
      старший: Math.max(...плейсхолдеры, 0),
      значений: штук,
    }).toEqual({ колонок: 20, плейсхолдеров: 20, старший: 20, значений: 20 });
  });

  it('base_max_hp стоит ровно под своим плейсхолдером', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Позиция колонки и позиция значения должны
    // совпадать, иначе одно поле пишется в другое.
    const позицияКолонки = колонки.indexOf('base_max_hp') + 1;
    // Значение сразу за character.maxHp, а character.maxHp идёт под $9.
    const позицияMaxHp = массив.indexOf('character.maxHp');
    const значениеПосле = массив.slice(позицияMaxHp + 'character.maxHp'.length);
    // Комментария сколько угодно - важно лишь, что значение идёт сразу
    // за maxHp, то есть на позицию 10.
    const базаСразуПосле = /^\s*,\s*(?:\/\/[^\n]*\n\s*)*character\.maxHp,/.test(значениеПосле);
    expect({
      позиция_колонки: позицияКолонки,
      значение_сразу_за_max_hp: базаСразуПосле,
    }).toEqual({ позиция_колонки: 10, значение_сразу_за_max_hp: true });
  });

  it('base_max_hp не в самом конце списка значений', () => {
    // Именно так это выглядело: колонка десятая, значение двадцатое.
    const хвост = массив.slice(-260);
    expect({ в_хвосте: /character\.maxHp,\s*\n\s*\]\s*;?\s*$/.test(хвост) })
      .toEqual({ в_хвосте: false });
  });
});

describe('Поведение пока не меняется', () => {
  it('обе колонки растут одним и тем же приростом', () => {
    // Шаг безопасный: base_max_hp введена, но max_hp не перестаёт расти
    // сам. Если бы max_hp уже стал вычисляемым, поведение изменилось бы
    // здесь, а не в следующем шаге.
    expect({
      max_hp_растёт: /max_hp = max_hp \+ \$4/.test(левелинг),
      база_растёт: /base_max_hp = base_max_hp \+ \$4/.test(левелинг),
      // Никакой формулы с бонусом гильдии - она в следующем шаге.
      бонуса_пока_нет: !/guildBonuses/.test(левелинг),
    }).toEqual({ max_hp_растёт: true, база_растёт: true, бонуса_пока_нет: true });
  });

  it('бонус гильдии подключён - навык можно купить', () => {
    // ПРОВАЛ ПРЕДЫДУЩЕЙ ВЕРСИИ ЭТОЙ ПРОВЕРКИ. Она искала
    // /WIRED_EFFECTS[^;]*;/ и брала ПЕРВОЕ совпадение в файле. А первое -
    // это не объявление, а упоминание в комментарии на строке 13. Дальше
    // [^;]* шёл до ближайшей точки с запятой - это был импорт на строке 15.
    // В найденном кусочке max_hp_bonus не было НИКОГДА, сколько бы его
    // ни добавляли в список, и проверка оставалась зелёной.
    //
    // Теперь ищем объявление, а не любое слово, и проверяем обратное:
    // навык подключён, значит его можно купить и бонус начисляется.
    const бонусы = читать('server/src/systems/GuildBonuses.ts');
    const объявление = /export const WIRED_EFFECTS[^\n]*/.exec(бонусы)?.[0] ?? '';
    must(объявление, 'объявления WIRED_EFFECTS в файле нет');

    // Второе условие. Моя первая версия искала hpMultiplierFor в
    // GuildBonuses и подставляла при промахе строку 'isSkillWired' -
    // а она сама содержит искомое слово, и проверка падала с причиной,
    // противоположной настоящей. Теперь сверяется родное свойство
    // справочника: эффект навыка стоит в списке подключённых.
    const эффектНавыка = /id: 'guild_hp_boost',[\s\S]{0,300}?effect: '(\w+)'/
      .exec(читать('server/src/data/guilds.ts'))?.[1] ?? '';
    must(эффектНавыка, 'у guild_hp_boost нет своего эффекта в справочнике');

    expect({
      hp_подключён: /max_hp_bonus/.test(объявление),
      // Одного попадания мало: эффект из справочника и из списка должны
      // совпадать, иначе навык купить нельзя, а проверка считала бы наоборот.
      эффекты_совпадают: объявление.includes(`'${эффектНавыка}'`),
    }).toEqual({ hp_подключён: true, эффекты_совпадают: true });
  });
});

describe('Запись в карте была неверна', () => {
  it('снаряжение в max_hp не входит - пересчитывать нечего', () => {
    // Запись обещала «пересчёт max_hp при каждом изменении снаряжения».
    // Формула считается из BASE_STATS класса, снаряжение применяется к
    // защите отдельно. Обещание вводило в заблуждение.
    const карта = читать('ROADMAP.md');
    expect({
      ложь_убрана: !/пересчёт `?max_hp`? при каждом изменении снаряжения/.test(карта),
      // Обратные кавычки вокруг max_hp обязательны: в карте колонка
      // записана как код.
      правда_есть: /снаряжение в формулу `?max_hp`? не входит/.test(карта),
    }).toEqual({ ложь_убрана: true, правда_есть: true });
  });
});
