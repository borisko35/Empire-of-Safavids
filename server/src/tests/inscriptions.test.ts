/** Числа из объявления константы: export const STELE = { height: 1.9, ... }. */
function читатьКонстанту(имя: string): Record<string, number> {
  const начало = inscriptionsSrc.indexOf(`const ${имя} = {`);
  must(начало >= 0, `не нашли объявление ${имя} в inscriptions.ts`);
  const конец = inscriptionsSrc.indexOf('};', начало);
  const блок = inscriptionsSrc.slice(начало, конец);
  const out: Record<string, number> = {};
  for (const m of блок.matchAll(/(\w+):\s*(-?[\d.]+)/g)) out[m[1]] = Number(m[2]);
  return out;
}

/**
 * Габариты коробки фасада из строки вида
 *   const win1 = box(1.4, 1.2, 0.2, M.teal, -2.9, 2.6, 3.05);
 * Подпись box(w, h, d, mat, x, y, z) взята из самого interiors.ts.
 */
function читатьКоробку(имя: string): { w: number; h: number; d: number; x: number; y: number; z: number } | null {
  const m = new RegExp(`const ${имя} = box\\(([^)]*)\\)`).exec(interiorsSrc);
  if (!m) return null;
  const числа = m[1].split(',').map((s) => s.trim());
  // Первые три - размеры, четвёртый - материал, дальше координаты.
  const w = Number(числа[0]);
  const h = Number(числа[1]);
  const d = Number(числа[2]);
  const x = Number(числа[4]);
  const y = Number(числа[5]);
  const z = Number(числа[6]);
  if ([w, h, d, x, y, z].some((v) => !Number.isFinite(v))) return null;
  return { w, h, d, x, y, z };
}