// Персидские надписи на городских стенах: «рассказ через детали».
//
// ЗАЧЕМ ФАЙЛ. Пункт списка владельца — «надписи на персидском, письма, сломанные весы,
// следы копыт» — был помечен «не измерено», то есть не начат. Из перечисленного взяты
// надписи: остальное надо решать с владельцем, потому что письмо читает игрок.
//
// ЧТО ЗАЩИЩАЕТ. Три класса ошибок, и все три видны только в игре:
//
//   1. Текст без персидских букв. Опечатка в строке литерала даёт пустую плиту, а
//      пустая плита выглядит как готовая работа.
//   2. Надпись без источника. Текст появляется в мире, и никто не знает, откуда он.
//      Для игры про Исфахан это не мелочь: выдуманная строка выдаёт эпоху.
//   3. Стела не там. Фасад меняется, окно или дверь съезжают, и стела оказывается в
//      стене или закрывает дверь. Здесь фасад не выписывается числами, а РАЗБИРАЕТСЯ из
//      interiors.ts, иначе проверка повторяла бы саму себя и молчала бы после правки
//      фасада.
//
// ПОЧЕМУ ПРОВЕРКА ЧИТАЕТ ИСХОДНИК, А НЕ ИМПОРТИРУЕТ МОДУЛЬ. inscriptions.ts тянет
// three.js и работает через document.createElement, то есть в тестовой среде без окна
// не запустится. Числа геометрии берутся из исходника регулярными выражениями.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(__dirname, '..', '..', '..');
const INSCRIPTIONS_FILE = join(ROOT, 'client/src/app/game3d/inscriptions.ts');
const INTERIORS_FILE = join(ROOT, 'client/src/app/game3d/interiors.ts');

function readText(file: string): string {
  return readFileSync(file, 'utf-8');
}

function must(ok: unknown, why: string): void {
  if (!ok) throw new Error(why);
}

const inscriptionsSrc = readText(INSCRIPTIONS_FILE);
const interiorsSrc = readText(INTERIORS_FILE);

/** Персидские и арабские буквы: U+0600..U+06FF. */
const ПЕРСИДСКИЕ = /[\u0600-\u06FF]/;

type Inscription = {
  id: string;
  buildingId: string;
  lines: string[];
  source: string;
  translit: string[];
};

/**
 * Надписи читаются из исходника регулярным выражением, а не импортом: модуль тянет
 * three.js и document, которых в тесте нет.
 */
function читатьНадписи(): Inscription[] {
  const блок = inscriptionsSrc.slice(
    inscriptionsSrc.indexOf('export const INSCRIPTIONS'),
    inscriptionsSrc.indexOf('];', inscriptionsSrc.indexOf('export const INSCRIPTIONS')),
  );
  const записи = [...блок.matchAll(
    /\{\s*id:\s*'([a-z_]+)',\s*buildingId:\s*'([a-z_]+)',\s*lines:\s*\[([\s\S]*?)\],\s*translit:\s*\[([\s\S]*?)\],\s*source:\s*'([^']+)'/g,
  )];
  return записи.map((m) => ({
    id: m[1],
    buildingId: m[2],
    lines: [...m[3].matchAll(/'([^']*)'/g)].map((s) => s[1]),
    translit: [...m[4].matchAll(/'([^']*)'/g)].map((s) => s[1]),
    source: m[5],
  }));
}

const надписи = читатьНадписи();

describe('Надписи на персидском: данные', () => {
  // Габариты плиты нужны и здесь: сообщение об ошибке должно называть число.
  const С = читатьКонстанту('STELE');

  it('список не пуст и каждая запись читается', () => {
    must(
      надписи.length >= 4,
      `в файле ${надписи.length} надписей, а их разобрано столько же только если формат не менялся. ` +
        'Разбор регулярным выражением разошёлся с исходником: новую запись он не увидит',
    );
  });

  it('у каждой надписи есть источник: поэт и произведение', () => {
    for (const и of надписи) {
      // В источнике допускаются цифры: «Hafez, Divan, ghazal 1» - законное название,
// и запрещать его было бы ошибкой проверки, а не строгостью данных.
const ЛАТИНИЦА_С_ЦИФРАМИ = /^[A-Za-z][A-Za-z0-9 ,.'-]+$/;

      must(
        и.source.length > 3 && ЛАТИНИЦА_С_ЦИФРАМИ.test(и.source),
        `у надписи ${и.id} источник пуст или не латиницей: '${и.source}'. ` +
          'Текст без источника выдаёт эпоху, а игра про Исфахан Сефевидов',
      );
    }
  });

  it('в каждой строке есть персидские буквы', () => {
    for (const и of надписи) {
      for (const строка of и.lines) {
        must(
          ПЕРСИДСКИЕ.test(строка),
          `в надписи ${и.id} строка без единой персидской буквы: '${строка.slice(0, 40)}'. ` +
            'Так плита остаётся пустой, и это видно только в игре',
        );
      }
    }
  });

  it('строк столько же, сколько переводов, и переводы латиницей', () => {
    for (const и of надписи) {
      must(
        и.lines.length === и.translit.length,
        `у надписи ${и.id} строк ${и.lines.length}, а переводов ${и.translit.length}. ` +
          'При несовпадении на камне окажется не та строка, которую переводили',
      );
      must(
        и.lines.length >= 1 && и.lines.length <= 3,
        `у надписи ${и.id} строк ${и.lines.length}: на плите высотой ${С.faceHeight} м ` +
          'больше трёх бейтов не разобрать, они сольются в полосу',
      );
      for (const перевод of и.translit) {
        must(
          перевод.length > 0 && /^[\x20-\x7E]+$/.test(перевод),
          `перевод в надписи ${и.id} не латиницей: '${перевод.slice(0, 30)}'. ` +
            'Он рисуется вместо персидского, когда гарнитуры нет, и должен быть читаем',
        );
      }
    }
  });

  it('надписи не повторяются: две стены с одним текстом — ошибка копипасты', () => {
    const тексты = new Map<string, string>();
    for (const и of надписи) {
      const ключ = и.lines.join('|');
      must(
        !тексты.has(ключ),
        `надпись ${и.id} повторяет ${тексты.get(ключ)}: одна стихотворение на двух стенах ` +
          'выглядит как недосмотр',
      );
      тексты.set(ключ, и.id);
    }
  });
});

describe('Надписи стоят там, где их видно', () => {
  /** Габариты стелы из inscriptions.ts. */
  const С = читатьКонстанту('STELE');
  const стелаВерх = С.offsetY + С.height;
  const стелаЛево = С.offsetX - С.width / 2;
  const стелаПраво = С.offsetX + С.width / 2;
  const стелаЛицо = С.offsetZ + С.depth / 2;

  /** Габариты фасада: разбираются из interiors.ts, а не выписаны здесь. */
  const коробка = читатьКоробку('body');
  const дверь = читатьКоробку('door');
  const окно = читатьКоробку('win1');

  it('стены дома и стела существуют в коде: фасад разобран', () => {
    must(коробка !== null, 'не нашли box(...) для body: фасад переехал, проверка ослепла');
    must(дверь !== null, 'не нашли box(...) для door: дверь переехала, проверка ослепла');
    must(окно !== null, 'не нашли box(...) для win1: окно переехало, проверка ослепла');
  });

  it('стела стоит перед стеной, а не внутри неё', () => {
    const граньСтены = коробка!.z + коробка!.d / 2;
    must(
      стелаЛицо > граньСтены,
      `лицевая сторона стелы на z=${стелаЛицо}, а стена кончается на z=${граньСтены}. ` +
        'Стела ушла в кладку и надписи не видно',
    );
    must(
      стелаЛицо - граньСтены < 1,
      `стела вынесена на ${(стелаЛицо - граньСтены).toFixed(2)} м от стены: это уже не стела ` +
        'у фасада, а отдельная тумба во дворе',
    );
  });

  it('верх стелы ниже подоконника окна', () => {
    const подоконник = окно!.y - окно!.h / 2;
    must(
      стелаВерх <= подоконник,
      `верх стелы на отметке ${стелаВерх}, подоконник окна на ${подоконник}. ` +
        'Стела перекрыла окно, и это видно с улицы',
    );
  });

  it('стела не залезает на дверь', () => {
    const крайДвери = дверь!.x - дверь!.w / 2;
    must(
      стелаПраво <= крайДвери,
      `правый край стелы на x=${стелаПраво}, левый край двери на x=${крайДвери}. ` +
        'Стела стоит в проёме и перекрывает вход',
    );
  });

  it('стела помещается по ширине стены', () => {
    const половина = коробка!.w / 2;
    must(
      стелаЛево >= -половина && стелаПраво <= половина,
      `стела занимает x от ${стелаЛево} до ${стелаПраво}, а стена шириной ` +
        `${коробка!.w} (половина ${половина}): стела выступает за угол`,
    );
  });

  it('надпись на плите уже ствола и помещается по высоте', () => {
    must(
      С.faceWidth <= С.width,
      `полоса с надписью шириной ${С.faceWidth}, а ствол ${С.width}: текст уходит в бок ствола`,
    );
    must(
      С.faceHeight <= С.height,
      `полоса с надписью высотой ${С.faceHeight}, а ствол ${С.height}: надпись выше ствола`,
    );
  });
});

