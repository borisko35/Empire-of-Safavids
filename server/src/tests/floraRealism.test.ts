// Растительность перестаёт быть примитивами.
//
// ЧТО БЫЛО (22 октября 2026, §287). Дикие деревья в лесу и в поле были
// «палкой с шариком»: ствол — ровный цилиндр, крона — один конус (кипарис)
// или один шар (платан). Трава на земле — маленький конус (шишка), а не
// трава. Куст в степи — шар на палочке. Горная хвоя — шишка.
//
// ЧТО ТЕПЕРЬ. У дерева есть корневой наплыв, наклон (ровные вертикальные
// стволы читались как колонны) и крона из двух объёмов: слой у кипариса,
// гроздь у платана. У каждого дерева свой оттенок листвы. Трава — пучок из
// четырёх blades, куст — гроздь из двух шаров, хвоя — в два слоя.
//
// ЧТО ПРОВЕРЯЕТСЯ. В рассеве растительности есть корневой наплыв, наклон,
// двухобъёмная крона и свой оттенок у каждого дерева; трава — пучок из
// blades, а не конус; куст и хвоя — составные.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Растительность — не примитивы', () => {
  it('у дерева есть корневой наплыв и наклон', () => {
    // Корневой наплыв: без него ствол начинается из земли ровно, как палка.
    // Проверяются ЧИСЛА: наплыв должен быть настоящим (высотой больше
    // полуметра) и расширяться книзу (нижний радиус больше верхнего).
    const наплыв = /flareGeo = new THREE\.CylinderGeometry\(([\d.]+), ([\d.]+), ([\d.]+), \d+\)/.exec(ТЕРРЕЙН);
    должен(наплыв, 'у дерева нет корневого наплыва');
    должен(Number(наплыв![3]) > 0.3, `корневой наплыв высотой ${наплыв![3]} м — его нет`);
    должен(
      Number(наплыв![2]) > Number(наплыв![1]),
      `корневой наплыв не расширяется книзу: ${наплыв![1]} → ${наплыв![2]}`,
    );
    // Наклон: деревья не растут отвесно.
    должен(
      /const наклон = \(rng\(\) - 0\.5\) \* ([\d.]+);/.test(ТЕРРЕЙН),
      'деревья стоят строго вертикально: читаются как колонны',
    );
    // Наклон достаётся до матрицы.
    должен(/tilt = 0\) =>/.test(ТЕРРЕЙН) && /new THREE\.Euler\(tilt, rotY/.test(ТЕРРЕЙН),
      'наклон не попадает в матрицу дерева');
    // И крона следует за наклоном, иначе ствол с кроной разъезжаются.
    должен(
      /const кронаY = s\.h \+ высота \+ над \* Math\.cos\(наклон\);/.test(ТЕРРЕЙН),
      'крона не следует за наклоном ствола',
    );
  });

  it('крона собрана из двух объёмов', () => {
    // Слой у кипариса: конус настоящего размера.
    const слой = /crownLowGeo = new THREE\.ConeGeometry\(([\d.]+), ([\d.]+), \d+\)/.exec(ТЕРРЕЙН);
    должен(слой, 'у кипариса один конус в кроне');
    должен(Number(слой![1]) > 0.5, `слой кроны радиусом ${слой![1]} — его нет`);
    должен(Number(слой![2]) > 1, `слой кроны высотой ${слой![2]} — его нет`);
    // Гроздь у платана: второй шар настоящего размера.
    const шар = /crown2bGeo = new THREE\.SphereGeometry\(([\d.]+), \d+, \d+\)/.exec(ТЕРРЕЙН);
    должен(шар, 'у платана один шар в кроне');
    должен(Number(шар![1]) > 0.5, `второй шар кроны радиусом ${шар![1]} — его нет`);
    // И оба объёма ставятся в сцену.
    должен(
      /scene\.add\(trunks, flares, crowns, crownsLow, crowns2, crowns2b,/.test(ТЕРРЕЙН),
      'новые части кроны не добавлены в сцену',
    );
  });

  it('у каждого дерева свой оттенок листвы', () => {
    должен(
      /color\.setHSL\(0\.2\d \+ rng\(\) \* [\d.]+, [\d.]+ \+ rng\(\) \* [\d.]+, [\d.]+ \+ rng\(\) \* [\d.]+\);/.test(ТЕРРЕЙН),
      'у всех деревьев один оттенок листвы',
    );
    должен(/crowns\.setColorAt\(idx, color\);/.test(ТЕРРЕЙН), 'оттенок не ставится кроне');
    должен(
      /if \(crowns\.instanceColor\) crowns\.instanceColor\.needsUpdate = true;/.test(ТЕРРЕЙН),
      'цвета инстансов не обновляются',
    );
  });

  it('трава — пучок из blades, а не конус', () => {
    // Пучок: четыре треугольных blade, двусторонние.
    должен(
      /for \(let b = 0; b < 4; b\+\+\) \{/.test(ТЕРРЕЙН),
      'трава не пучок из blades',
    );
    // Геометрия пучка — собственный BufferGeometry, а не готовый конус.
    должен(
      /const tuftGeo = new THREE\.BufferGeometry\(\);/.test(ТЕРРЕЙН),
      'трава — готовый конус, а не пучок blades',
    );
    // Обратная сторона: иначе клин гас с одной стороны.
    должен(
      /индексы\.push\(base \+ 2, base \+ 1, base\);/.test(ТЕРРЕЙН),
      'blade односторонний: с другой стороны его не видно',
    );
    // И трава ставится на землю, а не парит над ней.
    должен(/put\(tuftsMesh, idx, s\.x, s\.h, s\.z, k/.test(ТЕРРЕЙН), 'трава стоит не на земле');
  });

  it('куст и хвоя составные', () => {
    // Куст: второй шар настоящего размера.
    const куст = /brush2Geo = new THREE\.SphereGeometry\(([\d.]+), \d+, \d+\)/.exec(ТЕРРЕЙН);
    должен(куст, 'куст — один шар');
    должен(Number(куст![1]) > 0.2, `второй шар куста радиусом ${куст![1]} — его нет`);
    // Хвоя: нижний слой настоящего размера.
    const хвоя = /pineLowGeo = new THREE\.ConeGeometry\(([\d.]+), ([\d.]+), \d+\)/.exec(ТЕРРЕЙН);
    должен(хвоя, 'хвоя — один конус');
    должен(Number(хвоя![1]) > 0.3, `нижний слой хвои радиусом ${хвоя![1]} — его нет`);
    // И всё это попало в сцену.
    должен(
      /brushTrunks, brushesMesh, brushesMesh2, pinesMesh, pinesLow, pineTrunks\);/.test(ТЕРРЕЙН),
      'новые кусты и хвоя не добавлены в сцену',
    );
  });
});
