// Осады территорий гильдий: расписание, окно осады, урон и подключение.
//
// ЧТО БЫЛО. Территории объявлены в data/guilds.ts с расписанием
// «Saturday 20:00 UTC», таблица guild_territories создана миграцией 002 и
// засеяна этими id. Поиск territory_id по всему проекту давал только сами
// миграции: читать таблицу не читал никто. Уведомление siege_starting было
// объявлено в NotificationService и не отправлялось ни разу. То есть осады,
// которые дорожная карта обещала игрокам, не было ни в данных, ни в коде.
//
// ГЛАВНОЕ, ЧТО ЗДЕСЬ ЛОВИТСЯ. Расписание лежит СТРОКОЙ в файле данных.
// «Разбор по частям» без проверок означал бы, что опечатка в данных тихо
// выключает осаду навсегда, и выглядит это как «осад нет», а не как ошибка
// в одной строке. Поэтому разбор обязан отказывать, а не угадывать.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  разобратьРасписание,
  началоОсады,
  идётЛиОсада,
  пораНапомнить,
  уронЗаУбийство,
  ДЛИТЕЛЬНОСТЬ_ОСАДЫ_МС,
  НАПОМИНАНИЕ_ЗА_МС,
  ЦЕЛЬ_УБИЙСТВ,
} from '../systems/SiegeSystem';
import { TERRITORIES } from '../data/guilds';
import { GAME_SERVERS } from '../../../shared/constants';

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

/** Дата в UTC заданной строкой: «2026-10-03T20:00:00Z» → Date. */
function момент(iso: string): Date {
  return new Date(iso);
}

/**
 * Момент UTC числом миллисекунд.
 *
 * Через Date.UTC, а не сравнением строк toISOString: тот всегда печатает
 * миллисекунды («20:00:00.000Z»), и ожидание без них падало бы на ровном
 * месте - я на этом потерял один прогон.
 */
function utc(год: number, месяц: number, день: number, час: number, минута = 0): number {
  return Date.UTC(год, месяц, день, час, минута, 0, 0);
}

describe('Осады: разбор расписания', () => {
  it('разбирает расписание из данных и отказывает на битом', () => {
    // Четыре строки, которые реально лежат в data/guilds.ts.
    must(разобратьРасписание('Saturday 20:00 UTC')?.деньНедели === 6, 'Saturday не разобран');
    must(разобратьРасписание('Saturday 20:00 UTC')?.час === 20, 'час не разобран');
    must(разобратьРасписание('Sunday 20:00 UTC')?.деньНедели === 0, 'Sunday не разобран');
    must(разобратьРасписание('Friday 20:00 UTC')?.деньНедели === 5, 'Friday не разобран');
    must(разобратьРасписание('Saturday 18:00 UTC')?.час === 18, '18:00 не разобран');
    must(разобратьРасписание('Saturday 18:00 UTC')?.минута === 0, 'минуты не разобрано');

    // Отказ, а не догадка. Без него битая строка тихо выключила бы осаду.
    must(разобратьРасписание('Someday 20:00 UTC') === null, 'выдуманный день недели принят');
    must(разобратьРасписание('Saturday 25:00 UTC') === null, 'час 25 принят');
    must(разобратьРасписание('Saturday 20:60 UTC') === null, 'минута 60 принята');
    must(разобратьРасписание('Saturday UTC') === null, 'расписание без времени принято');
    must(разобратьРасписание('Saturday') === null, 'расписание без ничего принято');
    must(разобратьРасписание('') === null, 'пустая строка принята');
    must(разобратьРасписание(null) === null, 'null принят');
    must(разобратьРасписание(undefined) === null, 'undefined принят');
    must(разобратьРасписание('20:00 Saturday') === null, 'переставленные части приняты как день');
  });

  it('у ВСЕХ территорий расписание разбирается', () => {
    // Данные правятся руками. Опечатка в одной строке выключила бы осаду
    // этой территории навсегда, и нигде бы не появилось ошибки: не наступает
    // же не «неправильная» осада, а её нет.
    const битые = TERRITORIES
      .filter((t) => разобратьРасписание(t.siegeSchedule) === null)
      .map((t) => `${t.id}: «${t.siegeSchedule}»`);
    must(битые.length === 0, `расписание не разбирается у: ${битые.join(', ')}`);

    // И территория должна быть не пустой, иначе осада идёт «о регионе, которого нет».
    const безРегиона = TERRITORIES.filter((t) => typeof t.region !== 'string' || t.region.length === 0);
    must(безРегиона.length === 0, `территория без региона: ${безРегиона.map((t) => t.id).join(', ')}`);

    // И id обязаны совпадать с тем, чем засеяна таблица: иначе осада начнётся
    // для территории, которой в базе нет, и UPDATE не найдёт ни строки.
    const миграция = читать('database/migrations/002_ingame_structures.sql');
    for (const территория of TERRITORIES) {
      must(миграция.includes(`'${территория.id}'`), `id ${территория.id} не засеян в guild_territories`);
    }
  });
});

describe('Осады: окно осады', () => {
  it('начало осады строго позже и всегда в заданный день и час UTC', () => {
    const суббота = разобратьРасписание('Saturday 20:00 UTC');
    must(суббота !== null, 'расписание не разобралось для проверки');
    const расписание = суббота as NonNullable<typeof суббота>;

    // 2026-10-03 - суббота. За час до начала (19:00).
    const опорная = момент('2026-10-03T19:00:00Z');
    const начало = началоОсады(расписание, опорная);
    must(начало.getTime() === utc(2026, 9, 3, 20), `начало = ${начало.toISOString()}`);
    must(начало.getTime() > опорная.getTime(), 'начало не строго позже опорной точки');

    // Ровно в момент начала осада ещё не наступила: включительно было бы
    // «уже прошло», и осада не открылась бы в ту секунду, на которую назначена.
    const следующее = началоОсады(расписание, момент('2026-10-03T20:00:00Z'));
    must(следующее.getTime() === utc(2026, 9, 10, 20),
      `в момент начала ждали следующую субботу, а получили ${следующее.toISOString()}`);

    // За секунду до начала - начало сегодняшнее.
    const перед = началоОсады(расписание, момент('2026-10-03T19:59:59Z'));
    must(перед.getTime() === utc(2026, 9, 3, 20), `за секунду до начала ждали сегодня, а получили ${перед.toISOString()}`);

    // Час в UTC, а не по местному: сдвиг на 4 часа не должен двигать осаду.
    const соСдвигом = началоОсады(расписание, момент('2026-10-03T19:00:00+04:00'));
    must(соСдвигом.getTime() === utc(2026, 9, 3, 20),
      `локальное время сдвинуло начало на ${соСдвигом.toISOString()}`);
  });

  it('осада идёт ровно час и только внутри окна', () => {
    const расписание = разобратьРасписание('Saturday 20:00 UTC') as NonNullable<
      ReturnType<typeof разобратьРасписание>
    >;

    must(идётЛиОсада(расписание, момент('2026-10-03T19:59:59Z')) === false, 'осада идёт до начала');
    must(идётЛиОсада(расписание, момент('2026-10-03T20:00:00Z')) === true, 'осада не идёт в момент начала');
    must(идётЛиОсада(расписание, момент('2026-10-03T20:30:00Z')) === true, 'осада не идёт в середине');
    must(идётЛиОсада(расписание, момент('2026-10-03T20:59:59Z')) === true, 'осада не идёт за минуту до конца');
    must(идётЛиОсада(расписание, момент('2026-10-03T21:00:00Z')) === false, 'осада ещё идёт через час');
    must(идётЛиОсада(расписание, момент('2026-10-03T23:00:00Z')) === false, 'осада идёт через три часа');

    // В другой день недели осады быть не может: расписание «Saturday», а
    // сейчас вторник. Без этой проверки осада «гуляла» бы по дням.
    must(идётЛиОсада(расписание, момент('2026-10-06T20:00:00Z')) === false,
      'осада идёт во вторник, хотя назначена на субботу');
  });

  it('напоминание ровно за полчаса и не позже', () => {
    const расписание = разобратьРасписание('Saturday 20:00 UTC') as NonNullable<
      ReturnType<typeof разобратьРасписание>
    >;

    // За час - рано: напоминание обещает полчаса, и слать его за час значило
    // бы, что игрок получит «через 30 минут» за час до начала.
    must(пораНапомнить(расписание, момент('2026-10-03T19:00:00Z')) === false,
      'напоминаем за час, хотя обещали за полчаса');
    must(пораНапомнить(расписание, момент('2026-10-03T19:30:00Z')) === true, 'ровно за полчаса не напоминаем');
    must(пораНапомнить(расписание, момент('2026-10-03T19:45:00Z')) === true, 'за 15 минут не напоминаем');
    // Ровно в момент начала напоминать поздно: осада уже идёт.
    must(пораНапомнить(расписание, момент('2026-10-03T20:00:00Z')) === false, 'напоминаем в момент начала');
    must(пораНапомнить(расписание, момент('2026-10-03T20:30:00Z')) === false, 'напоминаем в середине осады');
    // За сутки до - рано.
    must(пораНапомнить(расписание, момент('2026-10-02T20:00:00Z')) === false, 'напоминаем за сутки');

    // Границы связаны с текстом уведомления, который обещает полчаса.
    must(НАПОМИНАНИЕ_ЗА_МС === 30 * 60 * 1000, 'напоминание не за полчаса, а текст обещает полчаса');
    must(ДЛИТЕЛЬНОСТЬ_ОСАДЫ_МС === 60 * 60 * 1000, 'осада длится не час');
  });
});

describe('Осады: урон', () => {
  it('любая территория пробивается за одно и то же число убийств', () => {
    // Главное свойство формулы: ЦЕЛЬ_УБИЙСТВ одинакова для всех. Иначе у
    // базара (прочность 5000) осада заканчивалась бы за минуты, а у порта
    // (60000) была бы недоступна никому.
    for (const территория of TERRITORIES) {
      const урон = уронЗаУбийство(территория.defensePoints);
      must(урон >= 1, `урон за убийство у ${территория.id} = ${урон}, это ноль или отрицательное`);
      must(ЦЕЛЬ_УБИЙСТВ * урон <= территория.defensePoints,
        `${территория.id}: ${ЦЕЛЬ_УБИЙСТВ} убийств дают ${ЦЕЛЬ_УБИЙСТВ * урон} - больше прочности ${территория.defensePoints}`);
      must((ЦЕЛЬ_УБИЙСТВ + 1) * урон > территория.defensePoints,
        `${территория.id}: пробить нельзя даже за ${ЦЕЛЬ_УБИЙСТВ + 1} убийств - стена недоступна`);
    }

    // Прочность обязана быть положительной: territories с нулевой прочностью
    // означали бы осаду, которая не начинается.
    for (const территория of TERRITORIES) {
      must(территория.defensePoints > 0, `у ${территория.id} неположительная прочность`);
      must(территория.capturePoints > 0, `у ${территория.id} неположительные очки захвата`);
    }
  });
});

describe('Осады: подключение', () => {
  it('планировщик запускается и останавливается вместе с игровым циклом', () => {
    // ПОЧЕМУ ЭТА ПРОВЕРКА. Та же болезнь была с боссами и достижениями:
    // система лежит в файле, никто её не создаёт, и всё выглядит сделанным
    // по объявлению данных. Без grep по GameLoop осады снова не случились бы
    // при четырёх объявленных территориях.
    const цикл = читать('server/src/systems/GameLoop.ts');
    must(/import \{ SiegeSystem \} from '\.\/SiegeSystem'/.test(цикл), 'SiegeSystem не импортирован в GameLoop');
    must(/SiegeSystem\.getInstance\(\)\.start\(\)/.test(цикл), 'планировщик осад не запускается');
    must(/SiegeSystem\.getInstance\(\)\.stop\(\)/.test(цикл), 'планировщик осад не останавливается');
    // restore обязан идти ДО start: иначе тик отработает на пустой памяти.
    must(цикл.indexOf('SiegeSystem.getInstance().restore()') < цикл.indexOf('SiegeSystem.getInstance().start()'),
      'restore вызывается после start: осада, оборванная перезапуском, потеряется');

    const система = читать('server/src/systems/SiegeSystem.ts');
    must(/setInterval\(/.test(система), 'у планировщика осад нет таймера');
    must(/clearInterval\(/.test(система), 'таймер осад не останавливается');
  });

  it('урон идёт от убийства, а система подключена к бою', () => {
    // Без вызова из обработчика боя осада начиналась бы и объявлялась, а
    // пробить крепость было бы нечем: тикающий планировщик сам по себе
    // механику не запускает.
    const бой = читать('server/src/socket/GameSocketHandler.ts');
    must(/SiegeSystem\.getInstance\(\)\.нанестиУрон/.test(бой),
      'обработчик боя не наносит урон по осаде');

    // void, а не await: это горячая точка, каждый удар каждого игрока.
    const строка = бой.split('\n').find((s) => s.includes('SiegeSystem.getInstance().нанестиУрон')) ?? '';
    must(строка.trimStart().startsWith('void '),
      `урон по осаде ждёт ответа: бой встанет на паузу - строка «${строка.trim()}»`);

    const система = читать('server/src/systems/SiegeSystem.ts');
    // Первым делом проверка по памяти: иначе на каждый удар каждого игрока
    // уходит запрос в базу, даже когда осады нет.
    must(система.indexOf('if (!this.идущие.has(территория.id)) return;')
      < система.indexOf('SELECT guild_id FROM characters'),
    'проверка «идёт ли осада» стоит после запроса в базу');
  });

  it('уникальный индекс запрещает вторую открытую осаду той же территории', () => {
    // ЛОВУШКА, КОТОРУЮ Я СНАЧАЛА И ПРОПУСТИЛ. Тик идёт каждые полминуты и
    // входит в код начала осады каждый раз. Без уникальности он вставлял бы
    // строку на каждый тик: к концу осады их было бы больше сотни, а «одна
    // открытая осада» была бы fiction. ON CONFLICT в коде опирается именно
    // на этот индекс, и текст его предиката обязан совпадать.
    const миграция = читать('database/migrations/066_guild_sieges.sql');
    must(/CREATE UNIQUE INDEX IF NOT EXISTS guild_sieges_open_idx\s*\n\s*ON guild_sieges \(territory_id\) WHERE ended_at IS NULL;/.test(миграция),
      'нет уникального индекса на одну открытую осаду по территории');

    // Совпадение предиката с текстом ON CONFLICT - иначе база отвергнет
    // запрос, а не поймает дубль.
    const система = читать('server/src/systems/SiegeSystem.ts');
    const конфликтов = система.match(/ON CONFLICT \(territory_id\) WHERE ended_at IS NULL DO NOTHING/g) ?? [];
    must(конфликтов.length >= 2,
      `ON CONFLICT по открытой осаде встречается ${конфликтов.length} раз - ожидалось в начале и при напоминании`);

    // И outcome закрыты списком в самой базе, а не только в коде.
    must(/CHECK \(outcome IN \('scheduled', 'in_progress', 'defended', 'captured'\)\)/.test(миграция),
      'список исходов осад не зафиксирован в базе');
  });

  it('уведомление идёт настоящим шардам, а не выдуманным', () => {
    // ЛОВУШКА, КОТОРУЮ Я ТОЖЕ СНАЧАЛА НАПИСАЛ. Я передал sendToRegion
    // идентификатор «all», которого нет ни среди шардов, ни среди подписок:
    // объявление ушло бы в канал, на который не подписан никто, и осада
    // выглядела бы «объявленной» при полном молчании.
    const система = читать('server/src/systems/SiegeSystem.ts');
    must(/for \(const шард of GAME_SERVERS\)/.test(система), 'объявление идёт не по настоящим шардам');
    must(!/sendToRegion\('all'/.test(система), 'объявление идёт на несуществующий шард all');

    // Канал, который слушает обработчик, должен совпадать с тем, куда шлём.
    const канал = читать('shared/constants.ts');
    must(/REGION_NOTIFICATION/.test(канал), 'в constants нет канала уведомлений региона');
    must(читать('server/src/socket/GameSocketHandler.ts').includes('REDIS_CHANNELS.REGION_NOTIFICATION(shardId, region)'),
      'обработчик не подписан на уведомления региона - объявление никто не получит');

    // Заодно: sendGlobal на канал global:notification не подписан никем, то
    // есть пользоваться им для осады нельзя. Ищем ВЫЗОВ со скобкой, а не
    // слово: слово есть в моём же комментарии, где объясняется, почему
    // sendGlobal не годится, и проверка на слово падала на своей же записке.
    must(!/sendGlobal\(/.test(система), 'осада вызывает sendGlobal, на который никто не подписан');
    // Комната, в которую обработчик пересылает уведомление, обязана собираться
    // из шарда И региона: по одному региону игроки всех восьми шардов получили
    // бы объявление чужого шарда.
    must(читать('server/src/socket/GameSocketHandler.ts').includes('shard:${shardId}:region:${region}'),
      'обработчик не собирает комнату региона из шарда и региона');

    // Шарды в системе и в игре - одни и те же.
    must(GAME_SERVERS.length > 0, 'в constants нет ни одного шарда');
    must(GAME_SERVERS.every((s) => typeof s.id === 'string' && s.id.length > 0), 'шард без идентификатора');
  });
});
