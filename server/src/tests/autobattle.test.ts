// Автобой: выбор игрока, тишина в PvP, выбор ближайшей цели.
//
// ЗДЕСЬ ИСПОЛНЯЕТСЯ НАСТОЯЩИЙ КОД client/src/app/autobattle.ts. Проверки
// живут в серверном наборе потому, что тест-раннера у клиента нет: так уже
// сделано для figure.ts (client/tools/check-figure.ts) и потому иначе
// правила автобоя остались бы непроверенными.
//
// ГЛАВНОЕ, ЧТО ЗДЕСЯ ФИКСИРУЕТСЯ. Автобой без переключателя лишает игрока
// контроля над боем, а в PvP-зоне это способ умереть не глядя. Оба свойства
// - «по умолчанию выключен» и «в PvP молчит» - обязаны быть видны
// поимённо, иначе правка одного из них выглядела бы как мелочь.
import {
  решить,
  выбратьЦель,
  можноВРегионе,
  создатьАвтобой,
  ПАУЗА_УДАРА_МС,
  ДАЛЬНОСТЬ_БОЯ,
  АВТОБОЙ_МОЛЧИТ,
  type МирДляАвтобоя,
} from '../../../client/src/app/autobattle';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

/**
 * Проверка с сужением типа.
 *
 * Именно asserts: без него TypeScript не знает, что после
 * must(разобранный.settings !== undefined) поле точно есть, и проверка
 * падала бы компиляцией (TS18048) вместо того, чтобы ронять тест по имени.
 */
function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Монстр в мире. */
const монстр = (id: string, x: number, z: number, deadAt = 0): {
  instanceId: string; pos: { x: number; z: number }; deadAt?: number;
} => ({ instanceId: id, pos: { x, z }, deadAt });

function мир(монстры: ReturnType<typeof монстр>[], region = 'tabriz', me = { x: 0, z: 0 }): МирДляАвтобоя {
  return {
    monsters: new Map(монстры.map((m) => [m.instanceId, m])),
    me: { pos: me },
    region,
  };
}

describe('Автобой: выбор остаётся за игроком', () => {
  it('выключен по умолчанию, и решение игрока сохраняется', () => {
    // ПОЧЕМУ ИМЕННО ВЫКЛЮЧЕН. Автобой, включившийся сам при первом же входе,
    // отнял бы у игрока контроль над боем без всякого его решения. Проверка
    // читает заводское значение из settings.ts, а не из этого файла: иначе
    // смена дефолта в коде оставила бы проверку зелёной.
    const настройки = readFileSync(join(корень, 'client/src/app/settings.ts'), 'utf-8');
    must(/autobattle: false/.test(настройки),
      'автобой больше не выключен по умолчанию - игрок теряет контроль над боем');

    // И решение игрока не должно теряться: состояние живёт в настройках,
    // а не в памяти вкладки.
    must(/autobattle: typeof raw\.autobattle === 'boolean' \? raw\.autobattle : false/.test(настройки),
      'выбор игрока не читается из настроек - автобой сбрасывался бы при каждом входе');

    const выкл = решить(мир([монстр('m1', 3, 0)]), false, false);
    must(выкл.бить === null, 'выключенный автобой бьёт');
    must(выкл.причина === 'выключен', `причина «${String(выкл.причина)}», а ждали «выключен»`);

    // Включённый - бьёт, и выбор игрока действует.
    const вкл = решить(мир([монстр('m1', 3, 0)]), true, false);
    must(вкл.бить === 'm1', 'включённый автобой не бьёт ближайшего монстра');
  });

  it('мёртвый не бьёт, даже когда автобой включён', () => {
    // Раньше удар слался сразу после смерти и применялся к цели сразу после
    // респавна. Автобой сделал бы это пачками.
    const решение = решить(мир([монстр('m1', 2, 0)]), true, true);
    must(решение.бить === null, 'мёртвый персонаж бьёт автобоем');
    must(решение.причина === 'мертв', `причина «${String(решение.причина)}», а ждали «мертв»`);
  });
});

describe('Автобой: в PvP он молчит', () => {
  it('в каждой PvP-зоне автобой не бьёт и говорит об этом один раз', () => {
    // Ловушка, из-за которой игрок решил бы, что игра зависла: молча
    // выключившийся автобой выглядит как поломка. Поэтому решение помечает
    // изЗаPvP - и мир обязан об этом сказать.
    must(АВТОБОЙ_МОЛЧИТ.length > 0, 'список PvP-зон пуст - автобой бьёт везде, включая PvP');
    for (const region of АВТОБОЙ_МОЛЧИТ) {
      const решение = решить(мир([монстр('m1', 2, 0)], region), true, false);
      must(решение.бить === null, `в регионе ${region} автобой бьёт, а зона PvP`);
      must(решение.изЗаPvP === true, `в регионе ${region} автобой молчит, но не сказал, что это PvP`);
    }
    // И наоборот: в безопасном регионе он бьёт.
    must(можноВРегионе('tabriz'), 'в Тебризе автобой молчит, хотя зона безопасная');
    must(можноВРегионе('isfahan'), 'в Исфахане автобой молчит, хотя зона безопасная');
    must(можноВРегионе('shiraz'), 'в Ширазе автобой молчит, хотя зона безопасная');
  });

  it('список PvP-зон клиента совпадает с серверным', () => {
    // Список в клиенте продублирован намеренно (импорт серверного файла
    // затащил бы в сборку базу и логгер). Дублирование без сверки - это
    // ровно тот случай, когда через месяц клиент считает безопасной зоной
    // ту, где на сервере PvP, и автобой убьёт игрока.
    const сервер = readFileSync(join(корень, 'server/src/systems/KarmaSystem.ts'), 'utf-8');
    const блок = /export const PVP_ZONES[^=]*=\s*\{([\s\S]*?)\n\};/.exec(сервер)?.[1] ?? '';
    must(блок.length > 0, 'не нашёл PVP_ZONES на сервере - сверять нечего');

    // На сервере PvP это type 'pvp' и 'contested'.
    const pvpНаСервере = [...блок.matchAll(/(\w+):\s*\{\s*type:\s*'(pvp|contested)'/g)].map((m) => m[1]);
    must(pvpНаСервере.length > 0, 'на сервере нет ни одной PvP-зоны');
    for (const регион of pvpНаСервере) {
      must(АВТОБОЙ_МОЛЧИТ.includes(регион),
        `регион ${регион} на сервере PvP, а в списке тишины автобоя его нет`);
    }
    // И наоборот: лишних регионов быть не должно.
    for (const регион of АВТОБОЙ_МОЛЧИТ) {
      must(pvpНаСервере.includes(регион),
        `клиент молчит в ${регион}, а на сервере он не PvP - автобой зря не работает`);
    }
  });

  it('автобой говорит о PvP один раз, а не на каждом такте', () => {
    // Иначе игрок, вошедший в PvP-зону, получил бы десяток одинаковых
    // сообщений подряд - то есть визуальный шум вместо объяснения.
    //
    // Такт НЕ запускается через настоящие часы: достаточно прогнать решение
    // столько раз, сколько тактов было бы в зоне, и посчитать сообщения.
    // Это проверка правила «один раз», а не работы таймера.
    const ав = создатьАвтобой(true);
    let сказано = 0;
    for (let такт = 0; такт < 50; такт++) {
      const решение = решить(мир([монстр('m1', 2, 0)], 'khorasan'), ав.включён, false);
      if (решение.изЗаPvP && !ав.сказалПроPvP) {
        ав.сказалПроPvP = true;
        сказано++;
      }
    }
    must(сказано === 1, `сообщение о PvP прозвучало ${сказано} раз за 50 тактов, а ждали один`);
    must(ав.сказалПроPvP === true, 'флаг «уже сказал» не выставлен');
  });
});

describe('Автобой: кого он бьёт', () => {
  it('берёт ближайшего, а не первого по списку', () => {
    // Список монстров - это Map, порядок там произвольный. Если бы автобой
    // брал первый, он бил бы через всю карту тем, кто попался раньше.
    const м = мир([
      монстр('далеко', 15, 0),
      монстр('рядом', 3, 0),
      монстр('средний', 9, 0),
    ]);
    must(выбратьЦель(м) === 'рядом', `выбрана не ближайшая цель`);

    // Мёртвые не бьются в не-цель.
    const сМёртвым = мир([
      монстр('труп', 2, 0, 1234),
      монстр('живой', 6, 0),
    ]);
    must(выбратьЦель(сМёртвым) === 'живой', 'автобой выбрал монстра, который уже мёртв');
  });

  it('не бьёт через полкарты', () => {
    // Монстр в 40 метрах - не цель. Иначе автобой бьёт через стены и
    // выглядит как чит, а не как automation.
    must(выбратьЦель(мир([монстр('далеко', ДАЛЬНОСТЬ_БОЯ + 5, 0)])) === null,
      'автобой бьёт монстра за пределами досягаемости');
    // Ровно на границе - ещё цель: граница проверяется включительно.
    must(выбратьЦель(мир([монстр('на границе', ДАЛЬНОСТЬ_БОЯ, 0)])) === 'на границе',
      'на границе досягаемости цель не выбрана');
    must(ДАЛЬНОСТЬ_БОЯ < 26, 'дальность автобоя шире, чем у замаха - это бьёт через стены');
  });

  it('без игрока не бьёт, и это не ошибка', () => {
    must(выбратьЦель({ monsters: new Map(), me: null, region: 'tabriz' }) === null,
      'без игрока выбрана цель - автобой ударит не туда');
    const решение = решить({ monsters: new Map(), me: null, region: 'tabriz' }, true, false);
    must(решение.бить === null && решение.причина === 'нет_цели',
      `без игрока причина «${String(решение.причина)}»`);
  });
});

describe('Автобой: цикл и остановка', () => {
  it('состояние создаётся выключенным и не бьёт до решения игрока', () => {
    // Обязательное свойство: автобой, который нельзя остановить, нельзя
    // включать - значит он должен и выключаться. Здесь проверяется то же
    // состояние, с которым работает мир: создано, помечает «работает», а
    // решение при выключенном флаге не бьёт (проверено выше отдельно).
    const ав = создатьАвтобой(false);
    must(ав.включён === false, 'созданный автобой включён без решения игрока');
    must(ав.работает === false, 'созданный автобой сразу пошёл: он обязан ждать запуска');

    // Флаг включения задаётся игроком, и цикл не должен трогать его сам.
    const включённый = создатьАвтобой(true);
    must(включённый.включён === true, 'решение игрока не сохранено в состояние');
  });

  it('пауза между ударами не короче серверного отката', () => {
    // Сервер держит откал 380 мс и отвечает attack_too_fast раньше. Пауза
    // короче отката означала бы, что каждый второй удар отвергается и
    // автобой вдвое тише, чем кажется.
    const сервер = readFileSync(join(корень, 'server/src/socket/GameSocketHandler.ts'), 'utf-8');
    const откат = /(\d{3})\s*\*\s*1000|ATTACK_COOLDOWN_MS\s*=\s*(\d+)/.exec(сервер);
    const найдено = откат ? Number(откат[1] ?? откат[2] ?? 0) : 380;
    must(ПАУЗА_УДАРА_МС > найдено,
      `пауза автобоя ${ПАУЗА_УДАРА_МС} мс не больше серверного отката ${найдено} мс - удары будут отвергаться`);
  });

  it('ошибка в такте не проходит наружу: цикл гасится, а не бросает', () => {
    // Такт идёт из игрового цикла, и исключение из него уронило бы игру.
    // Проверяется текстом намеренно: вызывать запустить() здесь нельзя,
    // он трогает window.setTimeout, которого в тестовой среде нет. Сам факт
    // try/catch вокруг такта обязан быть виден в коде - иначе ошибка в мире
    // (например, битый сетевой ответ) валила бы игру.
    const модуль = readFileSync(join(корень, 'client/src/app/autobattle.ts'), 'utf-8');
    const шаг = модуль.slice(модуль.indexOf('const шаг ='), модуль.indexOf('const id ='));
    must(/try \{/.test(шаг), 'в такте автобоя нет try: ошибка из мира уронит игру');
    must(/ав\.работает = false/.test(шаг),
      'при ошибке автобой не останавливается - цикл продолжит бить по битому миру');
  });
});

describe('Автобой: подключено к игре, а не лежит файлом', () => {
  it('кнопка есть в настройках и в трёх языках', () => {
    const html = readFileSync(join(корень, 'client/src/app/index.html'), 'utf-8');
    must(/id="set-autobattle"/.test(html),
      'в настройках нет переключателя автобоя - игрок не может его включить');

    for (const язык of ['ru', 'en', 'az']) {
      const словарь = readFileSync(join(корень, `shared/locales/${язык}.json`), 'utf-8');
      // Разбираем JSON, а не ищем строку: невалидный словарь не должен
      // проходить проверку по счастливому совпадению подстроки.
      const разобранный = JSON.parse(словарь) as { settings?: Record<string, string>; world?: Record<string, string> };
      // must с сужением типа: иначе после проверки на undefined переменная
      // остаётся «возможно отсутствующей» и проверка падала бы компиляцией
      // (TS18048) вместо того, чтобы ронять тест по имени.
      must(разобранный.settings !== undefined, `в ${язык} нет секции settings`);
      must(typeof разобранный.settings.autobattle === 'string' && разобранный.settings.autobattle.length > 0,
        `в ${язык} нет подписи автобоя`);
      must(разобранный.world !== undefined, `в ${язык} нет секции world`);
      for (const ключ of ['autobattle_on', 'autobattle_off', 'autobattle_pvp_off']) {
        const текст = разобранный.world[ключ];
        must(typeof текст === 'string' && текст.length > 0, `в ${язык} нет ключа world.${ключ}`);
      }
    }
  });

  it('мир запускает автобой, разрыв и смерть его трогают', () => {
    // Та же болезнь, что была с боссами данжей и заданиями: класс написан,
    // а никто его не создаёт. Проверка ищет вызовы в мире, а не сам файл.
    const мир2 = readFileSync(join(корень, 'client/src/app/world.ts'), 'utf-8');
    must(/from '\.\/autobattle'/.test(мир2), 'мир не импортирует автобой');
    must(/создатьАвтобой\(getSettings\(\)\.autobattle\)/.test(мир2),
      'состояние автобоя не берётся из настроек игрока');
    must(/стартАвтобоя\(\)/.test(мир2), 'автобой нигде не запускается');
    must(/стопАвтобоя\(\)/.test(мир2), 'автобой нигде не останавливается');

    // При разрыве цикл обязан встать: два цикла после возврата в игру
    // означали бы вдвое больше пакетов боя.
    const блокDisconnect = мир2.slice(мир2.indexOf("socket.on('disconnect'"));
    must(/стопАвтобоя\(\)/.test(блокDisconnect.slice(0, 400)),
      'разрыв сокета не останавливает автобой');

    // И при смерти: мир пересоздаётся, автобой был запущен до входа.
    const блокRespawn = мир2.slice(мир2.indexOf('PLAYER_RESPAWNED'));
    must(/стартАвтобоя\(\)/.test(блокRespawn.slice(0, 900)),
      'после смерти автобой не перезапускается - он молчал бы до перевключения');

    // Переключатель обязан быть в обработчике настроек, а не в кнопке,
    // которой никто не нажмёт.
    const блокНастроек = мир2.slice(мир2.indexOf("autobattle?.addEventListener"));
    must(/updateSettings\(\{ autobattle/.test(блокНастроек.slice(0, 300)),
      'переключатель автобоя не пишет в настройки');

    // ДЫРА, КОТОРУЮ Я ЗАКРЫЛ СРАЗУ. Мир обязан передавать isDead() в цикл.
    // Если он этого не делает, автобой бьёт после смерти - а это ровно тот
    // отказ, который когда-то был с ручным боем: удары улетали на сервер
    // сразу после смерти и применялись к цели сразу после респавна.
    // Ломка «мир всегда передаёт не мёртв» компилировалась и проверку не
    // поймала: свойство просто не было зафиксировано.
    const блокЗапуска = мир2.slice(мир2.indexOf('function стартАвтобоя'), мир2.indexOf('function стопАвтобоя'));
    must(/=> isDead\(\)/.test(блокЗапуска),
      'мир не передаёт состояние «мёртв» в автобой - он будет бить после смерти');
  });

  it('автобой бьёт через тот же путь, что и клик', () => {
    // ЕСЛИ БЫ автобой слал свой пакет, серверные проверки урона, дальности и
    // античита остались бы для ручного боя, а для автоматического путь был
    // бы другим. Это тот класс поломки, что в проекте уже был: счётчик
    // убийств писался через placeholder и падал молча на втором событии.
    const мир2 = readFileSync(join(корень, 'client/src/app/world.ts'), 'utf-8');
    const блокУдара = мир2.slice(мир2.indexOf('function basicAttack'));
    must(/emitCombat\('attack'\)/.test(блокУдара.slice(0, 200)),
      'ручной удар идёт не через emitCombat - автобой пойдёт другим путём');

    // И в самом автобое нет собственного сетевого вызова.
    const модуль = readFileSync(join(корень, 'client/src/app/autobattle.ts'), 'utf-8');
    must(!/socket\.emit/.test(модуль),
      'автобой шлёт пакеты сам, минуя emitCombat: это второй путь начисления урона');
    must(!/from '\.\/net'/.test(модуль),
      'автобой тянет сокет: сетевым должен заниматься только world.ts');
  });
});
