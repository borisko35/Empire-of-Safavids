// Мир стал в семь раз больше по площади, и появился восьмой регион.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ. Расширение мира и добавление региона - из тех правок,
// которые выглядят простыми и ломают всё вокруг. Здесь собрано то, что
// должно остаться правдой после них:
//
//   1. мир действительно в семь раз больше по площади, а не «примерно»;
//   2. клетка рельефа не стала грубой (иначе холмы превратятся в ступени);
//   3. восьмой регион настоящий: зоны, якорь, город, спавны, уровень;
//   4. ни одна правка не оставила мёртвой земли и не унесла чужие города.
//
// КАК ЧИТАЕТСЯ. terrain.ts нельзя импортировать в серверной проверке: он
// тянет three и рисует текстуры через document, а серверный tsconfig не
// включает клиент. Поэтому числа берутся из исходника. Это осознанно:
// единственный источник - он же, иначе проверка мерила бы копию.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ZONES, REGION_SPAWNS, REGION_LEVEL_REQUIREMENTS, getZoneAt } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ПОЛОВИНА = Number(/export const WORLD_HALF = (\d+);/.exec(ТЕРРЕЙН)?.[1]);
const СЕГМЕНТЫ = Number(/const TERRAIN_SEG = (\d+);/.exec(ТЕРРЕЙН)?.[1]);

// Прежний мир, который правка заменила. Зашит руками как ловушка: если
// расширение когда-нибудь откатят, проверка обязана это заметить, а не
// радостно пересчитать «7 раз» от нового числа и снова пройти.
const БЫЛО_ПОЛОВИНА = 1200;
const БЫЛО_КЛЕТКА = (БЫЛО_ПОЛОВИНА * 2) / 170;

describe('Мир расширен в семь раз по площади', () => {
  it('площадь мира выросла в семь раз, а не «примерно»', () => {
    // (6350/2400)^2 = 7.000 ровно. Первая версия проверки ждала 7.005:
    // арифметика в комментарии к WORLD_HALF была неверна, и поймала её
    // проверка, а не глаз.
    must(Number.isFinite(ПОЛОВИНА) && ПОЛОВИНА > 0,
      'не прочитал WORLD_HALF из terrain.ts — проверка ничего не меряет');
    // Имя без пробела: «во сколько» - это два слова, а не идентификатор,
    // и TypeScript падал с TS1005. Имена на кириллице работают, пробелы -
    // нет, и это легко спутать.
    const воСколько = (ПОЛОВИНА * 2) / (БЫЛО_ПОЛОВИНА * 2);
    const площадь = воСколько * воСколько;
    must(воСколько > 1, `WORLD_HALF не вырос: ${ПОЛОВИНА} против прежних ${БЫЛО_ПОЛОВИНА}`);
    expect({ линейный_рост: Number(воСколько.toFixed(3)), площадь: Number(площадь.toFixed(3)) })
      .toEqual({ линейный_рост: 2.646, площадь: 7 });
    must(площадь > 6.9 && площадь < 7.1,
      `площадь выросла в ${площадь.toFixed(2)} раз, а просили в семь`);
  });

  it('клетка рельефа осталась той же длины, а не стала грубой', () => {
    // Главная цена расширения. Сетка задаётся числом сегментов, а размер
    // клетки получается делением. Оставить 170 сегментов на стороне в семь
    // раз большей стороне - значит растянуть клетку с 14 до 37 единиц, и
    // рельеф станет грубой лестницей: холм шириной 200 единиц займёт
    // 8 клеток вместо 14.
    must(Number.isFinite(СЕГМЕНТЫ) && СЕГМЕНТЫ > 0,
      'не прочитал TERRAIN_SEG из terrain.ts — проверка ничего не меряет');
    const клетка = (ПОЛОВИНА * 2) / СЕГМЕНТЫ;
    // Разница с прежней клеткой не больше половины единицы: та же длина
    // с точностью до округления.
    must(Math.abs(клетка - БЫЛО_КЛЕТКА) < 0.5,
      `клетка рельефа ${клетка.toFixed(1)} ед. против прежних ${БЫЛО_КЛЕТКА.toFixed(1)} — ` +
      'рельеф стал грубым. Либо поднять TERRAIN_SEG, либо сознательно принять потерю деталей и описать её здесь.');
  });

  it('цену расширения измерили, а не прикинули', () => {
    // Число вершин обязано совпадать с плотностью сетки. Проверка не
    // измеряет миллисекунды - это нестабильно, - но требует, чтобы рядом
    // с решением лежал сам замер. Без него следующий человек либо не
    // поверит в 450 мс, либо не узнает про 605 мс на SEG 520.
    must(/SEG 450 - 450 мс, 203401 вершина/.test(ТЕРРЕЙН),
      'рядом с TERRAIN_SEG нет замера стоимости сборки — число 450 взято на глаз');
    must(/SEG 520 - 605 мс/.test(ТЕРРЕЙН),
      'в комментарии к TERRAIN_SEG нет замера следующего шага — 520 указан как запас');
  });
});

describe('Восьмой регион настоящий, а не строчка в перечислении', () => {
  it('у него есть зоны, якорь, уровень и город', () => {
    const зоныГерата = ZONES.filter((з) => з.region === 'herat');
    must(REGION_SPAWNS.herat !== undefined, 'у региона herat нет якоря — путешествовать некуда');
    must(REGION_LEVEL_REQUIREMENTS.herat !== undefined, 'у региона herat нет требования по уровню');
    // Якорь обязан лежать в зоне своего региона, а не просто где-то на карте.
    const зона = getZoneAt(REGION_SPAWNS.herat.x, REGION_SPAWNS.herat.z);
    must(зона !== null, 'якорь Герата вне всякой зоны — игрок возродится в пустоте');
    must(зона.region === 'herat', `якорь Герата попал в зону ${зона.id} региона ${зона.region}`);
    expect({
      зон: зоныГерата.length,
      якорь_в_своей_зоне: зона.region === 'herat',
      уровень_задан: REGION_LEVEL_REQUIREMENTS.herat !== undefined,
    }).toEqual({ зон: 3, якорь_в_своей_зоне: true, уровень_задан: true });
  });

  it('город Герата построен, а не только объявлен', () => {
    // Регион без построенного города - это полоса земли с монстрами и
    // подписью. Именно так выглядела поломка, найденная с картой: город
    // стоит, а на карте его нет.
    const города = /export const REGION_TOWNS[\s\S]*?\n\];/.exec(ТЕРРЕЙН)?.[0] ?? '';
    must(города.length > 0, 'не нашёл REGION_TOWNS в terrain.ts');
    must(/region: 'herat'/.test(города), 'в REGION_TOWNS нет города Герата — регион без построек');
    // У Герата свой силуэт, а не копия чужого: ворота вместо сада.
    must(/kind: 'gates'/.test(города), 'город Герата не отмечен как gates — силуэт не задан');
    must(/case 'gates':/.test(ТЕРРЕЙН), 'в buildRegionTowns нет ветки gates — вид Герата не рисуется');
  });

  it('у него есть монстры, и они где-то спавнятся', () => {
    // Запись в базе без точки спавна - монстр, до которого нельзя дойти.
    // Проверка «у каждого региона есть точки спавна» это сторожит, но
    // здесь важно другое: спавны стоят в ЗОНАХ Герата, а не где попало.
    const спавнСистема = читать('server/src/systems/SpawnSystem.ts');
    const её = [...спавнСистема.matchAll(/region:\s*Region\.HERAT,\s*position:\s*\{\s*x:\s*(-?\d+),\s*y:\s*-?\d+,\s*z:\s*(-?\d+)/g)];
    must(её.length > 0, 'в SpawnSystem нет ни одной точки спавна региона HERAT');
    const внеЗон: string[] = [];
    for (const [, x, z] of её) {
      const зона = getZoneAt(Number(x), Number(z));
      if (зона === null || зона.region !== 'herat') {
        внеЗон.push(`(${x}, ${z}) -> ${зона?.id ?? 'вне зон'}`);
      }
    }
    must(внеЗон.length === 0, `точки спавна Герата стоят не в его зонах:\n  ${внеЗон.join('\n  ')}`);
  });

  it('есть монстры Герата, и у каждого своя внешность', () => {
    // Монстр без ветки в разборе рисуется гуманоидом в капюшоне с мечом -
    // то есть выглядит как бандит из другого края света, молча.
    const монстры = читать('server/src/data/monsters.ts');
    const её = [...монстры.matchAll(/region:\s*Region\.HERAT/g)];
    must(её.length > 0, 'в monsters.ts нет ни одного монстра региона HERAT');
    const риг = читать('client/src/app/game3d/rig.ts');
    const безВетки: string[] = [];
    for (const блок of монстры.matchAll(/'([a-z0-9_]+)':\s*\{[\s\S]*?region:\s*Region\.HERAT/g)) {
      if (!риг.includes(`case '${блок[1]}'`)) безВетки.push(блок[1]);
    }
    must(безВетки.length === 0,
      `монстры Герата рисуются как гуманоид в капюшоне с мечом: ${безВетки.join(', ')}`);
  });

  it('он виден игроку: имя региона, зоны и список путешествий', () => {
    // Списки в клиенте перечислены руками. Новый регион в них не появляется
    // сам, и без этих строк игрок увидел бы зону без имени региона, а
    // путешествовать в Герат было бы некуда.
    const hud = читать('client/src/app/hud.ts');
    const панели = читать('client/src/app/panels.ts');
    must(/herat: 'regions\.herat'/.test(hud), 'в REGION_NAMES клиента нет herat — регион не подписан');
    must(/herat_city: 'zones\.herat_city'/.test(hud), 'в ZONE_NAMES клиента нет зон Герата');
    must(/id: 'herat',\s*nameKey: 'regions\.herat'/.test(панели), 'Герата нет в списке путешествий');
  });

  it('название региона и его зон переведено во всех трёх языках', () => {
    // Без ключа на экране появился бы сам путь ключа - «regions.herat»
    // вместо названия. Это выглядело бы как «сломался перевод», а на деле
    // переводить было нечего.
    const отсутствуют: string[] = [];
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`)) as Record<string, Record<string, string>>;
      if (typeof словарь.regions?.herat !== 'string') отсутствуют.push(`${язык}: regions.herat`);
      for (const зона of ZONES.filter((з) => з.region === 'herat')) {
        if (typeof словарь.zones?.[зона.id] !== 'string') отсутствуют.push(`${язык}: zones.${зона.id}`);
      }
    }
    must(отсутствуют.length === 0, `в словарях нет:\n  ${отсутствуют.join('\n  ')}`);
  });

  it('база его не отвергает: ограничение региона обновлено', () => {
    // Перечислить регион в enum Region мало. СУБД отвергла бы вставку в
    // region_visits, а recordRegionVisit специально не поднимает
    // исключение, чтобы сбой отметки не ронял путешествие. Итог выглядел
    // бы исправно, а молча перестал бы работать целый механизм.
    const миграция = читать('database/migrations/068_herat_region.sql').replace(/--[^\n]*/g, ' ');
    const список = /region IN \(([^)]*)\)/.exec(миграция)?.[1] ?? '';
    const имена = [...список.matchAll(/'([a-z_]+)'/g)].map((м) => м[1]);
    must(имена.includes('herat'),
      'в ограничении region_visits нет herat — запись о посещении Герата будет молча отброшена базой');
    // Ограничение обязано совпадать с перечнем в коде, иначе это две правды.
    must(имена.length === Object.keys(REGION_SPAWNS).length,
      `в ограничении ${имена.length} регионов, а якорей ${Object.keys(REGION_SPAWNS).length}`);
  });
});

describe('Расширение никого не выбросило', () => {
  it('старые города остались на своих местах и в своих зонах', () => {
    // Регион мог растянуть полосы так, что якорь уехал бы в чужую зону.
    // Все восемь якорей проверяются числами, а не списком.
    const чужие: string[] = [];
    for (const [регион, якорь] of Object.entries(REGION_SPAWNS)) {
      const зона = getZoneAt(якорь.x, якорь.z);
      if (зона === null) чужие.push(`${регион}: якорь вне всякой зоны`);
      else if (зона.region !== регион) чужие.push(`${регион}: якорь в зоне ${зона.id}`);
    }
    must(чужие.length === 0, `после расширения якоря оказались не в своих зонах:\n  ${чужие.join('\n  ')}`);
  });

  it('мир по-прежнему покрыт зонами целиком', () => {
    // Расширение без этого превратило бы новую землю в дыры: игрок ушёл бы
    // за край зон и оказался в месте без спавнов, подписи и проверки
    // уровня. Сетка грубее прежней, но сплошная.
    const ПОЛУШАГ = 40;
    const безЗоны: string[] = [];
    let всего = 0;
    for (let x = -ПОЛОВИНА + ПОЛУШАГ; x < ПОЛОВИНА; x += ПОЛУШАГ * 2) {
      for (let z = -ПОЛОВИНА + ПОЛУШАГ; z < ПОЛОВИНА; z += ПОЛУШАГ * 2) {
        всего++;
        if (getZoneAt(x, z) === null && безЗоны.length < 8) безЗоны.push(`(${x}, ${z})`);
      }
    }
    must(всего > 5000, `сетка проверки слишком мелкая: ${всего} точек, проверка ничего не меряет`);
    must(безЗоны.length === 0,
      `после расширения в мире появилась земля без зоны (${безЗоны.length} точек из ${всего}):\n  ${безЗоны.join(' ')}`);
  });

  it('интерьеры остались за краем мира', () => {
    // Комнаты зданий стоят в отдельном кармане за краем. Мир вырос, и
    // карман мог оказаться внутри него: тогда в комнате стоял бы рельеф,
    // а игрок, вошедший в здание на улице, попадал бы в точку открытой
    // земли. Проверка в relogInsideBuilding.test.ts ловит само смещение,
    // здесь - то, что край мира и карман не совпали.
    const комнаты = [...читать('server/src/data/interiors.ts')
      .matchAll(/(?:roomCx|roomCz):\s*(-?\d+)/g)]
      .map((м) => Math.abs(Number(м[1])));
    must(комнаты.length > 0, 'не нашёл координаты комнат интерьеров');
    const ближайшая = Math.min(...комнаты);
    must(ближайшая > ПОЛОВИНА,
      `комната интерьера стоит на ${ближайшая} ед., а край мира ${ПОЛОВИНА}: карман оказался внутри мира`);
  });
});
