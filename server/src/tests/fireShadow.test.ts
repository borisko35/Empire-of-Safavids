// Тень от костра.
//
// ЧТО БЫЛО (21 октября 2026, §267). У всех источников света в мире теней
// нет, и ночью огонь не отбрасывает ни одной. Это самый заметный недосчёт
// света: свет есть, а тени нет.
//
// ЧТО ТЕПЕРЬ. Тень отбрасывает ОДИН источник — направленный конус над костром
// в лагере. Тень от точечного источника — это куб, шесть проходов рендера на
// каждый источник, а источников десятки; конус — один проход.
//
// Тень считается только рядом с костром (в сорока метрах): вдали огонь всё
// равно не видно, а проход рендера теней стоил бы кадра.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Тень от костра', () => {
  it('тень отбрасывает один направленный источник, а не все', () => {
    // Конус, а не точка: куб теней у точечного источника — шесть проходов.
    должен(/const теньКостра = new THREE\.SpotLight\(/.test(МИР), 'тень отбрасывает не направленный источник');
    должен(/теньКостра\.castShadow = true;/.test(МИР), 'источник тени не отбрасывает тень');
    // Карта теней разумного размера.
    должен(/теньКостра\.shadow\.mapSize\.set\(1024, 1024\);/.test(МИР), 'карта теней не задана');
    // Цель источника — вниз, в костёр.
    должен(
      /теньКостра\.target\.position\.set\(CAMP\.x, groundHeight\(CAMP\.x, CAMP\.z\), CAMP\.z\);/.test(МИР),
      'источник тени светит не в костёр',
    );
    // Свет самого костра стал тише: главную работу делает конус.
    должен(/this\.torches\.push\(\{ light: fireLight, base: 1\.8, phase: 5\.5 \}\);/.test(МИР),
      'свет костра не притих, а конус светит в полную силу: будет вдвое светлее');
  });

  it('тень считается только рядом с костром', () => {
    должен(/const доКостра = Math\.hypot\(me\.pos\.x - CAMP\.x, me\.pos\.z - CAMP\.z\);/.test(МИР),
      'расстояние до костра не считается');
    должен(/const рядом = доКостра < 40;/.test(МИР), 'тень считается вдали от костра');
    должен(/this\.теньКостра\.castShadow = рядом;/.test(МИР), 'тень не выключается вдали');
    должен(/this\.теньКостра\.intensity = рядом \? 2\.2 : 0;/.test(МИР), 'источник тени горит вдали от костра');
  });
});
