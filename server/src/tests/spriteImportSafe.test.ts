// Динамический импорт ассета не имеет права ломать вызывающий код.
//
// ЧТО БЫЛО. `spriteUrl()` делала голый `await import(\`../assets/sprites/${base}.png\`)
// без обработки отказа. Путь собран из шаблонной строки, поэтому Vite не разбирает
// его статически и делает отдельный чанк на каждый спрайт:
//
//   char_qizilbash_0-B9oXK4an.js   72 байта
//   var e = `/game/assets/char_qizilbash_0-8wMs2jEu.png`; export { e as default };
//
// Имя чанка содержит хеш содержимого и меняется при КАЖДОЙ выкатке. Ровно этот
// случай описан в deploy.sh как «старый index-D24E_uzX.js -> 404»: игрок с
// закэшированной страницей после выкатки.
//
// ЧТО ИЗ ЭТОГО ПОЛУЧАЛОСЬ. Отказ импорта поднимался наружу, а вызывающий код к
// нему не был готов. Два последствия, оба неправдоподобные с точки зрения
// игрока:
//
//   1. `refreshList` падал в середине цикла по персонажам: часть строк
//      отрисовывалась, остальные нет. Экран выглядел как «список грузится».
//   2. `refreshList` зовётся после удаления персонажа внутри `try`, где любой
//      отказ показывается тостом «удалить не удалось». Персонаж удалялся, а
//      игроку говорили обратное — из-за картинки, которую никто не увидит.
//
// Второе хуже первого: сообщение врёт, и игрок решит, что удаление не сработало,
// и удалит снова.
//
// ЧТО ПРОВЕРЯЕТСЯ. Спрайт — украшение, и отказ от него не должен иметь цены. Три
// требования: функция не бросает, вызывающие не ждут исключения, и пустой адрес
// не присваивается — иначе браузер сам сходит на адрес страницы.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Кириллица в причинах иероглифами не печатается, но на условие это не влияет.
function должно(условие: unknown, причина: string): void {
  должен(условие, причина);
}

/** Все файлы клиента без комментариев: путь и код, готовый к проверке. */
function читатьКлиентскиеФайлы(): { путь: string; код: string }[] {
  const кореньКлиента = join(корень, 'client', 'src');
  const найдено: { путь: string; код: string }[] = [];
  const обойти = (папка: string): void => {
    for (const имя of readdirSync(папка)) {
      const полный = join(папка, имя);
      if (statSync(полный).isDirectory()) {
        обойти(полный);
        continue;
      }
      if (!имя.endsWith('.ts')) continue;
      найдено.push({
        путь: полный.slice(кореньКлиента.length + 1).replace(/\\/g, '/'),
        код: код(readFileSync(полный, 'utf-8')),
      });
    }
  };
  обойти(кореньКлиента);
  return найдено;
}

// Комментарии вырезаются: пояснение о поломке стоит прямо над местом поломки,
// и без вырезания оно само попадёт под проверку. Тот же класс ошибки, что в 142,
// 152, 153 и 154, — в пятый раз.
function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const ЭКРАН_КОД = код(читать('client/src/app/screens/chars.ts'));
const ЭКРАН_ВСЕ = читать('client/src/app/screens/chars.ts');
const СПРАЙТЫ = код(читать('client/src/app/sprites.ts'));

describe('Спрайты классов грузятся без риска для списка', () => {
  it('шаблонного импорта ассета в клиенте нет', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Путь из шаблонной строки Vite не разбирает
    // статически и собирает отдельный чанк на каждый возможный файл. Замерено:
    // таких чанков было двадцать шесть по 60–80 байт, каждый тянулся отдельным
    // запросом, а имя содержало хеш и менялось при каждой выкатке — то есть
    // давало 404 всем, кто не обновил страницу. Проверяется по всему клиенту,
    // а не по одному экрану: шаблонный импорт ассета опасен везде одинаково.
    const клиент = читатьКлиентскиеФайлы();
    должно(
      клиент.length > 20,
      'обход клиента нашёл подозрительно мало файлов: проверка ослепла',
    );
    const виновники = клиент.filter((ф) => /import\(\s*`[^`]*\$\{/.test(ф.код));
    должно(
      виновники.length === 0,
      `шаблонный импорт ассета вернулся в ${виновники.map((ф) => ф.путь).join(', ')}: ` +
        'сборка снова наделает по чанку на файл',
    );
  });

  it('адрес спрайта берётся из статической мапы', () => {
    // Адреса всех спрайтов уже импортированы явно в sprites.ts. Экран берёт их
    // оттуда, а не добывает заново.
    должно(
      /import\s*\{[^}]*spriteSource[^}]*\}\s*from\s*'\.\.\/sprites'/.test(ЭКРАН_КОД),
      'экран персонажей снова добывает адреса сам, а не берёт их из sprites.ts',
    );
    должно(
      /function\s+spriteUrl\([^)]*\)[^{]*\{\s*return\s+spriteSource\([^)]*\);\s*\}/.test(ЭКРАН_КОД),
      'функция адреса перестала быть простой отдачей мапы: проверь, что её не усложняют заново',
    );
    должно(
      /export function spriteSource\(name: string\): string \| undefined/.test(СПРАЙТЫ),
      'в sprites.ts нет функции адреса: экран снова не сможет взять статический адрес',
    );
  });

  it('вызывающие терпят отсутствие картинки', () => {
    // Адрес может не найтись в мапе. Без проверки пустая строка попадёт в
    // `img.src`, и браузер сам сойдёт на адрес текущей страницы.
    должно(
      /if\s*\(\s*спрайт\s*\)\s*img\.src\s*=\s*спрайт/.test(ЭКРАН_КОД),
      'карточка персонажа снова присваивает адрес спрайта без проверки',
    );
    должно(
      /if\s*\(\s*адрес\s*\)\s*img\.src\s*=\s*адрес/.test(ЭКРАН_КОД),
      'иконка выбора класса снова присваивает адрес без проверки',
    );
    должно(
      !/img\.src\s*=\s*await\s+spriteUrl/.test(ЭКРАН_КОД),
      'адрес спрайта снова присваивается прямо из await',
    );
  });

  it('причина поломки записана рядом с местом поломки', () => {
    // Без этого следующий читатель увидит простую функцию, решит, что она
    // лишняя, и вернёт шаблонный импорт вместе с 404 после выкатки.
    //
    // Проверяются ASCII-маркеры, а не русские фразы. Фраза в комментарии может
    // разъехаться переносом строки, и проверка начнёт искать текст там, где его
    // нет: это уже пятый случай, когда регулярка по пояснению оказалась хрупче
    // проверки по коду. Маркеры `char_qizilbash_0-*.js` и `index-D24E_uzX.js`
    // переносом не разъезжаются.
    должно(
      /char_qizilbash_0-[A-Za-z0-9_*]+\.js/.test(ЭКРАН_ВСЕ),
      'рядом с функцией не назван конкретный чанк: пояснение должно показывать, чего именно лишились',
    );
    должно(
      /index-D24E_uzX\.js/.test(ЭКРАН_ВСЕ),
      'не названа причина 404 после выкатки: пояснение о поломке должно её называть',
    );
  });
});