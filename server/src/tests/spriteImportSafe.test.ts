// Динамический импорт ассета не имеет права ломать вызывающий код.
//
// ЧТО БЫЛО. `spriteUrl()` делала голый `await import(\`../assets/sprites/${base}.png\`)
// без обработки отказа. Путь собран из шаблонной строки, поэтому Vite не разбирает
// его статически и делает отдельный чанк на каждый спрайт:
//
//   char_qizilbash_0-B9oXK4an.js   72 байта
//   var e = `/game/assets/char_qizilbash_0-8wMs2jEu.png`; export { e as default };
//
// Имя чанка содержит хеш содержимого и меняется при КАЖДОЙ выкатке. Ровно этот
// случай описан в deploy.sh как «старый index-D24E_uzX.js -> 404»: игрок с
// закэшированной страницей после выкатки.
//
// ЧТО ИЗ ЭТОГО ПОЛУЧАЛОСЬ. Отказ импорта поднимался наружу, а вызывающий код к
// нему не был готов. Два последствия, оба неправдоподобные с точки зрения
// игрока:
//
//   1. `refreshList` падал в середине цикла по персонажам: часть строк
//      отрисовывалась, остальные нет. Экран выглядел как «список грузится».
//   2. `refreshList` зовётся после удаления персонажа внутри `try`, где любой
//      отказ показывается тостом «удалить не удалось». Персонаж удалялся, а
//      игроку говорили обратное — из-за картинки, которую никто не увидит.
//
// Второе хуже первого: сообщение врёт, и игрок решит, что удаление не сработало,
// и удалит снова.
//
// ЧТО ПРОВЕРЯЕТСЯ. Спрайт — украшение, и отказ от него не должен иметь цены. Три
// требования: функция не бросает, вызывающие не ждут исключения, и пустой адрес
// не присваивается — иначе браузер сам сходит на адрес страницы.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Комментарии вырезаются: пояснение о поломке стоит прямо над местом поломки,
// и без вырезания оно само попадёт под проверку. Тот же класс ошибки, что в 142,
// 152 и 153, — в четвёртый раз.
function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const ЭКРАН_КОД = код(читать('client/src/app/screens/chars.ts'));
const ЭКРАН_ВСЕ = читать('client/src/app/screens/chars.ts');

describe('Спрайты классов грузятся без риска для списка', () => {
  it('функция загрузки не бросает наружу', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Отказ импорта обязан оставаться внутри функции.
    const тело = /async function spriteUrl\([^)]*\)[^{]*\{[\s\S]*?\n\}/.exec(ЭКРАН_КОД);
    должен(тело, 'функция spriteUrl не найдена: проверка ослепла');
    должен(
      /try\s*\{[\s\S]*await import\([\s\S]*catch\s*\(/.test(тело[0]),
      'загрузка спрайта снова бросает наружу: список персонажей будет рваться наполовину',
    );
    должен(
      /Promise<string \| null>/.test(ЭКРАН_КОД),
      'функция обещает спрайт, но не может его не дать: тип должен допускать null',
    );
  });

  it('вызывающие терпят отсутствие картинки', () => {
    // Два места, и оба обязаны проверять результат. Без проверки пустой адрес
    // попадёт в `img.src`, и браузер сам сходит на адрес текущей страницы.
    должен(
      /if\s*\(\s*спрайт\s*\)\s*img\.src\s*=\s*спрайт/.test(ЭКРАН_КОД),
      'карточка персонажа снова присваивает адрес спрайта без проверки',
    );
    должен(
      /if\s*\(\s*!url\s*\)\s*return/.test(ЭКРАН_КОД),
      'иконка выбора класса снова присваивает адрес без проверки',
    );
    должен(
      !/img\.src\s*=\s*await\s+spriteUrl/.test(ЭКРАН_КОД),
      'адрес спрайта снова присваивается прямо из await: исключение уйдёт в список',
    );
  });

  it('отказ виден в консоли и не повторяется двадцать раз', () => {
    // Молчание здесь опасно: ровно так в §149 погибло напоминание о голосовании.
    // Но и двадцать одинаковых строк на 404 тоже шум. Требуется предупреждение
    // с названием спрайта.
    должен(
      /console\.warn\([\s\S]*спрайт/.test(ЭКРАН_КОД),
      'отказ грузки спрайта снова молчит: по консоли нельзя будет понять, почему нет картинок',
    );
    // Проверяется по исходнику целиком: предупреждение обязано называть спрайт
    // и доставать текст из словаря — сторож i18n не пускает кириллицу в код.
    должен(
      /console\.warn\(`\[chars\] \$\{base\}: \$\{t\('chars\.sprite_failed'\)\}/.test(ЭКРАН_ВСЕ),
      'предупреждение не называет конкретный спрайт или берёт текст не из словаря',
    );
  });

  it('причина поломки записана рядом с местом поломки', () => {
    // Без этого следующий читатель увидит `try/catch` и решит, что он лишний,
    // и снесёт его — а вместе с ним вернётся и 404 после выкатки. Пояснение
    // обязано объяснять, что чанк переименовывается при выкатке.
    должен(
      /Имя чанка\s*—\s*с хешем содержимого|хешем содержимого/.test(ЭКРАН_ВСЕ),
      'рядом с try/catch не сказано, что чанк переименовывается при каждой выкатке',
    );
    должен(
      /удалить не удалось|delete_failed|t\('chars\.delete_failed'\)/.test(ЭКРАН_ВСЕ),
      'в файле пропал сам тост об удалении: правка ни при чём, если он исчез',
    );
  });
});