// Экстерьер ткацкой: четвёртое из шести зданий без экстерьера.
//
// ЧТО ЗАКРЕПЛЯЕТ. По точке (820, -260) не стояло ничего. Комплекс собран
// примитивами, и почти всё в нём выведено замером:
//
//   1. Площадка ровняется ПОСЛЕ ровнялки залива. Ровнялка залива имеет центр
//      (0, -820) и радиус 900, ровная часть её — 495 м, то есть полкарты, и
//      площадка выше неё молча получает чужой уровень. Таможня в 1853 м от
//      центра, ткацкая — в 1275, обе в зоне смешивания.
//   2. Уровень площадки равен измеренной медиане высот, и медиана там
//      ОТРИЦАТЕЛЬНАЯ: земля под ткацкой от -1.26 до -0.12, медиана -0.74.
//      Взят -0.7. Первый перебор уровня шёл от нуля и выдал нижнюю границу
//      диапазона вместо ответа: перебор, у которого весь массив по одну сторону
//      от диапазона, оптимума не находит.
//   3. Радиуса 46 НЕ хватило. Ровная часть была 25.3 м против полудиагонали
//      комплекса 24.2 м — запас 1.1 м, и замер показал перепад 0.187 м против
//      0.051 у таможни. Поднято до 50: ровная часть 27.5 м, запас 3.3.
//   4. Круг смешивания ткацки не достаёт до площадки дворца: 204 м против
//      суммы радиусов 134 м.
//   5. Начало местных координат — линия двери: в данных (820, -260) это сама
//      дверь, а выход (820, -256) на четыре метра дальше по плюс z.
//   6. Проём двери открыт: иначе к двери не подойти, а значит и не войти.
//   7. Проём забора есть ТОЛЬКО посередине передней стороны: общая версия
//      оставляла бы дыру и с боков, то есть двор проходим насквозь.
//   8. Вешалы для сушки не перекрывают подход от выхода к двери.
//   9. Окна настоящие проёмы, а не тёмные наклейки: станкам нужен свет, а
//      наклейка обманывает ровно до того момента, пока игрок не подойдёт.
//  10. Кладовая пристроена у самого порога — в интерьере мешки «ближе к двери».
//  11. Под комплексом сухо: центр на 2.4 м выше уровня моря.
//
// ЧЕГО ПРОВЕРКА НЕ ДЕЛАЕТ. Она не строит сцену и не мерит землю: terrain.ts
// требует document и canvas, в Node не импортируется, а копия функции измеряла
// бы саму себя. Ровность измерена инструментом по настоящему коду и записана
// в карте: дверь и точка выхода ровно -0.7000, отклонение 0.0000; перепад по
// двору 0.009, по мастерской 0.000, по комплексу 0.106; просвет в заборе 2.00 м.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

/** Блок постройки ткацкой внутри buildSettlements. */
function блокТкацки(): string {
  const начало = ТЕРРЕЙН.indexOf('  // ── Ткацкая с кладовой ──');
  must(начало > 0, 'в terrain.ts нет блока постройки ткацкой');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', начало);
  must(конец > начало, 'блок ткацки не найден по границе акведука');
  return ТЕРРЕЙН.slice(начало, конец);
}

describe('Ткацкая: площадка', () => {
  it('поставлена на месте записи интерьера', () => {
    must(
      /id: 'weaver',[^}]*dx: 820, dz: -260/.test(ИНТЕРЬЕРЫ),
      'запись ткацкой в интерьерах изменилась: площадка без неё окажется не там',
    );
    must(
      /export const WEAVER = \{ x: 820, z: -260,/.test(ТЕРРЕЙН),
      'площадка ткацкой не совпадает с записью интерьера (820, -260)',
    );
  });

  it('ровнялка стоит ПОСЛЕ ровнялки залива', () => {
    const код = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export function terrainHeight'),
      ТЕРРЕЙН.indexOf('const TERRAIN_SEG'),
    ).split('\n').filter((s) => !/^\s*(\/\/|\*|\/\*)/.test(s));
    const текст = код.join('\n');
    const залив = текст.indexOf('-820');
    const ткацка = текст.indexOf('WEAVER.x');
    must(залив > 0, 'ровнялка залива не найдена в terrainHeight');
    must(ткацка > 0, 'ровнялка ткацкой не найдена в terrainHeight');
    must(
      ткацка > залив,
      'площадка ткацкой поставлена выше ровнялки залива: она молча получит ' +
        'чужой уровень, ровно как дворец получил 2.367 вместо 2.2',
    );
  });

  it('уровень отрицательный и равен измеренной медиане', () => {
    // ЗЕМЛЯ ЗДЕСЬ ОТРИЦАТЕЛЬНАЯ. Перебор уровня от нуля выдал нижнюю границу
    // диапазона вместо ответа: сумма «срез плюс засыпка» на [0, 14] только
    // росла, потому что все высоты отрицательны.
    const m = /export const WEAVER = \{ x: 820, z: -260, radius: \d+, level: (-?[\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'уровень площадки ткацкой не объявлен');
    const уровень = Number(m![1]);
    must(
      уровень < 0,
      `уровень ${уровень} м положителен: земля под ткацкой отрицательна ` +
        '(от -1.26 до -0.12), и площадка станет насыпью в метр',
    );
    must(
      уровень >= -1.0 && уровень <= -0.5,
      `уровень ${уровень} м выходит за измеренную медиану -0.74`,
    );
  });

  it('запас ровной части достаточен: 46 не хватало', () => {
    // При радиусе 46 ровная часть была 25.3 м против полудиагонали комплекса
    // 24.2 м — запас 1.1 м, и замер дал перепад 0.187 м против 0.051 у
    // таможни. Поднято до 50.
    const m = /export const WEAVER = \{ x: 820, z: -260, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус площадки ткацкой не объявлен');
    const радиус = Number(m![1]);
    const ровная = радиус * 0.55;
    // Габарит: мастерская 16, плюс забор по 8 в стороны, плюс выступ 3.
    const полу = Math.hypot(16 / 2 + 8 + 3, 12 + 3);
    must(
      ровная - полу >= 2,
      `запас в ${(ровная - полу).toFixed(1)} м мал: при радиусе 46 он был ` +
        '1.1 м, и угол комплекса уезжал из-под ровнялки (перепад 0.187 м)',
    );
  });

  it('круги смешивания не достают до площадки дворца', () => {
    const ткацка = /export const WEAVER = \{ x: 820, z: -260, radius: (\d+)/.exec(ТЕРРЕЙН);
    const дворец = /export const PALACE = \{ x: 620, z: -299, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(ткацка && дворец, 'не найдены радиусы площадок ткацкой и дворца');
    const расстояние = Math.hypot(820 - 620, -260 - -299);
    const сумма = Number(ткацка![1]) + Number(дворец![1]);
    must(
      расстояние > сумма,
      `расстояние ${расстояние.toFixed(0)} м не больше суммы радиусов ` +
        `${сумма}: круг смешивания ткацки достаёт до площадки дворца`,
    );
  });

  it('под комплексом сухо', () => {
    must(!isWater(820, -260), 'под ткацкой вода: комплекс стоял бы в заливе');
    for (const [x, z] of [[804, -248], [836, -272], [820, -284]] as const) {
      must(!isWater(x, z), `вода в пределах комплекса, точка ${x},${z}`);
    }
  });
});

describe('Ткацкая: дверь и подход', () => {
  it('начало местных координат — линия двери', () => {
    must(
      /export const WEAVER = \{ x: 820, z: -260,/.test(ТЕРРЕЙН),
      'группа ткацкой должна стоять в точке двери из данных',
    );
    const блок = блокТкацки();
    must(
      /g\.position\.set\(WEAVER\.x, WEAVER\.level, WEAVER\.z\)/.test(блок),
      'группа ткацкой встала не в точку двери и не на уровень площадки',
    );
  });

  it('дверь кликабельная и ведёт в интерьер ткацкой', () => {
    const блок = блокТкацки();
    must(/doorBuilding: 'weaver'/.test(блок), 'у двери ткацкой нет doorBuilding');
    must(/doorAction: 'enter'/.test(блок), 'дверь ткацкой не ведёт внутрь');
    must(
      /doorName: t\('buildings\.weaver'\)/.test(блок),
      'дверь ткацкой подписана не тем названием',
    );
  });

  it('перед дверью нет коллайдера', () => {
    const блок = блокТкацки();
    must(
      /Math\.abs\(wx\) >= DOOR_W \/ 2 \+ 1\.6/.test(блок),
      'передний ряд коллайдеров мастерской не пропускает дверной проём: к двери ' +
        'не подойти, а значит и не войти',
    );
  });

  it('в проёме есть заглушка', () => {
    // Зала снаружи нет, и без заглушки сквозь проём видно небо.
    const блок = блокТкацки();
    must(/ТКАЦКАЯ_ЗАГЛУШКА/.test(блок), 'в проёме двери нет заглушки');
    must(
      /BoxGeometry\(DOOR_W, DOOR_H, 0\.3\)/.test(блок),
      'дверное полотно не по размеру проёма',
    );
  });
});

describe('Ткацкая: забор', () => {
  it('проём в заборе ТОЛЬКО посередине передней стороны', () => {
    // Общая версия оставляет дыру и с боков, то есть двор проходим насквозь.
    const блок = блокТкацки();
    must(
      /if \(Math\.abs\(fx\) >= проём \/ 2 \+ 0\.6\)/.test(блок),
      'условие проёма в заборе не сужает переднюю сторону: дыра окажется везде',
    );
    must(
      /const проём = 4\.0;/.test(блок),
      'ширина проёма в заборе не объявлена',
    );
  });

  it('боковые стороны забора глухие, без условия', () => {
    // Условие проёма на боковой стороне оставило бы дыру в боку двора.
    const блок = блокТкацки();
    must(
      /addCollider\(WEAVER\.x - заборX, WEAVER\.z \+ zx, 1\.0\);\r?\n\s*addCollider\(WEAVER\.x \+ заборX, WEAVER\.z \+ zx, 1\.0\);/.test(
        блок,
      ),
      'боковые стороны забора идут не сплошной цепочкой: в боку двора дыра',
    );
  });

  it('ворот у ткацки нет: это мастерская, а не застава', () => {
    // Ворота были бы враньём: застава здесь нет, и навес с досмотром на
    // таможне — единственное, что оправдывает проезд.
    const блок = блокТкацки();
    must(
      !/GATE|ВОРОТА/.test(блок),
      'у ткацки появились ворота: заставы здесь нет, и проезд не обоснован',
    );
    must(/ЗАБОР/.test(блок), 'у ткацки нет забора: двор не огорожен');
  });
});

describe('Ткацкая: двор объясняет интерьер', () => {
  it('окна настоящие проёмы, а не тёмные наклейки', () => {
    // Станки стоят у дальней стены и требуют света. Наклейка выглядит как окно
    // снаружи и обманывает, пока игрок не подойдёт вплотную.
    const блок = блокТкацки();
    must(
      /оконныйПроём\(HOUSE_H - 2\.0, 1\.8\)/.test(блок),
      'окна верхнего яруса не вынесены в отдельную функцию: их правка ' +
        'разъедется с вызовом',
    );
    must(
      /MAT\.dark/.test(блок) && /BoxGeometry\(1\.2, h, HOUSE_T \+ 0\.3\)/.test(блок),
      'окно сделано наклейкой, а не проёмом',
    );
    must(
      /BoxGeometry\(1\.55, h \+ 0\.3, HOUSE_T \+ 0\.15\)/.test(блок),
      'у окна нет откоса: проём читается как щель, а не как окно',
    );
  });

  it('окна есть и на дальней стене: свет в цех идёт оттуда', () => {
    // В интерьере станки стоят у дальней стены. Без окон на ней цех был бы
    // тёмным с обеих сторон.
    const блок = блокТкацки();
    must(
      /win\.position\.set\(-HOUSE_W \/ 2 \+ HOUSE_T \/ 2, HOUSE_H - 2\.0, z\)/.test(блок),
      'на дальней стене мастерской нет окон',
    );
  });

  it('кладовая пристроена у самого порога', () => {
    // В интерьере мешки и корзины «ближе к двери: занятого снегут первым, и
    // видно от входа». Двор обязан объяснять это снаружи.
    const блок = блокТкацки();
    must(
      /storeZ = zBack \+ STORE_D \/ 2 \+ 2\.4/.test(блок),
      'кладовая не пристроена к порогу: в интерьере мешки стоят у входа, ' +
        'а снаружи кладовая оказывается в глубине',
    );
    must(
      /const storeX = HOUSE_W \/ 2 \+ STORE_W \/ 2 - 0\.6;/.test(блок),
      'кладовая не сбоку от мастерской, а пристроена в её глубине',
    );
  });

  it('у кладовой есть свой проём, иначе мешки несут через стену', () => {
    const блок = блокТкацки();
    must(
      /const storeSeg = \(STORE_W - 1\.8\) \/ 2;/.test(блок),
      'передняя стена кладовой сплошная: проёма нет',
    );
    must(
      /Math\.abs\(sx2\) >= 0\.9 \+ 1\.4/.test(блок),
      'перед кладовой нет коллайдерного проёма: к нему не подойти',
    );
  });

  it('вешалы для сушки стоят в два ряда и не перекрывают подход', () => {
    // Отсюда на станках свисает готовый кусок ткани. Двор объясняет, откуда он.
    // Ряды стоят у дальней границы двора, а не посередине: посередине они
    // перекрыли бы путь от выхода к двери.
    const блок = блокТкацки();
    must(
      /const rackZ = \[zYard - racks\.gap \/ 2 - 1\.2, zYard - 1\.0\];/.test(блок),
      'вешалы поставлены не у дальней границы двора: они перекроют подход к двери',
    );
    must(/cloth/.test(блок), 'на вешалах нет провисающей ткани');
  });

  it('рулоны ткани лежат у кладовой и объясняют стеллаж в интерьере', () => {
    const блок = блокТкацки();
    must(/const РУЛОНЫ: \[number, number, number\]\[\]/.test(блок), 'рулоны не объявлены');
    must(
      /CylinderGeometry\(0\.36, 0\.36, 1\.9, 10\)/.test(блок),
      'рулон сделан не цилиндром: в сечении рулон круглый',
    );
    must(
      /addCollider\(WEAVER\.x \+ rx, WEAVER\.z \+ rz, 0\.6\);/.test(блок),
      'у рулонов нет коллайдеров: игрок проходит сквозь груз',
    );
  });

  it('столбы вешалов перекрыты, иначе игрок проходит сквозь перекладину', () => {
    const блок = блокТкацки();
    must(
      /addCollider\(\r?\n\s*WEAVER\.x \+ s \* \(racks\.w \/ 2 - 0\.3\),\r?\n\s*WEAVER\.z \+ rz,\r?\n\s*0\.45,\r?\n\s*\);/.test(
        блок,
      ),
      'у столбов вешалов нет коллайдеров: перекладина на высоте груди ' +
        'перестаёт держать и игрок проходит сквозь ткань',
    );
  });

  it('плита двора почти вровень, а не цоколь', () => {
    const m = /export const ТКАЦКАЯ_ДВОР = \{ t: ([\d.]+), подъём: ([\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'параметры плиты двора не объявлены');
    must(
      Number(m![2]) <= 0.1,
      `подъём плиты ${m![2]} м велик: двор читается как цоколь, а не как мощение`,
    );
  });
});
