// Гробница Шеиха: дверь одна и та же, зал собран под задание.
//
// ЧТО ЗАЩИЩАЕТ. Гробница — первая постройка, которая НЕ выглядит тем, чем
// является. Запись dungeon_shiraz_tomb обещает «один вход за попытку, проклятия,
// лут один на группу, таблицу рекордов», а механик из этого в проекте нет:
// счётчик попыток общий на все данжи (DUNGEON_ATTEMPTS_PER_DAY = 3), «лут один
// на группу» не встречается нигде.
//
// Здесь построено ТОЛЬКО место. Проверка ниже требует, чтобы это было сказано
// прямо в коде: без такой оговорки гробница выглядит готовой механикой, хотя
// механики за ней нет.
//
// ЧТО ПРОВЕРЯЕМ ПО-НАСТОЯЩЕМУ.
//   1. Место двери сухое — водой замерено настоящим waterMask.
//   2. Слот и дверь совпадают, все семнадцать построек держат слоты.
//   3. Саркофаг окружён решёткой: добыча видна, но не валяется на полу.
//   4. В коде сказано, что механик нет — иначе карта врёт.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';
import { waterMask } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

describe('Гробница: место подобрано измерением', () => {
  it('дверь стоит на сухой земле', () => {
    const def = INTERIORS.tomb;
    must(def !== undefined, 'на сервере нет записи tomb: дверь есть, а войти некуда');
    const влажность = waterMask(def.doorX, def.doorZ);
    must(
      влажность === 0,
      `у двери гробницы (${def.doorX}, ${def.doorZ}) влажность ${влажность.toFixed(4)}, ` +
        'а должно быть 0.0000: стена встанет в воду'
    );
  });

  it('проверка места не пустая: вода остаётся водой', () => {
    must(waterMask(-420, -160) > 0.9, 'озеро перестало быть водой: маска считается неверно');
    must(waterMask(620, 300) > 0.9, 'пруд перестал быть водой: маска считается неверно');
  });

  it('дверь не стоит на отпавшей точке', () => {
    // При замере (400, -1500) дало 1.0000 — это озеро.
    const def = INTERIORS.tomb!;
    must(!(def.doorX === 400 && def.doorZ === -1500), 'дверь переехала на точку, где озеро 1.0000');
  });

  it('гробница стоит отдельно от святилища, а не слиплась с ним', () => {
    const святилище = INTERIORS.shrine!;
    const гробница = INTERIORS.tomb!;
    const расстояние = Math.hypot(гробница.doorX - святилище.doorX, гробница.doorZ - святилище.doorZ);
    must(
      расстояние > 200,
      `гробница в ${расстояние.toFixed(0)} от святилища: это соседние постройки, а должны быть разными местами`
    );
  });
});

describe('Гробница: слот и дверь совпадают на клиенте и на сервере', () => {
  it('гробница держит шестнадцатый слот на обеих сторонах', () => {
    const ключи = Object.keys(INTERIORS);
    const слотСервер = ключи.indexOf('tomb');
    must(слотСервер === 16, `гробница на слоте ${слотСервер} из ${ключи.length}, а обязана быть шестнадцатой`);
    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    must(
      записи.indexOf('tomb') === слотСервер,
      `на клиенте гробница на слоте ${записи.indexOf('tomb')}, а на сервере ${слотСервер}`
    );
  });

  it('семнадцать построек держат свои слоты', () => {
    const ключи = Object.keys(INTERIORS);
    const ждём: [string, number, number][] = [
      ['stable', 0, 4000],
      ['barracks', 1, 4044],
      ['workshop', 2, 4088],
      ['tavern', 3, 4132],
      ['observatory', 4, 4176],
      ['science', 5, 4220],
      ['arena', 6, 4264],
      ['auction_house', 7, 4308],
      ['circus', 8, 4352],
      ['caravanserai', 9, 4396],
      ['fortress', 10, 4440],
      ['palace', 11, 4484],
      ['mosque', 12, 4528],
      ['weaver', 13, 4572],
      ['customs', 14, 4616],
      ['shrine', 15, 4660],
      ['tomb', 16, 4704],
    ];
    for (const [id, слот, комната] of ждём) {
      must(ключи[слот] === id, `на слоте ${слот} стоит ${ключи[слот]}, а ожидался ${id}`);
      must(
        INTERIORS[id as keyof typeof INTERIORS]!.roomCx === комната,
        `у ${id} roomCx ${INTERIORS[id as keyof typeof INTERIORS]!.roomCx}, а слот ${слот} даёт ${комната}`
      );
    }
  });

  it('координаты двери совпадают на клиенте и на сервере', () => {
    const def = INTERIORS.tomb!;
    const своя = /id: 'tomb', kind: 'tomb',[\s\S]{0,140}?dx: (-?\d+), dz: (-?\d+)/.exec(клиент);
    must(своя !== null, 'у гробницы на клиенте нет абсолютной двери');
    must(
      Number(своя![1]) === def.doorX && Number(своя![2]) === def.doorZ,
      `клиент рисует дверь в (${своя![1]}, ${своя![2]}), а сервер ждёт (${def.doorX}, ${def.doorZ})`
    );
  });

  it('комната не налезает на соседние', () => {
    const def = INTERIORS.tomb!;
    const чужие = Object.values(INTERIORS).filter((д) => д.id !== 'tomb');
    const тесные = чужие.filter((д) =>
      Math.abs(д.roomCx - def.roomCx) < 32 && Math.abs(д.roomCz - def.roomCz) < 32
    );
    must(тесные.length === 0, `комната налезает на: ${тесные.map((д) => д.id).join(', ')}`);
  });

  it('граница кармана покрывает новую комнату целиком', () => {
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+), z0: (-?\d+), z1: (\d+) \}/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    must(
      Number(прямоугольник![2]) >= INTERIORS.tomb!.roomCx + INTERIORS.tomb!.roomHalf,
      `правый край кармана ${прямоугольник![2]}, а правый край комнаты ` +
        `${INTERIORS.tomb!.roomCx + INTERIORS.tomb!.roomHalf}: под комнатой нет земли`
    );
  });
});

describe('Гробница: зал собран под задание, а не для украшения', () => {
  it('функция обстановки заведена и вызывается', () => {
    must(/function furnishTomb\(/.test(клиент), 'функции обстановки гробницы нет');
    must(/tomb: furnishTomb,/.test(клиент), 'гробница не прописан в выборе обстановки');
    must(
      /'tomb'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 900) ?? ''),
      'в типе BuildingKind нет гробницы'
    );
  });

  it('саркофаг на постаменте, и крышка сдвинута — гробницу вскрывали', () => {
    const начало = клиент.indexOf('function furnishTomb(');
    must(начало > 0, 'функция обстановки гробницы не найдена');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);
    must(тело.includes('box(5.4, 0.5, 2.8, M.stone'), 'постамента под саркофагом нет');
    must(тело.includes('box(2.8, 1.1, 1.3, M.stone'), 'самого саркофага нет');
    must(тело.includes('box(1.1, 0.22, 1.4, M.stone'), 'сдвинутой крышки нет: гробница выглядит нетронутой');
  });

  it('саркофаг окружён решёткой — добыча не лежит на полу', () => {
    const начало = клиент.indexOf('function furnishTomb(');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);
    must(/box\(0\.12, 2\.6, 0\.12, M\.iron/.test(тело), 'решётки вокруг саркофага нет: всё разнесут');
    must(тело.includes('box(7.2, 0.16, 0.16, M.iron'), 'поперечной планки решётки нет — прутья не держатся');
  });

  it('лестница вниз и ниши со свитками — по заданию', () => {
    const начало = клиент.indexOf('function furnishTomb(');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);
    // Ступени уходят вниз: убывающая высота.
    must(/for \(let i = 0; i < 5; i\+\+\) \{\s*\n\s*g\.add\(box\(3\.2, 0\.16, 0\.5, M\.stone, cx, FLOOR_Y \+ 0\.08 - i \* 0\.16/.test(тело),
      'лестницы вниз нет: в гробницу входят, а не спускаются');
    must(тело.includes('box(0.7, 2.4, 2, M.dark, px'), 'ниш нет');
    must(/sv\.rotation\.x = Math\.PI \/ 2;/.test(тело), 'свитки в нишах лежат не вдоль');
  });

  it('светильники не жаровни: в гробнице открытый огонь не уместен', () => {
    const начало = клиент.indexOf('function furnishTomb(');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);
    must(!/brazier\(/.test(тело), 'в гробнице стоят жаровни: открытый огонь в гробнице не уместен');
    must(/cyl\(0\.14, 2\.2, 0\.14, M\.iron/.test(тело), 'светильников на стойках нет');
  });
});

describe('Гробница: механик за ней нет, и это сказано', () => {
  it('в коде прямо написано, что механик не построено', () => {
    // Без этой оговорки гробница выглядит выполненной задачей: запись обещает
    // «один вход за попытку, проклятия, лут один на группу, рекорды», а механик
    // за ней нет. Проверка требует, чтобы это лежало в коде словами.
    const начало = клиент.indexOf('function furnishTomb(');
    const комментарий = клиент.slice(Math.max(0, начало - 900), начало);
    must(
      /нет|не построен|только место/i.test(комментарий),
      'рядом с функцией нет оговорки, что механик не построено: гробница выглядит готовой задачей'
    );
  });

  it('свой лимит попыток у гробницы есть, и это ровно один вход в сутки', () => {
    // Раньше здесь стояло обратное утверждение: «гробница лимит ещё не меняет».
    // Оно было честным, пока механики не было. Теперь механика сделана, и
    // проверка переписана: оставлять утверждение, которое противоречит коду,
    // было бы прямой неправдой.
    const данж = читать('server/src/data/dungeons.ts');
    const начало = данж.indexOf("'dungeon_shiraz_tomb': {");
    must(начало > 0, 'запись подземелья гробницы пропала: лимиту негде жив');
    must(
      /attemptsPerDay: 1,/.test(данж.slice(начало, начало + 3000)),
      'у гробницы нет своего лимита: она откроется трижды, как обычный данж'
    );
    // И общее число не должно поехать вместе с исключением.
    const сервис = читать('server/src/systems/DungeonService.ts');
    must(
      /const DUNGEON_ATTEMPTS_PER_DAY = 3;/.test(сервис),
      'общий лимит попыток изменился: у остальных данжей должно остаться 3'
    );
  });

  it('механики «лут один на группу» в проекте по-прежнему нет', () => {
    const сервис = читать('server/src/systems/DungeonService.ts');
    must(
      !/oncePerGroup|partyLootOnce/.test(сервис),
      '«лут один на группу» уже появился: гробница больше не половина задачи — обнови проверку'
    );
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.tomb === 'string' && словарь.buildings.tomb.length > 0,
        `в ${код}.json нет названия buildings.tomb`
      );
    }
  });
});