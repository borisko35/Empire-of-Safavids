// Надворный сарай с сеном.
//
// ЧТО БЫЛО (22 октября 2026, §314). В пригороде стояли кузница, склад и
// колодец (§310 ✓), но сарая не было: сено в пригороде лежало открытым стогом
// под небом, а двор без навеса выглядел так, будто стройка не доехала.
//
// ЧТО ТЕПЕРЬ. Сарай: четыре столба, наклонная крыша из ткани, стог сена под
// навесом и вилы в стене — видно, что сюда сено возят.
//
// ЧТО ПРОВЕРЯЕТСЯ. Столбы, крыша с наклоном, стог сена и вилы есть.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Надворный сарай', () => {
  it('четыре столба и наклонная крыша', () => {
    // Столбы: четыре.
    должен(
      /for \(const \[dx, dz\] of \[\[-1\.7, -1\.4\], \[1\.7, -1\.4\], \[-1\.7, 1\.4\], \[1\.7, 1\.4\]\] as const\) \{/.test(ТЕРРЕЙН),
      'у сарая не четыре столба',
    );
    // Крыша с наклоном: сено с неё стекает.
    должен(
      /const крышаСарая = new THREE\.Mesh\(new THREE\.BoxGeometry\(4\.2, 0\.14, 3\.6\), MAT\.clothRed\);/.test(ТЕРРЕЙН),
      'у сарая нет крыши',
    );
    должен(/крышаСарая\.rotation\.x = 0\.14;/.test(ТЕРРЕЙН), 'крыша сарая не наклонена');
  });

  it('стог сена под навесом и вилы в стене', () => {
    // Стог.
    должен(
      /const стогСарая = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.85, 1\.05, 1\.7, 10\), MAT\.sand\);/.test(ТЕРРЕЙН),
      'под навесом нет стога сена',
    );
    // Вилы: древко и зубья.
    должен(
      /const древко = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.035, 0\.04, 1\.7, 5\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'нет древка вил',
    );
    должен(
      /const зубья = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.34, 0\.05, 0\.12\), MAT\.dark\);/.test(ТЕРРЕЙН),
      'у вил нет зубьев',
    );
  });
});
