// Удар по площади и дальность навыков монстров.
//
// ЧТО БЫЛО. В данных у навыков игрока есть `aoe: true` и `aoeRadius` (5–15), у
// способностей монстров — `range` (2–12). Ни одно из этих полей не читалось нигде в
// серверном коде. «Дождь Стрел», «Гнев Шаха», «Танец Сема», «Экстаз Света»,
// «Засада на Шёлковом Пути», «Дворцовый Заговор», «Боевой Клич» и «Дымовая Бомба»
// били ровно одного врага, а ману и перезарядку тратили как за площадь. У всех
// монстров attackRange: 2, поэтому «Петля» (8) и «Буря Горизонта» (12) срабатывали
// вплотную. Тот же класс поломки, что и с мёртвой скоростью оружия.
//
// РЕШЕНИЯ ВЛАДЕЛЬЦА: радиус вокруг ЦЕЛИ; в PvP по площади бьётся только выбранная
// цель; способности монстров могут срабатывать со своей дистанции.
//
// ЧТО ПРОВЕРЯЕТСЯ ЧИСЛАМИ, А НЕ ТЕКСТОМ.
//  - Берутся настоящие навыки из данных: у скольких есть aoe, какие радиусы.
//  - Считается, кого накрывает круг радиуса из данных вокруг цели: ближайшие
//    да, дальние нет, главная цель в список не попадает.
//  - Проверяется, что монстр с навыком дальности 12 не бьёт кулаком с 12 метров и
//    что навык, не достающий до цели, не выбирается.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CombatService } from '../services/CombatService';
import { CharacterClass } from '../types/game.types';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СОКЕТ = читать('server/src/socket/GameSocketHandler.ts');
const ИИ = читать('server/src/systems/AISystem.ts');
const ПЕТЛЯ = читать('server/src/systems/GameLoop.ts');

const combat = new CombatService();

/** Навыки с пометкой «по площади» — из настоящей таблицы. */
const НАВЫКИ_ПЛОЩАДЬЮ = Object.values(CharacterClass).flatMap((класс) =>
  combat.getClassSkills(класс as CharacterClass).filter((н) => н.aoe === true)
);

/**
 * Текст ровно одного метода.
 *
 * Раньше окно задавалось в 6000 знаков от начала метода, и оно заезжало на
 * следующий метод: определения aoeTargetsFor и monsterAsCharacter стоят между
 * ветвями PvP и PvE, поэтому проверка «в PvP площади нет» находила её и ругалась
 * на собственную правку.
 */
function метод(имя: string): string {
  const начало = СОКЕТ.indexOf(`private async ${имя}(`);
  must(начало > 0, `не нашёл метод ${имя} в обработчике`);
  const конец = СОКЕТ.indexOf('\n  private ', начало + 1);
  return СОКЕТ.slice(начало, конец > 0 ? конец : СОКЕТ.length);
}

describe('Навыки по площади', () => {
  it('в данных есть навыки с площадью, и у каждого есть радиус', () => {
    must(
      НАВЫКИ_ПЛОЩАДЬЮ.length >= 8,
      `навыков с пометкой «по площади» всего ${НАВЫКИ_ПЛОЩАДЬЮ.length}: ` +
        'похоже, что все восемь обещанных навыков куда-то делись'
    );
    for (const н of НАВЫКИ_ПЛОЩАДЬЮ) {
      must(
        typeof н.aoeRadius === 'number' && н.aoeRadius > 0,
        `у навыка ${н.id} стоит aoe: true, но радиуса нет: «по площади» без круга ` +
          'означает «по всем» или «по одной цели», и оба варианта неверны'
      );
    }
  });

  it('круг действительно накрывает соседей, а не только цель', () => {
    // Считаем по-настоящему: цель в нуле, соседи вокруг. Радиус берётся из данных
    // навыка, поэтому проверка пересчитает вывод сама, если числа поменяются.
    const навык = НАВЫКИ_ПЛОЩАДЬЮ.find((н) => н.id === 'arch_rain');
    must(навык, 'не нашёл «Дождь Стрел» среди навыков с площадью');
    const радиус = навык!.aoeRadius!;

    const соседи = [
      { x: 0, z: 0, имя: 'цель' },
      { x: радиус - 0.5, z: 0, имя: 'почти в круге' },
      { x: радиус + 0.5, z: 0, имя: 'за кругом' },
      { x: -радиус * 2, z: радиус * 2, имя: 'далеко по диагонали' },
    ];

    const задетые = соседи.filter(
      (с) => с.имя !== 'цель' && Math.hypot(с.x, с.z) <= радиус
    );
    must(
      задетые.length === 1 && задетые[0].имя === 'почти в круге',
      `радиус ${радиус} накрывает ${задетые.map((с) => с.имя).join(', ') || 'никого'}: ` +
        'площадь должна брать соседей внутри круга и не трогать тех, кто снаружи'
    );
  });

  it('бой по площади выбирает цели из данных и бьёт их', () => {
    must(
      /aoeRadius/.test(СОКЕТ) && /навык\?\.aoe/.test(СОКЕТ),
      'обработчик не смотрит в поля aoe и aoeRadius: площадь не считается'
    );
    must(
      /this\.aoeTargetsFor\(attacker, action, monsterCtx, ai\)/.test(СОКЕТ),
      'в ветви PvE нет шага площади'
    );
    must(
      /for \(const цель of задетые\)/.test(СОКЕТ),
      'цели площади не перебираются: всё бьёт одну'
    );
    must(
      /ai\.takeDamage\(цель\.instanceId/.test(СОКЕТ),
      'урон по целям площади не наносится'
    );
  });

  it('главная цель в список площади не попадает дважды', () => {
    must(
      /if \(ctx\.instanceId === центр\.instanceId\) continue;/.test(СОКЕТ),
      'главная цель не исключается из списка площади: по ней придётся два раза'
    );
  });

  it('в PvP по площади не достаётся никто, кроме выбранной цели', () => {
    // Решение владельца: переделывать PvP без отдельного кулдауна опасно, а молча
    // задевать игроков — тем более. Площадь живёт только в ветви PvE.
    const кусокPvE = метод('combatPlayerVsMonster');
    const кусокPvP = метод('combatPlayerVsPlayer');
    must(
      !/aoeTargetsFor/.test(кусокPvP),
      'площадь появилась в PvP: так решить нельзя, удар по площади в PvP должен ' +
        'остаться по выбранной цели'
    );
    must(/aoeTargetsFor/.test(кусокPvE), 'в ветви PvE нет шага площади');
  });

  it('за каждой убитой целью площади идут та же награда и тот же путь', () => {
    // Копия блока смерти рядом с шагом площади рано или поздно разошлась бы с
    // оригиналом: опыт, лут, квесты, задания дня и осада живут в разных местах.
    must(
      /private async rewardMonsterKill\(/.test(СОКЕТ),
      'награда за убийство монстра не вынесена в отдельный метод'
    );
    must(
      /if \(добитый\) await this\.rewardMonsterKill\(socket, attacker, цель\);/.test(СОКЕТ),
      'цели площади не получают награду за убийство'
    );
    must(
      /if \(died\) await this\.rewardMonsterKill\(socket, attacker, monsterCtx\);/.test(СОКЕТ),
      'главная цель перестала получать награду: значит, вынос что-то сломал'
    );
    must(
      (СОКЕТ.match(/const def = monsterCtx\.definition;/g) || []).length === 1,
      'объявление def разъехалось по файлу: блок смерти и новый метод должны брать ' +
        'описание монстра в одном месте'
    );
  });
});

describe('Случайный выбор способности', () => {
  it('вес способности — урон, но не меньше единицы', () => {
    must(
      /return Math\.max\(1, Number\(skill\.damage\) \|\| 0\);/.test(ИИ),
      'вес способности считается неверно: клич и рык без урона должны хоть иногда выпадать'
    );
    must(
      /let roll = Math\.random\(\) \* суммаВесов;/.test(ИИ),
      'выбор способности снова детерминированный: разнообразия не будет'
    );
    must(
      !/available\.sort\(\(a, b\) => b\.damage - a\.damage\)\[0\]/.test(ИИ),
      'монстры снова всегда бьют самой сильной способностью'
    );
  });

  it('способность без урона не становится недоступной', () => {
    // Крик, рык, призыв: урон 0. При весе ровно по урону они выпадали бы с
    // вероятностью ноль, и поле снова стало бы мёртвым.
    const вес = (урон: number) => Math.max(1, Number(урон) || 0);
    must(вес(0) === 1, 'способность без урона получила вес ноль и не выпадет никогда');
    must(вес(1320) === 1320, 'вес сильной способности искажён');
    must(вес(Number.NaN) === 1, 'битое значение урона превращает вес в ноль');
  });
});

describe('Площадь монстров: решение владельца', () => {
  it('по группе бьют только элитные и боссы', () => {
    // Решение владельца: обычный разбойник не должен снимать пати, а у
    // «Землетрясения» (радиус 50) и бури Симурга (40) смысл появляется.
    must(
      /if \(тип !== 'elite' && тип !== 'boss' && тип !== 'world_boss'\) return 0;/.test(ПЕТЛЯ),
      'обычные монстры снова могут бить по группе: один разбойник снимал пати'
    );
    must(
      /private monsterAoeRadius\(/.test(ПЕТЛЯ),
      'правило «кому можно бить по группе» не записано в коде'
    );
  });

  it('центр площади — цель, а не сам монстр', () => {
    must(
      /сосед\.position\.x - target\.position\.x/.test(ПЕТЛЯ) &&
        /сосед\.position\.z - target\.position\.z/.test(ПЕТЛЯ),
      'площадь считается от монстра, а не от цели: удар накрывает не то место'
    );
  });

  it('у каждого задетого своя защита и своя реакция', () => {
    // Иначе площадь была бы сильнее любого одиночного удара: пять целей получили
    // бы полный урон без учёта их брони, уклонения и блока.
    must(
      /жертва\.stats\.endurance \* 0\.75/.test(ПЕТЛЯ),
      'у задетых площадью не считается их собственная защита'
    );
    must(
      /getIncomingMultiplier\(сосед\.id\)/.test(ПЕТЛЯ),
      'у задетых площадью не считается их уклонение и блок'
    );
  });

  it('эффект остаётся только на цели', () => {
    // Замедление и оглушение по всей группе из монстра — отдельное решение
    // владельца и отдельный пересмотр баланса. Здесь площадь означает урон.
    must(
      /debuff: null,/.test(ПЕТЛЯ) && /if \(план && isWorthApplying/.test(ПЕТЛЯ),
      'эффект навешивается на всю группу или слетел с цели: и то и другое нужно решение владельца'
    );
  });

  it('способности с пометкой «по площади» есть, и обычные монстры их не применяют', () => {
    const флагВТаблице = /aoe: true/.test(читать('server/src/data/monsters.ts'));
    must(флагВТаблице, 'в данных монстров не осталось способностей с пометкой aoe');
    must(
      /aoeRadius/.test(СОКЕТ) && /навык\?\.aoe/.test(СОКЕТ),
      'площадь считается только в ветви PvE игрока: решение владельца для монстров ' +
        'должно быть записано здесь же, иначе правило разъедется'
    );
  });

  it('в ветви PvP игрока площади по-прежнему нет', () => {
    // Площадь игрока бьёт только монстров вокруг цели. Других игроков она не
    // трогает: решение владельца, отдельный кулдаун на массовый урон не сделан.
    must(
      !/aoeTargetsFor/.test(метод('combatPlayerVsPlayer')),
      'площадь появилась в PvP: по решению владельца там бьётся только выбранная цель'
    );
  });
});

describe('Дальность навыков монстров', () => {
  it('навык выбирается под расстояние, а не «какой сильнее»', () => {
    must(
      /return расстояние <= Math\.max\(skill\.range, ctx\.definition\.attackRange\);/.test(ИИ),
      'навык выбирается без учёта расстояния: «Петля» с 8 метров сработает вплотную'
    );
    must(
      /this\.selectSkill\(ctx, now, дистанция\)/.test(ИИ),
      'выбор навыка не получает расстояние до цели'
    );
  });

  it('способности «вокруг себя» не стали недостижимыми', () => {
    // Десять способностей имеют range: 0 — это «у земли под ногами», а не
    // «недостаточно далеко». Строгое сравнение с нулём убивало их навсегда:
    // расстояние до цели никогда не равно нулю. Поэтому сравнение идёт с
    // максимумом из дальности навыка и собственной дистанции монстра.
    const вокругСебя = /range: 0[,}]/g;
    const всего = читать('server/src/data/monsters.ts').match(вокругСебя) || [];
    must(
      всего.length >= 10,
      `в данных способностей с range: 0 всего ${всего.length}: проверка перестала бы ` +
        'ловить случай, если такие способности переименуют или перепишут'
    );
    must(
      !/return расстояние <= skill\.range;/.test(ИИ),
      'сравнение идёт только с дальностью навыка: все способности «вокруг себя» ' +
        'с range: 0 стали бы недостижимы навсегда'
    );
  });

  it('бой начинается на расстоянии готового навыка, а не вплотную', () => {
    must(
      /Math\.max\(ctx\.definition\.attackRange, this\.maxSkillRange\(ctx, now\)\)/.test(ИИ),
      'состояние боя начинается только на attackRange: дальности навыков не значили ничего'
    );
  });

  it('базовая атака — только вплотную, иначе монстр сближается', () => {
    // Иначе навык на перезарядке превращался бы в удар кулаком с 12 метров.
    must(
      /if \(дистанция <= ctx\.definition\.attackRange\) \{/.test(ИИ),
      'базовая атака бьёт с любой дистанции: монстр достаёт через полкарты'
    );
    must(
      /type: 'move', destination: ctx\.targetPosition/.test(ИИ),
      'недостающий монстр не сближается: он стоит и не делает ничего'
    );
  });

  it('комментарий о выборе навыка соответствует коду', () => {
    // Раньше здесь стояло «случайный выбор с весом по урону», а код брал самый
    // сильный: комментарий врал. Теперь код случайный, и комментарий должен
    // говорить именно об этом — иначе следующий автор поверит ему и вернёт
    // детерминированный выбор, посчитав это «как задумано».
    must(
      !/Из готовых берётся самый сильный/.test(ИИ),
      'комментарий снова описывает выбор самой сильной способности, а код уже случайный'
    );
    must(
      /Случайный выбор с весом по урону/.test(ИИ),
      'в коде нет описания случайного выбора: поведение изменилось, а комментарий нет'
    );
    must(
      /roll -= this\.весНавыка\(skill\);/.test(ИИ) && /if \(roll <= 0\) return skill;/.test(ИИ),
      'взвешенный розыгрыш не собран: кубик не сужает список, а возвращает первый'
    );
  });
});