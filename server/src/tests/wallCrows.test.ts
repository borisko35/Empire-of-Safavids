// Вороны на парапете стены Исфахана.
//
// ЧТО БЫЛО (22 октября 2026, §309). Стена стояла пустой в вышине: город с
// высоты читался как каменное кольцо без жизни. Вороны в мире каркали только
// зимой (§262).
//
// ЧТО ТЕПЕРЬ. По парапету сидят четырнадцать ворон — чёрные, с клювом, хвостом
// и тонкими ногами. Места — по детерминированному генератору: после
// перезагрузки страницы вороны должны сидеть там же.
//
// ЧТО ПРОВЕРЯЕТСЯ. Ворона собрана из тела-капсулы, головы, клюва, хвоста и
// ног; ворон четырнадцать; они сидят на высоте парапета и по детерминированным
// местам.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Вороны на парапете стены', () => {
  it('ворона: тело, голова, клюв, хвост, ноги', () => {
    должен(/const ворона = \(/.test(ТЕРРЕЙН), 'нет сборщика вороны');
    // Тело — капсула, а не шарик.
    должен(
      /const тело = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.09, 0\.26, 3, 8\), перо\);/.test(ТЕРРЕЙН),
      'тело вороны — не капсула',
    );
    // Голова, клюв, хвост, ноги.
    должен(/const голова = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.075, 8, 6\), перо\);/.test(ТЕРРЕЙН),
      'у вороны нет головы');
    должен(/new THREE\.ConeGeometry\(0\.022, 0\.11, 5\)/.test(ТЕРРЕЙН), 'у вороны нет клюва');
    должен(/const хвост = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.06, 0\.05, 0\.22\), перо\);/.test(ТЕРРЕЙН),
      'у вороны нет хвоста');
    должен(/const нога = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.008, 0\.008, 0\.09, 4\), перо\);/.test(ТЕРРЕЙН),
      'у вороны нет ног');
  });

  it('ворон четырнадцать, и сидят они на парапете по детерминированным местам', () => {
    должен(/for \(let i = 0; i < 14; i\+\+\) \{/.test(ТЕРРЕЙН), 'ворон не четырнадцать');
    // Высота — парапет стены.
    должен(
      /const y = земляПод\(phi\) \+ WALL_TOP \+ 0\.05;/.test(ТЕРРЕЙН),
      'вороны сели не на парапете',
    );
    // Места — по хэшу, а не по случайному числу.
    должен(/const phi = \(i \/ 14\) \* Math\.PI \* 2 \+ hash2\(i, 31\) \* 0\.35;/.test(ТЕРРЕЙН),
      'места ворон считаются случайно: после перезагрузки они съедут');
    // И вороны добавлены в город.
    должен(/city\.add\(ворона\(x, y, z, phi \+ Math\.PI \/ 2\)\);/.test(ТЕРРЕЙН), 'вороны не добавлены в город');
  });
});
