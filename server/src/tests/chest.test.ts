// Сундук: модель и место у шатра в базарном квартале.
//
// Двадцать второй пакет из Assets.
//
// ЧТО ЛОВИТСЯ И ПОЧЕМУ ТАК.
// 1. Файл в сборке и совпадает с манифестом.
// 2. Модель в метрах. Исходник приехал 366 единицами в длину — это остов
//    длиной в полкилометра. Верхняя граница ловит именно это.
// 3. Рост сундука 0.45-0.75 м: ниже — коробка из-под обуви, выше — погреб.
// 4. ДЛИНА БОЛЬШЕ ВЫСОТЫ В ПОЛТОРА РАЗА. Это ловит поворот модели: импортёр
//    OBJ в Blender по умолчанию считает файл Y-вверх и кладёт сундук на бок.
//    На глаз это незаметно — у сундука две меньшие стороны почти равны, — но
//    отношение длин по осям остаётся верным и после поворота, и потому
//    единственная проверка, которая отличает «метр в длину» от «метр в высоту».
// 5. Основанием на ноль, а не висячий и не ушедший под землю.
// 6. Пять материалов: три деревянных и два металлических. Сундук из пяти
//    одинаковых серых частей читается как кирпич.
// 7. ДЕРЕВО НЕ МЕТАЛЛИЧЕСКОЕ, ОБРУЧИ МЕТАЛЛИЧЕСКИЕ. Обратное тоже ловится:
//    дерево, проводящее ток, выглядит как покрашенный металл.
// 8. Пять примитивов — по мешу на примитив.
// 9. ДЕСЯТЬ ТЕКСТУР: альбедо и нормаль на каждый материал. Без карт дерево
//    остаётся серым кубом, а на пакет потрачено 110 МБ карт впустую.
// 10. Карты не гигантские: 4096 на сундук — это сто мегабайтек на деталь.
// 11. Без скелета и анимации.
// 12. В узлах нет поворота, масштаба и сдвига.
// 13. Файл не раздутый: 1.29 МБ, а не 2.25 — нормали в 256, не в 512.
//
// Место:
// 14. Мир строит сундуки.
// 15. Ровно два, и они не слиплись.
// 16. Оба вне коллайдера шатра и не прижаты к нему.
// 17. На суше, включая весь след сундука, а не только точку.
// 18. По коллайдеру на сундук, и он покрывает метровую длину с запасом.
