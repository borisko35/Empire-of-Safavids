// Земля не должна остаться одним ровным тоном.
//
// ЧТО ЗДЕСЬ ЛОВИТСЯ. У рельефа до этого не было ни карты цвета, ни карты
// нормалей: только вершинные цвета по биомам. Цвет — есть, поверхности — нет,
// и земля вблизи читалась картоном. Это не «вкусовщина»: у земли пропали
// признаки поверхности — зерно, камешки, наклон под светом, — и половина кадра
// превратилась в один ровный массив.
//
// ПОЧЕМУ ПРОВЕРКИ ТЕКСТОВЫЕ. Собрать материалы и карты можно только в браузере
// (нужен canvas), поэтому здесь сторож на структуру: карты есть, они идут в
// материал, нормаль собрана как карта данных, а плитка задана в МЕТРАХ. Числа
// кадра снимаются в живом мире, как и у G-buffer (§216).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const читать = (путь: string): string =>
  readFileSync(join(корень, путь), 'utf8').replace(/\r\n/g, '\n');

const ТЕКСТУРЫ = читать(join('client', 'src', 'app', 'game3d', 'textures.ts'));
const ТЕРРЕЙН = читать(join('client', 'src', 'app', 'game3d', 'terrain.ts'));

describe('У земли есть детальная карта и карта нормалей', () => {
  it('плитка детали задана в метрах, а не «сколько-нибудь раз»', () => {
    must(
      /export const GROUND_TILE_M = \d+(\.\d+)?/.test(ТЕКСТУРЫ),
      'в textures.ts нет GROUND_TILE_M: размер плитки детали земли не задан, '
      + 'и повтор карты будет случайным при правке мира',
    );
    const м = /export const GROUND_TILE_M = (\d+(?:\.\d+)?)/.exec(ТЕКСТУРЫ);
    const плитка = Number(м?.[1]);
    // 1 м — крупинка размером с ладонь (мыло вблизи), 16 м — вблизи видно
    // одну и ту же плитку под ногами.
    must(
      плитка >= 1 && плитка <= 16,
      `плитка детали земли ${плитка} м вне разумных пределов: у ног либо мыло, `
      + 'либо видимый повтор одной картинки',
    );
    // Повтор считается от размера мира: при росте мира плитка обязана
    // остаться в метрах, иначе земля снова станет крупной и плоской.
    must(
      /SIZE \/ GROUND_TILE_M/.test(ТЕРРЕЙН),
      'повтор карты детали не считается от размера мира: при изменении мира '
      + 'плитка уедет по масштабу',
    );
  });

  it('цвет и нормаль строятся из ОДНОЙ карты высот', () => {
    // Иначе бугорок и его освещение окажутся в разных местах, и поверхность
    // прочтётся шумом: цвет рисует одно, нормаль светит другое.
    must(
      /function groundHeightCanvas\(/.test(ТЕКСТУРЫ),
      'в textures.ts нет общей карты высот земли',
    );
    const цвет = /export function groundDetailTexture\([\s\S]*?\n}/.exec(ТЕКСТУРЫ)?.[0] ?? '';
    const нормаль = /export function groundDetailNormalTexture\([\s\S]*?\n}/.exec(ТЕКСТУРЫ)?.[0] ?? '';
    must(цвет.length > 0, 'в textures.ts нет groundDetailTexture');
    must(нормаль.length > 0, 'в textures.ts нет groundDetailNormalTexture');
    must(
      /groundHeightCanvas\(\)/.test(цвет),
      'карта цвета земли не берёт общую высоту: цвет и рельеф разойдутся',
    );
    must(
      /groundHeightCanvas\(\)/.test(нормаль),
      'карта нормалей земли не берёт общую высоту: свет и рисунок разойдутся',
    );
  });

  it('нормаль собирается как карта ДАННЫХ, а не цвета', () => {
    // SRGB у карты нормалей — это наклон поверхности на 39 градусов. Ровно
    // такая беда уже была у камня и воды (§209, dataTextureColorSpace).
    const нормаль = /export function groundDetailNormalTexture\(([\s\S]*?)\n}/.exec(ТЕКСТУРЫ)?.[1] ?? '';
    must(нормаль.length > 0, 'в textures.ts нет groundDetailNormalTexture');
    must(
      /return toDataTexture\(/.test(нормаль),
      'карта нормалей земли собирается через toTexture: она получит '
      + 'SRGBColorSpace, и земля будет освещена как наклонённая на 39 градусов',
    );
    must(
      !/return toTexture\(/.test(нормаль),
      'карта нормалей земли отдаётся как карта цвета',
    );
  });

  it('материал рельефа использует обе карты и макро-слой', () => {
    const материал = /const материал = new THREE\.MeshStandardMaterial\(\{/.exec(ТЕРРЕЙН);
    must(материал, 'в buildTerrain материал рельефа не назван «материал»');
    must(
      /map: groundDetailTexture\(/.test(ТЕРРЕЙН),
      'у материала земли нет карты цвета: земля остаётся одним ровным тоном',
    );
    must(
      /normalMap: groundDetailNormalTexture\(/.test(ТЕРРЕЙН),
      'у материала земли нет карты нормалей: свет не показывает рельеф',
    );
    // Макро-слой обязателен рядом с деталью: одна плитка на 6350 м площади
    // читается решёткой повтора за секунды.
    must(
      /addMacroLayer\(материал, macroTexture\(\)/.test(ТЕРРЕЙН),
      'у земли нет макро-слоя: детальная плитка читается решёткой повтора',
    );
  });
});
