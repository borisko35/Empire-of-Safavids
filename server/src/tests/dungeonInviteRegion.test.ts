// Приглашение в заход зовёт игроков региона, а не только друзей.
//
// ЧТО БЫЛО ИЗМЕРЕНО. Панель подземелья брала список приглашаемых из api.friends()
// и показывала только принятых друзей онлайн. При этом заход рассчитан на
// 8-20 человек (maxPlayers в данных подземелий: 5, 10, 20, 8, 8). То есть
// набрать группу можно было только из тех, с кем уже дружишь, а случайного
// игрока рядом позвать было нечем: маршрут принимал userId, а не characterId.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ:
//   1. сервер отдаёт список игроков региона с именами (без имён панель показала
//      бы UUID);
//   2. список исключает того, кто спрашивает, и ограничен;
//   3. приглашение принимает characterId и по-прежнему принимает userId друга;
//   4. сервер проверяет регион приглашённого в обоих путях;
//   5. шард берётся у сервера, а не из запроса;
//   6. клиент зовёт именно этот список, а не список друзей.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const безКомментариев = (исходник: string): string =>
  исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const маршруты = читать('server/src/routes/game.ts');
const маршрутыКод = безКомментариев(маршруты);
const сервис = читать('server/src/systems/DungeonService.ts');
const сервисКод = безКомментариев(сервис);
const панели = читать('client/src/app/panels.ts');
const api = читать('client/src/app/api.ts');

describe('Список игроков региона: сервер отдаёт', () => {
  it('маршрут есть и требует своего персонажа', () => {
    must(
      /gameRouter\.get\(\s*'\/players'/.test(маршрутыКод),
      'маршрута списка игроков региона нет: пригласить можно только друзей'
    );
    must(
      /requireCharacterOwnership\(\)[\s\S]{0,400}char\.userId !== req\.userId/.test(маршрутыКод),
      'маршрут не проверяет, что персонаж принадлежит игроку: чужой регион можно запросить'
    );
  });

  it('в списке есть имя, уровень и класс', () => {
    must(
      /SELECT id, name, level, class FROM characters WHERE id = ANY/.test(маршрутыКод),
      'список отдаёт только идентификаторы: игрок не узнает, кого зовёт'
    );
    must(
      /name: с\.name/.test(маршрутыКод) && /level: Number\(с\.level\)/.test(маршрутыКод),
      'в ответе нет имени и уровня игрока'
    );
  });

  it('себя в списке нет, и список ограничен', () => {
    must(
      /ids\.filter\(\(id\) => id !== characterId\)/.test(маршрутыКод),
      'запрашивающий попадает в свой же список игроков региона'
    );
    must(
      /\.slice\(0, \d+\)/.test(маршрутыКод),
      'список региона ничем не ограничен: в людном регионе поедет вся база'
    );
  });

  it('шард берётся у сервера, а не из запроса', () => {
    // У персонажа шарда нет, он живёт в сокете. Если бы шард брался из запроса,
    // игрок назвал бы чужой регион и получил бы чужой список.
    must(
      /req\.query\.shardId|req\.body\.shardId/.test(маршрутыКод) === false,
      'маршрут доверяет шарду из запроса: игрок может запросить чужой регион'
    );
    must(
      /regionShardResolver/.test(маршрутыКод) && /getActiveShards\(\)/.test(маршрутыКод),
      'шард не берётся у сервера через список активных шардов'
    );
  });

  it('список берётся из Redis по региону персонажа', () => {
    must(
      /getPlayersInRegion\(shardId, char\.region\)/.test(маршрутыКод),
      'список берётся не по региону персонажа, а по чему-то другому'
    );
  });
});

describe('Приглашение принимает игрока региона и друга', () => {
  it('поиск идёт сначала по персонажу, потом по другу', () => {
    // Оба пути нужны: панель шлёт characterId из списка региона, а старый
    // вызов с friendUserId должен продолжать работать.
    must(
      /WHERE id = \$1 AND region = \$2/.test(сервисКод),
      'приглашение не ищет персонажа по characterId: игрока из региона позвать нельзя'
    );
    must(
      /WHERE user_id = \$1 AND region = \$2/.test(сервисКод),
      'приглашение друга по userId перестало работать'
    );
  });

  it('регион проверяется в обоих путях', () => {
    const регионПроверок = (сервисКод.match(/AND region = \$2/g) || []).length;
    must(
      регионПроверок >= 2,
      `регион проверяется в ${регионПроверок} путях, а их два: игрока из другого ` +
        'региона можно было бы позвать в заход'
    );
  });

  it('маршрут принимает targetId и прежний friendUserId', () => {
    must(
      /req\.body\.targetId \?\? req\.body\.friendUserId/.test(маршрутыКод),
      'маршрут принимает только одно имя поля: старый вызов с friendUserId перестанет работать'
    );
    must(
      /if \(!targetId\) \{[\s\S]{0,80}targetId is required/.test(маршрутыКод),
      'маршрут зовёт сервис без получателя и падает'
    );
  });

  it('защита захода не ослабла', () => {
    must(
      /session\.leaderId !== inviterId/.test(сервисКод),
      'пригласить может не только лидер'
    );
    must(
      /session\.members\.size >= \(DUNGEONS_DATABASE\[session\.dungeonId\]\?\.maxPlayers \|\| 1\)/.test(сервисКод),
      'приглашение перестало проверять размер захода: в заход пустят сверх maxPlayers'
    );
    must(
      /session\.members\.has\(персонаж\.id\)/.test(сервисКод),
      'в заход можно пригласить того, кто уже внутри'
    );
  });
});

describe('Панель зовёт игроков региона', () => {
  it('клиент спрашивает список региона, а не список друзей', () => {
    must(
      /api\.regionPlayers\(cid\(\)\)/.test(безКомментариев(панели)),
      'панель по-прежнему зовёт друзей: случайного игрока региона позвать нельзя'
    );
    must(
      /api\.friends\(\)/.test(безКомментариев(панели)),
      'список друзей исчез совсем: друзей перестало быть видно вовсе'
    );
  });

  it('приглашение уходит с идентификатором игрока', () => {
    must(
      /api\.dungeonInvite\(cid\(\), игрок\.id\)/.test(безКомментариев(панели)),
      'приглашение уходит не по идентификатору игрока из списка'
    );
    must(!/api\.dungeonInvite\(cid\(\), друг\.friendId\)/.test(панели),
      'приглашение всё ещё уходит по friendUserId: игрок из региона не примет');
  });

  it('в строке видно, кого зовут', () => {
    must(
      /\$\{игрок\.name\}/.test(панели),
      'строка приглашения не показывает имя игрока'
    );
    must(
      /\$\{игрок\.level\}/.test(панели),
      'строка приглашения не показывает уровень игрока'
    );
  });

  it('запрос списка объявлен в клиентском api', () => {
    must(
      /regionPlayers: \(characterId: string\)/.test(api),
      'в клиентском api нет regionPlayers: панель зовёт несуществующий метод'
    );
    must(
      /\/api\/game\/players\?characterId=/.test(api),
      'regionPlayers ходит не на маршрут списка игроков'
    );
  });
});
