// Один декодер Draco на клиент, и стенд, который не врёт о мире (§330).
//
// ЧТО БЫЛО. Две отдельные поломки, обе выглядят как «мир не такой, как в коде».
//
// 1. Каждый загрузчик создавал свой DRACOLoader: `loadDecorModel` — на каждую
//    из 177 моделей декора, интерьеры — на трон, кафедру и камень, realRig и
//    animalModels — по одному на модуль. DRACOLoader держит рабочие потоки, и
//    после пары сотен своих декодеров браузер перестаёт поднимать новые:
//    разбор Draco молча не начинается, обещание не сбывается ни успехом, ни
//    ошибкой. Модель просто не появляется.
//
// 2. Стенд `world-check.html` снимал кадр ровно через `wait` от старта. Модели
//    декора приходят по сети уже после постройки мира, и кадр показывал
//    недостроенный мир. Из-за этого §329 записал ложный недочёт «крона не
//    рисуется, хотя тень есть» — дерево не успевало приехать.
//
// ЧТО ПРОВЕРЯЕТСЯ. Декодер один и общий; своих `new DRACOLoader()` в клиенте
// больше нет; стенд ждёт, пока число мешей перестанет меняться, а не только
// таймер; деревья вдоль переулков стоят в коде и не сняты.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Все .ts клиента: ищем свои декодеры по всему дереву, а не по памяти. */
function всеИсходники(папка: string): { путь: string; код: string }[] {
  const итог: { путь: string; код: string }[] = [];
  for (const имя of readdirSync(папка)) {
    const путь = join(папка, имя);
    if (statSync(путь).isDirectory()) {
      итог.push(...всеИсходники(путь));
      continue;
    }
    if (!имя.endsWith('.ts')) continue;
    итог.push({ путь, код: readFileSync(путь, 'utf-8') });
  }
  return итог;
}

describe('Декодер Draco', () => {
  it('создаётся в одном месте и отдаётся всем', () => {
    const draco = читать('client/src/app/game3d/draco.ts');
    должен(/let общий: DRACOLoader \| null = null;/.test(draco),
      'декодер не кешируется: каждый загрузчик снова поднимает свои потоки');
    должен(/export function декодерDraco\(\): DRACOLoader \{/.test(draco),
      'нет общей точки выдачи декодера');

    const свои: string[] = [];
    for (const { путь, код } of всеИсходники(join(корень, 'client/src'))) {
      if (путь.endsWith(join('game3d', 'draco.ts'))) continue;
      if (/new DRACOLoader\(\)/.test(код)) свои.push(путь);
    }
    должен(свои.length === 0,
      'свой DRACOLoader снова заведён: ' + свои.map((p) => p.split('game3d')[1]).join(', ')
      + ' — это лишние рабочие потоки и молчащие модели');
  });

  it('все загрузчики берут один общий декодер', () => {
    // §344: ВТОРОЙ декодер пробовали и убрали. Замер: с ним перестали
    // грузиться ВСЕ персонажи (citizen3 тоже), а с общим — грузятся все.
    // Причина висящих моделей была не в нехватке потоков, а в порядке
    // загрузки: персонажи стояли в очереди за декором (§343).
    for (const файл of ['terrain.ts', 'realRig.ts', 'animalModels.ts', 'interiors.ts']) {
      const код = читать('client/src/app/game3d/' + файл);
      должен(/setDRACOLoader\(декодерDraco\(\)\)/.test(код),
        `${файл} не берёт общий декодер Draco`);
    }
    const драко = читать('client/src/app/game3d/draco.ts');
    должен(!/декодерПерсонажей/.test(драко),
      'вернулся второй декодер: с ним персонажи перестают грузиться');
  });
});

describe('Стенд не врёт о мире', () => {
  const стенд = читать('client/src/app/world-check.ts');

  it('кадр снимается по остановке мира, а не по таймеру', () => {
    должен(/function мешейВМире\(\): number \{/.test(стенд),
      'стенд не считает меши: кадр может быть снят до прихода моделей');
    должен(/if \(стабильных >= 3\) \{/.test(стенд),
      'стенд снимает кадр, не дождавшись остановки мешей');
    должен(/const ЖДАТЬ_МС = число\('wait', 40000\);/.test(стенд),
      'выдержка стенда снова короче прихода моделей');
  });
});

describe('Деревья вдоль переулков', () => {
  const террейн = читать('client/src/app/game3d/terrain.ts');

  it('платаны и кипарисы стоят в жилых улицах', () => {
    должен(/platan-\$\{1 \+ Math\.floor\(hash2\(dx, dz\) \* 4\)\}/.test(террейн),
      'платаны сняты с переулков: улица без деревьев');
    должен(/const имя = hash2\(dx, dz\) > 0\.35 \? 'cypress'/.test(террейн),
      'вдоль переулков нет кипарисов: остались одни платаны');
    должен(/сторонаДерева \*= -1;/.test(террейн),
      'деревья стоят в один ряд с фонарями: дерево в фонаре');
  });
});
