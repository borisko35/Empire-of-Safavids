// Сквер в середине городской площади.
//
// ЧТО БЫЛО (21 октября 2026, §239). Середина площади была пустой: 232
// метра плиты, на ней только фонтан в стороне, а город жил по краю. Пустая
// плита в центре читалась как зал, а не как площадь.
//
// ЧТО ТЕПЕРЬ. Сквер: клумба с кустами и кипарисами, каменный венец и
// скамейки лицом к городу.
//
// ЧТО ПРОВЕРЯЕТСЯ. Сквер стоит в середине (а не у края, где уже всё есть),
// и в нём есть зелень, венец и скамейки.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Сквер в середине площади', () => {
  it('сквер стоит в середине площади', () => {
    // Середина — это вблизи центра города (34, 26), а не у края: у края уже
    // рынок, караван-сарай и хибары.
    должен(/const скверX = -12, скверZ = 4;/.test(код), 'сквер не стоит в середине площади');
    должен(
      /const венецСквера = new THREE\.Mesh\(new THREE\.TorusGeometry\(6, 0\.2, 8, 28\), MAT\.sandstone\)/.test(код),
      'у сквера нет каменного венца: клумба не очерчена',
    );
  });

  it('в сквере есть зелень и скамейки', () => {
    должен(
      /куст\(city, скверX \+ Math\.cos\(a\) \* 4\.2, скверZ \+ Math\.sin\(a\) \* 4\.2, 0\.46, 1\.2\)/.test(
        код,
      ),
      'в сквере нет кустов: это пустая клумба',
    );
    должен(/кронаКипариса\(city, скверX \+ dx/.test(код), 'в сквере нет деревьев');
    должен(
      /const скамья = new THREE\.Mesh\(new THREE\.BoxGeometry\(2\.2, 0\.42, 0\.6\), MAT\.wood\)/.test(код),
      'в сквере нет скамеек: сидеть негде',
    );
  });
});
