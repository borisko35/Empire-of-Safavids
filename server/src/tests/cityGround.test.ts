// Площадь города и вход мечети.
//
// ЧТО БЫЛО (21 октября 2026, §227). Два недочёта, оба видны с улицы:
//   • плитка площади была 5.3 метра: в одном повторе текстуры четыре плитки
//     по стороне, а повтор ложился на все 232 метра площади. Это не мостовая,
//     а квадратные плиты размером с палатку;
//   • вход центральной мечети был ЧЁРНОЙ ПЛИТОЙ во весь проём: зала за ней
//     нет, и мечеть в центре города была самым тёмным пятном.
//
// ЧТО ТЕПЕРЬ. Плитка в масштабе человека (около 1.4 метра), а вход —
// деревянная дверь в каменной раме с двумя фонарями по бокам.
//
// ЧТО ПРОВЕРЯЕТСЯ. Масштаб плитки считается из кода, а не сверяется с
// константой: если кто-то вернёт repeat 10, сторож должен упасть на
// «плитка крупнее двух метров», а не на несовпадении строки.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Площадь города и вход мечети', () => {
  it('плитка площади не крупнее двух метров', () => {
    // С §317 площадь — не процедурная карта, а PBR-набор
    // patterned_cobblestone. Метр одного повтора задан в surfaces.json
    // (поле tile), а не в коде: там же лежит источник и лицензия.
    const площадь = /материалПлощади = surfaceMaterial\('patterned_cobblestone', \{([\s\S]*?)\}\)/.exec(код);
    должен(площадь, 'площадь больше не на patterned_cobblestone: материал потерян');
    const манифест = JSON.parse(читать('client/src/app/public/textures/surfaces.json'));
    const набор = манифест.surfaces.find((s: { id: string }) => s.id === 'patterned_cobblestone');
    должен(набор, 'в surfaces.json нет набора patterned_cobblestone');
    const плитка = Number(набор.tile);
    должен(
      плитка <= 2,
      `плитка площади ${плитка} м: это не мостовая, а плиты размером с палатку`,
    );
    // И не мелочь: плитка в 10 сантиметров читалась бы как ковёр.
    должен(
      плитка >= 0.5,
      `плитка площади ${плитка} м: мостовая в подошве, а не в кадре`,
    );
    // Повтор обязан считаться из диаметра площади и метража набора, а не
    // быть вписанным числом: иначе смена набора тихо растянет плитку.
    должен(
      /repeat: Math\.max\(1, Math\.round\(\(CITY\.radius \* 2\) \/ surfaceTile\('patterned_cobblestone'\)\)\)/.test(
        площадь![1],
      ),
      'повтор текстуры площади не выведен из диаметра и метража набора',
    );
  });

  it('вход мечети — дверь в раме, а не чёрная плита', () => {
    должен(
      !/const arch = new THREE\.Mesh\(new THREE\.BoxGeometry\(3\.4, 6, 0\.8\), MAT\.dark\)/.test(
        код,
      ),
      'у входа мечети снова чёрная плита: мечеть читается вырезом в стене',
    );
    должен(
      /const полотно = new THREE\.Mesh\(new THREE\.BoxGeometry\(3\.0, 5\.2, 0\.24\), MAT\.wood\)/.test(
        код,
      ),
      'у входа мечети нет дверного полотна',
    );
    должен(
      /const рама = new THREE\.Mesh\(new THREE\.BoxGeometry\(3\.7, 5\.9, 0\.34\), MAT\.sandstone\)/.test(
        код,
      ),
      'у входа мечети нет каменной рамы',
    );
  });

  it('у входа мечети горят фонари', () => {
    // Два фонаря-чаши: мечеть стоит в центре площади, и её портал был
    // единственным тёмным местом в центре города.
    const фонари = /for \(const side of \[-1, 1\] as const\) \{\s*const pole = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.12, 0\.18, 3\.2, 6\), MAT\.dark\);/.test(
      код,
    );
    должен(фонари, 'у входа мечети нет фонарей');
    должен(
      /lights\.push\(\{\s*x: CITY\.x \+ side \* 3\.4,/.test(код),
      'фонари у входа мечети не получают источников света',
    );
  });
});
