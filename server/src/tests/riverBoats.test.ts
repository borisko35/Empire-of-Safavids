// Лодки на реках.
//
// ЧТО БЫЛО (22 октября 2026, §304). На реках не было ни одной лодки: вода была
// пустой и читалась как пустая лента. Лодка у причала была сплюснутым
// цилиндром-поплавком.
//
// ЧТО ТЕПЕРЬ (§326). Лодка — готовая GLB-модель (Quaternius, CC0), ставится
// decorВещем с y над уровнем воды и носом по течению. Корпус из ящика с
// конусами удалён.
//
// ЧТО ПРОВЕРЯЕТСЯ. Модель лодки лежит в манифесте; постановка через
// decorВещь; лодки расставлены по обеим рекам и стоят на воде.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
  animals?: { file: string; name: string; bytes: number }[];
};
const вМанифесте = (раздел: 'decor' | 'animals', имя: string): boolean =>
  (МАНИФЕСТ[раздел] ?? []).some((д) => д.name === имя);

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Лодки на реках', () => {
  it('модель лодки лежит в сборке', () => {
    должен(вМанифесте('decor', 'boat'), 'boat.glb нет в манифесте: лодки не доедут');
  });

  it('лодка ставится моделью над водой', () => {
    должен(/function поставитьЧелн\(/.test(ТЕРРЕЙН), 'нет постановщика лодки');
    должен(/decorВещь\(scene, 'boat', x, z, \{ размер: [\d.]+, по: 'horizontal', y, ry \}\);/.test(ТЕРРЕЙН),
      'лодка ставится не через decorВещь');
    должен(!/BoxGeometry\(0\.9, 0\.42, 3\.4\)/.test(ТЕРРЕЙН), 'лодка снова ящик');
  });

  it('лодки стоят на обеих реках, носом по течению', () => {
    должен(
      /for \(const \[река, доли\] of \[\[RIVER_A, \[[\d., ]+\]\], \[RIVER_B, \[[\d., ]+\]\]\]/.test(ТЕРРЕЙН),
      'лодки не расставлены по обеим рекам',
    );
    должен(/поставитьЧелн\(scene, x, z, LAKE\.level \+ [\d.]+, Math\.atan2\(река\[i \+ 1\]\.x - река\[i\]\.x/.test(ТЕРРЕЙН),
      'лодка не на воде или не по течению');
  });
});
