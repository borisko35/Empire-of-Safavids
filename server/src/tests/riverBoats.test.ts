// Лодки-челны на реках.
//
// ЧТО БЫЛО (22 октября 2026, §304). На реках не было ни одной лодки: вода была
// пустой и читалась как пустая лента. Лодка у причала появилась в §297, но
// река мимо причала шла пустая.
//
// ЧТО ТЕПЕРЬ. Челн: вытянутый корпус с сужающимися носом и кормой, две
// поперечные планки, вёсла по бортам и шест — лодку ведут шестом. Лодки
// стоят по течению: нос вниз по реке.
//
// ЧТО ПРОВЕРЯЕТСЯ. Челн есть и состоит из корпуса, носа и кормы, планок,
// весел и шеста; лодки расставлены по обеим рекам и стоят на воде.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Лодки-челны на реках', () => {
  it('челн: корпус, сужающиеся нос и корма, планки, вёсла, шест', () => {
    должен(/function челн\(/.test(ТЕРРЕЙН), 'нет сборщика челна');
    // Корпус — вытянутый.
    должен(
      /const корпус = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.9, 0\.42, 3\.4\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'у челна нет корпуса',
    );
    // Нос и корма — конусы: лодка не ящик.
    должен(
      /const нос = new THREE\.Mesh\(new THREE\.ConeGeometry\(0\.45, 1\.1, 6\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'у челна нет сужающегося носа',
    );
    должен(/const корма = нос\.clone\(\);/.test(ТЕРРЕЙН), 'у челна нет сужающейся кормы');
    // Планки.
    должен(
      /const планка = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.85, 0\.06, 0\.2\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у челна нет планок',
    );
    // Вёсла и шест.
    должен(
      /const древко = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.03, 0\.04, 2\.2, 5\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у челна нет весел',
    );
    должен(
      /const шест = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.03, 0\.035, 3\.2, 5\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у челна нет шеста',
    );
  });

  it('лодки стоят на обеих реках, носом по течению', () => {
    // Обе реки.
    должен(
      /for \(const \[река, доли\] of \[\[RIVER_A, \[[\d., ]+\]\], \[RIVER_B, \[[\d., ]+\]\]\]/.test(ТЕРРЕЙН),
      'лодки не расставлены по обеим рекам',
    );
    // Лодка ставится на воду.
    должен(/лодка\.position\.set\(x, LAKE\.level \+ [\d.]+, z\);/.test(ТЕРРЕЙН), 'лодка не на воде');
    // И стоит по течению.
    должен(
      /лодка\.rotation\.y = Math\.atan2\(река\[i \+ 1\]\.x - река\[i\]\.x, река\[i \+ 1\]\.z - река\[i\]\.z\);/.test(ТЕРРЕЙН),
      'лодка не стоит по течению',
    );
    // И добавлена в сцену.
    должен(/scene\.add\(лодка\);/.test(ТЕРРЕЙН), 'лодка не добавлена в сцену');
  });
});
