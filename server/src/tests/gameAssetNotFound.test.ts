// Сборка игры не должна отдавать 404, который edge закэшит на год.
//
// ЧТО БЫЛО СЛОМАНО 08.10, 15.10 и 15.10.2026 - третий раз за неделю.
// В client/nginx.conf блок отдачи сборки выглядел так:
//
//   location ^~ /game/assets/ {
//     alias /usr/share/nginx/html/game/assets/;
//     add_header Cache-Control "public, max-age=31536000, immutable" always;
//   }
//
// try_files там не было, а add_header с `immutable` действует на ВСЕ ответы,
// включая ошибку. То есть отсутствующий файл отдавался как
//   404 Cache-Control: public, max-age=31536000, immutable
// и Cloudflare записывал это в кэш на год. HTML уже ссылался на новый бандл,
// а по его адресу edge отдавал «файла нет» — и игра не грузилась вовсе.
//
// ПРИЗНАК, ПО КОТОРОМУ ЭТО ВИДНО, НЕ ГЛЯДЯ НА КОД. Контейнер отдаёт файл
// (внутри 200 и 362380 байт), снаружи 404. Проверка выкатки падает на
// «не все файлы страницы доступны», хотя `sha256 sovpal` — то есть сам файл
// приходил и совпадал. Контейнер здоров, ядро исправно, сломан только кэш.
//
// ПОЧЕМУ ИМЕННО ТАК ПРОВЕРЯЕТСЯ. Поведение проверено живым nginx в контейнере:
// существующий файл - 200 с immutable, отсутствующий - 404 с no-store. Здесь
// сторож на структуру конфигурации, потому что гонять docker в каждом прогоне
// набора дорого, а структура однозначно определяет поведение.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const NGINX = readFileSync(join(корень, 'client', 'nginx.conf'), 'utf8')
  .replace(/\r\n/g, '\n');

/** Тело location-блока по имени. */
function блок(имя: string): string {
  const начало = NGINX.indexOf(`location ${имя}`);
  must(начало >= 0, `в nginx.conf нет блока «${имя}»: сборку игры нечем отдавать`);
  let скобок = 0;
  for (let i = начало; i < NGINX.length; i++) {
    if (NGINX[i] === '{') скобок++;
    else if (NGINX[i] === '}') {
      скобок--;
      if (скобок === 0) return NGINX.slice(начало, i + 1);
    }
  }
  throw new Error(`блок «${имя}» не закрылся`);
}

describe('404 по сборке игры не кэшируется', () => {
  it('у блока ассетов есть явная проверка файла', () => {
    const тело = блок('^~ /game/assets/');
    must(
      /try_files/.test(тело),
      'в блоке /game/assets/ нет try_files: отсутствие файла ничем не '
      + 'обрабатывается, и ответ уходит с теми же заголовками, что и успех',
    );
  });

  it('immutable не достаёт до ошибки', () => {
    const тело = блок('^~ /game/assets/');
    const запасной = /try_files\s+\$uri\s+@([\w-]+)/.exec(тело);
    must(
      запасной !== null,
      'try_files должен уводить промах в ИМЕНОВАННЫЙ обработчик, а не в =404 '
      + 'внутри того же блока: иначе заголовок immutable из блока повесится '
      + 'на ошибку, и edge запишет её в кэш на год',
    );

    const обработчик = блок(`@${запасной![1]}`);
    must(
      /Cache-Control[^\n]*no-store/.test(обработчик),
      `обработчик ${запасной![1]} не помечает 404 как no-store: Cloudflare `
      + 'запомнит отрицательный ответ и будет отдавать его год, хотя файл '
      + 'появится через секунды после выкатки',
    );
    must(
      /return 404/.test(обработчик),
      `обработчик ${запасной![1]} не отдаёт честный 404`,
    );
  });

  it('существующий файл по-прежнему кэшируется на год', () => {
    // Правка не должна была сломать быструю загрузку игры: имя файла содержит
    // хеш содержимого, поэтому год здесь честный.
    const тело = блок('^~ /game/assets/');
    must(
      /Cache-Control[^\n]*immutable/.test(тело),
      'успешный ответ по ассету больше не immutable: имя с хешем, менять файл '
      + 'без смены имени нельзя, и год здесь правильный',
    );
    must(
      /max-age=31536000/.test(тело),
      'год кэша ассетов убран: это то, ради чего игра должна открываться быстро',
    );
  });

  it('входной HTML по-прежнему не кэшируется', () => {
    const тело = блок('/game/');
    must(
      /Cache-Control[^\n]*no-cache/.test(тело),
      'HTML игры снова кэшируется: в нём имена файлов сборки, и закэшированная '
      + 'копия означает, что игрок месяц ходит на старую версию',
    );
  });
});