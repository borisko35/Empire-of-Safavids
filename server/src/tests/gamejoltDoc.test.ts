// Генератор инструкции Game Jolt не должен отдавать неокончательный адрес
// страницы как готовый.
//
// ЧТО БЫЛО (§196). Генератор печатал «Адрес страницы:
// https://gamejolt.com/games/<slug>/» и следующей строкой признавался, что
// «числовой id площадка добавит сама после публикации». То есть владельцу
// отдавался адрес, о котором сам генератор знал, что он не окончательный, —
// оформленный при этом как готовый факт.
//
// ПОЧЕМУ ПРОВЕРИТЬ АДРЕС НЕЛЬЗЯ, А ПРОВЕРЯТЬ НАДО БЫЛО РАНЬШЕ. Живой опыт:
// наш адрес и заведомо несуществующий отвечают одинаково — HTTP 200 и 15266
// байт; в браузере обе страницы дают одну и ту же пустую оболочку. Game Jolt —
// одностраничное приложение. Значит проверка по коду ответа здесь всегда прошла
// бы и ничего не доказывала.
//
// ЧТО СТОИТ ДОРОГО: документ, который печатает непроверяемый адрес как
// готовый, хуже документа, который честно говорит «не проверено». Владелец
// поверит адресу и не станет его проверять.
//
// ПРОМЕНЕННЫЕ ИМЕНА. Первая версия держала текст документа в переменной, и
// объявление с обращением различались одной буквой — компилятор молчал, а
// сборка падала. Третий раз за день с омоглифами. Поэтому здесь нет локальной
// переменной: текст читается функцией прямо там, где нужен. Лишнее имя —
// лишний шанс ошибиться в букве.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const генератор = join(корень, 'tools', 'build-gamejolt-instructions.js');
const документ = join(корень, 'tools', 'gamejolt-instructions.md');

function собрать(...args: string[]): { код: number; вывод: string } {
  try {
    const вывод = execFileSync('node', [генератор, ...args], {
      cwd: корень,
      encoding: 'utf-8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    return { код: 0, вывод };
  } catch (e) {
    const ошибка = e as { status?: number; stdout?: string; stderr?: string };
    return { код: ошибка.status ?? 1, вывод: (ошибка.stdout ?? '') + (ошибка.stderr ?? '') };
  }
}

function текст(): string {
  return readFileSync(документ, 'utf-8');
}

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

afterAll(() => {
  // Документ на диске должен остаться в состоянии по умолчанию: без
  // настоящего адреса, с честной пометкой «шаблон». Иначе набор оставлял бы
  // после себя документ, собранный с адресом из проверки.
  собрать('empire-of-safavids');
});

describe('Game Jolt: адрес страницы не выдаётся за проверенный', () => {
  it('без настоящего адреса документ говорит, что адрес — шаблон', () => {
    const сборка = собрать('empire-of-safavids');
    must(сборка.код === 0, 'сборка без адреса должна проходить, а не падать: ' + сборка.вывод.slice(0, 120));
    must(текст().includes('ШАБЛОН, не проверен'),
      'документ молчит, что адрес не проверен: владелец поверит шаблону');
    must(/не проверенная страница/.test(текст()),
      'нет пояснения, почему адрес не удалось проверить, — а это главное в этом месте');
  });

  it('вывод сборщика тоже не называет шаблон адресом', () => {
    const сборка = собрать('empire-of-safavids');
    must(!/адрес страницы: https:\/\/gamejolt/.test(сборка.вывод),
      'сборщик напечатал адрес, который не проверял: ' + сборка.вывод.slice(-90));
    must(/ШАБЛОН/.test(сборка.вывод), 'сборщик не сказал, что адрес не проверен');
  });

  it('с настоящим адресом документ вписывает его и снимает пометку', () => {
    const адрес = 'https://gamejolt.com/games/empire-of-safavids/12345/empire-of-safavids';
    const сборка = собрать('empire-of-safavids', адрес);
    must(сборка.код === 0, 'сборка с настоящим адресом должна проходить: ' + сборка.вывод.slice(0, 120));
    must(текст().includes(адрес), 'настоящий адрес не попал в документ');
    must(!текст().includes('ШАБЛОН, не проверен'),
      'пометка «шаблон» осталась, хотя адрес передан и проверен владельцем');
  });

  it('чужой домен в адресе отвергается', () => {
    // Адрес ведёт на сайт площадки — и только туда. Подмена домена на свой
    // означала бы, что в документе окажется ссылка на чужой сайт, а проверка
    // ссылок приняла бы её как «площадку» из своего списка.
    const сборка = собрать('empire-of-safavids', 'https://gamejolt.example/подделка');
    must(сборка.код !== 0, 'чужой домен в адресе принят: ' + сборка.вывод.slice(0, 120));
    must(!/gamejolt\.example/.test(текст()),
      'чужой домен попал в документ, хотя сборка должна была упасть');
  });
});