// Расстановка разрушаемого и мезонинов (§323, §324).
//
// Инфраструктура (destructible.ts, climbTargets, pickDestructible) выехала на
// прод раньше (5ed3ef2), но объекты считались «нерасставленными»: в комнату
// здания никто не ставил ни ящика, ни лестницы. Эта карта сторожит уже
// РАССТАНОВКУ: планы комнат дают разрушаемый декор, платформы с лестницами,
// а world3d умеет залезать.
//
// ЧТО ЛОВИТ:
// 1. Внутри Room нет поля платформ / нет wiring'а VERTICAL_MAP/DESTRUCTIBLE_MAP
//    в buildRoom - механики снова «есть, но недостижимы».
// 2. Лестница встала в дверной проём: у крепости на юге три проёма
//    (x = -7, 0, +7) шириной 3.2 м, по центру плиты (6.5) лестница закрыла
//    бы выход x=+7. Порог: ближе 2.0 м от центра проёма нельзя.
// 3. Сход с лестницы «в полушаге от плиты»: ladderTop в userData обязан
//    равняться верху платформы, иначе игрок сходит в пустоту.
// 4. Регресс предка клика: userData разрушаемого лежит на ГРУППЕ, а
//    hits[0].object - mesh-потомок; без подъёма к предку все клики по
//    разрушаемому молча глотались.
// 5. Шаг с края превратился в телепорт: сход с мезонина обязан падать, а не
//    сниппаться на пол комнаты.
// 6. Высота мезонина ниже прыжка: тогда мезонин мимо лестницы «берётся
//    прыжком», и весь инструмент лазания не нужен.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const интерьеры = читать('client/src/app/game3d/interiors.ts');
const мир = читать('client/src/app/game3d/world3d.ts');
const разрушаемое = читать('client/src/app/game3d/destructible.ts');

function блок(source: string, якорь: string, причина: string): string {
  const нач = source.indexOf(якорь);
  must(нач >= 0, причина);
  const кон = source.indexOf('};', нач);
  must(кон > нач, `${причина} (нет закрывающей };)`);
  return source.slice(нач, кон);
}

// ── Карты расстановки ──
const ВЕРТИКАЛЬ_БЛОК = блок(
  интерьеры,
  'const VERTICAL_MAP: Record<string, MezzaninePlan[]',
  'не нашёл VERTICAL_MAP в interiors.ts - мезонины ушли из расстановки');
const РАЗРУШ_БЛОК = блок(
  интерьеры,
  'const DESTRUCTIBLE_MAP: Record<string,',
  'не нашёл DESTRUCTIBLE_MAP в interiors.ts');

interface ПланПлатформы {
  комната: string; px: number; pz: number; w: number; d: number;
  h: number; lx: number; lz: number;
}

function планыМезонинов(): ПланПлатформы[] {
  const план = /(\w+): \[\{ px: (-?[\d.]+), pz: (-?[\d.]+), w: ([\d.]+), d: ([\d.]+), h: ([\d.]+), lx: (-?[\d.]+), lz: (-?[\d.]+)/g;
  const найдены: ПланПлатформы[] = [];
  let m: RegExpExecArray | null = план.exec(ВЕРТИКАЛЬ_БЛОК);
  while (m !== null) {
    найдены.push({
      комната: m[1], px: Number(m[2]), pz: Number(m[3]), w: Number(m[4]),
      d: Number(m[5]), h: Number(m[6]), lx: Number(m[7]), lz: Number(m[8]),
    });
    m = план.exec(ВЕРТИКАЛЬ_БЛОК);
  }
  return найдены;
}

// Половины комнат: залы подземелий 32x32 (внутренняя грань 15.75), здания
// 22x16 (грань 10.75/7.75).
const ГРАНЬ_СТЕН: Record<string, { x: number; z: number }> = {
  catacombs: { x: 15.75, z: 15.75 },
};

describe('Расстановка разрушаемого и мезонинов', () => {
  it('Room несёт платформы, а buildRoom прошивает обе карты', () => {
    must(/platforms: PlatformBox\[\];/.test(интерьеры),
      'в Room нет поля platforms - world3d не на что опирать игрока');
    must(/export interface PlatformBox/.test(интерьеры),
      'PlatformBox не экспортирован');
    must(/climbTargets\.push\(лестница\)/.test(интерьеры),
      'лестница не попадает в climbTargets - залезание недостижимо');
    must(/platforms\.push\(\{ x: cx \+ план\.px/.test(интерьеры),
      'плата не попадает в room.platforms');
    must(/destructibleTargets\.push\(obj\)/.test(интерьеры),
      'разрушаемое не попадает в destructibleTargets - §323 кликом не достать');
    must(/const платформа = this\.platformTopAt/.test(мир),
      'world3d не спрашивает platformTopAt - сход на мезонин не работает');
  });

  it('мезонины стоят в свободных зонах и не врезаются в стены', () => {
    const планы = планыМезонинов();
    must(планы.length >= 4,
      `планов мезонина ${планы.length}, ожидалось не меньше четырёх` +
      ' (stable/barracks/catacombs/fortress)');
    for (const п of планы) {
      const грань = ГРАНЬ_СТЕН[п.комната] ?? { x: 10.75, z: 7.75 };
      // Плата может ПРИСЛОНИТЬСЯ к стене, но не пересекать грань внутрь.
      must(п.px - п.w / 2 >= -грань.x - 0.01 && п.px + п.w / 2 <= грань.x + 0.01,
        `${п.комната}: плата x ${п.px - п.w / 2}..${п.px + п.w / 2} заходит за стену (+/-${грань.x})`);
      must(п.pz - п.d / 2 >= -грань.z - 0.01 && п.pz + п.d / 2 <= грань.z + 0.01,
        `${п.комната}: плата z ${п.pz - п.d / 2}..${п.pz + п.d / 2} заходит за стену (+/-${грань.z})`);
      must(Math.abs(п.lx) <= грань.x && Math.abs(п.lz) <= грань.z,
        `${п.комната}: лестница (${п.lx}, ${п.lz}) за внутренней гранью стены`);
    }
  });

  it('лестница не стоит в дверном проёме', () => {
    // Проёмы: юг комнаты; у крепости три (x=-7, 0, +7), у остальных один (0).
    // Ширина проёма 3.2 м (ROOM_DOOR_GAP), тело лестницы 0.68 м,
    // collider 0.42 - порог 2.0 м от центра проёма держит и то, и другое вне
    // проёма. Проверяем только лестницы, прислонённые к дверной стене.
    const проемы: Record<string, number[]> = {
      fortress: [-7, 0, 7],
      catacombs: [0],
      stable: [0], barracks: [0],
    };
    const двернаяСтена: Record<string, number> = {
      catacombs: 16, stable: 8, barracks: 8, fortress: 8,
    };
    for (const п of планыМезонинов()) {
      for (const s of проемы[п.комната] ?? []) {
        const уСтены = Math.abs(п.lz - двернаяСтена[п.комната]) < 1.2;
        if (уСтены) {
          must(Math.abs(п.lx - s) > 2.0,
            `${п.комната}: лестница (x=${п.lx}) стоит в проёме x=${s} - закроет выход`);
        }
      }
    }
  });

  it('плату с пола не допрыгнуть - только залезть по лестнице', () => {
    // Прыжок: v^2/(2g) - цифры читаются из world3d, а не вписываются:
    // если JUMP_V/GRAVITY поменяют, порог двинется сам.
    const v = /const JUMP_V = ([\d.]+);/.exec(мир);
    const g = /const GRAVITY = ([\d.]+);/.exec(мир);
    must(v !== null && g !== null, 'не нашёл JUMP_V/GRAVITY в world3d.ts');
    const прыжок = Number(v![1]) ** 2 / (2 * Number(g![1]));
    for (const п of планыМезонинов()) {
      must(п.h > прыжок + 0.05,
        `${п.комната}: мезонин ${п.h} м не выше прыжка (${прыжок.toFixed(2)} м)` +
        ' - достаётся прыжком, лестница балласт');
    }
    // Поддержка платы: ступни далеко под плитой (подпрыг снизу) опору не дают.
    must(/feetY > p\.y - 0\.55/.test(мир),
      'platformTopAt не отсекает плату от прыгуна снизу - игрок зависнет под ней');
  });

  it('сход с лестницы кладёт игрока ровно на плату', () => {
    // ladderTop = baseY + h в фабрике, а лестница строится на высоту плана:
    // числа обязаны биться, иначе сход оказывается «в полушаге» от плиты.
    must(/g\.userData = \{ ladderHeight: h, ladderTop: baseY \+ h \};/.test(интерьеры),
      'createInteriorLadder не кладёт ladderTop в userData');
    must(/const лестница = createInteriorLadder\(cx \+ план\.lx, FLOOR_Y, cz \+ план\.lz, план\.h/.test(интерьеры),
      'лестница строится не на высоту мезонина');
  });

  it('лазание в world3d держится связного набора', () => {
    must(/private climb: THREE\.Object3D \| null = null;/.test(мир),
      'нет поля climb - нет состояния «на лестнице»');
    must(/вершина > me\.pos\.y \+ 0\.1/.test(мир),
      'engage работает на уровне вершины - W у верха лестницы снова цепляет её');
    must(/if \(this\.climb\) \{ ix = 0; iz = 0; \}/.test(мир),
      'XZ не заморожены на лестнице - игрок уедет вбок, пока висит');
    // Ветка лазания обязана идти ПЕРЕД плаванием и падением.
    const порядок = мир.indexOf('if (this.climb) {');
    const плавание = мир.indexOf('} else if (this.swimming) {');
    const падение = мир.indexOf('} else if (!this.grounded) {');
    must(порядок >= 0 && плавание > порядок && падение > плавание,
      'ветка лазания не первая в вертикальной цепочке - её перебьют');
    must(/скорость = 2\.8/.test(мир) && /скорость = -3\.2/.test(мир),
      'вертикальные скорости лазания не на месте (2.8 / -3.2)');
    // Захват лестницы стоит у самой лестницы, а не по всему интерьеру.
    must(/дальность = 1\.4/.test(мир), 'радиус захвата лестницы не локальный');
  });

  it('шаг с края - падение, а не телепорт на пол', () => {
    const m = /} else if \(me\.pos\.y > effectiveGroundY \+ 0\.45\) \{\s*\n\s*[^}]*?this\.grounded = false;/.test(мир);
    must(m, 'нет схода с края: мезонин/мост снова сниппется на землю');
  });

  it('клик по разрушаемому ощупывается до предка с userData', () => {
    // userData лежит на группе разрушаемого, hits[0].object - mesh-потомок:
    // без подъёма к предку ВСЕ клики по разрушаемому молча глотались.
    must(/while \(target && !\(target\.userData as DestructibleData\)\?\.kind\) \{\s*\n\s*target = target\.parent;/.test(мир),
      'pickDestructible не поднимается к предку - клики по разрушаемому снова глотаются');
    must(/if \(!target\) return false;/.test(мир),
      'нет финиш-проверки подъёма к предку');
    // HP и удар согласованы: ящик 50 HP при уроне 25 - ровно два удара.
    const hp = /crate:\s*\{ health: (\d+)/.exec(разрушаемое);
    must(hp !== null && Number(hp![1]) % 25 === 0,
      'HP ящика не кратно удару в 25 - разъедется с числом удара');
  });

  it('карта разрушаемого заполнена и держит только известные виды', () => {
    const пара = /(\w+): \[\{[^}]*kind: '(\w+)', count: (\d+)[^}]*\}\]/g;
    const найдено = РАЗРУШ_БЛОК.match(пара);
    must(найдено !== null && найдено.length >= 8,
      'объявленных комнат меньше восьми - карта пуста или распалась');
    const виды = new Set(['crate', 'barrel', 'vase']);
    for (const строка of найдено!) {
      const m = /(\w+): \[\{[^}]*kind: '(\w+)', count: (\d+)[^}]*\}\]/.exec(строка)!;
      must(виды.has(m[2]), `неизвестный вид разрушаемого: ${m[2]}`);
      must(Number(m[3]) >= 1, `${m[1]}: count ${m[3]} - карта зря`);
    }
  });

  it('интерьерные цели пересобираются на входе и выходе', () => {
    // Баг §320: цели собирались один раз на init, выход их чистил, и второй
    // визит в здание терял кликабельность ящиков и лестниц.
    const звонки = мир.match(/this\.refreshInteriorTargets\(\);/g);
    must(звонки !== null && звонки.length >= 4,
      `refreshInteriorTargets зван ${звонки?.length ?? 0} раз, минимум четыре` +
      ' (вход, выход и локальные вход/выход)');
    must(/private refreshInteriorTargets\(\): void/.test(мир),
      'нет метода refreshInteriorTargets');
  });
});
