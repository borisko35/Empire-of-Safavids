// Масштабирование, шаг первый: доставка событий между инстансами.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА. До адаптера события междинстансами не ходили ВООБЩЕ:
// канал Redis публиковался, подписчик был в каждом процессе, а
// `activePlayers` — карта ЛОКАЛЬНАЯ. Личное событие (партия, рейд,
// приглашение) до сокета на другом инстансе не доходило.
//
// Проверка сторожит два свойства. Первое: адаптер РЕАЛЬНО ставится — не
// импортируется, а присваивается `io.adapter(...)`. Второе: за флажком. При
// одном инстансе (сейчас прод — один контейнер) адаптер не даёт ничего, зато
// добавляет два соединения с Redis; включать его незаметно для владельца —
// значит менять прод не решением.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const сервер = код('server/src/index/index.ts');
const пакет = JSON.parse(читать('server/package.json')) as {
  dependencies: Record<string, string>;
};

describe('Масштабирование: адаптер доставки', () => {
  it('пакет установлен', () => {
    must(пакет.dependencies['@socket.io/redis-adapter'], 'адаптера нет в зависимостях');
  });

  it('импортируется и присваивается', () => {
    // Импорт без присваивания — тот же мёртвый код, что и createRaid.
    must(/import \{ createAdapter \} from '@socket\.io\/redis-adapter';/.test(сервер), 'нет импорта');
    must(/io\.adapter\(createAdapter\(/.test(сервер), 'адаптер не присвоен io');
  });

  it('за флажком, а не всегда', () => {
    // По умолчанию ВЫКЛЮЧЕН: при одном инстансе он не даёт ничего, но
    // добавляет два соединения и ложку неочевидности в отладку.
    must(/process\.env\.EOS_SCALE === '1'/.test(сервер), 'флага EOS_SCALE нет');
    // Флаг должен реально гейтить присваивание.
    must(/if \(масштабирование\) \{[\s\S]{0,600}?io\.adapter\(/.test(сервер),
      'присваивание не под флажком');
  });

  it('два клиента: подписчик и публикатор', () => {
    // Один клиент на оба канала — известная ошибка: соединение в режиме
    // подписчика не может публиковать.
    must(/создать?[Куп]?[лп]иент/.test(сервер) || /createClient\(/.test(сервер), 'нет клиентов');
    const клиентов = (сервер.match(/createClient\(/g) ?? []).length;
    must(клиентов >= 2, `клиентов ${клиентов}: нужно два`);
  });

  it('ошибки соединений не молчат', () => {
    // Неподключенный адаптер даёт «события не доходят» без единой ошибки.
    must(/\.on\('error'/.test(сервер), 'ошибки соединений не пишутся в лог');
  });
});

describe('Масштабирование: что НЕ сделано', () => {
  it('боевой контекст всё ещё в памяти', () => {
    // Проверка-признан: шаг первый не выдан за второй. Пока contexts в Map,
    // продолжать бессмысленно — и это сказано в §96.
    const бой = код('server/src/systems/AISystem.ts');
    must(/private contexts = new Map<string, AIContext>\(\)/.test(бой), 'боевой контекст переехал: пересмотрите §96');
  });

  it('сессии данжей всё ещё в памяти', () => {
    const данжи = код('server/src/systems/DungeonService.ts');
    must(/private sessions = new Map<string, DungeonSession>\(\)/.test(данжи), 'сессии переехали: §96 устарел');
  });

  it('прод — один инстанс', () => {
    // Из разбора §96: у сервиса server нет ни replicas, ни deploy, ни ports.
    const compose = читать('deploy/docker-compose.prod.yml');
    const блок = compose.slice(compose.indexOf('\n  server:'));
    const конец = блок.indexOf('\n  ', 10);
    const сервис = конец > 0 ? блок.slice(0, конец) : блок;
    must(!/replicas:|deploy:/.test(сервис), 'в проде появились реплики: флаг надо включать');
  });
});