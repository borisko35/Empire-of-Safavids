// Абордаж: маршрут не висит без клиента.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА. Вся серия коммитов про одно: объявленное, но не
// связанное. Маршрут без клиентского вызова — тот же класс: сервер умеет,
// игрок не может. `apiSurface.test.ts` это уже сторожит, и он поймал мой
// маршрут сразу.
//
// Здесь сторож на предметной стороне: режимы, фильтр и тип цели должны быть
// видны клиенту ТАК ЖЕ, как их считает сервер. Если типы разойдутся, клиент
// нарисует кнопку, а сервер откажет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const маршруты = код('server/src/routes/game.ts');
const апи = код('client/src/app/api.ts');

describe('Абордаж: маршрут живой', () => {
  it('маршрут целей есть и защищён', () => {
    const начало = маршруты.indexOf("gameRouter.get('/boarding/targets'");
    must(начало > 0, 'маршрута списка целей нет');
    const блок = маршруты.slice(начало, начало + 400);
    must(/secureMiddleware/.test(блок), 'маршрут без secureMiddleware');
    must(/requireCharacterOwnership\(\)/.test(блок), 'маршрут не проверяет персонажа');
  });

  it('клиент зовёт его', () => {
    // Без этого apiSurface.test.ts роняет сборку — но он проверяет подстрокой,
    // а здесь проверяем смысл: режим едет в запрос.
    must(/boardingTargets:\s*\(characterId: string, mode: 'pve' \| 'pvp'\)/.test(апи),
      'в клиенте нет вызова списка целей: кнопка рисуется некому');
    must(/mode=\$\{mode\}/.test(апи), 'режим не едет в запрос');
  });

  it('без лодки сервер отдаёт причину, а не пустой список без объяснения', () => {
    // Иначе игрок не понимает, почему кнопка мертва.
    //
    // §191: код отказа больше не выбирается в маршруте, а приходит из общего
    // поиска. Проверяем оба конца — что код назван и что он доезжает в ответ,
    // иначе отказ остался бы в модуле, а игрок видел бы пустоту.
    must(/(targets: \[\]|targets: [])[^]*reason: поиск\.code/.test(маршруты),
      'причина отказа не доезжает до ответа маршрута');
    must(/code: 'board_no_boat'/.test(код('server/src/systems/BoardingSearch.ts')),
      'поиск не называет причину отказа без лодки');
    must(/'board_no_boat'/.test(код('server/src/systems/BoardingTypes.ts')), 'кода нет в общем списке ошибок');
  });

  it('режим по умолчанию безопасный', () => {
    // Без mode в запросе получается PvE. Явный PvP — осознанный выбор.
    must(/req\.query\.mode === 'pvp' \? 'pvp' : 'pve'/.test(маршруты),
      'режим по умолчанию не PvE');
  });

  it('маршрут и сокет идут через ОДИН поиск целей', () => {
    // §191. Список целей жил в маршруте, и сокету, который начинает заход,
    // понадобился бы второй такой же: игрок увидел бы цель, сервер её не
    // нашёл бы и ответил «цель не найдена» на цели с экрана.
    //
    // Свойство проверяется по построению, а не по вызову: оба места зовут
    // один и тот же экспорт. Регулярки с \w тут не работают — без флага u
    // \w не понимает кириллицу и не нашла бы ничего НИКОГДА.
    const поиск = код('server/src/systems/BoardingSearch.ts');
    const сокет = код('server/src/socket/GameSocketHandler.ts');
    must(/найтиЦелиАбордажа/.test(поиск), 'общего поиска целей нет');
    must(/найтиЦелиАбордажа\(/.test(маршруты),
      'маршрут собирает цели сам: картина для показа и для боя разойдутся');
    must(/найтиЦелиАбордажа\(/.test(сокет),
      'сокет собирает цели сам: игрок увидит цель, которой сервер не найдёт');
    // И ровно одно место, где список действительно фильтруется: если маршрут
    // и сокет разойдутся, это станет двумя вызовами boardTargets.
    must((поиск.match(/boardTargets\(/g) ?? []).length === 1,
      'в общем поиске несколько вызовов boardTargets: правила разошлись');
  });
});