// Скорость лодки под своей территорией (§190).
//
// ГЛАВНОЕ В ЭТОМ ФАЙЛЕ — сверка СЕРВЕРНОГО числа с КЛИЕНТСКИМ литералом.
// Сервер обязан знать, во сколько клиент ускоряет лодку рывком, иначе потолок
// античита окажется ниже честной езды. Такое расхождение не роняет ни один
// тест в своём кабинете: его обнаруживает игрок, и то баном.
//
// Числа читаются ИЗ ИСХОДНИКОВ, а не заданы константами в проверке. Иначе
// проверка подтверждала бы саму себя: переписали сервер — тест всё равно зелёный.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  BOATS,
  скоростьЛодки,
  потолокЛодки,
  МНОЖИТЕЛЬ_РЫВКА_НА_ВОДЕ,
} from '../systems/BoatSystem';
import { territoryBonuses } from '../systems/TerritoryBonuses';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/world3d.ts');
const СОКЕТ = читать('server/src/socket/GameSocketHandler.ts');
const МАРШРУТЫ = читать('server/src/routes/game.ts');
const СИСТЕМА = читать('server/src/systems/TerritoryBonuses.ts');
const ЛОДКИ = читать('server/src/systems/BoatSystem.ts');

const БАЗОВЫЙ_ПОТОЛОК = 12.0;
const БОНУС_ПОРТА = 1.2;

const портЗалива = {
  id: 'territory_persian_gulf_port', name: 'x', nameRu: 'x',
  region: 'persian_gulf' as never,
  bonuses: [{ type: 'sea_speed' as never, value: 0.2 }],
  capturePoints: 1, defensePoints: 1, siegeSchedule: 'Saturday 20:00 UTC',
};

describe('Скорость лодки под своей территорией (§190)', () => {
  it('серверный множитель рывка совпадает с клиентским', () => {
    // Клиент: shifting ? Math.max(swimSprint, boatSpeed * 1.25) : ...
    const клиентский = /boatSpeed \* ([\d.]+)/.exec(МИР);
    must(клиентский,
      'не нашёл в клиенте множитель рывка на лодке (boatSpeed * …): '
      + 'серверному зеркалу нечего сверять, и потолок может оказаться ниже езды');
    must(Number(клиентский![1]) === МНОЖИТЕЛЬ_РЫВКА_НА_ВОДЕ,
      `сервер считает рывок x${МНОЖИТЕЛЬ_РЫВКА_НА_ВОДЕ}, клиент x${клиентский![1]}: `
      + 'честная езда на лодке будет объявлена speed_hack');
  });

  it('потолок античита не ниже того, во что клиент честно едет', () => {
    for (const лодка of Object.values(BOATS)) {
      const эффективная = скоростьЛодки(лодка, БОНУС_ПОРТА);
      const потолок = потолокЛодки(эффективная, БАЗОВЫЙ_ПОТОЛОК);
      const едет = эффективная * МНОЖИТЕЛЬ_РЫВКА_НА_ВОДЕ;
      must(потолок >= едет,
        `на ${лодка.id} потолок ${потолок.toFixed(2)} ниже честной езды ${едет.toFixed(2)}: `
        + 'игрок на своей лодке получит speed_hack и бан после пяти нарушений');
      must(потолок >= БАЗОВЫЙ_ПОТОЛОК,
        `на ${лодка.id} лодка опустила потолок ниже пешего предела`);
    }
  });

  it('потолок не растёт, пока лодка не превышает базу', () => {
    // Соблазн сделать потолок «скорость лодки плюс база», как у скакуна. Тогда
    // предел, умноженный ещё на 1.3 в validateMovement, уехал бы за 27 м/с, и
    // читер на лодке ехал бы почти незаметно.
    for (const лодка of Object.values(BOATS)) {
      const безБонуса = потолокЛодки(скоростьЛодки(лодка, 1), БАЗОВЫЙ_ПОТОЛОК);
      must(безБонуса === БАЗОВЫЙ_ПОТОЛОК,
        `на ${лодка.id} обычная лодка подняла потолок до ${безБонуса}: `
        + 'бонус территории не должен ослаблять античит там, где лодка и без него не быстрее базы');
    }
  });

  it('бонус порта ускоряет лодку, а не замедляет', () => {
    // +20% скорости это 1.20. Со знаком наоборот лодка замедлялась бы под
    // своей же гаванью — и бонус «ускоряет» выглядел бы работающим.
    must(territoryBonuses([портЗалива], 'sea_speed') === 1.2,
      `бонус порта вышел ${territoryBonuses([портЗалива], 'sea_speed')}, а ждали 1.20`);
    must(/sea: territoryBonuses\(мои, 'sea_speed'\)/.test(СИСТЕМА),
      'sea считается не общей функцией: у моря другой знак, чем у защиты и крафта');
    must(/sea: territoryBonuses\(вРегионе, 'sea_speed'\)/.test(СИСТЕМА),
      'sea не посчитан в бонусах региона');
    const лодка = Object.values(BOATS)[0];
    must(скоростьЛодки(лодка, 1.2) > лодка.swimSpeed,
      'скорость с бонусом не превысила базовую: бонус есть в данных и нет в игре');
  });

  it('и клиенту, и античиту уходит одна и та же величина', () => {
    must(/скоростьЛодки\(лодка, бонус\.sea\)/.test(МАРШРУТЫ),
      'клиенту отдаётся не эффективная скорость: бонус есть в проверке, но не в игре');
    must(/потолокЛодки\(this\.boatSpeedFor\(characterId\), базовыйПотолок\)/.test(СОКЕТ),
      'потолок античита строится не из той же величины, что ушла клиенту');
    // Ровно два вызова: клиент и античит. Третье место — две правды.
    const вызовов = (СОКЕТ.match(/скоростьЛодки\(/g) ?? []).length
      + (МАРШРУТЫ.match(/скоростьЛодки\(/g) ?? []).length;
    must(вызовов === 2,
      `скоростьЛодки вызывается в ${вызовов} местах, а пересобирать её можно `
      + 'только в двух: клиент и античит');
  });

  it('мусор на входе не делает лодку якорем', () => {
    const лодка = Object.values(BOATS)[0];
    for (const мусор of [0, -1, Number.NaN, Number.POSITIVE_INFINITY]) {
      must(скоростьЛодки(лодка, мусор) === лодка.swimSpeed,
        `на мусоре ${String(мусор)} скорость не вернулась к обычной: игрок встал бы `
        + 'на воде, и это выглядело бы как «лодка не едет»');
    }
    must(скоростьЛодки(null, 1.2) === 0, 'у отсутствующей лодки ненулевая скорость');
  });

  it('бонус лодки не переживает уход из региона', () => {
    must(/СРОК_СКОРОСТИ_ЛОДКИ_МС/.test(СОКЕТ),
      'у кэша скорости лодки нет срока: бонус порта пережил бы уход в другой '
      + 'регион до конца сессии, и игрок уехал бы с чужим ускорением');
    must(/в: Date\.now\(\)/.test(СОКЕТ), 'в записи кэша не ставится время');
    must(/this\.boatSpeeds\.delete\(socket\.characterId\)/.test(СОКЕТ),
      'кэш не сбрасывается при выходе: следующий вход унаследовал бы чужой бонус');
    must(/catch \{\s*\n\s*this\.boatSpeeds\.set\(characterId, \{ boatId: '', speed: 0/.test(СОКЕТ),
      'при отказе базы в кэш не кладётся обычная скорость: игрок сохранил бы прежний бонус');
  });

  it('регион берётся вместе с лодкой одной выборкой', () => {
    must(/LEFT JOIN character_boats/.test(ЛОДКИ),
      'лодка и регион читаются разными запросами: на движении это десятки запросов в секунду');
    must(/\.бонусыИгрока\(characterId, регион\)/.test(СОКЕТ),
      'бонус лодки считается не по региону игрока');
    must(/\.бонусыИгрока\(characterId, mine\.region \?\? ''\)/.test(МАРШРУТЫ),
      'маршрут отдаёт клиенту скорость без учёта региона');
  });
});
