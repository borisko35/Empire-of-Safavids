// Пещеры Хорасана и Крепость Кавказа: геометрия по замеру.
//
// ЧТО ЗДЕСЬ ВАЖНО, А ЧТО ОКАЗАЛОСЬ ЕРУНДОЙ В МОЁМ ПЕРВОМ ЧЕРНОВИКЕ.
//
// 1. ОПОРНАЯ ТОЧКА — САМ БОСС, ЗНАЧИТ БОСС ВСЕГДА В СЕРЕДИНЕ ЗОНЫ. Я написал в
//    первом черновике «арззанг встанет в z = −15» и построил алтарь огня у
//    дальней стены. Это было неверно: босс и есть опора, поэтому он стоит там,
//    где стоит зона. Настоящий замер модуля: арззанг в (0, −7.5).
//    Проверка, защищавшая неверное число, хуже её отсутствия: она заставила
//    поставить геометрию не туда.
//
// 2. ДЖИННЫ НА ОДНОЙ ОСИ, А НЕ ВРАЗНОБОЙ. Они стоят в (0, −15) и (0, −4):
//    расстояние одиннадцать, но оба x = 0. Молния в трёх точках попадала мимо
//    обоих в двух местах из трёх.
//
// 3. ЗАЗОР У ВХОДА. Игрок появляется у края зала, и монстры входной комнаты
//    вставали вплотную к этому краю: у крепости четверо стояли в z = 15, то есть
//    у самой стены. Причина в данных — у входных комнат размах по глубине 15
//    единиц, а на три комнаты зал делится на 32. Теперь у входной комнаты
//    монстрам запрещено подходить к краю игрока ближе SPAWN_GAP.
//
// СУНДУКИ — ЧАСТЬ КАРТИНКИ, А НЕ МЕХАНИКА: поле treasureChests сервер не читает
// (проверка ниже это сторожит).
