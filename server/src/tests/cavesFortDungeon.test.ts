import { DUNGEONS_DATABASE } from '../data/dungeons';
import { planDungeonRooms, SPAWN_GAP } from '../systems/dungeonLayout';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');
const пещеры = DUNGEONS_DATABASE.dungeon_khorasan_caves;
const крепость = DUNGEONS_DATABASE.dungeon_caucasus_fort;

/** Тело обстановки — до следующей функции или списка построек. */
function телоФункции(имя: string): string {
  const начало = клиент.indexOf(`function furnish${имя}(`);
  must(начало > 0, `функции обстановки ${имя} нет`);
  const границы = [
    клиент.indexOf('\nfunction furnish', начало + 1),
    клиент.indexOf('export const BUILDINGS', начало),
  ].filter((к) => к > 0);
  return клиент.slice(начало, Math.min(...границы));
}

const залПещер = телоФункции('KhorasanCaves');
const залКрепости = телоФункции('CaucasusFort');

/** Значение смещения вида «cz - 7.5»: знак и число читаются по отдельности. */
function смещение(фрагмент: string): number {
  const м = /([+-])\s*([\d.]+)/.exec(фрагмент);
  must(м !== null, `не понял смещение «${фрагмент}»`);
  return м![1] === '-' ? -Number(м![2]) : Number(м![2]);
}

describe('Подземелья: точка входа равна комнате своего интерьера', () => {
  it('у всех пяти подземелий вход совпадает с комнатой интерьера', () => {
    // Правило «вход не в мире, а в кармане» было верным и бесполезным: у
    // гробницы вход стоял в 4968, а её комната 4704 — монстры появлялись в
    // пустом кармане за 264 единицы от гробницы, и заход нельзя было пройти.
    for (const [id, def] of Object.entries(DUNGEONS_DATABASE)) {
      const зал = INTERIORS[def.interiorId];
      must(зал !== undefined, `${id}: интерьера '${def.interiorId}' нет`);
      must(
        def.entryX === зал!.roomCx && def.entryZ === зал!.roomCz,
        `${id}: вход (${def.entryX}, ${def.entryZ}), а комната '${def.interiorId}' — ` +
          `(${зал!.roomCx}, ${зал!.roomCz}): монстры появятся не в той комнате`
      );
    }
  });
});

describe('Пещеры Хорасана: огонь там, где встанет арззанг', () => {
  it('интерьер на своём слоте, комната 4880', () => {
    must(INTERIORS.khorasan_caves !== undefined, 'интерьера пещер нет');
    const ключи = Object.keys(INTERIORS);
    must(ключи.length === 22, `интерьеров ${ключи.length}, а должно быть 22`);
    must(ключи[20] === 'khorasan_caves', `на слоте 20 стоит ${ключи[20]}, а ожидались khorasan_caves`);
    must(INTERIORS.khorasan_caves!.roomCx === 4880, 'комната пещер не по формуле слота');
    must(
      пещеры.entryX === INTERIORS.khorasan_caves!.roomCx,
      `вход пещер ${пещеры.entryX}, а комната ${INTERIORS.khorasan_caves!.roomCx}`
    );
  });

  it('арззанг встанет в середину зоны, и там же алтарь', () => {
    const боссовая = пещеры.rooms.find((р) => р.isBossRoom);
    must(боссовая !== undefined, 'боссовой комнаты нет');
    must(
      боссовая!.bossId === 'boss_div_arzhang',
      `босс ${боссовая!.bossId}, а ожидался boss_div_arzhang`
    );
    const план = planDungeonRooms(пещеры).find((к) => пещеры.rooms[к.index].isBossRoom);
    must(план !== undefined, 'боссовой комнаты в раскладке нет');
    const арззанг = план!.monsters.find((м) => м.monsterId === 'boss_div_arzhang');
    must(арззанг !== undefined, 'арззанг не запланирован');
    const z = арззанг!.z - пещеры.entryZ;
    const зона = план!.zoneZ - пещеры.entryZ;
    must(
      Math.abs(z - зона) < 1e-6,
      `арззанг в z = ${z}, а зона комнаты в z = ${зона}: опорная точка — сам босс, ` +
        'значит он обязан стоять в середине зоны'
    );
    must(z === -7.5, `зона пещер изменилась: ${z}, а геометрия построена под −7.5`);
    // Алтарь и огонь — в той же точке.
    const алтарь = /box\(3\.4, 0\.6, 2\.2, M\.stone, cx, FLOOR_Y \+ 0\.3, (cz [+-] [\d.]+)\)/.exec(
      залПещер
    );
    must(алтарь !== null, 'алтарь огня не найден');
    must(
      смещение(алтарь![1]) === z,
      `алтарь в z = ${смещение(алтарь![1])}, а босс в z = ${z}: босс окажется спиной к алтарю`
    );
    const огонь = /cyl\(0\.7, 0\.4, 0\.7, M\.fire, cx, FLOOR_Y \+ 2\.2, (cz [+-] [\d.]+), 10\)/.exec(
      залПещер
    );
    must(огонь !== null, 'огня на алтаре нет: зал назван вечным огнём');
    must(
      смещение(огонь![1]) === z,
      `огонь в z = ${смещение(огонь![1])}, а босс в z = ${z}`
    );
  });

  it('вход в пещеру — это спуск, а не дверь с улицы', () => {
    must(
      /FLOOR_Y \+ 0\.09 - i \* 0\.18/.test(залПещер),
      'ступеней вниз нет: в пещеру приходят по лестнице'
    );
    must(/M\.water/.test(залПещер), 'воды на дне нет: пещера без воды — просто дыра');
    must(/M\.stone/.test(залПещер), 'породы нет');
  });

  it('зон две, как комнат в данных', () => {
    must(пещеры.rooms.length === 2, `комнат в данных ${пещеры.rooms.length}, а зон заложено две`);
    must(/── Зона 1/.test(залПещер), 'входа в пещеру нет');
    must(/── Зона 2/.test(залПещер), 'зала вечного огня нет');
  });

  it('ни один монстр пещер не стоит в стене', () => {
    let проверено = 0;
    for (const комната of planDungeonRooms(пещеры)) {
      for (const монстр of комната.monsters) {
        проверено++;
        must(
          Math.abs(монстр.x - пещеры.entryX) <= ROOM_HALF - 1 &&
            Math.abs(монстр.z - пещеры.entryZ) <= ROOM_HALF - 1,
          `${монстр.monsterId} в (${монстр.x - пещеры.entryX}, ${монстр.z - пещеры.entryZ}) — в стене`
        );
      }
    }
    must(проверено >= 10, `проверено ${проверено} монстров, а в данных их 10`);
  });
});

describe('Крепость Кавказа: двое джиннов на одной оси, молния под обоими', () => {
  it('интерьер на своём слоте, комната 4924', () => {
    must(INTERIORS.caucasus_fort !== undefined, 'интерьера крепости нет');
    const ключи = Object.keys(INTERIORS);
    must(ключи[21] === 'caucasus_fort', `на слоте 21 стоит ${ключи[21]}, а ожидался caucasus_fort`);
    must(INTERIORS.caucasus_fort!.roomCx === 4924, 'комната крепости не по формуле слота');
    must(
      крепость.entryX === INTERIORS.caucasus_fort!.roomCx,
      `вход крепости ${крепость.entryX}, а комната ${INTERIORS.caucasus_fort!.roomCx}`
    );
  });

  it('джиннов двое, на оси, и молния бьёт под обоими', () => {
    const башня = крепость.rooms.find((р) => р.isBossRoom);
    must(башня !== undefined, 'боссовой комнаты нет');
    must(башня!.bossId === 'mob_storm_djinn', `босс ${башня!.bossId}, а ожидался mob_storm_djinn`);
    const джиннов = башня!.monsters
      .filter((г) => г.monsterId === 'mob_storm_djinn')
      .reduce((с, г) => с + г.count, 0);
    must(джиннов === 2, `джиннов в данных ${джиннов}, а башня рассчитана на двоих`);
    const план = planDungeonRooms(крепость).find((к) => крепость.rooms[к.index].isBossRoom);
    must(план !== undefined, 'боссовой комнаты в раскладке нет');
    const точки = план!.monsters.filter((м) => м.monsterId === 'mob_storm_djinn');
    must(точки.length === 2, `в раскладке джиннов ${точки.length}, а должно быть 2`);

    // НА ОДНОЙ ОСИ, А НЕ ВРАЗНОБОЙ: у обоих x = 0.
    const xs = точки.map((м) => м.x - крепость.entryX);
    must(
      xs.every((x) => x === 0),
      `джинны в x = ${xs.join(', ')}, а молния стоит на оси`
    );
    const расстояние = Math.abs(точки[0].z - точки[1].z);
    must(
      расстояние >= 8,
      `джинны в ${расстояние} друг от друга: одна точка молнии была бы ровно между ними`
    );

    // Молния и кольца — ПОД САМИМИ ДЖИННАМИ, и точек ровно две.
    const цикл = /for \(const dz of \[([-\d.,\s]+)\]\) \{\s*\n\s*g\.add\(box\(0\.3, 3\.4, 0\.3, M\.gold/.exec(
      залКрепости
    );
    must(цикл !== null, 'цикла молнии нет в башне');
    const dz = цикл![1].split(',').map((с) => Number(с.trim()));
    must(
      dz.length === 2,
      `молния в ${dz.length} точках, а джиннов два: лишние точки стоят мимо обоих`
    );
    for (const точка of точки) {
      const z = точка.z - крепость.entryZ;
      must(
        dz.includes(z),
        `молния не бьёт под джинном в z = ${z}: стоит в ${dz.join(', ')}`
      );
    }
    // Кольца — в том же цикле, а не отдельной строкой.
    must(
      /cyl\(1\.1, 0\.14, 1\.1, M\.gold/.test(залКрепости),
      'колец молнии нет'
    );
  });

  it('площадка башни накрывает обоих джиннов', () => {
    // Первая версия требовала глубину площадки не меньше размаха джиннов плюс
    // два, то есть 13, и ругалась на 12.4. Но площадка ЦЕНТРИРОВАНА на
    // джиннах: при центре −9.5 и глубине 12.4 она идёт от −15.7 до −3.3 и
    // накрывает обоих (в −15 и −4) с запасом. Мерилось не то свойство.
    const точки = planDungeonRooms(крепость)
      .find((к) => крепость.rooms[к.index].isBossRoom)!
      .monsters.filter((м) => м.monsterId === 'mob_storm_djinn');
    must(точки.length === 2, `джиннов ${точки.length}, а площадка рассчитана на двоих`);
    const zs = точки.map((м) => м.z - крепость.entryZ);
    const середина = (Math.min(...zs) + Math.max(...zs)) / 2;
    const площадка =
      /box\(12\.4, 0\.4, ([\d.]+), M\.stone, cx, FLOOR_Y \+ 0\.2, (cz [+-] [\d.]+)\)/.exec(
        залКрепости
      );
    must(площадка !== null, 'площадка башни не найдена');
    must(
      смещение(площадка![2]) === середина,
      'площадка в z = ' + смещение(площадка![2]) + ', джинны в ' + zs.join(', ') + ': ' +
        'площадка смещена относительно врагов'
    );
    const глубина = Number(площадка![1]);
    const крайНиз = середина - глубина / 2;
    const крайВерх = середина + глубина / 2;
    for (const z of zs) {
      must(
        z >= крайНиз && z <= крайВерх,
        'джинн в z = ' + z + ' вне площадки (от ' + крайНиз + ' до ' + крайВерх + '): ' +
          'он стоит на земле рядом с башней, а не на ней'
      );
    }
  });

  it('зон три, как комнат в данных', () => {
    must(крепость.rooms.length === 3, `комнат в данных ${крепость.rooms.length}, а зон заложено три`);
    must(/── Зона 1/.test(залКрепости), 'ворот крепости нет');
    must(/── Зона 2/.test(залКрепости), 'стены нет');
    must(/── Зона 3/.test(залКрепости), 'башни бури нет');
  });

  it('ворота выглядят воротами: арка, решётки, зубцы', () => {
    must(
      /box\(8\.6, 1\.2, 1\.4, M\.stone, cx, FLOOR_Y \+ 4\.4, cz \+ 14\)/.test(залКрепости),
      'арки ворот нет: ворота без перемычки — это проём'
    );
    must(/M\.iron/.test(залКрепости), 'кованых ворот нет');
    must(
      /box\(0\.8, 0\.7, 0\.8, M\.stone/.test(залКрепости),
      'зубцов парапета нет: стена должна читаться стеной'
    );
  });

  it('ни один монстр крепости не стоит в стене', () => {
    let проверено = 0;
    for (const комната of planDungeonRooms(крепость)) {
      for (const монстр of комната.monsters) {
        проверено++;
        must(
          Math.abs(монстр.x - крепость.entryX) <= ROOM_HALF - 1 &&
            Math.abs(монстр.z - крепость.entryZ) <= ROOM_HALF - 1,
          `${монстр.monsterId} в (${монстр.x - крепость.entryX}, ${монстр.z - крепость.entryZ}) — в стене`
        );
      }
    }
    must(проверено >= 14, `проверено ${проверено} монстров, а в данных их 14`);
  });
});

describe('Вход подземелья: у игрока есть место', () => {
  it('монстры входа не стоят вплотную к точке появления игрока', () => {
    // Причина находки: у крепости четверо входных монстров стояли в z = 15, то
    // есть у самой стены, где появляется игрок. Причина в данных: у входных
    // комнат размах по глубине 15 единиц, а на три комнаты зал делится на 32.
    for (const [id, def] of Object.entries(DUNGEONS_DATABASE)) {
      const зал = INTERIORS[def.interiorId]!;
      const входная = planDungeonRooms(def)[0];
      must(входная.monsters.length > 0, `${id}: входная комната пуста`);
      const спавнZ = зал.spawnZ - def.entryZ;
      // БЛИЖАЙШИЙ к игроку — это максимум по z, а не минимум: игрок
      // появляется у края зала, монстры стоят ниже. Math.min брал самого
      // дальнего и печатал зазор 10 там, где монстр стоял в точке спавна.
      const ближайший = Math.max(...входная.monsters.map((м) => м.z - def.entryZ));
      const зазор = спавнZ - ближайший;
      must(
        зазор >= SPAWN_GAP,
        `${id}: между спавном (z = ${спавнZ}) и ближайшим входным монстром ` +
          `(z = ${ближайший}) ${зазор} — меньше зазора ${SPAWN_GAP}: игрок появится вплотную к врагу`
      );
    }
  });

  it('игрок появляется выше по z, чем входные монстры', () => {
    for (const [id, def] of Object.entries(DUNGEONS_DATABASE)) {
      const зал = INTERIORS[def.interiorId]!;
      const входная = planDungeonRooms(def)[0];
      const среднийZ =
        входная.monsters.reduce((с, м) => с + м.z - def.entryZ, 0) / входная.monsters.length;
      const спавнZ = зал.spawnZ - def.entryZ;
      must(
        среднийZ < спавнZ,
        `${id}: входные монстры в среднем на z = ${среднийZ.toFixed(1)}, ` +
          `а спавн игрока на z = ${спавнZ}: игрок появляется позади врагов`
      );
    }
  });
});

describe('Оба подземелья: сундуки на схеме совпадают с данными', () => {
  /** Прямые сундуки на месте плюс элементы массива, который рисуется циклом. */
  function посчитатьСундуки(зал: string): number {
    // Запятая после cx тоже считается: сундук ворот стоит как «M.wood, cx,»,
    // и регулярка с пробелом его пропускала (6 вместо 7).
const прямые = (зал.match(/box\(1\.1, 0\.8, 0\.8, M\.wood, cx[ ,]/g) || []).length;
    const блокМассива = /const местаСундуков: \[number, number\]\[\] = \[([\s\S]*?)\];/.exec(зал);
    const вМассиве = блокМассива ? (блокМассива[1].match(/\[cx/g) || []).length : 0;
    return прямые + вМассиве;
  }

  it('сундуки пещер: 2 + 6', () => {
    const ожидается = пещеры.rooms.reduce((с, р) => с + р.treasureChests, 0);
    const нарисовано = посчитатьСундуки(залПещер);
    must(
      нарисовано === ожидается,
      `сундуков нарисовано ${нарисовано}, а в данных ${ожидается} (2 + 6)`
    );
    must(ожидается > 0, 'в данных нет сундуков: проверка холостая');
  });

  it('сундуки крепости: 1 + 2 + 4', () => {
    const ожидается = крепость.rooms.reduce((с, р) => с + р.treasureChests, 0);
    const нарисовано = посчитатьСундуки(залКрепости);
    must(
      нарисовано === ожидается,
      `сундуков нарисовано ${нарисовано}, а в данных ${ожидается} (1 + 2 + 4)`
    );
    must(ожидается > 0, 'в данных нет сундуков: проверка холостая');
  });

  it('сундук не стоит на месте босса', () => {
    // Первая версия сверяла только z и ругалась на сундук входа пещер: он в
    // z = −7.4, босс в z = −7.5 — рядом по глубине, но сундук стоит в x = −7.4,
    // а босс в x = 0. Место разное, и «рядом по z» ничего не значило.
    const пары: [typeof залПещер, typeof пещеры][] = [
      [залПещер, пещеры],
      [залКрепости, крепость],
    ];
    for (const пара of пары) {
      const зал = пара[0];
      const def = пара[1];
      const боссовая = def.rooms.find((р) => р.isBossRoom)!;
      const план = planDungeonRooms(def).find((к) => def.rooms[к.index].isBossRoom)!;
      const босс = план.monsters.find((м) => м.monsterId === боссовая.bossId);
      must(босс !== undefined, `${def.id}: босс не запланирован`);
      const боссX = босс!.x - def.entryX;
      const боссZ = босс!.z - def.entryZ;
      // Координаты сундука на схеме: сдвиг по x после «M.wood, cx» и z после
      // «cz». У части сундуков сдвига по x нет — они стоят ровно на оси, и
      // тогда группа не пишется вовсе.
      const найдены = [
        ...зал.matchAll(
          /box\(1\.1, 0\.8, 0\.8, M\.wood, cx(?: ([+-]) ([\d.]+))?, FLOOR_Y \+ [\d.]+, cz ([+-] [\d.]+)\)/g
        ),
      ];
      must(найдены.length > 0, `${def.id}: сундуков на схеме нет`);
      for (const м of найдены) {
        const x = м[1] ? (м[1] === '-' ? -Number(м[2]) : Number(м[2])) : 0;
        const z = смещение(м[3]);
        const расстояние = Math.hypot(x - боссX, z - боссZ);
        must(
          расстояние >= 2,
          def.id + ': сундук в (' + x + ', ' + z + '), босс в (' + боссX + ', ' + боссZ + '): ' +
            'сундук стоит на месте босса: игрок, подойдя к сундуку, окажется в боссе'
        );
      }
    }
  });

  it('поле treasureChests сервер не читает: сундуки — часть картинки', () => {
    // Чтобы никто не объявил это механикой. Если сервер начнёт читать поле,
    // проверка упадёт и её придётся переписать под механику.
    const сервис = читать('server/src/systems/DungeonService.ts');
    const маршруты = читать('server/src/routes/game.ts');
    must(
      !сервис.includes('treasureChests') && !маршруты.includes('treasureChests'),
      'сервер теперь читает treasureChests: сундуки перестали быть частью картинки, ' +
        'и проверку надо переписать под механику'
    );
  });
});

