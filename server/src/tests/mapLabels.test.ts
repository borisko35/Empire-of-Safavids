// Подписи на карте не наезжают друг на друга.
//
// ЧТО БЫЛО. Мир вырос до 6350x6350, холст карты 900x600, масштаб упал с
// 0.25 до 0.0945 пикселя на единицу. Всё, что рисуется шрифтом, осталось
// прежнего размера в пикселях, а полосы стали ниже. Замер показал:
//
//   полоса          высота     шрифт 20px
//   persian_gulf    248.0 px   помещается
//   mesopotamia      18.9 px   НЕ ПОМЕЩАЕТСЯ
//   tabriz           28.3 px   помещается
//   isfahan          37.8 px   помещается
//   shiraz           14.2 px   НЕ ПОМЕЩАЕТСЯ
//   caucasus         18.9 px   НЕ ПОМЕЩАЕТСЯ
//   khorasan         85.0 px   помещается
//   herat           148.8 px   помещается
//
// И подписи городов: шесть из семи пар ближе 40 пикселей, а подпись
// занимает 50-60. Самая тесная - Шираз и Кавказ, в 15.4 пикселя: наезжали
// бы гарантированно.
//
// ЧТО ПРОВЕРЯЕТСЯ. Два класса:
//   1. форма кода - жадная расстановка с measureText, а не угаданный порог;
//   2. числа - повторяется та же расстановка, что в коде, и требуется, чтобы
//      перекрытий не осталось и подписи не терялись.
//
// ЧАСТЬ ПРОВЕРКИ ПРО ЧИСЛАТА ЧЕСТНАЯ. measureText требует DOM, в серверной
// проверке недоступен, поэтому ширина подписи оценивается по кеглю и длине
// названия (0.62 от кегля на символ). Оценка заведомо щедрая: если при ней
// места хватает, то при настоящем шрифте хватит и подавно.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ZONES, getZoneAt } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const HUD = читать('client/src/app/hud.ts');
const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

// Холст карты: зашит в разметке. Читаем, а не берём из памяти - иначе
// проверка считала бы по канвасу, которого в игре уже нет.
const РАЗМЕТКА = читать('client/web/game/index.html');
const размер = /<canvas id="worldmap-canvas" width="(\d+)" height="(\d+)"/.exec(РАЗМЕТКА);
must(размер !== null, 'не нашёл canvas карты мира в разметке — проверка не знает, на чём считать');
const W = Number(размер![1]);
const H = Number(размер![2]);

const HАЛФ = Number(/export const WORLD_HALF = (\d+);/.exec(ТЕРРЕЙН)?.[1]);
must(Number.isFinite(HАЛФ) && HАЛФ > 0, 'не прочитал WORLD_HALF из terrain.ts — проверка ничего не меряет');
const масштаб = Math.min(W, H) / (HАЛФ * 2);
const toPx = (wx: number, wz: number) => ({ x: W / 2 + wx * масштаб, y: H / 2 + wz * масштаб });

/** Полосы регионов по z: та же лента, что и в hud.ts, из данных. */
function полосаРегиона(регион: string): { z1: number; z2: number } {
  const зоны = ZONES.filter((з) => з.region === регион);
  must(зоны.length > 0, `у региона ${регион} нет зон`);
  return {
    z1: Math.min(...зоны.map((з) => з.bounds.z1)),
    z2: Math.max(...зоны.map((з) => з.bounds.z2)),
  };
}

const ШИРИНА_СИМВОЛА = 0.62;
const ширинаНадписи = (надпись: string, кегль: number): number => надпись.length * кегль * ШИРИНА_СИМВОЛА;
const пересекают = (
  a: { x1: number; y1: number; x2: number; y2: number },
  b: { x1: number; y1: number; x2: number; y2: number },
): boolean => a.x1 < b.x2 && a.x2 > b.x1 && a.y1 < b.y2 && a.y2 > b.y1;

describe('Названия регионов на карте не наезжают', () => {
  it('шрифт подбирается под высоту полосы, а не стоит двадцать пунктов у всех', () => {
    // Фиксированные 20px были негодны: три полосы из восьми тоньше шрифта.
    // Первая версия починки ввела порог «полоса ниже 26 пикселей» и сдвинула
    // подпись влево - порог был угадан на глаз и оставил два наезда.
    must(/Math\.max\(9,\s*Math\.min\(20,/.test(HUD),
      'кегль названия региона не привязан к высоте полосы — в тонких полосах название не поместится');
    must(!/c\.font = 'bold 20px sans-serif';\s*\r?\n\s*для\s+\(const\s+полоса/i.test(HUD),
      'в цикле названий регионов снова фиксированный шрифт 20px');
  });

  it('расстановка жадная: меряет ширину и ищет свободное место, а не угадывает', () => {
    must(/measureText\(надпись\)/.test(HUD),
      'ширина названия региона не меряется — расстановка идёт вслепую');
    must(/занятыеНазвания/.test(HUD),
      'нет списка занятых мест: подписи регионов не проверяются на пересечение');
    // Минимум три столбца: с одним и двумя наезд не избежать, а столбцы
    // стоят копейки.
    const столбцов = /СТОЛБЦЫ\s*=\s*\[([^\]]*)\]/.exec(HUD)?.[1]?.split(',').filter(Boolean).length ?? 0;
    must(столбцов >= 3, `столбцов для расстановки ${столбцов}, нужно минимум 3 - иначе наезды вернутся`);
  });

  it('все восемь названий наносятся и ни одно не наезжает на другое', () => {
    // Повторяем расстановку кода на данных, а не доверяем коду на слово.
    const регионы = [...new Set(ZONES.map((з) => з.region))];
    const занятые: { x1: number; y1: number; x2: number; y2: number }[] = [];
    const столбцы = [W / 2, W * 0.25, W * 0.75, W * 0.12, W * 0.88];
    let нанесено = 0;
    const неНанесены: string[] = [];

    for (const регион of регионы) {
      const полоса = полосаРегиона(регион);
      const верх = toPx(0, полоса.z1).y;
      const низ = toPx(0, полоса.z2).y;
      const высота = Math.abs(низ - верх);
      const кегль = Math.max(9, Math.min(20, Math.round(высота - 4)));
      const надпись = регион; // длина строки влияет только на ширину
      const половина = ширинаНадписи(надпись, кегль) / 2 + 4;
      const y = (верх + низ) / 2;
      let нанесён = false;
      for (const столбец of столбцы) {
        const пр = { x1: столбец - половина, y1: y - кегль, x2: столбец + половина, y2: y + кегль * 0.4 };
        if (пр.x1 < 2 || пр.x2 > W - 2) continue;
        if (!занятые.some((з) => пересекают(пр, з))) {
          занятые.push(пр);
          нанесён = true;
          break;
        }
      }
      if (нанесён) нанесено++; else неНанесены.push(регион);
    }

    must(неНанесены.length === 0,
      `названия этих регионов не поместились ни в один столбец:\n  ${неНанесены.join('\n  ')}`);
    must(нанесено === регионы.length,
      `нанесено ${нанесено} названий из ${регионы.length}`);

    // И главное: пересечений быть не должно вообще.
    let перекрытий = 0;
    for (let i = 0; i < занятые.length; i++) {
      for (let j = i + 1; j < занятые.length; j++) {
        if (пересекают(занятые[i], занятые[j])) перекрытий++;
      }
    }
    must(перекрытий === 0, `названия регионов перекрываются в ${перекрытий} парах`);
  });

  it('высоты полос действительно разной, иначе проверка выше ничего не значит', () => {
    // Объявление исходного состояния. Если бы все полосы были одной высоты,
    // проверка на расстановку проходила бы вхолостую: наездов не было бы
    // и без починки.
    const высоты = [...new Set(ZONES.map((з) => з.region))].map((регион) => {
      const п = полосаРегиона(регион);
      return Math.abs(toPx(0, п.z2).y - toPx(0, п.z1).y);
    });
    const самаяНизкая = Math.min(...высоты);
    const самаяВысокая = Math.max(...высоты);
    must(высоты.length >= 8, `регионов ${высоты.length}, а проверка ждёт восемь`);
    must(самаяВысокая > самаяНизкая * 2,
      `высоты полос почти равны (${самаяНизкая.toFixed(1)} и ${самаяВысокая.toFixed(1)}) — наездов не бывает и без починки, проверка холостая`);
    must(самаяНизкая < 20,
      `самая узкая полоса ${самаяНизкая.toFixed(1)} px - фиксированный шрифт 20px в неё поместился бы, и проверка на подгонку кегля ничего бы не ловила`);
  });
});

describe('Подписи поселений на карте не наезжают', () => {
  it('значок рисуется всегда, даже если подписи некуда поставить', () => {
    // Порядок важен. Если бы проверка занятости стояла до отрисовки значка,
    // то при нехватке места пропал бы сам значок - то есть игрок не видел бы
    // города вообще. Значок важнее подписи: где город - это факт, а как он
    // называется - можно прочесть в подсказке.
    // Ориентир — отказ от подписи `if (yПодписи === null) continue;`. Он есть
    // только в цикле карты мира, тогда как список занятых подписей ОБЪЯВЛЯЕТСЯ
    // ДО цикла. Я сначала цеплялся за объявление и искал перед ним последний
    // цикл поселений — и попадал в цикл мини-карты, где расстановки нет вовсе.
    // Значит порядок обратный: сначала отказ, потом цикл перед ним.
    const отказ = HUD.indexOf('if (yПодписи === null) continue;');
    must(отказ > 0, 'в hud.ts нет отказа от подписи — некуда поставить подпись, и она ляжет поверх соседней');
    const начало = HUD.lastIndexOf('for (const s of MINIMAP_SETTLEMENTS)', отказ);
    must(начало > 0, 'не нашёл цикл поселений карты мира');
    const цикл = HUD.slice(начало, отказ);
    const значок = цикл.indexOf('ctx.fillText(s.icon');
    const проверка = цикл.indexOf('занятыеПодписи');
    must(значок > 0, 'в цикле поселений карты мира не найдена отрисовка значка');
    must(проверка > 0, 'в цикле поселений не найдена проверка занятости подписи');
    must(значок < проверка,
      'проверка занятости идёт ДО отрисовки значка: при нехватке места пропадёт значок, и город будет не виден вовсе');
  });

  it('подпись сдвигается, а не наезжает, и пропускается, а не лезет поверх', () => {
    must(/const сдвиг of \[12, -12, 24, -24/.test(HUD),
      'подписи поселений не сдвигаются при наезде — они накладываются друг на друга');
    must(/if \(yПодписи === null\) continue;/.test(HUD),
      'нет отказа от подписи при нехватке места: она ляжет поверх соседней');
  });

  it('ни одна пара поселений не налезает даже при самом скромном размещении подписи', () => {
    // Повторяем расстановку кода на настоящих координатах поселений.
    // Все поселения читаются из terrain.ts - и девять городов регионов, и
    // старые шесть. Если кто-то поставит город в десяти единицах от соседнего,
    // эта проверка скажет об этом с именами.
    const городаРегионов = [...ТЕРРЕЙН.matchAll(/\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+)/g)]
      .map((м) => ({ имя: `город ${м[1]}`, x: Number(м[2]), z: Number(м[3]) }));
    // Девять, а не десять: регионов десять, но Исфахан - столица, её строит
    // buildCity, а не buildRegionTowns. Проверка на десять городов в
    // REGION_TOWNS была бы неверной и заставила бы добавить лишний город.
    must(городаРегионов.length === 9,
      `городов регионов в terrain.ts ${городаРегионов.length}, а ожидалось 9 — столица Исфахана строится отдельно, buildCity`);

    // Старые поселения: константы вида export const CITY = { x: 34, z: 26, ... }
    const старые = [...ТЕРРЕЙН.matchAll(/export const (CITY|CAMP|PORT|CARAVANSERAI|VILLAGE|FORT)\b[^=]*=\s*\{[^}]*?x:\s*(-?\d+),\s*z:\s*(-?\d+)/g)]
      .map((м) => ({ имя: м[1], x: Number(м[2]), z: Number(м[3]) }));
    must(старые.length === 6,
      `старых поселений прочитано ${старые.length}, а ожидалось 6 — вид констант в terrain.ts изменился`);

    const все = [...городаРегионов, ...старые];
    // Подпись «bold 12px»: длиннейшая - «Караван-сарай», 14 символов.
    const кегль = 12;
    const занятые: { x1: number; y1: number; x2: number; y2: number }[] = [];
    let нанесено = 0;
    const неНанесены: string[] = [];

    // Список кандидатов на сдвиг — тот же, что в коде. Восьми сдвигов
    // (12..48) не хватало: в центре карты шесть поселений в пятне 150x90
    // пикселей, и CAMP, CARAVANSERAI и VILLAGE остались без названия.
    // Расширено до восемнадцати: на холсте 600 пикселей место есть,
    // алгоритм просто переставал пробовать раньше времени.
    const СДВИГИ = [12, -12, 24, -24, 36, -36, 48, -48, 60, -60, 72, -72, 84, -84, 96, -96, 108, -108];
    must(HUD.includes('108, -108]'),
      `в коде список сдвигов короче ${СДВИГИ.length} — некоторым поселениям некуда будет поставить подпись`);

    for (const поселение of все) {
      const { x, y } = toPx(поселение.x, поселение.z);
      // Оценка ширины щедрая: считаем, что любое название — 14 символов.
      const половина = ширинаНадписи('Караван-сарай', кегль) / 2 + 3;
      let нанесён = false;
      for (const сдвиг of СДВИГИ) {
        const проба = y - сдвиг;
        const пр = { x1: x - половина, y1: проба - 11, x2: x + половина, y2: проба + 4 };
        if (проба < 12 || проба > H - 4) continue;
        if (!занятые.some((з) => пересекают(пр, з))) {
          занятые.push(пр);
          нанесён = true;
          break;
        }
      }
      if (нанесён) нанесено++; else неНанесены.push(поселение.имя);
    }

    must(неНанесены.length === 0,
      `подписи не поместились, поселений осталось без названия: ${неНанесены.join(', ')}`);
    must(нанесено === все.length,
      `подписано ${нанесено} поселений из ${все.length}`);

    let перекрытий = 0;
    const пары: string[] = [];
    for (let i = 0; i < занятые.length; i++) {
      for (let j = i + 1; j < занятые.length; j++) {
        if (пересекают(занятые[i], занятые[j])) {
          перекрытий++;
          пары.push(`${все[i].имя} и ${все[j].имя}`);
        }
      }
    }
    must(перекрытий === 0, `подписи поселений перекрываются:\n  ${пары.join('\n  ')}`);
  });

  it('каждое поселение лежит в мире, а не за его краем', () => {
    // Проверка на чистоту данных: город за краем мира не нарисовался бы, а
    // подпись уехала бы за холст и была бы срезана.
    const все = [...ТЕРРЕЙН.matchAll(/\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+)/g)]
      .map((м) => ({ имя: `город ${м[1]}`, x: Number(м[2]), z: Number(м[3]) }));
    const заКраем: string[] = [];
    for (const п of все) {
      if (Math.abs(п.x) > HАЛФ || Math.abs(п.z) > HАЛФ) {
        заКраем.push(`${п.имя} (${п.x}, ${п.z})`);
      }
      // И обязан быть в зоне: иначе подпись есть, а зоны нет.
      const зона = getZoneAt(п.x, п.z);
      if (зона === null) заКраем.push(`${п.имя} вне всякой зоны`);
    }
    must(заКраем.length === 0, `поселения не на своём месте:\n  ${заКраем.join('\n  ')}`);
  });
});
