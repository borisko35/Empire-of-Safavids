// Продавцы за прилавками в городах регионов.
//
// ЧТО БЫЛО (21 октября 2026, §260). Жители городов стояли только в трёх
// городах из девяти, а торговые ряды в остальных шести стояли с товаром и без
// продавцов. Базар без продавца — декорация, а не базар.
//
// ЧТО ТЕПЕРЬ. Жители есть во всех девяти городах и стоят за торговыми рядами
// (углы рядов — 0, 90, 180 и 270 градусов от центра города).
//
// ГЛАВНОЕ ПРАВИЛО. Житель должен стоять В СВОЕЙ ЗОНЕ. Полосы регионов идут по
// z, и город у края полосы наполовину лежит в соседнем регионе: житель в чужой
// зоне — это уже не его город, и игрок увидит чужой регион. Углы у края зоны
// (Шираз, Месопотамия, Залив) подобраны так, чтобы все фигуры оставались в
// своей полосе.
//
// ЧТО ПРОВЕРЯЕТСЯ. Жители есть во всех городах; каждый стоит у торгового ряда;
// и ни одна фигура не вышла за границу своей зоны.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { getZoneAt } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts') + читать('shared/terrainHeight.ts');
const ЖИТЕЛИ = читать('client/src/app/game3d/townfolk.ts');

interface Город {
  region: string;
  x: number;
  z: number;
  radius: number;
}

const ГОРОДА: Город[] = [...ТЕРРЕЙН.matchAll(/\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+), radius: (\d+)/g)]
  .map(m => ({ region: m[1], x: +m[2], z: +m[3], radius: +m[4] }));

const СПИСКИ: { region: string; углы: number[] }[] = [
  ...ЖИТЕЛИ.matchAll(/\{ region: '([a-z_]+)', углы: \[([^\]]*)\] \}/g),
].map(m => ({ region: m[1], углы: m[2].split(',').map(v => +v.trim()) }));

/** Радиус, на котором стоят жители (общий с кодом townfolk). */
const КОЛЬЦО = 0.42;

describe('Продавцы в городах регионов', () => {
  it('жители есть в каждом городе региона', () => {
    должен(
      СПИСКИ.length === ГОРОДА.length,
      `жители есть в ${СПИСКИ.length} городах, а городов ${ГОРОДА.length}`,
    );
    for (const город of ГОРОДА) {
      const свои = СПИСКИ.find(s => s.region === город.region);
      должен(свои, `в городе ${город.region} жителей нет`);
      должен(свои!.углы.length >= 3, `в городе ${город.region} всего ${свои!.углы.length} жителей`);
    }
  });

  it('жители стоят за торговыми рядами', () => {
    // Ряды в городах регионов стоят на углах 0, 90, 180 и 270 градусов.
    const ряды = [0, 90, 180, 270];
    for (const город of СПИСКИ) {
      const уРяда = город.углы.filter(угол => ряды.includes(угол));
      должен(
        уРяда.length >= 2,
        `в городе ${город.region} у рядов стоит ${уРяда.length} жителей: базар без продавцов`,
      );
    }
  });

  it('ни один житель не вышел за границу своей зоны', () => {
    const чужие: string[] = [];
    for (const город of СПИСКИ) {
      const t = ГОРОДА.find(g => g.region === город.region);
      if (!t) continue;
      for (const градус of город.углы) {
        const угол = (градус * Math.PI) / 180;
        const x = Math.round(t.x + Math.cos(угол) * t.radius * КОЛЬЦО);
        const z = Math.round(t.z + Math.sin(угол) * t.radius * КОЛЬЦО);
        const зона = getZoneAt(x, z);
        if (!зона || зона.region !== город.region) {
          чужие.push(`${город.region} ${градус}° -> (${x}, ${z}) зона ${зона ? зона.region : 'НЕТ'}`);
        }
      }
    }
    должен(чужие.length === 0, `жители стоят не в своей зоне:\n  ${чужие.join('\n  ')}`);
  });
});
