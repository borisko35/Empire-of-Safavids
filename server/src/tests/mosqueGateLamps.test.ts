// Фонари у входа в мечетный двор и огни у ворот крепостей.
//
// ЧТО БЫЛО (21 октября 2026, §252). У входа в мечетный двор стояли свои
// столб, чаша и шар огня: без стеклянного фонаря и без источника света — тот
// же дефект, что был у фонарей садов в §249. А у кавказского форпоста и
// Багдадской цитадели стояли золотые чаши без пламени: ворота крепости ночью
// стояли чёрными.
//
// ЧТО ТЕПЕРЬ. Фонари мечети — общие, со стеклом, колпаком и огнём, и со
// своим источником света. У сторожевых факелов крепостей — пламя и свой
// источник света.
//
// ЧТО ПРОВЕРЯЕТСЯ. Фонари мечети построены общим фонарём (свои столбы без
// стекла вернутся), у всех этих огней есть источники света по ночному
// правилу, и world3d создаёт их по спискам огней террейна.
//
// Проверка смотрит ТОЛЬКО свои разделы кода: строки фонарей в городе совпадают
// слово в слово, и без границы проверка цепляла бы чужой блок (см. §247).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

/** Кусок кода своего раздела: метки разделов — комментарии, ищем по исходнику. */
function свойРаздел(код: string, начало: string, конец: string): string {
  const от = код.indexOf(начало);
  должен(от >= 0, `в коде нет раздела «${начало}»`);
  const до = код.indexOf(конец, от);
  должен(до > от, `в коде нет раздела «${конец}» после «${начало}»`);
  return код.slice(от, до).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const МЕЧЕТЬ = свойРаздел(
  ТЕРРЕЙН,
  '// Два фонаря у входа: тёплый свет на ступенях.',
  '// ── Факелы у ворот караван-сарая',
);
const КАВКАЗ = свойРаздел(
  ТЕРРЕЙН,
  '// Огонь в факеле и свой источник света (§252): стояла золотая чаша без',
  '// Стена с зубцами по бокам двора.',
);
const БАГДАД = свойРаздел(
  ТЕРРЕЙН,
  '// Огонь в факеле и свой источник света (§252): как у кавказского',
  '// Стена с зубцами по бокам двора.',
);
const ИСТОЧНИКИ = свойРаздел(
  МИР,
  '// Фонари у входа в мечетный двор (§252)',
  '// Акведук деревни',
);

describe('Фонари мечети и огни у ворот крепостей', () => {
  it('фонари мечети — общие, со стеклом и огнём', () => {
    должен(/const высотаОгня = фонарь\(scene, x, z\);/.test(МЕЧЕТЬ),
      'фонари мечети построены своими столбами без стекла');
    должен(
      !/new THREE\.CylinderGeometry\(0\.12, 0\.16, 3\.2/.test(МЕЧЕТЬ),
      'у входа в мечетный двор снова свой столб фонаря без стекла',
    );
    должен(/огни\.push\(\{ x, y: высотаОгня, z \}\);/.test(МЕЧЕТЬ),
      'фонари мечети не отдают огни');
  });

  it('у сторожевых факелов крепостей есть пламя и свой огонь', () => {
    должен(/const пламяКавказ = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.2, 8, 6\), MAT\.lampGlow\)/.test(КАВКАЗ),
      'у факела кавказского форпоста нет пламени');
    должен(/x: CAUCASUS_FORT\.x \+ px,/.test(КАВКАЗ), 'у кавказского форпоста нет огня');
    должен(/const пламяБагдад = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.22, 8, 6\), MAT\.lampGlow\)/.test(БАГДАД),
      'у факела багдадской цитадели нет пламени');
    должен(/x: BAGHDAD_CITADEL\.x \+ px,/.test(БАГДАД), 'у багдадской цитадели нет огня');
  });

  it('источники создаются по спискам огней и горят по ночному правилу', () => {
    должен(
      /export function buildMosqueCourtyard\(scene: THREE\.Scene\): \{ x: number; y: number; z: number \}\[\]/.test(ТЕРРЕЙН),
      'buildMosqueCourtyard не возвращает огни: источники создать не из чего',
    );
    должен(
      /for \(const \[i, огонь\] of огниДвора\.entries\(\)\)/.test(ИСТОЧНИКИ),
      'источники света двора мечети не создаются по списку огней',
    );
    должен(
      /const light = new THREE\.PointLight\(0xffa04a, 0, 20, 1\.8\);/.test(ИСТОЧНИКИ),
      'источники света двора мечети не создаются',
    );
    должен(/this\.scene\.add\(light\);/.test(ИСТОЧНИКИ), 'источники света двора мечети не в сцене');
    должен(
      /this\.torches\.push\(\{ light, base: 1\.6, phase: i \* 2\.4 \+ 2\.1 \}\)/.test(ИСТОЧНИКИ),
      'огни двора мечети не горят по ночному правилу',
    );
  });
});
