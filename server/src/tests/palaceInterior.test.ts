// Дворец: дверь одна и та же на клиенте и на сервере, тронный зал обставлен.
//
// ЧТО ЗАЩИЩАЕТ. Три молчаливых поломки, каждая из которых выглядит как готовая
// работа. Ровно они уже случались в проекте: дверь нарисована у одной комнаты,
// а войти игрок в другую; стена сдвинулась у одного здания и молча испортила
// десять других.
//
// ЧТО ПРОВЕРЯЕМ ПО-НАСТОЯЩЕМУ.
//   1. Место двери сухое — водой замерено настоящим waterMask, а не на глаз.
//   2. Слот комнаты и соседство записей: слот считается индексом в SPOTS, и
//      он обязан совпадать с числом, зашитым на сервере.
//   3. Тронный зал действительно обставлен, а страж действительно нарисован
//      там, где стоит пост в правиле.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';
import { waterMask } from '../../../shared/water';
import { GUARD_POSTS, DOCUMENT_SPOTS } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

describe('Дворец: место подобрано измерением, а не на глаз', () => {
  it('дверь стоит на сухой земле', () => {
    const def = INTERIORS.palace;
    must(def !== undefined, 'на сервере нет записи palace: дверь есть, а войти некуда');
    // Здесь 0 означает «сухо»: waterMask растёт к единице в воде. Кандидат
    // (-40, -700) был отпаден именно потому, что давал 0.1488 — там река.
    const влажность = waterMask(def.doorX, def.doorZ);
    must(
      влажность === 0,
      `у двери дворца (${def.doorX}, ${def.doorZ}) влажность ${влажность.toFixed(4)}, ` +
        'а должно быть 0.0000: стена встанет в воду, и дверь перестанет открываться'
    );
  });

  it('проверка места не пустая: вода там, где её ждут', () => {
    // Обратная сторона той же проверки. Если бы waterMask вообще ничего не
    // возвращал, условие «влажность === 0» проходило бы всегда.
    must(waterMask(-420, -160) > 0.9, 'озеро в (-420, -160) перестало быть водой: вода посчитана неверно');
    must(waterMask(620, 300) > 0.9, 'пруд в (620, 300) перестал быть водой: вода посчитана неверно');
    const def = INTERIORS.palace!;
    must(
      waterMask(def.doorX, def.doorZ) < waterMask(-420, -160),
      'сухая дверь дворца посчиталась мокрее центра озера: сравнение бессмысленно'
    );
  });
});

describe('Дворец: слот и дверь совпадают на клиенте и на сервере', () => {
  it('дворец держит одиннадцатый слот на обеих сторонах', () => {
    const ключи = Object.keys(INTERIORS);
    const слотСервер = ключи.indexOf('palace');
    must(слотСервер === 11, `дворец на слоте ${слотСервер} из ${ключи.length}, а обязан быть одиннадцатым`);

    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    const слотКлиент = записи.indexOf('palace');
    must(
      слотКлиент === слотСервер,
      `на клиенте дворец на слоте ${слотКлиент}, а на сервере ${слотСервер}: ` +
        'дверь нарисована у одной комнаты, а войти игрок будет в другую'
    );
  });

  it('крепость и караван-сарай не сдвинулись', () => {
    const ключи = Object.keys(INTERIORS);
    must(ключи[9] === 'caravanserai', `на девятом слоте ${ключи[9]}, а не караван-сарай`);
    must(ключи[10] === 'fortress', `на десятом слоте ${ключи[10]}, а не крепость`);
    must(INTERIORS.caravanserai!.roomCx === 4396, `у караван-сарая roomCx ${INTERIORS.caravanserai!.roomCx}, а слот 9 даёт 4396`);
    must(INTERIORS.fortress!.roomCx === 4440, `у крепости roomCx ${INTERIORS.fortress!.roomCx}, а слот 10 даёт 4440`);
    must(INTERIORS.palace!.roomCx === 4484, `у дворца roomCx ${INTERIORS.palace!.roomCx}, а слот 11 даёт 4484`);
  });

  it('координаты двери совпадают на клиенте и на сервере', () => {
    const def = INTERIORS.palace!;
    const своя = /id: 'palace', kind: 'palace',[\s\S]{0,140}?dx: (-?\d+), dz: (-?\d+)/.exec(клиент);
    must(своя !== null, 'у записи дворца на клиенте нет абсолютной двери: она снова посчитается от столицы');
    must(
      Number(своя![1]) === def.doorX && Number(своя![2]) === def.doorZ,
      `клиент рисует дверь в (${своя![1]}, ${своя![2]}), а сервер ждёт ` +
        `(${def.doorX}, ${def.doorZ}): игрок подойдёт к одной двери, а попадёт в другую`
    );
  });

  it('комната не налезает на соседние', () => {
    const def = INTERIORS.palace!;
    const чужие = Object.values(INTERIORS).filter((д) => д.id !== 'palace');
    const тесные = чужие.filter((д) =>
      Math.abs(д.roomCx - def.roomCx) < 32 && Math.abs(д.roomCz - def.roomCz) < 32
    );
    must(тесные.length === 0, `комната дворца налезает на: ${тесные.map((д) => д.id).join(', ')}`);
  });

  it('граница кармана покрывает новую комнату', () => {
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+), z0: (-?\d+), z1: (\d+) \}/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден: под комнатой не будет земли');
    const x1 = Number(прямоугольник![2]);
    // Граница — центр последней комнаты, а не её край: так было и раньше.
    must(
      // Правый край комнаты, а не центр: полкомнаты 16.
      x1 >= INTERIORS.palace!.roomCx + INTERIORS.palace!.roomHalf,
      `правый край кармана ${x1}, а правый край комнаты ` +
        `${INTERIORS.palace!.roomCx + INTERIORS.palace!.roomHalf}: под комнатой нет земли`
    );
  });
});

describe('Дворец: тронный зал обставлен и охраняется', () => {
  it('функция обстановки заведена и вызывается для дворца', () => {
    must(/function furnishPalace\(/.test(клиент), 'функции обстановки дворца нет');
    must(/palace: furnishPalace,/.test(клиент), 'дворец не прописан в выборе обстановки: он получил бы чужую комнату');
    must(/'palace'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 400) ?? ''),
      'в типе BuildingKind нет дворца');
  });

  it('в тронном зале есть трон, колонны и библиотека', () => {
    const начало = клиент.indexOf('function furnishPalace(');
    must(начало > 0, 'функция обстановки дворца не найдена');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 4000);
    // Что обещано в описании и в задании владельца.
    must(/i < 10/.test(тело), 'в обстановке нет ряда из десяти колонн: дворец обещает колонны');
    must(/M\.gold/.test(тело), 'у трона нет золотой отделки: тронный зал выглядит как конюшня');
    must(/M\.hay|M\.red/.test(тело), 'в зале нет книг и ковра: библиотека из списка не построена');
    // Трон — готовая модель с текстурой, а не коробки: рендер в Blender
    // подтвердил фас, смотрит в +Z, то есть ровно на дверь. Коллайдер
    // на месте трона оставлен.
    must(
      /loadThroneModel\(\)\.then/.test(тело),
      'трон не грузится моделью: в зале стоят процедурные коробки вместо готовой модели'
    );
    must(
      /трон\.position\.set\(cx, FLOOR_Y, cz - 8\);/.test(тело),
      'модель трона стоит не на месте процедурного (cx, cz − 8): коллайдер и ковёр разойдутся с ней'
    );
    must(
      /cols\.push\(\{ x: cx, z: cz - 8, r: 1\.4 \}\);/.test(тело),
      'коллайдер трона убран: сквозь трон ходят пешком'
    );
    // Путь модели сверяется с манифестом и диском: опечатка в пути — и зал
    // стоит с пустым ковром, а проверка молчит. Константа на уровне модуля,
    // поэтому ищется по всему файлу, а не в теле обстановки.
    const путь = /const THRONE_MODEL = '([^']+)';/.exec(клиент)?.[1];
    must(путь !== undefined, 'константа пути трона не найдена: модель грузится неизвестно откуда');
    const манифест = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
      decor?: { file: string; name: string; bytes: number }[];
    };
    must(
      (манифест.decor ?? []).some((з) => з.file === `models/${путь}`),
      `путь трона ${путь} не ведёт в запись decor манифеста: файл и код разойдутся молча`
    );
    // Колонн обещано двадцать: десять в ряду, два ряда. Проверяем формулой.
    const рядов = (тело.match(/for \(let i = 0; i < (\d+); i\+\+\)/g) || []).length;
    must(рядов >= 1, 'у колонн нет счётчика: их число ничем не задано');
  });

  it('у поста стража дворца есть видимая фигура', () => {
    // Инвариант проекта: у каждого поста есть кто-то, кого видит игрок. Здесь
    // фигуру рисует обстановка, а не NPC_GROUPS.
    must(
      /buildHumanoid\(\{ robe: 0x2f3f6e/.test(клиент),
      'в обстановке дворца нет фигуры стража: пост есть, а видно никого'
    );
    const пост = GUARD_POSTS.find((п) => п.id === 'npc_palace_guard');
    must(пост !== undefined, 'поста npc_palace_guard нет в правиле стелса: дворец не охраняется');
    // Координата фигуры обязана совпасть с постом по формуле комнаты.
    const cx = INTERIORS.palace!.roomCx;
    const cz = INTERIORS.palace!.roomCz;
    must(
      пост!.x === cx - 8 && пост!.z === cz + 6,
      `пост дворца стоит (${пост!.x}, ${пост!.z}), а фигура рисуется в (${cx - 8}, ${cz + 6}): ` +
        'игрок увидит стража не там, где вас заметят'
    );
  });

  it('тайные документы лежат в тронном зале, а не в крепости', () => {
    // Задание владельца: документы во дворцовом комплексе. Пока дворца не было,
    // стол стоял в крепости — теперь он там, где просили.
    const стол = DOCUMENT_SPOTS.find((с) => с.buildingId === 'palace');
    must(стол !== undefined, 'в дворце нет стола с документами: обещание задания не выполнено');
    const вКрепости = DOCUMENT_SPOTS.filter((с) => с.buildingId === 'fortress');
    must(
      вКрепости.length === 0,
      'стол с документами остался в крепости: он стоит там, где владелец его не просил'
    );
  });

  it('название дворца переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.palace === 'string' && словарь.buildings.palace.length > 0,
        `в ${код}.json нет названия buildings.palace: игрок увидит пустое место`
      );
    }
  });
});


describe('Дворец: мебель внутри комнаты 22x16', () => {
  // Комнаты зданий строятся 22x16 (стены на ±11/±8), а ряд колонн шёл с шагом
  // 2.05 от −9: последняя пара вставала на +9.45, то есть за южной стеной, и
  // её не было видно — при обещанных двадцати сосчитанных колоннах. Жаровни
  // стояли там же, за стеной. Мебель за стеной — это невидимые коллайдеры.
  const начало = клиент.indexOf('function furnishPalace(');
  // Тело — до следующей функции обстановки: дальше идут мечеть и остальные,
  // и их жаровни попали бы в счёт дворца (четыре вместо двух).
  const конец = клиент.indexOf('\nfunction furnish', начало + 1);
  const тело = клиент.slice(начало, конец > 0 ? конец : начало + 4000);

  it('ряд колонн сжат в комнату, их по-прежнему двадцать', () => {
    const шаг = /const pz = cz - ([\d.]+) \+ i \* ([\d.]+);/.exec(тело);
    must(шаг !== null, 'формула ряда колонн не найдена: проверка слепа');
    const старт = Number(шаг[1]);
    const шагРяда = Number(шаг[2]);
    const рядов = Number(/for \(let i = 0; i < (\d+); i\+\+\)/.exec(тело)?.[1]);
    must(рядов === 10, `колонн в ряду ${рядов}, а обещано 10`);
    // Ряд идёт от −старт до −старт + (n−1)·шаг: край — больший из концов.
    // Ошибка первой версии: считался старт + (n−1)·шаг без минуса, и край
    // выходил 20.5 вместо 7 — проверка падала на верном коде.
    const край = Math.max(старт, -старт + (рядов - 1) * шагРяда);
    must(
      край <= 8 - 0.7,
      `последняя колонна ряда на ${край}: при стене на +8 и радиусе 0.7 она за стеной`
    );
    must(
      /for \(const side of \[-1, 1\]\)/.test(тело),
      'второго ряда колонн нет: колонн десять, а не двадцать'
    );
  });

  it('жаровни стоят у входа внутри зала', () => {
    const жаровни = [...тело.matchAll(/brazier\(g, cx ([+-]) ([\d.]+), cz ([+-]) ([\d.]+), FLOOR_Y\);/g)];
    must(жаровни.length === 2, `жаровен нарисовано ${жаровни.length}, а у входа их две`);
    for (const ж of жаровни) {
      const x = (ж[1] === '-' ? -1 : 1) * Number(ж[2]);
      const z = (ж[3] === '-' ? -1 : 1) * Number(ж[4]);
      must(
        Math.abs(x) <= 11 && Math.abs(z) <= 8,
        `жаровня в (${x}, ${z}): за стеной комнаты 22x16 её не видно`
      );
    }
  });
});
