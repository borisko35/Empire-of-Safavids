// Городская стена: настоящая кладка из модели удвоенного размера.
//
// ЧТО БЫЛО. Стена была `CylinderGeometry(116, 116, высота, 192, 1, true, ...)`
// — оболочкой нулевой толщины высотой 6 м, по гребню которой стояли 168
// кубов 1.6 × 0.8 × 0.6 м. Силуэт читался как жестяная обшивка, а не как
// крепость: сквозь стену не было видно, сколько она занимает места, и рядом
// с ней нечего было поставить.
//
// ЧТО СТАЛО. 22 сегмента настоящей модели `decor/Wall-Type01.glb`, все
// размеры удвоены по решению владельца от 08.10.2026: гребень 12 м, уход в
// грунт 3 м, толщина 13.06 м, ширина сегмента 33.30 м, зубцы 84 шт по
// 3.2 × 1.6 × 1.2 м. Одна загрузка модели, 22 копии.
//
// ГЛАВНОЕ, ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, — НЕ ФОРМА КОДА, А СООТВЕТСТВИЕ ЧИСЛАМ
// НАСТОЯЩЕГО ФАЙЛА. Масштаб, число сегментов и радиус коллайдера выведены из
// габаритов GLB, который лежит в репозитории. Если модель перегонят заново,
// проверки обязаны упасть и заставить пересчитать числа руками, а не поехать
// молча с неверным масштабом.
//
// И ВТОРОЕ, НЕ МЕНЕЕ ВАЖНОЕ: ЩЕЛИ МЕЖДУ СЕГМЕНТАМИ. Прямые отрезки на
// окружности либо расходятся (щель — видно сквозь неё город), либо налезают
// друг на друга (не видно вовсе). Здесь выводится, что налезают, и это
// утверждается числом, а не «вроде должно сойтись».
