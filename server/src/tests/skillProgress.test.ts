// Прокачка навыков: арифметика уровней и правила начисления.
//
// Арифметика вынесена в чистые функции именно ради этих проверок: сдвиг на
// единицу в пороге не виден ни в описании навыка, ни в панели, и заметить
// его можно было бы только по ощущению, что прокачка «какая-то не такая».
import { applySkillXp, skillXpForNextLevel, SKILL_XP_DAMAGE_STEP } from '../services/SkillsService';

describe('Порог опыта растёт, а не стоит', () => {
  it('каждый следующий уровень дороже предыдущего', () => {
    // Прежде было level * 100: десять, двадцать, тридцать. Само по себе
    // неплохо, но остаток при повышении считался по новому уровню, и на
    // втором уровне игрок получал лишнее. Порог теперь явно растущий.
    const costs = [1, 2, 3, 4, 5].map(skillXpForNextLevel);
    expect({ стоимости: costs, растут: costs.every((c, i) => i === 0 || c > costs[i - 1]) })
      .toEqual({ стоимости: [100, 150, 200, 250, 300], растут: true });
  });
});

describe('Переход через уровень', () => {
  it('ровно на пороге — уровень взят, остатка нет', () => {
    expect(applySkillXp(1, 0, 100)).toEqual({ level: 2, xp: 0, levelsGained: 1 });
  });

  it('на единицу меньше порога — уровень не взят', () => {
    // Регрессия на старой арифметике: там порог считался по старому
    // уровню, а остаток вычитался по новому, и граница «ровно / на единицу
    // меньше» вела себя по-разному на разных уровнях.
    expect(applySkillXp(1, 0, 99)).toEqual({ level: 1, xp: 99, levelsGained: 0 });
  });

  it('остаток переносится на следующий уровень', () => {
    const r = applySkillXp(1, 0, 250);
    // 250: сначала съедается 100 за первый уровень, остаётся 150; на втором
    // порог 150 — съедается целиком, остаётся 0, уровень 3.
    expect(r).toEqual({ level: 3, xp: 0, levelsGained: 2 });
  });

  it('остаток не пропадает при неполном переходе', () => {
    const r = applySkillXp(1, 0, 130);
    expect(r).toEqual({ level: 2, xp: 30, levelsGained: 1 });
  });

  it('сложенный остаток не теряется', () => {
    // Пять раз по 30 — это 150: уровень 2, остаток 50. Если бы каждая
    // порция считалась сама по себе, получалось бы 30 плюс пять раз, и
    // игрок, бьющий чаще, качался бы быстрее просто из-за частоты.
    //
    // levelsGained суммируется отдельно: в состоянии хранятся только
    // уровень и остаток, а levelsGained у последней порции равен нулю —
    // уровень-то взяло на второй. Присваивать его в состояние значило бы
    // сравнивать разные вещи.
    let level = 1;
    let xp = 0;
    let totalGained = 0;
    for (let i = 0; i < 5; i++) {
      const r = applySkillXp(level, xp, 30);
      level = r.level;
      xp = r.xp;
      totalGained += r.levelsGained;
    }
    expect({ уровень: level, остаток: xp, всего_уровней_взято: totalGained })
      .toEqual({ уровень: 2, остаток: 50, всего_уровней_взято: 1 });
  });
});

describe('Границы', () => {
  it('потолок 50 держится, опыт не уходит в бесконечный рост', () => {
    const r = applySkillXp(49, 0, 10_000_000);
    expect({ уровень: r.level, не_выше_потолка: r.level <= 50 }).toEqual({ уровень: 50, не_выше_потолка: true });
  });

  it('отрицательный опыт не отнимает уровень', () => {
    // Приходит из пакета или из-за ошибки в расчёте. Уровень упасть не должен.
    const r = applySkillXp(5, 200, -1000);
    expect({ уровень: r.level, опыт_не_отрицателен: r.xp >= 0 }).toEqual({ уровень: 5, опыт_не_отрицателен: true });
  });

  it('нулевой уровень в базе не ломает расчёт', () => {
    // character_skills.level — обычная колонка без ограничения снизу, и
    // ручная правка или миграция могли оставить там 0. Формула обязана
    // начинать с первого уровня, а не считать порог от нуля.
    const r = applySkillXp(0, 0, 100);
    expect({ уровень: r.level, остаток: r.xp }).toEqual({ уровень: 2, остаток: 0 });
  });

  it('бесконечный опыт не вешает цикл', () => {
    // Цикл while с шагом level++ и порогом, зависящим от level, обязан
    // сходиться. Если бы порог перестал расти, этот тест висел бы.
    const started = Date.now();
    const r = applySkillXp(1, 0, Number.MAX_SAFE_INTEGER);
    expect({ уровень: r.level, уложился_в_мс: Date.now() - started < 1000 })
      .toEqual({ уровень: 50, уложился_в_мс: true });
  });
});

describe('Порог начисления за урон', () => {
  it('мелкий урон не даёт опыта, крупный даёт', () => {
    // Именно поэтому порог нужен: при начислении на каждый удар мелкие
    // удары округлялись бы к нулю, и быстрый клинок качался бы медленнее
    // тяжёлого — противоположно смыслу.
    const small = Math.floor((SKILL_XP_DAMAGE_STEP - 1) / SKILL_XP_DAMAGE_STEP);
    const big = Math.floor((SKILL_XP_DAMAGE_STEP * 3) / SKILL_XP_DAMAGE_STEP);
    expect({ порог: SKILL_XP_DAMAGE_STEP, мелкий_удар: small, крупный_удар: big })
      .toEqual({ порог: 60, мелкий_удар: 0, крупный_удар: 3 });
  });
});
