// Игроку не показывают текст запроса.
//
// ЧТО БЫЛО НА БОЮ. POST /api/game/dungeons/:id/enter ответил
//   500 {"code":"42702","message":"column reference \"reset_date\" is ambiguous"}
// То есть игрок получил в теле ответа кусок SQL - с названием колонки и
// условием. Обработчик отдавал err.message ЛЮБОЙ ошибки без разбора, то
// есть каждая ошибка базы по всем маршрутам утекала в браузер.
//
// ГЛАВНАЯ ПРОВЕРКА. Для ошибки сервера (5xx) настоящее сообщение не
// уходит игроку. Оно остаётся в журнале - там оно и нужно.
//
// ЧТО НЕ ТРОГАЕТСЯ. Ошибки клиента (4xx): их message написан руками и
// по нему клиент рисует подсказку. Проверяется, что 4xx сохранились - иначе
// правка тихо сломала бы интерфейс там, где он работает.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const обработчик = читать('server/src/middleware/errorHandler.ts');

describe('Ошибка сервера не показывается игроку', () => {
  it('для 5xx отдаётся нейтральный текст, а не err.message', () => {
    expect({
      есть_порог: /statusCode < 500/.test(обработчик),
      сообщение_из_ошибки_не_отдаётся:
        !/message,\s*\n\s*\.\.\./.test(обработчик),
      нейтральный_текст: /Внутренняя ошибка/.test(обработчик),
    }).toEqual({ есть_порог: true, сообщение_из_ошибки_не_отдаётся: true, нейтральный_текст: true });
  });

  it('настоящее сообщение остаётся в журнале', () => {
    // Убрать его из ответа - правильно. Убрать из журнала - значит
    // потерять причину, и поломка станет неразбираемой.
    expect({ в_журнале: /logger\.error\(`\[Error\] \$\{statusCode\} \$\{code\}: \$\{message\}`/.test(обработчик) })
      .toEqual({ в_журнале: true });
  });

  it('ошибки клиента (4xx) не пострадали', () => {
    // По message клиент рисует подсказку. Если убрать его у всех - вход
    // «персонаж не найден» станет «внутренняя ошибка» и перестанет быть
    // понятным. Проверка сторожит именно эту регрессию.
    expect({
      порог_по_статусу: /виднаИгроку \? message/.test(обработчик),
    }).toEqual({ порог_по_статусу: true });
  });

  it('стек ошибки тоже не уходит игроку на бою', () => {
    // Стек показывается только в разработке И только для ошибок клиента.
    // На бою NODE_ENV=production, и проверка это фиксирует.
    expect({
      за_dev: /isDev &&/.test(обработчик),
      не_безусловно: !/,\s*stack: err\.stack\s*\}/.test(обработчик),
    }).toEqual({ за_dev: true, не_безусловно: true });
  });
});

describe('Число попыток не врёт при сломанном запросе', () => {
  const подземелья = читать('server/src/systems/DungeonService.ts');

  it('ошибка чтения не превращается в «попыток не использовано»', () => {
    // queryOne возвращает null когда строки нет - честный случай. Ошибку он
    // БРОСАЕТ, и catch превращал её в то же: игрок видел «осталось 3
    // попытки», нажимал и получал 500.
    const блок = подземелья.slice(
      подземелья.indexOf('async attemptsLeft'),
      подземелья.indexOf('async attemptsLeft') + 1400);
    expect({
      глушителя_нет: !/\.catch\(\(\) => null\)/.test(блок),
      причина_логируется: /не удалось прочитать число попыток/.test(блок),
      ошибка_поднимается: /DUNGEON_ATTEMPTS_UNREADABLE/.test(блок),
    }).toEqual({ глушителя_нет: true, причина_логируется: true, ошибка_поднимается: true });
  });

  it('проверка не закрепляет ошибку как норму', () => {
    const проверкаЧитаетDungeon = читать('server/src/tests/dungeonNoDeath.test.ts');
    expect({
      // Раньше эта проверка ТРЕБОВАЛА наличия .catch(() => null) - то есть
      // закрепляла поломку как норму. Теперь требует обратного.
      требует_отсутствия: !/toEqual\(\{ глотает_ошибку: true \}\)/.test(проверкаЧитаетDungeon),
      называет_дыру_дырой: /ПРЕЖДЕ ЗДЕСЬ СТОЯЛО ПРОТИВНОПОЛОЖНОЕ/.test(проверкаЧитаетDungeon),
    }).toEqual({ требует_отсутствия: true, называет_дыру_дырой: true });
  });
});

