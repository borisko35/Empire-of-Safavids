// Выкатка не должна уметь «успешно» ничего не задеплоить.
//
// ЗАЧЕМ ФАЙЛ. Найдено на себе, 30 сентября. Команда была:
//
//   git pull --ff-only origin main 2>&1 | tail -3 && docker compose ... up
//
// `git pull` УПАЛ с кодом 1: на сервере лежал незакоммиченный
// tools/build-trailer.sh, а git не перезаписывает неотслеживаемые файлы и
// отменяет merge. Код возврата пайпа берётся у ПОСЛЕДНЕЙ команды, то есть у
// `tail`, а он всегда ноль. `&&` исполнился, контейнеры пересобрались на
// СТАРОМ коде, и выкатка отрапортовала:
//
//   Updating deef120..ec30537
//
// Эта строка git печатает ДО отказа. Три коммита на прод не попали, страница
// трейлера осталась старой, ролик не появился - и это выглядело как успех.
//
// ЧТО ТЕПЕРЬ ОБЯЗАТЕЛЬНО. Скрипт tools/deploy.sh проверяет код возврата
// `git pull` БЕЗ пайпа, сверяет коммит до и после, и останавливается, если
// ничего не изменилось. Проверяется здесь, чтобы правило не потерялось при
// следующей правке инструкции.
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Выкатка не может отрапортовать об успехе, сделав пустое дело', () => {
  it('скрипт выкатки есть и проверяет код возврата без пайпа', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА.
    const п = join(корень, 'tools/deploy.sh');
    must(existsSync(п), 'нет tools/deploy.sh');
    const код = читать('tools/deploy.sh');
    // Ключевое: pull идёт БЕЗ пайпа, и код возврата проверяется явно.
    // Регулярка требует, чтобы после pull шла проверка кода - иначе скрипт
    // повторит ровно ту ошибку, ради которой написан.
    const pull = /git pull --ff-only origin main\s*>\/tmp\/deploy-pull\.log 2>&1\s*\n\s*KOD=\$\?/;
    expect({
      // Пайпа нет: вывод уходит в файл, а не в пайп.
      pull_bez_pajpa: pull.test(код),
      // И код проверяется ДО любых других действий.
      proverka_koda: /if \[ "\$KOD" -ne 0 \]/.test(код),
      // И пустая выкатка запрещена: если коммит не сдвинулся, стоп.
      proverka_kega_sdvinulsya: /= "\$posle" \]/.test(код),
      // И есть предварительная проверка, без неё пересборка может убить сайт.
      predproverka: /deploy-preflight\.sh/.test(код),
      // И сервер опрашивается с ожиданием: контейнеру нужно время на миграции.
      proverka_posle: /gotovo=0/.test(код),
    }).toEqual({
      pull_bez_pajpa: true, proverka_koda: true, proverka_kega_sdvinulsya: true,
      predproverka: true, proverka_posle: true,
    });
  });

  it('инструкция ведёт на скрипт, а не на три команды вручную', () => {
    // Иначе через месяц кто-нибудь скопирует из инструкции старые три шага,
    // и всё вернётся. Инструкция — то, что читают по привычке.
    const инструкция = читать('deploy/README.md');
    expect({
      ведёт_на_скрипт: /bash tools\/deploy\.sh/.test(инструкция),
      // И объясняет, почему вручную нельзя: без этого объяснения старый
      // способ выглядит короче и соблазнительнее.
      объясняет_про_pajp: /код берётся у|код возврата пайпа/i.test(инструкция),
      // И велит смотреть лог, а не строку Updating.
      предупреждает_про_Updating: /Updating/.test(инструкция),
    }).toEqual({
      ведёт_на_скрипт: true, объясняет_про_pajp: true, предупреждает_про_Updating: true,
    });
  });

  it('причина сбоя объяснена там, где её ищут', () => {
    // «untracked working tree files would be overwritten by merge» — фраза,
    // ради которой человек открывает скрипт. Рядом должна быть команда,
    // которой эти файлы ищутся.
    const код = читать('tools/deploy.sh');
    expect({
      // Сама причина названа.
      называет_prichinu: /незакоммиченн|neotslezhivaem|untracked/i.test(код),
      // И дана команда, чтобы их найти.
      dayot_komandu: /git status --porcelain \| grep '\^\?\?'/.test(код),
    }).toEqual({ называет_prichinu: true, dayot_komandu: true });
  });
});
