// Лагерь перестаёт быть конусами.
//
// ЧТО БЫЛО (22 октября 2026, §289). Полевой лагерь был собран из конусов:
// четыре шатра и большой шатёр вождя — вулканы на песке. Частокол — палки
// без перекладин, костёр — круглое пятно с конусом пламени.
//
// ЧТО ТЕПЕРЬ. Шатёр — полотнище: два ската от конька к земле с провисом, задняя
// стенка, откидной клапан, конёк, шесты, верёвки с кольями и коврик у входа.
// Частокол — заострённые колья, связанные перекладинами. Костёр — очаг из
// камней, поленья крест-накрест и пламя.
//
// ЧТО ПРОВЕРЯЕТСЯ. В лагере нет конусов-шатров, шатёр собран из полотнища с
// деталями, частокол связан перекладинами, костёр — из камней и поленьев.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Лагерь — не конусы', () => {
  it('шатёр — полотнище, а не конус', () => {
    // Сборщик шатра есть.
    должен(/function шатёр\(/.test(ТЕРРЕЙН), 'нет сборщика шатра');
    // Полотнище — своя геометрия со скатами и провисом.
    должен(
      /const провис = Math\.sin\(t \* Math\.PI\) \* [\d.]+ \* s;/.test(ТЕРРЕЙН),
      'полотнище шатра не провисает',
    );
    должен(/const геометрия = new THREE\.BufferGeometry\(\);/.test(ТЕРРЕЙН), 'нет геометрии полотнища');
    // Конусов-шатров быть не должно.
    должен(
      !/new THREE\.ConeGeometry\(2\.6, 3\.4, 7\)/.test(ТЕРРЕЙН),
      'шатры снова конусы',
    );
    должен(
      !/new THREE\.ConeGeometry\(3\.6, 4\.6, 8\)/.test(ТЕРРЕЙН),
      'большой шатёр снова конус',
    );
    // И полотнище двустороннее: из прохода видно изнутри.
    должен(/копия\.side = THREE\.DoubleSide;/.test(ТЕРРЕЙН), 'полотнище шатра одностороннее');
  });

  it('у шатра есть клапан, конёк, шесты, верёвки и коврик', () => {
    должен(/const клапан = new THREE\.Mesh\(new THREE\.PlaneGeometry/.test(ТЕРРЕЙН), 'у шатра нет клапана');
    должен(/const конёк = new THREE\.Mesh\(new THREE\.CylinderGeometry/.test(ТЕРРЕЙН), 'у шатра нет конька');
    должен(/const шест = new THREE\.Mesh\(new THREE\.CylinderGeometry/.test(ТЕРРЕЙН), 'у шатра нет шестов');
    // Верёвка и кол: шатёр должен стоять, а не висеть.
    должен(/const верёвка = new THREE\.Mesh\(new THREE\.CylinderGeometry/.test(ТЕРРЕЙН), 'у шатра нет верёвок');
    должен(/const кол = new THREE\.Mesh\(new THREE\.CylinderGeometry/.test(ТЕРРЕЙН), 'у шатра нет кольев');
    // Коврик у входа.
    должен(/const ковёр = new THREE\.Mesh\(new THREE\.BoxGeometry/.test(ТЕРРЕЙН), 'у шатра нет коврика');
  });

  it('частокол связан перекладинами', () => {
    // Колья — заострённые брёвна, а не бруски.
    должен(
      /const stake = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.13, 0\.19, 2\.6, 6\)/.test(ТЕРРЕЙН),
      'кол частокола — брусок',
    );
    // Перекладина, связывающая соседние колья.
    должен(
      /const перекладина = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.07, 0\.07, 1, 5\)/.test(ТЕРРЕЙН),
      'у частокола нет перекладин',
    );
    // И она стоит поперёк, а не вдоль: направление — между двумя кольями.
    должен(
      /перекладина\.quaternion\.setFromUnitVectors\(/.test(ТЕРРЕЙН),
      'перекладина не повернута поперёк кольев',
    );
    должен(
      /new THREE\.Vector3\(x2 - x1, 0, z2 - z1\)\.normalize\(\)/.test(ТЕРРЕЙН),
      'перекладина повёрнута не вдоль двух соседних кольев',
    );
  });

  it('костёр — из камней и поленьев', () => {
    // Каменный очаг.
    должен(
      /const камень = new THREE\.Mesh\(new THREE\.DodecahedronGeometry\(0\.22, 0\)/.test(ТЕРРЕЙН),
      'у костра нет камней',
    );
    // Поленья крест-накрест.
    должен(
      /const полено = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.09, 0\.11, 1\.5, 6\)/.test(ТЕРРЕЙН),
      'у костра нет поленьев',
    );
    // И пламя на месте — его анимирует мир по имени.
    должен(/flame\.name = 'campfire-flame';/.test(ТЕРРЕЙН), 'пламя костра потеряло имя');
  });
});
