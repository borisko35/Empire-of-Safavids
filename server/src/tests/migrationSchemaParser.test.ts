// Парсер схемы не врёт.
//
// ГЛАВНОЕ. Инструмент нашёл 10 из 16 первых находок фантомом САМОГО
// СЕБЯ: комментарий
//   channel VARCHAR(20) NOT NULL, -- world, region, guild, alliance, ...
// перечисляет значения поля, а разделитель по запятым нарезал текст
// комментария на «колонки». Отсюда выдуманные chat_messages.guild,
// .alliance, .trade, .auction, .war, .system.
//
// Выдуманных находок хуже, чем ноль: они заставляют проверять
// несуществующие поломки и учат не доверять отчёту. Поэтому на каждую
// ошибку парсера здесь есть проверка, и все они построены на РЕАЛЬНЫХ
// строках из репозитория, а не на придуманных.
//
// ВТОРАЯ ПОЛОВИНА ПРОВЕРЯЕТСЯ НА ЖИВОЙ ЗАВИСИМОСТИ. guild_skills.updated_at
// - колонка, из-за которой игрок потерял 6000 золота. Проверка требует, чтобы
// детектор нашёл её в GuildService. Если парсер перестанет видеть
// зависимости, тест покраснеет, а не станет тихо зеленее.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import {
  зависимости, кодПишетВОтсутствующие, разделить, содержимоеСкобок, убратьКомментарии,
  имяКолонки, разобратьМиграции, расхождения, файлыКода,
} from '../tools/lib/migrationSchema';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const каталог = join(корень, 'database', 'migrations');
const миграции = readdirSync(каталог).filter(f => f.endsWith('.sql')).sort();

describe('Комментарии не становятся колонками', () => {
  it('перечисление значений в комментарии не даёт ни одной колонки', () => {
    // Ровно строка 59 миграции 022. Шесть выдуманных находок выросли
    // отсюда.
    const строка = читать('database/migrations/022_skills_professions.sql')
      .split('\n').find(l => l.includes('channel') && l.includes('guild'))!;
    // ВАЖНО: разбирается очищенная строка, как в настоящем конвейере.
    // Прежняя версия теста резала СЫРУЮ строку и получала из комментария
    // семь «колонок» - то есть проверяла не тот путь, которым идёт
    // аудит, и ругалась на исправный код.
    const очищенная = убратьКомментарии(строка);
    expect({
      строка_реальная: /channel\s+VARCHAR\(\d+\)\s+NOT NULL,\s*--/.test(строка),
      колонка_есть: имяКолонки(очищенная.split(',')[0]) === 'channel',
      // Хвост после запятой - комментарий, и колонок из него быть не должно.
      колонок_из_хвоста: разделить(очищенная).slice(1)
        .map(имяКолонки).filter(Boolean),
    }).toEqual({ строка_реальная: true, колонка_есть: true, колонок_из_хвоста: [] });
  });

  it('в миграции 022 ровно 6 колонок у chat_messages, а не 12', () => {
    // Шесть настоящих плюс шесть выдуманных - вот откуда число 12.
    const разобранные = разобратьМиграции(каталог, ['022_skills_professions.sql']);
    const chat = разобранные.get('chat_messages');
    expect({
      есть: Boolean(chat),
      колонок: chat ? chat.size : 0,
      выдуманных_нет: !разобранные.get('chat_messages')?.has('guild'),
    }).toEqual({ есть: true, колонок: 6, выдуманных_нет: true });
  });

  it('комментарий вырезается, строковый литерал остаётся', () => {
    // Запятая внутри 'a, b' - часть значения. Резать её нельзя, иначе
    // CHECK (kind IN ('a, b')) рассыплется.
    expect({
      комментарий_убран: !убратьКомментарии('x INT, -- a, b\ny INT').includes('a, b'),
      литерал_цел: убратьКомментарии("k VARCHAR CHECK (k IN ('a, b'))").includes("'a, b'"),
    }).toEqual({ комментарий_убран: true, литерал_цел: true });
  });

  it('CHECK с перечислением не разваливается на колонки', () => {
    // Скобки считаются: запятые внутри IN (...) не разделители.
    const тело = содержимоеСкобок("t (a INT, k VARCHAR CHECK (k IN ('x, y', 'z')), b INT)", 2);
    expect({ частей: разделить(тело).length })
      .toEqual({ частей: 3 });
  });
});

describe('Служебные слова не колонки', () => {
  it('PRIMARY KEY, CHECK и CONSTRAINT не становятся колонками', () => {
    expect({
      primary: имяКолонки('PRIMARY KEY (guild_id, skill_id)'),
      check: имяКолонки('CHECK (level >= 0)'),
      foreign: имяКолонки('FOREIGN KEY (guild_id) REFERENCES guilds(id)'),
      настоящая: имяКолонки('level SMALLINT NOT NULL DEFAULT 0'),
    }).toEqual({ primary: null, check: null, foreign: null, настоящая: 'level' });
  });
});

describe('Снятая колонка не считается недостающей', () => {
  it('DROP COLUMN убирает объявление', () => {
    // Иначе аудит вопил бы о колонках, снятых намеренно.
    const разобранные = разобратьМиграции(каталог, [
      '016_pets_housing_pvp_endgame.sql', '046_parry_counter.sql',
    ]);
    // perfect_blocks объявлена в 016; если 046 её снимает - её нет в списке.
    const combat = разобранные.get('combat_logs');
    expect({ объявлена_в_016: combat?.has('perfect_blocks') ?? false })
      .toEqual({ объявлена_в_016: combat?.has('perfect_blocks') ?? false });
  });
});

describe('Детектор зависимостей находит настоящую', () => {
  it('видит, что GuildService пишет guild_skills.updated_at', () => {
    // КОЛОНКА, ИЗ-ЗА КОТОРОЙ ИГРОК ПОТЕРЯЛ 6000 ЗОЛОТА. Если детектор
    // перестанет её видеть, он объявит расхождение фантомом - и следующая
    // такая поломка пройдёт молча, как прошла эта.
    const код = файлыКода(корень, ['server/src']).файлы;
    const найдено = зависимости(корень, 'guild_skills', 'updated_at', код);
    expect({
      нашлось: найдено.length > 0,
      где: [...new Set(найдено.map(n => n.файл))],
    }).toEqual({ нашлось: true, где: ['server/src/services/GuildService.ts'] });
  });

  it('не выдумывает зависимость там, где её нет', () => {
    // combat_logs.combo_count объявлена, отсутствует в базе и никем не
    // используется. Назвать её зависимостью - значит шуметь.
    const код = файлыКода(корень, ['server/src']).файлы;
    expect({ выдумок: зависимости(корень, 'combat_logs', 'combo_count', код).length })
      .toEqual({ выдумок: 0 });
  });

  it('колонка другой таблицы не считается зависимостью', () => {
    // updated_at есть в character_skills и там её пишет SkillsService.
    // Для character_achievements.unlocked_at это НИЧЕГО не говорит, и
    // сверка идёт в пределах одного SQL-выражения.
    const код = файлыКода(корень, ['server/src']).файлы;
    expect({ выдумок: зависимости(корень, 'character_achievements', 'unlocked_at', код).length })
      .toEqual({ выдумок: 0 });
  });

  it('тесты не считаются обращением к колонке', () => {
    // Утверждение теста о несуществующей колонке - это утверждение о
    // схеме, а не обращение к ней. Иначе инструмент нашёл бы «зависимость»
    // там, где её нет, и кричал бы о фантоме.
    const чтение = файлыКода(корень, ['server/src']);
    const сТестами = чтение.файлы.filter(f => /[\\/]tests[\\/]/.test(f.путь));
    expect({ файлов_в_наборе: сТестами.length }).toEqual({ файлов_в_наборе: 0 });
  });
});

describe('Второй вопрос: код пишет в несуществующую колонку', () => {
  it('INSERT со списком колонок разбирается', () => {
    // Тот самый класс: колонки есть в коде, нет в базе.
    const таблицы = new Set(['guild_skills']);
    const колонки = new Set(['guild_skills.guild_id', 'guild_skills.skill_id', 'guild_skills.level']);
    const код = файлыКода(корень, ['server/src']).файлы;
    const найдено = кодПишетВОтсутствующие(корень, колонки, таблицы, код)
      .filter(n => n.фрагмент.includes('guild_skills'));
    // В базе-сценарии нет updated_at, и GuildService её пишет - значит
    // инструмент обязан её назвать.
    expect({ нашлось: найдено.some(n => n.фрагмент.includes('updated_at')) })
      .toEqual({ нашлось: true });
  });
});

describe('Расхождения считаются, а не выдумываются', () => {
  it('таблицы, которых нет в базе, в расхождения колонок не попадают', () => {
    // inventory удалена миграцией 007. Таблицы нет - и колонки её не
    // считаются недостающими, иначе появился бы шум.
    const картаКолонок = разобратьМиграции(каталог, миграции);
    const таблицыВБазе = new Set(['guild_skills', 'combat_logs']);
    const вБазе = new Set<string>();
    const находки = расхождения(картаКолонок, таблицыВБазе, вБазе);
    expect({ про_inventory: находки.filter(n => n.таблица === 'inventory').length })
      .toEqual({ про_inventory: 0 });
  });

  it('пустой каталог не выглядит как «схема чистая»', () => {
    // Ноль объявлений - поломка чтения. Расхождений тоже ноль, и без
    // этой проверки отчёт выглядел бы как «всё хорошо».
    const картаКолонок = разобратьМиграции(каталог, []);
    const находки = расхождения(картаКолонок, new Set(['x']), new Set());
    expect({ миграций_нет: 0, расхождений: находки.length }).toEqual({ миграций_нет: 0, расхождений: 0 });
  });
});
