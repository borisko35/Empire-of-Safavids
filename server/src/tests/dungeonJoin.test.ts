// Групповой заход: присоединение к чужому заходу.
//
// ЧТО ЗАЩИЩАЕТ. До этого обновления присоединения не существовало вовсе:
// dungeon_members писал только создатель сессии, а restoreActiveSessions
// возвращал в members только лидера. То есть minPlayers: 3 и maxPlayers: 8
// были надписью, зайти можно было только в одиночку. Из-за этого и «лут один
// на группу» было негде делить — делить было некому.
//
// Проверка намеренно смотрит на ПОРЯДОК ВХОДА, а не только на состав members:
// следующий шаг — раздача добычи, где предметы достаются по очереди. Если
// Set перестанет хранить порядок входа, добыча начнёт доставаться не тем.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = код('server/src/systems/DungeonService.ts');
const маршруты = код('server/src/routes/game.ts');

// Тело метода join — до следующего объявления метода, а не окном в символах.
// Окно однажды обрежет проверку, и она станет зелёной на неполном коде: такой
// дефект в серии уже был, с окном в 400 символов.
function телоJoin(): string {
  const начало = сервис.indexOf('async join(');
  const конец = сервис.indexOf('\n  async ', начало + 10);
  return сервис.slice(начало, конец > начало ? конец : начало + 4000);
}

describe('Групповой заход: присоединение существует', () => {
  it('метод join объявлен и возвращает тот же вид ответа, что enter', () => {
    must(/async join\(characterId: string, sessionId: string\)/.test(сервис), 'метода join нет');
    must(
      /\{ ok: true; session: DungeonSession; attemptsLeft: number \} \| \{ ok: false; code: string \}/.test(
        сервис
      ),
      'join возвращает не тот вид ответа, что enter: клиенту придётся разбирать два формата'
    );
  });

  it('маршрут присоединения есть и защищён так же, как вход', () => {
    must(маршруты.includes("'/dungeons/:dungeonId/join'"), 'маршрута присоединения нет');
    // Без secureMiddleware маршрут был бы дырой: любой мог бы вписать чужого
    // персонажа в чужой заход.
    const блок = маршруты.slice(
      маршруты.indexOf("'/dungeons/:dungeonId/join'"),
      маршруты.indexOf("'/dungeons/:dungeonId/join'") + 320
    );
    must(блок.includes('secureMiddleware'), 'маршрут присоединения не защищён');
    must(блок.includes('requireCharacterOwnership()'), 'не проверяется владение персонажем');
  });
});

describe('Групповой заход: цифра размера стала настоящей', () => {
  it('размер берётся из описания данжа, а не из константы', () => {
    must(
      /session\.members\.size >= def\.maxPlayers/.test(сервис),
      'размер группы не сверяется с maxPlayers: цифра снова станет надписью'
    );
    must(
      !/const MAX_MEMBERS|DUNGEON_MAX_PLAYERS/.test(сервис),
      'размер объявлен константой в сервисе: он разойдётся с описанием данжа'
    );
  });

  it('при полном заходе отказ с внятным кодом', () => {
    must(/'dungeon_full'/.test(сервис), 'нет кода отказа при полном заходе');
  });

  it('нельзя войти в закрытый или несуществующий заход', () => {
    must(/'dungeon_session_not_found'/.test(сервис), 'нет отказа на несуществующий заход');
    must(/'dungeon_session_closed'/.test(сервис), 'нет отказа на завершённый заход');
  });

  it('нельзя войти в заход дважды и нельзя быть в двух заходах', () => {
    must(
      /session\.members\.has\(characterId\)/.test(сервис),
      'повторный вход в тот же заход не отсекается'
    );
    must(
      /this\.characterToSession\.get\(characterId\)/.test(сервис),
      'не проверяется, что персонаж не состоит уже в другом заходе'
    );
    must(/'dungeon_already_in_session'/.test(сервис), 'нет кода отказа на повторный вход');
  });
});

describe('Групповой заход: проверки те же, что при входе', () => {
  it('уровень, регион и попытка проверяются до списания', () => {
  const тело = телоJoin();
    // Именно ВЫЗОВ attemptsLeft(characterId, …), а не слово attemptsLeft: слово
    // есть ещё и в типе возврата, на 102-м символе тела, и проверка на него
    // смотрела бы в объявление типа, а не в проверку остатка.
    const чтениеПопытки = тело.indexOf('attemptsLeft(characterId');
    const уровень = тело.indexOf('dungeon_level_range');
    const регион = тело.indexOf('dungeon_wrong_region');
    // ПЕРВОЕ списание, а не последнее: последним может оказаться списание
    // уже после проверок, и тогда подсчёт будет врать. Списание до проверки
    // уровня — это деньги, взятые за отказ.
    const списание = тело.indexOf('spendAttempt');
    must(уровень > 0 && регион > 0, 'в join нет проверок уровня и региона');
    // Чтение остатка должно быть ДО списания, а не где-то в коде: после
    // списания остаток всё равно возвращается в ответе, и «просто есть
    // упоминание» ничего не доказывает. Первая ломка так и обманула проверку.
    must(
      чтениеПопытки > 0 && чтениеПопытки < списание && списание > уровень && списание > регион,
      'попытка списывается раньше проверок уровня и региона, либо остаток не проверяется вовсе: игрок заплатит за отказ'
    );
  });

  it('шард проверяется: без этого вошедший увидит пустой заход', () => {
    must(
      /shard !== session\.shardId/.test(сервис),
      'шард не сверяется: игрок из другого шарда войдёт в заход, где монстров не видно'
    );
    must(/'dungeon_wrong_shard'/.test(сервис), 'нет кода отказа из-за чужого шарда');
  });

  it('участник пишется в базу и попадает в members', () => {
  const тело = телоJoin();
    must(/session\.members\.add\(characterId\)/.test(тело), 'участник не добавлен в members');
    must(
      /this\.characterToSession\.set\(characterId, session\.id\)/.test(тело),
      'участник не записан в обратный индекс: выход из данжа его не увидит'
    );
    // Со скобкой: без неё «dungeon_members_kakie_to» проходил как «dungeon_members»,
// потому что поиск без границы слова берёт префикс. Первая ломка так и
// обманула проверку.
    must(
      /INSERT INTO dungeon_members \(/.test(тело),
      'участник не записан в dungeon_members: после перезапуска он пропадёт из захода'
    );
  });
});

describe('Групповой заход: порядок входа сохраняется', () => {
  it('participants хранятся в Set, а не в объекте без порядка', () => {
    // На порядке Set держится раздача добычи по очереди: предметы достаются
    // участникам в порядке входа. Объект или Map с числовыми ключами дали бы
    // другой порядок, и добыча стала бы доставаться не тем.
    must(/members: Set<string>;/.test(сервис), 'members — не Set: порядок входа не сохранится');
  });

  it('join добавляет в конец, а не в начало списка', () => {
    // Участники, вошедшие раньше, стоят раньше: set.add всегда дописывает в
    // конец, и проверка ловит попытку отсортировать участников перед выдачей.
    must(
      !/members\s*=\s*new Set\(\[\s*characterId/.test(телоJoin()),
      'join пересоздаёт members: порядок входа теряется'
    );
  });

  it('в описании данных есть цифры, ради которых это всё затевалось', () => {
    const данж = код('server/src/data/dungeons.ts');
    must(/maxPlayers: \d+[,;]/.test(данж), 'в описании данжа нет maxPlayers');
    must(
      /minPlayers: \d+[,;]/.test(данж),
      'в описании данжа нет minPlayers: минимальный размер тоже надо проверять'
    );
    // Не «поле есть», а «цифра больше одного». Ломка maxPlayers: 8 → 1
    // прошла на проверке наличия: гробница перестала быть групповой, и поле
    // при этом осталось на месте.
    const начало = данж.indexOf("'dungeon_shiraz_tomb': {");
    must(начало > 0, 'запись гробницы не найдена в описании данжей');
    const блок = данж.slice(начало, начало + 3000);
    const размер = /maxPlayers: (\d+)/.exec(блок);
    must(размер !== null, 'у гробницы нет maxPlayers');
    must(
      Number(размер![1]) > 1,
      `у гробницы maxPlayers: ${размер![1]} — заход в одиночку, и весь групповой заход впустую`
    );
  });
});

describe('Групповой заход: чего ещё нет', () => {
  it('клиент умеет присоединяться, и это проверяется отдельно', () => {
    // Раньше здесь стояло утверждение «клиент не умеет присоединяться» — оно
    // было правдой, пока кнопки не было. Теперь оно падало бы само, и это
    // правильно: значит оговорка работала. Сама кнопка проверяется в
    // joinButton.test.ts, здесь — только честная фиксация, что заход
    // доступен игроку.
    const клиент = читать('client/src/app/api.ts') + читать('client/src/app/panels.ts');
    must(
      /dungeonJoin/.test(клиент) && /join_raid/.test(клиент),
      'клиент снова не умеет присоединяться: групповой заход недоступен игроку'
    );
  });

  it('раздача добычи построена: заход без неё больше не бессмыслен', () => {
    // Эта проверка раньше утверждала обратное — «раздачи ещё нет» — и была
    // правдой, пока механики не было. Теперь она падает сама, и это правильно:
    // значит оговорка работала. Замена на утверждение о наличии.
    must(
      /private async claimLoot\(/.test(сервис),
      'раздачи добычи нет: заход остаётся ради одиночки, а весь групповой заход — впустую'
    );
    must(
      /loot_claimed_at IS NULL/.test(сервис),
      'признак «добыча уже выдана» не проверяется: повторный вызов удвоит награду'
    );
  });
});
