// Продавцы за базарными прилавками столицы.
//
// ЧТО БЫЛО (21 октября 2026, §272). В городах регионов за прилавками
// продавцы стоят (§260), а в столице за рядами никого: базар столицы пустее
// базара Тебриза, и это заметно.
//
// ЧТО ТЕПЕРЬ. Четыре продавца за прилавками базара у мечети, и к каждому можно
// подойти и открыть торговлю.
//
// ГЛАВНОЕ ПРАВИЛО. Продавец стоит ЗА СВОИМ ПРИЛАВКОМ, а не где попало.
// Позиции прилавков считаются из кода terrain.ts, и проверка считает их так же:
// если базар переедет, продавцы должны поехать вместе с рядами.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const NPC = читать('client/src/app/game3d/npc.ts');

/** Прилавки базара — те же числа, что и в terrain.ts. */
function прилавки(): { x: number; z: number }[] {
  const рядки: { x: number; z: number }[] = [];
  for (let i = 0; i < 7; i++) {
    const a = Math.PI * 0.6 + (i / 7) * Math.PI * 0.8;
    рядки.push({ x: Math.cos(a) * 20, z: -8 + Math.sin(a) * 20 });
  }
  return рядки;
}

describe('Продавцы за прилавками базара', () => {
  it('у каждого продавца есть имя и торговая панель', () => {
    for (const [id, имя] of [
      ['npc_bazaar_trader_0', 'Торговец Абдуллах'],
      ['npc_bazaar_trader_2', 'Торговка Фатима'],
      ['npc_bazaar_trader_4', 'Торговец Махмуд'],
      ['npc_bazaar_trader_6', 'Купец Ибрагим'],
    ] as const) {
      должен(NPC.includes(`id: '${id}'`), `нет продавца ${имя} (${id})`);
      должен(NPC.includes(`nameRu: '${имя}'`), `нет имени ${имя}`);
      должен(
        new RegExp(`id: '${id}'[\\s\\S]{0,160}?panel: 'panel-shop'`).test(NPC),
        `продавец ${имя} не открывает торговлю`,
      );
    }
  });

  it('продавец стоит за своим прилавком', () => {
    const прилавкиГород = прилавки();
    // Ряд i из семи; берём каждый второй: 0, 2, 4, 6.
    for (const i of [0, 2, 4, 6]) {
      const прилавок = прилавкиГород[i];
      const вход = new RegExp(
        `id: 'npc_bazaar_trader_${i}'[\\s\\S]{0,220}?dx: (-?[\\d.]+), dz: (-?[\\d.]+)`,
      ).exec(NPC);
      должен(вход, `нет позиции продавца у прилавка ${i}`);
      const dx = Number(вход![1]);
      const dz = Number(вход![2]);
      // Расстояние от центра базара: у прилавка 20, у продавца — 21.8 (он за ним).
      const d = Math.hypot(dx, dz + 8);
      должен(
        Math.abs(d - 21.8) < 0.35,
        `продавец ${i} стоит на расстоянии ${d.toFixed(1)} от центра базара, а должен быть за прилавком (21.8)`,
      );
      // И с другой стороны от центра, чем сам прилавок.
      const знакПрилавка = Math.sign(
        прилавок.x * dx + (прилавок.z + 8) * (dz + 8),
      );
      должен(
        знакПрилавка > 0,
        `продавец ${i} стоит перед прилавком, а не за ним`,
      );
    }
  });
});
