// Карты данных серая — карта шероховатости в том числе
//
// ЗАЧЕМ ФАЙЛ. Проверялась стена после правки гигантских надписей. По ходу
// нашлось другое: карта шероховатости камня получалась цветной.
//
// ЧТО БЫЛО. В stoneRoughnessTexture верх грани заливался вот так:
//
//     `rgb(${200 + rnd()},${200 + rnd()},${200 + rnd()})`
//
// Три независимые Math.random() — значит R, G и B почти всегда разные.
//
// ПОЧЕМУ ЭТО НЕПРАВИЛЬНО, А НЕ «СТИЛЬ». Карта шероховатости цветом не
// является: three.js читает из неё зелёный канал (texelRoughness.g,
// meshphysical_frag). Из красно-зелёно-синей карты в шейдер попадает
// ровно один из трёх независимо розыгранных шумов, а два остальных
// выбрасываются. Итог: там, где задумана одинаковая шероховатость всего
// камня, она гуляет случайно на ±20/255, и кладка выглядит пестрой.
//
// По счастливой случайности остальные карты данных написаны правильно —
// shade считается один и подставляется во все три канала. Проверка ниже
// сторожит именно от возврата тройного Math.random().
//
// ЧТО ПРОВЕРЯЕТСЯ. Правило одно и простое: в картах данных из файла не
// должно остаться rgb(...), где в три канала подставлены разные вызовы
// Math.random(). Считаем по исходнику — картинку в тесте не нарисовать,
// а вот «три независимых броска в одном rgb» ищется точно.
import { readFileSync } from 'fs';
import { join } from 'path';

const root = join(__dirname, '..', '..', '..');
const текст = readFileSync(join(root, 'client/src/app/game3d/textures.ts'), 'utf8');

function must(cond: boolean, why: string): void {
  if (!cond) throw new Error(why);
}

describe('Карты данных не получают цвет там, где нужен оттенок серого', () => {
  it('в файле нет rgb() с тремя независимыми Math.random()', () => {
    // Ищем rgb(...), где внутри НЕ МЕНЬШЕ трёх Math.random() — то есть
    // каждый канал получил своё число. Ровно такой шаблон стоял в карте
    // шероховатости камня.
    const подозрительные = текст
      .split('\n')
      .map((строка, номер) => ({ строка, номер: номер + 1 }))
      .filter(({ строка }) => {
        const начало = строка.indexOf('rgb(');
        if (начало < 0) return false;
        const внутри = строка.slice(начало);
        return (внутри.match(/Math\.random\(\)/g) ?? []).length >= 3;
      })
      .map(({ номер, строка }) => `  строка ${номер}: ${строка.trim()}`);

    must(подозрительные.length === 0,
      `карта данных подставляет в каналы разные значения:\n${подозрительные.join('\n')}\n` +
      'Каналы карты данных (шероховатость, нормаль, смещение) должны совпадать.');
  });

  it('камень и дерево по-прежнему рисуют камень и дерево', () => {
    // Правка не должна была выкинуть содержимое: оба генератора обязаны
    // остаться на месте и заливать грани цветом.
    must(/function stoneRoughnessTexture/.test(текст), 'генератор шероховатости камня исчез');
    must(/function woodRoughnessTexture/.test(текст), 'генератор шероховатости дерева исчез');
    must(/ctx\.fillRect\(x \+ 1\.5, y \+ 1\.5, bw - 3, bh - 3\)/.test(текст),
      'заливка верхней грани камня пропала — шероховатость больше не рисуется');
  });
});