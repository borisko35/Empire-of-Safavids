// Бой: связка из трёх стадий и блок с откатом.
//
// ЧТО БЫЛО. Каждый клик — один и тот же замах: второй клип атаки в проекте
// отсутствует, и стадии не было вовсе. Блок хуже: повторный ПКМ продлевал щит
// и обновлял его начало, то есть окно парирования открывалось заново при
// каждом нажатии. Спам щитом держал парирование вечно — бесконечные «−1».
//
// ЧТО ПРОВЕРЯЕТСЯ. Клики чередуют прямой и обратный замах (второй — тот же
// клип задом наперёд); навык в окне после клика — финишер и закрывает связку;
// повторный щит поверх активного отклоняется, после истекшего — передышка;
// отклонённый щит не тратит стамину; урон стадий не трогали — цифры считает
// серверная цепочка, как раньше.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МИР3Д = читать('client/src/app/game3d/world3d.ts');
const МИР = читать('client/src/app/world.ts');
const РИГ = читать('client/src/app/game3d/realRig.ts');
const ПРОЦЕДУРНЫЙ = читать('client/src/app/game3d/rig.ts');
const ЗАЩИТА = читать('server/src/systems/DefenseStates.ts');
const ХЕНДЛЕР = читать('server/src/socket/GameSocketHandler.ts');

/** Тело метода: от сигнатуры до конца функции по балансу скобок. */
function телоМетода(исходник: string, началоСигнатуры: string): string {
  const начало = исходник.indexOf(началоСигнатуры);
  must(начало >= 0, `не нашли ${началоСигнатуры}: код переехал, проверка ослепла`);
  let глубина = 0;
  let i = исходник.indexOf('{', начало);
  must(i >= 0, `нет тела у ${началоСигнатуры}`);
  for (; i < исходник.length; i++) {
    if (исходник[i] === '{') глубина++;
    if (исходник[i] === '}') {
      глубина--;
      if (глубина === 0) return исходник.slice(начало, i + 1);
    }
  }
  throw new Error(`не закрыт ${началоСигнатуры}`);
}

describe('Связка ударов: три стадии', () => {
  it('клики чередуют прямой и обратный замах в окне', () => {
    const окно = Number(/const COMBO_WINDOW_MS = (\d+);/.exec(МИР3Д)?.[1]);
    must(
      Number.isFinite(окно),
      'нет окна связки: второй клик неотличим от первого',
    );
    must(
      окно >= 1000 && окно <= 3000,
      `окно связки ${окно} мс: меньше секунды — вторую стадию не выбить, больше трёх — связки сливаются`,
    );
    must(
      /this\.comboStage = now - this\.lastSwingAt < COMBO_WINDOW_MS && this\.comboStage === 1 \? 2 : 1;/.test(МИР3Д),
      'стадия не чередуется 1-2-1-2: каждый клик снова первый замах',
    );
    must(
      /this\.attackStage = this\.comboStage;/.test(МИР3Д),
      'стадия клика не доходит до анимации: считается, но не показывается',
    );
    must(
      /b\.rig\.triggerAttack\(this\.attackStage\)/.test(МИР3Д),
      'замах вызывается без стадии: риг всегда играет первую',
    );
  });

  it('третий клик подряд связку не продолжает', () => {
    // Завершающая атака — это клик плюс навык, а не третий клик. Без
    // чередования третий клик подряд стал бы «финишером без навыка».
    must(
      /[Тт]ретий клик подряд связку не продолжает/.test(МИР3Д),
      'правило третьей стадии не записано в коде: следующий правильщик вернёт третий клик-финишер',
    );
  });

  it('навык в окне после клика — финишер и закрывает связку', () => {
    must(
      /world3d\?\.getComboStage\(\)/.test(МИР),
      'навык не читает связку: финишер срабатывает всегда, а не после клика',
    );
    must(
      /world3d\.playFinisherSwing\(\);/.test(МИР),
      'у финишера нет своего замаха: навык идёт без связки',
    );
    must(
      /world3d\.resetCombo\(\);/.test(МИР),
      'связка не закрывается навыком: окно висит за эффектом',
    );
    must(
      /world\.finisher/.test(МИР),
      'у финишера нет подписи: игрок не поймёт, что связка завершена',
    );
    // Стадия 0 вне окна: иначе навык через минуту после клика всё ещё финишер.
    const геттер = телоМетода(МИР3Д, 'getComboStage()');
    must(
      /performance\.now\(\) - this\.lastSwingAt > COMBO_WINDOW_MS/.test(геттер) && /return 0;/.test(геттер),
      'связка не истекает: окно вышло, а стадия осталась',
    );
  });

  it('обратный замах — настоящий реверс клипа', () => {
    // Второго файла анимации в проекте нет. Ускоренная копия первого —
    // это не вторая стадия, а та же. Реверс виден: замах идёт с другой руки.
    must(
      /triggerAttack\(stage: 1 \| 2 = 1\): void/.test(РИГ),
      'у triggerAttack нет стадии: второй замах вызвать нечем',
    );
    must(
      /действие\.timeScale = -1;/.test(РИГ),
      'обратный замах не реверсирует клип: вторая стадия неотличима от первой',
    );
    must(
      /действие\.time = клип\.duration;/.test(РИГ),
      'реверс стартует не с конца клипа: замах начнётся с середины',
    );
    // Дисциплина масштаба: действие кешируется на клип, и -1 без сброса
    // развернул бы все следующие обычные замахи.
    const включить = телоМетода(РИГ, 'private включить(');
    must(
      /действие\.timeScale = 1;/.test(включить),
      'включить не сбрасывает timeScale: после обратного замаха все прямые пойдут задом наперёд',
    );
    must(
      /triggerAttack: \(stage\?: 1 \| 2\) => void;/.test(ПРОЦЕДУРНЫЙ),
      'интерфейс рига не знает стадию: вызов со стадией не скомпилируется у всех ригов',
    );
  });

  it('подпись финишера переведена на три языка', () => {
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`)) as Record<string, Record<string, string>>;
      must(
        typeof словарь.world?.finisher === 'string',
        `в словаре ${язык} нет world.finisher: подпись покажет путь ключа`,
      );
    }
  });
});

describe('Блок: откат, а не бесконечность', () => {
  it('повторный щит поверх активного отклоняется без обновления начала', () => {
    // Ядро бага: продление обновляло blockStartedAt, окно парирования
    // открывалось заново, и каждый удар парировался — вечные «−1».
    const метод = телоМетода(ЗАЩИТА, 'activateBlock(');
    must(
      /: boolean/.test(метод.split('{')[0]),
      'activateBlock ничего не возвращает: отказ выразить нечем',
    );
    const отказПоверх = метод.indexOf('if (now < st.blockUntil) return false;');
    must(
      отказПоверх >= 0,
      'нет отказа поверх активного щита: спам ПКМ снова продлевает блок',
    );
    const обновлениеНачала = метод.indexOf('st.blockStartedAt = now;');
    must(
      обновлениеНачала > отказПоверх,
      'начало блока обновляется до отказа: парирование снова вечное',
    );
  });

  it('после истекшего щита — передышка', () => {
    const пауза = Number(/const BLOCK_RECAST_GAP_MS = (\d+);/.exec(ЗАЩИТА)?.[1]);
    must(
      Number.isFinite(пауза),
      'нет передышки: щит поднимается заново в тот же миг, как упал',
    );
    must(
      пауза >= 300 && пауза <= 2000,
      `передышка ${пауза} мс: меньше 300 — спам почти непрерывен, больше 2000 — щит мёртв`,
    );
    must(
      /now - st\.blockUntil < BLOCK_RECAST_GAP_MS/.test(ЗАЩИТА),
      'передышка объявлена, но не проверяется',
    );
  });

  it('отказ приходит кодом, стамина не тратится', () => {
    // Резерв до списания, как у рывка: иначе спам списывал бы стамину за
    // каждый отклонённый щит, и игрок платил бы за отказ.
    const путь = телоМетода(ХЕНДЛЕР, 'private async handleDefensiveAction(');
    must(
      /!this\.defenseStates\.activateBlock\(character\.id\)\) \{\s*\r?\n\s*socket\.emit\(SOCKET_EVENTS\.COMBAT_ERROR, \{ code: 'block_cooldown' \}\);/.test(путь),
      'отказ щита не уходит кодом block_cooldown: игрок жмёт, а в ответ тишина',
    );
    const резерв = путь.indexOf('activateBlock(character.id)');
    const списание = путь.indexOf('spendResources(character.id');
    must(
      резерв >= 0 && списание >= 0 && резерв < списание,
      'резерв щита после списания стамины: гонка двух пакетов спишет дважды',
    );
    must(
      /clearBlock\(character\.id\)/.test(путь),
      'нет отката резерва при нехватке стамины: игрок ждёт передышку за щит, которого не было',
    );
  });

  it('код отказа переведён на три языка', () => {
    must(
      /block_cooldown: 'world\.combat_error_block_cooldown'/.test(читать('shared/combatErrors.ts')),
      'код block_cooldown не внесён в карту ошибок: клиент покажет код как есть',
    );
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`)) as Record<string, Record<string, string>>;
      must(
        typeof словарь.world?.combat_error_block_cooldown === 'string',
        `в словаре ${язык} нет перевода отказа щита`,
      );
    }
  });
});
