// Птицы садятся на воду.
//
// ЧТО БЫЛО (21 октября 2026, §273). Стая летала всегда в воздухе: озеро у
// порта было пустым, и вода читалась как зеркало, а не как место, где что-то
// живёт.
//
// ЧТО ТЕПЕРЬ. Когда стая подлетает к озеру, она опускается на воду, сидит
// какое-то время (крылья сложены, бой затихает) и снова взлетает.
//
// ЧТО ПРОВЕРЯЕТСЯ. Высота стаи идёт к уровню воды у озера и возвращается в
// небо; крылья на воде сложены; и всё считается от настоящего уровня озера.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ПТИЦЫ = читать('client/src/app/game3d/birds.ts');
const ВОДА = читать('shared/water.ts');

describe('Птицы садятся на воду', () => {
  it('уровень озера берётся из общих данных', () => {
    // Озеро одно на весь мир, и его уровень — общий: вода в шахте и вода в
    // озере не должны разойтись на сантиметр.
    должен(/import \{ LAKE \} from '\.\/terrain'/.test(ПТИЦЫ), 'стая не знает, где озеро');
    должен(/export const LAKE = \{ x: (-?\d+), z: (-?\d+), r: (\d+), level: (-?[\d.]+) \};/.test(ВОДА),
      'озеро не описано в общих данных');
  });

  it('стая опускается на воду у озера и поднимается обратно', () => {
    должен(
      /const уОзера = Math\.hypot\(центрX - LAKE\.x, центрZ - LAKE\.z\) < 150;/.test(ПТИЦЫ),
      'стая не проверяет, рядом ли озеро',
    );
    // Цель — уровень воды плюс чуть-чуть, чтобы птица не тонула.
    должен(
      /const цельY = уОзера \? LAKE\.level \+ 0\.22 : ВЫСОТА;/.test(ПТИЦЫ),
      'стая не садится на уровень воды',
    );
    // Высота меняется плавно, а не скачком.
    должен(
      /высота \+= \(цельY - высота\) \* Math\.min\(1, dt \* 0\.5\);/.test(ПТИЦЫ),
      'стая перескакивает между небом и водой',
    );
  });

  it('на воде крылья сложены и птица не покачивается', () => {
    // Бой затихает по мере посадки.
    должен(
      /const бой = \(Math\.sin\(now \* 7\.5 \+ п\.фаза\) \* 0\.55 \+ взмах\) \* \(1 - сидит\);/.test(ПТИЦЫ),
      'на воде крылья продолжают бить',
    );
    // И птица не покачивается над водой.
    должен(/\* 2\.2 \* \(1 - сидит\)/.test(ПТИЦЫ), 'птица покачивается и на воде');
  });
});
