// Лужи на площади после ливня.
//
// ЧТО БЫЛО (21 октября 2026, §264). Земля в дождь темнела (§261), но стоячей
// воды на мостовой не было: дождь выглядел как притирка — капли падают, темно,
// и всё.
//
// ЧТО ТЕПЕРЬ. После ливня вода собирается в лужи: тёмные и гладкие, они ловят
// небо и отражают фонари. Лужи появляются не все сразу, а порциями: у каждой
// свой порог.
//
// ЧТО ПРОВЕРЯЕТСЯ. Лужи стоят на площади (на уровне плиты), они тёмные и
// гладкие, появляются по мере мокроты и прячутся, когда земля высыхает; места
// их — по детерминированному генератору, иначе после перезагрузки страницы
// лужи стояли бы в других местах.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Лужи после ливня', () => {
  it('лужи тёмные, гладкие и стоят на площади', () => {
    должен(/function buildPuddles\(city: THREE\.Group\)/.test(ТЕРРЕЙН), 'нет строителя луж');
    // Гладкая поверхность: вода ловит небо, а не рассеивает свет.
    должен(/roughness: 0\.0\d,/.test(ТЕРРЕЙН), 'лужа не гладкая: это тёмное пятно, а не вода');
    // Уровень плиты города: площадь поднята на 0.3, лужа лежит на ней.
    должен(/лужа\.position\.set\(CITY\.x \+ Math\.cos\(a\) \* r, 0\.31, CITY\.z \+ Math\.sin\(a\) \* r\);/.test(ТЕРРЕЙН),
      'лужа лежит не на уровне плиты');
    // Лужи строятся в городе.
    должен(/buildPuddles\(city\);/.test(ТЕРРЕЙН), 'лужи не строятся в городе');
  });

  it('лужи появляются по мере мокроты и прячутся, когда земля сохнет', () => {
    должен(/export function setPuddles\(wet: number\)/.test(ТЕРРЕЙН), 'нет управления лужами');
    // У каждой лужи свой порог: появляются порциями, а не разом.
    должен(
      /const доля = Math\.max\(0, Math\.min\(1, \(мокрота - л\.порог\) \/ 0\.35\)\);/.test(ТЕРРЕЙН),
      'у луж нет своего порога: они появляются разом',
    );
    // Сухая земля — луж не видно.
    должен(/л\.mesh\.visible = доля > 0\.01;/.test(ТЕРРЕЙН), 'лужи не прячутся, когда земля сухая');
    // Движок зовёт их по мокроте.
    должен(/setPuddles\(this\.мокрота\);/.test(МИР), 'лужи не ставятся по мокроте');
  });

  it('места луж — по детерминированному генератору', () => {
    // Иначе после перезагрузки страницы лужи стояли бы в других местах, и
    // игрок сравнивал бы город с тем, что видел в прошлый раз.
    должен(
      /const a = hash2\(i \* 3\.7, 11\.3\) \* Math\.PI \* 2;/.test(ТЕРРЕЙН),
      'места луж считаются случайно: после перезагрузки они съедут',
    );
    должен(!/Math\.random\(\)/.test(ТЕРРЕЙН.replace(/[\s\S]*?function buildPuddles[\s\S]*?\n}\n/, '')),
      'в построении луж есть случайность');
  });
});
