// Дальние края: мир перестал быть одной полосой на всю ширину.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ПРАВКИ. getZoneAt отдаёт первую подходящую зону, а все
// 24 зоны были полосами ВО ВСЮ ШИРИНУ: у каждой стояло x1: -3175, x2: 3175.
// Различался только север-юг. Замер по миру дал:
//
//   z=   26: 1 зона на весь мир
//   z= 200: 1 зона на весь мир
//   z= 600: 1 зона на весь мир
//   z=1000: 1 зона на весь мир
//   z=2250: 1 зона на весь мир
//   идя на восток от Исфахана: 3141 единица, зона та же
//
// То есть игрок уходил от столицы на 3141 единицу и оставался в зоне «Центр
// Исфахана. Безопасная зона для новичков» с монстрами первого уровня.
// Расширение мира в семь раз по площади растянуло «зону новичка» на все 6350
// единиц ширины. Мир стал длиннее, а содержание в нём не изменилось.
//
// РЕШЕНИЕ ВЛАДЕЛЬЦА. Дальние края - самостоятельные регионы: девятый и десятый,
// по три зоны у каждого, со своими городами, монстрами и точками спавна.
//
// ПОЧЕМУ ПОЛОСЫ СУЗИЛИСЬ, А НЕ ДОБАВЛЕНЫ ПОВЕРХ. Полоса во всю ширину и
// полоса с края налезают по площади всегда, а getZoneAt отдаёт первую
// подходящую: игрок увидел бы на экране чужой регион, а вся проверка по
// региону врала бы. Поэтому центральная часть сведена к x от -СРЕДНИЙ_КРАЙ до
// СРЕДНИЙ_КРАЙ, и за этой чертой живут два новых региона.
import { ZONES, REGION_SPAWNS, REGION_LEVEL_REQUIREMENTS, getZoneAt } from '../../../shared/constants';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const WORLD_HALF = 3175;
const СРЕДНИЙ_КРАЙ = 2350;

describe('Дальние края: мир не полоса на всю ширину', () => {
  it('идя на восток от Исфахана, игрок попадает в другой регион', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Именно это ломалось: одна зона на всю
    // ширину. Проверяется не список, а поведение - переход зоны по дороге.
    const старт = getZoneAt(34, 26);
    must(старт !== null, 'Исфахан вне зон - проверять нечего');
    must(старт.region === 'isfahan', `ворота Исфахана оказались в регионе ${старт.region}`);

    let сменилась = false;
    // Имя без пробела. Первая версия назвала переменную «на какой», и
    // TypeScript разобрал её как два идентификатора: «на» объявился, а на
    // «какой» он споткнулся. Ошибки посыпались сорока строками ниже и
    // выглядели как несовместимость типов, а это был пробел в имени.
    let новыйРегион: string | null = null;
    for (let x = 34; x <= WORLD_HALF; x += 10) {
      const зона = getZoneAt(x, 26);
      if (зона && зона.region !== 'isfahan') { сменилась = true; новыйРегион = зона.region; break; }
    }
    must(сменилась,
      'игрок, идущий на восток от Исфахана, нигде не выходит из региона isfahan - ' +
      'значит вся восточная половина мира подписана как столичная зона новичка');
    must(новыйРегион === 'east_frontier',
      `на востоке игрок попал в регион ${новыйРегион}, а ждали east_frontier - полосы легли не туда`);
  });

  it('на каждой широте мира есть больше одной зоны', () => {
    // До правки на любой широте встречалась ровно одна зона. Теперь на всех
    // широтах минимум три: западный край, центральная полоса, восточный край.
    const плохие: string[] = [];
    for (const z of [26, 200, 600, 1000, 2250, -300, 2800]) {
      const разные = new Set<string>();
      for (let x = -WORLD_HALF; x <= WORLD_HALF; x += 20) {
        const зона = getZoneAt(x, z);
        разные.add(зона ? зона.region : 'НЕТ ЗОНЫ');
      }
      if (разные.size < 3) плохие.push(`z=${z}: ${разные.size} (${[...разные].join(', ')})`);
    }
    must(плохие.length === 0,
      `на этих широтах мир всё ещё полоса на всю ширину:\n  ${плохие.join('\n  ')}`);
  });

  it('ни одна наземная полоса не тянется во всю ширину', () => {
    // Ключевое свойство геометрии. Полоса во всю ширину на суше означает,
    // что она налезает на любую полосу края, а getZoneAt отдаёт первую.
    // Во всю ширину остались только заливные полосы: они лежат южнее
    // z = -483, а дальние края начинаются с z = -483 и не пересекаются с ними.
    const сплошные: string[] = [];
    for (const з of ZONES) {
      const б = з.bounds;
      if (б.x1 === -WORLD_HALF && б.x2 === WORLD_HALF) {
        сплошные.push(`${з.id} (z ${б.z1}..${б.z2})`);
      }
    }
    must(сплошные.every((с) => /persian_gulf|mesopotamia_river/.test(с)),
      `во всю ширину остались не только заливные полосы:\n  ${сплошные.join('\n  ')}`);
    // И число: ровно четыре - три залива и месопотамская река.
    must(сплошные.length === 4,
      `во всю ширину ${сплошные.length} полос, а ожидалось 4 (три залива и река): ${сплошные.join(', ')}`);
  });

  it('дальние края - два новых региона с тремя зонами у каждого', () => {
    for (const регион of ['east_frontier', 'west_frontier']) {
      const зоны = ZONES.filter((з) => з.region === регион);
      must(зоны.length === 3,
        `у региона ${регион} ${зоны.length} зон, а ожидалось 3 - край без третьей зоны снова станет плоским`);
      must(REGION_LEVEL_REQUIREMENTS[регион] !== undefined,
        `у региона ${регион} нет требования по уровню - путешествовать будет некуда и показывать будет нечего`);
      must(REGION_SPAWNS[регион] !== undefined, `у региона ${регион} нет якоря - путешествие в него невозможно`);
    }
    // Полосы края обязаны идти по x: иначе это ещё две горизонтальные полосы
    // посреди мира, а не края.
    for (const регион of ['east_frontier', 'west_frontier']) {
      for (const з of ZONES.filter((з) => з.region === регион)) {
        must(з.bounds.x1 === СРЕДНИЙ_КРАЙ || з.bounds.x2 === -СРЕДНИЙ_КРАЙ,
          `зона ${з.id} не примыкает к краю мира: x ${з.bounds.x1}..${з.bounds.x2}`);
      }
    }
  });

  it('требования по уровню растут к краю света', () => {
    // Порядок уровней - это обещание игроку: чем дальше, тем труднее. Если
    // новый регион окажется легче предыдущего, игрок уйдёт на край и ему
    // станет легче, чем в Исфахане.
    //
    // СНАЧАЛА ЧИСЛО ПОЛОС, И ТОЛЬКО ПОТОМ УРОВНИ. Ломка убрала полосы краёв, и
    // проверка прошла вхолостую: цикл по пустому списку не делает ничего, и
    // утверждение о росте уровней оказывается верным при краях, которых нет.
    // Пустой цикл - это не доказательство, а отсутствие проверки.
    const края = ZONES.filter((з) => з.region === 'east_frontier' || з.region === 'west_frontier');
    must(края.length === 6,
      `полос дальних краёв ${края.length}, а ожидалось 6 - дальше уровни не проверяются вовсе`);
    const уровни = ZONES.map((з) => з.minLevel);
    must(Math.max(...уровни) <= 100, 'зона требует уровень выше предела игры в 100');
    for (const з of края) {
      must(з.minLevel >= REGION_LEVEL_REQUIREMENTS.herat,
        `зона ${з.id} требует ${з.minLevel}, а Герат уже ${REGION_LEVEL_REQUIREMENTS.herat} - ` +
        'на краю света должно быть не легче, чем в Хорасане');
    }
  });

  it('у каждого края есть монстры, и стоят они в своих зонах', () => {
    const монстры = читать('server/src/data/monsters.ts');
    const спавны = читать('server/src/systems/SpawnSystem.ts');
    for (const регион of ['EAST_FRONTIER', 'WEST_FRONTIER']) {
      const сколько = (спавны.match(new RegExp(`region: Region\\.${регион}`, 'g')) ?? []).length;
      must(сколько >= 3,
        `у региона ${регион} ${сколько} точек спавна, а нужно хотя бы 3 - иначе это полоса земли, куда доезжаешь и не встречаешь никого`);
      must(new RegExp(`region: Region\\.${регион}`).test(монстры) ||
        new RegExp(`Region\\.${регион}`).test(монстры),
        `в базе монстров нет ни одного с регионом ${регион}`);
    }
  });

  it('каждая точка спавна края стоит в зоне своего региона', () => {
    // Иначе монстр, помеченный регионом востока, стоял бы в центральной
    // полосе: игрок убивал бы его и не получал отметки о посещении края.
    const спавны = читать('server/src/systems/SpawnSystem.ts');
    const точки = [...спавны.matchAll(
      /makePoint\(\{ id: '(sp_(?:east|west)[a-z_]*)',\s*monsterId: '([a-z_]+)',\s*region: Region\.([A-Z_]+),\s*position: \{ x: (-?\d+), y: 0, z: (-?\d+) \}/g)];
    must(точки.length >= 8, `прочитано ${точки.length} точек спавна краёв, а ожидалось не меньше 8 - вид разбора изменился`);
    const неверные: string[] = [];
    for (const [, id, , , x, z] of точки) {
      const зона = getZoneAt(Number(x), Number(z));
      const регион = (REGION_SPAWNS as Record<string, { x: number; z: number }>);
      const имя = id.startsWith('sp_east') ? 'east_frontier' : 'west_frontier';
      if (!зона || зона.region !== имя) {
        неверные.push(`${id} (${x}, ${z}) -> ${зона ? зона.region : 'НЕТ ЗОНЫ'}`);
      }
      void регион;
    }
    must(неверные.length === 0,
      `эти точки стоят не в своей зоне:\n  ${неверные.join('\n  ')}`);
  });

  it('названия краёв есть в интерфейсе и во всех трёх переводах', () => {
    // Подпись на карте рисуется по ключу. Нет ключа - на карте будет сам путь
    // ключа, и это видно, но выглядит как недописанный словарь.
    const hud = читать('client/src/app/hud.ts');
    must(/east_frontier: 'regions\.east_frontier'/.test(hud),
      'в списке имён регионов на экране нет дальнего востока - игрок увидит имя зоны без имени региона');
    must(/west_frontier: 'regions\.west_frontier'/.test(hud),
      'в списке имён регионов на экране нет дальнего запада');
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`)) as {
        regions: Record<string, string>; zones: Record<string, string>;
      };
      for (const ключ of ['east_frontier', 'west_frontier']) {
        must(typeof словарь.regions[ключ] === 'string', `в ${язык}.regions нет ключа ${ключ}`);
      }
      for (const зона of ZONES.filter((з) => з.region === 'east_frontier' || з.region === 'west_frontier')) {
        must(typeof словарь.zones[зона.id] === 'string', `в ${язык}.zones нет ключа ${зона.id}`);
      }
    }
  });

  it('база перечисляет все десять регионов', () => {
    // Перечислить регион в коде мало: СУБД отвергла бы запись в
    // region_visits, а recordRegionVisit не поднимает исключение, чтобы сбой
    // отметки не ронял путешествие. Ошибка гасилась, а «посетить все
    // регионы» было недостижимо. Так терялся Герат.
    const файлы = require('node:fs').readdirSync(join(корень, 'database', 'migrations'))
      .filter((f: string) => f.endsWith('.sql')).sort() as string[];
    const трогающие = файлы.filter((f) =>
      /region IN\s*\(/i.test(читать(`database/migrations/${f}`).replace(/--[^\n]*/g, ' ')));
    must(трогающие.length > 0, 'ни одна миграция не задаёт список регионов в CHECK');
    const последняя = читать(`database/migrations/${трогающие[трогающие.length - 1]}`)
      .replace(/--[^\n]*/g, ' ');
    const список = /region IN\s*\(([^)]*)\)/.exec(последняя)?.[1] ?? '';
    const имена = [...список.matchAll(/'([a-z_]+)'/g)].map((м) => м[1]);
    must(имена.includes('east_frontier'), 'в ограничении базы нет east_frontier');
    must(имена.includes('west_frontier'), 'в ограничении базы нет west_frontier');
    must(имена.length === Object.keys(REGION_SPAWNS).length,
      `в ограничении базы ${имена.length} регионов, а якорей ${Object.keys(REGION_SPAWNS).length}`);
  });

  it('у каждого региона есть город, и стоит он в зоне этого региона', () => {
    // Без города регион - полоса земли: игрок возрождается на якоре и стоит
    // в пустом поле, как стоял до появления поселений.
    const текст = читать('client/src/app/game3d/terrain.ts');
    const города = [...текст.matchAll(/\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+)/g)]
      .map((м) => ({ регион: м[1], x: Number(м[2]), z: Number(м[3]) }));
    for (const регион of ['east_frontier', 'west_frontier']) {
      const город = города.find((г) => г.регион === регион);
      must(город !== undefined, `у региона ${регион} нет города на карте - игрок возродится в пустом поле`);
      const зона = getZoneAt(город.x, город.z);
      must(зона !== null && зона.region === регион,
        `город региона ${регион} стоит в зоне ${зона ? зона.region : 'НЕТ ЗОНЫ'}`);
    }
  });
});