// Раскладка монстров подземелья по залу.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ПОЧЕМУ ИМЕННО ТАК.
//
// 1. НИ ОДИН МОНСТР НЕ СТОИТ ЗА ПРЕДЕЛАМИ ЗАЛА. Раньше позиции всех комнат
//    сводились в одну точку, и у дворца размах по x выходил 40 при ширине зала
//    32: часть монстров оказывалась в стене. Проверка берёт настоящую раскладку
//    и требует, чтобы каждая точка лежала внутри зала с отступом от стены.
//
// 2. КОМНАТЫ НЕ НАКЛАДЫВАЮТСЯ В ОДНУ ТОЧКУ. Зоны разные и упорядочены: комната
//    0 ближе к двери (больший z), боссовая — дальше всех. Если это отвалится,
//    все комнаты опять сольются.
//
// 3. БОСС СТОИТ В СЕРЕДИНЕ СВОЕЙ ЗОНЫ. Опорная точка боссовой комнаты — сам
//    босс, и по этой причине трон и алтарь рисуются вокруг него. Раньше трон
//    ставился по позиции босса из данных, а босс вставал по геометрии, и они
//    расходились: трон в (0, −12), босс в (0, 0).
//
// 4. КОМНАТА БЕЗ БОССА ЦЕНТРИРУЕТСЯ ПО СВОИМ ПОЗИЦИЯМ. Иначе комната с
//    одиночным монстром у края выдаёт его за стену.
//
// 5. ЧИСЛА ИЗ ДАННЫХ, А НЕ ИЗ КОММЕНТАРИЕВ: сколько монстров, столько и
//    запланировано. Проверка обязана видеть ненулевое число, иначе она холостая.
import { ROOM_HALF } from '../data/interiors';
import { DUNGEONS_DATABASE } from '../data/dungeons';
import { planDungeonRooms, roomAnchor, roomCentre, zoneShift, ROOM_MARGIN } from '../systems/dungeonLayout';

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const подземелья = Object.entries(DUNGEONS_DATABASE);
const всегоМонстров = подземелья.reduce((с, [, def]) => {
  for (const комната of def.rooms) {
    for (const группа of комната.monsters) с += группа.count;
  }
  return с;
}, 0);

describe('Раскладка подземелий по залу', () => {
  it('проверка замерена на непустых данных', () => {
    must(подземелья.length >= 5, `подземелий ${подземелья.length}, а проверка писалась под пять`);
    must(всегоМонстров >= 60, `монстров в данных ${всегоМонстров}: проверка на таком объёме ничего не значит`);
    must(ROOM_HALF === 16, `ROOM_HALF = ${ROOM_HALF}, а проверка считает зал 32x32`);
  });

  it('ни один монстр не стоит за пределами зала', () => {
    for (const [id, def] of подземелья) {
      for (const комната of planDungeonRooms(def)) {
        for (const монстр of комната.monsters) {
          const внутри =
            Math.abs(монстр.x - def.entryX) <= ROOM_HALF - ROOM_MARGIN &&
            Math.abs(монстр.z - def.entryZ) <= ROOM_HALF - ROOM_MARGIN;
          must(
            внутри,
            `${id}: ${монстр.monsterId} из комнаты ${комната.index} в ` +
              `(${монстр.x}, ${монстр.z}) — зал занимает ` +
              `${def.entryX - ROOM_HALF}…${def.entryX + ROOM_HALF} по x, монстр в стене`
          );
        }
      }
    }
  });

  it('комнаты стоят в разных зонах, входная у двери, боссовая дальше всех', () => {
    for (const [id, def] of подземелья) {
      const комнаты = planDungeonRooms(def);
      must(комнаты.length >= 2, `${id}: комнат ${комнаты.length}, а зоны раскладываются от двух и выше`);
      for (let k = 1; k < комнаты.length; k++) {
        must(
          комнаты[k].zoneZ < комнаты[k - 1].zoneZ,
          `${id}: зона ${k} (z = ${комнаты[k].zoneZ}) не дальше зоны ${k - 1} ` +
            `(z = ${комнаты[k - 1].zoneZ}) — комнаты слиплись или идут не от двери`
        );
      }
      const боссовая = def.rooms.findIndex((р) => р.isBossRoom);
      must(боссовая >= 0, `${id}: боссовой комнаты нет, а раскладка её ждёт`);
      must(
        боссовая === комнаты.length - 1 || комнаты[боссовая].zoneZ === zoneShift(боссовая, комнаты.length),
        `${id}: боссовая комната не на своём месте по раскладке`
      );
    }
  });

  it('босс стоит в середине своей зоны', () => {
    for (const [id, def] of подземелья) {
      const планы = planDungeonRooms(def);
      for (const план of планы) {
        const комната = def.rooms[план.index];
        if (!комната.isBossRoom || !комната.bossId) continue;
        const боссы = план.monsters.filter((м) => м.monsterId === комната.bossId);
        must(боссы.length > 0, `${id}: босс ${комната.bossId} не запланирован вовсе`);
        for (const босс of боссы) {
          must(
            Math.abs(босс.z - план.zoneZ) <= ROOM_HALF,
            `${id}: босс ${комната.bossId} в z = ${босс.z - def.entryZ}, а зона комнаты ` +
              `${план.index} в z = ${план.zoneZ - def.entryZ} — он не в своём зале`
          );
          must(
            Math.abs(босс.x - def.entryX) <= ROOM_HALF,
            `${id}: босс ушёл по x в ${босс.x - def.entryX} от центра зала`
          );
        }
        // Опорная точка боссовой комнаты — сам босс, а не середина позиций.
        const опора = roomAnchor(комната);
        const позицииБосса = комната.monsters
          .filter((г) => г.monsterId === комната.bossId)
          .flatMap((г) => г.positions);
        if (позицииБосса.length === 1) {
          must(
            опора.x === позицииБосса[0].x && опора.z === позицииБосса[0].z,
            `${id}: опорная точка (${опора.x}, ${опора.z}) — это не позиция босса ` +
              `(${позицииБосса[0].x}, ${позицииБосса[0].z}): трон рисуется вокруг опоры, ` +
              `а босс встанет в другое место`
          );
        }
        // Совпадение опоры с серединой позиций бывает случайно (у Рустама обе точки
        // равны нулю), и требовать, чтобы они различались, значит требовать
        // ошибки. Поэтому второго утверждения здесь нет: правило опоры целиком
        // проверяется предыдущим — опора есть позиция босса.
      }
    }
  });

  it('комната без босса центрируется по своим позициям', () => {
    let проверено = 0;
    for (const [, def] of подземелья) {
      for (const план of planDungeonRooms(def)) {
        const комната = def.rooms[план.index];
        if (комната.isBossRoom && комната.bossId) continue;
        const z = план.monsters.map((м) => м.z);
        must(z.length > 0, 'комната без монстров: проверке не на чем стоять');
        // Опорная точка обычной комнаты — ровно середина её позиций: не босс
        // и не ручное число.
        must(
          roomAnchor(комната).x === roomCentre(комната).x &&
            roomAnchor(комната).z === roomCentre(комната).z,
          `комната ${план.index}: опора (${roomAnchor(комната).x}, ${roomAnchor(комната).z}) ` +
            `разошлась с серединой позиций (${roomCentre(комната).x}, ${roomCentre(комната).z})`
        );
        // Середина зоны должна попадать внутрь диапазона монстров либо рядом:
        // после обрезки по стене это единственное, что можно требовать.
        must(
          Math.min(...z) <= план.zoneZ + ROOM_HALF && Math.max(...z) >= план.zoneZ - ROOM_HALF,
          `зона комнаты ${план.index} (z = ${план.zoneZ}) не пересекается с её монстрами ` +
            `${Math.min(...z)}…${Math.max(...z)}`
        );
        проверено++;
      }
    }
    must(проверено >= 8, `небоссовых комнат ${проверено}: слишком мало`);
  });

  it('запланировано столько же монстров, сколько в данных', () => {
    for (const [id, def] of подземелья) {
      const вДанных = def.rooms.reduce(
        (с, комната) => с + комната.monsters.reduce((н, г) => н + г.count, 0),
        0
      );
      const вРаскладке = planDungeonRooms(def).reduce((с, комната) => с + комната.monsters.length, 0);
      must(
        вРаскладке === вДанных,
        `${id}: в данных ${вДанных} монстров, в раскладке ${вРаскладке}`
      );
      must(вДанных > 0, `${id}: в данных нет монстров, проверка холостая`);
    }
  });

  it('обрезка по стене не стирает комнату в ноль', () => {
    for (const [id, def] of подземелья) {
      for (const план of planDungeonRooms(def)) {
        const различные = new Set(план.monsters.map((м) => `${м.x}:${м.z}`));
        must(
          различные.size === план.monsters.length,
          `${id}: комната ${план.index}: ${план.monsters.length} монстров легли в ` +
            `${различные.size} точек — половина захода стоит друг на друге`
        );
      }
    }
  });

  it('зона тем уже, чем больше комнат, и не схлопывается', () => {
    must(zoneShift(0, 2) === 7.5, `зона для двух комнат: ${zoneShift(0, 2)}`);
    must(zoneShift(0, 3) === 10, `зона для трёх комнат: ${zoneShift(0, 3)}`);
    must(zoneShift(2, 3) === -10, `дальняя зона для трёх комнат: ${zoneShift(2, 3)}`);
    must(
      zoneShift(0, 5) > zoneShift(0, 3),
      'пять комнат не могут получить зону шире трёх: зал не резиновый'
    );
    for (let n = 1; n <= 40; n++) {
      const зоны = Array.from({ length: n }, (_, k) => zoneShift(k, n));
      if (n <= 9) {
        must(
          new Set(зоны).size === n,
          `${n} комнат: зон ${зоны.length}, разных ${new Set(зоны).size} — комнаты слиплись`
        );
      }
      // Дальняя зона обязана остаться в зале для любого числа комнат: у этой
      // границы нет отдельной проверки в коде, и она обязана быть тут.
      const дальняя = Math.max(...зоны.map(Math.abs));
      must(
        дальняя <= ROOM_HALF,
        `${n} комнат: самая дальняя зона уходит на ${дальняя} — за стену (зал ${ROOM_HALF * 2})`
      );
    }
    // Ширина зоны обязана зависеть от числа комнат, иначе подземелье с пятью
    // комнатами растянуло бы их на весь зал.
    must(
      zoneShift(0, 5) > zoneShift(0, 3) && zoneShift(2, 3) === -10,
      'ширина зоны не зависит от числа комнат: зоны растянуты по всему залу'
    );
  });
});