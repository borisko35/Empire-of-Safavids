// Игра распространяется по GPL-3.0, и лицензия должна ехать вместе с ней.
//
// ЗАЧЕМ ФАЙЛ. Проверено, что на сайте не было НИ ОДНОГО упоминания лицензии:
// LICENSE лежал в корне репозитория, а игрок и посетитель его не видят. На
// трёх страницах, которые расходятся по соцсетям, ни текста лицензии, ни
// слов о том, что игра свободная. Для публикации на itch.io и Reddit это не
// украшение: GPL требует передавать текст лицензии вместе с программой.
//
// ЧТО ТРЕБУЕТСЯ И ЧТО НЕ ПРОВЕРЯЕТСЯ. Проверяется то, что можно проверить
// кодом: файл едет вместе с игрой, на страницах есть видимая ссылка с
// rel="license", она ведёт на существующий файл, текст на трёх языках.
// НЕ проверяется и не может быть проверено здесь: выполнение условий GPL
// целиком. Текст лицензии требует, чтобы исходный код предлагался -
// где и как, решает владелец, и это отдельно стоит в tools/itch-reddit-draft.md.
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ЯЗЫКИ = ['ru', 'en', 'az'] as const;
const словари = ЯЗЫКИ.map(l => JSON.parse(читать('shared/locales/' + l + '.json')) as {
  site: Record<string, string>;
});

describe('Лицензия едет вместе с игрой', () => {
  it('текст GPL лежит в поставляемой папке и совпадает с корневым', () => {
    // Именно совпадает, а не «похож на GPL». Копия текста лицензии, которая
    // разошлась с оригиналом, - это уже другой документ.
    const кореньLICENSE = join(корень, 'LICENSE');
    const вПоставке = join(корень, 'client/web/LICENSE');
    must(existsSync(кореньLICENSE), 'нет LICENSE в корне репозитория');
    must(existsSync(вПоставке), 'нет client/web/LICENSE - лицензия не едет с игрой');
    const разница = readFileSync(кореньLICENSE).compare(readFileSync(вПоставке));
    expect({ разница_байт: разница, размер: statSync(вПоставке).size })
      .toEqual({ разница_байт: 0, размер: 35823 });
  });

  it('это действительно GPL версии 3, а не что-то другое', () => {
    const текст = читать('client/web/LICENSE');
    expect({
      название: /GNU GENERAL PUBLIC LICENSE/.test(текст),
      версия: /Version 3, 29 June 2007/.test(текст),
      // Право распространять: без этой формулировки это не лицензия, а
      // упоминание о ней.
      право_razdayat: /Everyone is permitted to copy and distribute verbatim copies/.test(текст),
    }).toEqual({ название: true, версия: true, право_razdayat: true });
  });

  it('на лендинге в подвале есть видимая ссылка с rel="license"', () => {
    // ГЛАВНАЯ ПРОВЕРКА. Ссылка должна быть в подвале рядом со строкой об
    // авторе, а не спрятана где-то. rel="license" — машинно-читаемая
    // пометка: без неё ссылка выглядит как ещё один пункт меню.
    const лендинг = читать('client/web/index.html');
    const подвал = лендинг.slice(лендинг.indexOf('<footer'));
    must(подвал.length > 0, 'в index.html нет подвала');
    // Расстояние меряется ПО БЕЗ HTML-комментариев. Первая версия мерила по
    // сырому тексту и требовала не больше 200 символов между строкой об
    // авторе и ссылкой. Между ними стоял мой же комментарий в пять строк -
    // 332 символа, и проверка краснела, хотя посетитель видит их вплотную.
    // Проверка обязана мерить то, что видно, а не то, как длинно объяснение.
    const видимое = подвал.replace(/<!--[\s\S]*?-->/g, '');
    expect({
      ссылка_есть: /<a href="\/LICENSE"[^>]*rel="license"/.test(подвал),
      ключ_перевода_есть: /data-i18n="site\.license"/.test(подвал),
      // И рядом со строкой об авторе: держатель назван, лицензия должна
      // стоять вплотную к нему, а не болтаться в углу подвала.
      рядом_с_автором:
        видимое.indexOf('rel="license"') - видимое.indexOf('Sigma Arena') < 200,
    }).toEqual({ ссылка_есть: true, ключ_перевода_есть: true, рядом_с_автором: true });
  });

  it('ссылка ведёт на файл, который реально отдаётся', () => {
    // Ссылка на /LICENSE, которой нет, - это «ссылка плохая» снаружи и
    // «сломанный файл» внутри. Проверяется на диске: файл лежит рядом с
    // index.html, значит nginx отдаст его из того же корня.
    const лендинг = читать('client/web/index.html');
    const цели = [...лендинг.matchAll(/<a href="(\/LICENSE)"/g)].map(m => m[1]);
    must(цели.length > 0, 'в index.html нет ссылки на /LICENSE');
    const отсутствуют = цели.filter(путь => {
      const локально = join(корень, 'client/web', путь.replace(/^\//, ''));
      return !existsSync(локально) || statSync(локально).size < 1000;
    });
    expect({ ссылок: цели.length, отсутствуют }).toEqual({ ссылок: 1, отсутствуют: [] });
  });

  it('на трейлере лицензия есть на трёх языках и переключается', () => {
    // Трейлер - та страница, которую кладут в тред. Если строка про
    // лицензию есть только по-русски, половина читателей её не увидит.
    // Первая версия этой проверки требовала, чтобы все три строки были видны
    // сразу - то есть проверка сама требовала недоделки из трёх строк подряд.
    const трейлер = читать('client/web/trailer.html');
    const языки = [...трейлер.matchAll(/data-lic="(\w+)"/g)].map(m => m[1]);
    expect({
      языки_в_разметке: языки,
      // Ровно три: и русский, и английский, и азербайджанский.
      все_три: ['ru', 'en', 'az'].every(я => языки.includes(я)),
      // И при смене языка остальные две строки прячутся.
      переключение_есть: /s\.style\.display = s\.dataset\.lic === lang/.test(трейлер),
    }).toEqual({
      языки_в_разметке: ['ru', 'en', 'az'],
      все_три: true,
      переключение_есть: true,
    });
  });

  it('текст лицензии на трёх языках не пустой и говорит одно и то же', () => {
    // Перевод в одном языке оставляет на двух старый текст, а это хуже,
    // чем вовсе: выглядит как «перевод не доделан».
    const пустые: Record<string, boolean> = {};
    for (let i = 0; i < ЯЗЫКИ.length; i++) {
      const текст = словари[i].site.license;
      пустые[ЯЗЫКИ[i]] = !текст || текст.trim().length < 5;
    }
    expect({ пустые }).toEqual({ пустые: { ru: false, en: false, az: false } });
    // И все три называют одну и ту же лицензию - иначе это три разных
    // обещания на трёх языках.
    const называютGPL = ЯЗЫКИ.map((_, i) => /GNU GPL v3/.test(словари[i].site.license));
    expect({ называютGPL }).toEqual({ называютGPL: [true, true, true] });
  });

  it('в поставляемой папке лицензия не единственная, а ключ один', () => {
    // Защита от двух расхождений сразу: страница ссылается на ключ, которого
    // в словаре нет (пустая ссылка на лендинге), и словарь содержит ключ,
    // который никто не использует (мёртвый перевод).
    const лендинг = читать('client/web/index.html');
    const используется = /data-i18n="site\.license"/.test(лендинг);
    must(используется, 'ключ site.license не используется на лендинге');
    const естьВ = ЯЗЫКИ.filter((_, i) => typeof словари[i].site.license === 'string');
    expect({ ключ_в_языках: естьВ }).toEqual({ ключ_в_языках: ['ru', 'en', 'az'] });
  });
});

/**
 * ГЛАВНОЕ, ЧТО ОСТАЛОСЬ НЕ ЗАКРЫТЫМ. Репозиторий приватный.
 *
 * Проверено не догадкой: пользователь borisko35 на GitHub отвечает 200,
 * заведомо публичный torvalds/linux отвечает 200, а
 * api.github.com/repos/borisko35/Empire-of-Safavids отвечает 404 - при том
 * что пушить в него можно. Значит репозиторий приватный, и игрок, у которого
 * есть собранная игра, не может получить исходный код.
 *
 * GPL-3.0 требует предлагать исходный код. Это решение владельца, и оно не
 * моё. Но одно можно закрыть сегодня: сайт НЕ ДОЛЖЕН обещать исходный код,
 * не указав где. Пока обещания нет - все в порядке. Обещание без адреса -
 * это ровно такая же ложь, как была подпись «Утренний Тебриз» над кадром из
 * Исфахана: короткая, правдоподобная и неправда.
 */
describe('Обещание исходного кода не должно остаться без адреса', () => {
  const ОБЕЩАНИЯ = [
    /исходн(ый|ого|ым)\s+код/i,
    /source\s+code/i,
    /исходник(и|ов|ам)?\s+(доступн|открыт|свободн)/i,
    /open[\s-]?source/i,
  ];

  it('если сайт обещает исходный код, он говорит где', () => {
    const страницы = ['client/web/index.html', 'client/web/trailer.html', 'client/web/forum.html'];
    const тексты: string[] = [];
    for (const p of страницы) {
      if (!existsSync(join(корень, p))) continue;
      // HTML-комментарии вырезаются ДО сканирования. Комментарий посетителю
      // не виден, значит и обещанием он не является. Первая версия их
      // сканировала, и нашла обещание в комментарии, который я сам только что
      // написал про ссылку на исходный код: адрес лежал дальше окна в 140
      // символов, за комментарием. Проверка указала, что я сделал, но видела
      // не то, что читает человек.
      тексты.push(читать(p).replace(/<!--[\s\S]*?-->/g, ' '));
    }
    for (const словарь of словари) {
      for (const раздел of Object.values(словарь as unknown as Record<string, unknown>)) {
        if (!раздел || typeof раздел !== 'object') continue;
        // Только строки. В словарях кроме строк лежат вложенные объекты и
        // числа, и без проверки типа текст.matchAll падал с TypeError -
        // то есть проверка падала не по своей причине, а по чужой.
        for (const значение of Object.values(раздел as Record<string, unknown>)) {
          if (typeof значение === 'string') тексты.push(значение);
        }
      }
    }

    const АДРЕС = /https?:\/\/|github\.com|репозитор/i;
    // Обещание ищется вместе с окрестностями, а адрес ищется ТОЛЬКО В НЁМ.
    // Первая версия проверяла адрес по всему тексту страницы, и обещание
    // «Source code available» проходило: в <meta og:image> на той же
    // странице лежит посторонний https://game.eos-gameonline.com/... ,
    // и он засчитывался как «адрес назван». Поломка на странице не гасила
    // проверку - ровно та ловушка, ради которой всё затевалось.
    // Адрес ищется ТОЛЬКО ВПЕРЁД от обещания, и не дальше 80 символов.
    //
    // Окно в обе стороны было ошибкой дважды. Первая версия брала окно по
    // всей странице, и посторонний https:// в <meta og:image> засчитывался
    // как «адрес назван». Вторая брала ±140 символов, и адрес из СОСЕДНЕГО
    // блока засчитывался: обещание «Source code available» в подсказке
    // проходило, потому что через сто символов начиналась строка со ссылкой
    // на ролик. Требование простое: адрес идёт сразу за обещанием.
    //
    // В наших блоках адрес идёт через 15–25 символов после слов «Ролик
    // целиком», «Исходный код», «Свободное ПО» - 80 хватает с запасом.
    const ОКНО = 80;
    const обещания: string[] = [];
    for (const текст of тексты) {
      for (const образец of ОБЕЩАНИЯ) {
        const флаги = образец.flags.includes('g') ? образец.flags : образец.flags + 'g';
        const re = new RegExp(образец.source, флаги);
        for (const m of текст.matchAll(re)) {
          const начало = m.index ?? 0;
          const до = Math.min(текст.length, начало + m[0].length + ОКНО);
          обещания.push(текст.slice(начало, до));
        }
      }
    }
    const безАдреса = [...new Set(обещания.filter(т => !АДРЕС.test(т)).map(выжимка))];

    // Требуется ровно одно: у каждого обещания есть адрес. НЕ требуется, чтобы
    // обещаний не было вовсе. Первая версия проверяла «обещаний_найдено: 0»
    // и тем самым запрещала то, ради чего всё затевалось: стоит владельцу
    // открыть репозиторий и вписать ссылку - и проверка краснеет на честном
    // тексте. Обещать молчание нельзя, обещать можно только с адресом.
    expect({ без_адреса: безАдреса }).toEqual({ без_адреса: [] });

    // Детектор проверяется на заведомо положительном примере. Ноль найденных
    // обещаний сам по себе НИЧЕГО не значит: он одинаков и когда обещаний
    // правда нет, и когда регулярка сломалась и перестала находить. Без этой
    // строки «0» - это подозрительный ноль, а не результат.
    expect({
      детектор_ловит: ОБЕЩАНИЯ.some(r => r.test('Исходный код доступен')),
      адрес_распознаётся: АДРЕС.test('github.com/borisko35/Empire-of-Safavids'),
    }).toEqual({ детектор_ловит: true, адрес_распознаётся: true });
  });
});

/** Короткая выжимка для отчёта: не сам текст, а его начало. */
function выжимка(текст: string): string {
  return текст.replace(/\s+/g, ' ').trim().slice(0, 40);
}
