// Экстерьер таможни: третье из шести зданий без экстерьера.
//
// ЧТО ЗАКРЕПЛЯЕТ. По точке (-900, 800) не стояло ничего: запись интерьера
// «Таможенный двор. Западнее города: проверяет идущих снаружи внутрь» была без
// дома — ни здания, ни ровнялки, ни двери. Комплекс собран примитивами, и
// почти всё в нём выведено замером:
//
//   1. Площадка ровняется ПОСЛЕ ровнялки залива. Ровнялка залива стоит выше с
//      центром (0, -820) и радиусом 900, а таможня в 1853 м от её центра и
//      попадает в зону смешивания. Поставленная выше, площадка молча получала
//      бы не свой уровень — ровно то, из-за чего дворец стоял на 2.367 вместо
//      2.2 и дверь с игроком расходились на 17 см.
//   2. Радиуса ровнялки хватает на весь комплекс ВКЛЮЧАЯ башни: flatten()
//      держит ровную землю только до 0.55r, а meshHeight интерполирует по
//      вершинам сетки шагом 14.11 м, и вершина уезжает за круг.
//   3. Уровень площадки равен измеренной медиане высот по габариту, а не
//      выбран на глаз: место стоит на склоне с перепадом 2.05 м в 40 м.
//   4. Начало местных координат — линия двери, а не центр площадки. Точка
//      выхода в данных на четыре метра дальше по плюс z, и сдвиг начала на
//      метр сдвинул бы дверь от игрока.
//   5. Проём ворот есть ТОЛЬКО в стене с воротами. Первая версия поставила
//      условие на ЗАДНЕЙ стене, а стена с воротами шла сплошной цепочкой:
//      ворота были запечатаны, игрок не мог выйти из двора. Поймала проверка
//      проходимости, а не чтение кода.
//   6. Перед передней стеной дома нет коллайдера, иначе к двери не подойти.
//   7. Коллайдеры идут цепочкой с шагом не больше двойного радиуса.
//   8. Под комплексом сухо: вода залива в 1853 м, а берег у таможни сухой.
//   9. Навес досмотра не перекрывает проезд от ворот к двери.
//  10. Дверь кликабельная и ведёт в интерьер таможни.
//
// ЧЕГО ПРОВЕРКА НЕ ДЕЛАЕТ. Она не строит сцену и не мерит землю: terrain.ts
// требует document и canvas, в Node не импортируется, а копия функции измеряла
// бы саму себя. Ровность площадки измерена инструментом по настоящему коду и
// записана в карте: дверь и точка выхода ровно 0.2000, перепад по двору 0.000,
// по комплексу с башнями 0.051, просвет по оси ворот 0.80 м.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

/** Только исполняемые строки: комментарии и пустые убираются. */
function безКомментариев(код: string): string {
  return код
    .split('\n')
    .filter((строка) => !/^\s*(\/\/|\*|\/\*)/.test(строка))
    .filter((строка) => строка.trim() !== '')
    .join('\n');
}

/** Строки кода блока таможни внутри buildSettlements, а не константы. */
function блокТаможни(): string {
  const начало = ТЕРРЕЙН.indexOf('Таможенный двор ──');
  must(начало > 0, 'в terrain.ts нет блока постройки таможни');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', начало);
  must(конец > начало, 'блок таможни не найден по границе акведука');
  return ТЕРРЕЙН.slice(начало, конец);
}

describe('Таможня: площадка', () => {
  it('поставлена на месте записи интерьера', () => {
    // Запись «Таможенный двор. Западнее города» стоит в (-900, 800), и площадка
    // обязана совпадать с ней: дом в другой точке означал бы, что игрок доходит
    // до пустоты, а двор стоит отдельно.
    must(
      /id: 'customs',[^}]*dx: -900, dz: 800/.test(ИНТЕРЬЕРЫ),
      'запись таможни в интерьерах изменилась: площадка без неё окажется не там',
    );
    must(
      /export const CUSTOMS = \{ x: -900, z: 800,/.test(ТЕРРЕЙН),
      'площадка таможни не совпадает с записью интерьера (-900, 800)',
    );
  });

  it('ровнялка стоит ПОСЛЕ ровнялки залива', () => {
    // Порядок, а не причина. Ровнялка залива имеет центр (0, -820) и радиус
    // 900, то есть ровная часть её — 495 м и накрывает полкарты. Площадка,
    // поставленная выше, молча подтягивается к уровню залива. Так дворец
    // получил 2.367 вместо своих 2.2.
    const код = безКомментариев(ТЕРРЕЙН);
    const залив = код.indexOf('flatten(h, x, z, 0, -820, 900, 3.5)');
    const дворец = код.indexOf('flatten(h, x, z, PALACE.x');
    const таможня = код.indexOf('flatten(h, x, z, CUSTOMS.x');
    must(залив > 0, 'ровнялка залива не найдена в terrainHeight');
    must(дворец > залив, 'дворец почему-то поставлен выше залива');
    must(
      таможня > залив,
      'площадка таможни поставлена выше ровнялки залива: она молча получит ' +
        'чужой уровень, ровно как дворец получил 2.367 вместо 2.2',
    );
  });

  it('радиуса хватает на комплекс вместе с башнями', () => {
    // Ровная часть ровнялки — это 0.55 радиуса. Габарит таможни 26 x 24 м, и с
    // выступами башен полудиагональ 23.3 м: при радиусе 42 (23.1 м) не хватает.
    const m = /export const CUSTOMS = \{ x: -900, z: 800, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус площадки таможни не объявлен');
    const радиус = Number(m![1]);
    const ровная = радиус * 0.55;
    const полу = Math.hypot(26 / 2 + 3, 24 / 2 + 3);
    must(
      ровная >= полу,
      `ровная часть ровнялки ${ровная.toFixed(1)} м уже полудиагонали ` +
        `${полу.toFixed(1)} м: угол с башней уедет из-под ровнялки`,
    );
    must(
      ровная - полу >= 2,
      `запас в ${(ровная - полу).toFixed(1)} м мал: вершина сетки в 14.11 м ` +
        'уезжает за круг и тянет площадку к родной земле',
    );
  });

  it('уровень площадки совпадает с измеренной медианой, а не выбран на глаз', () => {
    // Замер по габариту 26 x 24, 1155 точек: минимум -0.05, максимум 1.45,
    // среднее 0.39, медиана 0.23. Уровень 0.2 даёт минимум суммы «срез плюс
    // засыпка». Если уровень увеличат без замера, площадка станет цоколем.
    const m = /export const CUSTOMS = \{ x: -900, z: 800, radius: \d+, level: ([\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'уровень площадки таможни не объявлен');
    const уровень = Number(m![1]);
    must(
      уровень >= 0.05 && уровень <= 0.5,
      `уровень ${уровень} м выходит за измеренную медиану 0.23: площадка ` +
        'станет цоколем или уйдёт в срез',
    );
  });

  it('под комплексом сухо', () => {
    // Ровнялка залива центр (0, -820), радиус 900. Таможня в 1853 м от центра,
    // то есть далеко за заливом, но сушу надо проверить по данным, а не по
    // расстоянию до центра ровнялки.
    must(!isWater(-900, 800), 'под таможней вода: комплекс стоял бы в заливе');
    for (const [x, z] of [[-913, 787], [-887, 814], [-925, 825]] as const) {
      must(!isWater(x, z), `вода в пределах комплекса, точка ${x},${z}`);
    }
  });
});

describe('Таможня: проём в воротах', () => {
  it('проём есть ТОЛЬКО в стене с воротами, а не в задней', () => {
    // БЫЛ БАГ, ИЗ-ЗА КОТОРОГО ДВОР БЫЛ ЗАПЕЧАТАН. Условие `|wx| >= GATE_W/2`
    // стояло на ЗАДНЕЙ стене, а стена с воротами шла сплошной цепочкой. Итог:
    // игрок не мог выйти из двора, а сайт при этом отвечал, /health был зелёный
    // и все модели на месте. Поймала проверка проходимости.
    const блок = блокТаможни();
    must(
      /if \(Math\.abs\(wx\) >= GATE_W \/ 2\)/.test(блок),
      'в коллайдерах стены нет условия проёма: ворота запечатаны, как было',
    );
    // Условие должно ОХВАТЫВАТЬ ряд стены с воротами и НЕ охватывать
    // задний. Порядок строк в исходнике ничего не значит, и судить по нему
    // нельзя: первая версия проверки именно так и делала, и падала на
    // правильном коде, потому что прокси на признак не равен признаку.
    const ifБлок = /if \(Math\.abs\(wx\) >= GATE_W \/ 2\) \{\n([^}]*)\n\s*\}/.exec(блок);
    must(ifБлок !== null, 'не найден блок условия проёма в коллайдерах стены');
    const внутриУсловия = ifБлок![1];
    must(
      /zGate - WALL_T \/ 2/.test(внутриУсловия),
      'условие проёма НЕ охватывает ряд стены с воротами: ворота запечатаны, ' +
        'игрок не может выйти из двора',
    );
    must(
      !/CUSTOMS\.z \+ zBack/.test(внутриУсловия),
      'условие проёма охватывает заднюю стену: в глухой стене появилась дыра',
    );
    // Задний ряд обязан быть ВНЕ условия и идти сплошным.
    const заднийРяд = /addCollider\(CUSTOMS\.x \+ wx, CUSTOMS\.z \+ zBack, [\d.]+\);/.exec(блок);
    must(заднийРяд !== null, 'не найден ряд коллайдеров задней стены');
    must(
      !внутриУсловия.includes('zBack'),
      'задняя стена попала внутрь условия проёма',
    );
  });

  it('проём в геометрии совпадает с объявленным GATE_W', () => {
    // Полотна стены кладутся по краям проёма, поэтому внутренняя кромка равна
    // ровно GATE_W/2 с каждой стороны.
    const блок = блокТаможни();
    must(
      /const seg = \(WALL_W - WALL_T \* 2 - GATE_W\) \/ 2;/.test(блок),
      'полотна стены с воротами считаются не от GATE_W: проём в геометрии ' +
        'разойдётся с тем, что заявлен',
    );
    must(
      /s \* \(GATE_W \/ 2 \+ seg \/ 2\)/.test(блок),
      'полотно стены поставлено не вплотную к проёму',
    );
  });

  it('столбы ворот не перекрыты отдельными кругами', () => {
    // Круг радиусом 1.0 на местных ±2.55 заходил в проём на 0.55 м с каждой
    // стороны и сужал просвет до 1.1 м. Столб стоит на тех же местах, что и
    // стена, а стена уже закрыта коллайдером, то есть круг был и лишним, и
    // вредным.
    const блок = блокТаможни();
    must(
      !/addCollider\(CUSTOMS\.x \+ s \* \(GATE_W/.test(блок),
      'у столбов ворот снова появились свои коллайдеры: они дублируют стену и ' +
        'заходят в проём, сужая просвет для игрока',
    );
  });

  it('просвет по оси ворот остаётся для игрока', () => {
    // Игрок — круг радиусом 1.0 м. Он проходит, если просвет по оси больше
    // нуля, то есть |блокер| минус (его радиус плюс радиус игрока) > 0.
    // Измерено по коду: 0.80 м с каждой стороны.
    const блок = блокТаможни();
    const m = /addCollider\(CUSTOMS\.x \+ wx, CUSTOMS\.z \+ zGate - WALL_T \/ 2, ([\d.]+)\)/.exec(блок);
    must(m !== null, 'не найден коллайдер стены с воротами');
    const радиусСтены = Number(m![1]);
    // Ближайший коллайдер к оси стоит на |wx| >= 3 при шаге 2 от центра.
    const ближайший = 3;
    const просвет = ближайший - (радиусСтены + 1.0);
    must(
      просвет > 0,
      `просвет по оси ${просвет.toFixed(2)} м: игрок радиусом 1.0 м не пройдёт`,
    );
    must(
      просвет >= 0.5,
      `просвет ${просвет.toFixed(2)} м впритык: игрок будет скрести створками`,
    );
  });
});

describe('Таможня: дверь и подход', () => {
  it('начало местных координат — линия двери', () => {
    // Точка выхода в данных (-900, 804) на четыре метра дальше по плюс z от
    // двери (-900, 800). Если начало координат сдвинуть (как у дворца, где
    // пришлось ставить HALL_FRONT_Z = -1), дверь уедет от игрока на метр.
    must(
      /export const CUSTOMS = \{ x: -900, z: 800,/.test(ТЕРРЕЙН),
      'группа таможни должна стоять в точке двери из данных',
    );
    const блок = блокТаможни();
    must(
      /door\.position\.set\(0, 1\.7, HOUSE_T \/ 2 \+ 0\.15\)/.test(блок),
      'дверь поставлена не в нулевой линии: она уедет от игрока',
    );
    must(
      /g\.position\.set\(CUSTOMS\.x, CUSTOMS\.level, CUSTOMS\.z\)/.test(блок),
      'группа таможни встала не в точку двери и не на уровень площадки',
    );
  });

  it('дверь кликабельная и ведёт в интерьер таможни', () => {
    const блок = блокТаможни();
    must(/doorBuilding: 'customs'/.test(блок), 'у двери таможни нет doorBuilding');
    must(/doorAction: 'enter'/.test(блок), 'дверь таможни не ведёт внутрь');
    must(
      /doorName: t\('buildings\.customs'\)/.test(блок),
      'дверь таможни подписана не тем названием',
    );
  });

  it('перед дверью нет коллайдера', () => {
    // Иначе игрок подойдёт к стене вплотную и не сможет её кликнуть, то есть
    // не сможет войти. Ровно та же причина, по которой у караван-сарая убран
    // коллайдер в середине ворот.
    const блок = блокТаможни();
    must(
      /Math\.abs\(wx\) >= ТАМОЖЕННЫЙ_ПРОЁМ \/ 2 \+ 1\.6/.test(блок),
      'передний ряд коллайдеров дома не пропускает дверной проём: к двери ' +
        'не подойти, а значит и не войти',
    );
  });

  it('в проёме есть заглушка, иначе дверь читается как дыра', () => {
    // Зала снаружи нет, и без заглушки сквозь проём видно небо.
    const блок = блокТаможни();
    must(/MAT\.dark/.test(блок), 'в проёме двери нет тёмной заглушки');
    must(
      /BoxGeometry\(ТАМОЖЕННЫЙ_ПРОЁМ, 3\.4, 0\.25\)/.test(блок),
      'заглушка проёма не по размеру двери',
    );
  });
});

describe('Таможня: двор', () => {
  it('навес досмотра не перекрывает проезд от ворот к двери', () => {
    // Навес стоит у ворот, а не посередине двора. Посередине он перекрыл бы
    // проход, и караван встал бы под крышей вместо того, чтобы въехать.
    const блок = блокТаможни();
    must(
      /const canopyZ = zGate - CANOPY_D \/ 2 - 1\.5;/.test(блок),
      'навес поставлен не у ворот: он перекрыл бы проход от ворот к двери',
    );
    must(
      /const CANOPY_H = 3\.2;/.test(блок),
      'высота навеса не объявлена: проход под ним не проверить',
    );
    must(
      /CANOPY_H \+ 0\.09/.test(блок) && /CANOPY_H \+ 0\.24/.test(блок),
      'кровля навеса не на его высоте: она либо внутри навеса, либо в воздухе',
    );
  });

  it('столы стоят по краям навеса, ось проезда свободна', () => {
    const блок = блокТаможни();
    must(
      /const cx = s \* \(CANOPY_W \/ 2 - 1\.1\);/.test(блок),
      'столы досмотра поставлены не по краям: проезд между ними перекрыт',
    );
    must(
      /for \(const s of \[-1, 1\] as const\) \{\n\s+const cx/.test(блок),
      'столы не строятся симметрично по краям навеса',
    );
  });

  it('плита двора почти вровень с землёй', () => {
    // Подъём 4 см читается как мощение. Полметра — это цоколь, и двор перестаёт
    // быть двором, а становится террасой.
    const m = /export const ТАМОЖЕННЫЙ_ДВОР = \{ t: ([\d.]+), подъём: ([\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'параметры плиты двора не объявлены');
    const подъём = Number(m![2]);
    must(
      подъём <= 0.1,
      `подъём плиты ${подъём} м велик: двор читается как цоколь, а не как мощение`,
    );
  });

  it('коллайдеры идут цепочкой, а не редеют', () => {
    // Шаг не больше двойного радиуса, иначе между кругами игрок пройдёт сквозь
    // стену.
    const блок = блокТаможни();
    for (const шаг of [
      /let wx = -WALL_W \/ 2; wx <= WALL_W \/ 2; wx \+= 2/,
      /let wz = zBack; wz <= zGate; wz \+= 2/,
      /let wx = -HOUSE_W \/ 2; wx <= HOUSE_W \/ 2; wx \+= 2/,
    ]) {
      must(шаг.test(блок), 'цепочка коллайдеров идёт с шагом больше 2 м');
    }
  });

  it('у ящиков и бочки есть свои коллайдеры', () => {
    // Иначе игрок проходит сквозь конфискованный груз, а это главный смысл
    // таможни: двор без груза читается как пустая площадка.
    const блок = блокТаможни();
    must(/const CRATES: \[number, number, number\]\[\]/.test(блок), 'ящики не объявлены');
    must(
      /for \(const \[cx, cz, cs\] of CRATES\) \{\n\s+addCollider/.test(блок),
      'у ящиков нет коллайдеров: игрок проходит сквозь груз',
    );
    must(/CylinderGeometry/.test(блок), 'нет бочки: силуэт двора однообразный');
    must(
      /addCollider\(CUSTOMS\.x \+ barrel\.position\.x/.test(блок),
      'у бочки нет коллайдера',
    );
  });
});
