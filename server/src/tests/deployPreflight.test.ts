// Сторож перед выкаткой. Проверяем, что он вообще работает, и —
// главное — что он НЕ пропустит ровно те ситуации, которые 27 сентября
// стоили получаса и лежавшего сайта.
//
// Почему на это тратятся тесты. Скрипт на bash нельзя проверить,
// запустив его в тестах, — его проверяют на сервере. Значит единственная
// защита от того, что он молча перестанет ловить ошибки, — тест на
// нём самом. Случай из сегодняшнего дня как раз такой: тест требовал
// имени несуществующей таблицы, проходил, и баг жил месяцами.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const repoRoot = join(__dirname, '..', '..', '..');
const guard = readFileSync(join(repoRoot, 'tools/deploy-preflight.sh'), 'utf-8');

describe('Сторож выкатки: проверяет до пересборки, а не после', () => {
  it('ничего не меняет — только смотрит', () => {
    // Скрипт, который «попутно чинит», способен испортить то, что
    // проверяет. Единственное изменение в нём — mkdir при создании
    // папки, и то выполняется до проверок, к данным игры отношения
    // не имеет
    expect(guard).not.toMatch(/^\s*rm\s/m);
    expect(guard).not.toMatch(/^\s*mv\s/m);
    expect(guard).not.toMatch(/^\s*docker\s+(rm|rmi|stop|kill|down)\b/m);
  });

  it('проверяет файл секретов и останавливает выкатку без него', () => {
    // ГЛАВНЫЙ СЛУЧАЙ: файл исчез, пересборка его не нашла, сервер
    // не поднялся, сайт лежал
    expect(guard).toMatch(/ENV_FILE="deploy\/\.env"/);
    expect(guard).toMatch(/\[ -f "\$ENV_FILE" \]/);
    expect(guard).toMatch(/НЕТ ФАЙЛА/);
  });

  it('восстанавливать секреты из контейнера умеет', () => {
    // В тексте ошибки должна быть готовая команда. Пользователь в этот
    // момент не в состоянии искать её по чату
    expect(guard).toMatch(/docker inspect/);
    expect(guard).toMatch(/X-Filename|JWT_SECRET/);
  });

  it('проверяет не пустоту, а наличие переменной', () => {
    // Тонкость, из-за которой проверка врёт: пустое значение — это
    // «вход через провайдера выключен», и оно законно. Ошибка — когда
    // переменной НЕТ вовсе, и тогда вход отключается молча
    expect(guard).not.toMatch(/if \[ -z "\$\(\$\(grep/);
    expect(guard).toMatch(/grep -q "\^\$\{key\}="/);
  });

  it('обязательные и необязательные переменные разделены', () => {
    expect(guard).toMatch(/REQUIRED="POSTGRES_PASSWORD JWT_SECRET CLIENT_ORIGIN DOMAIN DB_NAME DB_USER"/);
    expect(guard).toMatch(/OPTIONAL="GOOGLE_CLIENT_ID/);
  });

  it('пустой секрет провайдера — предупреждение, не ошибка', () => {
    expect(guard).toMatch(/вход через этого провайдера выключен/);
  });

  it('проверяет права на файл секретов', () => {
    // Пароль от базы не должен быть доступен никому, кроме владельца
    expect(guard).toMatch(/stat -c '%a'/);
    expect(guard).toMatch(/chmod 600/);
  });
});

describe('Сторож выкатки: ловит неверный git', () => {
  it('сверяет, куда наведён git, с папкой игры', () => {
    // РОВНО ТА ОШИБКА, ЧТО СТОИЛА ВСЕГО ДНЯ. git смотрел в корень
    // сервера, а не в папку игры; из-за этого сброс выписал копию
    // проекта не туда, а команда pull тянула бы не то
    expect(guard).toMatch(/git rev-parse --show-toplevel/);
    expect(guard).toMatch(/--show-toplevel -ne|\[ "\$top" = "\$here" \]/);
  });

  it('сравнивает канонизированные пути, а не строки', () => {
    // Оболочка и git одно и то же место показывают по-разному: с
    // симлинками, с двойным слэшем, с разными регистрами букв
    expect(guard).toMatch(/pwd -P/);
  });

  it('при неверном git прямо запрещает команды сброса', () => {
    // Формулировка запрета в тексте ошибки: человек должен понять,
    // что делать нельзя, ещё до того, как нажмёт
    expect(guard).toMatch(/НЕЛЬЗЯ выполнять/);
    expect(guard).toMatch(/git pull и git reset/);
  });

  it('молчит, если git в проекте нет', () => {
    // На сервере git может быть не установлен — это не повод
    // останавливать выкатку
    expect(guard).toMatch(/command -v git/);
  });
});

describe('Сторож выкатки: ведёт себя как сторож', () => {
  it('останавливает с ненулевым кодом', () => {
    // Иначе вызывающий скрипт продолжит работу, даже если сработала
    // ошибка, — и пересборка всё-таки запустится
    expect(guard).toMatch(/exit 1/);
  });

  it('при отсутствии проблем разрешает выкатку', () => {
    expect(guard).toMatch(/Можно выкатывать/);
    expect(guard).toMatch(/exit 0/);
  });

  it('печатает найденное, а не только проблемы', () => {
    // Полезно видеть, что именно проверено: иначе «пусто» выглядит
    // как «не сработало»
    expect(guard).toMatch(/Проверено:/);
    expect(guard).toMatch(/notes\+=/);
  });

  it('сам находит корень проекта, а не доверяет приглашению оболочки', () => {
    // Ровно на этом сегодня всё и поехало: рабочая папка консоли
    // неожиданно сменилась на /root, и относительные пути указывали
    // не туда
    expect(guard).toMatch(/BASH_SOURCE/);
    expect(guard).toMatch(/SCRIPT_DIR/);
  });

  it('говорит, что перезапуска не было, если остановился', () => {
    // Человек должен понимать: сайт лежит не из-за его действий
    expect(guard).toMatch(/Пересборка не запускалась/);
  });
});

describe('Порядок выкатки на сервере описан', () => {
  it('в инструкции есть шаг со сторожем', () => {
    // Иначе скрипт будет лежать в репозитории и никем не вызван
    const start = readFileSync(join(repoRoot, 'deploy/README.md'), 'utf-8');
    expect(start).toMatch(/deploy-preflight/);
  });
});
