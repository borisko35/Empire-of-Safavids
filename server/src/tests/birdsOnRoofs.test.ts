// Птицы садятся на крыши.
//
// ЧТО БЫЛО (22 октября 2026, §279). Стая облетала игрока всегда на одной
// высоте: в небе ровно одна высота, и с высоты птица — точка. Город читался
// пустым сверху.
//
// ЧТО ТЕПЕРЬ. Над городом стая опускается до уровня крыш и сидит там, пока
// не отлетит. Над озером она садится на воду (§273) — так у стаи два места
// отдыха.
//
// ЧТО ПРОВЕРЯЕТСЯ. Над городом высота цели — уровень крыш, а не высота полёта;
// и это второй случай посадки наравне с водой.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ПТИЦЫ = читать('client/src/app/game3d/birds.ts');

describe('Птицы садятся на крыши', () => {
  it('над городом стая опускается до уровня крыш', () => {
    должен(/const ВЫСОТА_КРОВ = 9;/.test(ПТИЦЫ), 'нет уровня крыш');
    // Над городом — крыши, и только над городом.
    должен(
      /const надГородом = Math\.hypot\(центрX - CITY\.x, центрZ - CITY\.z\) < 95;/.test(ПТИЦЫ),
      'стая не проверяет, над городом ли она',
    );
    // Цель — крыши, а не полёт.
    должен(
      /const цельY = уОзера \? LAKE\.level \+ 0\.22 : надГородом \? ВЫСОТА_КРОВ : ВЫСОТА;/.test(ПТИЦЫ),
      'над городом стая не садится на крыши',
    );
    // Город — из общих данных.
    должен(/import \{ LAKE, CITY \} from '\.\/terrain'/.test(ПТИЦЫ), 'стая не знает, где город');
  });
});
