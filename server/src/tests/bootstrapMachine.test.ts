// Подготовка новой машины: tools/bootstrap-machine.sh.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ ПРОВЕРОК, А НЕ ДЕСЯТОЕ ПРАВИЛО В deployScript.
// Переезд на Oracle упирался в мелочи, каждая из которых стоила времени:
//   * порт, открытый в панели Oracle, закрыт в iptables — и Caddy не получил
//     сертификат;
//   * пустой deploy/.env поднимает сервер с выключенным входом, и это замечают
//     только игроки;
//   * iptables у Oracle режет всё, что не разрешено явно, и «открыл порт в
//     панели» ничего не значит.
//
// Скрипт решает это заранее: идём через туннель Cloudflare, порты не открываем,
// iptables не трогаем. Ниже закреплено именно это решение — чтобы следующий
// переезд не начинался с той же ошибки.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СКРИПТ = читать('tools/bootstrap-machine.sh');

/** Только исполняемые строки: комментарии и пустые убираются. */
function безКомментариев(код: string): string {
  return код
    .split('\n')
    .filter((строка) => !/^\s*#/.test(строка))
    .filter((строка) => строка.trim() !== '')
    .join('\n');
}

function естьBash(): boolean {
  for (const путь of ['C:/Program Files/Git/bin/bash.exe', '/bin/bash', '/usr/bin/bash']) {
    try {
      execFileSync(путь, ['-n', '-c', 'true'], { stdio: 'pipe' });
      return true;
    } catch {
      // пробуем следующий
    }
  }
  return false;
}

describe('Подготовка машины: скрипт', () => {
  it('файл на месте и разбирается bash -n', () => {
    must(СКРИПТ.length > 3000, `tools/bootstrap-machine.sh подозрительно короткий: ${СКРИПТ.length} байт`);
    must(/^#!\/usr\/bin\/env bash/m.test(СКРИПТ), 'нет shebang с bash');
    if (!естьBash()) {
      console.log('bash не найден — синтаксис не проверен');
      return;
    }
    try {
      execFileSync('C:/Program Files/Git/bin/bash.exe', ['-n', join(корень, 'tools/bootstrap-machine.sh')], {
        stdio: 'pipe',
      });
    } catch {
      try {
        execFileSync('bash', ['-n', join(корень, 'tools/bootstrap-machine.sh')], { stdio: 'pipe' });
      } catch (ошибка) {
        must(false, `скрипт не разбирается bash: ${(ошибка as Error).message}`);
      }
    }
  });

  it('отказывается работать не на Linux и ничего не трогает до этого', () => {
    // Проверка uname идёт ПЕРВОЙ фазой, до установки Docker и до клонирования.
    // Порядок важен: скрипт, который сначала ставит Docker, а потом
    // обнаруживает, что он не на Linux, уже оставил на машине следы.
    const строки = безКомментариев(СКРИПТ);
    const uname = строки.indexOf('uname -s');
    const установка = строки.indexOf('get.docker.com');
    const клон = строки.indexOf('git clone');
    must(uname > 0, 'скрипт не проверяет, что это Linux');
    must(установка > uname, 'Docker ставится ДО проверки системы: следы останутся');
    must(клон > uname, 'репозиторий клонируется ДО проверки системы');
    must(
      /if \[ "\$\(uname -s\)" != "Linux" \]/.test(строки),
      'нет явной остановки на не-Linux',
    );
  });
});

describe('Подготовка машины: ресурсы машины', () => {
  // На t3.micro 911 МБ памяти, доступно 538 МБ. Сборка клиента (`npm ci` и
  // Vite) столько не съедает спокойно, а cloudflared по QUIC отдельно
  // жалуется на размер UDP-буфера. Обе правки 10 октября 2026 были сделаны
  // РУКАМИ, вне скрипта, — то есть следующая машина упёрлась бы в то же самое.

  it('память меряется, а не предполагается', () => {
    const строки = безКомментариев(СКРИПТ);
    must(
      /MemTotal/.test(строки),
      'объём памяти не меряется: решение про своп принимается на глаз',
    );
  });

  it('своп создаётся на машине с малой памятью', () => {
    const строки = безКомментариев(СКРИПТ);
    must(
      /swapon/.test(строки) && /fallocate|dd if=\/dev\/zero/.test(строки),
      'своп не создаётся: на 911 МБ сборка клиента упирается в память и падает',
    );
  });

  it('наличие свопа проверяется по подключённому, а не по файлу', () => {
    // Файл свопа переживает остановку машины. Проверка по файлу объявила бы
    // готовность там, где своп не подключён, и переезд упал бы по той же
    // памяти, ради которой своп и поднимали.
    const строки = безКомментариев(СКРИПТ);
    must(
      /swapon --show/.test(строки),
      'подключённый своп не проверяется: наличие файла не значит подключения',
    );
  });

  it('файл свопа переживает перезагрузку', () => {
    const строки = безКомментариев(СКРИПТ);
    must(
      /\/etc\/fstab/.test(строки),
      'своп не вписан в /etc/fstab: после перезагрузки машины его не будет, ' +
        'и переезд следующего раза снова упрётся в память',
    );
  });

  it('UDP-буфер поднимается до значения, которого просит cloudflared', () => {
    // cloudflared печатает на старте про 212992 против желаемых 7340032 и сам
    // называет причину: UDP-буфер ядра по умолчанию мал. Правится и rmem_max,
    // и wmem_max.
    const строки = безКомментариев(СКРИПТ);
    must(
      /net\.core\.rmem_max/.test(строки) && /net\.core\.wmem_max/.test(строки),
      'размер UDP-буфера не поднимается: cloudflared по QUIC рвёт соединения, ' +
        'а сайт снаружи становится нестабильным без всякой видимой причины',
    );
  });

  it('правка буфера кладётся в sysctl.d, а не в sysctl.conf', () => {
    // /etc/sysctl.conf переписывают установщики пакетов, и правка молча
    // исчезает при обновлении. Каталог /etc/sysctl.d/ для этого и существует.
    const строки = безКомментариев(СКРИПТ);
    must(
      /\/etc\/sysctl\.d\//.test(строки),
      'правка буфера попадает в /etc/sysctl.conf: её затрёт установка пакетов, ' +
        'и после обновления туннель снова начнёт рваться',
    );
  });

  it('ресурсы настраиваются ДО установки Docker и до выкатки', () => {
    const строки = безКомментариев(СКРИПТ);
    const память = строки.indexOf('MemTotal');
    const установка = строки.indexOf('get.docker.com');
    const выкатка = строки.indexOf('bash tools/deploy.sh');
    must(память > 0, 'память не меряется');
    must(
      память < установка,
      'ресурсы настраиваются ПОСЛЕ установки Docker: своп нужен уже на сборке, ' +
        'а не когда стек половина поднята',
    );
    must(
      память < выкатка,
      'ресурсы настраиваются ПОСЛЕ выкатки: переезд упадёт по памяти раньше, ' +
        'чем дойдёт до их настройки',
    );
  });
});

describe('Подготовка машины: группа docker', () => {
  // ВСЁ ЭТО — ПРО БАГ ПЕРЕЕЗДА НА AWS 10 ОКТЯБРЯ 2026. Docker поставился,
  // скрипт отрапортовал «OK» и пошёл выкатывать, где compose сказал
  //   permission denied ... at unix:///var/run/docker.sock
  // Пользователь не был в группе `docker`. На новой машине это воспроизводится
  // всегда: установщик добавляет в группу, но права группы действуют только в
  // новой сессии, а переезд запускают по уже открытой.

  it('работоспособность проверяется docker info, а не --version', () => {
    // `docker --version` читает файл и отвечает всегда, даже когда сокет
    // недоступен. Именно поэтому скрипт рапортовал «OK» при мёртвом docker.
    const строки = безКомментариев(СКРИПТ);
    must(
      /docker info >\/dev\/null 2>&1/.test(строки),
      'работоспособность docker не проверяется через docker info: ' +
        '`--version` читает файл и отвечает даже при недоступном сокете',
    );
  });

  it('пользователь добавляется в группу docker', () => {
    const строки = безКомментариев(СКРИПТ);
    must(
      /usermod -aG docker/.test(строки),
      'пользователь не добавляется в группу docker: переезд упирается в ' +
        'permission denied и падает на выкатке',
    );
  });

  it('группа применяется перезапуском скрипта, а не только usermod', () => {
    // КЛЮЧЕВОЕ. Одного `usermod` мало: права группы действуют только в новой
    // сессии. Без перезапуска скрипт продолжил бы работу с теми же правами и
    // упал бы там же. `sg` применяет новую группу к текущей сессии.
    must(
      /exec sg docker -c/.test(СКРИПТ),
      'новые права группы не применяются к текущей сессии: usermod без ' +
        'перезахода бесполезен, и переезд снова упадёт на том же месте',
    );
  });

  it('перезапуск защищён от бесконечного цикла', () => {
    // Без предохранителя скрипт, которому так и не дали группу, перезапускал бы
    // себя снова и снова — и переезд никогда не кончился бы.
    //
    // ПЕРВАЯ ВЕРСИЯ ПРОВЕРКИ БЫЛА СЛАБОЙ, И ЛОМКА ЭТО ПОКАЗАЛА. Она требовала
    // лишь упоминания EOS_DOCKER_REEXEC, а это имя стоит и в проверке, и в
    // `export`. Ломка удаляла блок `if ...; then ... fi` — имя оставалось в
    // export, проверка проходила, и защита была бы сломана. Теперь требуется
    // САМО УСЛОВИЕ, а не имя переменной.
    must(
      /if \[ "\$\{EOS_DOCKER_REEXEC:-\}" = "1" \]; then/.test(СКРИПТ),
      'нет самого предохранителя: проверка требовала только упоминания имени ' +
        'переменной, а удаление блока if оставлял export — защита выглядела бы ' +
        'работающей при сломанном цикле',
    );
    const строки = безКомментариев(СКРИПТ);
    must(
      строки.indexOf('if [ "${EOS_DOCKER_REEXEC:-}" = "1" ]; then') <
        строки.indexOf('exec sg docker'),
      'предохранитель проверяется ПОСЛЕ перезапуска: цикл не прервётся',
    );
  });

  it('группа проверяется ДО выкатки, а не после', () => {
    // Порядок и есть суть бага: проверки не было вовсе, и первое, где это
    // обнаружилось, — сборка образов.
    const строки = безКомментариев(СКРИПТ);
    const проверка = строки.indexOf('docker info >/dev/null 2>&1');
    const выкатка = строки.indexOf('bash tools/deploy.sh');
    must(проверка > 0, 'работоспособность docker не проверяется');
    must(
      проверка < выкатка,
      'группа docker проверяется ПОСЛЕ выкатки: первым об этом узнаёт сборка ' +
        'образов, и переезд падает на середине',
    );
  });

  it('успех честно подтверждается пользователем, для которого проверено', () => {
    // Раньше строка «OK: docker --version» говорила, что docker есть. Теперь
    // сказать «OK» можно только после docker info — то есть про того
    // пользователя, который дальше будет запускать выкатку.
    must(
      /docker works for the current user/.test(СКРИПТ),
      'успех не подтверждается тем, что docker работает для текущего пользователя',
    );
  });
});

describe('Подготовка машины: путь через туннель', () => {
  it('порты не открываются и iptables не трогается', () => {
    // ЭТО И СУТЬ РЕШЕНИЕ. На Oracle образы держат правила REJECT для всего, что
    // не разрешено явно, и открытие порта в панели не снимает их. Скрипт идёт
    // через туннель, и тогда править систему не нужно вовсе.
    //
    // ПРОВЕРЯЮТСЯ ТОЛЬКО ИСПОЛНЯЕМЫЕ СТРОКИ. Первая версия искала `iptables -I
    // INPUT` по всему файлу и сразу упала: эти строки есть, но они внутри
    // `say "..."` — скрипт ПЕЧАТАЕТ команды как совет на случай, если токена
    // туннеля нет. То есть проверка ловила саму себя, ровно как это уже было с
    // комментарием в deployScript.
    //
    // Поэтому шаблон требует, чтобы строка начиналась с самой команды:
    // `iptables` или `sudo iptables`. Строка, начинающаяся с `say`, под него не
    // попадает, и совет остаётся советом.
    const строки = безКомментариев(СКРИПТ);
    const код = строки
      .split('\n')
      .map((строка) => строка.trim())
      .filter((строка) => !/^(say|printf|echo|cat)\b/.test(строка))
      .join('\n');
    must(
      !/^(sudo\s+)?iptables\s/m.test(код),
      'скрипт исполняет iptables: решение «идти через туннель» при этом ' +
        'отменяется, а вместе с ним — и отсутствие возни с REJECT',
    );
    must(
      !/^(sudo\s+)?(ufw|firewall-cmd)\s/m.test(код),
      'скрипт трогает брандмауэр: машина настраивается не нами',
    );
  });

  it('DNS не меняется: адрес уже указывает на туннель', () => {
    const строки = безКомментариев(СКРИПТ);
    must(
      !/\bns\b|\bnameserver\b|cloudflare.*dns.*(edit|update)|dig\s/.test(строки),
      'скрипт лезет в DNS: туннель тот же, менять нечего, а лишняя правка ' +
        'может уронить сайт',
    );
  });

  it('туннель подключается по токену, а не флажком', () => {
    must(
      /CLOUDFLARE_TUNNEL_TOKEN=\.\.\*/.test(СКРИПТ),
      'наличие токена не проверяется: без него compose не стартует и сообщение ' +
        'об этом нечитаемо',
    );
    // И профиль подключается сам — ровно как в deploy.sh.
    must(
      /docker-compose\.tunnel\.yml/.test(СКРИПТ),
      'профиль туннеля не подключается: Caddy займёт 80 и 443, и понадобится ' +
        'сертификат и открытые порты',
    );
  });
});

describe('Подготовка машины: секреты', () => {
  it('пустой deploy/.env не создаётся', () => {
    // Молчаливый пустой файл поднимает сервер с выключенным входом. Это
    // замечают только игроки, и замечают поздно.
    const строки = безКомментариев(СКРИПТ);
    must(
      !/touch\s+\$?\{?ENV_FILE/.test(строки),
      'скрипт создаёт файл секретов: пустой файл поднимает сервер без входа',
    );
    must(
      !/>\s*"?\$?\{?ENV_FILE"?\s*$/.test(строки.replace(/^\s*\|/, '')),
      'файл секретов перезаписывается безусловно: это снесло бы рабочий вход',
    );
    must(/if \[ ! -f "\$ENV_FILE" \]/.test(строки), 'отсутствие файла секретов не проверяется');
    must(
      /die "\$ENV_FILE not found/.test(строки),
      'при отсутствии файла секретов скрипт не останавливается',
    );
  });

  it('права 600 выставляются: на Linux это работает', () => {
    // В deploy-preflight.sh для Windows chmod объявлен бесполезным — и там это
    // верно. Здесь машина Linux, и права нужны по-настоящему.
    must(
      /chmod 600 "\$ENV_FILE"/.test(СКРИПТ),
      'права на файл секретов не выставляются: он доступен всем на машине',
    );
  });
});

describe('Подготовка машины: идемпотентность', () => {
  it('каждая фаза сначала проверяет, не сделано ли уже', () => {
    // Повторный запуск на машине, где всё есть, не должен ничего ломать.
    // Иначе переезд приходится начинать заново после любой ошибки.
    const строки = безКомментариев(СКРИПТ);
    must(
      /command -v docker/.test(строки) && /already here/.test(строки),
      'Docker не проверяется на наличие: повторный запуск переустанавливал бы его',
    );
    must(
      /\[ -d "\$PROJECT_DIR\/\.git" \]/.test(строки),
      'наличие клона не проверяется: повторный запуск упал бы на занятую папку',
    );
  });

  it('в конце зовётся та же выкатка, что и на этой машине', () => {
    // Отдельная логика развёртывания на новой машине — это второй путь, и он
    // разойдётся с первым. Скрипт обязан звать tools/deploy.sh.
    must(
      /bash tools\/deploy\.sh/.test(СКРИПТ),
      'скрипт не зовёт tools/deploy.sh: появится вторая логика выкатки',
    );
    must(
      /idempotent/.test(СКРИПТ),
      'в скрипте не сказано, что он повторный: об этом должен помнить тот, ' +
        'кто будет запускать его второй раз',
    );
  });

  it('после выкатки проверяется не только exit-код', () => {
    // Ответ /health ничего не говорит о том, какой код запущен: старый
    // контейнер отвечает так же. Скрипт обязан перечислить контейнеры.
    const строки = безКомментариев(СКРИПТ);
    must(
      /docker ps/.test(строки),
      'состояние контейнеров не проверяется',
    );
    must(
      /localhost:3000\/health/.test(строки),
      '/health не опрашивается после выкатки',
    );
    // И состав файлов compose собирается в переменную: пустой `-f ""` — ошибка
    // разбора, и проверка молча падала бы при живом сервере.
    must(
      /COMPOSE_ARGS=\(/.test(строки),
      'файлы compose подставляются на месте: пустой -f ломает разбор',
    );
  });
});