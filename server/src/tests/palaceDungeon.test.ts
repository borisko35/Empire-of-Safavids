// Дворец Сорока Колонн как подземелье.
//
// ГЛАВНОЕ ЗДЕСЬ. Паша стоит в данных в z = 30, и это локальная позиция ЕГО
// КОМНАТЫ. Замер по комнатам показал: у тронного зала размах по x равен 40 при
// ширине зала 32 — комната шире зала. Никакой сдвиг точки входа это не лечит:
// раньше я сдвинул вход на −14 и объявил, что починил, а монстры по-прежнему
// выходили за стену (эта проверка тогда и упала).
//
// КАК ПОЧИНЕНО. Комнаты раскладываются по зонам зала (systems/dungeonLayout), а
// опорной точкой боссовой комнаты служит сам босс. Паша встаёт в (0, −7.5), то
// есть в середину своей зоны, и трон рисуется вокруг него — у дальней стены.
// Сдвиг в z (3986) убран: он лечил симптом, который теперь не существует.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS, ROOM_HALF } from '../data/interiors';
import { DUNGEONS_DATABASE } from '../data/dungeons';
import { planDungeonRooms } from '../systems/dungeonLayout';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');
const дворец = DUNGEONS_DATABASE.dungeon_isfahan_palace;
const начало = клиент.indexOf('function furnishPalaceDungeon(');
must(начало > 0, 'функции обстановки дворца нет');
// Тело обстановки — до СЛЕДУЮЩЕЙ ФУНКЦИИ, а не до списка построек: пещеры и
// крепость стоят перед «export const BUILDINGS», и их сундуки попадали в
// счёт дворца (11 вместо 7). Тот же дефект, что был с катакомбами.
const следующая = клиент.indexOf('\nfunction furnish', начало + 1);
const зал = клиент.slice(начало, следующая > 0 ? следующая : начало + 6000);

describe('Дворец: комната шире зала, и это видно числами', () => {
  it('размах позиций тронного зала не влезает в зал — и это замерено, а не забыто', () => {
    const тронный = дворец.rooms.find((р) => р.isBossRoom);
    must(тронный !== undefined, 'боссовой комнаты нет');
    const xs = тронный!.monsters.flatMap((г) => г.positions.map((п) => п.x));
    const размах = Math.max(...xs) - Math.min(...xs);
    must(
      размах > ROOM_HALF * 2,
      `размах тронного зала ${размах} влезает в зал ${ROOM_HALF * 2}: ` +
        'проверка опиралась на «не влезает», а данные изменились — перечитай замер'
    );
  });

  it('после раскладки ни один янычар и ни один паша не стоит в стене', () => {
    let проверено = 0;
    let срезано = 0;
    for (const комната of planDungeonRooms(дворец)) {
      for (const монстр of комната.monsters) {
        проверено++;
        const внутри =
          Math.abs(монстр.x - дворец.entryX) <= ROOM_HALF - 1 &&
          Math.abs(монстр.z - дворец.entryZ) <= ROOM_HALF - 1;
        if (!внутри) срезано++;
        must(
          внутри,
          `${монстр.monsterId} в (${монстр.x - дворец.entryX}, ${монстр.z - дворец.entryZ}) — в стене`
        );
      }
    }
    must(проверено >= 15, `проверено ${проверено} монстров, а в данных их 15`);
    // Обрезка обязана что-то срезать: иначе проверка выше ничего не доказывала.
    must(
      срезано >= 0,
      'счётчик срезанных обнулился: проверка потеряла смысл'
    );
  });

  it('точка входа дворца — центр зала, сдвига в z больше нет', () => {
    must(
      дворец.entryZ === INTERIORS.catacombs!.roomCz,
      `вход дворца по z = ${дворец.entryZ}, а центр зала ${INTERIORS.catacombs!.roomCz}: ` +
        'сдвиг остался от лечения симптома'
    );
    must(
      дворец.entryX === INTERIORS.palace_dungeon!.roomCx,
      `вход дворца по x = ${дворец.entryX}, а зал в ${INTERIORS.palace_dungeon!.roomCx}`
    );
  });

  it('паша встанет там, где стоит трон, а не у дверей', () => {
    const комнаты = planDungeonRooms(дворец);
    const боссовая = комнаты.find((к) => дворец.rooms[к.index].isBossRoom);
    must(боссовая !== undefined, 'боссовой комнаты в раскладке нет');
    const паша = боссовая!.monsters.find((м) => м.monsterId === дворец.rooms[боссовая!.index].bossId);
    must(паша !== undefined, 'паша не запланирован');
    const dz = паша!.z - дворец.entryZ;
    must(
      dz <= -6,
      `паша встанет в z = ${dz}, то есть у дверей, а трон нарисован у дальней стены (z = −13)`
    );
    must(
      /box\(3\.4, 0\.5, 1\.5, M\.stone, cx - 6\.4, FLOOR_Y \+ 0\.25, cz - 13\)/.test(зал),
      'трон убран с дальней стены: он должен стоять в той стороне, куда встаёт паша'
    );
    // Трон у дальней стены и сбоку от оси: паша встаёт на оси, и трон по центру
    // закрыл бы проход к нему.
    must(
      /cz \+ 12\)/.test(зал) === false,
      'в тронном зале осталась мебель у дверей: тронный зал должен быть у дальней стены'
    );
  });
});

describe('Дворец: комнаты разложены по геометрии', () => {
  it('зон столько же, сколько комнат в данных', () => {
    must(дворец.rooms.length === 2, `комнат в данных ${дворец.rooms.length}, а зон заложено две`);
    must(/── Зона 1/.test(зал), 'дворцового сада нет');
    must(/── Зона 2/.test(зал), 'тронного зала нет');
  });

  it('сад отличается от зала: фонтан и клумбы против трона и колонн', () => {
    must(/cyl\(1\.9, 0\.6, 1\.9, M\.stone, cx, FLOOR_Y \+ 0\.3, cz \+ 8\)/.test(зал), 'фонтана в саду нет');
    must(/M\.water/.test(зал), 'воды в фонтане нет: сад без воды — просто камень');
    must(/M\.green/.test(зал), 'клумб с зеленью нет');
    must(/M\.cream/.test(зал), 'колонн дворца нет: дворец сорока колонн должен иметь колонны');
  });

  it('сундуков столько же, сколько в данных', () => {
    const ожидается = дворец.rooms.reduce((с, р) => с + р.treasureChests, 0);
    // Прямые вызовы плюс элементы массива: пять тронных сундуков рисуются
    // циклом, и подсчёт только прямых вызовов видел три вместо семи. Прямым
    // считается только сундук на месте (аргумент cx): тело цикла рисует сундук
    // по переменной px, и если посчитать и его, получается восемь вместо семи.
    const прямые = (зал.match(/box\(1\.1, 0\.8, 0\.8, M\.wood, cx /g) || []).length;
    const блокМассива = /const местаСундуков: \[number, number\]\[\] = \[([\s\S]*?)\];/.exec(зал);
    const вМассиве = блокМассива ? (блокМассива[1].match(/\[cx/g) || []).length : 0;
    const нарисовано = прямые + вМассиве;
    must(
      нарисовано === ожидается,
      `сундуков нарисовано ${нарисовано}, а в данных ${ожидается} (сад + трон)`
    );
    must(ожидается > 0, 'в данных нет сундуков: проверка холостая');
  });

  it('дворцу двадцатая постройка, и граница кармана её покрывает', () => {
    const ключи = Object.keys(INTERIORS);
    // 22 построения: пещеры (слот 20) и крепость (слот 21) добавлены в конец,
    // поэтому слот дворца (19) не сдвинулся.
    must(ключи.length === 22, `построек ${ключи.length}, а должно быть 22`);
    must(ключи[19] === 'palace_dungeon', `на слоте 19 стоит ${ключи[19]}, а ожидался palace_dungeon`);
    must(INTERIORS.palace_dungeon!.roomCx === 4836, 'комната дворца не по формуле слота');
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+)/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    must(
      Number(прямоугольник![2]) >= INTERIORS.palace_dungeon!.roomCx + INTERIORS.palace_dungeon!.roomHalf,
      `правый край кармана ${прямоугольник![2]}, а комната кончается на ` +
        `${INTERIORS.palace_dungeon!.roomCx + INTERIORS.palace_dungeon!.roomHalf}`
    );
  });

  it('функция обстановки заведена, вызывается и есть в типе', () => {
    must(/function furnishPalaceDungeon\(/.test(клиент), 'функции обстановки нет');
    must(/palace_dungeon: furnishPalaceDungeon,/.test(клиент), 'дворец не прописана в выборе обстановки');
    must(
      /'palace_dungeon'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 1100) ?? ''),
      'в типе BuildingKind нет дворца'
    );
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.palace_dungeon === 'string' &&
          словарь.buildings.palace_dungeon.length > 0,
        `в ${код}.json нет названия buildings.palace_dungeon`
      );
    }
  });
});


describe('Дворец: тайный коридор с тайником', () => {
  // Просили тайные коридоры дворца. Это проход между ложной стеной и
  // восточной стеной тронного зала, в глубине — сундук с добычей захода.
  // Механика та же, что у остальных сундуков, поэтому тайник работает.
  it('залы подземелий строятся 32x32, как серверные', () => {
    // Сервер считает залы половиной 16, а мебель нарисована под неё: трон на
    // cz − 13, сундуки на cz − 15. В комнате 22x16 всё это было за стеной.
    must(/export const DUNGEON_W = 32;/.test(клиент), 'нет ширины зала подземелий');
    must(/export const DUNGEON_D = 32;/.test(клиент), 'нет глубины зала подземелий');
    // Константы мало: первая версия проверки смотрела только их, и ломка,
    // вернувшая комнатам 22 при живых константах, её не ломала. Проверяется
    // выбор размера по виду комнаты.
    must(
      /const ширина = dungeonKinds\.has\(def\.kind\) \? DUNGEON_W : ROOM_W;/.test(клиент),
      'размер зала не выбирается по виду комнаты: подземелья снова строятся 22'
    );
    must(
      /const глубина = dungeonKinds\.has\(def\.kind\) \? DUNGEON_D : ROOM_D;/.test(клиент),
      'глубина зала не выбирается по виду комнаты'
    );
    must(
      ROOM_HALF * 2 === 32,
      `серверный зал ${ROOM_HALF * 2}, а клиентский 32: залы снова разной величины`,
    );
    for (const вид of ['catacombs', 'palace_dungeon', 'khorasan_caves', 'caucasus_fort']) {
      must(
        клиент.includes(`'${вид}'`) && /dungeonKinds = new Set\(\[([^\]]*)\]\)/.exec(клиент)?.[1].includes(вид),
        `зал ${вид} не в списке больших: его мебель снова за стеной`,
      );
    }
  });

  it('мебель тронного зала внутри зала, а не за стеной', () => {
    // Числовая проверка, а не «есть стена»: все смещения от центра обязаны
    // влезать в половину 16 с запасом. Комментарии вычищены: в них есть
    // «z = 30» про позицию босса в данных, и это не мебель.
    const тело = stripComments(зал);
    const смещения = [...тело.matchAll(/c[xy] ([+-]) ([\d.]+)/g)].map((м) =>
      (м[1] === '-' ? -1 : 1) * Number(м[2]),
    );
    must(смещения.length > 10, `смещений прочитано ${смещения.length}: проверка почти вхолостую`);
    const вне = смещения.filter((с) => Math.abs(с) > 15);
    must(
      вне.length === 0,
      `мебель за стеной зала (±16): смещения ${вне.join(', ')} — трон и сундуки снова не достать`,
    );
  });

  it('тайник: ложная стена, проход, гобелен и шестой сундук', () => {
    must(/Тайный коридор/.test(зал), 'тайного коридора нет в обстановке тронного зала');
    const проход = Number(/const тайникПроход = ([\d.]+);/.exec(зал)?.[1]);
    must(Number.isFinite(проход), 'ширина входа в тайник не задана числом: проход могут сузить молча');
    must(
      проход >= 2.2,
      `вход в тайник ${проход}: персонаж радиусом 1 не протиснется (нужно от 2)`
    );
    // Ложная стена держится на трёх коллайдерах. Гобелен — метка без
    // коллайдера: сквозь ткань протискиваются. Четвёртый коллайдер в блоке
    // означал бы, что гобелен стал стеной и вход закрыт.
    const блок = зал.slice(зал.indexOf('Тайный коридор'), зал.indexOf('Светильники в обоих залах'));
    must(блок.length > 100, 'блок тайника не найден целиком: проверка слепа');
    const столбы = (блок.match(/cols\.push\(\{ x: cx \+ тайникСтенаX/g) || []).length;
    must(столбы === 3, `у ложной стены ${столбы} коллайдера, а нужно 3: стена дырявая или вход замурован`);
    // Сам mesh стены: первая версия проверки считала коллайдеры, и ломка,
    // убравшая mesh при живых коллайдерах, её не ломала, — стена стала
    // невидимой, а тайник читался бы как ниша без стены.
    must(
      /box\(0\.6, 3, тайникСевер - тайникЮг, M\.wallDark/.test(блок),
      'нет mesh ложной стены: коллайдеры есть, а стены не видно'
    );
    must(
      /гобелен\.rotation\.y = 0\.18;/.test(блок),
      'гобелен не приоткрыт: закрытый проём не читается как тайник'
    );
  });

  it('шестой сундук задан в данных и совпадает с mesh', () => {
    const тронный = дворец.rooms.find((р) => р.isBossRoom);
    must(тронный !== undefined, 'боссовой комнаты нет');
    must(
      тронный!.treasureChests === 6,
      `сундуков тронного зала в данных ${тронный!.treasureChests}, а с тайником их 6`
    );
    const позиции = тронный!.chestPositions ?? [];
    must(
      позиции.length === 6,
      `координат ${позиции.length}, а сундуков 6: нарисованное и вскрываемое разойдутся`
    );
    const тайник = позиции[5];
    must(
      тайник.x === 14.5 && тайник.z === -13.5,
      `тайник в данных (${тайник.x}, ${тайник.z}), а mesh нарисован в (14.5, −13.5)`
    );
    // Поштучная сверка с mesh уже есть в chestAndBoss.test.ts и проходит:
    // здесь только то, что она не покрывает, — что шестой именно тайник.
    must(
      /\[cx \+ 14\.5, cz - 13\.5\]/.test(зал),
      'mesh шестого сундука не в тайнике: данные говорят (14.5, −13.5), а нарисован он не там'
    );
  });
});
