// Двор мечети: экстерьер первого из шести зданий без экстерьера.
//
// ЧТО ЗАКРЕПЛЯЕТ. Владелец велел «заполним здание экстерьером». Мечеть — первое
// из шести, и почти всё в ней неочевидно:
//
//   1. Это НЕ глухое здание, а вокруг двора. В Assets лежит stone-mosque, но
//      модель — стена по периметру с минаретом на одном конце и куполом на
//      другом. Проверка закрепляет форму: если придёт глухая коробка без двора,
//      это будет другой предмет и другое решение владельца.
//   2. Масштаб выведен из ширины ДВОРА, а не из высоты стен. Двор 18 x 7.59 x
//      9.9 м, и по одной только высоте можно ошибиться на треть.
//   3. Основание на ноль: земля под двором ровная до сантиметра, и подъём не
//      нужен.
//   4. Стены выше городской. Иначе купол с минаретом не видно из-за угла, а
//      ради этого здание и строят.
//   5. Ворота смотрят в сторону ВЫХОДА, а не куда попало. Игрок выходит из
//      мечети в (-20,-476), то есть в +z от двери (-20,-480). Поворот на pi
//      ставит найденную по геометрии сторону -Y именно туда.
//   6. Коллайдеры — частями, с ПРОМЕЖУТКОМ под ворота. Один круг радиусом
//      9.8 м не пустил бы игрока к двери: до неё было бы не дойти.
//   7. Проём в воротах не меньше ширины игрока и не шире двора.
//   8. Купол закрыт коллайдером: в него нельзя войти, и он в 5 м от двери.
//   9. Карта на месте: без неё двор серый, а пакет принёс 4096-битную карту.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';
import { блокЭкспортируемой } from './decorText';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');
const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
};

interface GlbJson {
  nodes?: { name?: string; rotation?: number[]; scale?: number[]; translation?: number[] }[];
  meshes?: { primitives?: { attributes: { POSITION: number } }[] }[];
  skins?: unknown[];
  animations?: unknown[];
  accessors?: { min: number[]; max: number[] }[];
  materials?: unknown[];
  textures?: unknown[];
}

const ФАЙЛ = join(корень, 'client/src/app/public/models/decor/mosque.glb');

function jsonGlb(путь: string): GlbJson {
  const буфер = readFileSync(путь);
  must(буфер.readUInt32LE(0) === 0x46546c67, `${путь}: это не GLB`);
  const длина = буфер.readUInt32LE(12);
  return JSON.parse(буфер.subarray(20, 20 + длина).toString('utf-8')) as GlbJson;
}

/** Габарит двора по всем частям: глиб может быть разбит по материалам. */
function габариты(): { ширина: number; высота: number; глубина: number; низ: number } {
  const gltf = jsonGlb(ФАЙЛ);
  const список = (gltf.meshes ?? []).flatMap((меш) =>
    (меш.primitives ?? []).map((примитив) => (gltf.accessors ?? [])[примитив.attributes.POSITION]),
  );
  must(список.length > 0, 'в модели двора нет ни одной части');
  let ширина = 0;
  let глубина = 0;
  let верх = -Infinity;
  let низ = Infinity;
  for (const a of список) {
    ширина = Math.max(ширина, a.max[0] - a.min[0]);
    глубина = Math.max(глубина, a.max[2] - a.min[2]);
    верх = Math.max(верх, a.max[1]);
    низ = Math.min(низ, a.min[1]);
  }
  return { ширина, высота: верх - низ, глубина, низ };
}

function число(константа: string): number {
  const м = new RegExp(`export const ${константа} = ([\\dxa-fA-F0-9.]+)`).exec(ТЕРРЕЙН);
  must(м !== null, `не нашлась константа ${константа}`);
  const текст = м![1];
  return текст.toLowerCase().startsWith('0x') ? parseInt(текст, 16) : Number(текст);
}

/** Дверь и выход мечети читаются из interiors.ts, а не перечислены здесь. */
function дверь(): { dx: number; dz: number; ex: number; ez: number } {
  const строка = /\{ id: 'mosque'[^}]*\}/.exec(ИНТЕРЬЕРЫ);
  must(строка !== null, 'в interiors.ts нет мечети');
  const dx = /dx: (-?\d+)/.exec(строка![0]);
  const dz = /dz: (-?\d+)/.exec(строка![0]);
  const ex = /ex: (-?\d+)/.exec(строка![0]);
  const ez = /ez: (-?\d+)/.exec(строка![0]);
  must(dx && dz && ex && ez, 'не разобрались координаты двери мечети');
  return {
    dx: Number(dx![1]),
    dz: Number(dz![1]),
    ex: Number(ex![1]),
    ez: Number(ez![1]),
  };
}

describe('Мечетный двор: модель', () => {
  it('файл в сборке и совпадает с манифестом', () => {
    const запись = МАНИФЕСТ.decor?.find((д) => д.name === 'mosque');
    must(запись !== undefined, 'в манифесте нет двора мечети');
    must(запись!.file === 'models/decor/mosque.glb', 'путь к двору в манифесте не тот');
    must(existsSync(ФАЙЛ), 'файла двора нет на диске');
    must(
      statSync(ФАЙЛ).size === запись!.bytes,
      `двор: на диске ${statSync(ФАЙЛ).size}, в манифесте ${запись!.bytes}`,
    );
  });

  it('модель в метрах, а не в единичном кубе трипо', () => {
    // Модель пришла нормализованной: 0.99981 в длину. Без применения масштаба
    // игрок получил бы куб со стороной в метр.
    const г = габариты();
    must(
      г.ширина > 10,
      `ширина двора ${г.ширина.toFixed(3)} м: масштаб не применён. ` +
        'Исходник 1.0 в длину, и без применения именно это и приехало бы',
    );
  });

  it('двор, а не глухая коробка: ширина больше высоты', () => {
    // У настоящего двора-сахна ширина втрое больше высоты стен. У глухого
    // здания наоборот, и тогда это был бы другой предмет.
    const г = габариты();
    must(
      г.ширина > г.высота * 1.5,
      `ширина ${г.ширина.toFixed(2)} м, высота ${г.высота.toFixed(2)} м: ` +
        'это не двор, а глухая постройка',
    );
    must(
      г.глубина < г.ширина * 0.6,
      `глубина ${г.глубина.toFixed(2)} м при ширине ${г.ширина.toFixed(2)}: ` +
        'двор должен быть вытянутым, иначе это здание',
    );
  });

  it('стены выше городской: купол видно из-за угла', () => {
    const г = габариты();
    must(
      г.высота > 6 && г.высота < 14,
      `высота стен ${г.высота.toFixed(2)} м: ниже 6 — за городскую стену не ` +
        'выглянет, выше 14 — это уже минарет-башня',
    );
  });

  it('основанием на ноль, а не висячий и не ушедший под землю', () => {
    const г = габариты();
    must(
      Math.abs(г.низ) <= 0.02,
      `низ двора на ${г.низ.toFixed(3)} по Y: уедет под землю или повиснет`,
    );
  });

  it('карта на месте: иначе двор серый', () => {
    const gltf = jsonGlb(ФАЙЛ);
    must(
      (gltf.textures ?? []).length >= 1,
      'в модели двора нет ни одной текстуры: пакет принёс карту 4096, ' +
        'а в игру она не попала',
    );
  });

  it('без скелета и анимации, и без остатков трансформации', () => {
    const gltf = jsonGlb(ФАЙЛ);
    must((gltf.skins ?? []).length === 0, 'в дворе есть скелет');
    must((gltf.animations ?? []).length === 0, 'в дворе анимация');
    for (const узел of gltf.nodes ?? []) {
      // Единичный кватернион — [0, 0, 0, 1], а не [0, 0, 0, 0].
      const поворот = узел.rotation ?? [0, 0, 0, 1];
      must(
        поворот.every((в, i) => Math.abs(в - (i === 3 ? 1 : 0)) < 1e-6),
        `в узле «${узел.name ?? '(без имени)'}» остался поворот ${JSON.stringify(поворот)}`,
      );
      const масштаб = узел.scale ?? [1, 1, 1];
      must(
        масштаб.every((в) => Math.abs(в - 1) < 1e-6),
        `в узле «${узел.name ?? '(без имени)'}» остался масштаб`,
      );
      const сдвиг = узел.translation ?? [0, 0, 0];
      must(
        сдвиг.every((в) => Math.abs(в) < 1e-6),
        `в узле «${узел.name ?? '(без имени)'}» остался сдвиг`,
      );
    }
  });

  it('файл не тяжелее трёх мегабайт', () => {
    // 100876 полигонов сжаты до 20174, карта ужата до 1024. Если приедет
    // полная трипо-геометрия, файл потяжелеет.
    const вес = statSync(ФАЙЛ).size;
    must(
      вес < 3 * 1024 * 1024,
      `двор весит ${(вес / 1048576).toFixed(2)} МБ: полигоны не уменьшены ` +
        'либо карта не ужата',
    );
  });
});

describe('Мечетный двор: у двери', () => {
  it('мир строит двор мечети', () => {
    must(/buildMosqueCourtyard\(this\.scene\)/.test(МИР), 'мир не строит двор мечети');
    must(/import[\s\S]{0,900}buildMosqueCourtyard/.test(МИР), 'функция не импортирована');
    must(
      /export function buildMosqueCourtyard/.test(ТЕРРЕЙН),
      'в terrain.ts нет buildMosqueCourtyard',
    );
  });

  it('двор стоит на двери мечети', () => {
    const д = дверь();
    const центр = /export const MOSQUE_COURTYARD = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН);
    must(центр !== null, 'не нашёлся MOSQUE_COURTYARD');
    must(
      Number(центр![1]) === д.dx && Number(центр![2]) === д.dz,
      `двор стоит в (${центр![1]}, ${центр![2]}), а дверь мечети в ` +
        `(${д.dx}, ${д.dz}): игрок не дойдёт до своих ворот`,
    );
  });

  it('ворота смотрят в сторону выхода', () => {
    // Выход из мечети на 4 единицы в +z от двери. Значит ворота должны быть
    // со стороны +z, иначе игрок выйдет вплотную к стене.
    const д = дверь();
    must(
      д.ez > д.dz,
      `выход мечети (${д.ex}, ${д.ez}) не в сторону +z от двери ` +
        `(${д.dx}, ${д.dz}): расчёт стороны ворот тогда неверен`,
    );
    const поворот = /MOSQUE_COURTYARD = \{[^}]*ry: ([^},]+)/.exec(ТЕРРЕЙН);
    must(поворот !== null, 'не разобрался поворот двора');
    const значение = поворот![1].trim();
    must(
      значение === 'Math.PI',
      `поворот двора «${значение}»: ворота найдены по геометрии на стороне -Y, ` +
        'и поворот на pi ставит их в +z, к выходу',
    );
  });

  it('подъём нулевой: земля под двором ровная', () => {
    const блок = блокЭкспортируемой(ТЕРРЕЙН, 'export function buildMosqueCourtyard');
    must(
      /placeDecor\(scene, 'decor\/mosque\.glb', c\.x, c\.z, 0, c\.ry/.test(блок),
      'двор ставится не на нулевой подъём: скан нашёл ровную площадку ' +
        'с перепадом по четырём углам 0.000, а основание модели уже на нуле',
    );
  });

  it('коллайдеры частями, с проёмом под ворота', () => {
    const блок = блокЭкспортируемой(ТЕРРЕЙН, 'export function buildMosqueCourtyard');
    // ОДИН БОЛЬШОЙ КРУГ НЕЛЬЗЯ: он держал бы игрока в десяти метрах от двери.
    must(
      /addCollider\(c\.x \+ wx, c\.z [+-] hz, 1\.1\)/.test(блок),
      'стены двора не закрыты цепочкой точек: один круг радиусом с полдвора ' +
        'не пустит игрока к двери',
    );
    // И в проёме должно быть пропущено: без continue игрок не пройдёт в ворота.
    must(
      /if \(Math\.abs\(wx\) < МЕЧЕТЬ_ВОРОТА \/ 2\) continue;/.test(блок),
      'в воротах нет проёма: игрок выйдет из мечети в стену',
    );
    const радиус = /addCollider\(c\.x \+ wx, c\.z [+-] hz, ([\d.]+)\)/.exec(блок);
    must(радиус !== null, 'не разобрался радиус коллайдера стены');
    const r = Number(радиус![1]);
    const шаг = /for \(let wx = -hx; wx <= hx; wx \+= ([\d.]+)\)/.exec(блок);
    must(шаг !== null, 'не разобрался шаг точек стены');
    must(
      Number(шаг![1]) <= r * 2,
      `шаг ${шаг![1]} м при радиусе ${r} м: между точками останется щель, ` +
        'в которую пролезает игрок',
    );
  });

  it('проём в воротах проходим и не шире двора', () => {
    const ворота = число('МЕЧЕТЬ_ВОРОТА');
    const ширина = габариты().ширина;
    const половина = /МЕЧЕТЬ_ПОЛУШИНА = \{ x: ([\d.]+)/.exec(ТЕРРЕЙН);
    must(половина !== null, 'не нашлась МЕЧЕТЬ_ПОЛУШИНА');
    const hx = Number(половина![1]);
    must(ворота >= 1.6, `проём ${ворота} м: игрок в ширину не пройдёт`);
    must(
      ворота <= ширина * 0.4,
      `проём ${ворота} м при ширине двора ${ширина.toFixed(2)}: ` +
        'проём шире сорока процентов стены — это уже разрыв, а не ворота',
    );
    must(hx * 2 > ворота, 'половина габарита меньше проёма — ворота шире стены');
  });

  it('купол закрыт коллайдером: в него нельзя войти', () => {
    const блок = блокЭкспортируемой(ТЕРРЕЙН, 'export function buildMosqueCourtyard');
    must(
      /addCollider\(c\.x - 5, c\.z, МЕЧЕТЬ_КУПОЛ\)/.test(блок),
      'купол не закрыт: он в 5 м от двери, и в него можно войти',
    );
    const r = число('МЕЧЕТЬ_КУПОЛ');
    const г = габариты();
    must(
      r < г.глубина / 2,
      `коллайдер купола ${r} м при глубине двора ${г.глубина.toFixed(2)}: ` +
        'он шире половины двора и запирает проход к воротам',
    );
  });

  it('на сухе, включая весь след двора', () => {
    const центр = /export const MOSQUE_COURTYARD = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН);
    must(центр !== null, 'не нашёлся MOSQUE_COURTYARD');
    const cx = Number(центр![1]);
    const cz = Number(центр![2]);
    const hx = Number(/МЕЧЕТЬ_ПОЛУШИНА = \{ x: ([\d.]+)/.exec(ТЕРРЕЙН)![1]);
    const hz = Number(/z: ([\d.]+)/.exec(/МЕЧЕТЬ_ПОЛУШИНА = \{[^}]*\}/.exec(ТЕРРЕЙН)![0])![1]);
    for (const [ox, oz] of [
      [0, 0], [-hx, -hz], [hx, -hz], [-hx, hz], [hx, hz], [0, hz], [0, -hz],
    ]) {
      must(
        !isWater(cx + ox, cz + oz),
        `под двором вода в (${cx + ox}, ${cz + oz}): угол утонет в реке`,
      );
    }
  });
});