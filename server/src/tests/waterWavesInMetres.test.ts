// Вода должна считаться в метрах, а не в uv.
//
// ЧТО БЫЛО СЛОМАНО 15.10.2026. Шейдер воды брал длину волны от uv — то есть от
// координаты 0..1 на КАЖДОЕ водное тело — а смещение складывал в мировые
// метры. Метров на единицу uv у тел было разное:
//
//   озеро  Ø 340 м   «9 метров» = 2720 м — всё озеро внутри одной волны
//   пруд   Ø 140 м   «9 метров» = 1120 м
//   река   Ø 17 м    «9 метров» =  136 м
//   море   6350 м    «9 метров» = 50800 м
//
// Озеро выглядело медленно кренящейся плитой. Море вдобавок было плоскостью
// 1x1 — четыре вершины на 6.3 километра, — и вершинному смещению негде было
// звучаться вовсе: гладь стояла идеально ровной.
//
// И ещё три поломки в том же месте, которые разговор про «метры» не ловит:
//   - глубина считалась как uWaterLevel минус y, а у покоящейся воды y равна
//     уровню, то есть глубина выходила НОЛЬ ВСЕГДА: и море в 8.8 м, и пруд
//     рисовались мелкой бирюзой;
//   - уровень был один на все тела (уровень озера), так что море получало ещё
//     и чужую глубину;
//   - карта нормалей тиражировалась в uv, то есть одна плитка растягивалась на
//     794 м на море и на 42 м на озере.
//
// ПОЧЕМУ ПРОВЕРКИ ТЕКСТОВЫЕ, А ЧИСЛОВЫЕ - В ОТДЕЛЬНОМ ФАЙЛЕ. Клиентские модули
// не тянутся сервером. Все числа меряет client/tools/check-water-waves.ts тем же
// кодом, что и шейдер; здесь сторож ловит именно «вернулись волны в uv».
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
// Клиентский модуль поднимается здесь специально: он тянет только
// shared/water, без three и без DOM, поэтому сервер может посмотреть на
// настоящий сгенерированный GLSL и на настоящие числа сетки, а не на их
// описание в комментариях.
import {
  WAVE_GLSL,
  WAVE_FIELDS,
  WATER_GRIDS,
  WORLD_HALF,
  gradedAxis,
  stepAt,
  корочеВсехВершиннаяОктава,
  seaShoreProfile,
} from '../../../client/src/app/game3d/waterWaves';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const прочитать = (...путь: string[]): string =>
  readFileSync(join(корень, ...путь), 'utf8').replace(/\r\n/g, '\n');

/**
 * Код без комментариев.
 *
 * Без этого сторож проверяет сам себя: фраза «было depth = uWaterLevel -
 * vWorldPos.y» живёт в комментарии рядом с исправлением, и проверка на
 * отсутствие формулы находила её и падала на собственном же объяснении.
 */
function кодБезКомментариев(исходник: string): string {
  return исходник
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/^\s*\/\/.*$/gm, ' ')
    .replace(/\/\/.*$/gm, ' ');
}

const код = (путь: string[]): string => кодБезКомментариев(прочитать(...путь));

const TERRAIN = ['client', 'src', 'app', 'game3d', 'terrain.ts'];
const WAVES = ['client', 'src', 'app', 'game3d', 'waterWaves.ts'];
const WORLD3D = ['client', 'src', 'app', 'game3d', 'world3d.ts'];

describe('Вода считается в метрах, а не в uv', () => {
  const terrain = прочитать(...TERRAIN);
  const waves = прочитать(...WAVES);

  it('волны берутся из мировых координат, а не из uv', () => {
    must(
      /pickField\(off, base\.xz, uTime/.test(terrain),
      'вершинный шейдер воды больше не смотрит на base.xz: длина волны снова '
      + 'берётся из uv, а это разный метраж на каждом теле',
    );
    must(
      !/gerstnerWave\(uv/.test(terrain),
      'вернулась старая gerstnerWave(uv): она мешает точки в uv с мировыми '
      + 'метрами, и на озере «9 м» становятся 2720 м',
    );
  });

  it('шейдер берёт октавы из таблицы, а не из записанного вручную списка', () => {
    must(
      /\$\{WAVE_GLSL\}/.test(terrain),
      'шейдер не вставляет сгенерированный WAVE_GLSL: таблица октав и шейдер '
      + 'разъедутся, и править придётся в двух местах',
    );

    // Модуль тянет только shared/water - ни three, ни DOM, - поэтому его можно
    // поднять прямо здесь и посмотреть на НАСТОЯЩИЙ текст шейдера, а не искать
    // его в исходнике. Текст генерируется из таблицы октав, так что если
    // генератор отдаст не то, шейдер в браузере будет считать не то.
    must(
      /void gerstner_\w+\(inout vec3 acc/.test(WAVE_GLSL),
      `в сгенерированном GLSL нет ни одной функции поля. Получено: ${
        (WAVE_GLSL.match(/void \w+\(/g) || []).join(', ') || 'ничего'}`,
    );
    for (const тело of ['lake', 'pond', 'river', 'sea'] as const) {
      must(
        new RegExp(`void gerstner_${тело}\\(inout vec3 acc, vec2 p, float t, float scale\\)`).test(WAVE_GLSL),
        `в GLSL нет функции поля «${тело}»: вершинный шейдер не сможет выбрать `
        + 'волны для этого тела, и оно останется плоским',
      );
    }
    must(
      !/gerstner_озеро|gerstner_море|gerstner_пруд|gerstner_река/.test(WAVE_GLSL),
      'в имени функции кириллица: идентификаторы GLSL ES допускают только '
      + '[A-Za-z0-9_], такой шейдер не скомпилируется',
    );
    // Длина волны обязана попасть в GLSL числом: если генератор забудет про
    // octaves, октав не будет ни одной и вода снова станет плоскостью.
    const октавВGLSL = (WAVE_GLSL.match(/gerstner\(acc, p, t,/g) || []).length;
    const октавВТаблице = Object.values(WAVE_FIELDS)
      .reduce((s, f) => s + f.octaves.filter((o) => o.carriedBy === 'mesh').length, 0);
    must(
      октавВGLSL === октавВТаблице,
      `в GLSL ${октавВGLSL} вершинных октав, а в таблице ${октавВТаблице}: `
      + 'генератор и таблица разошлись, шейдер будет считать не то, что помечено',
    );
  });

  it('море больше не плоскость из двух треугольников', () => {
    must(
      !/PlaneGeometry\(WORLD_HALF \* 2, seaDepth, 1, 1\)/.test(terrain),
      'море снова строится плоскостью 1x1: четыре вершины на 6.3 километра, '
      + 'и вершинным волнам негде звучаться',
    );
    must(
      /seaGeometry\(/.test(terrain),
      'нет сетки моря с растущим шагом: равномерная сетка в 5 м стоила бы '
      + '4.8 миллиона треугольников только на воду',
    );
  });

  it('вершинные октавы не мельче сетки', () => {
    // Пробник check-water-waves.ts меряет это числами; здесь сторож следит,
    // чтобы в таблице появился признак carriedBy и его никто не убрал.
    must(
      /carriedBy: 'mesh'/.test(waves) && /carriedBy: 'detail'/.test(waves),
      'в таблице октав нет признака carriedBy: непонятно, что несёт сетка, '
      + 'а что карта нормалей, и однажды мелочь опять потащат в вершины',
    );
  });
});

describe('Море действительно разрезано на сетку', () => {
  it('сетка моря достаточно мелкая, чтобы на ней было чем рисовать волны', () => {
    const сетка = WATER_GRIDS.sea;
    const xs = gradedAxis(0, сетка.radius, сетка.step, сетка.growth);
    const колонок = xs.length * 2 - 1;
    // Z: от самой северной возможной точки берега до края мира.
    const zs = gradedAxis(-660 + 60, -WORLD_HALF, сетка.step, сетка.growth);
    const треугольников = (колонок - 1) * (zs.length - 1) * 2;

    must(колонок >= 40 && zs.length >= 20,
      `сетка моря ${колонок}x${zs.length}: вершин слишком мало, вершинному `
      + 'смещению негде звучаться. Прежнее море было 2x2 на 6.3 километра');
    must(треугольников < 60_000,
      `сетка моря стоит ${треугольников} треугольников - это уже не вода`);
    must(треугольников > 5_000,
      `сетка моря всего ${треугольников} треугольников: волн на горизонте не будет`);
  });

  it('шаг не перерастает длину волны раньше, чем смещение погаснет', () => {
    // Шейдер гасит вершинное смещение между uLodNear (70) и uLodFar (210).
    // Если на 210 м шаг уже длиннее вершинной волны, то участок, где волна ещё
    // рисуется, рисуется в треугольниках, которые её не держат.
    const шагУГасания = stepAt(210, WATER_GRIDS.sea.step, WATER_GRIDS.sea.growth);
    const худшая = корочеВсехВершиннаяОктава(WAVE_FIELDS.sea);
    must(худшая !== null, 'у моря нет ни одной вершинной октавы');
    must(шагУГасания <= (худшая as { wavelength: number }).wavelength,
      `вершинное смещение гаснет на 210 м, а шаг сетки там уже `
      + `${шагУГасания.toFixed(0)} м - длиннее волны в ${худшая?.wavelength} м`);
  });

  it('gradedAxis не раздувается на нечисле', () => {
    // С ловушкой на NaN сетка становилась в 4097 точек и 67 миллионов
    // треугольников: сравнение с NaN всегда ложно, и цикл выходил только по
    // предохранителю. Так и вышло, когда пробник подсунул сюда несуществующий
    // WORLD_HALF.
    must(gradedAxis(0, 100, 5, 1.06).length === 15,
      'gradedAxis считает не то, чего от неё ждут');
    let поймало = false;
    try {
      gradedAxis(0, Number.NaN, 5, 1.06);
    } catch {
      поймало = true;
    }
    must(поймало,
      'gradedAxis молча согласилась на NaN и вернула 4097 точек: сетка воды '
      + 'раздулась бы в 67 миллионов треугольников вместо пятнадцати тысяч');
  });

  it('линия берега моря существует и ведёт себя как линия', () => {
    const профиль = seaShoreProfile(128);
    must(профиль.length === 128, 'профиль берега не той длины');
    let размах = 0;
    for (const z of профиль) {
      must(Number.isFinite(z), `в профиле берега не число: ${z}`);
      if (z < -4000 || z > 400) {
        throw new Error(
          `берег на z=${z.toFixed(0)} - это суша или край мира, а не граница `
          + 'воды: мелкая полоса уехала бы с берега',
        );
      }
      размах = Math.max(размах, 0);
    }
    const минимум = Math.min(...профиль);
    const максимум = Math.max(...профиль);
    must(максимум - минимум < 400,
      `берег гуляет на ${(максимум - минимум).toFixed(0)} м - профиль из 128 `
      + 'шагов по 50 м не может перерисовать настоящий контур, и мелкая полоса '
      + 'пойдёт лесом');
    must(минимум > -2000, `берег уехал на ${минимум.toFixed(0)}: это не граница моря`);
  });
});

describe('Глубина воды считается, а не равна нулю', () => {
  const terrain = код(TERRAIN);

  it('старой формулы глубины больше нет', () => {
    must(
      !/uWaterLevel\s*-\s*vWorldPos\.y/.test(terrain),
      'вернулась формула depth = uWaterLevel - vWorldPos.y: у покоящейся воды '
      + 'vWorldPos.y равен уровню, то есть глубина выходит ноль ВСЕГДА и вся '
      + 'вода рисуется мелкой бирюзой',
    );
  });

  it('глубина идёт от расстояния до берега', () => {
    must(
      /distanceToShore/.test(terrain),
      'в шейдере нет меры расстояния до берега: без неё цвет воды не зависит '
      + 'от глубины, и мелкая полоса у берега не появляется',
    );
    must(
      /uNominalDepth/.test(terrain),
      'нет номинальной глубины тела: у моря дно на -12, у озера на -5.2',
    );
  });

  it('у каждого тела свой уровень воды', () => {
    must(
      /WATER_LOOKS/.test(terrain),
      'нет таблицы уровней и глубин по телам: один общий уровень (озерный) '
      + 'даёт морю чужую глубину',
    );
    must(
      /level: LAKE\.level/.test(terrain) && /level: POND\.level/.test(terrain)
      && /level: SEA\.level/.test(terrain),
      'не у всех тел записан свой уровень: значит, кто-то снова делит озерный',
    );
  });
});

describe('У воды несколько материалов, и время у них общее', () => {
  const terrain = код(TERRAIN);
  const world3d = код(WORLD3D);

  it('world3d обходит все материалы воды, а не один', () => {
    must(
      /for \(const mat of waterMaterials\)/.test(world3d),
      'world3d обновляет один материал воды: у остальных застынет время, и '
      + 'волны на стыке тел разойдутся фазой',
    );
    must(
      !/waterMaterial\.uniforms\.uTime/.test(world3d),
      'world3d всё ещё пишет в единый waterMaterial: общий материал вернулся, '
      + 'и у моря снова чужая глубина',
    );
  });

  it('общее время воды хранится, а не накапливается в одном материале', () => {
    must(
      /private waterTime = 0/.test(world3d),
      'нет общего счётчика времени воды: каждый материал считал бы своё',
    );
    must(
      /this\.waterTime \+= dt/.test(world3d),
      'время воды не растёт: волны стоят',
    );
  });

  it('море едет за камерой, иначе игрок останется в крупных треугольниках', () => {
    must(
      /followSeaToCamera/.test(world3d) && /followSeaToCamera/.test(terrain),
      'сетка моря не едет за камерой: мелкая область сидит в мировом нуле, и '
      + 'игрок, ушедший на лодке вдоль берега, оказывается в треугольниках '
      + 'шире волны',
    );
  });

  it('погода управляет высотой волн', () => {
    must(
      /chopFor\(this\.currentWeather\)/.test(world3d),
      'погода не влияет на воду: в шторм и в ясный полдень озеро одинаковое, '
      + 'хотя окружение давно темнеет по погоде',
    );
    must(
      /storm: 2\.2/.test(код(WAVES)),
      'в таблице погод нет шторма: волны не знают о буре',
    );
  });

  it('мёртвый uniform uWaveScale больше не объявляется', () => {
    must(
      !/uWaveScale/.test(terrain),
      'uniform uWaveScale объявлен в шейдере, но не читается ни разу: это '
      + 'ложный рычаг, которым нельзя управлять водой',
    );
  });
});