// Разбор ответа Epoint. Здесь проверяется то решение, которое придумано по
// таблице кодов: зачислять по status, а не по коду 000.
import { epointResultToEvent, epointIsBankInternalError } from '../services/payments/epoint/result';

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

describe('Ответ Epoint переводится в наш платёжный путь', () => {
  it('status success - единственное основание начислить', () => {
    const r = epointResultToEvent({
      order_id: 'наш-1',
      status: 'success',
      code: '000',
      message: 'Подтверждено',
      transaction: 'te0011111111',
      bank_transaction: 'bnk-1',
      amount: 20.5,
    });
    must(r.kind === 'completed', `ожидалось completed, получено ${r.kind}`);
    must(r.amount === 20.5, `сумма не прочитана: ${r.amount}`);
    must(r.transaction === 'te0011111111', 'номер операции не прочитан');
    must(r.orderId === 'наш-1', 'наш order_id не прочитан - платёж пришлось бы угадывать');
  });

  it('код 000 БЕЗ status success не начисляет', () => {
    // ГЛАВНАЯ ЛОВУШКА. В документе есть 500 «согласовано, в балансе» и 501
    // «согласовано, вне баланса»: банк подтвердил, а денег на балансе ещё
    // нет. Если начислять по 000, игрок получит валюту раньше, чем придут
    // деньги, и при неудачном исходе мы будем должны за их счёт.
    const r = epointResultToEvent({ status: 'error', code: '000', amount: 20.5, transaction: 'te1' });
    must(r.kind !== 'completed', 'по коду 000 без status success платёж начислен');
    must(r.kind === 'failed', `ожидался failed, получено ${r.kind}`);
  });

  it('код 500 «согласовано, в балансе» - это ещё не наш успех', () => {
    // Звучит как успех, но решение принимает status, а он здесь не success.
    const r = epointResultToEvent({ status: 'error', code: '500' });
    must(r.kind === 'failed', `ожидался failed, получено ${r.kind}`);
  });

  it('923 «запрос в процессе» - это ожидание, а не отказ', () => {
    // Иначе игроку покажут «отклонён» в момент, когда платёж ещё в работе,
    // и он попробует заплатить второй раз.
    const r = epointResultToEvent({ status: 'error', code: '923' });
    must(r.kind === 'pending', `ожидался pending, получено ${r.kind}`);
    must(r.message.includes('обрабатывается'), `текст не про ожидание: ${r.message}`);
  });

  it('пустой ответ не превращается в выдуманный отказ', () => {
    // Ни статуса, ни кода: сказать «отклонено» значит придумать причину.
    // Такое приходит при обрезанном ответе, и видно это только здесь.
    const r = epointResultToEvent({});
    must(r.kind === 'unknown', `ожидался unknown, получено ${r.kind}`);
    must(r.message.includes('не прошёл'), `текст не про «не проверено»: ${r.message}`);
  });

  it('отсутствующая сумма - это null, а не ноль', () => {
    // Молчаливый ноль выглядит как настоящая сумма: платёж на 0 успешен и
    // приносит ноль валюты, а разница видна только в тексте ошибки.
    const без = epointResultToEvent({ status: 'success', transaction: 'te1' });
    must(без.amount === null, `сумма без поля равна ${без.amount}, а должна быть null`);
    const ноль = epointResultToEvent({ status: 'success', amount: 0, transaction: 'te1' });
    must(ноль.amount === 0, 'настоящий ноль должен остаться нулём');
    must(ноль.amount !== без.amount, 'null и 0 неразличимы - потерян смысл различия');
  });

  it('сумма приходит и числом, и строкой - обе формы читаются', () => {
    // В примерах документа сумма передаётся то строкой, то числом. Ответ
    // может прийти так же, и строка не должна читаться как «нет суммы».
    must(epointResultToEvent({ status: 'success', amount: '20.50' }).amount === 20.5, 'строка не прочитана');
    must(epointResultToEvent({ status: 'success', amount: 20.5 }).amount === 20.5, 'число не прочитано');
    must(epointResultToEvent({ status: 'success', amount: '20,50' }).amount === null, 'запятая принята за число');
    must(epointResultToEvent({ status: 'success', amount: 'abc' }).amount === null, 'мусор принят за сумму');
  });

  it('игроку не показывают банковские подробности', () => {
    // Тексты в документе на русском и про банк: «подозрение в мошенничестве»,
    // «нарушение безопасности». Игрок с этим ничего не может.
    for (const код of ['102', '122', '109', '909', '911', '950']) {
      const r = epointResultToEvent({ status: 'failed', code: код });
      must(
        !r.message.includes(код),
        `игроку показан банковский код ${код}: ${r.message}`,
      );
    }
    // Про 109 отдельно: это НАША ошибка, не покупателя.
    must(epointIsBankInternalError('109'), '109 не распознан как наша ошибка');
    must(epointIsBankInternalError('122'), '122 не распознан как наша ошибка');
    must(!epointIsBankInternalError('116'), '116 - это не наша ошибка, а нехватка средств');
  });

  it('игроку показывают то, с чем он может что-то сделать', () => {
    const нехватка = epointResultToEvent({ status: 'failed', code: '116' });
    must(нехватка.message.includes('Недостаточно средств'), `не сказано про средства: ${нехватка.message}`);
    const неверныйPin = epointResultToEvent({ status: 'failed', code: '117' });
    must(неверныйPin.message.includes('другую карту'), `не сказано про карту: ${неверныйPin.message}`);
    const истёкшая = epointResultToEvent({ status: 'failed', code: '101' });
    must(истёкшая.message.includes('Срок действия'), `не сказано про срок: ${истёкшая.message}`);
  });

  it('ни один код банка не попадает в текст для игрока - перебором, а не выборочно', () => {
    // ПОЧЕМУ ПЕРЕБОР, А НЕ ШЕСТЬ КОДОВ СПИСКОМ. Раньше проверка смотрела
    // шесть кодов из шестидесяти, и код 110 в список не попал. После этого
    // поломка «в текст для игрока подставился сам код» прошла незамеченной:
    // проверка была зелёной при сломанном коде. Выборочная проверка всегда
    // пропускает то, о чём не подумали, а перебор спрашивает у каждого кода.
    const ВСЕ_КОДЫ = [
      '000', '100', '101', '102', '103', '104', '105', '106', '107', '108',
      '109', '110', '111', '112', '113', '114', '115', '116', '117', '118',
      '119', '120', '121', '122', '123', '124', '125', '126', '127', '128',
      '129', '180', '203', '206', '207', '208', '209', '210', '300', '301',
      '304', '305', '307', '400', '499', '500', '501', '502', '503', '504',
      '600', '601', '602', '603', '604', '605', '606', '680', '681', '700',
      '800', '900', '901', '902', '903', '904', '905', '906', '907', '908',
      '909', '910', '911', '912', '913', '914', '915', '916', '917', '918',
      '919', '920', '921', '922', '923', '950',
    ];
    // Коды, которые в документе названы успехом, а не отказом. Их код в
    // тексте для игрока тоже неуместен, но начислять их нельзя - поэтому
    // проверяем текст, а не kind.
    const утечки: string[] = [];
    for (const код of ВСЕ_КОДЫ) {
      const r = epointResultToEvent({ status: 'failed', code: код, message: 'текст банка' });
      if (r.message.includes(код)) {
        утечки.push(`${код} -> ${r.message}`);
      }
    }
    must(
      утечки.length === 0,
      `банковский код попал в текст для игрока: ${утечки.slice(0, 5).join(' | ')}`,
    );

    // Отдельно: текст банка из поля message тоже не должен показываться
    // игроку как есть. Он написан банком и может содержать что угодно.
    const сБанковскимТекстом = epointResultToEvent({
      status: 'failed', code: '116', message: 'REJECTED: card declined by issuer XYZ',
    });
    must(
      !сБанковскимТекстом.message.includes('XYZ'),
      `игроку показан сырой текст банка: ${сБанковскимТекстом.message}`,
    );
  });

  it('банковские номера остаются в результате для журнала', () => {
    const r = epointResultToEvent({
      status: 'failed', code: '116', bank_transaction: 'bnk-77', transaction: 'te9',
    });
    must(r.bankCode === '116', 'код банка потерян');
    must(r.bankTransaction === 'bnk-77', 'номер банка потерян - разбираться будет не с чем');
  });

  it('не-объект в ответе приводит к отказу, а не к тихому успеху', () => {
    // Редирект или HTML вместо JSON: раньше такое дошло бы до разбора
    // свойств и упало бы позже, в другом месте, с чужим текстом ошибки.
    for (const плохое of [null, 'строка', 42, undefined]) {
      let отказ = false;
      try { epointResultToEvent(плохое); } catch { отказ = true; }
      must(отказ, `ответ ${JSON.stringify(плохое) ?? 'undefined'} не привёл к отказу`);
    }
  });
});
