// Суточный цикл: подпись, небо и свет должны говорить одно и то же.
//
// ЧТО БЫЛО. Три места описывали одни сутки по-разному:
//
//   1. WorldTimeSystem.timeOfDayOf — подпись в углу экрана. Закат это
//      18:00-21:00, ночь 21:00-02:00, рассвет 05:00-07:00.
//   2. sky.ts — дуга солнца. Восход 6, закат 18. То есть ночь по небу
//      начиналась в 18:36 — почти на два с половиной часа раньше подписи.
//   3. nightFactor (shared/stealth.ts) и такой же подсчёт в world.ts —
//      фактор ночи для света и скрытности. Оба проверяли фазу 'evening',
//      которой в типе TimeOfDay НЕТ И НЕ БЫЛО. Закат получал 0 — полный
//      день.
//
// На скриншоте это видно: часы 19:13, подпись «весна · закат · ясно», а на
// небе луна и звёзды. Три часа закатa рисовались ночью и считались днём.
//
// ЧТО ПРОВЕРЯЕТСЯ. Имена фаз настоящие (есть в типе TimeOfDay), фактор ночи
// реагирует на закат, и дуга солнца накрывает ровно объявленный сервером
// день.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');


const ВРЕМЯ = читать('server/src/systems/WorldTimeSystem.ts');
const НЕБО = читать('client/src/app/game3d/sky.ts');
const СКРЫТНОСТЬ = читать('shared/stealth.ts');
const КЛИЕНТ = читать('client/src/app/world.ts');

/** Фазы, которые сервер реально отдаёт. */
const ФАЗЫ = [
  'dawn', 'morning', 'noon', 'afternoon', 'dusk', 'night', 'midnight',
] as const;

describe('Суточный цикл говорит одно и то же', () => {
  it('список фаз в типе TimeOfDay совпадает с расписанием', () => {
    // Якорь: если набор фаз в типе разойдётся с timeOfDayOf, вся проверка
    // ниже будет сверять несуществующие имена — и промолчит.
    const тип = /type TimeOfDay\s*=\s*([^;]+);/.exec(ВРЕМЯ);
    должен(тип, 'тип TimeOfDay не читается');
    for (const фаза of ФАЗЫ) {
      должен(тип![1].includes(фаза), `в типе TimeOfDay нет фазы ${фаза}`);
      // И обратная сторона: name, которого нет в типе, не должен
      // использоваться. Именно 'evening' сюда и не входит.
      должен(тип![1].includes('evening') === false,
        'в типе появилась фаза evening — но timeOfDayOf её не выдаёт');
    }
  });

  it('фазы неба и света — настоящие имена из TimeOfDay', () => {
    // 'evening' звучит как фаза, но сервер её не выдаёт. Проверка на
    // пустое имя ловит ровно ту опечатку, из-за которой закат считался днём.
    for (const [имя, текст] of [
      ['nightFactor', СКРЫТНОСТЬ],
      ['подсчёт в world.ts', КЛИЕНТ],
    ] as const) {
      должен(!/===\s*'evening'/.test(текст),
        `${имя} проверяет фазу 'evening': её не существует, закат считается полным днём`);
    }
  });

  it('закат даёт пол-ночи, а не полный день', () => {
    // Закат 18:00-21:00 — это сумерки, и свет с ним должен согласоваться.
    должен(/'dusk'\s*\|\|/.test(СКРЫТНОСТЬ) || /'dusk'/.test(СКРЫТНОСТЬ),
      'nightFactor не упоминает закат: сумерки считаются полым днём');
    должен(/'dusk'\s*\|\|/.test(КЛИЕНТ) || /'dusk'/.test(КЛИЕНТ),
      'world.ts не упоминает закат: клиентский подсчёт ночи расходится с серверным');
  });

  it('дуга солнца накрывает объявленный сервером день', () => {
    // Подпись говорит: день 05:00-21:00 (рассвет 5-7, день 7-18, закат 18-21).
    // Значит восход должен быть в 5, закат в 21. Было 6 и 18 — и ночь
    // начиналась на два с половиной часа раньше подписи.
    const м = /dayAngle\s*=\s*\(\(hour01\s*-\s*([\d.]+)\)\s*\/\s*([\d.]+)\)/.exec(НЕБО);
    должен(м, 'в sky.ts не нашлась дуга солнца: проверка потеряла смысл');
    const начало = Number(м![1]);
    const полудуга = Number(м![2]);
    // Полудуга 16 часов: восход в 5, закат в 5+16=21.
    должен(полудуга === 16,
      `полудуга ${полудуга} часов: день$_$ не накрывает 05:00-21:00`.replace('$_$', ' '));
    должен(начало === 5, `восход в ${начало}: рассвет по серверу начинается в 5`);
  });

  it('луна идёт той же дугой, иначе светила разъедутся', () => {
    // Луна обязана пользоваться тем же делителем: с другим периодом через
    // сутки она оказалась бы не напротив солнца.
    const солнце = /dayAngle\s*=\s*\(\(hour01\s*-\s*[\d.]+\)\s*\/\s*([\d.]+)\)/.exec(НЕБО);
    const луна = /mAngle\s*=\s*\(\(hour01\s*\+\s*12\s*-\s*[\d.]+\)\s*\/\s*([\d.]+)\)/.exec(НЕБО);
    должен(солнце && луна, 'дуга солнца или луны не читается');
    должен(солнце![1] === луна![1],
      `делители разные (солнце ${солнце![1]}, луна ${луна![1]}): светила разъедутся`);
  });

  it('в час заката солнце над горизонтом', () => {
    // Не формула, а результат по часам: в каждый час закатa солнце должно
    // быть выше горизонта. Иначе сумерки рисуются ночью — ровно то, что
    // было на скриншоте.
    const м = /dayAngle\s*=\s*\(\(hour01\s*-\s*([\d.]+)\)\s*\/\s*([\d.]+)\)/.exec(НЕБО);
    const начало = Number(м![1]);
    const дуга = Number(м![2]);
    for (const час of [18.5, 19.2, 20.5]) {
      const высота = Math.sin(((час - начало) / дуга) * Math.PI);
      должен(высота > 0,
        `в ${час}:00 солнце под горизонтом (высота ${высота.toFixed(2)}) — закат рисуется ночью`);
    }
    // И в ночь оно действительно под горизонтом.
    for (const час of [0, 3, 23]) {
      const высота = Math.sin(((час - начало) / дуга) * Math.PI);
      должен(высота < 0,
        `в ${час}:00 солнце над горизонтом — ночь светлая как день`);
    }
  });

  it('границы фаз в WorldTimeSystem не разъехались с дугой', () => {
    // Подпись — источник правды: дуга обязана начинаться там, где сервер
    // объявляет рассвет, и кончаться там, где объявляет ночь.
    должен(/hour >= 5\s*&&\s*hour < 7/.test(ВРЕМЯ), 'рассвет больше не 5-7: дуга считает от 5');
    должен(/hour >= 18\s*&&\s*hour < 21/.test(ВРЕМЯ), 'закат больше не 18-21');
    должен(/hour >= 21\s*\|\|/.test(ВРЕМЯ), 'ночь больше не начинается в 21');
  });
});


function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}
