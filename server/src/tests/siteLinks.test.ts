// Ссылки на игру должны вести на существующее имя.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Отслеживаемые файлы: git знает, что попадёт в сборку. */
function отслеживаемые(): string[] {
  return execFileSync('git', ['ls-files'], { cwd: корень, encoding: 'utf-8' })
    .split('\n')
    .filter(Boolean);
}

describe('Ссылки на игру ведут на существующее имя', () => {
  it('нигде нет префикса www перед нашим именем', () => {
    // НАЙДЕНО: битых ссылок было 59 в 17 файлах. Префикс www был прописан
    // везде одинаково, и проверки этого не ловили: они сверяли совпадение
    // строк между файлами, а совпадение одинаково неверных строк истинно.
    // Проверка правды, а не согласованности.
    //
    // ROADMAP И docs/archive ЗДЕСЬ ЛИШНИЕ, КАК И С МЁРТВЫМ АДРЕСОМ НИЖЕ.
    // В карте проекта префикс www стоит внутри описания находки — так
    // сохраняется то, что именно было сломано. Обход всего подряд ругался
    // на документ, который честно описывает поломку.
    const ИСКЛЮЧЕНЫ = ['ROADMAP.md', /^docs\/archive\//];
    const пропускается = (файл: string): boolean =>
      ИСКЛЮЧЕНЫ.some((п) => (п instanceof RegExp ? п.test(файл) : п === файл));

    const виновники: string[] = [];
    for (const файл of отслеживаемые()) {
      if (пропускается(файл)) continue;
      const путь = join(корень, файл);
      if (!existsSync(путь)) continue;
      const текст = readFileSync(путь, 'utf-8');
      if (/www\.[a-z0-9-]*game[a-z0-9-]*\.eos-gameonline\.com/i.test(текст)) {
        виновники.push(файл);
      }
    }
    must(
      виновники.length === 0,
      `префикс www перед нашим именем в файлах: ${виновники.join(', ')}. ` +
        'Такого имени в DNS нет: опубликовано только game.eos-gameonline.com',
    );
  });

  it('адрес отключённого сервера не упоминается', () => {
    // Vultr отключён за долг, инстанс удалён. Ссылка «играть» на его адрес
    // увела бы игрока в пустоту.
    //
    // ПЕРВЫЙ ВАРИАНТ БЫЛ НЕВЕРНЫМ. Проверка обходила все отслеживаемые
    // файлы и ругалась на ROADMAP.md, где старый адрес стоит намеренно: там
    // записано, что NS долго отдавал именно его, — это часть истории
    // переезда, а не ссылка для игрока. Обход всего подряд даёт честное
    // замечание о самой проверке, а не о ссылке.
    //
    // Теперь проверяем то, что игрок видит или что исполняется при выкладке:
    // страницы сайта, скрипты выкладки и тексты публикации.
    const ОТДАЁТСЯ = [
      'client/web/index.html',
      'client/web/forum.html',
      'client/web/feedback.html',
      'client/web/trailer.html',
      'client/web/sitemap.xml',
      'client/web/robots.txt',
      'tools/publish-instructions.md',
      'tools/itch-reddit-draft.md',
      'tools/deploy-vps.py',
      'tools/deploy.sh',
      'tools/deploy-preflight.sh',
      'tools/build-trailer.sh',
    ];
    const виновники: string[] = [];
    for (const файл of ОТДАЁТСЯ) {
      const путь = join(корень, файл);
      must(existsSync(путь), `файл ${файл} исчез: список отдаваемого разошёлся с диском`);
      if (readFileSync(путь, 'utf-8').includes('45.32.220.58')) виновники.push(файл);
    }
    must(
      виновники.length === 0,
      `адрес отключённого сервера в файлах: ${виновники.join(', ')}`,
    );
  });

  it('адреса в отдаваемых страницах принадлежат нашему домену', () => {
    const ОТДАЁТСЯ = [
      'client/web/index.html',
      'client/web/forum.html',
      'client/web/feedback.html',
      'client/web/trailer.html',
      'client/web/sitemap.xml',
      'client/web/robots.txt',
      'tools/publish-instructions.md',
      'tools/itch-reddit-draft.md',
    ];
    let проверено = 0;
    for (const файл of ОТДАЁТСЯ) {
      const путь = join(корень, файл);
      if (!existsSync(путь)) continue;
      const текст = readFileSync(путь, 'utf-8');
      // Хватает не наше имя, а любой домен. Прежняя проверка искала только
      // eos-gameonline и молчала на любом другом: подмена адреса на
      // game.eos-gameonline.example оставалась незамеченной, потому что
      // подстрока 'game.eos-gameonline.com' в нём как раз есть, а вот
      // полного совпадения адреса с нашим именем проверялось ровно ноль раз.
      const адреса = [...new Set(
        (текст.match(/https?:\/\/[a-z0-9-]+(?:\.[a-z0-9-]+)+[^\s"'<>)]*/gi) || []),
      )];
      for (const адрес of адреса) {
        проверено++;
        const наше = /^https?:\/\/game\.eos-gameonline\.com([/?#]|$)/i.test(адрес);
        // Площадки, куда игра выходит: каталоги, сообщества, площадка игроков.
        // Список назван по факту из index.html — Discord, соцсети и itch.io
        // стоят там как наши каналы связи, и «чужим» их назвать нельзя.
        const площадка = /(bmmorpg|browsermmorpg|itch\.io|github\.com|discord\.gg|facebook\.com|twitter\.com|reddit\.com)/i
          .test(адрес);
        // Схемы разметки (schema.org) и локальные адреса при разработке — не
    // наши ссылки, но и не чужие площадки: их игрок не кликает.
        // sitemaps.org — это xmlns карты сайта, а не ссылка: робот читает его как
        // имя пространства имён, игрок не кликает.
        const служебное =
          /localhost|127\.0\.0\.1|schema\.org|schemas\.|w3\.org|sitemaps\.org|creativecommons/i
            .test(адрес);
        must(
          наше || площадка || служебное,
          `${файл}: адрес ${адрес} не наш и не наш партнёрский`,
        );
      }
    }
    must(проверено > 40, `адресов нашлось всего ${проверено}: проверка почти ничего не смотрела`);
  });

  it('поисковикам отдан настоящий адрес, а не пустота', () => {
    // robots.txt и карта сайта — это то, по чему игра попадает в выдачу.
    // Если из них вынут наш адрес, страница не просто «плохо индексируется»:
    // робот приходит не туда и уходит.
    const robots = readFileSync(join(корень, 'client/web/robots.txt'), 'utf-8');
    must(
      /Sitemap:\s*https:\/\/game\.eos-gameonline\.com\/sitemap\.xml/.test(robots),
      'в robots.txt нет настоящего адреса карты сайта',
    );
    const карта = readFileSync(join(корень, 'client/web/sitemap.xml'), 'utf-8');
    must(
      /https:\/\/game\.eos-gameonline\.com\//.test(карта),
      'в карте сайта нет нашего адреса',
    );
    // Игровое приложение в карту не попадает намеренно: оно на JavaScript,
    // индексировать в нём нечего.
    must(
      !/<loc>[^<]*\/game\/[^<]*<\/loc>/.test(карта),
      'игровое приложение попало в карту сайта: обход только жрёт лимит',
    );
  });

  it('главная страница ведёт на существующую игру', () => {
    // Кнопка «Играть» — это href ровно на /game/. Раньше здесь стояло
    // «/game/ есть где-то вообще», и замена на /game-old/ проверку не
    // замечала: игрок нажимал «Играть» и попадал на страницу 404.
    const текст = readFileSync(join(корень, 'client/web/index.html'), 'utf-8');
    const игра = [...new Set((текст.match(/href="(\/game[^"]*)"/g) || []))];
    must(игра.length > 0, 'на главной нет ни одной ссылки на игру: игрок не найдёт, куда нажать');
    for (const ссылка of игра) {
      // Путь игры ровно /game/; после него допустим только параметр входа
      // для гостя (guest=1) — он открывает ту же игру, а не другую страницу.
      const путь = ссылка.match(/href="(\/game[^"]*)"/)![1];
      must(
        /^\/game\/(\?guest=1)?$/.test(путь),
        `ссылка на игру ведёт не туда: ${путь}`,
      );
    }
    // Секция голосования на площадке: она привлекает игроков, и она должна
    // быть на месте. Раньше была прямая ссылка, теперь кнопки + скрипт
    // рейтинга, но логика голосования остаётся на сайте.
    must(
      /vote-open|vote-claim|bmmorpg/.test(текст),
      'на главной пропала секция голосования на browsermmorpg: привлечение игроков',
    );
  });
});