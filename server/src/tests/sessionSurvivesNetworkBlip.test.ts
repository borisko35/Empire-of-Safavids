// Обрыв связи не должен выкидывать игрока из аккаунта.
//
// ЗАЧЕМ ФАЙЛ. Токен стирался в безусловном catch: любая ошибка запроса
// считалась отказом в сессии, включая ситуацию, когда сервер не ответил
// НИЧЕГО (обрыв сети, перезапуск, спящий ноутбук). Сценарий, который это
// давал, найден на живом проде во время съёмки скриншотов:
//
//   1. сокет отвалился на пару секунд;
//   2. клиент выкинул игрока к выбору персонажа;
//   3. игрок нажал «Играть за 10 секунд» — обычный ответ в такой ситуации;
//   4. сервер завёл НОВЫЙ гостевой аккаунт;
//   5. список персонажей пуст, прогресс выглядит пропавшим.
//
// Шаг 4 — самое дорогое: он съедает суточный лимит гостей на адрес и
// прячет реальный аккаунт. Чинится тем, что сессию стирает ТОЛЬКО сервер
// (401/403), а сеть ждём.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

const main = читать('client/src/app/main.ts');
const api = читать('client/src/app/api.ts');
const html = читать('client/src/app/index.html');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/**
 * Вырезать функцию из исходника или упасть.
 *
 * Отдельная функция, а не `must(исходник)` + `исходник!`: TypeScript не
 * сужает тип по утверждению о ПЕРЕМЕННОЙ, и проверка либо не компилировалась
 * бы, либо молча проверяла бы пустую строку.
 */
function вырезать(код: string, имя: string, причина: string): string {
  const найдено = new RegExp(`function ${имя}\\([^)]*\\): [^{]+\\{[\\s\\S]*?\\n\\}`).exec(код)?.[0];
  must(найдено, причина);
  return найдено as string;
}

describe('Обрыв связи не выкидывает из аккаунта', () => {
  it('сессию стирает только серверный отказ 401/403', () => {
    // Проверяется НАСТОЯЩАЯ функция из исходника, а не её смысл: если
    // в коде поменяют 401 на что-то другое, тест обязан упасть.
    const исходник = вырезать(main, 'сессияОтозвана', 'в main.ts нет функции сессияОтозвана — нечем отличить отказ от обрыва');

    must(
      /err instanceof ApiError/.test(исходник),
      'сессияОтозвана проверяет что это НЕ сетевая ошибка: обычный TypeError из fetch не должен считаться отказом в сессии',
    );
    must(
      /status === 401/.test(исходник) && /status === 403/.test(исходник),
      'в сессияОтозвана нет 401 и 403 — без них токен стирается при любой сетевой ошибке',
    );
    // Главное свойство: 5xx и сетевой обрыв НЕ отказ. Если появится
    // `|| err.status >= 400`, обрыв на 502 снова выкинет из игры.
    must(
      !/status >= 400|status >= 500/.test(исходник),
      'в сессияОтозвана проверяется весь класс 4xx/5xx — обрыв связи снова будет стирать сессию',
    );
  });

  it('ни один выход на экран входа не стирает токен без проверки', () => {
    // ЧТО ЗДЕСЬ БЫЛО ОШИБКОЙ. Проверка искала слово «сессияОтозвана» в 400
    // символах вокруг clearAuth() - и этого хватало, чтобы ПОПАСТЬ В ЛОВУШКУ:
    // комментарий «см. сессияОтозвана» рядом с безусловным clearAuth() считался
    // за проверку, и тест проходил на сломанном коде. Нашли поломкой, а не
    // чтением: guard в gotoCharacters() был потерян, а тест стоял зелёный.
    //
    // Поэтому комментарии вырезаются, и считается только живой ВЫЗОВ.
    const код = main
      .replace(/\/\*[\s\S]*?\*\//g, ' ')  // блоковые комментарии
      .replace(/\/\/[^\n]*/g, ' ');       // строковые комментарии

    const места = [...код.matchAll(/clearAuth\(\)/g)];
    must(места.length > 0, 'clearAuth() в main.ts не найден — проверка выродилась бы в пустую');

    const безПроверки: number[] = [];
    for (const [индекс, место] of места.entries()) {
      // Проверка должна стоять В ТОМ ЖЕ catch, то есть выше clearAuth по
      // тексту и не дальше, чем на 400 символов. Ниже — значит в другом
      // блоке, и это не защита.
      const выше = код.slice(Math.max(0, (место.index ?? 0) - 400), место.index ?? 0);
      if (!/сессияОтозвана\(/.test(выше)) безПроверки.push(индекс);
    }
    expect({ всего_clearAuth: места.length, без_проверки: безПроверки.length })
      .toEqual({ всего_clearAuth: места.length, без_проверки: 0 });
  });

  it('при обрыве показывается оверлей связи, а не экран входа', () => {
    // Экран входа с живым токеном — ловушка: там кнопка гостя, а гость
    // заводит новый аккаунт. То есть ровно тот шаг, который чиним.
    const телоФункции = вырезать(main, 'showConnectionLost', 'в main.ts нет функции showConnectionLost');
    must(
      /overlay-lost/.test(телоФункции),
      'при обрыве показывается не оверлей связи, а что-то другое',
    );
    // Экран входа в функции ЕСТЬ - но только как запасной путь, когда
    // оверлея в разметке нет. Проверяем, что основной путь - оверлей.
    const экранВхода = телоФункции.indexOf("showScreen('screen-auth')");
    const оверлей = телоФункции.indexOf("getElementById('overlay-lost')");
    must(
      оверлей >= 0 && оверлей < экранВхода,
      'основной путь showConnectionLost ведёт на экран входа, а не на оверлей связи',
    );
  });

  it('на оверлее связи есть кнопка повтора, и она перезагружает страницу', () => {
    must(
      /id="btn-retry"/.test(html),
      'на оверлее потери связи нет кнопки повтора — игрок останется на нём навсегда',
    );
    must(
      /data-i18n="common\.retry"/.test(html),
      'кнопка повтора без перевода: игрок увидит пустое место',
    );
    const world = читать('client/src/app/world.ts');
    const обработчик = вырезать(world, 'wireLostRetry', 'в world.ts нет wireLostRetry — кнопка ничего не делает');
    must(
      /window\.location\.reload\(\)/.test(обработчик),
      'кнопка повтора не перезагружает страницу: токен живой, и перезагрузка возвращает игрока в его аккаунт',
    );
    // Обработчик должен вызываться и ДО входа в мир: оверлей показывается
    // из boot(), когда мир ещё не загружался.
    must(
      /wireLostRetry/.test(main),
      'wireLostRetry не вызывается при загрузке страницы — на оверлее связи кнопка будет мёртвой',
    );
  });

  it('сетевой сбой отличается от отказа сервера на уровне api', () => {
    // Заложник решения: fetch бросает TypeError без статуса, а серверный
    // отказ - ApiError со status. Если бы req() начал подставлять status 0
    // или оборачивать сетевую ошибку в ApiError без статуса, проверка
    // сессияОтозвана перестала бы отличавать одно от другого.
    must(
      /throw new ApiError\([^)]*res\.status/.test(api),
      'в api.ts серверный отказ бросается не через ApiError с res.status — по статусу не отличить 401 от обрыва',
    );
    must(
      !/new ApiError\([^)]*,\s*0\s*,/.test(api),
      'в api.ts сетевой сбой оборачивается в ApiError со статусом 0 — это делает его неотличимым от отказа',
    );
  });
});
