// «Аламы» отнимали 85 процентов урона вместо того, чтобы добавлять 15.
//
// ЧТО БЫЛО СЛОМАНО. В данных навыка пассивный бонус урона записан как 0.15 —
// то есть «плюс 15 процентов». SkillsService умножал урон на это число как есть:
// damage *= def.passive.damage. Итог: дервиш, выучивший «Аламы», бил на 15
// процентов вместо 115, то есть терял 85 процентов урона.
//
// ПОЧЕМУ ЭТО ТЯЖЕЛО. «Аламы» — единственный пассивный бонус урона в игре, а
// бонуса к урону у профессии «дервиш» нет вовсе: в professionBonuses такого
// случая нет, поэтому дервиш попадает в default и получает единицы. То есть это
// был не слабый класс, а класс, который на первом же выученном навыке ломал
// себе урон в семь раз.
//
// ЧТО ПРОВЕРЯЕТСЯ. Настоящий SkillsService с подставленной базой: база отдаёт
// выученный «Аламы», и проверка требует, чтобы урон вырос на 15 процентов, а
// не упал. Досягаемость рядом записана множителем и умножается напрямую —
// трогать её нельзя, и проверка следит, чтобы она осталась как была.
import { SkillsService } from '../services/SkillsService';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Сервис, у которого база отвечает списком выученных навыков. */
function сервис(выучены: string[]): SkillsService {
  const service = new SkillsService();
  (service as unknown as { db: unknown }).db = {
    query: jest.fn(async (sql: string) => {
      if (sql.includes('character_skills')) {
        return выучены.map((id) => ({ skill_id: id }));
      }
      return [];
    }),
    queryOne: jest.fn(async () => null),
  };
  return service;
}

describe('Пассивный бонус урона «Аламы»', () => {
  it('выученные «Аламы» добавляют 15 процентов урона', async () => {
    const пусто = await сервис([]).getPassiveMultipliers('игрок');
    must(
      пусто.damage === 1 && пусто.reach === 1,
      `без навыков множители должны быть единицами, а получилось урон ${пусто.damage}, ` +
        `досягаемость ${пусто.reach}`
    );

    const сАламами = await сервис(['alams']).getPassiveMultipliers('игрок');
    must(
      Math.abs(сАламами.damage - 1.15) < 1e-9,
      `«Аламы» дают множитель урона ${сАламами.damage}: бонус должен быть 1.15, ` +
        'то есть плюс 15 процентов, а не 0.15'
    );
    must(
      Math.abs(сАламами.reach - 1.25) < 1e-9,
      `«Аламы» дают множитель досягаемости ${сАламами.reach}, а должны 1.25: ` +
        'это поле множитель, его правка не должна была его тронуть'
    );
  });

  it('пассивный бонус урона ни у кого не отнимает силы', async () => {
    // Общая защита от повторения той же ошибки на новых пассивках: любая
    // надбавка должна быть не меньше единицы, иначе игрок платит очко навыка
    // за become хуже. Проверка перебирает все навыки с пассивным уроном.
    const навыки = читать('server/src/services/SkillsService.ts');
    const найдено = [...навыки.matchAll(/passive: \{ damage: ([\d.]+)/g)].map((m) => Number(m[1]));
    must(
      найдено.length > 0,
      'не нашлось ни одного пассивного бонуса урона: проверка потеряла предмет работы'
    );
    for (const доля of найдено) {
      must(
        доля >= 0 && доля < 1,
        `пассивный бонус урона ${доля} — доля надбавки, а не множитель. ` +
          'Умножать на неё напрямую нельзя: игрок получит меньше урона, чем без навыка'
      );
    }
  });

  it('умножение идёт от единицы, а не от самой доли', () => {
    must(
      /damage \*= 1 \+ def\.passive\.damage;/.test(читать('server/src/services/SkillsService.ts')),
      'пассивный урон снова умножается напрямую на долю: «Аламы» отнимут 85% урона'
    );
    must(
      /reach \*= def\.passive\.reach;/.test(читать('server/src/services/SkillsService.ts')),
      'досягаемость пассивки перестала умножаться напрямую: это поле МНОЖИТЕЛЬ (1.25)'
    );
  });
});