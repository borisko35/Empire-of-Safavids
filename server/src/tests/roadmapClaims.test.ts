// Утверждения карты о том, что сделано, проверяются по коду.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ. Цифры в ROADMAP проверяются (roadmapNumbers.test.ts),
// а УТВЕРЖДЕНИЯ - нет. Из-за этого в карте накопились записи, которые врали:
//
//   «robots.txt + sitemap.xml. Их нет»   -> есть, отдаются продом
//   «Фильтр чата + жалобы. Фильтрации
//    нет вообще»                         -> есть, и в пути отправки
//   «2FA и жалобы в админку»             -> жалобы есть, 2FA нет
//
// Ложь в источнике истины хуже отсутствующей строки: по ней решили бы, что
// работу не сделали, и сделали бы заново поверх рабочей. Или наоборот - не
// сделали бы нужного.
//
// ЧТО ПРОВЕРЯЕТСЯ. Только те утверждения, которые можно сверить с кодом
// механически. Утверждения вида «нужен аккаунт itch.io» или «нужен скриншот
// от владельца» здесь не проверяются: их правдивость определяется не кодом, и
// проверка была бы спектаклем.
//
// ПРАВИЛО. Если утверждение перестало быть правдой - проверка краснеет и
// требует решения: либо починить код, либо исправить карту. Молча следовать
// другому варианту нельзя, иначе расхождение просто переедет.
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const карта = читать('ROADMAP.md');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/** Есть ли в исходнике кусок кода. Пустой результат - тоже ответ. */
const вКоде = (путь: string, игла: RegExp): boolean => {
  if (!existsSync(join(корень, путь))) return false;
  return игла.test(читать(путь));
};

describe('Карта не спорит с кодом', () => {
  it('фильтр чата действительно стоит в пути отправки', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Не «фильтр написан» и не «сервис есть», а
    // именно вызов в обработчике отправки сообщения. Разница огромна:
    // сервис без вызова - это код, который выглядит работающим и не
    // работает ни разу. Именно так выглядела поломка с мьютом, который
    // писался в character_mutes, а читался из базы кем-то другим.
    //
    // Утверждение карты - «фильтрации нет вообще» - было ложным, и это
    // проверяет: если фильтр уберут из пути, карта рассыплется.
    const обработчик = 'server/src/socket/GameSocketHandler.ts';
    const текстОбработчика = читать(обработчик);

    // ДЫРА, НАЙДЕННАЯ ПОЛОМКОЙ. Я искал /chatModeration\.screen\(/ - то есть
    // просто наличие ВЫЗОВА. Прогон выглядит так:
    //
    //     await this.chatModeration.screen(socket.characterId, sanitized)
    //       .catch(() => undefined);
    //     const verdict = { action: 'allow' as const, text: sanitized };
    //
    // Вызов есть, фильтр НЕ РАБОТАЕТ, результат выброшен - а проверка была
    // зелёная. Хуже: в этой поломке код ещё и не компилируется, так что
    // jest прогонялся мимо, и «Tests: 4 passed» стояло на сломанном файле.
    //
    // Правильный признак: результат вызова стоит СПРАВА от присваивания
    // verdict, и именно этот verdict решает, что уйдёт в чат.
    const присвоен = /=\s*(?:await\s+)?this\.chatModeration\.screen\(/.test(текстОбработчика);
    const вПутиОтправки = /chatModeration\.screen\(/.test(текстОбработчика);

    expect({
      // Вызов есть.
      вызывается: вПутиОтправки,
      // И его результат РЕШАЕТ, что уйдёт в чат. Без этого вызов — пустое
      // дело, а фильтр — декорация.
      результат_решает: присвоен,
      // Отказ доносится до игрока, а не глотается: игрок должен знать, что
      // его замутили, иначе он решит, что сообщения просто не доходят.
      отказ_доходит: /CHAT_MUTED/.test(текстОбработчика),
      // Текст на отправку идёт уже отфильтрованным, а не исходным.
      отправляется_отфильтрованное: /verdict\.action === 'filter' \? verdict\.text : sanitized/
        .test(текстОбработчика),
      // Карта утверждает, что фильтр есть. Если утверждение сменить на
      // «нет» - проверка заставит подтвердить это решением, а не молчанием.
      карта_утверждает_что_есть: /✅ \| C \| \*\*Фильтр чата/.test(карта),
    }).toEqual({
      вызывается: true,
      результат_решает: true,
      отказ_доходит: true,
      отправляется_отфильтрованное: true,
      карта_утверждает_что_есть: true,
    });
  });

  it('жалобы идут в очередь, а не в никуда', () => {
    // Жалоба, которую никто не читает, хуже отсутствия жалоб: игрок
    // сообщил о нарушителе и уверен, что его услышали.
    const сервис = 'server/src/services/ChatModerationService.ts';
    const админка = 'server/src/routes/admin.ts';
    const игра = 'server/src/routes/game.ts';
    expect({
      игрок_может_пожаловаться: вКоде(игра, /fileReport\(/),
      админ_может_прочитать: вКоде(админка, /listReports\(/),
      запись_есть: вКоде(сервис, /channel\s*=\s*'report'|channel = 'report'/)
        || вКоде(сервис, /report/),
      карта_не_обещает_лишнего: !/2FA и жалобы в админку/.test(карта),
    }).toEqual({
      игрок_может_пожаловаться: true,
      админ_может_прочитать: true,
      запись_есть: true,
      // Запись про 2FA и жалобы была ложной вдвойне: жалобы есть, 2FA нет.
      // Слово «2FA» рядом с «жалобы в админку» обязано исчезнуть.
      карта_не_обещает_лишнего: true,
    });
  });

  it('файлы для поисковиков на месте и описаны в карте как сделанные', () => {
    // Вторая ложная запись. Файлы сделаны коммитом c35d643.
    const есть = ['robots.txt', 'sitemap.xml'].every(f => existsSync(join(корень, 'client/web', f)));
    must(есть, 'robots.txt или sitemap.xml отсутствуют - карта права, чинить код');
    expect({
      на_месте: есть,
      карта_говорит_что_сделано: /✅ \| A \| \*\*`robots\.txt` \+ `sitemap\.xml`/.test(карта),
    }).toEqual({ на_месте: true, карта_говорит_что_сделано: true });
  });
});

describe('Утверждения, которые проверяются не кодом, помечены', () => {
  it('в карте есть пометка о непроверяемом', () => {
    // Иначе кто-то решит, что все ⬜ это код, и возьмётся делать то, что
    // кодом не делается. Например «аккаунты на itch.io» - это не задача
    // программиста, и попытка «сделать» её кончится выдуманной интеграцией.
    const помечено = /⚠️|нужен|нужны|кодом|владел/i.test(карта);
    expect({ помечено }).toEqual({ помечено: true });
  });
});
