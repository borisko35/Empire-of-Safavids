// Мостовая мира: дорога не должна быть светлее песка вокруг.
//
// ЧТО БЫЛО (21 октября 2026, §248). Полотно грунтовой дороги было светлее
// земли, и на песке читалось как вырезанная из мира белая лента. Город после
// §230 стал тёмнее и тише, и дорога из него выбивалась ещё сильнее.
//
// ЧТО ТЕПЕРЬ. Песчаная дорога — тот же тёплый песок, чуть темнее, с колеями.
//
// ЧТО ПРОВЕРЯЕТСЯ. Цвета полотна заданы числами: иначе «дорога посветлее
// песка» вернётся правкой одного символа, и заметят это только по кадру.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Мостовая мира', () => {
  it('песчаная дорога не светлее песка', () => {
    const свет = /const light = stone \? '#[0-9a-f]{6}' : '#([0-9a-f]{6})';/.exec(ТЕРРЕЙН);
    должен(свет, 'не найден цвет полотна грунтовой дороги');
    // 0xc6a670 — тёплый песок, темнее прежнего #d9b87e.
    должен(
      свет[1] === 'c6a670',
      `полотно дороги светлее песка (${свет[1]}): на песке это белая лента`,
    );
    // И обочина темнее середины — иначе края дороги светлее земли.
    const темно = /const dark = stone \? '#[0-9a-f]{6}' : '#([0-9a-f]{6})';/.exec(ТЕРРЕЙН);
    должен(темно, 'не найден цвет обочины');
    const s = parseInt(свет[1], 16);
    const d = parseInt(темно![1], 16);
    должен(s > d, 'обочина не темнее середины полотна: края дороги светлее земли');
  });
});
