// Городские фонари: стеклянный фонарь с огнём, а не пустая чаша.
//
// ЧТО БЫЛО (21 октября 2026, §232). Фонарь был столбом с золотой чашей:
// днём она читалась как золотая миска на палке, а ночью источник света
// горел НАД чашей в воздухе — фонаря не было вовсе.
//
// ЧТО ТЕПЕРЬ. Под чашей стеклянный фонарь с огнём внутри, и источник света
// оказывается ВНУТРИ фонаря.
//
// ЧТО ПРОВЕРЯЕТСЯ. Три вещи: у фонаря есть стекло и огонь, свет стоит по
// высоте огня (а не над чашей), и оба места — город и кварталы — берут одну
// и ту же функцию.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Городские фонари', () => {
  it('у фонаря есть стекло, огонь и колпак', () => {
    должен(/function фонарь\(/.test(код), 'нет функции фонаря');
    const блок = /function фонарь\([\s\S]*?\n}\n/.exec(код);
    должен(блок, 'не разобрался фонарь');
    const тело = блок![0];
    должен(/const стекло = new THREE\.Mesh/.test(тело), 'у фонаря нет стекла');
    должен(
      /const огонь = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.22, 8, 6\), MAT\.lampGlow\)/.test(тело),
      'у фонаря нет огня: чаша остаётся пустой',
    );
    должен(/колпак/.test(тело), 'у фонаря нет колпака: он не заканчивается');
    должен(/lampGlow:\s*new THREE\.MeshStandardMaterial/.test(код), 'нет материала огня фонаря');
  });

  it('свет стоит по высоте огня, а не над чашей', () => {
    // Прежде источник света висел в воздухе над чашей: фонаря не было, был
    // только столб с миской.
    должен(
      /lights\.push\(\{ x: CITY\.x \+ x, z: CITY\.z \+ z, y: city\.position\.y \+ высотаОгня \}\)/.test(код),
      'свет фонаря снова висит над чашей: источник не в фонаре',
    );
    должен(/return 5\.2;/.test(код), 'фонарь не возвращает высоту огня: свет некуда поставить');
  });

  it('город и кварталы ставят один и тот же фонарь', () => {
    // С §328 проспекты тоже берут общую функцию: до этого у них была своя
    // палка с чашей, и правка фонаря до них не доходила.
    const вызовы = (код.match(/фонарь\(/g) || []).length;
    должен(вызовы >= 3, `вызовов фонаря ${вызовы}: город и кварталы разошлись`);
  });
});
