// Обнаружение стражем: правило живое и связано с обеими сторонами.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ЭТОЙ ПРОВЕРКИ. У NPC на сервере не было обнаружения
// вообще: ноль совпадений по пяти признакам - дистанция до игрока, aggro у
// NPC, преследование, npcTarget, серверный поток действий NPC. Приседание
// при этом было и работало (клавиша C и Ctrl в world3d.ts). То есть
// погасить было нечего: правила скрытности без обнаружения - поле без
// потребителя.
//
// ПОЧЕМУ ПРОВЕРКА СЧИТАЕТ ЧИСЛА, А НЕ ИЩЕТ СТРОКУ. Поиск строки
// "spottedBy" доказал бы, что строка есть, и ничего больше: радиус можно
// испортить числом в другом месте, и проверка осталась бы зелёной. Здесь
// функция вызывается по-настоящему, а утверждения - про расстояния.
//
// ПОЧЕМУ ПРОВЕРКА СВЕРЯЕТ КОПИИ. Посты стражей в shared/stealth.ts сложены из
// координат поселений (client/src/app/game3d/terrain.ts) и смещений NPC
// (client/src/app/game3d/npc.ts). Это две копии одного факта, и ровно на этом
// уже разъехались двери интерьеров: координаты комнат жили в двух списках, и
// кнопка перехода существовала, а ничего не происходило. Если клиентскую
// сторону переставят - эта проверка упадёт по имени.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { GUARD_POSTS, GUARD_SIGHT, canSee, distanceSq, spottedBy, type GuardPost } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Обнаружение: правило действительно замечает игрока', () => {
  // Исходное состояние объявляется числами, а не проверкой «функция есть».
  // Молчаливый ноль здесь означал бы ровно то, что мы чиним: правило есть,
  // а не замечает никого.
  it('в базе есть посты, и это не пустой список', () => {
    must(GUARD_POSTS.length > 0, 'GUARD_POSTS пуст - стражей нет, правилу нечего замечать');
    // Больше одного: если постов станет один, проверка расстояний ниже
    // начнёт проверять одно и то же и замолчит.
    must(GUARD_POSTS.length >= 3, 'постов меньше трёх: проверке нечем обучаться, ожидалось 3 стража');
  });

  it('радиус обнаружения равен 20 - числу из базы монстров', () => {
    // 20 - самая частая дальность обнаружения в игре (из 40 монстров: 20
    // встречается 7 раз, 18 - 7 раз, среднее 20.3). Взято оттуда, чтобы
    // стелс попал в существующий баланс, а не вводил свой.
    // Сравнение идёт через Number(). При прямом GUARD_SIGHT === 20 тип
    // сужается до литерального 12, и TypeScript выдаёт TS2367 «нет
    // пересечения» - то есть ломка радиуса падала бы компиляцией, а не
    // тестом. Запрещено: доказательством считается только упавший по
    // имени тест. Number() убирает сужение, и неверный радиус роняет
    // утверждение ниже.
    must(Number(GUARD_SIGHT) === 20, `ожидался радиус 20, а в коде ${GUARD_SIGHT}`);
    for (const post of GUARD_POSTS) {
      must(
        Number(post.sight) === 20,
        `у стража ${post.id} радиус ${post.sight}, а не 20: стражи должны видеть одинаково`
      );
    }
  });

  it('страж замечает игрока на 19 единицах и НЕ замечает на 21', () => {
    const стража = GUARD_POSTS[0];

    // Ровно на посту - замечает. Это ненулевая исходная точка: без неё
    // проверка «не заметил на 21» прошла бы и при полностью сломанной
    // функции, которая всегда возвращает false.
    const наПосту = spottedBy({ x: стража.x, z: стража.z });
    must(наПосту !== null, 'страж не заметил игрока, стоящего вплотную: правило мертво');
    must(наПосту.id === стража.id, `на посту ожидался ${стража.id}, а заметил ${наПосту?.id}`);

    // 19 - внутри радиуса, 21 - снаружи. Проверка идёт по числам, поэтому
    // сломанное правило (например, с жёстким > вместо <=) её уронит.
    const ближко: GuardPost = { ...стража, x: стража.x + 19, z: стража.z };
    const далеко: GuardPost = { ...стража, x: стража.x + 21, z: стража.z };

    must(canSee({ x: ближко.x, z: ближко.z }, стража), 'на 19 единицах должен видеть');
    must(!canSee({ x: далеко.x, z: далеко.z }, стража), 'на 21 единице не должен видеть');

    // То же самое через публичную функцию, а не только через canSee:
    // вызывающий код пользуется именно ей.
    must(spottedBy({ x: ближко.x, z: ближко.z }, [стража]) !== null, 'spottedBy молчит на 19 единицах');
    must(spottedBy({ x: далеко.x, z: далеко.z }, [стража]) === null, 'spottedBy ловит на 21 единице');
  });

  it('сравнение идёт по квадрату расстояния, а граница включена', () => {
    const стража = GUARD_POSTS[0];
    // 20^2 = 400. Ровно на границе - заметил (сравнение <=).
    must(distanceSq({ x: стража.x + 20, z: стража.z }, стража) === 400, 'квадрат расстояния считается неверно');
    must(canSee({ x: стража.x + 20, z: стража.z }, стража), 'на ровно 20 единицах должен видеть: граница включена');
    must(!canSee({ x: стража.x + 20.5, z: стража.z }, стража), 'чуть за границей не должен видеть');
  });

  it('поле зрения стража не зависит от порядка постов', () => {
    const стража = GUARD_POSTS[0];
    const посты = GUARD_POSTS as readonly GuardPost[];
    const прямой = spottedBy({ x: стража.x + 5, z: стража.z }, посты);
    const перевёрнутый = spottedBy({ x: стража.x + 5, z: стража.z }, [...посты].reverse());
    // Игрока рядом со стражем должен заметить кто-то в обоих порядках.
    must(прямой !== null, 'в прямом порядке не заметил');
    must(перевёрнутый !== null, 'в перевёрнутом порядке не заметил: результат зависит от порядка обхода');
  });

  it('в стороне от всех стражей не замечает никто', () => {
    // Точка далеко от постов: сараван (505,55), порт (-225,-150), форт
    // (-320,-705). (0,0) - начало координат, в стороне от всех.
    must(spottedBy({ x: 0, z: 0 }) === null, 'в начале координат кто-то заметил игрока: радиус слишком велик');
  });
});

describe('Обнаружение: посты совпадают с живыми NPC на клиенте', () => {
  // Координаты в shared/stealth.ts сложены вручную: origin поселения плюс
  // смещение NPC. Это две копии одного факта, и ровно на этом разъехались
  // двери. Если кто-то переставит NPC на клиенте, эта проверка упадёт.
  it('каждый пост стоит там, где стоит его NPC в NPC_GROUPS', () => {
    const terrain = читать('client/src/app/game3d/terrain.ts');
    const npc = читать('client/src/app/game3d/npc.ts');

    must(npc.length > 1000, 'npc.ts не прочитан: проверка молча прошла бы вхолостую');
    must(terrain.length > 1000, 'terrain.ts не прочитан: проверка молча прошла бы вхолостую');

    for (const post of GUARD_POSTS) {
      // 1. NPC с таким id есть в NPC_GROUPS.
      const строкаNpc = npc.split('\n').find((l) => l.includes(`id: '${post.id}'`));
      must(строкаNpc !== undefined, `NPC ${post.id} не найден в NPC_GROUPS - пост в shared/ остался бы висящим`);

      // 2. У него есть смещения dx/dz.
      const dx = /dx:\s*(-?\d+(?:\.\d+)?)/.exec(строкаNpc!);
      const dz = /dz:\s*(-?\d+(?:\.\d+)?)/.exec(строкаNpc!);
      must(dx !== null, `у ${post.id} нет dx в NPC_GROUPS`);
      must(dz !== null, `у ${post.id} нет dz в NPC_GROUPS`);

      // 3. Origin его группы есть в terrain.ts. Ищем строку с именем
      //    поселения прямо перед блоком группы: проще - по факту наличия
      //    самого поселения и добираем его координаты отдельным поиском.
      const origin = найтиOrigin(terrain, post.id, npc);
      must(origin !== null, `не удалось определить поселение группы, где стоит ${post.id}`);

      // 4. Сумма должна совпасть с постом в shared.
      const ожидаемыйX = origin!.x + Number(dx![1]);
      const ожидаемыйZ = origin!.z + Number(dz![1]);
      must(
        post.x === ожидаемыйX && post.z === ожидаемыйZ,
        `пост ${post.id} стоит в (${post.x},${post.z}), а NPC_GROUPS даёт ` +
          `(${ожидаемыйX},${ожидаемыйZ}) - копии разъехались, как разъехались двери`
      );
    }
  });
});

/**
 * Поселение группы, в которой стоит NPC с id.
 *
 * Ищет НАЗАД от строки NPC первую встретившуюся `origin:` и берёт её
 * координаты из terrain.ts. Возвращает null, если проследить не удалось:
 * молчаливый ноль здесь означал бы, что проверка ничего не сравнила.
 *
 * ПОЧЕМУ БЕЗ ОГРАНИЧЕНИЯ РАССТОЯНИЯ. Первая версия смотрела вверх ровно
 * 8 строк. Этого хватало, пока у самых дальних NPC группа была рядом, и
 * перестало хватать, когда в столице добавился привратник: он на 10-й строке
 * от `origin: CITY`. Поиск «до первой origin:» семантически правильнее
 * фиксированного окна: группа объявлена ровно один раз, и следующая origin
 * за спиной - это уже другая группа.
 */
function найтиOrigin(terrain: string, npcId: string, npc: string): { x: number; z: number } | null {
  const строки = npc.split('\n');
  const индекс = строки.findIndex((l) => l.includes(`id: '${npcId}'`));
  if (индекс < 0) return null;

  let имя: string | null = null;
  for (let i = индекс - 1; i >= 0; i--) {
    const найдено = /origin:\s*([A-Z_]+)/.exec(строки[i]);
    if (найдено) {
      имя = найдено[1];
      break;
    }
  }
  if (имя === null) return null;

  const объявление = new RegExp(
    `export const ${имя}\\s*=\\s*\\{\\s*x:\\s*(-?\\d+(?:\\.\\d+)?)\\s*,\\s*z:\\s*(-?\\d+(?:\\.\\d+)?)`
  ).exec(terrain);
  if (объявление === null) return null;

  return { x: Number(объявление[1]), z: Number(объявление[2]) };
}

describe('Обнаружение: правило действительно вызывается', () => {
  // Правило без вызова - мёртвое поле: выглядит как работа, ничего не делает.
  // Поэтому проверяется не только функция, но и то, что сервер её зовёт,
  // а клиент слушает то, что сервер шлёт.
  it('сервер считает обнаружение в потоке движения и шлёт событие', () => {
    const socket = читать('server/src/socket/GameSocketHandler.ts');
    must(socket.length > 1000, 'GameSocketHandler.ts не прочитан');

    // Шаг 2 добавил в вызов контекст скрытности, поэтому строка стала
    // spottedBy(data.position, GUARD_POSTS, {...}). Проверка обновлена под
    // новую сигнатуру, но смысл прежний: правило вызывается в потоке
    // движения по позиции из пакета. Совпадение по data.position обязательно
    // - вызов с другой позицией был бы подменой.
    must(
      /spottedBy\(\s*data\.position/.test(socket),
      'сервер не вызывает spottedBy по позиции из пакета движения: правило есть, вызова нет'
    );
    must(
      /GUARD_SPOTTED/.test(socket),
      'сервер не шлёт GUARD_SPOTTED: клиенту нечего показывать'
    );
    // Состояние должно запоминаться, иначе событие уходит на каждом пакете
    // движения - десятки раз в секунду.
    must(
      /spottedGuards\.set/.test(socket),
      'состояние обнаружения не запоминается: событие будет слаться спамом'
    );
  });

  it('клиент слушает именно то событие, что шлёт сервер', () => {
    const world = читать('client/src/app/world.ts');
    const константы = читать('shared/constants.ts');
    must(world.length > 1000, 'world.ts не прочитан');

    must(
      /socket\.on\('guard:spotted'/.test(world),
      'клиент не слушает guard:spotted - серверное событие умирает в пустоту'
    );
    // Имя события обязано совпадать в обоих файлах, иначе это две строки,
    // которые выглядят связанными, а не связаны.
    const вКонстантах = /GUARD_SPOTTED:\s*'guard:spotted'/.test(константы);
    must(вКонстантах, "в shared/constants.ts нет GUARD_SPOTTED со значением 'guard:spotted'");
  });

  it('клиентский tsconfig собирает shared/stealth.ts', () => {
    // Файл в shared/, но клиент включает в сборку только три файла оттуда.
    // Если новый модуль не вписан, клиент не сможет импортировать правило -
    // и через несколько итераций обнаружение посчитает только сервер.
    const tsconfig = читать('client/tsconfig.json');
    must(tsconfig.length > 100, 'client/tsconfig.json не прочитан');
    must(
      tsconfig.includes('shared/stealth.ts'),
      'shared/stealth.ts не вписан в client/tsconfig.json: клиент его не увидит'
    );
  });

  it('слово spotted есть в трёх словарях', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = читать(`shared/locales/${код}.json`);
      must(словарь.length > 1000, `${код}.json не прочитан`);
      const ключ = /"stealth"\s*:\s*\{[^}]*"spotted"\s*:/.test(словарь);
      must(ключ, `в ${код}.json нет ключа stealth.spotted: игрок увидит путь ключа вместо текста`);
    }
  });
});