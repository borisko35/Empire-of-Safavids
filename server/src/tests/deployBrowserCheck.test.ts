// Выкатка должна проверять сайт так, как его спрашивает браузер.
//
// ЧТО СЛОМАЛОСЬ 15.10.2026. Главный бандл подключается в index.html как
// `<script crossorigin>`. Атрибут crossorigin заставляет браузер отправить
// заголовок Origin — а Cloudflare кэширует отрицательный ответ ОТДЕЛЬНО для
// запросов с этим заголовком. Выкатка спрашивала файл без Origin, получала
// закэшированную 200, объявляла RESULT: PASS — и игроки тем временем получали
// 404 (страница nginx, 1040 байт, cf-cache-status HIT, age больше часа).
// Игра не грузилась вовсе: без главного бандла нет ни переводов интерфейса,
// ни обработчиков формы входа. Контейнер при этом был здоров: nginx отдавал
// тот же файл с кодом 200 и полным телом и с Origin, и без.
//
// ПОЧЕМУ ЭТО БЫЛО НЕВИДИМО. Проверка «все файлы страницы доступны» существует
// в deploy.sh именно для этой поломки и описана в её комментариях — но curl в
// ней шёл без Origin, то есть проверка смотрела не на тот запрос, который
// делает браузер.
//
// ЭТА ПРОВЕРКА сторожит не «наличие curl», а САМО РАСХОЖДЕНИЕ: каждая сетевая
// проверка ассетов в deploy.sh обязана слать Origin. Появится новый curl без
// него — проверка упадёт и назовёт строку.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const DEPLOY = 'tools/deploy.sh';

describe('Выкатка спрашивает сайт так же, как браузер', () => {
  const код = readFileSync(join(корень, DEPLOY), 'utf8');

  it('заголовок Origin вообще объявлен', () => {
    must(/ORIGIN_HDR=/.test(код),
      'в deploy.sh нет ORIGIN_HDR: проверки сайта спрашивают без заголовка Origin, ' +
      'который браузер шлёт из-за crossorigin — и 404 на стороне игрока для них невидим');
  });

  it('Origin уходит до первой сетевой проверки', () => {
    const объявление = код.indexOf('ORIGIN_HDR=');
    const перваяПроверка = Math.min(
      ...['hash_served()', 'INDEX_HTML=', 'curl -fsS -o /dev/null']
        .map((я) => код.indexOf(я))
        .filter((i) => i >= 0),
    );
    must(объявление >= 0 && объявление < перваяПроверка,
      `ORIGIN_HDR объявлен на позиции ${объявление}, а первая проверка — на ${перваяПроверка}: ` +
      'переменная использовалась бы раньше, чем задана');
  });

  it('каждая сетевая проверка ассетов шлёт Origin', () => {
    // Строки, которые реально ходят в сеть за ассетами игры.
    const строки = код.split(/\r?\n/);
    const проверки = строки
      .map((л, i) => ({ л, i: i + 1 }))
      .filter(({ л }) => /curl -fsS/.test(л)
        && !/^\s*#/.test(л.trim())
        // api.ipify.org — внешний сервис определения адреса, не ассет игры.
        && !/api\.ipify\.org/.test(л));

    must(проверки.length >= 4,
      `найдено только ${проверки.length} сетевых проверок ассетов, ожидалось не меньше четырёх: ` +
      'похоже, проверки перестали существовать, а не потеряли заголовок');

    const безOrigin = проверки.filter(({ л }) => !/Origin/.test(л));
    must(безOrigin.length === 0,
      'эти проверки идут в сеть без заголовка Origin, то есть не видят того 404, ' +
      'который получает браузер:\n'
      + безOrigin.map(({ л, i }) => `  строка ${i}: ${л.trim()}`).join('\n'));
  });
});