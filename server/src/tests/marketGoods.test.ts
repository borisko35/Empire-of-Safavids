// Рынок: товар должен быть виден с улицы.
//
// ЧТО БЫЛО (21 октября 2026, §237). Лавки стояли под навесами, и товар на
// них тонул в тени навеса: с улицы читался пустой тёмный стол. Рынка не
// было — были пустые прилавки под навесами.
//
// ЧТО ТЕПЕРЬ. На переднем крае прилавка — полотнище цвета навеса (лавка
// видна издали даже в тени), горшки светлые и с крышками, на ящиках — свитки
// ткани, по краям — мешки.
//
// ЧТО ПРОВЕРЯЕТСЯ. Три вещи: полотнище есть, горшки светлые, мешки стоят.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Рынок', () => {
  it('на прилавке есть полотнище цвета навеса', () => {
    // Без полотнища лавка в тени навеса читается пустым тёмным столом.
    должен(
      /const полотнище = new THREE\.Mesh\(\s*new THREE\.BoxGeometry\(3\.02, 0\.72, 0\.06\),\s*canopies\[kind % 3\],?\s*\)/.test(
        код,
      ),
      'на прилавке нет полотнища: лавка читается пустой',
    );
    // С 22 октября 2026 (§290) высота полотнища другая: столешница стала
    // тонкой и поднялась на ножки.
    должен(
      /полотнище\.position\.set\(0, [\d.]+, 0\.83\)/.test(код),
      'полотнище висит не на переднем крае прилавка',
    );
  });

  it('горшки светлые и с крышками', () => {
    // Тёмный горшок в тени навеса не читался вовсе.
    // С 22 октября 2026 (§290) кувшин гончарный: тело вращением профиля,
    // горло и ручка — вместо цилиндра с крышкой.
    должен(
      /const кувшин = new THREE\.Mesh\(new THREE\.LatheGeometry\(профиль, 9\), MAT\.sandstone\)/.test(
        код,
      ),
      'горшки на лавке снова тёмные: их не видно в тени',
    );
    должен(/горло\.position\.set\(/.test(код), 'у кувшинов нет горла: сверху они читаются обручем');
    должен(/ручка\.position\.set\(/.test(код), 'у кувшинов нет ручки');
  });

  it('у лавки стоят мешки, а на ящиках — свитки', () => {
    должен(
      /const мешок = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.34, 8, 6\), MAT\.sand\)/.test(код),
      'у лавки нет мешков: прилавок выглядит пустым',
    );
    должен(/const свиток = new THREE\.Mesh/.test(код), 'на ящиках нет свитков ткани');
  });
});
