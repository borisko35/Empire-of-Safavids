// Выбор класса: живые 3D-превью вместо плоских спрайтов.
//
// ЧТО БЫЛО. Карточки классов показывали пиксельные спрайты 36x36, а в игре
// персонаж — настоящая 3D-модель. Выбор выглядел другой игрой.
//
// ЧТО ПРОВЕРЯЕТСЯ. Карточки строят canvas с живым превью (модель класса,
// честное оружие, медленный круг, idle-анимация), а не img; превью
// останавливаются при уходе с экрана (иначе пять GL-контекстов уезжали бы
// в игру); модель без rig не даёт пустую карточку — встаёт спрайт;
// setWeaponKind пересобирает оружие, иначе все классы показывали бы меч.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ЭКРАН = читать('client/src/app/screens/chars.ts');
const ПРЕВЬЮ = читать('client/src/app/screens/classPreview.ts');
const РИГ = читать('client/src/app/game3d/realRig.ts');
const СТИЛИ = читать('client/src/app/styles.css');

describe('Выбор класса: живые 3D-превью', () => {
  it('карточки классов строят canvas с превью, а не картинку', () => {
    must(
      /from '\.\/classPreview'/.test(ЭКРАН),
      'экран выбора не импортирует classPreview: карточки снова на спрайтах',
    );
    must(
      /attachClassPreview\(canvas, id\)/.test(ЭКРАН),
      'выбор класса не вешает превью на карточку',
    );
    must(
      /document\.createElement\('canvas'\)/.test(ЭКРАН),
      'в карточке класса нет canvas: рисовать превью некуда',
    );
    must(
      /canvas\.replaceWith\(img\)/.test(ЭКРАН),
      'нет запаса на спрайт: если модель не загрузилась, карточка останется пустой тёмной',
    );
  });

  it('превью останавливаются при уходе с экрана', () => {
    // Пять живых GL-контекстов плюс игровой — и тикающий цикл поверх игры.
    // Останавливать надо везде, откуда уходят: вход новым, вход готовым,
    // выход из аккаунта и повторный показ экрана. Считаются вызовы на
    // экране выбора, а не определение в модуле превью.
    const вызовы = (ЭКРАН.match(/stopClassPreviews\(\)/g) || []).length;
    must(
      вызовы >= 4,
      `stopClassPreviews вызывается ${вызовы} раз, а уходов с экрана четыре: вход новым, вход готовым, выход, повторный показ`,
    );
    must(
      /cancelAnimationFrame\(цикл\)/.test(ПРЕВЬЮ),
      'цикл превью не останавливается: модели крутятся поверх игры',
    );
    must(
      /п\.rig\.dispose\(\)/.test(ПРЕВЬЮ) && /п\.renderer\.dispose\(\)/.test(ПРЕВЬЮ),
      'превью не освобождает риг и рендер: GL-контексты текут при каждом показе экрана',
    );
  });

  it('цикл один на все превью, а не пять', () => {
    // Пять requestAnimationFrame — пять тикающих циклов на пять карточек.
    must(
      /if \(цикл !== null\) return;/.test(ПРЕВЬЮ),
      'нет защиты от повторного запуска цикла: каждый attach плодит свой',
    );
    must(
      /п\.rig\.group\.rotation\.y \+=/.test(ПРЕВЬЮ),
      'модель не крутится: превью статично, и это снова картинка, только дороже',
    );
    must(
      /moving: false/.test(ПРЕВЬЮ),
      'поза превью не idle: модель идёт или лежит вместо того, чтобы стоять',
    );
  });

  it('у каждого класса честное оружие и щит только у кизылбаша', () => {
    // Без карты оружия превью показывало бы меч всем: мистик с мечом,
    // лучник с мечом. Карта сверяется дословно — расхождение означает,
    // что превью врёт про класс.
    const карта = /export const CLASS_WEAPON: Record<string, Weapon> = \{([^}]*)\}/.exec(ПРЕВЬЮ)?.[1];
    must(карта !== undefined, 'не нашли CLASS_WEAPON: оружие классов неизвестно откуда');
    const пары: Record<string, string> = {};
    for (const м of (карта as string).matchAll(/(\w+): '(\w+)'/g)) пары[м[1]] = м[2];
    const честно: Record<string, string> = {
      qizilbash: 'sword', sufi_mystic: 'staff', persian_archer: 'bow',
      bazaar_merchant: 'dagger', court_diplomat: 'rapier',
    };
    for (const [класс, оружие] of Object.entries(честно)) {
      must(
        пары[класс] === оружие,
        `у класса ${класс} в превью ${пары[класс] ?? 'нет оружия'}, а воюет он с ${оружие}`,
      );
    }
    must(
      /classHasShield\(classId: string\): boolean \{\s*\r?\n\s*return classId === 'qizilbash';/.test(ПРЕВЬЮ),
      'щит дают не только кизылбашу: в игре щит только у него',
    );
    must(
      /classShowsWeapon\(classId: string\): boolean \{\s*\r?\n\s*return classId !== 'sufi_mystic';/.test(ПРЕВЬЮ),
      'мистику показывают оружие: в игре он воюет без него, превью врёт',
    );
  });

  it('смена вида оружия пересобирает меш, а не молчит', () => {
    // Вид оружия в риге захардкожен мечом. Без пересборки setWeaponKind
    // менял бы поле, а в руке оставался бы меч — проверка ловит именно это.
    must(
      /setWeaponKind\(kind: Weapon\): void/.test(РИГ),
      'в RealRig нет setWeaponKind: вид оружия не сменить',
    );
    must(
      /this\.оружие\.removeFromParent\(\);/.test(РИГ),
      'старый меш оружия не снимается: в руке останется меч при любом виде',
    );
    must(
      /this\.оружие = null;/.test(РИГ),
      'поле оружия не сбрасывается: equipWeapon не соберёт новый меш',
    );
  });

  it('карточка под 3D: canvas 120x140, а не 36 пикселей', () => {
    // Без стилей canvas встанет 300x150 по умолчанию и разорвёт сетку.
    must(
      /\.class-option canvas\.class-preview \{/.test(СТИЛИ),
      'нет стиля превью карточки: canvas ляжет как попало',
    );
    must(
      /width: 120px;/.test(СТИЛИ) && /height: 140px;/.test(СТИЛИ),
      'размер превью не 120x140: модель либо мелкая, либо рвёт карточку',
    );
  });
});
