// Оазис перестаёт быть пустым местом с пальмами.
//
// ЧТО БЫЛО (22 октября 2026, §307). Оазис был пустым: пальмы у пруда в
// пустыне. Жить тут было нечем — ни источника, ни горшков, ни стенки
// цистерны, ни кустарника.
//
// ЧТО ТЕПЕРЬ. Каменный источник с жёлобом и струёй, девять глиняных горшков
// у берега, круглая стенка цистерны из двадцати двух камней и кустарник по
// кромке.
//
// ЧТО ПРОВЕРЯЕТСЯ. Источник, жёлоб и струя есть; горшки стоят у берега
// (девять штук, с горлом); стенка цистерны кольцом; кустарник по кромке.
// Проверки счёта ищут ЦИКЛЫ ВНУТРИ блока оазиса: такой же цикл есть и у
// цветов, и проверка «где-нибудь в файле» была бы враньём.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Оазис — место, где живут', () => {
  it('источник: каменный круг, жёлоб и струя', () => {
    должен(
      /const круг = new THREE\.Mesh\(new THREE\.CylinderGeometry\(1\.5, 1\.7, 0\.5, 12\), MAT\.sandstone\);/.test(ТЕРРЕЙН),
      'у источника нет каменного круга',
    );
    должен(
      /const жёлоб = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.8, 0\.4, 0\.7\), MAT\.sandstoneDark\);/.test(ТЕРРЕЙН),
      'у источника нет жёлоба',
    );
    // Струя — вода: полупрозрачная и голубая.
    должен(
      /const струя = new THREE\.Mesh\(\s*new THREE\.CylinderGeometry\(0\.07, 0\.1, 0\.85, 7\),\s*new THREE\.MeshStandardMaterial\(\{ color: 0x9fd4e0, roughness: 0\.15, transparent: true, opacity: 0\.75 \}\),/.test(ТЕРРЕЙН),
      'у источника нет струи воды',
    );
  });

  it('глиняные горшки у берега, с горлом', () => {
    // Девять горшков — цикл внутри блока оазиса.
    должен(
      /const ox = POND\.x[\s\S]{0,4000}?for \(let i = 0; i < 9; i\+\+\) \{/.test(ТЕРРЕЙН),
      'горшков не девять',
    );
    должен(
      /const горшок = new THREE\.Mesh\(\s*new THREE\.CylinderGeometry\(0\.24 \* k, 0\.34 \* k, 0\.72 \* k, 9\),/.test(ТЕРРЕЙН),
      'горшки не глиняные',
    );
    // У горшка есть горло — иначе это просто конус.
    должен(
      /const горло = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.14 \* k, 0\.2 \* k, 0\.14 \* k, 9\), MAT\.sandstoneDark\);/.test(ТЕРРЕЙН),
      'у горшков нет горла',
    );
  });

  it('стенка цистерны кольцом и кустарник по кромке', () => {
    // Двадцать два камня по кольцу — цикл внутри блока оазиса.
    должен(
      /const ox = POND\.x[\s\S]{0,8000}?for \(let i = 0; i < 22; i\+\+\) \{/.test(ТЕРРЕЙН),
      'камней цистерны не двадцать два',
    );
    должен(
      /const камень = new THREE\.Mesh\(new THREE\.BoxGeometry\(2\.4, 1\.1, 0\.7\), MAT\.sandstone\);/.test(ТЕРРЕЙН),
      'стенка цистерны — не камни',
    );
    // Кустарник по кромке оазиса.
    должен(
      /const ox = POND\.x[\s\S]{0,12000}?for \(let i = 0; i < 26; i\+\+\) \{/.test(ТЕРРЕЙН),
      'кустарника по кромке нет',
    );
    должен(/куст\(scene, px, pz, groundHeight\(px, pz\), 1 \+ \(i % 3\) \* 0\.2\);/.test(ТЕРРЕЙН),
      'кустарник не поставлен по кромке оазиса');
  });
});
