// Живые последствия, кусок 1 (§359): NPC помнят вора.
//
// ЗА ЧТО БОРЕТСЯ. Владелец назвал пример живого последствия прямо: «стража,
// NPC перестают говорить». Крамольное было в том, что тон дружбы и так
// существовал, но реплику не менял — мир помнил только цифру. Попытка
// обокрасть торговца, пойманная им за руку, ничем не отличалась от первой
// встречи: то же «привет», тот же квест.
//
// ЧТО ТЕПЕРЬ. Цель, ВИДЕВШАЯ попытку (reason 'seen' — проверка взгляда
// сработала), запоминает вора в своей памяти: счётчик theftsSeen, каноничная
// заметка. Диалог с таким NPC больше не открывается — один упрёк, закрыть.
// Удачная кража памяти не двигает: жертва ни о чём не знает, и мир не
// реагирует на то, чего не видел.
//
// ПОЧЕМУ ТОН ПРОВЕРЯЕТСЯ ПОВЕДЕНЬЕМ, А МАРШРУТ — ИСХОДНИКОМ. toneByFriendship —
// чистая функция: её можно вызвать. Маршрут обвешан await'ами Redis — его
// честно проверяет только разбор живого кода, включая ПОРЯДОК проверок:
// обида обязана стоять раньше дружеского приветствия, иначе «привет, друг!»
// перебивал бы упрёк.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { toneByFriendship } from '../services/NpcMemoryService';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Тон: обида сильнее дружбы', () => {
  it('видевший кражу NPC враждебен даже лучшему другу', () => {
    must(toneByFriendship(5, [], 1) === 'hostile', 'друг с пятёркой дружбы не враждебен после кражи');
    must(toneByFriendship(0, [], 3) === 'hostile', 'счётчик краж не делает тон враждебным');
  });

  it('без краж тон считается по-старому', () => {
    must(toneByFriendship(0, []) === 'neutral', 'нейтральная память стала враждебной без причины');
    must(toneByFriendship(5, []) === 'friendly', 'дружба без краж сломалась');
    must(toneByFriendship(0, ['он предал меня']) === 'hostile', 'старое правило нот перестало работать');
    must(toneByFriendship(3, [], 0) === 'friendly', 'нулевой счётчик краж ведёт себя как отсутствие поля: старые записи памяти не должны внезапно враждовать');
  });
});

describe('Память: запись обиды', () => {
  const сервис = читать('server/src/services/NpcMemoryService.ts');

  it('rememberTheft растит счётчик, ставит время и пишет каноничную заметку', () => {
    must(/memory\.theftsSeen = \(memory\.theftsSeen \?\? 0\) \+ 1;/.test(сервис),
      'счётчик краж не растёт: одна попытка ничем не отличается от десяти');
    must(/memory\.lastTheftSeenAt = now;/.test(сервис),
      'время попытки не записывается: когда обидел — неизвестно');
    must(/пытался обчистить мои карманы/.test(сервис),
      'каноничной заметки нет: диалоговая подсказка осталась без живого текста');
    const метод = сервис.slice(сервис.indexOf('async rememberTheft'), сервис.indexOf('async addNote'));
    must(/await this\.saveMemory/.test(метод),
      'обида не сохраняется в память');
  });

  it('дефолт памяти не враждебен', () => {
    must(/theftsSeen: 0,\s*\n\s*lastTheftSeenAt: 0,/.test(сервис),
      'дефолт памяти без счётчика: свежий NPC(undefined) не должен враждовать');
  });
});

describe('Событие: цель видит попытку — и помнит', () => {
  const обработчик = читать('server/src/socket/GameSocketHandler.ts');

  it('пойманный за руку вор запоминается жертвой', () => {
    must(/if \(причина === 'seen'\) \{\s*\n\s*void this\.npcMemory\.rememberTheft\(цель\.id, characterId\);/.test(обработчик),
      'попытка, которую цель видела, не доходит до памяти NPC');
  });

  it('too_loud память не двигает: жертва могла ничего не видеть', () => {
    // canPickpocket проверяет приседание РАНЬШЕ взгляда: 'too_loud' значит,
    // что проверка взгляда не выполнялась — знать, видела ли цель, нельзя.
    const блок = обработчик.slice(
      обработчик.indexOf('if (!canPickpocket(вор, цель, ctx))'),
      обработчик.indexOf('socket.emit(SOCKET_EVENTS.STEAL_RESULT, {\n        ok: true'),
    );
    must((блок.match(/rememberTheft/g) ?? []).length === 1,
      'память двигается не только на seen: мир реагирует на то, чего не видел');
  });
});

describe('Реакция: диалог больше не открывается', () => {
  const маршрут = читать('server/src/routes/npc.ts');

  it('GET-диалог отвечает упрёком вместо приветствия', () => {
    must((маршрут.match(/\(memory\.theftsSeen \?\? 0\) > 0/g) ?? []).length === 2,
      'проверка обиды стоит не в обоих маршрутах диалога: POST обходит отказ GET');
    must(/id: 'grudge_theft',/.test(маршрут), 'упрёка нет: NPC говорит как ни в чём не бывало');
    must(/Уходи, пока я не позвал стражу/.test(маршрут), 'текст упрёка потерялся');
  });

  it('обида проверяется раньше дружеского приветствия и знакомства', () => {
    const grudge = маршрут.indexOf('theftsSeen ?? 0) > 0');
    const знакомство = маршрут.indexOf('Первое знакомство');
    const дружеское = маршрут.indexOf('Дружеское приветствие');
    must(grudge >= 0 && знакомство > grudge && дружеское > grudge,
      'обида стоит после приветствий: «привет, друг!» перебивает упрёк');
  });

  it('отказавший NPC не засчитывает разговор', () => {
    // talk-цели квестов идут через recordTalk при открытии диалога; упрёк
    // обязан вернуться ДО recordTalk, иначе разговор «состоялся» без слов.
    const grudge = маршрут.indexOf('theftsSeen ?? 0) > 0');
    const talk = маршрут.indexOf('recordTalk');
    must(grudge < talk, 'упрёк после recordTalk: отказавший NPC засчитывает talk-цель');
    must(!/questsCompleted,/.test(маршрут.slice(grudge, маршрут.indexOf('recordTalk'))),
      'упрёк отдаёт questsCompleted: разговор засчитан, хотя не состоялся');
  });
});
