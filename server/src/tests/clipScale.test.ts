// Масштаб клипа раньше был константой: `корневойМасштаб < 0.5 ? 100 : 1`.
//
// Замерено по ассетам, чему на самом деле равны кости моделей против костей
// клипов: 231 (guard), 120 (sufi), 112 (archer), 109 (vendor), 112
// (diplomat) и около 1 у граждан и паладина. Константа 100 была неверна ни
// для одной из семи моделей: кости вставали в 43…92 % от нужного расстояния.
// Это и был дефект тела - голова в плечах, шеи нет, руки прижаты к корпусу,
// ноги ломаются.
//
// Теперь число берётся измерением по костям самой модели. Проверка падает, если
// вернётся константа, если пропадёт замер или если испортится порядок.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const РИГ = читать('client/src/app/game3d/realRig.ts');
const ТОЛЬКО_КОД = код(РИГ);

describe('Масштаб клипа по костям', () => {
  it('сторож читает код, а не пояснение', () => {
    должен(
      /ЧТО БЫЛО\. Константа/.test(РИГ),
      'пояснение из файла исчезло, страховке не на что опереться',
    );
    должен(
      !/ЧТО БЫЛО\. Константа/.test(ТОЛЬКО_КОД),
      'комментарии больше не вырезаются: проверка читает пояснение вместо кода',
    );
  });

  it('константа 100 больше не решает исход задачи', () => {
    // Возврат константы означает возврат дефекта тела. Ровно эта строка стояла
    // в коде и была неверна для всех семи моделей.
    должен(
      !/корневойМасштаб\(сцена\) < 0\.5 \? 100 : 1;\s*$/m.test(
        ТОЛЬКО_КОД.split('коэффициентКлипа(').join('РАЗДЕЛ'),
      ),
      'константа 100 снова решает исход: кости встанут в 43…92 % от нужного расстояния',
    );
  });

  it('число берётся измерением, а не подставляется', () => {
    должен(
      /коэффициентКлипа\(\s*сцена,\s*первыйКлип,/.test(ТОЛЬКО_КОД),
      'масштаб клипа не берётся измерением по костям',
    );
    должен(
      /isBone\s*!==\s*true/.test(ТОЛЬКО_КОД),
      'кости не отбираются признаком: перебор по именам угадывал бы формат',
    );
  });

  it('кость ищется по тому же имени, что и в дорожке three.js', () => {
    // three.js убирает двоеточие из `mixamorig:Head`. Если бы сравнение шло по
    // сырому имени, ни одна кость не нашлась бы и число не вычислялось бы.
    должен(
      /replace\(\/:\/g,\s*''\)/.test(ТОЛЬКО_КОД),
      'двоеточие из имени кости не убирается: дорожки и кости не сойдутся',
    );
    должен(
      /\.position'/.test(ТОЛЬКО_КОД) && /\.position'/.test(ТОЛЬКО_КОД.split('имяКостиВДорожке')[1] || ''),
      'имя кости не вырезается из дорожки по суффиксу .position',
    );
  });

  it('берётся медиана, а не первая кость', () => {
    // Единичная выбившаяся кость не должна утягивать всё: у моделей разброс
    // внутри скелета достигает 0,59…1,09 от медианы.
    должен(
      /sort\(\(a, b\) => a - b\)/.test(ТОЛЬКО_КОД),
      'коэффициенты не сортируются: медиана посчитана неверно',
    );
    должен(
      /коэффициенты\.length < 3\) return запасное/.test(ТОЛЬКО_КОД),
      'нет проверки, что костей хватило: по одной кости число бы выдумывалось',
    );
  });
});