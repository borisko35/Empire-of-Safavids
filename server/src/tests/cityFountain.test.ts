// Фонтан в центре площади: камень, струя, перелив.
//
// ЧТО БЫЛО (21 октября 2026, §231). Чаша фонтана была тёмным цилиндром с
// сильной полосатостью на боку и читалась как ДЕРЕВЯННАЯ БОЧКА, а струя —
// отдельным конусом, висящим в воздухе над чашей: между конусом и водой не
// было ничего, и фонтан выглядел сломанным.
//
// ЧТО ТЕПЕРЬ. Каменная чаша с венцом и ступенчатым основанием, струя идёт
// от чаши к воде, по кромке чаши переливаются четыре тонких струи.
//
// ЧТО ПРОВЕРЯЕТСЯ. Четыре вещи: чаша не бочка, струя не висит в воздухе,
// перелив есть, струя не светится как лампа.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Фонтан в центре площади', () => {
  it('чаша каменная, с венцом и основанием', () => {
    const блок = /const fountain = new THREE\.Group\(\);([\s\S]*?)fountain\.position\.set/.exec(код);
    должен(блок, 'не найден фонтан');
    const тело = блок![1];
    // Тёмный полосатый цилиндр читался как деревянная бочка.
    должен(
      /const basin = new THREE\.Mesh\(new THREE\.CylinderGeometry\(3\.4, 3\.8, 1\.1, 16\), MAT\.sandstone\)/.test(тело),
      'чаша снова тёмная: она читается как бочка',
    );
    должен(/венец/.test(тело), 'у чаши нет венца: верх чаши — просто срез');
    должен(/пьедестал/.test(тело), 'у чаши нет основания: она стоит на земле боком');
  });

  it('струя идёт от чаши к воде, а не висит в воздухе', () => {
    const блок = /const fountain = new THREE\.Group\(\);([\s\S]*?)fountain\.position\.set/.exec(код);
    должен(блок, 'не найден фонтан');
    const тело = блок![1];
    // Прежний конус висел над чашей: между ним и водой ничего не было.
    должен(
      !/const jet = new THREE\.Mesh\(new THREE\.ConeGeometry\(0\.24, 1\.5, 6\)/.test(тело),
      'струя снова конус в воздухе: фонтан выглядит сломанным',
    );
    должен(
      /const jet = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.09, 0\.16, 1\.7, 8\), MAT\.fountainWater\)/.test(тело),
      'струи нет: из чаши ничего не течёт',
    );
    должен(/капля/.test(тело), 'нет падающих капель: струя читается гладкой палочкой');
  });

  it('через край чаши переливается в бассейн', () => {
    const блок = /const fountain = new THREE\.Group\(\);([\s\S]*?)fountain\.position\.set/.exec(код);
    должен(блок, 'не найден фонтан');
    // Проверяем САМУ струю, а не только цикл: цикл может остаться, а струи
    // в нём не быть — и перелива не будет.
    должен(
      /const струя = new THREE\.Mesh\(\s*new THREE\.CylinderGeometry\(0\.05, 0\.07, 2\.1, 5\),\s*MAT\.fountainWater,?\s*\)/.test(
        блок![1],
      ),
      'нет перелива через край чаши',
    );
    должен(
      /fountain\.add\(струя\)|fountain\.add\(пьедестал/.test(блок![1]) ||
        /fountain\.add\([^\)]*струя/.test(блок![1]),
      'струи перелива не добавлены в фонтан',
    );
  });

  it('струя не светится: вода, а не лампа', () => {
    // Блик шейдера воды (1.8) на тонкой струе уходил в белое, bloom
    // раздувал струю в светящуюся трубку. Поэтому у струй свой материал:
    // полупрозрачный, с мягким бликом и слабым свечением.
    const материал = /fountainWater: new THREE\.MeshStandardMaterial\(\{([\s\S]*?)\n\s*\}\),/.exec(код);
    должен(материал, 'у струй фонтана нет своего материала');
    const тело = материал![1];
    должен(/transparent: true/.test(тело), 'струя непрозрачна: вода читается пластиком');
    const прозрачность = /opacity: ([0-9.]+)/.exec(тело);
    должен(прозрачность, 'у струи не задана прозрачность');
    должен(Number(прозрачность![1]) <= 0.7, 'струя слишком плотная: просвечивать не будет');
    const свечение = /emissiveIntensity: ([0-9.]+)/.exec(тело);
    должен(свечение, 'у струи нет ограниченного свечения');
    должен(Number(свечение![1]) <= 0.5, 'струя светится как лампа: bloom превратит её в трубку');
    // Проверяем сами струи: поверхность чаши — вода (MAT.water), а блик шейдера
    // на тонкой струе был тем, что её «плющило». Струи должны на своём материале.
    const блок = /const fountain = new THREE\.Group\(\);([\s\S]*?)fountain\.position\.set/.exec(код);
    должен(блок, 'не найден фонтан');
    должен(
      !/const jet = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.09, 0\.16, 1\.7, 8\), MAT\.water\)/.test(блок![1]),
      'струя снова на шейдере воды: блик 1.8 уйдёт в белое',
    );
  });
});
