// Регионы не врут: якорь внутри своей зоны, зоны не пересекаются,
// столица называется одним именем.
//
// ЧТО БЫЛО, и почему это стоило проверки. Регион менялся одним UPDATE
// (`UPDATE characters SET region = $2`) без координат: путешествие меняло
// МЕТКУ, а персонаж оставался стоять на месте. При этом зона считалась
// функцией getZoneAt(x, z) на каждом шаге. Итог: приехав в Хорасан, игрок
// получал region = khorasan и zone = tabriz_north одновременно - оба
// значения хранились в базе, оба показывались.
//
// Хуже: якоря регионов стояли рядом со столицей (z от -170 до 200) при том,
// что зоны Хорасана лежат на z 700..1050. То есть регион как понятие не
// означал ничего: он был подписью, а не местом.
//
// ЧТО ТЕПЕРЬ ТРЕБУЕТСЯ. Якорь каждого региона обязан лежать ВНУТРИ зоны
// своего региона. Это и есть проверка, которая бы поймала рассинхрон до
// того, как он дойдёт до игрока.
import { ZONES, REGION_SPAWNS, REGION_LEVEL_REQUIREMENTS, getZoneAt } from '../../../shared/constants';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

/**
 * Падение с внятной причиной вместо невнятного false в deep equality.
 *
 * Именно asserts, а не void: без него TypeScript не сужает тип после
 * вызова, и следующая строка падает с TS18047 («возможно null») - то есть
 * проверка не может быть написана так, как её задумали. Пустая функция
 * молча превращалась в требование к проверяющему: объяви тип.
 */
function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Регионы: якоря лежат в своих зонах', () => {
  it('якорь каждого региона внутри зоны своего региона', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Именно её не хватало: якоря стояли у
    // столицы, а зоны далеко, и никто этого не сверял.
    const вне: string[] = [];
    for (const [регион, якорь] of Object.entries(REGION_SPAWNS)) {
      const зона = getZoneAt(якорь.x, якорь.z);
      if (зона === null) {
        вне.push(`${регион}: якорь (${якорь.x}, ${якорь.z}) вне всякой зоны`);
        continue;
      }
      if (зона.region !== регион) {
        вне.push(`${регион}: якорь (${якорь.x}, ${якорь.z}) попал в зону ${зона.region} (${зона.id})`);
      }
    }
    must(вне.length === 0, `якоря вне своих регионов:\n  ${вне.join('\n  ')}`);
  });

  it('у каждого региона есть хотя бы одна зона', () => {
    // Регион без зон - это метка без места: путешествие туда работает,
    // а зона на экране остаётся от прошлого региона.
    const регионы = Object.keys(REGION_SPAWNS);
    const безЗон = регионы.filter((р) => !ZONES.some((з) => з.region === р));
    must(безЗон.length === 0, `у регионов нет ни одной зоны: ${безЗон.join(', ')}`);

    // И зона без региона невозможна, но если регион в ZONES дописан, а в
    // REGION_SPAWNS забыт - якоря не будет, и путешествие уронит игрока.
    const безЯкоря = [...new Set(ZONES.map((з) => з.region))].filter((р) => !(р in REGION_SPAWNS));
    must(безЯкоря.length === 0, `у регионов из ZONES нет якоря: ${безЯкоря.join(', ')}`);

    // И требование по уровню обязано быть у каждого региона с зонами:
    // без него путешествие не проверяет ничего и открывает всё подряд.
    const безТребования = регионы.filter((р) => !(р in REGION_LEVEL_REQUIREMENTS));
    must(безТребования.length === 0, `у регионов нет требования по уровню: ${безТребования.join(', ')}`);
  });

  it('якоря регионов не совпадают между собой', () => {
    // Раньше tabriz и isfahan указывали в (0,0): путешествие в Исфахан было
    // полным no-op, и регион менялся, а персонаж стоял на месте.
    const якоря = Object.entries(REGION_SPAWNS);
    for (let i = 0; i < якоря.length; i++) {
      for (let j = i + 1; j < якоря.length; j++) {
        const [р1, я1] = якоря[i];
        const [р2, я2] = якоря[j];
        must(!(я1.x === я2.x && я1.z === я2.z),
          `регионы ${р1} и ${р2} указывают в одну точку (${я1.x}, ${я1.z}) - путешествие между ними ничего не делает`);
      }
    }
  });

  it('столица называется одним именем в коде и в зонах', () => {
    // Построенный город один. Он назван Исфаханом в ISFAHAN (SpawnSystem),
    // в PVP_ZONES и в якорях - и при этом полоса вокруг него называлась
    // tabriz_center. На экране было «Центр Тебриза» внутри Исфахана.
    const полосаСтолицы = ZONES.filter((з) => {
      const б = з.bounds;
      // Ворота стоят на (34, 26) - это и есть построенный город.
      return 34 >= б.x1 && 34 <= б.x2 && 26 >= б.z1 && 26 <= б.z2;
    });
    must(полосаСтолицы.length >= 1, 'полоса столицы не найдена - ворота (34, 26) вне зон');
    const регионСтолицы = полосаСтолицы[0].region;
    must(регионСтолицы === 'isfahan',
      `столица (34, 26) оказалась в регионе ${регионСтолицы}, а не в isfahan`);

    // И якорь Исфахана обязан быть рядом с воротами, а не в другой полосе.
    const якорь = REGION_SPAWNS.isfahan;
    const расстояние = Math.hypot(якорь.x - 34, якорь.z - 26);
    must(расстояние < 120, `якорь Исфахана в ${Math.round(расстояние)} м от ворот - путешествие увело бы игрока от города`);
  });
});

describe('Зоны: не пересекаются и покрывают мир', () => {
  it('ни одна пара зон не налезает друг на друга', () => {
    // Налезание означало бы, что getZoneAt вернёт не ту зону: игрок в
    // Исфахане увидел бы на экране Тебриз, и все проверки по региону
    // врали бы. Порядок в массиве тогда решал бы, чья зона победит.
    //
    // Общая граница - НЕ налезание. Зоны выложены полосами по z и соседние
    // полосы обязаны смыкаться: между isfahan_center (z -50..33) и
    // isfahan_outskirts (z 33..117) нет щели, иначе игрок на стыке получил
    // бы getZoneAt = null, то есть «зоны нет» посреди безопасной столицы.
    // Проверяем поэтому на ПЛОЩАДЬ, а не на касание: налезание есть там,
    // где пересечение положительно по обеим осям сразу.
    const налезания: string[] = [];
    for (let i = 0; i < ZONES.length; i++) {
      for (let j = i + 1; j < ZONES.length; j++) {
        const a = ZONES[i].bounds;
        const b = ZONES[j].bounds;
        const поX = Math.min(a.x2, b.x2) - Math.max(a.x1, b.x1);
        const поZ = Math.min(a.z2, b.z2) - Math.max(a.z1, b.z1);
        if (поX > 0 && поZ > 0) {
          налезания.push(`${ZONES[i].id} и ${ZONES[j].id} (на ${поX} x ${поZ})`);
        }
      }
    }
    must(налезания.length === 0, `зоны налезают друг на друга:\n  ${налезания.join('\n  ')}`);
  });

  it('стыки полос не оставляют щелей', () => {
    // Обратная сторона предыдущей проверки. Если соседние полосы одного
    // региона не смыкаются, между ними остаётся коридор, где getZoneAt
    // возвращает null. Игрок, идущий на север из столицы, провалился бы в
    // зону, которой нет: ни спавнов, ни подписи, ни проверки уровня.
    const щели: string[] = [];
    for (const регион of new Set(ZONES.map((з) => з.region))) {
      const полосы = ZONES.filter((з) => з.region === регион).sort((a, b) => a.bounds.z1 - b.bounds.z1);
      for (let i = 0; i + 1 < полосы.length; i++) {
        const низ = полосы[i];
        const верх = полосы[i + 1];
        const разрыв = верх.bounds.z1 - низ.bounds.z2;
        if (разрыв > 0) {
          щели.push(`${низ.id}..${верх.id} в {регион}: щель {разрыв} по z (z ${низ.bounds.z2}..${верх.bounds.z1})`);
        }
      }
    }
    must(щели.length === 0, `между полосами регионов есть щели:\n  ${щели.join('\n  ')}`);
  });

  it('id зон уникальны и не пусты', () => {
    const id = ZONES.map((з) => з.id);
    must(new Set(id).size === id.length, 'есть зоны с одинаковым id');
    must(id.every((s) => s.length > 0), 'есть зона без id');
  });

  it('уровень зоны не ниже требования её региона', () => {
    // Зона ниже требования региона - это зона, где можно стоять, не
    // доехав до региона. Или, наоборот, регион открыт, а зона внутри него
    // закрыта: и требование региона показывает обманчивое число.
    const ниже: string[] = [];
    for (const з of ZONES) {
      const требование = REGION_LEVEL_REQUIREMENTS[з.region];
      if (требование === undefined) continue;
      if (з.minLevel < требование) ниже.push(`${з.id} (min ${з.minLevel}) в регионе с требованием ${требование}`);
    }
    must(ниже.length === 0, `зоны доступны раньше региона:\n  ${ниже.join('\n  ')}`);
  });
});

describe('Новый персонаж рождается там, где стоит его город', () => {
  // ЧТО БЫЛО. В createCharacter точка старта и регион задавались двумя
  // разными вещами: position = (0,0) — это Исфахан по REGION_SPAWNS, а
  // region стоял Region.TABRIZ. Персонаж 1-го уровня рождался на площади
  // столицы, а сервер считал его в Тебризе, где требуется 20 уровень.
  //
  // Чем это оборачивалось. Требование уровня переставало быть затвором:
  // новичок рождался по ту сторону ворот. Монстры, комнаты сокетов, чат и
  // квесты ключились на Тебриц, а игрок стоял в Исфахане. В углу экрана
  // горело «Тебриз» рядом с площадью Исфахана. И recordRegionVisit сразу
  // помечал Тебриз посещённым — «посетить Тебриз» засчитывалось, никуда
  // не сходив.
  //
  // Комментарий в коде это оправдывал: «Тебриц — их стартовый город». Но
  // город, который построен и в который ставят спавн, — Исфахан. Это
  // остался след от времени, когда столицу называли tabriz.
  const сервис = () => readFileSync(join(корень, 'server/src/services/CharacterService.ts'), 'utf-8');

  it('стартовый регион — Исфахан, а не Тебриз', () => {
    const код = сервис();
    must(/const СТАРТОВЫЙ_РЕГИОН = Region\.ISFAHAN/.test(код),
      'стартовый регион снова не Исфахан: персонаж будет рождаться не в том регионе, где стоит его город');
    must(!/region: Region\.TABRIZ/.test(код),
      'в createCharacter снова прописан Region.TABRIZ — новый персонаж числится в чужом регионе');
  });

  it('стартовая точка берётся из якоря, а не пишется руками', () => {
    // Точка и регион должны браться из ОДНОГО источника. Раньше они
    // задавались отдельно, и разошлись: точка уехала в Исфахан, а регион
    // остался в Тебризе. Отдельный ввод — это и есть причина поломки.
    const код = сервис();
    must(/REGION_SPAWNS\[СТАРТОВЫЙ_РЕГИОН\]/.test(код),
      'стартовая точка не берётся из REGION_SPAWNS — её можно рассинхронизировать с регионом снова');
    must(!/position: \{ x: 0, y: 0, z: 0 \}/.test(код),
      'стартовая точка снова захардкожена числами вместо якоря региона');
  });

  it('зона при создании считается от той же точки', () => {
    // Колонка zone в INSERT отсутствовала целиком и молча бралась из
    // умолчания базы, а подпись региона бралась из characters.region.
    // Вместе это и давало «Тебриз» рядом с площадью Исфахана.
    const код = сервис();
    must(/getZoneAt\(якорь\.x, якорь\.z\)/.test(код),
      'зона при создании не считается от стартовой точки');
    must(/zone: стартовая_зона\?\.id/.test(код),
      'поле zone не заполняется при создании персонажа');
    const insert = /INSERT INTO characters\s*\(([\s\S]*?)\)\s*VALUES/.exec(код)?.[1] ?? '';
    must(insert.includes('zone'),
      'колонки zone нет в списке INSERT: значение молча не запишется, и зона снова возьмётся из умолчания базы');
  });

  it('якорь старта лежит в зоне своего региона — это проверяемо', () => {
    // Связка из трёх полей проверяется не только чтением кода: берём
    // настоящий якорь, считаем настоящую зону и сверяем с регионом.
    // Если якорь Исфахана уедет в другую полосу, тест упадёт на числах,
    // а не на совпадении строк в исходнике.
    const якорь = REGION_SPAWNS.isfahan;
    const зона = getZoneAt(якорь.x, якорь.z);
    must(зона !== null, 'якорь Исфахана вне всякой зоны');
    must(зона.region === 'isfahan',
      `якорь Исфахана попал в зону ${зона.id} региона ${зона.region}`);
    // Персонаж 1-го уровня обязан рождаться там, куда его пускают.
    must(REGION_LEVEL_REQUIREMENTS.isfahan <= 1,
      `Исфахан требует ${REGION_LEVEL_REQUIREMENTS.isfahan} уровня, а новый персонаж всегда 1-го: он снова рождается за закрытой дверью`);
  });
});

describe('Клиент не заводит свою копию якорей', () => {
  it('якоря в клиенте берутся из общего места', () => {
    // world.ts держал свою таблицу REGION_ANCHORS, и она разошлась с
    // REGION_SPAWNS: копия осталась у столицы после того, как общее место
    // исправили. Две правды об одном числе - источник рассинхрона, который
    // повторится при следующей правке.
    const клиент = readFileSync(join(корень, 'client/src/app/world.ts'), 'utf-8');
    must(/const REGION_ANCHORS: Record<string, \{ x: number; z: number \}> = REGION_SPAWNS;/.test(клиент),
      'клиент снова держит свою таблицу якорей вместо общей');
  });

  it('путешествие реально перемещает персонажа', () => {
    // ГЛАВНАЯ ПОЛOMКА СИСТЕМЫ, найденная по дороге. updateRegion делал
    // `UPDATE characters SET region = $2` и всё: ни координат, ни зоны.
    // Значит «поездка» меняла только подпись, а игрок оставался стоять.
    const сервис = readFileSync(join(корень, 'server/src/services/CharacterService.ts'), 'utf-8');
    // Окно generous: метод вырос с комментариями, чем он объясняет, что
    // раньше делал, поэтому жёсткий лимит символов однажды сломал бы
    // проверку на ровном месте - на длине комментария, а не на поломке.
    const обновление = /async updateRegion[\s\S]{0,4000}?\n  \}/.exec(сервис)?.[0] ?? '';
    must(обновление.length > 0, 'не нашёл updateRegion');
    must(/SET region = \$2/.test(обновление), 'updateRegion больше не меняет region - проверка устарела');
    must(/position/.test(обновление),
      'updateRegion не двигает персонажа: путешествие меняет только метку, игрок остаётся на месте');
  });
});
