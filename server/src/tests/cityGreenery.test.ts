// Зелень города: кусты, трава и деревья по кварталам.
//
// ЧТО БЫЛО (21 октября 2026, §229). Зелень в Исфахане была только в садах —
// десять кипарисов на весь город. Стены домов, полоса у городской стены и
// кварталы стояли голыми, и город читался как песчаный двор, из которого
// торчат коробки.
//
// ЧТО ТЕПЕРЬ. Кусты вдоль стены и у домов, трава полосой перед стеной,
// кипарис и кусты у каждого квартала.
//
// ЧТО ПРОВЕРЯЕТСЯ. Три вещи, которые легко потерять при правке города:
//   • куст — это ЗАРОСЛЬ из нескольких лепков, а не один шар;
//   • зелень стоит на мостовой (верх плиты), а не в ноль: в ноль она утонула
//     бы в плиту на пол-метра;
//   • проём ворот остаётся проёмом: у ворот кусты не ставятся.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Зелень города', () => {
  it('куст — заросль из нескольких лепков листвы', () => {
    должен(/function куст\(/.test(код), 'нет куста: город без зелени у стен');
    const блок = /function куст\([\s\S]*?\n}\n/.exec(код);
    должен(блок, 'не разобрался куст');
    // Не один шар, а несколько лепков вокруг центра.
    должен(/const сколько = 3 \+/.test(блок![0]), 'куст — один шар, а не заросль');
    должен(
      /SphereGeometry\(r, 6, 5\)/.test(блок![0]) && /лепок\.scale\.y = 0\.82/.test(блок![0]),
      'лепки куста не приплюснуты: куст читается шаром',
    );
  });

  it('трава стоит пучками, а не поодиночке', () => {
    должен(/function трава\(/.test(код), 'нет травы: край плитки обрывается в песок');
    const блок = /function трава\([\s\S]*?\n}\n/.exec(код);
    должен(блок, 'не разобралась трава');
    должен(/for \(let i = 0; i < 3; i\+\+\)/.test(блок![0]), 'трава не пучком');
  });

  it('зелень ставится на мостовой, а не в ноль', () => {
    // Площадь — цилиндр высотой 0.5 с центром на 0.05, то есть верх на 0.3.
    // Зелень в ноль утонула бы в плиту на пол-метра.
    должен(
      /const ВЕРХ_ПЛИТКИ = 0\.3/.test(код),
      'нет высоты поверх плиты: зелень утонет в мостовой',
    );
    const кустВызов = /куст\(city, [^;]*ВЕРХ_ПЛИТКИ/.test(код);
    const траваВызов = /трава\(city, [^;]*ВЕРХ_ПЛИТКИ/.test(код);
    должен(кустВызов, 'кусты ставятся не на мостовую');
    должен(траваВызов, 'трава ставится не на мостовую');
  });

  it('проём ворот остаётся проёмом', () => {
    // Куст в воротах — это куст в проезде: мимо ворот нельзя проехать.
    должен(
      /доВорот < 0\.22\) continue/.test(код),
      'у ворот теперь ставятся кусты: проём перекрыт',
    );
    // Зелень должна стоять у самой стены, а не в середине площади.
    должен(
      /CITY\.radius \* 0\.94/.test(код),
      'кусты отошли от стены: зелёная полоса должна идти по краю города',
    );
  });

  it('у каждого квартала своё дерево', () => {
    const деревья = /for \(const \[qx, qz, s\] of \[([\s\S]*?)\] as const\) \{([\s\S]*?)\n  \}/.exec(код);
    должен(деревья, 'у кварталов нет своих деревьев');
    const строки = деревья![1].split('\n').filter((с) => с.includes(','));
    должен(строки.length >= 3, `кварталов с деревьями ${строки.length}: их мало`);
    должен(/cypress\(city, qx/.test(деревья![2]), 'у квартала не посажено дерево');
  });
});
