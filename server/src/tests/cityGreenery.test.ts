// Зелень города.
//
// ЧТО БЫЛО (21 октября 2026, §258). Кусты — гроздь приплюснутых шаров, трава
// — конусы-лезвия. Город между домами читался песчаным двором с шариками.
//
// ЧТО ТЕПЕРЬ (§326). Куст — готовая модель (bush-1/bush-2, Quaternius, CC0),
// трава — готовый пучок (grass-tuft-1..3). Оба качаются по ветру (§258).
//
// ЧТО ПРОВЕРЯЕТСЯ. Модели лежат в манифесте; куст и трава ставятся
// decorВещь с записью в качающиеся; примитивных шаров и конусов больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
  animals?: { file: string; name: string; bytes: number }[];
};
const вМанифесте = (раздел: 'decor' | 'animals', имя: string): boolean =>
  (МАНИФЕСТ[раздел] ?? []).some((д) => д.name === имя);

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Зелень города', () => {
  it('куст — готовая модель двух вариантов, и она качается', () => {
    должен(вМанифесте('decor', 'bush-1'), 'bush-1.glb нет в манифесте');
    должен(вМанифесте('decor', 'bush-2'), 'bush-2.glb нет в манифесте');
    должен(/function куст\(/.test(ТЕРРЕЙН), 'нет постановщика куста');
    должен(/bush-1' : 'bush-2'/.test(ТЕРРЕЙН), 'куст не чередует варианты');
    должен(/качание: \{ амплитуда: [\d.]+ \* s, фаза: hash2/.test(ТЕРРЕЙН.split('function куст')[1].split('\n}\n')[0]),
      'куст не качается');
    должен(!/SphereGeometry\(r, 6, 5\)/.test(ТЕРРЕЙН), 'куст снова из шаров');
  });

  it('трава — готовый пучок, и она качается', () => {
    должен(вМанифесте('decor', 'grass-tuft-1'), 'grass-tuft-1.glb нет в манифесте');
    должен(/function трава\(/.test(ТЕРРЕЙН), 'нет постановщика травы');
    const траваКод = ТЕРРЕЙН.split('function трава')[1].split('\n}\n')[0];
    должен(/grass-tuft-1', 'grass-tuft-2', 'grass-tuft-3'/.test(траваКод), 'трава не чередует пучки');
    должен(/качание: \{ амплитуда: [\d.]+ \* s/.test(траваКод), 'трава не качается');
    должен(!/ConeGeometry\(0\.075 \* s, 0\.55 \* s, 3\)/.test(ТЕРРЕЙН), 'трава снова конусы');
  });

  it('деревья полей качаются по ветру: качание у поля, а не у одиночной модели (§333)', () => {
    const блокПоля = ТЕРРЕЙН.split('function decorПоле')[1].split('\n}\n')[0];
    должен(/качание\?: \{ амплитуда: number; фаза: number \}/.test(блокПоля),
      'decorПоле не принимает качание: деревья полей не могут качаться');
    должен(/decorПоле\(scene, `platan-\$\{i \+ 1\}`, точки, \{ качание/.test(ТЕРРЕЙН),
      'поля платанов не передают качание');
    должен(/decorПоле\(scene, 'cypress', кипарисы, \{ качание/.test(ТЕРРЕЙН),
      'поле кипарисов не передаёт качание');
    должен(/if \(к\.матрицы\)/.test(читать('client/src/app/game3d/world3d.ts')),
      'ветер не пишет наклон в матрицу инстанса: поле стоит неподвижно');
  });
});