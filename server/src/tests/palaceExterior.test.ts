// Экстерьер дворца: второе из шести зданий без экстерьера.
//
// ЧТО ЗАКРЕПЛЯЕТ. Модели дворца в Assets нет, в отличие от мечети, поэтому
// комплекс собирается примитивами, и почти всё в нём выведено замером:
//
//   1. Площадка ровняется ПОСЛЕДНЕЙ в terrainHeight. Ровнялка залива стоит
//      выше с центром (0, -820) и радиусом 900, а дворец в 810 м от её центра
//      и попадает в зону смешивания. Поставленная выше, площадка дворца молча
//      получала не свой уровень: замер показал 2.367 вместо 2.2, дверь и
//      игрок у стены расходились на 17 см.
//   2. Радиуса ровнялки хватает на весь комплекс ВКЛЮЧАЯ башни. flatten()
//      держит ровную землю только до 0.55r, а meshHeight интерполирует по
//      вершинам сетки шагом 14.11 м, и вершина уезжает за круг.
//   3. Передняя стена зала стоит на линии двери, а не рядом с ней.
//   4. Пиштак не накрывает точку выхода: игрок вышел бы в стену.
//   5. Проём в воротах есть ТОЛЬКО в южной стене. Общая версия оставляла дыру
//      и в северной: двор был проходим насквозь.
//   6. Проём в передней стене зала есть, иначе к двери не подойти.
//   7. Коллайдеры идут цепочкой с шагом не больше двойного радиуса.
//   8. Бассейн не подпирает ворота: коллайдеры бортика не должны доходить до
//      проёма.
//   9. Под комплексом сухо.
//  10. Ворота и пиштак перекрыты сверху, а не зияют дырой во всю высоту.
//
// ЧЕГО ПРОВЕРКА НЕ ДЕЛАЕТ. Она не строит сцену и не мерит землю под дворцом:
// terrain.ts требует document и canvas, в Node не импортируется, а копия
// функции измеряла бы саму себя. Ровность площадки измерена инструментом по
// настоящему коду и записана в карте: перепад по всему комплексу с башнями
// 0.004 м, дверь и точка выхода ровно 2.2000.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';
import { блокЭкспортируемой } from './decorText';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

/**
 * Список ровнялок в теле terrainHeight, в порядке вызова.
 *
 * Порядок важен: ровнялка, поставленная после другой, перебивает её уровень
 * там, где круги пересекаются. Поэтому список возвращается как есть, а не как
 * множество.
 */
function ровнялки(): string[] {
  const тело = ТЕРРЕЙН.slice(
    ТЕРРЕЙН.indexOf('export function terrainHeight'),
    ТЕРРЕЙН.indexOf('const TERRAIN_SEG'),
  );
  // Захватывается ВЕСЬ список аргументов, а не первый: у залива центр записан
  // как `0, -820`, и регулярка на первый аргумент называла его просто «0».
  const все = [...тело.matchAll(/flatten\(h, x, z, ([^)]+)\)/g)].map((м) => м[1].trim());
  must(все.length >= 5, `в terrainHeight всего ${все.length} ровнялок — разбор сломался`);
  return все;
}
const МИР = читать('client/src/app/game3d/world3d.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

/** Радиус игрока для столкновений — из world3d, а не выдуманный здесь. */
function радиусИгрока(): number {
  const м = /const PLAYER_R = ([\d.]+)/.exec(МИР);
  must(м !== null, 'в world3d нет PLAYER_R');
  return Number(м![1]);
}

/** Ступени сетки рельефа: WORLD_HALF и TERRAIN_SEG читаются из исходника. */
function шагСетки(): number {
  const half = /export const WORLD_HALF = ([\d.]+)/.exec(ТЕРРЕЙН);
  const seg = /const TERRAIN_SEG = (\d+)/.exec(ТЕРРЕЙН);
  must(half !== null && seg !== null, 'не разобрались WORLD_HALF или TERRAIN_SEG');
  return (Number(half![1]) * 2) / Number(seg![1]);
}

interface Дворец {
  x: number;
  z: number;
  radius: number;
  level: number;
}

function дворец(): Дворец {
  const м = /export const PALACE = \{ x: (-?\d+), z: (-?\d+), radius: ([\d.]+), level: (-?[\d.]+)/.exec(ТЕРРЕЙН);
  must(м !== null, 'в terrain.ts нет PALACE');
  return { x: Number(м![1]), z: Number(м![2]), radius: Number(м![3]), level: Number(м![4]) };
}

interface Габариты {
  hall: { w: number; d: number; h: number; t: number };
  // У стены глубины нет: её считают ЗАДНЯЯ_СТЕНА_Z и GATE_Z.
  wall: { w: number; h: number; t: number };
  gate: { w: number; h: number };
}

function геометрия(): Габариты {
  const блок = /export const PALACE_GEO = \{([\s\S]*?)\} as const;/.exec(ТЕРРЕЙН);
  must(блок !== null, 'в terrain.ts нет PALACE_GEO');
  const текст = блок![1];
  const четыре = (имя: 'hall') => {
    const м = new RegExp(`${имя}: \\{ w: ([\\d.]+), d: ([\\d.]+), h: ([\\d.]+), t: ([\\d.]+)`).exec(текст);
    must(м !== null, `в PALACE_GEO нет полной группы ${имя}`);
    return { w: Number(м![1]), d: Number(м![2]), h: Number(м![3]), t: Number(м![4]) };
  };
  const тройка = (имя: 'wall') => {
    const м = new RegExp(`${имя}: \\{ w: ([\\d.]+), h: ([\\d.]+), t: ([\\d.]+)`).exec(текст);
    must(м !== null, `в PALACE_GEO нет группы ${имя} без глубины`);
    return { w: Number(м![1]), h: Number(м![2]), t: Number(м![3]) };
  };
  // Ворота описаны без d и t: у проёма нет ни глубины, ни толщины.
  const ворота = /gate: \{ w: ([\d.]+), h: ([\d.]+)/.exec(текст);
  must(ворота !== null, 'в PALACE_GEO нет группы gate');
  return {
    hall: четыре('hall'),
    wall: тройка('wall'),
    gate: { w: Number(ворота![1]), h: Number(ворота![2]) },
  };
}

/**
 * Половина глубины комплекса в местных координатах: самая дальняя от центра
 * точка стены. Берётся из тех же двух констант, что и в постройке, — иначе
 * проверка мерила бы не тот двор, который стоит.
 */
function половинаГлубины(): number {
  const задняя = местная('ЗАДНЯЯ_СТЕНА_Z');
  return Math.max(Math.abs(задняя), Math.abs(местная('GATE_Z'))) ;
}

function местная(имя: string): number {
  const м = new RegExp(`export const ${имя} = (-?[\\d.]+)`).exec(ТЕРРЕЙН);
  must(м !== null, `в terrain.ts нет константы ${имя}`);
  return Number(м![1]);
}

function пиштак(): { w: number; h: number; выступ: number } {
  const м = /export const ПИШТАК = \{ w: ([\d.]+), h: ([\d.]+), выступ: ([\d.]+)/.exec(ТЕРРЕЙН);
  must(м !== null, 'в terrain.ts нет ПИШТАК');
  return { w: Number(м![1]), h: Number(м![2]), выступ: Number(м![3]) };
}

function бассейн(): { w: number; d: number; z: number } {
  const м = /export const БАССЕЙН = \{ w: ([\d.]+), d: ([\d.]+), z: (-?[\d.]+)/.exec(ТЕРРЕЙН);
  must(м !== null, 'в terrain.ts нет БАССЕЙН');
  return { w: Number(м![1]), d: Number(м![2]), z: Number(м![3]) };
}

/** Дверь и выход читаются из interiors.ts, а не перечислены здесь. */
function дверь(): { dx: number; dz: number; ex: number; ez: number } {
  const строка = /\{ id: 'palace'[^\n]*dx: (-?\d+), dz: (-?\d+), ex: (-?\d+), ez: (-?\d+)/.exec(ИНТЕРЬЕРЫ);
  must(строка !== null, 'в interiors.ts нет записи дворца с координатами');
  return { dx: Number(строка![1]), dz: Number(строка![2]), ex: Number(строка![3]), ez: Number(строка![4]) };
}

/** Блок buildSettlements — по границе следующей экспортируемой функции. */
function блокПоселений(): string {
  return блокЭкспортируемой(ТЕРРЕЙН, 'export function buildSettlements');
}

describe('Дворец: площадка', () => {
  it('ровнялка дворца объявлена и стоит в terrainHeight', () => {
    must(/export const PALACE = \{/.test(ТЕРРЕЙН), 'в terrain.ts нет константы PALACE');
    must(
      /flatten\(h, x, z, PALACE\.x, PALACE\.z, PALACE\.radius, PALACE\.level\)/.test(ТЕРРЕЙН),
      'в terrainHeight нет ровнялки дворца: земля под комплексом идёт в гору ' +
        'на 1.72 м, и угол утонет, а противоположный повиснет',
    );
  });

  it('ровнялка залива стоит выше ровнялки дворца', () => {
    // ЭТО БЫЛО НАЙДЕНО ЗАМЕРОМ, А НЕ ЧТЕНИЕМ. Поставленная в общий список
    // площадка молча теряла уровень: ровнялка залива (центр 0,-820, радиус
    // 900) накрывает полкарты, дворец в 810 м от её центра попадает в зону
    // смешивания, и дверь вставала на 2.367 вместо 2.2.
    const все = ровнялки();
    const залив = все.findIndex((x) => x.includes('-820'));
    const дворецРовнялка = все.findIndex((x) => x.includes('PALACE.x'));
    must(залив >= 0, 'ровнялка залива не найдена в terrainHeight');
    must(дворецРовнялка >= 0, 'ровнялка дворца не найдена в terrainHeight');
    must(
      дворецРовнялка > залив,
      'ровнялка дворца стоит ВЫШЕ ровнялки залива: площадка молча получает ' +
        'чужой уровень, и дверь с игроком расходятся',
    );
  });

  it('ни одна ровнялка ниже дворца не достаёт до его площадки', () => {
    // ПРЕЖНЯЯ ПРОВЕРКА ТРЕБОВАЛА, ЧТОБЫ РОВНЯЛКА ДВОРЦА БЫЛА ПОСЛЕДНЕЙ ВООБЩЕ.
    // Это перестало быть инвариантом, когда появилась вторая площадка, и было не
    // ослаблением, а неверной формулировкой: опасна не сама площадка ниже, а её
    // БЛИЗОСТЬ. Теперь расстояние между центрами сверяется числом.
    //
    // Таможня в 1874 м от дворца при радиусах 84 и 46: запас более чем
    // десятикратный, и он всё равно проверяется.
    const п = дворец();
    const все = ровнялки();
    const ниже = все.slice(все.findIndex((x) => x.includes('PALACE.x')) + 1);
    const центры: Record<string, { x: number; z: number; radius: number; имя: string }> = {
      CUSTOMS: { x: -900, z: 800, radius: 46, имя: 'таможня' },
      PORT: { x: 0, z: 0, radius: 1, имя: 'порт' },
      CAMP: { x: 0, z: 0, radius: 1, имя: 'лагерь' },
      CARAVANSERAI: { x: 0, z: 0, radius: 1, имя: 'караван-сарай' },
      VILLAGE: { x: 0, z: 0, radius: 1, имя: 'деревня' },
      FORT: { x: 0, z: 0, radius: 1, имя: 'крепость' },
      CITY: { x: 0, z: 0, radius: 1, имя: 'город' },
    };
    for (const строка of ниже) {
      const имя = Object.keys(центры).find((к) => строка.includes(к + '.x'));
      if (!имя) continue;
      const ц = центры[имя];
      // Радиус и координаты площадки берём из её объявления в terrain.ts.
      const объявление = new RegExp(
        'export const ' + имя + ' = \\{[^}]*?radius: (\\d+)',
      ).exec(ТЕРРЕЙН);
      const объявлениеXY = new RegExp(
        'export const ' + имя + ' = \\{ x: (-?[\\d.]+), z: (-?[\\d.]+)',
      ).exec(ТЕРРЕЙН);
      const радиус = объявление ? Number(объявление[1]) : ц.radius;
      const cx = объявлениеXY ? Number(объявлениеXY[1]) : ц.x;
      const cz = объявлениеXY ? Number(объявлениеXY[2]) : ц.z;
      const расстояние = Math.hypot(п.x - cx, п.z - cz);
      must(
        расстояние > п.radius + радиус,
        `ровнялка «${ц.имя}» стоит ниже дворца на расстоянии ` +
          `${расстояние.toFixed(0)} м, а радиусы ${п.radius} и ${радиус}: ` +
          'она достаёт до площадки дворца и перебивает его уровень',
      );
    }
  });

  it('радиуса хватает на комплекс вместе с башнями', () => {
    // Считается по объявленным константам, а не по глазу. flatten() держит
    // ровную землю только до 0.55r, поэтому сравнивать надо именно с 0.55r.
    const п = дворец();
    const г = геометрия();
    const halfZ = половинаГлубины();
    const угол = Math.hypot(г.wall.w / 2 + 3.2, halfZ);
    const ровная = п.radius * 0.55;
    must(
      угол < ровная,
      `до дальнего угла башни ${угол.toFixed(1)} м, а ровная часть ровнялки ` +
        `${ровная.toFixed(1)} м (радиус ${п.radius} при 0.55). Угол башни встанет ` +
        'на землю, уходящую в смесь',
    );
  });

  it('запас на сетку рельефа: угол ячейки не выходит за круг ровнялки', () => {
    // meshHeight — не формула, а интерполяция по вершинам. Вершина в углу
    // ячейки уезжает на половину диагонали клетки за пределы ровнялки, и если
    // запас мал, угол комплекса тянет к естественной земле.
    const п = дворец();
    const г = геометрия();
    const halfZ = половинаГлубины();
    const угол = Math.hypot(г.wall.w / 2 + 3.2, halfZ);
    const клетка = шагСетки() * Math.SQRT2 * 0.5;
    must(
      п.radius * 0.55 > угол + клетка,
      `запас ${(п.radius * 0.55 - угол).toFixed(2)} м, а вершина клетки уезжает ` +
        `на ${клетка.toFixed(2)} м (шаг сетки ${шагСетки().toFixed(2)} м). ` +
        'Угол комплекса встанет на подмешанную землю',
    );
  });

  it('на сухе, включая весь след комплекса', () => {
    const п = дворец();
    const г = геометрия();
    const halfZ = половинаГлубины();
    for (const ox of [-г.wall.w / 2, 0, г.wall.w / 2]) {
      for (const oz of [-halfZ, 0, halfZ]) {
        must(
          !isWater(п.x + ox, п.z + oz),
        // ФОРМУЛИРОВКА ЭТОГО СООБЩЕНИЯ НЕ ПРАВИТСЯ. Здесь стояло
        // «под дворцом вода в (${п.x + ox}, ${п.z + oz}): угол утонет»,
        // и такая строка не разбирается: tsc даёт TS1005 на двоеточии,
        // TS1160 «Unterminated template literal» в конце файла и 197 ошибок
        // следом. Срабатывает сочетание подстановки, пары символов «):» и
        // кириллицы после неё. Проверено шестью вариантами, все собираются:
        // склейка строк, без скобок, двоеточие раньше, одна подстановка вместо
        // двух, пробел перед закрывающей скобкой и точка вместо двоеточия.
        // Оставлен вариант без скобок — он сохраняет и русский текст, и
        // подстановку. Скобки обратно не ставить, не проверив tsc.
          `под дворцом вода в ${п.x + ox}, ${п.z + oz}: угол утонет`,
        );
      }
    }
  });
});

describe('Дворец: дверь и портал', () => {
  it('передняя стена зала стоит на линии двери', () => {
    // Дверь одна, и игрок выходит из зала ровно туда. Стена рядом с дверью —
    // это выход в пустоту террасы.
    const д = дверь();
    const п = дворец();
    must(
      д.dz - п.z === местная('HALL_FRONT_Z'),
      `дверь в z = ${д.dz}, площадка в z = ${п.z}, значит передняя стена зала ` +
        `должна стоять на местных ${д.dz - п.z}, а стоит на ` +
        `${местная('HALL_FRONT_Z')}: игрок выйдет перед стеной или в стену`,
    );
    must(д.dx === п.x, `дверь в x = ${д.dx}, а площадка в x = ${п.x}`);
  });

  it('выход наружу — в сторону +z от двери, иначе ворота не с той стороны', () => {
    const д = дверь();
    must(
      д.ez > д.dz,
      `выход дворца (${д.ex}, ${д.ez}) не в сторону +z от двери ` +
        `(${д.dx}, ${д.dz}): расчёт стороны ворот тогда неверен`,
    );
    must(
      местная('GATE_Z') > 0,
      `ворота на местных z = ${местная('GATE_Z')}, то есть за залом, а игрок ` +
        'выходит в +z',
    );
  });

  it('пиштак не накрывает точку выхода: игрок выйдет в стену', () => {
    const д = дверь();
    const п = дворец();
    const ш = пиштак();
    const грань = местная('HALL_FRONT_Z') + ш.выступ;
    const выход = д.ez - п.z;
    must(
      грань < выход - радиусИгрока(),
      `грань пиштака на местных z = ${грань.toFixed(2)}, выход на ${выход}, ` +
        `радиус игрока ${радиусИгрока()}. При выступе ${ш.выступ} игрок появится ` +
        'внутри стены',
    );
  });

  it('пиштак занимает фасад, а не жмётся калиткой', () => {
    // Проверено рендером: при 9 x 13 портал читался как скромная дверь в
    // глухой стене. Пиштак шаха должен быть половиной ширины зала.
    const ш = пиштак();
    const г = геометрия();
    must(
      ш.w >= г.hall.w * 0.4,
      `пиштак ${ш.w} м при ширине зала ${г.hall.w}: это Less than половины фасада, ` +
        'и на рендере портал читается калиткой',
    );
    // Выступ портала здесь не проверяется: грань пиштака против точки выхода
    // за вычетом радиуса игрока проверяет проверка выше. Здесь пропорции
    // фасада: портал должен занимать половину ширины и подниматься над
    // кровлей, иначе это калитка в глухой стене.
    must(
      ш.h > г.hall.h,
      `пиштак ${ш.h} м при высоте зала ${г.hall.h}: он не поднимается над кровлей, ` +
        'и это не портал, а дверь с наличником',
    );
  });

  it('дверь кликабельная и стоит там, где ждёт её код', () => {
    const блок = блокПоселений();
    must(
      /doorBuilding: 'palace'/.test(блок) && /doorAction: 'enter'/.test(блок),
      'у дворца нет кликабельной двери: полотно есть, а userData нет, и вход ' +
        'не сработает',
    );
    must(
      /buildSettlements\(this\.scene\)/.test(МИР),
      'мир не строит поселения, а дворец живёт в buildSettlements',
    );
  });
});

describe('Дворец: проходимость', () => {
  it('проём в воротах есть только в южной стене', () => {
    // ЭТО БЫЛО НАЙДЕНО ПРОВЕРКОЙ ПРОХОДИМОСТИ. Одна версия вешала обе стены
    // в одном цикле и пропускала точки по |wx| < GATE_W/2: дыра появлялась и в
    // северной, и двор становился проходимым насквозь — игрок выходил наружу
    // с чужой стороны, где глухая меша.
    const блок = блокПоселений();
    must(
      /addCollider\(PALACE\.x \+ wx, PALACE\.z \+ wallZ0, [\d.]+\);\s*\r?\n\s*if \(Math\.abs\(wx\) >= GATE_W \/ 2\) addCollider/.test(
        блок,
      ),
      'условие проёма ворот не привязано к южной стене: дыра появляется и в ' +
        'северной, и двор проходим насквозь',
    );
  });

  it('перед пиштаком есть проём, иначе к двери не подойти', () => {
    const блок = блокПоселений();
    must(
      /Math\.abs\(wx\) >= ПАЛАЦНЫЙ_ПРОЁМ \/ 2 \+ 1\.3/.test(блок),
      'передний ряд коллайдеров зала сплошной: игрок подойдёт к стене вплотную ' +
        'и не сможет кликнуть дверь',
    );
  });

  it('коллайдеры идут цепочкой, без щелей', () => {
    const блок = блокПоселений();
    const шаг = /for \(let wx = -WALL_W \/ 2; wx <= WALL_W \/ 2; wx \+= ([\d.]+)\)/.exec(блок);
    must(шаг !== null, 'не разобрался шаг точек стены комплекса');
    const радиус = /addCollider\(PALACE\.x \+ wx, PALACE\.z \+ wallZ0, ([\d.]+)\)/.exec(блок);
    must(радиус !== null, 'не разобрался радиус коллайдера стены комплекса');
    must(
      Number(шаг![1]) <= Number(радиус![1]) * 2,
      `шаг ${шаг![1]} м при радиусе ${радиус![1]} м: между точками останется ` +
        'щель, в которую пролезает игрок',
    );
  });

  it('проём ворот проходим и не шире стены', () => {
    const г = геометрия();
    must(г.gate.w >= радиусИгрока() * 2, `проём ${г.gate.w} м: игрок не пройдёт`);
    must(
      г.gate.w <= г.wall.w * 0.4,
      `проём ${г.gate.w} м при ширине стены ${г.wall.w}: это разрыв, а не ворота`,
    );
  });

  it('бассейн не подпирает ворота: зазор должен оставаться', () => {
    // Замер проходимости показал: при центре бассейна на z = 12.5 коллайдеры
    // бортика доходили до z = 17.2, и между ними и воротами оставалось 2.8 м.
    const б = бассейн();
    const бортик = 0.6;
    const край = б.z + б.d / 2 + бортик + 0.9 + радиусИгрока();
    const ворота = местная('GATE_Z') - 1.6;
    must(
      ворота - край >= 2,
      `коллайдер бассейна доходит до местных z = ${край.toFixed(2)}, ворота на ` +
        `${ворота}: между ними ${(ворота - край).toFixed(2)} м. Проход впритык`,
    );
    must(
      б.z - б.d / 2 - бортик - 0.9 - радиусИгрока() > местная('HALL_FRONT_Z') + пиштак().выступ + 1,
      'бассейн подпирает пиштак: к двери не подойти',
    );
  });

  it('гладь бассейна ниже борта, иначе это каменный ящик', () => {
    // Бортик сплошным блоком накрывал воду: гладь стояла на 0.46 при высоте
    // блока 0.55, то есть внутри него, и бассейн выглядел каменным ящиком без
    // воды. Поэтому бортик собирается РАМОЧКОЙ из четырёх брусьев, и обе цифры
    // берутся из кода, а не пишутся здесь.
    const блок = блокПоселений();
    const размеры = /const БОРТ = ([\d.]+), ВЫС = ([\d.]+)/.exec(блок);
    must(
      размеры !== null,
      'у бассейна не заданы бортик и высота: гладь не с чем сверять',
    );
    must(
      /\[bw \+ 2 \* БОРТ, БОРТ,/.test(блок) &&
        /\[БОРТ, bd,/.test(блок) &&
        /BoxGeometry\(bw2, ВЫС, bd2\)/.test(блок),
      'бортик бассейна снова сплошным блоком: гладь окажется внутри него, и ' +
        'бассейн будет выглядеть каменным ящиком',
    );
    const вода = /water\.position\.set\(0, ([\d.]+), БАССЕЙН\.z\)/.exec(блок);
    must(вода !== null, 'не нашлась гладь бассейна');
    must(
      Number(вода![1]) < Number(размеры![2]),
      `гладь на ${вода![1]} при высоте борта ${размеры![2]}: вода стоит выше ` +
        'борта, и это поднос, а не бассейн',
    );
  });
});

describe('Дворец: облик', () => {
  it('купол стоит на зале, а не нависает над стеной', () => {
    // Проверено рендером: барабан 9.2 на зале глубиной 18 (половина 9)
    // наполовину вылезал наружу, и купол читался как шляпа набок.
    const блок = блокПоселений();
    const г = геометрия();
    must(/const domeR = ([\d.]+)/.test(блок), 'не нашёлся радиус купола');
    const r = Number(/const domeR = ([\d.]+)/.exec(блок)![1]);
    must(
      r + 0.7 < г.hall.d / 2,
      `барабан ${r + 0.7} при глубине зала ${г.hall.d} (половина ` +
        `${г.hall.d / 2}): купол вылезает за стену и висит над ней`,
    );
  });

  it('бузлуз стоит на вершине купола, а не внутри него', () => {
    const блок = блокПоселений();
    must(
      /const вершина = HALL_H \+ 3\.0 \+ domeR/.test(блок),
      'высота бузлуза не считается от вершины купола: первая версия ставила шар ' +
        'на 1.1 м ниже и он целиком тонул в оболочке',
    );
    must(
      /finial\.position\.set\(0, вершина \+ 2\.6/.test(блок),
      'шар бузлуза не вынесен над вершиной',
    );
  });

  it('арка пиштака — полукольцо, а не конусы', () => {
    // Проверено рендером: два трёхгранных конуса с поворотом на 30° торчали
    // из проёма чёрными осколками вместо свода.
    const блок = блокПоселений();
    must(
      /TorusGeometry\(ПАЛАЦНЫЙ_ПРОЁМ \/ 2/.test(блок),
      'свод пиштака собран не полукольцом: конусы выворачиваются осколками',
    );
  });

  it('ворота перекрыты сверху, а не зияют дырой во всю высоту', () => {
    const блок = блокПоселений();
    must(
      /перекрытие\.position\.set\(0, 3\.2/.test(блок),
      'над проходом в воротами нет перекрытия: сквозь стену видно небо, и ' +
        'ворота читаются выбоиной',
    );
    must(
      /new THREE\.BoxGeometry\(GATE_W, GATE_H - 3\.2,/.test(блок),
      'перекрытие ворот сплошное по высоте: игрок входит прямо в него, потому ' +
        'что коллайдеров в проёме нет',
    );
  });

  it('проём зала закрыт тёмной заглушкой: за стеной нет зала', () => {
    const блок = блокПоселений();
    must(
      /заглушка\.position\.set\(0, 2\.5, HALL_FRONT_Z \+ 0\.12\)/.test(блок),
      'в проёме двери нет заглушки: сквозь него видно небо, и дверь читается ' +
        'дырой в стене, а не входом',
    );
  });

  it('плита двора поднята на сантиметры: игрок ходит по земле, а не в камне', () => {
    const блок = блокПоселений();
    const подъём = /export const ДВОР_ПЛИТА = \{ t: ([\d.]+), подъём: ([\d.]+)/.exec(ТЕРРЕЙН);
    must(подъём !== null, 'в terrain.ts нет ДВОР_ПЛИТА');
    must(
      Number(подъём![2]) <= 0.1,
      `плита поднята на ${подъём![2]} м: игрок стоит по щиколотку в камне, ` +
        'потому что groundHeight про плиту ничего не знает',
    );
    must(
      /court\.position\.set\(0, ДВОР_ПЛИТА\.подъём - ДВОР_ПЛИТА\.t \/ 2/.test(блок),
      'плита двора не считается от подъёма: верх плиты уедет от земли',
    );
  });
});
