// Угловые башни города Исфахана: настоящая модель вместо цилиндров с колпаками.
//
// ЧТО БЫЛО. Восемь башен по углам стены строились из
// `CylinderGeometry(3, 3.6, 9)` и `ConeGeometry(3.6, 2.6)` — трубы с
// конусными шляпами. При выходе к воротам это читалось в упор: город был
// окружён колоннами с колпаками, а не башнями.
//
// ЧТО СТАЛО. `decor/onion-dome-tower.glb` — та же модель, что уже стоит к
// востоку от мечети. Она сжата Draco, лежит в манифесте, текстуры на месте.
// Сеть одна: загрузчик декораций кэширует по пути, восемь башен — одна
// загрузка и восемь копий.
//
// ГЛАВНОЕ, ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, — НЕ ФОРМА КОДА, А СООТВЕТСТВИЕ ЧИСЛАМ
// НАСТОЯЩЕЙ МОДЕЛИ. Масштаб и радиус коллайдера выведены из габаритов
// файла, который лежит в репозитории. Если модель когда-нибудь перегонят
// заново и она станет другой, проверка должна упасть и заставить пересчитать
// числа руками, а не поехать молча с неверным масштабом.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Габариты GLB по данным accessor'ов POSITION. Читается как есть, без декодирования. */
function габаритыGLB(путь: string): { size: number[]; min: number[]; max: number[] } {
  const buf = readFileSync(join(корень, путь));
  must(buf.slice(0, 4).toString('ascii') === 'glTF', `${путь}: не GLB`);
  const длинаJSON = buf.readUInt32LE(12);
  const gltf = JSON.parse(buf.slice(20, 20 + длинаJSON).toString('utf-8')) as {
    meshes?: { primitives?: { attributes: { POSITION: number } }[] }[];
    accessors?: { min?: number[]; max?: number[] }[];
  };
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  for (const mesh of gltf.meshes ?? []) {
    for (const prim of mesh.primitives ?? []) {
      const acc = gltf.accessors?.[prim.attributes.POSITION];
      if (!acc?.min || !acc?.max) continue;
      for (let k = 0; k < 3; k++) {
        min[k] = Math.min(min[k], acc.min[k]);
        max[k] = Math.max(max[k], acc.max[k]);
      }
    }
  }
  return { size: [0, 1, 2].map((k) => +(max[k] - min[k]).toFixed(3)), min, max };
}

const ПУТЬ_МОДЕЛИ = 'client/src/app/public/models/decor/onion-dome-tower.glb';
const БАШНЯ_ВЫСОТА_МОДЕЛИ = 25.504;
const БАШНЯ_СЛЕД_МОДЕЛИ = 10.36;

describe('Угловые башни города стоят на настоящей модели', () => {
  it('файл модели на месте и он в манифесте', () => {
    must(existsSync(join(корень, ПУТЬ_МОДЕЛИ)), `${ПУТЬ_МОДЕЛИ} нет: башни останутся пустыми`);
    const манифест = JSON.parse(
      читать('client/src/app/public/models/manifest.json'),
    ) as { decor?: { file: string; name: string; bytes: number }[] };
    const запись = (манифест.decor ?? []).find(
      (з) => з.file === 'models/decor/onion-dome-tower.glb',
    );
    must(запись !== undefined, 'башни нет в манифесте: расхождение файла и манифеста не увидят');
    const размер = readFileSync(join(корень, ПУТЬ_МОДЕЛИ)).length;
    must(
      размер === запись!.bytes,
      `в манифесте ${запись!.bytes} байт, на диске ${размер}: файл заменили, а манифест нет`,
    );
  });

  it('примитивов-труб с колпаками больше нет', () => {
    // Ломка с откатом: вернуть CylinderGeometry(3, 3.6, 9) и ConeGeometry(3.6,
    // 2.6) — и город снова станет окружённым трубами.
    must(
      !/CylinderGeometry\(3, 3\.6, 9, 10\)/.test(ТЕРРЕЙН),
      'прежняя башня-цилиндр снова в коде: город окружён трубами с колпаками',
    );
    must(
      !/ConeGeometry\(3\.6, 2\.6, 10\)/.test(ТЕРРЕЙН),
      'прежний колпак-конус снова в коде: башня без настоящей модели',
    );
  });

  it('восемь башен на радиусе стены, через 45 градусов', () => {
    // Ломка: иначе башен будет не восемь, или они встанут не на стену, и
    // защита города пропадёт с одной из сторон.
    must(/БАШНЯ_МОДЕЛЬ = 'decor\/onion-dome-tower\.glb'/.test(ТЕРРЕЙН), 'башня не берёт настоящую модель');
    must(/for \(let i = 0; i < 8; i\+\+\) \{\s*\n\s*const a = \(i \/ 8\) \* Math\.PI \* 2;/.test(ТЕРРЕЙН),
      'башен не восемь или они не через равный угол');
    must(/const wx = CITY\.x \+ Math\.cos\(a\) \* CITY\.radius;/.test(ТЕРРЕЙН),
      'башня встаёт не на радиус стены');
  });

  it('высота модели в коде совпадает с настоящим файлом', () => {
    // Главная проверка набора. Масштаб считается как «хочу 11 м, делю на
    // высоту модели», и высота модели — это константа в коде. Если модель
    // перегонят заново, она перестанет совпадать, и проверка упадёт.
    const { size } = габаритыGLB(ПУТЬ_МОДЕЛИ);
    must(
      Math.abs(size[1] - БАШНЯ_ВЫСОТА_МОДЕЛИ) < 0.01,
      `в коде высота модели ${БАШНЯ_ВЫСОТА_МОДЕЛИ} м, в файле ${size[1]} м. Масштаб башни поехал бы молча — пересчитай`,
    );
    must(
      Math.abs(size[2] - БАШНЯ_СЛЕД_МОДЕЛИ) < 0.01,
      `в коде след модели ${БАШНЯ_СЛЕД_МОДЕЛИ} м, в файле ${size[2]} м. Коллайдер считается от следа и поедет`,
    );
  });

  it('модель стоит основанием на земле, начало координат в основании', () => {
    // Ломка: если начало координат модели окажется в центре объёма, башня
    // наполовику уйдёт под землю. Проверяем по нижней границе.
    const { min } = габаритыGLB(ПУТЬ_МОДЕЛИ);
    must(
      Math.abs(min[1]) < 0.01,
      `низ модели на ${min[1]} м, а не на нуле: башня встанет в землю или в воздух`,
    );
  });

  it('коллайдер считается от следа модели, а не от прежнего примитива', () => {
    // Прежний радиус 4.1 брался от примитива радиусом 3.6. У настоящей модели
    // след 4.47 м, то есть r = 2.23, и с запасом 2.6. Если вернуть 4.1, игрок
    // будет упираться в воздух в полутора метрах от башни.
    must(/const БАШНЯ_СЛЕД = 10\.36 \* БАШНЯ_МАСШТАБ;/.test(ТЕРРЕЙН), 'след башни не считается от модели');
    must(/const БАШНЯ_РАДИУС = БАШНЯ_СЛЕД \/ 2 \+ 0\.4;/.test(ТЕРРЕЙН),
      'радиус коллайдера не считается от следа башни');
    must(/addCollider\(wx, wz, БАШНЯ_РАДИУС\)/.test(ТЕРРЕЙН), 'коллайдер башни не использует посчитанный радиус');
    must(
      !/addCollider\(CITY\.x \+ Math\.cos\(a\) \* CITY\.radius, CITY\.z \+ Math\.sin\(a\) \* CITY\.radius, 4\.1\)/.test(ТЕРРЕЙН),
      'вернулся прежний радиус 4.1 от примитива: игрок упирается в воздух',
    );
  });

  it('база каждой башни берётся из земли под ней, а не общая высота', () => {
    // Стена идёт по окружности 116, где рельеф меняется. Общая высота
    // оставила бы одну из восьми башен висящей или утонувшей — это ровно то,
    // из-за чего стена когда-то уходила в землю на половине окружности.
    must(/localY\(т\.x, т\.z\)/.test(ТЕРРЕЙН), 'высота базы башни не берётся из земли под точкой');
  });

  it('восемь копий из одной загрузки, а не восемь запросов', () => {
    // Ломка с откатом. Первая версия этой проверки считала литерал
    // `loadDecorModel('decor/onion-dome-tower.glb')` — и ПРОХОДИЛА на старом
    // коде, где башен-труб вообще нет: единственный такой вызов и так есть,
    // у башни к востоку от мечети. Проверка охраняла чужой код и ничего не
    // говорила о башнях города.
    //
    // Теперь сторожит то, что относится к делу: путь вынесен в константу,
    // загрузка по ней одна, а копии делаются в цикле по восьми точкам.
    must(/const БАШНЯ_МОДЕЛЬ = 'decor\/onion-dome-tower\.glb';/.test(ТЕРРЕЙН),
      'путь модели башни не вынесен в константу: восемь башен нечем собрать из одной загрузки');
    const вызовы = ТЕРРЕЙН.match(/loadDecorModel\(БАШНЯ_МОДЕЛЬ\)/g) ?? [];
    must(вызовы.length === 1,
      `модель башен грузится ${вызовы.length} раз: восемь башен должны быть восемью копиями одной загрузки`);
    must(/const башня = модель\.clone\(\);/.test(ТЕРРЕЙН),
      'башни не клонируются из одной модели, а грузятся по одной');
    must(/for \(const т of БАШНЯ_ТОЧКИ\)/.test(ТЕРРЕЙН),
      'копии не делаются по списку точек: восемь башен должны строиться циклом');
  });
});