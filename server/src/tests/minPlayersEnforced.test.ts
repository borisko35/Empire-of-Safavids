// minPlayers: число наконец что-то значит — но только у рейдов.
//
// ЧТО БЫЛО. Поле minPlayers записано у всех шести подземелий (1, 3, 5...,
// 10 у рейда) и не читалось НИГДЕ. Решение владельца: проверять только у
// рейдов. Причина не в лени, а в том, что жёсткий минимум везде сделал бы
// одиночную игру невозможной — у караван-сарая заявлено 5, у гробницы 3.
//
// ПОЧЕМУ ПРОВЕРКА НА ЗАВЕРШЕНИИ, А НЕ НА ВХОДЕ. Рейд и собирают: открывают
// сбор и набирают людей. Запретить вход одному значило бы запретить открыть
// сбор вообще — рейд стал бы недостижим. Недостижимым он становится на
// завершении: штурм меньшим составом не засчитывается.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const сервис = код('server/src/systems/DungeonService.ts');
const данные = читать('server/src/data/dungeons.ts');
const панель = код('client/src/app/panels.ts');
const апи = код('client/src/app/api.ts');

describe('minPlayers: правило действует', () => {
  it('поле заполнено у подземелий', () => {
    // Без этой проверки тест был бы страховкой от воображаемой проблемы.
    const значений = (данные.match(/minPlayers:/g) ?? []).length;
    must(значений >= 5, `minPlayers есть у ${значений} подземелий — чинить нечего`);
  });

  it('проверка читает поле', () => {
    must(/def\.minPlayers/.test(сервис), 'minPlayers по-прежнему не читается');
  });

  it('проверяется только у рейдов', () => {
    // Решение владельца. У обычных подземелий число не трогаем: игрок должен
    // иметь право зайти в гробницу в одиночку.
    must(
      /if \(def\.isRaid && session\.members\.size < def\.minPlayers\)/.test(сервис),
      'проверка не ограничена рейдами: одиночная игра сломается',
    );
  });
});

describe('minPlayers: проверка в правильном месте', () => {
  it('стоит на завершении, а не на входе', () => {
    // На входе она запретила бы открыть сбор вообще.
    must(/raid_under_min_players/.test(сервис), 'кода отказа нет');
    must(
      /входа/.test(сервис) === false || /enter/.test(сервис) === false,
      'проверка появилась и на входе: рейд стало не открыть',
    );
  });

  it('отказ не ломает заход', () => {
    // completedAt снимается: заход снова живой, игроки внутри, босс ждёт
    // остальных. Иначе нехватка людей закрывала бы заход навсегда.
    must(
      /session\.completedAt = undefined;/.test(сервис),
      'при отказе completedAt остаётся выставленным: заход закроется как завершённый',
    );
  });

  it('в отказе есть числа, а не молчание', () => {
    // Игрок должен понять, сколько не хватает.
    must(/minPlayers: def\.minPlayers/.test(сервис), 'в отказе нет требований');
    must(/have: session\.members\.size/.test(сервис), 'в отказе нет фактического состава');
  });
});

describe('minPlayers: число видно игроку', () => {
  it('панель показывает минимум — только у рейдов', () => {
    must(/d\.isRaid && d\.minPlayers/.test(панель),
      'панель показывает минимум не разбирая, рейд это или нет: обычные подземелья получили бы ложное обещание');
  });

  it('тип ответа несёт число', () => {
    must(/minPlayers\?: number/.test(апи), 'minPlayers не объявлен в типе: панель не смогла бы нарисовать');
  });

  it('подпись переведена во всех трёх языках', () => {
    for (const кодЯзыка of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${кодЯзыка}.json`)) as {
        panels: Record<string, string>;
      };
      must(
        словарь.panels?.min_players,
        `в ${кодЯзыка}.json нет panels.min_players: панель покажет пустое имя`,
      );
    }
  });
});