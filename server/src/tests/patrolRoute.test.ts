// Патруль: сторожевой пост, который ходит.
//
// ЗАЧЕМ ЭТОТ ШАГ. Стоящий страж не создаёт напряжения: с ним можно просто
// уйти в сторону, и он ничего не сможет. Владелец просил наблюдателя, который
// замечает игрока В ДВИЖЕНИИ - это основа для «скрытого пути в крепости».
//
// ГЛАВНОЕ ТРЕБОВАНИЕ ФАЙЛА. Позиция стража обязана совпадать на картинке и в
// правиле. Если сервер считает по своим числам, а клиент двигает модель у себя,
// они разойдутся - ровно как разошлись двери интерьеров, когда координаты
// комнат жили в двух списках. Поэтому здесь проверяется, что клиент зовёт ту
// же postPosition из shared, а не какую-то свою формулу.
//
// ПОЧЕМУ СЧИТАЕМ ЧИСЛА. Поиск строки "patrol" доказал бы наличие поля. Здесь
// считается, куда страж приходит за цикл и с какой скоростью идёт.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { GUARD_POSTS, postPosition, spottedBy, GUARD_SIGHT } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const патрульные = GUARD_POSTS.filter((p) => p.patrol);
const стоящие = GUARD_POSTS.filter((p) => !p.patrol);

describe('Патруль: маршрут задан и он не вырожденный', () => {
  it('патрульный есть, а стоящие посты остались стоящими', () => {
    must(патрульные.length > 0, 'никто не ходит: патруля нет');
    must(стоящие.length > 0, 'все посты ходят: это не патруль, а карусель');
  });

  it('маршрут не нулевой длины и период положительный', () => {
    for (const p of патрульные) {
      const длина = Math.hypot(p.patrol!.toX - p.x, p.patrol!.toZ - p.z);
      must(длина > 1, `маршрут поста ${p.id} короче единицы: страж не пройдёт и шага`);
      must(p.patrol!.periodMs > 0, `у поста ${p.id} неположительный период`);
    }
  });

  it('страж идёт не быстрее игрока', () => {
    // Скорость игрока измерена в коде: WALK_SPEED = 4.2, RUN_SPEED = 7.6
    // (client/src/app/game3d/world3d.ts). Если страж быстрее бега, он
    // догоняет игрока на своей скорости и скрытность становится нечестной.
    const БЕГ = 7.6;
    for (const p of патрульные) {
      const длина = Math.hypot(p.patrol!.toX - p.x, p.patrol!.toZ - p.z);
      // Полный цикл - это туда и обратно, то есть удвоенная длина.
      const скорость = (длина * 2) / (p.patrol!.periodMs / 1000);
      must(
        скорость < БЕГ,
        `скорость патруля ${скорость.toFixed(2)} ед/с не меньше бега игрока ${БЕГ}: ` +
          `пост ${p.id} обгоняет игрока на своей скорости`
      );
      // И не слишком медленно: иначе страж фактически стоит на месте.
      must(
        скорость > 0.3,
        `скорость патруля ${скорость.toFixed(2)} ед/с почти нулевая: пост ${p.id} не ходит`
      );
    }
  });
});

describe('Патруль: позиция считается одинаково обеими сторонами', () => {
  it('путь замкнут: через полпериода страж на середине, через период вернулся', () => {
    for (const p of патрульные) {
      const начало = postPosition(p, 0);
      const середина = postPosition(p, p.patrol!.periodMs / 2);
      const конец = postPosition(p, p.patrol!.periodMs);

      must(Math.abs(середина.x - p.patrol!.toX) < 1e-6, `через полпериода страж не в конечной точке (x=${середина.x})`);
      must(Math.abs(середина.z - p.patrol!.toZ) < 1e-6, `через полпериода страж не в конечной точке (z=${середина.z})`);

      must(Math.abs(начало.x - конец.x) < 1e-6, 'через период страж не вернулся в начальную точку');
      must(Math.abs(начало.z - конец.z) < 1e-6, 'через период страж не вернулся в начальную точку');
    }
  });

  it('ход непрерывен: за секунду страж не прыгает', () => {
    for (const p of патрульные) {
      let предыдущая = postPosition(p, 0);
      // Секунда за секундой - не тысячи точек: достаточно, чтобы поймать
      // телепорт на развороте маршрута.
      for (let секунда = 1; секунда <= 20; секунда++) {
        const текущая = postPosition(p, секунда * 1000);
        const шаг = Math.hypot(текущая.x - предыдущая.x, текущая.z - предыдущая.z);
        must(
          шаг <= (Math.hypot(p.patrol!.toX - p.x, p.patrol!.toZ - p.z) * 2) / 5 + 0.01,
          `пост ${p.id} за секунду сместился на ${шаг.toFixed(2)} ед - это прыжок, а не ходьба`
        );
        предыдущая = текущая;
      }
    }
  });

  it('без маршрута пост стоит ровно на месте', () => {
    for (const p of стоящие) {
      must(
        postPosition(p, 12345).x === p.x && postPosition(p, 12345).z === p.z,
        `пост ${p.id} без маршрута сдвинулся сам по себе`
      );
    }
  });

  it('клиент двигает модель той же функцией, что и правило', () => {
    const npc = читать('client/src/app/game3d/npc.ts');
    must(npc.length > 1000, 'npc.ts не прочитан');
    must(
      /import \{[^}]*postPosition[^}]*\} from '\.\.\/\.\.\/\.\.\/\.\.\/shared\/stealth'/.test(npc),
      'клиент не импортирует postPosition из shared: считает позицию по-своему, ' +
        'и страж на экране разойдётся со стражем в правиле'
    );
    must(/walkers/.test(npc), 'в клиенте нет списка патрульных: тело стража не двигается');
    // Клиентский tsconfig собирает shared/stealth.ts - иначе импорт не сработает.
    const tsconfig = читать('client/tsconfig.json');
    must(tsconfig.includes('shared/stealth.ts'), 'shared/stealth.ts не вписан в client/tsconfig.json');
  });

  it('сервер передаёт время в правило', () => {
    const socket = читать('server/src/socket/GameSocketHandler.ts');
    must(
      /spottedBy\([\s\S]{0,400}?Date\.now\(\)/.test(socket),
      'сервер не передаёт Date.now() в spottedBy: патрульный считается по нулевому времени, ' +
        'то есть стоит на своей точке, и страж на экране уйдёт, а в правиле останется'
    );
  });
});

describe('Патруль: он меняет то, ради чего делался', () => {
  it('одна и та же точка игрока то замечена, то нет - в зависимости от времени', () => {
    const патруль = патрульные[0];
    // Точка рядом с началом маршрута, но достаточно далеко, чтобы в момент,
    // когда страж ушёл к концу, она оказалась вне его обзора.
    const длина = Math.hypot(патруль.patrol!.toX - патруль.x, патруль.patrol!.toZ - патруль.z);
    const nx = (патруль.patrol!.toX - патруль.x) / длина;
    const nz = (патруль.patrol!.toZ - патруль.z) / длина;
    // Точка сбоку от маршрута, на расстоянии чуть больше обзора в момент,
    // когда страж стоит в начале.
    const точка = {
      x: патруль.x - nz * (GUARD_SIGHT + 2) + nx * 3,
      z: патруль.z + nx * (GUARD_SIGHT + 2) + nz * 3,
    };

    const уНачала = spottedBy(точка, [патруль], {}, 0);
    const уКонца = spottedBy(точка, [патруль], {}, патруль.patrol!.periodMs / 2);
    must(
      уНачала === null || уКонца === null || уНачала.id !== уКонца.id,
      'патруль не меняет картину вообще: одна и та же точка замечена в обе фазы, ' +
        'то есть ходящий страж не отличается от стоящего'
    );
  });

  it('заметивший страж меняет своё место', () => {
    const патруль = патрульные[0];
    // Ловим любую фазу, в которой страж заметил игрока в своей точке,
    // и проверяем, что в другой фазе он там уже не стоит.
    let пойман = false;
    for (let ф = 0; ф <= 8 && !пойман; ф++) {
      const t = (ф / 8) * патруль.patrol!.periodMs;
      const где = postPosition(патруль, t);
      if (spottedBy(где, [патруль], {}, t) !== null) {
        const позже = postPosition(патруль, t + патруль.patrol!.periodMs / 2);
        const сдвиг = Math.hypot(позже.x - где.x, позже.z - где.z);
        must(сдвиг > 1, 'страх заметил, но за полпериода не сдвинулся - он стоячий');
        пойман = true;
      }
    }
    must(пойман, 'не нашлось фазы, в которой страж видит игрока рядом с собой');
  });
});