// Марево в жару над пустыней.
//
// ЧТО БЫЛО (21 октября 2026, §265). В пустыне в жару над горизонтом должно
// «плавать» марево. Было чистое небо — и пустыня читалась как декорация.
//
// ЧТО ТЕПЕРЬ. Над горизонтом стоит полоса марева, она идёт за игроком и дышит
// волнами. Появляется только в жару: солнце высоко, день, небо не совсем
// пасмурно. В дождь, снег, бурю и туман марева нет.
//
// ЧТО ПРОВЕРЯЕТСЯ. Полоса есть, идёт за игроком и дышит; жар считается от
// высоты солнца, дня и пасмурности; в непогоду марева нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАРЕВО = читать('client/src/app/game3d/mirage.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Марево в жару', () => {
  it('полоса идёт за игроком и дышит', () => {
    должен(/export function createMirage/.test(МАРЕВО), 'нет марева');
    // Кольцо вокруг игрока.
    должен(
      /кольцо\.position\.x = px;[\s\S]{0,80}?кольцо\.position\.z = pz;/.test(МАРЕВО),
      'полоса марева не идёт за игроком',
    );
    // Дышит: две волны и ползущий текст.
    должен(/const волна = Math\.sin\(now \/ 1400\) \* 0\.6 \+ Math\.sin\(now \/ 620\) \* 0\.4;/.test(МАРЕВО),
      'полоса марева не дышит');
    должен(/текстура\.offset\.x = \(now \/ 2600\) % 1;/.test(МАРЕВО), 'текстура марева не ползёт');
  });

  it('жар считается от солнца, дня и пасмурности', () => {
    должен(
      /Math\.max\(0, Math\.min\(1, \(sunDir\.y - 0\.12\) \/ 0\.45\)\) \* \(1 - night\) \* \(1 - this\.sky\.overcast\)/.test(
        МИР,
      ),
      'жар не считается от высоты солнца и пасмурности',
    );
    // В непогоду марева нет.
    должен(
      /const неЖарко = this\.currentWeather === 'rain' \|\| this\.currentWeather === 'storm'[\s\S]{0,300}?this\.currentWeather === 'fog';/.test(
        МИР,
      ),
      'в дождь и снег марево не выключается',
    );
    должен(/const жар = неЖарко\s*\?\s*0\s*:/ .test(МИР), 'в непогоду марево всё равно видно');
    // Движок зовёт марево.
    должен(/this\.марево\.update\(dt, now, me\.pos\.x, me\.pos\.z, жар\);/.test(МИР), 'марево не обновляется');
  });

  it('марево создаётся и вычищается вместе с миром', () => {
    должен(/this\.марево = createMirage\(this\.scene\);/.test(МИР), 'марево не создаётся');
    должен(/this\.марево\?\.dispose\(\);/.test(МИР), 'марево не вычищается');
  });
});
