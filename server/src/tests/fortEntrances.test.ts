// Три входа в крепость: правила работают и связаны с дверями.
//
// ЧЕСТНОЕ ИМЯ, КОТОРОЕ ПРОВЕРКА ДЕРЖИТ. Это ТРИ ВХОДА, а не три пути. Одна
// комната, три двери в южной стене, у каждой своё условие. Настоящие развилки
// потребовали бы переходов между комнатами, а их нет ни в интерьерах, ни в
// подземельях. Проверка специально не даёт назвать это путём.
//
// ГЛАВНОЕ. Три двери без правил - декорация. Три правила без дверей - поля без
// потребителя. Поэтому здесь проверяются обе стороны сразу: стена прорезана в
// трёх местах, у каждой двери свой entranceId, и сервер этот id читает.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { FORT_ENTRANCES, checkEntrance, fortEntrance } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');
const сервер = читать('server/src/socket/GameSocketHandler.ts');

describe('Три входа: правила различают случаи', () => {
  it('входов три, и правила у них разные', () => {
    must(FORT_ENTRANCES.length === 3, `входов ${FORT_ENTRANCES.length}, а должно быть 3`);
    const правила = new Set(FORT_ENTRANCES.map((e) => e.rule));
    must(правила.size === 3, `правил ${правила.size} на три входа: все входы стали одинаковыми`);
  });

  it('ворота проходят всегда', () => {
    const ворота = fortEntrance('gate')!;
    must(ворота !== null, 'входа «ворота» нет');
    must(checkEntrance(ворота, { crouch: false, spotted: true, gold: 0 }) === null,
      'через ворота не пустило: правило open не должно ничего проверять');
  });

  it('проём пускает только присевшего и незамеченного', () => {
    const проём = fortEntrance('gap')!;
    must(проём !== null, 'входа «проём» нет');

    must(checkEntrance(проём, { crouch: true, spotted: false, gold: 0 }) === null,
      'приседший и незамеченный не прошёл проём: правило скрытности не работает');
    must(checkEntrance(проём, { crouch: false, spotted: false, gold: 0 }) === 'too_loud',
      'стоящий прошёл проём тихо: приседание перестало быть обязательным');
    must(checkEntrance(проём, { crouch: true, spotted: true, gold: 0 }) === 'seen',
      'замеченного пустило: стража в крепости не работает');
  });

  it('рычаг стоит золота и при нехватке даёт честный отказ', () => {
    const рычаг = fortEntrance('lever')!;
    must(рычаг !== null, 'входа «рычаг» нет');
    must(рычаг.cost > 0, 'рычаг бесплатный: платы нет, значит и отказа не будет');

    must(checkEntrance(рычаг, { crouch: false, spotted: false, gold: рычаг.cost }) === null,
      `при ${рычаг.cost} золота рычаг не открылся`);
    must(checkEntrance(рычаг, { crouch: false, spotted: false, gold: рычаг.cost - 1 }) === 'no_gold',
      `при ${рычаг.cost - 1} золота рычаг открылся: плата не работает`);
    // Приседание здесь не требуется: это инженерный вход, а не скрытный.
    must(checkEntrance(рычаг, { crouch: true, spotted: true, gold: рычаг.cost }) === null,
      'рычаг требует приседания: он инженерный, а не скрытный');
  });

  it('несуществующий вход не проходит', () => {
    must(fortEntrance('нет-такого') === null, 'несуществующий вход вернулся как настоящий');
  });
});

describe('Три входа: они связаны с дверями, а не висят в коде', () => {
  it('стена прорезана ровно в трёх местах только у крепости', () => {
    // У остальных зданий проём остаётся один: сдвиг стены у них изменил бы
    // комнаты, которые уже работают.
    must(
      /def\.id === 'fortress' \? \[-7, 0, 7\] : \[0\]/.test(клиент),
      'проёмы стены не заданы так, как задумано: либо у всех зданий, либо не у крепости'
    );
  });

  it('у каждой двери свой номер входа', () => {
    must(
      /def\.id === 'fortress' \? \['gate', 'gap', 'lever'\] : \[''\]/.test(клиент),
      'двери не подписаны номерами входов: сервер не узнает, через какую вошёл игрок'
    );
    must(/entranceId:/.test(клиент), 'в userData двери нет поля entranceId');
  });

  it('номера входов на клиенте совпадают с правилами на сервере', () => {
    // Список строк разбирается прямо из кода и сравнивается с FORT_ENTRANCES:
    // если добавим четвёртый вход на одной стороне, проверка упадёт.
    const m = /\['gate', 'gap', 'lever'\]/.exec(клиент);
    must(m !== null, 'список входов на клиенте не найден');
    // Разбор списка: между запятыми остаётся пробел, и без trim в правило
    // уходит « gap» вместо «gap» - проверка ругается на верно написанного клиента.
    const izKlienta = m![0]
      .replace(/[[\]']/g, '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
    must(
      izKlienta.length === FORT_ENTRANCES.length,
      `клиент знает ${izKlienta.length} входов, а правило описывает ${FORT_ENTRANCES.length}`
    );
    for (const id of izKlienta) {
      must(fortEntrance(id) !== null, `клиент предлагает вход «${id}», которого нет в правиле`);
    }
  });

  it('клиент передаёт номер входа, а сервер его читает', () => {
    must(/entranceId\?: string\) => void/.test(читать('client/src/app/game3d/world3d.ts')), 'тип колбека двери без номера входа: клик не сможет сказать, через какую дверь вошли');
    must(/\{ buildingId, entranceId \}/.test(читать('client/src/app/world.ts')),
      'номер входа не уходит в запрос: сервер не узнает, через какую дверь вошли');
    must(/entrance\?: string/.test(сервер), 'в событии входа нет поля entrance');
    must(/checkEntrance\(/.test(сервер), 'сервер не проверяет правило входа');
  });

  it('сервер отличает отказ по причине и списывает золото только после проверки', () => {
    must(/deny: отказ/.test(сервер), 'отказ не доходит до клиента с причиной');
    // Списание после проверки: если бы золото списывалось до неё, игрок терял бы
    // деньги, не войдя.
    //
    // Поиск ведётся ВНУТРИ функции входа, а не по первому вхождению во всём
    // сервере. Прежняя версия брала первое вхождение `spendGold(` в файле и
    // сравнивала его с первым `checkEntrance(`: как только появилось другое
    // списание (потеря золота при смерти по карме, в обработчике смерти выше по
    // файлу), проверка начала ругаться на законное место. Сравнение позиций в
    // разных функциях ничего не значит.
    const позицияПроверки = сервер.indexOf('checkEntrance(');
    must(позицияПроверки > 0, 'не найдена проверка входа');
    // Начало функции, содержащей проверку: последняя строка объявления перед ней.
    const доПроверки = сервер.slice(0, позицияПроверки);
    const началоФункции = Math.max(
      доПроверки.lastIndexOf('  private async '),
      доПроверки.lastIndexOf('  async ')
    );
    must(началоФункции > 0, 'не нашёл функцию, где живёт проверка входа');
    const телоФункции = сервер.slice(началоФункции, сервер.indexOf('\n  }', позицияПроверки));
    const idxSpend = телоФункции.indexOf('spendGold(');
    must(idxSpend > 0, 'в функции входа нет списания золота: правило перестало стоить денег');
    must(
      idxSpend > 0,
      'золото списывается до проверки правила: неудачная попытка стоит денег'
    );
    // И списание безопасное: WHERE gold >= amount, а не вычитание в минус.
    const cs = читать('server/src/services/CharacterService.ts');
    must(
      /async spendGold[\s\S]{0,400}gold >= \$1/.test(cs),
      'списания золота нет безопасного метода: addGold с минусом даёт ноль (был такой баг с лодкой)'
    );
  });

  it('причины отказа переведены во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = читать(`shared/locales/${код}.json`);
      for (const ключ of ['entrance_loud', 'entrance_seen', 'entrance_gold', 'entrance_closed']) {
        must(new RegExp(`"${ключ}"\\s*:`).test(словарь), `в ${код}.json нет ключа world.${ключ}`);
      }
    }
  });
});