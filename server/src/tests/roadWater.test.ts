// Вода в колеях дороги и лужи в пригороде.
//
// ЧТО БЫЛО (21 октября 2026, §269). После ливня лужи были только на городской
// площади (§264). В пригороде и у дороги сухо: колея, выбитая тысячами колёс,
// стоит сухой, хотя вокруг мокро.
//
// ЧТО ТЕПЕРЬ. В колеях дороги после дождя стоит вода — две узкие тёмные
// ленты вдоль полотна, глянцевые. И в пригороде, где земля мягче, — лужи.
//
// ЧТО ПРОВЕРЯЕТСЯ. Вода стоит именно в колеях (поперёк полотна, по обе
// стороны от осевой линии), а не плёнкой под дорогой; лужи в пригороде
// проступают порциями, как городские; и всё это живёт по мокроте земли.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ВОДА = читать('client/src/app/game3d/roadWater.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Вода в колеях дороги', () => {
  it('вода стоит в колеях, а не плёнкой под дорогой', () => {
    должен(/export function createRoadWater/.test(ВОДА), 'нет воды на дороге');
    // Две ленты — левая и правая колея.
    должен(/for \(const сторона of \[-1, 1\]\)/.test(ВОДА), 'колей не две');
    // Смещение поперёк полотна, от осевой линии.
    должен(
      /const половина = ближняя\.дорога\.w \* КОЛЯ;[\s\S]{0,400}?лента\.position\.set\(ближняя\.x \+ nx, y, ближняя\.z \+ nz\);/.test(
        ВОДА,
      ),
      'вода не стоит по обе стороны от осевой линии',
    );
    // Глянцевая: вода отражает небо, мокрый песок — просто темнее.
    должен(/roughness: 0\.1,/.test(ВОДА), 'вода в колеях не глянцевая');
  });

  it('лужи в пригороде проступают порциями', () => {
    должен(/const ПРИГОРОД: \{ x: number; z: number; r: number; порог: number \}\[\] = \[/.test(ВОДА),
      'нет луж в пригороде');
    должен(
      /const доля = Math\.max\(0, Math\.min\(1, \(м - л\.порог\) \/ 0\.3\)\);/.test(ВОДА),
      'лужи в пригороде появляются разом, а не порциями',
    );
  });

  it('вода живёт по мокроте земли и вычищается с миром', () => {
    должен(/this\.водаДороги\.update\(dt, now, me\.pos\.x, me\.pos\.z, this\.мокрота\);/.test(МИР),
      'вода на дороге не обновляется');
    должен(/this\.водаДороги\?\.dispose\(\);/.test(МИР), 'вода на дороге не вычищается');
    должен(/this\.водаДороги = createRoadWater\(this\.scene\);/.test(МИР), 'вода на дороге не создаётся');
  });
});
