// Появление NPC переходных зон: фигуры появляются по расписанию и только там.
//
// ЧТО ЗАЩИЩАЕТ. Расписание сделано и проверено, но оно ничего не рисует. Эта
// проверка закрывает разрыв между «правило считает» и «игрок видит».
//
// ГЛАВНЫЕ РИСКИ ЗДЕСЬ, и почему они именно такие:
//   1. Фигура создаётся один раз при сборке мира. Если не выключить её видимость
//      сразу, патруль, караван и банда будут стоять на тропе ВСЕГДА — то есть
//      механика «раз в 20 минут» станет «постоянно».
//   2. Проходящие по тропе не должны попадать в кликабельные объекты и в
//      коллайдеры: у жителей города есть панель диалога, а у патруля её нет, и
//      стоять вплотную к идущему нельзя — он идёт.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { TRANSITION_EVENTS, transitionEventsNow } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const npc = читать('client/src/app/game3d/npc.ts');

describe('Появление переходных зон: фигуры создаются, но не видны сразу', () => {
  it('фигура создаётся невидимой — иначе тропа занята всегда', () => {
    // Ключевая строка. Без неё три фигуры стоят на тропе с момента загрузки
    // мира, и расписание перестаёт что-либо значить.
    must(
      /rig\.group\.visible = false;/.test(npc),
      'фигуры переходных зон создаются видимыми: патруль, караван и банда будут стоять на тропе всегда'
    );
  });

  it('видимость и позиция берутся из расписания, а не заданы вручную', () => {
    must(/transitionEventsNow\(now\)/.test(npc), 'клиент не спрашивает расписание: фигуры не знают, когда появиться');
    must(
      /transitionEventsNow\(now - 1\)/.test(npc),
      'направление не берётся из предыдущей позиции: фигура не развернётся по ходу движения'
    );
    must(/п\.group\.visible = true;/.test(npc), 'фигура не становится видимой, когда событие есть');
    must(/п\.group\.visible = false;/.test(npc), 'фигура не прячется, когда события нет');
  });

  it('фигура ставится на землю, а не висит в воздухе', () => {
    must(
      /п\.group\.position\.set\(найдено\.x, groundHeight\(найдено\.x, найдено\.z\), найдено\.z\)/.test(npc),
      'позиция ставится без groundHeight: фигура провалится под землю или всплывёт'
    );
  });

  it('фигура идёт, а не скользит', () => {
    must(/moving: true/.test(npc), 'анимация шага не включена: фигура скользит по земле');
  });
});

describe('Появление переходных зон: проходящие не становятся жителями', () => {
  it('фигуры переходных зон не кликабельны', () => {
    // У жителей города клик открывает панель. У патруля панели нет: если он
    // попадёт в clickTargets, игрок нажмёт в пустоту.
    // Проверяем по коду блока создания: там НЕ должно быть push в clickTargets
    // и НЕ должно быть userData с панелью.
    const начало = npc.indexOf('const переходные:');
    must(начало > 0, 'блок создания фигур не найден');
    const до = npc.indexOf('for (const событие of TRANSITION_EVENTS)', начало);
    must(до > начало, 'цикл создания фигур не найден');
    // Граница блока — следующая строка «for (const { origin, npcs } of NPC_GROUPS)».
    const конец = npc.indexOf('for (const { origin, npcs } of NPC_GROUPS)', до);
    const блок = npc.slice(до, конец > 0 ? конец : до + 1500);
    must(!/clickTargets\.push/.test(блок), 'фигуры переходных зон попали в clickTargets: клик откроет пустую панель');
    must(!/npcPanel/.test(блок), 'фигурам переходных зон назначена панель диалога: у них нет диалога');
    must(!/COLLIDERS\.push/.test(блок), 'фигуры переходных зон попали в коллайдеры: игрок встанет вплотную к идущему');
    must(!/textSprite/.test(блок), 'фигуры переходных зон подписаны именами: имя над головой выдаёт их за жителей');
  });

  it('вид у каждого события свой — их нельзя перепутать', () => {
    for (const вид of ['patrol', 'caravan', 'band']) {
      must(
        new RegExp("событие\\.kind === '" + вид + "'").test(npc) ||
          /событие\.kind === 'patrol'[\s\S]{0,400}событие\.kind === 'caravan'[\s\S]{0,400}событие\.kind === 'band'/.test(npc),
        `для события ${вид} нет отдельного вида: все три фигуры выглядят одинаково`
      );
    }
    must(/hat: 'helmet'/.test(npc), 'патруль без шлема: его не отличить от остальных');
    must(/hat: 'turban'/.test(npc), 'караван без тюрбана');
    must(/hat: 'hood'/.test(npc), 'банда без капюшона');
  });
});

describe('Появление переходных зон: рисунок совпадает с расписанием', () => {
  it('в коде ровно три вида фигур, по одному на событие', () => {
    // createNpcs вызывается один раз на мир; лишняя фигура означала бы либо
    // вторую копию патруля, либо забытое событие.
    //
    // Считаем НЕ циклы по имени переменной, а СОЗДАННЫЕ ФИГУРЫ. Первая версия
    // проверки считала вхождения строки `for (const событие of TRANSITION_EVENTS)`,
    // и ломка с дублирующим циклом под другим именем переменной осталась
    // зелёной: цикл новый, а имя другое. Считать надо результат, а не текст.
    const созданий = (npc.match(/переходные\.push\(/g) || []).length;
    must(созданий === 1, `фигура добавляется в список ${созданий} раз: при пересборке мира часть фигур удвоится`);
    must(TRANSITION_EVENTS.length === 3, `событий ${TRANSITION_EVENTS.length}, а фигур заведено на три`);
  });

  it('фигура видима ровно тогда, когда событие есть — по тем же данным', () => {
    // Прямая проверка: берём тот же список, что использует клиент, и сверяем
    // с тем, что делает код. Если в коде появится «показать всегда», эта проверка
    // его не поймает — зато поймает следующая.
    const при = transitionEventsNow(0);
    must(при.length > 0, 'в момент ноль никого нет, а первая проверка требует событие');
    for (const s of при) {
      must(s.x !== null && s.z !== null, `${s.kind} присутствует, но без координат — поставить некуда`);
    }
  });

  it('за цикл каждое событие хотя бы раз становится видимым', () => {
    // Если событие есть в расписании, но клиент никогда его не покажет,
    // механика выглядит сделанной и не работает.
    const шагов = 600;
    const период = 20 * 60 * 1000;
    const видели = new Set<string>();
    for (let i = 0; i < шагов; i++) {
      for (const s of transitionEventsNow((i * период) / шагов)) {
        if (s.x !== null) видели.add(s.kind);
      }
    }
    for (const e of TRANSITION_EVENTS) {
      must(видели.has(e.kind), `${e.kind} ни разу не получает координат за цикл: фигура не появится`);
    }
  });
});