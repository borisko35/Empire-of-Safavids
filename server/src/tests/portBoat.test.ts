// Лодка у пирса перестаёт быть воронкой с фантиком.
//
// ЧТО БЫЛО (22 октября 2026, §297). Лодка у причала: корпус — конус, парус —
// плоская плита на мачте. Лодка читалась как воронка с фантиком на палке.
//
// ЧТО ТЕПЕРЬ. Корпус собран из сечений: выгнутое днище, острый нос, круглая
// корма; борта, поперечные планки-сиденья, киль; мачта с поперечиной; парус с
// провисом на верёвочных штагах; вёсла у борта.
//
// ЧТО ПРОВЕРЯЕТСЯ. Корпус — своя геометрия из сечений (не готовый конус); есть
// борта, планки, киль, поперечина, штаги и вёсла; парус с провисом, а не плита.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Лодка — не воронка с фантиком', () => {
  it('корпус собран из сечений, а не готовый конус', () => {
    // Своя геометрия: сечения вдоль длины, в каждом — дуга днища.
    должен(/const корпусГео = new THREE\.BufferGeometry\(\);/.test(ТЕРРЕЙН), 'нет геометрии корпуса');
    должен(
      /вершины\.push\(-Math\.cos\(a\) \* ширина, -Math\.sin\(a\) \* высота, z\);/.test(ТЕРРЕЙН),
      'сечение корпуса не дуга днища',
    );
    // Ширина сходит у носа и широка у кормы.
    должен(
      /const ширина = 0\.44 \* Math\.sin\(Math\.min\(1, t \* 1\.2\) \* Math\.PI \* 0\.86 \+ 0\.1\);/.test(ТЕРРЕЙН),
      'корпус не сужается к носу',
    );
    // Готового конуса вместо корпуса быть не должно.
    должен(
      !/new THREE\.CylinderGeometry\(0\.9, 0\.5, 3\.4, 7\)/.test(ТЕРРЕЙН),
      'корпус лодки снова конус',
    );
    // Внутри лодки видно изнутри — борт двусторонний.
    должен(/доски\.side = THREE\.DoubleSide;/.test(ТЕРРЕЙН), 'внутренний борт лодки не виден');
  });

  it('борта, планки, киль и вёсла', () => {
    // Борта по краю.
    должен(
      /const борт = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.08, 0\.14, длина \* 0\.86\)/.test(ТЕРРЕЙН),
      'у лодки нет бортов',
    );
    // Поперечные планки — сиденья.
    должен(
      /const планка = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.8, 0\.07, 0\.2\)/.test(ТЕРРЕЙН),
      'у лодки нет планок',
    );
    // Киль вдоль днища.
    должен(
      /const киль = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.1, 0\.16, длина \* 0\.9\)/.test(ТЕРРЕЙН),
      'у лодки нет киля',
    );
    // Вёсла: древко и лопасть.
    должен(/const древко = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.035, 0\.045, 1\.8, 5\)/.test(ТЕРРЕЙН),
      'у лодки нет вёсел');
    должен(
      /const лопасть = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.42, 0\.03, 0\.18\)/.test(ТЕРРЕЙН),
      'у вёсел нет лопастей',
    );
  });

  it('парус с провисом, штаги и поперечина', () => {
    // Парус — часть цилиндра (прогиб), а не плита.
    должен(
      /new THREE\.CylinderGeometry\(0\.66, 0\.66, 1\.5, 10, 1, true, -Math\.PI \/ 2, Math\.PI\)/.test(ТЕРРЕЙН),
      'парус без провиса: это плита',
    );
    // Плоской плиты вместо паруса быть не должно.
    должен(
      !/new THREE\.BoxGeometry\(1\.5, 1\.3, 0\.05\)/.test(ТЕРРЕЙН),
      'парус снова плита',
    );
    // Штаги — верёвочные растяжки от мачты к бортам.
    должен(
      /const штаг = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.012, 0\.012, 2\.1, 4\)/.test(ТЕРРЕЙН),
      'у мачты нет штагов',
    );
    // Поперечина, на которой висит парус.
    должен(
      /const поперечина = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.04, 0\.04, 1\.8, 5\)/.test(ТЕРРЕЙН),
      'нет поперечины мачты',
    );
  });
});
