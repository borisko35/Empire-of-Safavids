// Дорожные путники перестают быть столбами с шаром.
//
// ЧТО БЫЛО (22 октября 2026, §296). Путник на дороге: тело — цилиндр, голова —
// шар, шапка — цилиндр, ноги — цилиндры, и **рук не было вовсе**. Человек без
// рук читался как столб с шаром наверху.
//
// ЧТО ТЕПЕРЬ. Халат-капсула с плечами и перевязью через грудь; руки в рукавах
// с кистями, качаются в противофазе с ногами; голова с носом и бородой;
// тюрбан — намотка и шапка сверху, шапка — купол с козырьком.
//
// ЧТО ПРОВЕРЯЕТСЯ. У путника есть капсульный халат, плечи, перевязь, руки с
// кистями, нос, борода, намотанный тюрбан и шапка с козырьком; цилиндра вместо
// халата нет, и руки не забыты.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТРАФИК = читать('client/src/app/game3d/roadTraffic.ts');

describe('Дорожные путники — не столбы', () => {
  it('халат-капсула с плечами и перевязью', () => {
    должен(
      /const body = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.26, 0\.62, 4, 12\), robe\);/.test(ТРАФИК),
      'халат путника — не капсула',
    );
    должен(
      /const плечи = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.25, 10, 8\), robe\);/.test(ТРАФИК),
      'у путника нет плеч',
    );
    // Перевязь через грудь.
    должен(
      /const перевязь = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.07, 0\.9, 0\.44\), ткань\);/.test(ТРАФИК),
      'у путника нет перевязи',
    );
    // Цилиндра вместо халата быть не должно.
    должен(
      !/const body = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.26, 0\.36, 1\.0, 8\), robe\);/.test(ТРАФИК),
      'халат путника снова цилиндр',
    );
  });

  it('руки в рукавах с кистями', () => {
    должен(
      /const рука = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.075, 0\.06, 0\.62, 6\), robe\);/.test(ТРАФИК),
      'у путника нет рук в рукавах',
    );
    должен(
      /const кисть = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.065, 6, 5\), M\.skin\);/.test(ТРАФИК),
      'у путника нет кистей',
    );
    // Руки качаются вместе с ногами: добавлены в тот же список.
    должен(/legs\.push\(пивот\);/.test(ТРАФИК), 'руки не качаются при ходьбе');
  });

  it('голова с носом и бородой, головной убор намотан', () => {
    должен(
      /const нос = new THREE\.Mesh\(new THREE\.ConeGeometry\(0\.05, 0\.13, 5\), M\.skin\);/.test(ТРАФИК),
      'у путника нет носа',
    );
    должен(
      /const борода = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.1, 8, 6\), M\.dark\);/.test(ТРАФИК),
      'у путника нет бороды',
    );
    // Тюрбан: намотка (тор) и шапка сверху.
    должен(
      /const намотка = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.19, 0\.07, 6, 12\), M\.skin\);/.test(ТРАФИК),
      'тюрбан не намотан',
    );
    // Шапка: купол с козырьком.
    должен(
      /const козырёк = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.2, 0\.03, 0\.16\), M\.dark\);/.test(ТРАФИК),
      'у шапки нет козырька',
    );
  });
});
