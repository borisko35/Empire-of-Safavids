// Дорожные путники.
//
// ЧТО БЫЛО (§296). Путник — халат-капсула с бородой и руками, качающимися
// синусом.
//
// ЧТО ТЕПЕРЬ (§327). Путник — ригованная модель горожанина (citizen/citizen2/
// citizen3 — те же, что в столице) с настоящей походкой из клипа walking.
//
// ЧТО ПРОВЕРЯЕТСЯ. Модели лежат в сборке; путник собирается через общий
// пайплайн (подогнать, безМёртвыхДорожек, клон скелета, миксер); капсульной
// сборки больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТРАФИК = читать('client/src/app/game3d/roadTraffic.ts');

describe('Дорожные путники', () => {
  it('путник — ригованный горожанин с клипом ходьбы', () => {
    должен(/const ПУТНИКИ_МОДЕЛИ = \['citizen', 'citizen2', 'citizen3'\] as const;/.test(ТРАФИК),
      'путники не чередуют модели горожан');
    const сборка = ТРАФИК.split('async function собратьПутника')[1].split('\n}\n')[0];
    должен(/подогнать\(сцена, имя\)/.test(сборка), 'масштаб путника не подгоняется');
    должен(/безМёртвыхДорожек\(клип, fitted, имя\)/.test(сборка), 'дорожки клипа не чистятся');
    должен(/миксер\.clipAction\(чистый\)\.play\(\);/.test(сборка), 'клип ходьбы не играет');
  });

  it('капсульной сборки больше нет', () => {
    должен(!/CapsuleGeometry\(0\.34, 0\.72, 3, 8\)/.test(ТРАФИК), 'халат снова капсула');
    должен(!/'turban' | 'cap'/.test(ТРАФИК), 'шапки из примитивов вернулись');
  });

  it('миксер путника тикается на кадр', () => {
    должен(/if \(w\.зверь\) w\.зверь\.update\(dt\);/.test(ТРАФИК), 'миксер путника не тикается');
  });
});
