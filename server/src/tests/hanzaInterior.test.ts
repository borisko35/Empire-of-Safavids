// Ханжа: «Рассказ через детали» — место построено, улик пока нет.
//
// ЧТО ЗАЩИЩАЕТ. Замер показал: слова «весы» в данных проекта нет ни разу, а
// локации с таким названием нет вовсе. То есть это строилось с нуля, и главный
// риск здесь — выдать построенное место за выполненную задачу.
//
// ГРАНИЦА ЭТОГО ШАГА. Детали в комнате есть (надписи, письма, сломанные весы,
// следы копыт), а ПРАВИЛА ОСМОТРА нет: оно требует системы улик — сбор,
// вывод, связь с NPC. Оговорка об этом лежит в коде словами, и проверка
// требует, чтобы она там была.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';
import { waterMask } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

describe('Ханжа: место подобрано измерением', () => {
  it('дверь стоит на сухой земле', () => {
    const def = INTERIORS.hanza;
    must(def !== undefined, 'на сервере нет записи hanza: дверь есть, а войти некуда');
    const влажность = waterMask(def.doorX, def.doorZ);
    must(
      влажность === 0,
      `у двери ханжи (${def.doorX}, ${def.doorZ}) влажность ${влажность.toFixed(4)}, а должно быть 0.0000`
    );
  });

  it('проверка места не пустая: вода остаётся водой', () => {
    // Шесть кандидатов дали 0.0000, и это могло означать «маска всегда ноль».
    must(waterMask(-420, -160) > 0.9, 'озеро перестало быть водой: маска считается неверно');
    must(waterMask(620, 300) > 0.9, 'пруд перестал быть водой: маска считается неверно');
  });

  it('ханжа стоит отдельно от святилища и гробницы', () => {
    const ханжа = INTERIORS.hanza!;
    for (const сосед of [INTERIORS.shrine!, INTERIORS.tomb!]) {
      const расстояние = Math.hypot(ханжа.doorX - сосед.doorX, ханжа.doorZ - сосед.doorZ);
      must(
        расстояние > 200,
        `ханжа в ${расстояние.toFixed(0)} от ${сосед.id}: это соседние постройки, а должны быть разными местами`
      );
    }
  });
});

describe('Ханжа: слот и дверь совпадают на клиенте и на сервере', () => {
  it('ханжа держит семнадцатый слот', () => {
    const ключи = Object.keys(INTERIORS);
    const слотСервер = ключи.indexOf('hanza');
    must(слотСервер === 17, `ханжа на слоте ${слотСервер} из ${ключи.length}, а обязана быть семнадцатой`);
    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    must(
      записи.indexOf('hanza') === слотСервер,
      `на клиенте ханжа на слоте ${записи.indexOf('hanza')}, а на сервере ${слотСервер}`
    );
  });

  it('двадцать построек держат свои слоты', () => {
    const ключи = Object.keys(INTERIORS);
    // 22 построения: пещеры (слот 20) и крепость (слот 21) добавлены в конец,
    // поэтому слот ханжи (17) не сдвинулся.
    must(ключи.length === 22, `построек ${ключи.length}, а должно быть 22`);
    must(ключи[16] === 'tomb', `на слоте 16 стоит ${ключи[16]}, а ожидался tomb`);
    must(ключи[17] === 'hanza', `на слоте 17 стоит ${ключи[17]}, а ожидалась hanza`);
    must(
      INTERIORS.hanza!.roomCx === 4748,
      `у ханжи roomCx ${INTERIORS.hanza!.roomCx}, а слот 17 даёт 4748`
    );
  });

  it('координаты двери совпадают на клиенте и на сервере', () => {
    const def = INTERIORS.hanza!;
    const своя = /id: 'hanza', kind: 'hanza',[\s\S]{0,140}?dx: (-?\d+), dz: (-?\d+)/.exec(клиент);
    must(своя !== null, 'у ханжи на клиенте нет абсолютной двери');
    must(
      Number(своя![1]) === def.doorX && Number(своя![2]) === def.doorZ,
      `клиент рисует дверь в (${своя![1]}, ${своя![2]}), а сервер ждёт (${def.doorX}, ${def.doorZ})`
    );
  });

  it('граница кармана покрывает новую комнату целиком', () => {
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+), z0: (-?\d+), z1: (\d+) \}/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    must(
      Number(прямоугольник![2]) >= INTERIORS.hanza!.roomCx + INTERIORS.hanza!.roomHalf,
      `правый край кармана ${прямоугольник![2]}, а правый край комнаты ` +
        `${INTERIORS.hanza!.roomCx + INTERIORS.hanza!.roomHalf}: под комнатой нет земли`
    );
  });
});

describe('Ханжа: детали по заданию, а не украшение', () => {
  it('функция обстановки заведена и вызывается', () => {
    must(/function furnishHanza\(/.test(клиент), 'функции обстановки ханжи нет');
    must(/hanza: furnishHanza,/.test(клиент), 'ханжа не прописана в выборе обстановки');
    must(
      /'hanza'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 900) ?? ''),
      'в типе BuildingKind нет ханжи'
    );
  });

  // Проверка идёт по ГЕОМЕТРИИ, а не по слову «весы»: минификатор и
  // переименования тут не при чём, но слово в комментарии ничего не доказывает.
  const тело = клиент.slice(клиент.indexOf('function furnishHanza('));
  const зал = тело.slice(0, тело.indexOf('export const BUILDINGS') > 0 ? тело.indexOf('export const BUILDINGS') : 6000);

  it('надписи на стене разной высоты', () => {
    must(/box\(1\.9, высота, 0\.14, M\.stone/.test(зал), 'надписей на стене нет');
    must(/const высота = 1\.9 \+ \(i % 3\) \* 0\.55/.test(зал), 'надписи одинаковой высоты: читаются как обои');
  });

  it('сломанные весы именно сломанные: чаша на боку, стрелка отдельно', () => {
    must(/const чаша = cyl\(1\.1, 0\.3, 1\.1, M\.gold/.test(зал), 'чаши весов нет');
    must(/чаша\.rotation\.z = Math\.PI \/ 2;/.test(зал), 'чаша стоит ровно: весы не сломаны');
    must(/g\.add\(box\(1\.4, 0\.08, 0\.22, M\.gold/.test(зал), 'стрелки весов нет: она упала отдельно');
    must(
      /box\(0\.5, 0\.5, 0\.5, M\.gold/.test(зал) && /box\(0\.4, 0\.4, 0\.4, M\.gold/.test(зал),
      'гирь на полу нет: упавшей стрелке не на что опираться'
    );
  });

  it('следы копыт ведут к выходу, а не стоят пятном', () => {
    must(/box\(0\.34, 0\.05, 0\.5, M\.cream/.test(зал), 'следов копыт нет');
    must(/for \(let i = 0; i < 7; i\+\+\)/.test(зал), 'следов мало: след должен вести, а не отмечаться');
    must(/cz \+ 4\.4 \+ i \* 1\.15/.test(зал), 'следы не разложены по направлению к двери');
  });

  it('письма и свитки: столы и стеллажи', () => {
    must(/box\(2\.6, 0\.16, 1\.5, M\.wood/.test(зал), 'столов со свитками нет');
    must(/свиток\.rotation\.x = Math\.PI \/ 2;/.test(зал), 'свитки лежат не вдоль стола');
    must(/box\(1\.3, 0\.8, 0\.9, M\.wood/.test(зал), 'ящика с письмами нет');
    must(/box\(0\.5, 2\.6, 3\.2, M\.wood/.test(зал), 'стеллажей со свитками нет');
  });

  it('свет в ханже есть: читают при лампаде', () => {
    must(/cyl\(0\.34, 0\.44, 0\.34, M\.gold/.test(зал), 'лампад нет');
  });
});

describe('Ханжа: улик пока нет, и это сказано', () => {
  it('в коде прямо написано, что правила осмотра нет', () => {
    // Без этой оговорки ханжа выглядит выполненной задачей: детали в комнате
    // есть, а улики не собираются и вывода не делается.
    const начало = клиент.indexOf('function furnishHanza(');
    const комментарий = клиент.slice(Math.max(0, начало - 900), начало);
    must(
      /правил[а-я]* осмотра нет|нет.*осмотр/i.test(комментарий),
      'рядом с функцией нет оговорки, что правила осмотра нет: ханжа выглядит готовой задачей'
    );
  });

  it('проверка требует сама оговорку, а не ищет слово «улика»', () => {
    // Оговорка проверяется текстом рядом с функцией, а не наличием слова
    // «улики» где угодно: слово в комментарии не доказывает ничего.
    must(
      /ПРАВИЛА ОСМОТРА НЕТ/.test(клиент),
      'оговорка о несуществующем правиле осмотра исчезла из кода'
    );
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.hanza === 'string' && словарь.buildings.hanza.length > 0,
        `в ${код}.json нет названия buildings.hanza`
      );
    }
  });
});
