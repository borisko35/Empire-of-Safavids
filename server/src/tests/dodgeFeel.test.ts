// Рывок: едет куда надо, одинаково при любой частоте кадров и не выглядит читерством.
//
// ЧТО БЫЛО СЛОМАНО. Скорость рывка гасилась величиной fall = 1 минус «сколько
// времени рывка ещё осталось». В первый же кадр остаток равен всей длительности,
// значит fall = 0, и скорость обнулялась после одного смещения: игрок ехал
// 0.25 метра вместо полутора. Комментарий обещал линейное гашение и 1.65 метра.
//
// ЧТО ОКАЗАЛОСЬ НЕДОСТАТОЧНЫМ. Простое гашение «на долю кадра» даёт правильную
// скорость и НЕПРАВИЛЬНУЮ ДЛИНУ. Скорость линейно убывает, и если складывать
// шаги по кадрам, сумма берётся по левому краю убывающей функции: на 30 кадрах
// рывок везёт 2.26 метра, на 144 — около 1.75. То есть на слабом компьютере
// игрока кидало вдвое дальше. Проверка на это упала и заставила переделать.
//
// КАК СДЕЛАНО. Позиция рывка считается аналитически: пройденный путь растёт как
// v*T*(t - t²/2), где t — доля пройденного времени. За кадр берётся РАЗНОСТЬ
// пути для текущей и прошлой доли, поэтому длина одинакова при любой частоте
// кадров: ровно v*T/2.
//
// ПОЧЕМУ РЫВОК НЕ СКЛАДЫВАЕТСЯ ПОВЕРХ БЕГА. Пик скорости рывка плюс бег дал бы
// DODGE_SPEED + RUN_SPEED = 22.6 при пределе анти-чита 12*1.3 = 15.6, то есть
// speed_hack, кик и бан после пяти. Проверка считает этот пик и требует, чтобы
// он остался в пределах.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/world3d.ts');
const АНТИЧИТ = читать('server/src/systems/AntiCheatSystem.ts');

function число(источник: string, шаблон: RegExp, что: string): number {
  const найдено = шаблон.exec(источник);
  must(найдено, `не нашёл ${что} в коде: проверка считала бы не то, что в игре`);
  return Number(найдено![1]);
}

const DODGE_SPEED = число(МИР, /DODGE_SPEED = ([\d.]+)/, 'стартовую скорость рывка');
const DODGE_TIME_MS = число(МИР, /DODGE_TIME_MS = (\d+)/, 'длительность рывка');
const RUN_SPEED = число(МИР, /RUN_SPEED = ([\d.]+)/, 'скорость бега');
const ПРЕДЕЛ = число(АНТИЧИТ, /const MAX_SPEED = ([\d.]+)/, 'предел скорости анти-чита') * 1.3;

/** Пройденный путь в доле t от начала рывка — ровно как в игре. */
function путь(t: number): number {
  return DODGE_SPEED * (DODGE_TIME_MS / 1000) * (t - (t * t) / 2);
}

/** Прогнать рывок по настоящей формуле из кода и вернуть путь с пиком скорости. */
function пройтиРывок(fps: number): { расстояние: number; пик: number } {
  let t = 0;
  let пройдено = 0;
  let пик = 0;
  while (t < 1) {
    const dt = 1 / fps;
    const следующий = Math.min(1, t + (dt * 1000) / DODGE_TIME_MS);
    const шаг = путь(следующий) - путь(t);
    пройдено += шаг;
    пик = Math.max(пик, Math.abs(шаг) / dt);
    t = следующий;
  }
  return { расстояние: пройдено, пик };
}

describe('Рывок: длина и скорость', () => {
  it('рывок везёт игрока на полтора метра, а не на 27 сантиметров', () => {
    for (const fps of [30, 60, 144]) {
      const { расстояние } = пройтиРывок(fps);
      must(
        расстояние > 1.4 && расстояние < 2.0,
        `при ${fps} fps рывок везёт ${расстояние.toFixed(2)} м: игрок либо не чувствует рывка, либо улетает`
      );
    }
  });

  it('длина рывка не зависит от частоты кадров', () => {
    // Складывание шагов по кадрам давало 2.26 м на 30 кадрах и 1.75 на 144: на
    // слабом компьютере игрока кидало вдвое дальше. Теперь результат один.
    const тридцать = пройтиРывок(30).расстояние;
    const сто = пройтиРывок(144).расстояние;
    must(
      Math.abs(тридцать - сто) < 0.05,
      `при 30 fps ${тридцать.toFixed(3)} м, при 144 fps ${сто.toFixed(3)} м: длина рывка зависит от частоты кадров`
    );
  });

  it('длина равна половине пути на полной скорости', () => {
    // Прямая проверка формулы: путь за всё время = v*T/2. Если рывок едет
    // больше или меньше, значит он гаснет не так, как задумано.
    const ожидаемое = (DODGE_SPEED * (DODGE_TIME_MS / 1000)) / 2;
    must(
      Math.abs(пройтиРывок(60).расстояние - ожидаемое) < 0.02,
      `рывок проехал ${пройтиРывок(60).расстояние.toFixed(3)} м, а по формуле v*T/2 = ` +
        `${ожидаемое.toFixed(3)} м`
    );
  });

  it('пик скорости не превышает предел анти-чита', () => {
    // Это главная причина, по которой нельзя было просто починить гашение:
    // пик «рывок плюс бег» дал бы 22.6 при пределе 15.6, и игрока вышибает.
    for (const fps of [30, 60, 144]) {
      const { пик } = пройтиРывок(fps);
      must(
        пик < ПРЕДЕЛ,
        `при ${fps} fps пик рывка ${пик.toFixed(2)} при пределе ${ПРЕДЕЛ.toFixed(2)}: честный рывок объявят читерством`
      );
    }
  });

  it('наивная починка дала бы пик выше предела — и это проверено', () => {
    const писк = DODGE_SPEED + RUN_SPEED;
    must(
      писк > ПРЕДЕЛ,
      `пик «рывок плюс бег» равен ${писк.toFixed(2)} и НЕ превышает предел ` +
        `${ПРЕДЕЛ.toFixed(2)}: значит опасения не было и менять нечего`
    );
  });
});

describe('Рывок: как именно он считается в коде', () => {
  it('позиция берётся разностью пути, а не складыванием шагов', () => {
    must(
      /const смещение = путь\(t\) - путь\(this\.dodgeT\);/.test(МИР),
      'нет разности пути: длина рывка снова зависит от частоты кадров'
    );
    must(
      /DODGE_SPEED \* \(DODGE_TIME_MS \/ 1000\) \* \(доля - \(доля \* доля\) \/ 2\)/.test(МИР),
      'формула пути рывка пропала: рывок едет не полтора метра'
    );
  });

  it('гашения по отношению времени больше нет', () => {
    must(
      !/\(this\.dodgeUntil - Date\.now\(\)\) \/ DODGE_TIME_MS/.test(МИР),
      'старое гашение по отношению времени осталось: в первый кадр оно равно нулю ' +
        'и рывок гаснет после одного смещения'
    );
    must(
      !/dodgeV[xz]/.test(МИР),
      'скорость рывка по кадрам вернулась: она снова копится кадр за кадром'
    );
  });

  it('два рывка подряд не складывают скорость', () => {
    // Раньше тут стояло «+=»: второй удар складывал скорость с первым и уносил
    // вдвое дальше. Теперь направление присваивается.
    must(
      /this\.dodgeDx = \(dx \/ len\) \* cos - \(dz \/ len\) \* sin;/.test(МИР),
      'направление рывка снова складывается со старым: второй рывок уносит вдвое дальше'
    );
    must(!/this\.dodgeDx \+=/.test(МИР), 'направление рывка прибавляется, а не задаётся заново');
  });

  it('пока идёт рывок, ходьба не применяется', () => {
    must(
      /const бежитРывок = Date\.now\(\) < this\.dodgeUntil/.test(МИР),
      'нет признака «идёт рывок»'
    );
    must(
      /if \(len > 0 && !бежитРывок\) \{/.test(МИР),
      'ходьба применяется поверх рывка: пик скорости удваивается и игрока вышибает'
    );
    must(
      /if \(бежитРывок\) \{/.test(МИР),
      'рывок больше не применяется без нажатых клавиш'
    );
  });
});