// Море существует, и оно настоящее.
//
// ЧТО БЫЛО. Моря в мире не было вообще: вода - это озеро LAKE, пруд POND
// и русла двух рек. При этом в данных есть регион PERSIAN_GULF с тремя
// зонами, и одна из них называлась «Персидский залив — воды». То есть
// регион «Залив» стоял на суше, а его водная зона была пустой не из-за
// нехватки монстров, а потому что воды физически не существовало.
//
// Проверки построены на разборе исходника клиента: файлы рисования
// используют three.js и document, их нельзя ни импортировать, ни
// исполнить в серверном наборе. Поэтому проверяется замысел в коде, а
// числа геометрии проверены отдельным замером (sea-probe) по функциям
// terrain.ts, запущенным в Node с заглушкой canvas.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ZONES } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Геометрия воды живёт в shared/water.ts - её читает и клиент, и сервер.
// Рельеф и рисование остались в клиенте: там хребет глушится и строится
// меш.
//
// ПЕРВАЯ ВЕРСИЯ ЭТОЙ ПРОВЕРКИ читала только terrain.ts. Когда море уехало
// в shared/, проверка покраснела на пяти пунктах - и это правильно: она
// следит не за «наличием слов в файле», а за тем, что в коде написано
// нужное. Но читать надо то место, где теперь правда.
const РЕЛЬЕФ = readFileSync(join(корень, 'client/src/app/game3d/terrain.ts'), 'utf-8');
const ВОДА = readFileSync(join(корень, 'shared/water.ts'), 'utf-8');

describe('Море Персидского залива: оно есть в коде', () => {
  it('море входит в общую маску воды', () => {
    // ГЛАВНАЯ ПРОВЕРКА. Пока seaMask не входил в waterMask, весь залив
    // оставался сушей: вода в игре рисовалась только озером, прудом и
    // реками, а зона называлась «Залив — воды».
    const функция = /export function waterMask[\s\S]{0,900}?\n}/.exec(ВОДА)?.[0] ?? '';
    must(функция.length > 0, 'не нашёл waterMask в terrain.ts');
    must(
      /seaMask\(x,\s*z\)/.test(функция),
      'waterMask не учитывает море: залив стоит на суше, а зона «Залив — воды» пустая',
    );
  });

  it('у моря есть уровень, дно и линия берега', () => {
    must(/export const SEA\s*=\s*\{/.test(ВОДА), 'нет константы SEA');
    must(/level:\s*-?[\d.]+/.test(ВОДА), 'у SEA нет уровня воды');
    must(/bed:\s*-?[\d.]+/.test(ВОДА), 'у SEA нет глубины дна');
    must(/coast:\s*-?[\d.]+/.test(ВОДА), 'у SEA нет линии берега');

    // Уровень воды выше дна, иначе гладь лежит ниже дна и её не видно.
    const блок = /export const SEA\s*=\s*\{[\s\S]*?\};/.exec(ВОДА)?.[0] ?? '';
    const level = Number(/level:\s*(-?[\d.]+)/.exec(блок)?.[1]);
    const bed = Number(/bed:\s*(-?[\d.]+)/.exec(блок)?.[1]);
    must(Number.isFinite(level) && Number.isFinite(bed), 'уровень или дно не прочитались');
    must(
      level > bed,
      `уровень моря ${level} не выше дна ${bed}: гладь окажется под рельефом и её не будет видно`,
    );
    // И дно глубже порога плавания (world3d SWIM_MIN_DEPTH = 1.2),
    // иначе в море нельзя войти вглубь.
    must(
      level - bed > 1.2,
      `глубина моря ${level - bed} меньше порога плавания 1.2: в море только брод`,
    );
  });

  it('дно моря глубже дна озера, иначе гладь будет по щиколотку', () => {
    // Замерено: с тем же дном, что у озера, в заливе была бы вода по
    // щиколотку и плавание не наступало бы.
    const блок = /export const SEA\s*=\s*\{[\s\S]*?\};/.exec(ВОДА)?.[0] ?? '';
    const bed = Number(/bed:\s*(-?[\d.]+)/.exec(блок)?.[1]);
    const дноОзера = -2.0 - 3.2;
    must(
      bed < дноОзера,
      `дно моря ${bed} не глубже дна озера ${дноОзера} - залив окажется мелкой лужей`,
    );
  });
});

describe('Море: границы не заливают сушу и не висят в воздухе', () => {
  it('хребет глушится в заливе', () => {
    // Замерено ДО правки: на (0, -1000) земля была 55 м, то есть юг
    // мира был стеной гор. Море в стену не доходило, а на пологом склоне
    // вода висела плёнкой в 20 м над землёй.
    must(
      /вЗамире/.test(РЕЛЬЕФ),
      'хребет не глушится в заливе: юг останется горной стеной и море не дойдёт до берега',
    );
    must(
      /\(1 - вЗамире\)/.test(РЕЛЬЕФ),
      'глушение хребта не применяется к его высоте - стена останется',
    );
  });

  it('берег подрезается по уровню моря', () => {
    // Линейное смешивание с дном оставляет полосу, где маска мала, а
    // земля выше уровня воды: вода висит над склоном, а глубина
    // считается отрицательной.
    must(
      /SEA\.level \+ 0\.5/.test(РЕЛЬЕФ),
      'нет подрезки рельефа по уровню моря: на прибрежной полосе вода повиснет над землёй',
    );
  });

  it('уровень поверхности моря не подменяется уровнем озера', () => {
    // Замерено: на прибрежной полосе залива функция возвращала -2.0 -
    // уровень озера, то есть точка у залива считалась лежащей в озере.
    must(
      /seaMask\(x,\s*z\)\s*>\s*0\.45\)\s*return SEA\.level/.test(РЕЛЬЕФ),
      'море не определяется по своей маске в waterSurfaceY - гладь отдаёт чужой уровень',
    );
    must(
      /if \(seaMask\(x,\s*z\)\s*>\s*0\.05\)\s*return null/.test(РЕЛЬЕФ),
      'прибрежная полоса залива не возвращается землёй - она отдаёт уровень озера',
    );
  });

  it('поверхность моря рисуется мешем, а не только считается', () => {
    // Маска и уровень без геометрии означают, что воду по которой
    // считают глубину не видно.
    must(
      /new THREE\.PlaneGeometry\([^)]*\)/.test(РЕЛЬЕФ) && /sea\.name = 'sea'/.test(РЕЛЬЕФ),
      'нет меша моря: глубина считается по воде, которой не видно',
    );
    must(
      /sea\.position\.set\(0,\s*SEA\.level/.test(РЕЛЬЕФ),
      'меш моря не стоит на уровне воды',
    );
  });
});

describe('Море и данные региона', () => {
  it('море стоит в полосе залива, а не в другом регионе', () => {
    const блок = /export const SEA\s*=\s*\{[\s\S]*?\};/.exec(ВОДА)?.[0] ?? '';
    const coast = Number(/coast:\s*(-?[\d.]+)/.exec(блок)?.[1]);
    const залив = ZONES.filter((з) => з.region === 'persian_gulf');
    must(залив.length === 3, `ожидалось 3 зоны залива, найдено ${залив.length}`);
    const юг = Math.min(...залив.map((з) => з.bounds.z1));
    const север = Math.max(...залив.map((з) => з.bounds.z2));

    // Линия берега обязана лежать ВНУТРИ полосы залива. Первая версия
    // проверки требовала обратного (coast южнее самой южной зоны) и
    // поэтому падала на правильном коде: -660 и так внутри -1100..-550.
    must(
      coast > юг && coast < север,
      `линия берега ${coast} вне полосы залива (${юг}..${север}) - море оказалось бы в другом регионе`,
    );

    // И открытая вода обязана накрывать зону, которая так и называется
    // «Залив — воды»: её середина должна быть южнее берега.
    const водная = залив.find((з) => з.id === 'persian_gulf_waters');
    must(водная !== undefined, 'зона persian_gulf_waters пропала из данных');
    const середина = (водная.bounds.z1 + водная.bounds.z2) / 2;
    must(
      середина < coast,
      `середина зоны «${водная.id}» (z=${середина}) не южнее берега (${coast}) - зона остаётся сушей`,
    );
  });

  it('есть острова, иначе залив не перейти пешком', () => {
    // Замерено: остров с мягким краем в 45% радиуса дотягивался через
    // полполосы и гасил воду вне гавани. Поэтому проверка требует и
    // наличия островов, и узкого края.
    must(/export const SEA_ISLANDS/.test(ВОДА), 'в заливе нет островов: перейти его пешком нельзя');
    must(
      /islandCore:\s*0\.\d+/.test(ВОДА),
      'нет доли радиуса, занимаемой сушей острова - край острова снова размажется по воде',
    );
  });
});