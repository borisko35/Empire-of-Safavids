// Тайные документы: правило работает и связано со столом.
//
// ЧЕСТНОЕ ИМЯ МЕСТА. Документы лежат в крепости на перевале, а не во дворце.
// Замер до начала работы: дворец существует только записью в
// server/src/data/dungeons.ts — карт .umap на диске нет вовсе, клиент не рисует
// подземелий, а mapPath не читает никто. Игрок не стоит в тронном зале, он
// входит в данж через панель и дерётся в общем мире. «Стелс к документу» там
// был бы кнопкой в списке, а не действием.
//
// ГЛАВНОЕ. Документ без стража — декорация. Стол без правила — поле без
// потребителя. Поэтому проверяются обе стороны: правило различает случаи, и
// стол с координатой, за которой сервер и клиент идут по одному списку.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import {
  DOCUMENT_SPOTS,
  DOCUMENT_ITEM_ID,
  DOCUMENT_REACH,
  canTakeDocument,
  documentSpot,
} from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');
const мир3д = читать('client/src/app/game3d/world3d.ts');
const мир = читать('client/src/app/world.ts');
const сервер = читать('server/src/socket/GameSocketHandler.ts');

const стол = documentSpot('desk_throne');

describe('Тайные документы: правило различает случаи', () => {
  it('стол тронного зала существует и он не пустой', () => {
    must(DOCUMENT_SPOTS.length > 0, 'столов с документами нет ни одного');
    must(стол !== null, 'стола тронного зала нет — проверять правило не на чем');
    must(Number.isFinite(стол!.x) && Number.isFinite(стол!.z), `координаты стола не числа: ${стол!.x}, ${стол!.z}`);
  });

  it('стол стоит в тронном зале дворца, а не висит в ниоткуда', () => {
    must(стол!.buildingId === 'palace', `стол привязан к «${стол!.buildingId}», а не к дворцу`);
    // Комната дворца: слот 11, cx = 4000 + 11 * 44 = 4484, cz = 4000,
    // полукомната 16. Стол обязан лежать внутри.
    must(
      Math.abs(стол!.x - 4484) <= 16 && Math.abs(стол!.z - 4000) <= 16,
      `стол (${стол!.x}, ${стол!.z}) вышел за пределы комнаты дворца 4468..4500 / 3984..4016`
    );
  });

  it('стол рядом со стражем, иначе стелс нечего отменять', () => {
    const страж = читать('shared/stealth.ts');
    const m = /id: 'npc_palace_guard',[\s\S]{0,120}?x: (\d+), z: (\d+)/.exec(страж);
    must(m !== null, 'пост стража дворца не найден в правиле');
    const dx = стол!.x - Number(m![1]);
    const dz = стол!.z - Number(m![2]);
    const расстояние = Math.hypot(dx, dz);
    must(
      расстояние > 5,
      `стол в ${расстояние.toFixed(1)} от стража: слишком близко, чтобы подойти незаметно`
    );
    must(
      расстояние <= 30,
      `стол в ${расстояние.toFixed(1)} от стража: страж его не накроет, документ лежит вне наблюдения`
    );
  });

  it('присевший и незамеченный берёт документ', () => {
    const игрок = { x: стол!.x + 1, z: стол!.z };
    must(
      canTakeDocument(игрок, стол!, { crouch: true, spotted: false, alreadyHas: false }) === null,
      'присевший у стола не смог взять документ: правило не работает'
    );
  });

  it('стоящий не берёт — приседание обязательно явно', () => {
    const игрок = { x: стол!.x + 1, z: стол!.z };
    must(
      canTakeDocument(игрок, стол!, { crouch: false, spotted: false, alreadyHas: false }) === 'too_loud',
      'стоящий взял документ тихо: приседание перестало быть обязательным'
    );
  });

  it('замеченный не берёт даже присев', () => {
    const игрок = { x: стол!.x + 1, z: стол!.z };
    must(
      canTakeDocument(игрок, стол!, { crouch: true, spotted: true, alreadyHas: false }) === 'seen',
      'замеченного пустило: стража в крепости не работает'
    );
  });

  it('взятый документ не берётся второй раз', () => {
    const игрок = { x: стол!.x + 1, z: стол!.z };
    must(
      canTakeDocument(игрок, стол!, { crouch: true, spotted: false, alreadyHas: true }) === 'done',
      'повторное взятие прошло: документ можно брать сколько угодно раз'
    );
  });

  it('из соседней комнаты не берут даже присев', () => {
    const игрок = { x: стол!.x + DOCUMENT_REACH + 3, z: стол!.z };
    must(
      canTakeDocument(игрок, стол!, { crouch: true, spotted: false, alreadyHas: false }) === 'far',
      'достал до стола издалека: вытянутая рука не проверяется'
    );
    // А на границе досягаемости — берёт.
    must(
      canTakeDocument(
        { x: стол!.x + DOCUMENT_REACH, z: стол!.z },
        стол!,
        { crouch: true, spotted: false, alreadyHas: false }
      ) === null,
      `на расстоянии ровно ${DOCUMENT_REACH} документ не берётся: граница досягаемости отрезана`
    );
  });

  it('несуществующий стол не проходит', () => {
    must(documentSpot('нет-такого') === null, 'несуществующий стол вернулся как настоящий');
  });
});

describe('Тайные документы: они связаны со столом и с сервером', () => {
  it('клиент рисует стол по тому же списку, что проверяет сервер', () => {
    must(/DOCUMENT_SPOTS/.test(клиент), 'клиент не берёт список столов из правила');
    must(
      /if \(place\.buildingId !== def\.id\) continue;/.test(клиент),
      'стол строится не в своей комнате: проверка «это моя комната» отсутствует'
    );
    must(/documentTargets/.test(клиент), 'у комнаты нет списка кликабельных столов');
    must(
      /clickTargets\.push\(\.\.\.room\.documentTargets\)/.test(клиент),
      'стол не попал в кликабельные объекты: по нему нельзя будет кликнуть'
    );
  });

  it('клик по столу и клавиша заводят запрос, а не рисуют событие сами', () => {
    must(/documentSpot\?: string/.test(мир3д), 'тип объекта клика не знает о столе');
    must(
      /if \(ud\.documentSpot\) \{[\s\S]{0,120}documentRequested = true;/.test(мир3д),
      'клик по столу не ставит запрос'
    );
    must(/consumeDocumentRequest\(\): boolean/.test(мир3д), 'запрос нельзя прочитать: он не сбрасывается');
    must(
      /e\.code === 'KeyE'[\s\S]{0,120}documentRequested = true/.test(мир3д),
      'клавиша на документы не назначена'
    );
    // Запрос уходит из world.ts, а не из 3D-класса: там сокета нет.
    must(
      /consumeDocumentRequest\(\)\) \{\s*socket\.emit\(SOCKET_EVENTS\.DOCUMENT_ATTEMPT\)/.test(мир),
      'запрос не уходит на сервер из игрового цикла'
    );
  });

  it('сервер проверяет правило и не берёт координаты из события', () => {
    must(/SOCKET_EVENTS\.DOCUMENT_ATTEMPT/.test(сервер), 'сервер не слушает попытку взять документ');
    must(/canTakeDocument\(игрок, стол/.test(сервер), 'сервер не проверяет правило документа');
    // Событие не несёт позицию: координаты берутся из проверенного пакета.
    must(
      !/DOCUMENT_ATTEMPT[^\n]*\n?[^\n]*x:\s*number/.test(сервер),
      'событие входа начало нести координаты: это путь для читов'
    );
    must(
      // Кеш общий (server/src/systems/StealthStates.ts): с прошлого шага его
      // читает ещё и тик стражи. Проверка ищет обращение к кешу, а не поле.
      /const где = this\.stealthStates\.get\(characterId\)/.test(сервер),
      'позиция игрока берётся не из проверенного пакета движения'
    );
  });

  it('«уже брал» решается инвентарём, а не новой таблицей', () => {
    must(/getItemQuantities\(characterId\)/.test(сервер), 'наличие документа не проверяется инвентарём');
    must(
      /количества\[DOCUMENT_ITEM_ID\] \?\? 0\) > 0/.test(сервер),
      'проверка «документ уже есть» написана не по тому предмету'
    );
    must(
      /addItems\(characterId, \[\{ itemId: DOCUMENT_ITEM_ID, qty: 1 \}\]\)/.test(сервер),
      'документ выдаётся не через addItems: обойдутся гильдейские задания'
    );
    // Для документов НЕ должна заводиться колонка: «уже брал» решается
    // наличием предмета в инвентаре.
    //
    // Раньше здесь стояло «в проверке числа миграций написано 70». Это было
    // не про документы: ЛЮБАЯ новая миграция роняла проверку документов, а
    // миграция 071 заведена была совсем про другое — признак выдачи добычи.
    // Теперь проверка смотрит на суть: нет ли в миграциях колонки про
    // документ. Общее число миграций считается в roadmapNumbers.
    const папка = join(корень, 'database', 'migrations');
    const все = readdirSync(папка)
      .filter((ф) => ф.endsWith('.sql'))
      .map((ф) => читать(`database/migrations/${ф}`))
      .join('\n');
    // Ищется ИМЯ КОЛОНКИ, а не слово «документ». По слову проверка ловила
    // «секретные локации» в описании профессии исследователя — то есть
    // проверяла не то.
    must(
      !/dossiers?|taken_documents?|documents?_taken|picked_documents?/i.test(
        все.replace(/--[^\n]*/g, '')
      ),
      'для тайных документов заведена миграция: значит «уже брал» решили таблицей, а не инвентарём'
    );
  });

  it('предмет существует в базе вещей и он не стакается', () => {
    const вещи = читать('server/src/data/items.ts');
    must(
      вещи.includes(`'${DOCUMENT_ITEM_ID}': {`),
      `в базе вещей нет предмета ${DOCUMENT_ITEM_ID}: документ нечего положить в сумку`
    );
    const начало = вещи.indexOf(`'${DOCUMENT_ITEM_ID}': {`);
    const тело = вещи.slice(начало, вещи.indexOf('},', начало) + 2);
    must(/maxStack: 1/.test(тело), 'у документа не задан предел стака');
    must(/price: 0/.test(тело), 'у документа не задана цена: тип вещи требует оба поля');
  });

  it('причины отказа переведены во всех трёх языках', () => {
    const ключи = ['document_ok', 'document_far', 'document_loud', 'document_seen', 'document_done'];
    for (const код of ['ru', 'en', 'az']) {
      const словарь = читать(`shared/locales/${код}.json`);
      const разобранный = JSON.parse(словарь);
      must(разобранный.stealth !== undefined, `в ${код}.json нет секции stealth`);
      for (const ключ of ключи) {
        must(
          разобранный.stealth[ключ] !== undefined,
          `в ${код}.json нет ключа stealth.${ключ}: игрок увидит путь ключа вместо текста`
        );
      }
    }
  });
});