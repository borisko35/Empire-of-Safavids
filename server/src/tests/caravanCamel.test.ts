// Верблюд каравана перестаёт быть ящиком на палках.
//
// ЧТО БЫЛО (22 октября 2026, §294). Верблюд каравана: тело — ящик 0.9×0.9×1.9,
// голова — куб, ноги — ровные цилиндры без копыт, тюки — гладкие коробки,
// приклеенные к бокам. Караван читался как ящики на палках.
//
// ЧТО ТЕПЕРЬ. Тело — капсула с грудью и крупом, шея и голова — капсулы, морда
// сужается к носу, уши на месте; ноги сужаются к копыту; груз лежит на
// **седле с попоной**, а тюки стянуты **верёвками**.
//
// ЧТО ПРОВЕРЯЕТСЯ. У верблюда капсульное тело, капсульные шея и голова,
// сужающаяся морда, ноги с копытом, седло с попоной и верёвки на тюках; ящика
// вместо тела больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТРАФИК = читать('client/src/app/game3d/roadTraffic.ts');

describe('Верблюд каравана — не ящик на палках', () => {
  it('тело, шея и голова — капсулы', () => {
    должен(
      /const body = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.42, 1\.05, 4, 12\), M\.camel\);/.test(ТРАФИК),
      'тело верблюда — не капсула',
    );
    должен(
      /const neck = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.17, 0\.62, 3, 9\)/.test(ТРАФИК),
      'шея верблюда — не капсула',
    );
    должен(
      /const head = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.15, 0\.28, 3, 9\)/.test(ТРАФИК),
      'голова верблюда — не капсула',
    );
    // Морда сужается к носу.
    должен(
      /const морда = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.1, 0\.15, 0\.3, 7\)/.test(ТРАФИК),
      'у верблюда нет сужающейся морды',
    );
    // Ящика вместо тела быть не должно.
    должен(
      !/new THREE\.BoxGeometry\(0\.9, 0\.9, 1\.9\)/.test(ТРАФИК),
      'тело верблюда снова ящик',
    );
    должен(
      !/new THREE\.BoxGeometry\(0\.28, 0\.26, 0\.55\)/.test(ТРАФИК),
      'голова верблюда снова куб',
    );
  });

  it('ноги сужаются к копыту', () => {
    должен(
      /const leg = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.095, 0\.065, 0\.88, 6\)/.test(ТРАФИК),
      'нога верблюда не сужается',
    );
    должен(
      /const копыто = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.075, 0\.085, 0\.09, 6\)/.test(ТРАФИК),
      'у верблюда нет копыт',
    );
  });

  it('груз лежит на седле с попоной, тюки стянуты верёвками', () => {
    // Попона и седло.
    должен(
      /const попона = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.05, 0\.1, 1\.35\), M\.camelDark\);/.test(ТРАФИК),
      'у верблюда нет попоны',
    );
    должен(
      /const седло = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.78, 0\.16, 0\.5\), M\.wood\);/.test(ТРАФИК),
      'у верблюда нет седла',
    );
    // Верёвка стягивает тюк: без неё тюк выглядит приклеенным.
    должен(
      /const верёвка = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.42, 0\.022, 4, 10\), M\.wood\);/.test(ТРАФИК),
      'тюки не стянуты верёвками',
    );
  });
});
