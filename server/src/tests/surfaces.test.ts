// §317. Настоящие PBR-поверхности и архитектурный силуэт.
//
// ЧТО ЛОВИТСЯ И ПОЧЕМУ ТАК.
// 1. Наборы карт лежат на диске, и в каждом есть цвет, нормаль и
//    шероховатость. Без нормали камень остаётся крашеной плоскостью.
// 2. Размер карт — 1K, а не 8K: 8K на 12 наборов — это гигабайты
//    репозитория и минуты загрузки, а стена дома на экране всё равно
//    занимает меньше 1024 текселей.
// 3. Лицензия записана в манифесте и в THIRD_PARTY.md. Политика проекта:
//    чужой ассет получает строку до коммита, а не после.
// 4. Цветная карта грузится в sRGB, нормаль и шероховатость — в линейном
//    пространстве. Перепутанное пространство делает поверхность или
//    выбеленной, или тёмной, и это не видно в коде — только на экране.
// 5. Метрический UV: одна и та же штукатурка 2.4 м на доме любой ширины.
//    Без него дом 15 м получает кирпич вдвое крупнее, чем дом 7 м.
// 6. У дома три варианта стены, и выбор детерминированный: по позиции,
//    а не Math.random — иначе мир выглядит иначе после перезагрузки.
// 7. Купол — LatheGeometry с луковичным профилем, а не сплющенный шар.
// 8. Снег не отбирает у камня PBR-карту. Это был настоящий баг: снег
//    запоминал карту до её загрузки (null), подменял на снежную и при
//    таянии возвращал null — стены и мостовая оставались заливкой.
// 9. Анизотропия ставится из возможностей рендера, а не зашитой четвёркой.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ПОВЕРХНОСТИ = читать('client/src/app/game3d/surfaces.ts');
const МЕТРИКА = читать('client/src/app/game3d/metricUv.ts');
const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
const ЛИЦЕНЗИИ = читать('THIRD_PARTY.md');
const ПАПКА = 'client/src/app/public/textures';

interface Набор {
  id: string;
  tile: number;
  use: string;
  maps: { diff?: string; nor?: string; rough?: string };
}

const МАНИФЕСТ = JSON.parse(читать(`${ПАПКА}/surfaces.json`)) as {
  licence: string;
  source: string;
  resolution: string;
  surfaces: Набор[];
};

describe('§317. PBR-поверхности: файлы', () => {
  it('манифест называет источник, лицензию и разрешение', () => {
    must(/CC0/i.test(МАНИФЕСТ.licence), 'в surfaces.json не CC0');
    must(/polyhaven/i.test(МАНИФЕСТ.source), 'в surfaces.json не назван Poly Haven');
    must(МАНИФЕСТ.resolution === '1k', 'разрешение не 1K: репозиторий распухнет');
  });

  it('каждый набор — три карты, и все лежат на диске', () => {
    must(МАНИФЕСТ.surfaces.length >= 10, 'наборов меньше десяти: город останется из двух материалов');
    for (const набор of МАНИФЕСТ.surfaces) {
      must(набор.tile > 0.3 && набор.tile < 12, `${набор.id}: неправдоподобный метр повтора ${набор.tile}`);
      for (const карта of ['diff', 'nor', 'rough'] as const) {
        const путь = набор.maps[карта];
        must(путь !== undefined, `${набор.id}: нет карты ${карта}`);
        must(путь!.startsWith('/game/textures/'), `${набор.id}: карта ${карта} не под /game/textures`);
        const файл = join(корень, ПАПКА, набор.id, путь!.split('/').pop()!);
        must(existsSync(файл), `${набор.id}: файла карты ${карта} нет на диске`);
        const байт = statSync(файл).size;
        must(байт > 20_000, `${набор.id}/${карта}: ${байт} байт — это не 1K-карта`);
        must(байт < 1_500_000, `${набор.id}/${карта}: ${байт} байт — карта тяжелее 1K`);
      }
    }
  });

  it('чужие карты записаны в THIRD_PARTY.md', () => {
    must(/Poly Haven/i.test(ЛИЦЕНЗИИ), 'в THIRD_PARTY.md нет строки Poly Haven');
    must(/PBR-поверхности/i.test(ЛИЦЕНЗИИ), 'в THIRD_PARTY.md нет строки про PBR-поверхности');
    must(/surfaces\.test\.ts/.test(ЛИЦЕНЗИИ), 'THIRD_PARTY.md не ссылается на сторожа surfaces.test.ts');
  });
});

describe('§317. PBR-поверхности: загрузка', () => {
  it('цвет в sRGB, нормаль и шероховатость — линейные', () => {
    must(/TextureLoader/.test(ПОВЕРХНОСТИ), 'surfaces.ts не грузит текстуры');
    must(/SRGBColorSpace/.test(ПОВЕРХНОСТИ), 'цветная карта не помечена sRGB — стены выбелятся');
    must(/NoColorSpace/.test(ПОВЕРХНОСТИ), 'нормаль/шероховатость не помечены линейными');
    must(/RepeatWrapping/.test(ПОВЕРХНОСТИ), 'нет RepeatWrapping: на длинной стене будут полосы');
  });

  it('карта ставится только после загрузки, а не чёрной сразу', () => {
    // Пустая текстура в three рисуется чёрным. Поэтому материал получает
    // карту в .then после Promise.all, а до этого остаётся процедурным.
    must(/Promise\.all/.test(ПОВЕРХНОСТИ), 'нет ожидания загрузки трёх карт');
    must(/if \(!d\.image \|\| !n\.image \|\| !r\.image\) return;/.test(ПОВЕРХНОСТИ),
      'нет проверки, что картинки пришли: материал станет чёрным');
    must(/colorMap/.test(ПОВЕРХНОСТИ), 'нет режима «только нормаль и шероховатость» для земли');
  });

  it('анизотропия берётся у рендера', () => {
    must(/setSurfaceAnisotropy/.test(ПОВЕРХНОСТИ), 'в surfaces.ts нет установки анизотропии');
    must(/setSurfaceAnisotropy/.test(МИР), 'world3d.ts не передаёт максимум анизотропии поверхностям');
    must(/getMaxAnisotropy/.test(МИР), 'анизотропия не читается из возможностей железа');
  });
});

describe('§317. Метрический UV', () => {
  it('коробка: шесть граней по своим метрам', () => {
    must(/metricBoxUV/.test(МЕТРИКА), 'нет metricBoxUV');
    must(/uv\.count !== 24/.test(МЕТРИКА), 'metricBoxUV не проверяет формат коробки');
    must(/\[d, h\], \[d, h\]/.test(МЕТРИКА), 'боковые грани не считаются по глубине и высоте');
    must(/\[w, d\], \[w, d\]/.test(МЕТРИКА), 'верх и низ не считаются по ширине и глубине');
  });

  it('дом получает метрический UV, а материал — repeat 1', () => {
    must(/metricBoxUV\(new THREE\.BoxGeometry\(w, h, d\)/.test(ТЕРРЕЙН),
      'главный корпус дома не получил метрический UV');
    must(/metricBoxUV\(new THREE\.BoxGeometry\(dw, dh, dd\)/.test(ТЕРРЕЙН),
      'пристройка дома не получила метрический UV');
  });
});

describe('§317. Дома и город', () => {
  it('три варианта штукатурки, выбор по позиции', () => {
    must(/houseWall: surfaceMaterial/.test(ТЕРРЕЙН), 'нет материала стены houseWall');
    must(/houseWallOchre/.test(ТЕРРЕЙН), 'нет охристого варианта стены');
    must(/houseWallClay/.test(ТЕРРЕЙН), 'нет глиняного варианта стены');
    must(/hash2\(x \* 1\.7, z \* 1\.3\)/.test(ТЕРРЕЙН),
      'вариант стены выбирается не по позиции: после перезагрузки дома изменятся');
  });

  it('окна считаются от ширины дома, а не всегда два', () => {
    must(/function окнаПоФасаду/.test(ТЕРРЕЙН), 'нет раскладки окон по фасаду');
    must(/Math\.round\(w \/ 3\.2\)/.test(ТЕРРЕЙН), 'число окон не зависит от ширины дома');
    must(/окнаПоФасаду\(house, w, h, d\)/.test(ТЕРРЕЙН), 'brickHouse не раскладывает окна');
  });

  it('мостовая площади — настоящий камень, а не процедурный рисунок', () => {
    must(/surfaceMaterial\('patterned_cobblestone'/.test(ТЕРРЕЙН),
      'площадь не получила каменную поверхность');
    must(!/map: plazaTexture\(40\)/.test(ТЕРРЕЙН),
      'площадь всё ещё на процедурной карте plazaTexture(40)');
  });
});

describe('§317. Купола', () => {
  it('луковичный профиль строится вращением, а не сплющенным шаром', () => {
    must(/export function onionDomeGeometry/.test(ТЕРРЕЙН), 'нет onionDomeGeometry');
    must(/LatheGeometry/.test(ТЕРРЕЙН), 'купол не строится вращением профиля');
    must(/SplineCurve/.test(ТЕРРЕЙН), 'профиль купола не сглажен: будут углы');
  });

  it('все купола мира используют новый профиль', () => {
    const вызовы = ТЕРРЕЙН.match(/onionDomeGeometry\(/g)?.length ?? 0;
    // Мечеть, дом-пристройка, купол дома, дом столицы, приморский дом.
    must(вызовы >= 5, `onionDomeGeometry вызывается ${вызовы} раз: часть куполов осталась шарами`);
    must(!/SphereGeometry\([^)]*\), MAT\.tealDome\)/.test(ТЕРРЕЙН),
      'остался купол из SphereGeometry с бирюзовым материалом');
  });
});

describe('§317. Снег не отбирает PBR-карту', () => {
  it('подмена карты касается только зелени', () => {
    must(/Подмена карты касается ТОЛЬКО зелени/.test(ТЕРРЕЙН),
      'нет объяснения, почему снег не трогает камень');
    must(/if \(зелень\) \{\s*\n\s*const своя/.test(ТЕРРЕЙН),
      'снег подменяет карту всем материалам: камень потеряет PBR');
    must(/§317, НАЙДЕННЫЙ БАГ/.test(ТЕРРЕЙН),
      'баг со снегом не отмечен в коде');
  });
});
