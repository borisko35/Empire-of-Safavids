// Огород за городской стеной.
//
// ЧТО БЫЛО (22 октября 2026, §302). Дворы за стеной — пустые участки, обнесённые
// забором. Земля в заборе, но пустая, читалась как недоделанная стройка, а не
// как огород.
//
// ЧТО ТЕПЕРЬ. Виноградник на решётке: столбы, поперечины, лоза и грозди;
// рядом грядки — дощатый борт, земля и ряды посадок.
//
// ЧТО ПРОВЕРЯЕТСЯ. Огород есть, виноградник стоит на решётке (столбы и
// поперечины), у лозы есть грозди, грядки с бортом и рядами посадок; и огород
// реально поставлен у домов пригорода.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Огород за городской стеной', () => {
  it('виноградник на решётке, с лозой и гроздями', () => {
    должен(/function огород\(/.test(ТЕРРЕЙН), 'нет сборщика огорода');
    // Столбы решётки.
    должен(
      /const столб = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.14, высота, 0\.14\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у решётки нет столбов',
    );
    // Поперечины.
    должен(
      /const перекладина = new THREE\.Mesh\(new THREE\.BoxGeometry\(ширина, 0\.08, 0\.08\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у решётки нет поперечин',
    );
    // Лоза.
    должен(
      /const лоза = new THREE\.Mesh\(new THREE\.BoxGeometry\(ширина, 0\.36, 0\.44\), MAT\.foliage\);/.test(ТЕРРЕЙН),
      'на решётке нет лозы',
    );
    // Грозди — восемь кистей.
    должен(
      /const гроздь = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.12, 7, 6\), цветЯгод\);/.test(ТЕРРЕЙН),
      'у лозы нет гроздей',
    );
    должен(/function огород\([\s\S]{0,4000}?for \(let i = 0; i < 8; i\+\+\) \{[\s\S]{0,400}?гроздь/.test(ТЕРРЕЙН), 'гроздей не восемь');
  });

  it('грядки с бортом и рядами посадок', () => {
    // Земля в грядке.
    должен(
      /const земля = new THREE\.Mesh\(new THREE\.BoxGeometry\(длина, 0\.22, ширинаГрядки\), MAT\.sand\);/.test(ТЕРРЕЙН),
      'у грядки нет земли',
    );
    // Дощатый борт.
    должен(
      /const борт = new THREE\.Mesh\(new THREE\.BoxGeometry\(длина, 0\.3, 0\.09\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'у грядки нет борта',
    );
    // Ряды посадок — три.
    должен(
      /const ряд = new THREE\.Mesh\(new THREE\.BoxGeometry\(длина - 0\.4, 0\.16, 0\.2\), MAT\.foliageLight\);/.test(ТЕРРЕЙН),
      'в грядке нет рядов посадок',
    );
    должен(/for \(let i = 0; i < 3; i\+\+\) \{/.test(ТЕРРЕЙН), 'рядов посадок не три');
  });

  it('огород стоит у домов пригорода', () => {
    должен(/огород\(city, д\.x/.test(ТЕРРЕЙН), 'огород не поставлен у домов пригорода');
  });
});
