// Экстерьер ханзы: последний из шести зданий без экстерьера.
//
// ЧЕМ ОТЛИЧАЕТСЯ ОТ ПРЕДЫДУЩИХ. Таможня — застава, ткацкая — мастерская,
// святилище — руина на уступе. Ханза — торговый двор: товарные ряды под навесом,
// весы у въезда, надписи на столбах, мешки и короба, следы копыт к воротам.
// Двор не защищают, а принимают товар.
//
// ЧТО ЗАМЕРЕНО:
//   * уровень -8.4 выбран ВОКРУГОМ МЕДИАНЫ (-8.38 по габариту 775 точек).
//     Перебор от нуля у ткацки выдал границу диапазона instead оптимума.
//   * ханза стоит в старой ложбине: срез до 1.66 м, засыпка до 1.19 м. Стенки
//     двора высотой 1.2 м закрывают край насыпи и читаются как ограда.
//   * радиус 52: полудиагональ комплекса 25.6 м, запас 3.0 м. При 48 запас 0.8 м.
//   * замер: дверь и выход ровно -8.4000, отклонение 0.0000; перепад по двору
//     0.000, по залу 0.012, по комплексу 0.034.
//   * РЕДКОЙШИЙ дефект первой сборки: товарный ряд стоял поперёк оси и
//     перекрывал подход к двери на 4 м. Исправлено: центральный проход шириной
//     7 м оставлен свободным, и замер это подтвердил — 22 из 24 точек оси.
//   * вода задана КОНТУРАМИ, а не высотой: на высоте земля была -8.4 при море
//     -3.2, но isWater дал 0 мокрых точек. Ошибка святилища не повторяется.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

function блокХанзы(): string {
  const начало = ТЕРРЕЙН.indexOf('  // ── Ханза');
  must(начало > 0, 'в terrain.ts нет блока постройки ханзы');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', начало);
  must(конец > начало, 'блок ханзы не найден по границе акведука');
  return ТЕРРЕЙН.slice(начало, конец);
}

describe('Ханза: площадка', () => {
  it('поставлена на месте записи интерьера', () => {
    must(
      /id: 'hanza',[^}]*dx: 1600, dz: 1000/.test(ИНТЕРЬЕРЫ),
      'запись ханзы в интерьерах изменилась: площадка без неё окажется не там',
    );
    must(
      /export const HANZA = \{ x: 1600, z: 1000,/.test(ТЕРРЕЙН),
      'площадка ханзы не совпадает с записью интерьера (1600, 1000)',
    );
  });

  it('ровнялка стоит ПОСЛЕ ровнялки залива и после святилища', () => {
    const код = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export function terrainHeight'),
      ТЕРРЕЙН.indexOf('const TERRAIN_SEG'),
    ).split('\n').filter((s) => !/^\s*(\/\/|\*|\/\*)/.test(s));
    const текст = код.join('\n');
    const залив = текст.indexOf('-820');
    const ханза = текст.indexOf('HANZA.x');
    must(залив > 0 && ханза > залив, 'ровнялка ханзы не после залива');
  });

  it('уровень близок к измеренной медиане -8.38', () => {
    const m = /export const HANZA = \{ x: 1600, z: 1000, radius: \d+, level: (-?[\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'уровень площадки ханзы не объявлен');
    const уровень = Number(m![1]);
    must(
      уровень >= -8.8 && уровень <= -8.0,
      `уровень ${уровень} м далеко от измеренной медианы -8.38`,
    );
  });

  it('запас ровной части достаточен: 48 дало бы 0.8 м', () => {
    const m = /export const HANZA = \{ x: 1600, z: 1000, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус не объявлен');
    const радиус = Number(m![1]);
    const ровная = радиус * 0.55;
    const полу = Math.hypot(28 / 2 + 3, 16 + 1.4 + 3);
    must(
      ровная - полу >= 2,
      `запас ${(ровная - полу).toFixed(1)} м мал: при радиусе 48 он был 0.8 м`,
    );
  });

  it('круги смешивания не достают до соседей', () => {
    const радиус = Number(/export const HANZA = \{ x: 1600, z: 1000, radius: (\d+)/.exec(ТЕРРЕЙН)![1]);
    for (const [имя, x, z] of [
      ['гробницы', 1400, 1400],
      ['святилища', 1200, 1200],
    ] as [string, number, number][]) {
      const расстояние = Math.hypot(1600 - x, 1000 - z);
      must(расстояние > радиус, `до ${имя} ${расстояние.toFixed(0)} м, радиус ${радиус} м`);
    }
  });

  it('под комплексом сухо: вода задана контурами', () => {
    // Замер по высоте дал -8.4 при море -3.2, и я чуть не сдвинул ханзу на 400 м.
    // isWater дал 0 мокрых точек: ложбина ниже моря — это впадина, а не залив.
    must(!isWater(1600, 1000), 'под ханзой вода');
    for (const [x, z] of [[1586, 1010], [1614, 990], [1600, 1030]] as const) {
      must(!isWater(x, z), `вода в пределах комплекса, точка ${x},${z}`);
    }
  });
});

describe('Ханза: дверь и подход', () => {
  it('начало местных координат — линия двери', () => {
    must(/export const HANZA = \{ x: 1600, z: 1000,/.test(ТЕРРЕЙН), 'группа не в точке двери');
    const блок = блокХанзы();
    must(/g\.position\.set\(HANZA\.x, HANZA\.level, HANZA\.z\)/.test(блок), 'группа не там');
  });

  it('дверь кликабельная и ведёт в интерьер ханзы', () => {
    const блок = блокХанзы();
    must(/doorBuilding: 'hanza'/.test(блок), 'у двери ханзы нет doorBuilding');
    must(/doorAction: 'enter'/.test(блок), 'дверь не ведёт внутрь');
    must(/doorName: t\('buildings\.hanza'\)/.test(блок), 'не то название');
  });

  it('проём двери открыт: передний ряд пропускает дверной проём', () => {
    const блок = блокХанзы();
    must(/Math\.abs\(sx\) >= DOOR_W \/ 2 \+ 1\.5/.test(блок), 'дверь перекрыта');
  });

  it('в проёме есть заглушка', () => {
    must(/ХАНЗА_ЗАГЛУШКА/.test(блокХанзы()), 'нет заглушки');
  });

  it('центральный проход свободен: товара нет у двери', () => {
    // Первая сборка ставила два ряда мешков поперёк оси, и подход к двери был
    // перекрыт на 4 м: мешок x=1599 закрывал выход. Мешки обязаны стоять только
    // по бокам от прохода шириной 7 м.
    const блок = блокХанзы();
    must(
      /if \(Math\.abs\(mx\) < 3\.5\) continue;/.test(блок),
      'товарный ряд стоит на оси: подход к двери перекрыт',
    );
  });
});

describe('Ханза: товарный двор объясняет интерьер', () => {
  it('навес над рядами товара', () => {
    const блок = блокХанзы();
    must(/canopy/.test(блок), 'нет навеса');
    must(/навес\.position\.set/.test(блок), 'навес не стоит над рядами');
  });

  it('весы у въезда: стойка и чаши', () => {
    const блок = блокХанзы();
    must(/весыX = YARD_W \/ 2 - 3\.0/.test(блок), 'весы не у въезда');
    must(/перекладина/.test(блок), 'у весов нет перекладины');
    must(/addCollider\(HANZA\.x \+ весыX, HANZA\.z \+ весыZ, 1\.2\)/.test(блок), 'у весов нет коллайдера');
  });

  it('надписи на столбах у въезда, разной высоты', () => {
    const блок = блокХанзы();
    must(/плита\.position\.set/.test(блок), 'плиты с надписями не построены');
    must(/rotation\.z = \(i % 2 === 0 \? 1 : -1\) \* 0\.05/.test(блок), 'плиты стоят ровно: у надписей должен быть наклон');
    must(/addCollider\(HANZA\.x - YARD_W \/ 2 \+ 2\.5 \+ i \* 2\.4/.test(блок), 'у столбов нет коллайдеров');
  });

  it('мешки и короба в рядах, с коллайдерами', () => {
    const блок = блокХанзы();
    must(/МЕШКИ\.push/.test(блок), 'мешки не объявлены');
    must(/addCollider\(HANZA\.x \+ mx, HANZA\.z \+ mz, 0\.8\)/.test(блок), 'у товара нет коллайдеров');
  });

  it('следы копыт у въезда, дугой как в интерьере', () => {
    const блок = блокХанзы();
    must(/СЛЕДЫ\.push/.test(блок), 'следы не объявлены');
    must(/YARD_D \+ 1\.0 \+ i \* 1\.6/.test(блок), 'следы не выезжают со двора');
  });

  it('стенки двора чтят ограду, а не ворота', () => {
    const блок = блокХанзы();
    must(/wallYard/.test(блок), 'нет стенок двора');
    must(
      /проём2 = DOOR_W \+ 2\.0/.test(блок),
      'проём двора не шире двери: торговец не везёт',
    );
  });

  it('плита двора почти вровень, а не цоколь', () => {
    const m = /export const ХАНЗА_ПЛИТА = \{ t: ([\d.]+), подъём: ([\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'параметры плиты не объявлены');
    must(Number(m![2]) <= 0.1, `подъём плиты ${m![2]} м велик`);
  });
});

describe('Ханза: размеры проезда и ворот', () => {
  it('ширина двери достаточна для телеги', () => {
    // Первая сборка имела дверь 3.4 м, это минимальный проезд для торговца.
    // Дверь 1.2 м ещё проходима пешком, но телега не едет, а торговец с
    // повозкой не ввозит товар. Заявлено 3.4 м.
    // Брать дверь надо из блока ХАНЗЫ, а не первое совпадение во всём файле: так
    // проверка скользила на дверь святилища (2.8 м) и ничего не говорила про
    // ханзу. Пока ломка «дверь 1.2 м» не ломала проверку — именно поэтому.
    // Дверь объявлена в секции констант HANZA_GEO, не в buildSettlements.
    const константы = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export const HANZA_GEO'),
      ТЕРРЕЙН.indexOf('// ── Акведук деревни', ТЕРРЕЙН.indexOf('export const HANZA_GEO')),
    );
    const m = /door: \{ w: ([\d.]+), h: ([\d.]+) \}/.exec(константы);
    must(m !== null, 'ширина двери не объявлена в HANZA_GEO');
    must(Number(m![1]) >= 2.4, 'дверь уже 2.4 м: телега не въедет');
  });

  it('проём у въезда шире двери и не запечатан', () => {
    // Двор принимает товар: проём двора шире двери зала на 2 м, и цепочка
    // коллайдеров передней стенки двора должна оставлять этот проём. Число
    // проём2 берём из блока ханзы, а не первое по файлу: иначе проверка била бы
    // по святилищу или таможне, у которых свои проёмы.
    const блок = блокХанзы();
    const m = /проём2 = DOOR_W \+ (\d+\.?\d*)/.exec(блок);
    must(m !== null, 'ширина проёма двора не объявлена');
    must(Number(m![1]) >= 1.5, 'проём двора не шире двери: торговец не везёт');
    must(
      /if \(Math\.abs\(tx\) >= проём2 \/ 2 \+ 0\.6\)/.test(блок),
      'условие проёма у въезда отсутствует: въезд в двор запечатан',
    );
  });

  it('стенки двора симметричны: обе стороны закрыты', () => {
    // Заглушка зеркальности: если боковые коллайдеры двора смещены на ту же
    // сторону, где стоит вес, то с другой стороны двор проходим насквозь.
    const блок = блокХанзы();
    must(
      /addCollider\(HANZA\.x - YARD_W \/ 2 - wallYard\.t \/ 2, HANZA\.z \+ tz, 1\.0\);\s*addCollider\(HANZA\.x \+ YARD_W \/ 2 \+ wallYard\.t \/ 2, HANZA\.z \+ tz, 1\.0\);/.test(блок),
      'боковые коллайдеры двора не на обеих сторонах: двор проходим сбоку',
    );
  });
});