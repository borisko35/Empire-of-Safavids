// Лимиты стека: maxStack был объявлением, которого в игре не существовало.
//
// ЧТО БЫЛО. Поле maxStack заполнено у 79 предметов (у 34 - 999, у 5 - 99...,
// у 28 - 1) и не проверялось нигде: addItems складывал количество одним
// INSERT...ON CONFLICT без всякого условия. Предмет с maxStack 5 доходил до
// 5000 в ОДНОЙ строке.
//
// ПОЧЕМУ ЭТО НЕ ПОЧИНИТЬ ПРОВЕРКОЙ. 3000 зелий с maxStack 20 - это 150 стеков,
// а уникальный ключ (character_id, item_id, enhancement) допускал одну строку
// на предмет. То есть данные предполагали возможность, которой в схеме не
// было. Миграция 075 добавила stack_index в ключ.
//
// ГЛАВНОЕ, ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ - не само число, а то, что при раскладке
// ничего не теряется и списание умеет забирать из НЕСКОЛЬКИХ стеков.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const предметы = читать('server/src/data/items.ts');
const сервис = код('server/src/services/CharacterService.ts');
const миграция = читать('database/migrations/075_inventory_stack_limit.sql');

describe('Лимиты стека: данные и схема', () => {
  it('предел объявлен у большинства предметов', () => {
    // Без этой проверки тест был бы страховкой от воображаемой проблемы.
    const максимумов = (предметы.match(/maxStack:/g) ?? []).length;
    must(максимумов >= 50, `maxStack объявлен у ${максимумов} предметов — проверять нечего`);
    const стековых = (предметы.match(/stackable:/g) ?? []).length;
    must(стековых >= 50, `stackable объявлен у ${стековых} предметов`);
  });

  it('схема допускает несколько стеков одного предмета', () => {
    // Это и есть корень: без stack_index предел нельзя было enforce'ить,
    // потому что второй стек просто не вставлялся.
    must(
      /ADD COLUMN IF NOT EXISTS stack_index INT NOT NULL DEFAULT 0/.test(миграция),
      'столбец номера стека не добавлен',
    );
    must(
      /UNIQUE \(character_id, item_id, enhancement, stack_index\)/.test(миграция),
      'номер стека не входит в уникальный ключ',
    );
    // Старый ключ снят ДО создания нового: на тех же столбцах осталось бы
    // два ограничения, и второй стек не вставить.
    must(
      миграция.indexOf('DROP CONSTRAINT IF EXISTS character_items_char_item_enh_key') <
        миграция.indexOf('ADD CONSTRAINT character_items_char_item_enh_stack_key'),
      'старый ключ снят после нового: вставка второго стека упала бы',
    );
  });
});

describe('addItems: раскладка по стекам', () => {
  it('складывает не одним запросом, а до предела', () => {
    // Прежде был один INSERT...ON CONFLICT складывающий без условия.
    must(
      !/ON CONFLICT \(character_id, item_id, enhancement\)\s*DO UPDATE SET quantity = character_items\.quantity \+ EXCLUDED\.quantity/.test(сервис),
      'складывание снова безусловное',
    );
    must(/quantity < \$4/.test(сервис), 'неполные стеки не ищутся');
  });

  it('предел берётся из данных, а не константа', () => {
    must(
      /def\?\.maxStack \?\? 1/.test(сервис),
      'предел не берётся из maxStack предмета',
    );
  });

  it('нестекаемый предмет всегда один в стеке', () => {
    // stackable: false - это отдельное правило, а не дубль maxStack. У оружия
    // и брони maxStack 1 всё равно, но опираться на это нельзя: предмет
    // может оказаться нестекаемым с maxStack больше 1.
    must(
      /def\?\.stackable === false \? 1 :/.test(сервис),
      'нестекаемый предмет может лежать в стеке больше одного',
    );
  });

  it('остаток раскладывается, а не обрезается', () => {
    // Урезать было бы проще и выглядело бы работающим. Но 3000 зелий при
    // пределе 20 - это 150 стеков, и обрезка молча теряла бы вещи.
    must(/while \(осталось > 0\)/.test(сервис), 'остаток не раскладывается: он теряется или обрезается');
    must(
      /MAX\(stack_index\), -1\) \+ 1/.test(сервис),
      'номер нового стека считается не в базе: два дозаполнения завели бы стек 0 дважды',
    );
  });
});

describe('removeItems: списание умеет забирать из нескольких стеков', () => {
  it('больше не требует одной строки с нужным количеством', () => {
    // Прежде было `WHERE quantity >= $1`: раз предмет лежал одной строкой,
    // этого хватало. С несколькими стеками отказ был бы ложным —
    // при трёх стеках по 20 и списании 50 сервер сказал бы «не хватает».
    must(
      !/WHERE character_id = \$2 AND item_id = \$3 AND quantity >= \$1\s*ORDER BY enhancement DESC LIMIT 1/.test(сервис),
      'списание снова требует одного стека с полным количеством',
    );
  });

  it('осушает стеки по кругу', () => {
    must(/while \(надо > 0/.test(сервис) || /for \(let круг = 0; надо > 0/.test(сервис),
      'списание идёт одним стеком');
    must(/quantity > 0\s*\n\s*ORDER BY enhancement DESC, quantity DESC/.test(сервис),
      'непустые стеки не выбираются');
  });

  it('снимает по остатку, а не сверх него', () => {
    // Иначе стек уходил в минус, а CHECK (quantity >= 0) ронял бы транзакцию.
    must(/const снять = Math\.min\(надо, вСтеке\)/.test(сервис),
      'снятие не ограничено остатком стека');
  });

  it('цикл не бесконечный', () => {
    // Стеков может быть много, но не бесконечно. Без предела ошибка подсчёта
    // повесила бы запрос навсегда.
    must(/круг < 200/.test(сервис), 'у цикла списания нет предела');
  });

  it('нехватка по-прежнему честная', () => {
    // Прежнее сообщение показывало сколько есть. Оно важно: без него игрок
    // не понимает, чего не хватило.
    must(
      /Not enough items: \$\{it\.itemId\} \(need/.test(сервис),
      'сообщение о нехватке потеряло числа',
    );
  });
});