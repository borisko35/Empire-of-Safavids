// Ступени и тумбы у городских ворот (§337).
//
// ЧТО БЫЛО (21 октября 2026, §236). Замеренный перепад у ворот: земля
// снаружи на 0.4 м ниже порога (снаружи y=1.08, у ворот y=1.48) — в ворота
// приходилось запрыгивать. Тумб, которые должны были держать караван от
// стены, не было вовсе.
//
// ЧТО ТЕПЕРЬ (§337). Ворота — готовая GLB-модель (city-gate.glb):
// ступени, тумбы, башни, арка, створки — всё в одной модели.
// Процедурный код ступеней и тумб удалён.
//
// ЧТО ПРОВЕРЯЕТСЯ. Ворота загружаются как GLB-модель; процедурные
// ступени и тумбы удалены.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

export function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Ступени и тумбы у ворот (§337)', () => {
  it('ворота загружаются как GLB-модель city-gate.glb', () => {
    if (!/loadDecorModel\('models\/decor\/city-gate\.glb'\)/.test(ТЕРРЕЙН)) {
      throw new Error('городские ворота не загружают city-gate.glb');
    }
  });

  it('процедурные ступени удалены: нет ручного расчёта ступеней от localY', () => {
    // Процедурный код расчёта ступеней от localY удалён
    if (/const низ = localY\(CITY\.x \+ gx \+ outX \* 7/.test(ТЕРРЕЙН)) {
      throw new Error('процедурный расчёт ступеней от localY не удалён');
    }
    if (/const порог = localY\(CITY\.x \+ gx/.test(ТЕРРЕЙН)) {
      throw new Error('процедурный расчёт порога не удалён');
    }
    if (/if \(порог > низ \+ 0\.05\) \{/.test(ТЕРРЕЙН)) {
      throw new Error('процедурное условие построения ступеней не удалено');
    }
    if (/const ступеней = 3;/.test(ТЕРРЕЙН)) {
      throw new Error('зашитое число ступеней не удалено');
    }
  });

  it('процедурные тумбы удалены: нет ручного создания тумб', () => {
    // Процедурное создание тумб удалено
    if (/new THREE\.Mesh\(\s*new THREE\.CylinderGeometry\(0\.28, 0\.34, 0\.95, 8\)/.test(ТЕРРЕЙН)) {
      throw new Error('процедурные тумбы не удалены');
    }
    if (/for \(const отступ of \[3\.6, 5\.2\]\)/.test(ТЕРРЕЙН)) {
      throw new Error('цикл создания тумб не удалён');
    }
    if (/addCollider\(CITY\.x \+ тумба\.position\.x/.test(ТЕРРЕЙН)) {
      throw new Error('коллайдеры тумб не удалены');
    }
  });

  it('процедурные ступени удалены: нет ручного создания ступеней', () => {
    // Процедурное создание ступеней удалено
    if (/new THREE\.BoxGeometry\(8\.4, высота, 1\.1\)/.test(ТЕРРЕЙН)) {
      throw new Error('процедурные ступени не удалены');
    }
    if (/const ступеней = 3;/.test(ТЕРРЕЙН)) {
      throw new Error('зашитое число ступеней не удалено');
    }
  });

  it('ворота имеют GLB-модель со ступенями и тумбами внутри', () => {
    // Проверяем, что модель city-gate.glb загружается
    if (!/loadDecorModel\('models\/decor\/city-gate\.glb'\)/.test(ТЕРРЕЙН)) {
      throw new Error('city-gate.glb не загружается');
    }
  });
});