// Ступени и тумбы у городских ворот.
//
// ЧТО БЫЛО (21 октября 2026, §236). Замеренный перепад у ворот: земля
// снаружи на 0.4 м ниже порога (снаружи y=1.08, у ворот y=1.48) — в ворота
// приходилось запрыгивать. Тумб, которые должны были держать караван от
// стены, не было вовсе.
//
// ЧТО ТЕПЕРЬ. Три ступени перед воротами и четыре тумбы по краям проезда.
//
// ЧТО ПРОВЕРЯЕТСЯ. Главное — ступени считаются от РЕАЛЬНОЙ ЗЕМЛИ (localY),
// а не от зашитого числа: перепад зависит от склона, и зашитое число
// разъехалось бы с землёй при любой правке рельефа.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Ступени и тумбы у ворот', () => {
  it('ступени считаются от реальной земли, а не от зашитого числа', () => {
    должен(
      /const низ = localY\(CITY\.x \+ gx \+ outX \* 7, CITY\.z \+ gz \+ outZ \* 7\)/.test(код),
      'низ ступеней не берётся с земли: зашитое число разъедется со склоном',
    );
    должен(
      /const порог = localY\(CITY\.x \+ gx, CITY\.z \+ gz\)/.test(код),
      'порог ворот не берётся с земли',
    );
    // Ступени строятся только если в ворота есть куда подниматься.
    должен(
      /if \(порог > низ \+ 0\.05\) \{/.test(код),
      'ступени строятся без проверки перепада: на ровном месте вылезет порог',
    );
    должен(/const ступеней = 3;/.test(код), 'ступеней не три');
  });

  it('тумбы стоят по краям проезда', () => {
    должен(
      /const тумба = new THREE\.Mesh\(\s*new THREE\.CylinderGeometry\(0\.28, 0\.34, 0\.95, 8\),\s*MAT\.sandstoneDark,?\s*\)/.test(
        код,
      ),
      'тумб у ворот нет: караван подъезжает вплотную к стене',
    );
    // По две с каждой стороны.
    должен(
      /for \(const отступ of \[3\.6, 5\.2\]\)/.test(код),
      'тумб не по две с каждой стороны',
    );
    // И каждая тумба — препятствие: коллайдер у неё есть.
    должен(
      /addCollider\(CITY\.x \+ тумба\.position\.x, CITY\.z \+ тумба\.position\.z, 0\.4\)/.test(код),
      'у тумбы нет коллайдера: игрок проходит сквозь неё',
    );
  });
});
