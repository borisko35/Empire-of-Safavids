// Живые последствия, кусок 2 (§360): стража помнит того, кого ударила.
//
// ЗА ЧТО БОРЕТСЯ. Вторая половина примера владельца «стража, NPC перестают
// говорить» (первую сделал §359). Пойманный тёмный отсиживался приседом:
// страж, ТОЛЬКО ЧТО ударивший игрока, тут же «забывал» его лицо, и тот же
// страж на том же месте не видел присевшего вора — наказание не оставляло
// последствий, мир не помнил.
//
// ЧТО ТЕПЕРЬ. Удар стража ставит метку розыска (10 минут): приседание больше
// не прячет — знающий в лицо страж приглядывается. Метка живёт в общем
// StealthStates, потому что читают её обе стороны детекции: тик удара
// (GameLoop) и обнаружение по пакетам движения (сокет-обработчик).
//
// ПОЧЕМУ ПОВЕДЕНЧЕСКАЯ ЧАСТЬ ОБЯЗАТЕЛЬНА. isWanted с истёкшей меткой обязан
// вернуть false И убрать метку: карта «розыск» иначе росла бы вечно (та же
// история, что с lastRegenPos и chatLastSent).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { StealthStates } from '../systems/StealthStates';
import { GUARD_GRUDGE_MS } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Розыск: поведение метки', () => {
  const ст = StealthStates.getInstance();
  const игрок = `test-grudge-${Date.now()}`;

  it('метка ставится и отвечает, пока жива', () => {
    const теперь = Date.now();
    ст.markWanted(игрок, теперь + GUARD_GRUDGE_MS);
    must(ст.isWanted(игрок, теперь + 1000), 'свежая метка розыска не читается');
  });

  it('истёкшая метка снимается сама', () => {
    const теперь = Date.now();
    ст.markWanted(`${игрок}-old`, теперь + 1000);
    must(!ст.isWanted(`${игрок}-old`, теперь + 2000), 'истёкшая метка держит розыск');
    must(!ст.isWanted(`${игрок}-old`, теперь + 3000), 'истёкшая метка не убралась: карта растёт вечно');
  });

  it('выход из сессии забывает розыск', () => {
    const теперь = Date.now();
    ст.markWanted(`${игрок}-cleanup`, теперь + GUARD_GRUDGE_MS);
    ст.cleanup(`${игрок}-cleanup`);
    must(!ст.isWanted(`${игрок}-cleanup`, теперь), 'ушедший игрок остался в розыске до перезапуска');
  });

  it('длительность в рамках: заметно, но не вечна', () => {
    must(GUARD_GRUDGE_MS >= 5 * 60 * 1000 && GUARD_GRUDGE_MS <= 30 * 60 * 1000,
      `розыск ${GUARD_GRUDGE_MS} мс вне рамок: либо игрок не заметит, либо дольше памяти мира`);
  });
});

describe('Проводка: обе стороны детекции читают одну метку', () => {
  const обработчик = читать('server/src/socket/GameSocketHandler.ts');
  const цикл = читать('server/src/systems/GameLoop.ts');
  const клиент = читать('client/src/app/world.ts');
  const stealth = читать('server/src/systems/StealthStates.ts');

  it('удар стража ставит метку на GUARD_GRUDGE_MS из shared', () => {
    must(/markWanted\(игрок\.id, теперь \+ GUARD_GRUDGE_MS\)/.test(цикл),
      'удар стража не ставит розыск: наказание без последствий');
    must(!/markWanted\([^,]+,\s*[^,]+\+\s*\d+\s*\*\s*60/.test(цикл),
      'длительность розыска вбита числом в тик: копия разойдётся с shared');
  });

  it('присед не прячет от знающих — в обоих путях', () => {
    must(/crouch: data\.crouch === true && !розыск,/.test(обработчик),
      'сокет-путь прячет присевшего розыскного: страж знает в лицо, но делает вид');
    must(/crouch: скрытность\?\.crouch === true && !розыск\.has\(игрок\.id\),/.test(цикл),
      'тик удара прячет присевшего розыскного');
  });

  it('метка живёт в общем StealthStates, а не в двух картах', () => {
    must(/wanted\.delete\(characterId\)/.test(stealth), 'cleanup не снимает розыск');
    must((обработчик.match(/markWanted/g) ?? []).length === 0,
      'сокет-обработчик сам ставит розыск: ставит его только удар стража в тике');
    must(!/new Map<string, number>\(\)/.test(обработчик.split('StealthStates.getInstance')[0]),
      'в сокет-обработчике заводится своя карта розыска: копия разойдётся');
  });

  it('игрок узнаёт причину: почему присед перестал прятать', () => {
    must(/wanted: розыск,/.test(обработчик), 'GUARD_SPOTTED не помечает розыск');
    must(/stealth\.spotted_wanted/.test(клиент), 'клиент не показывает строку розыска');
  });
});
