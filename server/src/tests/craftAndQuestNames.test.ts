// Предметы на экранах крафта и заданий называются переводом, а не
// по-русски.
//
// ЧТО ЗДЕСЬ ВСКРЫТО. Сервер в этих ответах уже присылает itemId рядом с
// nameRu — QuestService.ts:375 и recipesForClient() в data/crafting.ts.
// То есть перевести было чем: имяПредмета() существовала и работала, а эти
// два экрана её не вызывали и печатали nameRu напрямую. Игрок на en или az
// видел «Сварить Малое Зелье» и «Клинок Шаха Аббаса ×1» — по-русски
// посреди интерфейса, который целиком переведён.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Экраны крафта и заданий переводят названия предметов', () => {
  it('панель крафта называет результат через itemName', () => {
    // Проверяется весь код панели, а не строки, попавшие под фильтр по
    // слову. Первая версия фильтровала строки по /resultNameRu|ingredients/,
    // и строка с чипом ингредиента в проверку не попадала: слово
    // ingredients стоит на строке выше, в заголовке цикла. Фильтр молча
    // выкидывал ровно ту строку, ради которой написан, и панель можно было
    // вернуть к печати по-русски, не получив ни одной ошибки.
    //
    // Поэтому здесь общий запрет на подстановку nameRu предмета в строку
    // панели плюс требование, что перевод вообще используется.
    const панель = stripComments(читать('client/src/app/panels.ts'));
    must(!/\$\{\s*i\.nameRu\s*\}/.test(панель),
      'название ингредиента печатается по-русски: чип вернулся к i.nameRu');
    must(!/\$\{\s*r\.resultNameRu\s*\}/.test(панель),
      'название результата печатается по-русски: вернулась подстановка r.resultNameRu');
    must(/itemName\(\s*r\.resultItemId/.test(панель),
      'название результата крафта больше не переводится — itemName(r.resultItemId) не найден');
  });

  it('тост о выполненном задании называет предметы через имяПредмета', () => {
    // Отдельно от крафта: тост собирается в world.ts и раньше печатал
    // `${i.nameRu}`. Проверка на весь файл слишком широкая — nameRu в
    // world.ts встречается для монстров и NPC, и там это законно.
    const исходник = stripComments(читать('client/src/app/world.ts'));
    must(!/\$\{\s*i\.nameRu\s*\}/.test(исходник),
      'тост задания печатает i.nameRu напрямую: предмет покажут по-русски');
    must(/имяПредмета\(/.test(исходник),
      'world.ts перестал пользоваться имяПредмета() — проверка молчит, а экран опять русский');
  });

  it('название рецепта переводится по ключу recipes.<id>', () => {
    // У рецепта есть name и nameRu в данных, но самого ключа в словаре
    // раньше не было: панель печатала r.nameRu напрямую, и игрок на en или
    // az видел «Сварить Малое Зелье» посреди переведённого интерфейса.
    const панель = stripComments(читать('client/src/app/panels.ts'));
    must(!/\$\{\s*r\.nameRu\s*\}/.test(панель),
      'название рецепта печатается по-русски: подстановка r.nameRu вернулась');
    must(/tOr\(\s*`recipes\.\$\{/.test(панель),
      'перевод названия рецепта больше не ищется — tOr(`recipes.…`) не найден');
  });

it('тип награды за задание объявляет itemId', () => {
    // Объявление типа в world.ts повторяет форму ответа сервера. Когда
    // itemId убрали из типа, TypeScript перестал проверять это место, и
    // подстановка имяПредмета(i.itemId, ...) собрала бы undefined молча.
    const исходник = читать('client/src/app/world.ts');
    const объявление = /items:\s*\{[^}]*\}\[\]/.exec(исходник);
    must(объявление !== null, 'объявление items в типе награды не найдено');
    must(/itemId:\s*string/.test(объявление![0]),
      'в типе награды нет itemId — подстановка имени предмета не проверяется компилятором');
  });
});