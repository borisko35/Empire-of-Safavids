// Каждый вызов клиента имеет маршрут на сервере.
//
// ЧТО ЭТО ЗАЩИЩАЕТ. Если клиент зовёт /api/что-то, чего сервер не держит,
// игрок получает 404 в момент нажатия. Класс ошибок, который не виден ни
// в логах сервера (запрос просто не совпал ни с одним роутом), ни в
// проверках компиляции.
//
// ПОЧЕМУ ТАКАЯ ПРОВЕРКА ОПАСНА И КАК ЭТО УЧТЕНО. Она разбирает исходники
// регулярками, а регулярки молчат: сканер, который ничего не находит,
// выглядит как «всё хорошо». Первая версия этого аудита искала
// req('POST', url), тогда как клиент пишет req(url, { method }) — и нашла
// НОЛЬ вызовов, рапортовав «расхождений нет». Потом \\b перед Router не
// сработал на authRouter.post, и 95 вызовов выглядели как 404. Потом был
// пропущен целый каталог клиентских файлов, и все маршруты админки
// показались мёртвыми.
//
// Поэтому здесь обязательна самопроверка: сканер сначала обязан доказать,
// что он вообще что-то находит. Числа проверки не выдуманы — они сняты
// с живого кода и зафиксированы с запасом.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

function файлы(dir: string, подкаталоги = true): string[] {
  const out: string[] = [];
  for (const имя of readdirSync(dir)) {
    const полный = join(dir, имя);
    if (statSync(полный).isDirectory()) {
      if (подкаталоги) out.push(...файлы(полный));
    } else if (/\.(ts|js)$/.test(имя) && !имя.endsWith('.test.ts')) {
      out.push(полный);
    }
  }
  return out;
}

/**
 * Схлопывает `${...}` в «:», включая вложенные шаблоны.
 *
 * Нужно ради URL вида
 *   `/api/feedback${fbStatus ? `?status=${fbStatus}` : ''}`
 * где внутри подстановки есть свои кавычки. Регулярка по обратным
 * кавычкам обрывается на первой внутренней и оставляет хвост
 * `/api/feedback${fbStatus`, который не совпадает ни с одним маршрутом.
 * Считаем баланс скобок, идя по коду от руки: вложенные кавычки и
 * фигурные скобки пропускаем целиком.
 */
function схлопнутьПодстановки(код: string): string {
  let выход = '';
  let i = 0;
  while (i < код.length) {
    if (код[i] === '$' && код[i + 1] === '{') {
      let глубина = 1;
      let j = i + 2;
      while (j < код.length && глубина > 0) {
        if (код[j] === '{') глубина++;
        else if (код[j] === '}') глубина--;
        else if (код[j] === '`') {
          // Пропускаем вложенный шаблон целиком, вместе с его ${}.
          j++;
          while (j < код.length && код[j] !== '`') {
            if (код[j] === '\\') j++;
            j++;
          }
        }
        j++;
      }
      if (глубина !== 0) {
        // Несбалансированная подстановка — исходник битый, оставляем как есть.
        выход += код.slice(i);
        return выход;
      }
      выход += ':';
      i = j;
      continue;
    }
    выход += код[i];
    i++;
  }
  return выход;
}

const маршрутыСервера = new Set<string>();
const монтирования = new Map<string, string>();
const файлыРоутов = файлы(join(корень, 'server/src/routes'), false);
const исходникСервера = readFileSync(join(корень, 'server/src/index/index.ts'), 'utf-8');
for (const m of исходникСервера.matchAll(/app\.use\(\s*'([^']+)'\s*,\s*(\w+)\s*\)/g)) {
  монтирования.set(m[2], m[1]);
}

const привязкаФайла = new Map<string, string>();
for (const файл of файлыРоутов) {
  const код = readFileSync(файл, 'utf-8');
  // Файл может объявлять НЕСКОЛЬКО роутов (media.ts: mediaRouter и
  // galleryRouter под разными префиксами). Первая версия брала только
  // первый, и маршрут галереи приписывался админскому префиксу — сайт
  // получал «404» на работающем fetch.
  const начала = [...код.matchAll(/(?:export\s+)?const\s+(\w*[Rr]outer)\s*=\s*Router\(\)/g)];
  must(начала.length > 0, `Файл роутов ${файл} не содержит ни одного Router()`);
  начала.forEach((начало, индекс) => {
    const имя = начало[1];
    const позиция = начало.index ?? 0;
    // Латиница вперемешку с кириллицей — ловушка этого проекта: `index`
    // кириллицей в одном месте и латиницей в другом дают TS2304 «не найдено»
    // при живом параметре. Имя параметра и обращение к нему должны быть
    // одним и тем же символом.
    const следующий = начала[индекс + 1]?.index ?? код.length;
    // Роут внутри файла может называться как угодно, а смонтирован под
    // другим именем: в guilds.ts это `const router`, а в index.ts -
    // guildsRouter. Разрешаем по трём признакам подряд: точное имя,
    // имя файла, и только потом сдаёмся.
    const основаФайла = файл.split(/[\\/]/).pop()!.replace(/\.ts$/, '').toLowerCase();
    const префикс = монтирования.get(имя)
      ?? монтирования.get(`${[...монтирования.keys()].find((к) => к.replace(/Router$/, '').toLowerCase() === основаФайла) ?? ''}Router`)
      ?? [...монтирования.entries()].find(
        ([переменная]) => переменная.replace(/Router$/, '').toLowerCase() === основаФайла,
      )?.[1]
      ?? '';
    if (!префикс) {
      привязкаФайла.set(файл, `РОУТ НЕ СМОНТИРОВАН: ${имя}`);
      return;
    }
    for (const m of код.slice(позиция, следующий).matchAll(/\w*[Rr]outer\.(get|post|put|patch|delete)\(\s*'([^']*)'/g)) {
      const полный = `${префикс}${m[2]}`.replace(/\/$/, '') || '/';
      маршрутыСервера.add(`${m[1].toUpperCase()} ${полный.replace(/:[A-Za-z_][\w]*/g, ':')}`);
    }
  });
}

const вызовыКлиента = new Map<string, Set<string>>();
for (const файл of [...файлы(join(корень, 'client/src')), ...файлы(join(корень, 'client/web'))]) {
  // Подстановки схлопываются ДО разбора URL, иначе вложенный шаблон
  // рвёт регулярку по обратным кавычкам.
  const код = схлопнутьПодстановки(readFileSync(файл, 'utf-8'));
  // Отсечка по готовому ключу «метод + путь», а НЕ по одному URL.
  // Один и тот же путь встречается с разными методами: GET /api/characters
  // (список) и POST /api/characters (создание). Отсечка по URL проглатывала
  // пару целиком, и 20 живых маршрутов выглядели «никем не вызванными».
  const добавить = (url: string, метод: string) => {
    if (!url.startsWith('/api/')) return;
    const путь = url.split('?')[0].split('#')[0].replace(/\/$/, '');
    // Хвостовое ':' бывает двух видов. `/api/characters/${id}` — это
    // законный параметр, и срезать его нельзя: иначе DELETE
    // /api/characters/abc не найдёт серверный DELETE /api/characters/:id.
    // А `/api/feedback${q ? '?..' : ''}` — подстановка может быть пустой,
    // и там нужен ещё и вариант без хвоста. Поэтому заносим оба.
    // Вариант без хвоста срезается ВМЕСТЕ со слэшем: иначе остаётся
    // '/api/feedback/', а у маршрута слэша нет, и живой вызов начинает
    // выглядеть как 404.
    const варианты = путь.endsWith(':') ? [путь, путь.replace(/:\/?$/, '')] : [путь];
    for (const вариант of варианты) {
      if (!вариант) continue;
      const ключ = `${метод} ${вариант}`;
      if (вызовыКлиента.has(ключ)) continue;
      вызовыКлиента.set(ключ, new Set());
      вызовыКлиента.get(ключ)!.add(файл);
    }
  };
  // Тип-аргумент req<...> разбираем НЕЖАДНО до «> перед открытой скобкой».
  // Обычное <[^>]*> обрывается на первом «>», а в обобщении типа встречаются
  // стрелочные функции (x: T) => U. Из-за этого терялись вызовы с
  // нетривиальным типом ответа — целый /api/game/boats, /api/chronicles и
  // два десятка других, все живые.
  const ТИП = '(?:<[\\s\\S]{0,900}?>)?\\s*\\(';
  // Метод лежит в объекте опций через несколько символов после URL.
  for (const m of код.matchAll(new RegExp(`(?<![.\\w])req${ТИП}\\s*(?:'([^']+)'|\`([^\`]+)\`)\\s*,\\s*\\{([\\s\\S]{0,400}?)\\}`, 'g'))) {
    добавить(m[1] ?? m[2], /method:\s*'([A-Z]+)'/.exec(m[3])?.[1] ?? 'GET');
  }
  // Голый вызов req(url) — это GET по умолчанию. Его регулярка попадает и
  // в req(url, { method: 'POST' }), и такой вызов попадал бы в список
  // ДВАЖДЫ: один раз верный, второй раз как GET — 40 живых маршрутов
  // выглядели 404. Отличаем по тому, что реально стоит после запятой:
  // есть фигурная скобка — это объект опций, его метод уже прочитан выше.
  // Запятая сама по себе не значит опций: `req('/api/chronicles',\n  )`
  // — это голый GET, и по признаку «дальше запятая» он ошибочно
  // отбрасывался, а маршрут /api/chronicles выглядел мёртвым.
  for (const m of код.matchAll(new RegExp(`(?<![.\\w])req${ТИП}\\s*(?:'([^']+)'|\`([^\`]+)\`)\\s*,?\\s*(\\{)?`, 'g'))) {
    if (m[3] === '{') continue;
    добавить(m[1] ?? m[2], 'GET');
  }

  // Админка зовёт через свою обёртку api(url, { method }), а не через req.
  for (const m of код.matchAll(/(?<![.\w])api\(\s*(?:'([^']+)'|`([^`]+)`)\s*,\s*\{([\s\S]{0,300}?)\}/g)) {
    добавить(m[1] ?? m[2], /method:\s*'([A-Z]+)'/.exec(m[3])?.[1] ?? 'GET');
  }
  for (const m of код.matchAll(/(?<![.\w])api\(\s*(?:'([^']+)'|`([^`]+)`)\s*\)/g)) добавить(m[1] ?? m[2], 'GET');

  for (const m of код.matchAll(/fetch\(\s*`?'?([^'`,\s)]+)([\s\S]{0,300}?)\)/g)) {
    добавить(m[1], /method:\s*'([A-Z]+)'/.exec(m[2])?.[1] ?? 'GET');
  }
}

describe('Каждый вызов клиента обеспечен маршрутом сервера', () => {
  it('сканер видит и маршруты, и вызовы', () => {
    // Если сканер ослеп, все проверки ниже превращаются в «пройдено».
    must(
      маршрутыСервера.size >= 200,
      `Найдено ${маршрутыСервера.size} маршрутов, а их больше двухсот: регулярка перестала ловить форму записи.`,
    );
    must(
      вызовыКлиента.size >= 100,
      `Найдено ${вызовыКлиента.size} вызовов, а их больше ста: регулярка перестала ловить форму вызова.`,
    );
    must(
      привязкаФайла.size === 0,
      `Роуты объявлены, но не смонтированы — их не найдёт ни один запрос:\n  ${[...привязкаФайла.values()].join('\n  ')}`,
    );
  });

  it('ни один вызов клиента не упирается в 404', () => {
    const безМаршрута: string[] = [];
    for (const [ключ, откуда] of вызовыКлиента) {
      if (маршрутыСервера.has(ключ)) continue;
      // Ключ, кончающийся на ':', — это второй, ОБЯЗАТЕЛЬНЫЙ вариант
      // вызова с хвостовым параметром: `/api/characters/${id}` даёт и
      // `DELETE /api/characters/:`, и `DELETE /api/characters`. Пара с
      // хвостом настоящая (её держит серверный маршрут), а пара без
      // хвоста — про запас, на случай пустой подстановки. Если безавый
      // вариант не нашёлся, фантомом считается ИМЕННО он, и настоящий
      // вызов с параметром ошибкой быть не может.
      if (ключ.endsWith(':')) continue;
      // Серверный :param обслуживает конкретный путь клиента:
      // GET /api/site/content/:key отдаёт /api/site/content/news.
      const подходит = [...маршрутыСервера].some((маршрут) => {
        if (!маршрут.includes(':')) return false;
        if (маршрут.slice(0, маршрут.indexOf(' ')) !== ключ.slice(0, ключ.indexOf(' '))) return false;
        const сегментыСервера = маршрут.split(' ')[1].split('/');
        const сегментыКлиента = ключ.split(' ')[1].split('/');
        return сегментыСервера.length === сегментыКлиента.length
          && сегментыСервера.every((с, i) => с.startsWith(':') || с === сегментыКлиента[i]);
      });
      if (!подходит) безМаршрута.push(`${ключ}  <- ${[...откуда].join(', ')}`);
    }
    must(
      безМаршрута.length === 0,
      `Клиент зовёт эти маршруты, которых сервер не держит — игрок получит 404:\n  ${безМаршрута.join('\n  ')}`,
    );
  });

  it('реестр маршрутов без клиентского вызова не меняется молча', () => {
    // ЧТО ЭТО ЗА СПИСОК, А ЧТО НЕТ. Это НЕ доказательство мёртвого кода.
    // Маршрут без вызова бывает минимум трёх видов, и сканер их не различает:
    //   - вебхуки платёжных систем (yookassa, xsolla) — их зовёт внешний
    //     сервис, а не браузер;
    //   - внутренние маршруты без UI (зоны, регионы, память NPC);
    //   - настоящий дубль: у game.ts есть свой набор гильдий
    //     (/api/game/guilds...), а клиент ходит в /api/guilds.
    // Утверждать «здесь ноль мёртвых» было бы враньём: чтобы так утверждать,
    // нужно прочитать каждый из 41 вручную, а не посчитать регуляркой.
    //
    // ЧТО ПРОВЕРКА ДЕЛАЕТ. Фиксирует состав списка. Новое uncalled-роут
    // не появится незаметно, а исправленное или удалённое придётся
    // отметить здесь руками — вместе с решением, что с ним делать.
    const вызванные = new Set<string>();
    for (const ключ of вызовыКлиента.keys()) {
      вызванные.add(ключ);
      // Динамический сегмент клиента покрывает любой конкретный путь
      // сервера с параметром: DELETE /api/characters/: покрывает и
      // DELETE /api/characters/abc.
      const части = ключ.split(' ')[1].split('/');
      for (let i = 0; i < части.length; i++) {
        if (!части[i].startsWith(':')) continue;
        вызванные.add(`${ключ.slice(0, ключ.indexOf(' '))} ${[...части.slice(0, i), '*', ...части.slice(i + 1)].join('/')}`);
      }
    }
    const безВызова = [...маршрутыСервера].filter((маршрут) => {
      if (вызванные.has(маршрут)) return false;
      const части = маршрут.split(' ')[1].split('/');
      return ![...вызванные].some((в) => {
        if (в.slice(0, в.indexOf(' ')) !== маршрут.slice(0, маршрут.indexOf(' '))) return false;
        const п = в.split(' ')[1].split('/');
        return п.length === части.length
          && п.every((с, i) => с === '*' || с === части[i] || с.startsWith(':'));
      });
    });

    // Ожидаемый состав. Правка здесь = осознанное решение по конкретному
    // маршруту, а не следствие того, что сканер что-то сломал.
    const ожидаемый = [
      'POST /api/admin/seasonal-event',
      'POST /api/admin/give-item',
      'POST /api/admin/set-level',
      'GET /api/admin/violations/:',
      'GET /api/admin/logs',
      'GET /api/admin/online',
      'GET /api/admin/combat-log',
      'GET /api/admin/reports',
      'POST /api/auth/logout-all',
      'GET /api/auth/check-username/:',
      'GET /api/auth/check-email/:',
      'POST /api/auth/reset-rate-limit',
      'GET /api/chronicles/:',
      'GET /api/game/shops/:',
      // Вебхуки платёжных систем: вызывает внешний сервис, не браузер.
      'POST /api/game/payments/webhook/yookassa',
      'POST /api/game/payments/webhook/xsolla',
      'POST /api/game/payments/webhook/:',
      // Дубль набора гильдий: клиент ходит в /api/guilds, а не сюда.
      'GET /api/game/guilds',
      'POST /api/game/guilds',
      'GET /api/game/guilds/:',
      'POST /api/game/guilds/:/invite',
      'POST /api/game/guilds/:/kick',
      'POST /api/game/guilds/:/deposit',
      'POST /api/game/guilds/:/deposit-item',
      'POST /api/game/guilds/:/withdraw-item',
      'GET /api/game/quests/:',
      'GET /api/game/dungeons/:',
      'GET /api/game/world-bosses',
      'GET /api/guilds/territories',
      'POST /api/media/gallery',
      'PATCH /api/media/gallery/:',
      'DELETE /api/media/gallery/:',
      'GET /api/chess/current',
      'POST /api/npc/:/complete-quest',
      'GET /api/npc/:/memory',
      'GET /api/progression/achievements/:/progress',
      'GET /api/progression/reputation/:',
      'GET /api/site/content/:',
      'PUT /api/site/content/:',
      'GET /api/world/zones',
      'POST /api/world/zone/check',
      'GET /api/world/regions/:',
    ];

    // Сравнение по содержанию, а не по длине: и новый маршрут, и
    // исчезнувший должны называться, молчаливого схождения быть не должно.
    const лишние = безВызова.filter((м) => !ожидаемый.includes(м));
    const исчезнувшие = ожидаемый.filter((м) => !безВызова.includes(м));
    must(
      лишние.length === 0 && исчезнувшие.length === 0,
      [
        лишние.length ? `Появились маршруты без клиентского вызова (${лишние.length}):\n  ${лишние.join('\n  ')}` : '',
        исчезнувшие.length ? `Эти маршруты перестали быть «без вызова» — отметь решение в списке ожидаемых (${исчезнувшие.length}):\n  ${исчезнувшие.join('\n  ')}` : '',
      ].filter(Boolean).join('\n'),
    );
  });
});
