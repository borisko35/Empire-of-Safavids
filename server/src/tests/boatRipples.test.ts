// Рябь от лодок у причала.
//
// ЧТО БЫЛО (22 октября 2026, §280). Лодки качались на волнах (§277), а вода
// вокруг них стояла стеклом: волны шли по всему озеру одинаково. Причал с
// лодками читался как декорация.
//
// ЧТО ТЕПЕРЬ. От борта лодки расходятся круги: волна расширяется и гаснет.
//
// ЧТО ПРОВЕРЯЕТСЯ. Круги заводятся от лодок, расширяются и бледнеют, и их
// немного — иначе причал покроется пеной.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РЯБЬ = читать('client/src/app/game3d/boatRipples.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Рябь от лодок', () => {
  it('круги заводятся от лодок, расширяются и гаснут', () => {
    должен(/export function createRipples/.test(РЯБЬ), 'нет ряби');
    // Круг появляется у лодки.
    должен(
      /к\.sprite\.position\.set\(л\.x, л\.y \+ 0\.05, л\.z\);/.test(РЯБЬ),
      'круг появляется не у лодки',
    );
    // Расширяется: от малого к большому.
    должен(
      /const радиус = МАЛЫЙ \+ \(БОЛЬШОЙ - МАЛЫЙ\) \* доля;/.test(РЯБЬ),
      'круг не расширяется',
    );
    // И бледнеет.
    должен(
      /opacity = 0\.5 \* \(1 - доля\) \* \(1 - доля\);/.test(РЯБЬ),
      'круг не гаснет',
    );
    // Кругов немного.
    должен(/const КРУГОВ = 8;/.test(РЯБЬ), 'кругов слишком много: причал в пене');
  });

  it('движок передаёт ряби лодки', () => {
    должен(
      /this\.рябь\.update\(dt, now, лодкиНаВоде\);/.test(МИР),
      'рябь не обновляется',
    );
    // Мировые точки лодок собираются из самих лодок.
    должен(/const мир = л\.группа\.getWorldPosition\(new THREE\.Vector3\(\)\);/.test(МИР),
      'мировая точка лодки не берётся');
    должен(/this\.рябь\?\.dispose\(\);/.test(МИР), 'рябь не вычищается');
  });
});
