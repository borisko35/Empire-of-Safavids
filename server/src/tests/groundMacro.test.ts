// Площадь не должна читаться решёткой.
//
// ЧТО БЫЛО. Настил — цилиндр с одной детальной текстурой и repeat 10. Одна
// текстура на большой площади всегда читается решёткой: глаз очень быстро
// находит период повтора, и площадь перестаёт быть площадью. Это было
// главным, что выдавало браузерную игру в кадре.
//
// ЧТО СДЕЛАНО. Поверх детальной карты кладётся низкочастотная макро-пестрота,
// растянутая на всю площадь целиком: её повтор глаз не видит. Рисунок плиты
// при этом остаётся — маска не перекрашивает, а гасит и подсвечивает.
//
// ЧТО ПРОВЕРЯЕТСЯ. Слой действительно добавлен (а не объявлен), умножение
// идёт вокруг единицы, макро-координаты СЫРЫЕ (без repeat детальной карты —
// иначе макро тоже начнёт повторяться), и ключ программы задан.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ТЕКСТУРЫ = читать('client/src/app/game3d/textures.ts');
const МИР = читать('client/src/app/game3d/terrain.ts');

describe('Площадь не читается решёткой', () => {
  it('макро-слой добавлен к настилу', () => {
    должен(/export function addMacroLayer\(/.test(ТЕКСТУРЫ), 'нет addMacroLayer');
    должен(/export function macroTexture\(/.test(ТЕКСТУРЫ), 'нет macroTexture');
    должен(
      /addMacroLayer\(материалПлощади,\s*macroTexture\(\)/.test(МИР),
      'макро-слой не добавлен к площади: решётка плиты останется',
    );
  });

  it('слой действительно патчит шейдер, а не просто объявлен', () => {
    // Объявить функцию и не вызвать onBeforeCompile — значит ничего не
    // изменилось, а выглядит как готовая правка.
    должен(/onBeforeCompile\s*=/.test(ТЕКСТУРЫ), 'нет патча onBeforeCompile: слой не попадёт в шейдер');
    // Ищем САМ ВЫЗОВ replace с этим куском, а не просто упоминание имени.
    // ЧЕТВЁРТЫЙ РАЗ одно и то же: проверка падает (или проходит не по делу)
    // на собственном пояснении — здесь имя куска стоит в комментарии.
    должен(
      /\.replace\(\s*['"]#include <map_fragment>['"]/.test(ТЕКСТУРЫ),
      'патч не встраивается после map_fragment: умножение не применится',
    );
    должен(/shader\.vertexShader[\s\S]{0,400}vMacroUv\s*=\s*uv/.test(ТЕКСТУРЫ),
      'в вершинном шейдере не отдаётся сырая координата');
  });

  it('макро берёт СЫРУЮ координату, а не умноженную на repeat', () => {
    // vMapUv в three уже домножена на repeat детальной карты. Если взять её,
    // макро повторится ровно так же, как плитка, — и обе текстуры будут
    // решёткой синхронно. Это самая частая ошибка в таком патче.
    должен(/vMacroUv\s*=\s*uv\s*;/.test(ТЕКСТУРЫ), 'макро-координата берётся не из сырого uv');
    должен(
      /texture2D\(uMacroMap,\s*vMacroUv\s*\*\s*uMacroRepeat\)/.test(ТЕКСТУРЫ),
      'макро сэмплится не по своей координате: повтор уйдёт в плитку',
    );
  });

  it('умножение идёт вокруг единицы, а не перекрашивает', () => {
    // mix(1-s, 1+s, v): маска варьирует яркость и ничего не подменяет.
    // Перекрашивание убило бы рисунок плиты — то есть вылечило бы
    // повтор, сломав саму площадь.
    должен(
      /mix\(\s*1\.0\s*-\s*uMacroStrength,\s*1\.0\s*\+\s*uMacroStrength/.test(ТЕКСТУРЫ),
      'маска не умножается вокруг единицы: либо перекрасит, либо ничего не даст',
    );
  });

  it('задан ключ программы, иначе патч исчезнет', () => {
    // three переиспользует скомпилированную программу у материалов с
    // одинаковыми параметрами. Без своего ключа материал без макро-слоя
    // может занять программу, и патч пропадёт молча — у другого материала.
    должен(
      /customProgramCacheKey/.test(ТЕКСТУРЫ),
      'нет customProgramCacheKey: патч может исчезнуть из-за переиспользования программы',
    );
  });

  it('сила слоя разумна', () => {
    // Слишком сильно — плита «плывёт» и узор рассыпается; слишком слабо —
    // решётка остаётся. Разумный коридор и есть содержание проверки.
    const м = /addMacroLayer\(материалПлощади,\s*macroTexture\(\),\s*([\d.]+)/.exec(МИР);
    должен(м, 'сила макро-слоя не задана числом');
    const сила = Number(м![1]);
    должен(сила >= 0.15 && сила <= 0.5,
      `сила ${сила}: слишком слабо (решётка останется) или слишком сильно (плита рассыплется)`);
  });
});