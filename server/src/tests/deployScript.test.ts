describe('Предварительная проверка: обязательные переменные', () => {
  it('список выводится из compose, а не выписан руками', () => {
  // Обязательным считается ровно то, на что compose ставит `:?`, то есть
  // подстановка без значения по умолчанию. Список, выписанный руками,
  // требовал DB_NAME и DB_USER, у которых в compose есть умолчания, и
  // объявлял рабочую конфигурацию неполной.
  //
  // Сверка подстрочная, а не регуляркой: регулярка в TypeScript требует
  // удвоения всех обратных слэшей, и первая версия проверки искала сама
  // себя в виде `\.test(` — то есть даже не компилировалась.
  must(
    безКомментариев(ПРОВЕРКА).includes('docker-compose.prod.yml'),
    'в предварительной проверке нет ссылки на файл compose, ' +
      'из которого берётся список обязательных переменных',
  );
  must(
    безКомментариев(ПРОВЕРКА).includes('grep -o'),
    'обязательные переменные не выводятся из docker-compose.prod.yml: ' +
      'список разойдётся с ним молча',
  );
  must(
    безКомментариев(ПРОВЕРКА).includes('[A-Z_][A-Z0-9_]*:?'),
    'в предварительной проверке нет шаблона подстановки, ' +
      'по которой ищутся обязательные переменные',
  );
  // Перечисление руками требовало переменных со значениями по умолчанию.
  for (const имя of ['DB_NAME', 'DB_USER']) {
    const строкиREQUIRED = безКомментариев(ПРОВЕРКА)
      .split('\n')
      .filter((с) => /^\s*REQUIRED=.*\S/.test(с));
    must(
      строкиREQUIRED.every((с) => !с.includes(имя)),
      `${имя} снова вписан в список обязательных: в compose у него значение ` +
        'по умолчанию, и проверка объявляет рабочую конфигурацию неполной',
    );
  }
});

  it('compose различает обязательное и необязательное, и это правда', () => {
    const обязательные = [...COMPOSE.matchAll(/\$\{([A-Z_][A-Z0-9_]*):?/g)].map((м) => м[1]);
    const сЗначениемПоУмолчанию = [...COMPOSE.matchAll(/\$\{[A-Z_][A-Z0-9_]*:-/g)].map((м) =>
      м[0].slice(2),
    );
    for (const имя of ['DOMAIN', 'POSTGRES_PASSWORD', 'JWT_SECRET']) {
      must(
        обязательные.includes(имя),
        `в compose нет обязательного ${имя}: без него контейнер не стартует`,
      );
    }
    for (const имя of ['DB_NAME', 'DB_USER', 'CLIENT_ORIGIN']) {
      const естьУмолчание = COMPOSE.includes(`${имя}:-`) || COMPOSE.includes(`${имя}: `);
      must(
        !сЗначениемПоУмолчанию.includes(`${имя}:`) || естьУмолчание,
        `${имя} разбирается неоднозначно — проверь, что он помечен как необязательный`,
      );
    }
  });
});

