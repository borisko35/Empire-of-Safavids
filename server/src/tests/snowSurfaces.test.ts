// Снег на зелени и крышах.
//
// ЧТО БЫЛО (21 октября 2026, §263). Земля белела (§262), а кусты, пальмы и
// черепица оставались летними: дерево в снегу с зелёной кроной выглядит
// нелепо, и снегопад читался как декорация половины мира.
//
// ЧТО ТЕПЕРЬ. Снег ложится и на зелень, и на кровли, и на купола, и на
// городскую площадь с дорогами.
//
// ГЛАВНАЯ ТОНКОСТЬ. Снег — это КАРТА, а не только цвет материала. Зелёная
// текстура листвы, помноженная на белый цвет, остаётся зелёной: цвет её
// только осветляет. Поэтому под снегом материал берёт снежную карту, а
// плавность белизны даёт цвет — он идёт от своего к белому. Своя карта
// возвращается, когда снег сходит.
//
// ЧТО ПРОВЕРЯЕТСЯ. Снег кладут и на зелень, и на кровли, и на площадь с
// дорогами; карта под снегом меняется на снежную и возвращается обратно; и
// цвет белится плавно, от своего к белому.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Снег на зелени и крышах', () => {
  it('снег кладут на зелень, кровли, площадь и дороги', () => {
    должен(/export function setSnowOnSurfaces\(snow: number\)/.test(ТЕРРЕЙН), 'нет функции снега на поверхностях');
    // Зелень.
    должен(
      /MAT\.foliage, MAT\.foliageDark, MAT\.foliageLight, MAT\.brush,/.test(ТЕРРЕЙН),
      'снег не кладётся на зелень',
    );
    // Кровли и купола.
    должен(
      /MAT\.clothRed, MAT\.clothTeal, MAT\.clothPurple,/.test(ТЕРРЕЙН),
      'снег не кладётся на ткань и купола',
    );
    // Камень.
    должен(/MAT\.tealDome, MAT\.sandstone, MAT\.sandstoneDark, MAT\.stone,/.test(ТЕРРЕЙН),
      'снег не кладётся на камень');
    // Площадь города.
    должен(
      /СНЕЖНЫЕ_МАТЕРИАЛЫ\.push\(материалПлощади\);/.test(ТЕРРЕЙН),
      'городская площадь не покрывается снегом',
    );
    // Дороги.
    должен(
      /for \(const материал of \[roadMat, stoneRoadMat\]\)/.test(ТЕРРЕЙН),
      'дороги не покрываются снегом',
    );
  });

  it('под снегом карта снежная, а своя возвращается', () => {
    // Зелёная текстура, помноженная на белый цвет, остаётся зелёной.
    должен(
      /const карта = с > 0\.02 \? \(MAT\.snow\.map \?\? своя\) : своя;/.test(ТЕРРЕЙН),
      'под снегом не меняется карта: зелень останется зелёной',
    );
    // Смена карты пересобирает шейдер — это должно случиться редко.
    должен(/материал\.needsUpdate = true;/.test(ТЕРРЕЙН), 'смена карты без пересборки шейдера');
    // Исходная карта сохранена: без неё после таяния всё останется снежным.
    должен(
      /ИСХОДНЫЕ_КАРТЫ\.set\(материал, материал\.map \?\? null\);/.test(ТЕРРЕЙН),
      'исходная карта материала не сохранена',
    );
  });

  it('цвет белится плавно, от своего к белому', () => {
    должен(
      /материал\.color\.copy\(база\)\.lerp\(ЦВЕТ_СНЕГА, доля\);/.test(ТЕРРЕЙН),
      'цвет материала не белеет',
    );
    // Зелень белеет слабее: снег на иголках виден, но иголки видны.
    должен(/доля = зелень \? с \* 0\.55 : с \* 0\.8;/.test(ТЕРРЕЙН),
      'зелень и камень белеют одинаково: хвоя пропала бы совсем',
    );
  });

  it('движок зовёт снег на поверхностях', () => {
    должен(/setSnowOnSurfaces\(this\.снег\);/.test(МИР), 'снег на поверхностях не ставится');
  });
});
