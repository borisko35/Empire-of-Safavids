// Мечи у кузницы деревни.
//
// Двадцать первый пакет из Assets.
//
// ЧТО ЛОВИТСЯ И ПОЧЕМУ ТАК.
// 1. Файл в сборке и совпадает с манифестом.
// 2. Модель в метрах. Исходник приехал 4.66 м — это не меч, а осадная балка.
//    Верхняя граница 1.3 м ловит именно это.
// 3. Рост ручного меча: 0.8-1.15 м. Ниже — кинжал, выше — двуручник.
// 4. Ширина 0.12-0.20 м: это гарда, а не поперечный брус. Слишком широко —
//    меч проходит как бревно, слишком узко — как палка.
// 5. Основанием на ноль, а не висячий и не ушедший под землю.
// 6. ГАРДА ШИРЕ КЛИНКА В ДВА И БОЛЕЕ РАЗ. Это признак того, что перед нами
//    меч, а не клюка: у меча поперечник в 2-4 раза шире лезвия. Проверка на
//    одну лишь высоту пропустила бы и заострённый брус.
// 7. ДВА МАТЕРИАЛА. В исходнике материал один. Одним цветом гарда, лезвие и
//    рукоять сливаются в серую полосу, и меч перестаёт читаться.
// 8. Материалы разные по цвету: сталь и дерево не одного цвета.
// 9. ОСТРИЁ ВНИЗ: самая широкая часть не на самом верху. Стоящий остриём вверх
//    меч читается как антенна. Верх меча узкий — это рукоять.
// 10. Без скелета и анимации.
// 11. В узлах нет поворота, масштаба и сдвига.
// 12. Лёгкий: 1028 полигонов должны сжиматься.
//
// Место:
// 13. Мир строит мечи.
// 14. Ровно два, и они не слиплись: точки разнесены минимум на 2 м.
// 15. Оба вне коллайдера кузницы — меч в стене кузницы читается как часть стены.
// 16. Утоплены: основание ниже земли, а не стоит на остриё.
// 17. На суше и не в воде.
