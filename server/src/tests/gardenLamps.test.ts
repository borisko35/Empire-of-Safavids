// Фонари у пруда в садах.
//
// ЧТО БЫЛО (21 октября 2026, §249). На весь квартал садов был один фонарь
// у дороги, а пруд, кувшинки и кольцо кипарисов стояли в темноте: сад читался
// как выключенный.
//
// ЧТО БЫЛО ЕЩЁ (та же правка, поймано ночным кадром). Первый вариант сделал
// фонари сада своими: столб, чаша и маленький шар огня. В кадре ночью это
// читалось как ТЁМНЫЙ ШЕСТ — у городского фонаря есть стеклянный фонарь с
// огнём и колпак, а у самодельного их не было, и огня не видно.
//
// ЧТО ТЕПЕРЬ. Фонари сада — те же, что и в городе, общим помощником.
//
// ЧТО ПРОВЕРЯЕТСЯ. Фонарей у пруда три, и каждый построен общим фонарём
// (свои столбы с чашей без стекла вернутся) и даёт свой источник света по
// высоте огня. Проверка смотрит ТОЛЬКО свой раздел кода: строки фонарей в
// городе совпадают слово в слово, и без границы проверка цепляла бы чужой
// блок (см. §247).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

/** Кусок кода своего раздела: метки разделов — комментарии, ищем по исходнику. */
function свойРаздел(начало: string, конец: string): string {
  const от = ТЕРРЕЙН.indexOf(начало);
  должен(от >= 0, `в коде нет раздела «${начало}»`);
  const до = ТЕРРЕЙН.indexOf(конец, от);
  должен(до > от, `в коде нет раздела «${конец}» после «${начало}»`);
  return ТЕРРЕЙН.slice(от, до).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const САДЫ = свойРаздел('// Сады: кипарисы, пруд, скамейки', '// Пруд в садах (§242)');

describe('Фонари у пруда в садах', () => {
  it('у пруда три фонаря', () => {
    должен(
      /for \(const \[lx, lz\] of \[\[-38\.5, 77\.9\], \[-24\.5, 77\.9\], \[-31\.5, 86\.5\]\] as const\)/.test(САДЫ),
      'фонарей у пруда не три',
    );
  });

  it('фонари садов — те же, что и в городе, со стеклом и огнём', () => {
    должен(
      /const высотаОгня = фонарь\(city, lx, lz\);/.test(САДЫ),
      'фонари садов построены своими столбами: ночью это тёмный шест, огня не видно',
    );
    // Своих столбов в разделе быть не должно.
    должен(
      !/new THREE\.CylinderGeometry\(0\.12, 0\.16, 3\.4/.test(САДЫ),
      'в садах снова свой столб фонаря без стекла',
    );
  });

  it('фонари садов дают свет по высоте огня', () => {
    должен(
      /lights\.push\(\{ x: CITY\.x \+ lx, z: CITY\.z \+ lz, y: city\.position\.y \+ высотаОгня \}\)/.test(
        САДЫ,
      ),
      'фонари садов не получают источников света',
    );
  });
});
