// Рябь от дождя в лужах.
//
// ЧТО БЫЛО (22 октября 2026, §285). Лужи на площади и в пригороде (§264,
// §269) стояли гладкими зеркалами: вода в луже никогда не двигалась. Дождь
// шёл, капли падали, земля темнела — а вода в луже оставалась мёртвой. По
// стоячей воде читается, что дождя нет.
//
// ЧТО ТЕПЕРЬ. В луже идут круги от капель: круг расходится, слабеет и гаснет.
// Кругов много, и они идут непрерывно, пока идёт дождь, — вода живая.
// Под дождём поверхность лужи перестаёт быть зеркалом.
//
// ЧТО ПРОВЕРЯЕТСЯ. Круги появляются в лужах и только в дождь, расходятся и
// гаснут; кольца берутся из пула, а не создаются на каждую каплю; случайных
// чисел в модуле нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РЯБЬ = читать('client/src/app/game3d/puddleRipples.ts');
const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Рябь от дождя в лужах', () => {
  it('круги от капель идут в лужах и только в дождь', () => {
    // Круги берутся из луж города — по мировым координатам.
    должен(/import \{ лужиГорода \} from '\.\/terrain';/.test(РЯБЬ), 'рябь не знает, где лужи');
    // Пока дождь не идёт или земля сухая, кругов нет.
    должен(
      /const идёт = rain > 0\.05 && wet > 0\.35 && лужиГорода\.length > 0;/.test(РЯБЬ),
      'круги идут и без дождя',
    );
    // Круг появляется в точке лужи, а не в воздухе над городом.
    должен(
      /к\.меш\.position\.set\(\s*лужа\.x \+ Math\.cos\(угол\) \* r,\s*лужа\.y \+ 0\.012,\s*лужа\.z \+ Math\.sin\(угол\) \* r,/.test(РЯБЬ),
      'круг появляется не в луже',
    );
  });

  it('круг расходится и гаснет', () => {
    // Радиус растёт со временем жизни круга.
    должен(
      /const размер = 0\.12 \+ доля \* РОСТ;/.test(РЯБЬ),
      'круг не расходится: он либо есть, либо нет',
    );
    // И исчезает, когда жизнь кончилась.
    должен(
      /к\.осталось <= 0\) \{ к\.меш\.visible = false; continue; \}/.test(РЯБЬ),
      'круг не гаснет: круги копятся в сцене',
    );
  });

  it('кольца берутся из пула, а не создаются на каждую каплю', () => {
    должен(/const КОЛЕЦ = \d+;/.test(РЯБЬ), 'нет пула колец');
    // Кольцо ищется свободное, а не создаётся новое.
    должен(
      /const к = кольца\.find\(\(x\) => x\.осталось <= 0\);/.test(РЯБЬ),
      'на каждую каплю создаётся новое кольцо: сцена засоряется',
    );
    // И при вычистке пул убирается из сцены.
    должен(/for \(const к of кольца\) scene\.remove\(к\.меш\);/.test(РЯБЬ), 'кольца не убираются из сцены');
  });

  it('под дождём поверхность лужи перестаёт быть зеркалом', () => {
    // Гладкая вода ловит небо; взбалтывачная — рассеивает свет.
    должен(
      /л\.материал\.roughness = 0\.06 \+ 0\.2 \* дождь \* доля;/.test(ТЕРРЕЙН),
      'поверхность лужи в дождь остаётся зеркалом',
    );
    // Движок отдаёт лужам и мокроту, и дождь.
    должен(/setPuddles\(this\.мокрота, дождь\);/.test(МИР), 'движок не отдаёт лужам дождь');
    // И круги в лужах идут по тому же дождю.
    должен(
      /this\.рябьЛуж\.update\(dt, дождь, this\.мокрота, me\.pos\.x, me\.pos\.z\);/.test(МИР),
      'рябь в лужах не обновляется',
    );
    должен(/createPuddleRipples\(this\.scene\);/.test(МИР), 'движок не создаёт рябь в лужах');
  });

  it('в модуле нет случайных чисел', () => {
    // Круги должны падать одни и те же при каждом запуске мира.
    должен(!/Math\.random\(\)/.test(РЯБЬ), 'в ряби есть случайность: мир собирается по-разному');
    должен(/function hashЛужи\(a: number, b: number\): number/.test(РЯБЬ), 'нет псевдослучайного генератора');
  });
});
