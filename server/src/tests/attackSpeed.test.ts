// Скорость удара: оружие и стойка перестали быть мёртвыми данными.
//
// ЧТО БЫЛО. У каждого оружия в данных есть speed — от 0.36 у самого быстрого до
// 0.8 у самого тяжёлого, 0.45 у пустых рук. У каждой стойки есть attackSpeed:
// 0.8 у «Шахского щита», 1.3 у «Серповой пляски». Ни то, ни другое не
// участвовало в бою: откат был жёстким 380 мс на сервере и вбитым 0.45 на
// клиенте. Любое оружие било одинаково, а стойка с обещанными +30 % скорости
// не давала ничего.
//
// ПОЧЕМУ ПРОВЕРКА СЧИТАЕТ ЧИСЛА. Проверка не сверяет текст, а считает откат из
// настоящих данных: берёт самое быстрое и самое тяжёлое оружие, стойки с
// крайними множителями и требует, чтобы откаты различались и оставались внутри
// разумных пределов. Если кто-то снова сделает скорость мёртвой, числа сойдутся
// и проверка упадёт.
//
// ПОЧЕМУ КЛИЕНТ И СЕРВЕР ДОЛЖНЫ СЧИТАТЬ ОДИНАКОВО. Откат на сервере авторитетен:
// клиент, который держит свою цифру, либо ограничивает игрока (быстрое оружие
// не быстрее), либо спамит отказом «слишком быстро» на законный темп. Поэтому
// проверка требует, чтобы стойки на клиенте совпадали с серверными числами
// буквально, а не «примерно».
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { STANCES as СТОЙКИ } from '../systems/CombatStance';
import { DEFAULT_WEAPON } from '../services/EquipmentCache';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const БОЙ = читать('server/src/socket/GameSocketHandler.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
const КЛИЕНТ_СТОЙКИ = читать('client/src/app/stance.ts');
const ПРЕДМЕТЫ = читать('server/src/data/items.ts');

/** Все оружия из данных: их время замаха в секундах. */
const ЗАМАХИ_ОРУЖИЯ = [...ПРЕДМЕТЫ.matchAll(/weapon: \{ damage: ([\d.]+), speed: ([\d.]+), range: ([\d.]+) \}/g)].map(
  (m) => ({ damage: Number(m[1]), speed: Number(m[2]), range: Number(m[3]) })
);

/** Множители времени замаха по стойкам — из настоящей таблицы. */
const МНОЖИТЕЛИ_СТОЕК = Object.values(СТОЙКИ).map((с) => с.attackSpeed);

/** Откат в секундах — ровно так, как считает сервер. */
function откат(замахОружия: number, множительСтойки: number, замедление = 1): number {
  const порог = Number(/const MIN_ATTACK_INTERVAL_MS = (\d+)/.exec(БОЙ)![1]);
  return Math.max(порог, (замахОружия * 1000) / множительСтойки) / 1000 / замедление;
}

describe('Скорость удара: оружие', () => {
  it('в данных есть оружие, и времена замаха в нём разные', () => {
    must(ЗАМАХИ_ОРУЖИЯ.length >= 5, `в данных всего ${ЗАМАХИ_ОРУЖИЯ.length} оружий: слишком мало, чтобы судить о скорости`);
    const времена = new Set(ЗАМАХИ_ОРУЖИЯ.map((о) => о.speed));
    must(
      времена.size >= 3,
      `у оружий всего ${времена.size} различных времени замаха: если оно одно у всех, поле speed мёртвое и правка снова отвалится`
    );
  });

  it('пустые руки бьют с тем же темпом, который стоит в данных', () => {
    const порог = Number(/const MIN_ATTACK_INTERVAL_MS = (\d+)/.exec(БОЙ)![1]);
    const замах = откат(DEFAULT_WEAPON.speed, 1);
    must(
      замах * 1000 >= порог,
      `пустые руки дают откат ${(замах * 1000).toFixed(0)} мс, а страховка ${порог} мс: ` +
        'поломанный предмет с speed меньше порога должен срезаться, но не наоборот'
    );
  });

  it('самое быстрое оружие действительно быстрее самого тяжёлого', () => {
    const быстрое = Math.min(...ЗАМАХИ_ОРУЖИЯ.map((о) => о.speed));
    const тяжёлое = Math.max(...ЗАМАХИ_ОРУЖИЯ.map((о) => о.speed));
    must(
      откат(быстрое, 1) < откат(тяжёлое, 1),
      `быстрое оружие даёт откат ${откат(быстрое, 1)}, тяжёлое ${откат(тяжёлое, 1)}: ` +
        'выбор оружия перестал влиять на темп боя'
    );
  });

  it('откат остаётся в пределах, в которых бой остаётся возможным', () => {
    for (const оружие of ЗАМАХИ_ОРУЖИЯ) {
      for (const множитель of МНОЖИТЕЛИ_СТОЕК) {
        const замах = откат(оружие.speed, множитель);
        must(
          замах >= 0.25 && замах <= 1.2,
          `оружие со скоростью ${оружие.speed} в стойке с множителем ${множитель} даёт ` +
            `откат ${(замах * 1000).toFixed(0)} мс: либо бой невозможен, либо удары слишком редки`
        );
      }
    }
  });
});

describe('Скорость удара: стойка', () => {
  it('стойка меняет темп удара', () => {
    const щит = откат(DEFAULT_WEAPON.speed, СТОЙКИ.shah_shield.attackSpeed);
    const пляска = откат(DEFAULT_WEAPON.speed, СТОЙКИ.sickle_dance.attackSpeed);
    must(
      щит > пляска,
      `«Шахский щит» даёт ${(щит * 1000).toFixed(0)} мс, «Серповая пляска» ${(пляска * 1000).toFixed(0)} мс: ` +
        'стойка с обещанной скоростью ни на что не влияет'
    );
  });

  it('числа стоек на клиенте совпадают с серверными', () => {
    // Расхождение в одну сотую даст постоянные отказы «слишком быстро»: сервер
    // ждёт дольше, чем клиент успевает отправить.
    //
    // Сравниваются ЧИСЛА, а не текст строки: сервер хранит 1, а клиент написан
    // как 1.0, и сверка шаблоном руками ломалась бы на ровно этом.
    for (const [id, стойка] of Object.entries(СТОЙКИ)) {
      const найдено = new RegExp(`${id}: \\{[^}]*attackSpeed: ([\\d.]+)`).exec(КЛИЕНТ_СТОЙКИ);
      must(
        найдено !== null,
        `в клиентских стойках нет записи ${id}: клиент возьмёт множитель undefined, ` +
          'и замах посчитается по стойке, которой нет'
      );
      const число = Number(найдено![1]);
      must(
        Math.abs(число - стойка.attackSpeed) < 1e-9,
        `в клиентских стойках у ${id} множитель ${число}, а на сервере ${стойка.attackSpeed}: ` +
          'клиент и сервер считают разный откат, и игрок получит отказ «слишком быстро» ' +
          'на собственном нормальном темпе'
      );
    }
  });
});

describe('Скорость удара: как это считается в коде', () => {
  it('сервер берёт откат из оружия и стойки, а не из константы', () => {
    must(
      /const замах = \(\(weapon\?\.speed \?\? DEFAULT_WEAPON\.speed\) \* 1000\) \/ stance\.attackSpeed;/.test(БОЙ),
      'откат на сервере снова считается из константы: скорость оружия и стойки мертвы'
    );
    must(
      !/\* stance\.attackSpeed/.test(БОЙ),
      'время замаха умножается на attackSpeed, а надо делить: это множитель СКОРОСТИ, ' +
        'и от умножения «Серповая пляска» стала бы самой медленной стойкой'
    );
    must(
      !/MIN_ATTACK_INTERVAL_MS \/ Math\.max\(0\.2, Math\.min\(1, скорость\)\)/.test(БОЙ),
      'старое деление на константу осталось: откат снова одинаков для всего оружия'
    );
  });

  it('проверка отката стоит там, где известны оружие и стойка', () => {
    const оружие = БОЙ.indexOf('const weapon = await this.equipment.getWeapon');
    const стойка = БОЙ.indexOf('const stance = STANCES[stanceId]');
    const откатСтрок = БОЙ.indexOf("code: 'attack_too_fast'");
    must(оружие > 0 && стойка > 0 && откатСтрок > 0, 'не нашёл ни оружие, ни стойку, ни проверку отката');
    must(
      откатСтрок > оружие && откатСтрок > стойка,
      'проверка отката стоит раньше, чем прочитаны оружие и стойка: считать не из чего'
    );
  });

  it('клиентский замах идёт по данным, а не по вбитому числу', () => {
    must(
      /this\.attackCd = this\.swingSeconds\(\);/.test(МИР),
      'замах в 3D снова вбит константой: смена оружия ничего не меняет'
    );
    must(
      !/this\.attackCd = 0\.45;/.test(МИР),
      'вбитый замах 0.45 остался в замахе'
    );
    must(
      /const оружие = this\.localGear\?\.swingSeconds \?\? ЗАМАХ_ПУСТЫМИ_РУКАМИ;/.test(МИР),
      'время замаха не берётся из данных оружия'
    );
    must(
      /STANCES\[getStance\(\)\]\.attackSpeed/.test(МИР),
      'множитель стойки не применяется к замаху'
    );
  });

  it('время замаха доезжает до клиента из данных предмета', () => {
    must(
      /swingSeconds: def\?\.weapon\?\.speed,/.test(читать('server/src/services/CharacterService.ts')),
      'сервер не отправляет время замаха в экипировке: клиент не знает темп своего оружия'
    );
    must(
      /swingSeconds: equipped\.get\('weapon'\)\?\.swingSeconds \?\? null,/.test(читать('client/src/app/hud.ts')),
      'панель не передаёт время замаха в 3D-слой'
    );
  });
});