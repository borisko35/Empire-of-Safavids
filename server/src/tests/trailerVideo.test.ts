// Собранный ролик лежит на сайте, и страница на него ссылается.
//
// ЗАЧЕМ ФАЙЛ. Черновик публикации прямо запрещал постить ссылку на трейлер,
// пока ролик не собран: страница, которую надо смотреть глазами и записывать
// экран, - это не то же самое, что видео, и человек почувствует себя
// обманутым. Ролик собран, значит ограничение снято, и страница должна на
// него ссылаться.
//
// ССЫЛКА АБСОЛЮТНАЯ, и это не опечатка. Связка для itch.io собирается из
// одного файла трейлера и шести кадров; ролика на 2.9 МБ в ней нет и быть
// не должно - он лежит на нашем домене. Ссылка вида assets/trailer.mp4 на
// площадке дала бы 404, а это ровно то, из-за чего страница уже показывала
// пустые сцены.
//
// ЧТО ПРОВЕРЯЕТСЯ. Файл есть и он не пустой; на странице ссылка в трёх
// языках с переключением; ссылка ведёт на существующий файл, а не в
// никуда. Текст ролика глазами не проверен - об этом сказано в самом
// сборщике, и здесь он тоже не смотрится.
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const ролик = join(корень, 'client/web/assets/trailer.mp4');
const трейлер = readFileSync(join(корень, 'client/web/trailer.html'), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Ролик трейлера лежит на сайте', () => {
  it('файл есть и он не пустой', () => {
    must(existsSync(ролик), 'нет client/web/assets/trailer.mp4 - ролик не положен на сайт');
    const вес = statSync(ролик).size;
    // Полмигабайта - это кадр, а не ролик. Порог взят с запасом: ролик
    // весит около трёх мегабайт, и вдвое меньше - уже обрывок.
    expect({ вес_байт: вес }).toEqual({ вес_байт: expect.any(Number) });
    expect({ больше_полутора_мегабайт: вес > 1_500_000 }).toEqual({ больше_полутора_мегабайт: true });
  });

  it('это действительно mp4, а не переименованная картинка', () => {
    // Расширение .mp4 ничего не значит. Сигнатура ftyp стоит в первых
    // двенадцати байтах, и без неё браузер покажет пустое место.
    const начало = readFileSync(ролик).subarray(0, 12).toString('latin1');
    expect({ сигнатура: начало.slice(4, 8) }).toEqual({ сигнатура: 'ftyp' });
  });

  it('страница ссылается на ролик в трёх языках и переключает их', () => {
    // Как и строка про лицензию. На азербайджанском игрок иначе просто не
    // увидит, что видео существует.
    const языки = [...трейлер.matchAll(/data-vid="(\w+)"/g)].map(m => m[1]);
    expect({
      языки: языки,
      переключение: /s\.dataset\.vid === lang/.test(трейлер),
      стартовое: /s\.dataset\.vid === 'ru'/.test(трейлер),
    }).toEqual({ языки: ['ru', 'en', 'az'], переключение: true, стартовое: true });
  });

  it('ссылка абсолютная и ведёт на существующий файл', () => {
    // ГЛАВНАЯ ПРОВЕРКА. Ссылка вида assets/trailer.mp4 работала бы на нашем
    // домене случайно - страница лежит в корне - и сломалась бы на itch.io,
    // где в корне чужое. Ровно так уже было с кадрами.
    const ссылки = [...трейлер.matchAll(/<a href="([^"]*trailer\.mp4)"/g)].map(m => m[1]);
    must(ссылки.length > 0, 'на странице нет ссылки на ролик');
    const всеАбсолютные = ссылки.every(h => /^https:\/\//.test(h));
    const совпадают = ссылки.every(h => h === ссылки[0]);
    // И адрес из ссылки реально отдаёт файл: локально он ищется от корня
    // client/web, то есть там же, откуда nginx его отдаёт.
    const путь = new URL(ссылки[0]).pathname.replace(/^\//, '');
    const локально = join(корень, 'client/web', путь);
    expect({
      ссылки_штук: ссылки.length,
      все_абсолютные: всеАбсолютные,
      адрес_один: совпадают,
      файл_по_адресу_есть: existsSync(локально),
    }).toEqual({ ссылки_штук: 3, все_абсолютные: true, адрес_один: true, файл_по_адресу_есть: true });
  });
});
