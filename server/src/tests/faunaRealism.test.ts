// Звери и птицы перестают быть примитивами.
//
// ЧТО БЫЛО (22 октября 2026, §286). Зверь был картонной коробкой на палочках:
// тело — ящик 0.9×0.5×0.45, голова — куб, ноги — тонкие бруски, уши и рога —
// конусы. На кадре горный козёл выглядел именно так. Птица — конус с
// треугольными крыльями и material без освещения (светилась сама, даже в
// сумерках).
//
// ЧТО ТЕПЕРЬ. Тело — капсула (грудь, спина, сужение к шее), шея, голова,
// морда, глаза, уши, рога-дуги, хвост; нога из двух сужающихся звеньев с
// копытом и коленом, и качается она от бедра. Птица: капсула, голова, клюв,
// хвост, изогнутое крыло, освещаемый материал.
//
// ЧТО ПРОВЕРЯЕТСЯ. В фауне нет ящиков вместо тел; у зверя есть части тела;
// нога качается от бедра; рога — дуги; птица освещается; материалы не
// плодятся на каждую часть тела.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ФАУНА = читать('client/src/app/game3d/fauna.ts');

describe('Звери и птицы — не примитивы', () => {
  it('тело зверя — не ящик', () => {
    // Капсула вместо ящика: у зверя есть грудь и круп.
    должен(
      /new THREE\.CapsuleGeometry\(opts\?\.fluffy \? [\d.]+ : [\d.]+, opts\?\.fluffy \? [\d.]+ : [\d.]+, 4, 12\)/.test(ФАУНА),
      'тело зверя — не капсула: зверь читается как коробка',
    );
    // Ящика в теле быть не должно.
    должен(
      !/new THREE\.BoxGeometry\(0\.9, 0\.5, 0\.45\)/.test(ФАУНА),
      'тело зверя снова ящик',
    );
  });

  it('у зверя есть голова, морда, глаза, уши и копыта', () => {
    // Шея и голова — капсулы.
    должен(/const neck = new THREE\.Mesh\(new THREE\.CapsuleGeometry/.test(ФАУНА), 'у зверя нет шеи');
    должен(/const head = new THREE\.Mesh\(new THREE\.CapsuleGeometry/.test(ФАУНА), 'у зверя нет круглой головы');
    // Морда — сужающийся цилиндр, а не куб.
    должен(
      /const морда = new THREE\.Mesh\(new THREE\.CylinderGeometry\([\d.]+, [\d.]+, [\d.]+, 8\)/.test(ФАУНА),
      'у зверя нет морды',
    );
    // Глаза.
    должен(/const глаз = new THREE\.Mesh\(new THREE\.SphereGeometry/.test(ФАУНА), 'у зверя нет глаз');
    // Копыто.
    должен(/const копыто = new THREE\.Mesh\(копытоГео/.test(ФАУНА), 'у зверя нет копыт');
  });

  it('нога качается от бедра, а не от середины', () => {
    // Нога — группа в бедре, а звенья — её дети. Иначе нога качается из
    // середины и зверь ходит, будто его колени на нитках.
    должен(
      /const нога = new THREE\.Group\(\);\s*нога\.position\.set\(lx, legH, lz\);/.test(ФАУНА),
      'нога не стоит в бедре',
    );
    должен(/колено\.add\(голень, копыто\);/.test(ФАУНА), 'голень и копыто не в колене');
    // И нога качается целиком — через группу.
    должен(/legs\.push\(нога\);/.test(ФАУНА), 'в список ног попадает не группа');
  });

  it('рога — изогнутые дуги, а не конусы', () => {
    должен(
      /const рог = new THREE\.Mesh\(new THREE\.TorusGeometry\(/.test(ФАУНА),
      'рога снова конусы',
    );
    // Дуга лежит в плоскости головы: тор, повёрнутый плашмя, читался как
    // тёмный блинок на черепе.
    должен(/рог\.rotation\.set\(0, 0, -[\d.]+\);/.test(ФАУНА), 'рог повёрнут не в плоскости головы');
  });

  it('птица — капсула с головой, клювом и хвостом, и она освещается', () => {
    // Тело птицы — капсула.
    должен(
      /const body = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.075, 0\.26, 3, 8\)/.test(ФАУНА),
      'тело птицы — не капсула',
    );
    // Голова, клюв, хвост.
    должен(/const head = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.062/.test(ФАУНА), 'у птицы нет головы');
    должен(/const beak = new THREE\.Mesh\(/.test(ФАУНА), 'у птицы нет клюва');
    должен(/const tail = new THREE\.Mesh\(tailGeo/.test(ФАУНА), 'у птицы нет хвоста');
    // Материал птицы освещаемый: без света птица светилась сама.
    должен(
      /const wingMat = new THREE\.MeshStandardMaterial\(/.test(ФАУНА),
      'птица светится сама: материал без освещения',
    );
    // И крыло — изогнутая пластина из четырёх вершин, а не треугольник.
    должен(/wingGeo\.setIndex\(\[0, 1, 2, 0, 2, 3\]\);/.test(ФАУНА), 'крыло — треугольник');
  });

  it('материалы зверей не плодятся на каждую часть тела', () => {
    // Материал на каждую часть — это десятки материалов на зверя.
    должен(/const МАТЕРИАЛЫ = new Map<string, THREE\.MeshStandardMaterial>\(\);/.test(ФАУНА),
      'нет кэша материалов: на зверя десятки материалов');
    должен(
      /let м = МАТЕРИАЛЫ\.get\(ключ\);/.test(ФАУНА) && /МАТЕРИАЛЫ\.set\(ключ, м\);/.test(ФАУНА),
      'материалы не кэшируются',
    );
  });
});
