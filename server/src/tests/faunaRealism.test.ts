// Звери и птицы — настоящие модели.
//
// ЧТО БЫЛО (§286). Четвероногий собирался из капсул и конусов (тело, шея,
// голова, морда, рога-торусы, двухзвенные ноги), птица — из капсулы и
// треугольных крыльев, рыба — из сплюснутой капсулы.
//
// ЧТО ТЕПЕРЬ (§326). Каждый вид — готовый GLB (animalModels.ts): ригованные
// звери играют свои клипы Walk/Gallop/Idle, статичные живут позой. Процедурные
// сборщики makeQuadruped/makeBird/makeFish удалены.
//
// ЧТО ПРОВЕРЯЕТСЯ. Виды лежат в манифесте; таблица видов знает клипы;
// сборка нормализует масштаб и поворот; фауна спавнит зверей по биомам и
// тикает миксеры; процедурных сборщиков больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
  animals?: { file: string; name: string; bytes: number }[];
};
const вМанифесте = (раздел: 'decor' | 'animals', имя: string): boolean =>
  (МАНИФЕСТ[раздел] ?? []).some((д) => д.name === имя);

const ФАУНА = читать('client/src/app/game3d/fauna.ts');
const МОДЕЛИ = читать('client/src/app/game3d/animalModels.ts');

describe('Звери — настоящие модели', () => {
  it('виды фауны лежат в сборке', () => {
    for (const имя of ['camel', 'goat', 'lizard', 'seagull', 'heron', 'stork', 'duck']) {
      должен(вМанифесте('animals', имя), `${имя}.glb нет в манифесте`);
    }
    for (const имя of ['stag', 'fox', 'sheep', 'bunny', 'fish-a', 'piranha', 'koi', 'tuna']) {
      должен(вМанифесте('animals', имя), `${имя}.glb нет в манифесте`);
    }
  });

  it('ригам обещаны клипы: ходьба, бег, покой, плавание', () => {
    должен(/клипы: \{ walk: 'Walk', run: 'Gallop', idle: 'Idle' \}/.test(МОДЕЛИ),
      'у ригованных зверей не обещаны клипы');
    должен(/клипы: \{ swim: 'Swim' \}/.test(МОДЕЛИ), 'у рыбы не обещан клип плавания');
    // Таблица видов полна: в файле 28 видов.
    const видов = (МОДЕЛИ.match(/файл: 'animals\//g) || []).length;
    должен(видов >= 28, `в таблице видов ${видов} — меньше, чем файлов в сборке`);
  });

  it('сборка нормализует масштаб, посадку и поворот', () => {
    // Измерение Box3 и нормализация под заданную длину.
    должен(/new THREE\.Box3\(\)\.setFromObject\(модель\)/.test(МОДЕЛИ), 'модель не измеряется');
    должен(/const k = длина \/ горизонт;/.test(МОДЕЛИ), 'масштаб не нормализуется');
    // Посадка на землю: низ bbox — в y = 0.
    должен(/внешняя\.position\.y = -boxПосле\.min\.y;/.test(МОДЕЛИ), 'зверь не посажен на землю');
    // Поправка курса: у вида есть yaw.
    должен(/внутренняя\.rotation\.y = спека\.yaw;/.test(МОДЕЛИ), 'поправка курса не применяется');
  });

  it('фауна спавнит зверей по биомам и тикает миксеры', () => {
    // Спавн через собратьЗверя, а не сборку из капсул.
    должен((ФАУНА.match(/заспавнить\('/g) || []).length >= 7, 'фауна спавнит слишком мало видов');
    // Переключение клипов на каждом кадре.
    должен(/вестиЗверя\(w\.зверь, !стоит, dt\);/.test(ФАУНА), 'миксеры зверей не тикают');
    должен(/вестиЗверя\(f\.зверь, true, dt\);/.test(ФАУНА), 'рыбы не плавают клипом');
    // Процедурных сборщиков больше нет.
    должен(!/makeQuadruped/.test(ФАУНА), 'makeQuadruped вернулся');
    должен(!/makeBird/.test(ФАУНА), 'makeBird вернулся');
    должен(!/makeFish/.test(ФАУНА), 'makeFish вернулся');
  });

  it('движок тикает зверей вне фауны', () => {
    const МИР = читать('client/src/app/game3d/world3d.ts');
    должен(/тикатьЗверей\(dt\)/.test(МИР), 'миксеры зверей вне фауны никто не тикает');
  });
});
