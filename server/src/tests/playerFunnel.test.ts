// Воронка новичка и удержание D1/D7/D30.
//
// ГЛАВНОЕ В ЭТОМ ТЕСТЕ — ОТРИЦАНИЕ ВРЕМЕНИ. Молодая когорта не
// «удерживается на нуле», она ещё не дожила до дня N. Если вернуть 0% для
// когорты вчерашнего дня, владелец увидит «никто не возвращается на 7-й
// день» и сделает вывод об игре, а не об измерении. Поэтому там, где дня
// ещё не наступило, стоит null, и это проверяется отдельно.
//
// Второе, что проверяется честно: когорты, собранные до появления
// session_start (29 сентября 2026), помечаются как неполные. До этого входа
// в мир не существовало в аналитике, и часть возвратов просто не
// засчитана — показывать их как точные нельзя.
//
// ПЕРВАЯ ВЕРСИЯ ЭТИХ ПРОВЕРОК ОШИБАЛАСЬ В ПЯТИ МЕСТАХ, И ВО ВСЕХ ПРАВ БЫЛ
// КОД. Разбор ошибок оставлен рядом с проверками — он полезнее самих цифр:
//   1. Доля level10 от предыдущего шага: 30 из тех 60, кто дошёл до 5-го, то
//      есть 50%, а не 30% (30% — это доля от первого шага, её считает
//      fromStart). Перепутаны были два разных показателя.
//   2. У вчерашней когорты D1 УЖЕ посчитан: их «первый день» — вчера, а D1
//      это сегодня. Ждал null по всем трём дням.
//   3. У когорты 1 октября D30 = null: 1 октября + 30 дней = 31 октября, а
//      сегодня 20-е. День возврата ещё не наступил, и 5 в таблице это число
//      «из будущего».
//   4. Недозревших когорт три, а не две: у когорты 1 октября тоже не
//      наступил D30.
//   5. Взвешивание по игрокам даёт 33.3%, а не 66.7%: вернулось 100 из 300.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  buildFunnelSteps,
  buildRetention,
  shiftDay,
  isoDay,
  type RetentionRow,
} from '../services/playerFunnel';
import { stripComments } from './helpers/stripCode';

const TODAY = '2026-10-20';
/** С какого дня существует событие session_start */
const SINCE = '2026-09-29';

describe('Дни считаются через границы месяцев и високосный год', () => {
  it('сдвиг на день', () => {
    expect(shiftDay('2026-10-20', 1)).toBe('2026-10-21');
  });

  it('через конец месяца', () => {
    expect(shiftDay('2026-01-31', 1)).toBe('2026-02-01');
  });

  it('через конец года', () => {
    expect(shiftDay('2026-12-31', 1)).toBe('2027-01-01');
  });

  it('в високосном году 29 февраля есть', () => {
    // 2028 — високосный. Если бы сдвиг считал по датам «в лоб», 28 февраля
    // уехало бы в 1 марта, и когорты на границе года считались бы неверно
    expect(shiftDay('2028-02-28', 1)).toBe('2028-02-29');
  });

  it('из даты в UTC получается YYYY-MM-DD', () => {
    expect(isoDay(new Date('2026-10-20T23:59:59Z'))).toBe('2026-10-20');
  });
});

describe('Воронка: доли между соседними шагами', () => {
  const steps = buildFunnelSteps({
    started: 200,
    withCharacter: 100,
    levels: { 5: 60, 10: 30, 20: 5 },
  });

  it('шаги идут в порядке: зашли, персонаж, 5, 10, 20', () => {
    expect(steps.map(s => s.step)).toEqual(['started', 'character', 'level5', 'level10', 'level20']);
  });

  it('у первого шага нет доли от предыдущего', () => {
    // Предыдущего шага нет — доля была бы от пустоты
    expect(steps[0].fromPrevious).toBeNull();
  });

  it('доля от предыдущего шага, а не от первого', () => {
    // Первая версия проверки ждала здесь 30% и была неправа: 30 человек
    // дошли до 10-го уровня из тех 60, кто дошёл до 5-го, — это 50%. 30%
    // — это доля от первого шага (30 из 200), и её показывает fromStart.
    // Разница принципиальна: воронка показывает провал между соседями
    // («из тех, кто завёл персонажа, до 10-го дошла половина»), иначе виден
    // только общий процент от входа.
    expect({
      персонаж: steps[1].fromPrevious,
      десятый: steps[3].fromPrevious,
      десятый_от_начала: steps[3].fromStart,
    }).toEqual({ персонаж: 50, десятый: 50, десятый_от_начала: 15 });
  });

  it('доля от первого шага считается от всех зашедших', () => {
    expect(steps.map(s => s.fromStart)).toEqual([100, 50, 30, 15, 2.5]);
  });

  it('подписи шагов на русском', () => {
    // Отчёт читает владелец, а не программист
    expect(steps.every(s => s.titleRu.trim().length > 0)).toBe(true);
  });

  it('на пустой воронке доли null, а не NaN', () => {
    // Ноль знаменателя — обычное дело для нового сервера. NaN в JSON
    // превращается в null, а деление на ноль даёт Infinity, и владелец
    // увидел бы «бесконечные проценты»
    const empty = buildFunnelSteps({ started: 0, withCharacter: 0, levels: {} });
    expect({
      доли_null: empty.every(s => s.fromPrevious === null && s.fromStart === null),
      нет_NaN: empty.every(s => !Number.isNaN(s.users)),
    }).toEqual({ доли_null: true, нет_NaN: true });
  });

  it('недостижимый уровень не роняет расчёт', () => {
    // Уровень, которого в счётчиках нет (события начались не с первого
    // уровня), должен давать 0, а не исключение
    const sparse = buildFunnelSteps({ started: 10, withCharacter: 5, levels: { 5: 2 } });
    expect(sparse.find(s => s.step === 'level10')?.users).toBe(0);
  });
});

describe('Удержание: не доживший день — это null, а не ноль', () => {
  const rows: RetentionRow[] = [
    { day: '2026-10-01', users: 100, d1: 40, d7: 20, d30: 5 },  // 1 октября + 30 дней = 31-е, не наступило
    { day: '2026-10-14', users: 50, d1: 20, d7: 0, d30: 0 },    // 6 дней: D1 есть, D7 только завтра
    { day: '2026-10-19', users: 20, d1: 5, d7: 0, d30: 0 },     // вчера: D1 это сегодня
  ];
  const rep = buildRetention(rows, TODAY, SINCE);
  const byDay = (d: string) => rep.cohorts.find(c => c.day === d)!;

  it('у вчерашней когорты D1 уже посчитан, а D7 и D30 ещё нет', () => {
    // Первая версия ждала null по всем трём дням и была неправа: у вчерашней
    // когорты «первый день» — вчера, а D1 это сегодня, так что день уже
    // наступил и возвраты посчитаны: 5 из 20 = 25%. Неизвестны только D7 и
    // D30 — они дальше сегодняшнего.
    expect(byDay('2026-10-19')).toMatchObject({ d1: 25, d7: null, d30: null });
  });

  it('у шестидневной когорты D1 посчитан, D7 ещё нет', () => {
    expect(byDay('2026-10-14')).toMatchObject({ d1: 40, d7: null, d30: null });
  });

  it('у когорты 1 октября посчитаны D1 и D7, но не D30', () => {
    // 1 октября плюс 30 дней — это 31 октября, а сегодня 20-е. День
    // возврата ещё не наступил, поэтому 5 вернувшихся в таблице это число
    // «из будущего», и показывать его как 5% нельзя.
    expect(byDay('2026-10-01')).toMatchObject({ d1: 40, d7: 20, d30: null });
  });

  it('когорта, которой ровно 7 дней, уже получила D7', () => {
    // Граница дня: сегодня минус семь — день наступил, значение законное
    const r = buildRetention([{ day: '2026-10-13', users: 10, d1: 5, d7: 2, d30: 0 }], TODAY, SINCE);
    expect(r.cohorts[0].d7).toBe(20);
  });

  it('когорта, которой 6 дней, D7 ещё не получает', () => {
    const r = buildRetention([{ day: '2026-10-14', users: 10, d1: 5, d7: 9, d30: 9 }], TODAY, SINCE);
    expect(r.cohorts[0].d7).toBeNull();
  });

  it('число недозревших когорт показано явно', () => {
    // Иначе в отчёте тихо появляются нули, и их не отличить от провала.
    // Недозревших тут все три: у когорты 1 октября не наступил D30, и
    // первая версия проверки ждала две, посчитав только очевидное.
    expect(rep.incompleteCohorts).toBe(3);
  });

  it('все когорты помечены полными (после появления session_start)', () => {
    expect(rep.cohorts.every(c => c.full)).toBe(true);
  });

  it('D30 не появится раньше 29 октября — и это не поломка данных', () => {
    // Полной считается когорта, собранная начиная с появления session_start
    // (29 сентября). Плюс 30 дней — первая дата, когда хоть у одной когорты
    // может быть честный D30. Проверка фиксирует именно эту дату, чтобы
    // никто не удивлялся пустому D30 и не искал баг там, где его нет.
    const заДеньДо = buildRetention(
      [{ day: SINCE, users: 10, d1: 5, d7: 2, d30: 5 }],
      '2026-10-28',
      SINCE,
    );
    const вДень = buildRetention(
      [{ day: SINCE, users: 10, d1: 5, d7: 2, d30: 5 }],
      '2026-10-29',
      SINCE,
    );
    expect({ за_день_до: заДеньДо.cohorts[0].d30, в_день_наступил: вДень.cohorts[0].d30 })
      .toEqual({ за_день_до: null, в_день_наступил: 50 });
  });
});

describe('Удержание: когорты до эпохи session_start неполные', () => {
  it('возвраты не выдаются за точные', () => {
    // До 29 сентября входа в мир в аналитике не было: игрок, зашедший по
    // живой сессии, не оставлял событий. Считать такие когорты по полной
    // нельзя — они покажут ненулевое, но заниженное удержание.
    const r = buildRetention([{ day: '2026-09-20', users: 80, d1: 3, d7: 1, d30: 0 }], TODAY, SINCE);
    expect(r.cohorts[0]).toMatchObject({ full: false, d1: null, d7: null, d30: null });
  });

  it('в сумме по таким когортам ничего не выдумывается', () => {
    // Итог по D7 строится только из дозревших когорт. Если бы в сумму
    // попали недозревшие с нулями, общий D7 упал бы ниже правды
    const r = buildRetention(
      [
        { day: '2026-09-20', users: 1000, d1: 0, d7: 0, d30: 0 }, // неполная
        { day: '2026-10-01', users: 100, d1: 50, d7: 25, d30: 0 }, // полная
      ],
      TODAY,
      SINCE,
    );
    expect(r.totals.d7).toBe(25);
  });

  it('если не дозрел никто — итог null, а не 0', () => {
    const r = buildRetention([{ day: '2026-10-20', users: 7, d1: 0, d7: 0, d30: 0 }], TODAY, SINCE);
    expect({ d1: r.totals.d1, d7: r.totals.d7, d30: r.totals.d30 })
      .toEqual({ d1: null, d7: null, d30: null });
  });

  it('сумма по игрокам считается всегда', () => {
    const r = buildRetention([{ day: '2026-10-20', users: 7, d1: 0, d7: 0, d30: 0 }], TODAY, SINCE);
    expect(r.totals.users).toBe(7);
  });
});

describe('Удержание: среднее взвешено по игрокам, а не по когортам', () => {
  it('когорта вдвое больше тянет итог за собой', () => {
    // 200 человек, из них 100 вернулись (50%), и 100 человек, из которых не
    // вернулся никто. Среднее по когортам дало бы 25% и занизило бы картину
    // почти вдвое; по людям правильный ответ 33.3%.
    const r = buildRetention(
      [
        { day: '2026-10-01', users: 200, d1: 100, d7: 0, d30: 0 },
        { day: '2026-10-02', users: 100, d1: 0, d7: 0, d30: 0 },
      ],
      TODAY,
      SINCE,
    );
    expect(r.totals.d1).toBeCloseTo(33.3, 1);
  });
});

describe('Отчёт собирает всё, что нужно владельцу', () => {
  const repoRoot = join(__dirname, '..', '..', '..');
  const route = stripComments(
    readFileSync(join(repoRoot, 'server/src/routes/admin.ts'), 'utf-8'),
  );

  it('эндпоинт есть и отдаёт три среза', () => {
    expect(route).toMatch(/adminRouter\.get\('\/funnel'/);
    expect(route).toMatch(/playerFunnel\.getFunnel/);
    expect(route).toMatch(/playerFunnel\.getRetention/);
    expect(route).toMatch(/playerFunnel\.getActiveSeries/);
  });

  it('эндпоинт закрыт админской проверкой', () => {
    // Отчёт по игрокам не должен доставаться кому угодно
    expect(route).toMatch(/adminRouter\.get\('\/funnel', adminCheck/);
  });

  it('размер когорты ограничен сверху', () => {
    // Без ограничения запрос на 100000 дней уронил бы базу
    expect(route).toMatch(/Math\.min\(180/);
  });

  it('в ответе указано, с какого дня честные данные', () => {
    expect(route).toMatch(/sessionStartSince/);
  });
  it('отчёт показывает, с какого дня есть каждое событие', () => {
    // ГЛАВНОЕ О ЧЕСТНОСТИ ОТЧЁТА. character_created и level_up до этой
    // выкатки не писал никто, поэтому в воронке за прошлые дни шаг «завели
    // персонажа» всегда ноль. Без даты появления события владелец прочтёт
    // этот ноль как «игроки застревают» — а дело в измерении.
    // Проверка обязана смотреть в ОТВЕТ, а не в файл: отчёт ломается
    // удалением eventSince из res.json, при этом переменная в коде остаётся.
    // Первая версия искала слово по всему файлу и потому прошла на сломанном
    // отчёте — это нашлось проверкой нехолостотности, слой I.
    const payload = /adminRouter\.get\('\/funnel'[\s\S]{0,4000}?res\.json\(\{([^}]*)\}\)/.exec(route)?.[1] ?? '';
    expect({
      нашёлся_ответ: payload.length > 0,
      карта_в_ответе: payload.includes('eventSince'),
      когорты_в_ответе: payload.includes('retention'),
    }).toEqual({ нашёлся_ответ: true, карта_в_ответе: true, когорты_в_ответе: true });
    for (const ev of ['session_start', 'guest_login', 'player_login', 'character_created', 'level_up']) {
      expect({ событие: ev, есть_в_карте: route.includes(ev) }).toEqual({ событие: ev, есть_в_карте: true });
    }
  });

  it('неизвестное событие в карте — это null, а не молчание', () => {
    // Карта заполняется предварительно всеми пятью событиями со значением
    // null, и только потом дополняется найденными датами. Иначе событие без
    // записей просто не упоминалось бы в ответе, и отсутствие данных
    // выглядело бы как «ещё не смотрел»
    expect(route).toMatch(/character_created: null/);
    expect(route).toMatch(/level_up: null/);
  });
});
