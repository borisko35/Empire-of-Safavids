// Столы у причала и колодец на площади перестают быть ящиками.
//
// ЧТО БЫЛО (22 октября 2026, §298). Торговый стол у причала — сплошной ящик
// 1.8×0.9×1.0 на палках: столешницы не было, товара не было, полки не было.
// Колодец на площади города региона — ровный цилиндр: бак без намёка, без
// вала, без верёвки.
//
// ЧТО ТЕПЕРЬ. Стол: столешница-доска, полка с товаром снизу, ткань, свисающая с
// края, горшок, корзина и мешок. Колодец: каменный ворот с зубцами, стойки и
// перекладина вала, верёвка и ведро.
//
// ЧТО ПРОВЕРЯЕТСЯ. У стола есть столешница, полка, ткань и товар; ящика вместо
// стола нет. У колодца есть ворот с зубцами, стойки, вал, верёвка и ведро.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Столы причала и колодец — не ящики', () => {
  it('стол: столешница, полка, ткань и товар', () => {
    // Столешница — доска, а не ящик во всю высоту.
    должен(
      /const table = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.8, 0\.08, 1\.0\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'столешницы стола нет: стол — ящик',
    );
    // Полка с товаром снизу.
    должен(
      /const полка = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.6, 0\.06, 0\.8\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'у стола нет полки с товаром',
    );
    // Ткань с края.
    должен(
      /const ткань = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.82, 0\.5, 0\.04\), MAT\.clothTeal\);/.test(ТЕРРЕЙН),
      'у стола нет ткани',
    );
    // Товар на столе: горшок, корзина, мешок.
    должен(/const горшок = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.13, 0\.18, 0\.36, 8\)/.test(ТЕРРЕЙН),
      'на столе нет горшка');
    должен(/const корзина = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.26, 0\.19, 0\.3, 10\)/.test(ТЕРРЕЙН),
      'на столе нет корзины');
    // Ящика вместо стола быть не должно.
    должен(
      !/new THREE\.BoxGeometry\(1\.8, 0\.9, 1\.0\)/.test(ТЕРРЕЙН),
      'торговый стол снова ящик',
    );
  });

  it('колодец: ворот с зубцами, вал, верёвка и ведро', () => {
    // Каменный ворот.
    должен(
      /const ворот = new THREE\.Mesh\(new THREE\.TorusGeometry\(1\.28, 0\.16, 6, 14\), MAT\.sandstoneDark\);/.test(ТЕРРЕЙН),
      'у колодца нет каменного воротка',
    );
    // Зубцы по ободу.
    должен(/const зубец = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.26, 0\.22, 0\.4\)/.test(ТЕРРЕЙН),
      'у колодца нет зубцов');
    // Стойки вала.
    должен(
      /const стойка = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.16, 1\.5, 0\.16\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у колодца нет стоек вала',
    );
    // Вал.
    должен(
      /const вал = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.12, 0\.12, 2\.3, 6\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у колодца нет вала',
    );
    // Верёвка и ведро.
    должен(
      /const верёвка = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.02, 0\.02, 1\.9, 4\), MAT\.dark\);/.test(ТЕРРЕЙН),
      'у колодца нет верёвки',
    );
    должен(
      /const ведро = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.19, 0\.16, 0\.28, 9\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'у колодца нет ведра',
    );
  });
});
