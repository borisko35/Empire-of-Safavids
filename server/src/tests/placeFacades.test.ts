// Фасады четырёх мест: стекло вместо дыр, стены вместо голых плит.
//
// ЧТО БЫЛО (21 октября 2026, §224). Четыре места — таможня, ткацкая,
// святилище и ханза — стояли рядом с городами, но фасадами не читались:
//   • в мастерской ткацкой окна были чёрными плашками во всю толщину стены
//     (MAT.dark в проёме), то есть дырами; стекло в игре было одно, и стояло
//     оно только в домах Исфахана (§222);
//   • в таможне у дома не было ни одного окна, а стена комплекса была гладкой
//     плитой в пять метров — без зубцов, без пояса;
//   • в святилище «дым» из трубы в коде РОС вверх, хотя комментарий обещал
//     убывающий столб, и стоял он белой глыбой; «огонь» был конусом из
//     тёмно-красной ткани и золота — дорожным конусом на треноге;
//   • в ханзе боковые стены зала мерились ШИРИНОЙ зала вместо его глубины:
//     20.6 м при глубине 16, и стены вылезали на 4.6 м во двор.
//
// ЧТО ТЕПЕРЬ. Окно — одна функция на всю игру (windowPane) с размерами в
// аргументах; у каждого из четырёх мест есть окна; стены получили пояса и
// карнизы; огонь светится, дым сужается; стены зала ханзы меряются глубиной.
//
// ЧТО ПРОВЕРЯЕТСЯ. Каждая правка — отдельной строкой, и каждая ломается
// обратно: сторож падает, если правку убрать.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/terrain.ts');

// Проверки ведём по КОДУ, без комментариев. Иначе сторож ловит сам себя:
// объяснение правки в комментарии содержит старую строку кода — и проверка
// «дым больше не растёт» падала на собственном пояснении.
const КОД = МИР
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\/\/.*$/gm, '');

/**
 * Отрезок кода между двумя опорными метками.
 *
 * Метки ищутся в исходнике (они — комментарии), а проверки идут по очищенному
 * от комментариев куску: иначе сторож ловит собственное пояснение правки.
 */
function между(начало: string, конец: string): string {
  const от = МИР.indexOf(начало);
  должен(от >= 0, `в коде нет метки «${начало}»: проверка ослепла`);
  // Конечную метку ищем ПОСЛЕ начальной: часть заголовков повторяется в
  // шапке файла, и первый проход находил её там.
  const до = МИР.indexOf(конец, от);
  должен(до > от, `в коде нет метки «${конец}» после «${начало}»: проверка ослепла`);
  return МИР.slice(от, до)
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/.*$/gm, '');
}

const ТАМОЖНЯ = между('── Стены комплекса ──', '── Мастерская ──');
const ТКАЦКАЯ = между('── Мастерская ──', '── Передняя стена с проёмом двери ──');
const СВЯТИЛИЩЕ = между('── Передняя стена с проёмом двери ──', '── Зал: стены ──');
const ХАНЗА = между('── Зал: стены ──', '── Гробница Шеиха ──');

describe('Фасады четырёх мест', () => {
  it('окно принимает размеры, а не строит одно на всю игру', () => {
    // Пока размеры были зашиты (0.9 x 1.3), окно подходило только дому
    // Исфахана: мастерская, таможня и ханза остались с чужими подделками.
    должен(
      /function windowPane\([\s\S]*?W = 0\.9, H = 1\.3/.test(КОД),
      'у windowPane нет размеров в аргументах: любое здание получит окно чужого размера',
    );
  });

  it('у каждого из четырёх мест есть стеклянные окна', () => {
    const места: [string, string][] = [
      ['таможня', ТАМОЖНЯ],
      ['ткацкая', ТКАЦКАЯ],
      ['святилище', СВЯТИЛИЩЕ],
      ['ханза', ХАНЗА],
    ];
    for (const [имя, кусок] of места) {
      должен(
        /windowPane\(/.test(кусок),
        `в ${имя} нет ни одного окна: фасад остаётся голой стеной`,
      );
    }
  });

  it('в мастерской ткацкой больше нет чёрных проёмов', () => {
    // Плашка во всю толщину стены читалась дырой: материал почти чёрный,
    // матовый, без рамы и средника. Ловим по сути — тёмная вставка глубже
    // стены, — а не по точному набору чисел: размеры у окон менялись.
    должен(
      !/BoxGeometry\([^)]*HOUSE_T \+ 0\.3\),\s*MAT\.dark/.test(ТКАЦКАЯ),
      'в мастерской снова чёрная плашка вместо окна: фасад читается дырой',
    );
    должен(
      !/BoxGeometry\([^)]*HOUSE_T \+ 0\.3\),\s*MAT\.dark/.test(ТАМОЖНЯ),
      'в таможне снова чёрная плашка вместо окна',
    );
  });

  it('стена таможни читается как стена: зубцы и пояс', () => {
    // Гладкая плита в пять метров читалась как забор из двух прямоугольников.
    должен(/const зубец = /.test(ТАМОЖНЯ), 'на стене таможни нет зубцов');
    должен(
      /WALL_H \+ 0\.275/.test(ТАМОЖНЯ),
      'зубцы таможни стоят не на стене: стена остаётся гладкой',
    );
    должен(/WALL_H - 0\.78/.test(ТАМОЖНЯ), 'на стене таможни нет пояса под зубцами');
  });

  it('огонь святилища светится, а дым сужается', () => {
    // Комментарий обещал убывающий дым, код делал наоборот: блоки РОСЛИ
    // (chimney.w + i * 1.1), и над трубой вырастала белая глыба.
    должен(
      !/chimney\.w \+ i \* 1\.1/.test(СВЯТИЛИЩЕ),
      'дым снова растёт вверх: над трубой будет белая глыба',
    );
    должен(/ConeGeometry\(0\.95 - i \* 0\.28/.test(СВЯТИЛИЩЕ), 'дым не сужается');
    // Огонь должен светиться сам — иначе это снова фигура, а не пламя.
    должен(/fire:\s*new THREE\.MeshStandardMaterial/.test(КОД), 'нет материала огня');
    const блок = /fire:\s*new THREE\.MeshStandardMaterial\(\{([\s\S]*?)\}\)/.exec(КОД);
    должен(блок, 'материал огня не читается');
    должен(
      /emissive:\s*0x[0-9a-f]+/.test(блок![1]),
      'огонь не светится: он останется тёмной фигурой',
    );
  });

  it('стены зала ханзы меряются глубиной зала, а не шириной', () => {
    // 20.6 м боковой стены при глубине зала 16: стены вылезали на 4.6 м во
    // двор и делали въезд узкой щелью между двумя высокими стенами.
    должен(
      /zЗад \+ \(HALL_D - WALL_T\) \/ 2, WALL_T, HALL_D - WALL_T\]/.test(ХАНЗА),
      'боковые стены зала снова меряются шириной: они торчат во двор',
    );
    должен(
      !/WALL_T, HALL_W - WALL_T\]/.test(ХАНЗА),
      'боковые стены зала снова длиной в ширину зала',
    );
  });
});

