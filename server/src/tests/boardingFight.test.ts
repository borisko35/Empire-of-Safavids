// Бой абордажа: исход и добыча.
//
// ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. Бой — круги, а не формула. Формула «урон = атака −
// защита» дала бы мгновенный исход при любой разнице уровней, и рейд 80-х
// убивал бы 60-го одним ударом. Проверка требует накопления и предела кругов.
//
// Второе: добыча в PvE и PvP различается только источником. Правила одни —
// победитель забирает, проигравший остаётся с тем, что унёс.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const бой = код('server/src/systems/BoardingFight.ts');

describe('Абордаж: бой — круги, а не один удар', () => {
  it('есть предел кругов', () => {
    // Без него защита выше атаки сделала бы бой бесконечным.
    must(/BOARD_MAX_ROUNDS = 12/.test(бой), 'предела кругов нет');
    must(/круг < BOARD_MAX_ROUNDS/.test(бой), 'цикл не ограничен пределом');
  });

  it('урон не меньше единицы с любой стороны', () => {
    // Иначе защита выше атады дала бы ноль урона навсегда.
    must(/Math\.max\(1, [^\s.]+\.attack - [^\s.]+\.defense\)/.test(бой), 'урон по цели может быть нулевым');
    must(/Math\.max\(1, [^\s.]+\.targetAttack/.test(бой), 'ответный урон может быть нулевым');
  });

  it('исход не виснет: есть явная победа и явное поражение', () => {
    must(/won: [^\s.]+ <= 0 && [^\s.]+ > 0/.test(бой), 'условие победы неявное');
  });
});

describe('Абордаж: добыча — одни правила на оба режима', () => {
  it('победитель забирает, проигравший — нет', () => {
    must(/исход\.won \? boardReward\(/.test(бой), 'награда не зависит от исхода');
    must(/исход\.won \? \[\.\.\.[^\s.]*\.targetItems\] : \[\]/.test(бой), 'трофеи выдаются не по исходу');
  });

  it('проигравший не теряет ничего и не получает', () => {
    // В PvE поражение ничего не стоит: монстр остаётся жив, на нём остаётся
    // награда. Это же правило в PvP: проигравший остаётся с тем, что унёс.
    // Проверяем не комментарий (stripComments его убирает — проверка по
    // комментарию не проходила бы НИКОГДА), а поведение: исход решает всё.
    must(/attackerWon: [^\s.]+\.won/.test(бой), 'в исходе не пишется, кто выиграл');
    must(/const gold = [^\s.]+\.won \? boardReward\([^\s.]+\.baseGold, [^\s.]+\.mode\) : 0;/.test(бой),
      'проигравшему мог уйти золото');
    must(/const items = [^\s.]+\.won \? \[\.\.\.[^\s.]+\.targetItems\] : \[\];/.test(бой),
      'проигравшему могли уйти трофеи');
  });
});

describe('Абордаж: PvP-потери', () => {
  it('теряется часть груза, а не весь', () => {
    // Полная потеря на каждый рейс означала бы, что один неудачный клик
    // обнуляет торговый рейс.
    must(/BOARD_PVP_CARGO_LOSS_SHARE = 1 \/ 3/.test(бой), 'доля потери не треть');
    must(/Math\.max\(1, Math\.floor\([^\s.]+\.length \* BOARD_PVP_CARGO_LOSS_SHARE\)\)/.test(бой),
      'снятие груза не считает от доли');
  });

  it('пустой груз не ломает функцию', () => {
    // slice(0, 1) от пустого даёт пустой, но явная проверка честнее.
    must(/if \([^)]*\.length\) return \[\];/.test(бой), 'нет раннего выхода для пустого груза');
  });
});

describe('Абордаж: силы берутся из игры', () => {
  it('своей формулы урона нет', () => {
    // Иначе «сильный игрок» в двух местах значил бы разное.
    must(!/attackPower \*|множитель урона|свой коэффициент/.test(бой), 'появилась своя формула урона');
  });

  it('силы описаны интерфейсом, а не считаются внутри', () => {
    // Бой получает числа сюда — значит, их источник можно поменять (например,
    // на оружие) не трогая бой.
    must(/export interface BoardCombatant/.test(бой), 'нет интерфейса сил');
  });
});