// Бой абордажа: исход и добыча.
//
// ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. Бой — круги, а не формула. Формула «урон = атака −
// защита» дала бы мгновенный исход при любой разнице уровней, и рейд 80-х
// убивал бы 60-го одним ударом. Проверка требует накопления и предела кругов.
//
// Второе: добыча в PvE и PvP различается только источником. Правила одни —
// победитель забирает, проигравший остаётся с тем, что унёс.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';
import { pvpCargoLoss, boardGoldTake } from '../systems/BoardingFight';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const бой = код('server/src/systems/BoardingFight.ts');

describe('Абордаж: бой — круги, а не один удар', () => {
  it('есть предел кругов', () => {
    // Без него защита выше атаки сделала бы бой бесконечным.
    must(/BOARD_MAX_ROUNDS = 12/.test(бой), 'предела кругов нет');
    must(/круг < BOARD_MAX_ROUNDS/.test(бой), 'цикл не ограничен пределом');
  });

  it('урон не меньше единицы с любой стороны', () => {
    // Иначе защита выше атады дала бы ноль урона навсегда.
    must(/Math\.max\(1, [^\s.]+\.attack - [^\s.]+\.defense\)/.test(бой), 'урон по цели может быть нулевым');
    must(/Math\.max\(1, [^\s.]+\.targetAttack/.test(бой), 'ответный урон может быть нулевым');
  });

  it('исход не виснет: есть явная победа и явное поражение', () => {
    must(/won: [^\s.]+ <= 0 && [^\s.]+ > 0/.test(бой), 'условие победы неявное');
  });
});

describe('Абордаж: добыча — одни правила на оба режима', () => {
  it('победитель забирает, проигравший — нет', () => {
    must(/исход\.won \? boardReward\(/.test(бой), 'награда не зависит от исхода');
    must(/исход\.won \? \[\.\.\.[^\s.]*\.targetItems\] : \[\]/.test(бой), 'трофеи выдаются не по исходу');
  });

  it('проигравший не теряет ничего и не получает', () => {
    // В PvE поражение ничего не стоит: монстр остаётся жив, на нём остаётся
    // награда. Это же правило в PvP: проигравший остаётся с тем, что унёс.
    // Проверяем не комментарий (stripComments его убирает — проверка по
    // комментарию не проходила бы НИКОГДА), а поведение: исход решает всё.
    must(/attackerWon: [^\s.]+\.won/.test(бой), 'в исходе не пишется, кто выиграл');
    must(/const gold = [^\s.]+\.won \? boardReward\([^\s.]+\.baseGold\) : 0;/.test(бой),
      'проигравшему мог уйти золото');
    must(!/boardReward\([^)]*\.mode\)/.test(бой),
      'золото снова считается по режиму: множитель PvP удалён решением владельца (§194)');
    must(/const items = [^\s.]+\.won \? \[\.\.\.[^\s.]+\.targetItems\] : \[\];/.test(бой),
      'проигравшему могли уйти трофеи');
  });
});

describe('Абордаж: PvP-потери', () => {
  // Считает, сколько ПРЕДМЕТОВ уйдёт из указанного груза.
  const снято = (груз: { itemId: string; quantity: number }[]): number =>
    pvpCargoLoss(груз).reduce((с, з) => с + з.qty, 0);

  it('доля потери — треть', () => {
    must(/BOARD_PVP_CARGO_LOSS_SHARE = 1 \/ 3/.test(бой), 'доля потери не треть');
  });

  it('один стек теряет треть, а не весь', () => {
    // Именно этот случай уехал на прод. Прежняя версия считала треть от
    // числа стеков (один стек → одна «доля») и снимала стек целиком:
    // игрок с одним стеком в девять штук терял все девять.
    must(снято([{ itemId: 'шкура', quantity: 9 }]) === 3,
      'при одном стеке из 9 теряется не треть: ' + снято([{ itemId: 'шкура', quantity: 9 }]));
  });

  it('треть считается по количеству, а не по числу стеков', () => {
    // Три стека по девять — это 27 предметов, и треть здесь 9, а не 3×весь стек.
    const три = [{ itemId: 'шкура', quantity: 9 }, { itemId: 'железо', quantity: 9 }, { itemId: 'рыба', quantity: 9 }];
    must(снято(три) === 9, 'из трёх стеков по 9 теряется не 9: ' + снято(три));
    // Стек разной величины: 5 и 4 — всего 9, значит теряется 3 по обоим.
    must(снято([{ itemId: 'шкура', quantity: 5 }, { itemId: 'железо', quantity: 4 }]) === 3,
      'из стеков 5 и 4 теряется не 3');
  });

  it('снятие не превышает того, что есть', () => {
    // Сверх количества снять нельзя ни при каком раскладе.
    for (const груз of [
      [{ itemId: 'а', quantity: 1 }],
      [{ itemId: 'а', quantity: 2 }],
      [{ itemId: 'а', quantity: 3 }],
      [{ itemId: 'а', quantity: 4 }],
      [{ itemId: 'а', quantity: 5 }],
      [{ itemId: 'а', quantity: 9 }],
      [{ itemId: 'а', quantity: 9 }, { itemId: 'б', quantity: 0 }],
      [{ itemId: 'а', quantity: 0 }],
    ]) {
      const есть = груз.reduce((с, з) => с + з.quantity, 0);
      const ушло = снято(груз);
      must(ушло <= есть && ушло >= 0, 'снято ' + ушло + ' из ' + есть);
    }
  });

  it('золото берётся в пределах кошелька жертвы', () => {
    // Ровно тот случай, что уехал на прод: 500 у жертвы, 2.5 — множитель
    // PvP, и 1250 уходили атакующему, пока у жертвы не сняли ни гроша.
    must(boardGoldTake(1250, 500) === 500,
      'при кошельке 500 просят 1250, а берут ' + boardGoldTake(1250, 500));
    must(boardGoldTake(100, 1000) === 100, 'при кошельке 1000 просят 100, а берут иначе');
    must(boardGoldTake(500, 500) === 500, 'ровно весь кошель должен браться целиком');
    must(boardGoldTake(0, 500) === 0, 'при нулевой награде что-то берётся');
    must(boardGoldTake(1250, 0) === 0, 'с пустого кошелька что-то берётся');
    must(boardGoldTake(100, -5) === 0, 'с отрицательным кошельком что-то берётся');
  });

  it('взятое золото не превышает кошель ни при каком множителе', () => {
    // Множитель PvP — 2.5, и при любом кошельке он даёт больше, чем есть.
    // Обойти это можно было бы только одним: не брать больше кошелька.
    for (const кошель of [0, 1, 7, 99, 500, 12345]) {
      const взято = boardGoldTake(Math.floor(кошель * 2.5), кошель);
      must(взято <= кошель, 'взято ' + взято + ' при кошельке ' + кошель);
    }
  });

  it('пустой груз не ломает функцию', () => {
    must(pvpCargoLoss([]).length === 0, 'пустой груз что-то вернул');
    must(pvpCargoLoss([{ itemId: 'а', quantity: 0 }]).length === 0, 'нулевой стек что-то вернул');
  });

});

describe('Абордаж: силы берутся из игры', () => {
  it('своей формулы урона нет', () => {
    // Иначе «сильный игрок» в двух местах значил бы разное.
    must(!/attackPower \*|множитель урона|свой коэффициент/.test(бой), 'появилась своя формула урона');
  });

  it('силы описаны интерфейсом, а не считаются внутри', () => {
    // Бой получает числа сюда — значит, их источник можно поменять (например,
    // на оружие) не трогая бой.
    must(/export interface BoardCombatant/.test(бой), 'нет интерфейса сил');
  });
});