// Зелень: пальма с поникающими листьями и кипарис слоями.
//
// ЧТО БЫЛО (21 октября 2026, §228). Листва финика и кипариса была
// примитивами «на глаз»:
//   • лист пальмы — конус 0.34 x 2.6 на четыре грани; семь таких шипов торчали
//     во все стороны, и пальма читалась чёрной звездой, а не деревом;
//   • крона кипариса — ровный конус; два кипариса рядом были одинаковыми
//     геометрическими фигурами.
//
// ЧТО ТЕПЕРЬ. Лист — поникающее перо из четырёх сегментов (последний
// загнут вверх: без изгиба финик не узнаётся). Крона кипариса — четыре слоя
// со смещением и разным поворотом. И то и другое — общие функции, а не
// копии в четырёх местах.
//
// ЧТО ПРОВЕРЯЕТСЯ. Чтобы зелень не «съехала» обратно в шипы при правке
// силуэта: сторож требует именно сегментный лист и именно слоистую крону.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Зелень', () => {
  it('лист пальмы — поникающие сегменты, а не шипы', () => {
    // Шип-конус читался чёрной звездой: у кроны не было ни листа, ни ветки.
    должен(
      !/ConeGeometry\(0\.34 \* k, 2\.6 \* k, 4\)/.test(код),
      'лист пальмы снова конус-шип: крона читается звездой',
    );
    должен(
      /function листФиника/.test(код) && /BoxGeometry\(д, 0\.06 \* k/.test(код),
      'лист пальмы не собран из плоских сегментов',
    );
    // Четыре сегмента: изгиб вниз, потом вверх.
    const сегменты = /const сегменты = \[([\s\S]*?)\];/.exec(код);
    должен(сегменты, 'не найден список сегментов листа');
    const строки = сегменты![1].split('\n').filter((с) => с.includes('наклон'));
    должен(строки.length >= 4, `сегментов листа ${строки.length}: нужен изгиб, а не прямая палка`);
    // Последний сегмент загнут вверх: наклон меньше (ближе к нулю), чем у
    // предыдущего, который свисает вниз.
    const наклоны = строки.map((с) => Number(/наклон:\s*(-?[\d.]+)/.exec(с)![1]));
    должен(
      наклоны[наклоны.length - 1] > наклоны[наклоны.length - 2],
      'кончик листа не загнут вверх: пальма без изгиба не финик',
    );
  });

  it('крона финика густая и с шапкой у ствола', () => {
    // Одинокие листья висели в воздухе: шапка нужна, чтобы лист начинался
    // у ствола.
    должен(
      /function кронаФиника\(parent: THREE\.Object3D, k: number, листьев = (\d+)\)/.exec(код) !== null,
      'нет общей кроны финика',
    );
    const листьев = Number(/function кронаФиника\(parent: THREE\.Object3D, k: number, листьев = (\d+)\)/.exec(код)![1]);
    должен(листьев >= 10, `листьев в кроне ${листьев}: крона прорежена`);
    должен(/MAT\.foliageLight/.test(код), 'шапка кроны из того же тёмного материала: середина кроны чёрная');
  });

  it('крона кипариса слоистая, а не ровный конус', () => {
    должен(
      /function кронаКипариса/.test(код),
      'нет общей кроны кипариса',
    );
    // Ровный конус — силуэт без объёма.
    должен(
      !/const crown = new THREE\.Mesh\(new THREE\.ConeGeometry\(0\.85 \* s, 3\.6 \* s, 7\)/.test(код),
      'крона кипариса снова ровный конус',
    );
    const слои = /const слои = \[([\s\S]*?)\];/.exec(код);
    должен(слои, 'не найдены слои кроны кипариса');
    const строки = слои![1].split('\n').filter((с) => с.includes('р:'));
    должен(строки.length >= 4, `слоёв кроны ${строки.length}: силуэт без объёма`);
  });

  it('все четыре места зелени используют общие кроны', () => {
    // Копии разъезжаются: пальма в городе и пальма в городах регионов —
    // одна и та же крона. Считаем вхождения: определение плюс два применения.
    const пальм = (код.match(/кронаФиника\(/g) || []).length;
    const кипарисов = (код.match(/кронаКипариса\(/g) || []).length;
    должен(пальм >= 3, `вызовов кронаФиника ${пальм}: пальмы города и регионов разошлись`);
    должен(кипарисов >= 3, `вызовов кронаКипариса ${кипарисов}: кипарисы разошлись`);
  });
});
