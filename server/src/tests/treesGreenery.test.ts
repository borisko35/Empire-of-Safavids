// Деревья мира и зелень пальм/кипарисов.
//
// ЧТО БЫЛО (21-22 октября, §228/§258/§287). Пальма собиралась из брусков,
// кипарис — из слоёв конусов, деревья полей — из пяти примитивов на
// InstancedMesh.
//
// ЧТО ТЕПЕРЬ (§326). Всё дерево — готовая GLB-модель: платаны (platan-1..4),
// кипарис (cypress), пальмы (palm-1..4). Слои и листы ушли вместе с
// процедурной сборкой; поле деревьев строится decorПолем — матрицы сразу,
// геометрия доезжает по сети.
//
// ЧТО ПРОВЕРЯЕТСЯ. Модели лежат в манифесте; поле деревьев собирается
// decorПолем с вариантами и наклоном; у каждого дерева свой оттенок; пальмы
// города и регионов едут из одних файлов (копий загрузки нет).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
  animals?: { file: string; name: string; bytes: number }[];
};
const вМанифесте = (раздел: 'decor' | 'animals', имя: string): boolean =>
  (МАНИФЕСТ[раздел] ?? []).some((д) => д.name === имя);

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Деревья мира', () => {
  it('платаны и кипарисы — готовые модели в манифесте', () => {
    for (const имя of ['platan-1', 'platan-2', 'platan-3', 'platan-4', 'cypress', 'palm-1', 'palm-2', 'palm-3', 'palm-4']) {
      должен(вМанифесте('decor', имя), `${имя}.glb нет в манифесте`);
    }
  });

  it('поле деревьев собирается decorПолем: варианты, наклон, оттенок', () => {
    const блок = ТЕРРЕЙН.split('Деревья: настоящие модели')[1].split('Камыш у самой кромки')[0];
    // Четыре варианта платана и кипарис.
    должен(/const платаны: ТочкаПоля\[\]\[\] = \[\[\], \[\], \[\], \[\]\];/.test(блок),
      'поле платанов не разбито на варианты');
    // Наклон: деревья не растут отвесно.
    должен(/const наклон = \(rng\(\) - 0\.5\) \* [\d.]+;/.test(блок), 'деревья стоят строго вертикально');
    // Свой оттенок: слабый множитель у каждого дерева.
    должен(/tint: new THREE\.Color\(\)\.setHSL\(/.test(блок), 'у всех деревьев один оттенок');
    // Поле ставится, кипарис отдельно.
    должен(/платаны\.forEach\(\(точки, i\) => decorПоле\(scene, `platan-\$\{i \+ 1\}`, точки\)\);/.test(блок),
      'платаны не поставлены полем');
    должен(/decorПоле\(scene, 'cypress', кипарисы\);/.test(блок), 'кипарисы не поставлены полем');
    // Примитивных крон и стволов больше нет.
    должен(!/CrownGeo = new THREE\.ConeGeometry/.test(код), 'кроны снова конусы');
    должен(!/const trunkGeo = new THREE\.CylinderGeometry\(0\.19, 0\.34, 3\.2, 6\);/.test(код),
      'стволы снова цилиндры');
  });

  it('пальмы города и регионов едут из одних файлов', () => {
    // Обе функции берут вариант из ПАЛЬМЫ — копий загрузки нет.
    должен(/const ПАЛЬМЫ = \['palm-1', 'palm-2', 'palm-3', 'palm-4'\] as const;/.test(код),
      'нет общего списка пальм');
    должен((код.match(/ПАЛЬМЫ\[Math\.floor\(/g) || []).length >= 2,
      'пальмы города и регионов не используют общий список');
  });

  it('пальма ставится моделью, а не цилиндром с брусками', () => {
    должен(!/CylinderGeometry\(0\.16 \* k, 0\.26 \* k, 5\.4 \* k, 6\)/.test(код),
      'ствол пальмы снова цилиндр');
    должен(!/function листФиника/.test(код), 'листья-бруски вернулись');
    const блок = код.split('function addPalm')[1].split('\n}\n')[0];
    должен(/decorВещь\(parent, имя, x, z, \{/.test(блок), 'пальма ставится не через decorВещь');
    должен(/качание: \{ амплитуда: 0\.02 \* k/.test(блок), 'пальма не качается');
  });
});
