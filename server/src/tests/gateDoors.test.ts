// Входимость: у каждого здания, которому в мире построена геометрия, есть дверь.
//
// ЗАЧЕМ ФАЙЛ. Найдено чтением кода: дверь входа в клиенте существует ровно в одном
// месте - buildTownBuildings, а та функция пропускает записи без lx и lz, то есть
// городские дома. Итог был такой:
//
//   зданий в SPOTS                          22
//   с фасадом и кликабельной дверью          9
//   войти нельзя                             13
//     из них с геометрией в мире              2   (караван-сарай, крепость)
//     из них без геометрии вовсе             11
//
// Подземелья (5) входят через панель захода, это отдельный путь и он работает. Значит
// без входа оставались восемь именованных зданий, и у караван-сарая с крепостью ворота
// были нарисованы, а коллайдер в проёме не давал войти даже подойти.
//
// ЧТО ТЕПЕРЬ. У караван-сарая и крепости стоят двери с doorAction: 'enter', коллайдеры из
// проёмов убраны, рядом с воротами стоят стелы с надписями.
//
// ГЛАВНАЯ ПРОВЕРКА ФАЙЛА - «у каждого именованного места мира есть дверь». Она и есть
// та проверка, которой не было: будь она написана раньше, баг не дожил бы до релиза.
// Места перечислены константами вида export const FORT = { x, z, radius, level }, и
// список не выписан здесь - новое место в мире автоматически попадёт под требование.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(__dirname, '..', '..', '..');
const TERRAIN = join(ROOT, 'client/src/app/game3d/terrain.ts');
const INTERIORS = join(ROOT, 'client/src/app/game3d/interiors.ts');
const INSCRIPTIONS = join(ROOT, 'client/src/app/game3d/inscriptions.ts');
const SOCKET = join(ROOT, 'server/src/socket/GameSocketHandler.ts');

const terrain = readFileSync(TERRAIN, 'utf-8');
const interiors = readFileSync(INTERIORS, 'utf-8');
const inscriptions = readFileSync(INSCRIPTIONS, 'utf-8');
const socket = readFileSync(SOCKET, 'utf-8');

/**
 * must объявлена как утверждение, а не как void: без этого TypeScript считает
 * результат регулярного выражения «possibly null» после проверки, и каждое чтение
 * приходилось бы дублировать отдельным if. Здесь проверок много, и они все одного
 * смысла - «это обязано существовать».
 */
function must(ok: unknown, why: string): asserts ok {
  if (!ok) throw new Error(why);
}

/** Именованные места мира: export const FORT = { x: -320, z: -705, radius: 28, level: 22 }. */
function местаМира(): { имя: string; x: number; z: number }[] {
  return [...terrain.matchAll(
    /export const (\w+) = \{ x: (-?[\d.]+), z: (-?[\d.]+), radius:/g,
  )].map((m) => ({ имя: m[1], x: Number(m[2]), z: Number(m[3]) }));
}

/** Здания без фасада: записи SPOTS с dx/dz, у которых нет lx/lz. */
function зданияБезФасада(): { id: string; x: number; z: number }[] {
  const начало = interiors.indexOf('const SPOTS');
  const блок = interiors.slice(начало, interiors.indexOf('];', начало));
  return [...блок.matchAll(
    /\{\s*id:\s*'([a-z_]+)',[^}]*?dx:\s*(-?[\d.]+),\s*dz:\s*(-?[\d.]+)/g,
  )].map((m) => ({ id: m[1], x: Number(m[2]), z: Number(m[3]) }));
}

/** Все id, для которых в terrain.ts поставлена дверь входа. */
function двериВхода(): string[] {
  return [...terrain.matchAll(/doorBuilding:\s*'([a-z_]+)'[\s\S]{0,80}?doorAction:\s*'enter'/g)]
    .map((m) => m[1]);
}

/** Радиус, которым сервер решает, что игрок подошёл к двери. */
function радиусПодхода(): number {
  const m = /Math\.hypot\(px - d\.doorX, pz - d\.doorZ\) <= (\d+(?:\.\d+)?)/.exec(socket);
  must(m, 'не нашли, как сервер считает близость к двери: порог поменялся, проверка ослепла');
  return Number(m[1]);
}

const места = местаМира();
const безФасада = зданияБезФасада();
const двери = двериВхода();

describe('Войти в здание можно', () => {
  it('список дверей и список зданий разобрались', () => {
    must(места.length > 0, 'не нашлось ни одного именованного места в мире');
    must(безФасада.length > 0, 'не нашлось зданий без фасада');
    must(двери.length > 0, 'в terrain.ts нет ни одной двери входа');
  });

  it('у каждого именованного места, совпадающего с зданием, есть дверь', () => {
    const безДвери: string[] = [];
    for (const место of места) {
      // Совпадение по имени: CARAVANSERAI -> caravanserai, FORT -> fortress.
      const здание = безФасада.find((з) => з.id.toUpperCase() === место.имя.toUpperCase());
      if (!здание) continue;
      if (!двери.includes(здание.id)) безДвери.push(`${здание.id} (${место.имя})`);
    }
    must(
      безДвери.length === 0,
      `у мест без двери входа: ${безДвери.join(', ')}. Ворота нарисованы, а войти нельзя: ` +
        'подойти можно, открыть - нет, и это видно только в игре',
    );
  });

  it('каждая дверь в terrain.ts ведёт в существующий интерьер', () => {
    for (const id of двери) {
      must(
        interiors.includes(`id: '${id}'`),
        `дверь ведёт в '${id}', а такого здания в SPOTS нет: клик уйдёт в никуда`,
      );
    }
  });

  it('дверь стоит не дальше, чем сервер считает подходом', () => {
    const порог = радиусПодхода();
    const центры: Record<string, { x: number; z: number }> = {};
    for (const место of места) центры[место.имя.toUpperCase()] = место;

    // Локальные координаты дверей читаются из terrain.ts: это единственное место,
    // где они заданы, и выписывать их здесь значило бы проверять саму себя.
    const пары = [...terrain.matchAll(
      /const (\w*[Vv]orota\w*) = new THREE\.Mesh\([\s\S]{0,120}?\.position\.set\((-?[\d.]+), (-?[\d.]+), (-?[\d.]+)\)[\s\S]{0,200}?doorBuilding: '([a-z_]+)'/g,
    )];
    must(пары.length > 0, 'не нашли ни одной двери ворот в terrain.ts');

    for (const [, , lx, ly, lz, id] of пары) {
      const здание = безФасада.find((з) => з.id === id);
      must(здание, `дверь ведёт в '${id}', а такого здания нет`);
      // Ищем ближайшее именованное место: дверь стоит в его локальных координатах.
      let ближайшее: { имя: string; x: number; z: number } | null = null;
      let лучший = Infinity;
      for (const место of места) {
        const d = Math.hypot(место.x + Number(lx) - здание.x, место.z + Number(lz) - здание.z);
        if (d < лучший) { лучший = d; ближайшее = место; }
      }
      must(ближайшее, `дверь '${id}' не привязана ни к одному месту мира`);
      // Расстояние считается от МИРОВОЙ позиции двери до координаты из данных, а не
      // от центра места. Прежняя версия мерила от центра и вообще не зависела от
      // того, где стоит дверь: сдвинь дверь на 50 метров - проверка бы не заметила.
      const мирX = ближайшее.x + Number(lx);
      const мирZ = ближайшее.z + Number(lz);
      const расстояние = Math.hypot(мирX - здание.x, мирZ - здание.z);
      must(
        расстояние <= порог,
        `дверь '${id}' стоит в мире в (${мирX}, ${мирZ}), а сервер ждёт игрока у ` +
          `(${здание.x}, ${здание.z}) - это ${расстояние.toFixed(1)} единиц при пороге ` +
          `${порог}. Игрок подойдёт к воротам, а сервер не признает его подошедшим`,
      );
      void ly;
    }
  });
});

describe('В ворота можно пройти, а не только подойти', () => {
  it('коллайдера в проёме караван-сарая нет', () => {
    must(
      !/addCollider\(CARAVANSERAI\.x, CARAVANSERAI\.z \+ 14,/.test(terrain),
      'в середине ворот караван-сарая снова стоит коллайдер: ворота нарисованы, ' +
        'но проём затыкает, и войти нельзя',
    );
  });

  it('коллайдера в проёме крепости нет', () => {
    must(
      !/addCollider\(FORT\.x, FORT\.z \+ 9,/.test(terrain),
      'в воротах крепости снова стоит коллайдер: куртины с трёх сторон, ' +
        'южный проём и есть ворота, и затыкать его нечем',
    );
  });

  it('проём шире ствола двери', () => {
    // Караван-сарай: столбы ворот на x = ±11, ширина каждого 1,6, значит проём
    // от -10,2 до 10,2 - всего 20,4. Дверь 5, в проём входит с запасом.
    // Ширина столба берётся из BoxGeometry, а x - из position.set. Раньше регулярное
    // выражение брало третьим числом z, то есть 14, и называло это шириной: проём
    // «получался» шириной 2,8 и проверка падала на верном коде.
    const столбы = /const gateL = new THREE\.Mesh\(new THREE\.BoxGeometry\(([\d.]+), [\d.]+, [\d.]+\)[\s\S]{0,90}?gateL\.position\.set\((-?[\d.]+), [\d.]+, [\d.]+\)/.exec(terrain);
    must(столбы, 'не нашли столбы ворот караван-сарая: геометрия переехала, проверка ослепла');
    const x = Math.abs(Number(столбы[2]));
    const ширинаСтолба = Number(столбы[1]);
    must(
      x - ширинаСтолба > 5,
      `проём караван-сарая шириной ${(x - ширинаСтолба).toFixed(1)}, а дверь 5: ` +
        'дверь шире проёма и станет торчать из ворот',
    );
  });
});

describe('Стелы у ворот стоят снаружи и не в стене', () => {
  /** Положения стел читаются из inscriptions.ts. */
  function положения(): Record<string, { x: number; z: number; ry: number }> {
    const начало = inscriptions.indexOf('export const GATE_STELES');
    must(начало >= 0, 'в inscriptions.ts нет GATE_STELES: положения стел нигде не заданы');
    const блок = inscriptions.slice(начало, inscriptions.indexOf('};', начало));
    const out: Record<string, { x: number; z: number; ry: number }> = {};
    for (const m of блок.matchAll(/([a-z_]+):\s*\{\s*x:\s*(-?[\d.]+),\s*z:\s*(-?[\d.]+),\s*ry:\s*(-?[\d.]+)\s*\}/g)) {
      out[m[1]] = { x: Number(m[2]), z: Number(m[3]), ry: Number(m[4]) };
    }
    return out;
  }

  const стелы = положения();

  it('положения заданы для обеих построек и разбираются', () => {
    must(
      Object.keys(стелы).length === 2,
      `положений стел у ворот ${Object.keys(стелы).length}, а построек две: ` +
        'караван-сарай и крепость',
    );
  });

  it('стела не стоит в проёме ворот', () => {
    // Проём караван-сарая: x от -10,2 до 10,2 на линии z = 14. Стела при z = 17 стоит
    // снаружи. Если её сдвинуть на z = 14 и внутрь проёма, она встанет прямо в ворота.
    must(
      стелы.caravanserai.z > 14 || Math.abs(стелы.caravanserai.x) > 10.2,
      'стела караван-сарая попала в проём ворот: игрок будет входить в стелу',
    );
    must(
      стелы.fortress.z > 9 || Math.abs(стелы.fortress.x) > 8.1,
      'стела крепости попала в ворота: проём там шириной 16,2, и стела перекрыла бы вход',
    );
  });

  it('стела не налезает на угловую башню', () => {
    // Башни караван-сарая на (±14, ±14), коллайдер 2,5. Башни крепости на (±9, ±9),
    // коллайдер 2,7. Числа взяты из terrain.ts, а не выдуманы.
    const башни = [
      { сайт: 'caravanserai', x: стелы.caravanserai.x, z: стелы.caravanserai.z, база: 14, радиус: 2.5 },
      { сайт: 'fortress', x: стелы.fortress.x, z: стелы.fortress.z, база: 9, радиус: 2.7 },
    ];
    for (const б of башни) {
      // Ближайшая угловая башня: (±база, ±база).
      const d = Math.hypot(Math.abs(б.x) - б.база, Math.abs(б.z) - б.база);
      must(
        d > б.радиус,
        `стела ${б.сайт} в ${d.toFixed(2)} от угловой башни, а коллайдер башни ` +
          `${б.радиус}: стела встанет внутрь башни и будет не видна`,
      );
    }
  });

  it('обе стелы реально ставятся в terrain.ts, а не лежат в данных', () => {
    for (const сайт of Object.keys(стелы)) {
      must(
        new RegExp(`stele\\w*\\.position\\.set\\(mesto\\w*\\.x`).test(terrain) ||
          /steleMesh\(/.test(terrain),
        `в terrain.ts нет сборки стелы: данные на ${сайт} есть, а в мире ничего`,
      );
    }
    must(
      (terrain.match(/steleMesh\(/g) || []).length >= 2,
      'steleMesh вызывается меньше двух раз: хотя бы у одной постройки стела не появится',
    );
    must(
      /GATE_STELES\./.test(terrain),
      'terrain.ts не читает GATE_STELES: положения стел заданы, но не применены',
    );
  });

  it('у каждой надписи есть место, где она встанет', () => {
    const городские = [...interiors.matchAll(/\{ id: '([a-z_]+)',[^}]*?lx:/g)].map((m) => m[1]);
    for (const m of inscriptions.matchAll(/buildingId: '([a-z_]+)'/g)) {
      const id = m[1];
      must(
        городские.includes(id) || стелы[id] !== undefined,
        `надпись ведёт на '${id}', а у него нет ни городского фасада, ни положения ` +
          'у ворот: текст есть, а стены, на которой он должен висеть, нет',
      );
    }
  });
});