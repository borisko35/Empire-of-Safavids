// Спринт перестал быть бесплатным.
//
// ЧТО БЫЛО. Выносливость тратилась только в воде. На суше шёл только отдых, и
// при удержании Shift выполнялась именно вторая ветка: игрок держал «усиленную
// скорость» сколько угодно, полоска стояла на месте, порог «ниже 5 % бег
// невозможен» не срабатывал, подсказка «выдохся» не появлялась. От монстров можно
// было убегать вечно — это не «неудобно», это дыра в игре.
//
// ЧТО ПРОВЕРЯЕТСЯ. Считается настоящий расход из настоящих констант: сколько
// секунд можно бежать с полной выносливости, хватает ли порога «бег невозможен»
// на то, чтобы бег в самом деле прекратился, и — главное — что сервер выводит бег
// по измеренной скорости, а не по словам клиента. Иначе достаточно не отправлять
// пакет движения, и расхода не будет вовсе.
//
// ПОЧЕМУ СЧИТАЕТСЯ ВРЕМЯ, А НЕ «ПОЛНА ЛЕНТА УМЕНЬШИТСЯ». Время до нуля можно
// проверить числом: полная выносливость при 8 % в секунду — это двенадцать с
// половиной секунд непрерывного бега. Полоска при этом не обязана исчезать за
// двадцать секунд, но обязана опуститься ниже порога «бег невозможен», иначе Shift
// не выключится и игрок будет бежать на нуле.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { STAMINA } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СОКЕТ = читать('server/src/socket/GameSocketHandler.ts');
const СЕРВИС = читать('server/src/services/CharacterService.ts');
const КЛИЕНТ = читать('client/src/app/world.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

/** Скорость ходьбы и бега из клиента: по ним судим, где проходит порог. */
function число(источник: string, шаблон: RegExp, что: string): number {
  const найдено = шаблон.exec(источник);
  must(найдено, `не нашёл ${что} в коде: проверка считала бы не то, что в игре`);
  return Number(найдено![1]);
}

const ХОДЬБА = число(МИР, /const WALK_SPEED = ([\d.]+)/, 'скорость ходьбы');
const БЕГ = число(МИР, /const RUN_SPEED = ([\d.]+)/, 'скорость бега');

describe('Расход выносливости за бег', () => {
  it('расход задан и он ощутим', () => {
    must(
      STAMINA.SPRINT_DRAIN_PER_SEC > 0.02 && STAMINA.SPRINT_DRAIN_PER_SEC <= 0.2,
      `расход ${STAMINA.SPRINT_DRAIN_PER_SEC} в секунду: либо бег почти бесплатный, ` +
        'либо полоса кончается за пару секунд'
    );
  });

  it('с полной выносливости можно отбежать на десяток с лишним секунд', () => {
    // Обратная величина расхода: 1 / 0.08 = 12.5 секунды. Это и есть смысл цифры —
    // у игрока есть время догнать монстра или оторваться, но не уйти навсегда.
    const секунды = 1 / STAMINA.SPRINT_DRAIN_PER_SEC;
    must(
      секунды >= 8 && секунды <= 20,
      `с полной полоски хватает на ${секунды.toFixed(1)} с бега: ` +
        'либо слишком мало, чтобы успеть, либо слишком много, чтобы убегать вечно'
    );
  });

  it('порог беговой скорости стоит между ходьбой и бегом', () => {
    // Иначе либо ровный шаг считался бы бегом и полоса пульсировала бы сама, либо
    // настоящий бег не считался бы и расхода не было бы вовсе.
    must(
      STAMINA.SPRINT_SPEED_MIN > ХОДЬБА && STAMINA.SPRINT_SPEED_MIN < БЕГ,
      `порог ${STAMINA.SPRINT_SPEED_MIN} при ходьбе ${ХОДЬБА} и беге ${БЕГ}: ` +
        'шаг не должен выглядеть бегом, а бег должен'
    );
  });

  it('порог «бег невозможен» ниже расхода, иначе бег не остановится', () => {
    // Ключевая связка: расход доводит полоску до SPRINT_MIN, и тогда клиент
    // перестаёт бежать. Если бы порог был выше расхода, Shift работал бы вечно.
    must(
      STAMINA.SPRINT_MIN > 0 && STAMINA.SPRINT_MIN < 0.5,
      `порог отключения бега ${STAMINA.SPRINT_MIN}: при слишком высоком бег не кончится, ` +
        'при слишком низком игрок будет задыхаться на ровном месте'
    );
  });
});

describe('Кто решает, что игрок бежал', () => {
  it('сервер смотрит на измеренную скорость, а не на слова клиента', () => {
    must(
      /бежалЗаОкно\(socket\.characterId, pos, inWater\)/.test(СОКЕТ),
      'регенерация не спрашивает, бежал ли игрок: выносливость за бег не списывается'
    );
    must(
      /расстояние \/ секунды > STAMINA\.SPRINT_SPEED_MIN/.test(СОКЕТ),
      'бег выводится не по измеренной скорости: клиент может объявить себя стоящим'
    );
  });

  it('сервис списывает выносливость, когда сказано, что игрок бежал', () => {
    must(
      /WHEN \$4::boolean/.test(СЕРВИС),
      'в расходе выносливости нет ветки бега'
    );
    must(
      /regenResources\(characterId: string, inWater = false, sprinting = false\)/.test(СЕРВИС),
      'regenResources не принимает признак бега: серверный расход невозможен'
    );
  });

  it('в воде расход за бег не применяется', () => {
    // В воде своя, более дорогая строка. Складывать две траты нельзя: плавание
    // уже учитывает воду через waterStaminaSave.
    must(
      /const бег = inWater \? false : sprinting === true;/.test(СЕРВИС),
      'расход за бег суммируется с плаванием вместо выбора одного'
    );
  });
});

describe('Как это считается на клиенте', () => {
  it('полоса убывает при спринте и не отдыхает', () => {
    must(
      /session\.stamina = Math\.max\(0, session\.stamina - session\.maxStamina \* STAMINA\.SPRINT_DRAIN_PER_SEC \* dt\)/.test(КЛИЕНТ),
      'при спринте выносливость не тратится: удержание Shift бесплатно'
    );
    must(
      /else if \(world3d\?\.isSprinting\(\)\)/.test(КЛИЕНТ),
      'ветки бега нет вовсе: на суше выполняется отдых даже при нажатом Shift'
    );
  });

  it('признак бега совпадает с тем, чем выбирается скорость', () => {
    // Если бы бег считался приседом или в воде, полоса убывала бы стоя.
    must(/isSprinting\(\): boolean/.test(МИР), '3D-слой не умеет сказать, бежит ли игрок');
    must(
      /if \(!this\.sprintAllowed \|\| !this\.me \|\| this\.crouch \|\| this\.swimming\) return false;/.test(МИР),
      'признак бега не учитывает выносливость, присед или воду'
    );
  });
});