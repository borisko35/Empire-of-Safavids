// Абордаж: двойной принцип, а не два отдельных механизма.
//
// Решение владельца: режим выбирает атакующий — PvE (пираты) или PvP (чужая
// лодка). Оба через одно ядро.
//
// ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. Именно симметрия. Всё, что относится к бою
// (дистанция, срок, ошибки, порог уровня), обязано работать одинаково; если
// бы новая возможность или отказ добавлялись в один режим и не доставались
// другому, один из режимов тихо стал бы беднее. Ровно так в проекме уже
// случалось трижды: ключи перевода, рейд-панель и лимиты стека.
//
// Проверка не «в коде есть BoardMode», а то, что каждая возможность
// выражается через тип, общий на оба режима.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ядро = код('server/src/systems/Boarding.ts');
const типы = код('server/src/systems/BoardingTypes.ts');

describe('Абордаж: режимы есть, и их выбирает атакующий', () => {
  it('тип режима объявлен ровно с двумя значениями', () => {
    // Больше — значит ядро разрослось; меньше — двойного принципа нет.
    must(/export type BoardMode = 'pve' \| 'pvp';/.test(типы), 'BoardMode не «pve | pvp»');
  });

  it('режим — часть цели и сессии, а не флаг где попало', () => {
    must(/mode: BoardMode;/.test(типы), 'у цели нет режима: непонятно, что выбираем');
    must(/session\.mode/.test(ядро) || /mode: BoardMode/.test(типы), 'сессия не помнит режим');
  });
});

describe('Абордаж: механика одна на оба режима', () => {
  it('дистанция одна', () => {
    // Отдельное расстояние под PvP сделало бы PvP опасно не боем, а геометрией.
    must(/BOARD_RANGE = 24/.test(типы), 'дистанции нет');
    must(
      /export function boardInRange\([\s\S]*?range = BOARD_RANGE/.test(ядро),
      'у boardInRange нет общего запаса: режимам грозит разная дистанция',
    );
    must(!/pvp.*RANGE|RANGE.*pvp/i.test(код('server/src/systems/BoardingTypes.ts')), 'появилась отдельная дистанция под режим');
  });

  it('срок один', () => {
    must(/BOARD_TIME_LIMIT_MIN = 10/.test(типы), 'срока нет');
    must(/boardAlive\(/.test(ядро), 'проверки живости захода нет');
  });

  it('список ошибок общий', () => {
    // Добавление отказа в один режим невозможно: тип один.
    const м = /export type BoardErrorCode =([\s\S]*?);/.exec(типы);
    must(м !== null, 'тип ошибок не разобран');
    const коды = (м![1].match(/'(board_[a-z_]+)'/g) ?? []).length;
    must(коды >= 8, `ошибок ${коды}: список слишком мал или развалился`);
    // Ни одного имени режима в идентификаторах ошибок: «board_pvp_*»
    // означало бы, что у режимов свои отказы.
    must(!/board_pvp_|board_pve_/.test(типы), 'у режимов свои коды ошибок');
  });

  it('порог уровня разный только для PvP, и это осознанно', () => {
    // PvE-порога нет: монстры не «слабые игроки», а контент.
    must(/pvpLevelGapAllowed\(/.test(ядро), 'порога разрыва уровней нет');
    must(/Math\.abs\(attackerLevel - targetLevel\) <= 10/.test(ядро), 'порог не 10 уровней');
  });

  it('награда умножается только для PvP, в одном месте', () => {
    // Единственная намеренная разница между режимами.
    must(
      /mode === 'pvp' \? baseGold \* BOARD_PVP_REWARD_MULT : baseGold/.test(ядро),
      'награда перестала считаться по режиму в одном месте',
    );
    must(/BOARD_PVP_REWARD_MULT = 2\.5/.test(типы), 'множителя нет');
  });
});

describe('Абордаж: своих не трогаем', () => {
  it('своя лодка — отказ, общей проверкой', () => {
    // В pve цель — монстр, и его id никогда не равен id персонажа; в pvp —
    // другой персонаж. Одна проверка работает в обоих, без ветвления.
    must(/boardSelfRejected\(/.test(ядро), 'проверки «своего» нет');
    must(/board_self/.test(типы), 'кода отказа «своё» нет');
  });

  it('отказ по уровню общий', () => {
    must(/board_level_too_low/.test(типы), 'кода отказа по уровню нет');
  });
});