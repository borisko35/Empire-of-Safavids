// Ночью город расходится по домам (§351).
//
// ЗА ЧТО БОРЕТСЯ. Днище планировки «ночь = меньше NPC» стояло в карте
// задолго до реализации, а город не спал никогда: тридцать горожан ходили,
// болтали и толкались круглые сутки, и полночь не отличалась от полудня ни
// одной душой. Время суток уже управляло светом, фонарями, стражей и
// респавном монстров — только население его не читало.
//
// ПОЧЕМУ ПРОВЕРКА ПО ИСХОДНИКУ. Горожане — клиентский рендер без серверной
// истины: запустить их цикл без браузера нечем. Как и соседние проверки
// (civiliansFollow, civiliansRevive), сторож требует в живом коде ровно тех
// решений, из которых складывается ночная механика, и падает при вычищении
// любого из них.
//
// ГЛАВНАЯ МИНА, которую сторож держит: два цикла видимости (предел 900 м и
// «проявление вернувшихся»). Оба написаны раньше сна и оба ОБЯЗАНЫ будить
// спящего, если забыть про состояние 'сон': первый ставит visible по
// дистанции, второй проявляет всякого невидимого. Уход в дом без этих
// оговорок отменился бы первым же кадром.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const repoRoot = join(__dirname, '..', '..', '..');
const civ = stripComments(readFileSync(join(repoRoot, 'client/src/app/game3d/civilians.ts'), 'utf-8'));
const мир = stripComments(readFileSync(join(repoRoot, 'client/src/app/game3d/world3d.ts'), 'utf-8'));

describe('Ночь: у города есть режим сна', () => {
  it('у горожанина есть состояние сна и флаг «ночует»', () => {
    expect(civ).toMatch(/state: 'idle' \| 'walk' \| 'talk' \| 'сон'/);
    expect(civ).toMatch(/ночует: boolean;/);
  });

  it('ночуют не все: у ночной улицы остаётся жизнь', () => {
    // Все тридцать спят — город ночью мёртв целиком, и стелс-игрок в
    // полночь ходит по декорациям, а не по городу.
    expect(civ).toMatch(/ночует: i % 4 !== 0/);
  });

  it('режим переключается фактом ночи из пакета, а не своим расписанием', () => {
    // Своя арифметика часов рядом с world:time — та же мина, что и всякая
    // копия справочника: сервер сменит границы суток, клиент не заметит.
    expect(civ).toMatch(/night\?: number/);
    expect(civ).toMatch(/const режимНочи = \(night \?\? 0\) >= 1/);
    // и провод жив: мир передаёт night в горожан тем же вызовом, что и
    // позицию игрока
    expect(мир).toMatch(/civilians\.update\(dt, now, me\.pos\.x, me\.pos\.z, night\)/);
  });

  it('уход в дом идёт через улицу, а не выключателем', () => {
    // Ночью ночующий идёт именно к своему дому, а не замирает и не
    // переносится: дом у него свой с §289, и дверь настоящая.
    expect(civ).toMatch(/c\.target = \{ x: c\.homeX, z: c\.homeZ \}/);
    // У двери — исчезает: состояние сна ставится вместе с visible=false.
    expect(civ).toMatch(/c\.state = 'сон';\s*\n\s*c\.group\.visible = false;/);
    // Стоящие не исчезают одним кадром: каждому отложен свой срок.
    expect(civ).toMatch(/stateUntil = now \+ Math\.random\(\) \* 45000/);
  });

  it('спящий невидим для обоих циклов видимости', () => {
    // Предел 900 м обязан учитывать сон...
    expect(civ).toMatch(/visible = dist < LEASH && now >= c\.hiddenUntil && c\.state !== 'сон'/);
    // ...и «проявление вернувшихся» тоже: иначе оно выведет спящего из
    // дома на первом же кадре.
    expect(civ).toMatch(/if \(c\.state === 'сон'\) continue;\s*\n\s*c\.group\.visible = true;/);
  });

  it('спящий не мешает живым', () => {
    // Коллайдер невидимки — стена из ничего посреди улицы.
    expect(civ).toMatch(/if \(c\.state === 'сон'\) continue;\s*\n\s*CIV_COLLIDERS\.push/);
    // И разговоров на ночь не хватает: ночующий по пути домой не должен
    // останавливаться поболтать, иначе застынет посреди улицы навсегда.
    expect(civ).toMatch(/c\.state !== 'talk' && c\.state !== 'сон' && !\(ночнойРежим && c\.ночует\)/);
  });

  it('на рассвете спящие возвращаются сами, а не проявлением', () => {
    // Обратное переключение будит именно спящих: visible=true в блоке
    // смены режима.
    expect(civ).toMatch(/} else if \(c\.state === 'сон'\) \{\s*\n\s*c\.state = 'idle';\s*\n\s*c\.group\.visible = true;/);
  });
});
