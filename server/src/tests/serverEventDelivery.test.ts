// Событие, которое сервер отдал, а клиент не слушает, пропадает молча.
//
// ЧТО БЫЛО. Три события из SERVER_EVENTS отправлялись из
// GameSocketHandler, но в клиенте не было ни одного обработчика:
// dungeon:completed, karma:changed, world:event. Игрок проходил
// подземелье — опыт и золото приходили на руки молча, без объяснения.
// Менялся статус кармы (с нейтрального на красный) — молча. Появлялся
// мировой босс — молча.
//
// ПОЧЕМУ НИКТО НЕ ЗАМЕТИЛ. Событие нигде не пропадало с ошибкой: сервер
// отправлял его успешно, сокет его доставлял, клиент его отбрасывал. Все
// три имени при этом были объявлены в SERVER_EVENTS с комментариями о
// смысле — то есть код выглядел законченным.
//
// КАК ПРОВЕРЯЕМ. Берём таблицу SERVER_EVENTS, ищем по всему серверу все
// места отправки, и по всему клиенту все места подписки — включая
// подписку через константу (socket.on(SERVER_EVENTS.X)) и через
// переменную в цикле (chat-каналы). Каждое отправленное событие должно
// иметь приёмника.
//
// ЛОВУШКА, КОТОРУЮ ЭТА ПРОВЕРКА ОБХОДИТ. Наивная проверка ищет в
// клиенте строковый литерал и на этом успокаивается. Но клиент
// подписывается и через константу, и через переменную цикла — раньше
// respawn:error и daily:task выглядели «необработанными», хотя
// обрабатывались. Проверка обязана видеть обе формы, иначе она
// заставит чинить несуществующее.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Все файлы .ts/.js в каталоге, кроме тестов */
function файлы(dir: string): string[] {
  const out: string[] = [];
  for (const имя of readdirSync(dir)) {
    const полный = join(dir, имя);
    if (statSync(полный).isDirectory()) out.push(...файлы(полный));
    else if (/\.(ts|js)$/.test(имя) && !имя.endsWith('.test.ts')) out.push(полный);
  }
  return out;
}

/**
 * Таблица констант вида `KEY: 'value'` → Map. Считает только строковые
 * значения: REDIS_CHANNELS содержит и функции, их сюда брать нельзя.
 */
function таблица(исходник: string, имя: string): Map<string, string> {
  const i = исходник.indexOf(`export const ${имя}`);
  must(i >= 0, `В constants.ts нет таблицы ${имя}`);
  const начало = исходник.indexOf('{', i);
  let глубина = 0;
  let конец = -1;
  for (let j = начало; j < исходник.length; j++) {
    if (исходник[j] === '{') глубина++;
    else if (исходник[j] === '}') {
      глубина--;
      if (глубина === 0) { конец = j; break; }
    }
  }
  must(конец > начало, `Не нашёл закрывающую скобку таблицы ${имя}`);
  const map = new Map<string, string>();
  for (const m of исходник.slice(начало, конец).matchAll(/([A-Z0-9_]+)\s*:\s*'([^']*)'/g)) {
    map.set(m[1], m[2]);
  }
  must(map.size > 0, `Таблица ${имя} разобралась пустой — регулярка устарела`);
  return map;
}

const КОНСТАНТЫ = readFileSync(join(корень, 'shared/constants.ts'), 'utf-8');
const SERVER_EVENTS = таблица(КОНСТАНТЫ, 'SERVER_EVENTS');
const SOCKET_EVENTS = таблица(КОНСТАНТЫ, 'SOCKET_EVENTS');

/** Где сервер отправляет: имя константы → файл */
function отправкиСервера(): Map<string, string> {
  const найдено = new Map<string, string>();
  for (const файл of файлы(join(корень, 'server/src'))) {
    const код = readFileSync(файл, 'utf-8');
    // emit(SERVER_EVENTS.ИМЯ) и emit(SOCKET_EVENTS.ИМЯ).
    //
    // ВАЖНО: обе таблицы, а не только SERVER_EVENTS. Первая версия этой
    // проверки искала только SERVER_EVENTS, и потому объявляла события,
    // отправляемые через SOCKET_EVENTS, неотправленными - то есть
    // требовала переименовать или удалить работающее. События партии,
    // аукциона и баунти живут именно в SOCKET_EVENTS.
    for (const m of код.matchAll(/\.emit\(\s*(?:SERVER_EVENTS|SOCKET_EVENTS)\.([A-Z0-9_]+)/g)) {
      if (!найдено.has(m[1])) найдено.set(m[1], файл);
    }
    // Отправка по переменной: emit(событие, ...), куда событие - второй
    // аргумент вызова метода-помощника
    //   await переслатьУчастникам(REDIS_CHANNELS.X, SOCKET_EVENTS.Y, ...)
    // Без этого событие партии считалось неотправленным, хотя партия
    // менялась и доходила до игроков.
    for (const вызов of код.matchAll(/(?:переслатьУчастникам|отправить|рассылка)\(\s*[^,)]+\s*,\s*(?:SERVER_EVENTS|SOCKET_EVENTS)\.([A-Z0-9_]+)/g)) {
      if (!найдено.has(вызов[1])) найдено.set(вызов[1], файл);
    }
  }
  return найдено;
}

/** Где клиент слушает: имя события (строка) → файл */
function подпискиКлиента(): Map<string, string> {
  const найдено = new Map<string, string>();
  for (const файл of файлы(join(корень, 'client/src'))) {
    const код = readFileSync(файл, 'utf-8');
    // 1) socket.on('имя', ...) — литерал
    for (const m of код.matchAll(/\.on\(\s*'([^']+)'/g)) {
      if (!найдено.has(m[1])) найдено.set(m[1], файл);
    }
    // 2) socket.on(SERVER_EVENTS.ИМЯ, ...) — через константу
    for (const m of код.matchAll(/\.on\(\s*(?:SERVER_EVENTS|SOCKET_EVENTS)\.([A-Z0-9_]+)/g)) {
      const значение = SERVER_EVENTS.get(m[1]) ?? SOCKET_EVENTS.get(m[1]);
      must(значение, `Клиент подписан на ${m[1]}, которого нет ни в одной таблице событий`);
      if (!найдено.has(значение!)) найдено.set(значение!, файл);
    }
    // 3) Цикл подписки. Две формы, и обе нужны:
    //    for (const ev of ['a','b']) socket.on(ev, ...)
    //    for (const ev of chatEvents) socket.on(ev, ...) — где сам массив
    //    объявлен выше константой. Без второй формы четыре вида чата
    //    считались необработанными, хотя клиент их слушает: проверка
    //    врала бы и заставила чинить рабочее.
    const массивы = new Map<string, string[]>();
    for (const m of код.matchAll(/(?:const|let)\s+(\w+)\s*(?::[^=]+)?=\s*(\[[\s\S]{0,600}?\])\s*(?:as const)?\s*[;,]/g)) {
      массивы.set(m[1], [...m[2].matchAll(/'([^']+)'/g)].map((x) => x[1]));
    }
    for (const цикл of код.matchAll(/for\s*\(\s*const\s+(\w+)\s+of\s+(\[[\s\S]{0,400}?\]|\w+)\s*\)/g)) {
      const тело = код.slice(цикл.index ?? 0, (цикл.index ?? 0) + цикл[0].length + 400);
      if (!/\.on\(/.test(тело)) continue;
      const список = цикл[2].startsWith('[')
        ? [...цикл[2].matchAll(/'([^']+)'/g)].map((x) => x[1])
        : массивы.get(цикл[2]) ?? [];
      // Цикл по массиву констант, а не по строкам — подписка идёт по
      // SOCKET_EVENTS.X через переменную. Тогда берём имена констант
      // и переводим их через таблицу.
      if (цикл[2].startsWith('[') && /\w*[Ee]vents\b/.test(цикл[2])) {
        for (const m of цикл[2].matchAll(/([A-Z0-9_]+)/g)) {
          const значение = SERVER_EVENTS.get(m[1]) ?? SOCKET_EVENTS.get(m[1]);
          if (значение && !найдено.has(значение)) найдено.set(значение, файл);
        }
        continue;
      }
      for (const имя of список) {
        if (!найдено.has(имя)) найдено.set(имя, файл);
      }
    }
  }
  return найдено;
}

const отправляется = отправкиСервера();
const слушается = подпискиКлиента();

describe('События сервера доходят до клиента', () => {
  it('сканер вообще видит отправку и подписку', () => {
    // Проверка на сам сканер. Предыдущие версии аудита рапортовали
    // «ресурсы не отправляются» и «подписок нет» — потому что искали
    // строковый литерал там, где стояла константа. Ноль находится
    // раньше, чем список, и выглядит как чистота.
    must(
      отправляется.size >= 10,
      `Сканер нашёл всего ${отправляется.size} отправок. Их правда больше десятка, значит регулярка не ловит форму отправки и любой список ниже — пустота.`,
    );
    must(
      слушается.size >= 20,
      `Сканер нашёл всего ${слушается.size} подписок. Их правда больше двадцати, значит регулярка не ловит форму подписки.`,
    );
  });

  it('каждое отправленное событие имеет приёмника в клиенте', () => {
    const потерянные: string[] = [];
    for (const [константа, файл] of отправляется) {
      const событие = SERVER_EVENTS.get(константа) ?? SOCKET_EVENTS.get(константа);
      must(событие, `Сервер отправляет ${константа}, а такого события нет в таблицах`);
      if (!слушается.has(событие!)) потерянные.push(`${событие} (${константа}, отправка из ${файл})`);
    }
    must(
      потерянные.length === 0,
      `Сервер отдаёт эти события, но клиент их не слушает — сообщения пропадают молча:\n  ${потерянные.join('\n  ')}`,
    );
  });

  it('все ключи перевода для этих событий есть во всех трёх языках', () => {
    // Обработчик показывает t('...') — если ключа нет, игрок читает
    // путь ключа вместо текста. Проверяем именно используемые ключи.
    const используемые = [
      'dungeon.completed',
      'dungeon.completed_generic',
      'karma.status_changed',
      'world_event.boss_started',
      'world_event.boss_defeated',
      // Партия, аукцион, баунти, админские действия
      'party.members_changed',
      'party.you_joined',
      'party.you_left',
      'party.disbanded',
      'auction_notice.new_listing',
      'bounty.placed',
      'admin.muted',
      'admin.teleported',
      'admin.item_given',
      // Подписи, которые переиспользуются в новых сообщениях
      'world.gold',
      'world.exp',
    ];
    const статусы = ['saint', 'good', 'neutral', 'chaotic', 'red', 'outlaw'];
    for (const статус of статусы) используемые.push(`karma.status.${статус}`);

    function значение(словарь: Record<string, unknown>, путь: string): unknown {
      return путь.split('.').reduce<unknown>(
        (узел, ключ) => (узел == null ? undefined : (узел as Record<string, unknown>)[ключ]),
        словарь,
      );
    }

    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(
        readFileSync(join(корень, 'shared/locales', `${язык}.json`), 'utf-8'),
      ) as Record<string, unknown>;
      const нет: string[] = [];
      for (const ключ of используемые) {
        if (typeof значение(словарь, ключ) !== 'string') нет.push(ключ);
      }
      must(
        нет.length === 0,
        `В языке ${язык} нет ключей: ${нет.join(', ')}. Игрок увидит путь ключа вместо текста.`,
      );
    }
  });

  it('клиент слушает все события, которые сервер шлёт поимённо', () => {
    // Обратная сторона: не только «сервер шлёт, клиент молчит», но и
    // проверка, что три починенных события действительно на месте.
    // Точечная проверка по одному имени холостая, поэтому берём весь
    // список событий, которые сервер отправляет, и сверяем целиком.
    must(
      SERVER_EVENTS.get('DUNGEON_COMPLETED') === 'dungeon:completed',
      'Событие подземелия переименовано, а клиент на старом имени',
    );
    must(
      SERVER_EVENTS.get('KARMA_CHANGED') === 'karma:changed',
      'Событие кармы переименовано, а клиент на старом имени',
    );
    must(
      SERVER_EVENTS.get('WORLD_EVENT') === 'world:event',
      'Событие мировых событий переименовано, а клиент на старом имени',
    );
  });
});
