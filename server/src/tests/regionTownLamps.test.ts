// Фонари в городах регионов.
//
// ЧТО БЫЛО (21 октября 2026, §250). В городах регионов были стены, дома, ряды
// и колодец — и НИ ОДНОГО источника света. Ночью такой город стоял тёмным
// силуэтом: игрок, выбравший регион, возрождался у ворот и не видел ничего.
//
// ЧТО ТЕПЕРЬ. Два фонаря на город — у колодца на площади и у ворот. Фонарь
// тот же, что и в столице (§232), со стеклом и огнём. Источники создаёт
// world3d: свет — его дело, там же ночное правило.
//
// ЧТО ПРОВЕРЯЕТСЯ. Фонари стоят в городах регионов (а не только в столице),
// построены общим фонарём, координаты огней — мировые, и для каждого огня
// создаётся источник света по ночному правилу.
//
// Проверка смотрит ТОЛЬКО свои разделы кода: строки фонарей в городе совпадают
// слово в слово, и без границы проверка цепляла бы чужой блок (см. §247).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

/** Кусок кода своего раздела: метки разделов — комментарии, ищем по исходнику. */
function свойРаздел(код: string, начало: string, конец: string): string {
  const от = код.indexOf(начало);
  должен(от >= 0, `в коде нет раздела «${начало}»`);
  const до = код.indexOf(конец, от);
  должен(до > от, `в коде нет раздела «${конец}» после «${начало}»`);
  return код.slice(от, до).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const ГОРОДА = свойРаздел(
  ТЕРРЕЙН,
  '// ── Фонари: у колодца и у ворот (§250)',
  '// ── Зелень по кольцу, кроме сектора ворот',
);
const ИСТОЧНИКИ = свойРаздел(
  МИР,
  '// Фонари городов регионов (§250)',
  '// Указатели сбоку от дорог',
);

describe('Фонари в городах регионов', () => {
  it('в каждом городе региона два фонаря — у колодца и у ворот', () => {
    должен(
      /for \(const \[lx, lz\] of \[\[0, -t\.radius \* 0\.46\], \[0, t\.radius \* 0\.82\]\] as const\)/.test(ГОРОДА),
      'фонарей в городах региона не два',
    );
    должен(
      /const высотаОгня = фонарь\(g, lx, lz\);/.test(ГОРОДА),
      'фонари городов региона построены своими столбами без стекла',
    );
  });

  it('координаты огней — мировые, с высотой огня', () => {
    должен(
      /огни\.push\(\{ x: t\.x \+ lx, y: baseY \+ высотаОгня, z: t\.z \+ lz \}\)/.test(ГОРОДА),
      'координаты огней не мировые: источник света окажется не там',
    );
    должен(
      /buildRegionTowns\(scene: THREE\.Scene\): \{ x: number; y: number; z: number \}\[\]/.test(ТЕРРЕЙН),
      'buildRegionTowns не возвращает огни: источники света создать не из чего',
    );
  });

  it('источники создаются и горят по ночному правилу', () => {
    должен(
      /const огниГородов = buildRegionTowns\(this\.scene\);/.test(МИР),
      'огни городов региона не берутся из террейна',
    );
    // Источники создаются ИМЕННО по списку огней террейна: если перебрать
    // что-то другое (или ничего), фонарей в городах не будет, а код останется.
    должен(
      /for \(const \[i, огонь\] of огниГородов\.entries\(\)\)/.test(ИСТОЧНИКИ),
      'источники света не создаются по списку огней террейна',
    );
    должен(
      /const light = new THREE\.PointLight\(0xffa04a, 0, 20, 1\.8\);/.test(ИСТОЧНИКИ),
      'источники света городов региона не создаются',
    );
    должен(
      /this\.scene\.add\(light\);/.test(ИСТОЧНИКИ),
      'источники света городов региона не добавлены в сцену',
    );
    // Факелы: днём тише, ночью в полную силу.
    должен(
      /this\.torches\.push\(\{ light, base: 1\.6, phase: i \* 2\.4 \+ 0\.7 \}\)/.test(ИСТОЧНИКИ),
      'фонари городов региона не горят по ночному правилу',
    );
  });
});
