// Пыль из-под копыт и дым от огней.
//
// ЧТО БЫЛО (21 октября 2026, §255). Караван шёл по песку и не поднимал пыли,
// а костёр в лагере и факелы у караван-сарая не дымили. Огонь без дыма и
// движение без пыли читаются как мир из пластика.
//
// ЧТО ТЕПЕРЬ. Пул короткоживущих клубов на каждое место: у копыт — пыль, у
// больших огней — дым. Клуб живёт недолго, растёт, бледнеет и уходит.
//
// ЧТО ПРОВЕРЯЕТСЯ. Клубы вообще есть и живут своей жизнью (пул, рост, затухание);
// пыль поднимается у копыт верблюдов; дым идёт от костра в лагере и от
// факелов караван-сарая; и всё это обновляется и вычищается при разборке.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const КЛУБЫ = читать('client/src/app/game3d/puffs.ts');
const ДОРОГИ = читать('client/src/app/game3d/roadTraffic.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

/** Размер пула клубов у места: ищет createPuffs после метки и берёт число. */
function пул(код: string, метка: string): number {
  const i = код.indexOf(метка);
  должен(i >= 0, `не найдено место «${метка}»`);
  const кусок = код.slice(i, i + 900);
  const m = /createPuffs\([\s\S]{0,300}?количество: (\d+)/.exec(кусок);
  должен(m, `у места «${метка}» не задан размер пула клубов`);
  return Number(m![1]);
}

describe('Пыль и дым', () => {
  it('клубы живут своей жизнью: растут, бледнеют и уходят', () => {
    должен(/export function createPuffs/.test(КЛУБЫ), 'нет модуля клубов');
    // Клуб растёт...
    должен(/const размер = к\.база \+ opts\.рост \* \(1 - доля\);/.test(КЛУБЫ),
      'клуб не растёт');
    // ...и бледнеет.
    должен(/непрозрачность \* Math\.pow\(доля, opts\.затухание \?\? 2\)/.test(КЛУБЫ),
      'клуб не бледнеет');
    // ...и уходит, а не живёт вечно.
    должен(/к\.sprite\.visible = false;/.test(КЛУБЫ), 'клуб не исчезает');
    // Пул конечный: клубов не больше заданного.
    должен(/for \(let i = 0; i < opts\.количество; i\+\+\)/.test(КЛУБЫ), 'пул клубов не ограничен');
  });

  it('пыль поднимается у копыт верблюдов', () => {
    // Верблюд помечен флагом копытного: у модели нет ног, по которым фильтр
    // старого сборщика отличал зверя от путника.
    должен(
      /column\.filter\(w => w\.копытный\)/.test(ДОРОГИ),
      'пыль каравана не привязана к копытным: клубы пойдут и под путниками',
    );
    должен(
      /караваны\.push\(\{ верблюды: column\.filter\(w => w\.копытный\), пыль, таймер: 0 \}\);/.test(ДОРОГИ),
      'пыль не собирается в караваны',
    );
  });

  it('дым идёт от костра в лагере и от факелов караван-сарая', () => {
    должен(/private дым: \{ дым: Puffs; x: number; y: number; z: number; таймер: number \}\[\] = \[\];/.test(МИР),
      'у движка нет списка дымов');
    // Костёр в лагере.
    должен(пул(МИР, '// Дым над костром (§255)') > 0, 'над костром в лагере нет дыма');
    // Факелы у караван-сарая.
    должен(пул(МИР, '// Дым над факелом (§255)') > 0, 'над факелами караван-сарая нет дыма');
    // Дым появляется и обновляется каждый кадр.
    должен(/д\.дым\.всплеск\(д\.x, д\.y, д\.z\)/.test(МИР), 'дым не появляется');
    должен(/д\.дым\.update\(dt\)/.test(МИР), 'дым не обновляется');
    должен(/for \(const д of this\.дым\) д\.дым\.dispose\(\);/.test(МИР), 'дым не вычищается');
  });
});
