// Мини-карта по выбору владельца: поворот по взгляду игрока.
//
// ЧТО ПРОВЕРЯЕТСЯ И ПОЧЕМУ ТАК.
//
// 1. Угол поворота. Знак угла легко перепутать: с осью z вниз на экране
//    поворот равен yaw, а не -yaw. Проверка считает это самостоятельно: берёт
//    вектор взгляда из замеров движения (-sin yaw, -cos yaw) и поворачивает его
//    на угол из кода. Если знак поменяется, карта будет вверх ногами, и это
//    заметно только в игре — значит проверка обязана считать, а не читать текст.
//
// 2. Запас под поворот. Выборка рельефа рисуется квадратом на холст. Поворот на
//    45° требует, чтобы сторона была не меньше диагонали: иначе по углам
//    пустота и биом обрывается. Проверка сравнивает константу с √2.
//
// 3. Масштаб не поехал. Запас добавлен и к мировым единицам, и к пикселям
//    слоя: если расширить только одно, рельеф уедет относительно маркеров или
//    карта станет мыльнее. Проверка следит за обоими.
//
// 4. Стрелка игрока не вращается. Она нарисована остриём вверх и после поворота
//    означает направление взгляда; внутри поворота она крутилась бы и смотрела
//    вбок. Проверка сверяет, что поворот закрывается ДО стрелки.
//
// 5. Два бага, найденных замером и починенных попутно: вызов мини-карты не
//    передавал NPC и маршрут (маршрут не рисовался никогда), и подпись региона
//    не писалась никуда при живом элементе в разметке.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const hud = читать('client/src/app/hud.ts');
const world = читать('client/src/app/world.ts');
const разметка = читать('client/src/app/index.html');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Мини-карта: поворот по взгляду', () => {
  it('запас подложки не меньше диагонали, иначе по углам пустота', () => {
    const найдено = /const MINIMAP_OVERSCAN = ([\d.]+);/.exec(hud);
    must(найдено, 'нет константы MINIMAP_OVERSCAN: поворот без запаса оставит пустые углы');
    const запас = Number(найдено![1]);
    must(
      запас >= Math.SQRT2,
      `запас ${запас} меньше диагонали ${Math.SQRT2.toFixed(3)}: при повороте на 45° ` +
        'по углам холста будет пусто, а биом оборвётся по краю'
    );
  });

  it('запас добавлен и к миру, и к пикселям: масштаб не должен поехать', () => {
    must(
      /const extent = \(MINIMAP_RANGE \* 2 \+ TERRAIN_PAD \* 2\) \* MINIMAP_OVERSCAN;/.test(hud),
      'слой не расширен по мировым единицам: либо пустые углы, либо мыло'
    );
    must(
      /const layerPx = Math\.round\(size \* MINIMAP_OVERSCAN\)/.test(hud),
      'слой не расширен по пикселям: та же самая местность станет мыльнее'
    );
    // Расширение только по одной стороне и есть поломка масштаба.
    const расширений = (hud.match(/MINIMAP_OVERSCAN/g) || []).length;
    must(
      расширений >= 5,
      `MINIMAP_OVERSCAN встречается ${расширений} раз: похоже, одно из применений потерялось`
    );
  });

  it('слой центрируется на игроке, а не на своём краю', () => {
    // Расширили слой — центр сдвинулся бы, и пересборка перестала бы срабатывать:
    // карта ехала бы за игроком и показывала чужой мир.
    must(
      /const ox = snap\(cx\) - extent \/ 2;/.test(hud) && /const oz = snap\(cz\) - extent \/ 2;/.test(hud),
      'слой считается от края, а не от центра: после расширения игрок уедет из середины карты'
    );
    must(
      /Math\.abs\(me\.x - \(terrainOrigin\.x \+ terrainExtent \/ 2\)\)/.test(hud),
      'пересборка слоя сверяется с краем, а не с центром: карта перестанет перерисовываться'
    );
  });

  it('выборка кладётся с запасом и остаётся по центру', () => {
    must(
      /const swЗапас = sw \* MINIMAP_OVERSCAN;/.test(hud),
      'выборка не расширена: поворот отрежет углы'
    );
    must(
      /-выносСлоя, -выносСлоя, size \* MINIMAP_OVERSCAN/.test(hud),
      'расширенный слой не вынесен за холст: игрок сместится из центра'
    );
  });

  it('угол поворота равен yaw камеры, а не отрицанию', () => {
    // Поворот холста на угол θ переводит вектор (a,b) в
    // (a cos θ − b sin θ, a sin θ + b cos θ). Взгляд по замерам движения —
    // (−sin yaw, −cos yaw). Подставить θ = yaw должно дать ровно вверх (0,−1).
    for (const yaw of [0, 0.7, Math.PI / 2, Math.PI, 2.9, -1.4]) {
      const fx = -Math.sin(yaw);
      const fz = -Math.cos(yaw);
      const повёрнутыйX = fx * Math.cos(yaw) - fz * Math.sin(yaw);
      const повёрнутыйY = fx * Math.sin(yaw) + fz * Math.cos(yaw);
      must(
        Math.abs(повёрнутыйX) < 1e-9,
        `при yaw ${yaw} взгляд ушёл вбок на ${повёрнутыйX}: знак угла перепутан`
      );
      must(
        Math.abs(повёрнутыйY + 1) < 1e-9,
        `при yaw ${yaw} взгляд смотрит на ${повёрнутыйY}, а должен быть вверх (−1)`
      );
    }
    // И код обязан использовать именно этот угол.
    must(
      /ctx\.rotate\(yaw\);/.test(hud),
      'угол камеры в поворот не подставлен: карта остаётся севером вверх'
    );
    must(
      /world3d\?\.getCameraPose\(\)\.yaw \?\? 0/.test(world),
      'цикл игры не передаёт угол взгляда в мини-карту'
    );
  });

  it('угол приходит из камеры, а не из направления движения', () => {
    // Направление движения — прошлое, камера — настоящее. Если взять движение,
    // карта дёргалась бы на месте после остановки.
    must(
      !/updateMinimap\([\s\S]{0,400}moveDir/.test(world),
      'в мини-карту попал направление движения: после остановки она дёргалась бы'
    );
    must(/getCameraPose\(\)/.test(world), 'угол взгляда не берётся из позы камеры');
  });

  it('стрелка игрока и рамка не вращаются вместе с картой', () => {
    const позицияRestore = hud.indexOf('ctx.restore();', hud.indexOf('ctx.save();\n  ctx.translate(size / 2, size / 2);'));
    const позицияСтрелки = hud.indexOf('// Игрок в центре');
    must(позицияRestore > 0, 'поворот нигде не закрывается');
    must(
      позицияRestore < позицияСтрелки,
      'поворот не закрыт до стрелки игрока: стрелка будет крутиться и смотреть вбок'
    );
    must(
      /ctx\.save\(\);\s*\n\s*ctx\.translate\(nx, ny\);\s*\n\s*ctx\.rotate\(yaw\);/.test(hud),
      'стрелка севера не повернута вместе с картой: будет смотреть не туда'
    );
  });

  it('холст не остаётся повёрнутым или сломанным', () => {
    const save = (hud.match(/ctx\.save\(\);/g) || []).length;
    const restore = (hud.match(/ctx\.restore\(\);/g) || []).length;
    must(
      save === restore,
      `save вызван ${save} раз, restore ${restore}: лишний save навсегда оставит карту повёрнутой`
    );
  });

  it('север помечен: без метки игрок теряет ориентир', () => {
    must(
      /const nx = size \/ 2 \+ Math\.sin\(yaw\) \* радиусСевера;/.test(hud) &&
        /const ny = size \/ 2 - Math\.cos\(yaw\) \* радиусСевера;/.test(hud),
      'метка севера не считается из угла: игрок не видит, где север'
    );
    // При нулевом повороте север вверху — как было до правки.
    must(
      hud.includes("t('map.north')"),
      'метка севера не подписана буквой'
    );
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(словарь.map?.north, `${код}.json: нет map.north`);
    }
  });

  it('позиция метки севера считается верно', () => {
    // Север мира — это −z. После поворота на yaw его экранное направление:
    // (sin yaw, −cos yaw). Проверяем на нескольких углах, что метка стоит на
    // радиусе от центра и там, куда указывает север, а не куда попало.
    for (const yaw of [0, 1.2, Math.PI / 2, Math.PI]) {
      const радиусСевера = 90 - 9;
      const nx = 90 + Math.sin(yaw) * радиусСевера;
      const ny = 90 - Math.cos(yaw) * радиусСевера;
      const расстояние = Math.hypot(nx - 90, ny - 90);
      must(
        Math.abs(расстояние - радиусСевера) < 1e-9,
        `при yaw ${yaw} метка ушла с радиуса карты: расстояние ${расстояние}`
      );
      // Север по вектору (0,−1) в мире должен совпасть с местом метки.
      must(
        Math.abs(Math.sin(yaw) - (nx - 90) / радиусСевера) < 1e-9 &&
          Math.abs(-Math.cos(yaw) - (ny - 90) / радиусСевера) < 1e-9,
        `при yaw ${yaw} метка севера стоит не в ту сторону`
      );
    }
  });
});

describe('Мини-карта: два бага, найденных замером', () => {
  it('NPC и маршрут передаются в мини-карту', () => {
    // Раньше вызов отдавал только игрока и монстров, поэтому зелёные точки NPC
    // и пунктир до цели не рисовались НИКОГДА, хотя код для них был.
    const вызов = world.slice(world.indexOf('updateMinimap('), world.indexOf('updateMinimap(') + 700);
    must(
      вызов.includes('NPC_WORLD_POSITIONS'),
      'NPC не передаются в мини-карту: зелёных точек нет никогда'
    );
    must(
      вызов.includes('getNavRoute()'),
      'маршрут не передаётся в мини-карту: пунктир до цели не рисуется'
    );
    // Большая карта передаёт то же самое — иначе расхождение между двумя картами.
    // Ищем ОПРЕДЕЛЕНИЕ функции: первое вхождение имени — это обработчик клавиши M,
    // и в нём никаких данных нет. Проверка на «первое вхождение» в файле такого
    // вида молча смотрела не туда.
    const определение = world.indexOf('function redrawWorldMap(');
    must(определение > 0, 'не нашёл определение redrawWorldMap');
    const большая = world.slice(определение, определение + 700);
    must(
      большая.includes('NPC_WORLD_POSITIONS') && большая.includes('getNavRoute()'),
      'большая карта передаёт больше данных, чем мини-карта: они разошлись'
    );
  });

  it('подпись региона пишется, а не висит пустой', () => {
    must(
      разметка.includes('id="minimap-region"'),
      'в разметке нет плашки подписи региона'
    );
    must(
      /const regionLabel = updateMinimap\(/.test(world),
      'возвращаемое значение мини-карты отбрасывается: подпись региона пустая'
    );
    must(
      /getElementById\('minimap-region'\)/.test(world),
      'подпись региона никуда не пишется'
    );
    // Плашка прячется, когда региона нет, иначе над картой висит пустая полоса.
    must(
      /regionEl\.classList\.toggle\('hidden', !regionLabel\)/.test(world),
      'пустая плашка подписи остаётся видимой'
    );
  });

  it('подпись не переводится второй раз', () => {
    // updateMinimap отдаёт уже переведённое название. Повторный t() на строке
    // вернул бы сам ключ игроку.
    must(
      !/t\(regionLabel\)/.test(world),
      'подпись прогоняется через перевод второй раз'
    );
  });
});