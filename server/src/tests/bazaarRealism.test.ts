// Базарные прилавки перестают быть ящиками.
//
// ЧТО БЫЛО (22 октября 2026, §290). Прилавок был ящиком 3×1×1.6 без ножек, под
// ним — плоская наклонённая плита вместо навеса, кувшины — цилиндры, ящики —
// сплошные бруски. Лавка читалась как коробка с плоской крышей.
//
// ЧТО ТЕПЕРЬ. Столешница на четырёх ножках с полкой снизу; навес — дуга из
// полотна (своя геометрия, дуга вверх, полотно двустороннее) с бахромой;
// кувшины — гончарные (тело вращением профиля, горло, ручка); ящики — из реек
// с щелями; корзина — плетёная, с ободком и дужкой.
//
// ЧТО ПРОВЕРЯЕТСЯ. У прилавка есть ножки, полка и полотняный навес-дуга;
// кувшины гончарные; ящики из реек; корзина с ободком и дужкой.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Прилавки — не ящики', () => {
  it('стол на ножках, с полкой', () => {
    // Столешница — тонкая, а не ящик во всю высоту.
    должен(
      /const table = new THREE\.Mesh\(new THREE\.BoxGeometry\(3, 0\.12, 1\.6\)/.test(ТЕРРЕЙН),
      'столешница прилавка не тонкая: это ящик',
    );
    // Ножки.
    должен(/const ножка = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.07, 0\.09, 0\.94, 6\)/.test(ТЕРРЕЙН),
      'у прилавка нет ножек');
    // Полка снизу.
    должен(/const полка = new THREE\.Mesh\(new THREE\.BoxGeometry\(2\.7, 0\.08, 1\.2\)/.test(ТЕРРЕЙН),
      'у прилавка нет полки');
    // Ящика-стола быть не должно.
    должен(!/new THREE\.BoxGeometry\(3, 1, 1\.6\)/.test(ТЕРРЕЙН), 'стол прилавка снова ящик');
  });

  it('навес — дуга из полотна, а не плита', () => {
    // Своя геометрия дуги: поворотами цилиндра дуга вставала боком.
    должен(
      /const геометрияНавеса = new THREE\.BufferGeometry\(\);/.test(ТЕРРЕЙН),
      'навес прилавка не дуга',
    );
    // Дуга идёт от края через верх к краю.
    должен(
      /const a = -Math\.PI \/ 2 \+ \(Math\.PI \* i\) \/ дуг;/.test(ТЕРРЕЙН),
      'дуга навеса не поднята над столом',
    );
    // Полотно двустороннее: из-под навеса его видно.
    должен(/полотно\.side = THREE\.DoubleSide;/.test(ТЕРРЕЙН), 'навес односторонний');
    // Бахрома по краю.
    должен(/const бахрома = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.06, 0\.22, 0\.3\)/.test(ТЕРРЕЙН),
      'у навеса нет бахромы');
    // Плоской плиты вместо навеса быть не должно.
    должен(!/new THREE\.BoxGeometry\(3\.4, 0\.2, 2\.4\)/.test(ТЕРРЕЙН), 'навес снова плита');
  });

  it('кувшины гончарные: тело, горло, ручка', () => {
    // Тело — вращение профиля.
    должен(
      /const кувшин = new THREE\.Mesh\(new THREE\.LatheGeometry\(профиль, 9\)/.test(ТЕРРЕЙН),
      'кувшин не гончарный: это цилиндр',
    );
    // Горло и ручка.
    должен(/const горло = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.075, 0\.095, 0\.11, 7\)/.test(ТЕРРЕЙН),
      'у кувшина нет горла');
    должен(
      /const ручка = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.075, 0\.018, 5, 10, Math\.PI\)/.test(ТЕРРЕЙН),
      'у кувшина нет ручки',
    );
    // Старых цилиндров-кувшинов быть не должно.
    должен(
      !/const jar = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.14, 0\.2, 0\.42, 7\)/.test(ТЕРРЕЙН),
      'кувшины снова цилиндры',
    );
  });

  it('ящики из реек, корзина с ободком и дужкой', () => {
    // Ящик: угловые стойки и планки с щелями.
    должен(/const стойка = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.07, h, 0\.07\)/.test(ТЕРРЕЙН),
      'у ящика нет стоек');
    должен(/const бок = new THREE\.Mesh\(new THREE\.BoxGeometry\(w, h \* 0\.3, 0\.05\)/.test(ТЕРРЕЙН),
      'у ящика нет планок');
    // Корзина.
    должен(
      /const корзина = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.34, 0\.24, 0\.4, 10\)/.test(ТЕРРЕЙН),
      'на прилавке нет корзины',
    );
    должен(/const ободок = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.34, 0\.03, 5, 12\)/.test(ТЕРРЕЙН),
      'у корзины нет ободка');
    должен(/const дужка = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.33, 0\.018, 5, 12, Math\.PI\)/.test(ТЕРРЕЙН),
      'у корзины нет дужки');
  });
});
