// Ночные патрули (§352): пост, который живёт только ночью.
//
// ЗА ЧТО БОРЕТСЯ. «Больше патрулей» ночью стояло в карте рядом с «меньше NPC»
// с самого начала, а караул не знал про часы: десять постов стояли круглые
// сутки, и единственный ходячий страж ходил и в полдень, и в полночь
// одинаково. Ночь уже была временем вора (горожане спят, обзор стража режет
// nightFactor) — но добавить ей стража было нечем.
//
// ГЛАВНАЯ ОПАСНОСТЬ ЭТОЙ МЕХАНИКИ — РАСКОЛ КАРТИНКИ И ПРАВИЛА. Ночной страж
// существует в двух местах: в правиле детекции (сервер) и на экране (клиент).
// Если правило читает GUARD_POSTS напрямую, минуя activeGuardPosts, игрок
// будет «замечен» стражем, которого днём не видно, — стелс начнёт наказывать
// за пустой двор. Поэтому здесь проверяются ОБА места детекции, а не только
// сам фильтр.
//
// ПОЧЕМУ ЧАСТЬ ПРОВЕРОК ПОВЕДЕНЧЕСКАЯ. activeGuardPosts, spottedBy и
// postPosition — чистые функции shared: их можно вызвать по-настоящему.
// Regexом фильтр не проверяется — проверяется тем, что он фильтрует.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  GUARD_POSTS, activeGuardPosts, postPosition, spottedBy,
} from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ночные = GUARD_POSTS.filter((p) => p.nightOnly);
const дневные = GUARD_POSTS.filter((p) => !p.nightOnly);
const патруль = ночные.find((p) => p.id === 'npc_night_patrol');

describe('Ночной патруль: пост существует и не вырожден', () => {
  it('ночной пост есть, обычные посты не помечены', () => {
    must(GUARD_POSTS.length > 0, 'GUARD_POSTS пуст');
    must(ночные.length >= 1, 'ночных постов нет: ночь не принесла стражи');
    must(дневные.length >= 3, 'дневных постов меньше трёх: вся караульная служба ушла в ночь');
    must(патруль !== undefined, 'поста npc_night_patrol нет в списке');
  });

  it('ночной пост ходит по изведенной тропе, а не сквозь город', () => {
    must(патруль!.patrol !== undefined, 'ночной пост стоит: это не патруль');
    // Тропа переходных событий идёт (60,32) → (0,0). Старт поста обязан
    // лежать на ней — иначе страж идёт по непроверенной геометрии и может
    // пройти сквозь стену. Проверяем прямую: x/60 === z/32.
    const на_линии = Math.abs(патруль!.x / 60 - патруль!.z / 32) < 1e-9;
    must(на_линии, `пост (${патруль!.x},${патруль!.z}) не на тропе (60,32)→(0,0): маршрут через город не проверен`);
    // Конец маршрута — тоже на ней.
    const конец = патруль!.patrol!;
    must(конец.toX === 0 && конец.toZ === 0, 'маршрут не кончается в (0,0): своя непроверенная тропа');
    // И старт внутри отрезка, а не за его пределами.
    must(патруль!.x >= 0 && патруль!.z >= 0, 'старт маршрута за пределами тропы');
  });

  it('ночный страж не обгоняет пешехода', () => {
    const длина = Math.hypot(патруль!.patrol!.toX - патруль!.x, патруль!.patrol!.toZ - патруль!.z);
    const скорость = (длина * 2) / (патруль!.patrol!.periodMs / 1000);
    // Ходьба игрока 4.2 (world3d.ts). Патруль, который догоняет шагом,
    // делает скрытность нечестной.
    must(скорость < 4.2, `ночный патруль идёт ${скорость.toFixed(2)} ед/с — не медленнее ходьбы 4.2`);
    must(скорость > 0.3, `ночный патруль идёт ${скорость.toFixed(2)} ед/с — фактически стоит`);
  });
});

describe('activeGuardPosts: правило зависит от часа', () => {
  it('ночью ночной пост стоит на постах, днём его не существует', () => {
    const день = activeGuardPosts(0);
    const ночь = activeGuardPosts(1);
    must(!день.some((p) => p.nightOnly), 'днём в правиле есть ночной страж: наказание за пустой двор');
    must(ночь.some((p) => p.id === 'npc_night_patrol'), 'ночью ночной страж не стоит в правиле');
    // Сумерки (0.5) — ещё день для ночных постов: режим включает ровно ночь.
    must(!activeGuardPosts(0.5).some((p) => p.nightOnly), 'в сумерках ночной страж уже на посту');
  });

  it('обычные посты стоят круглосуточно', () => {
    const день = activeGuardPosts(0);
    for (const p of дневные) {
      must(день.includes(p), `дневной пост ${p.id} пропал из дневного списка`);
    }
  });

  it('обнаружение по-настоящему меняется: ночью замечает, днём нет', () => {
    // Поведенческая проверка: игрок стоит на маршруте ночного патруля
    // в тот момент цикла, когда страж проходит через его точку.
    must(патруль !== undefined, 'поста нет');
    const половина = патруль!.patrol!.periodMs / 2;
    const где = postPosition(патруль!, половина);
    must(
      Math.hypot(где.x - патруль!.patrol!.toX, где.z - патруль!.patrol!.toZ) < 1,
      'на середине цикла страж не дошёл до конца маршрута: формула позиции разошлась с постом',
    );
    const ctx = { crouch: false, night: 1, visibility: 1 };
    const ночью = spottedBy(где, activeGuardPosts(1), ctx, половина);
    must(ночью?.id === 'npc_night_patrol', `ночью у точки маршрута замечает ${ночью?.id ?? 'никто'}`);
    const днём = spottedBy(где, activeGuardPosts(0), { ...ctx, night: 0 }, половина);
    must(днём === null || днём.id !== 'npc_night_patrol', 'днём замечает ночной страж, которого нет на экране');
  });
});

describe('Проводка: обе стороны берут список из одного места', () => {
  const обработчик = читать('server/src/socket/GameSocketHandler.ts');
  const цикл = читать('server/src/systems/GameLoop.ts');
  const клиент = читать('client/src/app/game3d/npc.ts');
  const мир = читать('client/src/app/game3d/world3d.ts');

  it('детекция в сокет-обработчике идёт через activeGuardPosts', () => {
    must(
      /spottedBy\([^)]*activeGuardPosts/.test(обработчик),
      'обнаружение читает GUARD_POSTS напрямую: ночной страж наказывает днём',
    );
    must(
      !/spottedBy\([^)]*GUARD_POSTS/.test(обработчик),
      'в обнаружении остался прямой GUARD_POSTS рядом с activeGuardPosts',
    );
  });

  it('удар стража в тике идёт через activeGuardPosts', () => {
    must(
      /strikingGuard\([^)]*activeGuardPosts/.test(цикл),
      'тикающий удар бьёт по полному списку: ночной страж бьёт днём',
    );
  });

  it('клиент прячет ночную фигуру и её имя, ведёт имя и коллайдер за стражем', () => {
    // Видимость тела по часу из пакета world:time.
    must(/if \(w\.post\.nightOnly\) w\.group\.visible = \(night \?\? 0\) >= 1;/.test(клиент),
      'клиент не прячет ночную фигуру днём: страж ходит при солнце');
    // Имя гаснет вместе с телом.
    must(/n\.ночью && !ночь/.test(клиент), 'имя ночного стража видно днём');
    // Коллайдер не остаётся стеной на тропе.
    must(/w\.коллайдер\.r = w\.post\.nightOnly && \(night \?\? 0\) < 1 \? 0 : 0\.55;/.test(клиент),
      'ночной страж днём остаётся невидимой стеной');
    // И ходячего стража вообще: имя и коллайдер следуют за телом (баг §352).
    must(/w\.имя\.sprite\.position\.set\(где\.x/.test(клиент), 'имя ходячего стража осталось на старте маршрута');
    must(/w\.коллайдер\.x = где\.x/.test(клиент), 'коллайдер ходячего стража остался на старте маршрута');
    // Мир передаёт ночь в NPC тем же вызовом.
    must(/npcs\.update\(dt, now, this\.camera\.position, night\)/.test(мир),
      'мир не передаёт ночь в NPC: клиенту неоткуда знать про ночной пост');
  });

  it('клик сквозь невидимую фигуру закрыт', () => {
    // Луч three.js не смотрит на visible: без фильтра невидимый ночной
    // страж днём перехватывал бы клик перед видимым NPC.
    const мир = читать('client/src/app/game3d/world3d.ts');
    must(/for \(let o: THREE\.Object3D \| null = h\.object; o; o = o\.parent\)/.test(мир),
      'pickNpc не фильтрует невидимые фигуры: ночной страж перехватывает клики днём');
  });
});
