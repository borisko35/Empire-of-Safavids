// Ветер чувствуется зеленью.
//
// ЧТО БЫЛО (22 октября 2026, §281). Зелень качалась по ветру (§258), но сила
// ветра не зависела от погоды: в буре зелень качалась вдвое сильнее, а в
// штиль — так же, как в буре. Ветер в мире один, и зелень его не чувствовала.
//
// ЧТО ТЕПЕРЬ. Сила ветра считается по погоде: в буре ветку рвёт, в штиль она еле
// шевелится, и порывы в сильный ветер идут чаще.
//
// ЧТО ПРОВЕРЯЕТСЯ. У каждой погоды своя сила, в буре она заметно больше, чем в
// штиле, и порывы учащаются вместе с ветром.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Ветер чувствуется зеленью', () => {
  it('у каждой погоды своя сила ветра', () => {
    должен(/export function ветерСилы\(weather: string\): number/.test(МИР),
      'нет функции силы ветра');
    // В буре ветер сильнее, чем в штиле, — и это видно по числам.
    const блок = /export function ветерСилы[\s\S]*?\n}/.exec(МИР);
    должен(блок, 'не разобрал функцию силы ветра');
    const буря = /case 'storm': return ([\d.]+);/.exec(блок![0]);
    const штиль = /default: return ([\d.]+);/.exec(блок![0]);
    должен(буря && штиль, 'не нашёл силу ветра для бури и для штиля');
    должен(
      Number(буря![1]) > Number(штиль![1]) * 2,
      `в буре ветер ${буря![1]}, в штиль ${штиль![1]} — разницы не читается`,
    );
  });

  it('погода задаёт силу качания и частоту порывов', () => {
    должен(/const ветер = ветерСилы\(this\.currentWeather\);/.test(МИР),
      'качание не зависит от погоды');
    // Чем сильнее ветер, тем чаще порывы.
    должен(/const быстро = 900 \/ ветер;/.test(МИР),
      'частота порывов не зависит от силы ветра');
  });
});
