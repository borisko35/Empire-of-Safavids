// Птицы над пустыней и городом.
//
// ЧТО БЫЛО (21 октября 2026, §259). Небо было пустым: в мире, где есть
// верблюды, коровы, пыльные вихри и ветер, который качает зелень, не летает ни
// одна птица. Небо читалось как фон, а не как воздух.
//
// ЧТО ТЕПЕРЬ. Стая: вожатый и двенадцать птиц по бокам и позади. Стая облетает
// игрока по широкой дуге, крылья бьют вразнобой (у каждой птицы своя фаза), и
// радиус облёта дышит — то издали, то близко над головой.
//
// ЧТО ПРОВЕРЯЕТСЯ. Стая создаётся и живёт: птицы в строю, крылья бьют, стая
// облетает игрока; и движок её обновляет и вычищает.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ПТИЦЫ = читать('client/src/app/game3d/birds.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Птицы над пустыней', () => {
  it('стая состоит из птиц с двумя крыльями', () => {
    должен(/export function createBirds/.test(ПТИЦЫ), 'нет модуля птиц');
    должен(/const ПТИЦ = 13;/.test(ПТИЦЫ), 'птиц в стае не 13');
    // Крылья: две пластины, левое и правое.
    должен(/const крылоЛ = new THREE\.Mesh/.test(ПТИЦЫ), 'нет левого крыла');
    должен(/const крылоП = new THREE\.Mesh/.test(ПТИЦЫ), 'нет правого крыла');
    // Строй: клином назад от вожатого.
    должен(/const ряд = i === 0 \? 0 : Math\.ceil\(i \/ 2\);/.test(ПТИЦЫ), 'строй не клин');
  });

  it('крылья бьют вразнобой, у каждой птицы своя фаза', () => {
    должен(/фаза: Math\.random\(\) \* 6\.28/.test(ПТИЦЫ), 'у птиц нет своей фазы взмахов');
    должен(
      /п\.крылоЛ\.rotation\.z = 0\.22 - бой;[\s\S]{0,120}?п\.крылоП\.rotation\.z = -0\.22 \+ бой;/.test(ПТИЦЫ),
      'крылья не бьют',
    );
    // С 21 октября 2026 (§273) взмах домножается на «не сидит» — птица на воде
    // не бьёт крыльями, — поэтому скобка в начале может стоять или нет.
    должен(/const бой = \(?Math\.sin\(now \* 7\.5 \+ п\.фаза\)/.test(ПТИЦЫ), 'нет взмахов');
  });

  it('стая облетает игрока, и радиус дышит', () => {
    должен(
      /const цельX = px \+ Math\.cos\(угол\) \* радиус;[\s\S]{0,120}?const цельZ = pz \+ Math\.sin\(угол\) \* радиус;/.test(
        ПТИЦЫ,
      ),
      'стая не облетает игрока',
    );
    должен(
      /const радиус = РАДИУС \+ Math\.sin\(угол \* 0\.7\) \* 28;/.test(ПТИЦЫ),
      'радиус облёта не дышит: стая всегда на одном расстоянии',
    );
  });

  it('движок создаёт стаю, обновляет и вычищает', () => {
    должен(/this\.птицы = createBirds\(this\.scene\);/.test(МИР), 'движок не создаёт птиц');
    должен(
      /this\.птицы\.update\(dt, now, me\.pos\.x, me\.pos\.z\);/.test(МИР),
      'стая не обновляется: птицы висят в воздухе',
    );
    должен(/this\.птицы\?\.dispose\(\);/.test(МИР), 'птицы не вычищаются');
  });
});
