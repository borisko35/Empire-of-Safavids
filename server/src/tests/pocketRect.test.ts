// Прямоугольник кармана стоит там, где комнаты, а не посреди мира.
//
// ЧТО БЫЛО. Комнаты интерьеров сдвинули на полтора километра за край мира
// (4000..4396), а прямоугольник земли-плато с невидимым забором остался на
// старом месте, 2470..2880. Он лежит ВНУТРИ мира (WORLD_HALF = 3175) и после
// расширения мира попал в зону east_frontier_far.
//
// ДВА ВРЕДА, И ОБА ИЗМЕРЕНЫ ПО ДВУМ ВЕТВЯМ РАСЧЁТА ВЫСОТЫ:
//
//   const groundY = this.interiors.isInside()
//     ? this.interiors.floorY()          // внутри интерьера - пол комнаты
//     : pocketY ?? groundHeight(x, z);   // снаружи - плато кармана
//
// 1. Невидимый забор POCKET_COLLIDERS посреди новой земли: коллайдер есть,
//    стены нет.
// 2. Вне интерьера высота берётся как pocketY ?? groundHeight, а pocketY в
//    этом прямоугольнике равен 0, то есть НЕ null, и подстановка не
//    срабатывает. Земля под ногами становится нулевой там, где настоящий
//    рельеф лежит около 20..40 метров: игрок то уходит под землю, то висит
//    в воздухе - и упирается в невидимую стену.
//
// ПОЧЕМУ ПРОВЕРКА ИМЕННО ТАКАЯ. Проверять надо не «числа красивые», а два
// свойства: прямоугольник накрывает все комнаты целиком (иначе забор будет
// стоять поверх комнаты) и целиком лежит за краем мира (иначе он снова
// окажется в зоне игрока и станет невидимой стеной).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

function прямоугольник(): { x0: number; x1: number; z0: number; z1: number } {
  const m = /export const POCKET_RECT = \{ x0: (-?\d+), x1: (-?\d+), z0: (-?\d+), z1: (-?\d+) \}/.exec(клиент);
  must(m !== null, 'не нашёл POCKET_RECT в interiors.ts - вид файла изменился');
  return { x0: Number(m[1]), x1: Number(m[2]), z0: Number(m[3]), z1: Number(m[4]) };
}

/** Край мира берём из terrain.ts, а не записываем числом: край уже двигался. */
function крайМира(): number {
  const m = /export const WORLD_HALF = (\d+)/.exec(читать('client/src/app/game3d/terrain.ts'));
  must(m !== null, 'не нашёл WORLD_HALF в terrain.ts');
  return Number(m[1]);
}

const RECT = прямоугольник();
const HALF = крайМира();
const комнаты = Object.values(INTERIORS);

/** Граница полосы может стоять числом или именем СРЕДНИЙ_КРАЙ. */
const МИН = (значение: string, край: number): number =>
  значение === 'СРЕДНИЙ_КРАЙ' ? край : Number(значение);

/** Комната полностью накрыта прямоугольником, с запасом хотя бы в 8 единиц. */
function накрыта(c: number, d: number, половина: number): boolean {
  return c - половина >= RECT.x0 + 8 && c + половина <= RECT.x1 - 8 &&
    d - половина >= RECT.z0 + 8 && d + половина <= RECT.z1 - 8;
}

describe('Прямоугольник кармана на месте', () => {
  it('накрывает каждую комнату целиком и с запасом', () => {
    const неНакрыты = комнаты.filter((к) =>
      !накрыта(к.roomCx, к.roomCz, Math.max(к.roomHalf, 8)));
    must(неНакрыты.length === 0,
      `прямоугольник кармана не накрывает: ${неНакрыты.map((к) =>
        `${к.id} (${к.roomCx}, ${к.roomCz})`).join(', ')} - ` +
      'забор встанет прямо на комнату, и игрок окажется за невидимой стеной у входа');
  });

  it('лежит целиком за краем мира, а не посреди него', () => {
    // Главная проверка. Прямоугольник, пересекающийся с миром, становится
    // невидимым забором в зоне игрока и нулевой землёй под ногами.
    const ближайший = Math.min(RECT.x0, RECT.z0);
    must(RECT.x0 > HALF && RECT.z0 > HALF,
      `прямоугольник ${RECT.x0}..${RECT.x1} / ${RECT.z0}..${RECT.z1} заходит в мир ` +
      `(WORLD_HALF = ${HALF}, ближайший край ${ближайший}) - невидимый забор окажется в зоне игрока`);
  });

  it('ни одна зона мира не пересекается с прямоугольником', () => {
    // То же самое, но словами игрока: какая зона затронута.
    //
    // ГРАНИЦА ИМЕНОВАННАЯ, И ЭТО НЕ КОСМЕТИКА. Первая версия брала границы зон
    // регуляркой с классом (\w+), а в constants.ts у двадцати полос стоит
    // `x1: СРЕДНИЙ_КРАЙ` - кириллица. \w в JavaScript кириллицу не берёт, и
    // все полосы центральной части вместе с обоими дальними краями просто не
    // разбирались. Проверка молча проходила на ДЕВЯТИ зонах из тридцати - то
    // есть именно на тех, где забора быть не может. Тот же класс поломки,
    // что и раньше: ноль из-за того, что ничего не нашлось, выглядит как
    // «всё хорошо».
    const зоны = читать('shared/constants.ts');
    const край = Number(/export const СРЕДНИЙ_КРАЙ = (\d+)/.exec(зоны)?.[1]);
    must(Number.isFinite(край), 'не нашёл СРЕДНИЙ_КРАЙ в constants.ts - границы зон изменились');
    // Значение идентификатора подставляется числом, а не именем.
    const полосы = [...зоны.matchAll(
      /id: '([a-z_]+)', region: '[a-z_]+'[^}]*?bounds: \{ x1: (-?[\wа-яА-ЯёЁ]+), z1: (-?\d+), x2: (-?[\wа-яА-ЯёЁ]+), z2: (-?\d+) \}/g,
    )].map((м) => ({
      id: м[1],
      x1: МИН(м[2], край), z1: Number(м[3]),
      x2: МИН(м[4], край), z2: Number(м[5]),
    }));
    must(полосы.length >= 30,
      `прочиталось ${полосы.length} полос из тридцати - регулярка разбирает не все, ` +
      'и проверка молча смотрит не на всё');

    const пересечены = полосы.filter((з) =>
      Math.min(з.x2, RECT.x1) - Math.max(з.x1, RECT.x0) > 0 &&
      Math.min(з.z2, RECT.z1) - Math.max(з.z1, RECT.z0) > 0);
    must(пересечены.length === 0,
      `прямоугольник кармана наезжает на зоны: ${пересечены.map((з) => з.id).join(', ')} - ` +
      'там игрок натыкается на невидимый забор и стоит на нулевой земле');
  });

  it('внутри интерьера высота берётся из пола комнаты, а не из кармана', () => {
    // Отвечает на вопрос, который закрывал правку: перенос прямоугольника
    // не должен менять высоту игрока внутри комнаты.
    const w = читать('client/src/app/game3d/world3d.ts');
    const mustHave = /const groundY = this\.interiors\.isInside\(\)\s*\n\s*\? this\.interiors\.floorY\(\)/;
    must(mustHave.test(w),
      'высота внутри интерьера больше не берётся из floorY() - тогда перенос прямоугольника ' +
      'менял бы высоту под ногами игрока во всех десяти комнатах, и правка была бы небезопасна');
  });

  it('забор стоит по периметру прямоугольника, а не внутри комнат', () => {
    // Забор должен быть снаружи комнат, иначе он отрежет вход.
    const доКрая = Math.min(...комнаты.map((к) => к.roomCx - RECT.x0));
    must(доКрая > 8,
      `от края прямоугольника до ближайшей комнаты ${доКрая} единиц - забор встанет впритык к ней`);
    const colliders = /POCKET_COLLIDERS\.push\(\{ x, z: POCKET_RECT\.z0/.test(клиент);
    must(colliders, 'забор по периметру не строится - при переносе прямоугольника он исчезнет вовсе');
  });
});