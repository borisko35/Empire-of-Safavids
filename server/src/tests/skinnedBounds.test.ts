// Габариты скелетной модели надо мерить по ПОЗЕ, а не по геометрии покоя.
//
// ЧТО БЫЛО. `подогнать()` мерила фигуру через
// `new THREE.Box3().setFromObject(сцена)`. Этот вызов умеет только одно: взять
// `geometry.boundingBox`, то есть ЛОКАЛЬНЫЕ координаты геометрии, то есть позу
// ПОКОЯ. Рядом стоял вызов `SkinnedMesh.computeBoundingBox()`, который считает
// по текущей позе, — но он заполняет СВОЁ поле `boundingBox`, и setFromObject
// его не читает. Пересчитанный бокс проходил мимо.
//
// Что отдавал такой замер, замерено на живой игре: 0,003-0,007 при фигуре
// ростом 1,6-3,7 м. Дальше k = 1,9 / 0,007 = 271, а MIN_SCALE…MAX_SCALE
// пропускают 0,2…5 — подгонка каждый раз честно отказывалась трогать размер, и
// персонаж выходил в мир в натуральную величину: кызылбаш 3,67 м, остальные
// 1,63-1,72 м.
//
// ПОЧЕМУ СТОРОЖ БЫЛ ПЕРЕПИСАН, А НЕ ПОПРАВЛЕН. Первая версия этого файла
// требовала, чтобы `setFromObject(сцена)` остался в коде, и проверяла, что он
// идёт ПОСЛЕ computeBoundingBox. То есть она охраняла ровно то, что сломано:
// правильный порядок двух вызовов не делает setFromObject скелетным. Проверка
// была зелёной на сломанном коде — хуже отсутствующей, потому что создавала
// видимость присмотра. Теперь она требует, чтобы замер шёл из `boundingBox`.
//
// ПРО ПОРЯДОК ПРОВЕРОК. Первая версия искала `computeBoundingBox` обычным
// `indexOf` по всему файлу и попадала в КОММЕНТАРИЙ, который стоит выше кода.
// Порядок получался правильным всегда. Сначала вырезаем комментарии, потом
// смотрим порядок.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

// Код без комментариев: и одиночных строк, и блоков /* */. Строки внутри блока
// не вырезаются целиком - регулярка с [\s\S] не знает про границы строк, -
// но порядок вызовов это не путает: в файле нет строковых литералов с
// вызовами методов.
function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const РИГ = читать('client/src/app/game3d/realRig.ts');
const ТОЛЬКО_КОД = код(РИГ);

describe('Габариты скелетной модели', () => {
  it('сторож проверяет код, а не комментарий', () => {
    // Страховка от повторения собственной ошибки. Условие НЕ «упоминания нет» -
    // упоминание как раз нужно. Условие в том, что объяснение есть в файле и
    // его НЕТ в коде: если вырезание комментариев перестанет работать, порядок
    // снова начнёт читаться по пояснению, и этот тест обязан упасть.
    должен(
      /ГАБАРИТЫ ПОЗЫ, А НЕ ГЕОМЕТРИИ/.test(РИГ),
      'пояснение из файла исчезло, страховке не на что опереться',
    );
    должен(
      !/ГАБАРИТЫ ПОЗЫ, А НЕ ГЕОМЕТРИИ/.test(ТОЛЬКО_КОД),
      'комментарии больше не вырезаются: порядок читается по пояснению, а не по коду',
    );
    должен(
      /computeBoundingBox/.test(ТОЛЬКО_КОД),
      'подсчёт позы не остался в коде: проверять нечего',
    );
  });

  it('замер идёт из скинед-бокса, а не из геометрии', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Именно setFromObject был причиной: он берёт
    // geometry.boundingBox, то есть позу покоя. Если он вернётся в подгонку,
    // замер снова станет 0,007 и подгонка снова откажется менять размер.
    должен(
      !/setFromObject\s*\(\s*сцена\s*\)/.test(ТОЛЬКО_КОД),
      'замер снова идёт через setFromObject(сцена): это поза покоя, а не поза',
    );
    должен(
      /узел\.boundingBox/.test(ТОЛЬКО_КОД),
      'замер не читает boundingBox скинед-меша, а без него рост неизвестен',
    );
    // Мир-координаты: локальный бокс без matrixWorld даст сантиметры вместо метров.
    должен(
      /узел\.boundingBox[\s\S]{0,200}applyMatrix4\s*\(\s*узел\.matrixWorld\s*\)/.test(ТОЛЬКО_КОД),
      'локальный бокс переносится в мир неверно: подошва уедет, рост будет не тот',
    );
  });

  it('поза считается ДО того, как читается её результат', () => {
    const поза = ТОЛЬКО_КОД.indexOf('узел.computeBoundingBox()');
    const чтение = ТОЛЬКО_КОД.indexOf('узел.boundingBox');
    должен(поза > 0, 'поза скелета не считается');
    должен(чтение > 0, 'бокс позы не читается');
    должен(
      поза < чтение,
      'бокс читается ДО подсчёта позы: он будет пустым, и рост снова выйдет неверным',
    );
  });

  it('модель отбирается по признаку скелета, а не по имени', () => {
    // Имя класса или префикс модели — это угадывание. Признак isSkinnedMesh
    // есть у самой модели и ничего не ломается при переименовании файла.
    должен(
      /isSkinnedMesh\s*===\s*true/.test(ТОЛЬКО_КОД),
      'модель не отбирается признаком скелета: смена имени файла всё сломает',
    );
    должен(
      /typeof\s+узел\.computeBoundingBox\s*===\s*'function'/.test(ТОЛЬКО_КОД),
      'нет проверки, что метод вообще есть: на обычном Mesh будет исключение',
    );
  });

  it('предупреждение не ссылается на причину, которой нет', () => {
    // Раньше: «масштаб корня в файле». Потом — версия про геометрию, которая
    // тоже была неверной. Обе вводили в заблуждение: обе называли причиной то,
    // чего в коде не было.
    const вызов = /console\.warn\([\s\S]{0,400}?не трогаю размер[\s\S]{0,400}?\);/.exec(ТОЛЬКО_КОД);
    должен(вызов, 'предупреждение «не трогаю размер» не читается');
    должен(
      !/масштаб корня в файле/.test(вызов![0]),
      'предупреждение снова указывает на масштаб корня — этой причины тут нет',
    );
  });
});

describe('Коэффициент клипа', () => {
  // ПОЧЕМУ ЗДЕСЬ, А НЕ ТОЛЬКО В check:figure. Пять гипотез подряд строились на
  // том, что измерение работает, а оно не работало ни разу. Проверка была в
  // клиентском скрипте, который CI не запускает, и потому никто её не видел.

  it('выбор компоненты начинается с нуля, а не с минус одного', () => {
    // `значения[лучший]` при лучший === -1 - это undefined, от него NaN,
    // а `x > NaN` всегда ложно. Компонента не выбиралась НИ РАЗУ, и функция
    // отдавала запасное число, то есть константу, вместо измерения.
    //
    // Проверяются ОБА края. Форма сравнения у сломанного и правильного кода
    // одинакова - `Math.abs(значения[k]) > Math.abs(значения[лучший])`, - и
    // отличается только начальное значение. Проверка на саму форму ничего бы
    // не различала; различают начальное значение и то, что цикл начинается
    // с единицы.
    должен(
      /лучший\s*=\s*0\s*;/.test(ТОЛЬКО_КОД),
      'выбор компоненты снова начинается с -1: при нём сравнение всегда ложно',
    );
    должен(
      /for\s*\(\s*let\s+k\s*=\s*1\s*;/.test(ТОЛЬКО_КОД),
      'цикл сравнения начинается с нуля: он будет сравнивать компоненту с самой собой',
    );
  });

  it('коэффициент измеряется по костям, а не берётся у корня', () => {
    должен(
      /коэффициентКлипа\s*\(/.test(ТОЛЬКО_КОД),
      'функция измерения коэффициента пропала из кода',
    );
    // Запасное число остаётся как страховка, но вызывать измерение обязаны.
    должен(
      /this\.масштабКлипа\s*=\s*коэффициентКлипа\s*\(/.test(ТОЛЬКО_КОД),
      'риг снова не зовёт измерение и пользуется запасным числом',
    );
  });
});