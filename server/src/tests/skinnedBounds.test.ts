// Габариты скелетной модели надо мерить по позе, а не по геометрии.
//
// ЧТО БЫЛО. `подогнать` меряла через `Box3.setFromObject`, а тот умеет
// только одно — взять `geometry.boundingBox`, то есть ЛОКАЛЬНЫЕ координаты
// геометрии. Модель со скелетом рисует совсем другое: позу костей. На живой
// игре при фигуре ростом 1,8 м отдавалось **0,0072 м** — расхождение примерно
// в 250 раз.
//
// Последствия оба были неверными:
//
//   - предупреждение кричало о поломке, которой нет: модели рисуются
//     правильно, и подгонка справедливо отказывалась их трогать;
//   - любая правка по этой цифре растянула бы нормальную фигуру в 250 раз.
//     Именно так и вышло в §140, откат которого стоил выката.
//
// ЧТО ТЕПЕРЬ. SkinnedMesh.computeBoundingBox() считает по текущей позе.
// Замер идёт после него, и только потом.
//
// ПРО ПОРЯДОК ПРОВЕРОК. Первая версия этого сторожа искала `computeBoundingBox`
// обычным `indexOf` по всему файлу — и попадала в КОММЕНТАРИЙ «computeBoundingBox()
// считает по текущей позе», который стоит выше замера. Порядок получался
// правильным всегда, и перенос кода за замер сторож не ловил. Ловушка старая и
// своя: проверка, которая читает пояснение вместо кода, не проверяет ничего.
// Поэтому сначала код, потом порядок.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

// Код без комментариев: и одиночных строк, и блоков /* */. Строки внутри
// блока не вырезаются целиком - регулярка с [\s\S] не знает про границы
// строк, - но искать порядок вызовов это не мешает, потому что в файле нет
// строковых литералов с вызовами методов.
function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const РИГ = читать('client/src/app/game3d/realRig.ts');
const ТОЛЬКО_КОД = код(РИГ);

describe('Габариты скелетной модели', () => {
  it('сторож проверяет код, а не комментарий', () => {
    // Страховка от повторения собственной ошибки. Условие НЕ «вызова нет» -
    // вызов как раз нужен. Условие в том, что пояснение есть в файле и его
    // НЕТ в коде: если вырезание комментариев перестанет работать, порядок
    // снова начнёт читаться по пояснению, и этот тест обязан упасть.
    должен(
      /ГАБАРИТЫ СКЕЛЕТНОЙ МОДЕЛИ/.test(РИГ),
      'пояснение из файла исчезло, страховке не на что опереться',
    );
    должен(
      !/ГАБАРИТЫ СКЕЛЕТНОЙ МОДЕЛИ/.test(ТОЛЬКО_КОД),
      'комментарии больше не вырезаются: порядок читается по пояснению, а не по коду',
    );
    должен(
      /computeBoundingBox/.test(ТОЛЬКО_КОД),
      'подсчёт позы не остался в коде: проверять нечего',
    );
    должен(
      /setFromObject\(сцена\)/.test(ТОЛЬКО_КОД),
      'замер габарита не читается из кода',
    );
  });

  it('поза скелета считается ДО замера габарита', () => {
    const поза = ТОЛЬКО_КОД.indexOf('computeBoundingBox');
    const замер = ТОЛЬКО_КОД.indexOf('new THREE.Box3().setFromObject(сцена)');
    должен(поза > 0, 'поза скелета не считается: замер берёт локальные координаты геометрии');
    должен(замер > 0, 'замер габарита не читается');
    должен(
      поза < замер,
      'замер идёт ДО подсчёта позы: получится снова 0,0072 вместо 1,8',
    );
  });

  it('модель отбирается по признаку скелета, а не по имени', () => {
    // Имя класса или префикс модели — это угадывание. Признак isSkinnedMesh
    // есть у самой модели и ничего не ломается при переименовании файла.
    должен(
      /isSkinnedMesh\s*===\s*true/.test(ТОЛЬКО_КОД),
      'модель не отбирается признаком скелета: смена имени файла всё сломает',
    );
    должен(
      /typeof\s+узел\.computeBoundingBox\s*===\s*'function'/.test(ТОЛЬКО_КОД),
      'нет проверки, что метод вообще есть: на обычном Mesh будет исключение',
    );
  });

  it('предупреждение не ссылается на причину, которой нет', () => {
    // Раньше: «масштаб корня в файле». После §140 это объяснение убрали, но
    // осталась другая неверная версия про геометрию. Обе вводили в заблуждение.
    const вызов = /console\.warn\([\s\S]{0,400}?не трогаю размер[\s\S]{0,400}?\);/.exec(ТОЛЬКО_КОД);
    должен(вызов, 'предупреждение «не трогаю размер» не читается');
    должен(
      !/масштаб корня в файле/.test(вызов![0]),
      'предупреждение снова указывает на масштаб корня — этой причины тут нет',
    );
  });

  it('замер не откатывается к прежней ошибке', () => {
    // Если кто-то вернёт Box3.setFromObject БЕЗ подсчёта позы, эта проверка
    // обязана упасть. Порядок смотрим по коду, а не по всему файлу.
    const началоЗамера = ТОЛЬКО_КОД.indexOf('new THREE.Box3().setFromObject(сцена)');
    должен(началоЗамера > 0, 'замер не найден');
    const послеЗамера = ТОЛЬКО_КОД.slice(началоЗамера, началоЗамера + 200);
    должен(
      !/computeBoundingBox/.test(послеЗамера),
      'подсчёт позы переехал за замер — это ровно та ошибка, что была',
    );
  });
});