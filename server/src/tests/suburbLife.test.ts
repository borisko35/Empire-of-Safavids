// Пригород оживает.
//
// ЧТО БЫЛО (22 октября 2026). У кузницы стоял пустой двор: ни дров, ни воды,
// ни хозяйства. Склад — телега из ящика, бочки из цилиндров с торусами.
//
// ЧТО ТЕПЕРЬ (§326). Телега — готовая модель (medieval-cart-lite, приехала
// раньше), бочка и поленница — готовые модели barrel и wood-log (Quaternius).
// Кузница остаётся своей: горн, наковальня и угли — работающее хозяйство
// со светом, а не заглушки.
//
// ЧТО ПРОВЕРЯЕТСЯ. Кузница на месте (горн, угли); телега, бочка и поленница —
// готовые модели из манифеста; примитивных бочек и брёвен больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
  animals?: { file: string; name: string; bytes: number }[];
};
const вМанифесте = (раздел: 'decor' | 'animals', имя: string): boolean =>
  (МАНИФЕСТ[раздел] ?? []).some((д) => д.name === имя);

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Пригород оживает', () => {
  it('колодец двора — готовая модель', () => {
    должен(вМанифесте('decor', 'well'), 'well.glb нет в манифесте');
    должен(/decorВещь\(city, 'well', px, pz, \{ размер: [\d.]+, ry: [\d.]+ \}\);/.test(ТЕРРЕЙН),
      'колодец двора стоит не готовой моделью');
    должен(!/CylinderGeometry\(0\.08, 0\.08, 1\.5, 6\)/.test(ТЕРРЕЙН), 'вал колодца снова цилиндр');
  });

  it('кузница: горн с углями', () => {
    должен(/const горн = new THREE\.Mesh\(new THREE\.BoxGeometry\(2\.0, 1\.1, 1\.4\), MAT\.sandstone\)/.test(код),
      'у кузницы нет горна');
    должен(/const угли = new THREE\.Mesh\(/.test(код), 'в горне нет углей');
  });

  it('у склада — готовые телега, вол, бочки и поленница', () => {
    // Вол в оглобле — ригованная модель из фауны, дышит в покое.
    должен(/void собратьЗверя\('bull', [\d.]+\)/.test(ТЕРРЕЙН), 'вол склада стоит не моделью');

    должен(вМанифесте('decor', 'barrel'), 'barrel.glb нет в манифесте');
    должен(вМанифесте('decor', 'wood-log'), 'wood-log.glb нет в манифесте');
    должен(/const бочка = \(px: number, pz: number, k: number\) => \{\s*decorВещь\(city, 'barrel', px, pz,/.test(код),
      'бочки ставятся не моделью');
    должен(/decorВещь\(g, 'wood-log', lx, lz, \{ размер: [\d.]+, по: 'горизонт'/.test(код),
      'поленница стоит не из готовых брёвен');
    // Цилиндров-бревен и бочек больше нет.
    должен(!/CylinderGeometry\(0\.36 \* k, 0\.32 \* k, 0\.85 \* k, 10\)/.test(код), 'бочки снова из примитивов');
    // Телега у склада — готовая модель, нормализованная постановка.
    должен(/decorВещь\(city, 'medieval-cart-lite', px, pz,/.test(ТЕРРЕЙН), 'телега у склада стоит не моделью');
    должен(!/BoxGeometry\(1\.3, 0\.7, 2\.2\)/.test(код), 'кузов телеги снова ящик');
  });
});
