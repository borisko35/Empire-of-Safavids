// Обратная сторона репутации: пошлина за лот растёт с рангом.
//
// ЧТО ЗАЩИЩАЕТСЯ. Репутация была только украшением: росла, давала титул, и
// больше ни на что не влияла. Теперь высокий ранг у «Торговцев Шёлкового пути»
// стоит серебра за каждый лот.
//
// ПОЧЕМУ ТАК МНОГО ПРОВЕРОК. Числа пошлины и пороги рангов лежат в двух разных
// местах — в правиле и в данных фракции. Если их поменяют по отдельности, игрок
// получит титул «Магнат» и пошлину «Новобранца», и заметить это будет негде.
// Поэтому пороги сверяются с данными фракции, а не просто проверяются на
// возрастание.
//
// ОТДЕЛЬНО ПРО ОШИБКУ. Раньше нехватка серебра приходила строкой по-английски
// с зашитым числом: клиент показывает err.message дословно. Как только пошлина
// стала зависеть от ранга, это сообщение стало бы прямой ложью. Проверяется и
// код, и то, что сумма приходит числом, а не текстом.
import { auctionListingFee, merchantDutyRate, AUCTION_DUTY_STEPS } from '../utils/economy';
import { AUCTION_LISTING_FEE_SILVER } from '../utils/economy';
import { FACTIONS } from '../services/ReputationService';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Ранги «Торговцев Шёлкового пути» из данных фракции — не выдуманные здесь.
const торговцы = FACTIONS.find((f) => f.id === 'merchants');
must(торговцы, 'в данных нет фракции merchants: правило пошлины повиснет в воздухе');
const ранги = торговцы!.ranks;

describe('Обратная сторона репутации: пошлина растёт с рангом', () => {
  it('пороги пошлины совпадают с рангами фракции', () => {
    must(
      AUCTION_DUTY_STEPS.length === ранги.length,
      `ступеней пошлины ${AUCTION_DUTY_STEPS.length}, рангов у фракции ${ранги.length}: ` +
        'одно из чисел забыли продублировать'
    );
    for (const [i, ранг] of ранги.entries()) {
      must(
        AUCTION_DUTY_STEPS[i].minRep === ранг.minRep,
        `ступень ${i} начинается с ${AUCTION_DUTY_STEPS[i].minRep}, а ранг «${ранг.nameRu}» ` +
          `с ${ранг.minRep}: по правилу и по титулу выйдут разные ранги`
      );
    }
  });

  it('у чужака пошлина равна базовой плате', () => {
    must(
      merchantDutyRate(0) === 0,
      `у нулевой репутации ставка ${merchantDutyRate(0)}, а должна быть 0`
    );
    must(
      auctionListingFee(0) === AUCTION_LISTING_FEE_SILVER,
      `ло�� у чужака стоит ${auctionListingFee(0)}, а базовая плата ${AUCTION_LISTING_FEE_SILVER}`
    );
  });

  it('ставка растёт вместе с рангом', () => {
    const ставки = ранги.map((р) => merchantDutyRate(р.minRep));
    for (let i = 1; i < ставки.length; i++) {
      must(
        ставки[i] > ставки[i - 1],
        `ставка ранга «${ранги[i].nameRu}» ${ставки[i]} не выше ставки ранга ` +
          `«${ранги[i - 1].nameRu}» ${ставки[i - 1]}: репутация перестала быть дорогой`
      );
    }
  });

  it('пошлина никогда не дешевле базовой', () => {
    // Иначе первый ранг был бы выгоднее нулевого: репутация не только ничего
    // не стоила бы, но ещё и окупала.
    for (const репутация of [0, 99, 100, 250, 300, 700, 1200, 1500, 5000, -50]) {
      must(
        auctionListingFee(репутация) >= AUCTION_LISTING_FEE_SILVER,
        `при репутации ${репутация} лот стоит ${auctionListingFee(репутация)}, ` +
          `а базовая плата ${AUCTION_LISTING_FEE_SILVER}`
      );
    }
  });

  it('пошлина целая: половина серебра выглядела бы опечаткой', () => {
    for (const репутация of [0, 100, 300, 700, 1500]) {
      const fee = auctionListingFee(репутация);
      must(Number.isInteger(fee), `при репутации ${репутация} пошлина ${fee} не целая`);
    }
  });

  it('высший ранг платит ощутимо, а не копейки', () => {
    const вершина = auctionListingFee(ранги[ранги.length - 1].minRep);
    must(
      вершина >= AUCTION_LISTING_FEE_SILVER * 1.05,
      `на высшем ранге лот стоит ${вершина} при базе ${AUCTION_LISTING_FEE_SILVER}: ` +
        'тёмная сторона репутации не читается'
    );
  });

  it('между рангами ставка прежняя', () => {
    // Пороги не должны становиться плотнее сами по себе: иначе игрок поднимает
    // ранг и сразу получает ставку следующего.
    for (let i = 0; i < ранги.length; i++) {
      const верх = i + 1 < ранги.length ? ранги[i + 1].minRep - 1 : ранги[i].minRep + 500;
      must(
        merchantDutyRate(верх) === merchantDutyRate(ранги[i].minRep),
        `при репутации ${верх} ставка ${merchantDutyRate(верх)}, а на ранге ` +
          `«${ранги[i].nameRu}» ${merchantDutyRate(ранги[i].minRep)}: ставка скакнула посреди ранга`
      );
    }
  });
});

describe('Пошлина подключена к аукциону', () => {
  const сервис = читать('server/src/services/AuctionService.ts');
  const маршрут = читать('server/src/routes/game.ts');
  const панель = читать('client/src/app/panels.ts');

  it('списывается пошлина по рангу, а не постоянная десятка', () => {
    must(
      /auctionListingFee\(репутация\)/.test(сервис),
      'лот списывается постоянной суммой: репутация на цену не влияет'
    );
    must(
      /\[silverFee, sellerId\]/.test(сервис),
      'в запрос списания идёт не та сумма, что посчитана'
    );
    must(
      !/AUCTION_LISTING_FEE_SILVER, sellerId/.test(сервис),
      'списывается базовая плата без пошлины'
    );
  });

  it('репутация читается из базы, а не выдумывается', () => {
    must(
      /merchantsReputation\(/.test(сервис),
      'репутация не читается: пошлина считается вслепую'
    );
    must(
      /character_reputation/.test(сервис),
      'чтения репутации нет: ранга из воздуха не взять'
    );
  });

  it('отказ говорит кодом и суммой, а не строкой', () => {
    // Раньше в ошибке было зашито «need 10 Isfahan silver», и клиент показывал
    // это дословно. С пошлиной по рангу такая надпись стала бы ложью.
    must(
      /AuctionError\('auction_no_silver', \{ fee: silverFee \}\)/.test(сервис),
      'отказ не несёт настоящую сумму: игроку скажут одно, а снимут другое'
    );
    must(
      !/need \$\{/.test(сервис) && !/Isfahan silver`/.test(сервис),
      'английская надпись с числом осталась в ошибке'
    );
    must(
      /err instanceof AuctionError/.test(маршрут) && /\.\.\.err\.params/.test(маршрут),
      'маршрут не отдаёт код и сумму: клиенту нечего переводить'
    );
  });

  it('клиент переводит код и подставляет свою сумму', () => {
    must(
      /auctionErrorMessage/.test(панель),
      'клиент по-прежнему показывает сырое сообщение сервера'
    );
    must(
      /t\('auction\.no_silver'\)\.replace\('\{fee\}'/.test(панель),
      'клиент не подставляет сумму пошлины в надпись'
    );
    // Неизвестный код не должен молчать: молчание выглядит как зависание.
    must(
      /if \(code\) return t\('auction\.failed'\)/.test(панель),
      'на неизвестный код клиент ничего не скажет'
    );
  });

  it('отмена лота не говорит про серебро', () => {
    // Отмена лота идёт через те же строки, что и выставление. Если перевод
    // подцепился к ней, игрок при отмене получал бы рассказ про пошлину.
    const отмена = панель.indexOf("t('auction.cancelled')");
    must(отмена > 0, 'не нашёл отмену лота в панели');
    const между = панель.slice(отмена, отмена + 1200);
    must(
      между.includes('auctionErrorMessage'),
      'отмена лота заговорила переводом пошлины: у неё свой перевод'
    );
  });
});

describe('Переводы пошлины', () => {
  it('надписи о нехватке серебра есть в трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(словарь.auction?.no_silver, `${код}.json: нет auction.no_silver`);
      must(словарь.auction.no_silver.includes('{fee}'), `${код}.json: в надписи нет {fee}`);
      must(словарь.auction?.failed, `${код}.json: нет запасного ключа auction.failed`);
    }
  });
});