// Тени стаи на земле.
//
// ЧТО БЫЛО (22 октября 2026, §284). Птицы летели над городом и пустыней, но
// на земле под ними было чисто: стая читалась только в небе. Тень от стаи,
// ползущая по мостовой, — самый верный признак, что над городом кто-то летит.
//
// ЧТО ТЕПЕРЬ. Под каждой птицей мягкое пятно на земле. Тень сдвинута от
// птицы в сторону, противоположную солнцу (в полдень она короткая, на закате
// длинная), лежит на настоящей высоте земли и гаснет ночью.
//
// ПОПУТНО. Фаза взмахов у птиц была по случайному числу — мир собирался
// по-разному при каждом запуске. Теперь фаза по хэшу.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ПТИЦЫ = читать('client/src/app/game3d/birds.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Тени стаи на земле', () => {
  it('у каждой птицы есть тень, и она лежит в сцене', () => {
    // Тень — отдельная плоскость под птицей.
    должен(
      /const тень = new THREE\.Mesh\(теньГео, теньМатериал\);/.test(ПТИЦЫ),
      'нет тени птицы',
    );
    должен(/scene\.add\(тень\);/.test(ПТИЦЫ), 'тень не добавлена в сцену: её не видно');
    // Тень мягкая: резкое пятно выдаёт подделку.
    должен(
      /createRadialGradient/.test(ПТИЦЫ) && /transparent: true/.test(ПТИЦЫ),
      'тень птицы не мягкая',
    );
  });

  it('тень лежит на земле, а высота меряется не каждый кадр', () => {
    // Высота земли — из общего источника правды, а не придуманная.
    должен(
      /п\.теньВысота = groundHeight\(sx, sz\);/.test(ПТИЦЫ),
      'тень не лежит на земле: высоты берутся не оттуда',
    );
    // Земля меряется дорого, поэтому не каждый кадр.
    должен(/const ТЕНЬ_ШАГ = \d+;/.test(ПТИЦЫ), 'нет шага замера земли');
    должен(
      /if \(кадр % ТЕНЬ_ШАГ === 0\) п\.теньВысота = groundHeight\(sx, sz\);/.test(ПТИЦЫ),
      'земля меряется каждый кадр: это съедает кадр',
    );
    // И тень к этой высоте подтягивается плавно, а не прыгает.
    должен(
      /п\.теньY \+= \(п\.теньВысота - п\.теньY\) \* Math\.min\(1, dt \* \d+\);/.test(ПТИЦЫ),
      'тень дёргается по высоте земли',
    );
  });

  it('тень сдвинута от птицы против солнца', () => {
    // Сдвиг — по направлению на солнце, и в сторону, противоположную ему.
    должен(
      /const sx = wx - солнцеX \* отступ;/.test(ПТИЦЫ) && /const sz = wz - солнцеZ \* отступ;/.test(ПТИЦЫ),
      'тень не сдвинута против солнца: она всегда под птицей',
    );
    // Чем ниже солнце, тем дальше тень.
    должен(
      /const отступ = Math\.min\(\d+, надЗемлёй \/ солнцеY\);/.test(ПТИЦЫ),
      'длина тени не зависит от высоты солнца',
    );
    // Солнце и ночь движок отдаёт стае.
    должен(
      /update\(dt: number, now: number, px: number, pz: number, ночь = \d+, солнце\?: THREE\.Vector3\)/.test(ПТИЦЫ),
      'стая не знает, где солнце и какая ночь',
    );
    должен(
      /this\.птицы\.update\(dt, now, me\.pos\.x, me\.pos\.z, night, sunDir\);/.test(МИР),
      'движок не отдаёт стае солнце и ночь',
    );
  });

  it('ночью тени нет, а сидящей птице тень на земле не нужна', () => {
    // Прозрачность от ночи: ночью птиц над землёй не видно.
    должен(
      /теньМатериал\.opacity = день \* \(0\.16 \+ 0\.46 \* Math\.min\(1, солнцеY\)\);/.test(ПТИЦЫ),
      'тень не гаснет ночью',
    );
    // Птица сидит на воде или на крыше — тени на земле под ней нет.
    должен(
      /п\.тень\.visible = теньМатериал\.opacity > 0\.01 && надЗемлёй > \d+ && сидит < 0\.5;/.test(ПТИЦЫ),
      'тень видна и там, где птица сидит',
    );
  });

  it('фаза взмахов по хэшу, а не по случайному числу', () => {
    должен(
      !/фаза: Math\.random\(\)/.test(ПТИЦЫ),
      'фаза взмахов по случайному числу: мир собирается по-разному',
    );
    должен(/фаза: hash2\(i, \d+\) \* 6\.28/.test(ПТИЦЫ), 'фаза взмахов не по хэшу');
  });
});
