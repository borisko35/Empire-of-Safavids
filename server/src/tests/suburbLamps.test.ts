// Свет в пригороде: окраина не должна быть выключенной.
//
// ЧТО БЫЛО (21 октября 2026, §247). У городских ворот и у мечети фонари
// есть, а в пригороде — только склады в темноте: с городской стены окраина
// читалась как выключенная.
//
// ЧТО ТЕПЕРЬ. Три фонаря в пригороде: у входа, между домами и у мельницы.
// Каждый — со столбом, чашей и огнём, и у каждого свой источник света.
//
// ЧТО ПРОВЕРЯЕТСЯ. Фонарей три, все с огнём и источником света, и стоят они по
// настоящей земле.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

/**
 * Кусок кода своего раздела.
 *
 * Без этого проверка цепляла чужой блок: строки фонарей в пригороде и на
 * проспектах совпадают слово в слово, и ломка «убери свет у фонарей
 * пригорода» молча правила фонари проспекта — а сторож этого не замечал.
 */
function свойРаздел(начало: string, конец: string): string {
  // Ищем по ИСХОДНИКУ: метки разделов — это комментарии, а в очищенном коде
  // их нет.
  const от = ТЕРРЕЙН.indexOf(начало);
  должен(от >= 0, `в коде нет раздела «${начало}»`);
  const до = ТЕРРЕЙН.indexOf(конец, от);
  должен(до > от, `в коде нет раздела «${конец}» после «${начало}»`);
  return ТЕРРЕЙН.slice(от, до).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const ПРИГОРОД = свойРаздел('── Свет в пригороде (§247) ──', '// Базар: два ряда лавок');

describe('Свет в пригороде', () => {
  it('в пригороде три фонаря, и у каждого огонь', () => {
    должен(
      /for \(const \[lx, lz\] of \[\[100, 92\], \[124, 108\], \[112, 82\]\] as const\)/.test(ПРИГОРОД),
      'фонарей в пригороде не три',
    );
    должен(
      /const огонь = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.16, 8, 6\), MAT\.lampGlow\)/.test(ПРИГОРОД),
      'у фонарей пригорода нет огня',
    );
  });

  it('фонари пригорода дают свет и стоят по земле', () => {
    должен(
      /lights\.push\(\{ x: CITY\.x \+ lx, z: CITY\.z \+ lz, y: city\.position\.y \+ земля \+ 3\.55 \}\)/.test(
        ПРИГОРОД,
      ),
      'фонари пригорода не получают источников света',
    );
    должен(
      /const земля = groundHeight\(CITY\.x \+ lx, CITY\.z \+ lz\) - city\.position\.y;/.test(ПРИГОРОД),
      'фонари пригорода стоят на зашитой высоте',
    );
  });
});
