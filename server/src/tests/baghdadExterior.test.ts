// Экстерьер Багдадской цитадели.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА. Рейд был построен с дверью в данных и интерьере, но
// без двери в мире: игрок, подойдя к цитадели в Месопотамии, находил
// пустой карман. Данные и мир расходились, и ни одна проверка этого не
// ловила — interiorSlots проверял только совпадение слотов.
//
// ЗАМЕР. Сетка 2 м по площади 80×80, функции высоты собраны из terrain.ts
// без графики: медиана 3.5, в центре 3.5, разброс 0.09 м. Земля уже почти
// идеально ровная, ровнялка фиксирует уровень, а не выравнивает склон.
// Сухо: isWater(200, −392) === false.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');
const ДАННЫЕ = читать('server/src/data/interiors.ts');

/** Блок постройки цитадели — от заголовка до следующего заголовка. */
function блокЦитадели(): string {
  const начало = ТЕРРЕЙН.indexOf('// ── Багдадская цитадель ─');
  must(начало > 0, 'нет блока постройки цитадели');
  // Ищем ПОСЛЕДНИЙ такой заголовок: их два — объявление и постройка, и
  // берётся нужный. Порядок: постройка идёт после объявления.
  const последний = ТЕРРЕЙН.lastIndexOf('// ── Багдадская цитадель ─');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', последний);
  must(конец > последний, 'конец блока не найден');
  return ТЕРРЕЙН.slice(последний, конец);
}

describe('Багдадская цитадель: площадка', () => {
  it('стоит там же, где дверь в данных и в интерьере', () => {
    // Три места обязаны совпадать: мир, интерьер клиента и интерьер сервера.
    // Расхождение любых двух означало бы, что дверь стоит не там, где вход.
    must(
      /export const BAGHDAD_CITADEL = \{ x: 200, z: -392,/.test(ТЕРРЕЙН),
      'площадка в мире не на месте двери',
    );
    must(
      /id: 'baghdad_citadel',[^}]*dx: 200, dz: -392, ex: 200, ez: -388/.test(ИНТЕРЬЕРЫ),
      'запись интерьера в клиенте не совпадает с миром',
    );
    must(
      /baghdad_citadel:\s*\{[\s\S]{0,240}?doorX: 200, doorZ: -392, exitX: 200, exitZ: -388/.test(ДАННЫЕ),
      'дверь на сервере не совпадает с миром',
    );
  });

  it('уровень равен замеренной медиане', () => {
    const m = /export const BAGHDAD_CITADEL = \{ x: 200, z: -392, radius: (\d+), level: (-?[\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'уровень или радиус не объявлены');
    const уровень = Number(m![2]);
    must(
      Math.abs(уровень - 3.5) < 0.05,
      `уровень ${уровень} разошёлся с замером: медиана была 3.5`,
    );
  });

  it('запас ровной части достаточен для двора и ворот', () => {
    const m = /export const BAGHDAD_CITADEL = \{ x: 200, z: -392, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус не объявлен');
    const ровная = Number(m![1]) * 0.55;
    // Двор 26×14 и пост ворот в 8.8 м от центра — полудиагональ двора
    // около 15 м плюс запас на стену.
    must(ровная - Math.hypot(26 / 2 + 1.8, 14 / 2 + 1.0) >= 2, 'запас ровной части мал');
  });

  it('ровнялка стоит после ровнялки крепости', () => {
    const код = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export function terrainHeight'),
      ТЕРРЕЙН.indexOf('const TERRAIN_SEG'),
    );
    must(
      код.indexOf('BAGHDAD_CITADEL.x') > код.indexOf('CAUCASUS_FORT.x'),
      'ровнялка цитадели не после крепости: порядок определяет, что на что наезжает',
    );
  });

  it('центр сухой', () => {
    must(!isWater(200, -392), 'под цитаделью вода');
  });
});

describe('Багдадская цитадель: дверь и подход', () => {
  it('дверь кликабельная и ведёт в интерьер', () => {
    const блок = блокЦитадели();
    must(/doorBuilding: 'baghdad_citadel'/.test(блок), 'нет doorBuilding');
    must(/doorAction: 'enter'/.test(блок), 'дверь не ведёт внутрь');
    must(/doorName: t\('buildings\.baghdad_citadel'\)/.test(блок), 'не то название');
  });

  it('портал шире крепостного: двадцать человек входят в рейд', () => {
    const m = /export const BAGHDAD_CITADEL_GEO = \{[\s\S]*?ворота: \{ w: ([\d.]+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'ворота цитадели не объявлены');
    const ширина = Number(m![1]);
    const крепость = /export const CAUCASUS_FORT_GEO = \{[\s\S]*?ворота: \{ w: ([\d.]+)/.exec(ТЕРРЕЙН);
    must(крепость !== null, 'ворота крепости не объявлены');
    must(
      ширина > Number(крепость![1]),
      `портал ${ширина} не шире крепостного ${крепость![1]}: рейд на 20 человек вжался бы в очередь`,
    );
  });

  it('стена, зубцы и коллайдеры на месте', () => {
    const блок = блокЦитадели();
    must(/MAT\.sandstoneDark/.test(блок), 'стены нет');
    must(/зубец/.test(блок), 'зубцов нет');
    // Коллайдеры обязаны быть у стен и столбов, иначе игрок проходит сквозь
    // цитадель, а дверь остаётся недостижимой с другой стороны.
    const коллайдеры = блок.match(/addCollider\(/g) ?? [];
    must(коллайдеры.length >= 3, `коллайдеров ${коллайдеры.length}, стены и посты без них пройдёшь насквозь`);
  });

  it('дверь не завалена: проём остаётся свободным', () => {
    // Прутья только у краёв, середина проёма пустая. Иначе двадцать
    // человек шли бы в стену, и кнопка «войти партией» работала бы вручную.
    const блок = блокЦитадели();
    const m = /for \(const s of \[-1, 1\] as const\) \{\s*\n\s*for \(let i = 0; i < 4; i\+\+\) \{\s*\n\s*const bx = s \* \(1\.6 \+ i \* 1\.5\)/.exec(блок);
    must(m !== null, 'прутья в проёме ставятся не только у краёв');
  });
});

describe('Багдадская цитадель: оформление постройки', () => {
  it('внешние размеры цитадели больше крепостных', () => {
    const цитадель = /export const BAGHDAD_CITADEL_GEO = \{([\s\S]*?)\} as const/.exec(ТЕРРЕЙН);
    must(цитадель !== null, 'геометрия цитадели не объявлена');
    must(/стена: \{ w: 30, h: 4\.2/.test(цитадель![1]), 'стена цитадели не выше и не длиннее крепостной');
  });

  it('постройка стоит в конце списка, а не в середине', () => {
    // Как и с интерьерами: порядок здесь ничего не сдвигает численно,
    // но блок, вставленный в середину, разъедется с объявлением и
    // окажется перед акведуком, который к нему отношения не имеет.
    const постройка = ТЕРРЕЙН.lastIndexOf('// ── Багдадская цитадель ─');
    const акведук = ТЕРРЕЙН.indexOf('// ── Акведук деревни', постройка);
    must(постройка > 0 && акведук > постройка, 'постройка цитадели не перед акведуком');
  });
});