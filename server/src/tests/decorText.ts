/**
 * Общие помощники для проверок декора.
 *
 * ВЫРЕЗКА БЛОКА ПО СЛЕДУЮЩЕЙ ЭКСПОРТИРУЕМОЙ ФУНКЦИИ, А НЕ ПО ЗАГОЛОВОЧНОМУ
 * КОММЕНТАРИЮ.
 *
 * Проверки декора читают terrain.ts как текст и вырезают из него кусок функции,
 * чтобы посчитать вызовы placeDecor и addCollider. Границей раньше служил
 * заголовок вроде «// ── Факелы у ворот» — то есть ДАЛЁКИЙ комментарий, между
 * которым и функцией может оказаться любая новая вставка.
 *
 * Так и вышло: сундук вставлен перед этим комментарием, вырезка меча захватила
 * его целиком, проверка увидела два вызова placeDecor вместо одного и упала на
 * совершенно правильном коде. Комментарий — не граница. Граница — следующая
 * `export function`: она есть всегда, потому что следующая постройка описана
 * функцией.
 *
 * По той же причине этим помощником пользуются все проверки декора, а не одна:
 * повторять такую границу в каждом файле — значит повторять и ошибку.
 */

/**
 * Текст экспортируемой функции: от её заголовка до следующей `export function`
 * либо `export const`, whichever comes first.
 *
 * Обе формы — потому что в terrain.ts вперемешку и `export function`, и
 * `export const`: константа следующей постройки тоже должна закрывать вырезку,
 * иначе она в неё попадёт.
 */
export function блокЭкспортируемой(исходник: string, заголовок: string): string {
  const начало = исходник.indexOf(заголовок);
  if (начало < 0) {
    throw new Error(`${заголовок} не найден в файле`);
  }
  const остаток = исходник.slice(начало + заголовок.length);
  const следующаяФункция = остаток.search(/\nexport (?:function|const) /);
  if (следующаяФункция < 0) {
    // Дальше ничего нет — блок до конца файла.
    return исходник.slice(начало);
  }
  return исходник.slice(начало, начало + заголовок.length + следующаяФункция);
}

/**
 * Аргументы единственного вызова функции в куске кода.
 *
 * Разбор по запятым с учётом вложенных скобок. Наивная регулярка съедала ноль с
 * точкой у радиуса и рапортовала 3 аргумента вместо 0.3, то есть проверка
 * коллайдера проверяла не то число.
 */
export function аргументыВызова(код: string, имя: string): string[] {
  const начало = код.indexOf(`${имя}(`);
  if (начало < 0) return [];
  let глубина = 0;
  let текущее = '';
  const части: string[] = [];
  for (let i = начало + имя.length + 1; i < код.length; i++) {
    const символ = код[i];
    if (символ === '(' || символ === '[') {
      глубина++;
    } else if (символ === ')' && глубина === 0) {
      части.push(текущее.trim());
      return части.filter((с) => с !== '');
    } else if (символ === ')' || символ === ']') {
      глубина--;
    } else if (символ === ',' && глубина === 0) {
      части.push(текущее.trim());
      текущее = '';
      continue;
    }
    текущее += символ;
  }
  return части;
}