// Фонари на караванах.
//
// ЧТО БЫЛО (21 октября 2026, §254). Караваны ходят по дальним дорогам и
// ночью, и в темноте читались чёрными силуэтами: дорога была пуста, а
// верблюды с тюками шли невидимыми.
//
// ЧТО ТЕПЕРЬ. У головы каждой колонны — фонарь: золотая коробка с огнём и
// колпаком, и свой источник света, который едет вместе с караваном. Ночное
// правило то же, что у городских фонарей: днём тише, ночью в полную силу.
//
// ЧТО ПРОВЕРЯЕТСЯ. Фонарь есть у каждой колонны, источник света создан и
// едет вместе с караваном, сила зависит от времени суток, а вдали свет гаснет
// (каравана не видно, а источник в сцене всё равно стоит кадру).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ДОРОГИ = читать('client/src/app/game3d/roadTraffic.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Фонари на караванах', () => {
  it('у каждой колонны есть фонарь у головы', () => {
    должен(/function makeLantern\(\)/.test(ДОРОГИ), 'нет фонаря каравана');
    // Фонарь с огнём и колпаком — не пустая коробка.
    должен(
      /const огонь = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.08, 8, 6\), M\.fire\)/.test(ДОРОГИ),
      'в фонаре каравана нет огня',
    );
    должен(/const колпак = new THREE\.Mesh\(new THREE\.ConeGeometry/.test(ДОРОГИ),
      'фонарь каравана не закончен колпаком');
    // Фонарь вешается на голову колонны.
    должен(
      /const глава = column\[0\];[\s\S]{0,300}?глава\.group\.add\(фонарь\.группа\)/.test(ДОРОГИ),
      'фонарь не у головы колонны',
    );
  });

  it('источник света едет вместе с караваном и горит по ночному правилу', () => {
    должен(
      /const свет = new THREE\.PointLight\(0xffa04a, 0, 18, 1\.8\);/.test(ДОРОГИ),
      'у фонаря каравана нет источника света',
    );
    должен(/scene\.add\(свет\);/.test(ДОРОГИ), 'источник света каравана не в сцене');
    // Источник считает своё место от головы колонны: позиция берётся из
    // координат лидера, а поворот — из его угла.
    должен(
      /const a = ф\.лидер\.group\.rotation\.y;/.test(ДОРОГИ),
      'источник света не знает, куда повёрнут караван',
    );
    должен(
      /ф\.свет\.position\.set\([\s\S]{0,200}?ф\.локX \* ca \+ ф\.локZ \* sa/.test(ДОРОГИ),
      'источник света не едет вместе с караваном',
    );
    должен(
      /ф\.свет\.intensity = 1\.6 \* \(0\.35 \+ night \* 0\.65\);/.test(ДОРОГИ),
      'фонарь каравана не горит по ночному правилу',
    );
    // Вдали свет гаснет.
    должен(
      /Math\.hypot\(p\.x - px, p\.z - pz\) > VISIBLE_DIST\) \{\s*ф\.свет\.intensity = 0;/.test(ДОРОГИ),
      'вдали фонарь каравана всё равно светит',
    );
    // Ночь приходит из движка: сервер задаёт время суток.
    должен(
      /this\.roadTraffic\.update\(dt, now, me\.pos\.x, me\.pos\.z, night\)/.test(МИР),
      'движок не передаёт время суток дорожному движению',
    );
  });
});
