// Тип тени должен быть ЖИВЫМ в рендере, а не только объявленным.
//
// ЧТО ЗАБЫЛИ И ЧТО ВЫШЛО. В §132 я прочитал в three.core.js строку
// `const PCFSoftShadowMap = 2`, решил, что тип жив, и включил его. Рендер
// тихо взял PCFShadowMap и написал в консоль:
//
//   THREE.WebGLShadowMap: PCFSoftShadowMap has been removed.
//   Using PCFShadowMap instead.
//
// То есть игра работала ровно на том, с чего я её убирал. Исходный
// комментарий проекта «мягкие тени вырезаны из Three.js» был ПРАВ — я
// отменил верное утверждение.
//
// ПОЧЕМУ ПРОВЕРКА НЕ СРАБОТАЛА. Она смотрела, объявлена ли константа, и
// константа объявлена. Константа и её реализация — разные вещи: тип могли
// убрать из рендера, оставив имя в экспортах ради совместимости.
//
// ЧТО ПРОВЕРЯЕТСЯ ТЕПЕРЬ. three предупреждает УСТАНОВКОЙ типа, когда он не
// поддерживается. Значит надёжный признак — ищем в сборке рендера это
// предупреждение. Типа, который three отвергает, в мире быть не должно.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/world3d.ts');
const НАСТРОЙКИ = читать('client/src/app/settings.ts');
// Рендер живёт в module-сборке: объявления констант в core, а код — здесь.
const РЕНДЕР = читать('client/node_modules/three/build/three.module.js');

/** Типы, которые three отвергает при установке: имя -> предупреждение. */
function отвергаемые(): string[] {
  const имена = new Set<string>();
  const образец = /warn\(\s*'WebGLShadowMap:\s*(\w+)\s+has been removed/g;
  let м: RegExpExecArray | null;
  while ((м = образец.exec(РЕНДЕР)) !== null) {
    if (м[1]) имена.add(м[1]);
  }
  return [...имена];
}

describe('Тип тени жив в рендере', () => {
  it('three вообще предупреждает о неподдерживаемых типах (якорь)', () => {
    // Если разбор перестанет находить предупреждения, все проверки ниже
    // молча превратятся в «тип поддерживается» — и будут врать.
    const отвергнутые = отвергаемые();
    должен(
      отвергнутые.length > 0,
      'в three.module.js не найдено ни одного предупреждения об удалённых типах: проверка потеряла смысл',
    );
  });

  it('мир не выбирает тип, который three отвергает', () => {
    for (const имя of отвергаемые()) {
      должен(
        !new RegExp(`shadowMap\\.type\\s*=\\s*THREE\\.${имя}\\b`).test(МИР),
        `мир выбирает ${имя}, а three его удалил: кадр тихо откатится на другой тип, а в консоли будет предупреждение`,
      );
      должен(
        !new RegExp(`p\\.shadows\\s*\\?\\s*THREE\\.${имя}\\b`).test(МИР),
        `профиль графики предлагает ${имя}, который three отвергает`,
      );
    }
  });

  it('мягкие тени — это VSM, и он действительно реализован', () => {
    // VSM — единственный оставшийся источник мягкой кромки: размывает по
    // площади, тогда как PCF берёт жёсткую выборку.
    должен(
      /this\.renderer\.shadowMap\.type\s*=\s*THREE\.VSMShadowMap/.test(МИР),
      'мир не перешёл на VSMShadowMap: мягкой кромки не будет',
    );
    // И размытие включено - без radius и blurSamples VSM жёстче PCF.
    должен(/shadow\.radius\s*=\s*\d+/.test(МИР), 'у VSM не задан радиус размытия: кромка останется жёсткой');
    должен(/shadow\.blurSamples\s*=\s*\d+/.test(МИР), 'у VSM не задано число проходов размытия');
  });

  it('VSM поддерживается рендером, а не только объявлен', () => {
    // Тот же класс ошибки, что и с PCFSoft: проверяем не имя, а код.
    должен(
      /SHADOWMAP_TYPE_VSM/.test(РЕНДЕР),
      'в сборке рендера нет SHADOWMAP_TYPE_VSM: VSM там не реализован',
    );
    должен(
      new RegExp(`this\\.type\\s*===\\s*VSMShadowMap`).test(РЕНДЕР),
      'в рендере нет ветки обработки VSM: тип не поддерживается',
    );
  });

  it('в настройках нет утверждения, которое однажды сбило с толку', () => {
    // Раньше там стояло «мягкие тени вырезаны из Three.js». Это было
    // ПРАВДОЙ, и я его отменил по слабой проверке. Формулировка теперь
    // другая, чтобы никто не переспорил её обратно.
    должен(
      !/вырезаны/.test(НАСТРОЙКИ),
      'в settings.ts вернулась старая формулировка о типах теней — разбираться заново придётся следующему',
    );
  });
});