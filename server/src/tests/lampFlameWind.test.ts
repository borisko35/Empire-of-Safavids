// Огни фонарей колышутся от ветра.
//
// ЧТО БЫЛО (22 октября 2026, §282). Огонь в каждом фонаре мерцал по-своему,
// но общего ветра не было: в бурю огонь стоял ровно, как в штиль. Ночной
// город в шторм не выдавал погоду.
//
// ЧТО ТЕПЕРЬ. Огонь наклоняется по ветру, и в бурю колышется сильнее. Тот же
// ветер, что качает зелень (§281), — ветер в мире один.
//
// ЧТО ПРОВЕРЯЕТСЯ. Огни фонарей записаны списком с исходной позой, движок
// наклоняет их по направлению ветра, и сила наклона зависит от погоды.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Огни фонарей колышутся', () => {
  it('огни фонарей записаны с исходной позой', () => {
    должен(
      /export const огниФонарей: \{ mesh: THREE\.Mesh; base: THREE\.Vector3 \}\[\] = \[\];/.test(ТЕРРЕЙН),
      'нет списка огней фонарей',
    );
    // Огонь записывается в том самом фонаре, который строит общий помощник.
    должен(
      /огниФонарей\.push\(\{ mesh: огонь, base: огонь\.position\.clone\(\) \}\);/.test(ТЕРРЕЙН),
      'огонь фонаря не записан: наклонять нечего',
    );
  });

  it('движок наклоняет огни по ветру, и сила зависит от погоды', () => {
    должен(/for \(const о of огниФонарей\)/.test(МИР), 'огни фонарей не наклоняются');
    // Наклон по направлению ветра, сила — от силы ветра в погоде.
    должен(
      /const сдвиг = наклон \* ветер \* 0\.06;/.test(МИР),
      'наклон огня не зависит от силы ветра',
    );
    // И огонь уходит из основания и возвращается: без этого он был бы
    // прибит к чаше.
    должен(
      /о\.mesh\.position\.set\(\s*о\.base\.x \+ Math\.sin\(НАПРАВЛЕНИЕ_ВЕТРА\) \* сдвиг,/.test(МИР),
      'огонь не сдвигается по ветру',
    );
  });
});
