// Свет от факелов караван-сарая: решение владельца «оранжево-яркий».
//
// ЧТО ЭТО ЗАКРЕПЛЯЕТ. До этого у факелов не было источника света вовсе, и в
// коде стояла заметка, что решение не принято. Владелец принял: «оранжево-
// яркий». Здесь закреплено всё, что из этого решения следует, потому что
// «оранжево-яркий» легко испортить тремя способами: взять не тот оттенок,
// поставить свет выше пламени и оставить все огни мигающими в такт.
//
// ЧТО ЛОВИТСЯ И ПОЧЕМУ ТАК.
// 1. Факелы вообще заводят источники света. Раньше их не было, и проверка
//    ругалась бы на отсутствие — теперь на отсутствие ругаться нельзя.
// 2. СВЕТ ОРАНЖЕВЫЙ. Оттенок читается из кода и сверяется по каналам: синий и
//    зелёный должны быть заметно ниже красного. Свет «белый» при выбранной
//    яркости выглядит как прожектор, а не как огонь.
// 3. ЯРЧЕ ГОРОДСКИХ ФАКЕЛОВ. Владелец сказал «яркий», а городские факелы — это
//    base 1.6. Если новые окажутся не ярче, то решение «яркий» не выполнено,
//    хотя формально источник есть.
// 4. ВЫСОТА СВЕТА ВЫВЕДЕНА ИЗ МОДЕЛИ, А НЕ ВЗЯТА НА ГЛАЗ. У факела пять
//    частей, и пламя опознаётся по файлу: это часть с самой высокой верхней
//    границей. Её центр минус утопление факела и есть высота света. Проверка
//    сама читает модель и считает — если в модели или в утоплении что-то
//    поменяется, проверка упадёт, а не промолчит.
// 5. СВЕТ НЕ ВЫШЕ ПЛАМЕНИ. Свет выше огня даёт шар в воздухе без источника.
// 6. СВЕТ НИЖЕ НИЗА ПЛАМЕНИ — тогда он светит из земли.
// 7. ДАЛЬНОСТЬ БОЛЬШЕ ВЫСОТЫ СВЕТА. Иначе свет гаснет раньше, чем кончается
//    пламя, и факел освещает только землю под собой.
// 8. ФАЗА У КАЖДОГО ОГНЯ СВОЯ. Раньше фаза считалась как `base * 7`, а у всех
//    городских факелов base одинаковый: два десятка огней мигали синхронно, а
//    два факела у ворот стоят в двух шагах друг от друга и мигали бы в унисон.
// 9. Обновление мерцания читает фазу из записи, а не вычисляет её из base.
//    Пока в коде стояло `t.base * 7`, поле phase было бы мёртвым.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

interface GlbJson {
  meshes?: { primitives?: { material?: number; attributes: { POSITION: number } }[] }[];
  accessors?: { min: number[]; max: number[] }[];
}

const ФАЙЛ = join(корень, 'client/src/app/public/models/decor/torch.glb');

function jsonGlb(путь: string): GlbJson {
  const буфер = readFileSync(путь);
  must(буфер.readUInt32LE(0) === 0x46546c67, `${путь}: это не GLB`);
  const длина = буфер.readUInt32LE(12);
  return JSON.parse(буфер.subarray(20, 20 + длина).toString('utf-8')) as GlbJson;
}

/** Все части факела с их вертикальными границами. */
function части(): { низ: number; верх: number; высота: number; ширина: number }[] {
  const gltf = jsonGlb(ФАЙЛ);
  const список: { низ: number; верх: number; высота: number; ширина: number }[] = [];
  for (const меш of gltf.meshes ?? []) {
    for (const примитив of меш.primitives ?? []) {
      const accessor = (gltf.accessors ?? [])[примитив.attributes.POSITION];
      список.push({
        низ: accessor.min[1],
        верх: accessor.max[1],
        высота: accessor.max[1] - accessor.min[1],
        ширина: accessor.max[0] - accessor.min[0],
      });
    }
  }
  must(список.length > 0, 'в факеле нет ни одной части');
  return список;
}

/**
 * Пламя: часть с самой высокой верхней границей.
 *
 * Не по имени материала: имена в модели — `lambert4`…`lambert8`, то есть
 * бесполезные. Не по ширине: ширину имеют и заклёпки. А верхняя граница у
 * пламени одна на весь факел, и она выше всего остального.
 */
function пламя(): { низ: number; верх: number; центр: number } {
  const верхняя = части().reduce((а, б) => (б.верх > а.верх ? б : а));
  return { низ: верхняя.низ, верх: верхняя.верх, центр: (верхняя.низ + верхняя.верх) / 2 };
}

function число(константа: string): number {
  const м = new RegExp(`export const ${константа} = ([\\dxa-fA-F0-9.]+)`).exec(ТЕРРЕЙН);
  must(м !== null, `не нашлась константа ${константа}`);
  const текст = м![1];
  // Шестнадцатеричное и десятичное в одном поле.
  //
  // Первая версия разбирала только десятичное число, и цвет света 0xffa04a
  // превращался в ноль: проверка радостно сообщала «свет чёрный», а не «свет
  // белый». Оттенок задан именно как 0x..., то есть исключать префикс нельзя.
  return текст.toLowerCase().startsWith('0x') ? parseInt(текст, 16) : Number(текст);
}

describe('Факел: источник света', () => {
  it('факелы завели источники света', () => {
    must(existsSync(ФАЙЛ), 'файла факела нет на диске');
    must(statSync(ФАЙЛ).size > 0, 'файл факела пуст');
    must(
      /new THREE\.PointLight\(\s*ТОРЧ_СВЕТ_ЦВЕТ/.test(МИР),
      'у факелов нет PointLight: до решения владельца источника не было, ' +
        'и это надо ловить отдельно',
    );
    // Функция обязана отдавать точки света, иначе источник некуда поставить.
    // Прежде она возвращала void, и свет просто некуда было повесить.
    must(
      /export function buildCaravanseraiTorches\(scene: THREE\.Scene\): \{ x: number; y: number; z: number \}\[]/.test(
        ТЕРРЕЙН,
      ),
      'buildCaravanseraiTorches не возвращает точки света',
    );
    // И мир обязан эти точки разобрать и повесить источники.
    must(
      /for \(const \[[^\]]+\] of buildCaravanseraiTorches\(this\.scene\)[\w.()]*\)/.test(МИР),
      'мир не разбирает точки света от buildCaravanseraiTorches',
    );
    must(
      /ТОРЧ_СВЕТ_ЯРКОСТЬ/.test(МИР) && /ТОРЧ_СВЕТ_ДАЛЬНОСТЬ/.test(МИР),
      'мир не использует яркость и дальность из terrain.ts: ' +
        'значения заданы там, а тут подставлены свои',
    );
  });

  it('свет оранжевый, а не белый', () => {
    const цвет = число('ТОРЧ_СВЕТ_ЦВЕТ');
    const красный = (цвет >> 16) & 0xff;
    const зелёный = (цвет >> 8) & 0xff;
    const синий = цвет & 0xff;
    must(
      красный > зелёный && красный > синий,
      `свет 0x${цвет.toString(16)} не оранжевый: ` +
        `красный ${красный}, зелёный ${зелёный}, синий ${синий}. ` +
        'Белый свет при выбранной яркости читается как прожектор',
    );
    must(
      красный - синий > 100,
      `свет 0x${цвет.toString(16)} слишком близок к белому: ` +
        'разница красного и синего ' + `${красный - синий} должна быть больше 100`,
    );
  });

  it('ярче городских факелов: решение «яркий» выполнено', () => {
    // Городские факелы заводятся с base 1.6 — читается из кода, а не взято
    // из памяти.
    const городской = /\.push\(\{ light, base: ([\d.]+), phase:/.exec(МИР);
    must(городской !== null, 'не разобралась яркость городских факелов');
    const своя = число('ТОРЧ_СВЕТ_ЯРКОСТЬ');
    must(
      своя > Number(городской![1]),
      `факел у ворот яркостью ${своя}, городские ${городской![1]}: ` +
        'владелец просил яркий свет, и при равной яркости решение не выполнено',
    );
  });

  it('высота света выведена из модели, а не подобрана на глаз', () => {
    const п = пламя();
    const утоплено = число('ТОРЧ_УТОПЛЕН');
    const высота = число('ТОРЧ_СВЕТ_ВЫСОТА');
    const ожидается = п.центр - утоплено;
    must(
      Math.abs(высота - ожидается) < 0.01,
      `высота света ${высота} м, а из модели выходит ${ожидается.toFixed(4)}: ` +
        `пламя ${п.низ.toFixed(4)}…${п.верх.toFixed(4)}, утопление ${утоплено}. ` +
        'Если модель или утопление поменялись, пересчитать высоту',
    );
  });

  it('свет не выше пламени и не ниже его низа', () => {
    const п = пламя();
    const утоплено = число('ТОРЧ_УТОПЛЕН');
    const высота = число('ТОРЧ_СВЕТ_ВЫСОТА');
    const верхПламени = п.верх - утоплено;
    const низПламени = п.низ - утоплено;
    must(
      высота <= верхПламени,
      `свет на ${высота} м, а пламя кончается на ${верхПламени.toFixed(4)}: ` +
        'свет выше огня даёт шар в воздухе без источника',
    );
    must(
      высота >= низПламени - 0.05,
      `свет на ${высота} м, а пламя начинается на ${низПламени.toFixed(4)}: ` +
        'свет ниже пламени светит из земли',
    );
  });

  it('дальность больше высоты света', () => {
    // Иначе свет гаснет раньше, чем кончается пламя, и факел освещает только
    // землю под собой.
    const высота = число('ТОРЧ_СВЕТ_ВЫСОТА');
    const дальность = число('ТОРЧ_СВЕТ_ДАЛЬНОСТЬ');
    must(
      дальность > высота,
      `дальность ${дальность} м при высоте света ${высота} м: ` +
        'свет гаснет раньше, чем кончается пламя',
    );
  });

  it('фаза у каждого огня своя', () => {
    // Каждый, кто добавляется в this.torches, получает phase. Поле обязано
    // быть у всех записей: одна запись без фазы даст undefined, и Math.sin с
    // undefined вернёт NaN — свет станет NaN и исчезнет.
    const добавления = [...МИР.matchAll(/this\.torches\.push\(\{([^}]*)\}\)/g)].map((м) => м[1]);
    must(добавления.length > 0, 'в мире нет ни одного источника в this.torches');
    for (const запись of добавления) {
      must(
        /phase:/.test(запись),
        `в this.torches.push({${запись}}) нет phase: без фазы свет мигает ` +
          'по NaN и исчезает',
      );
    }
    // ФАЗЫ РАЗНЫЕ — И ЭТО ПРОВЕРЯЕТСЯ ПО ВЫРАЖЕНИЯМ, А НЕ ПО ЗНАЧЕНИЯМ.
    //
    // Первая версия вытаскивала числа регуляркой /phase: ([\d.]+)/ и находила
    // ровно два: литерал 5.5 у костра и ничего у остальных, потому что фазы
    // городских огней и ворот считаются от индекса — `i * 2.4` и
    // `1.1 + i * 3.7`. Числа там нет, и проверка объявила «две фазы на два
    // огня», то есть синхронное мерцание, которого в коде нет.
    //
    // Что действительно надо поймать: одинаковые ВЫРАЖЕНИЯ фазы. Тогда все
    // огни получают одну и ту же фазу независимо от индекса и мигают в такт.
    const выражения = добавления.map((запись) => {
      const м = /phase: ([^,}]+)/.exec(запись);
      must(м !== null, `в записи без фазы: {${запись}}`);
      return м![1].trim();
    });
    must(
      выражения.length === добавления.length,
      `найдено ${выражения.length} фаз при ${добавления.length} источниках: ` +
        'потерялась запись без phase',
    );
    const уникальные = new Set(выражения);
    must(
      уникальные.size === выражения.length,
      `разных выражений фазы ${уникальные.size} при ${выражения.length} огнях ` +
        `(${выражения.join(" | ")}): одинаковая формула даёт синхронное ` +
        'мерцание, а два факела у ворот стоят в двух шагах друг от друга',
    );
    // И ни одна фаза не выводится из base: у всех городских факелов base
    // одинаковый, поэтому `base * 7` у всех даёт одно и то же.
    for (const выражение of выражения) {
      must(
        !/\bbase\b/.test(выражение),
        `фаза «${выражение}» считается от base: у всех городских факелов base ` +
          'одинаковый, то есть фаза одинаковая и огни мигают в такт',
      );
    }
  });

  it('обновление мерцания берёт фазу из записи, а не вычисляет из base', () => {
    must(
      /Math\.sin\(now \/ 90 \+ t\.phase\)/.test(МИР),
      'мерцание не использует t.phase: пока в коде стояло `t.base * 7`, ' +
        'поле phase было бы мёртвым, а все огни мигали в такт',
    );
    must(
      !/t\.base \* 7/.test(МИР),
      'в коде осталась старая формула фазы `t.base * 7`: у всех городских ' +
        'факелов base одинаковый, то есть они мигают синхронно',
    );
  });

  it('фазы огней в цикле зависят от индекса, а не константы', () => {
    // ВОТ ЧЕГО НЕ ХВАТАЛО ПРЕЖДЕ.
    //
    // Проверка требовала, чтобы ВЫРАЖЕНИЯ фаз различались, и этого
    // недостаточно: два разных выражения могут давать одно и то же число для
    // каждого элемента цикла:
    //
    //     phase: i * 2.4      и      phase: 2.4 * 2.4
    //
    // Второе выражение уникально и не содержит base, а фаза у всех огней этой
    // строки одинаковая — два десятка фонарей мигают в такт, и ни одна
    // проверка этого не видит. Слабая ломка на это и наткнулась: подставив
    // константу вместо выражения с индексом, она не сломала ничего.
    //
    // Настоящее свойство: у огней, которые заводятся В ЦИКЛЕ, фаза обязана
    // зависеть от индекса. Константа допустима только для костра — он один,
    // и мигать в такт ему не с кем.
    const записи = [...МИР.matchAll(/this\.torches\.push\(\{([^}]*)\}\)/g)].map((м) => м[1]);
    must(записи.length > 0, 'в мире нет ни одного источника в this.torches');
    const отИндекса = записи.filter((запись) => {
      const м = /phase: ([^,}]+)/.exec(запись);
      return м !== null && /\bi\b|\bindex\b/.test(м[1]);
    });
    must(
      отИндекса.length >= 2,
      `фаз, зависящих от индекса, ${отИндекса.length} при ${записи.length} ` +
        'источниках: огни, которые заводятся в цикле, обязаны мигать не в такт',
    );
  });

  it('свет выключается тем же torchOn, что и городские факелы', () => {
    // Иначе факел у ворот горит в полную силу среди дня, а городские гаснут,
    // и в одном кадре видно два разных правила освещения.
    must(
      /const torchOn = 0\.35 \+ night \* 0\.65;/.test(МИР),
      'не найден torchOn: факелы должны включаться тем же правилом, что и в городе',
    );
    const цикл = /\.forEach|for \(const t of this\.torches\)[\s\S]{0,200}torchOn/.test(МИР);
    must(
      цикл,
      'цикл мерцания не использует torchOn: факел будет гореть на полную силу днём',
    );
  });
});