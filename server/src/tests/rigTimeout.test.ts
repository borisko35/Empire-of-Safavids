// Модель, которая не пришла, не держит мир вечно (§342).
//
// ЧТО БЫЛО. Если GLTFLoader не зовёт ни onLoad, ни onError (тишина), обещание
// висит вечно: NPC остаётся процедурным, дерево не появляется, и в консоли
// ни строки. Именно так торговец на площади простоял конусом (§341), а
// платаны «не рисовались» (§330).
//
// ЧТО ТЕПЕРЬ. У загрузки сцены есть таймаут 60 с: по нему обещание сбывается
// с null и пишется предупреждение с именем модели.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РИГ = читать('client/src/app/game3d/realRig.ts');

describe('Загрузка сцены: таймаут', () => {
  it('таймаут объявлен и применяется к сцене', () => {
    должен(/const ТАЙМАУТ_МОДЕЛИ_МС = 60000;/.test(РИГ),
      'нет таймаута: висящая загрузка снова будет вечной');
    const блок = /export function загрузитьСцену[\s\S]*?сцены\.set/.exec(РИГ)?.[0] ?? '';
    должен(/setTimeout\(/.test(блок), 'таймер не ставится в загрузке сцены');
    должен(/net otveta za \$\{ТАЙМАУТ_МОДЕЛИ_МС\} ms/.test(блок),
      'о таймауте не сообщается: причина снова спрячется');
  });

  it('успех и отказ снимают таймер', () => {
    const блок = /export function загрузитьСцену[\s\S]*?сцены\.set/.exec(РИГ)?.[0] ?? '';
    должен(/clearTimeout\(таймер\)/.test(блок),
      'таймер не снимается: после загрузки прилетит ложное предупреждение');
    должен(/const ответить = \(значение: THREE\.Group \| null\)/.test(блок),
      'нет единой точки ответа: успех/отказ/таймаут могут сработать дважды');
    const ответов = (блок.match(/ответить\(/g) || []).length;
    должен(ответов >= 4, `точек ответа ${ответов}: часть путей мимо страховки`);
  });
});
