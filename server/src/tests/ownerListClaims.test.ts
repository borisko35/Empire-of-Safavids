// Список локаций владельца не должен устареть: четыре утверждения из него уже неверны.
//
// ЗАЧЕМ ФАЙЛ. В списке локаций есть колонка «состояние», и по его же правилам она должна
// быть «проверена по коду либо честно помечена не измеренной». Проверка показала, что
// четыре утверждения устарели - то есть код уехал вперёд, а карта осталась на месте:
//
//   1. «ночью считается только как условие для диалогов». Ночь считается скрытностью:
//      NIGHT_SIGHT = 0.5 вычитается из обзора стража (shared/stealth.ts).
//   2. «осада: следов 9, территории 8 - система есть, но застроена ли она, не измерено».
//      Территорий 4, а не 8, и система подключена: GameLoop её запускает, GameSocketHandler
//      наносит урон, есть REST-эндпоинт. То есть не «не измерено», а «сделано».
//   3. Гробница: «уведомление о завершении захода получают только участники-убийцы, и
//      приглашение зовёт только друзей». И то и другое уже исправлено: DungeonCompleteInfo
//      несёт shares на каждого участника, а список приглашения - игроки региона.
//   4. «репутация и фракции: как система прогрессии - не измерено». Репутацию читают
//      тринадцать файлов, включая аукцион, торговлю, квесты, PvP и подземелья.
//
// ЧТО ДЕЛАЕТ ФАЙЛ. Каждое исправленное утверждение закреплено проверкой. Без этого карта
// снова устареет молча: устаревшее утверждение выглядит ровно так же, как верное.

import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(__dirname, '..', '..', '..');

function читать(часть: string): string {
  return readFileSync(join(ROOT, часть), 'utf-8');
}

/** Ищет файл по имени в server/src и shared: путь не угадывается, а находится. */
const найдено = new Map<string, string>();
function найтиФайл(имя: string): string | null {
  if (найдено.has(имя)) return найдено.get(имя)!;
  let ответ: string | null = null;
  const обход = (папка: string) => {
    if (ответ) return;
    for (const имяЭлемента of readdirSync(папка)) {
      const полный = join(папка, имяЭлемента);
      if (statSync(полный).isDirectory()) {
        обход(полный);
        if (ответ) return;
      } else if (имяЭлемента === `${имя}.ts`) {
        ответ = полный;
        return;
      }
    }
  };
  for (const корень of ['server/src', 'shared']) {
    const папка = join(ROOT, корень);
    if (existsSync(папка)) обход(папка);
    if (ответ) break;
  }
  найдено.set(имя, ответ ?? '');
  return ответ;
}

function must(ok: unknown, why: string): void {
  if (!ok) throw new Error(why);
}

const stealth = читать('shared/stealth.ts');
const guilds = читать('server/src/data/guilds.ts');
const gameLoop = читать('server/src/systems/GameLoop.ts');
const бой = читать('server/src/socket/GameSocketHandler.ts');
const данжи = читать('server/src/systems/DungeonService.ts');

describe('Карта владельца: утверждения, которые были неверны', () => {
  it('ночь считается скрытностью, а не только диалогами', () => {
    must(
      /export const NIGHT_SIGHT = [\d.]+/.test(stealth),
      'в shared/stealth.ts нет NIGHT_SIGHT: ночь перестала влиять на обзор стража, ' +
        'и «ночью легче спрятаться» из списка владельца больше не верно',
    );
    must(
      /export function nightFactor\(/.test(stealth),
      'в shared/stealth.ts нет функции ночного фактора: он объявлен, но не считается',
    );
    must(
      /NIGHT_SIGHT \* \(ctx\.night \?\? 0\)/.test(stealth),
      'ночной фактор не входит в формулу обзора: константа есть, а на обзор не влияет',
    );
    // Проверка ищет устаревшую формулировку ТОЛЬКО в строке списка локаций, а не во всей
    // карте. Иначе раздел «что было неверно», где старая формулировка цитируется как
    // цитата, ломал бы проверку: запрещать само слово нельзя, запрещать надо утверждение.
    //
    // Регистр тоже важен: строка начинается с заглавной «Ночью», и без флага i
    // устаревшее утверждение возвращалось прямо в текст, а проверка молчала.
    const карта = читать('ROADMAP.md');
    const строкаНочи = карта
      .split(/\r?\n/)
      .find((с) => /Сезонные и динамические эффекты/.test(с));
    must(строкаНочи !== undefined, 'в карте нет строки «Сезонные и динамические эффекты»: проверять нечего');
    must(
      !/ночью считается только как условие для диалогов/i.test(строкаНочи!),
      'строка про сезонные эффекты снова утверждает, что ночь считается только как ' +
        'условие для диалогов: это неверно, ночь сокращает обзор стража вдвое',
    );
  });

  it('осада подключена, а территории четыре, а не восемь', () => {
    const начало = guilds.indexOf('export const TERRITORIES');
    must(начало >= 0, 'в данных нет списка территорий');
    const блок = guilds.slice(начало, guilds.indexOf('];', начало));
    const территории = [...блок.matchAll(/id:\s*'([a-z_]+)'/g)].map((m) => m[1]);
    // Сверяется не число записей, а их состав. Число проверялось прежде, и ломка это
    // показала: переименование территории оставляло записи на месте, счёт оставался
    // прежним, и проверка молчала. Устаревшая карта говорит именно о составе.
    const ожидаемые = [
      'territory_tabriz_market',
      'territory_isfahan_palace',
      'territory_caucasus_fortress',
      'territory_persian_gulf_port',
    ];
    must(
      территории.length === ожидаемые.length && ожидаемые.every((t) => территории.includes(t)),
      `состав территорий разошёлся с картой: в данных ${территории.join(', ')}, ` +
        `а карта обещает ${ожидаемые.join(', ')}. Территория переименована или исчезла`,
    );
    must(
      территории.length === 4,
      `территорий ${территории.length}, а карта обещает четыре: ${территории.join(', ')}`,
    );
    must(
      /import \{ SiegeSystem \}/.test(gameLoop) && /SiegeSystem\.getInstance\(\)\.start\(\)/.test(gameLoop),
      'GameLoop не запускает планировщик осад: система есть, но осада никогда не начнётся',
    );
    must(
      /SiegeSystem\.getInstance\(\)\.нанестиУрон/.test(бой),
      'бой не наносит урон осаде: за участие в осаде ничего не дают',
    );
  });

  it('уведомление о завершении захода получают все участники, а не только убийцы', () => {
    must(
      /shares: \{ characterId: string/.test(данжи),
      'в DungeonCompleteInfo нет shares: уведомление о завершении опять получает только ' +
        'добивший босса, а остальные золото берут молча',
    );
    must(
      /for \(const доля of dungeonDone\.shares\)/.test(бой),
      'обработчик не рассылает событие по shares: список участников есть, а рассылки нет',
    );
    must(
      /shares: получили\.map/.test(данжи),
      'доли не собираются при завершении захода: значит shares всегда пуст',
    );
  });

  it('репутация работает как система прогрессии, а не только как число на панели', () => {
    // Потребители ищутся по имени файла во всём сервере, а не по угаданному пути.
    // Пути угадывались дважды и оба раза неверно: AuctionService, QuestService и
    // PvPService лежат в services/, а не в systems/. Искать по имени дешевле, чем
    // чинить проверку при каждом переезде.
    const потребители = ['AuctionService', 'TradeService', 'QuestService', 'PvPService', 'DungeonService'];
    const чистые = потребители.filter((имя) => найтиФайл(имя) !== null
      && /reputation/i.test(readFileSync(найтиФайл(имя)!, 'utf-8')));
    must(
      чистые.length === потребители.length,
      `репутацию читают только ${чистые.length} из ${потребители.length} подсистем: ` +
        `нет их в ${потребители.filter((n) => !чистые.includes(n)).join(', ')}. ` +
        'Репутация перестала быть системой прогрессии',
    );
    // Ранги фракций показываются игроку - значит репутация видима, а не внутренняя.
    const панели = читать('client/src/app/panels.ts');
    must(
      /reputation\.rank\./.test(панели),
      'в интерфейсе нет рангов репутации: игрок не видит, во что он вложился',
    );
  });
});

describe('Числа в карте проверяемы, а не выписаны', () => {
  it('число территорий в карте совпадает с данными', () => {
    const начало = guilds.indexOf('export const TERRITORIES');
    const блок = guilds.slice(начало, guilds.indexOf('];', начало));
    const сколько = [...блок.matchAll(/id:\s*'([a-z_]+)'/g)].length;
    const карта = читать('ROADMAP.md');
    // Раньше в списке локаций стояло «территории 8». Проверка требует, чтобы рядом с
    // упоминанием территорий было верное число, иначе карта снова врёт.
    const строкаПроОсаду = карта
      .split(/\r?\n/)
      .find((с) => /осад/i.test(с) && /территор/i.test(с));
    if (!строкаПроОсаду) {
      must(false, 'в карте нет строки про осаду и территории: нечего сверять с данными');
    }
    must(
      !/территори\w*\s*8/.test(строкаПроОсаду!),
      `в карте про осаду снова написано про 8 территорий, а в данных ${сколько}: ` +
        'число уехало, а текст остался',
    );
  });
});