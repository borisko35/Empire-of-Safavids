// Жильё в пригороде: дома, а не только склады.
//
// ЧТО БЫЛО (21 октября 2026, §246). В пригороде стояли только склады и
// мастерская: жить рядом было нечем, и место читалось как товарная станция, а
// не как окраина города.
//
// ЧТО ТЕПЕРЬ. Два дома: корпус, плоская крыша с парапетом, дверь, два окна
// (те же, что везде: windowPane) и забор вдоль двора.
//
// ЧТО ПРОВЕРЯЕТСЯ. Дома есть, они с окнами (окно без стекла — дыра) и стоят
// по настоящей земле.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Жильё в пригороде', () => {
  it('в пригороде есть дома с окнами', () => {
    должен(
      /\{ x: 117, z: 119, w: 6\.5, d: 5\.5, h: 3\.6, поворот: 0\.3 \}/.test(код),
      'первого дома пригорода нет',
    );
    должен(
      /\{ x: 131, z: 100, w: 5\.5, d: 5, h: 3\.2, поворот: -0\.6 \}/.test(код),
      'второго дома пригорода нет',
    );
    // Окна — общие со всей игрой, а не тёмные плашки.
    должен(
      /дом\.add\(windowPane\(-д\.w \/ 4, 1\.7, д\.d \/ 2 \+ 0\.02, 0, 0\.9, 1\.2\)\)/.test(код),
      'у домов пригорода нет стеклянных окон',
    );
  });

  it('дома стоят по настоящей земле и с забором', () => {
    должен(
      /const земля = groundHeight\(CITY\.x \+ д\.x, CITY\.z \+ д\.z\) - city\.position\.y;/.test(код),
      'дома пригорода ставятся на зашитой высоте: за стеной склон',
    );
    // Парапет по крыше и забор вдоль двора.
    должен(/const борт = new THREE\.Mesh\(new THREE\.BoxGeometry\(bw, 0\.55, bd\), MAT\.sandstoneDark\)/.test(код),
      'у домов пригорода нет парапета по крыше');
    должен(/const рейка = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.12, 0\.5, 2\.8\), MAT\.wood\)/.test(код),
      'у домов пригорода нет забора вдоль двора');
  });
});
