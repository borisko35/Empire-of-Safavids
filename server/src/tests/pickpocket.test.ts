// Угол обзора и кража кошелька.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ЭТОЙ ПРОВЕРКИ.
//   Направление взгляда группы в мире = (sin(yaw), cos(yaw)). Подтверждено
//   дважды: fauna.ts:346 двигает существо по (sin(yaw), cos(yaw)),
//   navigator.ts:147 так же целится в следующую точку маршрута.
//   NPC разворачиваются по client/src/app/game3d/npc.ts:198:
//   yaw = atan2(origin.x - x, origin.z - z) + Math.PI, то есть взглядом ОТ
//   центра поселения. Для NPC это равно его собственному смещению dx/dz.
//   Торговец базара: CITY (34,26) + (15,2) = (49,28), взгляд (15,2).
//
// ПОЧЕМУ ПРОВЕРКА ТРЕБУЕТ, ЧТОБЫ СТРАЖИ НЕ ИЗМЕНИЛИСЬ. Конус добавлен ради
// одной механики. Если он затронет круговых наблюдателей, шаги 1 и 2,
// которые уже на проде, поедут незаметно - и сообщение «страж заметил»
// начнёт появляться не оттуда. Это главная проверка файла.
//
// ПОЧЕМУ ПРОВЕРКА СЧИТАЕТ ЧИСЛА. Поиск строки "inCone" доказал бы, что
// функция есть. Здесь считаются направления: сломанный знак в косинусе
// роняет утверждение.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  GUARD_POSTS,
  GUARD_SIGHT,
  PICKPOCKET_TARGETS,
  THEFT_GOLD,
  THEFT_REACH,
  WATCHER_FOV_DEG,
  canPickpocket,
  canSee,
  effectiveSight,
  spottedBy,
} from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const торговец = PICKPOCKET_TARGETS[0];

describe('Конус зрения: круговые наблюдатели не изменились', () => {
  it('стражи остались без направления', () => {
    must(GUARD_POSTS.length >= 3, 'постов стражи меньше трёх — проверка ослабла бы сама');
    for (const p of GUARD_POSTS) {
      must(
        p.facingX === undefined && p.facingZ === undefined,
        `у стража ${p.id} появилось направление взгляда: он перестал видеть кругом, ` +
          'а шаги 1 и 2 на проде считают круг. Это тихая поломка.'
      );
    }
  });

  it('шаг 1 не сломан: страж по-прежнему замечает со всех сторон', () => {
    const стража = GUARD_POSTS[0];
    // Обход круга: восемь направлений на расстоянии 15. У кругового наблюдателя
    // все восемь должны быть видны. С конусом «спина» была бы не видна - значит
    // проверка поймала бы подмену стража на торговца.
    for (let i = 0; i < 8; i++) {
      const угол = (i * Math.PI) / 4;
      const точка = { x: стража.x + Math.cos(угол) * 15, z: стража.z + Math.sin(угол) * 15 };
      must(
        spottedBy(точка, [стража]) !== null,
        `стража не заметил игрока с направления ${i * 45} градусов: он перестал видеть кругом`
      );
    }
    // И по-прежнему не замечает за радиусом.
    must(spottedBy({ x: стража.x + 21, z: стража.z }, [стража]) === null, 'обзор стража расползся');
  });

  it('шаг 2 не сломан: приседание по-прежнему сокращает обзор стража', () => {
    const стража = GUARD_POSTS[0];
    must(
      spottedBy({ x: стража.x + 14, z: стража.z }, [стража], { crouch: true }) === null,
      'приседший на 14 единицах замечен: скрытность перестала работать'
    );
    must(
      spottedBy({ x: стража.x + 14, z: стража.z }, [стража], {}) !== null,
      'стоящий на 14 единицах не замечен: обнаружение перестало работать'
    );
  });
});

describe('Конус зрения: направление сужает круг', () => {
  it('спереди видно, сзади нет', () => {
    const s = Number(THEFT_REACH) - 1; // 5 единиц — внутри досягаемости
    // Взгляд торговца направлен на (facingX, facingZ) — это наружу от центра.
    const спереди = { x: торговец.x + торговец.facingX! * 0.25, z: торговец.z + торговец.facingZ! * 0.25 };
    const сзади = { x: торговец.x - торговец.facingX! * 0.25, z: торговец.z - торговец.facingZ! * 0.25 };

    must(canSee(спереди, торговец), 'перед торговцем не видно: конус смотрит не туда');
    must(!canSee(сзади, торговец), 'за спиной торговца тоже видно: конус не работает');

    // Расстояние одно и то же - разницу даёт только направление.
    const d1 = Math.hypot(спереди.x - торговец.x, спереди.z - торговец.z);
    const d2 = Math.hypot(сзади.x - торговец.x, сзади.z - торговец.z);
    must(Math.abs(d1 - d2) < 1e-9, 'точки подобраны на разном расстоянии — сравнение нечестное');
    must(s <= THEFT_REACH, 'подобрана точка дальше досягаемости');
  });

  it('ширина конуса ненулевая и меньше полного круга', () => {
    must(Number(WATCHER_FOV_DEG) > 0, 'конус нулевой: не видно ничего');
    must(Number(WATCHER_FOV_DEG) < 360, 'конус равен полному кругу: это не конус, а прежнее правило');
  });

  it('вырожденные случаи видны, а не спрятаны', () => {
    // Наблюдатель с нулевым направлением не должен слепнуть из-за ошибки в данных.
    const сломанный = { ...торговец, id: 'broken', facingX: 0, facingZ: 0 };
    must(canSee({ x: торговец.x + 2, z: торговец.z }, сломанный), 'нулевое направление сделало наблюдателя слепым');
    // Ровно на посту - уж точно заметит.
    must(canSee({ x: торговец.x, z: торговец.z }, торговец), 'на самом посту не видно: вырожденная дистанция');
  });
});

describe('Кража: механика наконец возможна', () => {
  it('приседши со спины — крадёшь, спереди — нет', () => {
    const сзади = { x: торговец.x - торговец.facingX! * 0.25, z: торговец.z - торговец.facingZ! * 0.25 };
    const спереди = { x: торговец.x + торговец.facingX! * 0.25, z: торговец.z + торговец.facingZ! * 0.25 };

    must(
      canPickpocket(сзади, торговец, { crouch: true }),
      'приседший за спиной не смог обокрасть: механика по-прежнему невозможна'
    );
    must(
      !canPickpocket(спереди, торговец, { crouch: true }),
      'спереди у торговца тоже крадётся: конус не влияет'
    );
    must(
      !canPickpocket(сзади, торговец, {}),
      'стоя сзади обокрал: приседание не требуется'
    );
  });

  it('далеко не дотянуться даже со спины', () => {
    const далеко = { x: торговец.x - (THEFT_REACH + 1) * торговец.facingX!, z: торговец.z - (THEFT_REACH + 1) * торговец.facingZ! };
    must(
      !canPickpocket(далеко, торговец, { crouch: true }),
      `в ${THEFT_REACH + 1} единицах дотянулись, а дальность рук ${THEFT_REACH}`
    );
  });

  it('механика согласована сама с собой', () => {
    must(Number(THEFT_REACH) < effectiveSight(торговец, { crouch: true }), 'дальность рук не меньше приседного обзора');
    must(Number(THEFT_REACH) < Number(GUARD_SIGHT), 'дальность рук не меньше обычного обзора');
    must(Number(THEFT_GOLD) > 0, 'награда нулевая: кража бессмысленна');
  });
});

describe('Кража: взгляд торговца совпадает с его настоящим поворотом', () => {
  it('направление равно смещению NPC в NPC_GROUPS', () => {
    const npc = читать('client/src/app/game3d/npc.ts');
    const terrain = читать('client/src/app/game3d/terrain.ts');
    must(npc.length > 1000 && terrain.length > 1000, 'файлы не прочитаны: проверка молчала бы');

    const строка = npc.split('\n').find((l) => l.includes(`id: '${торговец.id}'`));
    must(строка !== undefined, `NPC ${торговец.id} не найден в NPC_GROUPS`);
    const dx = /dx:\s*(-?\d+(?:\.\d+)?)/.exec(строка!);
    const dz = /dz:\s*(-?\d+(?:\.\d+)?)/.exec(строка!);
    must(dx !== null && dz !== null, `у ${торговец.id} нет dx/dz`);

    // Взгляд наружу от центра поселения = собственное смещение NPC.
    must(
      торговец.facingX === Number(dx![1]) && торговец.facingZ === Number(dz![1]),
      `взгляд (${торговец.facingX},${торговец.facingZ}), а NPC_GROUPS даёт смещение ` +
        `(${dx![1]},${dz![1]}) - копии разъехались`
    );

    // И позиция совпадает: CITY плюс смещение.
    const город = /export const CITY\s*=\s*\{\s*x:\s*(-?\d+(?:\.\d+)?)\s*,\s*z:\s*(-?\d+(?:\.\d+)?)/.exec(terrain);
    must(город !== null, 'не найдено объявление CITY в terrain.ts');
    must(
      торговец.x === Number(город![1]) + Number(dx![1]) && торговец.z === Number(город![2]) + Number(dz![1]),
      'позиция цели разошлась с NPC_GROUPS'
    );
  });

  it('взгляд в shared считается так же, как поворот в клиенте', () => {
    // Связь «+Math.PI разворачивает взгляд от центра» держится на соглашении
    // (sin(yaw), cos(yaw)) = направление взгляда. Если клиент когда-нибудь
    // поменяет соглашение, это перестанет быть правдой - и проверка должна
    // упасть, а не тихо разойтись с картинкой.
    const npc = читать('client/src/app/game3d/npc.ts');
    const fauna = читать('client/src/app/game3d/fauna.ts');
    must(
      /atan2\(origin\.x - x, origin\.z - z\) \+ Math\.PI/.test(npc),
      'в npc.ts изменилась формула поворота NPC - взгляд торговца надо пересчитать'
    );
    must(
      /Math\.sin\([a-z]+\.group\.rotation\.y\)[\s\S]{0,80}Math\.cos\([a-z]+\.group\.rotation\.y\)/.test(fauna),
      'в fauna.ts нет движения по (sin(yaw), cos(yaw)): соглашение о взгляде не подтверждено'
    );
  });
});

describe('Кража: подключена с обеих сторон', () => {
  it('сервер обрабатывает попытку и платит золотом', () => {
    const socket = читать('server/src/socket/GameSocketHandler.ts');
    must(socket.length > 1000, 'GameSocketHandler.ts не прочитан');
    must(/STEAL_ATTEMPT/.test(socket), 'сервер не слушает попытку кражи');
    must(/canPickpocket\(/.test(socket), 'сервер не зовёт правило кражи');
    // Именно addGoldReward, а не addGold: прямая награда в GameSocketHandler
    // запрещена правилом проекта, иначе игрок крадёт мимо сезонного бонуса.
    must(
      /addGoldReward\(\s*characterId\s*,\s*THEFT_GOLD\s*\)/.test(socket),
      'золото за кражу идёт не через addGoldReward: игрок получает меньше, чем за любую другую награду'
    );
  });

  it('сервер не верит присланным координатам', () => {
    const socket = читать('server/src/socket/GameSocketHandler.ts');
    // stealthStates - общий кеш (server/src/systems/StealthStates.ts), а не
    // приватная карта сокета: с прошлого шага его читает ещё и тик стражи.
    // Проверка ищет обращение к кешу, а не конкретное поле.
    must(/stealthStates\.get\(/.test(socket), 'сервер не берёт позицию из кеша движений');
    must(/stealthStates\.set\(/.test(socket), 'кеш позиции не наполняется');
    const обработчик = socket.slice(
      socket.indexOf('private async handleSteal'),
      socket.indexOf('private async regenTick')
    );
    must(обработчик.length > 200, 'обработчик кражи не найден');
    must(
      !/position\s*:\s*\{/.test(обработчик),
      'обработчик кражи доверяет координатам из события: игрок объявил бы выдуманное место'
    );
  });

  it('клиент шлёт запрос по клавише и показывает ответ', () => {
    const world = читать('client/src/app/world.ts');
    const world3d = читать('client/src/app/game3d/world3d.ts');
    must(world.length > 1000 && world3d.length > 1000, 'файлы не прочитаны');
    must(/consumeStealRequest\(\)/.test(world), 'клиент не спрашивает движок о нажатии F');
    must(/steal:attempt/.test(world), 'клиент не отправляет попытку кражи');
    must(/steal:result/.test(world), 'клиент не слушает ответ');
    must(/e\.code === 'KeyF'/.test(world3d), 'в движке нет клавиши F');
    must(
      /consumeStealRequest\(\)[\s\S]{0,200}this\.stealRequested\s*=\s*false/.test(world3d),
      'флаг кражи не сбрасывается чтением: удержание F даст сотни запросов'
    );
  });

  it('три причины отказа переведены в трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = читать(`shared/locales/${код}.json`);
      must(словарь.length > 1000, `${код}.json не прочитан`);
      for (const ключ of ['steal_ok', 'steal_seen', 'steal_far']) {
        must(new RegExp(`"${ключ}"\\s*:`).test(словарь), `в ${код}.json нет ключа stealth.${ключ}`);
      }
    }
  });
});