// Трейлер и файлы лендинга: то, что обещано, обязано существовать.
//
// ЗАЧЕМ ФАЙЛ. Найдено три независимые поломки, и все три были не видны снаружи.
//
// 1. ТРЕЙЛЕР ССЫЛАЛСЯ НА ФАЙЛОВ, КОТОРЫХ НЕТ. Сцены 4 и 5 звали dungeon.png
//    и simurgh.png. В репозитории их нет и никогда не было. Из шести сцен
//    работали три, и это выглядело как «треть трейлера чёрная».
//
// 2. NGINX ОТДАВАЛ ЛЕНДИНГ ВМЕСТО ОТСУТСТВУЮЩЕГО ФАЙЛА, КОД 200.
//    Общее правило try_files ... /index.html нужно, чтобы /forum отдавал
//    страницу. Но браузер просил картинку, получал HTML с кодом 200, не мог
//    его показать и рисовал пустое место. Проверено на бою: три отсутствующих
//    файла отдали ровно 23867 байт - размер лендинга. Ни в сети, ни в журнале
//    сервера не видно, что файла нет. По коду ответа это не отличить от успеха.
//
// 3. СЦЕНАРИЙ И СБОРЩИК НАЗЫВАЛИ ТЕ ЖЕ НЕСУЩЕСТВУЮЩИЕ ИМЕНА. Сценарий
//    раздаётся как готовый материал, сборщик падает на первом отсутствующем
//    файле. Оба выглядели рабочими, пока не дошли до запуска.
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const трейлер = читать('client/web/trailer.html');
const nginx = читать('client/nginx.conf');
const сценарий = читать('tools/trailer-storyboard.md');
const сборщик = читать('tools/build-trailer.ps1');

/**
 * Имя кадра из строки сцены на странице: img: '/assets/bg-history.png'
 * либо img: SHOTS + 'city.png'. Берётся ПОСЛЕДНИЙ компонент пути в кавычках.
 *
 * Первые две версии шли от кавычки и брали класс [\w.-], а в нём нет '/'.
 * На '/assets/bg-history.png' совпадения не было ни с одного места, и
 * страница давала ПУСТОЙ список - который смотрится как «всё в порядке»,
 * если не с чем сравнить. Третья версия взяла ЖАДНЫЙ префикс, и тогда
 * отдавался последний кусок имени: 'p.png' вместо 'bg-history.png'.
 * Работает ленивый префикс без отдельной кавычки после «img: ».
 */
const ИМЯ = '(?:[\\w.-]+\\/)*([\\w.-]+\\.png)';
const КАДР_СТРАНИЦЫ = /img: ([^,\n]*?)([\w.-]+\.png)['`]/g;
const кадрыСтраницы = (t: string): string[] =>
  [...new Set([...t.matchAll(КАДР_СТРАНИЦЫ)].map(m => m[2]))];

/** Имя кадра из строки таблицы сценария: | 2 | `city.png` | 7 с | ... */
const КАДР_СЦЕНАРИЯ = new RegExp(`^\\|\\s*\\d+\\s*\\|\\s*\`${ИМЯ}\``, 'gm');
const кадрыСценария = (t: string): string[] =>
  [...new Set([...t.matchAll(КАДР_СЦЕНАРИЯ)].map(m => m[1]))];

/** Имя кадра из сегмента сборщика: Join-Path $shots 'city.png' */
const КАДР_СБОРЩИКА = /Join-Path\s+\$\w+\s+'((?:[\w.-]+\/)*[\w.-]+\.png)'/g;
const кадрыСборщика = (t: string): string[] =>
  [...new Set([...t.matchAll(КАДР_СБОРЩИКА)].map(m => m[1]))];

/**
 * Имена из ВТОРОГО списка сборщика - того, что проверяет наличие файлов перед
 * сборкой. Найдено поломкой: замена имени в этом списке не погасила ни одну
 * проверку, потому что все смотрели только на сегменты. А расхождение между
 * списками означает, что сборщик узнает о недостающем файле поздно - не в
 * предварительной проверке, а уже на вызове ffmpeg, после сборки четырёх
 * сегментов из семи.
 */
const ПРЕДПРОВЕРКА = /foreach\s*\(\$f\s+in\s*@\(([^)]*)\)\)/g;
const ИМЯ_В_КАВЫЧКАХ = /'([\w.-]+\.png)'/g;
const кадрыПредпроверки = (t: string): string[] => {
  // Плоский цикл, а не flatMap по matchAll: flatMap здесь ронял компиляцию
  // (TS7053) и требовал угадывания типов итератора RegExp. Проверка, которую
  // нельзя собрать, хуже проверки без проверки.
  const имена: string[] = [];
  for (const список of t.matchAll(ПРЕДПРОВЕРКА)) {
    for (const имя of (список[1] ?? '').matchAll(ИМЯ_В_КАВЫЧКАХ)) {
      if (имя[1]) имена.push(имя[1]);
    }
  }
  return [...new Set(имена)].sort();
};

/**
 * Общая проверка на диске. Ищет файл сначала прямо в assets/, потом в
 * assets/screenshots/ - чтобы имя совпадало, но спор о подкаталоге не мешал.
 */
const лежит = (кадр: string): boolean =>
  existsSync(join(корень, 'client/web/assets', кадр)) ||
  existsSync(join(корень, 'client/web/assets/screenshots', кадр));

const отсутствующие = (кадры: string[]): Record<string, string> => {
  const нет: Record<string, string> = {};
  for (const к of кадры) if (!лежит(к)) нет[к] = 'нет файла';
  return нет;
};

describe('Каждый кадр трейлера существует', () => {
  it('все три языка ссылаются только на файлы, которые лежат на диске', () => {
    const найдено = кадрыСтраницы(трейлер);
    // Страховка от молчаливой пустоты: если регулярка перестанет находить
    // сцены, список кадров станет пустым и проверка пройдёт, не проверив
    // ничего. Раньше так уже было - искали 'data-i18n="ss_..."' вместо
    // 'data-i18n="site.ss_..."' и насчитали ноль подписей вместо четырёх.
    must(найдено.length > 0,
      'в trailer.html не нашлось ни одного кадра - возможно, сменился формат записи, ' +
      'и проверка молча ищет не то');
    const нет = отсутствующие(найдено);
    expect({ кадров_проверено: найдено.length, отсутствуют: нет })
      .toEqual({ кадров_проверено: 6, отсутствуют: {} });
  });

  it('все семь сцен на месте и они идут в порядке сценария', () => {
    // Трейлер - семь сцен по 48 секунд. Если сцен отрезали, сумма поедет и
    // хронометраж перестанет совпадать с тем, что обещан в сценарии.
    const сцены = [...трейлер.matchAll(/img: (?:'[^']+'|SHOTS \+ '[^']+'),?\s*(\s*)dur: (\d+)/g)];
    const всего = сцены.length;
    const миллисекунд = сцены.map(m => Number(m[2]));
    expect({ сцен_на_язык: всего / 3, миллисекунд: миллисекунд.slice(0, 7) })
      .toEqual({ сцен_на_язык: 7, миллисекунд: [6000, 7000, 8000, 7000, 8000, 9000, 3000] });
  });

  it('сценарий и сборщик называют те же файлы, что и страница', () => {
    // Расхождение между тремя источниками - это то, из-за чего сборщик
    // падал на первом же файле, а сценарий раздавался как готовый.
    //
    // Берутся ТОЛЬКО структурные места: строки сцен, строки таблицы,
    // сегменты сборки. Пояснение к таблице, где сказано, что dungeon.png
    // убран, - это текст, а не кадр. Первая версия проверки брала любые
    // имена в кавычках и потому требовала, чтобы сценарий молчал про то,
    // почему кадр убрали.
    const эталон = [...кадрыСтраницы(трейлер)].sort();
    const вСценарии = [...кадрыСценария(сценарий)].sort();
    const вСборщике = [...кадрыСборщика(сборщик)].sort();
    const вПредпроверке = кадрыПредпроверки(сборщик);
    must(вСценарии.length > 0, 'в таблице сценария не нашлось ни одного кадра');
    must(вСборщике.length > 0, 'в сборщике не нашлось ни одного сегмента с картинкой');
    must(вПредпроверке.length > 0,
      'в сборщике не нашёлся список предварительной проверки foreach ($f in @(...))');
    const одинаковы = (a: string[]) => JSON.stringify(a) === JSON.stringify(эталон);
    expect({
      сценарий_совпал: одинаковы(вСценарии),
      сборщик_совпал: одинаковы(вСборщике),
      // Второй список сборщика обязан совпадать с сегментами. Иначе файл
      // проверяется, но не используется, либо наоборот: используется, но не
      // проверяется, и отсутствие вскрывается на середине сборки.
      предпроверка_совпала: JSON.stringify(вПредпроверке) === JSON.stringify(вСборщике),
      // И все названные файлы есть на диске - иначе совпадение с эталоном
      // ничего не значит: эталон тоже может оказаться пустым набором.
      нет_файлов: {
        сценарий: отсутствующие(вСценарии),
        сборщик: отсутствующие(вСборщике),
        предпроверка: отсутствующие(вПредпроверке),
      },
    }).toEqual({
      сценарий_совпал: true, сборщик_совпал: true, предпроверка_совпала: true,
      нет_файлов: { сценарий: {}, сборщик: {}, предпроверка: {} },
    });
  });

  it('ни страница, ни сценарий не обещают подземелья кадром, которого нет', () => {
    // Подземелья и мировые боссы в игре есть, но кадра нет. Обещать их
    // поверх пустоты - та же ложь, что была с подписью «Тебриз» над кадром
    // из Исфахана. Возвращаются, когда снимут настоящие кадры.
    //
    // Ищутся не сами слова, а слоган В РОЛИ ЗАГОЛОВКА КАДРА. Первая версия
    // проверки искала слова где угодно и сразу нашла их в пояснении к
    // таблице - то есть сама проверка объясняла, почему их убрали, и
    // проверка от этого краснела. Проверять надо обещание, а не упоминание.
    const слоган = 'Подземелья и мировые боссы';
    const обещания = new RegExp(
      `title: '${слоган}'|title = '${слоган}'|\\| ${слоган} \\|`);
    expect({
      страница: обещания.test(трейлер),
      сценарий: обещания.test(сценарий),
      сборщик: обещания.test(сборщик),
      // Упоминание в пояснении остаётся и это правильно: читатель должен
      // знать, почему сцены нет.
      пояснение_на_месте:
        слоган.length > 0 && сценарий.includes(слоган),
    }).toEqual({
      страница: false, сценарий: false, сборщик: false, пояснение_на_месте: true,
    });
  });
});

describe('Отсутствующий файл отдаёт 404, а не лендинг', () => {
  it('для /assets/, /css/ и /js/ стоит правило с =404', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Общее правило location / заканчивается на
    // try_files ... /index.html - без него /forum не отдал бы страницу. Но
    // на файлах с расширением та же подстановка означает тихую поломку.
    const безЗащиты: Record<string, string> = {};
    for (const префикс of ['/assets/', '/css/', '/js/']) {
      const блок = nginx.match(
        new RegExp(`location \\^~ ${префикс.replace('/', '\\/')} \\{([^}]*)\\}`));
      if (!блок) { безЗащиты[префикс] = 'нет отдельного правила'; continue; }
      if (!/try_files[^;]*=404/.test(блок[1])) {
        безЗащиты[префикс] = 'в правиле нет =404';
      }
    }
    expect({ без_защиты: безЗащиты }).toEqual({ без_защиты: {} });
  });

  it('ни одно правило с try_files не подставляет index.html для файлов', () => {
    // Слабее предыдущей проверки, но ловит другую ошибку: если кто-то
    // добавит ещё один префикс с подстановкой, предыдущая проверка его не
    // увидит - она знает только три имени. Порядок - как в файле: правило
    // игры стоит раньше правила лендинга.
    const подстановки = [...nginx.matchAll(
      /location\s+(\^~\s*)?([^\s{]+)\s*\{([^}]*try_files[^}]*)\}/g)]
      .filter(m => /\/index\.html/.test(m[3]))
      .map(m => m[2].trim());
    expect({ подставляют_лендинг: подстановки })
      .toEqual({ подставляют_лендинг: ['/game/', '/'] });
  });

  it('кэш у картинок задан явно, а не пропадает вместе с правилом', () => {
    // add_header в location / не действует на ^~ /assets/: префиксное
    // совпадение выигрывает, и правило из location / не наследуется. Без
    // своей строки кэша картинки отдавались бы без Cache-Control вовсе.
    const безКэша: Record<string, string> = {};
    for (const префикс of ['/assets/', '/css/', '/js/']) {
      const блок = nginx.match(
        new RegExp(`location \\^~ ${префикс.replace('/', '\\/')} \\{([^}]*)\\}`));
      if (блок && !/Cache-Control/.test(блок[1])) безКэша[префикс] = 'нет Cache-Control';
    }
    expect({ без_кеша: безКэша }).toEqual({ без_кеша: {} });
  });

  it('все кадры лендинга на месте и не пустые', () => {
    // Кадр удалили - и раньше страница всё равно отдавалась 200, только уже
    // лендингом. Теперь будет 404, но лучше и не доходить до этого: пустой
    // файл браузер показывает как битую картинку.
    const проблемы: Record<string, string> = {};
    for (const кадр of ['city.png', 'combat.png', 'tasks.png', 'worldmap.png']) {
      const путь = join(корень, 'client/web/assets/screenshots', кадр);
      if (!existsSync(путь)) { проблемы[кадр] = 'нет файла'; continue; }
      if (statSync(путь).size < 20_000) проблемы[кадр] = 'пустой или обрезан';
    }
    expect({ проблемы }).toEqual({ проблемы: {} });
  });
});
