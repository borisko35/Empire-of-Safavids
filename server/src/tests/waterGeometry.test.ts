// Вода описана ОДИН раз, и сервер знает про море.
//
// ЧТО БЫЛО. Геометрия воды была описана дважды: в клиенте
// (client/src/app/game3d/terrain.ts) и на сервере
// (server/src/utils/spawn.ts). В шапке серверного файла стояло
// предупреждение «при изменении террейна клиента обновить и здесь» -
// но никакой проверки не было, и копии разошлись.
//
// Чем это кончилось на практике: море добавили в клиент, и сервер о нём
// не узнал. Последствия были бы тихими и серьёзными - спасение из воды
// выкидывает игрока из залива на сушу, ИИ водных монстров не находит
// себе воду, лодки и рыбалка в море не работают.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater, isDeepWater, seaMask, SEA, SEA_ISLANDS, LAKE, POND } from '../../../shared/water';
import { isWater as serverIsWater, isDeepWater as serverIsDeepWater } from '../utils/spawn';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const КЛИЕНТ = readFileSync(join(корень, 'client/src/app/game3d/terrain.ts'), 'utf-8');
const СЕРВЕР_СПАВН = readFileSync(join(корень, 'server/src/utils/spawn.ts'), 'utf-8');
const ВОДА = readFileSync(join(корень, 'shared/water.ts'), 'utf-8');

describe('Вода описана в одном месте', () => {
  it('клиент не диктует контуры воды заново', () => {
    // Локальные определения в клиенте - это та самая вторая копия,
    // из-за которой всё и началось.
    must(
      !/^\s*(export )?const LAKE\s*=/m.test(КЛИЕНТ),
      'клиент снова описывает LAKE сам: контуры воды разъедутся с сервером',
    );
    must(
      !/^\s*(export )?const RIVER_A\s*=/m.test(КЛИЕНТ),
      'клиент снова описывает RIVER_A сам',
    );
    must(
      !/^\s*(export )?const BRIDGES\s*=/m.test(КЛИЕНТ),
      'клиент снова описывает BRIDGES сам',
    );
    must(
      !/^\s*export function waterMask\b/m.test(КЛИЕНТ),
      'клиент снова пишет свою waterMask: сервер будет считать воду по другой карте',
    );
  });

  it('сервер берёт воду из общего места, а не держит копию', () => {
    must(
      /from '\.\.\/\.\.\/\.\.\/shared\/water'/.test(СЕРВЕР_СПАВН),
      'сервер не импортирует воду из shared/water: копия контуров вернулась',
    );
    // Ищем ЛЮБУЮ локальную константу воды, а не только имя LAKE. Первая
    // версия проверки искала ровно `const LAKE`, и ломка с именем _LAKE
    // прошла начисто: копия воды на сервере вернулась, а проверка её
    // не увидела. Проверка на одно имя - это проверка на слово.
    const своиКонтуры = [...СЕРВЕР_СПАВН.matchAll(/^\s*(?:const|let|var)\s+(\w+)/gm)]
      .map((м) => м[1])
      .filter((имя) => /LAKE|POND|RIVER|BRIDGE|SEA/i.test(имя));
    must(
      своиКонтуры.length === 0,
      `сервер снова описывает контуры воды сам: ${своиКонтуры.join(', ')} - это вторая копия воды`,
    );
    must(
      !/^\s*function distToSegment/m.test(СЕРВЕР_СПАВН),
      'сервер снова считает расстояние до реки сам - счёт сойдётся с клиентским',
    );
  });

  it('общее место действительно общее: его читают обе стороны', () => {
    must(
      /shared\/water/.test(КЛИЕНТ),
      'клиент не берёт воду из shared/water',
    );
    must(
      /export const SEA\s*=/.test(ВОДА),
      'в shared/water.ts нет описания моря',
    );
  });
});

describe('Сервер знает про море', () => {
  it('море считается глубокой водой и водой вообще', () => {
    // Замерено на клиенте: вода в z -740..-860 глубиной 6.0-8.8 м.
    // Если сервер считает там сушу, игрок, которого только что выкинуло
    // из воды, снова окажется в ней на следующей же проверке, а ИИ
    // водных монстров не найдёт себе воду.
    must(
      serverIsDeepWater(0, -800),
      'сервер не считает открытую гладь залива глубокой водой: спасение выкинет игрока обратно в море',
    );
    must(serverIsWater(0, -800), 'сервер не считает гладь залива водой: рыбалка и лодки там не появятся');
  });

  it('острова залива считаются сушей', () => {
    // Портовый остров держит гавань и наземных монстров залива. Если
    // сервер считает его водой, спасение из воды будет выкидывать с
    // острова туда, где монстров нет.
    must(
      !serverIsWater(0, -980),
      'сервер считает портовый остров водой - гавань с монстрами уйдёт под воду',
    );
    must(
      !serverIsDeepWater(60, -1010),
      'сервер считает сушу острова глубокой водой: игрок на гавани будет «спасён» сам у себя',
    );
  });

  it('озеро и пруд остались тем, чем были', () => {
    must(
      serverIsDeepWater(LAKE.x, LAKE.z),
      'озеро перестало быть глубокой водой',
    );
    // Про пруд. Я сперва написал здесь «пруд НЕ должен быть глубокой
    // водой» - и проверка упала на собственном предположении: пруд
    // всегда считался глубокой водой и на сервере, и на клиенте (дно
    // -5.2, поверхность -1.6, глубина 3.6 м - плавание). Проверять
    // надо не «как я думаю», а «что было и осталось»: поэтому здесь
    // сверяется с фактом, а не с догадкой.
    must(
      serverIsWater(POND.x, POND.z),
      'пруд перестал быть водой',
    );
    must(
      serverIsDeepWater(POND.x, POND.z),
      'глубина пруда изменилась: раньше он был глубокой водой, и клиент с этим считался',
    );
  });

  it('суша севернее берега осталась сушей', () => {
    // Столица, Хорасан и Кавказ не должны уехать под воду из-за того,
    // что море описано через шум.
    for (const [имя, x, z] of [['столица', 34, 26], ['Хорасан', 0, 750], ['Кавказ', 0, 600]] as const) {
      must(!serverIsWater(x, z), `сервер считает водой сушу: ${имя} (${x}, ${z})`);
    }
  });
});

describe('Общее место и его копии не молчат', () => {
  it('функции из общего места и из серверного модуля - одно и то же', () => {
    // Тонкая, но важная проверка: если серверный модуль начнёт
    // оборачивать и подменять воду, разъезд вернётся, а по именам это
    // не видно - функции просто будут разные.
    must(
      serverIsWater === isWater,
      'server/src/utils/spawn.ts больше не отдаёт общую функцию воды: появилась обёртка или копия',
    );
    must(
      serverIsDeepWater === isDeepWater,
      'server/src/utils/spawn.ts больше не отдаёт общую isDeepWater',
    );
  });

  it('маска моря в норме', () => {
    // Границы маски важны для всего остального: из неё считаются
    // и спасение, и спавн, и биом.
    must(seaMask(0, -800) > SEA.waterThreshold, 'в открытом заливе маска воды ниже порога - гладь не считается водой');
    must(seaMask(34, 26) === 0, 'в столице маска моря ненулевая - столица на море');
    must(SEA_ISLANDS.length >= 2, 'в заливе меньше двух островов: перейти его пешком нельзя');
  });
});