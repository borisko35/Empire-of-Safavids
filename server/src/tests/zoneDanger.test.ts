// Опасность зоны доходит до игрока.
//
// ЧТО БЫЛО. Сервер отправляет в zone:changed объект зоны целиком, а зона из
// ZONES несёт dangerLevel - число 1..5, заполненное у всех двадцати четырёх
// зон и проверяемое тестом на диапазон. Клиент принимал это поле в тип,
// доставал из объекта только id и name, рисовал тост с именем зоны - и всё.
// Опасность летела по сети в каждый переход между зонами и умирала в
// приёмнике, молча.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ КЛАСС ПОЛОМОК. Обычно мёртвое поле просто лежит в
// данных. Здесь оно было живым по дороге: сервер его слал, сеть его нёс, тип
// его объявлял. Сломать можно было на любом из четырёх участков, и ни один
// не выглядел подозрительно.
//
// ЧТО ПРОВЕРЯЕТСЯ. Вся цепочка, а не только наличие ключа в словаре:
// сервер кладёт поле в полезную нагрузку, клиент его читает и рисует, ключ
// есть во всех трёх языках.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { ZONES, REGION_LEVEL_REQUIREMENTS } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СОКЕТ = читать('server/src/socket/GameSocketHandler.ts');
const КЛИЕНТ = читать('client/src/app/world.ts');

describe('Опасность зоны доходит до игрока', () => {
  it('сервер кладёт dangerLevel в полезную нагрузку', () => {
    // Объект зоны уходит целиком, поэтому проверяем, что при отправке берётся
    // именно он, а не собранный вручную объект из двух полей. Собранный
    // вручную - это ровно тот случай, где dangerLevel потерялся бы снова.
    const отправка = /emit\(\s*SERVER_EVENTS\.ZONE_CHANGED,[^)]*\)/.exec(СОКЕТ)?.[0] ?? '';
    must(отправка.length > 0, 'не нашёл отправку zone:changed в GameSocketHandler');
    must(/zone:\s*newZone/.test(отправка),
      'в zone:changed уходит не сам newZone, а собранный объект — опасность снова потеряется по дороге');
  });

  it('клиент читает поле, а не только объявляет его в типе', () => {
    // Слабое место всей цепочки: поле было в типе параметра, и этого хватало,
    // чтобы выглядеть рабочим. Читать - значит использовать в отрисовке.
    const обработчик = КЛИЕНТ.slice(
      КЛИЕНТ.indexOf("socket.on('zone:changed'"),
      КЛИЕНТ.indexOf("socket.on('zone:changed'") + 3200,
    );
    must(обработчик.length > 0, 'не нашёл подписку на zone:changed в клиенте');
    // Поле упомянуто в тексте, который реально печатается, а не только в типе.
    const вРисовании = /toast\([^\n]*dangerLevel/.test(обработчик);
    must(вРисовании,
      'поле dangerLevel объявлено в типе, но не попадает в тост: опасность по-прежнему умирает в приёмнике');
  });

  it('слово «Опасность» переведено во всех трёх языках', () => {
    // Без ключа на экране был бы путь ключа или английское слово игроку с
    // русским интерфейсом.
    const отсутствуют: string[] = [];
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`)) as Record<string, Record<string, string>>;
      if (typeof словарь.zones?.danger !== 'string' || словарь.zones.danger.length === 0) {
        отсутствуют.push(`${язык}: zones.danger`);
      }
    }
    must(отсутствуют.length === 0, `в словарях нет:\n  ${отсутствуют.join('\n  ')}`);
  });

  it('опасность заполнена у всех зон, а не у половины', () => {
    // Поле, заполненное не у всех строк, читается как «иногда работает».
    const безОпасности = ZONES.filter((з) => typeof з.dangerLevel !== 'number' || з.dangerLevel < 1 || з.dangerLevel > 5);
    must(безОпасности.length === 0,
      `зоны без корректной опасности: ${безОпасности.map((з) => з.id).join(', ')}`);
    must(ZONES.length >= 24, `зон ${ZONES.length}, а проверка ждёт двадцать четыре`);
  });

  it('подстановка собирается строкой, а не плейсхолдером', () => {
    // t() в этом проекте принимает только путь ключа. Если бы строка
    // опиралась на подстановку {n}, на экране остался бы литерал.
    const i18n = читать('client/src/app/i18n.ts');
    const сигнатура = /export function t\(path: string\): string/.test(i18n);
    must(сигнатура, 'сигнатура t() изменилась - проверка подстановки больше не годна, перечитай i18n');
    // Комментарии вырезаются. Первая версия проверки искала {n} по всему срезу
    // и находила его в МОЁМ ЖЕ комментарии про {n}. Проверка требовала
    // отсутствия литерала, а находила упоминание о нём.
    const безКомментариев = (текст: string): string => текст.replace(/\/\/[^\n]*/g, ' ');
    const начало = КЛИЕНТ.indexOf("socket.on('zone:changed'");
    const обработчик = безКомментариев(КЛИЕНТ.slice(начало, начало + 1400));
    must(обработчик.length > 0, 'не нашёл подписку на zone:changed в клиенте');
    must(!/\{\s*n\s*\}/.test(обработчик),
      'в коде тоста есть плейсхолдер {n}, которого t() не подставит: игрок увидит литерал');
  });

  it('клиент не подписывается на несуществующие события', () => {
    // По ходу работы я объявил zone:changed мёртвым событием, и это было неверно:
    // сервер отправляет его через SERVER_EVENTS, а я искал в SOCKET_EVENTS.
    // Реестров два, и в каждом своё направление. Эта проверка фиксирует
    // факт: клиентский обработчик зоны существует, и серверный emit есть.
    must(/socket\.on\('zone:changed'/.test(КЛИЕНТ), 'клиент не подписан на zone:changed');
    must(/emit\(\s*SERVER_EVENTS\.ZONE_CHANGED/.test(СОКЕТ), 'сервер не отправляет zone:changed');
    // Чего здесь НЕТ и быть не должно: требования, чтобы ключи не
    // пересекались между двумя реестрами. Первая версия проверки это
    // требовала и ругалась на 23 ключа, потому что пересечение задумано:
    // SOCKET_EVENTS перечисляет события вообще, SERVER_EVENTS — только те,
    // что сервер шлёт. Пересечение тут норма, а не две правды.
    //
    // Настоящая ошибка была в другом: я искал отправку только в
    // SOCKET_EVENTS и объявил zone:changed мёртвым, хотя сервер шлёт его
    // через SERVER_EVENTS. Поэтому обе стороны проверяются явно.
  });

  it('требование уровня зоны доходит до игрока, а не лежит в данных', () => {
    // ПОЧЕМУ ПОКАЗ, А НЕ ЗАПРЕТ. Требование уровня региона проверяется только
    // на /travel. Мир бесшовный: координату шлёт клиент, сервер её сохраняет,
    // зона выводится из координаты. Единого затвора, к которому прикрутили
    // бы проверку, нет — шаг нельзя запретить, не сделав движение рваным, а
    // запрет обходится тривиально. Монстры в зоне и так дают её уровень.
    //
    // Поэтому поле показывается. Игрок получает «во сколько опасна зона и с
    // какого уровня она открыта» и перестаёт заходить куда нельзя по
    // незнанию, а не потому, что его не пускают.
    const начало = КЛИЕНТ.indexOf("socket.on('zone:changed'");
    must(начало > 0, 'не нашёл подписку на zone:changed в клиенте');
    const безКомментариев = КЛИЕНТ.slice(начало, начало + 2600).replace(/\/\/[^\n]*/g, ' ');
    must(/zones\.need_level/.test(безКомментариев),
      'требование уровня не читается в тосте смены зоны: поле снова мёртвое');
    // Тип обязан знать поле: без него TypeScript не даст его прочитать.
    must(/dangerLevel: number; minLevel\?: number \}/.test(КЛИЕНТ),
      'в типе полезной нагрузки zone:changed нет minLevel — прочитать поле не дадут');
    must(/payload\.zone\.minLevel/.test(безКомментариев),
      'в тосте есть слово про уровень, но не само значение minLevel');
  });

  it('требование уровня заполнено у всех зон и не ниже региона', () => {
    const отсутствуют = ZONES.filter((з) => typeof з.minLevel !== 'number' || з.minLevel < 1);
    must(отсутствуют.length === 0,
      `зоны без требования по уровню: ${отсутствуют.map((з) => з.id).join(', ')}`);
    const ниже = ZONES.filter((з) => з.minLevel < (REGION_LEVEL_REQUIREMENTS[з.region] ?? 1));
    must(ниже.length === 0,
      `зоны доступны раньше региона: ${ниже.map((з) => з.id).join(', ')}`);
  });

  it('слово про уровень переведено во всех трёх языках', () => {
    const отсутствуют: string[] = [];
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`)) as Record<string, Record<string, string>>;
      if (typeof словарь.zones?.need_level !== 'string' || словарь.zones.need_level.length === 0) {
        отсутствуют.push(`${язык}: zones.need_level`);
      }
    }
    must(отсутствуют.length === 0, `в словарях нет:\n  ${отсутствуют.join('\n  ')}`);
  });

  it('файлов тестов в карте столько же, сколько на диске', () => {
    // Последняя мелочь перед выкаткой, но она уже дважды ломалась за серию:
    // карта обещает число файлов тестов, и число разъезжалось молча.
    const файлы = readdirSync(join(корень, 'server', 'src', 'tests')).filter((f) => f.endsWith('.test.ts'));
    const карта = читать('ROADMAP.md');
    const вКарте = /\*\*(\d+)[^*]{0,40}файл[а-яё]*[^*]{0,20}\*\*/.exec(карта);
    must(вКарте !== null, 'в карте нет числа файлов тестов');
    must(Number(вКарте![1]) === файлы.length,
      `в карте ${вКарте![1]} файлов тестов, на диске ${файлы.length}`);
  });
});
