// Жители городов: файл модели, места под фигуры и вызов из мира.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';
import { getZoneAt } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ЖИТЕЛИ = читать('client/src/app/game3d/townfolk.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const РИГ = читать('client/src/app/game3d/realRig.ts');
const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  characters?: { file: string; name: string; bytes: number }[];
  clips?: { file: string; name: string; bytes: number }[];
};

/**
 * Места под жителей читаются из самого кода, а не дублируются здесь числами.
 *
 * ТАК ПРОВЕРКА НЕ СЛЕПА. Раньше проверки декора искали константы вида
 * `export const RUIN_BRIDGE = { x: … }` регуляркой по terrain.ts. Здесь городов
 * девять, они считаются из радиуса и углов, и такая регулярка либо ничего не
 * найдёт, либо проверит не то место. Поэтому места вычисляются тем же кодом,
 * который их ставит: функция townfolkSpots подставляется в тело проверки.
 */
function места(): { region: string; x: number; z: number; ry: number }[] {
  const начало = ЖИТЕЛИ.indexOf('export function townfolkSpots()');
  must(начало > 0, 'функция townfolkSpots не найдена: проверять нечего');
  const тело = ЖИТЕЛИ.slice(начало, ЖИТЕЛИ.indexOf('export interface TownfolkHandle'));
  const кольцо = Number(/const КОЛЬЦО = ([\d.]+);/.exec(ЖИТЕЛИ)![1]);
  must(Number.isFinite(кольцо) && кольцо > 0, 'Кольцо жителей не задано');

  // Города и радиусы берём из исходника terrain.ts: числа должны совпадать
  // с настоящими городами, а не с копией в проверке.
  const города = [...ТЕРРЕЙН.matchAll(
    /\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+), radius: (\d+)/g,
  )].map((м) => ({
    region: м[1],
    x: Number(м[2]),
    z: Number(м[3]),
    radius: Number(м[4]),
  }));
  must(города.length >= 9, `городов в terrain.ts ${города.length}, а жителям нужно девять`);

  // Углы достаём из объявления TOWNSFOLK_TOWNS.
  const блок = ЖИТЕЛИ.slice(
    ЖИТЕЛИ.indexOf('export const TOWNSFOLK_TOWNS'),
    ЖИТЕЛИ.indexOf('export interface TownfolkSpot'),
  );
  const выбор = [...блок.matchAll(/region: '([a-z_]+)', углы: \[([\d, ]+)\]/g)];
  must(выбор.length === 3, `в TOWNSFOLK_TOWNS городов ${выбор.length}, ждали три`);

  const точки: { region: string; x: number; z: number; ry: number }[] = [];
  for (const строка of выбор) {
    const город = города.find((г) => г.region === строка[1]);
    must(город !== undefined, `город ${строка[1]} есть в списке жителей, но нет среди городов`);
    const углы = строка[2].split(',').map((с) => Number(с.trim()));
    must(углы.length === 3, `в городе ${строка[1]} углов ${углы.length}, ждали три`);
    углы.forEach((градус, номер) => {
      const угол = (градус * Math.PI) / 180;
      точки.push({
        region: строка[1],
        x: Math.round(город!.x + Math.cos(угол) * город!.radius * кольцо),
        z: Math.round(город!.z + Math.sin(угол) * город!.radius * кольцо),
        ry: Math.atan2(-Math.sin(угол), -Math.cos(угол)) + (номер - 1) * 0.7,
      });
    });
  }
  must(тело.includes('round'), 'места не округляются: числа в проверке разойдутся с игрой');
  return точки;
}

describe('Жители городов: модель на месте', () => {
  /**
   * Имена моделей берём из кода, а не перечисляем здесь.
   *
   * Иначе список в проверке и список в игре разошлись бы молча: добавили
   * третью модель в townfolk.ts, а проверка продолжала бы сверять первые две
   * и радоваться. Список кода — единственный источник правды.
   */
  // Требование «моделей хотя бы две» живёт НЕ здесь, а в проверке чередования.
  // Если поставить его здесь, то удаление второй модели из кода роняет
  // сверку файлов, а не ту проверку, которая про модели: и хозяин правки
  // видит не то.
  function моделиИзКода(): string[] {
    const блок = ЖИТЕЛИ.slice(
      ЖИТЕЛИ.indexOf('const МОДЕЛИ'),
      ЖИТЕЛИ.indexOf('const КЛИП'),
    );
    const выбор = [...блок.matchAll(/'([a-z0-9_]+)'/g)].map((м) => м[1]);
    must(выбор.length > 0, 'в townfolk.ts список моделей пуст: жителям не из чего строиться');
    return выбор;
  }

  it('файлы жителей в сборке и совпадают с манифестом', () => {
    const имена = моделиИзКода();
    for (const имя of имена) {
      const запись = МАНИФЕСТ.characters?.find((д) => д.file === `models/${имя}.glb`);
      must(запись !== undefined, `в манифесте нет ${имя}: файл никто не сверяет с диском`);
      const путь = join(корень, 'client/src/app/public', запись!.file);
      must(existsSync(путь), `файла ${имя} нет: города останутся пустыми`);
      must(
        statSync(путь).size === запись!.bytes,
        `${имя}: на диске ${statSync(путь).size}, в манифесте ${запись!.bytes}`,
      );
    }
  });

  it('в каждом городе есть обе модели, а не девять копий одной', () => {
    // Здесь же требование «моделей хотя бы две» — не в сверке файлов.
    // Иначе удаление второй модели из кода роняет проверку манифеста, и
    // правщик видит не ту причину.
    const имена = моделиИзКода();
    must(
      имена.length >= 2,
      `в townfolk.ts моделей ${имена.length}: все девять фигур станут клонами одной`,
    );
    // Модели чередуются по индексу точки внутри города. Если перебор заменят
    // на «по очереди по городам», в первом городе окажутся обе, а в двух
    // других по одной — и проверка молча согласится, потому что городов
    // всё ещё три.
    must(
      /свои\.entries\(\)/.test(ЖИТЕЛИ),
      'модели не чередуются по индексу точки внутри города',
    );
    must(
      /номер % модели\.length/.test(ЖИТЕЛИ),
      'нет чередования моделей: все жители будут копиями одной фигуры',
    );
    // Список моделей используется целиком, а не первый его элемент.
    must(
      !/МОДЕЛИ\[0\]/.test(ЖИТЕЛИ),
      'берётся только первая модель из списка: вторая скачана и не используется',
    );
  });

  it('модели лёгкие, сжаты и без вшитой анимации', () => {
    // Проверка идёт по всем моделям из кода: свойства одной не означают
    // свойств остальных, а список в проверке разошёлся бы с игрой молча.
    for (const имя of моделиИзКода()) {
      const путь = join(корень, 'client/src/app/public/models', `${имя}.glb`);
      const buf = readFileSync(путь);
      must(
        buf.length < 2 * 1024 * 1024,
        `${имя} весит ${(buf.length / 1048576).toFixed(1)} МБ: девять фигур это терпимо, а пакет непростим`,
      );
      const json = JSON.parse(buf.slice(20, 20 + buf.readUInt32LE(12)).toString('utf-8')) as {
        extensionsUsed?: string[];
        animations?: unknown[];
        skins?: unknown[];
        images?: unknown[];
      };
      must(
        (json.extensionsUsed ?? []).includes('KHR_draco_mesh_compression'),
        `${имя}: геометрия без Draco, житель весит как сырая`,
      );
      must((json.skins ?? []).length === 1, `${имя}: в модели нет скелета, по ней нельзя ходить`);
      must(
        (json.animations ?? []).length === 0,
        `${имя}: в модели вшита анимация — это поза привязки (T-pose, 250 одинаковых кадров), ` +
          'а движение даёт клип игры',
      );
      must((json.images ?? []).length >= 7, `${имя}: карт меньше семи, житель приедет голым`);
    }
  });

  it('у моделей одинаковый скелет, иначе клип оживит только одну', () => {
    // Клип цепляется к костям по ИМЕНАМ. Если у второй модели набор имён
    // отличается, она просто останется в T-позе, а ошибку видно только в игре.
    // Проверка идёт по именам, а не по количеству: 65 костей с другими
    // именами — то же самое отсутствие клипа, только тихое.
    const именаКостей = моделиИзКода().map((имя) => {
      const buf = readFileSync(join(корень, 'client/src/app/public/models', `${имя}.glb`));
      const json = JSON.parse(buf.slice(20, 20 + buf.readUInt32LE(12)).toString('utf-8')) as {
        nodes?: { name: string }[];
        skins?: { joints: number[] }[];
      };
      const узлы = json.nodes ?? [];
      return (json.skins ?? []).flatMap((с) => с.joints).map((j) => узлы[j]?.name ?? '').sort();
    });
    for (const [н, имена] of именаКостей.entries()) {
      must(
        имена.length > 0,
        `у модели номер ${н} не нашлось костей: проверка ничего не смотрела`,
      );
    }
    const эталон = именаКостей[0];
    for (const [н, имена] of именаКостей.entries()) {
      must(
        имена.join(',') === эталон.join(','),
        `модель номер ${н}: кости не совпали с первой — клип оживит только её. ` +
          `расхождение: ${имена.filter((и) => !эталон.includes(и)).join(', ') || эталон.filter((и) => !имена.includes(и)).join(', ')}`,
      );
    }
  });

  it('движение берётся клипом игры, а не вшито в модель', () => {
    // Имя файла в коде не пишется целиком: загрузчик сам дописывает .glb,
    // поэтому ищем имя клипа и сборку пути. Раньше проверка требовала
    // литерал "standing-idle.glb" в коде и падала на совершенно верной
    // реализации — искать надо обе половины, а не склейку.
    must(/const КЛИП = 'standing-idle'/.test(ЖИТЕЛИ), 'житель не получил клип игры');
    must(
      /\$\{БАЗА\}\$\{имя\}\.glb/.test(ЖИТЕЛИ),
      'загрузчик не дописывает .glb к имени: клип не найдётся по файлу',
    );
    must(
      МАНИФЕСТ.clips === undefined || МАНИФЕСТ.clips.length > 0,
      'раздел clips в манифесте пуст при заявленных клипах',
    );
  });

  it('скелет клонируется правильно и ноги ставятся на землю', () => {
    // Обычный Object3D.clone делит Skeleton с оригиналом: все девять фигур
    // движутся от одной кости, и стоит на месте шестеро из девяти.
    must(
      /SkeletonUtils\.js/.test(ЖИТЕЛИ),
      'нет импорта SkeletonUtils: клоны делят скелет и стоят столбом',
    );
    // Имя переменной-источника менялось вместе с числом моделей: раньше здесь
    // было копияСкелета(модель) — одна модель на всех. Проверка ищет вызов по
    // назначению, а не по прежнему имени переменной, иначе честное
    // расширение списка моделей роняло бы её.
    must(
      /копияСкелета\(имя\)/.test(ЖИТЕЛИ) || /копияСкелета\(модель\)/.test(ЖИТЕЛИ),
      'модель клонируется не через SkeletonUtils',
    );
    must(
      /подогнать\(клон/.test(ЖИТЕЛИ),
      'модель не проходит подгонку: ноги останутся на высоте начала координат',
    );
    must(/export function подогнать/.test(РИГ), 'подгонка не экспортирована: живётели её не вызовут');
  });

  it('смеситель один на город и его кто-то двигает', () => {
    // Один mixer на город: дорожки клипа ищут кости по именам внутри группы,
    // поэтому одно действие ведёт троих. Свой mixer на фигуру дороже втрое.
    must(/new THREE\.AnimationMixer\(группа\)/.test(ЖИТЕЛИ), 'смеситель не на группу города');
    must(/update\(dt: number\): void/.test(ЖИТЕЛИ), 'у жителей нет обновления анимации');
    must(
      /this\.townfolk\.update\(dt\)/.test(МИР),
      'мир не двигает жителей: без update они стоят столбом',
    );
    must(/createTownfolk\(this\.scene\)/.test(МИР), 'жители не создаются в мире');
    must(/this\.townfolk\?\.dispose\(\)/.test(МИР), 'жители не освобождаются при разборе мира');
  });

  it('коллайдеры заводятся до загрузки модели', () => {
    // Иначе в первые секунды игрок проходит сквозь ещё не видимых людей и
    // упирается в них, когда те появляются.
    const тело = ЖИТЕЛИ.slice(ЖИТЕЛИ.indexOf('export function createTownfolk'));
    const коллайдеры = тело.indexOf('addCollider(');
    const загрузка = тело.indexOf('загрузитьСцену(');
    must(коллайдеры > 0, 'жители без коллайдеров: игрок проходит сквозь человека');
    must(
      коллайдеры < загрузка || тело.indexOf('void Promise.all') < коллайдеры,
      'коллайдеры ставятся после старта загрузки: в окне загрузки сквозь людей проходят',
    );
  });
});

describe('Места под жителей: сухо, в своей зоне, не в стене', () => {
  it('девять мест: по три в городе, без совпадений', () => {
    const точки = места();
    must(точки.length === 9, `мест ${точки.length}, ждали девять`);
    const поГородам = new Map<string, number>();
    for (const т of точки) поГородам.set(т.region, (поГородам.get(т.region) ?? 0) + 1);
    must(поГородам.size === 3, `городов с жителями ${поГородам.size}, ждали три`);
    for (const [регион, сколько] of поГородам) {
      must(сколько === 3, `в городе ${регион} жителей ${сколько}, ждали троих`);
    }
    for (let i = 0; i < точки.length; i++) {
      for (let j = i + 1; j < точки.length; j++) {
        const d = Math.hypot(точки[i].x - точки[j].x, точки[i].z - точки[j].z);
        must(d >= 4, `жители в (${точки[i].x}, ${точки[i].z}) и (${точки[j].x}, ${точки[j].z}) стоят в ${d.toFixed(1)} м: слишком тесно`);
      }
    }
  });

  it('каждый житель стоит на суше в зоне своего города', () => {
    for (const т of места()) {
      must(!isWater(т.x, т.z), `житель в (${т.x}, ${т.z}) стоит в воде`);
      for (let dx = -2; dx <= 2; dx++) {
        for (let dz = -2; dz <= 2; dz++) {
          must(
            !isWater(т.x + dx, т.z + dz),
            `под жителем вода в (${т.x + dx}, ${т.z + dz})`,
          );
        }
      }
      const зона = getZoneAt(т.x, т.z);
      must(зона !== null, `житель в (${т.x}, ${т.z}) вне зон`);
      must(
        зона!.region === т.region,
        `житель в (${т.x}, ${т.z}) попал в зону ${зона!.id} региона ${зона!.region}, а стоит в ${т.region}`,
      );
    }
  });

  it('жители стоят внутри своих городов и не в стенах', () => {
    const города = [...ТЕРРЕЙН.matchAll(
      /\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+), radius: (\d+)/g,
    )].map((м) => ({
      region: м[1],
      x: Number(м[2]),
      z: Number(м[3]),
      radius: Number(м[4]),
    }));
    const столица = /export const CITY = \{ x: (-?\d+), z: (-?\d+), radius: (\d+)/.exec(ТЕРРЕЙН);
    must(столица !== null, 'столица не найдена: нечем проверить, что жители не влезли в неё');

    for (const т of места()) {
      const город = города.find((г) => г.region === т.region);
      must(город !== undefined, `города ${т.region} нет`);
      const d = Math.hypot(т.x - город!.x, т.z - город!.z);
      must(
        d < город!.radius - 4,
        `житель в (${т.x}, ${т.z}) в ${d.toFixed(1)} м от центра ${т.region} при радиусе ${город!.radius}: вне города`,
      );
      // Внутри стен города с запасом на фигуру.
      const доСтолицы = Math.hypot(т.x - Number(столица![1]), т.z - Number(столица![2]));
      must(
        доСтолицы >= Number(столица![3]) + 4,
        `житель в ${доСтолицы.toFixed(1)} м от центра столицы: замурован в Исфахане, где горожане уже есть`,
      );
    }
  });

  it('жители не стоят в одном месте дважды и смотрят в город', () => {
    const точки = места();
    const ключи = new Set(точки.map((т) => `${т.x}:${т.z}`));
    must(ключи.size === точки.length, `мест ${точки.length}, уникальных ${ключи.size}: двое стоят в одной точке`);
    for (const т of точки) {
      must(
        Number.isFinite(т.ry),
        `поворот жителя в (${т.x}, ${т.z}) не число: фигура встанет боком или ляжет`,
      );
    }
  });
});

describe('Границы зон: город не должен попадать в чужую зону', () => {
  it('у каждого города с жителями своя зона по всей площади', () => {
    // НАЙДЕННАЯ ОШИБКА, НЕ НАША. Зона caucasus_pass занимает z от 500 до
    // 567 на всю ширину мира, а Шираз стоит на z = 493 при радиусе 44. То
    // есть северная половина города целиком лежит в зоне Кавказа: игрок в
    // Ширазе видит чужое название зоны и встречает кавказских монстров.
    // Здесь фиксируется, чтобы правка границ не была забыта молча.
    const города = [...ТЕРРЕЙН.matchAll(
      /\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+), radius: (\d+)/g,
    )].map((м) => ({
      region: м[1],
      x: Number(м[2]),
      z: Number(м[3]),
      radius: Number(м[4]),
    }));
    const задетые = города.filter((г) => {
      const север = getZoneAt(г.x, г.z + Math.round(г.radius));
      return север !== null && север.region !== г.region;
    }).map((г) => г.region);

    for (const регион of задетые) {
      console.warn(
        `[зоны] у города ${регион} северная половина в зоне ` +
        `${getZoneAt(
          города.find((г) => г.region === регион)!.x,
          города.find((г) => г.region === регион)!.z
            + Math.round(города.find((г) => г.region === регион)!.radius),
        )?.id}`,
      );
    }

    // Известная ошибка, зафиксированная списком, а не «должно быть ноль».
    //
    // Зоны — прямоугольники, а границы соседних регионов проходят рядом:
    // caucasus_pass занимает z от 500 до 567 на всю ширину мира, и Шираз
    // (z = 493, радиус 44) наполовину в неё заходит. То же у Месопотамии и
    // Залива. Игрок в такой половине города видит чужое название зоны и
    // встречает чужих монстров.
    //
    // Почему список, а не must(... === 0). Раздельные прямоугольники не
    // развести без переделки границ зон, а это меняет, где какие монстры
    // спавнятся, то есть решение владельца. Пока решение не принято, список
    // зафиксирован: если границы поправят, тест об этом честно скажет, и
    // список обновят вместе с правкой, а не молча.
    const ИЗВЕСТНЫЕ = ['shiraz', 'mesopotamia', 'persian_gulf'];
    must(
      задетые.slice().sort().join(', ') === ИЗВЕСТНЫЕ.slice().sort().join(', '),
      `список городов с чужой половиной изменился: стало ${задетые.join(', ') || 'пусто'}, ` +
      `зафиксировано ${ИЗВЕСТНЫЕ.join(', ')}. Если границы зон поправили — ` +
      'обнови ИЗВЕСТНЫЕ вместе с правкой',
    );
  });
});
