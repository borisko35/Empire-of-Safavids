// Горожане получают одежду поверх модели.
//
// ЧТО БЫЛО (22 октября 2026, §300). Горожанин — это модель из GLB: халат есть,
// а перевязи, пояса и головного убора нет. На улице человек выглядит как
// персонаж из каталога: силуэт без деталей читается «слепо».
//
// ЧТО ТЕПЕРЬ. Перевязь через грудь, пояс и тюрбан. Одежда крепится к КОСТЯМ
// модели, а не к её корню, — иначе при ходьбе она висела бы в воздухе. Костя
// ищутся по имени на ходу: имена костей в разных моделях различаются, и
// жёстко прописанное имя однажды сломало бы всю одежду разом.
//
// ЧТО ПРОВЕРЯЕТСЯ. Одежда есть и состоит из перевязи, пояса и тюрбана; одежда
// крепится к костям, а не к корню модели; кости ищутся по имени, а не
// прописаны строкой.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ГРАЖДАНЕ = читать('client/src/app/game3d/civilians.ts');

describe('Горожане одеты', () => {
  it('перевязь, пояс и тюрбан', () => {
    должен(/function одетьГорожанина\(/.test(ГРАЖДАНЕ), 'нет сборщика одежды горожанина');
    // Перевязь через грудь.
    должен(
      /const перевязь = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.17, 0\.045, 6, 14\)/.test(ГРАЖДАНЕ),
      'нет перевязи',
    );
    // Пояс.
    должен(
      /const пояс = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.16, 0\.028, 5, 12\)/.test(ГРАЖДАНЕ),
      'нет пояса',
    );
    // Тюрбан: намотка и шапка.
    должен(
      /const намотка = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.1, 0\.035, 6, 12\)/.test(ГРАЖДАНЕ),
      'тюрбан не намотан',
    );
    должен(/const верх = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.085, 8, 6\)/.test(ГРАЖДАНЕ),
      'у тюрбана нет шапки');
  });

  it('одежда крепится к костям, а не к корню модели', () => {
    // Костя ищутся на ходу: имена костей у разных моделей различаются.
    должен(
      /const кость = \(фрагмент: string\): THREE\.Object3D \| null =>/.test(ГРАЖДАНЕ),
      'кости не ищутся по имени',
    );
    должен(
      /o\.name\.toLowerCase\(\)\.includes\(фрагмент\)/.test(ГРАЖДАНЕ),
      'кости ищутся не по имени',
    );
    // Одежда — детям костей, а не корню модели.
    должен(/спина\.add\(перевязь\);/.test(ГРАЖДАНЕ), 'перевязь не на спине');
    должен(/спина\.add\(пояс\);/.test(ГРАЖДАНЕ), 'пояс не на спине');
    должен(/голова\.add\(намотка, верх\);/.test(ГРАЖДАНЕ), 'тюрбан не на голове');
    // И вызывается при загрузке модели.
    должен(/одетьГорожанина\(cloned, ткань\);/.test(ГРАЖДАНЕ), 'одежда не надевается на модель');
  });
});
