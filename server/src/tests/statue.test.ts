// Статуя у базарного квартала.
//
// Девятнадцатый пакет из Assets. Тот же случай с масштабом, что указатель,
// стол, доска и корова: у модели после импорта FBX масштаб 0.01, и без
// применения в игру уехали бы сантиметры.
//
// ЧТО ЛОВИТСЯ И ПОЧЕМУ ТАК.
// 1. Модель в метрах по оси Y.
// 2. Человеческий рост: 1.5-2.2 м. Ниже — урна, выше — колонна. В третьем
//    пакете проверка была «размах меньше трёх», и она пропустила бы и урну.
// 3. Статуя без скелета и анимации.
// 4. Покрашена: в пакете материал от 3ds Max для V-Ray, и ни одна карта не
//    приехала — импортёр об этом предупреждает. Без покраски серая.
// 5. Стоит снаружи базарного квартала: внутри него торговые ряды, и статуя
//    посреди рядов — препятствие.
// 6. Не в резерве из кода столицы: кварталы, NPC, конюшни перечислены там
//    списком, и статуя не должна встать ни в один.
// 7. Не в центре столицы: там дворец, мечеть и точка возрождения.
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');
const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
};

interface GlbJson {
  meshes?: { primitives?: { attributes: { POSITION: number }; indices?: number }[] }[];
  skins?: unknown[];
  animations?: unknown[];
  accessors?: { min: number[]; max: number[] }[];
  materials?: { name?: string; pbrMetallicRoughness?: { baseColorFactor?: number[]; baseColorTexture?: unknown } }[];
  textures?: unknown[];
}

function jsonGlb(путь: string): GlbJson {
  const буфер = readFileSync(путь);
  must(буфер.readUInt32LE(0) === 0x46546c67, `${путь}: это не GLB`);
  const длина = буфер.readUInt32LE(12);
  return JSON.parse(буфер.subarray(20, 20 + длина).toString('utf-8')) as GlbJson;
}

const ФАЙЛ = join(корень, 'client/src/app/public/models/decor/statue.glb');

interface Часть {
  высота: number;
  низ: number;
  ширина: number;
  глубина: number;
}

/**
 * Все части модели по её файлу.
 *
 * Постамент собран из двух коробок, поэтому в файле три меша, и у каждого
 * свой accessor с min/max. Draco сжимает вершины, но границы в JSON остаются:
 * проверка может сказать «нижняя плита высотой 0.08», а не «что-то внизу».
 *
 * Смещение фигуры на постамент запечено в сетку, а не оставлено в узле.
 * Пока оно было в `location`, экспорт писал вершины фигуры с низом на -0.0024
 * и ростом 1.690 — мимо постамента, и по файлу это невозможно было проверить.
 */
function части(): Часть[] {
  const gltf = jsonGlb(ФАЙЛ);
  const список: Часть[] = [];
  for (const меш of gltf.meshes ?? []) {
    for (const примитив of меш.primitives ?? []) {
      const accessor = (gltf.accessors ?? [])[примитив.attributes.POSITION];
      список.push({
        высота: accessor.max[1] - accessor.min[1],
        низ: accessor.min[1],
        ширина: accessor.max[0] - accessor.min[0],
        глубина: accessor.max[2] - accessor.min[2],
      });
    }
  }
  must(список.length > 0, 'в модели статуи нет ни одной части');
  return список;
}

/**
 * Фигура — самая высокая часть: постамент ниже.
 *
 * Сравнение идёт ПО ИНДЕКСУ, а не по ссылке на объект. Части читаются из
 * файла заново на каждый вызов, и `ч !== фигура()` сравнивал бы разные
 * объекты с одинаковыми числами — то есть всегда истину, и в постамент
 * попадала бы сама фигура. На двухступенчатом постаменте это давало верх
 * 1.890 вместо 0.200.
 */
function индексФигуры(): number {
  const все = части();
  let лучший = 0;
  for (let i = 1; i < все.length; i++) {
    if (все[i].высота > все[лучший].высота) лучший = i;
  }
  return лучший;
}

/** Фигура — самая высокая часть: постамент ниже. */
function фигура(): Часть {
  return части()[индексФигуры()];
}

/** Части постамента: все, кроме фигуры. */
function ступени(): Часть[] {
  const все = части();
  const безФигуры = все.filter((_, i) => i !== индексФигуры());
  must(безФигуры.length > 0, 'в модели нет постамента');
  return безФигуры;
}

/** Часть постамента, что стоит на земле: та, у которой низ меньше всех. */
function плита(): Часть {
  return ступени().reduce((ниже, ч) => (ч.низ < ниже.низ ? ч : ниже));
}

/** Высота постамента — верх самой высокой его ступени, а не высота нижней. */
function высотаПостамента(): number {
  return Math.max(...ступени().map((ч) => ч.низ + ч.высота));
}

function габариты(): { ширина: number; высота: number; глубина: number } {
  const размах = [0, 0, 0];
  for (const ч of части()) {
    размах[0] = Math.max(размах[0], ч.ширина);
    размах[1] = Math.max(размах[1], ч.низ + ч.высота);
    размах[2] = Math.max(размах[2], ч.глубина);
  }
  return { ширина: размах[0], высота: размах[1], глубина: размах[2] };
}

function место(): { x: number; z: number; ry: number } {
  const начало = ТЕРРЕЙН.indexOf('export const BAZAAR_STATUE');
  must(начало > 0, 'в terrain.ts нет BAZAAR_STATUE — место статуи не описано');
  const блок = ТЕРРЕЙН.slice(начало, ТЕРРЕЙН.indexOf('export function buildBazaarStatue'));
  const м = /x: (-?\d+), z: (-?\d+), ry: (-?[\d.]+)/.exec(блок);
  must(м !== null, 'не разобрались координаты статуи');
  return { x: Number(м[1]), z: Number(м[2]), ry: Number(м[3]) };
}

/** Расстояние от статуи до центра базарного квартала, в мировых координатах. */
function расстояниеДоБазара(т: { x: number; z: number }): number {
  const столица = /export const CITY = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН);
  must(столица !== null, 'CITY не найден');
  const базар = { x: Number(столица[1]) + 84, z: Number(столица[2]) + 0 };
  return Math.hypot(т.x - базар.x, т.z - базар.z);
}

/**
 * Резервы столицы читаются из кода, а не перечислены здесь.
 *
 * Кроме круглых резервов вида `{ x, z, r }` читаются и NPC: в коде они
 * лежат списком пар и превращаются в круги только через `.map`, поэтому по
 * образцу `{ x, z, r }` они не видны. Список разбирается отдельно, иначе
 * ломка «статуя встала на место жителя» падала бы не на ту проверку.
 */
function резервы(): { x: number; z: number; r: number; имя: string }[] {
  const список = [
    ...ТЕРРЕЙН.matchAll(
      /\{ x: (-?[\d.]+), z: (-?[\d.]+), r: (\d+) \}(?:,\s*\/\/ ([^\n]*))?/g,
    ),
  ].map((м) => ({
    x: Number(м[1]),
    z: Number(м[2]),
    r: Number(м[3]),
    имя: (м[4] || 'резерв в коде').trim(),
  }));
  must(список.length > 5, `резервов столицы ${список.length}: разбор кода сломался`);

  // NPC: список пар перед `.map(([x, z]) => ({ x, z, r: 2 }))`.
  //
  // Ищем не по слову «NPC» в комментарии (он стоит после `.map`, то есть
  // список остался позади), а по самой форме: массив пар плюс `.map` с
  // разбором пары. Так список виден целиком, иначе проверка «не в резерве»
  // молча слепа к жителям.
  // Форма в коде: `...[[-8, 10], [20, 16], ...]` — список пар в одном внешнем
  // скобочном списке, без второго `]` в конце, поэтому берём от `[[` до
  // `\n .map` и вытаскиваем числа попарно.
  const блокNpc = /(\[\[-?\d+\s*,\s*-?\d+\](?:\s*,\s*\[-?\d+\s*,\s*-?\d+\])*)\s*\]\s*\n\s*\.map\(\(\[\s*\w+\s*,\s*\w+\s*\]\)\s*=>\s*\(\{\s*\w+\s*,\s*\w+\s*,\s*r:\s*(\d+)\s*\}\)\)/.exec(
    ТЕРРЕЙН,
  );
  must(блокNpc !== null, 'список жителей столицы не разобрался: проверка «не в резерве» их не видит');
  const радиусNpc = Number(блокNpc[2]);
  const числа = блокNpc[1].match(/-?\d+/g) || [];
  must(
    числа.length % 2 === 0 && числа.length >= 8,
    `в списке жителей ${числа.length} чисел, ждали чётное число пар`,
  );
  for (let i = 0; i + 1 < числа.length; i += 2) {
    const nx = Number(числа[i]);
    const nz = Number(числа[i + 1]);
    список.push({ x: nx, z: nz, r: радиусNpc, имя: `житель в (${nx}, ${nz})` });
  }
  must(
    список.some((р) => р.имя.startsWith('житель')),
    'жители столицы не разобрались: проверка «не в резерве» их не видит',
  );
  return список;
}

describe('Статуя: модель', () => {
  it('файл в сборке и совпадает с манифестом', () => {
    const запись = МАНИФЕСТ.decor?.find((д) => д.name === 'statue');
    must(запись !== undefined, 'в манифесте нет статуи: файл никто не сверяет с диском');
    must(запись!.file === 'models/decor/statue.glb', 'путь к статуе в манифесте не тот');
    must(existsSync(ФАЙЛ), 'файла статуи нет на диске');
    must(
      statSync(ФАЙЛ).size === запись!.bytes,
      `статуя: на диске ${statSync(ФАЙЛ).size}, в манифесте ${запись!.bytes}`,
    );
  });

  it('модель в метрах, а не в сантиметрах исходника', () => {
    // У модели после импорта FBX масштаб 0.01. Замер в Blender показывает верные
    // 1.69 м, а экспортёр glTF пишет локальные координаты сетки: в игру
    // уехали бы сантиметры. Ловится только чтением файла.
    const г = габариты();
    const наибольшее = Math.max(г.ширина, г.высота, г.глубина);
    must(
      наибольшее < 3.0,
      `наибольший размер ${наибольшее.toFixed(2)} м — масштаб объекта не применён. ` +
        'Проверяем файл, а не исходник: в исходнике всё выглядит верно',
    );
  });

  it('рост человеческий: не урна и не колонна', () => {
    // Границы 1.5-2.2 м, а не «меньше трёх». Предыдущие проверки на деко
    // ограничивались только сверху и пропускали бы урну 0.8 м на месте
    // статуи.
    //
    // Меряется ФИГУРА, а не вся статуя: с постаментом вся модель 1.89 м, и
    // граница прошла бы случайно. Фигура — самая высокая часть.
    const фиг = фигура();
    must(
      фиг.высота >= 1.5 && фиг.высота <= 2.2,
      `рост фигуры ${фиг.высота.toFixed(2)} м по оси Y: ждали 1.5-2.2, то есть человека`,
    );
    must(
      фиг.ширина < 1.0 && фиг.глубина < 1.0,
      `фигура ${фиг.ширина.toFixed(2)} на ${фиг.глубина.toFixed(2)} м в плане — это не фигура`,
    );
  });

  it('стоит на земле: низ постамента на нуле', () => {
    // Проверяется плита, а не первая попавшаяся часть. Порядок примитивов в
    // файле не задан, и «первый меш» — это не «то, что стоит на земле».
    const низ = плита().низ;
    must(
      Math.abs(низ) <= 0.02,
      `низ постамента на ${низ.toFixed(3)} по Y: статуя уедет под площадь или повиснет над ней`,
    );
  });

  it('не скелет и не анимация: статуя не должна двигаться', () => {
    const gltf = jsonGlb(ФАЙЛ);
    must((gltf.skins ?? []).length === 0, 'в статуе есть скелет — это не статуя');
    must((gltf.animations ?? []).length === 0, 'в статуе анимация');
  });

  it('покрашена в камень, а не осталась серой по умолчанию', () => {
    // Материал в исходнике был серым (0.5, 0.5, 0.5) и без карт: в пакете
    // один FBX, а материал от 3ds Max для V-Ray, и импортёр честно
    // предупреждает, что ссылки на карты отброшены.
    const gltf = jsonGlb(ФАЙЛ);
    const материалы = gltf.materials ?? [];
    must(материалы.length > 0, 'у статуи нет материала — будет серый куб');
    for (const материал of материалы) {
      const цвет = материал.pbrMetallicRoughness?.baseColorFactor ?? [1, 1, 1, 1];
      const серыйПоУмолчанию =
        Math.abs(цвет[0] - 0.5) < 0.02 && Math.abs(цвет[1] - 0.5) < 0.02;
      must(
        !серыйПоУмолчанию,
        `материал ${материал.name ?? '(без имени)'} остался серым по умолчанию: [${цвет.join(', ')}]`,
      );
      // Карт в пакете нет, и вшивать их неоткуда: если карта всё же появилась,
      // значит она не из этого пакета и её надо проверить.
      must(
        материал.pbrMetallicRoughness?.baseColorTexture === undefined,
        `у материала ${материал.name} есть карта цвета: в пакете её не было, откуда она взялась?`,
      );
    }
  });

  it('лёгкая: 10 тысяч полигонов сжаты', () => {
    const { размер } = { размер: statSync(ФАЙЛ).size };
    must(размер < 256 * 1024, `статуя весит ${размер} байт: 10 тысяч полигонов должны сжиматься`);
  });
});

describe('Статуя: постамент', () => {
  it('постамент есть: фигура не стоит прямо на земле', () => {
    // Решение владельца — «да, делать постамент». Фигура 1.69 м с основанием
    // 0.36 на 0.60 стояла вплотную к земле и читалась как столб, воткнутый
    // в площадь. Без этой проверки постамент можно забыть или снести молча.
    const все = части();
    must(
      все.length >= 2,
      `в модели ${все.length} частей: постамента нет, фигура стоит прямо на земле`,
    );
  });

  it('постамент поднимает фигугу, а не провисает под неё', () => {
    // Фигура должна стоять ВЫШЕ постамента, а не тонуть в нём: её низ — это
    // верх постамента. Проверяется по файлу, а не по скрипту сборки.
    const фиг = фигура();
    const высота = высотаПостамента();
    must(
      высота > 0.05,
      `постамент высотой ${высота.toFixed(3)} м: это подставка, а не постамент`,
    );
    must(
      Math.abs(фиг.низ - высота) <= 0.01,
      `низ фигуры на ${фиг.низ.toFixed(3)}, а верх постамента на ${высота.toFixed(3)}: ` +
        'фигура либо висит над постаментом, либо утонула в него',
    );
  });

  it('постамент в ступеньку, а не кубом', () => {
    // Решение: одна ступень, то есть куб 0.9x0.9x0.2, читалась бы как
    // шахматная база — ровно тот довод, которым отвергли доску 53 см на
    // земле. Две ступени дают отступ, и видно, где кончилась земля.
    const все = части();
    must(
      все.length >= 3,
      `ступеней постамента ${все.length - 1}: это куб, а не постамент в две ступени`,
    );
    const отсортированные = [...ступени()].sort((а, б) => а.низ - б.низ);
    for (let i = 1; i < отсортированные.length; i++) {
      const верхняя = отсортированные[i];
      const нижняя = отсортированные[i - 1];
      must(
        верхняя.ширина < нижняя.ширина - 0.05,
        `ступень ${i + 1} шириной ${верхняя.ширина.toFixed(2)} не уже нижней ` +
          `${нижняя.ширина.toFixed(2)}: отступа нет, постамент читается как куб`,
      );
    }
  });

  it('плита шире фигуры: постамент читается как постамент, а не как подставка', () => {
    // Основание фигуры — 0.36 на 0.60. Постáмент уже фигуры был бы подставкой:
    // фигура на нём держалась бы на честном слове, и снизу читалось бы
    // «столб, воткнутый в кубик».
    const п = плита();
    const фиг = фигура();
    must(
      п.ширина > фиг.ширина + 0.2,
      `плита ${п.ширина.toFixed(2)} м против фигуры ${фиг.ширина.toFixed(2)} м: ` +
        'плита не шире фигуры, постамент не читается',
    );
    must(
      п.глубина > фиг.глубина + 0.2,
      `плита ${п.глубина.toFixed(2)} м в глубину против фигуры ${фиг.глубина.toFixed(2)} м`,
    );
  });

  it('постамент тёмнее фигуры: два разных камня, а не один серый', () => {
    // На одном цвете постамент сливается с фигурой и перестаёт читаться как
    // постамент. Решение владельца: постамент делать; цвет — тёмный гранит
    // основания против светлого известняка статуи.
    //
    // Материалов постамента ДВА: плита и блок. Проверка «есть и светлый, и
    // тёмный» прошла бы, если бы тёмным остался хоть один из них, то есть
    // читалась бы половина постамента за тёмную половину светлой. Поэтому
    // сверяется каждый материал постамента отдельно.
    const gltf = jsonGlb(ФАЙЛ);
    const материалы = gltf.materials ?? [];
    const цвет = (м: { pbrMetallicRoughness?: { baseColorFactor?: number[] } }): number[] =>
      м.pbrMetallicRoughness?.baseColorFactor ?? [1, 1, 1];
    const светлость = (ц: number[]): number => (ц[0] + ц[1] + ц[2]) / 3;

    const постамент = материалы.filter((м) => /^Socle_/.test(м.name ?? ''));
    const фигура = материалы.filter((м) => !/^Socle_/.test(м.name ?? ''));
    must(
      постамент.length >= 2,
      `материалов постамента ${постамент.length}: у плиты и блока один материал, ` +
        'и половина постамента прочиталась бы за половину фигуры',
    );
    must(
      фигура.length >= 1,
      `материалов фигуры ${фигура.length}, а постамента ${постамент.length}: ` +
        'нечем сравнивать, какой камень темнее',
    );
    const светФигуры = светлость(цвет(фигура[0]));
    for (const м of постамент) {
      must(
        светлость(цвет(м)) < светФигуры - 0.05,
        `материал постамента ${м.name} светлее фигуры: ` +
          `${светлость(цвет(м)).toFixed(2)} против ${светФигуры.toFixed(2)} — ` +
          'постамент сольётся с фигурой',
      );
    }
  });
});

describe('Статуя: стоит у базара', () => {
  it('мир строит статую', () => {
    must(/buildBazaarStatue\(this\.scene\)/.test(МИР), 'мир не строит статую');
    must(/import[\s\S]{0,500}buildBazaarStatue/.test(МИР), 'buildBazaarStatue не импортирован');
    must(/export function buildBazaarStatue/.test(ТЕРРЕЙН), 'в terrain.ts нет buildBazaarStatue');
  });

  it('коллайдер один и он по плите постамента, а не по фигуре', () => {
    // Ставь коллайдер в placeDecor с нулём, а не здесь второй раз: два
    // коллайдера в одной точке — игрок упирается в невидимую стену.
    const блок = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export function buildBazaarStatue'),
      ТЕРРЕЙН.indexOf('export const REGION_TOWNS'),
    );
    const здесь = (блок.match(/addCollider\(/g) || []).length;
    const вДекоре = (блок.match(/placeDecor\(/g) || []).length;
    must(здесь === 1, `коллайдеров статуи ${здесь}, ждали один`);
    must(вДекоре === 1, `вызовов placeDecor ${вДекоре}, ждали один`);
    const радиус = /addCollider\(BAZAAR_STATUE\.x, BAZAAR_STATUE\.z, ([\d.]+)\)/.exec(блок);
    must(радиус !== null, 'не разобрался радиус коллайдера');
    // Коллайдер меряется по плите постамента (0.94), а не по фигуре (0.36):
    // игрок должен упереться в камень, а не в пустоту над ним. И не шире
    // плиты в полтора раза — иначе он не дотянется до края и статую не обойти.
    const плитаШирина = плита().ширина;
    must(
      Number(радиус![1]) >= плитаШирина / 2,
      `коллайдер ${радиус![1]} м при плите ${плитаШирина.toFixed(2)} м: ` +
        'игрок пройдёт сквозь постамент',
    );
    must(
      Number(радиус![1]) <= плитаШирина / 2 + 0.8,
      `коллайдер ${радиус![1]} м при плите ${плитаШирина.toFixed(2)} м: ` +
        'игрок будет упираться в пустоту',
    );
  });

  it('снаружи базарного квартала, а не посреди торговых рядов', () => {
    // Базарный квартал зарезервирован кругом r = 13 в локальных (84, 0).
    // Статуя внутри него — препятствие торговле.
    const т = место();
    const расстояние = расстояниеДоБазара(т);
    must(
      расстояние >= 13 + 0.3,
      `статуя в ${расстояние.toFixed(1)} м от центра базарного квартала: ` +
        'внутри него торговые ряды, и статуя станет им препятствием',
    );
  });

  it('видна с улицы, а не отодвинута в поле', () => {
    // Отдельная проверка, а не вторая половина предыдущей: ломка «отодвинули
    // в поле» должна падать здесь, а не в проверке про торговые ряды — иначе
    // видно «проверка поймала», а непонятно, какая.
    const т = место();
    const расстояние = расстояниеДоБазара(т);
    must(
      расстояние <= 30,
      `статуя в ${расстояние.toFixed(1)} м от базара: её не видно с улицы, ` +
        'и она перестаёт быть тем, для чего поставлена',
    );
  });

  it('не в резерве из кода столицы', () => {
    // Резервы перечислены в коде столицы: кварталы, NPC, конюшни, сады.
    // Список берётся оттуда же, а не копируется: копия разошлась бы молча.
    const т = место();
    const столица = { x: 34, z: 26 };
    for (const р of резервы()) {
      const d = Math.hypot(т.x - (столица.x + р.x), т.z - (столица.z + р.z));
      must(
        d > р.r + 0.5,
        `статуя в (${т.x}, ${т.z}) стоит в резерве «${р.имя}» в ` +
          `(${р.x}, ${р.z}) r=${р.r}: расстояние ${d.toFixed(1)} м`,
      );
    }
  });

  it('не в центре столицы, где дворец, мечеть и точка возрождения', () => {
    const т = место();
    const доЦентра = Math.hypot(т.x - 34, т.z - 26);
    must(
      доЦентра >= 60,
      `статуя в ${доЦентра.toFixed(0)} м от центра столицы: ` +
        'в центре дворец, мечеть и точка возрождения игрока',
    );
  });

  it('на суше, на ровном месте и повёрнута к проходу', () => {
    const т = место();
    must(!isWater(т.x, т.z), `статуя в (${т.x}, ${т.z}) стоит в воде`);
    for (let dx = -2; dx <= 2; dx++) {
      for (let dz = -2; dz <= 2; dz++) {
        must(!isWater(т.x + dx, т.z + dz), `под статуей вода в (${т.x + dx}, ${т.z + dz})`);
      }
    }
    must(Number.isFinite(т.ry), `поворот статуи ${т.ry} не число: она встанет боком`);
  });
});