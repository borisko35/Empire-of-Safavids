// Сборка образа роняет то, чего не видит локальная проверка.
//
// ЧТО БЫЛО. Три теста на сервере исполняют НАСТОЯЩИЙ код клиента:
// `gameI18n` тянет `client/src/app/i18n.ts`, `autobattle` тянет
// `client/src/app/autobattle.ts`, `fxCursor` тянет `client/src/app/entities.ts`.
// Локально всё зелёное: на машине лежит весь репозиторий.
//
// В образе — нет. `server/Dockerfile` кладёт в сборщик выборочные файлы,
// и каждый новый клиентский импорт в тесте обязан быть там объявлен. Если
// забыть, локальный `npm run typecheck` этого не заметит, `npm test` этого
// не заметит, и падать будет только СБОРКА ОБРАЗА — то есть выкатка.
//
// Это не гипотеза, а два случая подряд, и первый записан прямо в Dockerfile:
//   src/tests/autobattle.test.ts(21,8): error TS2307:
//   Cannot find module '../../../client/src/app/autobattle'
// Второй — мой, `fxCursor.test.ts`, поймала выкатка 08.10.2026:
//   src/tests/fxCursor.test.ts(18,23): error TS2307:
//   Cannot find module '../../../client/src/app/entities'
//
// ЧТО ПРОВЕРЯЕТСЯ. Каждый клиентский модуль, который тянут тесты сервера,
// должен быть скопирован в builder-стадию `server/Dockerfile` — вместе со
// всем, что он тянет сам. Список тестов читается с диска, а не записан
// константой: новый тест с клиентским импортом обязан сломать проверку.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const DOCKERFILE = 'server/Dockerfile';
const ТЕСТЫ = join(корень, 'server', 'src', 'tests');

/** Клиентские модули, которые тянут тесты сервера, извлечённые из текста импортов. */
function клиентскиеИмпорты(): string[] {
  const найдено = new Set<string>();
  for (const файл of readdirSync(ТЕСТЫ).filter((f) => f.endsWith('.test.ts'))) {
    const текст = readFileSync(join(ТЕСТЫ, файл), 'utf-8');
    for (const м of текст.matchAll(/from '((?:\.\.\/)+client\/[^']+)'/g)) {
      найдено.add(м[1].replace(/^(\.\.\/)+client\//, '').replace(/\.ts$/, ''));
    }
  }
  return [...найдено].sort();
}

/** Что Dockerfile кладёт в сборщик: строки вида `COPY client/src/app/X.ts ...`. */
function скопированныеКлиентскиеМодули(): Set<string> {
  const строки = читать(DOCKERFILE)
    .split('\n')
    .filter((с) => /^\s*COPY\s+client\//.test(с));
  const модули = new Set<string>();
  for (const строка of строки) {
    const [, путь] = /^\s*COPY\s+(\S+)/.exec(строка) ?? [];
    if (!путь) continue;
    модули.add(путь.replace(/^client\//, '').replace(/\.ts$/, ''));
  }
  return модули;
}

describe('Образ собирается с тестами, которые тянут клиентский код', () => {
  it('клиентские импорты в тестах вообще есть — иначе проверка пустая', () => {
    // Ломка с откатом: если бы совпадение регулярного выражения перестало
    // работать, проверка ниже стала бы проходить вхолостую, потому что
    // «всё объявлено» при «нечего объявлять».
    const импорты = клиентскиеИмпорты();
    must(
      импорты.length >= 3,
      `найдено клиентских импортов в тестах: ${импорты.length}. Регулярное выражение перестало ловить — проверка ниже проверяет пустоту`,
    );
  });

  it('каждый такой модуль скопирован в сборщик образа', () => {
    const скопировано = скопированныеКлиентскиеМодули();
    const забытые = клиентскиеИмпорты().filter((м) => !скопировано.has(м));
    must(
      забытые.length === 0,
      `${DOCKERFILE} не копирует: ${забытые.join(', ')}. Локально typecheck зелёный, но сборка образа упадёт на выкатке — добавь COPY client/src/app/<файл>.ts`,
    );
  });

  it('entities.ts тянет state.ts, и state тоже в образе', () => {
    // Транзитивная зависимость. entities.ts импортирует Vec3 из './state',
    // и tsc требует файл, даже если это чистый интерфейс. Забыть про
    // второй файл — значит поменять одну ошибку TS2307 на другую.
    const скопировано = скопированныеКлиентскиеМодули();
    must(
      скопировано.has('src/app/entities') && скопировано.has('src/app/state'),
      'entities.ts объявлен, но его зависимость state.ts — нет: ошибка TS2307 переедет на другой файл',
    );
  });

  it('Dockerfile объясняет, зачем в образ тянутся клиентские файлы', () => {
    // Ломка: Dockerfile без пояснения выглядит мусором, и следующий человек
    // удалит «лишние» COPY, не зная, что они держат сборку. Обе прежние
    // правки держали на комментарии — и он же объясняет, почему их было
    // починкой, а не костылём.
    const текст = читать(DOCKERFILE);
    must(
      /COPY client\/src\/app\/entities\.ts[\s\S]{0,900}COPY client\/src\/app\/state\.ts/.test(текст),
      'COPY для entities.ts и state.ts не подряд: между ними должен идти поясняющий комментарий',
    );
    must(
      /Cannot find module '\.\.\/\.\.\/\.\.\/client/.test(текст),
      'в Dockerfile нет записи о самой ошибке TS2307: непонятно, что чинили',
    );
  });
});