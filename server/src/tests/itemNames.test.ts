// Имена предметов приходят на трёх экранах из одного места, и это место
// проверяется здесь. Проверяет не «выглядит ли перевод красиво», а
// согласованность: одна и та же карта переводов против трёх языков и
// против данных предметов.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПУНКТ В gameI18n. gameI18n ловит
// опечатки в ключах по маске «строка с точкой». Значения псевдонимов
// пишутся БЕЗ префикса items., поэтому под маску не попадают и опечатку
// в них не ловят ничем. А опечатка в псевдониме не выглядит поломкой
// при просмотре: предмет просто молча показывается по-русски там, где
// соседние предметы переведены.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const i18n = читать('client/src/app/i18n.ts');
const предметы = читать('server/src/data/items.ts');
const словарь = (код: string): Record<string, Record<string, string>> =>
  JSON.parse(читать(`shared/locales/${код}.json`));

const ru = словарь('ru');
const en = словарь('en');
const az = словарь('az');

/** Значения ПСЕВДОНИМЫ: идентификатор в данных -> ключ в items.* */
function псевдонимы(): Record<string, string> {
  const блок = i18n.slice(i18n.indexOf('ПСЕВДОНИМЫ'), i18n.indexOf('}', i18n.indexOf('ПСЕВДОНИМЫ')));
  const найдено: Record<string, string> = {};
  const образец = /^\s{2}([a-z][a-z0-9_]*):\s*'([a-z][a-z0-9_]*)',/gm;
  let m: RegExpExecArray | null;
  while ((m = образец.exec(блок)) !== null) {
    if (m[1] !== undefined && m[2] !== undefined) найдено[m[1]] = m[2];
  }
  return найдено;
}

/** Идентификаторы предметов из данных. */
function идентификаторыПредметов(): Set<string> {
  const найдено = new Set<string>();
  const образец = /^ {2}'([a-z][a-z0-9_]*)': \{$/gm;
  let m: RegExpExecArray | null;
  while ((m = образец.exec(предметы)) !== null) {
    if (m[1] !== undefined) найдено.add(m[1]);
  }
  return найдено;
}

describe('Имена предметов согласованы', () => {
  it('псевдонимы во всех трёх языках указывают на существующий ключ', () => {
    // Главная проверка файла. Псевдоним, которого нет в словаре, означает
    // молчаливый откат на русский: предмет в сумке называется по-русски,
    // а соседние переведены, и это выглядит как недосмотр переводчика.
    const пары = Object.entries(псевдонимы());
    must(пары.length >= 2, `псевдонимов найдено ${пары.length} — разбор ПСЕВДОНИМЫ сломан`);
    for (const [id, ключ] of пары) {
      for (const [код, словари] of [['ru', ru], ['en', en], ['az', az]] as const) {
        must(
          typeof словари.items[ключ] === 'string' && словари.items[ключ]!.trim() !== '',
          `${код}: псевдоним ${id} -> ${ключ} есть в данных, но не переведён`,
        );
      }
    }
  });

  it('левый ключ псевдонима есть в данных, а не выдуман', () => {
    const идентификаторы = идентификаторыПредметов();
    for (const id of Object.keys(псевдонимы())) {
      must(идентификаторы.has(id), `псевдоним ${id} не соответствует ни одному предмету в данных`);
    }
  });

  it('у каждого предмета одно название во всех трёх языках', () => {
    // Одно и то же имя предмету на трёх языках — это признак, что название
    // скопировали, а не перевели. До правки так было у 21 предмета.
    const ключи = Object.keys(ru.items);
    must(ключи.length >= 21, `в словаре ${ключи.length} предметов — ожидалось не меньше 21`);
    for (const ключ of ключи) {
      const r = ru.items[ключ] ?? '';
      const e = en.items[ключ] ?? '';
      const a = az.items[ключ] ?? '';
      must(e.trim() !== '' && a.trim() !== '', `${ключ} переведён не во все языки`);
      must(e !== r, `${ключ}: английский текст совпадает с русским — перевода нет`);
      must(a !== r, `${ключ}: азербайджанский текст совпадает с русским — перевода нет`);
    }
  });

  it('русское название предмета совпадает с данными', () => {
    // Порядок важен: игрок видит имя из данных в сумке и перевод в словаре.
    // Пока это было не так, один предмет назывался в двух окнах по-разному
    // («Нишапурская Бирюза» и «Тофи»). Сверка идёт по русскому, потому что
    // nameRu в данных — тоже русский.
    const src = предметы;
    const образец = /^ {2}'([a-z][a-z0-9_]*)': \{\r?\n(?:.*\r?\n)*? {4}nameRu: '([^']*)',/gm;
    let m: RegExpExecArray | null;
    let сверено = 0;
    while ((m = образец.exec(src)) !== null) {
      const [, id, nameRu] = m;
      if (id === undefined || nameRu === undefined) continue;
      const вСловаре = ru.items[id];
      if (вСловаре === undefined) continue;
      must(
        вСловаре === nameRu,
        `${id}: в данных «${nameRu}», в словаре «${вСловаре}» — игрок увидит разные имена`,
      );
      сверено++;
    }
    // Якорь на 16, а не на 21. В словаре 21 запись, но пять из них — не
    // предметы из items.ts: три маунта живут в другом файле данных, а
    // acc_boots_silk_road и acc_cloak_monsoon существуют только как правые
    // стороны псевдонимов. Их сверять с nameRu нечего, и якорь на 21 падал
    // бы на верном коде — ровно та ошибка, которую проверка не должна
    // допускать.
    must(сверено >= 16, `сверено только ${сверено} предметов — разбор данных сломан`);
  });

  it('название предмета не содержит идентификатор', () => {
    // Заглушка иконки берёт первую букву названия. Если бы в название
    // просочился идентификатор, плитка показала бы «m» вместо «П».
    for (const ключ of Object.keys(ru.items)) {
      const значение = ru.items[ключ] ?? '';
      must(!значение.includes(ключ), `${ключ}: название содержит сам идентификатор — «${значение}»`);
      must(/[^\x00-\x7F]/.test(значение) || /^[A-Z]/.test(значение), `${ключ}: название не похоже на текст — «${значение}»`);
    }
  });
});
