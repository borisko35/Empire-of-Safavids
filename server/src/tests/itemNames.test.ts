// Имена предметов приходят на трёх экранах из одного места, и это место
// проверяется здесь. Проверяет не «выглядит ли перевод красиво», а
// согласованность: одна и та же карта переводов против трёх языков и
// против данных предметов.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПУНКТ В gameI18n. gameI18n ловит
// опечатки в ключах по маске «строка с точкой». Значения псевдонимов
// пишутся БЕЗ префикса items., поэтому под маску не попадают и опечатку
// в них не ловят ничем. А опечатка в псевдониме не выглядит поломкой
// при просмотре: предмет просто молча показывается по-русски там, где
// соседние предметы переведены.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const i18n = читать('client/src/app/i18n.ts');
const предметы = читать('server/src/data/items.ts');
const словарь = (код: string): Record<string, Record<string, string>> =>
  JSON.parse(читать(`shared/locales/${код}.json`));

const ru = словарь('ru');
const en = словарь('en');
const az = словарь('az');

/** Значения ПСЕВДОНИМЫ: идентификатор в данных -> ключ в items.* */
function псевдонимы(): Record<string, string> {
  const блок = i18n.slice(i18n.indexOf('ПСЕВДОНИМЫ'), i18n.indexOf('}', i18n.indexOf('ПСЕВДОНИМЫ')));
  const найдено: Record<string, string> = {};
  const образец = /^\s{2}([a-z][a-z0-9_]*):\s*'([a-z][a-z0-9_]*)',/gm;
  let m: RegExpExecArray | null;
  while ((m = образец.exec(блок)) !== null) {
    if (m[1] !== undefined && m[2] !== undefined) найдено[m[1]] = m[2];
  }
  return найдено;
}

/** Идентификаторы предметов из данных. */
function идентификаторыПредметов(): Set<string> {
  return new Set(предметыИзДанных().keys());
}

/**
 * Предметы из данных вместе с названиями на двух языках.
 *
 * Название встречается в двух видах: на своей строке (большинство
 * предметов) и на одной строке с id — так записаны рыбы. Разбор берёт
 * начало строки необязательным, иначе одиннадцать рыб выпадают молча:
 * проверка их полноты становится правдивой на неполных данных.
 *
 * Внутри строки допускается экранированный символ: иначе название
 * 'Scholar\'s Scroll' читается как 'Scholar\' и расхождение сначала
 * приписывают данным, а потом правят не тот файл.
 */
function предметыИзДанных(): Map<string, { ru: string; en: string }> {
  const найдено = new Map<string, { ru: string; en: string }>();
  const блок = /^ {2}'([a-z][a-z0-9_]*)': \{([\s\S]*?)^ {2}\},/gm;
  let m: RegExpExecArray | null;
  while ((m = блок.exec(предметы)) !== null) {
    const [, id, тело] = m;
    if (id === undefined || тело === undefined) continue;
    // Имя бывает и в двойных кавычках — так записаны восемь предметов, у
    // которых в английском названии есть апостроф ("Shah Abbas's Blade").
    // Разбор только одинарных кавычек молча терял их, и проверка полноты
    // радовалась неполным данным: восемь предметов выпадали из сверки.
    const en =
      /(?:^|[^\w])name: '((?:[^'\\]|\\.)*)'/.exec(тело) ??
      /(?:^|[^\w])name: "([^"]*)"/.exec(тело);
    const ru = /(?:^|[^\w])nameRu: '((?:[^'\\]|\\.)*)'/.exec(тело);
    if (en === null || ru === null) continue;
    const снять = (s: string): string => s.replace(/\\(.)/g, '$1');
    найдено.set(id, { ru: снять(ru[1] ?? ''), en: снять(en[1] ?? '') });
  }
  return найдено;
}

describe('Имена предметов согласованы', () => {
  it('псевдонимы во всех трёх языках указывают на существующий ключ', () => {
    // Главная проверка файла. Псевдоним, которого нет в словаре, означает
    // молчаливый откат на русский: предмет в сумке называется по-русски,
    // а соседние переведены, и это выглядит как недосмотр переводчика.
    const пары = Object.entries(псевдонимы());
    must(пары.length >= 2, `псевдонимов найдено ${пары.length} — разбор ПСЕВДОНИМЫ сломан`);
    for (const [id, ключ] of пары) {
      for (const [код, словари] of [['ru', ru], ['en', en], ['az', az]] as const) {
        must(
          typeof словари.items[ключ] === 'string' && словари.items[ключ]!.trim() !== '',
          `${код}: псевдоним ${id} -> ${ключ} есть в данных, но не переведён`,
        );
      }
    }
  });

  it('левый ключ псевдонима есть в данных, а не выдуман', () => {
    const идентификаторы = идентификаторыПредметов();
    for (const id of Object.keys(псевдонимы())) {
      must(идентификаторы.has(id), `псевдоним ${id} не соответствует ни одному предмету в данных`);
    }
  });

  it('у каждого предмета одно название во всех трёх языках', () => {
    // Одно и то же имя предмету на трёх языках — это признак, что название
    // скопировали, а не перевели. До правки так было у 21 предмета.
    const ключи = Object.keys(ru.items);
    must(ключи.length >= 79, `в словаре ${ключи.length} предметов — ожидалось не меньше 79`);
    for (const ключ of ключи) {
      const r = ru.items[ключ] ?? '';
      const e = en.items[ключ] ?? '';
      const a = az.items[ключ] ?? '';
      must(e.trim() !== '' && a.trim() !== '', `${ключ} переведён не во все языки`);
      must(e !== r, `${ключ}: английский текст совпадает с русским — перевода нет`);
      must(a !== r, `${ключ}: азербайджанский текст совпадает с русским — перевода нет`);
    }
  });

  it('русское и английское названия совпадают с данными', () => {
    // Порядок важен: игрок видит имя из данных в сумке и перевод в словаре.
    // Пока это было не так, один предмет назывался в двух окнах по-разному
    // («Нишапурская Бирюза» и «Тофи»). Сверяются оба языка: nameRu и name
    // в данных написаны авторами проекта, и словарь берётся из них, а не
    // наоборот. Расхождение означало бы, что название перепечатали вручную
    // и опечатались — предыдущая версия словаря так и расходилась с
    // данными в девяти местах.
    const изДанных = предметыИзДанных();
    must(изДанных.size >= 79, `разобрано ${изДанных.size} предметов, ожидалось не меньше 79`);
    for (const [id, имя] of изДанных) {
      const вRu = ru.items[id];
      const вEn = en.items[id];
      must(вRu !== undefined, `${id}: нет русского перевода в словаре`);
      must(вEn !== undefined, `${id}: нет английского перевода в словаре`);
      must(
        вRu === имя.ru,
        `${id}: в данных «${имя.ru}», в словаре «${вRu}» — игрок увидит разные имена`,
      );
      must(
        вEn === имя.en,
        `${id}: в данных «${имя.en}», в словаре «${вEn}» — игрок увидит разные имена`,
      );
    }
  });

  it('у каждого предмета из данных есть перевод во всех трёх языках', () => {
    // Полнота, а не согласованность. Пока переводили выборочно, 63 предмета
    // из 79 показывались азербайджанскому и английскому игроку по-русски:
    // имяПредмета() откатывается на nameRu, и откат выглядит как перевод,
    // которого просто ещё не сделали, а не как поломка.
    const изДанных = предметыИзДанных();
    for (const id of изДанных.keys()) {
      for (const [код, словари] of [['ru', ru], ['en', en], ['az', az]] as const) {
        const значение = словари.items[id];
        must(
          typeof значение === 'string' && значение.trim() !== '',
          `${id}: в ${код} нет названия — игрок увидит предмет по-русски`,
        );
      }
    }
  });

  it('в словаре нет названий предметов, которых нет в данных', () => {
    // Обратная сторона полноты. Лишний ключ — это опечатка в идентификаторе
    // либо предмет, удалённый из данных, но оставшийся в словаре. Он не
    // виден игроку, но означает, что словарь разошёлся с данными и
    // больше ни о чём не говорит.
    //
    // Пять ключей блока items — не предметы из items.ts: три маунта живут в
    // другом файле данных, а acc_boots_silk_road и acc_cloak_monsoon
    // существуют только как правые стороны псевдонимов в i18n.
    const неПредметы = new Set([
      'mount_arabian_horse',
      'mount_bactrian_camel',
      'mount_qizilbash_warhorse',
      'acc_boots_silk_road',
      'acc_cloak_monsoon',
    ]);
    const идентификаторы = идентификаторыПредметов();
    for (const код of ['ru', 'en', 'az'] as const) {
      for (const ключ of Object.keys(словарь(код).items)) {
        if (неПредметы.has(ключ)) continue;
        must(
          идентификаторы.has(ключ),
          `${код}: в словаре есть «${ключ}», а в данных такого предмета нет`,
        );
      }
    }
  });

  it('название предмета не содержит идентификатор', () => {
    // Заглушка иконки берёт первую букву названия. Если бы в название
    // просочился идентификатор, плитка показала бы «m» вместо «П».
    for (const ключ of Object.keys(ru.items)) {
      const значение = ru.items[ключ] ?? '';
      must(!значение.includes(ключ), `${ключ}: название содержит сам идентификатор — «${значение}»`);
      must(/[^\x00-\x7F]/.test(значение) || /^[A-Z]/.test(значение), `${ключ}: название не похоже на текст — «${значение}»`);
    }
  });
});
