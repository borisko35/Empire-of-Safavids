// Экстерьер горного святилища: пятое из шести зданий без экстерьера.
//
// ЧТО ЗАКРЕПЛЯЕТ. По точке (1200, 1200) не стояло ничего. Комплекс собран
// примитивами, и почти всё в нём выведено замером:
//
//   1. Площадка ровняется ПОСЛЕ ровнялки залива. Ровнялка залива имеет центр
//      (0, -820) и радиус 900, ровная часть её — 495 м, то есть полкарты, и
//      площадка выше неё молча получает чужой уровень.
//   2. Уровень земли 1.1 выбран перебором ВОКРУГ МЕДИАНЫ, а не от нуля. У
//      ткацки перебор от нуля выдал нижнюю границу диапазона вместо ответа.
//   3. Радиуса 48 НЕ хватило: полудиагональ комплекса 27.1 м, а ровная часть
//      при 48 равна 26.4 м, то есть запас МИНУС 0.7 м. При 52 запас 1.5 м —
//      тоже мало, у ткацки запас 1.1 м дал перепад 0.187 м. Взято 56.
//   4. Терраса ПОДНЯТА на 1.2 м и держится подпорной стенкой. Первая сборка
//      строила стенку и ступени прямо на ровной земле: замер показал 1.10 м на
//      всей дистанции до z = 27, то есть ступени спускались в ровную землю, а
//      стенке держать было нечего. Обе конструкции были враньём.
//   5. Число ступеней равно подъёму подиума: 3 по 0.4 = 1.2. Спуск заканчивается
//      на земле, а не висит в воздухе.
//   6. Планировка взята из интерьера, а не придумана: дальняя стена на локальном
//      z = -16 (глубина зала ROOM_D), пролом в ней, а не между дверью и
//      алтарём. Первая сборка поставила стену между дверью и алтарём, и просвет
//      по оси вышел -2.54 м, то есть прохода не было вовсе.
//   7. Панели руинной стены стоят ЦЕЛИКОМ ВНЕ ПРОЁМА. Первая сборка задала
//      панель, пересекавшую ось: стена оказалась сплошной, а щели были 0.2 и
//      0.5 м.
//   8. Пионы пролома стоят чуть внутри проёма, а не в кладке.
//   9. Ширина террасы равна ширине зала: иначе между стеной зала и стенкой
//      террасы остаётся щель, куда игрок заходит сбоку.
//  10. Проём под ступени в цепочке края подиума оставлен, иначе сход перекрыт.
//      Это и случилось: комментарий говорил «по проёму ничего не ставится», а код
//      ставил цепочку без условия.
//  11. Ширина террасы не превышает ширину зала — иначе появляется щель.
//
// ЧЕГО ПРОВЕРКА НЕ ДЕЛАЕТ. Она не строит сцену и не мерит землю: terrain.ts
// требует document и canvas, в Node не импортируется, а копия функции измеряла бы
// саму себя. Ровность измерена инструментом по настоящему коду и записана в
// карте: земля под подиумом 1.100..1.101, перепад 0.001 м; подъём террасы ровно
// 1.2000 м; просвет по оси в проломе 2.20 м; ось от двери наружу чиста на 60 м.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

/** Блок постройки святилища внутри buildSettlements. */
function блокСвятилища(): string {
  const начало = ТЕРРЕЙН.indexOf('  // ── Горное святилище ───');
  must(начало > 0, 'в terrain.ts нет блока постройки святилища');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', начало);
  must(конец > начало, 'блок святилища не найден по границе акведука');
  return ТЕРРЕЙН.slice(начало, конец);
}

/**
 * Панели руинной стены как пары [центр, ширина], прочитанные из кода.
 *
 * Панели заданы выражениями вида -HALL_W / 2 + 2.0, поэтому разбирать приходится
 * вычислением: обычным числом из кода они не являются. Проверка от этого
 * зависит — именно она ловит панель, пересекающую проём.
 */
function панелиРуины(): [number, number][] {
  // Ширина двора нужна вычислению: панели заданы как -HALL_W / 2 + 2.0. Имя
  // подставляется в выражение ТЕКСТОМ, а не объявляется переменной: tsc не видит
  // переменные сквозь eval и ругается на неиспользуемую, а подстановка текстом
  // ещё и снимает зависимость от области видимости.
  const HALL_W = Number(/зал: \{ w: (\d+)/.exec(ТЕРРЕЙН)![1]);
  const панели: [number, number][] = [];
  for (const m of блокСвятилища().matchAll(
    /\[([-\d. +/*A-Z_]+),\s*([\d.]+),\s*[\d.]+\]/g,
  )) {
    панели.push([eval(m[1].replace(/HALL_W/g, String(HALL_W))), Number(m[2])]);
  }
  return панели;
}

describe('Святилище: площадка', () => {
  it('поставлена на месте записи интерьера', () => {
    must(
      /id: 'shrine',[^}]*dx: 1200, dz: 1200/.test(ИНТЕРЬЕРЫ),
      'запись святилища в интерьерах изменилась: площадка без неё окажется не там',
    );
    must(
      /export const SHRINE = \{ x: 1200, z: 1200,/.test(ТЕРРЕЙН),
      'площадка святилища не совпадает с записью интерьера (1200, 1200)',
    );
  });

  it('ровнялка стоит ПОСЛЕ ровнялки залива', () => {
    const код = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export function terrainHeight'),
      ТЕРРЕЙН.indexOf('const TERRAIN_SEG'),
    ).split('\n').filter((s) => !/^\s*(\/\/|\*|\/\*)/.test(s));
    const текст = код.join('\n');
    const залив = текст.indexOf('-820');
    const святилище = текст.indexOf('SHRINE.x');
    must(залив > 0, 'ровнялка залива не найдена в terrainHeight');
    must(святилище > 0, 'ровнялка святилища не найдена в terrainHeight');
    must(
      святилище > залив,
      'площадка святилища поставлена выше ровнялки залива: она молча получит ' +
        'чужой уровень, ровно как дворец получил 2.367 вместо 2.2',
    );
  });

  it('уровень земли близок к измеренной медиане 1.13', () => {
    // ВОКРУГ МЕДИАНЫ, А НЕ ОТ НУЛЯ. Перебор от нуля на ткацке выдал нижнюю
    // границу диапазона вместо ответа: земля там отрицательная, и сумма
    // «срез плюс засыпка» только росла.
    const m = /export const SHRINE = \{ x: 1200, z: 1200, radius: \d+, level: (-?[\d.]+) \}/.exec(
      ТЕРРЕЙН,
    );
    must(m !== null, 'уровень площадки святилища не объявлен');
    const уровень = Number(m![1]);
    must(
      уровень >= 0.8 && уровень <= 1.4,
      `уровень ${уровень} м выходит за измеренную медиану 1.13 по габариту ` +
        'настоящей планировки',
    );
  });

  it('запас ровной части достаточен: 48 и 52 не годились', () => {
    // Полудиагональ комплекса 25.5 м. При радиусе 48 ровная часть 26.4 м, то
    // есть запас 0.9 м: площадка почти вровень с углом комплекса. У ткацки
    // запас 1.1 м дал перепад 0.187 м, то есть и 0.9 не удержат. При 52 запас
    // 3.1 м — достаточно.
    const m = /export const SHRINE = \{ x: 1200, z: 1200, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус площадки святилища не объявлен');
    const радиус = Number(m![1]);
    const ровная = радиус * 0.55;
    // Комплекс уходит и ВПЕРЁД (терраса со ступенями), и НАЗАД (двор на 16 м),
    // и сторона назад длиннее. Раньше задняя не учитывалась вовсе: запас выходил
    // 2.1 м при радиусе 48 вместо настоящих 0.9, и проверка пропускала площадку,
    // меньшую комплекса.
    const полу = Math.hypot(11 + 1.4 + 3, 16 + 1.4 + 3);
    must(
      ровная - полу >= 2,
      `запас в ${(ровная - полу).toFixed(1)} м мал: при радиусе 48 он был ` +
        'минус 0.7 м, и площадка оказывалась меньше комплекса',
    );
  });

  it('круги смешивания не достают до соседей', () => {
    const святилище = /export const SHRINE = \{ x: 1200, z: 1200, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(святилище !== null, 'радиус площадки святилища не объявлен');
    const радиус = Number(святилище![1]);
    // До гробницы (1400, 1400) и до ханзы (1600, 1000).
    for (const [имя, x, z] of [
      ['гробницы', 1400, 1400],
      ['ханзы', 1600, 1000],
    ] as [string, number, number][]) {
      const расстояние = Math.hypot(1200 - x, 1200 - z);
      must(
        расстояние > радиус,
        `до ${имя} ${расстояние.toFixed(0)} м, радиус ${радиус} м: круг ` +
          'смешивания святилища достаёт до него',
      );
    }
  });

  it('под комплексом сухо: вода задана контурами, а не высотой', () => {
    // МОЯ ОШИБКА БЫЛА ЗДЕСЬ. По высоте земля доходила до -4.96 при уровне
    // моря -3.2, то есть ниже моря, и я решил, что площадка в заливе. isWater
    // дала 0 мокрых точек из 1089: вода задана контурами (море, озеро, пруд,
    // реки), а сухая долина ниже уровня моря — это впадина.
    must(!isWater(1200, 1200), 'под святилищем вода: комплекс стоял бы в заливе');
    for (const [x, z] of [[1187, 1210], [1213, 1190], [1200, 1230], [1170, 1200]] as const) {
      must(!isWater(x, z), `вода в пределах комплекса, точка ${x},${z}`);
    }
  });
});

describe('Святилище: терраса на уступе', () => {
  it('терраса ПОДНЯТА над землёй, а не лежит на ней', () => {
    // Первая сборка строила подпорную стенку высотой 2.6 м и четыре ступени прямо
    // на ровной земле. Замер показал 1.10 м на всей дистанции до z = 27: ступени
    // спускались в ровную землю и вели в пустоту, а стенке держать было нечего.
    const m = /export const СВЯТИЛИЩЕ_ПОДЪЁМ = ([\d.]+);/.exec(ТЕРРЕЙН);
    must(m !== null, 'подъём террасы не объявлен');
    const подъём = Number(m![1]);
    must(
      подъём >= 0.8 && подъём <= 1.6,
      `подъём ${подъём} м: ниже метра — цоколь, выше полутора — крепость`,
    );
    must(
      /g\.position\.set\(SHRINE\.x, SHRINE\.level \+ ПОДЪЁМ, SHRINE\.z\)/.test(ТЕРРЕЙН),
      'группа святилища не поднята на подъём: терраса легла бы на землю',
    );
  });

  it('число ступеней равно подъёму подиума', () => {
    // Три ступени по 0.4 м ровно сходят с подъёма 1.2 м на землю. При большем
    // числе терраса читалась бы как амфитеатр, при меньшем спуск был бы крут
    // для шага.
    const подъём = Number(
      /export const СВЯТИЛИЩЕ_ПОДЪЁМ = ([\d.]+);/.exec(ТЕРРЕЙН)![1],
    );
    const m = /ступени: \{ число: (\d+), ширина: ([\d.]+), подъём: ([\d.]+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'ступени не объявлены в габаритах');
    const число = Number(m![1]);
    const ступ = Number(m![3]);
    must(
      Math.abs(число * ступ - подъём) < 0.01,
      `${число} ступеней по ${ступ} м дают ${(число * ступ).toFixed(2)} м, ` +
        `а подъём ${подъём} м: сход либо не доходит до земли, либо уходит под неё`,
    );
  });

  it('подпорная стенка идёт по всему периметру подиума', () => {
    const блок = блокСвятилища();
    must(
      /Подпорная стенка[\s\S]*ПОДЪЁМ \/ 2 - СВЯТИЛИЩЕ_ПЛИТА\.подъём/.test(блок),
      'подпорная стенка не считается от подъёма: она либо в воздухе, либо в земле',
    );
    // Стенка должна быть с четырёх сторон: две боковые, дальняя и передняя.
    const стенок = (блок.match(/sandstoneDark/g) || []).length;
    must(
      стенок >= 4,
      `подпорных полотен ${стенок}, должно быть не меньше четырёх: подиум ` +
        'с одной стороны повиснет',
    );
  });

  it('ширина террасы равна ширине зала, иначе появляется щель', () => {
    // Первая сборка взяла террасу шире зала (26 против 22), и между стеной зала
    // и подпорной стенкой террасы осталась щель в два метра: игрок заходил туда
    // сбоку, и это было мусорное место в руине.
    const m = /terrace: \{ w: (\d+), d: (\d+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'габарит террасы не объявлен');
    const терраса = Number(m![1]);
    // Имя латиницей среди кириллицы: переменная называлась `зал`, а в сообщении
    // я написал `зала` — то есть другое имя. TS2552. В кириллическом окружении
    // латинское ЗАЛ читается надёжнее, и ошибиться в падеже больше негде.
    const ЗАЛ = Number(/зал: \{ w: (\d+)/.exec(ТЕРРЕЙН)![1]);
    must(
      терраса === ЗАЛ,
      `ширина террасы ${терраса} против ширины двора ${ЗАЛ}: между стеной и ` +
        'подпорной стенкой остаётся щель, куда игрок заходит сбоку',
    );
  });
});

describe('Святилище: планировка из интерьера', () => {
  it('дальняя стена на глубине зала ROOM_D', () => {
    // Глубина зала 16 — это ROOM_D в interiors. Первая сборка взяла -14, и это
    // было расхождение с интерьером: снаружи руина была ближе к двери, чем
    // внутри.
    const ROOM_D = Number(/export const ROOM_D = (\d+);/.exec(ИНТЕРЬЕРЫ)![1]);
    const m = /export const СВЯТИЛИЩЕ_ЗАДНЯЯ_Z = (-?\d+);/.exec(ТЕРРЕЙН);
    must(m !== null, 'дальняя стена святилища не объявлена');
    const z = Number(m![1]);
    must(
      z === -ROOM_D,
      `дальняя стена на z = ${z}, а глубина зала в интерьере ROOM_D = ${ROOM_D}: ` +
        'двор снаружи не сойдётся с залом внутри',
    );
  });

  it('пролом в дальней стене, а не между дверью и алтарём', () => {
    // В furnishShrine стена с проломом стоит на cz - 10.2, а алтарь на cz - 7:
    // стена ЗА алтарём. Первая сборка поставила её между дверью и алтарём, и
    // просвет по оси вышел -2.54 м, то есть прохода не было вовсе.
    const блок = блокСвятилища();
    const стенаZ = /const стенаZ = zЗад \+ WALL_T \/ 2;/.test(блок);
    must(стенаZ, 'дальняя стена считается не от линии двора');
    must(
      /w\.position\.set\(rx, rh \/ 2, стенаZ\)/.test(блок),
      'панели руинной стены стоят не на дальней стене',
    );
  });

  it('панели стены стоят ЦЕЛИКОМ ВНЕ проёма', () => {
    // Первая сборка задала панель, ПЕРЕСЕКАВШУЮ ОСЬ: стена оказалась сплошной,
    // а щели были шириной 0.2 и 0.5 м вместо пролома в 9 м.
    const GAP = Number(/gap: \{ w: ([\d.]+) \}/.exec(ТЕРРЕЙН)![1]);
    const панели = панелиРуины();
    must(панели.length >= 2, 'панели руинной стены не найдены');
    for (const [центр, ширина] of панели) {
      const от = центр - ширина / 2;
      const до = центр + ширина / 2;
      must(
        !(от < GAP / 2 && до > -GAP / 2),
        `панель от ${от.toFixed(2)} до ${до.toFixed(2)} пересекает проём ` +
          `[${-GAP / 2}, ${GAP / 2}]: стена перекрывает проход`,
      );
    }
  });

  it('обе стороны пролома закрыты панелями', () => {
    const GAP = Number(/gap: \{ w: ([\d.]+) \}/.exec(ТЕРРЕЙН)![1]);
    const панели = панелиРуины();
    const слева = панели.filter(([c, w]) => c - w / 2 < -GAP / 2).length;
    const справа = панели.filter(([c, w]) => c + w / 2 > GAP / 2).length;
    must(слева > 0, 'слева от пролома панелей нет: стена с одной стороны дыра');
    must(справа > 0, 'справа от пролома панелей нет: стена с одной стороны дыра');
  });

  it('пионы пролома стоят по краю обвала, а не в кладке', () => {
    // Столб на +0.4 от границы проёма целиком уходил в панель стены, которая
    // начинается ровно с этой границы, и торчал из кладки без смысла.
    const блок = блокСвятилища();
    must(
      /столб\.position\.set\(s \* \(GAP_W \/ 2 - 0\.4\), 2\.1, стенаZ\)/.test(блок),
      'пион пролома смещён наружу от края обвала: он уходит в кладку стены',
    );
  });
});

