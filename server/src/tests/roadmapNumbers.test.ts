// Цифры в ROADMAP.md не должны разъезжаться.
//
// ЧТО БЫЛО. Карта объявлена источником истины, а в ней стояло «42 миграции»,
// «1190 тестов в 73 файлах», «1329 ключей». На деле было 59, 1782 в 111 и
// 1340. Никто этого не заметил: числа в карте никто не сверял, потому что
// сверять нечем было - считать надо, а считать некому.
//
// ПОЧЕМУ ИМЕННО ЭТО ОПАСНО. Решения принимаются по карте. Если она говорит
// «42 миграции», а их 60, то оценка остатка работ неверна - и это молча.
//
// ЧТО ПРОВЕРЯЕТСЯ. Три числа, которые карта называет прямо и которые
// меняются с каждой итерацией. Числа содержимого (предметы, монстры,
// квесты) не проверяются: они не трогались месяцами и требуют другого
// счёта - по данным, а не по файлам.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const карта = читать('ROADMAP.md');

/** Листовая функция подсчёта ключей: строка - это один ключ. */
function счётКлючей(node: unknown): number {
  if (node === null || node === undefined) return 0;
  if (typeof node === 'string') return 1;
  if (typeof node !== 'object') return 0;
  return Object.values(node as Record<string, unknown>)
    .reduce((n: number, v) => n + счётКлючей(v), 0);
}

describe('Цифры в карте соответствуют репозиторию', () => {
  it('число миграций', () => {
    const файлы = readdirSync(join(корень, 'database', 'migrations'))
      .filter(f => f.endsWith('.sql'));
    // Число зафиксировано руками: новая миграция обязана сломать проверку.
    // Без этого карта разъехалась бы снова - молча, как уже разъехалась.
    expect({ миграций: файлы.length, в_карте: /\*\*63 миграции\*\*/.test(карта) })
      .toEqual({ миграций: 63, в_карте: true });
  });

  it('последняя миграция указана в карте', () => {
    const файлы = readdirSync(join(корень, 'database', 'migrations'))
      .filter(f => f.endsWith('.sql')).sort();
    const последняя = файлы[файлы.length - 1];
    expect({
      // Карта называет не имя, а диапазон 001…062. Требовать от неё имени
      // означало бы заставить карту дублировать то, что и так считается.
      имя_настоящее: последняя,
      // И «…», и «...»: разделитель диапазона в карте типографский, и смена
      // оформления не должна выглядеть как дыра в проверке.
      диапазон_в_карте: /(?:\.\.\.|…)063/.test(карта),
    }).toEqual({ имя_настоящее: '063_two_factor.sql', диапазон_в_карте: true });
  });

  it('число файлов тестов', () => {
    const файлы = readdirSync(join(корень, 'server', 'src', 'tests'))
      .filter(f => f.endsWith('.test.ts'));
    expect({ файлов: файлы.length, в_карте: /\*\*127 теста в 130 файлах\*\*/.test(карта) })
      .toEqual({ файлов: 130, в_карте: true });
  });

  it('ключи переводов совпадают во всех трёх языках', () => {
    const счётчики = (['ru', 'en', 'az'] as const).map(l =>
      счётКлючей(JSON.parse(читать(`shared/locales/${l}.json`))));
    // Расхождение между языками - это ключ, который забыли перевести.
    // Оно ловится тут, а не на странице у игрока.
    expect({ ru: счётчики[0], en: счётчики[1], az: счётчики[2] })
      .toEqual({ ru: 1387, en: 1387, az: 1387 });
  });

  it('в карте сказано, что цифры проверяемы', () => {
    // Пометка нужна, чтобы следующий человек знал: цифры нельзя править
    // на глаз, их пересчитывает тест.
    expect({ помета: /Цифры в этой карте проверяемы/.test(карта) })
      .toEqual({ помета: true });
  });
});

describe('Числа содержимого НЕ проверяются этим тестом', () => {
  it('предметы, монстры, квесты остались непроверенными', () => {
    // Честная фиксация границы. Карта пишет «74 предмета, 24 монстра,
    // 48 квестов» - это правда на момент её написания, но никто их не
    // пересчитывал. Тест молча прикрывает это, поэтому объявляет вслух.
    const есть = /74 предмета/.test(карта);
    expect({
      в_карте_есть: есть,
      проверяется_здесь: false,
      причина: 'требует подсчёта по данным, а не по файлам',
    }).toEqual({ в_карте_есть: есть, проверяется_здесь: false,
      причина: 'требует подсчёта по данным, а не по файлам' });
  });
});
