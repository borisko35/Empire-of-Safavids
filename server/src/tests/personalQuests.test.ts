// Личные квесты по тёмной карме.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ.
//   1. Граница кармы задана данными и совпадает с таблицей статусов. Число в
//      данных намерино: хаотичным считается карма от −2000, значит красный — с
//      −2001. Первая версия проверки считала границу иначе и была неправа;
//      теперь расхождение ловится на всём диапазоне, а не на память.
//   2. Фильтр списка: святому личный квест не показывается ВООБЩЕ, а не просто
//      отклоняется при нажатии. Тёмный квест не должен висеть перед тем, кому он
//      не адресован.
//   3. Граница ровная: добрый не видит, изгой видит, и на самой границе тоже.
//   4. Данные квестов не выдуманы: NPC существует, монстры существуют, у второго
//      квеста есть предшественник.
//   5. Отказ при попытке взять имеет перевод во всех трёх языках.
//   6. Карма читается в одном месте: если формулировка запроса разъедется по
//      маршруту и сервису, одна из сторон молча начнёт считать ноль.
import { getAvailableQuests, QUESTS_DATABASE, PERSONAL_KARMA_MAX, PERSONAL_KARMA_GOOD_MIN } from '../data/quests';
import { CharacterClass } from '../types/game.types';
import { getKarmaStatus, isNpcHostile } from '../systems/KarmaSystem';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ЛИЧНЫЕ = Object.values(QUESTS_DATABASE).filter(q => q.type === 'personal');

/**
 * Ветки различаются по условию, а не по имени квеста: префикс — это деталь,
 * условие по карме — смысл.
 */
const ТЁМНЫЕ = ЛИЧНЫЕ.filter(q => q.requiresKarmaAtMost !== undefined);
const СВЕТЛЫЕ = ЛИЧНЫЕ.filter(q => q.requiresKarmaAtLeast !== undefined);

describe('Личные квесты: граница по карме', () => {
  it('личные квесты вообще есть, и у каждого есть условие по карме', () => {
    must(ЛИЧНЫЕ.length >= 4, `личных квестов ${ЛИЧНЫЕ.length}: ветки пустые`);
    for (const квест of ЛИЧНЫЕ) {
      must(
        квест.requiresKarmaAtMost !== undefined || квест.requiresKarmaAtLeast !== undefined,
        `${квест.id} помечен личным, но условия по карме у него нет: он достанется кому угодно`
      );
    }
    // Ветки должны быть зеркалом друг друга: одна тёмная без светлой читалась бы
    // как «поблажка только для плохих», а это ровно то, чего мы не хотели.
    must(
      ТЁМНЫЕ.length === СВЕТЛЫЕ.length,
      `тёмных ${ТЁМНЫЕ.length}, светлых ${СВЕТЛЫЕ.length}: одна из веток без пары`
    );
  });

  it('граница в данных совпадает с таблицей статусов', () => {
    // Смысл числа: всё, что не выше его, — красный или изгой. Проверяем на всём
    // диапазоне, чтобы пересчёт порогов в карме сразу указал на расхождение.
    let проверили = 0;
    for (let карма = -12000; карма <= 12000; карма += 13) {
      const враждебен = isNpcHostile(карма);
      const подходитПоГранице = карма <= PERSONAL_KARMA_MAX;
      if (враждебен !== подходитПоГранице) {
        throw new Error(
          `карма ${карма} (${getKarmaStatus(карма)}): по таблице враждебность ` +
            `${враждебен}, а PERSONAL_KARMA_MAX=${PERSONAL_KARMA_MAX} даёт ` +
            `${подходитПоГранице}. Граница в данных разошлась с кармой.`
        );
      }
      проверили++;
    }
    must(проверили > 900, `проверено ${проверили} значений: диапазон сузился`);
  });

  it('на самой границе изгой подходит, а добрый нет', () => {
    must(
      getKarmaStatus(PERSONAL_KARMA_MAX) === 'red',
      `на границе ${PERSONAL_KARMA_MAX} статус ${getKarmaStatus(PERSONAL_KARMA_MAX)}, а не красный`
    );
    must(
      !isNpcHostile(PERSONAL_KARMA_MAX + 1),
      `на границе +1 статус ${getKarmaStatus(PERSONAL_KARMA_MAX + 1)} уже враждебен`
    );
  });
});

describe('Личные квесты: список доступных', () => {
  const тёмныеАйди = ТЁМНЫЕ.map(q => q.id);
  const естьТёмный = (список: string[]): boolean => список.some(id => тёмныеАйди.includes(id));

  it('святому тёмные квесты не показываются', () => {
    for (const карма of [1000, 5000, 20000]) {
      const список = getAvailableQuests(50, [], CharacterClass.QIZILBASH, карма).map(q => q.id);
      must(
        !естьТёмный(список),
        `при карме ${карма} (${getKarmaStatus(карма)}) тёмный квест попал в список: ` +
          'тёмный заказ висит перед тем, кому он не адресован'
      );
    }
  });

  it('хаотичному тёмные квесты тоже не показываются', () => {
    // Хаотичный ещё не враждебен: граница проходит по красному, а не по нижней
    // границе «отрицательной» кармы.
    must(!isNpcHostile(-2000), 'хаотичный враждебен: граница тогда была бы выше');
    const список = getAvailableQuests(50, [], CharacterClass.QIZILBASH, -2000).map(q => q.id);
    must(!естьТёмный(список), `хаотичному показали тёмный квест: ${список.join(', ')}`);
  });

  it('красному и изгою тёмные квесты показываются', () => {
    for (const карма of [PERSONAL_KARMA_MAX, -4000, -5001, -12000]) {
      const список = getAvailableQuests(50, [], CharacterClass.QIZILBASH, карма).map(q => q.id);
      must(
        естьТёмный(список),
        `при карме ${карма} (${getKarmaStatus(карма)}) тёмный квест не показан: ` +
          'тёмная ветка недостижима, вход в неё закрыт навсегда'
      );
    }
  });

  it('без переданной кармы личные квесты не показываются', () => {
    // Вызывающий код может не знать карму (например, старый маршрут). Показывать
    // личные квесты тому, чью карму не проверили, — хуже, чем не показать.
    const список = getAvailableQuests(50, [], CharacterClass.QIZILBASH).map(q => q.id);
    const личныеАйди = ЛИЧНЫЕ.map(q => q.id);
    must(
      !список.some(id => личныеАйди.includes(id)),
      `без кармы показаны личные квесты: ${список.filter(id => личныеАйди.includes(id)).join(', ')}`
    );
  });

  it('уровень и класс по-прежнему учитываются: фильтр не сломан', () => {
    const всехУровней = getAvailableQuests(50, [], CharacterClass.QIZILBASH, -5001).map(q => q.id);
    const всехУровней5 = getAvailableQuests(5, [], CharacterClass.QIZILBASH, -5001).map(q => q.id);
    must(
      всехУровней.length > всехУровней5.length,
      'фильтр по уровню перестал работать: добавление кармы shouldn’t было его трогать'
    );
    must(
      !getAvailableQuests(50, [], CharacterClass.SUFI_MYSTIC, -5001).some(q => q.requiredClass === CharacterClass.QIZILBASH),
      'фильтр по классу перестал работать: проверяли на несуществующем классе, поэтому проходили бы всегда'
    );
  });
});

describe('Личные квесты: светлая ветка', () => {
  it('граница 1000 совпадает с таблицей статусов', () => {
    // В карме `>= 1000` — это уже «добрый». Значит добрыми считаются от 1000.
    let проверили = 0;
    for (let карма = -12000; карма <= 12000; карма += 17) {
      const статус = getKarmaStatus(карма);
      const добрый = статус === 'good' || статус === 'saint';
      const подходитПоГранице = карма >= PERSONAL_KARMA_GOOD_MIN;
      if (добрый !== подходитПоГранице) {
        throw new Error(
          `карма ${карма} (${статус}): по таблице это ${добрый ? 'добрый' : 'не добрый'}, ` +
            `а PERSONAL_KARMA_GOOD_MIN=${PERSONAL_KARMA_GOOD_MIN} даёт ${подходитПоГранице}`
        );
      }
      проверили++;
    }
    must(проверили > 700, `проверено ${проверили} значений: диапазон сузился`);
  });

  it('на границе светлая ветка начинается, и ветки не переплелись', () => {
    must(
      getKarmaStatus(PERSONAL_KARMA_GOOD_MIN) === 'good',
      `на границе ${PERSONAL_KARMA_GOOD_MIN} статус ${getKarmaStatus(PERSONAL_KARMA_GOOD_MIN)}`
    );
    must(
      PERSONAL_KARMA_MAX < PERSONAL_KARMA_GOOD_MIN,
      `тёмная граница ${PERSONAL_KARMA_MAX} не ниже светлой ${PERSONAL_KARMA_GOOD_MIN}: ветки переплелись`
    );
  });

  const светлыеАйди = СВЕТЛЫЕ.map(q => q.id);
  const тёмныеАйди = ТЁМНЫЕ.map(q => q.id);
  const естьСветлый = (список: string[]): boolean => список.some(id => светлыеАйди.includes(id));
  const естьТёмный = (список: string[]): boolean => список.some(id => тёмныеАйди.includes(id));
  const списокПри = (карма: number): string[] =>
    getAvailableQuests(50, [], CharacterClass.QIZILBASH, карма).map(q => q.id);

  it('святому видна светлая ветка и не видна тёмная', () => {
    const список = списокПри(6000);
    must(естьСветлый(список), `святому не показали светлые квесты: ${список.join(', ')}`);
    must(!естьТёмный(список), 'святому показали тёмный квест: светлое адресовано не ему');
  });

  it('изгою видна тёмная ветка и не видна светлая', () => {
    const список = списокПри(-7000);
    must(естьТёмный(список), 'изгою не показали тёмные квесты');
    must(!естьСветлый(список), 'изгою показали светлые квесты: доверия ему не от кого');
  });

  it('между ветками заказов нет, и они не налезают друг на друга', () => {
    for (const карма of [PERSONAL_KARMA_GOOD_MIN, 2500, PERSONAL_KARMA_MAX, -4000]) {
      const список = списокПри(карма);
      must(
        естьСветлый(список) !== естьТёмный(список),
        `карма ${карма} (${getKarmaStatus(карма)}): видны обе ветки или ни одной — ` +
          'зазор без заказов либо заказ не для того'
      );
    }
  });

  it('нейтральному не достаётся ни одной ветки — и это правильно', () => {
    // Пока веток две, между ними остаётся зазор. Это осознанно: заказ, который
    // берёт любой, был бы просто ещё одним побочным квестом.
    const список = списокПри(0);
    must(!естьСветлый(список), 'нейтральному показали светлый квест');
    must(!естьТёмный(список), 'нейтральному показали тёмный квест');
  });
});

describe('Личные квесты: данные не выдуманы', () => {
  const npкДанные = читать('server/src/data/quests.ts');
  const монстры = читать('server/src/data/monsters.ts');

  // Квест выдаёт охотник (тёмная ветка) или старец (светлая). Список не из
// памяти проверки: он вырос бы вместе с контентом и молчал бы о новом NPC.
const ИЗВЕСТНЫЕ_NPC = ['npc_tabriz_hunter', 'npc_village_elder'];

  it('NPC, который даёт личные квесты, существует в игре', () => {
    // Иначе квест недостижим: игрок придёт к пустому месту.
    for (const квест of ЛИЧНЫЕ) {
      const упоминание = new RegExp(`'${квест.npcGiver}'`).test(читать('client/src/app/game3d/npc.ts'))
        || new RegExp(`npc_${квест.npcGiver}`).test(читать('client/src/app/game3d/npc.ts'))
        || npкДанные.includes(`npcGiver: '${квест.npcGiver}'`);
      must(
        упоминание,
        `${квест.id}: NPC ${квест.npcGiver} не встречается в игре — квест невозможно взять`
      );
      must(
        ИЗВЕСТНЫЕ_NPC.includes(квест.npcGiver),
        `${квест.id} выдаёт неизвестный NPC ${квест.npcGiver}: проверка знает ` +
          `${ИЗВЕСТНЫЕ_NPC.join(' и ')} — нового NPC надо сюда внести`
      );
    }
  });

  it('у каждой ветки свой NPC: в одном городе две работы от разных людей', () => {
    const тёмныеNpc = new Set(ТЁМНЫЕ.map(q => q.npcGiver));
    const светлыеNpc = new Set(СВЕТЛЫЕ.map(q => q.npcGiver));
    for (const npк of светлыеNpc) {
      must(
        !тёмныеNpc.has(npк),
        `светлые и тёмные квесты выдаёт один NPC ${npк}: это одна ветка с двумя названиями`
      );
    }
  });

  it('цели убийства существуют в данных монстров', () => {
    for (const квест of ЛИЧНЫЕ) {
      for (const цель of квест.objectives) {
        if (цель.type !== 'kill') continue;
        must(
          монстры.includes(`'${цель.target}'`),
          `${квест.id}: монстра ${цель.target} нет в данных — цель недостижима`
        );
      }
    }
  });

  it('второй квест выводится из первого, а не висит рядом', () => {
    const первый = ЛИЧНЫЕ.find(q => q.id === 'personal_001_dirty_work');
    const второй = ЛИЧНЫЕ.find(q => q.id === 'personal_002_ledger');
    must(первый, 'нет первого личного квеста');
    must(второй, 'нет второго личного квеста');
    must(
      второй.prerequisites.includes(первый.id),
      `${второй.id} не требует ${первый.id}: ветка из одного квеста, а обещали дорогу`
    );
    must(
      второй.minLevel > первый.minLevel,
      `второй квест не сложнее первого по уровню (${второй.minLevel} против ${первый.minLevel})`
    );
  });

  it('у личных квестов есть награда', () => {
    for (const квест of ЛИЧНЫЕ) {
      must(
        квест.rewards.experience > 0 || квест.rewards.gold > 0,
        `${квест.id} без награды: работать не ради чего`
      );
    }
  });

  it('в данных и переводах нет символа замены', () => {
    // U+FFFD — обычный символ, а не ошибка синтаксиса: компилятор молчит,
    // тесты молчат, а игрок читает в журнале «Волки у заг??на». Так и случилось,
    // пока не поставили эту проверку.
    const испорчено = (текст: string, где: string): void => {
      const сколько = текст.split('\uFFFD').length - 1;
      if (сколько > 0) throw new Error(`${где}: символов замены ${сколько}`);
    };
    испорчено(npкДанные, 'quests.ts');
    for (const код of ['ru', 'en', 'az']) испорчено(читать(`shared/locales/${код}.json`), `${код}.json`);
  });

  it('квесты лежат внутри базы, а не рядом с ней', () => {
    // Ошибка уже была: квесты вставились перед объявлением и висели на верхнем
    // уровне модуля — файл не собирался. Проверка ловит это по объявлению.
    const объявлений = npкДанные.split('export const QUESTS_DATABASE').length - 1;
    must(объявлений === 1, `объявлений базы ${объявлений}: квесты снова снаружи`);
  });
});

describe('Личные квесты: отказ и переводы', () => {
  const сервис = читать('server/src/services/QuestService.ts');
  const маршрут = читать('server/src/routes/game.ts');
  const персонажи = читать('server/src/services/CharacterService.ts');
  const hud = читать('client/src/app/hud.ts');

  it('отказ при попытке взять есть с обеих сторон и причина у каждого своя', () => {
    // Два кода, а не один: «заказ слишком чистый для тебя» и «тебе не доверяют» —
    // противоположные вещи. Один код с формулировкой «не та карма» игроку ничего
    // не объяснял бы.
    must(
      сервис.includes("'quest_karma_too_high'") && сервис.includes("'quest_karma_too_low'"),
      'коды отказов по карме не добавлены в список кодов сервиса'
    );
    must(
      /requiresKarmaAtMost !== undefined \|\| def\.requiresKarmaAtLeast !== undefined/.test(сервис),
      'карма читается только для тёмной ветки: светлый квест можно взять мимо проверки'
    );
    must(
      /карма > def\.requiresKarmaAtMost[\s\S]{0,200}карма < def\.requiresKarmaAtLeast/.test(сервис),
      'одна из сторон не проверяется: отказ есть только с одного края'
    );
    must(
      !сервис.includes('quest_karma_mismatch'),
      'старый код отказа жив: на проде он значил бы «не та карма» вместо двух причин'
    );
  });

  it('причины отказа переведены во всех трёх языках — обе', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      for (const ключ of ['quest_karma_too_high', 'quest_karma_too_low']) {
        must(
          словарь.errors?.[ключ],
          `${код}.json: нет errors.${ключ} — игрок увидит код вместо причины`
        );
      }
      must(
        словарь.errors.quest_karma_mismatch === undefined,
        `${код}.json: старый ключ отказа ещё жив`
      );
      must(словарь.quest_type?.personal, `${код}.json: нет quest_type.personal`);
    }
  });

  it('клиент знает подпись типа квеста', () => {
    must(
      hud.includes("personal: 'quest_type.personal'"),
      'в карте типов квестов нет personal: в журнале личный квест без подписи'
    );
  });

  it('маршрут отдаёт фильтру карму', () => {
    // Второй аргумент - выполненные квесты. Раньше там стоял пустой массив, и
    // маршрут передавал карму в фильтр, не сказав ему ничего о выполненном:
    // личные квесты по карме фильтровались правильно, а цепочки и выполненные
    // квесты - нет. Проверка смотрит форму вызова целиком.
    must(
      /getAvailableQuests\(char\.level, выполненные, char\.class, карма\)/.test(маршрут),
      'маршрут не передаёт карму и выполненные квесты в фильтр: личные квесты либо у всех, либо ни у кого'
    );
  });

  it('карма читается в одном месте', () => {
    must(
      /async getKarma\(characterId: string\): Promise<number>/.test(персонажи),
      'в CharacterService нет чтения кармы'
    );
    must(
      !/private async getKarma\(/.test(сервис),
      'в QuestService остался свой запрос кармы: формулировки разъедутся'
    );
    // Запрос кармы по персонажу должен встречаться в CharacterService ровно один.
    const запросов = (персонажи.match(/SELECT karma FROM characters WHERE id = \$1/g) || []).length;
    must(запросов === 1, `запросов кармы в CharacterService ${запросов}`);
  });
});