// Снятая страница объявления обязана отдавать 404, а не лендинг.
//
// ПОЧЕМУ ЭТА ПРОВЕРКА НУЖНА. Общее правило `location /` заканчивается на
// `try_files $uri $uri/ /index.html`: так /forum и прочие пути без
// расширения отдают страницу. Но для снятой страницы с расширением та же
// подстановка означала, что /update.html отвечал кодом 200 и отдавал
// 24462 байта лендинга. Объявления в коде не было - и при этом адрес
// продолжал работать. То же уже чинили для картинок, где пустое место на
// лендинге выглядело как битая картинка.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const nginx = читать('client/nginx.conf');

describe('Снятая страница объявления отдаёт честный 404', () => {
  it('правило для /update.html есть и возвращает 404', () => {
    // Ищем блок location = /update.html и берём ЕГО тело, а не что попало
    // дальше по файлу. Проверка по позициям вместо поиска блока находила
    // соседний location и радовалась, не глядя, что это другой адрес.
    const блок = /(?:^|\n)[^\S\n]*location\s*=\s*\/update\.html\s*\{([^}]*)\}/.exec(nginx);
    must(блок !== null, 'в nginx.conf нет блока location = /update.html');
    must(/\breturn\s+404\b/.test(блок![1]), 'блок /update.html есть, но 404 в нём нет');

    // Подставку лендинга внутри блока быть не должно: она отменила бы 404
    // позже по тексту блока и правило перестало бы означать то, что написано.
    must(!/try_files/.test(блок![1]), 'в блоке /update.html есть try_files, он перебьёт 404');
  });

  it('файл страницы действительно убран из раздачи', () => {
    const раздаётся = ['client/web/update.html'].filter(p => {
      try {
        readFileSync(join(корень, p));
        return true;
      } catch {
        return false;
      }
    });
    must(
      раздаётся.length === 0,
      'страница всё ещё раздаётся из client/web: ' + раздаётся.join(', '),
    );
  });

  it('архив страницы остался в репозитории', () => {
    // Убрать совсем - стереть историю. Проверяем, что копия есть.
    let есть = false;
    try {
      есть = readFileSync(join(корень, 'docs/archive/update-2026-10-01.html')).length > 1000;
    } catch {
      есть = false;
    }
    must(есть, 'в docs/archive нет страницы объявления - сняли и стёрли, а это разные вещи');
  });

  it('объявления нет ни в меню, ни в ленте новостей на лендинге', () => {
    const лендинг = читать('client/web/index.html');
    must(!/href=["']\/update\.html/.test(лендинг), 'в лендинге осталась ссылка на /update.html');
    must(!/site\.update_title/.test(лендинг), 'в лендинге остался ключ site.update_title');
    must(!/site\.news_update_/.test(лендинг), 'в лендинге осталась карточка site.news_update_*');
  });

  it('миграция убирает пункт ленты, а не удаляет её целиком', () => {
    const миграция = читать('database/migrations/064_remove_update_announcement.sql');
    must(миграция.includes('/update.html'), 'миграция не упоминает адрес объявления');
    // Удаление пункта, а не всей ленты: в jsonb_set заменяется ключ items,
    // а не value. Если бы заменили value, лента бы пропала.
    must(/\{items\}/.test(миграция), 'миграция меняет не ключ items - лента была бы снесена');

    // Второй по важности момент: миграция обязана быть повторно применима.
    // На проде применённые миграции не откатываются, и проверка при откате
    // была бы «nothing to delete» - то есть падение на пустом месте.
    const гдеУдаляет = /jsonb_array_elements\(value->'items'\)[\s\S]*?WHERE[\s\S]*?<>/.test(миграция);
    must(гдеУдаляет, 'в миграции нет фильтра, который отбирает только нужный пункт');
  });
});
