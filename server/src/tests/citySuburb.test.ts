// Пригород за городской стеной.
//
// ЧТО БЫЛО (21 октября 2026, §241). За стеной (радиус 116) было пусто:
// город кончался обрывом кладки, а ближайший караван-сарай — за полкилометра.
// С городской стены было видно, что за ней ничего нет.
//
// ЧТО ТЕПЕРЬ. За воротами видно, что город чем-то живёт: два склада,
// мастерская с трубой и мельница (та же модель, что у караван-сарая).
//
// ЧТО ПРОВЕРЯЕТСЯ. Постройки стоят ЗА стеной (не внутри города) и по
// настоящей земле: за стеной рельеф идёт вниз, и зашитая высота оставила бы
// их висящими в воздухе.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Пригород за городской стеной', () => {
  it('постройки стоят за стеной и по настоящей земле', () => {
    // Радиус города — 116. Пригород должен быть дальше, иначе он окажется
    // внутри стен.
    должен(
      /\{ x: 106, z: 98, w: 11, d: 7, h: 4\.4, труба: false \}/.test(код),
      'склада пригорода нет',
    );
    должен(
      /\{ x: 120, z: 111, w: 7\.5, d: 6, h: 3\.6, труба: true \}/.test(код),
      'мастерской пригорода нет',
    );
    // Высота — от земли, а не зашитая: за стеной склон.
    должен(
      /const земля = groundHeight\(CITY\.x \+ п\.x, CITY\.z \+ п\.z\) - city\.position\.y;/.test(
        код,
      ),
      'постройки пригорода ставятся на зашитой высоте: за стеной они висят',
    );
  });

  it('у пригорода есть мельница', () => {
    должен(
      /loadDecorModel\('decor\/windmill\.glb'\)/.test(код),
      'мельницы за городом нет: за стеной пусто',
    );
    // И она тоже по земле.
    должен(
      /const земля = groundHeight\(CITY\.x \+ мx, CITY\.z \+ мз\) - city\.position\.y;/.test(код),
      'мельница стоит на зашитой высоте',
    );
  });
});
