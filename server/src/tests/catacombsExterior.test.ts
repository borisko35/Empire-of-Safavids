// Экстерьер катакомб: подземный данж 32x32, входная арка с лестницей вниз.
//
// ЗАМЕР: дверь и выход ровно 1.2000, отклонение 0.0000; перепад голого
// комплекса 0.002 м; ось чиста на 60 м; просвет при въезде 8.25 м; подход к
// двери свободен. Центр сухой, но 316 из 1089 точек мокрые: катакомбы у воды,
// уровень 1.2 выше воды -2.0.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

function блокКатакомб(): string {
  const начало = ТЕРРЕЙН.indexOf('  // ── Катакомбы');
  must(начало > 0, 'нет блока катакомб');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', начало);
  must(конец > начало, 'конец блока не найден');
  return ТЕРРЕЙН.slice(начало, конец);
}

describe('Катакомбы: площадка', () => {
  it('стоит на месте записи интерьера', () => {
    must(/id: 'catacombs',[^}]*dx: -520, dz: -340/.test(ИНТЕРЬЕРЫ), 'запись изменилась');
    must(/export const CATACOMBS = \{ x: -520, z: -340,/.test(ТЕРРЕЙН), 'константа не там');
  });

  it('ровнялка стоит ПОСЛЕ ровнялки залива', () => {
    const код = ТЕРРЕЙН.slice(ТЕРРЕЙН.indexOf('export function terrainHeight'), ТЕРРЕЙН.indexOf('const TERRAIN_SEG'))
      .split('\n').filter((s) => !/^\s*(\/\/|\*|\/\*)/.test(s)).join('\n');
    must(код.indexOf('CATACOMBS.x') > код.indexOf('-820'), 'ровнялка не после залива');
  });

  it('уровень близок к медиане 1.23', () => {
    const m = /export const CATACOMBS = \{ x: -520, z: -340, radius: \d+, level: (-?[\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'уровень не объявлен');
    const уровень = Number(m![1]);
    must(уровень >= 0.8 && уровень <= 1.6, `уровень ${уровень} далёк от медианы`);
  });

  it('запас ровной части достаточен', () => {
    const m = /export const CATACOMBS = \{ x: -520, z: -340, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус не объявлен');
    const ровная = Number(m![1]) * 0.55;
    // Полудиагональ считается по ВСЕМУ комплексу: двор 10 м плюс лестница
    // 6 м вперёд, ширина двора 20 м. Раньше считалась только двор, и ломка
    // «радиус 48» проходила насквозь.
    must(ровная - Math.hypot(20 / 2 + 3, 10 + 6 + 3) >= 2, 'запас мал');
  });

  it('центр сухой', () => {
    must(!isWater(-520, -340), 'под катакомбами вода');
  });
});

describe('Катакомбы: дверь и подход', () => {
  it('дверь кликабельная и ведёт в интерьер катакомб', () => {
    const блок = блокКатакомб();
    must(/doorBuilding: 'catacombs'/.test(блок), 'нет doorBuilding');
    must(/doorAction: 'enter'/.test(блок), 'дверь не ведёт внутрь');
    must(/doorName: t\('buildings\.catacombs'\)/.test(блок), 'не то название');
  });

  it('входная арка с лестницей вниз', () => {
    const блок = блокКатакомб();
    must(/арка/.test(блок), 'нет арки');
    must(/лестница\.число/.test(блок), 'лестница не объявлена');
    must(/ступеньY -=/.test(блок), 'ступени не спускаются');
  });

  it('в проёме двери заглушка', () => {
    must(/КАТАКОМБЫ_ЗАГЛУШКА/.test(ТЕРРЕЙН), 'нет заглушки');
  });
});

describe('Катакомбы: двор', () => {
  it('ограда двора по бокам', () => {
    const блок = блокКатакомб();
    must(/wallYard/.test(блок), 'нет ограды');
    must(/addCollider\(CATACOMBS\.x - двор\.w \/ 2 - wallYard\.t \/ 2/.test(блок), 'левая сторона не закрыта');
    must(/addCollider\(CATACOMBS\.x \+ двор\.w \/ 2 \+ wallYard\.t \/ 2/.test(блок), 'правая сторона не закрыта');
  });

  it('плита двора почти вровень', () => {
    const m = /export const CATACOMBS_GEO = \{[\s\S]*?плита: \{ t: ([\d.]+), подъём: ([\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'плита не объявлена');
    must(Number(m![2]) <= 0.1, 'плита велика');
  });
});