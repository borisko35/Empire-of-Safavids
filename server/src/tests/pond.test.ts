// Пруд в садах: берег, вода вровень с плитой, кувшинки.
//
// ЧТО БЫЛО (21 октября 2026, §242). Пруд был плоским диском воды, висящим
// НАД мостовой (0.5 при верхе плиты 0.3): ни берега, ни ямки, ни жизни.
//
// ЧТО ТЕПЕРЬ. Каменный берег-кольцо, вода вровень с плитой, кувшинки на
// воде и камыш по берегу.
//
// ЧТО ПРОВЕРЯЕТСЯ. Вода не висит над плитой (она ниже её верха), берег есть,
// и вокруг воды есть жизнь.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Пруд в садах', () => {
  it('вода вровень с плитой, а не висит над ней', () => {
    // Прежний диск стоял на 0.5 при верхе плиты 0.3 — вода висела в воздухе.
    должен(
      !/pond\.position\.set\(-31\.5, 0\.5, 77\.9\)/.test(код),
      'вода снова висит над мостовой: пруд не в ямке, а в воздухе',
    );
    должен(/const ПРУД_Y = 0\.3;/.test(код), 'высота воды не от верхней кромки плиты');
    должен(
      /вода\.position\.set\(-31\.5, ПРУД_Y \+ 0\.05, 77\.9\)/.test(код),
      'вода стоит не у плиты',
    );
  });

  it('у пруда есть берег, кувшинки и камыш', () => {
    должен(
      /const берег = new THREE\.Mesh\(new THREE\.TorusGeometry\(5\.6, 0\.4, 8, 28\), MAT\.sandstone\)/.test(
        код,
      ),
      'у пруда нет каменного берега: вода кончается в никуда',
    );
    должен(
      /const кувшинка = new THREE\.Mesh\(\s*new THREE\.CircleGeometry\(0\.28 \+ hash2\(i, 7\) \* 0\.2, 10\),\s*MAT\.foliage,?\s*\)/.test(
        код,
      ),
      'на воде нет кувшинок из листвы: это пятна на воде',
    );
    должен(/const камыш = new THREE\.Mesh/.test(код), 'по берегу нет камыша');
  });
});
