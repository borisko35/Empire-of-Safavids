// Список квестов показывает доступные, а не первые восемь из базы.
//
// ЧТО БЫЛО ИЗМЕРЕНО. Маршрут GET /api/game/quests вызывал
// getAvailableQuests(char.level, [], char.class, карма) - с ПУСТЫМ списком
// выполненных квестов. Это ломало две вещи сразу:
//
//   1. условие «квест уже выполнен» (строка
//      `if (!q.repeatable && completedIds.includes(q.id)) return false`)
//      никогда не срабатывало, и выполненные обычные квесты оставались в
//      списке навсегда;
//   2. условие по предыдущим квестам (`q.prerequisites.some(p =>
//      !completedIds.includes(p))`) с пустым списком отбрасывало ЛЮБОЙ квест с
//      предыдущими - отсутствие предыдущего квеста в списке означает «не
//      выполнен». То есть цепочки квестов были видны как ненаписанные.
//
// Плюс вторая половина: клиент вообще не спрашивал доступность. api.quests()
// уходил без параметров, маршрут отдавал всю базу, и вкладка показывала первые
// восемь квестов по порядку в базе. Доступные игроку в этот список могли не
// попасть.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ:
//   1. фильтр доступности работает на настоящих данных, когда ему дают
//      выполненные квесты (это и не проверялось);
//   2. маршрут передаёт настоящие выполненные, а не пустой массив;
//   3. клиент спрашивает список с уровнем и персонажем и не дублирует правило
//      доступности у себя.
//
// ПОЧЕМУ ПРОВЕРКА СЧИТАЕТ, А НЕ ИЩЕТ СТРОКУ. Поиск completedIds доказал бы
// только наличие слова. Здесь берутся настоящие квесты из базы и проверяется,
// что фильтр их прячет и показывает.
import { getAvailableQuests, QUESTS_DATABASE } from '../data/quests';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const все = Object.values(QUESTS_DATABASE);

// Квесты с предыдущими и без: на них держится главная проверка.
//
// ОТДЕЛЬНО ОТБИРАЕМ КВЕСТЫ БЕЗ ОГРАНИЧЕНИЙ ПО КАРМЕ. Первая версия проверки
// брала первые попавшиеся квесты, и это были личные квесты тёмной ветки
// (requiresKarmaAtMost): filter прятал их совершенно правильно, а проверка
// решила, что фильтр сломан. Проверять правило «предыдущие квесты» надо на
// квестах, где единственное правило - предыдущие квесты.
const безКармы = (квест: (typeof все)[number]): boolean =>
  квест.requiresKarmaAtMost === undefined && квест.requiresKarmaAtLeast === undefined;

const сПредыдущими = все.filter((задание) => задание.prerequisites.length > 0);
const безПредыдущих = все.filter((задание) => задание.prerequisites.length === 0);
const повторяемые = все.filter((задание) => задание.repeatable);
const чистые = сПредыдущими.filter(безКармы);
const чистыеБезПредыдущих = безПредыдущих.filter(безКармы);

describe('Список квестов: фильтр доступности работает на данных', () => {
  it('в базе есть квесты с предыдущими и без них', () => {
    must(
      сПредыдущими.length >= 5 && безПредыдущих.length >= 5,
      `с предыдущими ${сПредыдущими.length}, без ${безПредыдущих.length}: ` +
        'проверять нечего, база устроена не так, как считает проверка'
    );
    must(
      чистые.length >= 3,
      `квестов с предыдущими и без ограничений по карме всего ${чистые.length}: ` +
        'правило «предыдущие квесты» не на чем проверять'
    );
  });

  it('выполненный обычный квест пропадает из списка', () => {
    const выполненный = чистыеБезПредыдущих.find((задание) => !задание.repeatable && задание.minLevel <= 10);
    must(выполненный, 'в базе нет обычного квеста первого десятка уровней без ограничений по карме');
    const безВыполнения = getAvailableQuests(99, [], undefined, 0);
    const сВыполнением = getAvailableQuests(99, [выполненный.id], undefined, 0);
    must(
      безВыполнения.some((к) => к.id === выполненный.id),
      `${выполненный.id} не показывается даже до выполнения: фильтр прячет лишнее`
    );
    must(
      !сВыполнением.some((к) => к.id === выполненный.id),
      `${выполненный.id} остаётся в списке после выполнения: игрок видит квест, который уже сделан`
    );
  });

  it('повторяемый выполненный квест остаётся в списке', () => {
    must(повторяемые.length > 0, 'в базе нет повторяемых квестов: проверка не знает, что проверять');
    const к = повторяемые[0];
    const список = getAvailableQuests(99, [к.id], undefined, 0);
    must(
      список.some((х) => х.id === к.id),
      `${к.id} повторяемый, но после выполнения исчез из списка: его нельзя будет взять повторно`
    );
  });

  it('квест с предыдущими появляется, когда предыдущий выполнен', () => {
    const к = чистые[0];
    must(к, 'в базе нет квеста с предыдущими без ограничений по карме: проверять нечего');
    const предыдущий = к.prerequisites[0];
    const безПредыдущего = getAvailableQuests(99, [], undefined, 0);
    const сПредыдущим = getAvailableQuests(99, [предыдущий], undefined, 0);
    must(
      !безПредыдущего.some((х) => х.id === к.id),
      `${к.id} виден без выполнения ${предыдущий}: цепочка открыта с начала`
    );
    must(
      сПредыдущим.some((х) => х.id === к.id),
      `${к.id} не появился после выполнения ${предыдущий}: цепочка квестов не открывается`
    );
  });

  it('цепочка из нескольких предыдущих требует всех', () => {
    const сДвумя = чистые.find((задание) => задание.prerequisites.length >= 2);
    if (!сДвумя) {
      must(
        чистые.every((задание) => задание.prerequisites.length === 1),
        'в базе смесь цепочек в один и в два шага, а проверка считает только одно'
      );
      return;
    }
    const [первый, второй] = сДвумя.prerequisites;
    const один = getAvailableQuests(99, [первый], undefined, 0);
    const оба = getAvailableQuests(99, [первый, второй], undefined, 0);
    must(
      !один.some((х) => х.id === сДвумя.id),
      `${сДвумя.id} открылся после одного из двух предыдущих`
    );
    must(
      оба.some((х) => х.id === сДвумя.id),
      `${сДвумя.id} не открылся после обоих предыдущих`
    );
  });

  it('уровень, класс и карма по-прежнему учитываются', () => {
    // Фильтр доступности стал настоящим, а значит его правила нельзя потерять
    // при переносе аргументов.
    const новичок = getAvailableQuests(1, [], undefined, 0);
    must(
      новичок.every((к) => к.minLevel <= 1),
      `квест первого уровня недоступен новичку: ${JSON.stringify(новичок.map((к) => к.minLevel))}`
    );
    const классовый = безПредыдущих.find((к) => к.requiredClass);
    if (классовый) {
      const чужой = getAvailableQuests(99, [], 'wrong_class' as never, 0);
      must(
        !чужой.some((к) => к.id === классовый.id),
        `${классовый.id} показан персонажу чужого класса`
      );
    }
    const личный = все.find((к) => к.requiresKarmaAtMost !== undefined);
    if (личный) {
      must(
        !getAvailableQuests(99, [], undefined, 5000).some((к) => к.id === личный.id),
        `${личный.id} показан доброму персонажу, хотя адресован тёмному`
      );
      must(
        getAvailableQuests(99, [], undefined, -5000).some((к) => к.id === личный.id),
        `${личный.id} не показан тёмному персонажу`
      );
    }
  });
});

describe('Список квестов: сервер отдаёт доступное, а не базу', () => {
  const маршрут = читать('server/src/routes/game.ts');

  it('маршрут передаёт настоящие выполненные квесты', () => {
    must(
      !/getAvailableQuests\(char\.level, \[\],/.test(маршрут),
      'маршрут передаёт пустой список выполненных: и выполненные квесты видны, ' +
        'и цепочки не открываются'
    );
    must(
      /статус.*completed|status === 'completed'/.test(маршрут) &&
        /getAvailableQuests\(char\.level, выполненные/.test(маршрут),
      'маршрут не собирает выполненные квесты из состояния персонажа'
    );
  });

  it('доступность считается только при персонаже', () => {
    // Без characterId фильтр применять не к чему: уровень неизвестен.
    // Это остаётся как было - вопрос в том, что фильтр не должен считаться
    // применённым, когда его не просили.
    must(
      /if \(level\) \{/.test(маршрут) && /if \(!characterId\) \{/.test(маршрут),
      'фильтр доступности больше не требует персонажа: уровень неизвестен, а квесты отдаются как есть'
    );
  });
});

describe('Список квестов: клиент спрашивает доступное', () => {
  const hud = читать('client/src/app/hud.ts');
  const api = читать('client/src/app/api.ts');

  it('клиент передаёт уровень и персонажа', () => {
    must(
      /api\.quests\(\s*session\.character \? \{ level: уровень, characterId: session\.character\.id \}/.test(hud),
      'клиент не спрашивает список с уровнем и персонажем: сервер отдаёт всю базу'
    );
  });

  it('клиент больше не фильтрует уровень у себя', () => {
    // Свое правило доступности у клиента - вторая копия. С запасом +10 оно
    // показывало квесты, которые игрок взять не может, и прятало те, что может.
    must(
      !/minLevel <= level \+ 10/.test(hud) && !/minLevel <= уровень \+ 10/.test(hud),
      'у клиента остался свой фильтр по уровню с запасом: две копии правила расходятся'
    );
    must(
      /requiredRegion/.test(hud),
      'клиент потерял фильтр по региону: его нет в серверном фильтре'
    );
  });

  it('запрос умеет передавать параметры', () => {
    must(
      /quests: \(params\?: \{ level\?: number; characterId\?: string; type\?: string \}\)/.test(api),
      'api.quests не умеет передавать уровень и персонажа'
    );
    must(
      /поиск\.set\('level'/.test(api) && /поиск\.set\('characterId'/.test(api),
      'api.quests собирает не все параметры запроса'
    );
  });

  it('предел в восемь карточек остался и подписан', () => {
    // Это размер панели, а не правило игры. Отмечаем явно, чтобы следующий
    // человек не принял его за забытый фильтр.
    must(
      /available\.slice\(0, 8\)/.test(hud),
      'в списке квестов исчез предел в восемь карточек: панель стала показывать все'
    );
    must(
      /предел панели/.test(hud),
      'предел в восемь карточек не подписан: его примут за баг и сломают'
    );
  });
});
