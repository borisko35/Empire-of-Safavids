// Крафт: изготовленную вещь больше нельзя потерять.
//
// ЧТО БЫЛО. У сервера был готовый метод getActiveJobs — читает все задания в работе —
// но он не вызывался ниоткуда, и маршрута для него не было. Единственным источником
// знания о крафте был ключ в localStorage на браузере игрока. Отсюда два пути потерять
// вещь:
//
// 1. СБРОС БРАУЗЕРА. Ключ пропал — задание в базе осталось в работе навсегда: материалы
//    списаны, предмет не выдан, сервер не может даже сказать клиенту, что готово.
// 2. ВТОРОЙ КРАФТ ПОВЕРХ ПЕРВОГО. Сервер не проверял, есть ли уже задание. Клиент прячет
//    кнопки, но это защита интерфейса: двойной клик запускал два крафта, материалы
//    списывались дважды, а в localStorage попадал только второй идентификатор.
//
// ЧТО ПРОВЕРЯЕТСЯ.
//  - Сервер отказывает, если задание уже в работе: крафт один за раз.
//  - Список заданий отдаётся маршрутом, то есть getActiveJobs перестал быть мёртвым.
//  - Клиент сверяется с сервером и подхватывает задание, о котором забыл.
//  - Проверка требует, чтобы маршрут отдавал задания ИМЕННО ЭТОГО персонажа: иначе
//    подхват достался бы чужому игроку.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СЕРВИС = читать('server/src/services/CraftingService.ts');
const МАРШРУТЫ = читать('server/src/routes/game.ts');
const API = читать('client/src/app/api.ts');
const ПАНЕЛЬ = читать('client/src/app/panels.ts');

describe('Крафт: второй раз не запускается', () => {
  it('сервер проверяет, что задание уже не в работе', () => {
    must(
      /const задания = await this\.getActiveJobs\(characterId\);/.test(СЕРВИС),
      'сервер не спрашивает про активные задания: два крафта идут одновременно, ' +
        'материалы списываются дважды, а забрать можно только один предмет'
    );
    must(
      /throw new Error\(`Craft already in progress/.test(СЕРВИС),
      'отказ на второй крафт не происходит: игрок теряет и вторую порцию материалов'
    );
  });

  it('проверка стоит ДО списания материалов', () => {
    // Порядок обязателен: если сначала списывать, а потом проверять, материалы уже
    // заберут, а задание не создастся — то есть игрок потеряет всё и ничего не получит.
    const проверка = СЕРВИС.indexOf('Craft already in progress');
    const списание = СЕРВИС.indexOf('UPDATE character_items SET quantity = quantity - $1');
    must(проверка > 0 && списание > 0, 'не нашёл проверку или списание материалов');
    must(
      проверка < списание,
      'материалы списываются раньше проверки активных заданий: при отказе игрок ' +
        'потеряет всё и не получит ничего'
    );
  });

  it('маршрут списка заданий существует и отдаёт их', () => {
    must(
      /gameRouter\.get\('\/crafting\/jobs'/.test(МАРШРУТЫ),
      'маршрута списка заданий нет: клиент не может узнать о забытом крафте'
    );
    must(
      /getActiveJobs\(characterId\)/.test(МАРШРУТЫ),
      'маршрут есть, но он не читает задания: getActiveJobs снова мёртвый код'
    );
    must(
      /bodyCharacterId\(req, res\)/.test(
        МАРШРУТЫ.slice(МАРШРУТЫ.indexOf("gameRouter.get('/crafting/jobs'"), МАРШРУТЫ.indexOf("gameRouter.get('/crafting/jobs'") + 600)
      ),
      'маршрут заданий не проверяет, чей это персонаж: подхват задания достался бы ' +
        'чужому игроку'
    );
  });
});

describe('Крафт: забытое задание можно забрать', () => {
  it('клиент умеет спрашивать сервер о заданиях', () => {
    must(
      /craftingJobs: \(characterId: string\)/.test(API),
      'клиент не умеет спрашивать сервер о заданиях в работе'
    );
    must(
      /\/api\/game\/crafting\/jobs\?characterId=/.test(API),
      'клиентский запрос уходит не на тот маршрут'
    );
  });

  it('панель подхватывает задание, о котором клиент забыл', () => {
    must(
      /if \(!craftJobId\)/.test(ПАНЕЛЬ) && /api\.craftingJobs\(cid\(\)\)/.test(ПАНЕЛЬ),
      'панель не сверяется с сервером: после сброса браузера задание невидимо навсегда'
    );
    must(
      /localStorage\.setItem\('eos_craft_job', craftJobId\)/.test(ПАНЕЛЬ),
      'подхваченное задание не сохраняется: оно снова потеряется при следующем ' +
        'открытии панели'
    );
  });

  it('сохранённое задание не перетирается серверным', () => {
    // Подхват делается только когда клиент ничего не знает. Иначе серверный ответ
    // подменял бы уже идущий крафт — например, когда игрок только что нажал
    // «Начать» и сохранил новый идентификатор, а ответ пришёл по старому заданию.
    must(
      /if \(!craftJobId\) \{[\s\S]{0,400}api\.craftingJobs/.test(ПАНЕЛЬ),
      'сверка с сервером происходит безусловно и может переписать текущий крафт'
    );
  });
});

describe('Крафт: провал остаётся решением владельца', () => {
  it('возврата материалов нет, и это записано как решение, а не как недосмотр', () => {
    // Проверка не требует возврата: он не сделан намеренно (шанс виден в панели),
    // и менять это — решение владельца. Здесь фиксируется лишь то, что решение
    // принято осознанно: если возврат появится, проверка об этом скажет.
    must(
      !/refund|вернуть материал/i.test(СЕРВИС),
      'в сервисе появился возврат материалов при провале: это балансовое решение, ' +
        'и перед тем как считать его исправлением, с ним нужно согласовать'
    );
  });
});