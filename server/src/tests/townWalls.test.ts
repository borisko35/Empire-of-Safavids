// Стены и башни городов перестают быть бруском и барабаном.
//
// ЧТО БЫЛО (22 октября 2026, §292). Стены городов регионов — брусок, башни —
// голый цилиндр. Город читался как забор из коробок: ни зубцов, ни карнизов,
// ни цоколя, ни бойниц.
//
// ЧТО ТЕПЕРЬ. Стена: цоколь шире тела, само тело, карниз и зубцы по верху.
// Башня: база, ствол, карниз, восемь зубцов по ободу и две бойницы.
//
// ЧТО ПРОВЕРЯЕТСЯ. У стены есть цоколь, карниз и зубцы; у башни — база,
// карниз, зубцы по ободу и бойницы; бруска-стены и голого барабана больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Стены и башни городов — не бруски', () => {
  it('стена: цоколь, карниз и зубцы', () => {
    // Цоколь шире тела.
    должен(
      /const цоколь = new THREE\.Mesh\(new THREE\.BoxGeometry\(длина, 0\.7, 2\.0\)/.test(ТЕРРЕЙН),
      'у стены нет цоколя',
    );
    // Карниз над зубцами.
    должен(
      /const карниз = new THREE\.Mesh\(new THREE\.BoxGeometry\(длина, 0\.22, 2\.0\)/.test(ТЕРРЕЙН),
      'у стены нет карниза',
    );
    // Зубцы: их число зависит от длины сегмента.
    должен(
      /const зубцов = Math\.max\(3, Math\.round\(длина \/ 1\.6\)\);/.test(ТЕРРЕЙН),
      'зубцы стены не считаются по длине сегмента',
    );
    должен(
      /const зубец = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.55, 0\.75, 1\.6\), MAT\.stone\);/.test(ТЕРРЕЙН),
      'у стены нет зубцов',
    );
    // Бруска-стены быть не должно.
    должен(
      !/const wall = new THREE\.Mesh\(new THREE\.BoxGeometry\(t\.radius \* 0\.44, hСтены, 1\.6\)/.test(ТЕРРЕЙН),
      'стена снова брусок',
    );
    // Тело стены короче самой стены: низ занимает цоколь, верх — карниз.
    // Иначе стена снова ровный брусок во всю высоту.
    const тело = /const корпус = new THREE\.Mesh\(new THREE\.BoxGeometry\(длина, hСтены - ([\d.]+), 1\.6\)/.exec(ТЕРРЕЙН);
    должен(тело, 'тело стены не отличается от стены: нет цоколя и карниза');
    должен(Number(тело![1]) > 0.3, 'цоколь и карниз не оставляют места под тело стены');
  });

  it('башня: база, карниз, зубцы по ободу и бойницы', () => {
    // База шире ствола.
    должен(
      /const база = new THREE\.Mesh\(new THREE\.CylinderGeometry\(2\.25, 2\.5, 1\.2, 10\)/.test(ТЕРРЕЙН),
      'у башни нет базы',
    );
    // Карниз.
    должен(
      /const карниз = new THREE\.Mesh\(new THREE\.CylinderGeometry\(2\.15, 2\.0, 0\.24, 10\)/.test(ТЕРРЕЙН),
      'у башни нет карниза',
    );
    // Восемь зубцов по ободу.
    должен(/for \(let j = 0; j < 8; j\+\+\) \{/.test(ТЕРРЕЙН), 'зубцы башни не считаются');
    должен(
      /зубец\.position\.set\(Math\.cos\(угол\) \* 2\.0, 7\.3, Math\.sin\(угол\) \* 2\.0\);/.test(ТЕРРЕЙН),
      'зубцы башни не стоят по ободу',
    );
    // Бойницы.
    должен(
      /const щель = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.16, 0\.9, 0\.1\), MAT\.dark\);/.test(ТЕРРЕЙН),
      'у башни нет бойниц',
    );
    // Голого барабана быть не должно.
    должен(
      !/const башня = new THREE\.Mesh\(new THREE\.CylinderGeometry\(1\.9, 2\.1, 7\.4, 8\)/.test(ТЕРРЕЙН),
      'башня снова голый барабан',
    );
    // Ствол короче всей башни: снизу база, сверху карниз и зубцы.
    const ствол = /const ствол = new THREE\.Mesh\(new THREE\.CylinderGeometry\(1\.9, 2\.1, ([\d.]+), 10\)/.exec(ТЕРРЕЙН);
    должен(ствол, 'у башни нет ствола');
    должен(Number(ствол![1]) < 7, `ствол башни высотой ${ствол![1]} — базы и карниза нет`);
  });
});
