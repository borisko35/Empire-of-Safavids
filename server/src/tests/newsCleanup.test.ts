// Два старых пункта ленты новостей сняты 1 октября 2026.
//
// ПОЧЕМУ ПРОВЕРКА ИМЕННО ТАКАЯ. Пункты ленты не имеют ни id, ни даты, ни
// ссылки - только заголовок. Поэтому отбирать их можно было тремя способами
// с разной надёжностью:
//
//   1. По номеру пункта (10 и 11). Плохо: после любой правки ленты номера
//      седут, и следующий запуск удалит не то. Причём сегодня номера уже
//      сели: после снятия объявления эти пункты стали девятым и десятым.
//   2. По наличию пустых переводов. Плохо: признак не отличает эти пункты
//      от любой недопереведённой записи.
//   3. По точному заголовку. Годится: заголовок уникален в ленте и переживает
//      перестановку пунктов.
//
// Проверка требует именно третий способ и отдельно запрещает отбор по
// номеру: иначе миграция, однажды прочитанная неправильно, удалит чужие
// пункты и это будет выглядеть как успех.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const миграция = читать('database/migrations/065_remove_stale_news.sql');
const архив = читать('docs/archive/news-removed-2026-10-01.md');

const ГРЯДЕТ = '⚔️ ГРЯДЁТ ВЕЛИКОЕ ОБНОВЛЕНИЕ В EMPIRE OF SAFAVIDS! ⚔️';
const НОВОЕ = 'Новое обновление в игре!';

describe('Снятие двух старых пунктов ленты новостей', () => {
  it('отбирает по заголовку, а не по номеру пункта', () => {
    must(миграция.includes(ГРЯДЕТ), 'миграция не упоминает первый заголовок');
    must(миграция.includes(НОВОЕ), 'миграция не упоминает второй заголовок');
    must(миграция.includes('item->\'title\'->>\'ru\''), 'миграция не смотрит в заголовок');
  });

  it('отсекает хвостовой пробел в заголовке', () => {
    // Первый заголовок в базе кончился пробелом: «...SAFAVIDS! ⚔️ ».
    // Сравнение без btrim его не нашло бы, миграция прошла бы молча, ничего
    // не удалив, и отчиталась бы об успехе.
    must(/btrim\(COALESCE\(item->'title'->>'ru'/.test(миграция), 'миграция не отсекает пробелы');
  });

  it('не удаляет ленту целиком и не трогает пункты без заголовка', () => {
    must(/\{items\}/.test(миграция), 'миграция меняет не ключ items');
    // Пустой заголовок - это недопереведённая запись, её нельзя считать
    // «прочим текстом» и снести вместе со снятыми. Раньше фильтр был без
    // этой оговорки и вычистил бы всю недопереведённую часть ленты.
    must(
      /AND COALESCE\(item->'title'->>'ru', ''\) <> ''/.test(миграция),
      'миграция не охраняет пункты с пустым заголовком',
    );
  });

  it('повторно применима: отбор текстовый, а не позиционный', () => {
    // На проде применённые миграции не откатываются. Повторный запуск
    // обязан быть тихим no-op, а не падением на «nothing to delete».
    must(!/OFFSET|LIMIT/.test(миграция), 'в миграции есть OFFSET/LIMIT - отбор позиционный');
    must(!/jsonb_array_elements\(value->'items'\) WITH ORDINALITY/.test(миграция),
      'миграция нумерует пункты - отбор по номеру, он седет');
  });

  it('тексты снятых пунктов сохранены в архиве', () => {
    // Снять и стереть - разные вещи. Возврат должен быть возможен.
    must(архив.includes(ГРЯДЕТ), 'в архиве нет первого заголовка');
    must(архив.includes(НОВОЕ), 'в архиве нет второго заголовка');
    // Хотя бы кусок тела: заголовок можно повторить, тело - нет.
    must(/Банк Гильдии/.test(архив), 'в архиве нет тела второго пункта');
    must(/мини-игры/.test(архив), 'в архиве нет тела первого пункта');
  });

  it('снятые тексты не остались на лендинге статикой', () => {
    // Лента рисуется из базы, но на лендинге есть и запасные карточки.
    // Если бы текст остался в них, посетитель увидел бы его в обход миграции.
    const лендинг = читать('client/web/index.html');
    must(!лендинг.includes('ГРЯДЁТ ВЕЛИКОЕ ОБНОВЛЕНИЕ'), 'текст объявления остался в лендинге');
    must(!лендинг.includes('Банк Гильдии'), 'перечень выпущенного остался в лендинге');
  });
});
