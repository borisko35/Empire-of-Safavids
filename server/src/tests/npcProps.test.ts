// NPC получают предметы по роду занятия.
//
// ЧТО БЫЛО (22 октября 2026, §293). Рыбак стоял с пустыми руками, торговец —
// тоже. Рыбак у сетей без удочки и корзины, торговец без весов: работа
// читалась только по подписи над NPC.
//
// ЧТО ТЕПЕРЬ. У гуманоида есть поле «предмет»: удочка (древно, леска, крючок),
// весы (коромысло, две чаши на нитях) или корзина (тело, ободок, дужка).
// Корзина вешается на левую руку — на правой может быть удочка.
//
// ЧТО ПРОВЕРЯЕТСЯ. Сборщик гуманоида умеет предметы, удочка состоит из
// древна, лески и крючка, весы — из коромысла и двух чаш на нитях, корзина —
// из тела, ободка и дужки; и в мире эти предметы реально розданы: рыбакам —
// удочки и корзина, торговцу — весы.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РИГ = читать('client/src/app/game3d/rig.ts');
const НПЦ = читать('client/src/app/game3d/npc.ts');

describe('NPC с предметами по роду занятия', () => {
  it('сборщик гуманоида умеет предметы', () => {
    должен(
      /предмет\?: 'удочка' \| 'весы' \| 'корзина';/.test(РИГ),
      'у гуманоида нет поля «предмет»',
    );
    // Предмет вешается в руку, а не висит в воздухе рядом.
    должен(/if \(предметRef\) armR\.add\(предметRef\);/.test(РИГ), 'предмет не в руке');
    должен(/armL\.add\(корзина\);/.test(РИГ), 'корзина не на левой руке');
  });

  it('удочка: древно, леска, крючок', () => {
    должен(
      /const древко = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.018, 0\.032, 1\.9, 6\)/.test(РИГ),
      'у удочки нет древна',
    );
    должен(
      /const леска = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.005, 0\.005, 0\.78, 4\)/.test(РИГ),
      'у удочки нет лески',
    );
    должен(
      /const крючок = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.028, 0\.007, 4, 8\)/.test(РИГ),
      'у удочки нет крючка',
    );
  });

  it('весы: коромысло и две чаши на нитях', () => {
    должен(
      /const коромысло = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.5, 0\.028, 0\.028\)/.test(РИГ),
      'у весов нет коромысла',
    );
    // Две чаши.
    должен(/const чашаЛ = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.085, 0\.055, 0\.035, 10\)/.test(РИГ),
      'у весов нет чаш');
    // Нити: чаши висят на них, а не висят в воздухе.
    должен(
      /const нить = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.004, 0\.004, 0\.11, 4\)/.test(РИГ),
      'чаши весов висят в воздухе',
    );
  });

  it('корзина: тело, ободок и дужка', () => {
    должен(
      /const тело = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.19, 0\.13, 0\.26, 10\)/.test(РИГ),
      'у корзины нет тела',
    );
    должен(/const ободок = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.19, 0\.022, 5, 12\)/.test(РИГ),
      'у корзины нет ободка');
    должен(/const дужка = new THREE\.Mesh\(new THREE\.TorusGeometry\(0\.18, 0\.014, 5, 12, Math\.PI\)/.test(РИГ),
      'у корзины нет дужки');
  });

  it('предметы реально розданы', () => {
    // Рыбаки — с удочкой, один — с корзиной, торговец — с весами.
    const удочки = (НПЦ.match(/предмет: 'удочка'/g) || []).length;
    const корзины = (НПЦ.match(/предмет: 'корзина'/g) || []).length;
    const весы = (НПЦ.match(/предмет: 'весы'/g) || []).length;
    должен(удочки >= 2, `удочек только ${удочки} — рыбаки без удочек`);
    должен(корзины >= 1, 'корзина не досталась ни одному рыбаку');
    должен(весы >= 1, 'весы не достались ни одному торговцу');
  });
});
