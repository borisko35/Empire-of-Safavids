// Карта данных не должна получать цветовое пространство.
//
// ЧТО БЫЛО СЛОМАНО 15.10.2026. Все шесть карт данных игры — две карты
// нормалей (stone, wood), карта нормалей воды, две карты шероховатости и
// карта смещения камня — собирались функцией toTexture, которая ставит
// SRGBColorSpace. В three это не подпись, а указание GPU: при SRGBColorSpace
// и UnsignedByte текстура грузится во внутренний формат SRGB8_ALPHA8, и каждое
// чтение проходит через sRGB в линейное на уровне железа.
//
// ЧТО ЭТО ДАВАЛО. Карта нормалей хранит «ровно вверх» байтами 128,128,255.
// Декод отдаёт шейдеру 0.2159, и вычитание `normalMap - 0.5` даёт наклон
// поверхности на 38.8 градуса. Каждый камень, каждое дерево и вся вода были
// освещены как поверхности, развёрнутые на 39 градусов: свет «плывёт» по
// стенам. Шероховатость 0.5 читалась как 0.216 — глянцевее задуманного.
//
// ПОЧЕМУ ПРОВЕРКА ИМЕННО ТАКАЯ. Порог не выдуман: наклон посчитан из
// формулы sRGB в линейное, которую использует three, и напечатан пробником
// check-sky-environment раньше, чем появилась эта проверка. Проверка ловит
// сам класс поломки (карта данных с цветовым пространством), а не сравнение
// имён файлов.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** sRGB -> линейное, ровно как это делает three при загрузке SRGB8_ALPHA8. */
function srgbВЛинейное(v: number): number {
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
}

const КАРТЫ_ДАННЫХ = [
  'stoneNormalTexture',
  'woodNormalTexture',
  'waterNormalTexture',
  'stoneRoughnessTexture',
  'woodRoughnessTexture',
  'stoneDisplacementTexture',
  'groundDetailNormalTexture',
];

const ФАЙЛ = join('client', 'src', 'app', 'game3d', 'textures.ts');

describe('Карты данных не получают цветовое пространство', () => {
  const код = readFileSync(join(корень, ФАЙЛ), 'utf8').replace(/\r\n/g, '\n');

  /** Тело функции: от объявления до закрывающей скобки на нулевой вложенности. */
  function тело(имя: string): string {
    const строки = код.split('\n');
    const начало = строки.findIndex((л) => л.includes(`export function ${имя}(`));
    must(начало >= 0, `в ${ФАЙЛ} нет функции ${имя}: карта данных пропала`);
    let скобок = 0;
    for (let i = начало; i < строки.length; i++) {
      скобок += (строки[i].match(/{/g) ?? []).length - (строки[i].match(/}/g) ?? []).length;
      if (i > начало && скобок <= 0) return строки.slice(начало, i + 1).join('\n');
    }
    throw new Error(`функция ${имя} не закрылась — файл разобран неверно`);
  }

  it('все шесть карт данных на месте', () => {
    for (const имя of КАРТЫ_ДАННЫХ) {
      must(/export function /.test(тело(имя)), `${имя} не найдена`);
    }
  });

  it('ни одна карта данных не собирается цветовой сборкой', () => {
    const виновники: string[] = [];
    for (const имя of КАРТЫ_ДАННЫХ) {
      const кодФункции = тело(имя);
      if (/return toTexture\(/.test(кодФункции)) виновники.push(имя);
    }
    must(
      виновники.length === 0,
      'эти карты данных собираются через toTexture, то есть получают SRGBColorSpace. '
      + 'GPU декодирует их как цвет, и нормаль «ровно вверх» (128,128,255) приходит '
      + 'в шейдер как 0.216 — наклон поверхности на 38.8 градусов вместо нуля:\n'
      + виновники.map((имя) => `  ${имя}`).join('\n'),
    );
  });

  it('у сборки карт данных линейная передача, а у цветовой — sRGB', () => {
    must(/function toDataTexture\(/.test(код), 'в текстурах нет отдельной сборки для карт данных');
    const начало = код.indexOf('function toDataTexture(');
    const телоСборки = код.slice(начало, начало + 700);
    must(
      /colorSpace = THREE\.NoColorSpace/.test(телоСборки),
      'toDataTexture ставит цветовое пространство: карта данных снова декодируется как цвет',
    );

    const началоЦвета = код.indexOf('function toTexture(');
    const телоЦвета = код.slice(началоЦвета, началоЦвета + 700);
    must(
      /colorSpace = THREE\.SRGBColorSpace/.test(телоЦвета),
      'toTexture перестал ставить sRGB: карты ЦВЕТА теперь считаются линейными',
    );
  });

  it('наклон «ровной» карты нормалей нулевой, а не 38.8 градуса', () => {
    // Порог посчитан, а не взят на глаз.
    const нейтраль = srgbВЛинейное(128 / 255);
    must(Math.abs(нейтраль - 0.2159) < 0.001,
      `расчёт sRGB в линейное разъехался: ${нейтраль} вместо 0.2159 — порог проверки устарел`);

    const наклонПриSrgb = Math.atan2(Math.hypot(нейтраль - 0.5, нейтраль - 0.5), 1 - 0.5)
      * 180 / Math.PI;
    must(наклонПриSrgb > 35,
      `наклон вышел ${наклонПриSrgb.toFixed(1)}°, а проверка ждёт больше 35°: `
      + 'значит формула в комментарии устарела и правку надо пересчитать');

    // Линейная карта данных отдаёт байт 128 как есть. Остаток не нулевой ровно
    // потому, что 128/255 отличается от 0.5 на 1/255: это квантование байта, то
    // есть наклон 0.32 градуса. Считать его нулём нельзя — тогда проверка врала бы.
    const наклонПриЛинейной = Math.atan2(Math.hypot(128 / 255 - 0.5, 128 / 255 - 0.5), 1 - 0.5)
      * 180 / Math.PI;
    must(наклонПриЛинейной < 1,
      `карта данных даёт наклон ${наклонПриЛинейной.toFixed(2)}° вместо квантования `
      + `байта (0.32°): у неё снова появилось цветовое пространство`);

    // Разница между правильной картой и поломанной — не «немного хуже»:
    // поломанная в 100 раз дальше от «ровно».
    must(наклонПриSrgb > наклонПриЛинейной * 50,
      `sRGB-декод даёт ${наклонПриSrgb.toFixed(1)}°, линейный — ${наклонПриЛинейной.toFixed(2)}°: `
      + 'правка не даёт того, ради чего её делали');
  });
});

describe('Карта нормалей строится по высоте, а не по байтам RGBA', () => {
  const код = readFileSync(join(корень, ФАЙЛ), 'utf8').replace(/\r\n/g, '\n');

  /** Без комментариев: в пояснении к ошибке сама ошибка цитируется словами. */
  const безКомментариев = (текст: string): string =>
    текст.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');

  it('heightToNormal переводит RGBA в высоты до расчёта', () => {
    // ЧТО БЫЛО. heightToNormal принимает ImageData (4 байта на точку), но
    // читала его как «байт на точку»: heightData[y * size + x]. Соседние
    // индексы — это каналы R,G,B,A ОДНОЙ точки, высота прыгала каждый байт, и
    // нормаль чередовалась по столбцам. На земле это дало ровный «рубчик»
    // полосами в один тексель; так же были испорчены ВСЕ 18 карт нормалей игры.
    const тело = безКомментариев(/function heightToNormal\(([\s\S]*?)\n}/.exec(код)?.[1] ?? '');
    must(тело.length > 0, 'в textures.ts нет heightToNormal');
    must(
      /heightData\[i \* 4\]/.test(тело),
      'heightToNormal не берёт из RGBA одну высоту на точку: высота снова '
      + 'читается «байтом на точку», и нормаль чередуется по столбцам',
    );
    must(
      !/heightData\[[^\]]*y \* size \+ x/.test(тело),
      'heightToNormal читает высоту прямо из RGBA по индексу точки: это индекс '
      + 'БАЙТА, а не точки, и соседние столбцы получают разные каналы',
    );
  });

  it('чтение RGBA как высот даёт полосы, и это посчитано', () => {
    // Числа, а не слова. Маленькая карта 16×16: высота плавная (синус), каналы
    // G, B, A постоянны. Считаем разницу соседних столбцов двумя способами.
    const size = 16;
    const данные = new Uint8ClampedArray(size * size * 4);
    for (let y = 0; y < size; y++) {
      for (let x = 0; x < size; x++) {
        const i = (y * size + x) * 4;
        данные[i] = 100 + 2 * x;                              // высота в R
        данные[i + 1] = 200;                                  // G, B, A постоянны
        данные[i + 2] = 200;
        данные[i + 3] = 255;
      }
    }

    // Как было: высота = байт с индексом точки.
    const поБайтам = (x: number, y: number) => данные[y * size + x];
    // Как стало: высота = красный канал точки.
    const поТочкам = (x: number, y: number) => данные[(y * size + x) * 4];

    const соседние = (высота: (x: number, y: number) => number) => {
      let s = 0;
      for (let y = 0; y < size; y++) {
        for (let x = 0; x < size - 1; x++) s += Math.abs(высота(x, y) - высота(x + 1, y));
      }
      return s / (size * (size - 1));
    };

    const поБайтамРазница = соседние(поБайтам);
    const поТочкамРазница = соседние(поТочкам);

    // Высота в этом примере растёт ровно на 2 за столбец: настоящее различие
    // между соседними столбцами — двойка. Чтение по байтам подмешивает
    // постоянные каналы 200 и 255, поэтому перепад вырастает в разы.
    must(
      поТочкамРазница < 5,
      `в образце высота растёт на 2 за столбец, а перепад вышел `
      + `${поТочкамРазница.toFixed(1)}: образец больше не показывает разницы способов`,
    );
    must(
      поБайтамРазница > поТочкамРазница * 3,
      `чтение по байтам даёт перепад ${поБайтамРазница.toFixed(1)} против `
      + `${поТочкамРазница.toFixed(1)} по точкам: образец перестал ловить ошибку`,
    );
  });
});