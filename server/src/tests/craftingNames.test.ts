// Крафт: названия предметов в рецептах и в сообщении о нехватке.
//
// ЧТО ЗДЕСЬ ВСКРЫТО ЖИВЫМ ЗАМЕРОМ (§195). Маршрут /crafting/recipes отдавал
// 11 рецептов, и ни один не присылал названий предметов. Панель печатала
// «wpn_shah_blade» и «mat_dragon_scale» — идентификаторы вместо названий — и
// вообще не рисовала состав рецепта. Перо Симурга при этом описано в самом
// предмете как «крайне редкий материал для легендарного крафта», то есть
// обещание в данных было, а связи с рецептом на экране не было.
//
// И ВТОРОЕ. Кнопка «Крафтить» без материалов отвечала строкой
// «Missing materials: mat_dragon_scale (need 5, have 3)» — по-английски и
// идентификатором. canCraft этот список уже отдавал разобранным, подставить
// название было нечего.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CRAFTING_RECIPES, recipesForClient } from '../data/crafting';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Крафт: рецепты называют предметы, а не идентификаторы', () => {
  it('у каждого рецепта есть название результата, и это не сам идентификатор', () => {
    const рецепты = recipesForClient();
    must(рецепты.length === Object.keys(CRAFTING_RECIPES).length,
      `recipesForClient вернул ${рецепты.length} из ${Object.keys(CRAFTING_RECIPES).length}`);
    for (const r of рецепты) {
      must(r.resultNameRu.length > 0, `${r.id}: пустое название результата`);
      // Запасной вариант подстановки отдаёт идентификатор. Проверка «название
      // не равно ключу» ловит именно его — иначе сломанная ссылка молча
      // превратилась бы в «wpn_shah_blade» в интерфейсе.
      must(r.resultNameRu !== r.resultItemId,
        `${r.id}: результат ${r.resultItemId} не найден в каталоге предметов — игрок увидит идентификатор`);
    }
  });

  it('у каждого ингредиента есть название, и это не сам идентификатор', () => {
    for (const r of recipesForClient()) {
      for (const i of r.ingredients) {
        must(i.nameRu.length > 0, `${r.id}: пустое название ингредиента`);
        must(i.nameRu !== i.itemId,
          `${r.id}: ингредиент ${i.itemId} не найден в каталоге предметов — игрок увидит идентификатор`);
      }
    }
  });

  it('состав рецепта не пуст: панели есть что показать', () => {
    // Рецепт без состава — это «нажми кнопку и удивляйся». Таких в данных
    // нет, но проверить дешевле, чем обнаружить на игре.
    for (const r of recipesForClient()) {
      must(r.ingredients.length > 0, `${r.id}: рецепт без ингредиентов`);
    }
  });

  it('легендарный рецепт с пером Симурга назван и достижим', () => {
    // Проверка против ЛОЖИ В КАРТЕ. В карте написано, что «самого крафта нет»:
    // перо есть, назначения нет. На деле recipe_shah_blade есть, отдаётся
    // маршрутом, и перо в нём указано.
    const клинок = recipesForClient().find((r) => r.resultItemId === 'wpn_shah_blade');
    must(клинок !== undefined, 'легендарного крафта действительно нет — карта была права');
    must(клинок.ingredients.some((i) => i.itemId === 'mat_dragon_scale' && i.quantity > 0),
      'клинок не требует пера Симурга');
    must(клинок.requiredLevel > 0 && клинок.requiredLevel <= 100,
      `уровень рецепта ${клинок.requiredLevel} недостижим: потолок навыка 100`);
  });
});

describe('Крафт: маршрут и панель пользуются названиями', () => {
  // Панель собирается из DOM в браузере, и поднять её в тесте дороже, чем
  // проверить исходник. Это осознанный выбор, а не недосмотр: единственное,
  // что можно сломать в панели, — перестать рисовать состав или вернуть
  // идентификатор вместо названия, и оба случая видны в тексте.
  it('маршрут отдаёт рецепты через recipesForClient', () => {
    must(/recipesForClient\(/.test(читать('server/src/routes/game.ts')),
      'маршрут отдаёт рецепты без названий: игрок снова увидит идентификаторы');
  });

  it('панель рисует состав рецепта и название результата', () => {
    const панель = читать('client/src/app/panels.ts');
    must(/r\.resultNameRu/.test(панель), 'панель показывает идентификатор результата вместо названия');
    must(/r\.ingredients/.test(панель), 'панель не рисует состав рецепта');
    must(/i\.nameRu/.test(панель), 'панель показывает идентификаторы ингредиентов');
  });

  it('сообщение о нехватке называет предмет, а не ключ', () => {
    // Без stripComments сторож цепляется за КОММЕНТАРИЙ, где старая строка
    // процитирована как пример: комментарий, объясняющий поломку, ронял бы
    // сторож, который ловит поломку.
    const сервис = stripComments(читать('server/src/services/CraftingService.ts'));
    const места = [...сервис.matchAll(/Missing materials:/g)].map((m) => m.index ?? -1);
    must(места.length > 0, 'сообщение о нехватке материалов не найдено вовсе');
    for (const начало of места) {
      // Окно, а не остаток строки. Первая версия брала от сообщения только
      // до первой обратной кавычки, а подстановка названия живёт ВНУТРИ
      // вложенного шаблона — то есть проверялось ровно то место, где её нет,
      // и проверка падала на верном коде. Сообщение собирается в несколько
      // строк, поэтому и берём окно.
      const окно = сервис.slice(начало, начало + 200);
      must(/ITEMS_DATABASE\[/.test(окно),
        'в сообщении о нехватке нет названия предмета: игрок увидит '
        + окно.slice(0, 80).replace(/\s+/g, ' '));
    }
  });
});