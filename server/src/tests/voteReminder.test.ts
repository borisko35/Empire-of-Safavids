// Напоминание о голосовании ходит общим клиентом и несёт characterId.
//
// ЧТО БЫЛО. `voteReminder.ts` собирал запрос руками: голый `fetch` с одним
// заголовком `Authorization` и БЕЗ `characterId`. Сервер на `/api/game/vote/status`
// требует идентификатор через `requireCharacterOwnership()` и отвечает
// `400 Missing characterId`. Замерено на проде — перехват `fetch` на живом мире:
//
//   [{ via: 'fetch', status: 400, url: '/api/game/vote/status' }]
//
// ПОЧЕМУ ЭТО НЕ «ОДИН ЛИШНИЙ ЗАПРОС», А ПОЛНОМЕРНЫЙ БАГ. Клиент отвечал
// `if (!res.ok) return;` — то есть глотал 400 молча и выходил. Следствия:
//
//   1. Тост «Проголосуй на BrowserMMORPG — награда 500 золота» НЕ ПОЯВЛЯЛСЯ
//      НИКОГДА. Функция, ради которой написан весь файл, не работала с момента
//      своего появления, и никто этого не заметил: сбой был тихий и правильный
//      по форме — «сервер не ответил, молча разумно».
//   2. `setInterval` на десять минут при этом оставался включённым и стучал
//      гарантированным отказом, пока игрок в мире.
//
// Проверка ловит именно форму поломки, а не конкретное слово: любой ручной
// `fetch` в напоминании и любой вызов без `characterId` роняют набор.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

// Код без комментариев: и одиночных строк, и блоков /* */.
//
// ЗАЧЕМ ИМЕННО ТАК. Первая версия этого файла искала `if (!res.ok) return` по
// всему исходнику — и попадала в КОММЕНТАРИЙ, где этот кусок кода цитируется как
// «что было». Проверка падала сама на правильном коде: объяснение, стоящее выше,
// снова попало в проверку. Тот же класс ошибки, что в §142 и в стороже скелетных
// габаритов, - и он же повторился здесь в третий раз.
function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const НАПОМИНАНИЕ = читать('client/src/app/voteReminder.ts');
const КЛИЕНТ = читать('client/src/app/api.ts');
const МИР = читать('client/src/app/world.ts');
const ТОЛЬКО_КОД = код(НАПОМИНАНИЕ);
const ТОЛЬКО_КОД_КЛИЕНТА = код(КЛИЕНТ);
const ТОЛЬКО_КОД_МИРА = код(МИР);

describe('Напоминание о голосовании', () => {
  it('запрос собирается общим клиентом, а не руками', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Ручной fetch - это и есть поломка: в нём токен
    // достаётся руками, идентификатор забывается, и сервер отвечает отказом,
    // который клиент глотает. Общий клиент api.ts ставит и токен, и адрес по
    // одному правилу, поэтому забыть в нём нечего.
    должен(
      !/\bfetch\s*\(/.test(ТОЛЬКО_КОД),
      'напоминание снова собирает запрос руками: токен и идентификатор разъедутся',
    );
    должен(
      /api\.voteStatus\s*\(/.test(ТОЛЬКО_КОД),
      'напоминание не идёт через общий клиент: маршрут уехал из-под проверки',
    );
    должен(
      /voteStatus:\s*\(characterId:\s*string\)/.test(ТОЛЬКО_КОД_КЛИЕНТА),
      'в общем клиенте нет маршрута статуса голосования: напоминание снова повесит ручной запрос',
    );
  });

  it('в маршрут уходит characterId, а не только заголовок', () => {
    // Именно его не хватало. Сервер отвечает `400 Missing characterId`, а не
    // «нет доступа», поэтому по симптому это выглядит как «сервер не отвечает».
    должен(
      /vote\/status\?characterId=\$\{characterId\}/.test(ТОЛЬКО_КОД_КЛИЕНТА),
      'маршрут статуса голосования уходит без characterId: сервер вернёт 400',
    );
  });

  it('персонаж передаётся при старте, а не берётся из воздуха', () => {
    // Идентификатор берётся у того же входа в мир, который его и имеет.
    должен(
      /startVoteReminder\(\)\s*;/.test(ТОЛЬКО_КОД_МИРА) === false,
      'напоминание снова стартует без персонажа: запрос уйдёт без characterId',
    );
    должен(
      /startVoteReminder\(\s*character\.id\s*\)/.test(ТОЛЬКО_КОД_МИРА),
      'вход в мир не передаёт персонажа в напоминание',
    );
    должен(
      /export function startVoteReminder\(characterId:\s*string\)/.test(ТОЛЬКО_КОД),
      'функция старта не принимает персонажа: идентификатор взять неоткуда',
    );
  });

  it('отказ сервера не выглядит как «напоминание не нужно»', () => {
    // Прежний код глотал 400 через `if (!res.ok) return;`, и это выглядело как
    // разумное молчание. Теперь отказ ловится явно, и функция не решает по нему,
    // что голосование закрыто.
    должен(
      !/if\s*\(\s*!res\.ok\s*\)\s*return/.test(ТОЛЬКО_КОД),
      'отказ сервера снова выглядит как «напоминать нечего»',
    );
    должен(
      /catch\s*\{/.test(ТОЛЬКО_КОД),
      'отказ сервера ничем не ловится: исключение уйдёт наружу и уронит таймер',
    );
  });
});