// Динамические семейства ключей: подстрочный поиск объявляет их мёртвыми.
//
// ЗАЧЕМ. Наивный пересчёт «ключ не найден подстрокой -> мёртв» даёт по этому
// проекту 270 мёртвых пути. Большинство из них ложные: ключи собираются из
// переменной, и подстроки в коде нет. Например:
//   t(`world.combat_error_${code}`)   - 17 ключей;
//   t(`errors.${code}`)               - 31 ключ;
//   t(`panels.diff_${сложность}`)     - 4 ключа (мои, из лимитов подземелий);
//   t(`classes.${characterClass}`)    - 10 ключей;
//   `reputation.rank.${ранг}`         - 24 ключа;
//   `worldclock.${...}`               - 19 ключей.
// Удаление по такому списку стёрло бы живые подписи.
//
// ЧТО ЗАЩИЩАЕТСЯ. Не «в коде есть шаблон», а то, что семейство ВЕДЁТСЯ от
// настоящего перечня: список кодов ошибок боя, список рангов репутации, список
// классов. Если перечень и ключи разойдутся, часть семейства станет мёртвой
// молча - и именно этого подстрочный поиск не покажет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ru = читать('shared/locales/ru.json') as unknown as Record<string, Record<string, unknown>>;
const json = JSON.parse(ru as unknown as string);

/** Семейство: где ключ собирается и каким перечнем это оправдано. */
const СЕМЕЙСТВА = [
  {
    // Боевые ошибки: путь ключа лежит ЛИТЕРАЛОМ в shared/combatErrors.ts,
    // а клиент зовёт t(карта[code]) - то есть подстрочный поиск по клиенту
    // этих пути не видит. Предыдущий пересчёт поэтому объявил все 17
    // боевых ошибок мёртвыми, просканировав только client/. Настоящая
    // проверка - не «путь где-то встречается», а «у каждого кода есть
    // перевод», и её роль играет тест ниже.
    имя: 'world.combat_error_*',
    шаблон: /'world\.combat_error_[a-z_]+'/,
    где: 'shared/combatErrors.ts',
    перечень: /isCombatErrorCode/,
    ключейВСловаре: (Object.keys(json.world) as string[]).filter((k) => k.startsWith('combat_error_')).length,
  },
  {
    имя: 'errors.*',
    шаблон: /t\(`errors\.\$\{/,
    где: 'client/src/app/hud.ts',
    // Коды шлёт сервер: перечень - вид effect, его в словаре нет. Проверяем
    // обратное: что словарь не больше того, что способен выдать сервер.
    перечень: /code: '([a-z_]+)'/,
    ключейВСловаре: (Object.keys(json.errors) as string[]).length,
  },
  {
    имя: 'panels.diff_*',
    шаблон: /t\(`panels\.diff_\$\{/,
    где: 'client/src/app/panels.ts',
    // Перечень - DIFFICULTY_SCALING в данных подземелий.
    перечень: /export const DIFFICULTY_SCALING/,
    ключейВСловаре: (Object.keys(json.panels) as string[]).filter((k) => k.startsWith('diff_')).length,
  },
] as const;

describe('Динамические семейства ключей: они живые, и это доказуемо', () => {
  it('у каждого семейства есть шаблонная сборка', () => {
    for (const семейство of СЕМЕЙСТВА) {
      const текст = читать(семейство.где);
      must(
        семейство.шаблон.test(текст),
        `${семейство.имя}: сборка из переменной не найдена в ${семейство.где} — ` +
          'подстрочный поиск объявил бы семейство мёртвым',
      );
    }
  });

  it('difficulty: словарь покрывает все сложности шкалы', () => {
    // Прямая связь «перечень -> ключи». Если в DIFFICULTY_SCALING добавят
    // сложность без ключа, игрок увидит в выпадающем списке пустое имя.
    const данные = stripComments(читать('server/src/data/dungeons.ts'));
    const сложности = [...данные.matchAll(/^\s{2}(normal|hard|heroic|mythic):\s*\{/gm)].map((m) => m[1]);
    must(сложности.length >= 4, `в шкале найдено сложностей: ${сложности.length}`);
    for (const кодЯзыка of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${кодЯзыка}.json`)) as {
        panels: Record<string, string>;
      };
      for (const сложность of сложности) {
        must(
          словарь.panels?.[`diff_${сложность}`],
          `в ${кодЯзыка}.json нет panels.diff_${сложность}: игрок увидит пустое имя сложности`,
        );
      }
    }
  });

  it('боевые ошибки: ключи словаря покрыты перечнем кодов', () => {
    // Карта в shared/combatErrors.ts связывает код сервера с путём ключа.
    // Каждый путь обязан иметь перевод во всех трёх языках: сервер шлёт код
    // при отказе удара, и без перевода игрок видит сырой путь.
    const ошибки = читать('shared/combatErrors.ts');
    const пути = [...ошибки.matchAll(/'(world\.combat_error_[a-z_]+)'/g)].map((m) => m[1]);
    must(пути.length >= 15, `в карте боевых ошибок пути: ${пути.length}`);
    for (const кодЯзыка of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${кодЯзыка}.json`)) as {
        world: Record<string, string>;
      };
      for (const путь of пути) {
        const имя = путь.slice('world.'.length);
        must(
          typeof словарь.world?.[имя] === 'string' && словарь.world[имя].length > 0,
          `в ${кодЯзыка}.json нет ${путь}: игрок увидит путь ключа при отказе удара`,
        );
      }
    }
  });

  it('подстрочный поиск не пригоден для решения об удалении', () => {
    // Эта проверка существует, чтобы следующий проход не сделал то, что чуть не
    // сделал этот: не побежал удалять 270 пути, объявленных мёртвыми поиском.
    // Настоящий источник - AST-разбор t(), как в gameI18n.test.ts.
    const всего = Object.keys(json).length;
    must(всего > 20, `секций в словаре: ${всего}: он не прочитан`);
    const динамических = СЕМЕЙСТВА.reduce((все, с) => все + с.ключейВСловаре, 0);
    must(
      динамических >= 50,
      `динамических ключей всего ${динамических}: перечень семейств устарел`,
    );
  });
});