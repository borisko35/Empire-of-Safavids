// Мастера в интерьерах: станок без ткача — это витрина, а не мастерская.
//
// ЧТО БЫЛО (22 октября 2026, §316). Интерьеры были обставлены, но пусты:
// станок стоял без ткача, наковальня без кузнеца, конюшня без конюха.
// Игрок заходил в мастерскую и не видел никого, кто там работает.
//
// ЧТО ТЕПЕРЬ. Пять мастеров: кузнец у наковальни с молотом, ткач у станка с
// корзиной пряжи, конюх с вёдрами, астроном у карты, исследователь у колб.
// У кузнеца ещё и горн с раскалённым зевом.
//
// ЧТО ПРОВЕРЯЕТСЯ. Пять фигур на своих местах, у кузнеца — молот, у конюха —
// вёдра, у ткача — корзина; астроном в тюрбане, исследователь в капюшоне.
// Проверки ищут по телу нужной функции, а не «где-нибудь в файле»: иначе
// откат уходит не туда.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

/** Тело функции: от её заголовка до следующей функции на верхнем уровне. */
function тело(имя: string): string {
  const начало = ИНТЕРЬЕРЫ.indexOf(`function ${имя}(`);
  должен(начало >= 0, `в interiors.ts нет функции ${имя}`);
  const конец = ИНТЕРЬЕРЫ.indexOf('\nfunction ', начало + 1);
  return ИНТЕРЬЕРЫ.slice(начало, конец < 0 ? ИНТЕРЬЕРЫ.length : конец);
}

describe('Мастера в интерьерах', () => {
  it('помощник ставит фигуру на пол и поворачивает её', () => {
    const помощник = тело('мастер');
    должен(/buildHumanoid\(cfg\)/.test(помощник), 'помощник не строит фигуру');
    должен(/FLOOR_Y/.test(помощник), 'помощник не ставит фигуру на пол');
    должен(/rotation\.y = поворот/.test(помощник), 'помощник не поворачивает фигуру');
    должен(/g\.add\(фигура\.group\)/.test(помощник), 'помощник не добавляет фигуру в комнату');
  });

  it('кузнец у наковальни с молотом, рядом горн', () => {
    const мастерская = тело('furnishWorkshop');
    должен(/мастер\(g, cx, cz, 1\.5, -1\.8, -Math\.PI \/ 2, \{/.test(мастерская), 'кузнец не стоит у наковальни');
    должен(/предмет: ПРЕДМЕТ.молот/.test(мастерская), 'у кузнеца нет молота');
    // Горн: каменная очаговая и раскалённый зев.
    должен(/box\(1\.8, 1\.2, 1\.4, M\.stone, cx - 7\.5, FLOOR_Y \+ 0\.6, cz - 5\.5\)/.test(мастерская), 'в мастерской нет горна');
    должен(/box\(0\.9, 0\.5, 0\.3, M\.gold, cx - 7\.5, FLOOR_Y \+ 0\.55, cz - 4\.9\)/.test(мастерская), 'у горна нет раскалённого зева');
  });

  it('ткач у станка с корзиной пряжи', () => {
    const ткацкая = тело('furnishWeaver');
    должен(/мастер\(g, cx, cz, 0, -5\.6, Math\.PI, \{/.test(ткацкая), 'ткач не стоит у станка');
    должен(/предмет: ПРЕДМЕТ.корзина/.test(ткацкая), 'у ткача нет корзины с пряжей');
  });

  it('конюх в конюшне с вёдрами', () => {
    const конюшня = тело('furnishStable');
    должен(/мастер\(g, cx, cz, -3\.4, 2\.2, -Math\.PI \/ 2, \{/.test(конюшня), 'конюха нет в конюшне');
    должен(/предмет: ПРЕДМЕТ.вёдра/.test(конюшня), 'у конюха нет вёдер');
  });

  it('астроном у карты и исследователь у колб', () => {
    const обсерватория = тело('furnishObservatory');
    должен(/мастер\(g, cx, cz, -5\.4, 2\.0, 0, \{/.test(обсерватория), 'астронома нет у карты');
    должен(/hat: 'turban'/.test(обсерватория), 'астроном без тюрбана');
    const наука = тело('furnishScience');
    должен(/мастер\(g, cx, cz, -2\.2, 2\.6, Math\.PI \/ 2, \{/.test(наука), 'исследователя нет у колб');
    должен(/hat: 'hood'/.test(наука), 'исследователь без капюшона');
  });
});
