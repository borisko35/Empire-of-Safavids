// Факелы у ворот караван-сарая.
//
// Двадцатый пакет из Assets. Первый пакет с картами внутри: пламя
// antorcha_tx2.png на 24 мегапикселя и дерево madera.jpg.
//
// ЧТО ЛОВИТСЯ И ПОЧЕМУ ТАК.
// 1. Файл в сборке и совпадает с манифестом.
// 2. Модель в метрах: 10.7 см вместо 27.3 см означает, что масштаб не
//    применён и факел приехал свечой.
// 3. Рост ручного факела: 0.2-0.4 м. Ниже — свеча, выше — факель на шесте.
// 4. Ширина факела 0.08-0.14 м. Шире — это уже костёр, у́же — палка.
// 5. Основанием на ноль, а не висящим и не ушедшим под землю.
// 6. Текстуры внутри: пламя и дерево. Без карт факел был бы серым пузырём.
// 7. Карты не мельче 512 и не крупнее 2048: 6016 это сто раз больше нужного.
// 8. Без скелета и анимации.
// 9. В узлах нет поворота, масштаба и сдвига: иначе по файлу нельзя сказать,
//    куда модель встанет.
// 10. Пять частей: древко, пламя снаружи, пламя внутри, чаша, ободок. Меш
//     разбит по материалам, и чтение одного примитива видело бы только
//     древку в 15 см и объявляло факел готовым без пламени.
// 11. Пламя есть и оно самое высокое: верхняя часть — огонь, а не палка.
// 12. Мир строит факелы.
// 13. По одному коллайдеру на факел, и он не шире пламени втрое.
// 14. Ровно два факела, симметрично относительно ворот.
// 15. Оба в проёме ворот и оба перед стеной двора.
// 16. Не в коллайдере стены и не в коллайдере ворот.
// 17. Факелы утоплены: основание ниже земли, а не стоит на древке.
