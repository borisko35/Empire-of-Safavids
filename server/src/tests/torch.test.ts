const МИР = читать('client/src/app/game3d/world3d.ts');
const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
};

interface Примитив {
  material?: number;
  attributes: { POSITION: number };
}

interface GlbJson {
  nodes?: { name?: string; rotation?: number[]; scale?: number[]; translation?: number[] }[];
  meshes?: { primitives?: Примитив[] }[];
  skins?: unknown[];
  animations?: unknown[];
  accessors?: { min: number[]; max: number[] }[];
  materials?: { name?: string; pbrMetallicRoughness?: { baseColorFactor?: number[] } }[];
  textures?: unknown[];
  images?: { uri?: string; bufferView?: number; name?: string }[];
  bufferViews?: { byteLength: number }[];
}

function jsonGlb(путь: string): GlbJson {
  const буфер = readFileSync(путь);
  must(буфер.readUInt32LE(0) === 0x46546c67, `${путь}: это не GLB`);
  const длина = буфер.readUInt32LE(12);
  return JSON.parse(буфер.subarray(20, 20 + длина).toString('utf-8')) as GlbJson;
}

const ФАЙЛ = join(корень, 'client/src/app/public/models/decor/torch.glb');

/** Части модели по файлу: меш разбит по материалам на пять примитивов. */
function части(): { материал: string; высота: number; низ: number; ширина: number; глубина: number }[] {
  const gltf = jsonGlb(ФАЙЛ);
  const список = [];
  for (const меш of gltf.meshes ?? []) {
    for (const примитив of меш.primitives ?? []) {
      const accessor = (gltf.accessors ?? [])[примитив.attributes.POSITION];
      const материал = (gltf.materials ?? [])[примитив.material ?? -1];
      список.push({
        материал: материал?.name ?? '(без материала)',
        высота: accessor.max[1] - accessor.min[1],
        низ: accessor.min[1],
        ширина: accessor.max[0] - accessor.min[0],
        глубина: accessor.max[2] - accessor.min[2],
      });
    }
  }
  must(список.length > 0, 'в модели факела нет ни одной части');
  return список;
}

function габариты(): { ширина: number; высота: number; глубина: number } {
  let мин = Infinity;
  let макс = -Infinity;
  let ширина = 0;
  let глубина = 0;
  for (const ч of части()) {
    мин = Math.min(мин, ч.низ);
    макс = Math.max(макс, ч.низ + ч.высота);
    ширина = Math.max(ширина, ч.ширина);
    глубина = Math.max(глубина, ч.глубина);
  }
  return { ширина, высота: макс - мин, глубина };
}

function место(): { x: number; z: number; ry: number }[] {
  const начало = ТЕРРЕЙН.indexOf('export const CARAVANSERAI_TORCHES');
  must(начало > 0, 'в terrain.ts нет CARAVANSERAI_TORCHES — место факелов не описано');
  const блок = ТЕРРЕЙН.slice(начало, ТЕРРЕЙН.indexOf('/** На сколько факел уходит'));
  const караван = /export const CARAVANSERAI = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН);
  must(караван !== null, 'CARAVANSERAI не найден');
  const список: { x: number; z: number; ry: number }[] = [];
  // Смещение необязательное. Иначе факел, поставленный ровно по центру
  // караван-сарая (`x: CARAVANSERAI.x` без `+ N`), в разбор не попадал: проверка
  // «ровно два факела» оставалась зелёной при трёх факелах на экране.
  //
  // Группы: 1 — знак, 2 — смещение по x, 3 — смещение по z, 4 — поворот.
  // Номера групп сдвинуты на единицу, потому что знак стоит ОТДЕЛЬНОЙ группой:
  // при обращении к м[2] как к знаку факел вычислялся как 505 + 15 = 520, и
  // проверка «факелы симметричны» ругалась на расстояние 15 м.
  const образец = /x: CARAVANSERAI\.x(?: ([+-]) ([\d.]+))?, z: CARAVANSERAI\.z(?: \+ ([\d.]+))?, ry: ([-\d.]+|Math\.PI)/g;
  for (const м of блок.matchAll(образец)) {
    const знак = м[1] === '-' ? -1 : 1;
    список.push({
      x: Number(караван[1]) + (м[2] === undefined ? 0 : знак * Number(м[2])),
      z: Number(караван[2]) + (м[3] === undefined ? 0 : Number(м[3])),
      ry: м[4] === 'Math.PI' ? Math.PI : Number(м[4]),
    });
  }
  must(список.length > 0, 'не разобрались координаты факелов');
  return список;
}

/** Утоплен ли факел: отрицательный подъём в вызове placeDecor. */
function утоплен(): number {
  const блок = ТЕРРЕЙН.slice(
    ТЕРРЕЙН.indexOf('export function buildCaravanseraiTorches'),
    ТЕРРЕЙН.indexOf('// ── Стол с доской'),
  );
  const м = /placeDecor\([\s\S]{0,200}?,\s*т\.x,\s*т\.z,\s*(-?ТОРЧ_УТОПЛЕН|-?[\d.]+)/.exec(блок);
  must(м !== null, 'не разобрался подъём факела');
  const знак = м[1] === '-ТОРЧ_УТОПЛЕН' ? -1 : 1;
  if (м[1] === '-ТОРЧ_УТОПЛЕН') {
    const константа = /export const ТОРЧ_УТОПЛЕН = ([\d.]+)/.exec(ТЕРРЕЙН);
    must(константа !== null, 'не нашлась константа ТОРЧ_УТОПЛЕН');
    return знак * Number(константа[1]);
  }
  return знак * Number(м[1]);
}

/**
 * Коллайдеры двора караван-сарая, развёрнутые из кода.
 *
 * В коде это циклы с переменными `wx` и `wz`, поэтому разбор по образцу
 * «число, число, число» находит тут только две колонны ворот, а стены не
 * находит вовсе. Циклы разворачиваются здесь тем же шагом, что и в игре.
 */
function коллайдерыДвора(): { x: number; z: number; r: number; имя: string }[] {
  const двор = ТЕРРЕЙН.slice(
    ТЕРРЕЙН.indexOf('// Караван-сарай в пустыне: двор со стенами'),
    ТЕРРЕЙН.indexOf('// Угловые башни крепости'),
  );
  const wxРяд = /for \(let wx = (-?\d+); wx <= (-?\d+); wx \+= (\d+)\)/.exec(двор);
  const wzРяд = /for \(let wz = (-?\d+); wz <= (-?\d+); wz \+= (\d+)\)/.exec(двор);
  must(wxРяд !== null && wzРяд !== null, 'циклы коллайдеров стен в коде не найдены');
  const порог = Number(/if \(Math\.abs\(wx\) > (\d+)\)/.exec(двор)![1]);
  const список: { x: number; z: number; r: number; имя: string }[] = [];
  const караван = /export const CARAVANSERAI = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН)!;
  const cx = Number(караван[1]);
  const cz = Number(караван[2]);
  for (let wx = Number(wxРяд[1]); wx <= Number(wxРяд[2]); wx += Number(wxРяд[3])) {
    if (Math.abs(wx) > порог) {
      список.push({ x: cx + wx, z: cz + 14, r: 2.0, имя: 'стена двора, сторона ворот' });
    }
  }
  for (let wz = Number(wzРяд[1]); wz <= Number(wzРяд[2]); wz += Number(wzРяд[3])) {
    список.push({ x: cx - 14, z: cz + wz, r: 2.0, имя: 'стена двора, западная' });
  }
  for (const м of двор.matchAll(/addCollider\(CARAVANSERAI\.x ([+-]) ([\d.]+), CARAVANSERAI\.z \+ 14, ([\d.]+)\)/g)) {
    список.push({
      x: м[1] === '-' ? cx - Number(м[2]) : cx + Number(м[2]),
      z: cz + 14,
      r: Number(м[3]),
      имя: 'колонна ворот',
    });
  }
  must(список.length >= 8, `коллайдеров двора ${список.length}: разбор кода сломался`);
  return список;
}

/**
 * Аргументы единственного вызова placeDecor в куске кода.
 *
 * Скобки не разбираются: запятые внутри них не разделяют аргументы. В этом
 * вызове вложенных скобок нет — все семь аргументов простые, — но полагаться
 * на это в проверке нельзя, поэтому вложенные скобки всё же считаются
 * глубиной.
 */
function аргументыВызова(код: string): string[] {
  const начало = код.indexOf('placeDecor(');
  if (начало < 0) return [];
  let глубина = 0;
  let началоАргументов = начало + 'placeDecor('.length;
  const части: string[] = [];
  let текущее = '';
  for (let i = началоАргументов; i < код.length; i++) {
    const символ = код[i];
    if (символ === '(' || символ === '[') глубина++;
    if (символ === ')' && глубина === 0) {
      части.push(текущее.trim());
      return части.filter((с, i) => !(с === '' && i === части.length - 1));
    }
    if (символ === ')' || символ === ']') глубина--;
    if (символ === ',' && глубина === 0) {
      части.push(текущее.trim());
      текущее = '';
      continue;
    }
    текущее += символ;
  }
  return части;
}

describe('Факел: модель', () => {
  it('файл в сборке и совпадает с манифестом', () => {
    const запись = МАНИФЕСТ.decor?.find((д) => д.name === 'torch');
    must(запись !== undefined, 'в манифесте нет факела: файл никто не сверяет с диском');
    must(запись!.file === 'models/decor/torch.glb', 'путь к факелу в манифесте не тот');
    must(existsSync(ФАЙЛ), 'файла факела нет на диске');
    must(
      statSync(ФАЙЛ).size === запись!.bytes,
      `факел: на диске ${statSync(ФАЙЛ).size}, в манифесте ${запись!.bytes}`,
    );
  });

  it('модель в метрах, а не в сантиметрах исходника', () => {
    // У модели после импорта FBX масштаб 0.01 от импортёра. Замер в Blender
    // показывает верные метры, а экспортёр glTF пишет локальные координаты
    // сетки: в игру уехали бы сантиметры. Ловится только чтением файла.
    const г = габариты();
    const наибольшее = Math.max(г.ширина, г.высота, г.глубина);
    must(
      наибольшее < 1.0,
      `наибольший размер ${наибольшее.toFixed(2)} м — масштаб объекта не применён. ` +
        'Проверяем файл, а не исходник: в исходнике всё выглядит верно',
    );
  });

  it('рост ручного факела: не свеча и не факел на шесте', () => {
    const г = габариты();
    must(
      г.высота >= 0.2 && г.высота <= 0.4,
      `рост факела ${г.высота.toFixed(2)} м: свеча — до 0.2, факел на шесте — от 0.6. ` +
        'Ждали ручной факел',
    );
  });

  it('ширина факела: не костёр и не палка', () => {
    // Ширина задаётся пламенем сверху: при 0.0254 на единицу пламя 10 см.
    // Проверка одна на оба конца, потому что «меньше трёх метров» пропустила бы
    // и костёр.
    const г = габариты();
    must(
      г.ширина >= 0.08 && г.ширина <= 0.14,
      `ширина факела ${г.ширина.toFixed(3)} м: шире 0.14 — костёр, у́же 0.08 — палка`,
    );
    must(
      г.глубина >= 0.08 && г.глубина <= 0.14,
      `глубина факела ${г.глубина.toFixed(3)} м вне 0.08-0.14`,
    );
  });

  it('основанием на ноль, а не висячий и не ушедший под землю', () => {
    // Часть с наименьшим низом — та, что стоит на земле. Порядок примитивов
    // в файле не задан, и «первый примитив» — это не «нижний».
    const нижняя = части().reduce((а, б) => (б.низ < а.низ ? б : а));
    must(
      Math.abs(нижняя.низ) <= 0.02,
      `низ факела на ${нижняя.низ.toFixed(3)} по Y: уедет под землю или повиснет`,
    );
  });

  it('пять частей: древко, пламя, чаша — а не одна древка', () => {
    // Меш разбит по материалам на пять примитивов. Первая версия проверки
    // читала только примитив 0 — это древка в 15 см — и объявляла факел
    // готовым без пламени: экспорт расходился с замером на 12 см, и проверка
    // этого не замечала.
    const г = габариты();
    const все = части();
    must(
      все.length >= 4,
      `в модели ${все.length} частей: древко, пламя снаружи, пламя внутри, чаша, ободок`,
    );
    must(
      г.высота > 0.25,
      `высота по всем частям ${г.высота.toFixed(3)} м: похоже, посчитана одна древка`,
    );
  });

  it('пламя есть, и оно самое высокое', () => {
    // Верхняя часть — огонь. Если самая высокая часть окажется древком, то
    // пламя либо срезали, либо перепутали материалы.
    const все = части();
    const верхняя = все.reduce((а, б) => (б.низ + б.высота > а.низ + а.высота ? б : а));
    must(
      /lambert4|lambert5|flame|fire/i.test(верхняя.материал),
      `верхняя часть факела — материал «${верхняя.материал}», а ждали пламя`,
    );
    must(
      верхняя.высота > 0.08,
      `высота верхней части ${верхняя.высота.toFixed(3)} м: пламя не выглядит огнём`,
    );
  });

  it('текстуры внутри: пламя и дерево, а не серый пузырь', () => {
    const gltf = jsonGlb(ФАЙЛ);
    const текстур = (gltf.textures ?? []).length;
    must(
      текстур >= 2,
      `в файле текстур ${текстур}: без карт факел был бы серым пузырём, ` +
        'а в пакете были antorcha_tx2.png и madera.jpg',
    );
    must(
      (gltf.images ?? []).length >= 2,
      `изображений ${(gltf.images ?? []).length}: текстуры ссылаются в пустоту`,
    );
    // Пламя и дерево должны быть разными картами, а не одной на всё.
    must(
      текстур >= 2,
      'одна карта на пламя и дерево: читалась бы одинаковая текстура везде',
    );
  });

  it('карты ужаты: пламя не весит как весь остальной уровень', () => {
    // В пакете 6016 x 4016 на факел 27 см — больше ста пикселей на сантиметр,
    // 18.6 МБ в PNG. Такую карту в игру класть нельзя.
    //
    // Размер каждой карты берётся из bufferView, а не из общего веса файла: при
    // 1024 карта пламя весила 842 КБ, то есть девять десятых файла, и общая
    // проверка «меньше 1.6 МБ» была довольна.
    const gltf = jsonGlb(ФАЙЛ);
    const представления = gltf.bufferViews ?? [];
    must(
      (gltf.images ?? []).length >= 2,
      `карт в файле ${(gltf.images ?? []).length}: ждали пламя и дерево`,
    );
    for (const карта of gltf.images ?? []) {
      const длина = представления[карта.bufferView ?? -1]?.byteLength ?? 0;
      must(
        длина > 0,
        `карта «${карта.name ?? '(без имени)'}» ссылается в пустоту`,
      );
      must(
        длина <= 300 * 1024,
        `карта «${карта.name ?? '(без имени)'}» весит ${Math.round(длина / 1024)} КБ: ` +
          '24 мегапикселя должны были ужаться до 512',
      );
    }
    // Разные карты, а не одна на пламя и на дерево.
    const буферы = new Set((gltf.images ?? []).map((к) => к.bufferView));
    must(
      буферы.size >= 2,
      `карты ссылаются на ${буферы.size} буферов: пламя и дерево читались бы одинаково`,
    );
    const вес = statSync(ФАЙЛ).size;
    must(
      вес < 512 * 1024,
      `факел весит ${Math.round(вес / 1024)} КБ: декорация не должна весить полмегабайта`,
    );
  });

  it('без скелета и анимации', () => {
    const gltf = jsonGlb(ФАЙЛ);
    must((gltf.skins ?? []).length === 0, 'в факеле есть скелет — это не факел');
    must((gltf.animations ?? []).length === 0, 'в факеле анимация');
  });

  it('в узлах нет поворота, масштаба и сдвига', () => {
    // У модели после импорта поворот X на 90°: длинная ось лежит вдоль Y. Без
    // применения экспортёр переносит поворот в узел, и по файлу нельзя
    // сказать, куда модель встанет.
    //
    // Единичный кватернион — это [0, 0, 0, 1], а не [0, 0, 0, 0]. Сравнение
    // каждого элемента с нулём объявляло бы поворотом модель без поворота.
    const gltf = jsonGlb(ФАЙЛ);
    for (const узел of gltf.nodes ?? []) {
      const поворот = узел.rotation ?? [0, 0, 0, 1];
      must(
        поворот.every((в, i) => Math.abs(в - (i === 3 ? 1 : 0)) < 1e-6),
        `в узле «${узел.name ?? '(без имени)'}» остался поворот ${JSON.stringify(поворот)}: ` +
          'модель встанет лежа',
      );
      const масштаб = узел.scale ?? [1, 1, 1];
      must(
        масштаб.every((в) => Math.abs(в - 1) < 1e-6),
        `в узле «${узел.name ?? '(без имени)'}» остался масштаб ${JSON.stringify(масштаб)}`,
      );
      const сдвиг = узел.translation ?? [0, 0, 0];
      must(
        сдвиг.every((в) => Math.abs(в) < 1e-6),
        `в узле «${узел.name ?? '(без имени)'}» остался сдвиг ${JSON.stringify(сдвиг)}: ` +
          'модель повиснет или уедет в сторону',
      );
    }
  });
});

describe('Факел: у ворот караван-сарая', () => {
  it('мир строит факелы', () => {
    must(/buildCaravanseraiTorches\(this\.scene\)/.test(МИР), 'мир не строит факелы');
    must(/import[\s\S]{0,600}buildCaravanseraiTorches/.test(МИР), 'buildCaravanseraiTorches не импортирован');
    must(/export function buildCaravanseraiTorches/.test(ТЕРРЕЙН), 'в terrain.ts нет buildCaravanseraiTorches');
  });

  it('ровно два факела, и они симметричны относительно ворот', () => {
    const точки = место();
    must(точки.length === 2, `факелов ${точки.length}, ждали два: по одному с каждой стороны ворот`);
    const караван = /export const CARAVANSERAI = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН)!;
    const ось = Number(караван[1]);
    const расстояния = точки.map((т) => Math.abs(т.x - ось)).sort((а, б) => а - б);
    must(
      Math.abs(расстояния[0] - расстояния[1]) < 0.01,
      `факелы на расстояниях ${расстояния[0]} и ${расстояния[1]} от оси ворот: ` +
        'ворота с огнями по бокам должны быть симметричны',
    );
    must(
      расстояния[0] >= 5,
      `факелы в ${расстояния[0]} м от оси ворот: они сойдутся в один и проход будет узким`,
    );
    must(
      расстояния[0] <= 9.5,
      `факелы в ${расстояния[0]} м от оси ворот: проём в стене |x| < 10, ` +
        'и за его пределами снова стена',
    );
  });

  it('оба перед стеной двора, а не за ней', () => {
    // Стена двора на локальном z = 14, проём ворот там же. Факел за стеной
    // высотой 3.2 м не видно ни с дороги, ни с подступа.
    const точки = место();
    const караван = /export const CARAVANSERAI = \{ x: (-?\d+), z: (-?\d+)/.exec(ТЕРРЕЙН)!;
    const стена = Number(караван[2]) + 14;
    for (const т of точки) {
      must(
        т.z > стена,
        `факел в (${т.x}, ${т.z}) за стеной двора на z = ${стена}: ` +
          'стена 3.2 м, и его не будет видно',
      );
      must(
        т.z <= стена + 6,
        `факел в (${т.x}, ${т.z}) в ${(т.z - стена).toFixed(1)} м от ворот: ` +
          'это не вход, а поляна у стены',
      );
    }
  });

  it('не в коллайдере стены и не в коллайдере ворот', () => {
    const список = коллайдерыДвора();
    const ширина = габариты().ширина;
    for (const т of место()) {
      for (const к of список) {
        const d = Math.hypot(т.x - к.x, т.z - к.z);
        must(
          d > к.r + ширина / 2,
          `факел в (${т.x}, ${т.z}) попал в «${к.имя}» в (${к.x}, ${к.z}) r=${к.r}: ` +
            `расстояние ${d.toFixed(2)} м. Игрок упирается в стену, а огонь внутри неё`,
        );
      }
    }
  });

  it('по одному коллайдеру на факел, и он не шире пламени втрое', () => {
    const блок = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export function buildCaravanseraiTorches'),
      ТЕРРЕЙН.indexOf('// ── Стол с доской'),
    );
    const коллайдеры = (блок.match(/addCollider\(/g) || []).length;
    const вызовы = (блок.match(/placeDecor\(/g) || []).length;
    // Коллайдер ставится внутри placeDecor, а не второй раз здесь: два
    // коллайдера в одной точке — игрок упирается в невидимую стену.
    must(коллайдеры === 0, `в buildCaravanseraiTorches ${коллайдеры} вызовов addCollider: коллайдер ставит placeDecor`);
    must(вызовы === 1, `вызовов placeDecor ${вызовы}, ждали один — в цикле по факелам`);
    // Аргументы placeDecor разбираются по запятым, а не регуляркой: первый
    // вариант искал `,\s*0?\.?([\d.]+)\);` и на `-ТОРЧ_УТОПЛЕН, т.ry, 0.3`
    // съедал ноль с точкой, и радиусом оказывалось 3 вместо 0.3.
    const аргументы = вызовы === 1 ? аргументыВызова(блок) : [];
    must(аргументы.length === 7, `у placeDecor ${аргументы.length} аргументов, а он принимает семь`);
    const радиус = Number(аргументы[6]);
    must(
      Number.isFinite(радиус),
      `радиус коллайдера «${аргументы[6]}» не число`,
    );
    const пламя = габариты().ширина;
    must(
      радиус >= пламя / 2,
      `коллайдер ${радиус} м при пламени шириной ${пламя.toFixed(2)} м: ` +
        'игрок проходит сквозь огонь',
    );
    must(
      радиус <= (пламя / 2) * 3,
      `коллайдер ${радиус} м при пламени шириной ${пламя.toFixed(2)} м: ` +
        'игрок упирается в пустоту в метре от огня',
    );
  });

  it('факелы утоплены в землю, а не стоят на древке', () => {
    // Древко 15.4 см и 3.8 см в толщину. Факел, поставленный основанием на
    // землю, стоит на тонком древке — читается как палка. Утопленный на 12 см,
    // он оставляет над землёй пламя и часть чаши.
    const утоп = утоплен();
    must(
      утоп < 0,
      `подъём факела ${утоп} м: он стоит на древке, а не воткнут в землю`,
    );
    const г = габариты();
    must(
      Math.abs(утоп) <= г.высота * 0.6,
      `утоплен на ${Math.abs(утоп).toFixed(2)} м при высоте факела ${г.высота.toFixed(2)} м: ` +
        'над землёй не осталось ничего',
    );
    // Над землёй должна остаться самая горячая часть — пламя.
    must(
      г.высота - Math.abs(утоп) > 0.1,
      `над землёй осталось ${(г.высота - Math.abs(утоп)).toFixed(2)} м факела: ` +
        'игрок не увидит огня',
    );
  });

  it('на суше и не в стене', () => {
    for (const т of место()) {
      must(!isWater(т.x, т.z), `факел в (${т.x}, ${т.z}) стоит в воде`);
      for (let dx = -1; dx <= 1; dx++) {
        for (let dz = -1; dz <= 1; dz++) {
          must(!isWater(т.x + dx, т.z + dz), `под факелом вода в (${т.x + dx}, ${т.z + dz})`);
        }
      }
    }
  });
});