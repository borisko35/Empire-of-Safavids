// Удар стража: правило живое, последствия настоящие, обратная связь видна.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ЭТОЙ ПРОВЕРКИ. Поле guardAttack было объявлено в
// таблице последствий кармы (server/src/systems/KarmaSystem.ts) у рангов
// «красный» и «изгой» и не читалось НИГДЕ: поиск по всему серверу давал только
// само объявление поля. Стражи в шагах 1-3 стелса умели замечать игрока, но не
// бить. То есть город обещал тёмному игроку последствие, а наказывать было
// некому - тот же класс, что с сундуками в гробнице и с потерей золота при
// смерти: данные написаны, игры за ними нет.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, ПО ПОРЯДКУ ЧТЕНИЯ:
//   1. числа удара - те, что выбрал владелец, а не круглые;
//   2. правило бьёт того, кого видно и достают;
//   3. стелс действительно спасает: ночью в бураю стража не видно;
//   4. два стража рядом не дают двух ударов (измерено: посты в 7 и 11.7);
//   5. стража бьёт красного и изгоя, а хаотичного не бьёт;
//   6. карма за удар - то же число, что в правиле удара, а не второе;
//   7. наказание ограничено и выход из него существует;
//   8. сервер действительно зовёт правило, читает кулдаун по игроку и шлёт
//      удар тем же каналом, что и удар монстра;
//   9. клиент показывает, кто ударил и на сколько упала карма.
//
// ПОЧЕМУ ПРОВЕРКА СЧИТАЕТ ЧИСЛА, А НЕ ИЩЕТ СТРОКУ. Поиск строки
// "strikingGuard" доказал бы, что строка есть, и ничего больше: радиус можно
// испортить числом в другом месте, и проверка осталась бы зелёной. Здесь
// функция вызывается по-настоящему, а утверждения - про расстояния и про
// границы.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  GUARD_POSTS, GUARD_STRIKE, GUARD_SIGHT, strikingGuard,
  type GuardPost,
} from '../../../shared/stealth';
import {
  KARMA_EVENTS, KARMA_PENALTIES, getKarmaStatus, isGuardTarget,
} from '../systems/KarmaSystem';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Карма, дающая каждый ранг. Границы берутся из самого getKarmaStatus, а не
// выдумываются: иначе проверка считала бы не тот случай, который в игре.
const кармаСтатуса = {
  saint: 6000,
  good: 2000,
  neutral: 0,
  chaotic: -1000,
  red: -3000,
  outlaw: -7000,
} as const;

// Числа правила widened до number. Без этого TypeScript сравнивает литералы на
// этапе сборки: правка баланса роняла бы набор ошибкой компиляции, а правило
// проекта требует, чтобы проверка падала ПО ИМЕНИ ТЕСТА. С number сравнение
// остаётся проверкой времени выполнения.
const урон = GUARD_STRIKE.DAMAGE as number;
const кулдаун = GUARD_STRIKE.COOLDOWN_MS as number;
const кармаЗаУдар = GUARD_STRIKE.KARMA as number;

// Пост, который точно существует: привратник у ворот столицы. Он же патрульный,
// поэтому в проверках границ его не используем - только стоящие.
function постПоId(id: string): GuardPost {
  const найден = GUARD_POSTS.find((p) => p.id === id);
  must(найден, `поста ${id} нет в GUARD_POSTS: проверка считала бы несуществующую точку`);
  return найден!;
}

describe('Удар стража: числа', () => {
  it('урон, кулдаун и карма — те, что выбрал владелец', () => {
    // Решение владельца от 04.10.2026: 60 урона раз в 2 секунды, минус 100
    // кармы за удар. Проверка фиксирует именно эти числа, чтобы смена баланса
    // была осознанным изменением с именем теста, а не тихой правкой.
    must(урон === 60, `урон стража ${урон}, а решён 60`);
    must(кулдаун === 2000, `кулдаун ${кулдаун} мс, а решён 2000`);
    must(кармаЗаУдар === -100, `карма за удар ${кармаЗаУдар}, а решён минус 100`);
    must(
      GUARD_STRIKE.REACH > 0 && GUARD_STRIKE.REACH < GUARD_SIGHT,
      `радиус удара ${GUARD_STRIKE.REACH} при обзоре ${GUARD_SIGHT}: если радиус не меньше ` +
        'обзора, правило "страж бьёт того, кого видит" ничего не ограничивает, а если он ' +
        'нулевой - стража не достаёт ни до кого',
    );
  });

  it('кулдаун совпадает с периодом тика ИИ', () => {
    // Тик ИИ идёт раз в 2 секунды (AI_TICK_EVERY = 2 при TICK_INTERVAL_MS = 1000
    // в GameLoop). Если кулдаун будет короче тика, часть ударов просто не
    // досчитывается: правило врёт о частоте, а игрок этого не видит.
    const цикл = читать('server/src/systems/GameLoop.ts');
    const интервал = /const TICK_INTERVAL_MS = (\d+);/.exec(цикл);
    const каждые = /const AI_TICK_EVERY = (\d+);/.exec(цикл);
    must(интервал && каждые, 'в GameLoop нет TICK_INTERVAL_MS или AI_TICK_EVERY');
    const период = Number(интервал![1]) * Number(каждые![1]);
    must(
      кулдаун >= период,
      `кулдаун ${кулдаун} мс короче тика ИИ ${период} мс: удары ` +
        'выпадали бы между тиками и считывались бы неверно',
    );
  });
});

describe('Удар стража: правило бьёт того, кого достают', () => {
  it('стоит рядом со стражем — удар есть', () => {
    const пост = постПоId('npc_guard_east');
    const цель = { x: пост.x + 5, z: пост.z };
    const бьёт = strikingGuard(цель, [пост], {}, 0);
    must(бьёт, `игрок в 5 единицах от стража не получил удара: радиус ${GUARD_STRIKE.REACH}`);
    must(
      бьёт!.id === пост.id,
      `ударил ${бьёт!.id}, а стоял ${пост.id}: правило бьёт не тем постом`,
    );
  });

  it('на границе радиуса удар ещё есть, за ней уже нет', () => {
    const пост = постПоId('npc_guard_west');
    const ровно = strikingGuard({ x: пост.x + GUARD_STRIKE.REACH, z: пост.z }, [пост], {}, 0);
    must(ровно, `ровно на радиусе ${GUARD_STRIKE.REACH} удара нет: граница не включена`);
    const дальше = strikingGuard(
      { x: пост.x + GUARD_STRIKE.REACH + 0.5, z: пост.z },
      [пост], {}, 0,
    );
    must(!дальше, `на ${GUARD_STRIKE.REACH + 0.5} стража всё ещё достаёт: радиус не работает`);
  });

  it('далеко, но в обзоре — удара нет', () => {
    // Обзор 20, радиус удара 8. Игрок в 12 единицах прекрасно виден и должен
    // остаться в покое: иначе страж бьёт через полтора клинка.
    const пост = постПоId('npc_guard_east');
    const цель = { x: пост.x + 12, z: пост.z };
    must(
      strikingGuard(цель, [пост], {}, 0) === null,
      'страж ударил с 12 единиц: радиус удара не ограничен досягаемостью',
    );
  });

  it('один страж — один удар, даже когда в досягаемости двое', () => {
    // Измерено по GUARD_POSTS: привратник (60,32) и восточный стражник (54,42)
    // стоят в 11.66 единицах друг от друга, поэтому ровно посередине (57,37)
    // достают оба. Список постов не должен превращаться в два удара за раз.
    const привратник = постПоId('npc_guard_gate');
    const восточный = постПоId('npc_guard_east');
    const середина = {
      x: (привратник.x + восточный.x) / 2,
      z: (привратник.z + восточный.z) / 2,
    };
    const вДосягаемости = [привратник, восточный].filter(
      (p) => Math.hypot(середина.x - p.x, середина.z - p.z) <= GUARD_STRIKE.REACH,
    );
    must(
      вДосягаемости.length >= 2,
      `в досягаемости ${вДосягаемости.length} стража, а проверка считала двух: точка сместилась`,
    );
    const бьёт = strikingGuard(середина, GUARD_POSTS, {}, 0);
    must(бьёт, 'посередине между двумя стражами удара нет вовсе');
    must(
      typeof бьёт!.id === 'string',
      'правило вернуло не пост: из него нельзя взять имя для подписи',
    );
  });

  it('патрульный страж считается там, где он в этот момент', () => {
    // Привратник ходит между (60,32) и (52,26) за 16 секунд. Если бы правило
    // считало по началу маршрута, игрок у конца патруля получал бы удар в
    // пустоту. Поэтому момент времени задаётся явно: половина периода — это
    // ровно конец маршруля.
    const привратник = постПоId('npc_guard_gate');
    must(привратник.patrol, 'привратник перестал патрулировать: проверка ошибается адресно');
    const конец = { x: привратник.patrol!.toX, z: привратник.patrol!.toZ };
    const начало = { x: привратник.x, z: привратник.z };
    const вКонце = привратник.patrol!.periodMs / 2;

    must(
      strikingGuard(конец, [привратник], {}, вКонце) !== null,
      'у конца патруля стража нет рядом, хотя в этот момент он там стоит',
    );
    // В начале цикла он на 8.25 дальше от конца маршрута, чем радиус удара.
    must(
      strikingGuard(конец, [привратник], {}, 0) === null,
      'в начале патруля стража бьёт через весь маршрут: позиция считается не по времени',
    );
    must(
      strikingGuard(начало, [привратник], {}, 0) !== null,
      'на своей точке пост не достаёт до игрока, стоящего на ней',
    );
  });
});

describe('Удар стража: скрытность действительно спасает', () => {
  it('приседнего стража видит, но удар он всё равно получает', () => {
    // Приседание вдвое сокращает обзор: 20 -> 10. Радиус удара 8, так что
    // приседание само по себе от погони не спасает - и это правильно: у принцессы
    // нет времени прятаться, уйти из-под стража можно только ногами.
    const пост = постПоId('npc_guard_east');
    const цель = { x: пост.x + 5, z: пост.z };
    const стоя = strikingGuard(цель, [пост], {}, 0);
    const присев = strikingGuard(цель, [пост], { crouch: true }, 0);
    must(стоя && присев, 'приседание убрало удар стыка с радиусом 8: правило изменилось не по замыслу');
  });

  it('ночью в песчаной бураю стража не видно — удара нет', () => {
    // Ночь 0.5, буря 0.3: обзор 20 * 0.5 * 0.3 = 3. Игрок в 5 единицах от
    // стража попадает в зону поста (радиус 8), но ВНЕ обзора - и удара нет.
    // Ровно то, зачем владелец просил погодные множители в стелсе.
    //
    // Расстояние здесь важно: вплотную (2 единицы) стража всё равно видит, потому
    // что 2 меньше трёх. Проверка на 5 единицах ловит именно разрыв между
    // обзором и радиусом удара, а не «ночь отключает стражей вообще».
    const пост = постПоId('npc_guard_east');
    const цель = { x: пост.x + 5, z: пост.z };
    must(
      strikingGuard(цель, [пост], {}, 0) !== null,
      'днём на 5 единицах удара нет: расстояние взято неверно, проверка врёт о радиусе',
    );
    must(
      strikingGuard(цель, [пост], { night: 1, visibility: 0.3 }, 0) === null,
      'в ночную бурю стража бьёт с 5 единиц: множители обзора не участвуют в ударе',
    );
    // Сумерки без бури: обзор 20 * 0.75 = 15, до 5 единиц он дотягивается.
    must(
      strikingGuard(цель, [пост], { night: 0.5, visibility: 1 }, 0) !== null,
      'в сумерках стража перестал доставать: множитель ночи посчитан неверно',
    );
  });

  it('песчаная буря сокращает обзор стража, а не только картинку', () => {
    // visibilityMod = 0.3 у бури берётся из WEATHER_EFFECTS, и поле это было
    // объявлено и не читалось (о нём говорит weatherStealthConsumer). Здесь
    // проверяем, что цикл стражи берёт его из того же источника.
    const цикл = читать('server/src/systems/GameLoop.ts');
    must(
      /WEATHER_EFFECTS\[время\.weather\]\?\.visibilityMod/.test(цикл),
      'тик стражи не берёт видимость по погоде: буря не прячет игрока от удара',
    );
    must(
      /nightFactor\(время\.timeOfDay\)/.test(цикл),
      'тик стражи не считает ночь: ночью игрок остаётся на виду',
    );
  });
});

describe('Удар стража: кого он бьёт', () => {
  it('бьёт красного и изгоя', () => {
    must(isGuardTarget(-3000), 'красного стража не бьёт: город обещал наказание и не наказывает');
    must(isGuardTarget(-7000), 'изгоя стража не бьёт');
    must(KARMA_PENALTIES[getKarmaStatus(-3000)].guardAttack === true,
      'таблица последствий и функция isGuardTarget разошлись на красном');
    must(KARMA_PENALTIES[getKarmaStatus(-7000)].guardAttack === true,
      'таблица последствий и функция isGuardTarget разошлись на изгое');
  });

  it('хаотичного не бьёт', () => {
    // Граница ранга: хаотичный - карма от -500 до -2000. У него guardAttack
    // объявлен как false, и трогать его раньше порога нельзя.
    must(getKarmaStatus(-1000) === 'chaotic', '-1000 перестал быть хаотичным: проверка считает не тот ранг');
    must(isGuardTarget(-1000) === false,
      'стража бьёт хаотичного: наказание начинается раньше, чем обещано таблицей');
  });

  it('мирных не бьёт вообще', () => {
    for (const статус of ['saint', 'good', 'neutral'] as const) {
      must(KARMA_PENALTIES[статус].guardAttack === false,
        `${статус}: стража бьёт, а таблица обещает canBeAttacked = false`);
      must(isGuardTarget(кармаСтатуса[статус]) === false,
        `${статус}: функция isGuardTarget говорит, что стража бьёт`);
    }
  });
});

describe('Удар стража: карма', () => {
  it('за удар минус столько же, сколько в правиле удара', () => {
    // Одно число в одном месте. Если бы в таблице кармы стояло своё -100,
    // правило и последствия разошлись бы, и игрок получал бы не то, что
    // показывает интерфейс.
    must(
      KARMA_EVENTS.guard_strike === GUARD_STRIKE.KARMA,
      `в таблице кармы ${KARMA_EVENTS.guard_strike}, а в правиле удара ${GUARD_STRIKE.KARMA}: ` +
        'число разошлось в двух местах',
    );
    must(
      KARMA_EVENTS.guard_strike < 0,
      `за удар стража карма растёт (${KARMA_EVENTS.guard_strike}): город награждает за побои`,
    );
  });

  it('удар тяжелее монстра, но легче убийства мирного', () => {
    // Порядок величин таблицы по тяжести: убийство мирного -300, злой квест
    // -150, удар стража -100, убийство монстра -50. Удар стража тяжелее убийства
    // монстра (город наказывает тёмного) и легче убийства мирного (страж не
    // карает за PvP). Если бы порядок нарушился, пост отличил бы городскую
    // расправу от разбойничьей злобы.
    const тяжесть = (имя: string): number => Math.abs(KARMA_EVENTS[имя as keyof typeof KARMA_EVENTS]);
    must(
      тяжесть('pk_kill') > тяжесть('guard_strike'),
      `удар стража (${KARMA_EVENTS.guard_strike}) тяжелее убийства мирного ` +
        `(${KARMA_EVENTS.pk_kill}): это уже не наказание, а казнь`,
    );
    must(
      тяжесть('guard_strike') > тяжесть('npc_kill'),
      `удар стража (${KARMA_EVENTS.guard_strike}) легче убийства монстра ` +
        `(${KARMA_EVENTS.npc_kill}): город за городской порядок штрафует слабее, чем за бой с тварями`,
    );
    must(
      тяжесть('quest_evil') > тяжесть('guard_strike'),
      `удар стража (${KARMA_EVENTS.guard_strike}) тяжелее злого квеста ` +
        `(${KARMA_EVENTS.quest_evil}): порог слишком низкий`,
    );
  });

  it('наказание ограничено, а выход из него есть', () => {
    // Считаем на настоящих порогах ранга. Полоса красного по getKarmaStatus:
    // от -5000 до -2001. Хуже всего тому, кто только что в неё попал: с -2001
    // до изгоя (< -5000) нужно 30 ударов по 100, то есть ровно минута у поста.
    // Тому, кто уже на дне полосы (-4999), хватает одного удара.
    //
    // Эти числа важны вдвойне: раньше наказания не существовало вовсе, и вопрос
    // «а можно ли из этой ямы выбраться» был без ответа.
    function ударовДоИзгоя(откуда: number): number {
      let карма = откуда;
      let ударов = 0;
      while (getKarmaStatus(карма) === 'red' && ударов < 1000) {
        карма += KARMA_EVENTS.guard_strike;
        ударов++;
      }
      must(getKarmaStatus(карма) === 'outlaw', `с ${откуда} изгой не получается вовсе: яма бездонная`);
      return ударов;
    }

    must(getKarmaStatus(-2001) === 'red', '-2001 перестал быть красным: проверка считает не тот ранг');
    must(getKarmaStatus(-4999) === 'red', '-4999 перестал быть красным: проверка считает не тот ранг');
    // Порог изгоя включён в красного: -5000 ещё красный, -5001 уже изгой.
    must(getKarmaStatus(-5000) === 'red', '-5000 перестал быть красным: порог изгоя разошёлся');
    must(getKarmaStatus(-5001) === 'outlaw', '-5001 ещё не изгой: порог изгоя разошёлся');

    const сверху = ударовДоИзгоя(-2001);
    must(сверху === 30, `из верхней границы красного в изгоя уходит ${сверху} ударов, а проверка считала 30`);
    must(ударовДоИзгоя(-5000) === 1, 'у самого дна полосы требуется больше одного удара: полоса посчитана неверно');

    const секунд = Math.round((сверху * GUARD_STRIKE.COOLDOWN_MS) / 1000);
    must(
      секунд === 60,
      `на наказание уходит ${секунд} секунд вместо 60: кулдаун или величина удара разошлись с расчётом`,
    );
    // Выход: убийство красного возвращает карму. Проверяем, что он не слабее
    // удара стража, иначе яма бездонная.
    must(
      KARMA_EVENTS.pk_kill_red > 0,
      'убийство красного больше не возвращает карму: из-под стража не выйти',
    );
    must(
      KARMA_EVENTS.pk_kill_red >= Math.abs(KARMA_EVENTS.guard_strike),
      `убийство красного (${KARMA_EVENTS.pk_kill_red}) слабее удара стража ` +
        `(${KARMA_EVENTS.guard_strike}): выход медленнее наказания`,
    );
  });
});

describe('Удар стража: сервер действительно бьёт', () => {
  const цикл = читать('server/src/systems/GameLoop.ts');
  const сокет = читать('server/src/socket/GameSocketHandler.ts');
  const клиент = читать('client/src/app/world.ts');

  it('тик ИИ зовёт правило удара', () => {
    must(/strikingGuard\(/.test(цикл), 'GameLoop не зовёт strikingGuard: стража объявлена, но не бьёт');
    must(/await this\.tickGuards\(/.test(цикл), 'tickGuards написан, но из тика не вызывается');
  });

  it('цель выбирается по таблице последствий, а не по числу в коде', () => {
    // Дверь в таблицу последствий обязана быть именованной функцией рядом с
    // isNpcHostile: чтение KARMA_PENALTIES прямо из игрового цикла запрещено
    // проверкой karmaNpcHostile («таблица читается в одном месте»), и это
    // правильно - пороги ранга читаются из одного файла.
    const кармаСистема = читать('server/src/systems/KarmaSystem.ts');
    must(
      /export function isGuardTarget\(karma: number\): boolean \{[\s\S]{0,160}KARMA_PENALTIES\[getKarmaStatus\(karma\)\]\.guardAttack;/.test(кармаСистема),
      'в системе кармы нет функции «бьёт ли стража»: правило живёт в игровом цикле, а не в системе кармы',
    );
    must(
      /isGuardTarget\(/.test(цикл),
      'GameLoop не зовёт isGuardTarget: кого бить решается в обход таблицы последствий',
    );
    const безКомментариев = (исходник: string): string =>
      исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
    must(
      !/KARMA_PENALTIES/.test(безКомментариев(цикл)),
      'GameLoop читает таблицу последствий напрямую: правило «кого бьёт стража» живёт в двух местах',
    );
  });

  it('кулдаун держится на игроке, а не на страже', () => {
    // Кулдаун на посте дал бы два удара там, где стражей двое. Ключом должен
    // быть id игрока, а не id поста.
    must(
      /guardLastStrike\.set\(игрок\.id/.test(цикл),
      'время последнего удара пишется не по игроку: рядом с двумя стражами прилетит вдвое',
    );
    must(
      /guardLastStrike\.get\(игрок\.id/.test(цикл),
      'кулдаун читается не по игроку',
    );
    must(
      !/guardLastStrike\.set\(пост/.test(цикл),
      'кулдаун пишется по посту: два стража рядом дают два удара за раз',
    );
  });

  it('урон идёт через общую защиту цели, как у монстров', () => {
    must(
      /GUARD_STRIKE\.DAMAGE - защита/.test(цикл),
      'урон стража не вычитает защиту цели: броня бессмысленна против стража',
    );
    must(
      /getIncomingMultiplier\(игрок\.id\)/.test(цикл),
      'стража не спрашивает активную защиту: блок и уклонение не работают',
    );
  });

  it('уклонение отменяет и урон, и карму', () => {
    // За что не ударили, то и не берут. Иначе можно было бы уклоняться
    // бесконечно и платить только кармой.
    must(
      /applyKarmaEvent\(\s*игрок\.id, 'guard_strike'/.test(цикл),
      'карма за удар стража не применяется',
    );
    must(
      /if \(!уклонён\) \{\s*\n\s*\/\/ Регион/.test(цикл),
      'карма берётся даже при полном уклонении: можно уклоняться и не терять ничего',
    );
  });

  it('удар уходит тем же каналом, что и удар монстра', () => {
    must(
      /REGION_MONSTER_HIT/.test(цикл.slice(цикл.indexOf('private async tickGuards'))),
      'стража публикует удар не в тот канал, который слушает сокет-обработчик',
    );
    must(
      /guardStrike: true/.test(цикл) && /guardName: пост\.nameRu/.test(цикл),
      'удар стража идёт без отметки и без имени: клиент не поймёт, кто ударил',
    );
  });

  it('сокет-обработчик передаёт клиенту отметку, имя и потерю кармы', () => {
    must(
      /guardStrike: Boolean\(msg\.guardStrike\)/.test(сокет),
      'сокет не передаёт отметку удара стража: клиент не отличит его от удара монстра',
    );
    must(
      /guardName: msg\.guardName \? String\(msg\.guardName\) : ''/.test(сокет),
      'сокет не передаёт имя стража',
    );
    must(
      /karmaDelta: Number\(msg\.karmaDelta \?\? 0\)/.test(сокет),
      'сокет не передаёт потерю кармы',
    );
  });

  it('клиент показывает имя стража и потерю кармы', () => {
    must(
      /if \(r\.guardStrike\)/.test(клиент),
      'клиент игнорирует отметку удара стража: игрок увидит минус 60 и ничего больше',
    );
    must(
      /t\('stealth\.strike_karma'\)/.test(клиент),
      'клиент не показывает потерю кармы за удар: последствие невидимо',
    );
    must(
      /t\('stealth\.strike'\)/.test(клиент),
      'клиент не называет, кто ударил',
    );
  });

  it('приседание для удара берётся из проверенного пакета движения', () => {
    // Стойка приходит с пакетом, который уже прошёл античит на превышение
    // скорости. Свой флаг из отдельного события означал бы, что игрок сам
    // объявляет, присел он или нет, - и просто не присел бы.
    must(
      /stealthStates\.get\(игрок\.id\)/.test(цикл),
      'тик стражи не читает приседание игрока',
    );
    must(
      /stealthStates\.set\(characterId/.test(сокет),
      'сокет-обработчик не наполняет общее состояние скрытности',
    );
    must(
      /stealthStates\.cleanup\(socket\.characterId\)/.test(сокет),
      'состояние скрытности не чистится на выходе: карма растёт на каждого зашедшего',
    );
  });
});
