// Таможенный двор: дверь одна и та же на обеих сторонах, двор обставлен под задание.
//
// ЧТО ЗАЩИЩАЕТ. Таможня — первая постройка, у которой есть ПРАВИЛО в shared
// (CUSTOMS_POSTS, checkCustoms). Поэтому проверяется не только геометрия, но и
// то, что двор и правило относятся к одному миру: если правило живёт у ворот,
// а двор стоит на другом краю карты, игрок придёт к пошлине и не найдёт её.
//
// ЧТО ПРОВЕРЯЕМ ПО-НАСТОЯЩЕМУ.
//   1. Место двери сухое — водой замерено настоящим waterMask, не на глаз.
//   2. Слот комнаты и соседство записей: слот считается индексом в SPOTS, и он
//      обязан совпадать с числом, зашитым на сервере.
//   3. Мебель по пунктам задания: стойка, шлагбаум, весы, конфискат, архив.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';
import { waterMask } from '../../../shared/water';
import { CUSTOMS_POSTS, CUSTOMS_REACH } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

describe('Таможня: место подобрано измерением', () => {
  it('дверь стоит на сухой земле', () => {
    const def = INTERIORS.customs;
    must(def !== undefined, 'на сервере нет записи customs: дверь есть, а войти некуда');
    const влажность = waterMask(def.doorX, def.doorZ);
    must(
      влажность === 0,
      `у двери таможни (${def.doorX}, ${def.doorZ}) влажность ${влажность.toFixed(4)}, ` +
        'а должно быть 0.0000: стена встанет в воду'
    );
  });

  it('проверка места не пустая: вода остаётся водой', () => {
    must(waterMask(-420, -160) > 0.9, 'озеро перестало быть водой: маска считается неверно');
    must(waterMask(620, 300) > 0.9, 'пруд перестал быть водой: маска считается неверно');
    const def = INTERIORS.customs!;
    must(
      waterMask(def.doorX, def.doorZ) < waterMask(-420, -160),
      'сухая дверь посчиталась мокрее центра озера: сравнение бессмысленно'
    );
  });

  it('дверь не стоит на отпавших точках', () => {
    // При замере (-900,-900) и (-300,-1100) дали 1.0000, а (1000,-700) — 0.2071.
    const def = INTERIORS.customs!;
    must(def.doorZ !== -900 && def.doorX !== -300, 'дверь переехала на точку, где вода 1.0000');
    must(!(def.doorX === 1000 && def.doorZ === -700), 'дверь переехала на точку, где река 0.2071');
  });

  it('таможня стоит западнее города: она проверяет идущих снаружи внутрь', () => {
    const def = INTERIORS.customs!;
    must(
      def.doorX < 0,
      `дверь таможни на x=${def.doorX}, а не западнее города: двор внутри стен не имеет смысла — там досматривать некого`
    );
  });
});

describe('Таможня: слот и дверь совпадают на клиенте и на сервере', () => {
  it('таможня держит четырнадцатый слот на обеих сторонах', () => {
    const ключи = Object.keys(INTERIORS);
    const слотСервер = ключи.indexOf('customs');
    must(слотСервер === 14, `таможня на слоте ${слотСервер} из ${ключи.length}, а обязана быть четырнадцатой`);
    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    must(
      записи.indexOf('customs') === слотСервер,
      `на клиенте таможня на слоте ${записи.indexOf('customs')}, а на сервере ${слотСервер}: ` +
        'дверь нарисована у одной комнаты, а войти игрок будет в другую'
    );
  });

  it('пятнадцать построек держат свои слоты', () => {
    const ключи = Object.keys(INTERIORS);
    const ждём: [string, number, number][] = [
      ['stable', 0, 4000],
      ['barracks', 1, 4044],
      ['workshop', 2, 4088],
      ['tavern', 3, 4132],
      ['observatory', 4, 4176],
      ['science', 5, 4220],
      ['arena', 6, 4264],
      ['auction_house', 7, 4308],
      ['circus', 8, 4352],
      ['caravanserai', 9, 4396],
      ['fortress', 10, 4440],
      ['palace', 11, 4484],
      ['mosque', 12, 4528],
      ['weaver', 13, 4572],
      ['customs', 14, 4616],
    ];
    for (const [id, слот, комната] of ждём) {
      must(ключи[слот] === id, `на слоте ${слот} стоит ${ключи[слот]}, а ожидался ${id}`);
      must(
        INTERIORS[id as keyof typeof INTERIORS]!.roomCx === комната,
        `у ${id} roomCx ${INTERIORS[id as keyof typeof INTERIORS]!.roomCx}, а слот ${слот} даёт ${комната}`
      );
    }
  });

  it('координаты двери совпадают на клиенте и на сервере', () => {
    const def = INTERIORS.customs!;
    const своя = /id: 'customs', kind: 'customs',[\s\S]{0,140}?dx: (-?\d+), dz: (-?\d+)/.exec(клиент);
    must(своя !== null, 'у таможни на клиенте нет абсолютной двери: она посчитается от столицы');
    must(
      Number(своя![1]) === def.doorX && Number(своя![2]) === def.doorZ,
      `клиент рисует дверь в (${своя![1]}, ${своя![2]}), а сервер ждёт (${def.doorX}, ${def.doorZ})`
    );
  });

  it('комната не налезает на соседние', () => {
    const def = INTERIORS.customs!;
    const чужие = Object.values(INTERIORS).filter((д) => д.id !== 'customs');
    const тесные = чужие.filter((д) =>
      Math.abs(д.roomCx - def.roomCx) < 32 && Math.abs(д.roomCz - def.roomCz) < 32
    );
    must(тесные.length === 0, `комната налезает на: ${тесные.map((д) => д.id).join(', ')}`);
  });

  it('граница кармана покрывает новую комнату целиком', () => {
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+), z0: (-?\d+), z1: (\d+) \}/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    // Правый край комнаты, а не её центр: комната шириной 22, полкомнаты 16.
    // Проверка «x1 >= roomCx» пропускала дыру в 16 единиц — это уже было.
    must(
      Number(прямоугольник![2]) >= INTERIORS.customs!.roomCx + INTERIORS.customs!.roomHalf,
      `правый край кармана ${прямоугольник![2]}, а правый край комнаты ` +
        `${INTERIORS.customs!.roomCx + INTERIORS.customs!.roomHalf}: под комнатой нет земли`
    );
  });
});

describe('Таможня: двор и правило относятся к одному миру', () => {
  it('функция обстановки заведена и вызывается', () => {
    must(/function furnishCustoms\(/.test(клиент), 'функции обстановки таможни нет');
    must(/customs: furnishCustoms,/.test(клиент), 'таможня не прописан в выборе обстановки');
    must(
      /'customs'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 700) ?? ''),
      'в типе BuildingKind нет таможни'
    );
  });

  it('двор обставлен по всем пунктам задания владельца', () => {
    const начало = клиент.indexOf('function furnishCustoms(');
    must(начало > 0, 'функция обстановки таможни не найдена');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 6000);

    // Шлагбаум: столб и перекладина через весь проход.
    must(тело.includes('g.add(box(6.8, 0.24, 0.24, M.red, cx, FLOOR_Y + 3.2, cz - 9));'),
      'шлагбаума нет: въезд во двор открыт, и досматривать некому');
    // Стойка досмотра с ящиком.
    must(тело.includes('box(1, 0.3, 0.7, M.dark, cx - 2.2'), 'стойки досмотра нет');
    // Весы: чаша на столбе. Не гиря — именно взвешивают.
    must(/cyl\(0\.08, 0\.9, 0\.08, M\.gold/.test(тело), 'весов нет: караул не взвешивает товар');
    must(тело.includes('box(0.7, 0.14, 0.7, M.gold'), 'чаши весов нет');
    // Склад конфиската: ящики с пломбами и бочки.
    must(/for \(const \[bx, bz\] of \[\[-6, 6\]/.test(тело), 'склада конфиската нет');
    must(тело.includes('M.gold, cx + bx, FLOOR_Y + 1.05, cz + bz'), 'на ящиках нет пломб: конфискат не отличить от обычного груза');
    must(/for \(const \[kx, kz\] of \[\[2, 6\.6\]/.test(тело), 'бочек конфиската нет');
    // Архив: стеллаж со свитками.
    must(тело.includes('box(1.1, 3.2, 7, M.woodDark, cx - 9.8'), 'стеллажа архива нет');
    must(/sv\.rotation\.z = Math\.PI \/ 2;/.test(тело), 'свитки лежат не вдоль полки');
    // Навес: четыре столба и крыша.
    must(тело.includes('box(7.6, 0.2, 6.4, M.woodDark'), 'навеса над стойкой нет');
  });

  it('правило досмотра ещё живо и всё ещё про тех же караулов', () => {
    must(CUSTOMS_POSTS.length === 4, `постов таможни ${CUSTOMS_POSTS.length}, а должно быть 4`);
    must(CUSTOMS_REACH > 0, 'радиус досмотра обнулился: правило мертво');
    // Посты таможни — настоящие стражевые посты, и это должно остаться верным
    // после постройки двора.
    for (const таможня of CUSTOMS_POSTS) {
      must(
        таможня.x !== INTERIORS.customs!.roomCx,
        `пост ${таможня.id} стоит там же, где комната таможни: караул оказался внутри интерьера`
      );
    }
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.customs === 'string' && словарь.buildings.customs.length > 0,
        `в ${код}.json нет названия buildings.customs`
      );
    }
  });
});