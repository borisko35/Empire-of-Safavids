// Раздача добычи участникам захода: один раз, опыт полный, золото поровну.
//
// ЧТО ЗАЩИЩАЕТ. Три вещи, каждая из которых молча ломала бы игру:
//   1. добыча выдаётся ОДИН РАЗ — дважды вызванный complete удваивал бы всё;
//   2. атомарность — две вкладки, убившие босса, не удваивают добычу;
//   3. ДЕЛЕНИЕ — опыт каждому целиком, золото поровну, предметы по очереди входа.
//
// Проверки смотрят на результат расчёта, а не на слово «разделили»: дробь золота
// и очередь предметов — это арифметика, и её надо проверять числами.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = код('server/src/systems/DungeonService.ts');
const телоComplete = сервис.slice(сервис.indexOf('private async complete('));

// Тот же расчёт, что в сервисе, но на тестовых данных. Расхождение с сервисом
// здесь невозможно: правило проверяется числами, а не чтением строк.
function разделить(золото: number, предметов: number, народу: number) {
  const каждому = Math.floor(золото / народу);
  const остаток = золото - каждому * народу;
  const доли = [];
  for (let порядок = 0; порядок < народу; порядок++) {
    доли.push({
      gold: каждому + (порядок === 0 ? остаток : 0),
      // По кругу: предмет i достаётся участнику i % народу. Формула «свой по
      // индексу» отдавала бы лишние предметы никому — при двух людях и трёх
      // предметах третий исчезал бы. На этом проверка и поймала баг.
      items: Array.from({ length: предметов }, (_, i) => i).filter((i) => i % народу === порядок),
    });
  }
  return { каждому, остаток, доли };
}

describe('Раздача: считаем правильно, а не ищем слово', () => {
  it('золото делится поровну, и в сумме не теряется ни копейки', () => {
    const { доли } = разделить(1000, 3, 8);
    must(
      доли.reduce((с, д) => с + д.gold, 0) === 1000,
      `сумма долей ${доли.reduce((с, д) => с + д.gold, 0)} при золоте 1000: часть пропала или появилась`
    );
  });

  it('остаток от деления достаётся лидеру, а не теряется', () => {
    const { остаток } = разделить(1000, 3, 3);
    must(1000 % 3 === 1, 'расчётный пример перестал быть примером с остатком');
    must(остаток === 1, `остаток ${остаток}, а 1000 делится на 3 с остатком 1`);
    const доли = разделить(1000, 0, 3).доли;
    must(доли[0].gold > доли[1].gold, 'остаток должен достаться первому вошедшему, а не второму');
    must(доли[0].gold - доли[1].gold === 1, 'разница больше остатка: золото разъехалось');
    // Второе требование — про КОД, а не про тестовый расчёт. Без него этот
    // тест проверял сам себя: ломка «остаток достаётся второму» в сервисе
    // оставляла его зелёным, потому что пример считывался отдельно от кода.
    must(
      /порядок === 0 \? остаток : 0/.test(телоComplete),
      'в сервисе остаток достаётся не лидеру захода: остаток от деления уйдёт в никуда'
    );
  });

  it('предмет один на восемь человек достаётся ровно одному', () => {
    const { доли } = разделить(1000, 1, 8);
    const всегоПредметов = доли.reduce((с, д) => с + д.items.length, 0);
    must(всегоПредметов === 1, `предметов раздали ${всегоПредметов} при одном в списке: добыча размножилась`);
    must(доли[0].items.length === 1, 'предмет не достался первому вошедшему');
  });

  it('предметов больше, чем людей: лишние достаются следующим по порядку', () => {
    const { доли } = разделить(1000, 3, 2);
    // Главное здесь — НИ ОДИН предмет не потерян и ни один не выдан дважды.
    const выдано = доли.flatMap((д) => д.items);
    must(
      выдано.slice().sort((a, b) => a - b).join(',') === '0,1,2',
      `предметы выданы как [${выдано.join(',')}]: добыча пропала или размножилась`
    );
    must(доли[0].items.length === 2, 'лишний предмет должен достаться лидеру, а не пропасть');
    must(доли[1].items.length === 1, 'второй участник должен получить свой предмет');
  });

  it('проверка не холостая: заведомо неверный расчёт её роняет', () => {
    // Расчёт, который раздаёт каждому всю сумму, должен быть признан неверным.
    const жадный = Array.from({ length: 8 }, () => ({ gold: 1000, items: [0] }));
    must(
      жадный.reduce((с, д) => с + д.gold, 0) !== 1000,
      'жадный расчёт вдруг сошёлся: проверка суммы ничего не проверяет'
    );
  });
});

describe('Раздача: добыча достаётся один раз', () => {
  it('признак выдачи берётся атомарно, а не чтением и записью', () => {
    must(/private async claimLoot\(/.test(сервис), 'нет метода claimLoot');
    const тело = сервис.slice(сервис.indexOf('private async claimLoot('), сервис.indexOf('private async claimLoot(') + 900);
    must(
      /UPDATE dungeon_sessions[\s\S]*SET loot_claimed_at = NOW\(\)/.test(тело),
      'признак выдачи не проставляется одним UPDATE'
    );
    must(
      /WHERE id = \$1 AND loot_claimed_at IS NULL/.test(тело),
      'в UPDATE нет условия «признак ещё пуст»: две вкладки удвоят добычу'
    );
    must(!/SELECT[\s\S]{0,120}loot_claimed_at[\s\S]{0,200}UPDATE/.test(тело), 'вернулись к чтению и последующей записи');
  });

  it('миграция объявляет признак и его создаёт', () => {
    const миграция = читать('database/migrations/071_dungeon_loot_claim.sql');
    must(/ADD COLUMN IF NOT EXISTS loot_claimed_at/.test(миграция), 'миграция не объявляет признак выдачи');
    must(/TIMESTAMPTZ/.test(миграция), 'признак объявлен не как время: «когда выдали» без часового пояса');
  });

  it('раздача обёрнута в claimLoot, а не идёт безусловно', () => {
    must(
      /if \(await this\.claimLoot\(session\.id\)\) \{/.test(телоComplete),
      'раздача не проверяет признак выдачи: повторный вызов удвоит всё'
    );
    must(/addGoldReward\(/.test(телоComplete), 'золото больше не выдаётся вовсе');
  });

  it('старой выдачи одному добивателю не осталось', () => {
    // killerId в выдаче означал бы, что добыча по-прежнему вся у одного.
    const выдача = телоComplete.slice(телоComplete.indexOf('claimLoot(session.id)'));
    const блокВыдачи = выдача.slice(0, выдача.indexOf('closeSessionInDb') > 0 ? 1400 : 900);
    must(
      !/addGoldReward\(killerId/.test(блокВыдачи),
      'золото всё ещё идёт убийце, а не участникам'
    );
    must(!/addExperience\(killerId/.test(блокВыдачи), 'опыт всё ещё идёт убийце, а не каждому участнику');
  });
});

describe('Раздача: правила владельца соблюдены', () => {
  it('опыт достаётся каждому целиком, а не дробью', () => {
    // Смысл проверки — «опыт не делится», а не конкретная строка. Раньше она
    // требовала `experience: def.rewards.experience` буквально, и любое
    // осмысленное изменение (например, умножение на сложность захода)
    // роняло проверку, хотя правило владельца по-прежнему соблюдалось.
    // Поэтому проверяем, что масштабирование есть, а ДЕЛЕНИЯ нет.
    must(
      /experience: (?:def\.rewards\.experience|Math\.round\(def\.rewards\.experience \* множитель\))/.test(
        телоComplete
      ),
      'опыт не идёт участникам целиком: опыт учит, его не делят'
    );
    must(!/experience: Math\.floor/.test(телоComplete), 'опыт делится: так не просили');
  });

  it('золото делится и остаток лидеру', () => {
    must(/const каждому = Math\.floor\(gold \/ народу\)/.test(телоComplete), 'золото не делится поровну');
    must(/порядок === 0 \? остаток : 0/.test(телоComplete), 'остаток золота не достаётся лидеру захода');
    // И выдаётся именно ДОЛЯ, а не полная сумма захода. Ломка «каждому вся
    // сумма» прошла на двух предыдущих проверках: обе смотрели на расчёт
    // долей и не смотрели, что именно уходит в addGoldReward.
    must(
      /addGoldReward\(доля\.characterId, доля\.gold\)/.test(телоComplete),
      'золото выдаётся не из доли участника: каждый получит полную сумму захода'
    );
    must(
      !/addGoldReward\([^,]+, gold\)/.test(телоComplete),
      'кому-то выдаётся вся сумма золота захода'
    );
    must(
      /addExperience\(доля\.characterId, доля\.experience\)/.test(телоComplete),
      'опыт выдаётся не из доли участника'
    );
    must(
      /addItems\(доля\.characterId, \[\{ itemId, qty: 1 \}\]\)/.test(телоComplete),
      'предметы выдаются не из доли участника'
    );
  });

  it('предметы достаются по кругу входа, а не случайно', () => {
    // Массив называется `добыча`, а не guaranteedItems: с правкой бонусных
    // предметов в раздачу пошли и они, и по кругу теперь идёт весь выданный
    // список. Правило владельца не изменилось - предметы достаются по порядку
    // входа, поэтому проверка смотрит на форму, а не на прежнее имя.
    must(
      /добыча\.filter\(\(_, i\) => i % народу === порядок\)/.test(телоComplete),
      'предметы не выдаются по кругу участников'
    );
    // Случайности быть не должно. Ищем в блоке раздачи, а не во всём
    // complete: выше по тексту стоит Math.random() для суммы золота, и общий
    // поиск ловил его вместо раздачи.
    const блокРаздачи = телоComplete.slice(телоComplete.indexOf('claimLoot(session.id)'));
    const доЗакрытия = блокРаздачи.indexOf('closeSessionInDb');
    const окно = блокРаздачи.slice(0, доЗакрытия > 0 ? доЗакрытия : 1200);
    must(!/random|shuffle/.test(окно), 'в раздаче появилась случайность');
  });

  it('участники берутся из members, порядок входа сохраняется', () => {
    must(/\[\.\.\.session\.members\]/.test(телоComplete), 'участники не берутся из members захода');
  });

  it('отчёт говорит, сколько человек и сколько золота каждому', () => {
    must(/participants: участники\.length/.test(телоComplete), 'в отчёте нет числа участников');
    must(/goldEach: каждому/.test(телоComplete), 'в отчёте нет доли золота');
  });
});
