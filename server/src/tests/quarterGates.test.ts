// Ворота кварталов: вход на проспекте вместо пустого места.
//
// ЧТО БЫЛО (21 октября 2026, §235). Проспект упирался в пустое место:
// квартал был группами домов на площади, и входа в него не было. Табличка
// квартала стояла на столбе ПОСЕРЕДИ проспекта, прямо в проходе.
//
// ЧТО ТЕПЕРЬ. На конце проспекта — ворота: два столба, перекладина с зубцами
// и табличка квартала под перемычкой.
//
// ЧТО ПРОВЕРЯЕТСЯ. Ворота стоят на конце проспекта (а не посреди площади),
// табличка висит в проёме, и столба посреди проспекта больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Ворота кварталов', () => {
  it('ворота стоят на конце проспекта', () => {
    // Проспект идёт от r=30 до r=len-14, и ворота должны стоять на его
    // конце: посреди площади ворота были бы просто двумя столбами.
    должен(
      /const gx = ux \* r1, gz = uz \* r1;/.test(код),
      'ворота не стоят на конце проспекта',
    );
    должен(
      /const столб = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.2, 4\.4, 1\.2\), MAT\.sandstone\)/.test(код),
      'у ворот нет столбов',
    );
    должен(
      /const перемычка = new THREE\.Mesh\(new THREE\.BoxGeometry\(8\.0, 0\.8, 1\.3\), MAT\.sandstoneDark\)/.test(код),
      'у ворот нет перемычки',
    );
    // Зубцы по перемычке: ворота читаются как крепостные.
    должен(
      /for \(let i = 0; i < 5; i\+\+\) \{[\s\S]{0,220}?const зубец = new THREE\.Mesh/.test(код),
      'на перемычке ворот нет зубцов',
    );
  });

  it('табличка квартала висит в воротах, а не стоит в проходе', () => {
    должен(
      /sign\.position\.set\(gx, 3\.85, gz\)/.test(код),
      'табличка квартала не висит в воротах',
    );
    // Столб посреди проспекта убран: он стоял прямо в проходе.
    должен(
      !/const post = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.25, 3\.2, 0\.25\), MAT\.wood\)/.test(код),
      'столб с табличкой снова стоит посреди проспекта: он перекрывает проход',
    );
  });
});
