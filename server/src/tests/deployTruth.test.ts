// Выкатка не имеет права сказать «успех», если игрок получает не то, что выкачено.
//
// ЧТО БЫЛО. 8 октября 2026 выкатка отработала целиком: оба образа
// пересобрались, сервер ответил, 80 моделей из манифеста на месте, туннель
// зарегистрировал соединение — и скрипт напечатал `RESULT: PASS`. Живой сайт
// при этом отдавал СТАРУЮ сборку:
//
//   контейнер отдаёт  index-D24E_uzX.js
//   сайт снаружи      index-CuOyWCn8.js   (новый отдаёт 404)
//
// Причина в том, что ВСЕ проверки смотрели на локальный контейнер. Прод при
// этом живёт на AWS (§67), а имя туннеля Cloudflare одно и то же в обоих
// местах — то есть у туннеля два коннектора, и запросы обслуживал не тот, что
// пересобирали. Проверки были честные, просто не про то.
//
// ЧТО ТЕПЕРЬ ПОЯВИЛОСЬ. Проверка отдаваемого сайта: берётся index.html, который
// отдаётся СНАРУЖИ, из него вытаскивается имя бандла и сверяется с тем, что
// лежит в выкатанном контейнере. Не совпало — выкатка остановлена.
//
// ПОЧЕМУ ПРОВЕРЯЕТСЯ ФОРМА, А НЕ ПОВЕДЕНИЕ. Прогонять боевую выкатку внутри
// набора нельзя: она пересобирает образы и перезапускает контейнеры. Поэтому
// сторожим инварианты сценария — те самые места, где раньше можно было
// пройти мимо правды.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const СЦЕНАРИЙ = readFileSync(join(корень, 'tools', 'deploy.sh'), 'utf-8');
const ПРИМЕР_ENV = readFileSync(join(корень, 'deploy', '.env.example'), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Позиция последнего вхождения подстроки. */
function последний(hay: string, needle: string): number {
  return hay.lastIndexOf(needle);
}

describe('Выкатка не врёт о том, что попало на прод', () => {
  it('проверка отдаваемого сайта есть и стоит ПОСЛЕ всех остальных', () => {
    // Ломка с откатом: перенести блок проверки выше `RESULT: PASS` — и всё
    // снова станет можно пройти, не дойдя до правды.
    must(
      /=== 5\. CHTO OTDAYOT SAJT ===/.test(СЦЕНАРИЙ),
      'в сценарии нет шага «что отдаёт сайт»: PASS печатается без сверки с тем, что получает игрок',
    );
    const шаг = последний(СЦЕНАРИЙ, '=== 5. CHTO OTDAYOT SAJT ===');
    const проверкаОтвета = последний(СЦЕНАРИЙ, 'server otvechaet');
    const проверкаМоделей = последний(СЦЕНАРИЙ, 'vse modeley iz manifest.json na meste v obraze');
    must(проверкаОтвета > -1, 'в сценарии нет проверки ответа сервера — шаг 5 встал не туда');
    must(проверкаМоделей > -1, 'в сценарии нет проверки моделей — шаг 5 встал не туда');
    must(шаг > проверкаОтвета, 'проверка отдаваемого сайта идёт до проверки ответа сервера');
    must(шаг > проверкаМоделей, 'проверка отдаваемого сайта идёт до проверки моделей');
  });

  it('RESULT: PASS не может напечататься раньше проверки сайта', () => {
    // Ломка с откатом: если `RESULT: PASS` окажется выше шага 5, скрипт
    // напечатает успех и упадёт после — а по порядку вывода «успех» будет
    // последним, и его заметят, даже не читая отказа.
    const шаг = последний(СЦЕНАРИЙ, '=== 5. CHTO OTDAYOT SAJT ===');
    const pass = последний(СЦЕНАРИЙ, 'RESULT: PASS');
    must(pass > -1, 'в сценарии вообще нет RESULT: PASS');
    must(pass > шаг, 'RESULT: PASS печатается ДО проверки отдаваемого сайта');
  });

  it('при расхождении выкатка останавливается, а не идёт дальше', () => {
    // Ломка: заменить `stop` на `say` — и сценарий напечатает предупреждение и
    // радостно закончит словом PASS, то есть вернётся к прежнему поведению.
    must(
      /if \[ "\$SERVED_ASSET" != "\$DEPLOYED_ASSET" \]/.test(СЦЕНАРИЙ),
      'нет ветки, которая ловит несовпадение имени бандла',
    );
    must(
      /SAJT OTDAYAET NE TO, CHTO VYKACHENO/.test(СЦЕНАРИЙ),
      'нет сообщения о том, что сайт отдаёт не выкаченное',
    );
    must(
      /stop "prod ne poluchil novyy kod"/.test(СЦЕНАРИЙ),
      'расхождение не останавливает выкатку: скрипт дойдёт до PASS',
    );
  });

  it('имя бандла берётся из отдаваемого HTML, а не выдумывается', () => {
    // Ломка: если имя файла задать константой, сверка сравнит сайт с самим
    // собой и всегда пройдёт.
    must(
      /grep -o '\/game\/assets\/index-\[A-Za-z0-9_-\]\*\\\.js'/.test(СЦЕНАРИЙ),
      'имя бандла не вытаскивается из отдаваемого index.html',
    );
    must(
      /curl -fsS --max-time 30 -H 'Cache-Control: no-cache' "\$PUBLIC_URL\/game\/"/.test(СЦЕНАРИЙ),
      'отдаваемый index.html не читается по сети: сверять не с чем',
    );
  });

  it('цель выкатки выбирается явно и не угадывается', () => {
    // Ломка с откатом: вернуть жёстко зашитый локальный стек — и сценарий
    // снова будет проверять не тот стек, который отвечает снаружи.
    must(
      /env_get EOS_DEPLOY_TARGET/.test(СЦЕНАРИЙ),
      'цель выкатки не читается из deploy/.env: скрипт сам выбирает стек',
    );
    must(
      /neizvestnaya cel vykati/.test(СЦЕНАРИЙ),
      'неизвестная цель не отвергается, а молча трактуется как local',
    );
    must(
      /\[ -n "\$TARGET" \] \|\| TARGET="local"/.test(СЦЕНАРИЙ),
      'нет значения цели по умолчанию: скрипт упадёт на пустом TARGET',
    );
  });

  it('цель и параметры aws описаны в примере окружения', () => {
    // Владелец настраивает выкатку по примеру, а не по исходнику скрипта.
    for (const ключ of [
      'EOS_DEPLOY_TARGET',
      'EOS_AWS_HOST',
      'EOS_AWS_USER',
      'EOS_AWS_KEY',
      'EOS_AWS_DIR',
    ]) {
      must(
        ПРИМЕР_ENV.includes(ключ),
        `в deploy/.env.example нет ${ключ}: настроить боевую выкатку не по чему`,
      );
    }
  });

  it('недоступный SSH останавливает выкатку ДО сборки', () => {
    // Ломка: если связь проверять после пересборки, до AWS доезжает
    // пересобранный локальный стек, а ошибка видна только в конце — и тем
    // более выглядит как частичная выкатка.
    const проверкаSSH = последний(СЦЕНАРИЙ, 'SSH NE DOSTUPEN');
    const пересборка = последний(СЦЕНАРИЙ, '=== 3. PERESBORKA ===');
    must(проверкаSSH > -1, 'в сценарии нет проверки связи с боевой машиной');
    must(проверкаSSH < пересборка, 'связь с боевой машиной проверяется после пересборки');
    must(
      /dobav'te \$MY_IP\/32/.test(СЦЕНАРИЙ),
      'при недоступном SSH не печатается адрес, который надо открыть в группе безопасности',
    );
  });

  it('функции ssh заводятся только для боевой цели', () => {
    // Ломка: при `set -u` обращение к $AWS_KEY на локальной цели — это
    // «unbound variable», и выкатка стенда падает на ровном месте.
    must(
      /if \[ "\$TARGET" = "aws" \]; then\n  SSH_OPTS=/.test(СЦЕНАРИЙ),
      'параметры ssh заводятся безусловно: на локальной цели это unbound variable',
    );
  });

  it('на боевой машине запускается тот же сценарий, а не копия логики', () => {
    // Почему так: повторение пересборки и её проверок через ssh — это десяток
    // вызовов docker в кавычках, где любая ошибка кавычек означает пустую
    // выкатку на боевом стенде. Одна команда вместо этого.
    must(
      /EOS_DEPLOY_TARGET=local bash tools\/deploy\.sh/.test(СЦЕНАРИЙ),
      'на боевой машине сценарий не запускается: пересборка продублирована в вызывающем коде',
    );
    must(
      /git checkout -q \$LOCAL && git reset --hard \$LOCAL/.test(СЦЕНАРИЙ),
      'код не доводится на боевой машине до нужного коммита',
    );
  });
});