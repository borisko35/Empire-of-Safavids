// Пыль над дорогой в жару.
//
// ЧТО БЫЛО (21 октября 2026, §268). Над полотном дороги в жару должно висеть
// марево пыли: воздух над раскалённой дорогой дрожит, и дальний конец полотна
// тонет в мутном воздухе. Было чисто — дорога шла по пустыне стерильной лентой.
//
// ЧТО ТЕПЕРЬ. Пыль стоит над дорогой (а не над всей пустыней — нагрета дорога,
// а не ровный песок) и ползёт.
//
// ЧТО ПРОВЕРЯЕТСЯ. Пыль стоит над дорогой, а не за игроком; она ложится
// плашмя на полотно, а не стоит стеной; и появляется в тот же жар, что и
// марево над горизонтом.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ПЫЛЬ = читать('client/src/app/game3d/roadDust.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Пыль над дорогой', () => {
  it('пыль стоит над дорогой, а не за игроком', () => {
    должен(/export function createRoadDust/.test(ПЫЛЬ), 'нет пыли над дорогой');
    // Дороги берутся из общих данных: полоса встаёт на настоящее полотно.
    должен(/ROAD_PATHS\.map\(\(дорога\) => \(\{/.test(ПЫЛЬ), 'пыль не ищет дорогу');
    // Ближайшая дорога к игроку.
    должен(
      /for \(const д of дороги\) \{[\s\S]{0,200}?if \(d < лучшее\) \{ лучшее = d; ближняя = д; \}/.test(ПЫЛЬ),
      'пыль не ищет ближайшую дорогу',
    );
    // Вдали пыли нет: зачем она в пустыне без дороги.
    должен(/if \(!ближняя \|\| лучшее > 220\)/.test(ПЫЛЬ), 'пыль появляется вдали от дороги');
  });

  it('пыль ложится плашмя на полотно и ползёт', () => {
    // Плашмя: стена пыли поперёк дороги читалась бы как забор.
    должен(/полоса\.rotation\.x = -Math\.PI \/ 2;/.test(ПЫЛЬ), 'пыль стоит стеной, а не лежит на полотне');
    // Ползёт.
    должен(/полоса\.position\.x \+= Math\.sin\(now \/ 1900\) \* 1\.6;/.test(ПЫЛЬ), 'пыль не ползёт');
  });

  it('пыль идёт в том же жару, что и марево, и вычищается с миром', () => {
    должен(/this\.пыльДороги\.update\(dt, now, me\.pos\.x, me\.pos\.z, жар\);/.test(МИР), 'пыль не обновляется');
    должен(/this\.пыльДороги\?\.dispose\(\);/.test(МИР), 'пыль не вычищается');
    должен(/this\.пыльДороги = createRoadDust\(this\.scene\);/.test(МИР), 'пыль не создаётся');
  });
});
