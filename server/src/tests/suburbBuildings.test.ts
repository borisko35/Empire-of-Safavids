// Склады пригорода перестают быть коробками.
//
// ЧТО БЫЛО (22 октября 2026, §291). За городской стеной стояли склады и
// мастерская: корпус — ящик, крыша — плоская плита сверху, труба — брусок,
// ворота — одна доска. Здание читалось как коробка на крыше.
//
// ЧТО ТЕПЕРЬ. Цоколь из тёмного камня, каменный пояс под кровлей, бочка-свод
// вместо плоской крыши, контрфорсы у стен, ворота из досок с iron-обвязкой,
// сужающаяся труба с колпаком.
//
// ЧТО ПРОВЕРЯЕТСЯ. Есть сборщик свода (полуцилиндр, ось вдоль здания, дуга
// вверх); склад собран из цоколя, пояса, свода, контрфорсов и ворот с
// обвязкой; труба сужается и с колпаком; плоской крыши-коробки больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Склады пригорода — не коробки', () => {
  it('есть сборщик бочки-свода', () => {
    // Геометрия строится сразу в нужном положении: ось вдоль X, дуга вверх.
    // Поворотами цилиндра дуга вставала боком (как навес прилавка).
    должен(/function свод\(/.test(ТЕРРЕЙН), 'нет сборщика свода');
    должен(
      /const a = -Math\.PI \/ 2 \+ \(Math\.PI \* i\) \/ сегментов;/.test(ТЕРРЕЙН),
      'дуга свода не поднята над стенами',
    );
    // Рёбра идут вдоль здания: вершины отличаются по X.
    должен(
      /вершины\.push\(-длина \/ 2, y, z\);\s*вершины\.push\(длина \/ 2, y, z\);/.test(ТЕРРЕЙН),
      'свод собран не вдоль здания',
    );
  });

  it('склад: цоколь, пояс, свод, контрфорсы', () => {
    должен(/function склад\(/.test(ТЕРРЕЙН), 'нет сборщика склада');
    // Цоколь.
    должен(
      /const цоколь = new THREE\.Mesh\(new THREE\.BoxGeometry\(w \+ 0\.16, 0\.5, d \+ 0\.16\)/.test(ТЕРРЕЙН),
      'у склада нет цоколя',
    );
    // Каменный пояс.
    должен(
      /const пояс = new THREE\.Mesh\(new THREE\.BoxGeometry\(w \+ 0\.14, 0\.22, d \+ 0\.14\)/.test(ТЕРРЕЙН),
      'у склада нет пояса',
    );
    // Крыша — свод, а не плита.
    должен(/const крыша = new THREE\.Mesh\(свод\(w \+ 0\.4, d \/ 2 \+ 0\.25\)/.test(ТЕРРЕЙН),
      'у склада нет свода');
    // Контрфорсы.
    должен(
      /const контрфорс = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.45, h \* 0\.82, 0\.7\)/.test(ТЕРРЕЙН),
      'у склада нет контрфорсов',
    );
    // Плохой крыши-коробки быть не должно.
    должен(
      !/new THREE\.BoxGeometry\(п\.w \+ 0\.6, 0\.34, п\.d \+ 0\.6\)/.test(ТЕРРЕЙН),
      'крыша склада снова плоская плита',
    );
  });

  it('ворота с iron-обвязкой, труба сужается и с колпаком', () => {
    // Ворота из досок.
    должен(
      /const ворота = new THREE\.Mesh\(new THREE\.BoxGeometry\(w \* 0\.42, h \* 0\.6, 0\.16\)/.test(ТЕРРЕЙН),
      'у склада нет ворот',
    );
    // Обвязка — iron-полосы на воротах.
    должен(
      /const обвязка = new THREE\.Mesh\(new THREE\.BoxGeometry\(w \* 0\.44, 0\.09, 0\.07\), MAT\.dark\)/.test(ТЕРРЕЙН),
      'у ворот нет обвязки',
    );
    // Труба сужается кверху и с колпаком — брусок читался как пень.
    должен(
      /const труба = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.42, 0\.62, 3\.4, 8\)/.test(ТЕРРЕЙН),
      'труба не сужается',
    );
    должен(
      /const колпак = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.56, 0\.44, 0\.18, 8\)/.test(ТЕРРЕЙН),
      'у трубы нет колпака',
    );
    // Бруска-трубы быть не должно.
    должен(!/new THREE\.BoxGeometry\(1\.0, 3\.4, 1\.0\)/.test(ТЕРРЕЙН), 'труба снова брусок');
  });
});
