// Дворы у домов кварталов: крыльцо и забор.
//
// ЧТО БЫЛО (21 октября 2026, §238). Дома кварталов стояли прямо на
// мостовой: ни ступеньки, ни забора, ни двора. Жилой квартал после §222
// получил крыльцо, а остальные — нет.
//
// ЧТО ТЕПЕРЬ. Крыльцо со ступенькой отделяет вход от улицы, а забор по
// бокам фасада очерчивает двор.
//
// ЧТО ПРОВЕРЯЕТСЯ. Крыльцо и ступенька стоят у двери, забор — по бокам
// фасада, и всё это добавлено в общий дом квартала.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');
const код = ИНТЕРЬЕРЫ.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Дворы у домов кварталов', () => {
  it('у дома есть крыльцо со ступенькой', () => {
    должен(
      /const крыльцо = new THREE\.Mesh\(new THREE\.BoxGeometry\(3\.0, 0\.22, 1\.2\), M\.stone\)/.test(код),
      'у домов кварталов нет крыльца: вход выходит прямо на мостовую',
    );
    должен(
      /ступенька\.position\.set\(0, 0\.06, 4\.25\)/.test(код),
      'ступенька у крыльца не стоит',
    );
    // Крыльцо и ступенька добавлены в общий дом, а не висят в стороне.
    должен(
      /g\.add\(body, roof, frame, door, sign, lamp, win1, win2, пояс, крыльцо, ступенька\)/.test(код),
      'крыльцо и ступенька не добавлены в дом',
    );
  });

  it('по бокам фасада стоит забор', () => {
    должен(
      /const столб = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.26, 1\.0, 0\.26\), M\.woodDark\)/.test(код),
      'у домов кварталов нет забора: двор не очерчен',
    );
    должен(
      /const рейка = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.14, 0\.5, 3\.0\), M\.woodDark\)/.test(код),
      'между столбами забора нет рейки',
    );
    // По обе стороны от фасада.
    должен(
      /for \(const s of \[-1, 1\] as const\) \{\s*const столб = new THREE\.Mesh/.test(код),
      'забор поставлен с одной стороны',
    );
  });
});
