// Модели классов приезжают в сантиметрах, граждане и паладин — в метрах.
// Игра отличала их масштабом КЛИПА: `корневойМасштаб < 0.5 ? 100 : 1`, то
// есть к сантиметровой модели приставлялись переводы костей, умноженные на
// 100. Кости уезжали в сто раз от покоя, а `inverseBindMatrices` скина
// оставались в исходных единицах — их никто не трогал.
//
// Что это давало на игре: голова уходила в плечи, шеи нет, руки прижаты к
// корпусу, ноги ломаются. Размер при этом выглядел ПРАВИЛЬНЫМ — побочный
// эффект поломки: множитель 100 растягивал скелет вместе с мешем. Поэтому
// «модели нормального размера» и «модели сломаны» не противоречили.
//
// Правка: корень приводится к метрам ДО подгонки и ДО расчёта масштаба клипа.
//
// ПРО ЧТЕНИЕ. Порядок вызовов ищется по коду без комментариев. Первая версия
// проверки читала весь файл через indexOf и попадала в ПОЯСНЕНИЕ — порядок
// выходил правильным всегда. Проверка, читающая комментарий, не проверяет
// ничего.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

const РИГ = читать('client/src/app/game3d/realRig.ts');
const ТОЛЬКО_КОД = код(РИГ);

describe('Единицы модели', () => {
  it('сторож читает код, а не пояснение', () => {
    // Страховка от повторения собственной ошибки: если вырезание комментариев
    // перестанет работать, порядок начнёт читаться по пояснению.
    должен(
      /Порядок здесь — и есть вся правка/.test(РИГ),
      'пояснение из файла исчезло, страховке не на что опереться',
    );
    должен(
      !/Порядок здесь — и есть вся правка/.test(ТОЛЬКО_КОД),
      'комментарии больше не вырезаются: порядок читается по пояснению, а не по коду',
    );
  });

  it('корень приводится к метрам ДО расчёта масштаба клипа', () => {
    // Это и есть вся правка. Если поменять местами — снова поедут метровые
    // переводы по сантиметровым костям, и тело снова сольётся.
    const привели = ТОЛЬКО_КОД.indexOf('привестиКМетрам(сцена);');
    const масштаб = ТОЛЬКО_КОД.indexOf('корневойМасштаб(сцена) < 0.5 ? 100 : 1');
    должен(привели > 0, 'приведения корня к метрам в коде нет');
    должен(масштаб > 0, 'расчёта масштаба клипа не читается');
    должен(
      привели < масштаб,
      'масштаб клипа считается ДО приведения корня: метровые переводы поедут по сантиметровым костям',
    );
  });

  it('приведение делит корень на его масштаб, а не умножает на 100', () => {
    // Умножение на 100 - это ровно то, что чинили. Возврат означает возврат
    // поломки тела.
    const тело = /function привестиКМетрам[\s\S]*?\n}/.exec(ТОЛЬКО_КОД);
    должен(тело, 'функция приведения корня к метрам не читается');
    должен(
      /multiplyScalar\(\s*1\s*\/\s*корень\s*\)/.test(тело![0]),
      'корень не делится на свой масштаб: вместо метров останутся сантиметры',
    );
    должен(
      !/multiplyScalar\(\s*100\s*\)/.test(тело![0]),
      'приведение снова умножает на 100 — это и есть поломка тела',
    );
    должен(
      /updateMatrixWorld\(\s*true\s*\)/.test(тело![0]),
      'матрицы не пересчитаны после смены масштаба: замер возьмёт прежние габариты',
    );
  });

  it('подгонка больше не считает позу скелета', () => {
    // §142 утверждал, что виноват setFromObject, и добавлял computeBoundingBox.
    // Проверено на живой игре: цифра не изменилась ни на единицу. Замер был
    // верен по порядку величины — модель действительно крошечная в своих
    // единицах, — просто с ним работали неправильно. Код возвращён.
    const подогнать = /export function подогнать[\s\S]*?\n}/.exec(ТОЛЬКО_КОД);
    должен(подогнать, 'подгонка не читается');
    должен(
      !/computeBoundingBox/.test(подогнать![0]),
      'подсчёт позы вернулся: он не изменил ни одной цифры, а стоил выката',
    );
  });

  it('предупреждение не обвиняет позу, а указывает на единицы', () => {
    // §142 написала в предупреждении «поза скелета посчитана верно, значит
    // модель странная». Это неверно: поза считалась верно, а винова была
    // единицами. После правки единственная честная причина отказа — корень не
    // приведён к метрам, и её надо называть прямо.
    const вызов = /console\.warn\([\s\S]{0,400}?не трогаю размер[\s\S]{0,400}?\);/.exec(ТОЛЬКО_КОД);
    должен(вызов, 'предупреждение «не трогаю размер» не читается');
    должен(
      !/поза скелета посчитана верно/.test(вызов![0]),
      'предупреждение обвиняет позу: она считалась верно и винова не была',
    );
    должен(
      /масштаб корня/.test(вызов![0]),
      'предупреждение не называет причину: после приведения к метрам причина одна — корень',
    );
  });
});