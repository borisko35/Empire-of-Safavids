// Чайки на сваях у причала.
//
// ЧТО БЫЛО (22 октября 2026, §303). Причал был пустым, а чайки в этом мире
// летали только в небе (§273, §279): вблизи воды не было ни одной птицы, и
// озеро читалось как зеркало без живности.
//
// ЧТО ТЕПЕРЬ. Чайки стоят на сваях: туловище-капсула, голова, ОРАНЖЕВЫЙ клюв
// (по нему чайку и узнают), крылья вдоль тела, хвост и две тонкие ноги. Одна
// сидит на перилах, две стоят на сваях.
//
// ЧТО ПРОВЕРЯЕТСЯ. Чайки есть, у них тело-капсула, голова, клюв, крылья, хвост
// и ноги; клюв оранжевый; чайки поставлены на причале.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Чайки на сваях у причала', () => {
  it('у чайки тело, голова, клюв, крылья, хвост и ноги', () => {
    // Тело — капсула, а не шарик.
    должен(
      /const тело = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.1, 0\.2, 3, 8\), чайкаМатериал\);/.test(ТЕРРЕЙН),
      'тело чайки — не капсула',
    );
    // Голова.
    должен(
      /const голова = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.075, 8, 6\), чайкаМатериал\);/.test(ТЕРРЕЙН),
      'у чайки нет головы',
    );
    // Клюв — оранжевый, по нему чайку узнают.
    должен(
      /const клювМатериал = new THREE\.MeshStandardMaterial\(\{ color: 0xd8a13a, roughness: 0\.6 \}\);/.test(ТЕРРЕЙН),
      'клюв чайки не оранжевый',
    );
    // Крылья, хвост и ноги.
    должен(/const крыло = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.05, 0\.09, 0\.3\)/.test(ТЕРРЕЙН),
      'у чайки нет крыльев');
    должен(/const хвост = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.12, 0\.04, 0\.16\)/.test(ТЕРРЕЙН),
      'у чайки нет хвоста');
    должен(/const нога = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.008, 0\.008, 0\.16, 4\)/.test(ТЕРРЕЙН),
      'у чайки нет тонких ног');
  });

  it('чайки стоят на причале', () => {
    // Три чайки: одна на перилах, две на сваях.
    должен(/поставитьЧайку\(-1, -1\.9, 0\.6, true\);/.test(ТЕРРЕЙН), 'нет чайки на перилах');
    должен(/поставитьЧайку\(1, -5\.7, -0\.4, false\);/.test(ТЕРРЕЙН), 'нет чайки на сваях');
    // И причал их принимает.
    должен(/pier\.add\(чайка\);/.test(ТЕРРЕЙН), 'чайки не добавлены на причал');
  });
});
