// Мечеть и медресе: дверь одна и та же на клиенте и на сервере, зал обставлен.
//
// ЧТО ЗАЩИЩАЕТ. Три молчаливых поломки, каждая выглядит как готовая работа:
// дверь нарисована у одной комнаты, а войти игрок будет в другую; стена сдвинулась
// у одного здания и молча испортила остальные; «минарет есть» — потому что слово
// встречается в комментарии, а не в коде.
//
// ПОСЛЕДНЕЕ — НЕ ШУТКА. При замере поиск шёл в нижнем регистре и не нашёл
// «минарет» ни разу, хотя строки в terrain.ts есть: они с большой буквы. Почти
// вышло решение «мечети нет». Здесь поэтому проверка идёт по точному тексту и по
// числу, а не по «есть ли слово».
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';
import { waterMask } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

describe('Мечеть: место подобрано измерением', () => {
  it('дверь стоит на сухой земле', () => {
    const def = INTERIORS.mosque;
    must(def !== undefined, 'на сервере нет записи mosque: дверь есть, а войти некуда');
    const влажность = waterMask(def.doorX, def.doorZ);
    must(
      влажность === 0,
      `у двери мечети (${def.doorX}, ${def.doorZ}) влажность ${влажность.toFixed(4)}, ` +
        'а должно быть 0.0000: стена встанет в воду'
    );
  });

  it('проверка места не пустая: вода остаётся водой', () => {
    must(waterMask(-420, -160) > 0.9, 'озеро перестало быть водой: маска считается неверно');
    must(waterMask(620, 300) > 0.9, 'пруд перестал быть водой: маска считается неверно');
    const def = INTERIORS.mosque!;
    must(
      waterMask(def.doorX, def.doorZ) < waterMask(-420, -160),
      'дверь посчиталась мокрее центра озера: сравнение бессмысленно'
    );
  });

  it('дверь не стоит там, где вода — это проверено, а не предположено', () => {
    // Точки, которые при замере отпали: (-200, -700) дало 0.1392, (-320, -760) —
    // 1.0000. Если бы дверь встала на одну из них, проверка сработала бы. Здесь
    // фиксируем, что она стоит на другой, а не просто «где-то сухо».
    const def = INTERIORS.mosque!;
    must(
      !(def.doorX === -200 && def.doorZ === -700),
      'дверь переехала на отпавшую точку (-200, -700), где вода 0.1392'
    );
    must(def.doorX !== -320, 'дверь переехала на отпавшую точку (-320, -760), где это озеро');
  });
});

describe('Мечеть: слот и дверь совпадают на клиенте и на сервере', () => {
  it('мечеть держит двенадцатый слот на обеих сторонах', () => {
    const ключи = Object.keys(INTERIORS);
    const слотСервер = ключи.indexOf('mosque');
    must(слотСервер === 12, `мечеть на слоте ${слотСервер} из ${ключи.length}, а обязана быть двенадцатой`);

    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    const слотКлиент = записи.indexOf('mosque');
    must(
      слотКлиент === слотСервер,
      `на клиенте мечеть на слоте ${слотКлиент}, а на сервере ${слотСервер}: ` +
        'дверь нарисована у одной комнаты, а войти игрок будет в другую'
    );
  });

  it('предыдущие постройки не сдвинулись', () => {
    const ключи = Object.keys(INTERIORS);
    must(ключи[9] === 'caravanserai', `на девятом слоте ${ключи[9]}, а не караван-сарай`);
    must(ключи[10] === 'fortress', `на десятом слоте ${ключи[10]}, а не крепость`);
    must(ключи[11] === 'palace', `на одиннадцатом слоте ${ключи[11]}, а не дворец`);
    must(INTERIORS.caravanserai!.roomCx === 4396, `у караван-сарая roomCx ${INTERIORS.caravanserai!.roomCx}, а слот 9 даёт 4396`);
    must(INTERIORS.fortress!.roomCx === 4440, `у крепости roomCx ${INTERIORS.fortress!.roomCx}, а слот 10 даёт 4440`);
    must(INTERIORS.palace!.roomCx === 4484, `у дворца roomCx ${INTERIORS.palace!.roomCx}, а слот 11 даёт 4484`);
    must(INTERIORS.mosque!.roomCx === 4528, `у мечети roomCx ${INTERIORS.mosque!.roomCx}, а слот 12 даёт 4528`);
  });

  it('координаты двери совпадают на клиенте и на сервере', () => {
    const def = INTERIORS.mosque!;
    const своя = /id: 'mosque', kind: 'mosque',[\s\S]{0,140}?dx: (-?\d+), dz: (-?\d+)/.exec(клиент);
    must(своя !== null, 'у мечети на клиенте нет абсолютной двери: она посчитается от столицы');
    must(
      Number(своя![1]) === def.doorX && Number(своя![2]) === def.doorZ,
      `клиент рисует дверь в (${своя![1]}, ${своя![2]}), а сервер ждёт (${def.doorX}, ${def.doorZ})`
    );
  });

  it('комната не налезает на соседние', () => {
    const def = INTERIORS.mosque!;
    const чужие = Object.values(INTERIORS).filter((д) => д.id !== 'mosque');
    const тесные = чужие.filter((д) =>
      Math.abs(д.roomCx - def.roomCx) < 32 && Math.abs(д.roomCz - def.roomCz) < 32
    );
    must(тесные.length === 0, `комната мечети налезает на: ${тесные.map((д) => д.id).join(', ')}`);
  });

  it('граница кармана покрывает новую комнату', () => {
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+), z0: (-?\d+), z1: (\d+) \}/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    must(
      Number(прямоугольник![2]) >= INTERIORS.mosque!.roomCx,
      `правый край кармана ${прямоугольник![2]}, а центр комнаты мечети ${INTERIORS.mosque!.roomCx}`
    );
  });
});

describe('Мечеть: зал обставлен тем, что просили', () => {
  it('функция обстановки заведена и вызывается для мечети', () => {
    must(/function furnishMosque\(/.test(клиент), 'функции обстановки мечети нет');
    must(/mosque: furnishMosque,/.test(клиент), 'мечеть не прописан в выборе обстановки: получила бы чужую комнату');
    must(
      /'mosque'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 500) ?? ''),
      'в типе BuildingKind нет мечети'
    );
  });

  it('в зале есть михраб, галерея, комнаты учеников и библиотека', () => {
    const начало = клиент.indexOf('function furnishMosque(');
    must(начало > 0, 'функция обстановки мечети не найдена');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 5000);

    must(/M\.gold/.test(тело), 'у михраба нет золотой отделки: зал выглядит как склад');
    must(/cyl\(0\.24/.test(тело), 'нет колонн галереи');
    must(/M\.hay/.test(тело), 'нет ни книг, ни скамей: ни библиотека, ни комнаты учеников');
    // Счётчик задаёт число рядов: без него «галерея» — это две колонны.
    must(/for \(let i = 0; i < 7; i\+\+\)/.test(тело), 'у галереи нет семи рядов колонн');
    must(/for \(let i = 0; i < 3; i\+\+\)/.test(тело), 'нет трёх учебных мест');
    // Михраб проверяется по СВОЕЙ геометрии, а не по материалу. Проверка «есть
    // ли M.gold» обманчива: золотом окрашены ещё и капители колонн, и михраб
    // можно было бы снести, а проверка осталась бы зелёной. Это ровно тот
    // случай, когда ломка проверки выдаёт её слабое место — и она выдала.
    must(тело.includes('g.add(box(3.2, 3.4, 0.5, M.gold, cx, FLOOR_Y + 1.7, cz - 10.2));'),
      'михраба нет: ниша у северной стены должна стоять на месте');
    must(тело.includes('g.add(box(7, 0.05, 9, M.red, cx, FLOOR_Y + 0.03, cz - 4));'),
      'ковра перед михрабом нет: зал без ковра — это склад');
    must(тело.split('for (const side of [-1, 1])').length - 1 === 2,
      'боковые ряды должны быть ровно двумя: галерея и библиотека');
  });

  it('мечеть снаружи уже есть и это не выдумано', () => {
    // Купол и минареты стоят на площади ещё с прошлых заходов.
    //
    // ГЛАВНОЕ ЗДЕСЬ. Первая версия этой проверки искала слово «Минареты» — и это
    // была пустая проверка: единственное такое вхождение в файле оказалось
    // КОММЕНТАРИЕМ на строке 1326, а не геометрией. Слово можно было бы
    // переименовать, и проверка бы возмутилась; минареты же стоят строчкой ниже
    // как цилиндр с балконом, конусом и шпилем.
    //
    // Поэтому здесь проверяется геометрия: ствол, балкон, вершина и шпиль —
    // четыре обязательные детали минарета.
    const земля = читать('client/src/app/game3d/terrain.ts');
    must(
      /const shaft = new THREE\.Mesh\(new THREE\.CylinderGeometry\(1\.1, 1\.4, 22, 10\)/.test(земля),
      'в terrain.ts нет ствола минарета: минарет не построен'
    );
    must(/const balcony = new THREE\.Mesh\(new THREE\.CylinderGeometry\(1\.9/.test(земля),
      'у минарета нет балкона');
    must(/const top = new THREE\.Mesh\(new THREE\.ConeGeometry\(1\.5, 4, 10\)/.test(земля),
      'у минарета нет вершины');
    must(/const finial = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.5/.test(земля),
      'у минарета нет шпиля');
    must(/const dome = new THREE\.Mesh\(new THREE\.SphereGeometry\(7\.5/.test(земля),
      'в terrain.ts нет купола мечети');
    must(/mosque\.position\.set\(/.test(земля), 'мечеть не поставлена на площадь');
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.mosque === 'string' && словарь.buildings.mosque.length > 0,
        `в ${код}.json нет названия buildings.mosque`
      );
    }
  });
});