// Дворец и гробница: стены вместо глухих плит.
//
// ЧТО БЫЛО (21 октября 2026, §225). Два последних экстерьера стояли
// «на глаз»:
//   • стена тронного зала дворца — 26 метров сплошной штукатурки, без
//     единого окна; бирюзовая керамика на пилонах пиштака была ОДНОЙ
//     плитой, и с плоской стороны читалась как бирюзовая заплатка;
//   • корпус гробницы — коробка с пирамидальной крышей и чёрной дверью:
//     ни окон, ни карниза, ни наличника.
//
// ЧТО ТЕПЕРЬ. Дворец: окна на тронном зале (стекло, рама, средник) и
// изразцы отдельными плитками с зазором и тёмной подложкой. Гробница:
// узкие окна, каменный карниз под кровлей, наличник над входом и опоры
// у двери.
//
// ЧТО ПРОВЕРЯЕТСЯ. Каждая правка — отдельной строкой, и каждая ломается
// обратно: сторож падает, если правку убрать.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/terrain.ts');
// Проверки идут по коду без комментариев: иначе сторож ловит собственное
// пояснение правки.
const КОД = МИР.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

/** Отрезок кода между двумя опорными метками. */
function между(начало: string, конец: string): string {
  const от = МИР.indexOf(начало);
  должен(от >= 0, `в коде нет метки «${начало}»: проверка ослепла`);
  const до = МИР.indexOf(конец, от);
  должен(до > от, `в коде нет метки «${конец}» после «${начало}»: проверка ослепла`);
  return МИР.slice(от, до).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const ДВОРЕЦ = между('── Дворец ──', '── Мечетный двор');
const ГРОБНИЦА = между('── Корпус гробницы', '── Катакомбы Тебриза');

describe('Дворец и гробница', () => {
  it('на тронном зале дворца есть окна', () => {
    // Стена зала в 26 метров стояла глухой плитой: с двора её было видно
    // целиком, и зал читался как загородка.
    должен(
      /windowPane\(s \* 8\.2, 7\.2, HALL_FRONT_Z, 0, 1\.2, 1\.8\)/.test(ДВОРЕЦ),
      'на тронном зале дворца нет окон: стена в 26 метров глухая',
    );
    должен(
      (ДВОРЕЦ.match(/windowPane\(/g) || []).length >= 2,
      'окон на тронном зале меньше двух: стена читается глухой',
    );
  });

  it('бирюзовая керамика — изразцы, а не одна плита', () => {
    // Сплошная плита читалась как заплатка на стене. Изразцы стоят плиткой с
    // зазором, и шов виден.
    должен(
      !/const band = new THREE\.Mesh\(new THREE\.BoxGeometry\(pil/.test(ДВОРЕЦ),
      'на пилонах снова сплошная плита вместо изразцов',
    );
    должен(
      /const изразцов = 3/.test(ДВОРЕЦ) && /MAT\.tealDome/.test(ДВОРЕЦ),
      'изразцы на пилонах не собраны: керамика опять сплошная',
    );
    должен(
      /MAT\.sandstoneDark[\s\S]{0,400}подложка/.test(ДВОРЕЦ),
      'под изразцами нет тёмной подложки: швы не читаются',
    );
  });

  it('у гробницы есть окна, карниз и наличник', () => {
    должен(
      /windowPane\(s \* 3\.2, 2\.4, WALL_T, 0, 0\.7, 1\.3\)/.test(ГРОБНИЦА),
      'у гробницы нет узких окон: корпус читается коробкой',
    );
    должен(
      /const карниз = new THREE\.Mesh\(\s*new THREE\.BoxGeometry\(HALL_W \+ 0\.3, 0\.24, HALL_D \+ 0\.3\)/.test(
        ГРОБНИЦА,
      ),
      'у гробницы нет карниза под кровлей',
    );
    должен(
      /const наличник = new THREE\.Mesh/.test(ГРОБНИЦА),
      'у гробницы нет наличника над входом: дверь читается провалом',
    );
  });

  it('окна по-прежнему строятся одной функцией', () => {
    // Правки §224–§225 не должны заводить второе «окно»: стекло, рама и
    // средник должны быть одни и те же по всей игре.
    должен(
      /glass:\s*new THREE\.MeshStandardMaterial/.test(КОД),
      'нет общего материала стекла: окна разъедутся по игре',
    );
    должен(
      /function windowPane\([\s\S]*?W = 0\.9, H = 1\.3/.test(КОД),
      'у windowPane снова нет размеров: любое здание получит чужое окно',
    );
  });
});
