// Чужие тела догоняли настоящую позицию с ограничением скорости.
//
// ЧТО БЫЛО. Позиция чужого игрока или монстра приближалась к серверной точкой за
// точкой с ограничением СКОРОСТИ: чужие игроки — 6 ед/с, все монстры — константа
// (3.5 при появлении и 3.2 на пакетах перемещения), хотя серверные скорости
// монстров доходят до 8.0, а скакун разгоняется до 16.
//
// Почему ограничение скорости неверно по сути: если цель движется быстрее
// ограничения, разрыв не просто велик — он накапливается, и глаз видит объект,
// который едет медленнее, чем едет на самом деле. Быстрый монстр уезжал от
// своей настоящей позиции, а остановившийся ещё долго «доезжал» к ней.
//
// ЧТО ПРОВЕРЯЕТСЯ. Считается настоящее сглаживание из кода: сколько метров
// объект отстаёт у равномерно движущейся цели, не растёт ли отставание со
// временем, одинаково ли ведёт себя себя на 30 и 144 кадрах, и закрывается ли
// большой разрыв (телепорт) сразу.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СУЩНОСТИ = читать('client/src/app/entities.ts');
const МИР = читать('client/src/app/world.ts');

function число(источник: string, шаблон: RegExp, что: string): number {
  const найдено = шаблон.exec(источник);
  must(найдено, `не нашёл ${что} в коде: проверка считала бы не то, что в игре`);
  return Number(найдено![1]);
}

const СГЛАЖИВАНИЕ = число(СУЩНОСТИ, /const СГЛАЖИВАНИЕ_С = ([\d.]+)/, 'время сглаживания');
const ЩЕЛЧОК = число(СУЩНОСТИ, /const ЩЕЛЧОК_М = ([\d.]+)/, 'порог щелчка');
const СКАКУН = 16; // предел анти-чита по скорости: наибольшая честная скорость
const БЫСТРЫЙ_МОНСТР = 8;

/**
 * Прогнать сглаживание из кода против цели, которая равномерно едет.
 *
 * Цель стартует в нуле и движется сама по себе — так же, как настоящий объект,
 * которого клиент знает только по приходящим пакетам.
 */
function отставание(fps: number, скоростьЦели: number, секунд: number): number {
  let pos = 0;
  let target = 0;
  const dt = 1 / fps;
  for (let кадр = 0; кадр < fps * секунд; кадр++) {
    target += скоростьЦели * dt;
    const разрыв = target - pos;
    if (разрыв < 0.02) { pos = target; continue; }
    if (разрыв > ЩЕЛЧОК) { pos = target; continue; }
    pos += разрыв * (1 - Math.exp(-dt / СГЛАЖИВАНИЕ));
  }
  return target - pos;
}

describe('Отставание чужих тел', () => {
  it('на скакуне отставание невелико и не растёт', () => {
    const начало = отставание(60, СКАКУН, 1);
    const черезДесять = отставание(60, СКАКУН, 10);
    must(
      начало < 2.5,
      `через секунду езды тело отстаёт на ${начало.toFixed(2)} м: это уже видно как ошибка`
    );
    must(
      Math.abs(черезДесять - начало) < 0.5,
      `отставание растёт со временем: ${начало.toFixed(2)} м через секунду и ` +
        `${черезДесять.toFixed(2)} м через десять — это старое ограничение скорости, ` +
        'которое не догоняет быструю цель'
    );
  });

  it('быстрый монстр тоже не отстаёт', () => {
    const отставаниеМонстра = отставание(60, БЫСТРЫЙ_МОНСТР, 5);
    must(
      отставаниеМонстра < 1.2,
      `быстрый монстр отстаёт на ${отставаниеМонстра.toFixed(2)} м: при старых 3.5 ` +
        'он уезжал на полметра в секунду и разрыв только рос'
    );
  });

  it('отставание не зависит от частоты кадров', () => {
    const тридцать = отставание(30, СКАКУН, 3);
    const сто = отставание(144, СКАКУН, 3);
    must(
      Math.abs(тридцать - сто) < 0.2,
      `на 30 кадрах отставание ${тридцать.toFixed(2)} м, на 144 — ${сто.toFixed(2)} м: ` +
        'на слабом компьютере чужие тела едут иначе'
    );
  });

  it('медленная цель по-прежнему догоняется', () => {
    // Сглаживание не должно превращаться в «медленное появление»: шаг должен
    // идти быстрее медленной цели, иначе игроки выглядели бы скользящими.
    const шаг = отставание(60, 4.2, 3);
    must(шаг < 0.5, `идущий игрок отстаёт на ${шаг.toFixed(2)} м — сглаживание слишком вялое`);
  });
});

describe('Как это сделано в коде', () => {
  it('берётся доля пути за кадр, а не ограничение скорости', () => {
    must(
      /const доля = 1 - Math\.exp\(-dt \/ СГЛАЖИВАНИЕ_С\);/.test(СУЩНОСТИ),
      'сглаживания по времени нет: чужие тела снова догоняют с ограничением скорости'
    );
    must(
      /pos\.x \+= dx \* доля;/.test(СУЩНОСТИ),
      'шаг не берётся долей расстояния'
    );
    must(
      !/lerp\(p\.pos, p\.target, 6\)/.test(СУЩНОСТИ),
      'предел 6 ед/с для чужих игроков вернулся: верховой скакун для всех едет втрое медленнее'
    );
    must(
      !/m\.speed/.test(СУЩНОСТИ) && !/m\.speed/.test(МИР),
      'у монстра снова появилась скорость интерполяции, вбитая константой'
    );
  });

  it('вбитых скоростей монстров больше нет', () => {
    must(!/speed: 3\.5/.test(МИР), 'в коде снова появилась константа 3.5 для всех монстров');
    must(!/m\.speed = 3\.2/.test(МИР), 'в коде снова появилась константа 3.2 на пакетах перемещения');
  });

  it('большой разрыв закрывается сразу', () => {
    // Телепорт, воскрешение и появление из-за края: сглаживать такое бессмысленно,
    // объект долго летел бы через полкарты к настоящей позиции.
    must(
      /if \(dist > ЩЕЛЧОК_М\) \{ pos\.x = target\.x; pos\.z = target\.z; return true; \}/.test(СУЩНОСТИ),
      'большой разрыв не закрывается сразу: после телепорта объект будет долго долетать'
    );
  });

  it('сглаживание не выкидывает признак движения', () => {
    // moving отвечает за анимацию шага. При долевом сглаживании расстояние никогда
    // не обнуляется, поэтому без порога объект «бежал бы» на месте.
    must(
      /if \(dist < 0\.02\) \{ pos\.x = target\.x; pos\.z = target\.z; return false; \}/.test(СУЩНОСТИ),
      'нет порога, на котором объект считается дошедшим: анимация шага не выключится'
    );
  });
});