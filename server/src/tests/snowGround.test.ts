// Снег на земле.
//
// ЧТО БЫЛО (21 октября 2026, §262). Погода со снегом в мире есть, а земля под
// ним оставалась летней, песчаной: снег идёт, а мир под ним — тот же. Тот же
// провал, что был с дождём, только наоборот.
//
// ЧТО ТЕПЕРЬ. В снег земля белеет: снег ложится ПОВЕРХ, поэтому белеют
// вершинные цвета земли, а не красится песок. Снег лежит долго — дольше, чем
// сохнет вода, — и тает медленно.
//
// ЧТО ПРОВЕРЯЕТСЯ. Снег идёт от погоды; вершинные цвета земли уходят в белый;
// исходные цвета сохранены (иначе после таяния земля осталась бы серой);
// перекраска идёт шагом, а не каждый кадр — вершин десятки тысяч.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Снег на земле', () => {
  it('снег идёт от погоды и лежит дольше, чем сохнет вода', () => {
    должен(
      /const идётСнег = this\.currentWeather === 'snow';/.test(МИР),
      'снег не зависит от погоды',
    );
    // Набирается медленно (снег идёт не так быстро, как дождь)...
    должен(
      /this\.снег = Math\.min\(1, this\.снег \+ dt \* 0\.\d+\)/.test(МИР),
      'снег не ложится на землю',
    );
    // ...и тает ещё медленнее.
    должен(
      /this\.снег = Math\.max\(0, this\.снег - dt \* 0\.\d+\)/.test(МИР),
      'снег не тает',
    );
    должен(
      /setGroundState\(this\.мокрота, this\.снег\);/.test(МИР),
      'снег не передаётся земле',
    );
  });

  it('земля белеет вершинными цветами, а не покраской песка', () => {
    // Исходные цвета сохранены: без них после таяния земля осталась бы се��ой.
    должен(/цветаЗемли = colors\.slice\(\);/.test(ТЕРРЕЙН), 'исходные цвета земли не сохранены');
    // Атрибут вершинных цветов доступен для перекраски.
    должен(
      /материал\.userData\.цвета = цветАтрибут;/.test(ТЕРРЕЙН),
      'атрибут вершинных цветов не отдан материалу: снегу нечего белить',
    );
    // Перекраска идёт к белому.
    должен(
      /массив\[i\] = цветаЗемли\[i\] \+ \(ЦВЕТ_СНЕГА\.r - цветаЗемли\[i\]\) \* с;/.test(ТЕРРЕЙН),
      'снег не белит землю',
    );
    // И перекраска не каждый кадр: вершин десятки тысяч.
    должен(
      /if \(Math\.abs\(снегЗемли - с\) < 0\.02\) return;/.test(ТЕРРЕЙН),
      'земля перекрашивается каждый кадр: это дорого',
    );
  });

  it('мостовая города тоже белеет под снегом', () => {
    должен(
      /MAT\.street\.color\.setHex\(0x9a8a68\)\.multiplyScalar\(1 - 0\.26 \* м\)\.lerp\(ЦВЕТ_СНЕГА, с \* 0\.85\);/.test(
        ТЕРРЕЙН,
      ),
      'мостовая города не белеет под снегом',
    );
  });
});
