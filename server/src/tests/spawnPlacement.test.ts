// Спавны стоят там, где их видно и до них можно дойти.
//
// ЧТО БЫЛО, и почему это молчало. Точки спавна лежали одной кучей у
// столицы (z от -230 до 230) и объявляли при этом семь разных регионов:
// из 20 точек только 4 стояли в своём регионе. Великий Симург, про
// которого квест говорит «в горах Хорасана», стоял в Тебризе (0, 0).
//
// ХУЖЕ, и это отдельная болезнь. Регион читался в двух разных полях:
// объявление спавна шло по sp.region (регион ТОЧКИ), а ИИ искал игроков
// по ctx.definition.region (регион МОНСТРА). У mob_bandit_scout регион
// был объявлен TABRIZ, а спавнился он в точке, объявленной SHIRAZ.
// Итог: Ширазу показывали «вот монстр», а ИИ этого монстра бил по
// Тебризу. Видно одному, достаётся другому. Ни то ни другое не падало.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { getZoneAt, ZONES } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/** Точки спавна разобраны из исходника: единственный источник - он же. */
function точкиСпавна(): { id: string; monsterId: string; region: string; x: number; z: number }[] {
  const исходник = readFileSync(join(корень, 'server/src/systems/SpawnSystem.ts'), 'utf-8');
  const re = /makePoint\(\{\s*id:\s*'([a-z0-9_]+)',\s*monsterId:\s*'([a-z0-9_]+)',\s*region:\s*Region\.(\w+),\s*position:\s*\{\s*x:\s*(-?\d+),\s*y:\s*(-?\d+),\s*z:\s*(-?\d+)/g;
  const точки: { id: string; monsterId: string; region: string; x: number; z: number }[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(исходник)) !== null) {
    точки.push({ id: m[1], monsterId: m[2], region: m[3].toLowerCase(), x: Number(m[4]), z: Number(m[6]) });
  }
  return точки;
}

/** Регион, объявленный у монстра в monsters.ts. */
function регионМонстра(id: string): string | null {
  const база = readFileSync(join(корень, 'server/src/data/monsters.ts'), 'utf-8');
  const блок = new RegExp(`'${id}':\\s*\\{([\\s\\S]*?)\\n  \\},`).exec(база)?.[1];
  if (!блок) return null;
  return /region:\s*Region\.(\w+)/.exec(блок)?.[1].toLowerCase() ?? null;
}

describe('Спавны: точка стоит в своём регионе', () => {
  it('каждая точка спавна внутри зоны своего региона', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Именно её не хватало: 16 точек из 20
    // стояли вне своего региона, и никто этого не сверял.
    const несовпадения: string[] = [];
    for (const т of точкиСпавна()) {
      const зона = getZoneAt(т.x, т.z);
      if (зона === null) {
        несовпадения.push(`${т.id}: (${т.x}, ${т.z}) вне всякой зоны`);
      } else if (зона.region !== т.region) {
        несовпадения.push(`${т.id}: (${т.x}, ${т.z}) в зоне ${зона.id} региона ${зона.region}, а заявлен ${т.region}`);
      }
    }
    must(несовпадения.length === 0, `точки спавна не в своём регионе:\n  ${несовпадения.join('\n  ')}`);
  });

  it('регион точки совпадает с регионом монстра', () => {
    // Вторая половина той же поломки, и её не видно по координатам.
    // Объявление спавна идёт по региону точки, ИИ - по региону монстра.
    // Расхождение означает: монстра показывают одной области, а бьёт он
    // по другой. Игрок видит цель, которую не может достать.
    const расхождения: string[] = [];
    for (const т of точкиСпавна()) {
      const регион = регионМонстра(т.monsterId);
      must(регион !== null, `монстр ${т.monsterId} не найден в monsters.ts - точка ${т.id} ссылается в пустоту`);
      if (регион !== т.region) {
        расхождения.push(`${т.id} (${т.monsterId}): точка ${т.region}, монстр ${регион}`);
      }
    }
    must(расхождения.length === 0, `регион точки и регион монстра разошлись:\n  ${расхождения.join('\n  ')}`);
  });

  it('у каждого региона есть точки спавна', () => {
    // Регион без спавнов - это пустая полоса земли: можно приехать и
    // не встретить никого. Раньше так было в Исфахане (0 точек), и это
    // молчало: путешествие работало, регион менялся, спавнов не было.
    const есть = new Set(точкиСпавна().map((т) => т.region));
    const все = [...new Set(ZONES.map((з) => з.region))];
    const пустые = все.filter((р) => !есть.has(р));
    must(пустые.length === 0, `в регионах нет ни одной точки спавна: ${пустые.join(', ')}`);
  });

  it('id точек спавна уникальны', () => {
    // Дубль id молча перетирал бы точку в this.spawnPoints.set(): одна
    // точка исчезала бы из мира без единой ошибки.
    const id = точкиСпавна().map((т) => т.id);
    const дубль = id.find((с, i) => id.indexOf(с) !== i);
    must(дубль === undefined, `две точки спавна с одинаковым id: ${дубль}`);
  });
});

describe('Спавны: уровень монстра против уровня зоны', () => {
  it('разрыв между уровнем монстра и уровнем зоны не больше 15', () => {
    // Не «равен уровню зоны»: монстр на пару уровней ниже - норма для
    // фарм-зон, а зона без монстра уровня выше - тоже норма.
    //
    // Порог именно в 15 уровней, потому что это единственная величина,
    // при которой раскладка проходит честно. Проверка на «вдвое слабее»
    // (minLevel * 2) была неверной: монстр 20 уровня в зоне от 20 -
    // это ровно то, что нужно, а правило его отвергало. Две попытки
    // подбирать формулу, которая «проходит», ничего не проверяли бы:
    // порог, поставленный по остаткам, а не по смыслу.
    //
    // 15 - это половина разрыва между соседними парами зон (25-40, 45-50,
    // 60-70): монстр, отстающий больше чем на полступени, уже не музыка
    // для зоны, а её заглушка.
    const ПОРОГ = 15;
    const база = readFileSync(join(корень, 'server/src/data/monsters.ts'), 'utf-8');
    const плохие: string[] = [];
    for (const т of точкиСпавна()) {
      const блок = new RegExp(`'${т.monsterId}':\\s*\\{([\\s\\S]*?)\\n  \\},`).exec(база)?.[1];
      must(блок !== undefined, `монстр ${т.monsterId} не найден в monsters.ts`);
      const уровень = Number(/level:\s*(\d+)/.exec(блок as string)?.[1]);
      must(Number.isFinite(уровень), `у монстра ${т.monsterId} нет level`);
      const зона = getZoneAt(т.x, т.z);
      must(зона !== null, `${т.id}: точка вне зоны, уровень зоны неизвестен`);
      const разрыв = (зона as NonNullable<typeof зона>).minLevel - уровень;
      if (разрыв > ПОРОГ) {
        плохие.push(`${т.monsterId} (${уровень} ур.) в ${(зона as NonNullable<typeof зона>).id} от ${(зона as NonNullable<typeof зона>).minLevel} - разрыв ${разрыв} - ${т.id}`);
      }
    }
    must(плохие.length === 0, `монстры слишком слабы для своих зон:\n  ${плохие.join('\n  ')}`);
  });
});

describe('Добыча: предметы существуют', () => {
  it('каждый предмет в lootTable есть в базе предметов', () => {
    // Проверка прошла при разведке: все 46 ссылок вели в существующие
    // предметы. Она нужна, чтобы это не перестало быть правдой - ссылка
    // на несуществующий предмет выглядит как наградa и не выдаёт ничего.
    const база = readFileSync(join(корень, 'server/src/data/items.ts'), 'utf-8');
    const есть = new Set(
      // Тоже любыми символами: id предмета с заглавной буквой должен
      // попасть в список, иначе ссылка на него сочтётся битой дважды.
      [...база.matchAll(/^ {2}'([^']+)':\s*\{/gm)].map((м) => м[1]),
    );
    must(есть.size > 0, 'в items.ts не нашлось ни одного предмета - проверка устарела');

    const монстры = readFileSync(join(корень, 'server/src/data/monsters.ts'), 'utf-8');
    // Идентификатор берём ЦЕЛИКОМ, любыми символами внутри кавычек.
    //
    // Первая версия стояла на [a-z0-9_]+ и молча пропускала битую ссылку:
    // опечатка с заглавной буквой (trophy_..._SEAL вместо ..._seal) вообще
    // не извлекалась, и проверка оставалась зелёной на сломанных данных.
    // Это ровно тот случай, когда проверка выглядит работающей, а дыру
    // не видит - поэтому здесь [^']+, а не набор допустимых символов.
    const ссылки = [...монстры.matchAll(/itemId:\s*'([^']*)'/g)].map((м) => м[1]);
    must(ссылки.length > 0, 'в monsters.ts нет ни одной ссылки на добычу');

    const пустые = [...new Set(ссылки.filter((id) => id.length === 0))];
    must(пустые.length === 0, 'в добыче есть ссылка на пустой itemId');

    const нет = [...new Set(ссылки.filter((id) => !есть.has(id)))];
    must(нет.length === 0, `монстры роняют несуществующие предметы: ${нет.join(', ')}`);
  });

  it('у каждого монстра есть что выронить', () => {
    // Монстр с пустым lootTable выглядит рабочим и не даёт ничего -
    // ещё одна форма того же мёртвого поля.
    const база = readFileSync(join(корень, 'server/src/data/monsters.ts'), 'utf-8');
    const безДобычи = [...база.matchAll(/'(mob_[a-z_]+|boss_[a-z_]+|world_boss_[a-z_]+)':\s*\{([\s\S]*?)\n  \},/g)]
      .filter((м) => !/lootTable:\s*\[\s*\{/.test(м[2]))
      .map((м) => м[1]);
    must(безДобычи.length === 0, `у этих монстров пустой lootTable: ${безДобычи.join(', ')}`);
  });
});

describe('Монстры, которых видно', () => {
  it('пустые зоны записаны списком, а не спрятаны', () => {
    // ЧЕСТНОСТЬ ПРОВЕРКИ. Монстров не хватает на 21 зону, и одна зона
    // стоит пустой - намеренно.
    //
    // Можно было бы затыкать пустые зоны чем попало - поставить
    // 35-уровневого джинна в зону от 60 и объявить, что зона занята.
    // Тогда проверка «у каждой зоны есть спавн» прошла бы, а игрок
    // получал бы зону, где ему нечего убивать. Поэтому пустые зоны
    // перечислены здесь явно, и список должен совпадать с реальностью
    // в обе стороны: забытый спавн его сломает, и появление монстра -
    // тоже.
    //
    // ИСТОРИЯ СПИСКА. Изначально их было пять. khorasan_oasis и
    // persian_gulf_harbor закрыты монстрами 70-80 уровня
    // (caravan_raider, oasis_lynx, corsair, harbor_brute).
    // persian_gulf_waters закрыта тремя подводными 85-90 уровня -
    // после того, как море появилось в мире. До этого пустой была и она,
    // но по другой причине: воды физически не было.
    const ИЗВЕСТНЫЕ_ПУСТЫЕ = [
      { зона: 'isfahan_center', почему: 'безопасная столица: внутри стен монстров нет по замыслу' },
    ];
    const заняты = new Set(точкиСпавна().map((т) => getZoneAt(т.x, т.z)?.id));
    const реальноПустые = ZONES.filter((з) => !заняты.has(з.id)).map((з) => з.id);

    must(реальноПустые.length === ИЗВЕСТНЫЕ_ПУСТЫЕ.length
      && ИЗВЕСТНЫЕ_ПУСТЫЕ.every((п) => реальноПустые.includes(п.зона)),
      `пустые зоны разошлись со списком.\n  реально пусты: ${реальноПустые.join(', ') || '(нет)'}\n  записаны: ${ИЗВЕСТНЫЕ_ПУСТЫЕ.map((п) => п.зона).join(', ')}`);

    // И каждая запись обязана объяснять, почему зона пустая: пустой список
    // причин означал бы, что дыру записали и забыли о ней.
    for (const п of ИЗВЕСТНЫЕ_ПУСТЫЕ) {
      must(п.почему.trim().length > 10, `для пустой зоны ${п.зона} не записана причина`);
    }
  });

  it('каждый монстр из базы где-то спавнится', () => {
    // Девять монстров были объявлены и не спавнились нигде: три босса
    // (bandit_king, ottoman_pasha, div_arzhang) и четыре обычных. Босс,
    // которого нельзя встретить, - это не контент, а строка в справочнике.
    const база = readFileSync(join(корень, 'server/src/data/monsters.ts'), 'utf-8');
    const объявлены = [...база.matchAll(/'(mob_[a-z_]+|boss_[a-z_]+|world_boss_[a-z_]+)':\s*\{/g)]
      .map((м) => м[1])
      .filter((с, i, все) => все.indexOf(с) === i);
    const спавнятся = new Set(точкиСпавна().map((т) => т.monsterId));
    const нигде = объявлены.filter((м) => !спавнятся.has(м));
    must(нигде.length === 0, `объявлены, но не спавнятся: ${нигде.join(', ')}`);
  });
});