// Баг: монстры подземелий появлялись в начале координат, то есть в центре
// города. Позиции комнат локальные (8, 0, 5), а спавн брал их как мировые.
//
// ЧТО ЗАЩИЩАЕТ. Три вещи:
//   1. у каждого подземелья есть точка входа в мире;
//   2. спавн идёт ОТ ТОЧКИ ВХОДА, а не от нуля;
//   3. ни одна точка входа не стоит в начале координат — иначе баг вернётся.
//
// Проверка меряет числами: берёт локальные позиции комнат, прибавляет точку
// входа и проверяет, что результат далеко от нуля. Иначе проверка начнёт
// искать слово «entryX» и сможет пропустить именно тот случай, когда поле
// есть, а спавн его не использует.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { DUNGEONS_DATABASE } from '../data/dungeons';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const сервис = код('server/src/systems/DungeonService.ts');
const определения = Object.entries(DUNGEONS_DATABASE);

describe('Точка входа: монстры не появляются в начале координат', () => {
  it('у каждого подземелья задана точка входа', () => {
    for (const [id, def] of определения) {
      must(
        typeof def.entryX === 'number' && typeof def.entryZ === 'number',
        `у подземелья ${id} нет точки входа: монстры появятся в начале координат`
      );
    }
  });

  it('спавн идёт от точки входа, а не от нуля', () => {
    must(
      /spawnMonster\([\s\S]{0,220}def\.entryX \+ pos\.x/.test(сервис),
      'спавн не прибавляет точку входа: монстры снова окажутся в начале координат'
    );
    must(/def\.entryZ \+ pos\.z/.test(сервис), 'по оси z точка входа не прибавляется');
    must(
      !/spawnMonster\(monsterDef, pos, session\.shardId\)/.test(сервис),
      'спавн всё ещё идёт по локальной позиции без сдвига'
    );
  });

  it('точки входа далеко от начала координат', () => {
    // Именно это и было поломкой: спавн в (8, 0, 5), то есть рядом с нулём.
    for (const [id, def] of определения) {
      const расстояние = Math.hypot(def.entryX, def.entryZ);
      must(
        расстояние > 200,
        `точка входа ${id} в ${distance(def)} от начала координат: монстры появятся на площади`
      );
    }
  });

  it('точки входа не совпадают между собой', () => {
    // Иначе все пять подземелий стягивали бы врагов в одну кучу.
    const пары: [string, number][] = [];
    for (const [id, def] of определения) {
      for (const [другойId, другой] of определения) {
        if (id === другойId) continue;
        пары.push([`${id} и ${другойId}`, Math.hypot(def.entryX - другой.entryX, def.entryZ - другой.entryZ)]);
      }
    }
    const слишкомБлизко = пары.filter(([, d]) => d < 100);
    must(
      слишкомБлизко.length === 0,
      `точки входа почти совпадают: ${слишкомБлизко.map(([имя]) => имя).join(', ')}`
    );
  });

  it('проверка не холостая: ноль действительно провалил бы её', () => {
    // Нулевая точка входа — ровно тот случай, который был в коде.
    const расстояниеНуля = Math.hypot(0, 0);
    must(расстояниеНуля <= 200, 'нулевая точка входа прошла бы проверку: она ничего не проверяет');
  });
});

describe('Точка входа: комнаты остались на месте', () => {
  it('позиции комнат не изменились', () => {
    // Точка входа прибавляется при спавне, а не вписывается в данные: иначе
    // комнаты «поехали» бы вместе с монстрами, а вывод о геометрии изменился бы.
    for (const [id, def] of определения) {
      for (const комната of def.rooms) {
        for (const группа of комната.monsters) {
          for (const позиция of группа.positions) {
            must(
              Math.abs(позиция.x) < 200 && Math.abs(позиция.z) < 200,
              `позиция ${позиция.x}, ${позиция.z} в ${id} перестала быть локальной: ` +
                'она уже мировая, и точка входа прибавится второй раз'
            );
          }
        }
      }
    }
  });

  it('число комнат и монстров не изменилось', () => {
    const всего = определения.reduce(
      (с, [, def]) => с + def.rooms.length,
      0
    );
    must(всего >= 13, `комнат всего ${всего}: ожидалось не меньше 13 (по данным миграции 010)`);
  });
});

function distance(def: { entryX: number; entryZ: number }): string {
  return Math.hypot(def.entryX, def.entryZ).toFixed(0);
}
