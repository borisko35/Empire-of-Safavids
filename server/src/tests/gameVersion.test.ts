// Версия игры объявлена в одном месте и нигде не расходится.
//
// ЗАЧЕМ. Версия показывается игроку в двух местах — в меню персонажа и
// в ответе /health, — и раньше ещё была захардкожена в разметке отдельно от
// константы. Итог был предсказуем: в меню одна цифра, на сервере другая, и
// никто этого не замечал, потому что расхождение видно только тому, кто
// специально сверит.
//
// ЧТО ЗАЩИЩАЕМ. Во-первых, сама константа: формат и осмысленность. Во-
// вторых, её единственность: любое другое место в исходниках, где вручную
// написана та же версия, — расхождение по определению, потому что
// вспомнить его обновить невозможно.
//
// ГДЕ ИСКАТЬ. Только исходники: shared, server/src, client/src, client/web
// (без собранных пакетов в client/web/game/assets — они не отслеживаются git
// и пересобираются при выкатке) и site. Файлы в node_modules и
// package-lock пропускаются: там «0.3.0» встречается как версия чужих
// пакетов npm и к игре отношения не имеет.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { GAME_VERSION } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

/** Все файлы в каталоге, кроме node_modules, dist и собранных пакетов игры */
function файлы(dir: string, out: string[] = []): string[] {
  for (const имя of readdirSync(dir)) {
    if (имя === 'node_modules' || имя === 'dist' || имя === '.git') continue;
    const полный = join(dir, имя);
    if (statSync(полный).isDirectory()) {
      // Собранные бандлы игры не отслеживаются и не должны хранить версию
      if (полный.endsWith(join('web', 'game', 'assets'))) continue;
      файлы(полный, out);
    } else if (/\.(ts|js|html|json|md)$/.test(имя)) {
      out.push(полный);
    }
  }
  return out;
}

describe('Версия игры объявлена один раз', () => {
  it('GAME_VERSION записана в принятом формате', () => {
    must(
      /^\d+\.\d+\.\d+$/.test(GAME_VERSION),
      `GAME_VERSION = «${GAME_VERSION}», а ждём три числа через точку, например 0.4.0`,
    );
    const части = GAME_VERSION.split('.').map(Number);
    // Мажор 0 законен: игра ещё не вышла из первой версии. Первая
    // проверка требовала главная > 0 и отвергала бы любую версию вида
    // 0.4.0 — то есть проверяла не то.
    must(
      части.every((ч) => Number.isInteger(ч) && ч >= 0),
      `GAME_VERSION = «${GAME_VERSION}»: все три части должны быть целыми неотрицательными числами`,
    );
  });

  it('версия не написана руками больше нигде в исходниках', () => {
    // Ищем именно текущую версию. Старая («0.3.0») в чужих пакетах npm
    // не мешает, а вот «0.4.0» где-то ещё — это копия, которая завтра
    // разойдётся с константой.
    const каталоги = ['shared', 'server/src', 'client/src', 'client/web', 'site', 'tools']
      .map((п) => join(корень, п))
      .filter((п) => {
        try { statSync(п); return true; } catch { return false; }
      });
    must(каталоги.length >= 4, `Нашлось ${каталоги.length} каталогов для проверки, ожидалось не меньше четырёх — пути изменились`);

    const совпадения: string[] = [];
    for (const файл of каталоги.flatMap((п) => файлы(п))) {
      const код = readFileSync(файл, 'utf-8');
      if (код.includes('package-lock')) continue;
      код.split(/\r?\n/).forEach((строка, индекс) => {
        if (!строка.includes(GAME_VERSION)) return;
        const относ = relative(корень, файл);
        // Объявление константы — это и есть источник истины, оно законно.
        if (относ === join('shared', 'constants.ts') && /GAME_VERSION\s*=/.test(строка)) return;
        // Упоминание в этом файле проверки тоже законно: он знает версию
        // по необходимости и падает, если она не та.
        if (относ.includes(join('src', 'tests')) && относ.endsWith('gameVersion.test.ts')) return;
        совпадения.push(`${относ}:${индекс + 1}  ${строка.trim().slice(0, 70)}`);
      });
    }

    must(
      совпадения.length === 0,
      `Версия «${GAME_VERSION}» написана руками ещё здесь — это копия, которая разойдётся с константой при следующем обновлении:\n  ${совпадения.join('\n  ')}`,
    );
  });

  it('версия не зашита в разметку меню', () => {
    // В index.html лежит заглушка «v—», которую заполняет клиент из
    // GAME_VERSION. Если там появится «v0.4.0», до первой загрузки скрипта
    // игрок увидит прошлую версию — и на старой странице из кэша.
    const разметка = readFileSync(join(корень, 'client/web/game/index.html'), 'utf-8');
    const строкаВерсии = /id="menu-version"[^>]*>([^<]*)</.exec(разметка);
    must(строкаВерсии, 'В client/web/game/index.html нет элемента #menu-version — версия не показывается в меню');
    must(
      !/\d+\.\d+\.\d+/.test(строкаВерсии[1]),
      `В разметке #menu-version зашита версия «${строкаВерсии[1]}». Должна быть заглушка: значение подставляет клиент из GAME_VERSION.`,
    );
  });

  it('сервер отдаёт эту версию в /health', () => {
    // Тот самый ответ, который бейдж лендинга показывает игроку. Проверяем
    // текстом исходника: маршрут собирает объект из GAME_VERSION, и если
    // когда-нибудь там появится литерал, игрок увидит чужую цифру.
    const код = readFileSync(join(корень, 'server/src/index/index.ts'), 'utf-8');
    const маршрут = /app\.get\(\s*'\/health'[\s\S]{0,400}?\}/.exec(код);
    must(маршрут, "Не нашёл маршрут app.get('/health') в server/src/index/index.ts");
    must(
      /version:\s*GAME_VERSION/.test(маршрут[0]),
      'В /health версия не берётся из GAME_VERSION — ответ может разойтись с константой',
    );
    must(
      !/version:\s*'/.test(маршрут[0]),
      "В /health версия написана строкой, а не из GAME_VERSION",
    );
  });
});
