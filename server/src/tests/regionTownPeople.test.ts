// Жители городов регионов.
//
// ЧТО БЫЛО (21 октября 2026, §253). Девять городов регионов (Хорасан, Тебриз,
// Шираз, Кавказ, Месопотамия, Залив, Герат, Застава, Маяк) стояли без единого
// человека: стены, дома, торговые ряды и колодец на месте, а жителей нет.
// Город без жителей читается как макет.
//
// ЧТО ТЕПЕРЬ. По два жителя в каждом городе: стражник у ворот (рядом с фонарём
// §250) и торговец на площади.
//
// ЧТО ПРОВЕРЯЕТСЯ. Группы жителей строятся по списку городов регионов; смещение
// считается ОТ ГОРОДА (и потому масштабируется радиусом), имена у городов
// разные; и анимация дальних жителей не пересчитывается — иначе восемнадцать
// новых фигур утяжелили бы каждый кадр.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const NPC = читать('client/src/app/game3d/npc.ts');
const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts') + читать('shared/terrainHeight.ts');

describe('Жители городов регионов', () => {
  it('группы жителей строятся по списку городов', () => {
    должен(/import \{[^}]*REGION_TOWNS[^}]*\} from '\.\/terrain'/.test(NPC),
      'список городов регионов не импортирован');
    должен(/\.\.\.REGION_TOWNS\.map\(группаГорода\)/.test(NPC),
      'жители городов регионов не добавляются в общий список');
    // Список городов — девять.
    const города = (ТЕРРЕЙН.match(/\{ region: '/g) || []).length;
    должен(города === 9, `в мире ${города} городов регионов, а жители заведены под девять`);
  });

  it('жители стоят в своём городе и имена у городов разные', () => {
    // Смещение — от города и масштабом радиуса: город сдвинется — жители
    // поедут вместе с ним.
    должен(/dx: t\.radius \* 0\.12,/.test(NPC), 'стражник стоит не по своему городу');
    должен(/dz: t\.radius \* 0\.78,/.test(NPC), 'стражник стоит не у ворот');
    должен(/dx: t\.radius \* 0\.45,/.test(NPC), 'торговец стоит не на площади');
    // Имена — разные на каждый город.
    const имена = (NPC.match(/\[('[А-ЯЁ][^']*', '[А-ЯЁ][^']*')\]/g) || []).length;
    должен(имена >= 9, `разных имён для городов только ${имена}: города станут неразличимы`);
    const уникальные = new Set(
      (NPC.match(/\['[А-ЯЁ][^']*', '[А-ЯЁ][^']*'\]/g) || []).map(s => s),
    ).size;
    должен(уникальные === имена, 'имена городов повторяются');
  });

  it('анимация дальних жителей не пересчитывается', () => {
    // Восемнадцать новых фигур не должны утяжелять каждый кадр: поза камерой
    // пересчёт позы никто не видит.
    должен(
      /if \(камера && Math\.hypot\(r\.x - камера\.x, r\.z - камера\.z\) > 70\) continue;/.test(NPC),
      'дальние жители пересчитываются каждый кадр: кадр потяжелеет',
    );
    должен(/rigs\.push\(\{ update: \(dt, p\) => rig\.update\(dt, p\), x, z/.test(NPC),
      'у записи жителя нет координат: отсечь его от кадра нечем',
    );
  });
});
