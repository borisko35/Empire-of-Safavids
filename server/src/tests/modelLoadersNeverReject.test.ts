// Загрузчик модели обязан отдавать null, а не отказывать.
//
// ЧТО ЗДЕСЬ. Тридцать пять мест в клиенте написаны так:
//
//   void loadDecorModel('decor/oak.glb').then((модель) => { ... });
//
// `.then` без `.catch`. Такая запись работает ровно при одном условии: отказа
// быть не может. Проверено пересчётом по всему клиенту - именно такая форма
// там и есть, и именно поэтому молчание уместно.
//
// ЧТО БЫЛО БЫ, ЕСЛИ БЫ УСЛОВИЕ ПЕРЕСТАЛО ВЫПОЛНЯТЬСЯ. Загрузчики отдают `null`
// через две точки: колбэк ошибки загрузчика и `catch` на синхронный сбой.
// Стоит убрать одну из них - или переписать промис на `async`, где любая
// выброшенная ошибка становится отказом, - и отказ начнёт подниматься наружу.
// Тогда `.then` не выполнится вообще, и место, которое должно было поставить
// замену (дерево, мост, жителя), молча её не поставит. Карта останется без
// дерева, и никто не скажет почему: в консоли будет rejections без текста.
//
// ТА ЖЕ ФОРМА, ЧТО В §152 И §154. Там отказ тоже не доходил до того, кто умел
// с ним обойтись, и игрок видел последствие без причины. Здесь ровно тот же
// механизм, просто на тридцати пяти местах сразу.
//
// ПОЧЕМУ ПРОВЕРКА ТЕКСТОВАЯ, А ПО-НАСТОЯЩЕМУ. Запускать браузер в юнит-тесте
// нельзя, а свойство здесь одно и оно видно в исходнике: у промис-загрузчика
// есть ветка отказа, и она отдаёт null. Всё остальное проверка сознательно не
// пытается делать - она и не сможет.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Кириллица в причинах иероглифами не печатается, но на условие это не влияет.
function должно(условие: unknown, причина: string): void {
  должен(условие, причина);
}

/**
 * Комментарии вырезаются: пояснение о поломке стоит прямо над местом поломки,
 * и без вырезания оно само попадёт под проверку. Тот же класс ошибки, что в 142,
 * 152, 153, 154 и 156, - в шестой раз.
 */
function код(исходник: string): string {
  return исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
}

/** Тело функции по балансу скобок: регулярка обрывалась бы на `готово(null)`. */
function телоФункции(исходник: string, позиция: number): string {
  let i = исходник.indexOf('{', позиция);
  if (i < 0) return '';
  const начало = i;
  let глубина = 0;
  for (; i < исходник.length; i++) {
    if (исходник[i] === '{') глубина++;
    else if (исходник[i] === '}') {
      глубина--;
      if (глубина === 0) return исходник.slice(начало, i + 1);
    }
  }
  return '';
}

type Файл = { путь: string; код: string };

function читатьКлиентскиеФайлы(): Файл[] {
  const кореньКлиента = join(корень, 'client', 'src');
  const найдено: Файл[] = [];
  const обойти = (папка: string): void => {
    for (const имя of readdirSync(папка)) {
      const полный = join(папка, имя);
      if (statSync(полный).isDirectory()) {
        обойти(полный);
        continue;
      }
      if (!имя.endsWith('.ts')) continue;
      найдено.push({
        путь: полный.slice(кореньКлиента.length + 1).replace(/\\/g, '/'),
        код: код(readFileSync(полный, 'utf-8')),
      });
    }
  };
  обойти(кореньКлиента);
  return найдено;
}

const ФАЙЛЫ = читатьКлиентскиеФайлы();

/** Загрузчики: функция, возвращающая промис, который сама и разрешает. */
const ЗАГРУЗЧИКИ = ФАЙЛЫ.flatMap((ф) =>
  // Имя функции — целиком в своём классе символов, а не «первая буква плюс
  // `\w*`. `\w` в JavaScript — это латиница, цифры и подчёркивание, поэтому
  // `\w*` после первой кириллической буквы не идёт НИ ОДНОГО символа, и
  // `загрузитьСцену` не находилась вообще. Из-за этого же `\b` не работает
  // перед кириллицей. Обе ловушки одного класса, и обе уже словились здесь.
  [...ф.код.matchAll(/function\s+([A-Za-zа-яА-Я_0-9]+)\s*\([^)]*\)\s*:\s*Promise</g)]
    .map((m) => ({
      имя: m[1],
      путь: ф.путь,
      тело: телоФункции(ф.код, m.index + m[0].length),
    }))
    .filter((з) => /new\s+Promise\s*</.test(з.тело) && /готово\s*\(/.test(з.тело)),
);

describe('Загрузчики моделей отдают null, а не отказ', () => {
  it('обход клиента не ослеп', () => {
    должно(
      ФАЙЛЫ.length > 20,
      'обход клиента нашёл подозрительно мало файлов: проверка ослепла',
    );
    // Если загрузчики перестанут попадать под выражение, проверка станет
    // «всё хорошо» ни разу не сработав. Ноль загрузчиков - тоже поломка.
    должно(
      ЗАГРУЗЧИКИ.length >= 6,
      `найдено загрузчиков: ${ЗАГРУЗЧИКИ.length}, ожидалось не меньше 6. ` +
        'Либо их переписали в другую форму, либо проверка перестала их видеть',
    );
  });

  it('у каждого загрузчика есть ветка отказа, и она отдаёт null', () => {
    const виновники: string[] = [];
    for (const з of ЗАГРУЗЧИКИ) {
      // Две точки отказа обязаны быть обе. Первая - сетевой сбой загрузки,
      // вторая - синхронный сбой (нет загрузчика, битый путь, нет GL-контекста).
      // `\b` перед кириллицей не годится: в регулярках JavaScript `\w` — это
      // только латиница и цифры, а `г` в `\bготово` не считается символом слова,
      // поэтому границы там просто нет и выражение не срабатывает НИКОГДА.
      // Проверка на слепоту ниже сработала именно на этом и заставила смотреть.
      const разрешает = /готово\s*\(/.test(з.тело);
      const сетевойСбой = /\(\s*\)\s*=>\s*готово\s*\(\s*null\s*\)/.test(з.тело);
      const синхронныйСбой = /\bcatch\b/.test(з.тело);
      if (!разрешает || !сетевойСбой || !синхронныйСбой) {
        виновники.push(
          `${з.путь}: ${з.имя} (разрешает=${разрешает}, сеть=${сетевойСбой}, синхрон=${синхронныйСбой})`,
        );
      }
    }
    должно(
      виновники.length === 0,
      `загрузчик перестал отдавать null и может отказать: ${виновники.join('; ')}. ` +
        'Тридцать пять мест .then без .catch тогда перестанут ставить замену',
    );
  });

  it('места, которые держатся на этом свойстве, всё ещё есть', () => {
    // Обратная сторона: если таких мест не осталось, то либо правки (§157) уже
    // доделали все цепочки, либо regex разучился их находить - и охранять
    // больше нечего, а проверка молчит.
    let мест = 0;
    for (const ф of ФАЙЛЫ) {
      const строки = ф.код.split('\n');
      for (let i = 0; i < строки.length; i++) {
        if (!/\.then\s*\(/.test(строки[i])) continue;
        if (/\.catch\s*\(/.test(строки[i])) continue;
        if (/^\s*\.(catch|finally)\s*\(/.test(строки[i + 1] ?? '')) continue;
        мест++;
      }
    }
    должно(
      мест > 0,
      'не найдено ни одного .then без .catch: проверка либо ослепла, либо цепочки ' +
        'переписаны - тогда её надо переписать вместе с ними',
    );
  });

  it('причина записана рядом с местом поломки', () => {
    // ASCII-маркеры, а не русские фразы: фраза разъезжается переносом строки,
    // и проверка начнёт искать текст там, где его нет. Тот же вывод, что в §153
    // и §154, - в третий раз по этой теме.
    const текст = readFileSync(join(корень, 'client/src/app/game3d/terrain.ts'), 'utf-8');
    должно(
      /decor\/oak\.glb/.test(текст),
      'не назван конкретный загрузчик, на котором стоят места без .catch: ' +
        'пояснение должно показывать, что именно перестанет работать',
    );
    должно(
      /\.then\(модель\)/.test(текст.replace(/\.then\s*\(\s*\(модель\)/g, '.then(модель)')),
      'не показана сама форма цепочки без .catch: пояснение обязано её называть',
    );
  });
});