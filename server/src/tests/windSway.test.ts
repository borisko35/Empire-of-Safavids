// Ветер качает зелень.
//
// ЧТО БЫЛО (21 октября 2026, §258). Кусты, трава и кроны деревьев стояли
// неподвижно, хотя ветер в мире есть: и в пыльной буре, и в вихрях. Мир с
// ветром и зеленью, которая не шевелится, читается как декорация.
//
// ЧТО ТЕПЕРЬ. Движок наклоняет растения по ветру: сила порывов меняется сама,
// и в буре качание вдвое сильнее.
//
// ЧТО ПРОВЕРЯЕТСЯ. Зелень записана в список качающихся; крона кипариса —
// группа (качаться должна вся крона, а не каждый слой по отдельности); и
// движок качает растения рядом с камерой — за горизонтом качание не видно, а
// список на весь мир.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Ветер качает зелень', () => {
  it('зелень записана в список качающихся', () => {
    должен(/export const качающиеся: Качающееся\[\] = \[\];/.test(ТЕРРЕЙН), 'нет списка качающихся');
    // Кусты.
    должен(
      /лепок\.castShadow = true;[\s\S]{0,140}?parent\.add\(лепок\);[\s\S]{0,140}?записатьКачание\(лепок/.test(
        ТЕРРЕЙН,
      ),
      'кусты не качаются',
    );
    // Трава.
    должен(
      /blade\.castShadow = true;[\s\S]{0,140}?parent\.add\(blade\);[\s\S]{0,140}?записатьКачание\(blade/.test(
        ТЕРРЕЙН,
      ),
      'трава не качается',
    );
    // Крона пальмы.
    должен(/записатьКачание\(крона, 0\.05 \* k/.test(ТЕРРЕЙН), 'крона пальмы не качается');
  });

  it('крона кипариса — группа: качается вся, а не слои по отдельности', () => {
    должен(
      /const крона = new THREE\.Group\(\);\s*крона\.position\.set\(x, y, z\);/.test(ТЕРРЕЙН),
      'крона кипариса не собрана в группу: наклонять её нечем',
    );
    должен(/крона\.add\(конус\);/.test(ТЕРРЕЙН), 'слои кроны добавлены не в группу');
    должен(/записатьКачание\(крона, 0\.035 \* s/.test(ТЕРРЕЙН), 'крона кипариса не качается');
  });

  it('движок качает растения рядом с камерой и сильнее в буре', () => {
    должен(/for \(const к of качающиеся\)/.test(МИР), 'движок не качает зелень');
    // Дальние растения не трогаются: за горизонтом качание не видно.
    должен(
      /dx \* dx \+ dz \* dz > 4900\) continue;/.test(МИР),
      'качается вся зелень мира: за горизонтом это лишняя работа',
    );
    // Порывы. С 22 октября 2026 (§281) их частота зависит от силы ветра, а
    // сама сила считается отдельной функцией (правило на неё — в
    // windInLeaves.test.ts).
    должен(/Math\.sin\(now \/ быстро \+ к\.фаза\)/.test(МИР), 'нет порывов: зелень шевелится ровно');
    // Качание зависит от силы ветра.
    должен(
      /const ветер = ветерСилы\(this\.currentWeather\);/.test(МИР),
      'качание зелени не зависит от силы ветра',
    );
  });
});
