// Ветер качает зелень.
//
// ЧТО БЫЛО (21 октября 2026, §258). Кусты, трава и кроны стояли неподвижно.
//
// ЧТО ТЕПЕРЬ (§326). Зелень — готовые модели, и каждая записана в качающиеся
// через опцию качание у decorВещь: пальмы, кипарисы, кусты, трава города и
// поля. Механизм тот же: движок наклоняет объект рядом с камерой, в буре
// сильнее.
//
// ЧТО ПРОВЕРЯЕТСЯ. Список качающихся жив; декорВещь умеет качать; качание
// передано пальмам (addPalm), кипарисам (cypress), кустам и траве; движок
// качает растения рядом с камерой.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Ветер качает зелень', () => {
  it('список качающихся жив, decorВещь умеет качать', () => {
    должен(/export const качающиеся: Качающееся\[\] = \[\];/.test(ТЕРРЕЙН), 'нет списка качающихся');
    // Опция качания у постановщика моделей: только она ставит GLB-зелень
    // в качающиеся.
    должен(/if \(opts\.качание\) записатьКачание\(вещь, opts\.качание\.амплитуда, opts\.качание\.фаза\);/.test(ТЕРРЕЙН),
      'decorВещь не записывает зелень в качающиеся');
  });

  it('пальмы, кипарисы, кусты и трава качаются', () => {
    const функция = (имя: string): string => {
      const нач = ТЕРРЕЙН.indexOf(`function ${имя}`);
      должен(нач >= 0, `нет функции ${имя}`);
      return ТЕРРЕЙН.slice(нач, ТЕРРЕЙН.indexOf('\n}\n', нач));
    };
    for (const [имя, ожидание] of [
      ['addPalm', 'качание: { амплитуда: 0.02 * k'],
      ['cypress', 'качание: { амплитуда: 0.02 * s'],
      ['куст', 'качание: { амплитуда: 0.05 * s'],
      ['трава', 'качание: { амплитуда: 0.09 * s'],
    ] as const) {
      должен(функция(имя).includes(ожидание), `${имя} не качается`);
    }
  });

  it('движок качает растения рядом с камерой и сильнее в буре', () => {
    должен(/for \(const к of качающиеся\)/.test(МИР), 'движок не качает зелень');
    // Дальние растения не трогаются: за горизонтом качание не видно.
    должен(
      /dx \* dx \+ dz \* dz > 4900\) continue;/.test(МИР),
      'качается вся зелень мира: за горизонтом это лишняя работа',
    );
    // Порывы: их частота зависит от силы ветра.
    должен(/Math\.sin\(now \/ быстро \+ к\.фаза\)/.test(МИР), 'нет порывов: зелень шевелится ровно');
    // Качание зависит от силы ветра.
    должен(
      /const ветер = ветерСилы\(this\.currentWeather\);/.test(МИР),
      'качание зелени не зависит от силы ветра',
    );
  });
});
