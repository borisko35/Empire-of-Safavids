// Цапли у воды.
//
// ЧТО БЫЛО (22 октября 2026, §305). У воды не было ни одной водоплавающей
// птицы — только утки (§286) и чайки на сваях (§303). Болотистая кромка была
// пустой.
//
// ЧТО ТЕПЕРЬ. Цапля: тело-капсула, длинная шея из двух звеньев, голова с длинным
// клювом, сложенный хвост и две длинные тонкие ноги. Стоит по колено в воде
// там же, где камыш (§301).
//
// ЧТО ПРОВЕРЯЕТСЯ. Цапля есть и состоит из тела, шеи из двух звеньев, головы с
// клювом, хвоста и длинных ног; цапли ставятся на кромке, по уровню воды.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Цапли у воды', () => {
  it('у цапли тело, шея, голова с клювом, хвост и длинные ноги', () => {
    должен(/function цапля\(/.test(ТЕРРЕЙН), 'нет сборщика цапли');
    // Тело — капсула.
    должен(
      /const тело = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.14, 0\.4, 3, 10\), перья\);/.test(ТЕРРЕЙН),
      'тело цапли — не капсула',
    );
    // Шея из двух звеньев.
    должен(
      /const шея = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.05, 0\.3, 3, 7\), перья\);/.test(ТЕРРЕЙН),
      'у цапли нет шеи',
    );
    должен(
      /const шея2 = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.045, 0\.26, 3, 7\), перья\);/.test(ТЕРРЕЙН),
      'у цапли нет второго звена шеи',
    );
    // Голова и длинный клюв.
    должен(
      /const клюв = new THREE\.Mesh\(new THREE\.ConeGeometry\(0\.022, 0\.26, 5\), клювМатериал\);/.test(ТЕРРЕЙН),
      'у цапли нет длинного клюва',
    );
    // Хвост.
    должен(
      /const хвост = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.1, 0\.04, 0\.22\), тёмные\);/.test(ТЕРРЕЙН),
      'у цапли нет хвоста',
    );
    // Длинные ноги.
    должен(
      /const нога = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.014, 0\.018, 0\.9, 5\), клювМатериал\);/.test(ТЕРРЕЙН),
      'у цапли нет длинных ног',
    );
  });

  it('цапли стоят на кромке, по уровню воды', () => {
    должен(/if \(i % 5 === 0\) \{/.test(ТЕРРЕЙН), 'цапли ставятся не по кромке');
    должен(
      /цапляПтица\.position\.set\(x, LAKE\.level - 0\.05, z\);/.test(ТЕРРЕЙН),
      'цапля не стоит по уровню воды',
    );
    должен(/scene\.add\(цапляПтица\);/.test(ТЕРРЕЙН), 'цапля не добавлена в сцену');
  });
});
