// Цапли у воды.
//
// ЧТО БЫЛО (22 октября 2026, §305). У воды не было ни одной водоплавающей
// птицы — только утки (§286) и чайки на сваях (§303). Болотистая кромка была
// пустой.
//
// ЧТО ТЕПЕРЬ (§326). Цапля — готовая GLB-модель серой цапли (Google Poly,
// CC-BY), стоит в позе покоя по колено в воде там же, где камыш (§301).
// Процедурная сборка из капсул удалена вместе с переходом.
//
// ЧТО ПРОВЕРЯЕТСЯ. Модель цапли лежит в манифесте; terrain ставит её через
// decorВещь; стоят на кромке, по уровню воды.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАНИФЕСТ = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
  decor?: { file: string; name: string; bytes: number }[];
  animals?: { file: string; name: string; bytes: number }[];
};
const вМанифесте = (раздел: 'decor' | 'animals', имя: string): boolean =>
  (МАНИФЕСТ[раздел] ?? []).some((д) => д.name === имя);

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Цапли у воды', () => {
  it('модель цапли лежит в сборке', () => {
    должен(вМанифесте('animals', 'heron'), 'heron.glb нет в манифесте: цапля не доедет');
  });

  it('цапля ставится моделью, а не собирается из капсул', () => {
    должен(/function цапляПоставить\(/.test(ТЕРРЕЙН), 'нет постановщика цапли');
    должен(/decorВещь\(scene, 'animals\/heron', x, z, \{ размер: [\d.]+, ry, y \}\);/.test(ТЕРРЕЙН),
      'цапля просит модель из decor, а лежит она в animals: птиц нет');
    // Процедурной сборки больше быть не должно.
    должен(!/CapsuleGeometry\(0\.14, 0\.4, 3, 10\)/.test(ТЕРРЕЙН), 'цапля снова из капсул');
  });

  it('цапли стоят на кромке, по уровню воды', () => {
    должен(/if \(i % 5 === 0\) \{/.test(ТЕРРЕЙН), 'цапли ставятся не по кромке');
    должен(/цапляПоставить\(scene, x, z, LAKE\.level - 0\.05,/.test(ТЕРРЕЙН),
      'цапля не стоит по уровню воды');
  });

  it('загрузчик частей понимает путь от models, а не только decor', () => {
    // БЕЗ ЭТОГО ФИКС НЕ РАБОТАЕТ: имя 'animals/heron' уходило в
    // loadDecorModel как 'decor/animals/heron.glb', файла нет — и цапли
    // молча исчезали, хотя сторож выше был зелёным (он проверял только
    // строку вызова).
    должен(/const путь = имя\.includes\('\/'\) \? `\$\{имя\}\.glb` : `decor\/\$\{имя\}\.glb`;/.test(ТЕРРЕЙН),
      'частиМодели снова ищет всё в decor: модели из animals не найдутся');
  });
});
