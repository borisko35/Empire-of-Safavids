// Погода зависит от сезона, а часы с датой видны игроку.
//
// ЧТО БЫЛО, и почему это нельзя было заметить в коде.
//
// 1. Погода бралась из ОДНОГО списка на 30 слотов, и сезон в формулу не
//    входил вообще. Список был один и тот же круглый год, поэтому снег
//    шёл летом, а дождь зимой. Клиент при этом рисовал ровно то, что
//    прислал сервер, - то есть дело было не в отрисовке, а в расписании.
//
// 2. В углу экрана показывались только время суток и погода, то есть
//    «Утро · Дождь». Часы, число, месяц, год и сезон сервер вычислял и
//    присылал каждыми четырьмя минутами, а HUD всё это отбрасывал.
//    Отсутствие счётчика времени выглядело как «не сделано», хотя данные
//    были на руках.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  SEASON_WEATHER, currentWeather, worldTimeAt, seasonOf,
  GAME_EPOCH_MS, WEATHER_EFFECTS,
} from '../systems/WorldTimeSystem';
import type { Season, Weather } from '../systems/WorldTimeSystem';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СЕЗОНЫ: Season[] = ['spring', 'summer', 'autumn', 'winter'];
const СЛОТ_МС = 4 * 60 * 1000;
/** Год игры: 12 месяцев по 30 дней по 24 часа, игровой час = минута. */
const ГОД_МС = 12 * 30 * 24 * 60 * 1000;

describe('Погода по сезонам', () => {
  it('на каждый сезон есть своя таблица, и они одинаковой длины', () => {
    // Одинаковая длина нужна, чтобы смена сезона не сдвигала ритм: игрок,
    // ждавший бурю, получал бы её и в другое время года.
    const длины = СЕЗОНЫ.map((с) => SEASON_WEATHER[с].length);
    must(длины.every((д) => д > 0), `у сезона пустая таблица погоды: ${длины.join(', ')}`);
    must(
      new Set(длины).size === 1,
      `таблицы погоды разной длины: ${СЕЗОНЫ.map((с, i) => `${с}:${длины[i]}`).join(', ')} - смена сезона сдвинет ритм погоды`,
    );
  });

  it('снег бывает только зимой', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Раньше снег выпадал в любое время года,
    // потому что список погоды был один на все сезоны.
    const неверно: string[] = [];
    for (const с of СЕЗОНЫ) {
      if (SEASON_WEATHER[с].includes('snow') !== (с === 'winter')) неверно.push(с);
    }
    must(
      неверно.length === 0,
      `снег идёт не в тех сезонах: ${неверно.join(', ')}. Правило: снег только зимой.`,
    );
  });

  it('песчаная буря бывает только летом', () => {
    // Пыль в заливе зимой - такая же несообразность, как снег в засуху.
    const неверно: string[] = [];
    for (const с of СЕЗОНЫ) {
      if (SEASON_WEATHER[с].includes('sandstorm') !== (с === 'summer')) неверно.push(с);
    }
    must(
      неверно.length === 0,
      `песчаная буря идёт не в тех сезонах: ${неверно.join(', ')}. Правило: пыль только летом.`,
    );
  });

  it('дождь не идёт в разгар зимы', () => {
    // Зимой вместо дождя идёт снег. Летом дождя тоже нет: лето засушливое.
    must(
      !SEASON_WEATHER.winter.includes('rain'),
      'зимой идёт дождь: в разгар зимы вместо него должен идти снег',
    );
    must(
      SEASON_WEATHER.spring.includes('rain') && SEASON_WEATHER.autumn.includes('rain'),
      'в весне или осени совсем нет дождей - весна и осень в этом мире дождливые',
    );
  });

  it('в каждом сезоне погода не однообразная', () => {
    // Таблица из тридцати одинаковых слотов - это «ясно» весь сезон.
    for (const с of СЕЗОНЫ) {
      const виды = new Set(SEASON_WEATHER[с]);
      must(
        виды.size >= 4,
        `в сезоне ${с} только ${виды.size} видов погоды (${[...виды].join(', ')}) - погода однообразная`,
      );
    }
  });

  it('в таблицах только погоды, которые есть в справочнике', () => {
    // Погода без записи в WEATHER_EFFECTS выпала бы из расчёта: у неё
    // нет ни видимости, ни множителя опыта, ни погодных монстров.
    const неизвестные = new Set<string>();
    for (const с of СЕЗОНЫ) {
      for (const w of SEASON_WEATHER[с]) {
        if (!(w in WEATHER_EFFECTS)) неизвестные.add(w);
      }
    }
    must(
      неизвестные.size === 0,
      `в таблицах погоды есть несуществующие виды: ${[...неизвестные].join(', ')} - для них нет записи в WEATHER_EFFECTS`,
    );
  });

  it('смена сезона меняет погоду, а не только подпись', () => {
    // Сезон обязан влиять на результат currentWeather. Проверка идёт по
    // календарю целого года: если сезон не участвует в формуле, в разных
    // месяцах выпадет одно и то же.
    const поМесяцам = new Map<number, Set<Weather>>();
    for (let i = 0; i < ГОД_МС; i += СЛОТ_МС) {
      const t = GAME_EPOCH_MS + i;
      const месяц = worldTimeAt(t).gameMonth;
      if (!поМесяцам.has(месяц)) поМесяцам.set(месяц, new Set());
      поМесяцам.get(месяц)?.add(currentWeather(t));
    }
    must(поМесяцам.size === 12, `проверено месяцев: ${поМесяцам.size}, ожидалось 12`);

    for (const [месяц, погоды] of поМесяцам) {
      const сезон = seasonOf(месяц);
      const положноСнег = сезон === 'winter';
      const положноПыль = сезон === 'summer';
      must(
        погоды.has('snow') === положноСнег,
        `месяц ${месяц} (${сезон}): снег=${погоды.has('snow')}, а по сезону должно быть ${положноСнег}`,
      );
      must(
        погоды.has('sandstorm') === положноПыль,
        `месяц ${месяц} (${сезон}): пыль=${погоды.has('sandstorm')}, а по сезону должно быть ${положноПыль}`,
      );
    }
  });

  it('в игре есть все четыре сезона, а не один', () => {
    // Сезон считается по номеру месяца. Если месяцы не покрыты, часть
    // года шла бы с чужим сезоном.
    const найденные = new Set<Season>();
    for (let месяц = 1; месяц <= 12; месяц++) найденные.add(seasonOf(месяц));
    must(
      найденные.size === 4,
      `по месяцам 1..12 получаются не все сезоны: ${[...найденные].join(', ')}`,
    );
    for (const с of СЕЗОНЫ) {
      must(найденные.has(с), `сезон ${с} не наступает ни в одном месяце`);
    }
  });
});

describe('Часы и дата видны игроку', () => {
  const HUD = readFileSync(join(корень, 'client/src/app/hud.ts'), 'utf-8');

  it('HUD показывает час, дату и сезон, а не только погоду', () => {
    // ЧТО БЫЛО. В угол шли только время суток и погода. Часы, число,
    // месяц, год и сезон сервер присылал, а HUD их отбрасывал - игрок
    // видел «Утро · Дождь» и не знал, который час и какое время года.
    must(/payload\.gameHour/.test(HUD), 'HUD не читает игровой час: счётчика времени нет');
    must(/payload\.gameDay/.test(HUD), 'HUD не читает день: даты нет');
    must(/payload\.gameMonth/.test(HUD), 'HUD не читает месяц: даты нет');
    must(/payload\.gameYear/.test(HUD), 'HUD не читает год: даты нет');
    must(/payload\.season/.test(HUD), 'HUD не читает сезон: времени года не видно');
  });

  it('HUD не показывает незаполненные нули', () => {
    // Если сервер не прислал дату, в углу не должно быть «NaN · NaN» -
    // старые номера месяцев от 1501 года пугают игрока.
    must(
      /Number\.isFinite/.test(HUD),
      'HUD не проверяет числа перед выводом: при пустых данных в углу появятся NaN',
    );
  });

  it('название сезона переведено во всех трёх языках', () => {
    // Сезон показывается игроку, значит должен быть переведён, как погода.
    for (const код of ['ru', 'en', 'az'] as const) {
      const словарь = JSON.parse(
        readFileSync(join(корень, `shared/locales/${код}.json`), 'utf-8'),
      ) as Record<string, unknown>;
      const wc = словарь.worldclock as Record<string, string>;
      for (const с of СЕЗОНЫ) {
        const ключ = `season_${с}`;
        must(
          typeof wc[ключ] === 'string' && (wc[ключ] as string).length > 0,
          `в ${код}.json нет перевода worldclock.${ключ}: сезон показывается игроку и должен быть переведён`,
        );
      }
    }
  });
});