// Памятники городов регионов перестают быть бруском и ящиком.
//
// ЧТО БЫЛО (22 октября 2026, §299). В торговом городе портал — две колонны и
// перемычка-брусок; колонны стояли прямо на земле, без постамента и
// капители. Кладка в других городах — ящик 34×2.2×0.9: ровная плита без зубцов
// и пилястров.
//
// ЧТО ТЕПЕРЬ. У колонн есть постамент и капитель, перемычка стала балкой с
// карнизом и резьбой. Кладка сложена в два венца, у неё зубцы по верху и
// пилястры через каждые 8 м.
//
// ЧТО ПРОВЕРЯЕТСЯ. У колонн есть постамент и капитель, у балки — карниз и
// резьба; кладка сложена в два ряда, с зубцами и пилястрами, а не ящик.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Памятники городов — не брусок и не ящик', () => {
  it('у колонн постамент и капитель, у балки — карниз и резьба', () => {
    должен(
      /const база = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.95, 1\.05, 0\.4, 8\), MAT\.sandstone\);/.test(ТЕРРЕЙН),
      'у колонны нет постамента',
    );
    должен(
      /const капитель = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.88, 0\.72, 0\.35, 8\), MAT\.sandstone\);/.test(ТЕРРЕЙН),
      'у колонны нет капители',
    );
    // Карниз и резьба по балке.
    должен(
      /const карниз = new THREE\.Mesh\(new THREE\.BoxGeometry\(8\.8, 0\.22, 1\.45\), MAT\.sandstone\);/.test(ТЕРРЕЙН),
      'у балки нет карниза',
    );
    должен(
      /const резьба = new THREE\.Mesh\(new THREE\.BoxGeometry\(8\.0, 0\.16, 1\.26\), MAT\.sandstoneDark\);/.test(ТЕРРЕЙН),
      'у балки нет резьбы',
    );
    // Балка стала тоньше: раньше это был брусок во всю высоту.
    должен(
      /const перемычка = new THREE\.Mesh\(new THREE\.BoxGeometry\(8\.4, 0\.75, 1\.2\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'перемычка снова брусок',
    );
  });

  it('кладка сложена в два ряда, с зубцами и пилястрами', () => {
    // Два венца.
    должен(
      /const рядКладки = new THREE\.Mesh\(new THREE\.BoxGeometry\(длинаКладки, 1\.7, 0\.9\), MAT\.stone\);/.test(ТЕРРЕЙН),
      'нет нижнего ряда кладки',
    );
    должен(
      /const верхКладки = new THREE\.Mesh\(new THREE\.BoxGeometry\(длинаКладки - 1\.2, 0\.5, 0\.75\), MAT\.stone\);/.test(ТЕРРЕЙН),
      'нет верхнего ряда кладки',
    );
    // Зубцы.
    должен(
      /const зубец = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.1, 0\.55, 0\.75\), MAT\.stone\);/.test(ТЕРРЕЙН),
      'у кладки нет зубцов',
    );
    // Пилястры.
    должен(
      /const пилястр = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.2, 2\.3, 1\.15\), MAT\.sandstone\);/.test(ТЕРРЕЙН),
      'у кладки нет пилястров',
    );
    // Ящика-кладки больше нет.
    должен(
      !/new THREE\.BoxGeometry\(34, 2\.2, 0\.9\)/.test(ТЕРРЕЙН),
      'кладка снова ящик',
    );
  });
});
