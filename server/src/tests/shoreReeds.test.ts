// Камыш у кромки воды.
//
// ЧТО БЫЛО (22 октября 2026, §301). Берег кончался стеклянной полосой песка:
// вода подходила вплотную к голой земле, и озеро читалось как зеркало, а не как
// место, где что-то растёт.
//
// ЧТО ТЕПЕРЬ. По кромке озера растёт камыш — пучок из шести длинных узких
// листьев, наклонённых в стороны, двусторонних (иначе лист гас с одной
// стороны). Пучки ставятся кольцом вокруг озера, а не по общему рассеву:
// полоса у воды слишком узкая, из неё выходило три пучка на весь мир.
//
// ЧТО ПРОВЕРЯЕТСЯ. Камыш есть, это шесть листьев с прогибом; лист
// двусторонний; камыш ставится кольцом по кромке воды (а не по общему рассеву)
// и попадает в сцену; у пучков свой оттенок и он не чёрный.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Камыш у кромки воды', () => {
  it('камыш — пучок длинных листьев', () => {
    // Шесть листьев в пучке.
    должен(/for \(let b = 0; b < 6; b\+\+\) \{/.test(ТЕРРЕЙН), 'в пучке не шесть листьев');
    // Лист длинный и узкий.
    должен(
      /const w = 0\.035, h = 1\.5 \+ \(b % 2\) \* 0\.55;/.test(ТЕРРЕЙН),
      'лист камыша не длинный и узкий',
    );
    // Остриё листа уходит в сторону — листья не стоят столбом.
    должен(
      /вершины\.push\(dx \* h \* наклон, h, dz \* h \* наклон\);/.test(ТЕРРЕЙН),
      'листья камыша не наклоняются',
    );
    // Обратная сторона — именно у камыша: такой же приём есть у травы (§287),
    // и проверка «где-нибудь в файле» была бы враньём.
    должен(
      /камышГео[\s\S]{0,3000}?Двусторонний лист[^\n]*\n[^\n]*индексы\.push\(base \+ 2, base \+ 1, base\);/.test(ТЕРРЕЙН),
      'лист камыша односторонний',
    );
  });

  it('камыш ставится кольцом по кромке воды', () => {
    // Кольцо вокруг озера, а не общий рассев: полоса у воды узкая.
    должен(
      /for \(let i = 0; i < 1400 && камыш\.length < 260; i\+\+\) \{/.test(ТЕРРЕЙН),
      'камыш ставится не кольцом по кромке',
    );
    // Точка берётся на радиусе озера.
    должен(
      /const r = LAKE\.r \* \(0\.86 \+ hash2\(i, 3\) \* 0\.34\);/.test(ТЕРРЕЙН),
      'камыш ставится не по радиусу озера',
    );
    // И отбирается по маске воды: земля уже уходит под воду.
    должен(
      /if \(wm <= 0\.002 \|\| wm > 0\.16\) continue;/.test(ТЕРРЕЙН),
      'камыш ставится не по кромке воды',
    );
    // И он попадает в сцену.
    должен(/scene\.add\([^)]*камышMesh/.test(ТЕРРЕЙН), 'камыш не добавлен в сцену');
  });

  it('у пучков свой оттенок, и камыш не чёрный', () => {
    должен(/камышMesh\.setColorAt\(idx, color\);/.test(ТЕРРЕЙН), 'у пучков нет своего оттенка');
    // Светлота не ниже 0.3: иначе пучки читаются чёрными шипами. Оттенок ищем
    // по его собственным числам — в файле есть и другие setHSL, у деревьев.
    const оттенок = /0\.25 \+ rng\(\) \* 0\.06, 0\.3 \+ rng\(\) \* 0\.14, ([\d.]+) \+ rng\(\)/.exec(ТЕРРЕЙН);
    должен(оттенок, 'оттенок камыша не считается');
    должен(Number(оттенок![1]) >= 0.3, `камыш слишком тёмный: светлота ${оттенок![1]}`);
  });
});
