// Туман войны: память о местности.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ.
//   1. Геометрия памяти числами: сетка накрывает весь мир, радиус открытия не
//      меньше того, что игрок видит на мини-карте, память занимает разумно;
//   2. Настоящие функции из minimapFog.ts, вырезанные и исполняемые (не копия):
//      открывается круг, а не квадрат; повторное открытие не считается дважды;
//      за краем мира ничего не открывается и ничего не падает;
//   3. Подключение: маска ложится поверх рельефа и ДО маркеров, туман есть и на
//      большой карте, открытие местности не зависит от видимости мини-карты,
//      запись на диск не на каждом кадре, память своя у каждого персонажа;
//   4. Два кэша тумана не делят один флаг: перерисовка одного не должна объявлять
//      другой свежим. Это уже была ошибка, и она молча ломала большую карту.
//
// ПОЧЕМУ НЕ ИМПОРТ. minimapFog.ts тянет game3d/terrain, а тот — three. Клиентского
// раннера у тестов нет, поэтому берём тела функций из файла, как это уже сделано
// в panelClosing.test.ts: правка в коде ломает тест, копия логики не ломала бы
// его никогда.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildRunner } from './helpers/extractFn';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const fog = читать('client/src/app/minimapFog.ts');
const hud = читать('client/src/app/hud.ts');
const world = читать('client/src/app/world.ts');
const terrain = читать('client/src/app/game3d/terrain.ts');

// ── Константы читаем из кода, а не дублируем числами ─────────────────────
function числоИз(источник: string, шаблон: RegExp, что: string): number {
  const найдено = шаблон.exec(источник);
  must(найдено, `не нашёл ${что} в коде: проверка считала бы не то, что в игре`);
  return Number(найдено![1]);
}

const FOG_CELL = числоИз(fog, /export const FOG_CELL = (\d+);/, 'размер клетки тумана');
const FOG_REVEAL = числоИз(fog, /export const FOG_REVEAL_CELLS = (\d+);/, 'радиус открытия');
const MINIMAP_RANGE = числоИз(hud, /const MINIMAP_RANGE = (\d+);/, 'радиус мини-карты');

// Половина мира берётся из того же места, откуда её берёт сам туман: это константа
// клиента. Свою копию в проверке держать нельзя — тогда расхождение было бы
// невозможно заметить, а ровно расхождение тут и ломает карту.
const WORLD_HALF = числоИз(terrain, /WORLD_HALF\s*=\s*(\d+)/, 'половину мира в клиенте');
must(
  /import \{ WORLD_HALF \} from '\.\/game3d\/terrain';/.test(fog),
  'туман берёт половину мира не из terrain: маска может уехать относительно карты'
);
const FOG_GRID = Math.ceil((WORLD_HALF * 2) / FOG_CELL);

describe('Туман войны: геометрия памяти', () => {
  it('сетка накрывает весь мир без недокрытой полосы', () => {
    must(
      FOG_CELL * FOG_GRID >= WORLD_HALF * 2,
      `сетка покрывает ${FOG_CELL * FOG_GRID} единиц, а мир ${WORLD_HALF * 2}: ` +
        'у края мира осталась бы полоса, которая не открывается никогда'
    );
  });

  it('радиус открытия не меньше того, что игрок видит на мини-карте', () => {
    // Иначе игрок смотрел бы на карту и видел чёрное там, где стоит: карта врала
    // бы прямо под ногами.
    const радиус = FOG_REVEAL * FOG_CELL;
    must(
      радиус >= MINIMAP_RANGE,
      `открывается ${радиус} единиц, а мини-карта показывает ${MINIMAP_RANGE}: ` +
        'у игрока под ногами будет чёрное'
    );
  });

  it('память занимает разумно мало', () => {
    const байт = Math.ceil((FOG_GRID * FOG_GRID) / 8);
    must(байт < 8192, `память на персонажа ${байт} байт: хранилище текёт`);
    must(FOG_CELL >= 16, `клетка ${FOG_CELL} слишком мелкая: память растёт как квадрат`);
  });
});

describe('Туман войны: настоящие функции из minimapFog.ts', () => {
  const память = new Uint8Array(Math.ceil((FOG_GRID * FOG_GRID) / 8));
  const флаги = { слой: false, маска: false, запись: false };

  /** Заглушка document: buildRunner всегда объявляет её первым параметром,
 *  и значения подстановок идут ПОСЛЕ аргументов вызова. Без заглушки все
 *  подстановки съезжают на одну позицию. */
const безDom = { getElementById: () => null, createElement: () => null };

const функции = (
  buildRunner(
    fog,
    ['fogCell', 'индекс', 'fogSeen', 'открыть', 'revealAround'],
    {
      FOG_CELL,
      FOG_REVEAL_CELLS: FOG_REVEAL,
      FOG_GRID,
      WORLD_HALF,
      память,
      // Флаги — один объект, а не три отдельных значения. buildRunner передаёт
      // подстановки ЗНАЧЕНИЯМИ: присваивание внутри функции меняло бы локальную
      // копию, и снаружи не было бы видно ничего. Через объект видно всё.
      флаги,
    },
  ) as unknown as (doc: unknown) => {
    fogCell: (v: number) => number;
    fogSeen: (ix: number, iz: number) => boolean;
    revealAround: (x: number, z: number) => boolean;
  }
)(безDom);
  const { fogCell, fogSeen, revealAround } = функции;

  it('клетка по координате зажата в границах мира', () => {
    must(fogCell(-WORLD_HALF - 10000) === 0, `за левым краем мира клетка ${fogCell(-WORLD_HALF - 10000)}`);
    must(
      fogCell(WORLD_HALF + 10000) === FOG_GRID - 1,
      `за правым краем мира клетка ${fogCell(WORLD_HALF + 10000)}`
    );
    // Сетка нечётная (199 клеток при клетке 32), и ноль мира лежит ВНУТРИ клетки
    // 99, а не по её центру. Требовать 99.5 — значит требовать клетки, которой
    // не бывает: проверка защищала бы несуществующий случай.
    must(FOG_GRID % 2 === 1, `сетка чётная (${FOG_GRID} клеток): ноль мира попадает на границу клеток`);
    must(
      fogCell(0) === Math.floor(WORLD_HALF / FOG_CELL),
      `в нуле клетка ${fogCell(0)}, а деление мира на клетку даёт ${Math.floor(WORLD_HALF / FOG_CELL)}`
    );
  });

  it('открывается круг, а не квадрат', () => {
    const cx = fogCell(0);
    const cz = fogCell(0);
    must(revealAround(0, 0), 'в начале мира ничего не открылось');
    // Считаем ожидаемое число клеток круга независимо.
    let ожидалось = 0;
    for (let dz = -FOG_REVEAL; dz <= FOG_REVEAL; dz++) {
      for (let dx = -FOG_REVEAL; dx <= FOG_REVEAL; dx++) {
        if (dx * dx + dz * dz <= FOG_REVEAL * FOG_REVEAL) ожидалось++;
      }
    }
    let открыто = 0;
    for (let iz = 0; iz < FOG_GRID; iz++) {
      for (let ix = 0; ix < FOG_GRID; ix++) if (fogSeen(ix, iz)) открыто++;
    }
    must(
      открыто === ожидалось,
      `открылось ${открыто} клеток, а круг радиусом ${FOG_REVEAL} клеток это ${ожидалось}`
    );
    // Углы квадрата не открыты: за углом ничего не видно.
    must(
      !fogSeen(cx + FOG_REVEAL, cz + FOG_REVEAL),
      'угол квадрата открыт: за углом игрок не бывает'
    );
    // А ближняя клетка открыта.
    must(fogSeen(cx, cz), 'клетка под игроком не открыта');
  });

  it('повторное открытие ничего не меняет', () => {
    const до = revealAround(0, 0);
    must(!до, 'повторный вызов в той же точке заявил, что открылось новое');
  });

  it('второе место открывает ровно новую полосу', () => {
    // Идём на две длины радиуса: должен открыться только пояс между кругами.
    const сдвиг = FOG_REVEAL * FOG_CELL * 2;
    must(revealAround(сдвиг, 0), 'на новом месте ничего не открылось');
    const cx = fogCell(сдвиг);
    must(fogSeen(cx, fogCell(0)), 'точка, где игрок стоял раньше, должна остаться открытой');
    must(!fogSeen(fogCell(0), fogCell(0) - FOG_REVEAL - 2), 'далеко позади должно остаться закрытым');
  });

  it('у края мира открытие не падает и не лезет за сетку', () => {
    for (const [x, z] of [
      [-WORLD_HALF, -WORLD_HALF],
      [WORLD_HALF, WORLD_HALF],
      [-WORLD_HALF, WORLD_HALF],
      [WORLD_HALF, -WORLD_HALF],
    ]) {
      try {
        revealAround(x, z);
      } catch (ошибка) {
        console.error(ошибка);
        throw new Error(`открытие у края мира (${x}, ${z}) упало: память пишет за сетку`);
      }
      must(fogSeen(fogCell(x), fogCell(z)), `у края мира (${x}, ${z}) клетка игрока не открыта`);
    }
  });

  it('память помечается изменённой и её пора записать', () => {
    // Первый вызов уже открывал мир; здесь проверяем сам факт пометки на новом месте.
    память.fill(0);
    флаги.слой = false;
    флаги.маска = false;
    флаги.запись = false;
    revealAround(400, 400);
    must(флаги.слой, 'память изменилась, но слой не помечен грязным: карта показала бы старое');
    must(флаги.запись, 'память изменилась, но запись на диск не запланирована');
    must(
      флаги.маска,
      'маска большой карты не помечена: она осталась бы с прошлой памятью'
    );
  });
});

describe('Туман войны подключён к картам', () => {
  it('маска ложится поверх рельефа и до маркеров', () => {
    const рельеф = hud.indexOf('ctx.drawImage(terrainLayer');
    const маска = hud.indexOf('fogLayerFor(');
    const маркеры = hud.indexOf('// NPC (зелёные точки)');
    must(рельеф > 0, 'не нашёл отрисовку рельефа');
    must(маска > рельеф, 'маска тумана рисуется под рельефом: туман не будет виден');
    must(
      маска < маркеры,
      'маска рисуется после маркеров: монстры светятся сквозь незнакомую местность'
    );
  });

  it('маска в тех же мировых координатах, что и рельеф', () => {
    must(
      /fogLayerFor\(terrainOrigin\.x, terrainOrigin\.z, terrainExtent, terrainSizePx\)/.test(hud),
      'маска считается в других координатах, чем рельеф: туман поедет относительно биомов'
    );
    must(
      /if \(fog\) ctx\.drawImage\(fog, 0, 0\);/.test(hud),
      'маска не рисуется в повёрнутом холсте или рисуется со сдвигом'
    );
  });

  it('на большой карте туман тоже есть', () => {
    must(hud.includes('worldFogMask()'), 'на большой карте тумана нет');
    must(
      /const fx = W \/ 2 - WORLD_HALF \* scale;/.test(hud) &&
        /const fy = H \/ 2 - WORLD_HALF \* scale;/.test(hud),
      'маска большой карты не ложится по формуле координат слоя мира'
    );
    must(
      /ctx\.drawImage\(worldFog, fx, fy, fw, fw\);/.test(hud),
      'маска большой карты не рисуется'
    );
    // Большая карта рисуется раньше маски: иначе туман лёг бы под слой мира.
    must(
      hud.indexOf('ctx.drawImage(worldmapLayer, 0, 0);') < hud.indexOf('ctx.drawImage(worldFog'),
      'маска рисуется под слоем мира: её не видно'
    );
  });
});

describe('Туман войны подключён к игре', () => {
  it('местность открывается независимо от видимости мини-карты', () => {
    const вызов = world.indexOf('revealAround(me.pos.x, me.pos.z)');
    must(вызов > 0, 'открытие местности не вызывается вовсе');
    const вокруг = world.slice(Math.max(0, вызов - 300), вызов + 100);
    must(
      !/minimap'\)|set-minimap|settings\.minimap/.test(вокруг),
      'открытие местности поставлено в зависимость от настройки мини-карты: ' +
        'выключил виджет — потерял память о мире'
    );
  });

  it('запись на диск не на каждом кадре', () => {
    must(world.includes('flushFog()'), 'память не записывается на диск вовсе');
    must(
      /now - lastFogSave > \d{3,}/.test(world),
      'запись памяти без интервала: localStorage дёргался бы каждый кадр'
    );
    const интервал = Number(/now - lastFogSave > (\d+)/.exec(world)![1]);
    must(
      интервал >= 3000,
      `запись раз в ${интервал} мс: хранилище будет дёргаться слишком часто`
    );
  });

  it('память своя у каждого персонажа и грузится до появления на карте', () => {
    must(
      /loadFog\(character\.id\);/.test(world),
      'память не грузится по персонажу: у второго героя откроется чужая карта'
    );
    must(
      world.indexOf('loadFog(character.id);') < world.indexOf('    id: character.id,'),
      'память грузится после создания персонажа: первый кадр рисуется по чужой карте'
    );
    must(
      /const КЛЮЧ = \(id: string\): string => `eos_fog_v1_\$\{id\}`;/.test(fog),
      'ключ хранилища не включает персонажа: память одного героя попадёт к другому'
    );
  });

  it('у двух кэшей тумана свои флаги актуальности', () => {
    must(
      /if \(мироваяМаска && !флаги.маска\) return мироваяМаска;/.test(fog),
      'маска большой карты считается свежей по чужому флагу: перерисовали мини-карту — забыли про большую'
    );
    must(
      /флаги\.маска = true;/.test(fog),
      'открытие местности не помечает маску большой карты'
    );
    must(
      fog.includes('флаги.слой = false;'),
      'слой мини-карты не снимает свой флаг: перерисовывался бы на каждом кадре'
    );
  });

  it('смена персонажа начинает память заново', () => {
    must(
      /export function loadFog\(characterId: string\): void \{[\s\S]{0,200}if \(персонаж === characterId\) return;/.test(fog),
      'загрузка памяти не сверяется с текущим персонажем'
    );
    must(
      /память = new Uint8Array\(БАЙТОВ\);/.test(fog),
      'память не обнуляется при смене персонажа: карта утечёт от героя к герою'
    );
  });

  it('непригодное хранилище не ломает игру', () => {
    // Приватный режим и переполненное хранилище — обычное дело, а не авария.
    must(
      /try \{[\s\S]{0,400}localStorage\.setItem/.test(fog),
      'запись памяти без защиты: исключение хранилища уронит игру'
    );
    must(
      /catch \{[\s\S]{0,120}(память живёт|память просто пустая|играем с пустой картой)/.test(fog),
      'необработанное исключение при чтении памяти'
    );
  });
});