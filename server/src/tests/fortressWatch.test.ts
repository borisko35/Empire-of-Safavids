// Страж внутри крепости: фигура и правило стоят в одной точке.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА. Есть два способа сделать невидимого стража, и оба молчат
// выглядят готовыми: нарисовать фигуру, но не завести пост (тогда он ничего не
// делает), либо завести пост, но не нарисовать (тогда игрока ловит невидимый
// глаз, и он не понимает откуда). Здесь фигура и пост связаны ОДНОЙ формулой и
// сверяются числами.
//
// ПОЧЕМУ ФОРМУЛА, А НЕ ПРОСТО ЧИСЛА. Комната стоит на слоте: cx = POCKET_X +
// слот * ROOM_DX. Если завтра появится второй интерьер и слоты сдвинутся,
// пост, написанный числом, поедет молча - ровно как разъехались двери. Здесь
// координата выводится заново из данных клиента и сравнивается.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { GUARD_POSTS, GUARD_SIGHT, canSee, spottedBy } from '../../../shared/stealth';
import { INTERIORS } from '../data/interiors';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');
const страж = GUARD_POSTS.find((p) => p.id === 'npc_fort_watch');

describe('Страж в крепости: он есть и в картинке, и в правиле', () => {
  it('пост существует', () => {
    must(страж !== undefined, 'поста npc_fort_watch нет: внутри крепости никто не смотрит');
    must(Number(страж!.sight) > 0, 'у стража нулевой обзор: он ничего не видит');
  });

  it('фигура нарисована', () => {
    must(
      /Страж на смотровой площадке/.test(клиент),
      'фигуры стража в комнате нет: пост станет невидимым глазом'
    );
    must(/buildHumanoid\(/.test(клиент), 'фигура не строится через buildHumanoid');
  });

  it('пост стоит там же, где фигура, - координата выведена заново', () => {
    // Формула комнаты читается из данных клиента, а не из наших чисел.
    const px = Number(/const POCKET_X = (\d+)/.exec(клиент)![1]);
    const dx = Number(/const ROOM_DX = (\d+)/.exec(клиент)![1]);
    // POCKET_Z не нужен: координата Z комнаты берётся из записи на сервере, и
    // сверять её с клиентом нечего - ROOM_DX шагает только по X.

    const def = INTERIORS.fortress!;
    must(def !== undefined, 'интерьера fortress на сервере нет');
    const слот = Object.keys(INTERIORS).indexOf('fortress');
    // Слот клиента и номер на сервере - одно и то же число по определению.
    must(def.roomCx === px + слот * dx, `комната на сервере ${def.roomCx}, по формуле ${px + слот * dx}`);

    // Фигура стоит на (cx - 8, cz + 6) - так написано в furnishFortress.
    const ожидаемыйX = def.roomCx - 8;
    const ожидаемыйZ = def.roomCz + 6;
    must(
      страж!.x === ожидаемыйX && страж!.z === ожидаемыйZ,
      `страж в правиле (${страж!.x},${страж!.z}), а фигура на (${ожидаемыйX},${ожидаемыйZ}): ` +
        'игрок увидит стража не там, где тот смотрит'
    );
  });

  it('страж круговой: внутри маленькой комнаты за спиной не проскочить', () => {
    must(
      страж!.facingX === undefined && страж!.facingZ === undefined,
      'у стража в крепости появился конус зрения: в комнате шириной 22 можно было бы ' +
        'зайти ему за спину, и скрытый путь перестал бы быть задачей'
    );
    // Круговой обзор означает: за спиной тоже видно, пока не дальше радиуса.
    const заСпиной = { x: страж!.x - 10, z: страж!.z };
    must(
      canSee(заСпиной, страж!),
      'страж не видит на 10 единицах за спиной: он стал направленным'
    );
  });

  it('игрок внутри комнаты действительно замечен', () => {
    // Ключевая проверка всего шага. Если бы обнаружение не работало в интерьере,
    // пост был бы мёртвым полем при идеальном коде.
    const def = INTERIORS.fortress!;
    const центр = { x: def.roomCx, z: def.roomCz };
    must(
      spottedBy(центр, [страж!]) !== null,
      'в центре комнаты страж не заметил: обнаружение внутри интерьера не работает'
    );
    // И присевший в том же месте - тоже заметен, потому что 6 единиц до
    // стража меньше его приседного обзора в 10.
    must(
      spottedBy(центр, [страж!], { crouch: true }) !== null,
      'присевший в комнате не замечен: обзор схлопнулся в ноль'
    );
  });

  it('приседание всё же помогает у дальней стены', () => {
    // Иначе «скрытность» в крепости была бы пустым словом: у края комнаты
    // можно было бы стоять сколько угодно.
    // Имя без буквы ё: в первой версии проверки объявление и обращение разошлись
    // одной буквой (ё против е), и TypeScript сообщил "не найдено имя" при
    // полностью правильном коде. Причина не в логике, а в том, что глаз
    // не различает эти буквы.
    //
    // РАССТОЯНИЕ 14, А НЕ 10. Первая версия взяла ровно 10 - это граница
    // приседного обзора (20 * 0.5), а граница включена по устройству, и страж
    // там правда видит. Я это сам проектировал и сам же забыл в проверке.
    const уДальнейСтены = { x: страж!.x - 14, z: страж!.z };
    must(
      spottedBy(уДальнейСтены, [страж!], {}) !== null,
      'стоящий у дальней стены не замечен - приседание нечего давать'
    );
    must(
      spottedBy(уДальнейСтены, [страж!], { crouch: true }) === null,
      'присевший у дальней стены тоже замечен: правило скрытности перестало работать'
    );
  });

  it('обзор стража не равен нулю и не больше обычного', () => {
    must(страж!.sight === GUARD_SIGHT, `обзор ${страж!.sight}, а у остальных стражей ${GUARD_SIGHT}`);
  });
});