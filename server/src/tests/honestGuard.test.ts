// Почётного стража больше не существует: любой NPC в доспехах стража обязан
// быть сторожевым постом.
//
// ЧТО НАЙДЕНО. В NPC_GROUPS семь NPC с видом стража (look: GUARD). Трое из них
// были постами ещё с шага 1. Ещё ДВОЕ стояли в столице - Рустам и Бахрам - и
// были чистой декорацией: в доспехах, с панелью подземелий, при этом не видели
// вообще ничего. Теперь все семь сторожевые.
//
// ПОЧЕМУ ПРАВИЛО, А НЕ ПРОСТО СПИСОК. Список постов можно забыть дополнить:
// добавишь в город охрану, нарисуешь ей доспех - и она снова окажется
// декорацией, молча. Теперь проверка требует обратного: КАЖДЫЙ NPC с видом
// стража обязан быть постом. Забудешь - тест упадёт по имени, а не игрок
// обнаружит через месяц.
//
// ПОЧЕМУ НЕ ПО ВИДУ, А ПО СПИСКУ NPC. Слово GUARD( встречается и в
// определении функции-конструктора, поэтому поиск по нему находит и
// объявление. Берёмся только за строки данных NPC, где есть одновременно
// id и dx/dz, - это однозначно запись NPC.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { GUARD_POSTS } from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Почётная служба: стража не осталось декоративным', () => {
  it('в мире есть NPC в доспехах стража', () => {
    // Ненулевая исходная точка. Если бы поиск перестал что-то находить,
    // проверка «все они посты» прошла бы вхолостую на пустом списке.
    const npc = читать('client/src/app/game3d/npc.ts');
    must(npc.length > 1000, 'npc.ts не прочитан');

    const записиСтражем = npc
      .split('\n')
      .filter((l) => /id:\s*'[a-z_]+'/.test(l) && l.includes('look: GUARD'));
    must(
      записиСтражем.length >= 5,
      `найдено ${записиСтражем.length} NPC в доспехах стража - меньше ожидаемого: ` +
        'поиск сломался, и проверка ниже проверяет бы пустоту'
    );
    return;
  });

  it('каждый NPC в доспехах стража — сторожевой пост', () => {
    const npc = читать('client/src/app/game3d/npc.ts');
    const записиСтражем = npc
      .split('\n')
      .filter((l) => /id:\s*'([a-z_]+)'/.test(l) && l.includes('look: GUARD'));

    const посты = new Set(GUARD_POSTS.map((p) => p.id));
    const декорации: string[] = [];
    for (const строка of записиСтражем) {
      const id = /id:\s*'([a-z_]+)'/.exec(строка)![1];
      if (!посты.has(id)) декорации.push(id);
    }

    must(
      декорации.length === 0,
      `эти NPC одеты в доспехи стража, но не следят: ${декорации.join(', ')}. ` +
        'Декоративный страж - это тот же мёртвый игровой слой: выглядит как работа, ' +
        'ничего не делает. Добавь пост в GUARD_POSTS.'
    );
  });

  it('обратного тоже нет: сторожевой пост не должен быть без доспехов', () => {
    // Вторая сторона той же правды. Пост без стража в списке NPC - это
    // невидимый глаз в пустоте: игрок не понимает, откуда его заметили.
    const npc = читать('client/src/app/game3d/npc.ts');
    const idНпс = new Set(
      npc
        .split('\n')
        .filter((l) => /id:\s*'([a-z_]+)'/.test(l))
        .map((l) => /id:\s*'([a-z_]+)'/.exec(l)![1])
    );
    const безНпс = GUARD_POSTS.map((p) => p.id).filter((id) => !idНпс.has(id));
    must(
      безНпс.length === 0,
      `посты без NPC: ${безНпс.join(', ')} - сервер следит в точке, где никого не видно`
    );
  });

  it('столица теперь не пустая: там есть кто-то, кто смотрит', () => {
    // Конкретный след находки. Эти двое стояли в городе и не видели ничего.
    const вСтолице = GUARD_POSTS.filter(
      (p) => p.id === 'npc_guard_east' || p.id === 'npc_guard_west' || p.id === 'npc_guard_gate'
    );
    must(
      вСтолице.length === 3,
      `в столице сторожевых постов ${вСтолице.length}, а ожидалось 3: ` +
        'кто-то из стражников города снова выпал из наблюдения'
    );
  });
});