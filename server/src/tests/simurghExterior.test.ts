// Экстерьер и ровнялка храма Симурга.
//
// ЗАЧЕМ ОТДЕЛЬНО. Мера изменила решение: земля под храмом неровная —
// разброс 7.9 м (у цитадели было 0.09). Без ровнялки дверь стояла бы на склоне.
// В первом коммите храма я честно написал «замер не сделан, уровень не
// выдуман» — теперь замер есть, и ровнялка добавлена с его числом.
//
// Проверка сторожит: меру в комментарии, связь уровня с медианой, и что дверь
// экстерьера ведёт именно в интерьер храма.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('server/src/data/interiors.ts');
const КЛИЕНТ = читать('client/src/app/game3d/interiors.ts');

describe('Храм Симурга: ровнялка по замеру', () => {
  it('записана константа места', () => {
    must(
      /export const SIMURGH_TEMPLE = \{ x: 0, z: 1412,/.test(ТЕРРЕЙН),
      'площадка храма не объявлена в terrain.ts',
    );
  });

  it('уровень — медиана замера, а не центр', () => {
    // Замер: медиана 2.68, в центре 4.06. Медиана не зависит от того, где
    // именно встал игрок, поэтому берётся она.
    const м = /export const SIMURGH_TEMPLE = \{ x: 0, z: 1412, radius: (\d+), level: (-?[\d.]+) \}/.exec(ТЕРРЕЙН);
    must(м !== null, 'радиус или уровень не объявлены');
    expect({ уровень: м![2] }).toEqual({ уровень: '2.68' });
  });

  it('в комментарии записан РАЗБРОС, и он большой', () => {
    // Без числа в комментарии следующий читатель решит, что ровнялка —
    // «для красоты», как у цитадели, и уберёт её.
    must(/РАЗБРОС 7\.9/.test(ТЕРРЕЙН), 'в комментарии нет разброса: причина ровнялки не видна');
    must(/НО, ЗДЕСЬ РОВНЯЛКА НУЖНА|ЗДЕСЬ РОВНЯЛКА НУЖНА/.test(ТЕРРЕЙН), 'не сказано, что ровнялка обязательна');
  });

  it('ровнялка стоит после цитадельной', () => {
    // Порядок определяет, что на что наезжает. Храм добавлен последним.
    must(
      ТЕРРЕЙН.indexOf('SIMURGH_TEMPLE.x, SIMURGH_TEMPLE.z, SIMURGH_TEMPLE.radius') >
        ТЕРРЕЙН.indexOf('BAGHDAD_CITADEL.x, BAGHDAD_CITADEL.z, BAGHDAD_CITADEL.radius'),
      'ровнялка храма не после цитадельной',
    );
  });
});

describe('Храм Симурга: экстерьер', () => {
  it('дверь кликабельна и ведёт в интерьер храма', () => {
    must(
      /doorBuilding: 'simurgh_temple'/.test(ТЕРРЕЙН),
      'двери храма нет: экстерьер недостижим',
    );
    must(/doorAction: 'enter'/.test(ТЕРРЕЙН), 'дверь не ведёт внутрь');
    must(/doorName: t\('buildings\.simurgh_temple'\)/.test(ТЕРРЕЙН), 'не то название');
  });

  it('дверь экстерьера там же, где дверь интерьера', () => {
    // Два места обязаны совпадать: иначе вход стоит не там, куда ведёт.
    const экстерьер = /export const SIMURGH_TEMPLE = \{ x: (\d+), z: (\d+)/.exec(ТЕРРЕЙН);
    const интерьер = /simurgh_temple: \{[\s\S]{0,240}?doorX: (-?\d+), doorZ: (-?\d+)/.exec(ИНТЕРЬЕРЫ);
    must(экстерьер !== null && интерьер !== null, 'координаты не прочитались');
    expect({
      x: Number(экстерьер![1]),
      z: Number(экстерьер![2]),
      dx: Number(интерьер![1]),
      dz: Number(интерьер![2]),
    }).toEqual({ x: 0, z: 1412, dx: 0, dz: 1412 });
  });

  it('клиентская запись совпадает с серверной', () => {
    must(
      /id: 'simurgh_temple', kind: 'simurgh_temple'[^}]*dx: 0, dz: 1412, ex: 0, ez: 1416/.test(КЛИЕНТ),
      'клиентская дверь разошлась с серверной',
    );
  });

  it('плита двора есть — земля-то неровная', () => {
    // Без плиты на склоне подход шёл бы под землю.
    const блок = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('doorBuilding: ') - 3000,
      ТЕРРЕЙН.indexOf("doorBuilding: 'simurgh_temple'") + 200,
    );
    must(/плита/.test(блок), 'плиты двора нет');
  });

  it('есть коллайдеры', () => {
    const начало = ТЕРРЕЙН.indexOf("doorBuilding: 'simurgh_temple'");
    const блок = ТЕРРЕЙН.slice(начало, начало + 2600);
    const коллайдеров = (блок.match(/addCollider\(/g) ?? []).length;
    must(коллайдеров >= 3, `коллайдеров ${коллайдеров}: сквозь экстерьер можно пройти`);
  });
});