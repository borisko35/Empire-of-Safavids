// Живые последствия по карме: потеря золота при смерти.
//
// ЧТО БЫЛО БАГОМ. Таблица KARMA_PENALTIES была объявлена и не читалась нигде:
// поиск по всему серверу давал только её определение. Карма копилась, статусы
// считались, распад шёл — а обещанных последствий не было. Тот же класс, что с
// сундуками: данные написаны, игры за ними нет.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ:
//   1. таблица последствий вообще используется, а не лежит;
//   2. потеря считается по карте и берётся из той же цифры, что шанс;
//   3. у добрых и нейтральных потери нет вообще;
//   4. у мелких сумм потеря не обнуляется до нуля;
//   5. потеря не превышает золота;
//   6. карма читается из базы: в типе Character такого поля нет;
//   7. сумма видна игроку в событии смерти.
//
// Расчёт проверяется на числах, а не на тексте: функция чистая, случайность
// передаётся снаружи, поэтому каждый случай считается руками.
import { karmaDeathDrop, getKarmaStatus, KARMA_PENALTIES } from '../systems/KarmaSystem';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Карма, дающая каждый статус. Границы берутся из самого getKarmaStatus, а не
// выдумываются: иначе проверка считала бы не тот случай, который в игре.
const кармаСтатуса = {
  saint: 6000,
  good: 2000,
  neutral: 0,
  chaotic: -1000,
  red: -3000,
  outlaw: -7000,
} as const;

describe('Последствия кармы: потеря золота при смерти', () => {
  it('статусы считаются так, как думает проверка', () => {
    for (const [статус, карма] of Object.entries(кармаСтатуса)) {
      must(
        getKarmaStatus(карма as number) === статус,
        `карма ${карма} даёт статус ${getKarmaStatus(карма as number)}, а проверка ` +
          `считала ${статус}: проверка считает не тот случай, который в игре`
      );
    }
  });

  it('у добрых и нейтральных потери нет', () => {
    for (const статус of ['saint', 'good', 'neutral'] as const) {
      const штраф = KARMA_PENALTIES[статус];
      must(штраф.dropChanceOnDeath === 0, `${статус}: шанс потери ${штраф.dropChanceOnDeath}, а должен быть 0`);
      for (const roll of [0, 0.09, 0.2, 0.5, 0.99]) {
        const итог = karmaDeathDrop(кармаСтатуса[статус], 10000, roll);
        must(
          итог.dropped === 0,
          `${статус}: при броске ${roll} потеря ${итог.dropped}, а у ${статус} потерь быть не должно`
        );
      }
    }
  });

  it('шанс и доля берутся из одной цифры статуса', () => {
    for (const статус of ['chaotic', 'red', 'outlaw'] as const) {
      const доля = KARMA_PENALTIES[статус].dropChanceOnDeath;
      must(доля > 0 && доля < 1, `${статус}: доля ${доля} вне (0, 1)`);
      // Бросок ниже шанса — теряется ровно эта доля.
      const попал = karmaDeathDrop(кармаСтатуса[статус], 1000, доля / 2);
      must(
        попал.dropped === Math.floor(1000 * доля),
        `${статус}: потеря ${попал.dropped} при доле ${доля} от 1000`
      );
      // Бросок на самой границе шанса — уже не теряется: шанс строгий.
      const неПопал = karmaDeathDrop(кармаСтатуса[статус], 1000, доля);
      must(
        неПопал.dropped === 0,
        `${статус}: бросок ровно на шансе ${доля} всё же дал потерю ${неПопал.dropped}`
      );
    }
  });

  it('чем темнее статус, тем тяжелее потеря', () => {
    const потери = (['chaotic', 'red', 'outlaw'] as const).map(
      (с) => karmaDeathDrop(кармаСтатуса[с], 1000, 0).chance
    );
    must(
      потери[0] < потери[1] && потери[1] < потери[2],
      `шансы по статусам ${потери.join(', ')}: тяжесть последствий не растёт вместе с`
    );
  });

  it('мелкое золото не обнуляет потерю', () => {
    // Изгой с тремя золотом: доля 0,5 дала бы 1.5 -> 1. Проверяем, что потеря
    // не ноль: иначе смерть в этом случае не стоила бы ничего.
    const итог = karmaDeathDrop(кармаСтатуса.outlaw, 3, 0);
    must(итог.dropped >= 1, `изгой с 3 золотом теряет ${итог.dropped}: смерть не должна стоить ничего`);
    must(итог.dropped <= 3, `изгой с 3 золотом теряет ${итог.dropped}: больше, чем есть`);
  });

  it('без золота потери нет', () => {
    for (const статус of ['chaotic', 'red', 'outlaw'] as const) {
      for (const золото of [0, -10]) {
        const итог = karmaDeathDrop(кармаСтатуса[статус], золото, 0);
        must(
          итог.dropped === 0,
          `${статус}: при золоте ${золото} потеря ${итог.dropped}: нечего терять`
        );
      }
    }
  });

  it('потеря никогда не больше золота', () => {
    for (const статус of ['chaotic', 'red', 'outlaw'] as const) {
      for (const золото of [1, 2, 7, 999, 100000]) {
        const итог = karmaDeathDrop(кармаСтатуса[статус], золото, 0);
        must(
          итог.dropped <= золото,
          `${статус}: потеря ${итог.dropped} при золоте ${золото}`
        );
      }
    }
  });
});

describe('Последствия кармы подключены к игре', () => {
  const сокет = читать('server/src/socket/GameSocketHandler.ts');
  const кармаСистема = читать('server/src/systems/KarmaSystem.ts');

  it('потеря применяется при смерти, а не только посчитана', () => {
    must(
      /applyKarmaDeathDrop/.test(сокет),
      'потеря считается, но не применяется: карма обещает штраф, а смерти его нет'
    );
    must(
      /spendGold\(dead\.id, штраф\.dropped\)/.test(сокет),
      'золото не списывается: потеря посчитана и потеряна'
    );
  });

  it('сумма видна игроку', () => {
    must(
      /karmaDropGold/.test(сокет),
      'сумма потери не отправляется в окне смерти: последствие невидимо и выглядит как ошибка'
    );
  });

  it('карма читается из базы, а не из типа персонажа', () => {
    must(
      !/dead\.karma/.test(сокет),
      'обращение к полю karma, которого нет в типе Character: молча ноль и никакой потери'
    );
    must(
      /karmaSystem\.getKarma\(dead\.id\)/.test(сокет),
      'карма при смерти не читается'
    );
    must(
      /async getKarma\(characterId: string\)/.test(кармаСистема),
      'у KarmaSystem нет публичного чтения кармы'
    );
  });

  it('таблица последствий используется, а не лежит', () => {
    // Раньше проверка на отсутствие чтения проходила: таблица была мёртвой, и
    // это считалось нормой. Теперь требуется обратное — без неё последствий нет.
    const использований = (сокет.match(/KARMA_PENALTIES|dropChanceOnDeath/g) || []).length +
      (читать('server/src/systems/KarmaSystem.ts').match(/KARMA_PENALTIES\[/g) || []).length;
    must(
      использований >= 2,
      `ссылок на таблицу последствий ${использований}: она снова лежит мёртвой`
    );
  });
});