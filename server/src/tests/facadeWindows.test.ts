// Окна на фасаде: не тёмные плиты в стене.
//
// ЧТО БЫЛО. На фасадах домов висела плоская пластина 0.7x1.1 цвета 0x2a2a30
// (roughness 1), стоявшая вплотную к стене. Материал почти чёрный и полностью
// матовый: он отражал только рассеянный свет, ничего не обрамлял, стоял НА
// стене, а не В проёме. На скриншоте игры такие окна читались как дыры —
// тёмные прямоугольники на светлой штукатурке, и они портили фасад сильнее
// всего остального.
//
// ЧТО ТЕПЕРЬ. Стекло утоплено в проём и ловит небо (низкая шероховатость,
// металличность, слабое свечение), рама из светлого камня обрамляет проём,
// средник делит его на четыре части. Рама и есть то, что читается как окно.
//
// ЧТО ПРОВЕРЯЕТСЯ. Окно — это проём, а не пластина; и рамка на месте.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/terrain.ts');

describe('Окна на фасаде', () => {
  it('окно строится рамкой, а не тёмной пластиной', () => {
    должен(/function windowPane\(/.test(МИР), 'нет windowPane: окна строятся как попало');
    // Рама: четыре бруса.
    for (const часть of ['верх', 'низ', 'лево', 'право']) {
      должен(
        new RegExp(`const ${часть}\\s*=`).test(МИР),
        `в раме окна нет стороны ${часть}: проём не обрамлён`,
      );
    }
    // Средник — то, что отличает окно от прямоугольника.
    должен(/перекладина/.test(МИР), 'нет перекладины: стекло читается как просто прямоугольник');
    должен(/стойка/.test(МИР), 'нет стойки');
  });

  it('стекло выходит на стену, а не прячется в ней', () => {
    // Прежний фикс ставил стекло на −0.09 — «утоплено в проём». Но у всех
    // трёх применений windowPane стена — сплошной бокс: проёма в ней нет,
    // и стекло целиком пряталось внутри фасада. Проверено в живом мире
    // (§222): 202 стёкол в сцене и ни одного окна в кадре. Теперь стекло
    // торчит наружу на полтолщины; знак снова важен, но наоборот.
    const совпало = /стекло\.position\.z\s*=\s*(-?\d?\.?\d+)/.exec(МИР);
    должен(совпало, 'у стекла нет позиции: окно не собрано');
    должен(+совпало![1] >= 0, 'стекло спрятано в стене: фасад остаётся без окон');
  });

  it('стекло ловит небо, а не почти чёрное', () => {
    // Прежний материал: color 0x2a2a30 при roughness 1 — чистая дыра.
    должен(/glass:\s*new THREE\.MeshStandardMaterial/.test(МИР), 'нет материала стекла');
    const блок = /glass:\s*new THREE\.MeshStandardMaterial\(\{([\s\S]*?)\}\)/.exec(МИР);
    должен(блок, 'материал стекла не читается');
    const тело = блок![1];
    должен(/roughness:\s*0?\.\d+|roughness:\s*0\.\d+/.test(тело) && !/roughness:\s*1\b/.test(тело),
      'стекло полностью матовое: оно ничего не отражает и читается как дыра');
    должен(/metalness:\s*0?\.\d+/.test(тело), 'у стекла нет металличности: небо не отражается');
    // Слабое свечение — стекло всегда чуть светится от неба.
    должен(/emissive:\s*0x[0-9a-f]+/.test(тело), 'у стекла нет свечения от неба');
  });

  it('окно ставится в каждый этаж, а не одно на дом', () => {
    // Одно окно на двухэтажный дом читается как ошибка построения.
    // С §328 окна строятся окноСоСтавнями (окно со ставнями и
    // подоконником), а ярус считается по высоте дома: у двухэтажного
    // окна выше.
    должен(/окноСоСтавнями\([^)]*ярус/.test(МИР), 'окна первого этажа не поставлены');
    должен(
      /const ярус = h > 5\.2 \? h \* 0\.66 : h \* 0\.55;/.test(МИР),
      'на двухэтажном доме окно только одно: второй этаж пустой',
    );
    должен(
      /function окноСоСтавнями\([\s\S]*?windowPane\(cx, cy, faceZ, rotY, W, H\)/.test(МИР),
      'окно со ставнями перестало быть окном windowPane',
    );
  });

  it('старая тёмная пластина не вернулась', () => {
    // Прямой возврат к прежнему виду - то, что было в коде до §135.
    должен(
      !/BoxGeometry\(0\.7,\s*1\.1,\s*0\.1\),\s*MAT\.dark/.test(МИР),
      'вернулась плоская пластина из MAT.dark: окна снова будут читаться как дыры',
    );
  });
});