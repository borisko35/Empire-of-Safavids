// Отблески фонарей на мокрой земле.
//
// ЧТО БЫЛО (22 октября 2026, §276). Лужи и вода в колеях дороги ловят только
// небо — это карта окружения, а не фонари. Ночная площадь после дождя выглядела
// мёртвой, хотя под ней стоят два фонаря.
//
// ЧТО ТЕПЕРЬ. Под каждым фонарём, где земля мокрая, тянется отблеск вниз —
// вертикальная полоса света, как отражение фонаря в луже.
//
// ЧТО ПРОВЕРЯЕТСЯ. Отблески появляются только на мокрой земле, только у
// ближних фонарей (дальние отблеск не читаются, а спрайт стоит кадр), и гаснут
// вместе с мокротой.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const БЛЕСКИ = читать('client/src/app/game3d/wetGlints.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Отблески фонарей на мокрой земле', () => {
  it('отблеск появляется только на мокрой земле', () => {
    должен(/export function createGlints/.test(БЛЕСКИ), 'нет отблесков');
    // Сухая земля — отблеска нет.
    должен(/if \(!в \|\| м < 0\.05\) \{/.test(БЛЕСКИ), 'отблеск горит и на сухой земле');
    // Прозрачность — от мокроты.
    должен(
      /s\.material as THREE\.SpriteMaterial\)\.opacity = м \* 0\.5 \* \(1 - в\.d \/ ДАЛЕКО\);/.test(БЛЕСКИ),
      'прозрачность отблеска не зависит от мокроты и расстояния',
    );
  });

  it('отблеск только у ближних фонарей', () => {
    должен(/const ДАЛЕКО = 34;/.test(БЛЕСКИ), 'нет предела дальности отблеска');
    должен(
      /\.filter\(\(в\) => в\.d < ДАЛЕКО\)[\s\S]{0,200}?\.slice\(0, ОТБЛЕСКОВ\)/.test(БЛЕСКИ),
      'отблески ставятся не только ближним фонарям',
    );
    // Пул конечен: спрайтов не больше десяти.
    должен(/const ОТБЛЕСКОВ = 10;/.test(БЛЕСКИ), 'пул отблесков не ограничен');
  });

  it('движок передаёт отблескам лампы и мокроту', () => {
    должен(
      /this\.отблески\.update\(dt, now, me\.pos\.x, me\.pos\.z, this\.мокрота, лампыДляБлеска\);/.test(МИР),
      'отблески не обновляются',
    );
    // Лампы собираются из обоих списков: и факелы, и постоянные фонари.
    должен(/for \(const t of this\.torches\) \{/.test(МИР), 'факелы не идут в отблески');
    должен(/for \(const l of this\.lamps\) \{/.test(МИР), 'фонари не идут в отблески');
    должен(/this\.отблески\?\.dispose\(\);/.test(МИР), 'отблески не вычищаются');
  });
});
