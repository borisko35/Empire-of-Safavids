// Улица, а не коридор: поребрик, джуб с водой, тротуар (§331).
//
// ЧТО БЫЛО. Переулок — ровная плита от стены до стены: ни края, ни воды, ни
// тени у стены. С уровня глаз улица читалась коридором между двумя
// плоскостями, и деревья этого не спасали.
//
// ЧТО ТЕПЕРЬ. У каждой стороны свой порядок, как в Исфахане: край мостовой,
// поребрик, джуб (узкий канал с водой и каменным дном), тротуар до стены.
// Фонари переехали на тротуар (раньше стояли там, где теперь вода), через
// джуб перекинуты мостики к воротам.
//
// ЧТО ПРОВЕРЯЕТСЯ. Все четыре полосы на месте и посчитаны от одного края;
// вода стоит у кромки, а не на дне ямы; фонарь не в воде; мостики есть.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

function тело(имя: string): string {
  const начало = код.indexOf(`function ${имя}(`);
  должен(начало >= 0, `в коде нет функции ${имя}`);
  const конец = код.indexOf('\n}\n', начало);
  должен(конец > начало, `у функции ${имя} не найден конец`);
  return код.slice(начало, конец);
}

describe('Улица: поребрик, джуб, тротуар', () => {
  const улицы = тело('жилыеУлицы');

  it('у мостовой есть все четыре полосы, и они считаются от края', () => {
    должен(/const КРАЙ = ШИРИНА \/ 2;/.test(улицы), 'край мостовой не посчитан');
    должен(/const ПОРЕБРИК = 0\.35;/.test(улицы), 'нет поребрика');
    должен(/const ДЖУБ = 0\.55;/.test(улицы), 'нет джуба');
    должен(/const ТРОТУАР = 0\.8;/.test(улицы), 'нет тротуара');
    // Поребрик и тротуар — камень с метрическим UV: иначе плитка растянется.
    должен(/metricBoxUV\(new THREE\.BoxGeometry\(ПОРЕБРИК, 0\.24, длина\)/.test(улицы),
      'поребрик без метрического UV');
    должен(/metricBoxUV\(new THREE\.BoxGeometry\(ТРОТУАР, 0\.1, длина\)/.test(улицы),
      'тротуар без метрического UV');
  });

  it('в джубе вода у кромки и каменное дно', () => {
    должен(/new THREE\.PlaneGeometry\(ДЖУБ - 0\.16, длина\)/.test(улицы), 'воды в джубе нет');
    должен(/0\.34,/.test(улицы), 'вода утоплена: канал читается чёрной щелью');
    должен(/new THREE\.PlaneGeometry\(ДЖУБ - 0\.14, длина\)/.test(улицы),
      'под водой нет дна: сквозь неё просвечивает песок');
  });

  it('фонарь стоит на тротуаре, а не в воде', () => {
    // Смещение 3.35 = 2.1 (край) + 0.35 (поребрик) + 0.55 (джуб) + 0.35.
    должен(/\(ШИРИНА \/ 2 \+ 1\.25\)/.test(улицы),
      'фонарь снова стоит на краю мостовой: теперь это вода джуба');
  });

  it('вода джуба — свой тёмный материал, и поворот в геометрии', () => {
    // БАГ, найденный аэроснимком §339: джуб брал MAT.water — шейдер реки с
    // отражением неба. Полоса шириной 0.4 м с высоты 85 м — это 2–3 пикселя,
    // и отражённое небо делало из неё светлую синюю линию через город.
    должен(/jubWater: new THREE\.MeshStandardMaterial/.test(код),
      'у джуба нет своего материала: он снова берёт воду реки');
    должен(/new THREE\.Mesh\(геоВоды, MAT\.jubWater\)/.test(улицы),
      'джуб снова собирается на воде реки');
    // Поворот — в геометрии: так порядок Эйлера не поставит плоскость на ребро.
    должен(/геоВоды\.rotateX\(-Math\.PI \/ 2\);/.test(улицы),
      'поворот воды не в геометрии: Эйлер может поставить её вертикально');
    должен(!/вода\.rotation\.x/.test(улицы), 'у воды снова rotation.x');
    должен(/вода\.rotation\.y = -ПОВОРОТ_УЛИЦЫ;/.test(улицы),
      'вода не развёрнута вдоль улицы');
    должен(/геоДна\.rotateX\(-Math\.PI \/ 2\);/.test(улицы),
      'дно поворачивается мешем: та же ловушка, только ниже');
  });

  it('через джуб перекинуты мостики', () => {
    должен(/Мостики через джуб/.test(ТЕРРЕЙН), 'мостиков нет: к воротам не подойти');
    должен(/new THREE\.BoxGeometry\(1\.0, 0\.1, 1\.15\)/.test(улицы), 'мостик не построен');
  });
});

describe('Дувал: сакра и ниши', () => {
  const дувал = тело('дувал');

  it('глухая стена не полоса: рёбра, ниша и полка', () => {
    должен(/контрфорс/.test(дувал), 'у дувала нет рёбер: стена — сплошная пластина');
    должен(/ниша/.test(дувал) && /полка/.test(дувал),
      'у дувала нет ниши с полкой-сакрой');
  });

  it('ворота стоят на лицевой стороне, а не в толще стены', () => {
    должен(/const лицо = \(смещение: number\): number => сторона \* \(0\.18 \+ смещение\);/.test(дувал),
      'ворота снова прячутся в толще стены');
  });
});
