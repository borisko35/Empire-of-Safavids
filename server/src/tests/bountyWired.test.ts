// Награда за голову: обрывок между таблицей и слушателем клиента.
//
// ЧТО БЫЛО. Механика существовала тремя несвязанными кусками:
//   - `KarmaSystem.placeBounty()` — написан, но не вызван НИ РАЗУ;
//   - таблица bounties с колонками claimed_at и claimer_id — никем не
//     заполняемыми;
//   - клиентский слушатель BOUNTY_PLACED с тостом «На вас объявлена награда».
// Между ними ничего не было. Читатель кода видел живой тост и живой обработчик
// на сервере и делал вывод, что функция работает.
//
// Главный баг при этом был внутри мёртвого кода: UPDATE с условием
// `gold >= $1` выполнялся без проверки результата, а вставка шла всё равно.
// У игрока БЕЗ золота появлялась бесплатная награда за голову. Не поймали
// потому, что метод был недостижим.
//
// ЧТО ЗАЩИЩАЕТСЯ. Не «в коде есть слово bounty», а оба конца: списание,
// которое проверяется по числу строк, и выплата, которая заполняет те самые
// claimer_id и claimed_at.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const карма = код('server/src/systems/KarmaSystem.ts');
const маршруты = код('server/src/routes/game.ts');
const сокет = код('server/src/socket/GameSocketHandler.ts');
const клиент = код('client/src/app/api.ts');
const панель = код('client/src/app/panels.ts');
const константы = код('shared/constants.ts');
const мир = код('client/src/app/world.ts');

describe('Награда за голову: списание золота проверяется', () => {
  it('UPDATE проверяет результат, а не «исключения не было»', () => {
    // Прежде результат игнорировался: у игрока без золота не обновлялась ни
    // одна строка, а вставка шла. Получалась бесплатная награда за голову.
    must(
      /UPDATE characters SET gold = gold - \$1 WHERE id = \$2 AND gold >= \$1 RETURNING id/.test(карма),
      'списание не требует RETURNING — проверить результат нечем',
    );
    must(
      /if \(res\.rows\.length === 0\) return false;/.test(карма),
      'результат списания не проверяется: без золота награда всё равно встаёт',
    );
    must(
      /if \(!списано\) throw new Error\('Not enough gold'\)/.test(карма),
      'отказ по деньгам не доводится до вызывающего',
    );
  });

  it('награду нельзя поставить на самого себя', () => {
    // Иначе убийство себя давало бы свои же деньги: gold уже списан, а
    // claimer_id совпадает с target_id.
    must(/if \(placerId === targetId\) throw new Error\('Cannot place a bounty on yourself'\)/.test(карма),
      'награда на самого себя не запрещена');
  });

  it('событие теперь публикуется тем, кто вызывает', () => {
    must(/redis\.publish\('player:bounty_placed'/.test(карма), 'событие выставления не публикуется');
    must(
      /placeBounty\(/.test(маршруты),
      'placeBounty ни разу не вызывается: механика снова мёртвая, просто теперь в двух файлах',
    );
  });
});

describe('Награда за голову: выплата существует', () => {
  it('claimer_id и claimed_at наконец заполняются', () => {
    // Оба столбца стояли в схеме с миграции 003 и никем не заполнялись.
    must(
      /UPDATE bounties\s+SET is_active = FALSE, claimed_at = NOW\(\), claimer_id = \$1/.test(карма),
      'выплата не отмечается в таблице: деньги уходят без следа',
    );
  });

  it('выплата атомарна, а не «прочли и записали»', () => {
    // Условие is_active = TRUE в самом UPDATE вторая победа над той же целью
    // вернёт ноль строк и не заплатит повторно.
    must(
      /WHERE target_id = \$2 AND is_active = TRUE\s+RETURNING amount/.test(карма),
      'выплата не защищена условием в UPDATE: две победы заплатят дважды',
    );
  });

  it('выплата вызывается при убийстве игрока', () => {
    must(
      /this\.karmaSystem\.claimBounties\(killer\.id, dead\.id\)/.test(сокет),
      'claimBounties не вызывается при убийстве: награду по-прежнему некому выдать',
    );
  });

  it('убийца узнаёт, что ему заплатили', () => {
    must(/BOUNTY_CLAIMED: 'bounty:claimed'/.test(константы), 'события выплаты нет');
    must(
      /SOCKET_EVENTS\.BOUNTY_CLAIMED/.test(сокет) && /SOCKET_EVENTS\.BOUNTY_CLAIMED/.test(мир),
      'событие выплаты не доходит до клиента: игрок не знает, что получил золото',
    );
  });
});

describe('Награда за голову: доступна игроку', () => {
  it('оба маршрута есть и защищены', () => {
    // Без маршрутов место placeBounty в списке вызванных не поменялось бы:
    // его по-прежнему звал бы ни один не клиент.
    const получить = маршруты.indexOf("'/bounty'");
    must(получить > 0, 'маршрута чтения награды нет');
    const поставить = маршруты.indexOf("gameRouter.post('/bounty'");
    must(поставить > 0, 'маршрута объявления награды нет');
    const блок = маршруты.slice(поставить, поставить + 700);
    must(/secureMiddleware/.test(блок), 'маршрут объявления не защищён');
    must(/requireBodyField\('placerId'\)/.test(блок), 'маршрут не проверяет, кто объявляет');
    // Владение персонажем проверяется вручную, потому что placerId приходит в
    // теле, а не в пути.
    must(/placer\.userId !== req\.userId/.test(блок), 'не проверяется владение персонажем плательщика');
  });

  it('сумма проверяется снизу', () => {
    const поставить = маршруты.indexOf("gameRouter.post('/bounty'");
    const блок = маршруты.slice(поставить, поставить + 900);
    must(/amount < 100/.test(блок), 'мелкую награду сервер принимает: она мусорит в таблице');
    // 'bounty_self' проверяется и в маршруте, и в сервисе — дважды намеренно:
    // сервис защищает любого вызывающего, маршрут даёт понятный отказ.
    must(/bounty_self/.test(блок), 'отказ про «награду на самого себя» не отдаётся игроку');
  });

  it('клиент умеет и объявить, и прочитать', () => {
    must(/bountyPlace:\s*\(/.test(клиент), 'в клиенте нет вызова объявления награды');
    must(/bountyOn:\s*\(/.test(клиент), 'в клиенте нет чтения награды');
    must(/api\.bountyPlace\(/.test(панель), 'панель не объявляет награду: маршрут так и останется без вызывающего');
    must(/api\.bountyOn\(/.test(панель) || /bounty/.test(панель), 'награда нигде не показывается игроку');
  });

  it('чужие награды видны в списке игроков региона', () => {
    // Без этого игрок платит второй раз за цель, за которой уже охотятся.
    must(
      /WHERE target_id = ANY\(\$1::uuid\[\]\) AND is_active = TRUE/.test(маршруты),
      'список игроков не читает чужие награды: они невидимы до самой смерти',
    );
    must(/bounty: наградаИгрока\.get\(с\.id\)/.test(маршруты), 'награда не попадает в ответа списка');
    must(/игрок\.bounty/.test(панель), 'панель не показывает награду на цели');
  });

  it('подписи переведены во всех трёх языках', () => {
    for (const кодЯзыка of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${кодЯзыка}.json`)) as {
        panels: Record<string, string>;
        bounty: Record<string, string>;
      };
      for (const ключ of ['bounty', 'bounty_place', 'bounty_placed', 'bounty_failed']) {
        must(
          словарь.panels?.[ключ],
          `в ${кодЯзыка}.json нет panels.${ключ}: кнопка покажет пустое имя`,
        );
      }
      for (const ключ of ['placed', 'claimed']) {
        must(
          словарь.bounty?.[ключ],
          `в ${кодЯзыка}.json нет bounty.${ключ}: тост покажет путь ключа`,
        );
      }
    }
  });
});