// Живое последствие №2: монстры замечают красных и изгоев издалека.
//
// ПРОВЕРКА НА НАСТОЯЩЕМ КОДЕ. Здесь не копия логики, а настоящий AISystem:
// класс пустой (только карта контекстов, ни базы, ни сокета), поэтому его можно
// поднять прямо в тесте, заспавнить монстра и прогнать тик. Так видно то самое
// поведение, ради которого правка и делалась: враждебный игрок попадает в
// аггро-таблицу там, где мирный остаётся незамеченным.
//
// ПОЧЕМУ ИМЕННО ТАКАЯ ПРОВЕРОКА. Разница между «враждебного видно вдвое дальше» и
// «враждебного видно вообще» не видна ни в компиляции, ни в разборе кода. Видно
// только поведением.
//
// ЧТО ЕЩЁ ЗАЩИЩАЕТСЯ.
//   1. Враждебны только «красный» и «изгой» — по таблице последствий, а не по'
//   моему представлению о границах кармы;
//   2. Во сколько раз дальше — числом, и множитель не меньше двух, и не больше
//      разумного: при трёх и больше лес превращается в место, где бегут со всего
//      региона;
//   3. Карма читается тем же запросом, что и здоровье: отдельный запрос означал бы
//      лишний обход базы каждые 200 мс;
//   4. Таблица последствий не читается в двух местах: пришлось завести функцию
//      isNpcHostile, и это проверяется.
import { AISystem, NPC_HUNT_RANGE_MULTIPLIER } from '../systems/AISystem';
import { isNpcHostile, getKarmaStatus, KARMA_PENALTIES } from '../systems/KarmaSystem';
import type { MonsterDefinition } from '../data/monsters';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Минимальное определение монстра: столько нужно AISystem для спавна и тика.
// Остальные поля заполняются умолчаниями через приведение типа — сам AISystem
// их не читает, а расписывать все двадцать полей ради проверки бессмысленно.
const ОПРЕДЕЛЕНИЕ = {
  id: 'test_beast',
  nameRu: 'Зверь',
  type: 'normal',
  hp: 100,
  aggroRange: 20,
  attackRange: 3,
  moveSpeed: 4,
} as unknown as MonsterDefinition;

function зверь(): AISystem {
  return new AISystem();
}

describe('Живое последствие: монстры замечают враждебного издалека', () => {
  it('враждебны только красный и изгой — по таблице последствий', () => {
    for (const статус of ['saint', 'good', 'neutral', 'chaotic'] as const) {
      const карма = { saint: 6000, good: 2000, neutral: 0, chaotic: -1000 }[статус];
      must(
        !isNpcHostile(карма),
        `${статус} (карма ${карма}) враждебен по isNpcHostile, а в таблице ` +
          `npcHostile: ${KARMA_PENALTIES[статус].npcHostile}`
      );
    }
    for (const статус of ['red', 'outlaw'] as const) {
      const карма = { red: -3000, outlaw: -7000 }[статус];
      must(
        isNpcHostile(карма),
        `${статус} (карма ${карма}) не враждебен, а таблица обещает ` +
          `npcHostile: ${KARMA_PENALTIES[статус].npcHostile}`
      );
    }
  });

  it('враждебность считается по границам статусов, а не по круглому числу', () => {
    // Границы статусов взяты из getKarmaStatus, а не выдуманы: в нём `>= -2000` —
// это ещё хаотичный, значит красный начинается с -2001, а изгой — с -5001.
// Первая версия этой проверки была неправа дважды: она требовала, чтобы -2999 и
// -2000 были хаотичным... первое правда, второе нет. Границы намерили, а не
// придумали.
must(getKarmaStatus(-2000) === 'chaotic', 'на -2000 игрок ещё хаотичный');
must(!isNpcHostile(-2000), 'на -2000 враждебности быть не должно');
must(getKarmaStatus(-2001) === 'red', 'с -2001 игрок становится красным');
must(isNpcHostile(-2001), 'красный обязан быть враждебным');
must(getKarmaStatus(-5000) === 'red', 'на -5000 игрок ещё красный');
must(isNpcHostile(-5000), 'красный и на -5000 враждебен');
must(getKarmaStatus(-5001) === 'outlaw', 'с -5001 игрок становится изгоем');
must(isNpcHostile(-5001), 'изгой обязан быть враждебным');
must(!isNpcHostile(100000), 'святой с огромной кармой враждебным быть не должен');
must(!isNpcHostile(0), 'нейтральный враждебным быть не должен');
  });

  it('враждебность всегда совпадает с таблицей — на всём диапазоне', () => {
    // Сквозная сверка вместо точечных примеров: если у таблицы поменяют границы
    // или признак, проверка разойдётся сразу и укажет, где именно.
    let проверено = 0;
    for (let карма = -12000; карма <= 12000; карма += 37) {
      const статус = getKarmaStatus(карма);
      const ожидалось = KARMA_PENALTIES[статус].npcHostile;
      if (isNpcHostile(карма) !== ожидалось) {
        throw new Error(
          `карма ${карма} (статус ${статус}): isNpcHostile вернул ${isNpcHostile(карма)}, ` +
            `а таблица обещает ${ожидалось}`
        );
      }
      проверено++;
    }
    must(проверено > 600, `проверено всего ${проверено} значений кармы: диапазон сузился`);
  });

  it('множитель дальности не меньше двух и не безумен', () => {
    must(
      NPC_HUNT_RANGE_MULTIPLIER >= 2,
      `множитель ${NPC_HUNT_RANGE_MULTIPLIER}: разница не ощущается, это не последствие`
    );
    must(
      NPC_HUNT_RANGE_MULTIPLIER <= 3,
      `множитель ${NPC_HUNT_RANGE_MULTIPLIER}: лес превращается в место, где бегут со всего региона`
    );
    // В мире аггро 18-20 единиц — проверяем, во что это выливается.
    const ближняя = 18 * NPC_HUNT_RANGE_MULTIPLIER;
    must(
      ближняя >= 36 && ближняя <= 54,
      `при аггро 18 монстр замечает враждебного с ${ближняя} единиц: ` +
        'либо незаметно, либо слишком далеко'
    );
  });

  it('настоящий ИИ: враждебного видно там, где мирного нет', () => {
    const ai = зверь();
    const ctx = ai.spawnMonster(ОПРЕДЕЛЕНИЕ, { x: 0, y: 0, z: 0 });
    // Расстояние 30: обычному аггро (20) не видно, враждебному (40) видно.
    const враждебный = { id: 'red-1', position: { x: 30, y: 0, z: 0 }, hp: 1 };
    const мирный = { id: 'good-1', position: { x: 30, y: 0, z: 0 }, hp: 1 };

    ai.tick(ctx.instanceId, [{ ...мирный, npcHostile: false }]);
    must(
      !ctx.aggroTable.has(мирный.id),
      `мирный на 30 единиях попал в аггро: аггро ${ОПРЕДЕЛЕНИЕ.aggroRange}, а он дальше`
    );

    const ai2 = зверь();
    const ctx2 = ai2.spawnMonster(ОПРЕДЕЛЕНИЕ, { x: 0, y: 0, z: 0 });
    ai2.tick(ctx2.instanceId, [{ ...враждебный, npcHostile: true }]);
    must(
      ctx2.aggroTable.has(враждебный.id),
      `враждебный на 30 единиях не попал в аггро: при аггро ${ОПРЕДЕЛЕНИЕ.aggroRange} ` +
        `и множителе ${NPC_HUNT_RANGE_MULTIPLIER} дальность равна ` +
        `${ОПРЕДЕЛЕНИЕ.aggroRange * NPC_HUNT_RANGE_MULTIPLIER}`
    );
  });

  it('настоящий ИИ: рядом враждебного и мирного видны оба', () => {
    const ai = зверь();
    const ctx = ai.spawnMonster(ОПРЕДЕЛЕНИЕ, { x: 0, y: 0, z: 0 });
    ai.tick(ctx.instanceId, [
      { id: 'red-1', position: { x: 5, y: 0, z: 0 }, hp: 1, npcHostile: true },
      { id: 'good-1', position: { x: 6, y: 0, z: 0 }, hp: 1, npcHostile: false },
    ]);
    must(ctx.aggroTable.has('red-1'), 'враждебный вблизи не попал в аггро');
    must(ctx.aggroTable.has('good-1'), 'мирный вблизи не попал в аггро');
  });

  it('настоящий ИИ: очень далёкий враждебный не виден даже издалека', () => {
    const ai = зверь();
    const ctx = ai.spawnMonster(ОПРЕДЕЛЕНИЕ, { x: 0, y: 0, z: 0 });
    const далёкий = 500;
    ai.tick(ctx.instanceId, [
      { id: 'outlaw-1', position: { x: далёкий, y: 0, z: 0 }, hp: 1, npcHostile: true },
    ]);
    must(
      !ctx.aggroTable.has('outlaw-1'),
      `враждебный с ${далёкий} единиц попал в аггро: множитель ${NPC_HUNT_RANGE_MULTIPLIER} ` +
        'не должен превращать весь регион в зону охоты'
    );
  });
});

describe('Враждебность подключена правильно', () => {
  const цикл = читать('server/src/systems/GameLoop.ts');
  const ии = читать('server/src/systems/AISystem.ts');
  const карма = читать('server/src/systems/KarmaSystem.ts');

  it('карма читается тем же запросом, что и здоровье', () => {
    must(
      /SELECT id, hp, karma FROM characters WHERE id = ANY\(\$1::uuid\[\]\)/.test(цикл),
      'карма читается отдельным запросом: лишний обход базы каждые 200 мс'
    );
    const запросов = (цикл.match(/FROM characters WHERE id = ANY/g) || []).length;
    must(
      запросов === 1,
      `запросов characters по игрокам ${запросов}: карма пошла отдельным запросом`
    );
  });

  it('признак ставится игрокам, а не остаётся в карте', () => {
    must(
      /players\[i\]\.npcHostile = hostileById\.get\(players\[i\]\.id\) === true;/.test(цикл),
      'признак враждебности не доходит до ИИ: карта прочитана и забыта'
    );
    must(
      /isNpcHostile\(Number\(r\.karma \?\? 0\)\)/.test(цикл),
      'враждебность считается не через таблицу последствий'
    );
  });

  it('ИИ читает признак, а не карму', () => {
    must(
      /player\.npcHostile[\s\S]{0,120}NPC_HUNT_RANGE_MULTIPLIER/.test(ии),
      'ИИ не учитывает враждебность при наборе аггро'
    );
    must(
      /TargetPlayer[\s\S]{0,400}npcHostile\?: boolean;/.test(ии),
      'в интерфейсе цели нет признака враждебности'
    );
    // Смысл правила: враждебного видно СТРОГО дальше. Если бы множитель стоял
    // на месте в другой стороне сравнения, проверка на числах поймала бы, а эта
    // — страхует от подмены самого поля.
    must(
      /const дальность = player\.npcHostile\s*\?\s*ctx\.definition\.aggroRange \* NPC_HUNT_RANGE_MULTIPLIER\s*\s*:\s*ctx\.definition\.aggroRange;/.test(ии),
      'множитель применён не к тому игроку: либо враждебный стал незаметнее, либо наоборот'
    );
  });

  it('таблица последствий читается в одном месте', () => {
    // isNpcHostile — единственная дверь к таблице. Прямой доступ из GameLoop или
    // AISystem означал бы, что правило «кто враждебен» живёт в двух копиях.
    must(
      /export function isNpcHostile\(karma: number\): boolean \{[\s\S]{0,200}KARMA_PENALTIES\[getKarmaStatus\(karma\)\]\.npcHostile;/.test(карма),
      'в системе кармы нет функции враждебности'
    );
    // Счётчик смотрит код, а не комментарии: в моём же комментарии про признак
    // таблица упомянута, и первая версия проверки ругалась сама на себя.
    const безКомментариев = (исходник: string): string =>
      исходник.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
    const прямойДоступ =
      (безКомментариев(цикл).match(/KARMA_PENALTIES/g) || []).length +
      (безКомментариев(ии).match(/KARMA_PENALTIES/g) || []).length;
    must(
      прямойДоступ === 0,
      `таблица последствий читается напрямую в ${прямойДоступ} местах вне системы кармы`
    );
  });

  it('у враждебности есть собственный счётчик проверок', () => {
    must(
      /npcHostile/.test(цикл) && /npcHostile/.test(ии),
      'признак враждебности не доходит от базы до ИИ'
    );
  });
});