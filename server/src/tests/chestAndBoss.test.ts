// Сундуки в подземельях и «хватает одного босса» — по решениям владельца.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ.
//
// СУНДУКИ (решение владельца: даёт золото и опыт, вскрывается один раз):
//   1. координаты сундуков есть в данных и совпадают с нарисованными;
//   2. сервер их заводит в заход и обрезает по стене тем же, что монстров;
//   3. вскрытие один раз: повторное не даёт добычу;
//   4. до сундука надо дойти: слишком далеко — отказ;
//   5. добыча считается из наград захода, а не выдумана;
//   6. маршруты стоят ДО параметризованных, иначе «chests» станет :dungeonId.
//
// БОССЫ (решение владельца: хватает одного):
//   1. у боссовой комнаты ровно ОДНО условие захода, а не по одному на
//      каждого: у крепости джиннов два, у гробницы убийца три;
//   2. берётся первый спавн босса — детерминированно, а не «кто добежал»;
//   3. проверка захода требует именно этот экземпляр.
//
// ГРОБНИЦА — единственная без координат сундуков: её интерьер построен как
// «Рассказ через детали», сундуков там не нарисовано ни одного. Это должно быть
// ЯВНЫМ решением, а не тихо пустым полем.
