// Чайки на причале.
//
// ЧТО БЫЛО (21 октября 2026, §275). Над водой уже садятся птицы (§273), а сам
// причал стоял пустым: ни одной чайки на перилах у рыбацкой лодки.
//
// ЧТО ТЕПЕРЬ. Три чайки на досках причала: тело, хвост и клюв. Места их
// записываются, и сторож проверяет, что чайки стоят на причале, а не в поле.
//
// ЧТО ПРОВЕРЯЕТСЯ. Чайки построены и стоят на причале (расстояние от оси
// пирса — не больше его половины), и места их записаны.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Чайки на причале', () => {
  it('чайки построены: тело, хвост и клюв', () => {
    // С 22 октября 2026 (§278) в списке ещё и сама фигура с её позой: чайка
    // взлетает и возвращается, и для этого нужно знать, где она стояла.
    должен(
      /export const чайкиНаПричале: \{[\s\S]{0,700}?\}\[\] = \[\];/.test(ТЕРРЕЙН),
      'нет списка мест чаек',
    );
    должен(/const тело = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.19, 8, 6\), MAT\.white\);/.test(ТЕРРЕЙН),
      'у чайки нет тела');
    должен(/const хвост = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.1, 0\.03, 0\.28\), MAT\.white\);/.test(ТЕРРЕЙН),
      'у чайки нет хвоста');
    должен(/const клюв = new THREE\.Mesh\(new THREE\.ConeGeometry\(0\.035, 0\.13, 4\), MAT\.clothRed\);/.test(ТЕРРЕЙН),
      'у чайки нет клюва');
    должен(/чайкиНаПричале\.push\(\{[\s\S]{0,200}?x: PORT\.x \+ lx,[\s\S]{0,120}?z: PORT\.z \+ lz,/.test(ТЕРРЕЙН),
      'место чайки не записывается');
  });

  it('чайки стоят на причале, а не в поле', () => {
    // Таблица мест — из кода, а не из проверки: иначе правка причала осталась бы
    // незамеченной (так и вышло в первой версии этого правила).
    const найдено = /for \(const \[сдвиг, бок\] of (\[\[.*?\]\]) as const\) \{/.exec(ТЕРРЕЙН);
    должен(найдено, 'не найден список мест чаек на причале');
    const места = [...найдено![1].matchAll(/\[(-?[\d.]+), (-?[\d.]+)\]/g)].map(
      (м) => ({ сдвиг: Number(м[1]), бок: Number(м[2]) }),
    );
    должен(места.length === 3, `мест чаек ${места.length}, а должно быть три`);
    for (const м of места) {
      // На причале ли чайка: расстояние от оси пирса — не больше метра.
      должен(
        Math.abs(м.бок) <= 1,
        `чайка стоит в ${Math.abs(м.бок)} м от оси причала, а причал узкий`,
      );
      // И она на досках, а не в воде: дальше конца пирса (8 м) не заходит.
      должен(м.сдвиг <= 8, 'чайка стоит за концом причала');
      // И сдвиг положителен: причал уходит от берега в сторону озера.
      должен(м.сдвиг > 0, 'чайка стоит на берегу, а не на причале');
    }
  });
});
