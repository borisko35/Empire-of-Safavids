// Выбор цели абордажа: два режима, один фильтр.
//
// ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. Фильтр целей общий для PvE и PvP. Если бы «список
// пиратов» и «список игроков» фильтровались по отдельности, фильтры разошлись
// бы молча: в одном режиме цель на суше оказалась бы допустимой, в другом нет.
// Проверка требует, чтобы ОДНО условие применялось к обоим.
//
// Второе: PvE берёт только ВОДНЫХ монстров. Абордаж — морской бой, и «абордажил
// разбойника в степи» — ошибка фильтра, а не фича.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const цели = код('server/src/systems/BoardingTargets.ts');
const монстры = читать('server/src/data/monsters.ts');
const спавн = читать('server/src/systems/SpawnSystem.ts');

describe('Выбор цели: фильтр один на оба режима', () => {
  it('есть одна функция пригодности', () => {
    must(/export function boardEligible\(/.test(цели), 'функции пригодности нет: фильтры разъехались');
    // Оба режима проходят через неё.
    must(/boardEligible\(цель, вход, дальность\)/.test(цели), 'PvP не проходит через общий фильтр');
    must(/boardEligible\(цель, вход, дальность\)/.test(цели), 'PvE не проходит через общий фильтр');
  });

  it('условия общие: зона, дистанция, разрыв уровней', () => {
    // Имена параметров кириллические, а \w в JS без флага u — только ASCII.
    // Поэтому [^\\s.]+ вместо \\w+: регулярка с \\w не находила бы ничего в
    // этом коде никогда.
    must(/target\.region !== [^\s.]+\.attackerRegion/.test(цели), 'проверки зоны нет');
    must(/boardInRange\(/.test(цели), 'проверки дистанции нет');
    must(/Math\.abs\([^\s.]+\.attackerLevel - target\.level\) > 10/.test(цели), 'порога разрыва уровней нет');
  });

  it('своя лодка отсекается', () => {
    // Своя цель — self-harm, а не бой.
    must(/[^\s.]+\.id === [^\s.]+\.attackerId/.test(цели), 'своей цели нет в отсечении');
  });
});

describe('Выбор цели: PvE берёт только воду', () => {
  it('фильтр по aquatic', () => {
    // Иначе «абордажил разбойника в степи» — ошибка фильтра, а не фича.
    must(/if \(!def\.aquatic\) continue;/.test(цели), 'PvE не фильтрует по воде');
  });

  it('пиратские монстры в водах залива есть', () => {
    // Без них PvE-режим пустой по построению.
    for (const id of ['mob_corsair', 'mob_gulf_reef_raider']) {
      must(new RegExp(`'${id}': \\{`).test(монстры), `монстра ${id} нет`);
      must(new RegExp(`monsterId: '${id}'`).test(спавн), `${id} не спавнится в заливе`);
    }
  });

  it('aquatic — настоящее поле монстра', () => {
    must(/aquatic/.test(монстры), 'поля aquatic нет в монстрах: фильтр сломается');
  });
});

describe('Выбор цели: режим выбирает атакующий', () => {
  it('одна точка входа по режиму', () => {
    // [^\\s.]+ потому что \w в JS без флага u не понимает кириллицу.
    must(
      /[^\s.]+\.mode === 'pve'\s*\n\s*\? pveTargets\(/.test(цели),
      'нет единой развилки: режимами начинают распоряжаться в двух местах',
    );
  });

  it('PvP-цель требует чужой лодки', () => {
    // Без лодки абордаживать некого.
    const список = /игроки: \{ id: string; nameRu: string; level: number; boatId: string; x: number; z: number \}\[\]/.exec(цели);
    must(список !== null, 'в списке игроков нет boatId: PvP возьмёт пловца без лодки');
  });
});
