// Мёртвые ключи site.*: лендинг зовёт их коротким именем, и это меняет всё.
//
// ЗАЧЕМ ЭТА ПРОВЕРКА. Первый проход искал подстроку 'site.X' и объявил мёртвыми
// 45 ключей — из них 14 были живые. Лендинг зовёт ключи КОРОТКИМ именем:
// функция строка(ключ) делает `локаль?.site?.[ключ]`, префикс добавляет она
// сама. Подстрочный поиск такие вызовы не видит.
//
// ЧЕМ ГРОЗИЛО УДАЛЕНИЕ. При отсутствии ключа строка() возвращает ПУСТУЮ СТРОКУ
// (`?? ''`), а не путь ключа. Мёртвый ключ исчез бы не громко — он молча стёр
// бы текст с лендинга: подпись голосования, статус сервера, заголовок шахмат.
//
// Поэтому проверка считает ключ живым двумя способами сразу: полный путь
// (клиент игры) и короткое имя (лендинг). Список мёртвых зафиксирован числом —
// рост означает, что кто-то перестал звать ключ, и его надо либо вернуть в
// дело, либо удалить осознанно.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/** Все .ts/.js/.html клиента, кроме собранных бандлов. */
function файлыКлиента(): string[] {
  const результат: string[] = [];
  const обход = (каталог: string): void => {
    for (const запись of readdirSync(join(корень, каталог), { withFileTypes: true })) {
      if (запись.name === 'node_modules') continue;
      const путь = join(каталог, запись.name);
      const полный = join(корень, путь);
      if (statSync(полный).isDirectory()) {
        // client/web/game — собранный бандл: там ключей не ищут.
        if (путь.replace(/\\/g, '/').endsWith('web/game')) continue;
        обход(путь);
        continue;
      }
      if (!/\.(ts|js|html)$/.test(запись.name)) continue;
      if (путь.replace(/\\/g, '/').includes('web/game/assets')) continue;
      результат.push(путь);
    }
  };
  обход('client/src');
  обход('client/web');
  return результат;
}

const файлы = файлыКлиента();
const тексты = файлы.map((путь) => readFileSync(join(корень, путь), 'utf8'));

const словарь = JSON.parse(readFileSync(join(корень, 'shared/locales/ru.json'), 'utf8')) as {
  site: Record<string, string>;
};
const ключи = Object.keys(словарь.site ?? {});

/** Живой ли ключ: полный путь или короткое имя. */
function жив(ключ: string): boolean {
  if (тексты.some((t) => t.includes(`site.${ключ}`))) return true;
  const короткий = new RegExp(`['\`"]${ключ.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['\`"]`);
  return тексты.some((t) => короткий.test(t));
}

describe('Мёртвые ключи site.*: считаются правильно', () => {
  it('обход достаточно широк', () => {
    // Иначе проверка проходила бы на пустом множестве: «ключей нет» потому,
    // что смотреть негде.
    //
    // Порог 60, а не 80: собранный бандл client/web/game исключён намеренно
    // (ключи в нём не ищут), и в набор входят только исходники. Обход обязан
    // накрыть И client/src, И client/web/js - именно там short-name вызовы.
    must(файлы.length > 60, `файлов клиента набрано ${файлы.length}: обход не работает`);
    must(ключи.length >= 100, `ключей site.* ${ключи.length}: словарь не прочитан`);
    // На Windows join даёт обратные слеши, и поиск 'client/src' по прямой
    // строке не находил бы ничего — проверка падала бы на рабочем обходе.
    const норма = файлы.map((путь) => путь.replace(/\\/g, '/'));
    const естьИсходникиИгры = норма.some((путь) => путь.includes('client/src/app'));
    const естьЛендинг = норма.some((путь) => путь.includes('client/web/js'));
    must(естьИсходникиИгры, 'обход не накрыл client/src: full-path вызовы не найдутся');
    must(естьЛендинг, 'обход не накрыл client/web/js: именно там зовут коротким именем');
  });

  it('ни один живой ключ не объявлен мёртвым', () => {
    // Три ключа, на которых первый проход срезал угол: vote_cooldown,
    // vote_ok, vote_err. Лендинг зовёт их коротким именем.
    const короткие = ['vote_cooldown', 'vote_ok', 'vote_err'];
    for (const ключ of короткие) {
      must(ключи.includes(ключ), `ключа ${ключ} нет в словаре: проверка устарела`);
      must(жив(ключ), `ключ ${ключ} объявлен мёртвым, а лендинг его зовёт`);
    }
  });

  it('состав мёртвых не растёт незамеченным', () => {
    // Число зафиксировано намеренно. Выросло - значит какой-то ключ перестали
    // звать: либо его вернули в дело, либо удалили осознанно.
    const мёртвые = ключи.filter((к) => !жив(к));
    expect({ мёртвых: мёртвые.length }).toEqual({ мёртвых: 31 });
  });

  it('мёртвые ключи не зовутся динамически', () => {
    // Обратная сторона: сборка `site.${переменная}` подстрочный поиск не
    // найдёт. Проверяем, что такого в клиенте нет вовсе, - иначе список
    // мог бы снова соврать.
    const динамика = файлы.filter((путь) => {
      const t = readFileSync(join(корень, путь), 'utf8');
      return /`site\.\$\{/.test(t) || /['"]site\.['"]\s*\+/.test(t) || /\+\s*['"]site\./.test(t);
    });
    expect({ файловСДинамикой: динамика.length }).toEqual({ файловСДинамикой: 0 });
  });
});