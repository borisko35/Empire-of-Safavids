// Мокрая земля в дождь.
//
// ЧТО БЫЛО (21 октября 2026, §261). Дождь шёл полосами, а земля под ногами
// оставалась сухой и светлой: погода была декорацией поверх сухого мира.
//
// ЧТО ТЕПЕРЬ. В дождь земля и городская мостовая темнеют и блестят, а после
// дождя ещё некоторое время мокрые.
//
// ЧТО ПРОВЕРЯЕТСЯ. Мокрота идёт от погоги, земля от неё темнеет и становится
// глянцевой, мостовая — тоже, и сохнет земля медленно, чем набирает воду.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Мокрая земля', () => {
  it('земля темнеет и блестит, когда мокрая', () => {
    // С 21 октября 2026 (§262) функция стала общей для мокрой и заснеженной
    // земли: setGroundState(wet, snow).
    должен(
      /export function setGroundState\(wet: number, snow: number\)/.test(ТЕРРЕЙН),
      'нет функции состояния земли',
    );
    // Темнее.
    должен(
      /материалЗемли\.color\.setScalar\(1 - 0\.\d+ \* м\)/.test(ТЕРРЕЙН),
      'мокрая земля не темнеет: дождь не оставляет следов',
    );
    // Глянцеве: мокрая земля отражает небо, а не рассеивает свет.
    должен(
      /материалЗемли\.roughness = 1 - 0\.\d+ \* м;/.test(ТЕРРЕЙН),
      'мокрая земля не блестит: шероховатость не падает',
    );
    // Городская мостовая — тоже.
    должен(/MAT\.street\.roughness = 1 - 0\.\d+ \* м;/.test(ТЕРРЕЙН), 'мостовая не мокнет');
    // Материал земли должен быть доступен: он создаётся в buildTerrain.
    должен(
      /материалЗемли = материал;/.test(ТЕРРЕЙН),
      'материал земли не сохраняется: править мокроту нечем',
    );
  });

  it('мокрота идёт от погоды, и земля сохнет медленно', () => {
    должен(
      /const идётДождь = this\.currentWeather === 'rain' \|\| this\.currentWeather === 'storm';/.test(МИР),
      'мокрота не зависит от дождя',
    );
    // Набирает быстро, сохнет медленно.
    должен(
      /this\.мокрота = Math\.min\(1, this\.мокрота \+ dt \* 0\.\d+\)/.test(МИР),
      'земля не намокает в дождь',
    );
    должен(
      /this\.мокрота = Math\.max\(0, this\.мокрота - dt \* 0\.\d+\)/.test(МИР),
      'земля высыхает мгновенно: мокрой остаётся только во время дождя',
    );
    должен(/setGroundState\(this\.мокрота, this\.снег\);/.test(МИР), 'мокрота не передаётся земле');
  });
});
