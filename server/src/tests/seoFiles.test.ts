// Поисковикам: сайт отдаёт правила и карту, и они не врут.
//
// ЧТО ЗДЕСЬ ВАЖНО. Файл robots.txt и sitemap.xml в репозитории есть и на
// проде отдаются - проверено вживую. Запись в ROADMAP утверждала обратное
// («их нет - сайт не индексируется»), и это была неправда в источнике
// истины. Настоящая проблема в другом: боевой домен зашит ТЕКСТОМ в двенадцати
// местах четырёх файлов, и ничего не проверяет, что они совпадают.
//
// Что будет, если домен сменится: страницы продолжат объявлять старый
// канонический адрес, поисковик уведёт игроков в пустоту, и это будет
// выглядеть как «SEO перестал работать» без всякой видимой причины.
//
// ПОЧЕМУ НЕ ЧИТАЕТСЯ deploy/.env. Он вне git, и в CI его нет. Эталон
// домена берётся из самих файлов и проверяется на согласованность, а не на
// совпадение с секретом: смысл проверки в том, что двенадцать вхождений
// согласованы между собой и указывают на существующие страницы.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const web = 'client/web/';

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/** Все страницы, на которые поисковик может пойти. */
const СТРАНИЦЫ = readdirSync(join(корень, web))
  .filter(f => f.endsWith('.html'));

/**
 * Страницы, которые ВООБЩЕ не должны попадать в карту, с причиной.
 *
 * Список закрытый и с объяснением. Открытый список («всё, кроме
 * admin.html») означал бы, что забытая служебная страница молча попадёт в
 * карту, и заметить это можно будет только по жалобам поисковика.
 */
const ИСКЛЮЧЕНЫ: Record<string, string> = {
  'admin.html': 'служебная страница, в поиске ей нечего искать',
  // Объявление об обновлении. Стоит в верхнем меню и в первой новости, но в
  // карту не входит намеренно: страница снимается 1 октября, и добавлять
  // адрес, который завтра исчезнет, значит заранее отдать поисковику ссылку
  // в 404. Когда объявление снимут, запись перестанет быть нужной, и
  // проверка не заметит ничего - а это правильный исход.
  'update.html': 'временное объявление об обновлении, снимается 1 октября',
};

const robots = читать(web + 'robots.txt');
const sitemap = читать(web + 'sitemap.xml');
const ДОМЕН = /https:\/\/([\w.-]+)\//.exec(sitemap)?.[1] ?? '';
must(ДОМЕН, 'в sitemap.xml не найден домен в адресе страницы');

describe('Домен один, а не двенадцать', () => {
  it('везде в client/web боевой адрес указывает на один домен', () => {
    // ПЕРВАЯ ВЕРСИЯ БЫЛА СЛИШКОМ ШИРОКОЙ И ПАЛА НЕ ПО ДЕЛУ. Она брала ВСЕ
    // ссылки https:// из всех файлов и сравнивала с боевым доменом, а
    // попадали туда schema.org, fonts.googleapis.com, facebook.com и
    // reddit.com. Это чужие сайты, и они обязаны быть чужими: ссылка на
    // фейсбук это не расхождение.
    //
    // Проверяется то, где домен значит САМ СЕБЯ: канонический адрес,
    // og:url, адреса в карте сайта и строка Sitemap. Именно они уводят
    // поисковик, если расходятся.
    const разные: Record<string, string[]> = {};
    const адресаСвоегоСайта = (текст: string): string[] => {
      const найдено: string[] = [];
      // canonical и og:url
      for (const m of текст.matchAll(/<(?:link rel="canonical"|meta property="og:url")[^>]*(?:href|content)="([^"]+)"/g)) {
        найдено.push(m[1]);
      }
      // адреса карты сайта
      for (const m of текст.matchAll(/<loc>([^<]+)<\/loc>/g)) найдено.push(m[1]);
      // строка Sitemap в robots.txt
      for (const m of текст.matchAll(/^Sitemap:\s*(\S+)/gm)) найдено.push(m[1]);
      return найдено;
    };

    for (const файл of readdirSync(join(корень, web))) {
      if (!/\.(html|txt|xml)$/.test(файл)) continue;
      const посторонние = [...new Set(адресаСвоегоСайта(читать(web + файл)))]
        .map(a => /https?:\/\/([^/]+)/.exec(a)?.[1] ?? '')
        .filter(д => д !== '' && д !== ДОМЕН);
      if (посторонние.length) разные[файл] = посторонние;
    }
    expect({ посторонние: разные }).toEqual({ посторонние: {} });
  });

  it('домен не похож на заглушку из .env.example', () => {
    // deploy/.env.example содержит game.example.com - это шаблон для
    // настройки, а не боевой адрес. Если бы в файлы попал он, сайт был бы
    // «настроен» и при этом вёл бы в никуда.
    const шаблон = /DOMAIN=(.*)/.exec(читать('deploy/.env.example'))?.[1].trim() ?? '';
    must(шаблон, 'в deploy/.env.example нет строки DOMAIN');
    expect({ боевой_не_шаблон: ДОМЕН !== шаблон, боевой: ДОМЕН, шаблон })
      .toEqual({ боевой_не_шаблон: true, боевой: ДОМЕН, шаблон });
  });

  it('канонический адрес и og:url совпадают с картой сайта', () => {
    // Поисковик берёт канонический адрес из страницы. Если он указывает не
    // туда же, куда ведёт карта, индекс будет о двух разных сайтах.
    const лендинг = читать(web + 'index.html');
    const канонический = /<link rel="canonical" href="([^"]+)"/.exec(лендинг)?.[1] ?? '';
    const ogUrl = /<meta property="og:url" content="([^"]+)"/.exec(лендинг)?.[1] ?? '';
    must(канонический && ogUrl, 'в index.html нет canonical или og:url');
    expect({ совпадают: канонический === ogUrl, адрес: канонический })
      .toEqual({ совпадают: true, адрес: канонический });
  });
});

describe('Карта сайта описывает все страницы', () => {
  // Адрес / в карте - это лендинг, то есть index.html. Без подстановки
  // первая страница сайта считалась бы «не описанной», и проверка ругалась
  // бы на саму себя. Подстановка ИМЕННО такая: адрес без имени файла
  // равносилен index.html, и никакой другой страницы он не означает.
  const адреса = (): string[] => [...sitemap.matchAll(/<loc>[^<]*\/([^/<]*)<\/loc>/g)]
    .map(m => (m[1] === '' ? 'index.html' : m[1]));

  it('каждая публичная страница либо в карте, либо исключена с причиной', () => {
    // Именно эта проверка ловит забытую страницу. Страница может быть
    // создана, встроена в меню и о ней забыть, а поисковик о ней не узнает.
    const вКарте = адреса();
    const без = СТРАНИЦЫ.filter(ф => !вКарте.includes(ф) && !(ф in ИСКЛЮЧЕНЫ));
    expect({ страниц: СТРАНИЦЫ.length, в_карте: вКарте.length, без_следа: без })
      .toEqual({ страниц: СТРАНИЦЫ.length, в_карте: вКарте.length, без_следа: [] });
  });

  it('в карте нет страницы, которой больше нет', () => {
    // Обратная сторона: удалили страницу, а адрес в карте остался. Поисковик
    // будет приходить в 404 и сочтёт сайт сломанным.
    const лишние = адреса().filter(ф => !СТРАНИЦЫ.includes(ф));
    expect({ лишние }).toEqual({ лишние: [] });
  });

  it('у каждого исключения написана причина, а не пустая строка', () => {
    // Исключение без причины - это то же самое, что страница без решения:
    // через полгода никто не вспомнит, почему её нет.
    const безПричины = Object.entries(ИСКЛЮЧЕНЫ)
      .filter(([, причина]) => причина.trim().length < 10)
      .map(([страница]) => страница);
    expect({ без_причины: безПричины }).toEqual({ без_причины: [] });
  });

  it('у каждого адреса в карте есть lastmod в формате даты', () => {
    // Пустой lastmod - это «не знаю», и поисковик тратит обход впустую.
    const блоки = sitemap.split('<url>').slice(1);
    must(блоки.length > 0, 'в карте нет ни одного адреса');
    const плохие = блоки
      .map(b => /<lastmod>([^<]*)<\/lastmod>/.exec(b)?.[1] ?? 'НЕТ')
      .filter(v => !/^\d{4}-\d{2}-\d{2}$/.test(v));
    expect({ адресов: блоки.length, плохие }).toEqual({ адресов: блоки.length, плохие: [] });
  });
});

describe('robots.txt говорит с sitemap', () => {
  it('строка Sitemap указывает на существующую карту', () => {
    // Если бы адрес в robots.txt и настоящий путь разошлись, поисковик
    // сообщил бы о нём как о битом - то есть узнал бы о проблеме от
    // третьих лиц, а не от своей проверки.
    const указан = /Sitemap:\s*(\S+)/.exec(robots)?.[1] ?? '';
    must(указан, 'в robots.txt нет строки Sitemap');
    expect({
      домен_тот_же: указан.startsWith(`https://${ДОМЕН}/`),
      путь_существует: указан.endsWith('/sitemap.xml') && !!читать(web + 'sitemap.xml'),
    }).toEqual({ домен_тот_же: true, путь_существует: true });
  });

  it('администратор закрыт от индексации', () => {
    // Обслуживающий адрес в выдаче - это и лишний трафик, и публичная
    // форма входа в игру на странице, которую никто не проверял.
    expect({ закрыт: /Disallow:\s*\/admin\.html/.test(robots) }).toEqual({ закрыт: true });
  });

  it('закрыты служебные адреса', () => {
    // Без этого в индекс попадают ответы API и поток событий сокета:
    // они не страницы, и краулер будет ходить по ним впустую.
    const обязательные = ['/api/', '/socket.io/', '/download/', '/health'];
    const нет = обязательные.filter(п => !robots.includes('Disallow: ' + п));
    expect({ нет_закрытых: нет }).toEqual({ нет_закрытых: [] });
  });

  it('robots.txt не отдаётся лендингом вместо правил', () => {
    // ПОЧЕМУ ЭТА ПРОВЕРКА ВООБЩЕ НУЖНА. nginx отдаёт на любой путь
    // лендинг (try_files ... /index.html). Без явного robots.txt поисковик
    // получал вместо правил html-страницу - и считал, что правил нет
    // вовсе, то есть site не запрещён, но и не описан.
    //
    // Проверка ловит именно потерянный файл: если robots.txt исчезнет, путь
    // снова начнёт отдавать лендинг, и первое, что это сломает, здесь.
    expect({ на_месте: robots.trim().length > 0, есть_правило: /^User-agent:/m.test(robots) })
      .toEqual({ на_месте: true, есть_правило: true });
  });
});
