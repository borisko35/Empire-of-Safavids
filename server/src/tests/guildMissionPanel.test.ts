// Панель заданий в клиенте: не холостые кнопки и не выдуманный перевод.
//
// ПРАВИЛО ДНЯ. Проверка, которая не может краснеть, хуже отсутствующей.
// Здесь у каждой проверки назван способ поломки, который она ловит.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { GUILD_MISSIONS } from '../data/guilds';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const панель = читать('client/src/app/guild.ts');
const клиентApi = читать('client/src/app/api.ts');
const ru = JSON.parse(читать('shared/locales/ru.json')) as { guild: Record<string, string> };
const en = JSON.parse(читать('shared/locales/en.json')) as { guild: Record<string, string> };
const az = JSON.parse(читать('shared/locales/az.json')) as { guild: Record<string, string> };

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

describe('Панель заданий вызывается с сервера', () => {
  it('список, взятие и забор описаны в клиентском api', () => {
    // Без этого кнопки звали бы несуществующий маршрут, и панель падала бы
    // молча: ошибка ушла бы в catch и нарисовала «задания недоступны».
    expect({
      список: /guildMissions: \(characterId: string\)/.test(клиентApi),
      взять: /guildMissionStart: \(characterId: string, missionId: string\)/.test(клиентApi),
      забрать: /guildMissionClaim: \(characterId: string, missionId: string\)/.test(клиентApi),
      путь_списка: /\/api\/guilds\/missions\?characterId=/.test(клиентApi),
      путь_взятия: /\/api\/guilds\/missions\/start/.test(клиентApi),
      путь_забора: /\/api\/guilds\/missions\/claim/.test(клиентApi),
    }).toEqual({
      список: true, взять: true, забрать: true,
      путь_списка: true, путь_взятия: true, путь_забора: true,
    });
  });

  it('панель зовёт все три', () => {
    expect({
      список: /api\.guildMissions\(cid\(\)\)/.test(панель),
      взять: /api\.guildMissionStart\(cid\(\), задание\.id\)/.test(панель),
      забрать: /api\.guildMissionClaim\(cid\(\), задание\.id\)/.test(панель),
    }).toEqual({ список: true, взять: true, забрать: true });
  });
});

describe('Клиент не решает за сервер', () => {
  it('кнопка рисуется по решению сервера, а не по своим расчётам', () => {
    // Поломка: клиент рисует «взять» всем, у кого state === 'open', и
    // сервер отказывает. Игрок видит кнопку и получает отказ - и решает,
    // что задание сломано.
    const блок = панель.slice(панель.indexOf('function renderMission'));
    expect({
      причину_берёт_у_сервера: /MISSION_BLOCKS\[задание\.blockedBy\]/.test(блок),
      // Никаких пересчётов вида haveMembers < needMembers в клиенте:
      // сервер уже всё посчитал и прислал готовый blockedBy.
      не_пересчитывает: !/haveMembers\s*<\s*/.test(панель) && !/\.required\s*-\s*/.test(панель),
    }).toEqual({ причину_берёт_у_сервера: true, не_пересчитывает: true });
  });

  it('причина блокировки показывается вместо кнопки, а не подсказкой', () => {
    // Поломка: кнопка «взять» с подсказкой при наведении. На телефоне
    // подсказку никто не увидит, и кнопка выглядит как рабочая.
    const блок = панель.slice(панель.indexOf('const причина = MISSION_BLOCKS'));
    const доКнопки = блок.slice(0, блок.indexOf('const взять = document.createElement'));
    expect({
      подсказка_вместо_кнопки: /return карточка;/.test(доКнопки),
      видно_сколько_не_хватает: /\(\$\{задание\.haveMembers\}\/\$\{задание\.needMembers\}\)/.test(блок),
    }).toEqual({ подсказка_вместо_кнопки: true, видно_сколько_не_хватает: true });
  });

  it('забрать награду можно только в состоянии done', () => {
    // Поломка: кнопка «забрать» рисуется в 'active'. Игрок жмёт и получает
    // MISSION_NOT_DONE - то есть кнопка, которая всегда отказывает.
    const блок = панель.slice(панель.indexOf('function renderMission'));
    const взять = блок.indexOf('const взять = document.createElement');
    const забрать = блок.indexOf('const забрать = document.createElement');
    // Ищутся ВЕТКИ if, а не любое упоминание состояния: 'готово'
    // вычисляется в самом верху функции, и сравнение по нему давало бы
    // ложь на заведомо правильном коде.
    const claimed = блок.indexOf("if (задание.state === 'claimed')");
    const done = блок.indexOf("if (задание.state === 'done')");
    expect({
      claimed_раньше_всего: claimed >= 0 && claimed < done,
      done_раньше_забора: done >= 0 && done < забрать,
      забор_раньше_взятия: забрать > 0 && забрать < взять,
    }).toEqual({ claimed_раньше_всего: true, done_раньше_забора: true, забор_раньше_взятия: true });
  });
});

describe('Коды отказа показаны, а не спрятаны', () => {
  it('каждый код, который сервер может вернуть, есть в клиенте', () => {
    // Поломка: сервер добавил код, клиент о нём не знает, и игрок видит
    // сырой «MISSION_WHATEVER» вместо подсказки.
    const серверные = читать('server/src/routes/guilds.ts').match(/MISSION_[A-Z_]+/g) ?? [];
    const уникальные = [...new Set(серверные)];
    must(уникальные.length >= 5, 'найдено подозрительно мало кодов: ' + уникальные.length);
    const отсутствуют = уникальные.filter(к => !панель.includes(к));
    expect({ всего: уникальные.length, отсутствуют })
      .toEqual({ всего: уникальные.length, отсутствуют: [] });
  });

  it('каждый ключ панели переведён во всех трёх языках', () => {
    const изТаблиц = [...панель.matchAll(/'(guild\.(?:err_)?mission_[a-z_]+)'/g)].map(m => m[1]);
    const уникальные = [...new Set(изТаблиц)];
    must(уникальные.length > 20, 'найдено подозрительно мало ключей заданий: ' + уникальные.length);
    // В JSON ключи лежат ПОД объектом guild и без префикса: там
    // "missions_title", а обращаются через t('guild.missions_title'). Искать
    // ru.guild['guild.missions_title'] - значит искать несуществующий ключ
    // и объявлять переведённое непереведённым.
    const безПрефикса = (к: string): string => к.replace(/^guild\./, '');
    const без = {
      ru: уникальные.filter(к => ru.guild[безПрефикса(к)] === undefined),
      en: уникальные.filter(к => en.guild[безПрефикса(к)] === undefined),
      az: уникальные.filter(к => az.guild[безПрефикса(к)] === undefined),
    };
    expect({ всего: уникальные.length, без })
      .toEqual({ всего: уникальные.length, без: { ru: [], en: [], az: [] } });
  });

  it('названия видов целей покрывают все типы из справочника', () => {
    // Поломка: в справочнике появился новый вид цели, клиент о нём не знает
    // и рисует английский «collect: 12/500» посреди русского текста.
    const типы = [...new Set(GUILD_MISSIONS.flatMap(м => м.objectives.map(o => o.type)))];
    const покрыто = (панель.match(/mission_obj_[a-z]+/g) ?? []).map(к => к.replace('mission_obj_', ''));
    expect({ типы, не_покрыто: типы.filter(т => !покрыто.includes(т)) })
      .toEqual({ типы, не_покрыто: [] });
  });
});

describe('Русская буква вместо латинской не доходит до сборки', () => {
  it('каждый вызываемый в панели именованный идентификатор объявлен', () => {
    // СЕГОДНЯ ТРИ ОПЕЧАТКИ ПОДРЯД. Раскладка одна, буквы выглядят
    // одинаково, и компиляция падает, а не тест:
    //   т( ) кириллической вместо t( )   -> Cannot find name 'т'
    //   латинская p вместо кириллической п -> Cannot find name 'p'
    //
    // Проверка не пытается угадать «похожие» буквы - это ненадёжно. Она
    // берёт ВСЕ вызовы вида имя( в коде панели и сверяет каждое имя с тем,
    // что действительно объявлено или импортировано. Необъявленное имя -
    // это ровно та ошибка, что стоила сегодня часа.
    //
    // Список разрешённых: объявленные в файле функции и константы,
    // импортированные имена, и имена стандартных вызовов, которые не
    // требуют объявления.
    const встроенные = new Set([
      // Язык и браузер: всё это объявлено средой, а не файлом.
      'Number', 'String', 'Boolean', 'Array', 'Object', 'Math', 'JSON', 'Date',
      'Promise', 'Set', 'Map', 'Error', 'RegExp', 'parseInt', 'parseFloat', 'isNaN',
      'prompt', 'confirm', 'alert', 'fetch', 'setTimeout', 'clearTimeout',
      'document', 'window',
      // Ключевые слова. Регулярка вызовов не понимает грамматику и берёт
      // «async (» за вызов функции: async () => - это стрелочная функция,
      // а не вызов. Без них проверка краснела бы на заведомо верном коде.
      'if', 'for', 'while', 'switch', 'catch', 'return', 'typeof', 'function',
      'new', 'await', 'async', 'console', 'toast',
    ]);

    // Объявления: function имя(, const имя =, let имя =, import { a, b }
    const объявлены = new Set<string>();
    for (const m of панель.matchAll(/\b(?:function|const|let|class)\s+([A-Za-zА-Яа-яЁё_$][\w$]*)/g)) {
      объявлены.add(m[1]);
    }
    for (const m of панель.matchAll(/\bimport\s+(?:type\s+)?\{([^}]*)\}/g)) {
      for (const часть of m[1].split(',')) {
        const имя = часть.replace(/\btype\b/, '').split(/\bas\b/)[0].trim();
        if (имя) объявлены.add(имя);
      }
    }

    // Вызовы: имя (, но не ключевое слово и не метод через точку.
    const необъявленные: string[] = [];
    let найдено = 0;
    for (const m of панель.matchAll(/(^|[^.\w$А-Яа-яЁё])([A-Za-zА-Яа-яЁё_$][\w$]*)\s*\(/g)) {
      const имя = m[2];
      if (встроенные.has(имя)) continue;
      if (!объявлены.has(имя)) необъявленные.push(имя);
      найдено++;
    }
    // Проверка мертва, если вызовов не нашлось ВООБЩЕ: тогда «нет
    // необъявленных» ничего не значит. Считать надо найденные вызовы, а не
    // ненайденные имена - иначе проверка становится мёртвой ровно тогда,
    // когда начинает работать правильно.
    must(найдено > 50, 'регулярка вызовов нашла слишком мало: ' + найдено);
    const уникальные = [...new Set(необъявленные)];
    expect({ вызовов_найдено: найдено, необъявленные: уникальные })
      .toEqual({ вызовов_найдено: найдено, необъявленные: [] });
  });
});

describe('У используемых классов есть стили', () => {
  it('каждый класс из панели объявлен в таблице стилей', () => {
    // НАЙДЕНО ПРИ РАЗБОРЕ. Девять классов, которыми рисуются навыки и
    // задания, не были объявлены в styles.css ВООБЩЕ - блок навыков был
    // выкачен без единого правила и панель шла обычным потоком текста.
    // Ни одна проверка этого не ловила: отсутствие стилей не является
    // ошибкой сборки, CSS не сверяется с разметкой, и панель выглядит
    // «просто некрасиво», а не «сломанной».
    //
    // Проверка сверяет ДВА направления: класс из панели есть в CSS, и
    // наоборот. Второе направление ловит правила, от которых отказались,
    // а первое - новый класс, забытый при добавлении.
    const стили = читать('client/src/app/styles.css');

    // ДЫРА, НАЙДЕННАЯ ПОЛОМКОЙ С ОТКАТОМ. Сначала классы собирались
    // регуляркой /'(guild-[a-z-]+)/ - то есть только те, что стоят в
    // строке ПЕРВЫМ символом. Но классы добавляются ещё тремя способами:
    //   className += ' guild-mission-obj-done'   (пробел в начале)
    //   block('guild-block guild-missions')
    //   'a b' + (условие ? ' x' : ' y')
    // Удаление стиля .guild-mission-obj-done оставило проверку ЗЕЛЁНОЙ,
    // потому что этот класс в неё просто не попадал. Проверка, которая не
    // видит половину того, что проверяет, хуже отсутствующей.
    //
    // Теперь берутся ВСЕ строковые литералы, и из них - все токены,
    // начинающиеся с guild-. Это покрывает все способы задать класс.
    const используются = new Set<string>();
    for (const литерал of панель.matchAll(/['"`]([^'"`\n]*)['"`]/g)) {
      for (const токен of литерал[1].split(/[\s+]+/)) {
        const класс = токен.trim();
        if (/^guild-[a-z-]+$/.test(класс)) используются.add(класс);
      }
    }
    const список = [...используются];
    must(список.length >= 20, 'найдено подозрительно мало классов: ' + список.length);

    // ВТОРАЯ ДЫРА, ТОЖЕ НАЙДЕННАЯ ПОЛОМКОЙ. Регулярка была
    // /\.(guild-[a-z-]+)/ - она брала имя и из СОСТАВНОГО селектора
    // .guild-skill .guild-btn, где .guild-skill участвует как контекст, а не
    // как оформляемый элемент. Удаление .guild-skill { } оставляло проверку
    // зелёной: класс считался стилизованным по правилу, которое ничего ему
    // не задаёт.
    //
    // Считаются только селекторы, после которых идёт «{» или «,»: только там
    // класс получает свои собственные свойства.
    const объявлены = new Set(
      [...стили.matchAll(/\.(guild-[a-z-]+)\s*[,{]/g)].map(m => m[1]));

    const безСтиля = список.filter(к => !объявлены.has(к));
    expect({ всего: список.length, без_стиля: безСтиля })
      .toEqual({ всего: список.length, без_стиля: [] });
  });

  it('готовое задание выделяется рамкой, а уже полученное гаснет', () => {
    // Поломка: оба состояния выглядят одинаково, и игрок не видит, какое
    // задание можно забрать прямо сейчас.
    const стили = читать('client/src/app/styles.css');
    expect({
      готовое_с_рамкой: /\.guild-mission-done\s*\{[^}]*border/.test(стили),
      получено_погашено: /\.guild-skill-off\s*\{[^}]*opacity/.test(стили),
      // Выполненная цель помечается: по одному «100/100» не всегда видно,
      // что это конец пути, а не середина.
      цель_выполнена: /\.guild-mission-obj-done\s*\{/.test(стили),
    }).toEqual({ готовое_с_рамкой: true, получено_погашено: true, цель_выполнена: true });
  });
});

describe('Данные не переводятся', () => {
  it('название и описание задания берутся с сервера как есть', () => {
    // Выдуманный перевод названия задания хуже русского текста у
    // азербайджанца: он звучит как ошибка, а русский - как недоделка.
    const блок = панель.slice(панель.indexOf('function renderMission'));
    expect({
      имя_из_данных: /t\('lang'\) === 'ru' \? задание\.nameRu : задание\.name/.test(блок),
      описание_из_данных: /описание\.textContent = задание\.description/.test(блок),
    }).toEqual({ имя_из_данных: true, описание_из_данных: true });
  });
});
