// Ткацкая и кладовая: дверь одна и та же на обеих сторонах, станки на месте.
//
// ЧТО ОСОБЕННОГО В ЭТОЙ ПОСТРОЙКЕ. Замер по деревне дал две разные ложные
// нули, и обе — по вине инструмента, а не кода:
//
//   1. «минарет»: слово нашлось, но единственное вхождение — КОММЕНТАРИЙ.
//      Геометрия минаретов стояла рядом, безымянная, как и всегда.
//   2. «кузница»: по словам кузниц/forge ноль, и кузницы как будто нет.
//      Но furnishWorkshop содержит наковальню, верстак, бочки и стойку
//      инструментов — просто всё это безымянное.
//
// Отсюда правило этой проверки: ищем ГЕОМЕТРИЮ по точным конструкциям, а не
// слова. И отдельно: отсутствие названия — не отсутствие вещи.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';
import { waterMask } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');

describe('Ткацкая: место подобрано измерением', () => {
  it('дверь стоит на сухой земле', () => {
    const def = INTERIORS.weaver;
    must(def !== undefined, 'на сервере нет записи weaver: дверь есть, а войти некуда');
    const влажность = waterMask(def.doorX, def.doorZ);
    must(
      влажность === 0,
      `у двери (${def.doorX}, ${def.doorZ}) влажность ${влажность.toFixed(4)}, а должно быть 0.0000`
    );
  });

  it('проверка места не пустая: вода остаётся водой', () => {
    must(waterMask(-420, -160) > 0.9, 'озеро перестало быть водой: маска считается неверно');
    must(waterMask(620, 300) > 0.9, 'пруд перестал быть водой: маска считается неверно');
  });

  it('дверь не стоит на отпавших точках', () => {
    // При замере (-40, -820) и (-260, -840) дали 1.0000 — это озеро.
    const def = INTERIORS.weaver!;
    must(def.doorZ > -700, `дверь ушла на юг (${def.doorZ}), а там вода: точки ниже -700 отпадали при замере`);
  });
});

describe('Ткацкая: слот и дверь совпадают на клиенте и на сервере', () => {
  it('ткацкая держит тринадцатый слот на обеих сторонах', () => {
    const ключи = Object.keys(INTERIORS);
    const слотСервер = ключи.indexOf('weaver');
    must(слотСервер === 13, `ткацкая на слоте ${слотСервер} из ${ключи.length}, а обязана быть тринадцатой`);
    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    must(
      записи.indexOf('weaver') === слотСервер,
      `на клиенте ткацкая на слоте ${записи.indexOf('weaver')}, а на сервере ${слотСервер}`
    );
  });

  it('все четырнадцать построек держат свои слоты', () => {
    const ключи = Object.keys(INTERIORS);
    const ждём: [string, number, number][] = [
      ['stable', 0, 4000],
      ['barracks', 1, 4044],
      ['workshop', 2, 4088],
      ['tavern', 3, 4132],
      ['observatory', 4, 4176],
      ['science', 5, 4220],
      ['arena', 6, 4264],
      ['auction_house', 7, 4308],
      ['circus', 8, 4352],
      ['caravanserai', 9, 4396],
      ['fortress', 10, 4440],
      ['palace', 11, 4484],
      ['mosque', 12, 4528],
      ['weaver', 13, 4572],
    ];
    for (const [id, слот, комната] of ждём) {
      must(ключи[слот] === id, `на слоте ${слот} стоит ${ключи[слот]}, а ожидался ${id}`);
      must(
        INTERIORS[id as keyof typeof INTERIORS]!.roomCx === комната,
        `у ${id} roomCx ${INTERIORS[id as keyof typeof INTERIORS]!.roomCx}, а слот ${слот} даёт ${комната}`
      );
    }
  });

  it('координаты двери совпадают на клиенте и на сервере', () => {
    const def = INTERIORS.weaver!;
    const своя = /id: 'weaver', kind: 'weaver',[\s\S]{0,140}?dx: (-?\d+), dz: (-?\d+)/.exec(клиент);
    must(своя !== null, 'у ткацкой на клиенте нет абсолютной двери');
    must(
      Number(своя![1]) === def.doorX && Number(своя![2]) === def.doorZ,
      `клиент рисует дверь в (${своя![1]}, ${своя![2]}), а сервер ждёт (${def.doorX}, ${def.doorZ})`
    );
  });

  it('комната не налезает на соседние', () => {
    const def = INTERIORS.weaver!;
    const чужие = Object.values(INTERIORS).filter((д) => д.id !== 'weaver');
    const тесные = чужие.filter((д) =>
      Math.abs(д.roomCx - def.roomCx) < 32 && Math.abs(д.roomCz - def.roomCz) < 32
    );
    must(тесные.length === 0, `комната налезает на: ${тесные.map((д) => д.id).join(', ')}`);
  });

  it('граница кармана покрывает новую комнату', () => {
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+), z0: (-?\d+), z1: (\d+) \}/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    must(
      // Правый край комнаты, а не её центр: комната шириной 22, значит
      // земля обязана быть до roomCx + roomHalf. Проверка «x1 >= roomCx»
      // пропускала бы дыру в 16 единиц — и пропускала.
      Number(прямоугольник![2]) >=
        INTERIORS.weaver!.roomCx + INTERIORS.weaver!.roomHalf,
      `правый край кармана ${прямоугольник![2]}, а правый край комнаты ` +
        `${INTERIORS.weaver!.roomCx + INTERIORS.weaver!.roomHalf}: под комнатой нет земли`
    );
  });
});

describe('Ткацкая: станки и кладовая обставлены по-настоящему', () => {
  it('функция обстановки заведена и вызывается', () => {
    must(/function furnishWeaver\(/.test(клиент), 'функции обстановки ткацкой нет');
    must(/weaver: furnishWeaver,/.test(клиент), 'ткацкая не прописан в выборе обстановки');
    must(
      /'weaver'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 600) ?? ''),
      'в типе BuildingKind нет ткацкой'
    );
  });

  it('три станка стоят, и у каждого рама с нитями', () => {
    const начало = клиент.indexOf('function furnishWeaver(');
    must(начало > 0, 'функция обстановки ткацкой не найдена');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 5000);

    must(/for \(let i = 0; i < 3; i\+\+\)/.test(тело), 'станков не три: ткацкая без станков — это склад');
    // Рама: две стойки по бокам.
    must(/for \(const sx of \[-1\.4, 1\.4\]\)/.test(тело), 'у станка нет рамы');
    // Нити основы: тонкая светлая плоскость между стойками.
    must(/box\(3, 2\.2, 0\.05, M\.hay/.test(тело), 'на станке нет нитей основы');
    // Вал: цилиндр поперёк рамы.
    must(/cyl\(0\.14, 3\.2, 0\.14, M\.woodDark/.test(тело), 'у станка нет вала');
  });

  it('кладовая и рулоны ткани на месте', () => {
    const начало = клиент.indexOf('function furnishWeaver(');
    const конец = клиент.indexOf('export const BUILDINGS', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 5000);

    // Мешки кладовой: четыре штуки у порога.
    must(/for \(const \[mx, mz\] of \[\[7\.2/.test(тело), 'у кладовой нет мешков');
    must(/box\(1\.2, 1\.1, 1\.0, M\.hay/.test(тело), 'мешки не того размера: это не мешки');
    // Рулоны ткани на полке: цилиндры, повёрнутые на бок.
    must(/roll\.rotation\.x = Math\.PI \/ 2;/.test(тело), 'рулоны не лежат вдоль полки, а стоят столбом');
    must(/for \(let r = 0; r < 3; r\+\+\)/.test(тело), 'на полке не три рулона в ряд');
  });

  it('кузница деревни действительно есть — безымянная, но есть', () => {
    // Прямое следствие замера: по словам её найти нельзя. Здесь проверяется
    // геометрия workshop — наковальня, верстак и стойка инструментов.
    const начало = клиент.indexOf('function furnishWorkshop(');
    must(начало > 0, 'обстановка кузницы не найдена');
    const конец = клиент.indexOf('function furnishTavern(', начало);
    const тело = клиент.slice(начало, конец > 0 ? конец : начало + 3000);
    // Наковальня: низкое основание и верхняя плита.
    must(/box\(1\.6, 0\.7, 1\.6, M\.iron/.test(тело), 'в кузнице нет наковальни');
    // Верстак: столешница на четырёх ножках.
    must(/box\(4\.4, 0\.3, 1\.6, M\.wood/.test(тело), 'в кузнице нет верстака');
    // Стойка инструментов: болты, часть золотом — глазу видно, что висят.
    must(/for \(let i = 0; i < 4; i\+\+\)/.test(тело), 'в кузнице нет стойки инструментов');
    // И при этом ни одного слова «кузница»: ровно то, что сбило поиск.
    must(
      !/кузниц|forge/i.test(тело),
      'в обстановке кузницы появилось слово «кузница»: проверка на безымянность больше не значит того, что значила'
    );
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.weaver === 'string' && словарь.buildings.weaver.length > 0,
        `в ${код}.json нет названия buildings.weaver`
      );
    }
  });
});