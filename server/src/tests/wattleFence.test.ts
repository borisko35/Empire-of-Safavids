// Плетень и калитка в огороде.
//
// ЧТО БЫЛО (22 октября 2026, §312). Виноградник стоял открытым, а двор был
// обнесён двумя столбиками с одной жердью — это не забор, а заготовка.
//
// ЧТО ТЕПЕРЬ. Плетень из кольев с горизонтальными прутьями в два ряда, а в
// боковой плетни — прорезанная калитка: створка из жердей на петлях,
// приоткрытая.
//
// ЧТО ПРОВЕРЯЕТСЯ. Плетень есть (колья и прутья), в боковой плетни есть
// проход, калитка собрана из жердей и стоек и приоткрыта.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Плетень и калитка', () => {
  it('плетень: колья и прутья в два ряда', () => {
    должен(
      /const колье = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.045, 0\.06, 1\.35, 5\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'плетень без кольев',
    );
    // Прутья: два ряда.
    должен(/for \(const yy of \[0\.45, 0\.95\]\) \{/.test(ТЕРРЕЙН), 'прутьев плетня не два ряда');
    // Колья идут с наклоном — плетень живой, а не частокол.
    должен(/колье\.rotation\.z = \(i % 2 \? 1 : -1\) \* 0\.05;/.test(ТЕРРЕЙН),
      'колья плетня стоят по линейке');
  });

  it('в плетни прорезан проход под калитку', () => {
    должен(/if \(Math\.abs\(t\) < 0\.22\) continue; \/\/ проход для калитки/.test(ТЕРРЕЙН),
      'в плетни нет прохода под калитку');
  });

  it('калитка: жерди, стойки, приоткрыта', () => {
    // Створка собрана из жердей и стоек.
    должен(
      /const жердь = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.07, 0\.09, 1\.1\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у калитки нет жердей',
    );
    должен(
      /const стойка = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.05, 0\.05, 1\.2, 5\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у калитки нет стоек',
    );
    // И стоит приоткрытой.
    должен(/створка\.rotation\.y = сторона \* 0\.6;/.test(ТЕРРЕЙН), 'калитка не приоткрыта');
  });
});
