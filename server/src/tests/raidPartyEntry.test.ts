// Рейд перестал быть мёртвым кодом.
//
// ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. `PartySystem.createRaid` и `RaidGroup` лежали в
// коде, не имея ни одного вызова и ни одного читателя. Рейда в игре не
// существовало, хотя объявление «4 партии по 5 человек = 20 игроков» стояло
// прямо над функцией. Проверка требует не слова «raid», а ЗАХОДА: маршрута,
// который вызывает createRaid, чтения состава, и входа партией.
//
// ВТОРАЯ ПОЛОВИНА ПРОВЕРКИ. Ключи raid_open / join_raid / joined_raid
// подписывали обычные заходы в данж. Текст по-русски говорил «заход» и не
// врал игроку — врали ИМЕНА ключей, и ловушка была для того, кто их читает.
// Переименование в run_* проверяется отдельно: вернуть имя raid_open к
// заходам — значит снова заложить ту же ловушку.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const партии = код('server/src/systems/PartySystem.ts');
const маршруты = код('server/src/routes/game.ts');
const сервис = код('server/src/systems/DungeonService.ts');
const редис = код('server/src/services/RedisService.ts');
const апи = код('client/src/app/api.ts');
const панель = код('client/src/app/panels.ts');

/** Тело метода по имени — до следующего метода или конца класса. */
function тело(источник: string, имя: string): string {
  const начало = источник.indexOf(`${имя}(`);
  must(начало >= 0, `метода ${имя} нет`);
  const хвост = источник.slice(начало);
  const следующий = хвост.slice(1).search(/\n  (?:async |private |public |static )/);
  return следующий >= 0 ? хвост.slice(0, следующий + 1) : хвост.slice(0, 4000);
}

describe('Рейд: createRaid перестал быть мёртвым', () => {
  it('у createRaid появился вызывающий', () => {
    must(
      /partySystem\.createRaid\(/.test(маршруты),
      'createRaid никто не вызывает — рейд снова мёртвый код',
    );
  });

  it('состав рейда кто-то читает', () => {
    // RaidGroup без читателей — это структура ради самой себя.
    must(/raid\.parties\.length/.test(партии), 'состав партий не читается нигде');
    must(/raid\.parties\.push/.test(партии), 'в рейд нельзя добавить партию');
  });

  it('рейд привязан к заходу, а не существует сам по себе', () => {
    must(/sessionId:/.test(партии), 'у рейда нет sessionId — он ни к чему не привязан');
    must(/dungeonId:/.test(партии), 'у рейда нет dungeonId');
    must(
      /this\.dungeons\.getSession\(raid\.sessionId\)/.test(партии),
      'рейд не знает, жив ли его заход: список покажет закрытые сборы',
    );
  });

  it('не-рейд нельзя сделать рейдом', () => {
    // Иначе в рейд загнали бы гробницу на пять мест и показали «сбор 1/4».
    const телоСоздания = тело(партии, 'async createRaid');
    must(
      /if \(!def\?\.isRaid\) return \{ ok: false/.test(телоСоздания),
      'подземелье без isRaid принимается за рейд',
    );
  });

  it('число партий берётся из подземелья, а не написано', () => {
    const телоСоздания = тело(партии, 'async createRaid');
    must(
      /Math\.ceil\(def\.maxPlayers/.test(телоСоздания),
      'maxParties зашит числом: рейд на 8 человек обещал бы четыре партии',
    );
  });

  it('заход создаётся ДО записи в Redis', () => {
    // Наоборот — рейд остался бы в списке без захода: «сбор 1/4» и отказ
    // при нажатии, которого нет ни в одном слове интерфейса.
    const телоСоздания = тело(партии, 'async createRaid');
    must(
      телоСоздания.indexOf('this.dungeons.enter(') <
        телоСоздания.indexOf('await this.saveRaid(raid)'),
      'рейд пишется в Redis раньше, чем создаётся заход',
    );
  });
});

describe('Рейд: вход партией, а не поодиночке', () => {
  it('входит вся партия, а не только нажавший', () => {
    const телоВхода = тело(партии, 'async joinRaid');
    must(
      /members\.length > 0|for \(const id of members\)/.test(телоВхода) &&
        /this\.dungeons\.join\(id, raid\.sessionId\)/.test(телоВхода),
      'в рейд входит только тот, кто нажал кнопку, — это обычный заход',
    );
  });

  it('без партии в рейд не пускают', () => {
    must(/raid_no_party/.test(партии), 'в рейд можно войти без партии');
  });

  it('партия проверяется ЦЕЛИКОМ до входа первого', () => {
    // Половина партии внутри — хуже, чем её отсутствие: двое в рейде, двое
    // снаружи, и никто не понимает почему.
    const телоВхода = тело(партии, 'async joinRaid');
    const предвход = телоВхода.indexOf('for (const id of members)');
    const вход = телоВхода.indexOf('this.dungeons.join(id, raid.sessionId)');
    must(предвход > 0 && вход > предвход, 'проверки нет: партия входит по одному');
    must(
      /canJoinRun/.test(телоВхода.slice(предвход, вход)),
      'предварительной проверки нет — вход начнётся раньше, чем станет ясно, что кто-то не пройдёт',
    );
  });

  it('сорвавшийся вход откатывает уже вошедших', () => {
    const телоВхода = тело(партии, 'async joinRaid');
    must(
      /for \(const уже of вошедшие\)[\s\S]{0,120}this\.dungeons\.leave\(уже\)/.test(телоВхода),
      'если вход сорвался на третьем из пяти, двое остаются внутри рейда навсегда',
    );
  });

  it('уже вошедшая партия не входит повторно', () => {
    // Повторный вход списывал бы вторую попытку за нажатие той же кнопки.
    must(/raid_party_already_in/.test(партии), 'повторный вход партией не отвергается');
  });

  it('лидер не может открыть второй рейд', () => {
    // Партия лидера переиспользуется, значит второй рейд получил бы ту же
    // партию: человек оказался бы в двух рейдах с одним заходом.
    const телоСоздания = тело(партии, 'async createRaid');
    must(
      /raid_already_in_raid/.test(телоСоздания),
      'лидер, состоящий в рейде, открывает второй рейд той же партией',
    );
  });
});

describe('Рейд: список и его чистка', () => {
  it('не-рейд в списке пуст', () => {
    must(
      /async listOpenRaids\(dungeonId: string\)[\s\S]{0,160}if \(!def\?\.isRaid\) return \[\];/.test(партии),
      'список рейдов есть и у обычных подземелий',
    );
  });

  it('закрытые сборы и из ответа, и из индекса уходят', () => {
    // Не только из ответа: индекс в Redis иначе копил бы мёртвые записи
    // до конца TTL, и каждый список рейдов платил бы за них запросами.
    const телоСписка = тело(партии, 'async listOpenRaids');
    must(
      /completedAt[\s\S]{0,200}мёртвые\.push\(id\)/.test(телоСписка),
      'закрытый сбор попадает в список: кнопка «войти» ведёт в закрытый заход',
    );
    must(/this\.redis\.srem\(/.test(телоСписка), 'мёртвые сборы не убираются из индекса');
  });

  it('список отдаёт и партии, и людей', () => {
    const телоСписка = тело(партии, 'async listOpenRaids');
    must(
      /parties: raid\.parties\.length/.test(телоСписка) &&
        /members: сессия\.members\.size/.test(телоСписка),
      'в списке нет числа партий или числа людей — панели нечего показать',
    );
  });

  it('индекс рейдов — множество, а не список', () => {
    must(/this\.redis\.sadd\(this\.raidIndexKey/.test(партии), 'рейд не попадает в индекс');
    must(/this\.redis\.smembers\(this\.raidIndexKey/.test(партии), 'индекс не читается');
    // Методы множеств обязаны существовать в RedisService, иначе код не соберётся.
    for (const метод of ['async sadd(', 'async srem(', 'async smembers(']) {
      must(редис.includes(метод), `в RedisService нет метода ${метод}`);
    }
  });
});

describe('Рейд: маршруты и панель', () => {
  it('три маршрута есть и все защищены', () => {
    // Метод у каждого маршрута свой, и выводить его из пути («есть join —
    // значит post») нельзя: /raids/:dungeonId/create тоже post, а слово
    // join в нём отсутствует. Проверка однажды искала get там, где post,
    // и объявила бы маршрута нет.
    const маршрутыРейдов: { метод: 'get' | 'post'; путь: string; пишет: boolean }[] = [
      { метод: 'get', путь: '/raids/:dungeonId', пишет: false },
      { метод: 'post', путь: '/raids/:dungeonId/create', пишет: true },
      { метод: 'post', путь: '/raids/:raidId/join', пишет: true },
    ];
    for (const { метод, путь, пишет } of маршрутыРейдов) {
      const начало = маршруты.indexOf(`gameRouter.${метод}('${путь}'`);
      must(начало >= 0, `маршрута ${метод.toUpperCase()} ${путь} нет`);
      const блок = маршруты.slice(начало, начало + 320);
      must(/secureMiddleware/.test(блок), `маршрут ${путь} без secureMiddleware — рейд открыт всем подряд`);
      // Создание и вход меняют состояние: им нужна проверка владения персонажем.
      if (пишет) {
        must(
          /requireCharacterOwnership\(\)/.test(блок),
          `маршрут ${путь} не проверяет владение персонажем: можно войти в чужой сбор`,
        );
      }
    }
  });

  it('вход в рейд партией, а не кнопкой захода', () => {
    must(
      /raidJoin:\s*\(raidId: string/.test(апи) && /\/api\/game\/raids\/\$\{raidId\}\/join/.test(апи),
      'в клиенте нет вызова входа в рейд',
    );
    must(
      /raidCreate:\s*\(dungeonId: string/.test(апи) && /raids\/\(\) =>|raids: \(dungeonId: string\)/.test(апи),
      'в клиенте нет вызова открытия сбора или списка сборов',
    );
  });

  it('панель рисует блок рейда только для рейда', () => {
    must(/d\.isRaid/.test(панель), 'панель не спрашивает, рейд ли это подземелье');
    must(/api\.raids\(d\.id\)/.test(панель), 'панель не берёт список сборов');
    must(/api\.raidJoin\(/.test(панель), 'панель не даёт войти в сбор');
  });
});

describe('Рейд: имя «рейд» больше не у обычных заходов', () => {
  it('у заходов ключи с прочим именем', () => {
    must(
      /t\('panels\.run_open'\)/.test(панель) && /t\('panels\.join_run'\)/.test(панель),
      'панель заходов снова подписана ключами рейда',
    );
    for (const кодЯзыка of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${кодЯзыка}.json`)) as {
        panels: Record<string, string>;
      };
      must(
        словарь.panels.run_open && словарь.panels.join_run && словарь.panels.joined_run,
        `в ${кодЯзыка}.json нет переименованных ключей захода`,
      );
      for (const ложный of ['raid_open', 'join_raid', 'joined_raid']) {
        must(
          !словарь.panels[ложный],
          `${кодЯзыка}.json: panels.${ложный} снова подписывает обычный заход — ` +
            'это ловушка для того, кто ключ прочитает',
        );
      }
      // Настоящие ключи рейда обязаны быть, иначе панель покажет пустое имя.
      for (const настоящий of ['raid_section', 'raid_create', 'raid_join', 'raid_parties', 'raid_members']) {
        must(словарь.panels[настоящий], `в ${кодЯзыка}.json нет panels.${настоящий}`);
      }
    }
  });

  it('переименование не оставило старых имён в коде', () => {
    for (const имя of ['raid_open', 'join_raid', 'joined_raid']) {
      must(!панель.includes(имя), `панель всё ещё ссылается на ${имя}`);
      must(!апи.includes(имя), `api всё ещё ссылается на ${имя}`);
    }
  });

  it('заход и рейд — разные списки, а не один', () => {
    // Раньше рейд был бы ещё одной строкой в списке заходов, и разницы
    // между «войти одному» и «войти партией» не было бы в интерфейсе.
    must(
      /api\.dungeonSessions\(d\.id\)/.test(панель) && /api\.raids\(d\.id\)/.test(панель),
      'панель больше не различает заход и рейд',
    );
  });
});

