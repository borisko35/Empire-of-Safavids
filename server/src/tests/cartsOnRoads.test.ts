// Телеги на дорогах.
//
// ЧТО БЫЛО (22 октября 2026, §295). По дорогам ездили только люди и верблюды
// караванов: телег не было вовсе, и груз в мире возили как-то незаметно.
//
// ЧТО ТЕПЕРЬ. Телега: дощатый кузов с бортами, колёса с ободом, шестью спицами
// и ступицей, оглобель, козлы и купец на них; лошадь с капсульным телом,
// шеей, гривой и хвостом. Колёса крутятся по дороге.
//
// ЧТО ПРОВЕРЯЕТСЯ. Телега собрана из кузова, бортов, колёс со спицами, оглобля
// и купца; лошадь есть и у неё четыре ноги с копытами; колёса крутятся при
// движении; телеги реально поставлены на дороги.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТРАФИК = читать('client/src/app/game3d/roadTraffic.ts');

describe('Телеги на дорогах', () => {
  it('тележный кузов, борта, оглобель и купец', () => {
    должен(/function makeCart\(/.test(ТРАФИК), 'нет сборщика телеги');
    // Кузов — настил, борта по бокам.
    должен(
      /const кузов = new THREE\.Mesh\(new THREE\.BoxGeometry\(1\.25, 0\.12, 2\.1\)/.test(ТРАФИК),
      'у телеги нет кузова',
    );
    должен(
      /const борт = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.08, 0\.55, 2\.1\)/.test(ТРАФИК),
      'у телеги нет бортов',
    );
    // Оглобель — от передка к лошади.
    должен(
      /const оглобель = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.07, 0\.07, 1\.5\)/.test(ТРАФИК),
      'у телеги нет оглобля',
    );
    // Купец на козлах.
    должен(/const купец = new THREE\.Group\(\);/.test(ТРАФИК), 'на телеге нет купца');
    должен(/купец\.position\.set\(0, 1\.0, -0\.25\);/.test(ТРАФИК), 'купец не сидит на козлах');
    должен(/козлы\.position\.set\(0, 0\.98, -0\.25\);/.test(ТРАФИК), 'у телеги нет козлов');
  });

  it('колёса с ободом, спицами и ступицей', () => {
    // Обод — тор, спицы — бруски.
    должен(
      /const обод = new THREE\.Mesh\(new THREE\.TorusGeometry\(r, 0\.055, 5, 16\)/.test(ТРАФИК),
      'у колеса нет обода',
    );
    должен(
      /const спица = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.05, r \* 1\.8, 0\.05\)/.test(ТРАФИК),
      'у колеса нет спиц',
    );
    // Шесть спиц.
    должен(/for \(let i = 0; i < 6; i\+\+\) \{/.test(ТРАФИК), 'спиц не шесть');
    // Ступица.
    должен(
      /const ступица = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.1, 0\.1, 0\.16, 8\)/.test(ТРАФИК),
      'у колеса нет ступицы',
    );
    // Четыре колеса: два задних крупнее.
    должен(
      /колесо\(-0\.72, -0\.72, 0\.52\);/.test(ТРАФИК) && /колесо\(0\.72, 0\.72, 0\.4\);/.test(ТРАФИК),
      'колёс телеги не четыре или не разного размера',
    );
  });

  it('лошадь в оглобле: четыре ноги с копытами', () => {
    // Тело капсулой, шея и голова — тоже.
    должен(
      /const телоЛ = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.3, 1\.05, 4, 12\)/.test(ТРАФИК),
      'тело лошади — не капсула',
    );
    // Грива и хвост — с настоящей формой.
    должен(
      /const грива = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.1, 0\.34, 0\.6\)/.test(ТРАФИК),
      'у лошади нет гривы',
    );
    должен(
      /const хвост = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.04, 0\.11, 0\.6, 6\)/.test(ТРАФИК),
      'у лошади нет хвоста',
    );
    // Копыто.
    должен(
      /const копыто = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.065, 0\.075, 0\.09, 6\), M\.dark\);/.test(ТРАФИК),
      'у лошади нет копыт',
    );
    // Лошадь стоит перед телегой, в оглобле.
    должен(/лошадь\.position\.set\(0, 0, 2\.3\);/.test(ТРАФИК), 'лошадь не в оглобле');
  });

  it('колёса крутятся, телеги стоят на дорогах', () => {
    // Поле с колёсами у путника.
    должен(/колёса\?: THREE\.Object3D\[\];/.test(ТРАФИК), 'у путника нет колёс');
    // Вращение по пройденному пути.
    должен(
      /for \(const к of w\.колёса\) к\.rotation\.x \+= оборот \* w\.dir;/.test(ТРАФИК),
      'колёса телеги не крутятся',
    );
    // И телеги реально поставлены на дороги.
    должен(/const телега = makeCart\(/.test(ТРАФИК), 'телеги не ставятся на дороги');
    должен(/travellers\.push\(телега\);/.test(ТРАФИК), 'телеги не едут по дорогам');
  });
});
