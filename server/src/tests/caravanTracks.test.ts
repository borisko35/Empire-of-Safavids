// Следы караванов на дороге.
//
// ЧТО БЫЛО (21 октября 2026, §270). Караваны ходят по дороге каждый день, а на
// полотне — только колея от повозок. Следов копыт не было, и дорога читалась
// как пустая лента, по которой никто не ходил.
//
// ЧТО ТЕПЕРЬ. Между колёями идёт цепочка следов копыт. На сухом песке следы
// едва видны, на мокром проступают: мокрый песок держит отпечаток, сухой
// рассыпается.
//
// ЧТО ПРОВЕРЯЕТСЯ. Следы идут вдоль дороги и появляются по мокроте; лента
// лежит на полотне плашмя, а не стоит стеной; и всё это вычищается с миром.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СЛЕДЫ = читать('client/src/app/game3d/caravanTracks.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Следы караванов', () => {
  it('следы идут вдоль дороги и проступают по мокроте', () => {
    должен(/export function createCaravanTracks/.test(СЛЕДЫ), 'нет следов караванов');
    // Следы на дороге: берём ближайшую.
    должен(/ROAD_PATHS\.map\(\(дорога\) => \(\{/.test(СЛЕДЫ), 'следы не ищут дорогу');
    // Мокрый песок держит отпечаток, сухой рассыпается.
    должен(
      /материал\.opacity = 0\.22 \+ Math\.max\(0, Math\.min\(1, мокрота\)\) \* 0\.42;/.test(СЛЕДЫ),
      'следы не зависят от мокроты песка',
    );
  });

  it('лента следов лежит на полотне плашмя', () => {
    должен(/лента\.rotation\.x = -Math\.PI \/ 2;/.test(СЛЕДЫ), 'следы стоят стеной, а не лежат на дороге');
    // Вдоль дороги: длина ленты — длина полотна, и она именно используется.
    должен(
      /const длина = Math\.hypot\([\s\S]{0,200}?ближняя\.дорога\.to\.x - ближняя\.дорога\.from\.x,[\s\S]{0,200}?\);/.test(
        СЛЕДЫ,
      ),
      'длина ленты следов не берётся от длины дороги',
    );
    должен(/лента\.scale\.set\(ШИРИНА, длина, 1\);/.test(СЛЕДЫ), 'длина дороги посчитана и не используется');
  });

  it('следы живут по мокроте и вычищаются с миром', () => {
    должен(
      /this\.следыКараванов\.update\(dt, now, me\.pos\.x, me\.pos\.z, this\.мокрота\);/.test(МИР),
      'следы не обновляются',
    );
    должен(/this\.следыКараванов\?\.dispose\(\);/.test(МИР), 'следы не вычищаются');
    должен(/this\.следыКараванов = createCaravanTracks\(this\.scene\);/.test(МИР), 'следы не создаются');
  });
});
