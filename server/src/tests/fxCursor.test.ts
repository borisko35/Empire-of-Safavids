// Цифры урона и эффекты боя: поломка чтения в затяжной драке.
//
// ЧТО БЫЛО. Читатель в world3d.ts запоминал, сколько записей он уже показал,
// ИНДЕКСОМ в массиве entities.World и сверял его с `floaters.length`. Массив
// при этом укорачивается С НАЧАЛА: по сроку жизни (`filter` в `World.update`)
// и сдвигом при переполнении лимита. Как только первая запись истекала,
// массив становился короче, а курсор оставался на месте — и
// `cursor < length` намертво становилось ложью. Сброс курсора был только на
// пустом массиве, а в разгар боя пустым он не бывает НИКОГДА: урон приходит
// каждые ~450 мс при жизни флоатера 1100 мс.
//
// Итог на деле: через пару секунд любого затяжного боя цифры урона переставали
// появляться совсем и не возвращались, пока бой не замолкал. Частицы удара и
// лечения ломались так же, только быстрее (живут 320 мс).
//
// ПОЧЕМУ НЕ ИНДЕКС. Порядковый номер не сдвигается при уборке, поэтому
// «последний показанный» остаётся верным и при круговой переработке массива.
import { World } from '../../../client/src/app/entities';

/**
 * Гоняет бой и считает, сколько записей показал бы каждый из двух курсоров:
 * старый (индекс в укорачивающемся массиве) и новый (порядковый номер).
 */
function гонка(длительностьБоя: number, интервалУрона: number): {
  создано: number;
  показаноИндексом: number;
  показаноПоНомеру: number;
} {
  const мир = new World();
  let создано = 0;
  let показаноИндексом = 0;
  let показаноПоНомеру = 0;
  let курсорИндекс = 0;
  let курсорНомер = 0;

  for (let t = 0; t < длительностьБоя; t += 100) {
    if (t % интервалУрона < 100) {
      мир.addFloater(1, 2, `-${t}`, '#fff');
      создано++;
    }
    // Старим записи на шаг и прогоняем НАСТОЯЩИЙ фильтр по сроку жизни
    // из World.update — то есть по-настоящему чистим массив с начала.
    for (const f of мир.floaters) f.born -= 100;
    мир.update(0.016);

    // ── Старый курсор: индекс ──
    while (курсорИндекс < мир.floaters.length) {
      курсорИндекс++;
      показаноИндексом++;
    }
    if (мир.floaters.length === 0) курсорИндекс = 0;

    // ── Новый курсор: порядковый номер ──
    for (const f of мир.floaters) {
      if (f.seq <= курсорНомер) continue;
      курсорНомер = f.seq;
      показаноПоНомеру++;
    }
  }
  return { создано, показаноИндексом, показаноПоНомеру };
}

describe('Чтение флоатеров и эффектов не залипает за длиной массива', () => {
  it('ломается: индексный курсор показывал только первые ~2 секунды боя', () => {
    // Ломка с откатом. Замерено на живом коде: за 6 с боя с уроном каждые
    // 450 мс создано 14 флоатеров, а старый курсор показал 3 — то есть ровно
    // то, что успело показаться до первого истечения, и дальше тишина.
    const р = гонка(6000, 450);
    expect({ создано: р.создано, показаноИндексом: р.показаноИндексом })
      .toEqual({ создано: 14, показаноИндексом: 3 });
  });

  it('по номеру показывается всё созданное — урон не пропадает', () => {
    // Главная проверка на поведение: 14 создано, 14 показано.
    const р = гонка(6000, 450);
    expect(р.показаноПоНомеру).toBe(р.создано);
  });

  it('то же для частых эффектов: было 60 создано и показано 10', () => {
    // Частота эффектов выше, чем у флоатеров (живут 320 мс против 1100),
    // поэтому индексный курсор там терял ещё больше — 10 из 60.
    const р = гонка(6000, 100);
    expect({ показаноИндексом: р.показаноИндексом, показаноПоНомеру: р.показаноПоНомеру })
      .toEqual({ показаноИндексом: 10, показаноПоНомеру: 60 });
  });

  it('номер не сдвигается при уборке массива', () => {
    const мир = new World();
    мир.addFloater(0, 0, '1', '#fff');
    мир.addFloater(0, 0, '2', '#fff');
    мир.addFloater(0, 0, '3', '#fff');
    const номера = мир.floaters.map(f => f.seq);
    // Уборка с начала не имеет права трогать номера оставшихся.
    мир.floaters.shift();
    мир.floaters.shift();
    expect(мир.floaters.map(f => f.seq)).toEqual([номера[2]]);
  });

  it('номера строго возрастают и не переиспользуются', () => {
    const мир = new World();
    for (let i = 0; i < 6; i++) мир.addFloater(0, 0, `${i}`, '#fff');
    const номера = мир.floaters.map(f => f.seq);
    expect(номера).toEqual([...номера].sort((a, b) => a - b));
    expect(new Set(номера).size).toBe(номера.length);
  });

  it('лимит в 60 записей тоже не ломает чтение', () => {
    // Переполнение сдвигает массив, и это второй источник сдвига индексов
    // помимо срока жизни. Сценарий без единого истечения.
    const мир = new World();
    const прочитано: number[] = [];
    let курсор = 0;
    for (let i = 0; i < 200; i++) {
      мир.addFloater(0, 0, `${i}`, '#fff');
      for (const f of мир.floaters) {
        if (f.seq <= курсор) continue;
        курсор = f.seq;
        прочитано.push(f.seq);
      }
    }
    expect(прочитано.length).toBe(200);
    expect(прочитано).toEqual([...прочитано].sort((a, b) => a - b));
  });

  it('флоатеры и эффекты считаются разными счётчиками', () => {
    // Ломка: при общем счётчике номер эффекта встал бы между номерами
    // флоатеров и второй флоатер получил бы не 2, а 3.
    const мир = new World();
    мир.addFloater(0, 0, 'a', '#fff');
    мир.addEffect('slash', 0, 0, 1, 1);
    мир.addFloater(0, 0, 'b', '#fff');
    const ф = мир.floaters.map(f => f.seq);
    expect(ф[1] - ф[0]).toBe(1);
    expect(мир.effects.length).toBe(1);
  });
});