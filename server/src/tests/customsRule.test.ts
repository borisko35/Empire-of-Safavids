// Таможенный досмотр: правило работает и стоит на живых караулах.
//
// ЧЕСТНОЕ ИМЯ. Это НЕ «поиск контрабанды», как просил владелец. Поиск
// контрабанды требует случайности: караул находит или не находит. Детерминированного
// генератора в проекте нет — ноль seededRandom, mulberry32, xorshift, ноль
// Math.random в shared/. А правило обязано считаться одинаково на клиенте и
// сервере: иначе клиент покажет «пропущено», пока сервер считает «задержан».
// Это тот же класс расхождения, из-за которого когда-то разошлись двери.
//
// ПОЧЕМУ НЕТ СЛУЧАЙНОСТИ. Досмотр здесь — проверка скрытности: присел — не
// досмотрели, стоишь — платишь. Решение читается из приседания, которое уже
// есть и уже считается одинаково. Новую инфраструктуру ради одного правила не
// заводим.
//
// ГЛАВНОЕ. Караул без поста — поле без потребителя. Поэтому проверяется и то,
// что посты настоящие: их координаты совпадают с уже существующими сторожевыми
// постами, а не выдуманы рядом с ними.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  CUSTOMS_POSTS,
  CUSTOMS_TOLL,
  CUSTOMS_REACH,
  GUARD_SIGHT,
  GUARD_POSTS,
  checkCustoms,
  customsPost,
  customsPostNear,
  customsToll,
} from '../../../shared/stealth';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Таможня: правило различает случаи', () => {
  it('постов четыре, и все четверо — настоящие сторожевые посты', () => {
    must(CUSTOMS_POSTS.length === 4, `постов таможни ${CUSTOMS_POSTS.length}, а должно быть 4`);
    for (const таможня of CUSTOMS_POSTS) {
      const пост = GUARD_POSTS.find((п) => п.id === таможня.id);
      must(
        пост !== undefined,
        `${таможня.id} взят в таможню, но его нет в GUARD_POSTS: караул, которого не существует`
      );
      must(
        пост!.x === таможня.x && пост!.z === таможня.z,
        `${таможня.id}: таможня стоит в (${таможня.x}, ${таможня.z}), а сторожевой пост — в (${пост!.x}, ${пост!.z}). ` +
          'Два разных места для одного караула: игрок заплатит не тому'
      );
    }
  });

  it('досмотр срабатывает там же, где караул видит игрока', () => {
    // Если разойдутся, получится ровно то расхождение, ради которого написан
    // этот файл: караул стоит рядом и видит, а пошлина не берётся.
    must(
      CUSTOMS_REACH === GUARD_SIGHT,
      `радиус досмотра ${CUSTOMS_REACH}, а радиус обнаружения ${GUARD_SIGHT}: ` +
        'границы разошлись, и игрок будет видеть пошлину там, где её нет'
    );
  });

  it('присевший проходит без пошлины', () => {
    const ворота = customsPost('npc_guard_gate')!;
    must(ворота !== null, 'поста npc_guard_gate нет: проверять не на чем');
    const стоящий = { x: ворота.x + 2, z: ворота.z };
    must(
      checkCustoms(ворота, стоящий, { crouch: true, gold: 0 }) === null,
      'присевший не прошёл досмотр без золота: правило требует оплаты и от скрытного'
    );
    must(
      customsToll({ crouch: true, gold: 0 }) === 0,
      'с присевшего берут пошлину: скрытность перестала отменять досмотр'
    );
  });

  it('стоящий с достаточным золотом проходит и платит', () => {
    const ворота = customsPost('npc_guard_gate')!;
    const стоящий = { x: ворота.x + 2, z: ворота.z };
    must(
      checkCustoms(ворота, стоящий, { crouch: false, gold: CUSTOMS_TOLL }) === null,
      `при ${CUSTOMS_TOLL} золота досмотр не пропускает: оплата не работает`
    );
    must(
      customsToll({ crouch: false, gold: CUSTOMS_TOLL }) === CUSTOMS_TOLL,
      'с стоящего берут не ту сумму'
    );
  });

  it('без золота — честный отказ с причиной', () => {
    const ворота = customsPost('npc_guard_gate')!;
    const стоящий = { x: ворота.x + 2, z: ворота.z };
    must(
      checkCustoms(ворота, стоящий, { crouch: false, gold: CUSTOMS_TOLL - 1 }) === 'no_gold',
      `при ${CUSTOMS_TOLL - 1} золота досмотр проходит: плата не работает`
    );
    // Граница: ровно столько, сколько надо.
    must(
      checkCustoms(ворота, стоящий, { crouch: false, gold: CUSTOMS_TOLL }) === null,
      'на ровно нужной сумме отказ: граница платы сдвинута'
    );
  });

  it('издалека не досматривают, даже стоя с полными карманами', () => {
    const ворота = customsPost('npc_guard_gate')!;
    const издалека = { x: ворота.x + CUSTOMS_REACH + 5, z: ворота.z };
    must(
      checkCustoms(ворота, издалека, { crouch: false, gold: 99999 }) === 'too_far',
      'издалека берут пошлину: радиус досмотра не проверяется'
    );
    // А на границе — досматривают.
    must(
      checkCustoms(
        { ...ворота, x: 0, z: 0 },
        { x: CUSTOMS_REACH, z: 0 },
        { crouch: false, gold: CUSTOMS_TOLL }
      ) === null,
      `на расстоянии ровно ${CUSTOMS_REACH} досмотр не срабатывает: граница отрезана`
    );
  });

  it('несуществующий пост не проходит', () => {
    must(customsPost('нет-такого') === null, 'несуществующий пост вернулся как настоящий');
  });
});

describe('Таможня: пошлина обоснована, а не выбрана на глаз', () => {
  it('пошлина меньше стартовых денег', () => {
    // Старт — 30 золота (миграция 015). Пошлина обязана быть меньше старта,
    // иначе новичок физически не может пройти границу, и механика становится
    // не платой, а стеной.
    must(
      CUSTOMS_TOLL < 30,
      `пошлина ${CUSTOMS_TOLL} при стартовых 30: новичок не сможет пройти границу никогда`
    );
    must(
      CUSTOMS_TOLL > 0,
      'пошлина нулевая: караул ничего не берёт, и досмотра нет по сути'
    );
  });

  it('порядок величины совпадает с уже принятыми правилами', () => {
    // Уже задано: кража 25, рычаг 50. Пошлина — тот же порядок, а не копейка
    // и не число из другого века.
    must(CUSTOMS_TOLL >= 10 && CUSTOMS_TOLL <= 60, `пошлина ${CUSTOMS_TOLL} выпала из порядка 25 и 50`);
  });

  it('нулевая пошлина у присевшего, полная у стоящего', () => {
    must(customsToll({ crouch: true, gold: 1000 }) === 0, 'у присевшего берут пошлину');
    must(customsToll({ crouch: false, gold: 0 }) === CUSTOMS_TOLL, 'у стоящего не берут пошлину');
  });
});

describe('Таможня: посты ищутся по-настоящему', () => {
  it('ближайший пост находится, а не выдумывается', () => {
    // У ворот должен находиться привратник.
    const найденный = customsPostNear(60, 32);
    must(найденный !== null, 'у ворот ни одного поста не найдено');
    must(найденный!.id === 'npc_guard_gate', `у ворот найден ${найденный!.id}, а должен быть привратник`);
  });

  it('далеко от всех постов не находится ничего', () => {
    // В кармане интерьеров заведомо никого нет.
    const найденный = customsPostNear(4528, 4006);
    must(найденный === null, `внутри комнаты найден пост ${найденный?.id}: досмотр сработает за краем мира`);
  });
});

describe('Таможня: правило связано с тем, что уже работает', () => {
  it('приседание в правиле — то же самое, чем пользуется стелс', () => {
    // Иначе получится две разные «приседшие»: одна отменяет досмотр, вторая —
    // обнаружение, и они разойдутся.
    const сервер = читать('server/src/socket/GameSocketHandler.ts');
    must(
      /crouch: где\.crouch/.test(сервер),
      'сервер не передаёт приседание в правила: приседший и крадущий считаются по-разному'
    );
    must(кражаИспользуетПрисед(), 'правило кражи не пользуется приседанием — это два разных приседания');
  });

  it('правило живёт в shared, а не в одной стороне', () => {
    // Клиент обязан знать о пошлине раньше, чем нажмёт на ворота.
    const клиент = читать('client/tsconfig.json');
    must(
      /stealth\.ts/.test(клиент),
      "клиент не включает shared/stealth.ts: он не увидит правило и предложит то, что сервер отвергнет"
    );
  });
});

function кражаИспользуетПрисед(): boolean {
  const правило = читать('shared/stealth.ts');
  return /canPickpocket[\s\S]{0,400}crouch/.test(правило);
}