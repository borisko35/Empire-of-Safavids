// Загон для скота у лесной деревни.
//
// ЧТО БЫЛО (22 октября 2026, §308). Коровы и овцы стояли по лесу открыто и
// разбрелись, а деревня без загона выглядела так, будто скота не держат:
// просто лишние животные в лесу.
//
// ЧТО ТЕПЕРЬ. Загон из жердей: столбы с просветником, ворота-створка на
// петлях, кормушка с сеном, поилка с водой, навес от дождя на четырёх столбах
// и стог сена.
//
// ЧТО ПРОВЕРЯЕТСЯ. Жерди загона есть (столбы и рейки), ворота есть, кормушка
// с сеном и поилка с водой есть, навес на четырёх столбах стоит.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Загон для скота', () => {
  it('жерди: столбы и рейки', () => {
    должен(
      /const столб = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.09, 0\.12, 1\.5, 6\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у загона нет столбов',
    );
    // Просветник: две продольные жерди на каждой стороне.
    должен(
      /const рейка = new THREE\.Mesh\(new THREE\.BoxGeometry\(полу \* 2, 0\.08, 0\.08\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у загона нет жердей',
    );
    должен(/for \(const высота of \[0\.55, 1\.05\]\) \{/.test(ТЕРРЕЙН), 'жердей не два ряда');
  });

  it('ворота-створка', () => {
    должен(/const створка = new THREE\.Group\(\);/.test(ТЕРРЕЙН), 'у загона нет ворот');
    // Створка собрана из жердей — пустая группа ничего не закрывает.
    должен(
      /const жердь = new THREE\.Mesh\(new THREE\.BoxGeometry\(2\.6, 0\.08, 0\.08\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'створка ворот пустая: жердей нет',
    );
    // Створка приоткрыта.
    должен(/створка\.rotation\.y = -0\.7;/.test(ТЕРРЕЙН), 'створка ворот не приоткрыта');
  });

  it('кормушка с сеном, поилка с водой, навес и стог', () => {
    // Кормушка и сено.
    должен(
      /const кормушка = new THREE\.Mesh\(new THREE\.BoxGeometry\(3\.4, 0\.5, 0\.9\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'у загона нет кормушки',
    );
    должен(
      /const сено = new THREE\.Mesh\(new THREE\.SphereGeometry\(1\.0, 8, 6\), MAT\.sand\);/.test(ТЕРРЕЙН),
      'в кормушке нет сена',
    );
    // Поилка с водой.
    должен(
      /const поилка = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.6, 0\.55, 0\.45, 10\), MAT\.wood\);/.test(ТЕРРЕЙН),
      'у загона нет поилки',
    );
    должен(
      /const вода = new THREE\.Mesh\(\s*new THREE\.CylinderGeometry\(0\.52, 0\.52, 0\.06, 10\),\s*new THREE\.MeshStandardMaterial\(\{ color: 0x3a6a72/.test(ТЕРРЕЙН),
      'в поилке нет воды',
    );
    // Навес на четырёх столбах.
    должен(
      /for \(const \[dx, dz\] of \[\[-1\.6, -1\.6\], \[1\.6, -1\.6\], \[-1\.6, 1\.6\], \[1\.6, 1\.6\]\] as const\) \{/.test(ТЕРРЕЙН),
      'у навеса не четыре столба',
    );
    // Стог сена.
    должен(
      /const стог = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.9, 1\.1, 1\.6, 9\), MAT\.sand\);/.test(ТЕРРЕЙН),
      'у загона нет стога сена',
    );
  });
});
