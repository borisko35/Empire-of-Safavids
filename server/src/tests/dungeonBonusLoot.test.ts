// Бонусная добыча подземелий: обещанное в данных выпадает.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ЭТОЙ ПРОВЕРКИ. Поле bonusItems было объявлено у всех
// пяти подземелий - тринадцать записей с шансами от 0.001 до 0.4, среди них
// Священный Меч Исмаила I с шансом одна тысяча, - и не читалось НИГДЕ: поиск по
// серверу давал только сами объявления. Гарантированные предметы выдавались,
// бонусные не выпадали никогда. Игрок проходил данж и не получал того, что
// написано в данных.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ:
//   1. объявленные бонусы существуют: id есть в базе предметов, шанс в (0, 1];
//   2. бросок уважает границу шанса: при шансе 1 предмет выпадает всегда, при
//      шансе 0.001 - на одной тысяче;
//   3. шанс читается как вероятность, а не как «иногда»: 0.4 выпадает при roll
//      0.39 и не выпадает при 0.4;
//   4. сервер действительно бросает и выдаёт выпавшее, а экран захода показывает
//      выданное, а не объявленное в данных;
//   5. размер захода в базе берётся из данных, а не из вписанной пятёрки.
//
// ПОЧЕМУ ПРОВЕРКА СЧИТАЕТ, А НЕ ИЩЕТ СТРОКУ. Поиск строки rollBonusItems
// доказал бы, что строка есть. Здесь бросок считается числами с переданным
// броском: вероятность нельзя проверить, если бросок внутри функции.
import { ITEMS_DATABASE } from '../data/items';
import { DUNGEONS_DATABASE, rollBonusItems } from '../data/dungeons';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Все объявленные бонусы одним списком: подземелье, предмет и шанс.
const объявления = Object.values(DUNGEONS_DATABASE).flatMap((данж) =>
  данж.rewards.bonusItems.map((б) => ({ подземелье: данж.nameRu, ...б })),
);

describe('Бонусная добыча: объявленное в данных существует', () => {
  it('бонусы объявлены хотя бы у двух подземелий', () => {
    // Ноль означал бы, что проверка не видит данных и довольна пустотой.
    must(
      объявления.length >= 10,
      `объявлено ${объявления.length} записей бонуса: либо данные вычеркнули, либо проверка читает не то`
    );
    const сБонусами = Object.values(DUNGEONS_DATABASE).filter(
      (д) => д.rewards.bonusItems.length > 0,
    ).length;
    must(
      сБонусами >= 2,
      `бонусы есть только у ${сБонусами} подземелий: проверка считает не тот случай`
    );
  });

  it('каждый бонусный предмет есть в базе предметов', () => {
    // CharacterService.addItems пишет в базу, не сверяясь с ITEMS_DATABASE.
    // Опечатка в id дала бы игроку невидимый предмет: в инвентаре строка есть,
    // а в игре его нет, и починить это можно только вручную.
    const мусор = объявления.filter((б) => !(б.itemId in ITEMS_DATABASE));
    must(
      мусор.length === 0,
      `в данных есть ${мусор.length} бонусов с несуществующим предметом: ` +
        мусор.map((м) => `${м.подземелье} -> ${м.itemId}`).join(', ')
    );
  });

  it('шанс каждого бонуса лежит в (0, 1]', () => {
    for (const б of объявления) {
      must(
        б.chance > 0 && б.chance <= 1,
        `${б.подземелье}: шанс ${б.chance} у ${б.itemId}. Ноль или единица означали бы, ` +
          'что предмет либо невозможен, либо гарантирован, и это другое обещание, чем в данных'
      );
    }
  });
});

describe('Бонусная добыча: бросок уважает шанс', () => {
  // Бросок передаётся функцией: у каждой записи он свой. Первая версия функции
  // сравнивала со шансом один бросок на весь список, и тогда попадание в верхние
  // проценты выдавало сразу все предметы разом. Первая проверка на это упала
  // и заставила поменять сигнатуру - поэтому здесь бросок задан стрелкой.
  const бросок = (значение: number) => () => значение;

  it('шанс 1 - выпадает всегда', () => {
    for (const значение of [0, 0.5, 0.999999]) {
      const выпало = rollBonusItems([{ itemId: 'a', chance: 1 }], бросок(значение));
      must(выпало.length === 1, `при шансе 1 и броске ${значение} выпало ${выпало.length}: шанс не стопроцентный`);
    }
  });

  it('шанс 0.4 выпадает ниже границы и не выше неё', () => {
    const запись = { itemId: 'b', chance: 0.4 };
    must(
      rollBonusItems([запись], бросок(0.39)).includes('b'),
      'при шансе 0.4 и броске 0.39 предмет не выпал: граница включена не с той стороны'
    );
    must(
      !rollBonusItems([запись], бросок(0.4)).includes('b'),
      'при шансе 0.4 и броске ровно 0.4 предмет выпал: вероятность 0.4 стала 0.41'
    );
  });

  it('у каждой записи свой бросок, а не один на весь список', () => {
    // Редкий предмет (шанс 0.01) и частый (шанс 0.8). Первой записи достаётся
    // удачный бросок 0.005, второй - неудачный 0.9. При общем броске вторая
    // запись видела бы 0.005 и тоже выпала: вот это и ловит проверка.
    const список = [
      { itemId: 'редкий', chance: 0.01 },
      { itemId: 'частый', chance: 0.8 },
    ];
    let индекс = 0;
    const поОчереди = [0.005, 0.9];
    const результат = rollBonusItems(список, () => поОчереди[индекс++]);
    must(
      результат.join(',') === 'редкий',
      `при бросках ${поОчереди} выпало [${результат}], а должен выпасть только редкий: ` +
        'записи делят один бросок вместо своего'
    );
    // Обратный порядок: неудача для редкого, удача для частого.
    индекс = 0;
    const обратный = [0.9, 0.005];
    const результат2 = rollBonusItems(список, () => обратный[индекс++]);
    must(
      результат2.join(',') === 'частый',
      `при бросках ${обратный} выпало [${результат2}]: порядок записей влияет на исход`
    );
    // Ни один бросок не подходит ни одной записи.
    must(
      rollBonusItems(список, () => 0.9).length === 0,
      'при броске 0.9 выпало что-то, хотя оба шанса меньше 0.9'
    );
  });

  it('каждый объявленный бонус достижим', () => {
    // При своём шансе предмет обязан выпадать примерно с той частотой, которая
    // написана. Иначе в данных шанс, который не срабатывает как написан, - то
    // есть снова мёртвое обещание, только уже внутри строки.
    const шагов = 20000;
    for (const б of объявления) {
      const список = [{ itemId: б.itemId, chance: б.chance }];
      let попал = 0;
      for (let i = 0; i < шагов; i++) {
        if (rollBonusItems(список, бросок(i / шагов)).length > 0) попал++;
      }
      const доля = попал / шагов;
      must(
        доля > 0 && доля <= б.chance + 1 / шагов,
        `${б.подземелье}: шанс ${б.chance} у ${б.itemId} срабатывает в ${(доля * 100).toFixed(3)}% ` +
          'бросков: шанс в данных не соответствует тому, что считает бросок'
      );
      if (б.chance >= 0.02) {
        must(
          Math.abs(доля - б.chance) <= 0.02,
          `${б.подземелье}: шанс ${б.chance} измеряется как ${(доля * 100).toFixed(2)}%: бросок врёт`
        );
      }
    }
  });

  it('пустой список и нулевой шанс не выдают ничего', () => {
    must(rollBonusItems([], бросок(0)).length === 0, 'пустой список бонусов что-то выдал');
    must(
      rollBonusItems([{ itemId: 'x', chance: 0 }], бросок(0)).length === 0,
      'шанс 0 выдал предмет: данные с нулевым шансом всё же работают'
    );
  });

  it('на настоящих данных катакомб срабатывает всё, что заявлено', () => {
    const катакомбы = DUNGEONS_DATABASE['dungeon_tabriz_catacombs'];
    must(катакомбы, 'в базе нет катакомб, а проверка считала их бонусы');
    const заявлено = катакомбы.rewards.bonusItems.length;
    must(
      заявлено >= 2,
      `в катакомбах ${заявлено} бонусов: проверка считает не тот случай`
    );
    // Нулевой бросок выигрывает любой положительный шанс, поэтому на нём
    // выпадает ровно всё объявленное - и ни одной лишней записи.
    const выпало = rollBonusItems(катакомбы.rewards.bonusItems, бросок(0));
    must(
      выпало.length === заявлено,
      `на нулевом броске выпало ${выпало.length} из ${заявлено}: как минимум один шанс не срабатывает`
    );
    must(
      выпало.join(',') === катакомбы.rewards.bonusItems.map((б) => б.itemId).join(','),
      `на нулевом броске выпало [${выпало}], а объявлено ` +
        `[${катакомбы.rewards.bonusItems.map((б) => б.itemId)}]`
    );
  });
});

describe('Бонусная добыча: сервер её выдаёт', () => {
  const сервис = читать('server/src/systems/DungeonService.ts');

  it('бросок сделан при завершении захода', () => {
    must(
      /rollBonusItems\(def\.rewards\.bonusItems, Math\.random\)/.test(сервис),
      'сервер не бросает бонусную добычу: поле в данных осталось мёртвым'
    );
    // Функция броска, а не число: один бросок на весь список выдавал бы все
    // бонусы разом или ни одного.
    must(
      !/rollBonusItems\([^)]*Math\.random\(\)/.test(сервис),
      'сервер передаёт в бросок одно число: все бонусы делят один бросок'
    );
  });

  it('выпавшее идёт в раздачу, а не в никуда', () => {
    must(
      /const добыча = \[\.\.\.def\.rewards\.guaranteedItems, \.\.\.бонус\]/.test(сервис),
      'выпавшие бонусы не добавлены к раздаче: предмет засчитывается в отчёт и теряется'
    );
    must(
      /items: добыча\.filter/.test(сервис),
      'раздача по-прежнему идёт по одним гарантированным предметам'
    );
  });

  it('экран захода показывает выданное, а не объявленное', () => {
    must(
      /items: добыча,/.test(сервис),
      'в отчёте о заходе объявленные предметы: игрок увидит вещь, которой не получил'
    );
    must(
      !/items: def\.rewards\.guaranteedItems,/.test(сервис),
      'отчёт захода по-прежнему показывает только гарантированные предметы'
    );
  });

  it('размер захода в базе берётся из данных подземелья', () => {
    // Раньше в INSERT стояли вписанные 5: у гробницы maxPlayers 20, и в базу
    // писалось 5. Любое чтение этой колонки показывало неверный размер.
    must(
      /const размер = def\?\.maxPlayers \?\? 5;/.test(сервис),
      'размер захода в базе не берётся из данных подземелья'
    );
    must(
      !/VALUES \(\$1, \$2, 'normal', \$3, 5,/.test(сервис),
      'в записи сессии остались вписанные сложность и размер захода'
    );
    must(
      /dungeon_sessions[\s\S]{0,200}max_size/.test(сервис),
      'колонка размера захода вообще не пишется'
    );
  });

  it('сложность в базе не врёт: первая из объявленных в данных', () => {
    // Выбор сложности игроком в игре не сделан (hard/heroic/mythic объявлены и
    // не используются), поэтому пишем первую из данных, а не выдуманную.
    must(
      /const сложность = def\?\.difficulties\[0\] \?\? 'normal';/.test(сервис),
      'сложность сессии не берётся из данных подземелья'
    );
    const withHard = Object.values(DUNGEONS_DATABASE).filter((д) => д.difficulties.length > 1);
    must(
      withHard.length >= 2,
      'почти все подземелья объявляют несколько сложностей: проверка считает не тот случай'
    );
  });
});
