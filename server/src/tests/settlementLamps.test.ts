// Свет в поселениях: порт, лесная деревня, горный форт.
//
// ЧТО БЫЛО (21 октября 2026, §251). У порта горел маяк и стоял маячок-фонарь,
// в деревне была поленница и стог, у форта — ворота с айваном, и НИ У ОДНОГО
// из этих мест не было источника света: горели только нарисованные шары.
// Ночью порт, деревня и форт стояли чёрными силуэтами.
//
// ЧТО ТЕПЕРЬ. Свой огонь у маяка и маячка, фонарь у поленницы и два фонаря у
// ворот форта. Источники создаёт world3d: свет и ночное правило — его дело
// (как у городов регионов, §250).
//
// ЧТО ПРОВЕРЯЕТСЯ. Огни есть в каждом из трёх поселений, форт построен общим
// фонарём, координаты огней — мировые, и для каждого создаётся источник света
// по ночному правилу.
//
// Проверка смотрит ТОЛЬКО свои разделы кода: строки фонарей в городе совпадают
// слово в слово, и без границы проверка цепляла бы чужой блок (см. §247).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

/** Кусок кода своего раздела: метки разделов — комментарии, ищем по исходнику. */
function свойРаздел(код: string, начало: string, конец: string): string {
  const от = код.indexOf(начало);
  должен(от >= 0, `в коде нет раздела «${начало}»`);
  const до = код.indexOf(конец, от);
  должен(до > от, `в коде нет раздела «${конец}» после «${начало}»`);
  return код.slice(от, до).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

const МАЯЧОК = свойРаздел(ТЕРРЕЙН, '// Свет от маячка (§251)', '// Маяк на конце пирса');
const МАЯК = свойРаздел(ТЕРРЕЙН, '// Свет от маяка (§251)', 'for (const [wx, wz, ww] of');
const ДЕРЕВНЯ = свойРаздел(ТЕРРЕЙН, '// Фонарь у поленницы (§251)', '// стог сена');
const ФОРТ = свойРаздел(ТЕРРЕЙН, '// Два фонаря по краям ворот (§251)', '// Коллайдер в воротах УБРАН');
const ИСТОЧНИКИ = свойРаздел(МИР, '// Свет в поселениях (§251)', '// Города регионов: поселения в шести регионах');

/** Тело функции по скобкам: от открывающей скобки тела до закрывающей. */
function телоФункции(код: string, шапка: RegExp): string {
  const m = шапка.exec(код);
  должен(m, 'не найдена функция');
  const строкаШапки = код.indexOf('\n', m!.index);
  const телоНачало = код.lastIndexOf('{', строкаШапки);
  let глубина = 0;
  for (let i = телоНачало; i < код.length; i++) {
    if (код[i] === '{') глубина++;
    else if (код[i] === '}') {
      глубина--;
      if (глубина === 0) return код.slice(телоНачало + 1, i);
    }
  }
  throw new Error('функция не закрылась');
}

describe('Свет в поселениях', () => {
  it('у маячка, маяка и фонаря деревни есть свои огни', () => {
    должен(/огни\.push\(\{ x: PORT\.x - 10, y: g\.position\.y \+ 5\.6, z: PORT\.z - 4 \}\)/.test(МАЯЧОК),
      'у маячка нет огня');
    должен(/огни\.push\(\{ x: PORT\.x - 2\.2, y: g\.position\.y \+ 9\.6, z: PORT\.z - 12\.5 \}\)/.test(МАЯК),
      'у маяка нет огня');
    должен(/огни\.push\(\{ x: VILLAGE\.x - 5, y: g\.position\.y \+ 2\.8, z: VILLAGE\.z \+ 5 \}\)/.test(ДЕРЕВНЯ),
      'у фонаря деревни нет огня');
  });

  it('фонари у ворот форта — общие, со стеклом и огнём', () => {
    должен(/for \(const fx of \[-4\.2, 4\.2\]\)/.test(ФОРТ), 'у ворот форта не два фонаря');
    должен(/const высотаОгня = фонарь\(g, fx, 9\.5\);/.test(ФОРТ),
      'фонари форта построены своими столбами без стекла');
    должен(/огни\.push\(\{ x: FORT\.x \+ fx, y: g\.position\.y \+ высотаОгня, z: FORT\.z \+ 9\.5 \}\)/.test(ФОРТ),
      'у фонарей форта нет огней');
  });

  it('поселения отдают огни, источники создаются по ночному правилу', () => {
    должен(
      /export function buildSettlements\(scene: THREE\.Scene\): \{ x: number; y: number; z: number \}\[\]/.test(ТЕРРЕЙН),
      'buildSettlements не возвращает огни: источники создать не из чего',
    );
    должен(
      /for \(const \[i, огонь\] of огниПоселений\.entries\(\)\)/.test(ИСТОЧНИКИ),
      'источники света поселений не создаются по списку огней террейна',
    );
    должен(
      /const light = new THREE\.PointLight\(0xffa04a, 0, 20, 1\.8\);/.test(ИСТОЧНИКИ),
      'источники света поселений не создаются',
    );
    должен(/this\.scene\.add\(light\);/.test(ИСТОЧНИКИ), 'источники света поселений не в сцене');
    // Факелы: днём тише, ночью в полную силу.
    должен(
      /this\.torches\.push\(\{ light, base: 1\.6, phase: i \* 2\.4 \+ 1\.3 \}\)/.test(ИСТОЧНИКИ),
      'огни поселений не горят по ночному правилу',
    );
  });

  it('возврат огней — в самом конце функции, а не внутри постройки', () => {
    // ТУТ БЫЛА ОШИБКА (21 октября 2026, §251). `return огни;` стоял внутри
    // блока кавказского форпоста, и всё, что ниже по функции — Багдадская
    // цитадель и храм Симург — не строилось вовсе: рейд был недоступен, а
    // тесты были зелёные. Тесты проверяли наличие возврата, а не его место.
    const тело = телоФункции(
      ТЕРРЕЙН,
      /export function buildSettlements\([^)]*\)[^{]*\{/,
    ).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
    const возврат = тело.lastIndexOf('return огни;');
    должен(возврат > 0, 'в buildSettlements нет возврата огней');
    const последняяПостройка = Math.max(
      тело.lastIndexOf('scene.add('),
      тело.lastIndexOf('addCollider('),
    );
    должен(
      возврат > последняяПостройка,
      'возврат огней стоит раньше последней постройки: часть поселений не строится',
    );
  });
});
