// Погода влияет на игру, а не только на небо.
//
// ЧТО БЫЛО. WEATHER_EFFECTS объявлял пять модификаторов на каждую погоду
// (visibilityMod, speedMod, expMod, spawnMod, specialMobs) - и НИ ОДИН не
// читался. Поиск по всему репозиторию находил только объявление и один
// комментарий, ссылающийся на него. То есть погода меняла вид неба в
// клиенте и скорость респавна у точек с weatherBonus, а объявленные
// «в дождь опыта больше на 10%» и «монстры в эту погоду» были пустыми
// строками в справочнике.
//
// ЧТО НА САМОМ ДЕЛЕ. Утверждение выше врало про четыре поля из пяти, и
// разобраться пришлось после шага 2 стелса, когда visibilityMod получил
// потребителя и правда о соседях вылезла наружу:
//
//   spawnMod      - читает SpawnSystem.ts (respawnTime / spawnMod)
//   specialMobs   - читает SpawnSystem.ts (effect.specialMobs.includes)
//   expMod        - читает weatherExpMultiplier(), а через неё
//                   CharacterService начисляет опыт
//   visibilityMod - читает правило скрытности (shared/stealth.ts): обзор
//                   стража сокращается в дождь, бурю, туман и особенно в
//                   песчаную бурю - с 20 единиц до 6. Ровно то, что просил
//                   владелец: «пыльная буря ухудшает обзор, но скрывает
//                   игрока в стелсе».
//   speedMod      - читает клиент (§349): множитель суши едет в пакете
//                   world:time, world3d умножает на него шаг и бег. В
//                   песчаную бурю персонаж идёт на 0.6, в бурю - 0.7.
//                   Дольше всех поле оставалось мёртвым: до §349 не читал
//                   никто, погода тормозила спавн и стражей, но не игрока.
//
// ПОЧЕМУ ШАПКА ВРАЛА. Искали по имени поля рядом с WEATHER_EFFECTS и
// находили объявление, а не потребителя: читали его другие файлы - точечной
// ссылкой effect.spawnMod или через помощника weatherExpMultiplier.
// Список потребителей теперь проверяется по живому коду в
// weatherStealthConsumer.test.ts, чтобы он снова не разъехался.
//
// Проверки deliberately построены на разборе исходников, а не на
// импорте: иначе они просто пересказывали бы то же объявление, которое
// и оказалось мёртвым.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { WEATHER_EFFECTS, currentWeather, weatherExpMultiplier, worldTimeAt, GAME_EPOCH_MS } from '../systems/WorldTimeSystem';
import type { Weather } from '../systems/WorldTimeSystem';

const корень = join(__dirname, '..', '..', '..');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

function исходник(путь: string): string {
  return readFileSync(join(корень, путь), 'utf-8');
}

const ПОГОДЫ = Object.keys(WEATHER_EFFECTS) as Weather[];

describe('Погода: объявленные модификаторы применяются', () => {
  it('множитель опыта берётся из погоды и меняется вместе с ней', () => {
    // expMod объявлялся, но не читался: в дождь опыт шёл по базовой
    // ставке. Теперь он считается по расписанию погоды.
    //
    // ВАЖНО, ПОЧЕМУ ИДЁМ ПО ВРЕМЕНИ, А НЕ ПО СПИСКУ ПОГОД. Функция
    // берёт момент времени и сама решает, какая погода тогда была.
    // Первая версия проверки вызывала её без аргумента в цикле по
    // ПОГОДЫ - и получала одно и то же значение «сейчас» N раз, то
    // есть сравнивала число с самим собой. Проверка выглядела
    // содержательной и не проверяла ничего; поймал её TypeScript
    // (неиспользуемый параметр), а не логика.
    const шаг = 4 * 60 * 1000;
    const увиденные = new Set<number>();
    for (let i = 0; i < 400; i++) {
      const t = GAME_EPOCH_MS + i * шаг;
      const множитель = weatherExpMultiplier(t);
      must(
        typeof множитель === 'number' && Number.isFinite(множитель) && множитель > 0,
        `на слоте ${i} множитель опыта = ${String(множитель)} - ожидалось положительное число`,
      );
      увиденные.add(множитель);
    }
    must(
      увиденные.size > 1,
      `множитель опыта одинаков на всём цикле (${[...увиденные].join(', ')}) - объявленный expMod ни на что не влияет`,
    );
  });

  it('множитель опыта следует WEATHER_EFFECTS, а не своей копии числа', () => {
    // Проверка против самого справочника: если в начислении опыта появится
    // своя константа, расходящаяся с expMod, тест это увидит. Сверяем по
    // всей шкале времени - каждому слоту соответствует expMod именно
    // своей погоды.
    const шаг = 4 * 60 * 1000;
    for (let i = 0; i < 400; i++) {
      const t = GAME_EPOCH_MS + i * шаг;
      const погода = currentWeather(t);
      const ожидаем = WEATHER_EFFECTS[погода].expMod;
      must(
        weatherExpMultiplier(t) === ожидаем,
        `на ${new Date(t).toISOString()} погода ${погода}: ждали опыт x${ожидаем}, получили x${weatherExpMultiplier(t)}`,
      );
    }
  });

  it('начисление опыта умножает на weatherExpMultiplier, а не на константу', () => {
    // Третья ломка этой правки сначала НЕ была поймана: в addExperience
    // подставили `const weather = 1;` вместо вызова, и все проверки остались
    // зелёными. Функция weatherExpMultiplier при этом продолжала
    // существовать и честно возвращать верное число - просто начисление
    // перестало её звать.
    //
    // Вывод, который стоит запомнить: проверка «функция возвращает верное
    // значение» не проверяет, что её зовут. Проверять надо место, где
    // значение применяется.
    const сервис = исходник('server/src/services/CharacterService.ts');
    must(
      /const weather = weatherExpMultiplier\(\)/.test(сервис),
      'в начислении опыта нет вызова weatherExpMultiplier: объявленный бонус опыта за погоду не применяется',
    );
    must(
      /amount \* mult \* seasonal \* profExp \* guildExp \* weather/.test(сервис),
      'множитель погоды не входит в итоговую формулу опыта: он посчитан и отброшен',
    );
  });

  it('список погодных монстров читается системой спавна', () => {
    // specialMobs — самый явный мёртвый список: четыре монстра были
    // объявлены «уникальными в эту погоду», и поле не читалось нигде.
    const спавн = исходник('server/src/systems/SpawnSystem.ts');
    must(
      /specialMobs\s*\.\s*includes\s*\(/.test(спавн),
      'SpawnSystem не читает specialMobs: погодные монстры снова объявлены и никем не используются',
    );
    must(
      /spawnMod/.test(спавн),
      'SpawnSystem не читает spawnMod: количество монстров в погоду снова объявлено и не применяется',
    );
  });

  it('каждый погодный монстр существует в базе монстров', () => {
    // Список мог указывать на несуществующего монстра, и тогда проверка
    // «список читается» прошла бы вхолостую: сравнение includes ничего не
    // найдёт, и погода будет влиять на пустоту.
    const база = исходник('server/src/data/monsters.ts');
    const объявлены = new Set(
      [...база.matchAll(/'(mob_[a-z_]+|boss_[a-z_]+|world_boss_[a-z_]+)':\s*\{/g)].map((м) => м[1]),
    );
    for (const погода of ПОГОДЫ) {
      for (const id of WEATHER_EFFECTS[погода].specialMobs) {
        must(объявлены.has(id), `погода ${погода} ссылается на монстра ${id}, которого нет в monsters.ts`);
      }
    }
  });

  it('спавн-пересчёт делит на spawnMod, а не умножает', () => {
    // Направление деления легко перепутать, и ошибка не видна: при
    // spawnMod больше единицы «умножение» просто замедлит спавн в буре
    // вместо ускорения, и никто этого не заметит.
    const спавн = исходник('server/src/systems/SpawnSystem.ts');
    must(
      /respawnTime\s*=\s*respawnTime\s*\/\s*effect\.spawnMod/.test(спавн),
      'ожидалась формула respawnTime = respawnTime / effect.spawnMod - погода замедляет спавн вместо ускорения',
    );
    must(
      !/respawnTime\s*=\s*respawnTime\s*\*\s*effect\.spawnMod/.test(спавн),
      'spawnMod умножается на respawnTime: в буре монстры будут появляться реже, а не чаще',
    );
  });

  it('множитель скорости едет клиенту в world:time, а не считается у него самого', () => {
    // speedMod — последнее ожившее поле (§349). Провод — то же поле
    // WorldTime, что уходит в Redis и в сокет, поэтому проверяется
    // справочник против worldTimeAt по всей шкале времени.
    const шаг = 4 * 60 * 1000;
    for (let i = 0; i < 400; i++) {
      const t = GAME_EPOCH_MS + i * шаг;
      const время = worldTimeAt(t);
      must(
        время.speedMod === WEATHER_EFFECTS[время.weather].speedMod,
        `на ${new Date(t).toISOString()} погода ${время.weather}: ждали скорость x${WEATHER_EFFECTS[время.weather].speedMod}, получили x${время.speedMod}`,
      );
    }
    // Ручная погода админа обязана менять и множитель: кнопка «снег» в
    // админке, при которой игрок едет как по снегу, а не по его расписанию.
    must(
      worldTimeAt(GAME_EPOCH_MS, 'sandstorm').speedMod === WEATHER_EFFECTS.sandstorm.speedMod,
      'override погоды не меняет speedMod: в админской песчаной буре игрок идёт как в ясную',
    );
    must(worldTimeAt(GAME_EPOCH_MS, 'clear').speedMod === 1.0, 'в ясную погоду множитель скорости не 1.0');
  });

  it('клиент замедляет сушу и не трогает рывок и воду', () => {
    // Умножение должно стоять именно на шаге и беге. На всей скорости
    // целиком оно замедлило бы и рывок — чья математика посчитана и
    // проверена отдельно (dodgeFeel.test.ts), — и плавание, у которого
    // своя физика брода и снаряжения.
    const мир = исходник('client/src/app/game3d/world3d.ts');
    must(
      /landWalk\s*=\s*\(this\.mountSpeed > 0 \? this\.mountSpeed : WALK_SPEED\)\s*\*\s*this\.speedMod/.test(мир),
      'world3d не умножает шаг на speedMod: погода не замедляет игрока',
    );
    must(
      /landRun\s*=\s*\(this\.mountSpeed > 0 \? this\.mountSpeed \* MOUNT_SPRINT_MULT : RUN_SPEED\)\s*\*\s*this\.speedMod/.test(мир),
      'world3d не умножает бег на speedMod: в бурю можно бежать как в ясную',
    );
    // И провод: множитель приходит из пакета world:time, а не выдуман на
    // клиенте. Своя копия справочника на клиенте — та же мина, что и
    // везде: справочник поменяют на сервере и забудут про копию.
    const провод = исходник('client/src/app/world.ts');
    must(
      /payload\.speedMod/.test(провод) && /setSpeedMod\(/.test(провод),
      'world.ts не передаёт speedMod из world:time в движок',
    );
  });
});

describe('Погода: справочник не притворяется большим', () => {
  it('все погоды расписания имеют модификаторы и особые монстры существуют', () => {
    for (const погода of ПОГОДЫ) {
      const э = WEATHER_EFFECTS[погода];
      must(э !== undefined, `погода ${погода} объявлена в типе, но её нет в справочнике`);
      must(Array.isArray(э.specialMobs), `у погоды ${погода} specialMobs не массив`);
      for (const поле of ['visibilityMod', 'speedMod', 'expMod', 'spawnMod'] as const) {
        must(
          typeof э[поле] === 'number' && э[поле] > 0,
          `у погоды ${погода} поле ${поле} = ${String(э[поле])} - ожидалось положительное число`,
        );
      }
    }
  });

  it('распределение погод не вырождено', () => {
    // Если расписание сошлось к одной погоде, то и expMod, и спавн стали
    // бы константой, а проверки выше проходили бы вхолостую.
    const счётчик = new Map<Weather, number>();
    const шаг = 4 * 60 * 1000;
    for (let i = 0; i < 2000; i++) {
      const п = currentWeather(GAME_EPOCH_MS + i * шаг);
      счётчик.set(п, (счётчик.get(п) ?? 0) + 1);
    }
    must(счётчик.size >= 5, `в расписании только ${счётчик.size} погод из ${ПОГОДЫ.length}: погода почти не меняется`);
    const пусто = ПОГОДЫ.filter((п) => !счётчик.has(п));
    must(пусто.length === 0, `эти погоды не выпадают НИ РАЗУ за цикл: ${пусто.join(', ')}`);
  });
});