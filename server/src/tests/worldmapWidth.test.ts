// Мировая карта: правило ширины наконец работает, карта не мылится.
//
// ЧТО БЫЛО. В стиле карты стояло `width: 92vw; max-width: 940px`. Правило «92
// процента ширины окна» срабатывало только на экранах уже 1022 пикселей
// (940 / 0.92): на любом обычном мониторе карта упиралась в 940 и выглядела так,
// будто правила не было. Это и было видно на скриншоте.
//
// ЧТО ЕЩЁ БЫЛО. Холст нарисован в 900x600 и растянут стилем на всю рамку. Если
// рамку расширить, 900 пикселей растянутся на пол-экрана и карта станет мыльной —
// то есть увеличение ширины без увеличения разрешения просто портит картинку.
//
// ЧТО ПРОВЕРЯЕТСЯ. Считается, сколько именно ширины даёт правило на обычном
// мониторе и на 4K, и что холст следует за шириной на экране, а остаётся 900
// на 600. Оба числа берутся из кода, а не вписываются здесь.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const СТИЛИ = читать('client/src/app/styles.css');
const ХУД = читать('client/src/app/hud.ts');

/**
 * Стили без комментариев.
 *
 * Нужно потому, что в комментарии к правилу карты написано, каким оно было
 * раньше, — и поиск по тексту находит старое правило, которого в коде уже нет.
 * Проверять надо живые правила, а не пересказ истории в комментарии.
 */
const ПРАВИЛА = СТИЛИ.replace(/\/\*[\s\S]*?\*\//g, '');

/** Ширина рамки карты по правилу из стилей, в пикселях окна. */
function ширинаРамки(окно: number): number {
  const правило = /width: min\(92vw, (\d+)px\)/.exec(ПРАВИЛА);
  must(правило, 'в стилях нет правила min(92vw, …): правило ширины карты потеряно');
  return Math.min((окно * 92) / 100, Number(правило![1]));
}

describe('Ширина мировой карты', () => {
  it('правило работает на обычном мониторе', () => {
    // 1920 — самый частый рабочий монитор. Раньше здесь выходило 940, то есть
    // ровно половина окна вместо обещанных 92 процентов.
    const ширина = ширинаРамки(1920);
    must(
      ширина > 1700,
      `на окне 1920 карта занимает ${Math.round(ширина)} пикселей: ` +
        'правило 92 процента снова упирается в потолок, и карта мельче задуманного'
    );
  });

  it('на 4K карта не занимает пол-экрана', () => {
    // Потолок нужен: без него на 4K карта растянулась бы на 3456 пикселей, а
    // вокруг неё ничего.
    const окно = 3840;
    const ширина = ширинаРамки(окно);
    must(
      ширина < окно * 0.6,
      `на окне ${окно} карта занимает ${Math.round(ширина)} пикселей, то есть больше ` +
        'половины окна: потолок не работает'
    );
    must(ширина > 1500, `потолок срезал карту до ${Math.round(ширина)} пикселей: это меньше, чем на обычном мониторе`);
  });

  it('старого потолка в 940 у карты больше нет', () => {
    // Поиск идёт по блоку самой карты, а не по всему файлу: потолок 940 у другой
    // панели — законное дело, и проверка не должна обвинять его.
    const блокКарты = /\.worldmap \{[^}]*\}/.exec(ПРАВИЛА);
    must(блокКарты, 'в стилях нет блока .worldmap');
    must(
      !/max-width: 940px/.test(блокКарты![0]),
      'потолок 940 вернулся: правило 92 процента снова не работает на обычном мониторе'
    );
  });
});

describe('Разрешение холста карты', () => {
  it('холст приводится к ширине на экране', () => {
    must(
      /canvas\.getBoundingClientRect\(\)\.width/.test(ХУД),
      'холст не сверяется с шириной на экране: карта растягивается мыльно'
    );
    must(
      /canvas\.width = ширина;/.test(ХУД) && /canvas\.height = высота;/.test(ХУД),
      'размер холста не выставляется по экрану'
    );
    must(
      /window\.devicePixelRatio/.test(ХУД),
      'плотность пикселей не учитывается: на Retina карта останется мыльной'
    );
  });

  it('пропорция холста зафиксирована, а не гуляет сама', () => {
    // Размер меняется в рантайме. Если бы пропорция считалась из текущего размера,
    // каждое открытие карты чуть меняло бы её, и холст полз бы под содержимым.
    must(
      /const ПРОПОРЦИЯ_ХОЛСТА = 600 \/ 900;/.test(ХУД),
      'пропорция холста не зафиксирована: карта будет плыть сама под своим содержимым'
    );
  });

  it('при смене размера статичный слой перестраивается', () => {
    // Менять размер холста нельзя «втихую»: холст очищается, а статичный слой
    // террейна привязан к прежней ширине и остался бы старого размера.
    must(
      /worldmapLayer = null;/.test(ХУД),
      'слой террейна не сбрасывается при смене размера холста: карта останется старой'
    );
  });

  it('размер холста из разметки остаётся исходным', () => {
    // Проверки вскрытия карты считают раскладку по 900 на 600 из разметки. Эти
    // числа — исходная точка, а не то, что окажется на экране.
    const разметка = читать('client/src/app/index.html');
    must(
      /<canvas id="worldmap-canvas" width="900" height="600">/.test(разметка),
      'исходный размер холста в разметке изменился: проверки раскладки карты считают не то'
    );
  });
});