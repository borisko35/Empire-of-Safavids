// Лес, которого не было.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ПРАВКИ. Максимум forestMask на всём мире равнялся
// 0.078 при пороге биома 0.4. Лес не был слабым - его не было. Ни одной
// точки, которую biomeAt назвала бы лесом; ни зелёного пятна на земле
// (цвет красится той же маской, 0.078 - это неразличимо); ни одной ветки
// лесной фауны; деревья в лесу росли с плотностью поля, 0.12 вместо 0.9.
//
// ПОЧЕМУ МАСКА БЫЛА МЁРТВОЙ. Диск радиусом 360 вокруг (-460,-330) лежит в
// z от -690 до 30. Отсечка clamp01((z+120)/200) равна нулю при z <= -120 и
// растёт только после. Окна не пересекались: произведение
// (30-z)(z+120)/72000 на максимуме при z = -45 даёт 5625/72000 = 0.0781.
// Порог 0.4 недостижим был ни при каких x и z.
//
// ПОЧЕМУ ПРОВЕРКА ВЫЧИСЛЯЕТ МАСКУ, А НЕ ИЩЕТ ЕЁ ТЕКСТ. Поиск строки
// «hypot(x + 620, z + 430)» доказал бы, что строка есть, и ничего больше:
// маску можно было бы испортить числом в другом месте, и проверка осталась
// бы зелёной. Здесь функции вырезаются из исходника и выполняются, а
// утверждения — про числа. Радиус, порог и максимум проверяются числами.
//
// ПОЧЕМУ ТЕСТ ЖИВЫХ ЧИСЕЛ, А НЕ «ФУНКЦИЯ ВАЛИДНА». Мёртвая маска -
// это не ошибка компиляции. Код собрался, всё типизировалось, лес просто
// не наступал. Такие поломки ловятся только вычислением.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import * as ts from 'typescript';
import { waterMask } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРАЙН = читать('client/src/app/game3d/terrain.ts');
const ФАУНА = читать('client/src/app/game3d/fauna.ts');

/** Вырезать тело функции из исходника и выполнить его вместе с зависимостями.
 *
 *  Кусок исходника - TypeScript, с типами параметров, а Function() понимает
 *  только JavaScript и падает на первом же `: number`. Поэтому кусок сперва
 *  пропускается через тот же компилятор, которым собирается проект. Первая
 *  версия проверки не transpile-ила и падала «Unexpected token ':'» - то
 *  есть проверка не работала ни разу, вместо того чтобы проверять.
 */
function вычислить(имена: string[]): Record<string, (x: number, z: number) => number> {
  const куски: string[] = [];
  for (const имя of имена) {
    const начало = ТЕРРАЙН.search(new RegExp(`(^|\\n)(export )?function ${имя}\\s*\\(`));
    must(начало >= 0, `не нашёл функцию ${имя} в terrain.ts - проверка мерит не тот код`);
    const конец = ТЕРРАЙН.indexOf('\n}', начало);
    must(конец > начало, `функция ${имя} не закрылась - вид исходника изменился`);
    // Ключевое слово export убирается: Function() про него не знает.
    куски.push(ТЕРРАЙН.slice(начало, конец + 2).replace('export ', ''));
  }
  const js = ts.transpileModule(куски.join('\n'), {
    compilerOptions: { target: ts.ScriptTarget.ES2020, removeComments: false },
  }).outputText;
  must(js.length > 0, 'компилятор вернул пустой код - проверка не сможет ничего посчитать');
  const модуль = new Function(`${js}; return { ${имена.join(', ')} };`);
  return модуль() as Record<string, (x: number, z: number) => number>;
}

const маски = вычислить(['fract', 'hash2', 'smoothstep', 'clamp01', 'vnoise', 'fbm', 'forestMask']);
const forestMask = маски.forestMask;

const WORLD_HALF = 3175;
const СТОЛИЦА = { x: 34, z: 26, radius: 116 };
const ДЕРЕВНЯ = { x: -495, z: -415 };

/** Обход мира с шагом 40: 159x159 точек, ровные квадраты, доля = доля площади. */
function обойти(шаг: number) {
  let всего = 0, выше = 0, макс = -1;
  let максX = 0, максZ = 0;
  for (let x = -WORLD_HALF; x <= WORLD_HALF; x += шаг) {
    for (let z = -WORLD_HALF; z <= WORLD_HALF; z += шаг) {
      всего++;
      const m = forestMask(x, z);
      if (m > 0.4) выше++;
      if (m > макс) { макс = m; максX = x; максZ = z; }
    }
  }
  return { всего, выше, макс, максX, максZ };
}

describe('Лес на карте есть', () => {
  const обход = обойти(40);

  it('маска леса достигает единицы, а не 0.078', () => {
    // Исходное состояние, измеренное до правки: максимум 0.078 при пороге
    // биома 0.4. Маска, которая никогда не доходит до порога, - это не лес,
    // это поле, у которого есть функция. Требуем единицу с запасом.
    must(обход.макс > 0.9,
      `маска леса поднялась только до ${обход.макс.toFixed(3)} в точке (${обход.максX}, ${обход.максZ}) - ` +
      'лес снова мёртвый, порог биома 0.4 недостижим');
  });

  it('лес занимает заметную долю мира, а не пятнышко', () => {
    // Ноль был бы нормой для маски, но не для проверки: проверка обязана
    // сверяться на ненулевом значении, иначе она проходит на любом мусоре.
    const доля = (обход.выше / обход.всего) * 100;
    must(обход.выше > 0,
      'ни одной точки мира с маской выше порога - леса нет вовсе, проверка прошла бы вхолостую');
    must(доля > 0.5,
      `лес занимает ${доля.toFixed(2)}% мира - меньше, чем нужно, чтобы зелень читалась и чтобы набиралась лесная фауна`);
  });

  it('лесная деревня стоит в лесу, а не рядом с ним', () => {
    // VILLAGE так и называется в коде. Если лес уедет от деревни, деревня
    // останется в поле, а игрок, пришедший к лесной двери, её не найдёт.
    const m = forestMask(ДЕРЕВНЯ.x, ДЕРЕВНЯ.z);
    must(m > 0.4,
      `лесная деревня (${ДЕРЕВНЯ.x}, ${ДЕРЕВНЯ.z}) оказалась вне леса: маска ${m.toFixed(3)}`);
  });

  it('лес не наползает на столицу', () => {
    // Старый центр леса стоял в 608 единицах от столицы, и круг радиусом
    // 700 дотягивался бы до неё: земля вокруг Исфахана пошла бы зеленеть,
    // а игрок - видеть лес там, где города.
    const m = forestMask(СТОЛИЦА.x, СТОЛИЦА.z);
    must(m === 0,
      `столица (${СТОЛИЦА.x}, ${СТОЛИЦА.z}) попала в лес: маска ${m.toFixed(3)} - город в чаще`);
    // И не только в самой столице: вокруг города маска обязана быть нулевой
    // на радиусе города плюс запас, иначе зелень подступает к воротам.
    let зелёное = 0;
    for (let x = СТОЛИЦА.x - 200; x <= СТОЛИЦА.x + 200; x += 20) {
      for (let z = СТОЛИЦА.z - 200; z <= СТОЛИЦА.z + 200; z += 20) {
        if (forestMask(x, z) > 0.4) зелёное++;
      }
    }
    must(зелёное === 0, `в 200 единицах от столицы нашлось ${зелёное} лесных точек`);
  });

  it('лесной фауны хватает: шестеро набираются из 900 проб', () => {
    // Фауна набирает зверей пробами по всему миру и сдаётся после 900 попыток
    // (fauna.ts, want.forest = 6). Пока лес был мёртвым, эта цель была
    // недостижима в принципе. Теперь надо доказать, что она достижима и
    // именно тем способом, каким пользуется игра.
    const rng = (() => { let s = 777; return () => (s = (s * 16807) % 2147483647) / 2147483647; })();
    let найдено = 0;
    for (let i = 0; i < 900 && найдено < 6; i++) {
      const x = (rng() * 2 - 1) * WORLD_HALF;
      const z = (rng() * 2 - 1) * WORLD_HALF;
      if (Math.hypot(x - СТОЛИЦА.x, z - СТОЛИЦА.z) < СТОЛИЦА.radius + 12) continue;
      if (forestMask(x, z) > 0.4 && waterMask(x, z) <= 0.45) найдено++;
    }
    must(найдено >= 6,
      `за 900 проб лесных зверей набралось ${найдено} из нужных 6 - фауна леса останется полупустой, ` +
      'а оленей на экране не будет вовсе');
  });

  it('мёртвая отсечка (z+120)/200 не вернулась', () => {
    // Именно эта отсечка убивала лес: ноль при z <= -120 при диске,
    // сосредоточенном на z = -330. Возвращать её нельзя, даже «для вида»:
    // она снова убьёт лес, и проверки выше это поймают, но не сразу.
    const код = ТЕРРАЙН.replace(/\/\/[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
    must(!/\(z\s*\+\s*120\)\s*\/\s*200/.test(код),
      'вернулась отсечка (z+120)/200 - с ней лес снова не достигает порога биома');
  });

  it('лесная ветка фауны не пустая', () => {
    // Пока биом леса не наступал, ветка `biome === 'forest'` в fauna.ts была
    // мёртвой: ни одна точка мира туда не попадала. Проверяем, что ветка
    // есть и что в ней действительно заводят зверей, а не только строки.
    const ветка = /else if \(biome === 'forest'\) \{[\s\S]*?\n {2}\}/.exec(ФАУНА)?.[0] ?? '';
    must(ветка.length > 0, 'в fauna.ts нет ветки леса - звери леса не заводятся');
    must(/addWalker/.test(ветка),
      'ветка леса в fauna.ts пустая: ни одного зверя не ставится, лес без животных');
  });
});