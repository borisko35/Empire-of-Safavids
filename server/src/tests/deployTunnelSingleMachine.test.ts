// Туннель под боевым адресом должен быть ровно на одной машине.
//
// ЧТО ЗДЕСЬ. У выкатки есть две цели (`EOS_DEPLOY_TARGET`): `local` и `aws`.
// При цели `local` скрипт поднимает туннель на этой машине — это его работа.
// При цели `aws` тот же блок выполнялся ТОЖЕ, здесь, то есть домашняя машина
// вставала в тот же туннель Cloudflare, что и прод.
//
// Что из этого вышло на живом сайте, замерено:
//
//   • аккаунт, зарегистрированный через публичный адрес, через минуту отвечал
//     401 invalid_credentials: запрос попадал на домашнюю машину, где этого
//     пользователя нет;
//   • при входе в мир индикатор показывал ● Disconnected;
//   • домашняя база была пустой — два пользователя, новейшая запись 9 октября.
//
// Раскол возникал не сам по себе и не один раз: он воспроизводился при КАЖДОЙ
// выкатке с целью aws, потому что блок не смотрел на цель вовсе.
//
// ЧТО ПРОВЕРЯЕТСЯ. Тоннельный блок обязан быть разделён по цели: при `aws` —
// НЕ поднимать локальный туннель, а при `local` — поднимать. Блок без такой
// развилки вернёт раскол тихо, и вернётся он при ближайшей выкатке.
//
// ПОЧЕМУ ПРОВЕРКА ТЕКСТОВАЯ, А ПО-НАСТОЯЩЕМУ. `deploy.sh` написан на shell, и
// единственная честная проверка его структуры без запуска — такая. Запуск
// скрипта здесь невозможен: он пересобирает образы и едет на прод.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Кириллица в причинах иероглифами не печатается, но на условие это не влияет.
function должно(условие: unknown, причина: string): void {
  должен(условие, причина);
}

const СКРИПТ = readFileSync(join(корень, 'tools', 'deploy.sh'), 'utf-8');

describe('Туннель не висит на двух машинах сразу', () => {
  it('скрипт прочитался и не пустой', () => {
    должно(
      СКРИПТ.length > 2000,
      'tools/deploy.sh не прочитан или подозрительно мал: проверка ослепла',
    );
  });

  it('подъём туннеля разделён по цели выкатки', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Подъём туннеля идёт только при цели `local`.
    // Возврат к блоку без проверки цели означает, что при `aws` домашняя машина
    // снова зайдёт в боевой туннель — то есть раскол вернётся при каждой
    // выкатке, и вернётся молча.
    должно(
      /if \[ "\$TUNNEL" -eq 1 \] && \[ "\$TARGET" != "aws" \]; then/.test(СКРИПТ),
      'подъём туннеля снова не смотрит на цель выкатки: при aws домашняя машина ' +
        'снова встанет в боевой туннель и создаст раскол (§161)',
    );
  });

  it('локальный туннель при цели aws не остаётся работать', () => {
    // Не только «не поднимать», но и «убрать уже работающий»: иначе раскол,
    // однажды возникший, пережил бы все выкатки.
    должно(
      /if \[ "\$TUNNEL" -eq 1 \] && \[ "\$TARGET" = "aws" \]; then/.test(СКРИПТ),
      'нет ветки, которая убирает локальный туннель при цели aws',
    );
    должно(
      /\$C stop cloudflared/.test(СКРИПТ),
      'при цели aws локальный туннель не останавливается: два бэкенда продолжат ' +
        'делить боевой адрес',
    );
  });

  it('остановка безопасна: AWS проверен до этого места', () => {
    // Если бы скрипт доходил до остановки туннеля не проверив AWS, отключение
    // оставило бы сайт без обслуживания. Проверка связи стоит в шаге 1 и
    // останавливает выкатку на недоступном AWS ДО сборки.
    const проверкаAws = СКРИПТ.indexOf('SSH NE DOSTUPEN');
    const остановка = СКРИПТ.indexOf('$C stop cloudflared');
    должно(проверкаAws >= 0, 'в скрипте нет проверки связи с AWS — искать нечего');
    должно(остановка >= 0, 'в скрипте нет остановки локального туннеля');
    должно(
      проверкаAws < остановка,
      'туннель останавливается раньше, чем проверена связь с AWS: откат связи ' +
        'оставит сайт без обслуживания',
    );
  });

  it('остановка домашнего туннеля стоит до удалённой пересборки', () => {
    // 21 октября 2026: блок жил после шага 4 и выполнялся только при успешной
    // удалённой сборке, но сам раскол валит ШАГ 5 удалённой машины — выкатка
    // останавливалась до этой строки, блок не выполнялся, раскол каждый раз
    // разбирался руками. Глушить домашний туннель надо ДО пересборки.
    const остановка = СКРИПТ.indexOf('$C stop cloudflared');
    const удалённаяСборка = СКРИПТ.indexOf('EOS_DEPLOY_TARGET=local bash tools/deploy.sh');
    должно(остановка >= 0, 'в скрипте нет остановки локального туннеля');
    должно(удалённаяСборка >= 0, 'в скрипте нет запуска удалённой пересборки: сценарий сломался');
    должно(
      остановка < удалённаяСборка,
      'остановка домашнего туннеля стоит ПОСЛЕ запуска удалённой пересборки: ' +
        'раскол вберётся раньше, чем скрипт до него доберётся, и выкатка ' +
        'остановится на шаге 5, как 21.10.2026',
    );
  });

  it('причина записана рядом с местом правки', () => {
    // ASCII-маркеры, а не русские фраза: фраза разъезжается переносом строки,
    // и проверка начнёт искать текст не там. Тот же вывод, что в §153, §154,
    // §157 и §158.
    должно(
      /EOS_DEPLOY_TARGET=aws/.test(СКРИПТ),
      'не назван случай, который вызвал раскол: пояснение должно называть его прямо',
    );
    должно(
      /invalid_credentials/.test(СКРИПТ),
      'не назван наблюдаемый признак раскола: пояснение обязано показывать, ' +
        'что именно увидит читатель',
    );
  });
});