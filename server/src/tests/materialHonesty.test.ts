// Металличность должна стоять там, где металл, и нигде больше.
//
// ЧТО БЫЛО. У куполов стояло metalness: 0.2. Изразец — глазурованная
// керамика, то есть диэлектрик, а не металл. При metalness 0.2 двадцать
// процентов отражения окрашиваются собственным цветом и считаются
// металлическими; на сфере это даёт цветное пятно, и глаз читает его как
// СВЕЧЕНИЕ. На рассвете купола будто светятся изнутри — это выдавало их
// сильнее всего остального.
//
// Аналогично ошибся бы стекло: гладкий диэлектрик. Но стеклу здесь
// металличность поставлена сознательно (см. §135): в сцене нет карты
// окружения, и при metalness 0 стекло выходило бы чёрным.
//
// ЧТО ПРОВЕРЯЕТСЯ. Купол — диэлектрик; золото и железо — металлы; метка
// задания светится намеренно (у неё свой emissive, и это не путать).
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');
const НАВИГАТОР = читать('client/src/app/game3d/navigator.ts');

describe('Металличность честная', () => {
  it('изразцовый купол — диэлектрик, а не металл', () => {
    const м = /tealDome:\s*new THREE\.MeshStandardMaterial\(\{([^}]*)\}\)/.exec(МИР);
    должен(м, 'материал купола не читается');
    const тело = м![1];
    const мет = /metalness:\s*([\d.]+)/.exec(тело);
    должен(мет, 'у купола не задана металличность');
    должен(Number(мет![1]) === 0,
      `у купола metalness ${мет![1]}: изразец светится, как металл`);
    // Глазурь даёт блеск низкой шероховатостью, а не металличностью.
    const шер = /roughness:\s*([\d.]+)/.exec(тело);
    должен(шер && Number(шер[1]) <= 0.5, 'у купола слишком шероховатый глазурь не блестит');
  });

  it('золото и железо остаются металлами', () => {
    // Правка купола не должна была задеть металлы: они по природе металлы.
    for (const файл of [МИР, ИНТЕРЬЕРЫ]) {
      const м = /gold:\s*new THREE\.MeshStandardMaterial\(\{([^}]*)\}\)/.exec(файл);
      должен(м, 'золото не читается');
      const мет = /metalness:\s*([\d.]+)/.exec(м![1]);
      должен(мет && Number(мет[1]) >= 0.5, 'золото перестало быть металлом: оно стало пластилином');
    }
    const железо = /iron:\s*new THREE\.MeshStandardMaterial\(\{([^}]*)\}\)/.exec(ИНТЕРЬЕРЫ);
    должен(железо, 'железо не читается');
    const мет = /metalness:\s*([\d.]+)/.exec(железо![1]);
    должен(мет && Number(мет[1]) >= 0.5, 'железо перестало быть металлом');
  });

  it('метка задания светится намеренно', () => {
    // У неё СВОЙ emissive. Проверяем не просто «emissive есть», а что он
    // НЕ ЧЁРНЫЙ: первая версия искала /emissive:\s*0x[0-9a-f]+/, и этим
    // проходил и 0x000000 — то есть погашенная метка считалась исправной.
    // Hex-цифры это в том числе нули, и глаз regex-а тут не отличает свет от
    // темноты.
    const м = /emissive:\s*(0x[0-9a-fA-F]+)/.exec(НАВИГАТОР);
    должен(м, 'у метки задания нет emissive: она перестала светиться');
    const цвет = Number(м![1]);
    должен(цвет > 0, `emissive метки равен нулю (${м![1]}): метка погасла, а не «стала стильной»`);
    должен(
      /emissiveIntensity/.test(НАВИГАТОР),
      'у метки задания нет emissiveIntensity',
    );
  });
});