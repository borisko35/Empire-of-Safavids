// HDRI-окружение: связность.
//
// РАЗДЕЛЕНИЕ ПРОВЕРОК, И ОНО НЕ СЛУЧАЙНОЕ.
//   Числа — пробнику client/tools/check-sky-environment.ts. Он считает по той же
//     математике, что и игра: яркость неба, отношение неба и песка, наличие
//     ключевого света, отсутствие пересветов.
//   Связность — сюда, по исходникам. В клиенте нет своего тест-раннера, а поднять
//     WebGL в наботе дороже, чем написать его заново. Проверяется то, что можно
//     сломать незаметно: модуль не подключён, купол вернулся и закрывает фон,
//     пересборка идёт каждый кадр, освобождение забыто.
//
// Проверка по тексту отвечает на вопрос «написано ли это», а не «работает ли».
// Здесь именно «написано» и есть то, что нужно: математику проверяет пробник
// числами, и подменять его текстом было бы подменой измерения утверждением.
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МАТЕМАТИКА = 'client/src/app/game3d/skyEnvironmentMath.ts';
const ОКРУЖЕНИЕ = 'client/src/app/game3d/skyEnvironment.ts';
const НЕБО = 'client/src/app/game3d/sky.ts';
const МИР = 'client/src/app/game3d/world3d.ts';

describe('HDRI-окружение: математика проверяема без WebGL', () => {
  it('модуль математики есть и не тянет three', () => {
    must(existsSync(join(корень, МАТЕМАТИКА)), `нет ${МАТЕМАТИКА}: пробнику нечего считать`);
    const код = читать(МАТЕМАТИКА);
    must(!/from 'three'/.test(код),
      'математика импортирует three: её больше нельзя посчитать пробником без браузера');
    must(/export function buildEquirect/.test(код), 'нет сборки карты');
    must(/export function equirectStats/.test(код), 'нет сводки по карте — читаемость силуэтов нечем мерить');
  });

  it('карта линейная и HDR, а не sRGB', () => {
    // Карта в sRGB декодировалась бы, и солнце вышло бы блёклым серым кругом.
    const код = читать(ОКРУЖЕНИЕ);
    must(/LinearSRGBColorSpace/.test(код), 'карта помечена не линейной: солнце потеряет яркость');
    must(/FloatType/.test(код), 'карта не в числах с плавающей точкой — HDR не поместится');
    must(/EquirectangularReflectionMapping/.test(код), 'карта не помечена как эквиректангулярная');
  });

  it('HDRI грузится не устаревшим загрузчиком', () => {
    // С three 0.18x RGBELoader объявлен устаревшим и печатает предупреждение
    // при КАЖДОМ вызове, а их четыре — по варианту неба на старте. Загрузчик
    // заменён на HDRLoader; приёмник тот же (DataTexture в линейном
    // пространстве), поэтому остальные проверки этого файла не меняются.
    const код = читать(ОКРУЖЕНИЕ);
    must(
      !/from 'three\/addons\/loaders\/RGBELoader\.js'/.test(код)
      && !/new RGBELoader\(\)/.test(код),
      'HDRI грузится через RGBELoader: он устарел и печатает предупреждение '
      + 'на каждый вариант неба',
    );
    must(/new HDRLoader\(\)/.test(код), 'HDRI грузится не через HDRLoader');
  });

  it('подсвет неба и ядро светила — разные числа', () => {
    // Спутанные, они дают небо в 3.6 единицы, а это через ACES — белое пятно
    // на весь кадр (§204). Смысловое требование, а не формат.
    const стиль = читать(МАТЕМАТИКА);
    must(/sunGlow:/.test(стиль) && /sunCore:/.test(стиль),
      'подсвет неба и ядро солнца снова одно число: полдень уйдёт в белое');
    must(/moonGlow:/.test(стиль) && /moonCore:/.test(стиль),
      'у луны то же: подсвет и ядро должны быть разделены');
  });
});

describe('HDRI-окружение: подключено в мире', () => {
  it('мир создаёт окружение с рендерером и обновляет его в кадре', () => {
    const мир = читать(МИР);
    must(/new SkyEnvironment\(this\.scene, this\.renderer\)/.test(мир),
      'окружение не создаётся сценой и рендерером: без рендерера не собрать PMREM');
    must(/this\.env\.update\(/.test(мир), 'состояние неба не уходит в окружение — карта останется первой');
    // Порядок: окружение должно появиться после создания рендерера.
    const рендерер = мир.indexOf('new THREE.WebGLRenderer');
    const окружение = мир.indexOf('new SkyEnvironment');
    must(рендерер >= 0 && окружение > рендерер,
      'окружение создаётся раньше рендерера: PMREMGenerator без него не работает');
  });

  it('окружение освобождается при разрушении мира', () => {
    // Мир пересоздаётся при уходе в подземелье и обратно. Забытый dispose
    // здесь — это утечка текстур GPU на каждом переходе, а не раз за сессию.
    const мир = читать(МИР);
    must(/this\.env\?\.dispose\(\)/.test(мир), 'окружение не освобождается: текстуры переживут мир');
    const порядок = ['this.sky?.dispose();', 'this.env?.dispose();', 'this.renderer?.dispose();']
      .map((фрагмент) => мир.indexOf(фрагмент));
    must(порядок[0] < порядок[1] && порядок[1] < порядок[2],
      'освобождение идёт не в том порядке: dispose окружения обращается к рендереру');
  });

  it('пересборка карты не идёт каждый кадр', () => {
    // Без порогов карта пересобиралась бы на каждом кадре, и на слабой машине
    // свет дёргался бы именно там, где это заметнее всего.
    const код = читать(ОКРУЖЕНИЕ);
    must(/ПОРОГ_СОЛНЦА/.test(код) && /ПОРОГ_ПАСМУРНОСТИ/.test(код),
      'нет порогов пересборки: карта будет собираться каждый кадр');
    must(/МИНИМУМ_МЕЖДУ_КАДРАМИ/.test(код), 'нет минимального интервала между пересборками');
    must(!/if \(dt > 0\)/.test(код), 'пересборка привязана к длине кадра, а не к изменению неба');
  });
});

describe('HDRI-окружение: купол больше не рисуется', () => {
  it('в небе нет купола-шара', () => {
    // Купол был непрозрачной сферой радиусом SKY_RADIUS и перекрывал бы фон
    // целиком: карта осталась бы видна только как источник света, а небо на
    // экране было бы старое.
    const небо = читать(НЕБО);
    must(!/domeMat/.test(небо), 'купол вернулся: он перекроет фон сцены целиком');
    must(!/new THREE\.SphereGeometry\(SKY_RADIUS/.test(небо),
      'сфера неба на SKY_RADIUS вернулась: небом снова рисует старая геометрия');
  });

  it('палитры остались: туман должен совпадать с горизонтом', () => {
    // Туман берёт цвет из sky.horizonColor. Если палитры убрать вместе с
    // куполом, туман останется серым и сцена перестанет сливаться с небом.
    const небо = читать(НЕБО);
    must(/const DAY: Palette/.test(небо) && /const DUSK: Palette/.test(небо) && /const NIGHT: Palette/.test(небо),
      'палитры неба убраны вместе с куполом: туман перестанет совпадать с горизонтом');
    must(/horizonColor\.copy\(pal\.horizon\)/.test(небо), 'цвет горизонта больше не отдаётся туману');
  });
});

describe('HDRI-окружение: фон и свет — одна карта', () => {
  it('карта ставится и в фон, и в окружение', () => {
    // Только в окружение — свет есть, а небо прежнее. Только в фон — красиво,
    // а материалы освещаются числами из кадра. Обе цели сразу — небо и свет
    // расходятся, когда пересобирается одна из них.
    const код = читать(ОКРУЖЕНИЕ);
    must(/scene\.background = текстура/.test(код), 'карта не ставится фоном сцены');
    must(/scene\.environment = цель\.texture/.test(код), 'карта не ставится окружением сцены');
  });

  it('старое освобождается только после сборки нового', () => {
    // Наоборот — между освобождением и присваиванием кадр останется без
    // окружения, и это видно как вспышка.
    const код = читать(ОКРУЖЕНИЕ);
    const новое = код.indexOf('this.scene.environment = цель.texture');
    const старое = код.indexOf('старыйТекст.dispose()');
    must(новое >= 0 && старое > новое,
      'старое окружение освобождается до того, как поставлено новое: будет вспышка');
  });

  it('при освобождении сцена разводится с нашими текстурами', () => {
    // Иначе Three.js до следующего кадра читает уже освобождённую память GPU.
    const код = читать(ОКРУЖЕНИЕ);
    must(/scene\.background === this\.texture/.test(код) && /scene\.background = null/.test(код),
      'фон сцены не разводится с картой при освобождении');
    must(/scene\.environment = null/.test(код), 'окружение сцены не разводится при освобождении');
  });
});