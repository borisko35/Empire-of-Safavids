// Телеги в пригороде: парус, груз и вол в оглобле.
//
// ЧТО БЫЛО (22 октября 2026, §313). Телега у склада стояла пустой и без
// скота: оглобель был, а тянуть его было некому, и паруса не было.
//
// ЧТО ТЕПЕРЬ. Мачта с **парусом** (полотнище с провисом), **груз** в телеге —
// мешки и свёртки ткани, и **вол в оглобле**: тело-капсула, голова с рогами и
// четыре ноги.
//
// ЧТО ПРОВЕРЯЕТСЯ. У телеги есть мачта, парус, груз и вол; парус с провисом, у
// вола рога и четыре ноги.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Телеги: парус, груз, вол', () => {
  it('у телеги мачта и парус с провисом', () => {
    должен(
      /const мачта = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.06, 0\.08, 3\.0, 6\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у телеги нет мачты',
    );
    // Парус — часть цилиндра: полотнище с провисом, а не плита.
    должен(
      /new THREE\.CylinderGeometry\(0\.8, 0\.8, 1\.7, 10, 1, true, -Math\.PI \/ 2, Math\.PI\)/.test(ТЕРРЕЙН),
      'паруса нет или он без провиса',
    );
  });

  it('в телеге груз: мешки и свёртки', () => {
    должен(
      /const груз = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.3, 8, 6\), MAT\.sand\);/.test(ТЕРРЕЙН),
      'в телеге нет мешков',
    );
    должен(
      /const свёрток = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.17, 0\.17, 1\.0, 8\)/.test(ТЕРРЕЙН),
      'в телеге нет свёртков ткани',
    );
  });

  it('вол в оглобле: рога и четыре ноги', () => {
    // Тело — капсула, голова — с рогами.
    должен(
      /const тело = new THREE\.Mesh\(new THREE\.CapsuleGeometry\(0\.42, 1\.1, 4, 12\)/.test(ТЕРРЕЙН),
      'тело вола — не капсула',
    );
    должен(
      /const рог = new THREE\.Mesh\(new THREE\.ConeGeometry\(0\.07, 0\.42, 6\), MAT\.sandstone\);/.test(ТЕРРЕЙН),
      'у вола нет рогов',
    );
    // Четыре ноги: две пары.
    должен(/for \(const lx of \[-0\.32, 0\.32\]\) \{/.test(ТЕРРЕЙН), 'у вола не две пары ног');
    должен(/for \(const lz of \[-0\.55, 0\.55\]\) \{/.test(ТЕРРЕЙН), 'у вола не четыре ноги');
  });
});
