// Телеги в пригороде: парус, груз и вол в оглобле.
//
// ЧТО БЫЛО (22 октября 2026, §313). Телега у склада стояла пустой и без
// скота: оглобель был, а тянуть его было некому, и паруса не было.
//
// ЧТО ТЕПЕРЬ (§326). Телега — готовая модель (medieval-cart-lite), груз —
// готовые мешки и свёрток, вол — настоящая ригованная модель быка
// (Quaternius, CC0), дышит в покое. Парус остаётся своим: ткань с провисом
// на каркасе.
//
// ЧТО ПРОВЕРЯЕТСЯ. У телеги есть мачта и парус с провисом; телега, груз и
// вол — готовые модели из манифеста и фауны; процедурной сборки больше нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

describe('Телеги: парус, груз, вол', () => {
  it('у телеги мачта и парус с провисом', () => {
    // Телега сама — готовая модель.
    должен(/decorВещь\(city, 'medieval-cart-lite', px, pz, \{/.test(ТЕРРЕЙН),
      'телега стоит не готовой моделью');
    должен(
      /const мачта = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.06, 0\.08, 3\.0, 6\), MAT\.trunk\);/.test(ТЕРРЕЙН),
      'у телеги нет мачты',
    );
    // Парус — часть цилиндра: полотнище с провисом, а не плита.
    должен(
      /new THREE\.CylinderGeometry\(0\.8, 0\.8, 1\.7, 10, 1, true, -Math\.PI \/ 2, Math\.PI\)/.test(ТЕРРЕЙН),
      'паруса нет или он без провиса',
    );
  });

  it('груз у телеги — готовые мешки и свёрток', () => {
    должен(/decorВещь\(city, 'bags', px - 1\.6, pz - 0\.8,/.test(ТЕРРЕЙН), 'мешков у телеги нет');
    должен(/decorВещь\(city, 'package-1', px - 1\.4, pz \+ 0\.6,/.test(ТЕРРЕЙН), 'свёртка у телеги нет');
    должен(!/const груз = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.3, 8, 6\), MAT\.sand\);/.test(ТЕРРЕЙН),
      'мешки снова сферы');
  });

  it('вол в оглобле — ригованная модель быка', () => {
    const манифест = JSON.parse(читать('client/src/app/public/models/manifest.json')) as {
      animals?: { file: string; name: string; bytes: number }[];
    };
    должен((манифест.animals ?? []).some((д) => д.name === 'bull'), 'bull.glb нет в манифесте');
    должен(/void собратьЗверя\('bull', [\d.]+\)\.then\(\(зверь\) => \{/.test(ТЕРРЕЙН),
      'вол ставится не моделью быка');
    должен(/следитьЗверем\(зверь\);/.test(ТЕРРЕЙН), 'миксер вола никто не тикает');
    должен(!/CapsuleGeometry\(0\.42, 1\.1, 4, 12\)/.test(ТЕРРЕЙН), 'вол снова капсула');
  });
});
