// Ссылка должна выглядеть как игра, а не как пустое место.
//
// ЗАЧЕМ ФАЙЛ. Проверки карты сайта требовали, чтобы страницы были описаны
// в sitemap.xml, но МЕТАДАННЫЕ ДЛЯ РЕПОСТА не проверял никто. Итог был
// такой: у trailer.html, forum.html и feedback.html не было НИ ОДНОГО
// тега og:*. То есть страница, которую репостят чаще всего - трейлер, - в
// Discord, Telegram и Reddit показывалась без превью и без описания.
//
// Отсутствие мета-тегов не является ошибкой сборки: страница отдаётся 200,
// всё выглядит работающим. Заметить можно только репостом настоящей ссылки.
//
// ПРАВИЛО. Каждая публичная страница обязана иметь ПОЛНЫЙ набор и иметь
// СВОИ заголовок и описание. Свои - потому что заголовок лендинга в
// превью форума вводит в заблуждение: это другой документ.
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const web = 'client/web/';

/** Страницы с метаданными для репоста. Исключения — с причиной. */
const БЕЗ_РЕПОСТА: Record<string, string> = {
  'admin.html': 'служебная страница, её не репостят и в поиск не отдают',
};

/** Набор тегов без которого превью не соберётся. */
const ОБЯЗАТЕЛЬНЫЕ = [
  'og:type', 'og:title', 'og:description', 'og:image',
  'og:url', 'og:locale', 'og:image:width', 'og:image:height',
  'twitter:card', 'twitter:title', 'twitter:description', 'twitter:image',
] as const;

const СТРАНИЦЫ = readdirSync(join(корень, web)).filter(f => f.endsWith('.html'));

// Падает с внятным текстом. Без него «лендинг без og:title» сравнился бы
// с двумя пустыми строками и дал бы ложное «все страницы свои».
function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

describe('У каждой репостимой страницы есть превью', () => {
  it('полный набор тегов', () => {
    const дыры: Record<string, string[]> = {};
    for (const страница of СТРАНИЦЫ) {
      if (страница in БЕЗ_РЕПОСТА) continue;
      const html = читать(web + страница);
      const нет = ОБЯЗАТЕЛЬНЫЕ.filter(тег => !html.includes(тег));
      if (нет.length) дыры[страница] = нет;
    }
    expect({ страниц: СТРАНИЦЫ.length, дыры })
      .toEqual({ страниц: СТРАНИЦЫ.length, дыры: {} });
  });

  it('свой заголовок и своё описание, а не от лендинга', () => {
    // ГЛАВНОЕ, РАДИ ЧЕГО ФАЙЛ. Общие метаданные формально проходят
    // проверку «набор полный», но в превью трейлера или форума стоял бы
    // заголовок лендинга - и это хуже, чем никакого: выглядит как
    // «страница сломалась», а не как «описание не задано».
    const лендинг = читать(web + 'index.html');
    const лендингЗаголовок = /og:title" content="([^"]*)"/.exec(лендинг)?.[1] ?? '';
    const лендингОписание = /og:description" content="([^"]*)"/.exec(лендинг)?.[1] ?? '';
    must(лендингЗаголовок && лендингОписание, 'у лендинга нет og:title или og:description');

    const совпали: Record<string, string[]> = {};
    for (const страница of СТРАНИЦЫ) {
      if (страница === 'index.html' || страница in БЕЗ_РЕПОСТА) continue;
      const html = читать(web + страница);
      const заголовок = /og:title" content="([^"]*)"/.exec(html)?.[1] ?? '';
      const описание = /og:description" content="([^"]*)"/.exec(html)?.[1] ?? '';
      const чем: string[] = [];
      if (заголовок === лендингЗаголовок) чем.push('og:title');
      if (описание === лендингОписание) чем.push('og:description');
      if (чем.length) совпали[страница] = чем;
    }
    expect({ совпали_с_лендингом: совпали })
      .toEqual({ совпали_с_лендингом: {} });
  });

  it('адреса в og:url и canonical указывают на саму страницу', () => {
    // Неверный og:url делает все ссылки на страницу каноническими для
    // лендинга, и поисковик склеит их в один документ.
    const неверные: Record<string, string[]> = {};
    for (const страница of СТРАНИЦЫ) {
      if (страница in БЕЗ_РЕПОСТА) continue;
      const html = читать(web + страница);
      const url = /og:url" content="([^"]*)"/.exec(html)?.[1] ?? '';
      const имя = страница === 'index.html' ? '' : страница;
      const ожидается = `https://www.game.eos-gameonline.com/${имя}`;
      const список: string[] = [];
      if (url !== ожидается) список.push(`og:url=${url || 'нет'}`);
      if (!/<link rel="canonical"/.test(html)) список.push('canonical нет');
      if (список.length) неверные[страница] = список;
    }
    expect({ неверные }).toEqual({ неверные: {} });
  });

  it('картинка превью существует в репозитории', () => {
    // Ссылка на несуществующий файл - самая частая поломка метаданных:
    // страница отдаётся, разметка валидна, а превью пустое. Проверяется по
    // пути внутри content, а не по самой ссылке.
    const отсутствуют: Record<string, string> = {};
    for (const страница of СТРАНИЦЫ) {
      if (страница in БЕЗ_РЕПОСТА) continue;
      const html = читать(web + страница);
      const путь = /og:image" content="https?:\/\/[^/]+(\/[^"]+)"/.exec(html)?.[1];
      if (!путь) { отсутствуют[страница] = 'путь не разобран'; continue; }
      const локальный = 'client/web' + путь.replace(/^\/assets/, '/assets');
      if (!existsSync(join(корень, локальный))) отсутствуют[страница] = локальный;
    }
    expect({ отсутствуют }).toEqual({ отсутствуют: {} });
  });

  it('у каждой страницы заявлены все три языка игры', () => {
    // Игра переведена на ru/en/az. Без og:locale:alternate площадка знает
    // про один язык, и англоязычному репосту показывают русский текст как
    // единственный вариант.
    const безАльтернатив: string[] = [];
    for (const страница of СТРАНИЦЫ) {
      if (страница in БЕЗ_РЕПОСТА) continue;
      const html = читать(web + страница);
      const сколько = (html.match(/og:locale:alternate/g) ?? []).length;
      if (сколько < 2) безАльтернатив.push(`${страница}: ${сколько}`);
    }
    expect({ без_альтернатив: безАльтернатив }).toEqual({ без_альтернатив: [] });
  });
});
