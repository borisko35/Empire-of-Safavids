// Караван-сарай стал интерьером, а не пустой площадкой.
//
// ЧТО БЫЛО. Двор караван-сарая в мире построен целиком - ворота с айваном,
// стены, башни, аркада, шатры, колодец, верблюды. Экстерьер закрыт. А внутрь
// было нельзя: все девять интерьеров висели на Исфахане, потому что дверь
// считалась как CITY.x + lx. Караван-сарай на (505, 55) был открытой
// площадкой без двери.
//
// ЛОВУШКА, КОТОРУЮ ЗАКРЫВАЕТ ЭТА ПРОВЕРКА. Слот комнаты на клиенте считается
// по индексу в массиве SPOTS (POCKET_X + i * ROOM_DX), а на сервере зашит
// числом. Совпадают они только потому, что оба идут в одном порядке. Вставка
// новой записи в середину раздвинет клиентские слоты, серверные числа
// останутся прежними, и все комнаты после вставки разъедутся по координатам:
// игрок войдёт в одну комнату, а окажется в другой. Ни одна проверка на
// геометрию этого не поймает, потому что каждая по отдельности останется
// верной. Поэтому порядок записей проверяется прямо.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS } from '../data/interiors';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const WORLD_HALF = 3175;
const КАРАВАН = { x: 505, z: 55 };
const ВОРОТА = { x: 505, z: 69 };

describe('Караван-сарай: зайти внутрь', () => {
  it('интерьер заведён и держит свой слот', () => {
    const def = INTERIORS.caravanserai;
    must(def !== undefined, 'интерьера caravanserai нет в реестре - дверь в мире не откроется');
    // СЛОТ, А НЕ ПОЗИЦИЯ «ПОСЛЕДНИЙ». Требование было: караван-сарай последний.
    // После крепости он перестал быть последним, но слот обязан остаться прежним:
    // девятым, roomCx 4396 = 4000 + 9*44. Если новая запись встанет выше, слот
    // караван-сарая сдвинется, комната уедет из своих границ - и всё это молча.
    // Ровно тот баг, ради которого проверка и писалась.
    const ключи = Object.keys(INTERIORS);
    const слот = ключи.indexOf('caravanserai');
    must(слот === 9,
      `караван-сарай на слоте ${слот}, а обязан быть девятым: дверь нарисована у` +
      ' комнаты 4396, а войти игрок будет по индексу. Расхождение выглядит как' +
      ' работающая кнопка, которая никуда не ведёт.');
    must(def.roomCx === 4396,
      `у караван-сарая roomCx ${def.roomCx}, а слот 9 даёт 4396: запись сдвинулась`);
    // Требование было «после караван-сарая ровно одна запись» — это
    // значило «крепость последняя». После дворца она перестала быть
    // последней, но СМЫСЛ требования не изменился: между караван-сараем и
    // крепостью не должно появиться ничего, иначе крепость съедет слот
    // десятого. Поэтому проверяем не позицию «последняя», а соседство.
    const слотКрепости = ключи.indexOf('fortress');
    must(слотКрепости === слот + 1,
      `крепость на слоте ${слотКрепости}, а обязана быть сразу после` +
      ` караван-сарая, то есть ${слот + 1}: запись между ними разъедет слоты и комната уедет молча.`);
  });

  it('комната не налезает на остальные девять', () => {
    // Соседние комнаты стоят через 44 единицы, а половина комнаты 16. Значит
    // между центрами должно быть не меньше 32.
    const def = INTERIORS.caravanserai;
    const чужие = Object.values(INTERIORS).filter((д) => д.id !== 'caravanserai');
    const тесные = чужие.filter((д) =>
      Math.abs(д.roomCx - def.roomCx) < 32 && Math.abs(д.roomCz - def.roomCz) < 32);
    must(тесные.length === 0,
      `комната караван-сарая налезает на: ${тесные.map((д) => `${д.id} (${д.roomCx})`).join(', ')}`);
  });

  it('комната остаётся за краем мира', () => {
    // Требование существующее: комната стоит за краем, чтобы не попасть в
    // открытое поле и не совпасть с открытой землёй вокруг.
    const def = INTERIORS.caravanserai;
    must(def.roomCx > WORLD_HALF + 100,
      `комната на ${def.roomCx}, а мир кончается на ${WORLD_HALF} - она оказалась внутри мира`);
    must(Math.abs(def.roomCx) > WORLD_HALF + 100,
      'комната оказалась по другую сторону мира, чем остальные девять');
  });

  it('дверь стоит у ворот караван-сарая', () => {
    // Ворота построены на z + 14 от центра двора. Дверь в 470 единицах от
    // столицы означала бы, что интерьер открывается посреди пустыни.
    const def = INTERIORS.caravanserai;
    const доВорот = Math.hypot(def.doorX - ВОРОТА.x, def.doorZ - ВОРОТА.z);
    must(доВорот <= 20,
      `дверь в ${Math.round(доВорот)} единицах от ворот (${ВОРОТА.x}, ${ВОРОТА.z}) - ` +
      'игрок не дотянется до неё, а вход разрешён только рядом с дверью');
    const доСарая = Math.hypot(def.doorX - КАРАВАН.x, def.doorZ - КАРАВАН.z);
    must(доСарая <= 60,
      `дверь в ${Math.round(доСарая)} единицах от самого караван-сарая - это уже не он`);
    must(Math.abs(def.exitX - def.doorX) <= 30 && Math.abs(def.exitZ - def.exitZ) <= 30,
      'точка выхода далеко от двери - игрок выйдет из стены');
  });

  it('на клиенте запись держит свой слот и с абсолютной дверью', () => {
    // Прямая защита от разъезда слотов и от второго ограничения «дверь всегда
    // в столице». Если кто-то вставит запись выше или вернёт CITY.x в расчёт,
    // проверка упадёт по имени.
    const клиент = читать('client/src/app/game3d/interiors.ts');
    const записи = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    // Тот же смысл, что и на сервере: не «последний», а «девятый», и крепость
    // сразу за ним. После появления дворца крепость перестала быть последней,
    // но соседство обязано сохраниться — дверь нарисована у одной комнаты,
    // а войти игрок будет по индексу.
    const слот = записи.indexOf('caravanserai');
    must(слот === 9,
      `на клиенте караван-сарай на слоте ${слот}, а обязан быть девятым из ${записи.length}: ` +
      'слот комнаты считается индексом в этом массиве');
    const слотКрепости = записи.indexOf('fortress');
    must(слотКрепости === слот + 1,
      `крепость на клиенте на слоте ${слотКрепости}, а обязана быть сразу после` +
      ` караван-сарая, то есть ${слот + 1}`);
    const своя = /id: 'caravanserai', kind: 'caravanserai', nameKey: 'buildings\.caravanserai'[^\n]*dx: 505[^\n]*dz: 69/.test(клиент);
    must(своя,
      'у записи караван-сарая нет абсолютной двери (505, 69) - дверь снова посчитается от столицы');
    must(/if \(s\.lx === undefined \|\| s\.lz === undefined\) continue;/.test(клиент),
      'типовой домик ставится под караван-сарай по координате от столицы - он встанет в NaN');
  });

  it('комната обставлена под караван-сарай, а не под конюшню', () => {
    const клиент = читать('client/src/app/game3d/interiors.ts');
    must(/function furnishCaravanserai/.test(клиент),
      'нет функции обстановки - комната откроется пустой коробкой');
    must(/caravanserai: furnishCaravanserai,/.test(клиент),
      'функция написана, но не подключена - комната останется без обстановки');
    const тело = /function furnishCaravanserai[\s\S]*?\n}/.exec(клиент)?.[0] ?? '';
    for (const [что, зачем] of [
      ['M.hay', 'сено в стойлах'],
      ['M.purple', 'ковёр в комнате купца'],
      ['M.gold', 'светильник у стола купца'],
    ] as const) {
      must(тело.includes(что), `в обстановке нет ${что} (${зачем})`);
    }
  });

  it('название есть во всех трёх переводах', () => {
    for (const язык of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${язык}.json`)) as {
        buildings: Record<string, string>;
      };
      must(typeof словарь.buildings.caravanserai === 'string',
        `в ${язык}.buildings нет ключа caravanserai - на карте появится путь ключа`);
    }
  });

  it('число интерьеров совпадает у сервера и клиента', () => {
    // Реестры на двух сторонах разошлись бы тихо: игрок увидит дверь, а сервер
    // её не найдёт, и вход просто не сработает.
    const клиент = читать('client/src/app/game3d/interiors.ts');
    const уКлиента = [...клиент.matchAll(/\{ id: '([a-z_]+)', kind: '[a-z_]+'/g)].map((м) => м[1]);
    const уСервера = Object.keys(INTERIORS);
    must(уКлиента.length === уСервера.length,
      `клиент знает ${уКлиента.length} интерьеров, сервер ${уСервера.length} - двери и входы разойдутся`);
    const лишние = уКлиента.filter((id) => !(id in INTERIORS));
    must(лишние.length === 0, `на клиенте есть интерьеры, которых нет на сервере: ${лишние.join(', ')}`);
    const нет = уСервера.filter((id) => !уКлиента.includes(id));
    must(нет.length === 0, `на сервере есть интерьеры, которых нет на клиенте: ${нет.join(', ')}`);
  });
});