// Дома города с интерьерами: настоящие окна вместо наклеек.
//
// ЧТО БЫЛО (21 октября 2026, §233). Дома кварталов (мастерская, казарма,
// торговый ряд и другие) строились в interiors.ts как голый бокс 8 x 4.6 x 6
// с пирамидальной крышей, а окнами служили плоские бирюзовые плашки 1.4 x 1.2:
// наклейки, а не окна. В городе, где дома Исфахана после §222 получили
// стекло, раму и средник, эти дома оставались коробками с двумя пятнами.
//
// ЧТО ТЕПЕРЬ. Окна — общие с городом (windowPane из terrain.ts: стекло, рама,
// перекладина, стойка), и под кровлей появился каменный пояс.
//
// ЧТО ПРОВЕРЯЕТСЯ. Три вещи: наклейки не вернулись, окна строятся общей
// функцией, и у дома есть пояс под кровлей.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');
const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ИНТЕРЬЕРЫ.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Дома города с интерьерами', () => {
  it('окна настоящие, а не бирюзовые наклейки', () => {
    // Плашка 1.4 x 1.2 из ткани читалась как наклейка, а не как окно.
    должен(
      !/const win1 = box\(1\.4, 1\.2, 0\.2, M\.teal/.test(код),
      'окна снова плоские наклейки: дома кварталов — коробки с пятнами',
    );
    должен(
      /const win1 = windowPane\(-2\.9, 2\.6, 3\.02, 0, 1\.4, 1\.2\)/.test(код),
      'окна построены не общей функцией города: стекло разъедется',
    );
    должен(
      /import \{ CITY, addCollider, windowPane \} from '\.\/terrain'/.test(ИНТЕРЬЕРЫ),
      'общая функция окна не импортирована',
    );
    // Окно должно быть тем же, что и в домах Исфахана.
    должен(
      /export function windowPane\(/.test(ТЕРРЕЙН),
      'windowPane не экспортирован: домам города нечем пользоваться общим окном',
    );
  });

  it('у дома есть каменный пояс под кровлей', () => {
    должен(
      /const пояс = box\(8\.2, 0\.2, 6\.2, M\.wallDark, 0, 4\.2, 0\)/.test(код),
      'у домов кварталов нет пояса под кровлей: стена — просто коробка',
    );
  });
});
