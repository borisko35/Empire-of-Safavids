// Фонари на воде.
//
// ЧТО БЫЛО (21 октября 2026, §256). Вода в мире — свой шейдер: своё небо,
// своё солнце, свой туман, своя рябь. Точечных источников она не знала вовсе.
// Пруд в садах, у которого с §249 горит три фонаря, ночью оставался чёрным
// пятном: фонари стояли рядом, а вода их не видела.
//
// ЧТО ТЕПЕРЬ. В шейдер воды идут восемь ближних к камере ламп: от каждой —
// блик по воде и её отсвет. Равномерками, потому что ламп в мире десятки, а
// до шейдера доходит только то, что видно.
//
// ЧТО ПРОВЕРЯЕТСЯ. Равномерки в шейдере и в материале есть, вклад лампы
// считается, и движок наполняет равномерки ближними лампами — иначе вода
// снова останется слепой.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Фонари на воде', () => {
  it('шейдер воды знает про точечные источники', () => {
    должен(/uniform vec3 uLampPos\[8\];/.test(ТЕРРЕЙН), 'в шейдере воды нет равномерки фонарей');
    должен(/uniform vec3 uLampColor\[8\];/.test(ТЕРРЕЙН), 'в шейдере воды нет цвета фонарей');
    должен(/uniform float uLampCount;/.test(ТЕРРЕЙН), 'в шейдере воды нет счётчика фонарей');
    // Вклад лампы считается, а не только объявлен.
    должен(
      /if \(float\(i\) >= uLampCount\) break;[\s\S]{0,600}?uLampColor\[i\] \* \(s \* [\d.]+ \+ [\d.]+\) \* att;/.test(
        ТЕРРЕЙН,
      ),
      'шейдер воды не считает вклад лампы',
    );
  });

  it('материал воды создаёт равномерки', () => {
    должен(
      /uLampPos: \{ value: Array\.from\(\{ length: 8 \}, \(\) => new THREE\.Vector3\(\)\) \}/.test(ТЕРРЕЙН),
      'в материале воды нет равномерки фонарей',
    );
    должен(/uLampCount: \{ value: 0 \}/.test(ТЕРРЕЙН), 'в материале воды нет счётчика фонарей');
  });

  it('движок наполняет воду ближними лампами', () => {
    должен(
      /const лампыУВоды: \{ d: number; light: THREE\.PointLight \}\[\] = \[\];/.test(МИР),
      'движок не собирает лампы для воды',
    );
    // Берутся ближние к камере, и не больше восьми.
    должен(
      /for \(const t of this\.torches\) \{\s*лампыУВоды\.push/.test(МИР),
      'лампы для воды не собираются: вода останется слепой',
    );
    должен(
      /for \(const l of this\.lamps\) \{\s*лампыУВоды\.push/.test(МИР),
      'постоянные фонари для воды не собираются',
    );
    должен(/лампыУВоды\.sort\(\(a, b\) => a\.d - b\.d\);/.test(МИР), 'лампы для воды не сортируются по близости');
    должен(/const ближние = лампыУВоды\.slice\(0, 8\);/.test(МИР), 'в воду идёт больше ламп, чем шейдер держит');
    // И наполняются все три равномерки.
    должен(/u\.uLampCount\.value = ближние\.length;/.test(МИР), 'счётчик фонарей у воды не ставится');
    должен(/u\.uLampPos\.value\[i\]\.copy\(ближние\[i\]\.light\.position\);/.test(МИР), 'позиции фонарей в воду не идут');
    должен(
      /u\.uLampColor\.value\[i\][\s\S]{0,120}?\.copy\(ближние\[i\]\.light\.color\)/.test(МИР),
      'цвета фонарей в воду не идут',
    );
  });
});
