// Катакомбы Тебриза: первое подземелье с настоящей геометрией.
//
// ГЛАВНОЕ ЗДЕСЬ. Босс стоит в (0, 0) в данных, но это локальная позиция его
// КОМНАТЫ, а не зала. Замер показал: комнаты подземелья сводились в одну
// систему координат, размах у дворца выходил 40 при ширине зала 32, и часть
// монстров оказывалась в стене. Теперь комнаты раскладываются по зонам зала
// (systems/dungeonLayout), и Рустам встаёт в (0, −10) — в середину своей зоны.
//
// ПОЧЕМУ ТРОН У ДАЛЬНЕЙ СТЕНЫ, А НЕ В ЦЕНТРЕ ЗАЛА. Трон рисуется вокруг
// опорной точки боссовой комнаты, а опорная точка — сам босс. Если трон
// поставить в центр зала (0, 0), босс в (0, −10) окажется спиной к трону.
//
// ВТОРОЕ: точка входа подземелья равна центру его зала. Сдвиги в z, которые я
// ставил (3996 и 3986), лечили симптом — свод комнат в одну точку — и после
// раскладки стали лишними.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { INTERIORS, ROOM_HALF } from '../data/interiors';
import { DUNGEONS_DATABASE } from '../data/dungeons';
import { planDungeonRooms } from '../systems/dungeonLayout';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const клиент = читать('client/src/app/game3d/interiors.ts');
const катакомбы = DUNGEONS_DATABASE.dungeon_tabriz_catacombs;
const начало = клиент.indexOf('function furnishCatacombs(');
must(начало > 0, 'функции обстановки катакомб нет');
// Тело обстановки — до следующей функции. Без этой границы сюда попадала
// обстановка дворца, и проверка считала чужие сундуки и зоны: на этом
// проверка и поймала 9 сундуков вместо 6.
const следующая = клиент.indexOf('\nfunction furnish', начало + 1);
const тело = клиент.slice(начало, следующая > 0 ? следующая : начало + 7000);

describe('Катакомбы: точка входа = центр зала', () => {
  it('точка входа подземелья совпадает с комнатой интерьера', () => {
    must(INTERIORS.catacombs !== undefined, 'интерьера катакомб нет');
    must(
      катакомбы.entryX === INTERIORS.catacombs.roomCx && катакомбы.entryZ === INTERIORS.catacombs.roomCz,
      `точка входа (${катакомбы.entryX}, ${катакомбы.entryZ}) не совпадает с залом ` +
        `(${INTERIORS.catacombs.roomCx}, ${INTERIORS.catacombs.roomCz}): зоны комнат уедут не туда`
    );
  });

  it('у всех подземелий точка входа не в мире, а в центре своего зала', () => {
    // Верхняя граница выросла с 5000 до 5040 вместе с карманом. Храм Симурга
    // стоит на слоте 23 (cx = 5012), и его комната занимает 4996..5028 — то
    // есть целиком внутри кармана, правая граница которого 5056. Предел 5000
    // остался от времени, когда последний слот был 11 (4484).
    for (const [id, def] of Object.entries(DUNGEONS_DATABASE)) {
      must(
        def.entryX >= 4000 && def.entryX <= 5040,
        `точка входа ${id} в ${def.entryX} — это не карман построек, монстры окажутся на улице`
      );
      must(
        def.entryZ === INTERIORS.catacombs!.roomCz,
        `точка входа ${id} по z = ${def.entryZ}, а центр зала ${INTERIORS.catacombs!.roomCz}: ` +
          'сдвиг в z остался от лечения симптома, который теперь лечит раскладка'
      );
    }
  });

  it('комнаты данных разложены по зонам, а не сведены в одну точку', () => {
    const комнаты = planDungeonRooms(катакомбы);
    must(катакомбы.rooms.length === 3, `комнат в данных ${катакомбы.rooms.length}, а зон заложено три`);
    for (let k = 1; k < комнаты.length; k++) {
      must(
        комнаты[k].zoneZ < комнаты[k - 1].zoneZ,
        `зона ${k} не дальше зоны ${k - 1}: комнаты слиплись в одну точку`
      );
    }
  });
});

describe('Катакомбы: трон стоит там, где встанет босс', () => {
  it('босс встанет в (0, −10), трон у дальней стены в (0, −14)', () => {
    const комнаты = planDungeonRooms(катакомбы);
    const боссовая = комнаты.find((к) => катакомбы.rooms[к.index].isBossRoom);
    must(боссовая !== undefined, 'боссовой комнаты в раскладке нет');
    const босс = боссовая!.monsters.find((м) => м.monsterId === катакомбы.rooms[боссовая!.index].bossId);
    must(босс !== undefined, 'босс не запланирован');
    must(
      босс!.x - катакомбы.entryX === 0 && босс!.z - катакомбы.entryZ === -10,
      `Рустам встанет в (${босс!.x - катакомбы.entryX}, ${босс!.z - катакомбы.entryZ}), ` +
        'а трон нарисован под (0, −14): босс окажется спиной к трону'
    );
    must(
      /box\(3\.6, 0\.5, 1\.6, M\.stone, cx, FLOOR_Y \+ 0\.25, cz - 14\)/.test(тело),
      'трон убран с дальней стены: трон должен стоять там, где встанет босс, а не в его месте'
    );
    must(
      !/box\(3\.6, 0\.5, 1\.6, M\.stone, cx, FLOOR_Y \+ 0\.25, cz\)/.test(тело),
      'трон стоит ровно в середине зала — это и есть баг: босс встанет спиной'
    );
  });

  it('трон не занимает место босса: между ними не меньше двух шагов', () => {
    // Трон глубиной 1.6 и стоит в −14, то есть занимает −14.8…−13.2.
    // Босс в −10: до переднего края трона 3.2 шага.
    const переднийКрайТрона = -14 + 0.8;
    const боссZ = -10;
    must(
      боссZ > переднийКрайТрона + 2,
      `босс в ${боссZ}, передний край трона в ${переднийКрайТрона}: босс стоит в троне`
    );
  });

  it('ни один монстр катакомб не стоит в стене', () => {
    let проверено = 0;
    for (const комната of planDungeonRooms(катакомбы)) {
      for (const монстр of комната.monsters) {
        проверено++;
        must(
          Math.abs(монстр.x - катакомбы.entryX) <= ROOM_HALF - 1 &&
            Math.abs(монстр.z - катакомбы.entryZ) <= ROOM_HALF - 1,
          `${монстр.monsterId} в (${монстр.x - катакомбы.entryX}, ${монстр.z - катакомбы.entryZ}) — в стене`
        );
      }
    }
    must(проверено >= 14, `проверено ${проверено} монстров, а в данных их не меньше`);
  });
});

describe('Катакомбы: комнаты данных разложены по геометрии', () => {
  it('геометрия делит зал на три зоны, как в данных три комнаты', () => {
    must(/── Зона 1/.test(тело), 'входного зала нет');
    must(/── Зона 2/.test(тело), 'казарм нет');
    must(/── Зона 3/.test(тело), 'тронного зала нет');
    const расстояния = [...тело.matchAll(/cz ([+-]) ?(\d+(?:\.\d+)?)/g)].map((м) =>
      (м[1] === '-' ? -1 : 1) * Number(м[2])
    );
    must(
      new Set(расстояния).size >= 4,
      'зоны не разнесены по глубине: расстояний ' + расстояния.length + ', разных ' + new Set(расстояния).size
    );
  });

  it('сундуков столько же, сколько в данных', () => {
    const ожидается = катакомбы.rooms.reduce((с, р) => с + р.treasureChests, 0);
    const нарисовано = (тело.match(/box\(1\.1, 0\.8, 0\.8, M\.wood/g) || []).length;
    must(
      нарисовано === ожидается,
      `сундуков нарисовано ${нарисовано}, а в данных ${ожидается} (1 + 2 + 3)`
    );
  });

  it('спуск вниз есть: подземелье идёт под землёй', () => {
    must(
      /FLOOR_Y \+ 0\.08 - i \* 0\.16/.test(тело),
      'спуска нет: в подземелье приходят по лестнице внутри здания'
    );
  });

  it('факелы есть в каждой зоне', () => {
    // Считаются ПАРЫ фонарей, а не вхождения M.fire: четыре факела рисуются
    // одним циклом, и M.fire в коде встречается ровно один раз. Считать
    // вхождения материала здесь — значит всегда увидеть «1» и решить, что
    // фонарей нет.
    const пары = тело.match(/\[cx [+-] ?[\d.]+, cz [+-] ?[\d.]+\]/g) || [];
    must(пары.length >= 4, `пар фонарей ${пары.length}: подземелье должно освещаться по частям`);
    must(/M\.fire/.test(тело), 'огня на фонарях нет');
  });

  it('функция обстановки заведена и вызывается', () => {
    must(/function furnishCatacombs\(/.test(клиент), 'функции обстановки нет');
    must(/catacombs: furnishCatacombs,/.test(клиент), 'катакомбы не прописаны в выборе обстановки');
    must(
      /'catacombs'/.test(клиент.split('export type BuildingKind')[1]?.slice(0, 1100) ?? ''),
      'в типе BuildingKind нет катакомб'
    );
  });

  it('катакомбы двадцатая постройка списка, и граница кармана её покрывает', () => {
    const ключи = Object.keys(INTERIORS);
    // 22 построения: пещеры (слот 20) и крепость (слот 21) добавлены в конец,
    // поэтому слоты катакомб (18) и ханжи (17) не сдвинулись.
    must(ключи.length === 24, `построек ${ключи.length}, а должно быть 23`);
    must(ключи[18] === 'catacombs', `на слоте 18 стоит ${ключи[18]}, а ожидались catacombs`);
    const прямоугольник = /POCKET_RECT = \{ x0: (-?\d+), x1: (\d+)/.exec(клиент);
    must(прямоугольник !== null, 'POCKET_RECT не найден');
    must(
      Number(прямоугольник![2]) >= INTERIORS.catacombs!.roomCx + INTERIORS.catacombs!.roomHalf,
      `правый край кармана ${прямоугольник![2]}, а комната кончается на ` +
        `${INTERIORS.catacombs!.roomCx + INTERIORS.catacombs!.roomHalf}`
    );
  });

  it('название переведено во всех трёх языках', () => {
    for (const код of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${код}.json`));
      must(
        typeof словарь.buildings?.catacombs === 'string' && словарь.buildings.catacombs.length > 0,
        `в ${код}.json нет названия buildings.catacombs`
      );
    }
  });
});