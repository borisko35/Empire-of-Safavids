// Конвертер FBX/GLB → GLB обязан лежать в репозитории.
//
// ЧТО БЫЛО. Модели декораций получены конвертацией в Blender, и это описано
// в двух местах: `models/manifest.json` прямо пишет «Measured, not hand
// written. Regenerate with the Blender converter», а ROADMAP §24 даёт шагом
// замены модели персонажа вызов
//     blender --background --factory-startup --python convert-assets.py
// То есть и манифест, и карта обещали генератор, которого в репозитории не
// было: `git log --diff-filter=A` по этому имени не даёт ничего. Шаг описан,
// а выполнить его было нечем, и посторонний человек, взяв репозиторий, шаг
// повторить не мог.
//
// ЧТО ТЕПЕРЬ В ФАЙЛЕ. Конвертер восстановлен по его же отчётам, которые
// сохранились в `Assets/_staging/glb/*.report.json`, и по логам экспорта.
// Отчёты — это и есть спецификация: какие поля меряются и что пишется.
//
// ПРОВЕРЯЕТСЯ НЕ НАЛИЧИЕ ФАЙЛА, А ТРИ ЕГО РЕШЕНИЯ, каждое из которых
// соответствует настоящей поломке:
//
//  1. Стартовая сцена вычищается. Иначе в модель едет куб из
//     `--factory-startup`: он мал, на мосту почти не виден, но попадает в
//     габариты, а габариты потом ставят коллайдеры и масштаб. Проверено на
//     живой модели: без вычистки мост давал 8 мешей вместо 7 и глубину
//     3.537 м вместо настоящих 2.537 — ровно на метр, на половину куба.
//
//  2. Формат текстур выбирается СВЕРКОЙ пробных экспортов, а не верой.
//     Экспортёр при одноканальной карте пишет в лог «Image data is empty» и
//     ЕДЕТ ДАЛЬШЕ, так что «экспорт без ошибок» не значит «модель целая».
//     Именно так в игру попала дверь без одной карты.
//
//  3. Отчёт пишется ДО проверок. Отчёт нужен, когда всё плохо: потерянная
//     карта — причина искать, а не повод не записывать, что искать.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const путь = join(корень, 'tools', 'convert-assets.py');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

describe('Конвертер ассетов лежит в репозитории', () => {
  it('файл есть — шаг из карты выполним', () => {
    must(
      existsSync(путь),
      'tools/convert-assets.py нет: манифест обещает «Regenerate with the Blender converter», а выполнить шаг нечем',
    );
  });

  it('стартовая сцена вычищается, иначе в модель едет куб', () => {
    // Ломка с откатом: удали вычистку — мост начнёт давать 8 мешей вместо 7
    // и глубину 3.537 вместо 2.537, и это не видно глазом.
    const код = readFileSync(путь, 'utf-8');
    must(/def очистить_сцену\(\)/.test(код), 'в конвертере нет вычистки сцены');
    must(
      /for obj in list\(bpy\.data\.objects\):\s*\n\s*bpy\.data\.objects\.remove\(obj, do_unlink=True\)/.test(код),
      'очистить_сцену не удаляет объекты: стартовый куб Blender уедет в модель',
    );
    must(
      /очистить_сцену\(\)\s*\n\s*before = set/.test(код),
      'сцену чистят не ДО подсчёта импортированного, а после',
    );
  });

  it('формат текстур выбирается сверкой пробных экспортов', () => {
    // Ломка: единственный экспорт в WEBP означает, что модель с
    // одноканальными картами уедет без них, и логов об этом не узнать.
    const код = readFileSync(путь, 'utf-8');
    must(
      /def сравнение_форматов\(/.test(код),
      'нет сверки форматов: конвертер верит одному экспорту и молчит о потере карт',
    );
    must(
      /"WEBP", "JPEG"/.test(код),
      'нет списка пробных форматов: нечем ловить WebP, который не умеет одноканальные карты',
    );
    must(
      /max\(п\["images"\] for п in пробы\)/.test(код),
      'не сравнивается лучший пробанный результат с выбранным: тихая потеря проходит',
    );
  });

  it('отчёт пишется до проверок, а не после', () => {
    // Ломка: отчёт после проверок не пишется вовсе, и при аварийном выходе
    // файла нет — разбираться остаётся по логу экспортёра, где нужная
    // строчка теряется среди десятков.
    const код = readFileSync(путь, 'utf-8');
    const пишетОтчёт = код.indexOf('json.dump(отчёт');
    const перваяПроверка = код.indexOf('ПОТЕРЯ КАРТ');
    must(пишетОтчёт > -1, 'конвертер не пишет отчёт вовсе');
    must(перваяПроверка > -1, 'нет проверки потери карт');
    must(
      пишетОтчёт < перваяПроверка,
      'отчёт пишется после проверок: при аварийном выходе его не будет, а искать как раз и нужно',
    );
  });

  it('не правит манифест целиком, а дописывает одну запись', () => {
    // Манифест однородный: file, name, bytes. Переписывание целиком затерело
    // бы разделы characters и clips, которых конвертер не касается, и в них
    // лежат руками разложенные замеры скелета.
    const код = readFileSync(путь, 'utf-8');
    must(/setdefault\(раздел, \[\]\)/.test(код), 'раздел манифеста не создаётся и не берётся по имени');
    must(/з\.get\("name"\) == имя/.test(код), 'запись не ищется по имени, а дописывается дублем');
    must(/"bytes": байты/.test(код), 'в запись не пишется размер файла');
  });

  it('отчёт и манифест говорят по-английски в ключах', () => {
    // Манифест читает код клиента и проверки. Кириллица в ключах одной
    // записи среди латинских соседей — это ошибка, которую никто не ищет.
    const код = readFileSync(путь, 'utf-8');
    must(
      /"file":|файл":/.test(код),
      'запись манифеста пишется без ключа file',
    );
    const запись = /новая = \{[\s\S]*?\}/.exec(код);
    must(запись !== null, 'не найдено тело новой записи манифеста');
    const ключи = [...(запись![0].matchAll(/"([^"]+)":/g))].map(m => m[1]);
    must(
      ключи.every(к => /^[a-z_]+$/.test(к)),
      `в ключах записи манифеста есть не-латиница: ${ключи.join(', ')}`,
    );
  });

  it('из одного FBX можно взять один кусок, а не весь набор', () => {
    // Ломка с откатом: без отбора в игру едет весь пакет. В пакете
    // укреплений Wall-Type01 лежит рядом с воротами, бастионами и текстом,
    // и всё это одним куском в город не годится.
    const код = readFileSync(путь, 'utf-8');
    must(/def оставить_только\(/.test(код), 'конвертер не умеет оставить один кусок из набора');
    must(/re\.compile\(шаблон, re\.IGNORECASE\)/.test(код),
      'отбор мешей не регулярным выражением: точное имя не годится для «WatchTower/Bastion02-Large»');
    must(/--only ШАБЛОН/.test(код), 'ключ --only не объявлен в справке');
  });

  it('отбор идёт до замеров, иначе габариты в отчёте чужие', () => {
    // Ломка: если считать габариты всего пакета, а не выбранного куска,
    // то в отчёте лежат чужие числа, и по ним потом ставят масштаб.
    const код = readFileSync(путь, 'utf-8');
    const отбор = код.indexOf('оставить_только(ключи["only"])');
    const замер = код.indexOf('"measure_before": замерить()');
    must(отбор > -1, 'отбор мешей не вызывается');
    must(замер > отбор, 'отбор идёт после замера: габариты в отчёте от всего пакета');
  });

  it('модель ставится основанием в ноль, а не как её разложил автор', () => {
    // Ломка: у стены из пакета укреплений низ на y = 10.17, а по x она стоит
    // на 53.7. Без сдвига такая модель уезжает на десяток метров вбок и
    // вверх, и это выглядит как «модель сломалась».
    const код = readFileSync(путь, 'utf-8');
    must(/def в_начало_координат\(\)/.test(код), 'конвертер не ставит модель в начало координат');
    must(/-\(мин\[0\] \+ макс\[0\]\) \/ 2\.0/.test(код),
      'по X модель не центрируется');
    // Прижимать надо Z, а не Y, и это не опечатка.
//
// Blender после импорта Z-вертикален, и экспортёр glTF разворачивает Z в Y —
// то есть в готовом файле вертикалью становится Y. Но сдвиг применяется ДО
// экспорта, а значит до разворота. Жать по Y — значит жать по оси, которая
// после экспорта окажется НЕ высотой: на стене из пакета укреплений так
// прижали толщину, высота осталась нетронутой, и модель встала
// отцентрованной по вертикали, наполовину в земле. Отчёт конвертера при этом
// обещал правильные габариты, то есть врал именно в том, ради чего писался.
    must(/-мин\[2\],/.test(код), 'по Z модель не прижимается низом к нулю');
    must(!/^\s*-мин\[1\],\s*$/m.test(код),
      'вернулось прижатие по Y: после разворота экспорта это не высота, а поперечная ось');
    must(/--center 0/.test(код), 'ключ --center не объявлен в справке');
  });

  it('трансформы запекаются в геометрию, а не остаются в узле', () => {
    // ЧТО ЗДЕСЬ БЫЛО СЛОМАНО. `в_начало_координат()` двигает модель через
    // `o.location`. На экспорт это уходило узлом: в готовом GLB лежал
    // `nodes[0].translation`, а вершины оставались на месте. Для глаза в
    // редакторе разницы нет, для игры разница смертельная: three.js честно
    // применяет узел, и модель встаёт не там.
    //
    // У экспортёра glTF стоит `export_apply=True`, и это НЕ запекает
    // `location` в вершины. Запекать надо явно, до экспорта.
    const код = readFileSync(путь, 'utf-8');
    must(/def запечь_трансформы\(\)/.test(код), 'в конвертере нет запекания трансформов');
    must(/object\.transform_apply\(location=True, rotation=True, scale=True\)/.test(код),
      'трансформы не запекаются в геометрию: перенос уедет в узел и модель встанет не по земле');
    const запекание = код.indexOf('object.transform_apply');
    const экспорт = код.indexOf('bpy.ops.export_scene.gltf');
    must(запекание > -1 && экспорт > запекание,
      'запекание идёт после экспорта: узел останется, и результат будет прежним');
  });
});