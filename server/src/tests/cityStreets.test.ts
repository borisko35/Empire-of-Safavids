// Улицы города: плитка и разрез дорог у стен.
//
// ЧТО БЫЛО (21 октября 2026, §230). Улица-проспект была ровной заливкой
// без текстуры, и при замере в кадре она выходила РОВНО ТЕМ ЖЕ ЦВЕТОМ, что
// мостовая площади (полоса #a58457, мостовая рядом #a58357 — разница в один
// из 255). Читалась она не как улица, а как вырезанная из площади полоса без
// рисунка. И дороги, начинавшиеся в центре города, шли по площади мировым
// полотном.
//
// ЧТО ТЕПЕРЬ. Улица — плитка (мельче и темнее мостовой), и дорога делится у
// стен: внутри города — городская улица, снаружи — мировая дорога.
//
// ЧТО ПРОВЕРЯЕТСЯ. Две вещи, которые легко потерять: у улицы есть плитка и
// дорога внутри города не рисуется мировым полотном.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Улицы города', () => {
  it('у улицы есть плитка, а не ровная заливка', () => {
    // Голая заливка выходила тем же цветом, что мостовая, и читалась как
    // полоса, вырезанная из площади.
    const мат = /street:\s*new THREE\.MeshStandardMaterial\(\{([\s\S]*?)\}\)/.exec(код);
    должен(мат, 'нет материала городской улицы');
    должен(
      /map:\s*plazaTexture\(/.test(мат![1]),
      'у улицы нет плитки: она читается как полоса без рисунка',
    );
  });

  it('проспекты города берут общий материал улицы', () => {
    должен(
      /const streetMat = MAT\.street/.test(код),
      'проспекты снова заводят свой материал: улицы разъедутся',
    );
    должен(/streetMat/.test(код), 'проспекты не используют материал улицы');
  });

  it('дорога внутри города рисуется городской улицей', () => {
    // Точка возрождения лежит внутри стен, и полотно к ней шло по площади
    // мировым материалом — светлой полосой через город.
    должен(
      /d1 < CITY\.radius\) \{[\s\S]{0,200}?MAT\.street/.test(код),
      'дорога внутри города снова рисуется мировым полотном',
    );
    // Дорога, выходящая из города, делится у стен: улица внутри, дорога
    // снаружи.
    должен(
      /const выход = \{ x: r\.from\.x \+ dx \* t/.test(код),
      'дорога не делится у стен города: кусок внутри города красится миром',
    );
  });
});
