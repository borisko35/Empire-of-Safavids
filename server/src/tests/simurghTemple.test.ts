// Храм Симурга: первый рейд Хорасана.
//
// ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ. Храм — второй рейд в игре, и дорога к нему та же,
// что у цитадели: данные, интерьер, геометрия, якорь в мире. Каждое звено
// ломается тихо, если его забыть:
//   - данные без интерьера — заход в пустую комнату;
//   - интерьер без геометрии — сундуки и босс в пустоте;
//   - слот не последний — координаты всех комнат ниже съезжают.
//
// Отдельная проверка на ГАРНИЗОН: монстры должны быть хорасанскими, а не
// выдуманными. У Хорасана на карте есть рыси, разбойники караванов и
// арззанг — других войск у региона нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const данные = читать('server/src/data/dungeons.ts');
const серверИнтерьеры = читать('server/src/data/interiors.ts');
const клиентИнтерьеры = читать('client/src/app/game3d/interiors.ts');
const спавн = читать('server/src/systems/SpawnSystem.ts');
const монстры = читать('server/src/data/monsters.ts');

function блок(источник: string, имя: string): string {
  const начало = источник.indexOf(`'${имя}'`);
  must(начало > 0, `блока ${имя} нет`);
  const конец = источник.indexOf('\n  },', начало);
  must(конец > начало, `конец блока ${имя} не найден`);
  return источник.slice(начало, конец);
}

describe('Храм Симурга: это рейд', () => {
  it('объявлен и помечен рейдом', () => {
    must(/'dungeon_simurgh_temple': \{/.test(данные), 'храма нет в DUNGEONS_DATABASE');
    must(
      /id: 'dungeon_simurgh_temple',[\s\S]{0,900}?isRaid: true/.test(данные),
      'храм не помечен isRaid: панель не отличит его от обычного подземелья',
    );
  });

  it('на двадцать человек, минимум десять', () => {
    must(
      /id: 'dungeon_simurgh_temple',[\s\S]{0,900}?maxPlayers: 20/.test(данные),
      'храм не на 20 человек: это не рейд',
    );
    must(
      /id: 'dungeon_simurgh_temple',[\s\S]{0,900}?minPlayers: 10/.test(данные),
      'minPlayers не 10: штурм меньшим составом засчитывался бы',
    );
  });

  it('срок выше цитадельного — финал с пятью миллионами здоровья', () => {
    must(
      /id: 'dungeon_simurgh_temple',[\s\S]{0,900}?timeLimit: 150/.test(данные),
      'timeLimit не 150: бой на mythic (hp * 3.2) не влезет в цитадельные 120',
    );
  });

  it('уровни 80–90: финал — босс 90-го', () => {
    must(/id: 'dungeon_simurgh_temple',[\s\S]{0,900}?minLevel: 80/.test(данные), 'minLevel не 80');
    must(/id: 'dungeon_simurgh_temple',[\s\S]{0,900}?maxLevel: 90/.test(данные), 'maxLevel не 90');
  });
});

describe('Храм Симурга: гарнизон хорасанский, а не выдуманный', () => {
  it('все монстры существуют и стоят в Хорасане в мире', () => {
    const храм = блок(данные, 'dungeon_simurgh_temple');
    const ids = [...храм.matchAll(/monsterId: '([a-z_0-9]+)'/g)].map((m) => m[1]);
    must(ids.length >= 6, `монстров в храме ${ids.length}: подземелье слишком пустое`);
    for (const id of ids) {
      must(new RegExp(`'${id}': \\{`).test(монстры), `монстра ${id} нет в монстрах`);
    }
    // Рыси и разбойники — хорасанские точки спавна.
    for (const id of ['mob_oasis_lynx', 'mob_caravan_raider']) {
      must(ids.includes(id), `в гарнизоне нет ${id} — он есть в Хорасане в мире`);
    }
    // Дивы стоят в тех же пещерах Хорасана.
    must(ids.includes('mob_div_fire'), 'в гарнизоне нет огненных дивов — они в пещерах Хорасана');
  });

  it('финал — сам Симург', () => {
    const храм = блок(данные, 'dungeon_simurgh_temple');
    must(/bossId: 'world_boss_simurgh'/.test(храм), 'финальный босс не Симург');
    must(/monsterId: 'world_boss_simurgh', count: 1/.test(храм), 'Симурга в троне нет');
    // Он мировой босс Хорасана: дверь обязана быть в том же регионе.
    must(/region: Region.KHORASAN/.test(храм), 'храм не в Хорасане');
  });

  it('дверь — земля под гнездом, а не точка спавна в небе', () => {
    // Спавн Симурга (0, y=100, z=1450) висит на сотне над землёй. Вход на
    // нём увёл бы игрока в небо.
    const точка = /sp_khor_eas_simurgh[^\n]*position: \{ x: (-?\d+),\s*y: (\d+),\s*z: (-?\d+) \}/.exec(спавн);
    must(точка !== null, 'спавн Симурга не найден');
    must(Number(точка![2]) > 0, 'спавн Симурга перестал быть воздушным: проверка устарела');
    const дверь = /simurgh_temple: \{[\s\S]{0,240}?doorX: (-?\d+), doorZ: (-?\d+)/.exec(серверИнтерьеры);
    must(дверь !== null, 'дверь храма не объявлена');
    // X совпадает с точкой спавна (земля под ним), Z — на 38 южнее.
    must(Number(дверь![1]) === 0, 'дверь не под гнездом по X');
    must(Number(дверь![2]) < Number(точка![3]), 'дверь не смещена от точки спавна по Z');
  });
});

describe('Храм Симурга: связь с миром', () => {
  it('интерьер на своём слоте — последний', () => {
    must(
      /roomCx: 5012/.test(серверИнтерьеры),
      'интерьер храма не на слоте 23: 4000 + 23 * 44 = 5012',
    );
    // Слот обязан быть ПОСЛЕДНИМ: вставка выше сдвинула бы всех ниже.
    const всеСлоты = [...серверИнтерьеры.matchAll(/roomCx: (\d+)/g)].map((m) => Number(m[1]));
    must(всеСлоты[всеСлоты.length - 1] === 5012, 'храм не последний слот: комнаты ниже съехали');
  });

  it('вход подземелья совпадает с комнатой своего интерьера', () => {
    must(
      /id: 'dungeon_simurgh_temple',[\s\S]{0,700}?entryX: 5012/.test(данные),
      'вход не совпадает с комнатой: монстры появятся не там',
    );
  });

  it('клиентская запись совпадает с серверной', () => {
    must(
      /id: 'simurgh_temple', kind: 'simurgh_temple'[^}]*dx: 0, dz: 1412, ex: 0, ez: 1416/.test(клиентИнтерьеры),
      'клиентская дверь не совпадает с серверной',
    );
  });

  it('граница кармана накрывает новую комнату', () => {
    const граница = /POCKET_RECT = \{ x0: 3960, x1: (\d+)/.exec(клиентИнтерьеры)?.[1];
    must(граница !== undefined, 'граница кармана не найдена');
    // Комната слота 23 занимает 4996..5028.
    must(Number(граница) >= 5012 + 16, 'комната вылезает за границу кармана');
  });

  it('геометрия есть и подключена', () => {
    must(/function furnishSimurghTemple/.test(клиентИнтерьеры), 'функции обстановки нет: сундуки в пустоте');
    must(/simurgh_temple: furnishSimurghTemple/.test(клиентИнтерьеры), 'функция не подключена');
  });

  it('название переведено во всех трёх языках', () => {
    for (const кодЯзыка of ['ru', 'en', 'az']) {
      const словарь = JSON.parse(читать(`shared/locales/${кодЯзыка}.json`)) as {
        buildings: Record<string, string>;
      };
      must(
        словарь.buildings?.simurgh_temple,
        `в ${кодЯзыка}.json нет buildings.simurgh_temple: здание назовётся пустым именем`,
      );
    }
  });
});

describe('Храм Симурга: сундуки не в воздухе', () => {
  it('координаты сундуков нарисованы теми же, что в данных', () => {
    const храм = блок(данные, 'dungeon_simurgh_temple');
    const изДанных = [...храм.matchAll(/chestPositions: \[([^\]]*)\]/g)]
      .flatMap((m) => [...m[1].matchAll(/x: (-?[\d.]+),\s*z: (-?[\d.]+)/g)].map((p) => [p[1], p[2]].join(',')));
    must(изДанных.length === 12, `сундуков в данных ${изДанных.length}: ждали 12`);
    const функция = /function furnishSimurghTemple[\s\S]*?\n\}/.exec(клиентИнтерьеры)?.[0];
    must(функция !== undefined, 'функция обстановки не вырезалась');
    // Знак перед cx необязателен: точка на оси комнаты пишется просто
    // [cx, cz + 6.4], и без «?» такая пара выпадала бы из разбора.
    // ОДИНАРНЫЕ слеши: двойные верны только внутри строки, а внутри /.../
    // означают литеральный backslash — и регулярка не находила бы ничего.
    const изГеометрии = [...функция!.matchAll(/cx(?:\s*([+-])\s*([\d.]+))?\s*,\s*cz\s*([+-])\s*([\d.]+)/g)]
      .map((m) => [
        String(m[2] === undefined ? 0 : Number(m[2]) * (m[1] === '-' ? -1 : 1)),
        String(Number(m[4]) * (m[3] === '-' ? -1 : 1)),
      ].join(','));
    const есть = new Set(изГеометрии.map((p) => p));
    const потеряны = изДанных.filter((p) => !есть.has(p));
    expect({ потеряны }).toEqual({ потеряны: [] });
  });
});