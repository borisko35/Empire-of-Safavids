// Сторож вербовки караула и панелей.
//
// ЗАЧЕМ ДВА БЛОКА В ОДНОМ ФАЙЛЕ. Оба пойманы в один день, оба — тем, что
// панель или маршрут объявляли, а по-настоящему не работали, и оба выглядели
// снаружи одинаково: «игроку пусто».
//
//   1. Вербовка. Наём был бы панелью без смысла, если бы сервер не считал
//      караул в бою. Поэтому проверяется не только «маршрут есть», но и
//      «урон караула считается тем же ходом, что урон игрока».
//   2. Панели. Тринадцать загрузчиков брали ВНЕШНИЙ div и стирали свой
//      заголовок: в index.html внутри панели лежит <h3>, а innerHTML = ...
//      заменял всех детей целиком. Заголовок пропадал при открытии каждой
//      из тринадцати панелей. Внутренние контейнеры в разметке были всегда —
//      загрузчики просто указывали не туда.
//
// ПОЧЕМУ ПРОВЕРКА ТЕКСТОВАЯ, А НЕ ПОВЕДЕНЧЕСКАЯ. Панель рисуется в браузере,
// маршрут — в express; чтобы проверить поведением, нужен либо браузерный
// стенд, либо поднятый сервер. Сегодня уже доказано обратное: поведенческая
// проверка ловит то, что текстовая не видит, — но не туда, где ошибка в том,
// что связано. Здесь ошибка в том, что названия не совпадают между файлами,
// и это единственное, что можно проверить без сервера. Боевая половина
// вербовки проверяется стендом боя (tools/combat-check.mjs) и глазом.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function читать(...путь: string[]): string {
  return readFileSync(join(корень, ...путь), 'utf-8');
}

function должен(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const ПАНЕЛИ = читать('client', 'src', 'app', 'panels.ts');
const HTML = читать('client', 'src', 'app', 'index.html');
const HUB = читать('client', 'src', 'app', 'hub.ts');
const API = читать('client', 'src', 'app', 'api.ts');
const РОУТ = читать('server', 'src', 'routes', 'soldiers.ts');
const СЕРВИС = читать('server', 'src', 'services', 'SoldierService.ts');
const ДАННЫЕ = читать('server', 'src', 'data', 'soldiers.ts');
const СОКЕТ = читать('server', 'src', 'socket', 'GameSocketHandler.ts');
const LOOP = читать('server', 'src', 'systems', 'GameLoop.ts');
const ИНДЕКС = читать('server', 'src', 'index', 'index.ts');
const МИГРАЦИЯ = читать('database', 'migrations', '078_character_soldiers.sql');

describe('Вербовка караула связана целиком', () => {
  it('все части прочитаны', () => {
    // Проверка на слепоту: если хоть один источник не прочитан, остальные
    // проверки будут «зелёные» просто потому, что искали в пустоте.
    const источники = { ПАНЕЛИ, HTML, HUB, API, РОУТ, СЕРВИС, ДАННЫЕ, СОКЕТ, LOOP, ИНДЕКС, МИГРАЦИЯ };
    for (const [имя, текст] of Object.entries(источники)) {
      должен(текст.length > 100, `${имя} не прочитан или подозрительно мал: проверка ослепла`);
    }
  });

  it('маршрут зарегистрирован и подключён', () => {
    должен(/soldiersRouter/.test(ИНДЕКС), 'роутер караула не импортирован в index.ts');
    должен(
      /app\.use\('\/api\/soldiers', soldiersRouter\)/.test(ИНДЕКС),
      'роутер караула не подключён: панель звала бы адрес, которого нет',
    );
  });

  it('проверка владения персонажем есть на всех трёх маршрутах', () => {
    // Пропустить её — значит нанять солдата за чужое золото. Стоимость
    // списывается с персонажа, а не с аккаунта.
    const маршрутов = (РОУТ.match(/soldiersRouter\.(get|post)\('/g) ?? []).length;
    должен(маршрутов === 3, `маршрутов караула ${маршрутов}, ожидалось 3`);
    должен(
      /character\.userId !== req\.userId/.test(РОУТ),
      'в роутере караула нет проверки владения: солдат нанимается за чужое золото',
    );
  });

  it('списание золота и найм солдата идут одной транзакцией', () => {
    // Ровно тот случай, из-за которого в гильдейских навыках пришлось
    // заводить миграцию 058: списание прошло, вставка нет — игрок заплатил
    // за солдата, которого не получил.
    должен(
      /this\.db\.transaction/.test(СЕРВИС),
      'наём идёт не в транзакции: оплата может пройти без найма',
    );
    // Условие в самом UPDATE, а не проверка выше: между проверкой и списанием
    // золото могло уйти на что-то ещё.
    должен(
      /WHERE id = \$1 AND gold >= \$2/.test(СЕРВИС),
      'списание не защищено условием в самом UPDATE: проверка выше успевает устареть',
    );
  });

  it('караул бьёт в бою, а не только числится в панели', () => {
    // ГЛАВНАЯ ПРОВЕРКА БЛОКА. Найм без боя — это панель, которая ничего
    // не делает и стоит денег.
    должен(
      /this\.soldiers\.ударить/.test(СОКЕТ),
      'караул не участвует в бою: панель вербовки ничего не даёт',
    );
    // После проверки досягаемости: иначе игрок бил бы через полкарты и
    // «приводил» караул с собой.
    const удар = СОКЕТ.indexOf('this.soldiers.ударить');
    const досягаемость = СОКЕТ.indexOf("code: 'out_of_reach'");
    должен(удар > 0 && досягаемость > 0, 'не нашёл ни удар караула, ни проверку досягаемости');
    должен(
      удар > досягаемость,
      'караул бьёт ДО проверки досягаемости: солдат ударит оттуда, куда игрок дотянуться не мог',
    );
  });

  it('караул забирает урон после уклонения и блока', () => {
    // Порядок, а не наличие: игрок, уклонившийся или закрывшийся щитом, не
    // должен терять здоровье солдат — иначе «уклонение» платило бы караулу.
    должен(
      /принятьУрон/.test(LOOP),
      'караул не принимает урон: он только бьёт и никогда не защищает',
    );
    const вызов = LOOP.indexOf('this.soldiers\n');
    const поглощение = LOOP.indexOf('.принятьУрон(');
    const щит = LOOP.indexOf('getIncomingMultiplier');
    должен(поглощение > 0, 'не нашёл вызов принятия урона караулом');
    должен(
      поглощение > щит,
      'караул принимает урон ДО расчёта защиты: уклонение и блок перестают спасать игрока',
    );
    должен(вызов > 0 || LOOP.includes('private soldiers'), 'в GameLoop нет поля караула');
  });

  it('доля приходит игроку отдельным пакетом', () => {
    // Клиент рисует урон по идентификатору цели. Без отдельного пакета
    // солдатские удары просто не появились бы на экране — а именно их игрок
    // и ждёт, когда платит за караул.
    должен(
      /socket\.emit\('combat:soldiers'/.test(СОКЕТ),
      'солдатские удары не отправляются клиенту: платить есть, а видеть нечего',
    );
  });

  it('солдат не умирает от одного удара', () => {
    // Игрок выбирал караул как щит. Щит, рассыпающийся от первого
    // касания, щитом не был бы: вербовка превращалась бы в повторную
    // покупку после каждой стычки.
    должен(
      /Math\.max\(1, щит\.hp - поглощено\)/.test(СЕРВИС),
      'солдат может упасть до нуля от одного удара: караул не щит',
    );
  });

  it('ограничения в данных и в миграции совпадают', () => {
    // CHECK в базе и множество в коде — две разные записи одного и того же
    // списка. Расхождение выглядело бы как «доля есть, а сервис её не знает».
    const вДанных = [...ДАННЫЕ.matchAll(/^\s{2}(levy|veteran|elite):\s*\{/gm)].map((m) => m[1]);
    должен(вДанных.length === 3, `долей в данных ${вДанных.length}, ожидалось 3`);
    for (const доля of вДанных) {
      должен(
        МИГРАЦИЯ.includes(`'${доля}'`),
        `доля ${доля} есть в коде, но не в CHECK миграции: такую долю отвергнет база`,
      );
    }
  });
});

describe('Панели не стирают собственные заголовки', () => {
  it('в index.html у каждой проверяемой панели есть заголовок и внутренний контейнер', () => {
    // Разметка обязана содержать и то и другое: заголовок, который нечего
    // стирать, и контейнер, который можно наполнять.
    const нужны = [
      ['panel-leaderboard', 'lb-content'],
      ['panel-friends', 'friends-list'],
      ['panel-chess', 'chess-content'],
      ['panel-poetry', 'poetry-content'],
      ['panel-chronicles', 'chronicles-content'],
      ['panel-achievements', 'ach-content'],
      ['panel-pets', 'pets-list'],
      ['panel-mail', 'mail-list'],
      ['panel-soldiers', 'soldiers-content'],
      ['panel-hall-of-fame', 'hall-of-fame-list'],
      ['panel-pvp', 'pvp-content'],
      ['panel-tower', 'tower-content'],
      ['panel-reputation', 'rep-content'],
    ];
    for (const [панель, контейнер] of нужны) {
      const блок = new RegExp(`<div[^>]*id="${панель}"[\\s\\S]*?<(h[1-6]|div)[^>]*id="${контейнер}"`);
      должен(
        блок.test(HTML),
        `в разметке нет пары «${панель} с заголовком и ${контейнер}»: чинить нечего`,
      );
    }
  });

  it('загрузчик берёт внутренний контейнер, а не саму панель', () => {
    // ГЛАВНАЯ ПРОВЕРКА БЛОКА. innerHTML на внешнем div заменяет всех детей
    // целиком, включая <h3>: заголовок исчезал при открытии панели.
    const внешние = [...ПАНЕЛИ.matchAll(/const box = \$\('(panel-[a-z0-9-]+)'\)/g)].map((m) => m[1]);
    должен(
      внешние.length === 0,
      `загрузчики берут саму панель, а не её контейнер: ${внешние.join(', ')}. ` +
        'innerHTML затрёт заголовок панели',
    );
  });

  it('у караула есть кнопка в хабе', () => {
    // Панель, на которую нельзя попасть, не считается панелью.
    должен(
      /id: 'panel-soldiers'/.test(HUB),
      'у панели вербовки нет кнопки в хабе: открыть её нечем',
    );
    должен(/titleKey: 'hub\.soldiers'/.test(HUB), 'кнопка вербовки без подписи');
  });

  it('методы API существуют и адрес верный', () => {
    for (const имя of ['soldiers', 'soldierHire', 'soldierDismiss']) {
      должен(
        new RegExp(`\\b${имя}:`).test(API),
        `в api нет метода ${имя}: панель зовёт его и падает`,
      );
    }
    // Адрес проверяется отдельно от формы вызова: тип ответа многострочный и
    // содержит Record<string, string>, то есть внутри него есть «>», и
    // регулярка вида `req<[^>]*>` обрывалась на нём. Это проверка не ловила
    // адрес, а проверяла тип, — то есть молча проверяла не то.
    должен(
      /`\/api\/soldiers\?characterId=/.test(API),
      'метод soldiers ходит не на /api/soldiers',
    );
    должен(
      /\/api\/soldiers\/hire/.test(API) && /\/api\/soldiers\/dismiss/.test(API),
      'адреса найма или увольнения не совпадают с роутером',
    );
  });
});