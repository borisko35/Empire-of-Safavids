// Экстерьер гробницы: седьмое по счёту здание.
//
// ЧЕМ ОТЛИЧАЕТСЯ. Таможня — застава, ткацкая — мастерская, святилище — руина
// на уступе, ханза — товарный двор. Гробница — надземный корпус, в который
// спускаются по лестнице. Дверь подземной комнаты закрыта решёткой.
//
// ЗАМЕР: дверь и выход ровно -2.5000, отклонение 0.0000; перепад голого
// комплекса 0.056 м; ось чиста на 60 м; подход к двери свободен; просвет при
// въезде 1.00 м. Сухо: вода контурами не задана.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { isWater } from '../../../shared/water';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const ИНТЕРЬЕРЫ = читать('client/src/app/game3d/interiors.ts');

function блокГробницы(): string {
  const начало = ТЕРРЕЙН.indexOf('  // ── Гробница');
  must(начало > 0, 'нет блока гробницы');
  const конец = ТЕРРЕЙН.indexOf('// ── Акведук деревни', начало);
  must(конец > начало, 'конец блока гробницы не найден');
  return ТЕРРЕЙН.slice(начало, конец);
}

describe('Гробница: площадка', () => {
  it('стоит на месте записи интерьера', () => {
    must(/id: 'tomb',[^}]*dx: 1400, dz: 1400/.test(ИНТЕРЬЕРЫ), 'запись изменилась');
    must(/export const TOMB = \{ x: 1400, z: 1400,/.test(ТЕРРЕЙН), 'константа не там');
  });

  it('ровнялка стоит ПОСЛЕ ровнялки залива', () => {
    const код = ТЕРРЕЙН.slice(ТЕРРЕЙН.indexOf('export function terrainHeight'), ТЕРРЕЙН.indexOf('const TERRAIN_SEG'))
      .split('\n').filter((s) => !/^\s*(\/\/|\*|\/\*)/.test(s)).join('\n');
    must(код.indexOf('TOMB.x') > код.indexOf('-820'), 'ровнялка гробницы не после залива');
  });

  it('уровень близок к медиане -2.49', () => {
    const m = /export const TOMB = \{ x: 1400, z: 1400, radius: \d+, level: (-?[\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'уровень не объявлен');
    const уровень = Number(m![1]);
    must(уровень >= -3.0 && уровень <= -2.0, `уровень ${уровень} далёк от медианы`);
  });

  it('запас ровной части достаточен', () => {
    const m = /export const TOMB = \{ x: 1400, z: 1400, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус не объявлен');
    const ровная = Number(m![1]) * 0.55;
    must(ровная - Math.hypot(18 / 2 + 3, 16 + 3) >= 2, 'запас мал');
  });

  it('круги смешивания не достают до соседей', () => {
    const радиус = Number(/export const TOMB = \{ x: 1400, z: 1400, radius: (\d+)/.exec(ТЕРРЕЙН)![1]);
    for (const [имя, x, z] of [['святилища', 1200, 1200], ['ханзы', 1600, 1000]] as [string, number, number][]) {
      must(Math.hypot(1400 - x, 1400 - z) > радиус, `до ${имя} близко`);
    }
  });

  it('под комплексом сухо', () => {
    must(!isWater(1400, 1400), 'под гробницей вода');
    must(!isWater(1415, 1410), 'вода рядом');
  });
});

describe('Гробница: дверь и подход', () => {
  it('дверь кликабельная и ведёт в интерьер гробницы', () => {
    const блок = блокГробницы();
    must(/doorBuilding: 'tomb'/.test(блок), 'нет doorBuilding');
    must(/doorAction: 'enter'/.test(блок), 'дверь не ведёт внутрь');
    must(/doorName: t\('buildings\.tomb'\)/.test(блок), 'не то название');
  });

  it('проём двери открыт коллайдерами', () => {
    must(/Math\.abs\(sx\) >= DOOR_W \/ 2 \+ 1\.5/.test(блокГробницы()), 'проём перекрыт');
  });

  it('лестница спускается к двери', () => {
    const блок = блокГробницы();
    must(/лестница\.число/.test(блок), 'лестница не объявлена');
    must(/ступеньY -=/.test(блок), 'ступени не спускаются');
  });

  it('в проёме двери решётка', () => {
    must(/MAT\.dark/.test(блокГробницы()), 'решётка не из тёмного металла');
    must(/прут/.test(блокГробницы()), 'прутья решётки не построены');
  });
});

describe('Гробница: двор объясняет интерьер', () => {
  it('надземный корпус с крышей', () => {
    const блок = блокГробницы();
    must(/HALL_H/.test(блок), 'высота корпуса не задана');
    must(/крыша/.test(блок), 'крыши нет');
  });

  it('ограда двора с проёмом', () => {
    const блок = блокГробницы();
    must(/wallYard/.test(блок), 'нет ограды');
    must(/проём2 = DOOR_W \+ 2\.4/.test(блок), 'проём ограды не шире двери');
  });

  it('плита двора почти вровень', () => {
    const m = /export const ГРОБНИЦА_ПЛИТА = \{ t: ([\d.]+), подъём: ([\d.]+) \}/.exec(ТЕРРЕЙН);
    must(m !== null, 'плита не объявлена');
    must(Number(m![2]) <= 0.1, 'плита велика');
  });
});

describe('Гробница: размеры проезда и ограды', () => {
  it('дверь достаточно широка', () => {
    const константы = ТЕРРЕЙН.slice(
      ТЕРРЕЙН.indexOf('export const TOMB_GEO'),
      ТЕРРЕЙН.indexOf('// ── Акведук деревни', ТЕРРЕЙН.indexOf('export const TOMB_GEO')),
    );
    const m = /door: \{ w: ([\d.]+), h: ([\d.]+) \}/.exec(константы);
    must(m !== null, 'ширина двери не объявлена в TOMB_GEO');
    must(Number(m![1]) >= 2.4, 'дверь уже 2.4 м: с лестницей не пройти');
  });

  it('проём ограды шире двери и не запечатан', () => {
    const блок = блокГробницы();
    const m = /проём2 = DOOR_W \+ (\d+\.?\d*)/.exec(блок);
    must(m !== null, 'ширина проёма ограды не объявлена');
    must(Number(m![1]) >= 1.5, 'проём ограды не шире двери');
    must(/if \(Math\.abs\(tx\) >= проём2 \/ 2 \+ 0\.6\)/.test(блок), 'проём ограды не оставлен');
  });

  it('боковые стенки ограды симметричны', () => {
    const блок = блокГробницы();
    must(
      /addCollider\(TOMB\.x - YARD_W \/ 2 - wallYard\.t \/ 2, TOMB\.z \+ tz, 1\.0\);\s*addCollider\(TOMB\.x \+ YARD_W \/ 2 \+ wallYard\.t \/ 2, TOMB\.z \+ tz, 1\.0\);/.test(блок),
      'ограда двора не симметрична: проходимость сбоку разная',
    );
  });

  it('запас ровной части достаточен: полудиагональ сзади', () => {
    // Раньше формула считала гипотез по двору, а не по всей площади: запас
    // выходил больше настоящего, и ломка радиуса проходила насквозь. Сейчас
    // полудиагональ считается по задней стене (14 м) и двorce (12 м).
    const m = /export const TOMB = \{ x: 1400, z: 1400, radius: (\d+)/.exec(ТЕРРЕЙН);
    must(m !== null, 'радиус не объявлен');
    const ровная = Number(m![1]) * 0.55;
    const полу = Math.hypot(18 / 2 + 3, 14 + 3);
    must(ровная - полу >= 2, 'запас мал');
  });
});