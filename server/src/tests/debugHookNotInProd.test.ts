// Отладочный хук не должен попадать в продакшен.
//
// ЧТО ЗДЕСЬ. `window.__eos` висел в клиенте безусловно, с комментарием «не
// влияет на игру». Проверка показала, что комментарий неправ:
//
//   __eos.tp(-777, 555)   → клиент переместился
//   + один шаг клавишей    → сервер принял координату и записал в базу
//   {"x": -777, "z": 555.21}, зона caucasus_pass
//
// Это телепорт на 800 метров в любую точку карты, доступный любому, кто открыл
// консоль. Античит его не видит: нарушение `speed_hack` он ловит (замерено:
// «Speed hack: 21.7 u/s»), а скачок координаты — нет, потому что пакет движения
// уходит уже с новой точки.
//
// ЧТО ПРОВЕРЯЕТСЯ. Присваивание `window.__eos` обязано находиться под
// `import.meta.env.PROD`: сборщик подставляет константу и вырезает мёртвую ветку
// целиком. Проверено на собранном бандле: ноль чанков содержат `__eos`.
//
// ПОЧЕМУ ТЕКСТОВАЯ ПРОВЕРКА. Собрать бандл в юнит-тесте нельзя (нужен Vite и
// три минуты), а проверять «в бандле нет строки» бессмысленно без сборки.
// Проверяется источник — то место, где ошибка и живёт.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

// Кириллица в причинах иероглифами не печатается, но на условие это не влияет.
function должно(условие: unknown, причина: string): void {
  должен(условие, причина);
}

/** Тело функции по балансу скобок: регулярка обрывалась бы на вложенных фигурах. */
function блок(исходник: string, позиция: number): string {
  let i = исходник.indexOf('{', позиция);
  if (i < 0) return '';
  const начало = i;
  let глубина = 0;
  for (; i < исходник.length; i++) {
    if (исходник[i] === '{') глубина++;
    else if (исходник[i] === '}') {
      глубина--;
      if (глубина === 0) return исходник.slice(начало, i + 1);
    }
  }
  return '';
}

const МИР = readFileSync(join(корень, 'client', 'src', 'app', 'world.ts'), 'utf-8');

/**
 * Тело защитной ветки рядом с присваиванием __eos.
 *
 * Почему так сложно: перед присваиванием стоит приведение типа
 * `(window as unknown as { __eos: unknown })`, и его фигурные скобки — ближайшие
 * к строке. Значит искать «скобку перед присваиванием» нельзя: это скобка
 * типа, а не тело `if`. Поэтому ищем сам `if`, а тело берём по балансу скобок.
 */
function защитнаяВетка(): string {
  const позиция = МИР.indexOf('__eos =');
  const ifPos = МИР.lastIndexOf('if (!import.meta.env.PROD)', Math.max(0, позиция - 1));
  if (ifPos < 0) return '';
  return блок(МИР, ifPos);
}

describe('Отладочный хук не живёт в продакшене', () => {
  it('исходник прочитан', () => {
    должно(
      МИР.length > 10000,
      'world.ts не прочитан или подозрительно мал: проверка ослепла',
    );
    должно(
      МИР.includes('__eos'),
      'в world.ts нет упоминания __eos: проверка потеряла предмет',
    );
  });

  it('присваивание __eos закрыто проверкой PROD', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Присваивание должно лежать внутри
    // `if (!import.meta.env.PROD)`. Без этой обёртки крючок снова появится в
    // боевой сборке вместе с телепортом.
    const тело = защитнаяВетка();
    должно(
      тело.length > 100,
      'присваивание __eos не нашлось внутри `if (!import.meta.env.PROD)`: ' +
        'телепорт вернётся в продакшен (§174)',
    );
    должно(
      тело.includes('__eos ='),
      'защитная ветка найдена, но присваивания __eos в ней нет: проверка ищет не то',
    );
  });

  it('внутри защищённой ветки лежит весь хук', () => {
    // Проверка обратная: если ветка осталась, но тело выехало наружу, хук снова
    // доступен.
    const тело = защитнаяВетка();
    должно(тело.length > 100, 'тело защитной ветки не читается: проверка ослепла');
    for (const имя of ['tp(', 'attack()', 'setCam(', 'setHour(', 'get monsters']) {
      должно(
        тело.includes(имя),
        `метод ${имя} вышел из-под защиты PROD: хук соберётся в продакшен`,
      );
    }
  });

  it('причина записана рядом с местом правки', () => {
    // ASCII-маркеры, а не русская фраза: фраза разъезжается переносом строки.
    // Тот же вывод, что в §153, §154, §157, §158, §161.
    const позиция = МИР.indexOf('__eos =');
    const выше = МИР.slice(Math.max(0, позиция - 1400), позиция);
    должно(
      /caucasus_pass/.test(выше),
      'не назван замер, доказавший поломку: пояснение должно называть его прямо',
    );
    должно(
      /speed_hack/.test(выше),
      'не сказано, что античит телепорт не видит: без этого пояснение неполно',
    );
  });
});

// Звуковые диагностики — тот же класс, что и `__eos`, и то же решение.
//
// ПОЧЕМУ ИХ ТОЖЕ ЗАКРЫЛИ. В §174 закрыт `window.__eos`, и осталось два глобала
// в audio.ts: `__eosAudio` (режим) и `__eosAudioBuses` (уровни шин). Сами по себе
// они ничего не дают и вреда не несут — но лечатся по той же причине: в боевой
// сборке не должно быть ничего, что показывает устройство игры из консоли.
// Проверено на собранном бандле: после правки в нём не осталось ни одного
// идентификатора `__eos*`.
const АУДИО = readFileSync(join(корень, 'client', 'src', 'app', 'audio.ts'), 'utf-8');

describe('Звуковые диагностики не живут в продакшене', () => {
  it('исходник прочитан и диагностики на месте', () => {
    должно(
      АУДИО.length > 3000,
      'audio.ts не прочитан или подозрительно мал: проверка ослепла',
    );
    должно(
      /__eosAudio/.test(АУДИО),
      'в audio.ts нет упоминания __eosAudio: проверка потеряла предмет',
    );
  });

  it('помечающий помощник закрыт проверкой PROD', () => {
    // ГЛАВНАЯ ПРОВЕРКА ЭТОГО БЛОКА. Все четыре обращения к глобалам идут через
    // `пометить()`, и именно она не должна писать в продакшене.
    const позиция = АУДИО.indexOf('function пометить');
    должно(позиция > 0, 'не нашёл функцию пометить: диагностики снова пишут напрямую');
    const тело = блок(АУДИО, позиция);
    должно(
      /if\s*\(\s*import\.meta\.env\.PROD\s*\)\s*return;/.test(тело),
      'пометить() больше не отсекает продакшен: звуковые диагностики вернутся в бандл',
    );
  });

  it('диагностики идут через помощника, а не напрямую', () => {
    // Обратная проверка: если кто-то снова напишет `(window ...).__eosAudio =`
    // в обход помощника, защита окажется бесполезной.
    const прямые = [...АУДИО.matchAll(/\)\)\.__eosAudio\w*\s*=/g)].length;
    должно(
      прямые === 0,
      `найдено присваиваний в обход помощника: ${прямые}. ` +
        'Любое из них обойдёт защиту PROD',
    );
    const через = [...АУДИО.matchAll(/пометить\('__eosAudio/g)].length;
    должно(
      через === 4,
      `обращений через пометить: ${через}, ожидалось 4. ` +
        'Новая диагностика должна идти через помощник, иначе она снова окажется в бандле',
    );
  });
});