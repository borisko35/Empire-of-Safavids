// Иконки и описания предметов: данные говорили, а рисовать было нечего.
//
// ЧТО БЫЛО. Поле iconPath есть у 80 предметов в ITEMS_DATABASE, description —
// у 79. И то и другое не доходило до клиента: getInventory() и getEquipment()
// отдавали только имя, редкость и число. Также не читались iconPath у ездовых
// животных и лодок (11 путей).
//
// ГЛАВНАЯ НАХОДКА. Пути ведут в никуда: В ПРОЕКТЕ НЕТ НИ ОДНОГО .png ПО НИМ
// И НЕТ ПАПКИ icons. То есть это объявленный, но не созданный арт — а не
// сломанный путь. Проверка требует и того, чтобы поля доходили, и того, чтобы
// клиент НЕ ПОКАЗЫВАЛ БИТУЮ КАРТИНКУ при их отсутствии: без заглушки каждый
// игрок видел бы битые картинки в каждой строке сумки.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { existsSync } from 'node:fs';
import { stripComments } from './helpers/stripCode';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');
const есть = (p: string): boolean => existsSync(join(корень, p));
const код = (p: string): string => stripComments(читать(p));

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const предметы = читать('server/src/data/items.ts');
const сервис = код('server/src/services/CharacterService.ts');
const апи = код('client/src/app/api.ts');
const худ = код('client/src/app/hud.ts');
const стили = читать('client/src/app/styles.css');

describe('Иконки и описания доходят до клиента', () => {
  it('данные вообще заполнены', () => {
    // Без этой проверки тест был бы страховкой от воображаемой проблемы:
    // если iconPath есть у одного предмета, всё остальное не имеет смысла.
    const путей = (предметы.match(/iconPath:/g) ?? []).length;
    must(путей >= 50, `iconPath заполнен у ${путей} предметов — проверять нечего`);
    const описаний = (предметы.match(/description:/g) ?? []).length;
    must(описаний >= 50, `description заполнен у ${описаний} предметов`);
  });

  it('оба ответа отдают и то и другое', () => {
    must(/iconPath: def\?\.iconPath/.test(сервис), 'инвентарь не отдаёт иконку');
    must(/description: def\?\.description/.test(сервис), 'инвентарь не отдаёт описание');
    // Два места: сумка и экипировка. Забытое второе — та же болезнь, только
    // в панели персонажа.
    must(
      (сервис.match(/iconPath: def\?\.iconPath/g) ?? []).length >= 2,
      'иконка отдаётся только из одного ответа: экипировка осталась без неё',
    );
  });

  it('клиент объявил поля в типах', () => {
    // Без объявления TS отказал бы на it.iconPath, и нарисовать иконку было бы
    // нельзя даже при живых данных на сервере.
    must(/iconPath\?: string; description\?: string/.test(апи), 'в типе инвентаря нет иконки и описания');
    must(
      /iconPath\?: string; description\?: string/.test(апи.replace(/[^\n]*inventory[^\n]*/, '')),
      'в типе экипировки нет иконки и описания',
    );
  });
});

describe('Клиент рисует, и не показывает битые картинки', () => {
  it('описание показывается', () => {
    must(/if \(it\.description\) row\.title = it\.description;/.test(худ),
      'описание не показывается: игрок по-прежнему видит только имя и число');
  });

  it('иконка рисуется с обработчиком ошибки', () => {
    must(/картинка\.src = `\/assets\/\$\{it\.iconPath\}`/.test(худ), 'иконка не рисуется');
    // Заглушка обязательна: путей-то в проекте нет (см. ниже), и без неё
    // каждый игрок видел бы битые картинки в каждой строке сумки.
    must(
      /картинка\.addEventListener\('error'/.test(худ),
      'у иконки нет обработчика ошибки: при отсутствии файла игрок увидит битую картинку',
    );
    // Вызов внутри обработчика, а не существование функции. Проверка на имя
    // функция проходила бы, когда вызов убран и осталось только definition:
    // заглушка есть в файле и не показывается — проверка зелёная.
    const начало = худ.indexOf("картинка.addEventListener('error'");
    must(начало > 0, 'обработчик ошибки пропал');
    const обработчик = худ.slice(начало, худ.indexOf('});', начало));
    must(
      /replaceWith\(заглушкаПредмета\(/.test(обработчик),
      'обработчик ошибки не подставляет заглушку: игрок увидит битую картинку или пустое место',
    );
  });

  it('заглушка не пустая', () => {
    // Пустое место рядом с настоящими иконками, когда арт появится, смотрелось
    // бы дыркой.
    const блок = худ.slice(худ.indexOf('function заглушкаПредмета'), худ.indexOf('function заглушкаПредмета') + 700);
    must(/inv-icon-fallback/.test(блок), 'заглушка без собственного класса — ей нечем отличаться');
    must(/RARITY_COLOR\[редкость\]/.test(блок), 'заглушка не подкрашена редкостью');
    must(/charAt\(0\)\.toUpperCase\(\)/.test(блок), 'в заглушке нет буквы предмета');
  });

  it('у иконки есть размеры в стилях', () => {
    must(/\.inv-icon \{/.test(стили), 'у иконки нет размеров: строка инвентаря прыгает под загрузку');
    must(/\.inv-icon-fallback \{/.test(стили), 'у заглушки нет размеров');
  });
});

describe('Арт иконок: правда о его отсутствии', () => {
  it('пути ведут в файлы, которых нет', () => {
    // ЭТА ПРОВЕРКА ФИКСИРУЕТ ПРАВДУ, А НЕ ТРЕБУЕТ ЕЁ СКРЫТЬ.
    //
    // Раньше iconPath был нечитаемым полем, и казалось, что иконки работают.
    // Теперь они рисуются с заглушкой, но САМОГО АРТА НЕТ: ни одной .png по
    // этим путям, ни папки icons. Когда арт добавят, обе части этого файла
    // останутся правдой: заглушка просто перестанет показываться.
    //
    // Проверка требует, чтобы этого положения дел не скрыли: сказать «иконки
    // работают», имея на руке заглушки, было бы той же ложью.
    const первый = (/iconPath: '([^']+)'/.exec(предметы) ?? [])[1];
    must(!!первый, 'не удалось вычитать ни одного пути');
    must(!есть(`client/web/assets/${первый}`), 'первая иконка нашлась: проверка устарела, пересмотрите оба блока');
  });
});