// Мировая карта: значки, названия регионов и подписи поселений не наезжают.
//
// ЧТО ПОКАЗАЛ ВЛАДЕЛЕЦ. На мировой карте города, поселения, их названия и значки
// наваливаются друг на друга.
//
// ЗАМЕР ДО ПОЧИНКИ. Холст 900 пикселей, масштаб 0.1417 пикселя на единицу. Ближайшие
// пары поселений:
//
//   Шираз — Кавказ               23px   подписи наезжают
//   Хорасан — Кавказ             30px   подписи наезжают
//   Тебриз — Месопотамия         35px   подписи наезжают
//   Месопотамия — Персидский     44px   подписи наезжают
//   Тебриз — Персидский залив    46px   подписи наезжают
//
// Иконки между собой не пересекались: ближайшая пара 23 пикселя при иконке 16.
// Значит наезжали подписи, и значки с подписями. Причин было четыре, и все в коде:
//
//   1. ДВА НЕЗАВИСИМЫХ СПИСКА ЗАНЯТОСТИ. Названия регионов копятся при сборке слоя
//      карты, подписи поселений — при отрисовке, и спискам не известно друг о друге.
//      Название региона ложилось поверх названия города.
//   2. ЗНАЧКИ НЕ ОТМЕЧАЛИСЬ ВООБЩЕ. Подпись соседнего города ложилась на значок.
//   3. ШИРИНА ПОДПИСИ МЕРЯЛАСЬ ШРИФТОМ ЗНАЧКА: стоял font 16px, а подпись рисуется
//      bold 12px. Прямоугольник выходил на треть шире настоящего, подписи
//      расходились дальше нужного, а в тесных местах часть названий молча пропадала.
//   4. ТОЛЬКО ВЕРТИКАЛЬНЫЕ СДВИГИ. У поселений на одной горизонтали они
//      исчерпывались быстро.
//
// ЧТО ПРОВЕРЯЕТСЯ. Повторяется вся расстановка кода целиком и в том же порядке
// рисования: значки, названия регионов, подписи поселений. Требуется, чтобы всё
// нарисованное не пересекалось между собой и чтобы города не молчали.
//
// ЧТО НЕ ЯВЛЯЕТСЯ НАЕЗДОМ. Занятый столбец или занятая позиция сдвига — не наезд:
// код берёт следующую, а если все заняты, название просто не рисуется. Первая
// версия этой проверки записывала в наезды каждую неудачную попытку и «нашла»
// 18 наездов, которых в игре быть не может: отмеченный прямоугольник по построению
// не пересекается с уже отмеченными. Наезд — это когда нарисованное перекрыло
// нарисованное, и это проверяется в самом конце перебором всех пар.
//
// О ШИРИНЕ ПОДПИСЕЙ. measureText требует DOM, в серверной проверке недоступен,
// поэтому ширина оценивается по кеглю и длине названия. Оценка заведомо щедрая:
// если при ней места хватает, то при настоящем шрифте хватит и подавно.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ZONES } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const HUD = читать('client/src/app/hud.ts');
const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');

// Размер холста берём из собранной разметки, как это уже делает mapLabels.test.ts:
// иначе проверка считала бы по холсту, которого в игре уже нет.
const РАЗМЕТКА = читать('client/web/game/index.html');
const размер = /<canvas id="worldmap-canvas" width="(\d+)" height="(\d+)"/.exec(РАЗМЕТКА);
must(размер !== null, 'не нашёл canvas карты мира в собранной разметке — проверка не знает, на чём считать');
const W = Number(размер![1]);
const H = Number(размер![2]);

const ПОЛМИРА = Number(/export const WORLD_HALF = (\d+);/.exec(ТЕРРЕЙН)?.[1]);
must(Number.isFinite(ПОЛМИРА) && ПОЛМИРА > 0, 'не прочитал WORLD_HALF из terrain.ts — проверка ничего не меряет');

const масштаб = Math.min(W, H) / (ПОЛМИРА * 2);
const toPx = (wx: number, wz: number) => ({ x: W / 2 + wx * масштаб, y: H / 2 + wz * масштаб });

/** Ширина слова: настоящая меряется measureText, тут — оценка сверху. */
const ширинаСлова = (слово: string, кегль: number): number => слово.length * кегль * 0.62;

type Пр = { x1: number; y1: number; x2: number; y2: number; чей: string };

/** Поселения ровно те, что собирает MINIMAP_SETTLEMENTS в hud.ts. */
function поселения(): { имя: string; x: number; z: number }[] {
  const городаРегионов = [...ТЕРРЕЙН.matchAll(/\{ region: '([a-z_]+)', x: (-?\d+), z: (-?\d+)/g)]
    .map((м) => ({ имя: `город ${м[1]}`, x: Number(м[2]), z: Number(м[3]) }));
  // Девять, а не десять: столицу Исфахана строит buildCity, а не buildRegionTowns.
  must(
    городаРегионов.length === 9,
    `городов регионов в terrain.ts ${городаРегионов.length}, а ожидалось 9 — вид данных изменился`
  );
  const старые = [...ТЕРРЕЙН.matchAll(/export const (CITY|CAMP|PORT|CARAVANSERAI|VILLAGE|FORT)\b[^=]*=\s*\{[^}]*?x:\s*(-?\d+),\s*z:\s*(-?\d+)/g)]
    .map((м) => ({ имя: м[1], x: Number(м[2]), z: Number(м[3]) }));
  must(
    старые.length === 6,
    `старых поселений прочитано ${старые.length}, а ожидалось 6 — вид констант в terrain.ts изменился`
  );
  return [...городаРегионов, ...старые];
}

// Радиус значка — 12 пикселей диаметром, подобран по самой тесной паре поселений:
// при холсте 900x600 Шираз и Кавказ стоят в 15.4 пикселя друг от друга, и значок
// 16 пикселей шире промежутка — два значка всегда ложились друг на друга.
const ЗНАЧОК_РАДИУС = 6;
const КЕГЛЬ_ПОДПИСИ = 12;
const СДВИГИ = [12, -12, 24, -24, 36, -36, 48, -48, 60, -60, 72, -72, 84, -84, 96, -96, 108, -108];
const СТОЛБЦЫ = [W / 2, W * 0.25, W * 0.75, W * 0.12, W * 0.88];

function расставить(): {
  прямоугольники: Пр[];
  наезды: string[];
  нанесеноРегионов: number;
  всегоРегионов: number;
} {
  const прямоугольники: Пр[] = [];
  const отметить = (пр: Пр): void => {
    прямоугольники.push(пр);
  };
  const занято = (пр: Пр): boolean =>
    прямоугольники.some((д) => пр.x1 < д.x2 && пр.x2 > д.x1 && пр.y1 < д.y2 && пр.y2 > д.y1);

  // 1. Значки поселений. Рисуются всегда: где город — это факт, а как он
  //    называется — можно прочесть в подсказке. Место занимают сразу.
  for (const поселение of поселения()) {
    const { x, y } = toPx(поселение.x, поселение.z);
    отметить({
      x1: x - ЗНАЧОК_РАДИУС,
      y1: y - ЗНАЧОК_РАДИУС + 6,
      x2: x + ЗНАЧОК_РАДИУС,
      y2: y + ЗНАЧОК_РАДИУС + 6,
      чей: `значок ${поселение.имя}`,
    });
  }

  // 2. Названия регионов: пять столбцов, кегль от меньшей стороны полосы.
  //
  // Полоса, у которой в регионе есть город, названием НЕ помечается: города
  // регионов подписаны ключом `regions.<регион>` — тем же, что и полоса. Без
  // такой проверки каждое название писалось дважды: крупно бледным по полосе и
  // мелким чётким у города.
  const регионы = [...new Set(ZONES.map((з) => з.region))];
  const города = new Set(поселения().map((п) => `regions.${п.имя.replace('город ', '')}`));
  let нанесеноРегионов = 0;
  for (const регион of регионы) {
    if (города.has(регион)) continue;
    const зоны = ZONES.filter((з) => з.region === регион);
    const z1 = Math.min(...зоны.map((з) => з.bounds.z1));
    const z2 = Math.max(...зоны.map((з) => з.bounds.z2));
    const левый = toPx(-ПОЛМИРА, z1).x;
    const правый = toPx(ПОЛМИРА, z2).x;
    const верх = toPx(0, z1).y;
    const низ = toPx(0, z2).y;
    const ширинаПолосы = Math.abs(правый - левый);
    const высотаПолосы = Math.abs(низ - верх);
    const кегль = Math.max(9, Math.min(20, Math.round(Math.min(ширинаПолосы, высотаПолосы) - 4)));
    const надпись = регион;
    const половина = ширинаСлова(надпись, кегль) / 2 + 4;
    const y = (верх + низ) / 2;
    const центр = (левый + правый) / 2;
    const кандидаты = [центр, ...СТОЛБЦЫ.filter((с) => с >= левый + половина && с <= правый - половина)];
    for (const столбец of кандидаты) {
      const пр: Пр = {
        x1: столбец - половина,
        y1: y - кегль,
        x2: столбец + половина,
        y2: y + кегль * 0.4,
        чей: `название региона ${надпись}`,
      };
      if (пр.x1 < 2 || пр.x2 > W - 2) continue;
      if (занято(пр)) continue;
      отметить(пр);
      нанесеноРегионов++;
      break;
    }
  }

  // 3. Подписи поселений: сначала вверх-вниз, потом вбок.
  for (const поселение of поселения()) {
    const { x, y } = toPx(поселение.x, поселение.z);
    const половина = ширинаСлова(`поселение ${поселение.имя}`, КЕГЛЬ_ПОДПИСИ) / 2 + 3;
    let пр: Пр | null = null;
    for (const сдвиг of СДВИГИ) {
      const проба = y - сдвиг;
      const прям: Пр = {
        x1: x - половина, y1: проба - 11, x2: x + половина, y2: проба + 4,
        чей: `подпись ${поселение.имя}`,
      };
      if (проба < 12 || проба > H - 4) continue;
      if (занято(прям)) continue;
      пр = прям;
      break;
    }
    if (!пр) {
      // Запасные позиции — как в коде: четыре высоты и шесть смещений вбок.
      const вбок = Math.ceil(половина) + 8;
      const смещения = [вбок, -вбок, вбок * 2, -вбок * 2, вбок * 3, -вбок * 3];
      for (const высота of [-14, -32, -50, 18]) {
        for (const шаг of смещения) {
          const пробаX = x + шаг;
          if (пробаX - половина < 2 || пробаX + половина > W - 2) continue;
          const прям: Пр = {
            x1: пробаX - половина, y1: y + высота - 12,
            x2: пробаX + половина, y2: y + высота + 2,
            чей: `подпись ${поселение.имя}`,
          };
          if (занято(прям)) continue;
          пр = прям;
          break;
        }
        if (пр) break;
      }
    }
    if (пр) отметить(пр);
  }

  // Наезд — это когда нарисованное перекрыло нарисованное. Перебором всех пар:
  // иначе проверка доказывала бы сама себя, ведь отметка идёт только после
  // проверки занятости.
  const наезды: string[] = [];
  for (let i = 0; i < прямоугольники.length; i++) {
    for (let j = i + 1; j < прямоугольники.length; j++) {
      const a = прямоугольники[i];
      const b = прямоугольники[j];
      if (a.x1 < b.x2 && a.x2 > b.x1 && a.y1 < b.y2 && a.y2 > b.y1) {
        наезды.push(`${a.чей} налезает на «${b.чей}»`);
      }
    }
  }

  return { прямоугольники, наезды, нанесеноРегионов, всегоРегионов: регионы.length - [...города].filter((р) => регионы.includes(р)).length };
}

describe('Мировая карта: наложение подписей и значков', () => {
  it('нарисованное не перекрывает нарисованное', () => {
    const { наезды } = расставить();
    must(наезды.length === 0, `наездов осталось ${наезды.length}: ${наезды.join('; ')}`);
  });

  it('города и их названия показываются, а не молчат', () => {
    const { прямоугольники, нанесеноРегионов, всегоРегионов } = расставить();
    const всего = поселения().length;
    const значков = прямоугольники.filter((п) => п.чей.startsWith('значок')).length;
    const подписей = прямоугольники.filter((п) => п.чей.startsWith('подпись')).length;
    must(значков === всего, `значков ${значков} при ${всего} городах: часть исчезла`);
    // Подпись может не поместиться — это осознанно, значок важнее. Но молчать не
    // должна вся карта: раньше часть названий терялась из-за неверного шрифта при
    // замере, и это выглядело как «карта не работает».
    must(
      подписей >= всего - 1,
      `подписей поселений ${подписей} при ${всего} городах: почти все названия потеряны`
    );
    // Названия регионов — фон, они могут кончиться. Но не все: карта без них
    // превращается в сетку с точками.
    must(
      нанесеноРегионов >= всегоРегионов - 1,
      `названий регионов нанесено ${нанесеноРегионов} из ${всегоРегионов}`
    );
  });

  it('названия регионов не уезжают на край холста', () => {
    const { прямоугольники } = расставить();
    for (const пр of прямоугольники) {
      must(
        пр.x1 >= 0 && пр.x2 <= W,
        `${пр.чей} выходит за левый или правый край карты: x от ${пр.x1.toFixed(0)} до ${пр.x2.toFixed(0)} при ширине ${W}`
      );
      must(
        пр.y1 >= 0 && пр.y2 <= H,
        `${пр.чей} выходит за верхний или нижний край карты: y от ${пр.y1.toFixed(0)} до ${пр.y2.toFixed(0)} при высоте ${H}`
      );
    }
  });
});

describe('Мировая карта: причины наездов устранены в коде', () => {
  it('у обеих надписей один список занятости, а не два', () => {
    // Два независимых списка и были причиной: названия регионов и подписи
    // поселений не знали друг о друге.
    must(
      /const занятыеПодписи: Прямоугольник\[\] = \[\.\.\.мировыеНазванияРегионов\]/.test(HUD),
      'подписи поселений начинают с пустого списка и не знают названий регионов: наезд вернётся'
    );
    must(
      /мировыеНазванияРегионов\.push\(прямоугольник\)/.test(HUD),
      'прямоугольники названий регионов не сохраняются наружу: подписи их не увидят'
    );
  });

  it('значок занимает место: подпись не ляжет на него', () => {
    must(
      /ctx\.fillText\(s\.icon[\s\S]{0,260}занятыеПодписи\.push/.test(HUD),
      'значок не отмечается в списке занятых мест'
    );
  });

  it('ширина подписи меряется тем шрифтом, которым рисуется', () => {
    must(
      /ctx\.font = 'bold 12px sans-serif';\s*\r?\n\s*const половинаШирины = ctx\.measureText/.test(HUD),
      'перед замером ширины нет шрифта подписи: прямоугольник выходит неверным'
    );
    must(
      !/ctx\.font = '16px sans-serif';\s*\r?\n\s*const половинаШирины/.test(HUD),
      "перед замером ширины стоит шрифт значка 16px, а подпись рисуется 12px"
    );
  });

  it('горизонтальный запас есть: вертикаль на горизонтали кончается', () => {
    must(
      /const вбок = Math\.ceil\(половинаШирины\) \+ 8;/.test(HUD),
      'нет горизонтального запасного сдвига: поселения на одной горизонтали останутся без подписей'
    );
  });

  it('значок по-прежнему важнее подписи', () => {
    // Из этого правила mapLabels.test.ts уже есть проверка, но и здесь стоит
    // помнить: при нехватке места пропадать должна подпись, а не город.
    must(
      HUD.includes('if (yПодписи === null) continue;'),
      'в коде нет отказа от подписи — она ляжет поверх соседней'
    );
  });

  it('значок по размеру промежутка между городами, а не на глаз', () => {
    // При холсте 900x600 ближайшие города стоят в 15.4 пикселя друг от друга.
    // Значок шире этого промежутка — и два значка всегда ложились друг на друга.
    // Размер берётся из кода, чтобы правка шрифта не разъехалась с прямоугольником.
    const радиус = Number(/const ЗНАЧОК_РАДИУС = (\d+);/.exec(HUD)?.[1]);
    must(Number.isFinite(радиус), 'не нашёл ЗНАЧОК_РАДИУС в коде карты');
    const шрифтЗначка = Number(/ctx\.font = '(\d+)px sans-serif';[\s\S]{0,80}ctx\.fillText\(s\.icon/.exec(HUD)?.[1]);
    must(
      Number.isFinite(шрифтЗначка),
      'не нашёл шрифт значка на карте мира',
    );
    // Самая тесная пара на настоящих данных.
    let ближайшая = Infinity;
    const все = поселения();
    for (let i = 0; i < все.length; i++) {
      for (let j = i + 1; j < все.length; j++) {
        const a = toPx(все[i].x, все[i].z);
        const b = toPx(все[j].x, все[j].z);
        ближайшая = Math.min(ближайшая, Math.hypot(a.x - b.x, a.y - b.y));
      }
    }
    must(
      радиус * 2 < ближайшая,
      `значок занимает ${радиус * 2}px, а ближайшие города стоят в ${ближайшая.toFixed(1)}px: ` +
        'значки снова лягут друг на друга'
    );
    // Шрифт и прямоугольник должны быть одного размера: разъехались — наезд вернётся
    // либо появится пустое место вокруг каждого значка.
    must(
      шрифтЗначка <= радиус * 2,
      `шрифт значка ${шрифтЗначка}px шире отведённого прямоугольника ${радиус * 2}px`
    );
  });

  it('название региона не пишется дважды: у города оно уже есть', () => {
    must(
      /MINIMAP_SETTLEMENTS\.some\(\(s\) => s\.nameKey === `regions\.\$\{полоса\.region\}`\)/.test(HUD),
      'полоса рисует название, даже когда в регионе есть город с тем же именем: ' +
        'каждое названиеRegion попадёт на карту дважды'
    );
  });
});