// Двор мечети снаружи: подход, кипарисы, фонари.
//
// ЧТО БЫЛО (21 октября 2026, §243). Мечеть стояла на голом песке: к воротам
// приходилось идти по песку, и место читалось как модель, поставленная в
// пустыню.
//
// ПЕРВАЯ ВЕРСИЯ ПРАВКИ БЫЛА НЕ ТОЙ: ограда внутри двора. Замер показал,
// что модель занимает x −30…−10 и z −485…−470, то есть ограда оказывалась
// ВНУТРИ модели и её не было видно. Правило теперь проверяет то, что видно.
//
// ЧТО ПРОВЕРЯЕТСЯ. К воротам ведёт мостовая, по сторонам стоят кипарисы и
// два фонаря.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const код = ТЕРРЕЙН.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

describe('Двор мечети снаружи', () => {
  it('к воротам ведёт мостовая', () => {
    должен(
      /const подход = new THREE\.Mesh\(\s*new THREE\.BoxGeometry\(6\.0, 0\.14, 16\.0\),\s*MAT\.sandstoneDark,?\s*\)/.test(
        код,
      ),
      'к воротам мечети нет мостовой: подход идёт по песку',
    );
    // Подход — со стороны ворот (+z у двора).
    должен(/подход\.position\.set\(c\.x, 0\.07, c\.z \+ hz \+ 8\)/.test(код), 'мостовая положена не к воротам');
  });

  it('по сторонам подхода кипарисы, у входа фонари', () => {
    должен(
      /кронаКипариса\(scene, x, groundHeight\(x, z\), z, 0\.85 \+ i \* 0\.1, MAT\.foliageDark\)/.test(
        код,
      ),
      'по сторонам подхода нет кипарисов',
    );
    // Кипарисы стоят по настоящей земле.
    должен(/кронаКипариса\(scene, x, groundHeight\(x, z\)/.test(код), 'кипарисы не по земле');
    должен(
      /const огонь = new THREE\.Mesh\(new THREE\.SphereGeometry\(0\.18, 8, 6\), MAT\.lampGlow\)/.test(код),
      'у входа нет фонарей с огнём',
    );
  });
});
