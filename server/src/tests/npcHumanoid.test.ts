// NPC-персонажи перестают быть ящиками.
//
// ЧТО БЫЛО (22 октября 2026, §288). Персонажи, которых ставит buildHumanoid
// (стражи у ворот, квестовые NPC, жители городов регионов, портовые и
// горные), были собраны из коробок: грудь — ящик 0.42×0.56×0.26, рука —
// ящик 0.12×0.56×0.13, нога — ящик 0.16×0.95×0.19. Силуэт читался как
// каркас, а не как человек в халате.
//
// ЧТО ТЕПЕРЬ. Грудь — округлая, с плечами, воротником и перевязью через
// грудь; руки — сужающиеся, с манжетой; ноги — сужающиеся, сапог с округлым
// носком; юбка халата с подгибом по краю.
//
// ЧТО ПРОВЕРЯЕТСЯ. В rig.ts нет ящиков вместо тела, рук и ног, а детали
// (плечи, воротник, перевязь, манжета, носок, подгиб) на месте.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РИГ = читать('client/src/app/game3d/rig.ts');

describe('NPC-персонажи — не ящики', () => {
  it('грудь — округлая, с плечами, воротником и перевязью', () => {
    // Грудь — цилиндр, а не ящик.
    должен(
      /const chest = cyl\(0\.21, 0\.17, 0\.56, robe, 12\);/.test(РИГ),
      'грудь персонажа — ящик',
    );
    // Плечи.
    должен(/const плечоЛ = sphere\(0\.105, robe, 10\);/.test(РИГ), 'у персонажа нет плеч');
    // Воротник.
    должен(/const ворот = cyl\(0\.115, 0\.125, 0\.08, robeDark, 10\);/.test(РИГ), 'у персонажа нет воротника');
    // Перевязь через грудь.
    должен(/const перевязь = box\(0\.07, 0\.62, 0\.3, robeDark\);/.test(РИГ), 'нет перевязи');
    должен(/перевязь\.rotation\.z = 0\.42;/.test(РИГ), 'перевязь не положена наискось');
    // И всё это в torso.
    должен(
      /torso\.add\(chest, плечоЛ, плечоП, ворот, belt, перевязь\);/.test(РИГ),
      'детали торса не добавлены в тело',
    );
    // Ящика вместо груди быть не должно.
    должен(!/const chest = box\(0\.42, 0\.56, 0\.26, robe\);/.test(РИГ), 'грудь снова ящик');
  });

  it('рука — сужающийся цилиндр с манжетой', () => {
    должен(/const a = cyl\(0\.072, 0\.055, 0\.56, robe, 8\);/.test(РИГ), 'рука — ящик');
    должен(/const манжета = cyl\(0\.062, 0\.062, 0\.05, robeDark, 8\);/.test(РИГ), 'у руки нет манжеты');
    должен(!/const a = box\(0\.12, 0\.56, 0\.13, robe\);/.test(РИГ), 'рука снова ящик');
  });

  it('нога — сужающийся цилиндр, сапог с округлым носком', () => {
    должен(/const l = cyl\(0\.085, 0\.07, 0\.92, robeDark, 8\);/.test(РИГ), 'нога — ящик');
    // Носок округлый: острый угол читался как кирпич.
    должен(
      /const toe = sphere\(0\.075, MAT\.leatherDark, 8\);/.test(РИГ) && /toe\.scale\.set\(1, 0\.62, 1\.35\);/.test(РИГ),
      'у сапога нет округлого носка',
    );
    должен(!/const l = box\(0\.16, 0\.95, 0\.19, robeDark\);/.test(РИГ), 'нога снова ящик');
  });

  it('юбка халата с подгибом по краю', () => {
    должен(/const подгиб = torusRing\(0\.36, robe\);/.test(РИГ), 'у юбки нет подгиба');
    должен(/body\.add\(skirt, подгиб\);/.test(РИГ), 'подгиб не добавлен в тело');
  });
});
