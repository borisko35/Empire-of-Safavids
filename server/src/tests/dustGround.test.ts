// Пыль от бури ложится на землю.
//
// ЧТО БЫЛО (22 октября 2026, §283). В песчаной буре земля была как в штиль:
// своя, сухая, без пыли. Песок в воздухе летел (§ weather.ts), а земля под ним
// оставалась чистой — бура не оставляла следов.
//
// ЧТО ТЕПЕРЬ. Земля и городская мостовая в буре рыжеют от пыли. Пыль
// набирается не мгновенно и сходит не сразу: буря приходит и уходит постепенно.
//
// ЧТО ПРОВЕРЯЕТСЯ. Пыль — отдельный параметр земли, она красит и землю, и
// мостовую; в буре она копится постепенно, а когда буря кончилась — сходит.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const ТЕРРЕЙН = читать('client/src/app/game3d/terrain.ts');
const МИР = читать('client/src/app/game3d/world3d.ts');

describe('Пыль от бури ложится на землю', () => {
  it('земля принимает пыль третьим параметром', () => {
    должен(
      /export function setGroundState\(wet: number, snow: number, dust = 0\)/.test(ТЕРРЕЙН),
      'земля не умеет принимать пыль',
    );
    // Пыль — свой счётчик, а не мокрая земля и не снег.
    должен(/let пыльЗемли = -1;/.test(ТЕРРЕЙН), 'нет счётчика пыли на земле');
    // Цвет пыли задан: она рыжая, а не серая и не чёрная.
    const цвет = /const ЦВЕТ_ПЫЛИ = new THREE\.Color\(0x([0-9a-f]{6})\);/.exec(ТЕРРЕЙН);
    должен(цвет, 'нет цвета пыли');
    const красный = parseInt(цвет![1].slice(0, 2), 16);
    const синий = parseInt(цвет![1].slice(4, 6), 16);
    должен(
      красный > синий + 30,
      `цвет пыли 0x${цвет![1]} — не рыжий: пыль от бури тёплая, а не серая`,
    );
  });

  it('пыль красит и землю, и городскую мостовую', () => {
    // Земля: три канала, и от пыли она уходит в рыжий — синий гаснет
    // сильнее красного.
    должен(
      /материалЗемли\.color\.setRGB\(\s*\(1 - 0\.32 \* м\) \* \(1 - 0\.05 \* п\),\s*\(1 - 0\.32 \* м\) \* \(1 - 0\.22 \* п\),\s*\(1 - 0\.32 \* м\) \* \(1 - 0\.38 \* п\),/.test(ТЕРРЕЙН),
      'пыль не красит землю',
    );
    // Мостовая — тоже: в буре город выглядит занесённым.
    должен(
      /MAT\.street\.color\.setHex\(0x9a8a68\)\.multiplyScalar\(1 - 0\.26 \* м\)\.lerp\(ЦВЕТ_ПЫЛИ, п \* 0\.55\)/.test(ТЕРРЕЙН),
      'пыль не красит мостовую',
    );
  });

  it('пыль копится в буре постепенно и сходит не сразу', () => {
    // Пыль на земле — состояние мира, а не разовый перекрас.
    должен(/private пыль = 0;/.test(МИР), 'у мира нет счётчика пыли');
    // В буре — только песчаная буря: в дождь и в шторм пыли нет.
    должен(
      /const пылит = this\.currentWeather === 'sandstorm';/.test(МИР),
      'пыль ложится не в ту погоду',
    );
    // Копится и сходит постепенно, а не прыгает: иначе земля моргает.
    должен(
      /if \(пылит\) this\.пыль = Math\.min\(1, this\.пыль \+ dt \* 0\.5\);\s*else this\.пыль = Math\.max\(0, this\.пыль - dt \* 0\.25\);/.test(МИР),
      'пыль не копится и не сходит постепенно',
    );
    // И земля получает её вместе с мокротой и снегом.
    должен(
      /setGroundState\(this\.мокрота, this\.снег, this\.пыль\);/.test(МИР),
      'пыль не доходит до земли',
    );
  });
});
