// Рецепты крафта переведены, а предметы в них остались предметами.
//
// ЧТО ЗДЕСЬ ВСКРЫТО. У каждого рецепта в server/src/data/crafting.ts есть
// name и nameRu, но раздела recipes в словарях перевода не было вовсе.
// Панель печатала r.nameRu напрямую: игрок на en или az видел «Сварить
// Малое Зелье» и «Приготовить Персидский Кебаб» посреди переведённого
// интерфейса. Предметы в этих рецептах переводились, а сами рецепты — нет.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { CRAFTING_RECIPES } from '../data/crafting';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const словарь = (код: string): Record<string, string> =>
  JSON.parse(читать(`shared/locales/${код}.json`)).recipes;

const ru = словарь('ru');
const en = словарь('en');
const az = словарь('az');

const рецепты = Object.values(CRAFTING_RECIPES);

describe('Рецепты крафта переведены', () => {
  it('рецепты разбираются из данных', () => {
    // Якорь на 11. Разбор рецептов молча выкидывает записи с неразобранным
    // именем, и проверка полноты радуется неполным данным — ровно то,
    // из-за чего она и нужна.
    must(рецепты.length >= 11, `разобрано ${рецепты.length} рецептов, ожидалось не меньше 11`);
  });

  it('у каждого рецепта есть перевод во всех трёх языках', () => {
    for (const r of рецепты) {
      for (const [код, словари] of [['ru', ru], ['en', en], ['az', az]] as const) {
        const значение = словари[r.id];
        must(
          typeof значение === 'string' && значение.trim() !== '',
          `${r.id}: в ${код} нет названия рецепта — игрок увидит «${r.nameRu}»`,
        );
      }
    }
  });

  it('русское и английское названия рецепта совпадают с данными', () => {
    // Порядок источников тот же, что у предметов: данные каноничны,
    // словарь заполняется из них. Расхождение означало бы, что название
    // перепечатали вручную и опечатались.
    for (const r of рецепты) {
      must(ru[r.id] === r.nameRu,
        `${r.id}: в данных «${r.nameRu}», в словаре «${ru[r.id]}» — игрок увидит разные названия`);
      must(en[r.id] === r.name,
        `${r.id}: в данных «${r.name}», в словаре «${en[r.id]}» — игрок увидит разные названия`);
    }
  });

  it('название рецепта не содержит сам идентификатор', () => {
    // Заглушка иконки берёт первую букву названия. Если бы в название
    // просочился идентификатор, плитка показала бы «r» вместо буквы.
    for (const r of рецепты) {
      for (const [код, словари] of [['ru', ru], ['en', en], ['az', az]] as const) {
        const значение = словари[r.id] ?? '';
        must(!значение.includes(r.id), `${код}/${r.id}: название содержит сам идентификатор`);
      }
    }
  });

  it('два рецепта не называются одинаково', () => {
    // Тот же дефект, что был у предметов: два разных рецепта под одним
    // названием не различить в списке крафта.
    for (const [код, словари] of [['ru', ru], ['en', en], ['az', az]] as const) {
      const группы = new Map<string, string[]>();
      for (const r of рецепты) {
        const ключ = (словари[r.id] ?? '').trim().toLowerCase();
        if (ключ === '') continue;
        группы.set(ключ, [...(группы.get(ключ) ?? []), r.id]);
      }
      for (const [название, группа] of группы) {
        must(группа.length === 1,
          `${код}: «${название}» — это ${группа.length} разных рецептов (${группа.join(', ')})`);
      }
    }
  });
});