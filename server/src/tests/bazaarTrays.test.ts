// Продавцы базара больше не стоят с пустыми руками.
//
// ЧТО БЫЛО (22 октября 2026, §306). Четыре продавца за базарными рядами стояли
// с пустыми руками: торговый ряд выглядел нерабочим, а лотки и товар были
// только на прилавке.
//
// ЧТО ТЕПЕРЬ. У продавца в левой руке — лоток с товаром: плоды и свёртки
// разного цвета на круглом подносе.
//
// ЧТО ПРОВЕРЯЕТСЯ. Лоток есть и состоит из подноса и товара; он держится в
// левой руке; и все четыре продавца базара получили лоток.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РИГ = читать('client/src/app/game3d/rig.ts');
const НПЦ = читать('client/src/app/game3d/npc.ts');

describe('Продавцы базара с лотками', () => {
  it('лоток: поднос и товар', () => {
    // Поднос.
    должен(
      /const поднос = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.24, 0\.22, 0\.035, 12\), MAT\.wood\);/.test(РИГ),
      'у продавца нет подноса',
    );
    // Товар — пять плодов разного цвета.
    должен(
      /const товар = new THREE\.Mesh\(\s*new THREE\.SphereGeometry\(0\.05 \+ \(i % 2\) \* 0\.012, 7, 6\),/.test(РИГ),
      'на лотке нет товара',
    );
    должен(/for \(let i = 0; i < 5; i\+\+\) \{/.test(РИГ), 'товара на лотке не пять');
  });

  it('лоток в левой руке', () => {
    должен(/лоток\.position\.set\(0, -0\.72, 0\.16\);/.test(РИГ), 'лоток не в руке');
    должен(/armL\.add\(лоток\);/.test(РИГ), 'лоток не в левой руке');
  });

  it('все четыре продавца базара получили лоток', () => {
    // Поле «предмет» умеет лоток.
    должен(/предмет\?: 'удочка' \| 'весы' \| 'корзина' \| 'лоток';/.test(РИГ), 'лоток не в списке предметов');
    // И лоток есть у всех продавцов базара.
    const продавцов = (НПЦ.match(/id: 'npc_bazaar_trader_\d'/g) || []).length;
    const сЛотком = (НПЦ.match(/id: 'npc_bazaar_trader_\d'[^\n]*предмет: 'лоток'/g) || []).length;
    должен(продавцов >= 4, `продавцов базара только ${продавцов}`);
    должен(сЛотком === продавцов, `лоток есть у ${сЛотком} из ${продавцов} продавцов`);
  });
});
