// Покупка навыка не может стоить игроку денег.
//
// ЧТО БЫЛО. На бою покупка гильдейского навыка упала с
//   column "updated_at" of relation "guild_skills" does not exist
// и казна уменьшилась на 6000 при нулевом уровне навыка. Игрок заплатил и
// ничего не получил. 6000 вернули TestBot'у вручную.
//
// ДВА КЛАССА ПОЛОМКИ, ПРОВЕРЯЮТСЯ ОТДЕЛЬНО:
//
// 1. КОЛОНКИ НЕТ. Миграция 050 объявляет
//    CREATE TABLE IF NOT EXISTS guild_skills (..., updated_at ...), но
//    таблица была создана раньше без этой колонки, и IF NOT EXISTS молча
//    пропустил определение. Ограничения из следующих ALTER добавились, а
//    колонка - нет. Та же болезнь была с guilds, её лечила миграция 042.
//
// 2. ДЕНЬГИ СПИСЫВАЮТСЯ ДО ЗАПИСИ. Порядок «сначала списание» без
//    транзакции не защищает: он делает потерю гарантированной при любой
//    ошибке записи. Комментарий в коде утверждал обратное.
//
// ФАЙЛЫ ЧИТАЮТСЯ ВНУТРИ ТЕСТОВ, А НЕ НА ВЕРХНЕМ УРОВНЕ МОДУЛЯ. Проверка
// про отсутствующий файл - самый вероятный сценарий здесь. При чтении на
// верхнем уровне удаление файла роняло модуль целиком, и jest писал
// "Tests: 0 total" без единого имени: поломка поймана и потеряна.
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

// Отсутствие файла обязано превращаться в ПРОВАЛ этого теста, а не в
// падение загрузчика. Сообщение объясняет, что файл - часть проверки.
const файл = (путь: string): string => {
  if (!existsSync(join(корень, путь))) {
    throw new Error('ФАЙЛА НЕТ, а проверка его требует: ' + путь +
      ' - это и есть поломка, она обязана красеть поимённо');
  }
  return читать(путь);
};

const сервис = (): string => читать('server/src/services/GuildService.ts');
const миграция050 = (): string => читать('database/migrations/050_guild_skills.sql');
const миграция058 = (): string => файл('database/migrations/058_guild_skills_updated_at.sql');

// Отрезок метода upgradeSkill - до следующего объявления метода.
// Фиксированная длина в символах была ловушкой: длинный комментарий внутри
// метода выталкивал нужные строки за границу, и проверка падала на верном
// коде. Отрезок до следующего метода растёт вместе с методом.
const метод = (): string => {
  const код = сервис();
  const начало = код.indexOf('async upgradeSkill');
  return код.slice(начало, код.indexOf('  async ', начало + 10));
};

describe('Колонка updated_at существует', () => {
  it('миграция 050 объявляет колонку - и в этом ловушка', () => {
    // Объявление есть, и именно оно ввело в заблуждение: файл выглядит
    // правильным, миграция отчитывается об успехе, а колонки нет.
    expect({
      объявлена: /updated_at\s+TIMESTAMPTZ/i.test(миграция050()),
      // IF NOT EXISTS - причина, по которой объявление не сработало.
      условное_создание: /CREATE TABLE IF NOT EXISTS guild_skills/i.test(миграция050()),
    }).toEqual({ объявлена: true, условное_создание: true });
  });

  it('миграция 058 добавляет колонку отдельным файлом', () => {
    // Отдельная миграция, а не правка 050: 050 уже применена на бою, и её
    // текст больше не переигрывается. Это и есть ловушка IF NOT EXISTS -
    // починить 050 значит не починить ничего.
    expect({
      добавление: /ALTER TABLE guild_skills\s*ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW\(\)/.test(миграция058()),
      now_для_старых: /DEFAULT NOW\(\)/.test(миграция058()),
    }).toEqual({ добавление: true, now_для_старых: true });
  });

  it('миграция объясняет про IF NOT EXISTS, а не просто «добавь колонку»', () => {
    // Миграцию читают через полгода. Без причины её откатят как лишнюю,
    // и болезнь вернётся на следующей таблице.
    expect({ упоминает_iftnotexists: /IF NOT EXISTS/.test(миграция058()) })
      .toEqual({ упоминает_iftnotexists: true });
  });
});

describe('Деньги не списываются за неудачную покупку', () => {
  it('списание и запись уровня в одной транзакции', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Без транзакции падение записи уровня
    // оставляет казну уменьшенной - ровно то, что произошло на бою.
    expect({
      транзакция_есть: /await this\.db\.transaction\(async \(client\) =>/.test(метод()),
      списание_в_ней: /client\.query[\s\S]{0,200}UPDATE guilds SET gold = gold - /.test(метод()),
      запись_в_ней: /client\.query[\s\S]{0,200}INSERT INTO guild_skills/.test(метод()),
    }).toEqual({ транзакция_есть: true, списание_в_ней: true, запись_в_ней: true });
  });

  it('запросы идут через client, а не через this.db', () => {
    // this.db внутри транзакции - ДРУГОЕ соединение из пула, не её
    // участник. Списание прошло бы, откат - нет: защита была бы написана
    // и не работала. Самая коварная форма «выглядит правильно».
    const начало = метод().indexOf('await this.db.transaction');
    const блок = метод().slice(начало, начало + 900);
    expect({
      без_this_db: !/this\.db\.(query|queryOne)/.test(блок),
      есть_client: /client\.query/.test(блок),
    }).toEqual({ без_this_db: true, есть_client: true });
  });

  it('уровень записывается посчитанным, а не текущим', () => {
    // Молчаливая ошибка: записать старый уровень или записать цену вместо
    // уровня. И то и другое выглядит как «покупка прошла».
    expect({
      пишет_новый: /\[guildId, skillId, новый\]/.test(метод()),
      не_пишет_текущий: !/\[guildId, skillId, текущий/.test(метод()),
    }).toEqual({ пишет_новый: true, не_пишет_текущий: true });
  });

  it('старое ложное утверждение удалено', () => {
    // Комментарий «если запись упадёт, золото уже списано» был не
    // описанием, а ошибкой: порядок без транзакции именно это и вызывает.
    expect({
      ложного_утверждения_нет: !/если запись навыка упадёт, золото уже списано/.test(сервис()),
      про_транзакцию_есть: /ОДНОЙ ТРАНЗАКЦИЕЙ/.test(сервис()),
    }).toEqual({ ложного_утверждения_нет: true, про_транзакцию_есть: true });
  });

  it('нехватка золота всё ещё отказывает, а не списывает в долг', () => {
    // Транзакция не должна была испортить вторую защиту.
    expect({
      проверка_осталась: /gold >= \$1/.test(метод()),
      отказ_по_rowcount: /списание\.rowCount === 0\) throw new Error\('NOT_ENOUGH_GUILD_GOLD'\)/.test(метод()),
    }).toEqual({ проверка_осталась: true, отказ_по_rowcount: true });
  });
});

describe('Схема из миграций не разошлась с кодом', () => {
  it('потолок уровня в базе совпадает с данными', () => {
    // В базе CHECK (level >= 0 AND level <= 10), а потолок берётся из
    // maxLevel в data/guilds.ts. Поднять maxLevel в данных, оставив старую
    // миграцию, - значит получить отказ базы там, где код считает покупку
    // законной. Пока числа совпадают, но связь не зафиксирована.
    const потолок = /level >= 0 AND level <= (\d+)/.exec(миграция050())?.[1];
    expect({
      потолок_в_базе: потолок,
      // Зафиксировано руками: расхождение с data/guilds.ts обязано
      // сломать проверку.
      совпадает_с_данными: Number(потолок) === 10,
    }).toEqual({ потолок_в_базе: '10', совпадает_с_данными: true });
  });
});
