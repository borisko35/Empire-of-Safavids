// Синтаксическая валидность JS лендинга.
//
// ЗАЧЕМ. Лендинг — это обычные ES-модули, которые браузер
// загружает как есть, без сборщика и без проверки типов.
// Один фрагмент на TypeScript (приведение «as», аннотация
// «: string») в файле .js — это SyntaxError, и модуль не
// загружается ЦЕЛИКОМ: молчат все разделы страницы, которые
// он рисует — статус, рейтинг, галерея, таймлайн. Такой
// слом проходил незамеченным: сборка не проверяет веб-страницу,
// а тесты читали main.js как текст и не запускали его.
//
// ЧТО ЗДЕСЬ. `node --check` на каждом модуле: синтаксическая
// ошибка — падение теста. Проверка именно синтаксиса, а не
// семантики: ловит то, что ломает загрузку страницы.
import { readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const repoRoot = join(__dirname, '..', '..', '..');
const webJs = join(repoRoot, 'client', 'web', 'js');

describe('JS лендинга синтаксически валиден', () => {
  const файлы = readdirSync(webJs).filter((f) => f.endsWith('.js'));

  it('модулей больше одного — проверка не мёртвая', () => {
    expect(файлы.length).toBeGreaterThan(1);
  });

  for (const файл of файлы) {
    it(`${файл} разбирается как JavaScript`, () => {
      // node --check читает файл и падает с ненулевым кодом
      // на первой синтаксической ошибке — той же, что увидит
      // браузер при загрузке модуля.
      expect(() =>
        execFileSync('node', ['--check', join(webJs, файл)], {
          stdio: 'pipe',
        }),
      ).not.toThrow();
    });
  }
});
