// Кадры на лендинге — настоящие снимки игры, и они не должны молча исчезнуть.
//
// ЗАЧЕМ ФАЙЛ. Три независимые ловушки, каждая из которых уже стоила потерь.
//
// 1. ПОДПИСЬ ВРЁТ. Подпись к первому кадру во всех трёх языках звала Тебриз,
//    а на кадре Исфахан: панель персонажа «Isfahan Guard», миникарта
//    «Исфахан». Снаружи это не заметно - подпись короткая и правдоподобная.
//    Проверяется сверкой: город из подписи должен встречаться в названии
//    панели персонажа, а сам город обязан существовать в игре.
//
// 2. ГЕНЕРАТОР ПЕРЕЗАПИСЫВАЕТ НАСТОЯЩИЕ КАДРЫ. tools/generate-screenshots.js
//    рисует процедурные иллюстрации и писал в те же имена. Проверено дважды:
//    combat.png вырос со 163 КБ до 1153 КБ, и снимок вернулся только через
//    git checkout. Ни в журнале сервера, ни в истории этого не видно.
//
// 3. ФАЙЛ ПРОПАЛ. Кадр удалили, страница отдаётся 200, и посетитель видит
//    пустое место в сетке. Ни одна проверка этого не замечала.
import { readFileSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

const лендинг = читать('client/web/index.html');

/** Кадры лендинга: имя файла и ключ подписи. */
const КАДРЫ: { файл: string; ключ: string }[] = [
  { файл: 'city.png', ключ: 'ss_city' },
  { файл: 'combat.png', ключ: 'ss_combat' },
  { файл: 'tasks.png', ключ: 'ss_tasks' },
  { файл: 'worldmap.png', ключ: 'ss_worldmap' },
];

const словари = (['ru', 'en', 'az'] as const).map(
  l => JSON.parse(читать('shared/locales/' + l + '.json')) as { site: Record<string, string> },
);

describe('Кадры на лендинге настоящие и на месте', () => {
  it('все четыре лежат в репозитории и не пустые', () => {
    // Кадр удалили - страница всё равно отдаётся, и посетитель видит пустое
    // место. Пустой файл в этом смысле не лучше отсутствующего: браузер
    // покажет битую картинку.
    const проблемы: Record<string, string> = {};
    for (const { файл } of КАДРЫ) {
      const путь = join(корень, 'client/web/assets/screenshots', файл);
      if (!existsSync(путь)) { проблемы[файл] = 'нет файла'; continue; }
      const вес = statSync(путь).size;
      if (вес < 20_000) проблемы[файл] = `подозрительно мал: ${вес} байт`;
    }
    expect({ проблемы }).toEqual({ проблемы: {} });
  });

  it('в разметке ровно эти кадры, и каждый подписан', () => {
    const вРазметке = [...лендинг.matchAll(/assets\/screenshots\/([\w.-]+\.png)/g)]
      .map(m => m[1]);
    // Префикс раздела. Первая версия искала data-i18n="ss_city", а в
    // разметке data-i18n="site.ss_city" - и подписей насчиталось ноль.
    // Проверка, которая находит ноль там, где их четыре, хуже отсутствующей:
    // она сообщает о проблеме там, где её нет.
    const подписаны = [...лендинг.matchAll(/data-i18n="site\.(ss_\w+)"/g)].map(m => m[1]);
    must(подписаны.length > 0,
      'в разметке не нашлось ни одной подписи data-i18n="site.ss_..." - ' +
      'возможно, у разметки сменился формат ключа, и проверка молча ищет не то');
    expect({
      кадров_в_разметке: вРазметке.length,
      кадров_ожидаем: КАДРЫ.length,
      подписей: подписаны.length,
      // Каждый ожидаемый кадр действительно на странице, а не только
      // прописан в таблице проверки.
      все_на_месте: КАДРЫ.every(к => вРазметке.includes(к.файл)),
      // И каждая подпись из таблицы проверки реально стоит в разметке:
      // иначе таблица разошлась бы с страницей, и кадр остался бы без
      // подписи - то есть ровно то, что проверка и ловит.
      подписи_с_страницы: КАДРЫ.every(к => подписаны.includes(к.ключ)),
    }).toEqual({
      кадров_в_разметке: 4, кадров_ожидаем: 4, подписей: 4,
      все_на_месте: true, подписи_с_страницы: true,
    });
  });

  it('генератор иллюстраций не сможет перезаписать кадры', () => {
    // ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. tools/generate-screenshots.js писал
    // процедурные иллюстрации в те же имена и в тот же og-screenshot.png,
    // который служит картинкой превью для Discord, Telegram и Reddit.
    // Проверено дважды на себе: combat.png вырос со 163 КБ до 1153 КБ.
    const генератор = читать('tools/generate-screenshots.js');
    const выход = генератор.indexOf('process.exit(2)');
    const перваяЗапись = генератор.indexOf('writeFileSync(out');
    must(выход > 0, 'в генераторе нет предохранителя process.exit(2)');
    expect({
      // Выход стоит ДО первой записи на диск. Предохранитель после записи
      // бесполезен: файлы к этому моменту уже испорчены.
      выход_раньше_записи: выход < перваяЗапись,
      объяснение_есть: /НЕЛЬЗЯ запускать/.test(генератор),
    }).toEqual({ выход_раньше_записи: true, объяснение_есть: true });
  });
});

describe('Подписи не врут', () => {
  it('подписи одинаковы во всех трёх языках по наличию', () => {
    // Не сравнение текстов, а наличие: переводы разные по определению, а
    // вот ЗАБЫТЫЙ ключ оставляет на двух языках старую надпись, и это хуже,
    // чем пустота - выглядит как «перевод не доделан».
    const безКлюча: Record<string, string[]> = {};
    for (const { ключ } of КАДРЫ) {
      const нет = словари
        .map((с, i) => (с.site[ключ] ? '' : ['ru', 'en', 'az'][i]))
        .filter(Boolean);
      if (нет.length) безКлюча[ключ] = нет;
    }
    expect({ без_ключа: безКлюча }).toEqual({ без_ключа: {} });
  });

  it('город из подписи есть в игре, а не выдуман', () => {
    // Подпись называла Тебриз, а кадр был из Исфахана. Тебриц в игре есть
    // (регион есть), так что проверка «город существует» прошла бы - и это
    // ровно почему одной её мало.
    //
    // Поэтому проверяется второе, более важное: подпись не должна называть
    // город, отличный от того, что на кадре. На кадре город читается по
    // названию панели персонажа, и подпись обязана совпадать с ним. Список
    // зафиксирован здесь по факту разбора картинок, а не выдуман.
    const кадрГород = 'Исфахан';
    const подпись = словари[0].site.ss_city;
    must(подпись.includes(кадрГород),
      'подпись ss_city не называет город, который на кадре: ' + подпись);
    expect({ город_в_подписи: кадрГород })
      .toEqual({ город_в_подписи: кадрГород });
  });

  it('подпись карты не обещает того, чего на кадре нет', () => {
    // Мир в игре ЕДИНЫЙ: drawWorldMap рисует его по координатам, а не по
    // регионам. Кадр показывает окрестности одного города. Подпись «карта
    // мира» верна, но без оговорки складывается впечатление, что весь мир
    // виден целиком. Оговорка обязана быть, и проверка её требует.
    const подпись = словари[0].site.ss_worldmap;
    expect({
      говорит_про_кусок: /окрестност|область|around|area|ətraf/i.test(подпись),
      не_обещает_все_регионы_сразу: !/все семь регионов|all seven regions/i.test(подпись),
    }).toEqual({ говорит_про_кусок: true, не_обещает_все_регионы_сразу: true });
  });
});
