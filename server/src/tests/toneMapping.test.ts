// Тональная кривая: блики не должны срезаться в белое.
//
// ЧТО БЫЛО. Рендер не задавал toneMapping вовсе, а у Three.js по умолчанию
// NoToneMapping — кадр отдаётся как есть. Всё, что ярче единицы, становилось
// чистым белым: солнечные блики на металле, факелы, небо в зените. Белое пятно
// вместо градации — самая заметная «нереалистичность» кадра, потому что ни
// одна камера так не снимает.
//
// ЧТО ПРОВЕРЯЕТСЯ. Кривая задана в мире И в превью классов — и это одна
// кривая. Превью со своей кривой (или без) сделало бы выбор класса другой
// игрой: тот же персонаж выглядел бы по-разному на двух экранах.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const МИР = читать('client/src/app/game3d/world3d.ts');
const ПРЕВЬЮ = читать('client/src/app/screens/classPreview.ts');

describe('Тональная кривая кадра', () => {
  it('в мире задана кривая, а не оставлено значение по умолчанию', () => {
    must(
      /this\.renderer\.toneMapping\s*=\s*THREE\.\w+ToneMapping/.test(МИР),
      'в world3d.ts не задан toneMapping: блики срезаются в белое',
    );
    // По умолчанию именно NoToneMapping, поэтому проверка на «не про
    // умолчание» всё равно что проверка на «не пусто»: любое осмысленное
    // значение проходит. Смысл в том, что строка вообще есть.
    must(
      /NoToneMapping/.test(МИР) === false || /NoToneMapping[\s\S]{0,40}по умолчанию/.test(МИР),
      'в world3d.js упомянут NoToneMapping как выбираемое значение — это и есть запрет',
    );
  });

  it('экспозиция задана и компенсирует затемнение кривой', () => {
    const м = /toneMappingExposure\s*=\s*([\d.]+)/.exec(МИР);
    must(м, 'экспозиция не задана: кривая затемнит середину, и мир станет серым');
    const экспозиция = Number(м[1]);
    // Меньше единицы — гарантированно тёмнее, чем было. Кривая сжимает
    // свет, поэтому компенсация должна быть больше единицы.
    must(экспозиция > 1, `экспозиция ${экспозиция}: кино-кривая затемнит кадр без компенсации`);
    must(экспозиция < 3, `экспозиция ${экспозиция}: кадр выйдет белым, это не компенсация`);
  });

  it('превью классов смотрят той же кривой, что и мир', () => {
    // Превву без кривой (или со своей) сделало бы выбор класса другой
    // игрой: один персонаж, два разных вида.
    const криваяМира = /THREE\.(\w+ToneMapping)/.exec(МИР)?.[1];
    must(криваяМира, 'в мире не нашлась кривая');
    must(
      new RegExp(`THREE\\.${криваяМира}\\b`).test(ПРЕВЬЮ),
      `превью классов не используют ${криваяМира}: персонаж на выборе выглядит иначе, чем в игре`,
    );
  });

  it('кривая существует в подключенной версии three', () => {
    // Имя выдуманного метода упало бы только в браузере, при открытии
    // мира — то есть у игрока. three ставится клиенту, поэтому читаем
    // клиентскую копию: серверный jest её не видит.
    const пакет = JSON.parse(
      читать('client/node_modules/three/package.json'),
    ) as { version?: string };
    must(/^\d+\.\d+\.\d+$/.test(пакет.version ?? ''),
      'версия three не читается: ' + пакет.version);

    // Объявления констант лежат в three.core.js: const AgXToneMapping = 6;
    const ядро = читать('client/node_modules/three/build/three.core.js');
    const кривая = /THREE\.(\w+ToneMapping)/.exec(МИР)?.[1];
    must(кривая, 'в мире не нашлась кривая');
    must(
      new RegExp(`const ${кривая}\\s*=\\s*\\d+;`).test(ядро),
      `THREE.${кривая} не объявлено в three ${пакет.version}: кадр молча ушёл бы на кривую по умолчанию`,
    );
    // Имя должно ещё и экспортироваться — объявленное, но не отданное
    // наружу значение THREE-объект не получит.
    const экспорт = ядро.match(/export \{([^}]+)\}/s);
    must(экспорт !== null && new RegExp(`\\b${кривая}\\b`).test(экспорт[1]),
      `${кривая} объявлено, но не экспортируется: THREE.${кривая} окажется undefined`);
  });
});
