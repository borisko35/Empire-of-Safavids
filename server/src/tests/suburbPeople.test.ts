// Люди в пригороде.
//
// ЧТО БЫЛО (22 октября 2026, §311). Пригород был обставлен (§310: кузница,
// колодец, склад, телега), но пуст — никого. Постройки без людей читаются как
// выставка.
//
// ЧТО ТЕПЕРЬ. Кузнец у горна с молотом, носильщик у склада с корзиной и
// водонос у колодца с вёдрами на коромысле. У кузнеца и водоноса — свои
// предметы в руках.
//
// ЧТО ПРОВЕРЯЕТСЯ. Три новых предмета есть и собраны из деталей; три новых
// жителя пригорода поставлены на свои места и получили предметы.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function должен(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const РИГ = читать('client/src/app/game3d/rig.ts');
const НПЦ = читать('client/src/app/game3d/npc.ts');

describe('Люди в пригороде', () => {
  it('молот кузнеца и вёдра водоноса', () => {
    // Список предметов знает и молот, и вёдра.
    должен(
      /предмет\?: 'удочка' \| 'весы' \| 'корзина' \| 'лоток' \| 'молот' \| 'вёдра';/.test(РИГ),
      'в списке предметов нет молота и ведёр',
    );
    // Молот: рукоять и набойная головка.
    должен(
      /const рукоять = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.022, 0\.028, 0\.6, 6\), MAT\.wood\);/.test(РИГ),
      'у молота нет рукояти',
    );
    должен(
      /const набой = new THREE\.Mesh\(new THREE\.BoxGeometry\(0\.1, 0\.1, 0\.24\), MAT\.steelDark\);/.test(РИГ),
      'у молота нет набойной головки',
    );
    // Вёдра на коромысле: брус и два ведра.
    должен(
      /const брус = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.02, 0\.02, 1\.1, 5\), MAT\.wood\);/.test(РИГ),
      'нет коромысла',
    );
    должен(
      /const ведро = new THREE\.Mesh\(new THREE\.CylinderGeometry\(0\.13, 0\.11, 0\.22, 9\), MAT\.wood\);/.test(РИГ),
      'нет ведра на коромысле',
    );
  });

  it('три новых жителя пригорода на своих местах', () => {
    // Кузнец у горна, носильщик у склада, водонос у колодца.
    должен(/id: 'npc_suburb_blacksmith'/.test(НПЦ), 'нет кузнеца в пригороде');
    должен(/id: 'npc_suburb_carrier'/.test(НПЦ), 'нет носильщика у склада');
    должен(/id: 'npc_suburb_water'/.test(НПЦ), 'нет водоноса у колодца');
    // И у каждого — свой предмет.
    должен(/npc_suburb_blacksmith[^\n]*предмет: 'молот'/.test(НПЦ), 'у кузнеца нет молота');
    должен(/npc_suburb_carrier[^\n]*предмет: 'корзина'/.test(НПЦ), 'у носильщика нет корзины');
    должен(/npc_suburb_water[^\n]*предмет: 'вёдра'/.test(НПЦ), 'у водоноса нет ведёр');
  });
});
