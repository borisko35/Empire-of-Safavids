// Вход в опасную зону решает игрок. Затвора не будет - и это проверяется.
//
// РЕШЕНИЕ ВЛАДЕЛЬЦА. Если игрок в себе уверен и может справиться с сильными
// и опасными монстрами - это его право и его решение. Запрещать или ставить
// преграды на его путь нельзя.
//
// ПОЧЕМУ ЭТО НАДО ЗАКРЕПЛЯТЬ ПРОВЕРКОЙ, А НЕ ТОЛЬКО РЕШЕНИЕМ.
//
// У каждой из 24 зон заполнено поле minLevel - требуемый уровень, от 1 до 95.
// Рядом лежит minLevel у регионов, который проверяется на /travel. Всё это
// выглядит как заготовка под затворы, а выглядывающие данные давят на того,
// кто их увидит: «поле есть, а не работает» - и через несколько итераций
// вход закрывают, решив починить. Решение владельца при этом отменяется тихо,
// без единого вопроса, и выглядит как улучшение.
//
// Проверка ниже требует, чтобы такого кода не появилось. Она не запрещает
// показывать требование - показ это сведения, и он полезен.
//
// ЧТО ПРОВЕРЯЕТСЯ ТОЧНО. Ни в обработчике движения, ни в обработчике смены
// зоны, ни в записи посещения не должно быть сравнения уровня персонажа с
// уровнем зоны, которое отказывает. Слово minLevel в этих путях означать не
// должно ничего, кроме показа.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ZONES, REGION_LEVEL_REQUIREMENTS } from '../../../shared/constants';

const корень = join(__dirname, '..', '..', '..');
const читать = (p: string): string => readFileSync(join(корень, p), 'utf-8');

function must(условие: unknown, причина: string): asserts условие {
  if (!условие) throw new Error(причина);
}

const КЛИЕНТ = читать('client/src/app/world.ts');
const СОКЕТ = читать('server/src/socket/GameSocketHandler.ts');
/** Маршруты мира - там стоял затвор на путешествие. */
const СОКЕТЫ_WORLD = читать('server/src/routes/world.ts');

/**
 * Кусок обработчика zone:changed - от подписки до её закрывающей скобки.
 *
 * Граница настоящая, а не ширина в символах. Окно фиксированной длины
 * сломалось уже четыре раза за серию: комментарий рос, окно оставалось, и
 * проверка начинала мерить чужой обработчик по соседству.
 */
function обработчикСменыЗоны(): string {
  const начало = КЛИЕНТ.indexOf("socket.on('zone:changed'");
  must(начало > 0, 'не нашёл подписку на zone:changed в клиенте');
  const конец = КЛИЕНТ.indexOf('\n  });', начало);
  must(конец > начало, 'подписка на zone:changed не закрывается - разбор сломан');
  return безКомментариев(КЛИЕНТ.slice(начало, конец));
}
/** Отрезает комментарии: правило о запрете не должно ловить слова о нём же. */
const безКомментариев = (текст: string): string =>
  текст.replace(/\/\/[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');

describe('Вход в опасную зону решает игрок', () => {
  it('решение записано в коде, а не осталось в переписке', () => {
    // Решение, о котором знает только владелец, через полгода не помнит
    // никто, кроме него. Оно обязано лежать рядом с местом, где его можно
    // нечаянно отменить.
    must(/РЕШЕНИЕ ВЛАДЕЛЬЦА/.test(КЛИЕНТ),
      'рядом с показом требования уровня нет записи о решении владельца: ' +
      'следующий, кто увидит неиспользуемое поле minLevel, может закрыть вход без вопроса');
  });

  it('обработчик смены зоны ничего не запрещает', () => {
    // Зона приходит сюда при каждом переходе. Если здесь появится сравнение
    // уровня с отказом - игрок упрётся в невидимую стену на границе.
    //
    // Инвариант про форму, а не про слова.
    //
    // ПЕРВАЯ ВЕРСИЯ ИСКАЛА СЛОВА И ПРОПУСТИЛА ЗАТВОР. Регулярки были на
    // латинице - `character.level`, `level <`, - а код в проекте по-русски, и
    // затвор `if (мойУровень < нужно) return;` не попал ни под одну. Проверка
    // прошла с затвором на месте; нашла это ломка с откатом.
    //
    // Теперь запрещён оператор сравнения вообще. Затвор невозможен без
    // сравнения, а сравнение в этом обработчике не нужно ни для чего: он
    // рисует тост. Стрелки и знаки вопроса из тернарных выражений к
    // сравнениям не относятся и убираются перед проверкой.
    const обработчик = обработчикСменыЗоны();
    must(обработчик.length > 0, 'подписка на zone:changed не разобралась');
    const безСтрелок = обработчик.replace(/=>/g, '');
    const сравнения = [...безСтрелок.matchAll(/[<>]=?/g)];
    must(сравнения.length === 0,
      `в обработчике смены зоны появились операторы сравнения (${сравнения.length}): ${сравнения.map(с => с[0]).join(', ')}. ` +
      'Затвор по уровню это всегда сравнение, а сравнение здесь не нужно ни для чего.');
  });

  it('сервер не отказывает в движении по уровню зоны', () => {
    // Путь движения: клиент шлёт координату, сервер сохраняет её, зона
    // выводится из координаты. Затвора здесь не должно быть ни при какой
    // формулировке.
    const код = безКомментариев(СОКЕТ);
    must(!/zone\?\.minLevel\s*[<>=]/.test(код) && !/minLevel\s*[<>]=?\s*\w*level/.test(код),
      'в GameSocketHandler появилось сравнение уровня с уровнем зоны: ' +
      'это затвор на пути движения, а решение владельца обратном');
  });

  it('запись посещения не отказывает по уровню', () => {
    // Здесь особенно важно: ошибка и так гасится, чтобы не ронять путешествие,
    // поэтому отказ здесь выглядел бы как «посещение не засчиталось» без
    // единого сообщения.
    const сервис = безКомментариев(читать('server/src/services/CharacterService.ts'));
    const запись = сервис.slice(
      сервис.indexOf('private async recordRegionVisit'),
      сервис.indexOf('private async recordRegionVisit') + 1200,
    );
    must(запись.length > 0, 'не нашёл recordRegionVisit');
    must(!/level/.test(запись),
      'recordRegionVisit начал смотреть на уровень: отказ молчал бы, и достижение стало бы недостижимым');
  });

  it('требование по-прежнему показывается: решение не про молчание', () => {
    // Обратная сторона решения. Затвора нет, но игрок должен знать, во что
    // входит: решение «иди, если считаешь, что справишься» невозможно вслепую.
    const обработчик = обработчикСменыЗоны();
    must(/zones\.need_level/.test(обработчик),
      'требование уровня перестало показываться: решение владельца - свобода выбора, а не неинформированность');
    must(/payload\.zone\.minLevel/.test(обработчик),
      'показывается слово про уровень, но не само значение: игрок не узнает с какого уровня зона');
  });

  it('поле minLevel по-прежнему заполнено - решение не про вычистку данных', () => {
    // Данные остаются: показ требует их. А решение владельца - про запреты,
    // а не про то, чтобы выбросить сведения, которые показываются.
    const пустые = ZONES.filter((з) => typeof з.minLevel !== 'number' || з.minLevel < 1);
    must(пустые.length === 0,
      `зоны без требования по уровню: ${пустые.map((з) => з.id).join(', ')}`);
  });
});

describe('Преграды не ставятся и в меню путешествий', () => {
  it('сервер не отказывает в путешествии по уровню', () => {
    // Раньше здесь стояло сравнение уровня персонажа с требованием региона и
    // ответ 403 region_locked. Решение владельца: не пускать - значит не
    // сообщать, что закрыто.
    // Комментарии вырезаются: снятый затвор описан в коде словами, и проверка
    // нашла «region_locked» в собственном объяснении, а не в работающем коде.
    const кодМаршрута = СОКЕТЫ_WORLD.replace(/\/\/[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
    must(!/region_locked/.test(кодМаршрута),
      'сервер снова отвечает region_locked на путешествие: преграда вернулась');
    must(!/character\.level\s*</.test(кодМаршрута),
      'в обработчике путешествия появилось сравнение уровня - преграда вернулась');
  });

  it('кнопка путешествия доступна всегда, а строка не помечена замком', () => {
    // Замок только в интерфейсе выглядит как «город закрыт» не хуже
    // серверного: игрок видит серую кнопку и не понимает, что происходит.
    const hud = читать('client/src/app/hud.ts');
    const код = hud.replace(/\/\/[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
    must(!/const locked\b/.test(код),
      'в списке регионов снова есть переменная locked: часть города помечается как закрытая');
    must(!/btn\.disabled\s*=\s*locked/.test(код),
      'кнопка путешествия снова отключается по уровню - игрок не может уйти в город, который не считает закрытым');
    must(!/locked \? '🔒 /.test(код),
      'перед описанием региона снова рисуется замок');
  });

  it('решение записано в обоих местах, где стоял затвор', () => {
    // Решение, о котором знает только владелец, через полгода не помнит
    // никто. Оно обязано лежать и там, где его можно нечаянно вернуть.
    must(/преграды на пути/i.test(читать('server/src/routes/world.ts')),
      'в маршруте путешествия нет записи о решении владельца');
    must(/Замка нет/i.test(читать('client/src/app/hud.ts')),
      'в списке регионов нет записи о решении владельца');
  });

  it('требование осталось как сведения, а не исчезло молча', () => {
    // Решение - про свободу выбора, а не про вычистку: игрок должен видеть,
    // кто там живёт. Число в списке регионов остаётся.
    const hud = читать('client/src/app/hud.ts');
    must(/r\.minLevel/.test(hud),
      'из списка регионов исчезло требование уровня: игрок больше не видит, кто живёт в этом краю');
    must(REGION_LEVEL_REQUIREMENTS.herat !== undefined,
      'требование региона исчезло из данных - показать будет нечего');
  });
});
