// ЗАЧЕМ ДВА ВАРИАНТА ПРОВЕРКИ, И ПОЧЕМУ ПЕРВЫЙ НЕ ГОДИТСЯ.
//
// Наивный способ — искать по готовому слову. Он пропускает всё, что
// пишут не в лоб: «БЛЯДЬ», «бл@дь», «б л я д ь».
//
// Второй способ, который здесь применялся сначала: свести слово к основе
// (вырезать гласные) и искать основу подстрокой. Он ловит маскировку, но
// калечит обычные слова, и это обнаружил тест: из «идиот» остаётся «дт»,
// из «ебал» — «бл», а «дот» превращается в ту же «дт». Под фильтр попадали
// слова, в которых нет ничего плохого, а игрок, чьё обычное слово
// заменялось звёздочками, бросал бы чат вообще — то есть фильтр без
// ложных срабатываний строго полезнее фильтра с ними.
//
// Поэтому проверка двухчастная:
//
//   1. ТОЧНОЕ совпадение нормализованного слова — «хуй», «блядь».
//      Работает при любом регистре, раскладке, повторах и разделителях
//      внутри слова. Ничего лишнего не задевает по построению: «дот» и
//      «идиот» — разные слова, а не одна основа.
//
//   2. ОСНОВА как подстрока, но только для основ от MIN_STEM_LENGTH
//      букв. Короткие основы отбрасываются: именно они и роняли «дот».
//      Длинная основа «блдъ» внутри «сукаблядь» по-прежнему ловится.
//
// Проверка идёт по буквам всего сообщения подряд, а не по словам: так
// ловится и «б л я д ь», где буквы расставлены пробелами.
//
// ОГРАНИЧЕНИЕ, О КОТОРОМ ЧЕСТНО ПРЕДУПРЕЖДАЕМ. Обход, разбивающий слово
// точками («б.л.я.д.ь»), фильтр не видит: точки съедаются при нормализации,
// и совпадение находится, но помечаются все пять отдельных букв, а не
// слово. Полная неуязвимость к маскировке недостижима без модератора —
// поэтому список короткий, а рядом есть жалобы.
//
// Список вынесен в отдельный файл, чтобы администратор мог расширять его
// без правки логики фильтра. Слово «кринж», «имба», «лут» в него не
// входит: игровой сленг — основа разговора в чате, и фильтр не должен
// становиться инструментом цензуры.
export const CHAT_BLOCKLIST: readonly string[] = [
  // ── Русский мат ────────────────────────────────────────────
  // Внутри одной основы слова-синонимы держатся по одному: «ебан» и
  // «уёбан» дают одну основу «бн», и вторая копия в списке бесполезна.
  // Синонимы с РАЗНЫМИ основами оставляем все: «уебать» и «заебать»
  // склеиваются по-разному.
  'блядь', 'хуй', 'хуя', 'хуевина', 'хуес', 'пизда', 'ебан',
  'сука', 'сучка', 'мудак', 'мудила', 'гандон',
  'долбоёб', 'уебать', 'чмошник', 'ублюдок',
  'мразь', 'сволочь', 'тварь', 'крыса', 'подонок', 'урод', 'идиот', 'дебил',
  'залупа', 'дрочить', 'выебать', 'выебан', 'заебать',

  // ── Английский мат ─────────────────────────────────────────
  // 'fuck' и 'fuk'/'fck' дают разные основы, поэтому все три нужны
  'fuck', 'fucking', 'fuk', 'shit', 'bitch', 'cunt', 'asshole',
  'bastard', 'whore', 'slut', 'wanker', 'dickhead', 'motherfucker',

  // ── Азербайджан ────────────────────────────────────────────
  'orospu', 'qadini', 'deyi', 'bic', 'sik',
];

/** Гласные трёх языков; ё идёт вместе с е */
const VOWELS = 'аеёиоуыэюяаеиоуыaeiouy';

/**
 * Короткая основа НЕ ищется подстрокой.
 *
 * Обоснование — в комментарии наверху файла: «идиот» даёт «дт»,
 * «ебал» — «бл», и такие короткие основы встречаются внутри обычных
 * слов. Для точного совпадения (первая часть проверки) длина значения
 * не важна, ограничение касается только подстроки.
 */
export const MIN_STEM_LENGTH = 4;

/**
 * Нормализовать слово: только буквы, нижний регистр, повторы схлопнуты.
 *
 * Схлопывание обязано идти ДО сравнения с гласными: иначе «бляяяаадь»
 * дала бы «блять» и не совпала бы с «блядь».
 *
 * «ь» приводится к «ъ»: в слове «блядь» мягкий знак, в маскировке
 * «бл@дъ» — твёрдый, и без этого нормализация не сойдётся.
 */
export function normalizeWord(word: string): string {
  const letters = word.toLowerCase().replace(/[^a-zа-яё]/g, '');
  return letters.replace(/(.)\1+/g, '$1').replace(/ь/g, 'ъ');
}

/** Основа слова: нормализованное слово без гласных */
export function stemWord(word: string): string {
  return normalizeWord(word).replace(new RegExp(`[${VOWELS}]`, 'g'), '');
}

/** Слова, которые ловим точно — как есть, по границам слов */
export const CHAT_BLOCK_WORDS: ReadonlySet<string> = new Set(
  CHAT_BLOCKLIST.map(normalizeWord).filter((s) => s.length > 0),
);

/** Основы, которые ищем подстрокой — только длинные, короткие отброшены */
export const CHAT_BLOCK_STEMS: ReadonlySet<string> = new Set(
  CHAT_BLOCKLIST.map(stemWord).filter((s) => s.length >= MIN_STEM_LENGTH),
);

interface Token {
  /** Нормализованное слово — для сравнения */
  norm: string;
  /** Начало и конец в НОРМАЛИЗОВАННОМ сообщении */
  from: number;
  to: number;
}

/**
 * Отфильтровать сообщение.
 *
 * Возвращает текст, где сработавшие слова заменены звёздочками той же
 * длины, и число срабатываний. Слово не вырезается целиком: игрок должен
 * видеть, что написал, иначе решит, что у него отвалился чат.
 *
 * Сравнение идёт по СКЛЕЕННОМУ тексту букв, а не по словам по отдельности.
 * Так ловится «бл@дь» и «б л я д ь»: знак препинания и пробелы исчезают
 * при нормализации, и запрещённое оказывается одним куском. Обратная
 * задача тоже решена: найденный диапазон в склейке переносится обратно
 * на слова, и маскируются именно те, которых он коснулся.
 *
 * ОСНОВА ИЩЕТСЯ В ОСНОВЕ, А НЕ В СКЛЕЙКЕ. Это отличие стоило двух часов
 * отладки. В склейке «б л я д ь» остаётся «блядъ», а основа слова
 * «блядь» — «блдъ»: поиск «блдъ» в «блядъ» не находит ничего, и весь
 * обход с разбиением слова проходил мимо. Поэтому склейка сводится к
 * основе, а параллельно строится карта «позиция в основе → позиция в
 * склейке»: по ней найденное переносится обратно на слова.
 */
export function filterChatMessage(text: string): { text: string; hits: number } {
  // Слова исходного текста вместе с позициями: маскировать нужно именно их
  const words = [...text.matchAll(/[\p{L}\p{M}][\p{L}\p{M}'’-]*/gu)];
  if (words.length === 0) return { text, hits: 0 };

  const tokens: Token[] = [];
  let joined = '';
  for (const w of words) {
    const norm = normalizeWord(w[0]);
    const from = joined.length;
    joined += norm;
    if (norm) tokens.push({ norm, from, to: joined.length });
  }
  if (!joined) return { text, hits: 0 };

  /** Пометить все слова, которых касается диапазон [from, to) */
  const mark = (from: number, to: number, into: Set<number>): void => {
    tokens.forEach((tok, k) => {
      if (tok.to > from && tok.from < to) into.add(k);
    });
  };

  const blocked = new Set<number>();

  // 1. Точное совпадение — только целым словом. Иначе «хуй» нашлось бы
  //    внутри «мухин», а это не то же самое слово
  tokens.forEach((tok, k) => {
    if (CHAT_BLOCK_WORDS.has(tok.norm)) blocked.add(k);
  });

  // 2. Основа склейки + карта позиций обратно в склейку
  const stemOfJoined: string[] = [];
  const stemToJoined: number[] = [];
  for (let i = 0; i < joined.length; i++) {
    if (!VOWELS.includes(joined[i])) {
      stemOfJoined.push(joined[i]);
      stemToJoined.push(i);
    }
  }
  const stemmed = stemOfJoined.join('');

  for (const stem of CHAT_BLOCK_STEMS) {
    if (stem.length < MIN_STEM_LENGTH) continue;
    let at = stemmed.indexOf(stem);
    while (at !== -1) {
      const first = stemToJoined[at];
      const last = stemToJoined[at + stem.length - 1];
      // Всё слово, а не только совпавшие буквы: игрок должен увидеть
      // замаскированное слово целиком, иначе останется огрызок
      mark(tokens.find((t) => t.to > first && t.from <= first)?.from ?? first,
        (tokens.find((t) => t.from <= last && t.to > last)?.to ?? last + 1), blocked);
      at = stemmed.indexOf(stem, at + stem.length);
    }
  }

  if (blocked.size === 0) return { text, hits: 0 };

  // Маскируем справа налево.
  //
  // ТУТ БЫЛА ОШИБКА, ЕЁ ПОЙМАЛ ТЕСТ. Массив слов был развёрнут, а индексы
  // blocked — исходные. В итоге звёздочки вставали на чужие слова: вместо
  // «блядь» маскировалось «за» из соседней фразы, а само слово оставалось
  // написанным как есть. Слова и их индексы теперь идут вместе, а порядок
  // обхода (справа налево) задаётся циклом, а не разворотом массива.
  //
  // Длина замены равна длине слова — звёздочка на букву, — поэтому позиции
  // не «уезжают» и никакой поправки на сдвиг не нужно вовсе.
  let result = text;
  for (let k = words.length - 1; k >= 0; k--) {
    if (!blocked.has(k)) continue;
    const w = words[k];
    const at = w.index ?? 0;
    result = result.slice(0, at) + '*'.repeat(w[0].length) + result.slice(at + w[0].length);
  }
  return { text: result, hits: blocked.size };
}
