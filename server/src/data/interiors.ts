export interface InteriorDef {
  id: string;
  /** Центр комнаты (клиент телепортируется в spawn, сервер проверяет bounds). */
  roomCx: number;
  roomCz: number;
  roomHalf: number;
  /** Точка появления внутри. */
  spawnX: number;
  spawnZ: number;
  /** Дверь снаружи: вход разрешён, только если игрок рядом. */
  doorX: number;
  doorZ: number;
  /** Точка выхода снаружи. */
  exitX: number;
  exitZ: number;
}

