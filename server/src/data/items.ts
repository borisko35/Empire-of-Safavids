export function getItem(id: string): Item | undefined {
  return ITEMS_DATABASE[id];
}

export function getItemsByType(type: ItemType): Item[] {
  return Object.values(ITEMS_DATABASE).filter(i => i.type === type);
}

export function getItemsByRarity(rarity: ItemRarity): Item[] {
  return Object.values(ITEMS_DATABASE).filter(i => i.rarity === rarity);
}

export function getItemsByLevel(minLevel: number, maxLevel: number): Item[] {
  return Object.values(ITEMS_DATABASE).filter(
    i => i.level >= minLevel && i.level <= maxLevel
  );
}
