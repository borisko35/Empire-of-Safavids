// Перевод ответа Epoint в наш договор платежа.
//
// ГЛАВНОЕ, ЧТО ЗДЕСЬ РЕШЕНО. В документе есть код 000 «подтверждено» и
// рядом коды 500 «согласовано, в балансе», 501 «согласовано, вне баланса»,
// 502 «сумма не согласована». Из этого следует, что банк может подтвердить
// платёж, а деньги на баланс Epoint ещё не пришли. Зачислять по коду 000
// означало бы выдать валюту за деньги, которых у нас ещё нет.
//
// Поэтому решение принимает ПОЛЕ status, а code - это код ответа банка,
// из него берётся причина для показа игроку. Ещё одно: у 000 в документе
// на странице 16 написано «000 - удачное выполнение операции», то есть то же
// самое поле в разных методах значит разное. Ориентироваться на него нельзя.
'use strict';

export type EpointStatus = 'completed' | 'failed' | 'pending' | 'unknown';

export interface EpointPaymentResult {
  /** Решение для нашего платёжного пути. */
  kind: EpointStatus;
  /** Код ответа банка - строкой, потому что приходит строкой и может быть не '000'. */
  code: string | null;
  /** Текст для игрока. Наш, а не банковский. */
  message: string;
  /**
   * Сумма, которую подтвердил провайдер, - в манатах.
   * null означает «провайдер сумму не вернул», и это НЕ то же самое, что 0.
   */
  amount: number | null;
  /** Номер операции в системе Epoint: то, что идёт в provider_payment_id. */
  transaction: string | null;
  /** Наш order_id из ответа - по нему платёж опознаётся без догадок. */
  orderId: string | null;
  /** Банковский код ответа в исходном виде - для журнала. */
  bankCode: string | null;
  bankTransaction: string | null;
}

function must(условие: unknown, причина: string): void {
  if (!условие) throw new Error(причина);
}

/**
 * Коды банка, которые игроку бесполезно показывать.
 *
 * Тексты в документе на русском и относятся к банку: «подозрение в
 * мошенничестве», «нарушение безопасности», «превышена частота вывода».
 * Игрок с этим ничего сделать не может. Показать ему такое - значит
 * переложить на него проблему, которую нельзя решить. Такие коды уходят в
 * журнал, а игрок получает нейтральное сообщение.
 *
 * Свой код - 109 «недействительный торговец», 918-919 про ключи - это уже
 * НАША ошибка: ключи не заданы, рассинхронизированы или торговец не тот.
 * Игроку про это сказать нечего, но в журнал это обязано попасть как
 * тревога, а не как отказ платежа.
 */
const КОДЫ_НЕПОНЯТНЫЕ_ПОКУПАТЕЛЮ = new Set([
  '102', '103', '105', '106', '107', '108', '109', '113', '115', '122',
  '123', '124', '129', '203', '204', '205', '206', '207', '210', '300',
  '301', '302', '303', '304', '305', '306', '307', '308', '309', '601',
  '602', '603', '604', '605', '606', '680', '681', '900', '901', '902',
  '903', '904', '905', '906', '907', '908', '909', '910', '911', '912',
  '913', '914', '915', '916', '917', '918', '919', '920', '921', '922',
  '923', '950',
]);

/** Коды, где виноват банк, а не покупатель: переспрашиваем другую карту. */
const КОДЫ_ПРО_КАРТУ = new Set([
  '104', '111', '112', '117', '118', '119', '120', '125', '126', '127',
  '128', '208', '209', '210', '111',
]);

/** Код 923 «запрос в процессе» - платёж ещё ждёт, это не отказ. */
const КОД_В_ПРОЦЕССЕ = '923';

function текстДляИгрока(code: string | null): string {
  if (code === null) return 'Платёж не прошёл. Попробуйте позже.';
  if (КОДЫ_ПРО_КАРТУ.has(code)) return 'Банк отклонил карту. Попробуйте другую карту.';
  if (code === '110') return 'Банк отклонил сумму платежа.';
  if (code === '116') return 'Недостаточно средств на карте.';
  if (code === '101') return 'Срок действия карты истёк.';
  if (code === '180') return 'Платёж отклонён.';
  if (code === КОД_В_ПРОЦЕССЕ) return 'Платёж ещё обрабатывается банком.';
  if (КОДЫ_НЕПОНЯТНЫЕ_ПОКУПАТЕЛЮ.has(code)) {
    // Банковские подробности игроку ничего не дают. Показываем нейтральное
    // и добавляем, что можно написать в поддержку.
    return 'Платёж отклонён банком. Попробуйте другую карту или напишите в поддержку.';
  }
  if (code === '000') return 'Платёж не завершён банком. Попробуйте позже.';
  return 'Платёж отклонён банком. Попробуйте другую карту или напишите в поддержку.';
}

/**
 * Сумма из ответа.
 *
 * Возвращает null, когда суммы нет или она не число. Молчаливый 0 здесь
 * опасен: нулевая сумма это «зачислить ничего», а null это «провайдер не
 * сказал». Разница видна только в тексте ошибки, и без неё нулевая сумма
 * выглядит как настоящая.
 */
function суммаИз(value: unknown): number | null {
  if (typeof value === 'number' && Number.isFinite(value)) return value;
  if (typeof value === 'string' && value.trim() !== '') {
    const n = Number(value);
    if (Number.isFinite(n)) return n;
  }
  return null;
}

function строка(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null;
}

/**
 * Ответ провайдера -> решение для нашего платёжного пути.
 *
 * status берётся из поля status и сравнивается со словом success. Именно
 * status, а не code: код 000 означает подтверждение БАНКА, а решение о том
 * пришли ли деньги, принимает сервис Epoint и сообщает его в status.
 */
export function epointResultToEvent(body: unknown): EpointPaymentResult {
  must(body !== null && typeof body === 'object', 'ответ Epoint не объект');
  const o = body as Record<string, unknown>;
  const code = строка(o.code);
  const status = строка(o.status)?.toLowerCase() ?? null;

  let kind: EpointStatus;
  if (status === 'success') {
    kind = 'completed';
  } else if (code === КОД_В_ПРОЦЕССЕ) {
    // ПРОВЕРЯЕТСЯ ДО ВЕТКИ 'error', и это не перестановка для удобства.
    // Код 923 «запрос в процессе» стоит в общем списке банковских кодов, и
    // если сначала проверять status === 'error', он попадал бы в отказ:
    // игроку показывали «отклонено» в момент, когда платёж ещё в работе, и
    // он платил бы второй раз. Такое и случалось - проверка это поймала.
    kind = 'pending';
  } else if (status === 'failed' || status === 'error') {
    kind = 'failed';
  } else if (status === null && code === null) {
    // Ни статуса, ни кода: сказать «не прошло» - значит выдумать причину.
    // Такое бывает при обрезанном ответе, и честное здесь - не догадываться.
    kind = 'unknown';
  } else {
    kind = 'failed';
  }

  return {
    kind,
    code,
    message: kind === 'completed' ? 'Оплата подтверждена' : текстДляИгрока(code),
    amount: суммаИз(o.amount),
    transaction: строка(o.transaction),
    orderId: строка(o.order_id),
    bankCode: code,
    bankTransaction: строка(o.bank_transaction),
  };
}

/** Ручной возврат: те же коды, но решение принимает администратор. */
export function epointIsBankInternalError(code: string | null): boolean {
  // 109 - недействительный торговец, 122 - нарушение безопасности,
  // 918-919 - ключи. Всё это наша сторона, и в журнале это должно читаться
  // как тревога, а не как отказ платежа покупателя.
  if (code === null) return false;
  return ['109', '122', '918', '919', '920'].includes(code);
}
