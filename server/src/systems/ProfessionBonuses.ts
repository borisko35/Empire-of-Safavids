// ============================================================
// Бонусы профессий — Empire of Safavids
// ============================================================
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Шесть профессий были описаны игроку словами
// («Скидка 10% на все покупки», «Зелья действуют на 20% сильнее»), и эти
// слова не делали ровно ничего: ни одно описание не было связано с кодом.
// Текст, обещающий бонус, который не начисляется, хуже отсутствия текста —
// игрок тратит своё время, проверяя, и приходит к выводу, что его обманули.
//
// КАК УСТРОЕНО. Бонус зависит от уровня профессии, а не от самого факта
// выбора: иначе после первой прокачки профессия перестала бы что-то давать,
// и уровни были бы пустыми числами в панели. Каждая цифра — за один уровень
// профессии, и описания в PROFESSIONS обязаны совпадать с этим файлом.
//
// ПОТОЛОК И ГРАНИЦЫ. Уровень профессии зажат на 50 — столько же, сколько
// уровень навыка. Нижние границы скидки и удешевления не «про запас», а
// достижимы ровно на 50 уровне: 1% за уровень даёт 0.5 к цене, 1.2% даёт
// 0.4 к улучшению. Предыдущая версия держала потолок 20 при границах 0.5 и
// 0.4, то есть границы не могли сработать никогда: мёртвый код, который
// выглядел как защита экономики.
//
// ПРОВЕРЯЕМОСТЬ. Функция чистая: ни базы, ни времени. Поэтому бонусы
// перебираются числами в тесте, а не «на глаз».

export interface ProfessionBonuses {
  /** Итоговый множитель урона. 1 = без изменений. */
  damage: number;
  /** Множитель цены покупки. 1 = без скидки, 0.5 = вдвое дешевле. */
  price: number;
  /** Множитель лечения от зелий и настоек. */
  potion: number;
  /** Множитель опыта из заданий и убийств. */
  experience: number;
  /** Множитель стоимости улучшения вещей. */
  enhanceCost: number;
}

/** Потолок уровня профессии. Совпадает с потолком навыка. */
export const PROFESSION_MAX_LEVEL = 50;

/**
 * Бонусы по профессии и уровню.
 *
 * Профессия не выбрана или неизвестна — все множители единицы, то есть
 * бонусов нет. Возвращать тут нули было бы ошибкой: они умножались бы на
 * урон и цены и обнулили бы их.
 */
export function professionBonuses(professionId: string | null, level: number): ProfessionBonuses {
  const NONE: ProfessionBonuses = { damage: 1, price: 1, potion: 1, experience: 1, enhanceCost: 1 };
  if (!professionId) return NONE;
  // Уровень приходит из базы, где это обычная колонка: правка руками могла
  // оставить там 0, дробь или 999. Всё это обязано считаться, а не ломать
  // урон и экономику.
  const lv = Math.max(0, Math.min(PROFESSION_MAX_LEVEL, Math.floor(Number.isFinite(level) ? level : 0)));

  switch (professionId) {
    case 'warrior':
      // +2% урона за уровень: на 50 уровне вдвое больше базового удара.
      return { ...NONE, damage: 1 + 0.02 * lv };
    case 'archer':
      // Раньше обещали «точность на 20%». Точности в игре нет: снарядов
      // ещё не существует, а промах не моделируется, поэтому обещание было
      // пустым. Теперь обещают урон, и он считается по-настоящему.
      return { ...NONE, damage: 1 + 0.016 * lv };
    case 'merchant':
      // 1% за уровень, и на 50 ровно половина цены. Ниже не опускается:
      // бесплатные покупки обесценили бы золото.
      return { ...NONE, price: Math.max(0.5, 1 - 0.01 * lv) };
    case 'herbalist':
      return { ...NONE, potion: 1 + 0.024 * lv };
    case 'blacksmith':
      // Удешевление улучшения, а не запрет: игроки, которые уже улучшали
      // вещи без профессии, не должны потерять доступ задним числом.
      // 1.2% за уровень, на 50 — ровно 0.4.
      return { ...NONE, enhanceCost: Math.max(0.4, 1 - 0.012 * lv) };
    case 'explorer':
      return { ...NONE, experience: 1 + 0.016 * lv };
    default:
      // Неизвестная профессия из базы (переименовали или испортили вручную)
      // не должна ломать бой и экономику.
      return NONE;
  }
}
