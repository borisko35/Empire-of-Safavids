// ============================================================
// Репутация: за что и сколько
// ============================================================
//
// ЧТО БЫЛО. ReputationService.addReputation был написан целиком — поиск
// фракции, обновление записи, проверка нового ранга, уведомление о
// повышении. И его не вызывал НИКТО и НИГДЕ за всё время существования
// проекта. Панель репутации при этом была и показывала честные нули.
//
// Вдобавок маршрут отдавал сервису req.userId — идентификатор АККАУНТА,
// а сервис ищет по идентификатору ПЕРСОНАЖА (character_reputation.character_id).
// То есть даже если бы репутация начислялась, панель её не увидела бы.
// Ровно та же ошибка, что была с задачами дня.
//
// ЗДЕСЬ ЖИВУТ ВСЕ ЧИСЛА. Начисление размазано по обработчикам, и рано или
// поздно кто-то выбрал бы другую цифру для того же действия. Держим в одном
// месте: фракция, за что и сколько.

import { ReputationService } from '../services/ReputationService';

const reputation = new ReputationService();

/**
 * Сколько репутации даёт действие.
 *
 * Числа подобраны по разбросу рангов: первый ранг начинается со 100, а
 * высокий — с 1500. При +1 за монстра путь до «Адепта» занимает 100 убийств,
 * до «Мистика» — 300. Это примерно пара часов активной игры, то есть ранг
 * ощутим, но не выдаётся за полчаса.
 */
export const REP = {
  /** Убийство монстра в поле — Кизилбаши, воинское дело */
  monsterKill: { faction: 'qizilbash', amount: 1 },
  /** Пройденный данж — Кизилбаши */
  dungeonClear: { faction: 'qizilbash', amount: 10 },
  /** Выполненный квест — Суфии, они ищут знания */
  questDone: { faction: 'sufi', amount: 2 },
  /** Убийство игрока в PvP — Орден Ассасинов */
  pvpWin: { faction: 'assassins', amount: 5 },
  /** Продажа на аукционе — Торговцы Шёлкового пути */
  auctionSale: { faction: 'merchants', amount: 2 },
  /** Сделка с другим игроком — Торговцы */
  tradeDone: { faction: 'merchants', amount: 1 },
} as const;

export type RepKind = keyof typeof REP;

/**
 * Начислить репутацию, не давая действию упасть.
 *
 * Репутация — украшение, а не оплата: за убийство монстра игрок получает
 * опыт, золото и лут независимо от неё. Поэтому ошибка начисления
 * проглатывается с записью в журнал, а не ломает сам бой. И наоборот —
 * повышение ранга показывается игроку, потому что это единственный способ
 * узнать, что репутация вообще растёт.
 */
export async function grantReputation(
  characterId: string,
  kind: RepKind,
  onRankUp?: (factionId: string, rankRu: string) => void,
): Promise<void> {
  const { faction, amount } = REP[kind];
  try {
    const res = await reputation.addReputation(characterId, faction, amount);
    if (res.rankUp && res.newRank) onRankUp?.(faction, res.newRank);
  } catch (error) {
    console.warn('[Reputation] not granted:', error);
  }
}
