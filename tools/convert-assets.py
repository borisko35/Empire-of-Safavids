def прочитать_glb_json(путь):
    """Достать JSON-чанк GLB. Нужен, чтобы УВИДЕТЬ, что реально попало в файл."""
    with open(путь, "rb") as f:
        данные = f.read()
    if данные[:4] != b"glTF":
        raise SystemExit("НА ВЫХОДЕ НЕ GLB: %s" % путь)
    длина = int.from_bytes(данные[12:16], "little")
    if данные[16:20] != b"JSON":
        raise SystemExit("ПЕРВЫЙ ЧАНК НЕ JSON: %s" % путь)
    return json.loads(данные[20:20 + длина].decode("utf-8"))


def экспортировать(выход, формат):
    """Draco обязателен: на него завязана проверка в decorAssets.test.ts,
    и без него файл втрое тяжелее."""
    bpy.ops.export_scene.gltf(
        filepath=выход,
        export_format="GLB",
        use_selection=False,
        export_apply=True,
        export_draco_mesh_compression_enable=True,
        export_draco_mesh_compression_level=6,
        export_image_format=формат,
    )


# ─────────────────────────────────────────────────────────────────────────────
# Манифест. Правка точечная: переписывать его целиком нельзя, там руками
# разложены по разделам персонажи и клипы, которых конвертер не касается.
# ─────────────────────────────────────────────────────────────────────────────

def дописать_в_манифест(путь, раздел, имя, файл, замер, байты):
    """Дописать запись в manifest.json.

    Ключи — ЛАТИНИЦЕЙ и ровно те, что уже лежат в манифесте: `file`, `name`,
    `bytes`. Манифест читает код клиента и проверки, и он однородный: лишние
    поля в одной записи среди одинаковых соседей выглядят как ошибка, а
    подробные замеры (габариты, грани, текстуры) им и не нужны — им место в
    отчёте рядом с моделью, он для того и пишется.
    """
    with open(путь, "r", encoding="utf-8") as f:
        манифест = json.load(f)
    записи = манифест.setdefault(раздел, [])
    новая = {
        "file": файл.replace("\\", "/"),
        "name": имя,
        "bytes": байты,
    }
    for i, з in enumerate(записи):
        if з.get("name") == имя:
            записи[i] = новая
            break
    else:
        записи.append(новая)
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(манифест, f, ensure_ascii=False, indent=2)
    return новая


# ─────────────────────────────────────────────────────────────────────────────

def main():
    режим, позиционные, ключи = аргументы()
    if режим.upper() != "DECOR":
        usage()
        sys.exit(2)
    if len(позиционные) < 2:
        print("НУЖНЫ ВХОД И ВЫХОД: DECOR <вход.fbx> <выход.glb>")
        sys.exit(2)

    вход, выход = позиционные[0], позиционные[1]
    if not os.path.exists(вход):
        sys.exit("НЕТ ФАЙЛА НА ВХОДЕ: %s" % вход)
    os.makedirs(os.path.dirname(os.path.abspath(выход)), exist_ok=True)

    сторона = int(ключи.get("tex", "1024") or "0")
    бюджет = int(ключи.get("budget", "0") or "0")

    импортер, добавленные = импортировать(вход)
    if ключи.get("only"):
        отброшено = оставить_только(ключи["only"])
        print("ONLY %s -> оставлено %d, убрано %d"
              % (ключи["only"],
                 len([o for o in bpy.data.objects if o.type == "MESH"]),
                 len(отброшено)))
    сдвиг = в_начало_координат() if ключи.get("center", "1") != "0" else None
    if сдвиг:
        print("CENTERED %s" % сдвиг)
    выкинуто = выкинуть_пустое()

    отчёт = {
        "src": os.path.basename(вход),
        "ext": os.path.splitext(вход)[1].lower(),
        "importer": импортер,
        "dropped": выкинуто,
        "scene_before": {"objects": len(добавленные)},
        "only": ключи.get("only"),
        "centered_by": сдвиг,
        "measure_before": замерить(),
        "textures_before": собрать_текстуры(),
    }

    отчёт["textures_downscaled"] = len(уменьшить(отчёт["textures_before"], сторона))
    развёрнуто = сделать_трёхканальными()
    if развёрнуто:
        print("PROMOTED_TO_RGB %d" % len(развёрнуто))
    отчёт["promoted_to_rgb"] = развёрнуто
    # Сколько РАЗНЫХ карт glTF действительно увезёт. Это число — эталон,
    # с которым сверяется готовый файл.
    отчёт["textures_referenced"] = сколько_карт_просят()

    дец, до, после = децимовать(бюджет)
    if дец is not None:
        дец["src"] = отчёт["src"]
        дец["before"] = до
        с_путём = выход + ".decimate.json"
        with open(с_путём, "w", encoding="utf-8") as f:
            json.dump(дец, f, ensure_ascii=False, indent=2)
        print("DECIMATE_WRITTEN %s" % с_путём)

    # ─── Экспорт: формат выбирается сверкой, а не верой ───
    #
    # WebP меньше и он хочется. Но он не умеет одноканальные карты, а
    # экспортёр в этом случае НЕ ПРЕКРАЩАЕТ РАБОТУ: пишет в лог строчку и
    # едет дальше, унося модель без карты. Поэтому сначала экспорт в
    # эталонный JPEG, потом в WebP, и WebP принимается, только если положил
    # карт не меньше. Разница в весе — единицы процентов, а потеря карты
    # шероховатости видна как «пластик, который не туда блестит».
    порядок = ["WEBP", "JPEG"]
    if ключи.get("image_format"):
        порядок = [ключи["image_format"].upper()]
    формат, пробы = сравнение_форматов(выход, порядок)
    отчёт["export_format"] = формат
    отчёт["export_tried"] = пробы
    print("EXPORT_FORMAT %s" % формат)

    байты = os.path.getsize(выход)
    отчёт["export_dropped"] = []
    отчёт["measure"] = замерить()
    отчёт["textures"] = собрать_текстуры()
    отчёт["glb_mb"] = round(байты / 1048576.0, 2)
    отчёт["src_mb"] = round(os.path.getsize(вход) / 1048576.0, 2)

    gltf = прочитать_glb_json(выход)
    в_файле = gltf.get("images", [])
    отчёт["images_in_glb"] = len(в_файле)
    отчёт["images_in_glb_names"] = sorted(str(i.get("name")) for i in в_файле)
    отчёт["textures_lost"] = []

    # ─── Отчёт пишется ДО проверок ───
    #
    # Отчёт нужен именно тогда, когда всё плохо: потерянная карта — это
    # причина искать, а не повод не записывать, что искать. Раньше при
    # аварийном выходе файла не было вовсе, и разбираться приходилось по
    # логу экспортёра, где нужная строчка терялась среди десятков.
    с_отчётом = выход + ".report.json"
    with open(с_отчётом, "w", encoding="utf-8") as f:
        json.dump(отчёт, f, ensure_ascii=False, indent=2)
    print("REPORT_WRITTEN %s" % с_отчётом)

    # Главная проверка: выбранный формат не должен быть беднее любого из
    # пробанных. То есть потерь нет, если мы взяли лучший результат.
    лучший = max(п["images"] for п in пробы)
    if отчёт["images_in_glb"] < лучший:
        print("!! ПОТЕРЯ КАРТ: выбран %s положил %d, лучший пробанный %d"
              % (формат, отчёт["images_in_glb"], лучший))
        print("!! Смотри отчёт: %s" % с_отчётом)
        sys.exit(3)

    if отчёт["measure"]["meshes"] == 0:
        print("!! НИ ОДНОГО МЕША НА ВЫХОДЕ: импорт не дал геометрии")
        sys.exit(3)

    м = отчёт["measure"]
    print("DECOR %s meshes=%d verts=%d faces=%d bbox=%s tex=%d glb=%.2fMB"
          % (отчёт["src"], м["meshes"], м["verts"], м["faces"], м["bbox_m"],
             len(отчёт["textures"]), отчёт["glb_mb"]))

    манифест = ключи.get("manifest")
    if манифест:
        имя = ключи.get("name") or os.path.splitext(os.path.basename(выход))[0]
        раздел = ключи.get("section") or "decor"
        новая = дописать_в_манифест(
            манифест, раздел, имя,
            os.path.relpath(выход, os.path.dirname(os.path.abspath(манифест)) + "/.."),
            м, байты,
        )
        print("MANIFEST_WRITTEN %s %s" % (раздел, имя))


if __name__ == "__main__":
    main()