def аргументы():
    argv = sys.argv
    if "--" in argv:
        argv = argv[argv.index("--") + 1:]
    else:
        argv = []
    if not argv:
        usage()
        sys.exit(2)
    режим = argv[0]
    позиционные = [a for a in argv[1:] if not a.startswith("--")]
    ключи = {}
    i = 1
    while i < len(argv):
        if argv[i].startswith("--"):
            ключи[argv[i][2:]] = argv[i + 1] if i + 1 < len(argv) else ""
            i += 2
        else:
            i += 1
    return режим, позиционные, ключи


def usage():
    print(__doc__)
    print("РЕЖИМЫ: DECOR (декорация) — пока единственный.")


# ─────────────────────────────────────────────────────────────────────────────
# Импорт. Расширение решает, какой импортер звать: glTF и FBX — разные операторы.
# ─────────────────────────────────────────────────────────────────────────────

def очистить_сцену():
    """Убрать ВСЁ, что было в файле до импорта.

    Запускаем в `--factory-startup`, а там уже лежит стартовая сцена: куб,
    камера и лампа. Если её не вычистить, куб едет в модель вместе с
    содержимым. Это не гипотеза — так и случилось при первой сборке этого
    конвертера: в отчёте по мосту было 8 мешей вместо 7, и габариты по Z
    выходили 3.537 м вместо настоящих 2.537 — ровно на 1.0 м, то есть на
    половину куба, торчащего из-под моста.

    И это молчащая поломка худшего рода: куб маленький, на мосту почти не
    виден, но он попадает в bbox, а bbox потом ставит коллайдеры и масштаб.
    """
    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    for меш in list(bpy.data.meshes):
        if меш.users == 0:
            bpy.data.meshes.remove(меш)


def импортировать(путь):
    очистить_сцену()
    before = set(bpy.data.objects)
    if путь.lower().endswith(".fbx"):
        bpy.ops.import_scene.fbx(filepath=путь)
        импортер = "import_scene.fbx"
    elif путь.lower().endswith((".glb", ".gltf")):
        bpy.ops.import_scene.gltf(filepath=путь)
        импортер = "import_scene.gltf"
    else:
        raise SystemExit("НЕ ПОНИМАЮ ФОРМАТ: %s. Жду .fbx, .glb или .gltf" % путь)
    added = [o for o in bpy.data.objects if o not in before]
    return импортер, added


def оставить_только(шаблон):
    """Оставить в сцене только меши, чьё имя подходит под шаблон.

    Нужно для наборов, где один FBX на двести объектов, а в игру нужен один:
    в пакете укреплений `Wall-Type01` едет рядом с воротами, бастионами,
    текстом и ещё пятнадцатью кусками, и всё это в одну модель не годится.
    Отбор идёт ПОСЛЕ импорта и ДО замеров, иначе габариты в отчёте были бы
    габаритами всего пакета, а не выбранного куска.
    """
    ре = re.compile(шаблон, re.IGNORECASE)
    убрано = []
    for obj in list(bpy.data.objects):
        if obj.type == "MESH" and not ре.search(obj.name):
            убрано.append(obj.name)
            bpy.data.objects.remove(obj, do_unlink=True)
    return убрано


def в_начало_координат():
    """Сдвинуть всё так, чтобы основание стояло в нуле, а модель была в центре.

    Модели из готовых наборов стоят как их автор их разложил: у стены из пакета
    укреплений нижняя точка на y = 10.17, а по x она стоит на 53.7. Такую
    модель нельзя поставить на землю «как есть» — она уедет на десяток метров
    вбок и на десяток вверх, и это выглядит как «модель сломалась», а не как
    «начало координат не в основании».

    Ось Y прижимается НИЗОМ к нулю, X и Z — центром. Именно так ожидает
    код игры: существующие декорации уже сходятся в этой конвенции.
    """
    меши = [o for o in bpy.data.objects if o.type == "MESH"]
    if not меши:
        return None
    bb = [o.matrix_world @ Vector(c) for o in меши for c in o.bound_box]
    мин = [min(v[k] for v in bb) for k in range(3)]
    макс = [max(v[k] for v in bb) for k in range(3)]
    сдвиг = Vector((
        -(мин[0] + макс[0]) / 2.0,
        -мин[1],
        -(мин[2] + макс[2]) / 2.0,
    ))
    for o in меши:
        o.location = o.location + сдвиг
    return [round(v, 3) for v in сдвиг]


def выкинуть_пустое():
    """Убрать объекты без геометрии: камеры, лайты, пустые узлы FBX.

    Они не вредят сами по себе, но попадают в отчёт как «объекты» и сбивают
    с толку того, кто потом читает замер.
    """
    выкинуто = []
    for obj in list(bpy.data.objects):
        if obj.type == "MESH" and len(obj.data.polygons) > 0:
            continue
        выкинуто.append(obj.name)
        bpy.data.objects.remove(obj, do_unlink=True)
    return выкинуто


# ─────────────────────────────────────────────────────────────────────────────
# Замеры. Габариты в МЕТРАХ — это то, на что потом ставят коллайдеры.
# ─────────────────────────────────────────────────────────────────────────────

def замерить():
    минимум = [float("inf")] * 3
    максимум = [float("-inf")] * 3
    меши = вершины = грани = 0
    for obj in bpy.data.objects:
        if obj.type != "MESH" or obj.hide_render:
            continue
        меши += 1
        вершины += len(obj.data.vertices)
        грани += len(obj.data.polygons)
        for угол in obj.bound_box:
            мир = obj.matrix_world @ __import__("mathutils").Vector(угол)
            for k in range(3):
                минимум[k] = min(минимум[k], мир[k])
                максимум[k] = max(максимум[k], мир[k])
    if меши == 0:
        return {
            "meshes": 0, "verts": 0, "faces": 0,
            "bbox_m": [0.0, 0.0, 0.0], "min": [0.0, 0.0, 0.0], "max": [0.0, 0.0, 0.0],
        }
    return {
        "meshes": меши,
        "verts": вершины,
        "faces": грани,
        "bbox_m": [round(максимум[k] - минимум[k], 3) for k in range(3)],
        "min": [round(минимум[k], 3) for k in range(3)],
        "max": [round(максимум[k], 3) for k in range(3)],
    }


# ─────────────────────────────────────────────────────────────────────────────
# Текстуры. Здесь и была молчаливая потеря.
# ─────────────────────────────────────────────────────────────────────────────

# Замечания о поведении экспортёра, найденные на живой модели, — чтобы их
# не выводили снова «из спецификации»:
#
#   * Metallic и Roughness glTF сводит в ОДНУ карту metallic-roughness.
#     На мосте это видно прямо в имени: mat_bridge_1_Metallic-mat_bridge_1_
#     Roughness. На две входные карты выходит одна выходная.
#   * Specular в 5.2 вывозится (KHR_materials_specular), хотя в списке
#     непереносимых разъёмов его нет. Раньше он там стоял — и мост с целым
#     файлом объявлялся «потерявшим карту».
#   * После импорта FBX лежат дубли карт под именами .001: экспортёр берёт
#     такую один раз, а счёт по именам насчитал бы две.
#
# Именно поэтому ожидаемое число карт НЕ вычисляется по этим правилам, а
# берётся сравнением пробных экспортов: см. сравнение_форматов.


def собрать_текстуры():
    """Карты, реально занятые материалами сцены, с их размером и числом каналов.

    Считаем именно занятые, а не все: в файле после импорта FBX часто лежат
    карты, на которые ни один материал не ссылается, и они никуда не поедут.
    """
    занятые = set()
    for mat in bpy.data.materials:
        if not mat.use_nodes:
            continue
        for node in mat.node_tree.nodes:
            if node.type == "TEX_IMAGE" and node.image is not None:
                занятые.add(node.image.name)
    out = []
    for img in bpy.data.images:
        if img.name not in занятые:
            continue
        out.append({
            "name": img.name,
            "w": img.size[0],
            "h": img.size[1],
            # channels — то самое, на чём WebP спотыкается.
            "channels": img.channels,
            "format": img.file_format,
            "packed": bool(img.packed_file),
        })
    out.sort(key=lambda t: t["name"])
    return out


def сколько_карт_просят():
    """Сколько карт вообще занято материалами. Только для отчёта.

    Это НЕ ожидаемое число карт в файле: glTF пакует Metallic и Roughness в
    одну карту, дубли base_color после импорта FBX схлопываются, часть
    разъёмов в glTF нет. Считать «сколько должно уехать» по правилам и
    сверять с файлом пробовали — и мост тут же объявил себя потерявшим
    текстуру при целом файле, то есть правило врало. Поэтому ожидаемое число
    берётся не из теории, а из живого файла, см. сравнение_форматов.
    """
    занятые = set()
    for mat in bpy.data.materials:
        if not mat.use_nodes:
            continue
        for node in mat.node_tree.nodes:
            if node.type == "TEX_IMAGE" and node.image is not None:
                занятые.add(node.image.name)
    return len(занятые)


def сравнение_форматов(выход, порядок):
    """Экспортировать в несколько форматов и оставить самый полный.

    Эталон — формат, который молча ничего не теряет (JPEG). Остальные
    форматы принимаются, только если положили в файл столько же карт.
    Так правило не гадает, а сравнивает: «сколько карт может эта модель
    отдать» отвечает не эвристика, а сам экспортёр.

    Отдельно важно, что потеря здесь молчаливая. При одноканальной карте
    экспортёр пишет в лог «Image data is empty» и ЕДЕТ ДАЛЬШЕ, так что
    «экспорт прошёл без ошибок» здесь не значит «модель целая».
    """
    результаты = []
    лучший = None
    for формат in порядок:
        экспортировать(выход, формат)
        карты = len(прочитать_glb_json(выход).get("images", []))
        результаты.append({"format": формат, "images": карты})
        print("EXPORT_TRIED %s -> %d карт" % (формат, карты))
        if лучший is None or карты > результаты[лучший]["images"]:
            лучший = len(результаты) - 1
    # Переэкспортировать в лучший: предыдущий файл мог быть худшим.
    экспортировать(выход, результаты[лучший]["format"])
    return результаты[лучший]["format"], результаты


def сделать_трёхканальными():
    """Развернуть одноканальные карты в RGB.

    Откуда проблема. Экспортёр glTF пишет текстуры в WebP, а WebP не умеет
    одноканальные изображения — это карты шероховатости, металлисн��сти и
    прочие маски, у которых цветом считать нечего. OpenImageIO отказывается
    писать, экспортёр логирует «Image data is empty, not exporting image» и
    едет дальше. Модель уезжает без этой карты, и по отчёту это не видно:
    текстура в списке есть, в файле её нет.

    Поэтому одноканальную карту надо развернуть ЗДЕСЬ, до экспорта: сделать
    из неё обычную RGB, и WebP её уже принимает. Размер вырастет, но карта
    поедет, а не исчезнет.
    """
    развёрнуто = []
    for img in list(bpy.data.images):
        if img.channels >= 3:
            continue
        w, h = img.size
        if w == 0 or h == 0:
            continue
        пиксели = [0.0] * (w * h * 4)
        img.pixels.foreach_get(пиксели)
        новый = bpy.data.images.new(img.name + ".rgb", w, h, alpha=False)
        новый.pixels.foreach_set(пиксели)
        # Подменить во всех узлах, где на карту ссылаются.
        замен = 0
        for mat in bpy.data.materials:
            if not mat.use_nodes:
                continue
            for node in mat.node_tree.nodes:
                if node.type == "TEX_IMAGE" and node.image is img:
                    node.image = новый
                    замен += 1
        новый.pack()
        развёрнуто.append({"была": img.name, "каналов": img.channels, "замен": замен})
        bpy.data.images.remove(img)
    return развёрнуто


def уменьшить(текстуры, сторона):
    """Почистить текстуры по размеру. Возвращает список тех, кто не уменьшился."""
    не_уменьшились = []
    for t in текстуры:
        img = bpy.data.images.get(t["name"])
        if img is None:
            continue
        if сторона <= 0:
            continue
        if max(img.size) <= сторона:
            continue
        # scale() берёт РОВНО эти пиксели, пропорция теряется. Считаем сами,
        # иначе квадратная карта 8192 станет 1024×612, и при растяжении на
        # модель видно, что текстура «сжата по одной оси».
        w, h = img.size
        множитель = сторона / float(max(w, h))
        new_w = max(1, int(round(w * множитель)))
        new_h = max(1, int(round(h * множитель)))
        img.scale(new_w, new_h)
        t["w"], t["h"] = new_w, new_h
        if max(img.size) > сторона:
            не_уменьшились.append(t["name"])
    return не_уменьшились


# ─────────────────────────────────────────────────────────────────────────────
# Децимация. Отдельным шагом, потому что бюджет граней и бюджет текстур —
# разные ручки.
# ─────────────────────────────────────────────────────────────────────────────

def децимовать(бюджет):
    """Свести суммарные грани к бюджету. Меньше — не трогаем: модель уже лёгкая.

    Соотношение берём по граням всех мешей сразу и применяем ко всем: иначе
    один огромный меш схлопнется, а мелкие детали (резьба, болты) рассыплются
    сильнее, чем нужно.
    """
    замер = замерить()
    до = {"verts": замер["verts"], "faces": замер["faces"]}
    if бюджет <= 0 or до["faces"] <= бюджет:
        return None, до, до
    доля = float(бюджет) / до["faces"]
    for obj in bpy.data.objects:
        if obj.type != "MESH" or not obj.data.polygons:
            continue
        bpy.ops.object.select_all(action="DESELECT")
        obj.select_set(True)
        bpy.context.view_layer.objects.active = obj
        bpy.ops.object.modifier_add(type="DECIMATE")
        mod = obj.modifiers.get("Decimate")
        if mod is None:
            continue
        mod.ratio = доля
        # UNSUBDIV перед децимацией: иначе на поделённой сетке децимация
        # считает подразделения, а не грани, и результат не совпадает с
        # заявленным бюджетом.
        mod.decimate_type = "UNSUBDIV"
        try:
            bpy.ops.object.modifier_apply(modifier=mod.name)
        except RuntimeError:
            bpy.ops.object.modifier_remove(modifier=mod.name)
    после = {"verts": замер["verts"], "faces": замер["faces"]}
    return {"budget_faces": бюджет, "ratio": round(доля, 4), "after": после}, до, после


