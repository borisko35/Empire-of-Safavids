const вид = process.argv[2];
const режим = process.argv[3] ?? 'проверка';
const принятьДанные = process.argv[4] === 'принять-данные';

if (!ВИДЫ[вид]) {
  console.error(`неизвестный вид: ${вид}. Доступны: ${Object.keys(ВИДЫ).join(', ')}`);
  process.exit(2);
}

const конфиг = ВИДЫ[вид];
const { [конфиг.ключ]: сущности } = require(конфиг.модуль);

/** Код языка для раздела: первый раздел — русский, второй — английский. */
function языкРаздела(индекс) {
  return индекс % 2 === 0 ? 'ru' : 'en';
}

/**
 * Строки блока: сущности из данных, затем — с сохранением — ключи, которые
 * сущностями не являются.
 *
 * ЗАЧЕМ. Имена существ и подписи интерфейса исторически живут в одном
 * разделе: в pets лежат и «Питомец переименован», и «Серый Волк». При
 * заполнении блок переписывается целиком, и ключи, которых нет в данных,
 * молча пропадали бы. С pets это стоило семи подписей интерфейса, и
 * выглядело как успешная работа — разделы заполнены, ключей столько же.
 *
 * Название раздела при этом всё равно не должно совпадать с чужим: даже с
 * сохранением смешивание разного смысла в одном разделе делает ключи
 * неразличимыми по имени.
 */
function собратьСтроки(код, имяРаздела, сущности, значения) {
  let порядок = [];
  try {
    порядок = блок.прочитатьБлок(код, имяРаздела).порядок;
  } catch {
    порядок = [];
  }
  const свои = new Set(сущности.map((с) => с.id));
  const посторонние = порядок.filter((k) => !свои.has(k));
  let текущие = {};
  try {
    текущие = блок.прочитатьБлок(код, имяРаздела).значения;
  } catch {
    текущие = {};
  }
  const строки = сущности.map((с) => `    ${строка(с.id)}: ${строка(значения[с.id])}`);
  for (const k of посторонние) {
    строки.push(`    ${строка(k)}: ${строка(текущие[k])}`);
  }
  if (посторонние.length) {
    console.log(`${код}.${имяРаздела}: сохранено посторонних ключей ${посторонние.length}: ${посторонние.join(', ')}`);
  }
  return строки;
}

if (режим === 'заполнить') {
  // Разделы идут парами: сначала ru, потом en для одного и того же блока.
  const сделано = new Map();
  конфиг.разделы.forEach((раздел, индекс) => {
    const код = языкРаздела(индекс);
    const уже = сделано.get(раздел.имя) ?? { ru: null, en: null };
    уже[код] = сущности.map(раздел.поле);
    сделано.set(раздел.имя, уже);
  });

  for (const [имяРаздела, значенияПоЯзыкам] of сделано) {
    for (const код of ['ru', 'en']) {
      let текущие = {};
      try {
        текущие = блок.прочитатьБлок(код, имяРаздела).значения;
      } catch {
        текущие = {};
      }
      const значения = {};
      const переписано = [];
      let добавлено = 0;
      сущности.forEach((сущность, i) => {
        const значение = значенияПоЯзыкам[код][i];
        if (typeof значение !== 'string' || значение === '') {
          throw new Error(`${код}.${имяРаздела}: нет значения у ${сущность.id}`);
        }
        if (текущие[сущность.id] !== undefined && текущие[сущность.id] !== значение) {
          if (!принятьДанные) {
            throw new Error(
              `${код}.${имяРаздела}: ${сущность.id} в словаре «${текущие[сущность.id]}», `
              + `в данных «${значение}» — расхождение`,
            );
          }
          переписано.push(`${сущность.id}: «${текущие[сущность.id]}» -> «${значение}»`);
        }
        if (текущие[сущность.id] === undefined) добавлено++;
        значения[сущность.id] = значение;
      });
      блок.заменитьБлок(код, имяРаздела, собратьСтроки(код, имяРаздела, сущности, значения));
      console.log(`${код}.${имяРаздела}: записей ${сущности.length}, добавлено ${добавлено}, переписано ${переписано.length}`);
      for (const стр of переписано) console.log(`   ${стр}`);
    }
  }
}

if (режим === 'применить-az') {
  const файл = JSON.parse(fs.readFileSync(path.join(__dirname, конфиг.azФайл), 'utf8'));
  // У лодок в файле два поля — название и описание, у рецептов одно.
  const имяРаздела = Object.keys(файл);
  for (const раздел of имяРаздела) {
    const пары = файл[раздел];
    let текущие = {};
    try {
      текущие = блок.прочитатьБлок('az', раздел).значения;
    } catch {
      текущие = {};
    }
    const значения = {};
    let взятоСтарых = 0;
    for (const сущность of сущности) {
      if (typeof пары[сущность.id] === 'string' && пары[сущность.id].trim() !== '') {
        значения[сущность.id] = пары[сущность.id];
      } else if (typeof текущие[сущность.id] === 'string' && текущие[сущность.id].trim() !== '') {
        значения[сущность.id] = текущие[сущность.id];
        взятоСтарых++;
      }
    }
    блок.заменитьБлок('az', раздел, собратьСтроки('az', раздел, сущности, значения));
    console.log(`az.${раздел}: записей ${сущности.length}, новых ${сущности.length - взятоСтарых}, взято из словаря ${взятоСтарых}`);
  }
}

if (режим === 'проверка') {
  let плохо = 0;
  for (const раздел of конфиг.разделы) {
    const имяРаздела = раздел.имя;
    const язык = языкРаздела(конфиг.разделы.indexOf(раздел));
    // ru и en делят один блок: проверяем оба языка по очереди.
    for (const код of new Set([язык, 'az'])) {
      let d = {};
      try {
        d = блок.прочитатьБлок(код, имяРаздела).значения;
      } catch {
        console.log(`${код}: раздела ${имяРаздела} нет`);
        плохо++;
        continue;
      }
      const нет = сущности.filter((с) => !(с.id in d));
      if (нет.length) {
        console.log(`${код}.${имяРаздела}: без перевода ${нет.length}: ${нет.map((с) => с.id).join(', ')}`);
        плохо++;
        continue;
      }
      for (const с of сущности) {
        if (typeof d[с.id] !== 'string' || d[с.id].trim() === '') {
          console.log(`${код}.${имяРаздела}: ${с.id} — пустое значение`);
          плохо++;
        }
        if (код !== 'az') {
          const изДанных = раздел.поле(с);
          if (d[с.id] !== изДанных) {
            console.log(`${код}.${имяРаздела}: ${с.id} расходится с данными`);
            плохо++;
          }
        }
      }
      console.log(`${код}.${имяРаздела}: ${сущности.length} из ${сущности.length}`);
    }
  }
  process.exit(плохо ? 1 : 0);
}