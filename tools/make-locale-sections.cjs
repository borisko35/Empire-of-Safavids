// Создаёт пустые разделы recipes, boats и boat_desc в словарях, если их ещё
// нет. Нужен, чтобы новый раздел появился в правильном месте файла — рядом с
// craft, — а не в конце словаря, куда его положило бы простое дописывание.
//
// node make-recipes-section.cjs [recipes boats boat_desc]
const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');
const аргументы = process.argv.slice(2);
const разделы = аргументы.length > 0 ? аргументы : ['recipes', 'boats', 'boat_desc'];

// Куда ставить раздел: после craft — это тематическое место, а не конец.
const якорь = /^ {2}"craft": \{[\s\S]*?\r?\n {2}\},/m;

for (const код of ['ru', 'en', 'az']) {
  const путь = path.join(корень, 'shared', 'locales', `${код}.json`);
  let текст = fs.readFileSync(путь, 'utf8');
  // Перевод строки берётся из САМОГО файла, а не выводится по последнему
  // символу блока-якоря. Блок craft заканчивается «  },» без перевода
  // строки, поэтому endsWith('\r\n') всегда было ложно: в файл с LF
  // вставлялась строка с CRLF, и граница блока соскальзывала на символ.
  // Раздел закрывался не там, где стоял, и следующий ключ приклеивался
  // к скобке.
  const переводСтроки = текст.includes('\r\n') ? '\r\n' : '\n';
  const создано = [];
  for (const имяРаздела of разделы) {
    if (new RegExp(`^ {2}"${имяРаздела}":`, 'm').test(текст)) continue;
    const блокЯкоря = якорь.exec(текст);
    if (!блокЯкоря) {
      console.error(`${код}: блок craft не найден — раздел ${имяРаздела} не создан`);
      process.exit(1);
    }
    текст = текст.replace(блокЯкоря[0], `${блокЯкоря[0]}${переводСтроки}  "${имяРаздела}": {},`);
    создано.push(имяРаздела);
  }
  fs.writeFileSync(путь, текст, 'utf8');
  // Проверка сразу: разделы только что вставлены, и если что-то не так —
  // это видно здесь, а не через час в игре.
  const j = JSON.parse(fs.readFileSync(путь, 'utf8'));
  console.log(`${код}: создано [${создано.join(', ') || '—'}], JSON разбирается, разделов ${Object.keys(j).length}`);
}