// Живая проверка очереди идей §3: шесть пунктов, и каждый проверяется запросом.
//
// ЗАЧЕМ. В карте четыре пункта помечены «готово», два — нет. Оказалось, что
// готовы все шесть: «Вербовка караула» (§203) и «Шёлковый путь» тоже работают.
// То есть карта врала дважды в одном списке, и врала в ту сторону, что
// работа выглядит невыполненной.
//
// Причина одна: отметки в карте ставились по памяти и по именам файлов. Имя
// метода ничего не доказывает — этим сегодня пользовались и карта, и я.
//
// ЧТО ПРОВЕРЯЕТСЯ. Для каждого пункта — живой запрос и осмысленный ответ:
// 200 с данными либо 4xx с ошибкой ИЗ ДОМЕНА. Ответ «маршрут не найден» — это
// не «механика есть», а «я ищу не там», и такой ответ стенд отличает от
// остальных: проверенный признак, что адрес верен.
//
// ЗАПУСК: node tools/check-queue-live.mjs
import { readFileSync } from 'node:fs';

const АДРЕС = process.env.EOS_GAME_URL ?? 'https://game.eos-gameonline.com';
const лог = (...a) => console.log(...a);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const raw = readFileSync('D:/My Projects/Empire of Sefevids/deploy/.test-account', 'utf-8');
const ПОЧТА = raw.match(/почта\s*:\s*(\S+)/)?.[1] ?? '';
const ПАРОЛЬ = raw.match(/пароль\s*:\s*(\S+)/)?.[1] ?? '';

const токен = (await (await fetch(`${АДРЕС}/api/auth/login`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ email: ПОЧТА, password: ПАРОЛЬ }),
})).json()).data.token;
const герой = (await (await fetch(`${АДРЕС}/api/characters`, {
  headers: { Authorization: `Bearer ${токен}` },
})).json()).characters.find((c) => c.name === 'EosProbe');
const cid = герой.id;
лог(`герой проверки: ${герой.name} (уровень ${герой.level}, золото ${герой.gold})\n`);

async function опрос(имя, путь, { метод = 'GET', тело = null } = {}) {
  const р = await fetch(`${АДРЕС}${путь}`, {
    method: метод,
    headers: {
      Authorization: `Bearer ${токен}`,
      ...(тело ? { 'Content-Type': 'application/json' } : {}),
    },
    body: тело ? JSON.stringify(тело) : undefined,
  });
  const текст = await р.text();
  // «Маршрут не найден» — это ответ СЕРВЕРА О МАРШРУТЕ, а не о механике.
  // Такой ответ означает, что адрес верен, но функция другая: иначе ошибка
  // проверки неотличима от отсутствия механики.
  const маршрутаНет = /Route not found/i.test(текст);
  const домен = /not_found|not_in_transit|no_caravan|not_enough|character_not/i.test(текст);
  const признак = маршрутаНет ? 'МАРШРУТА НЕТ' : домен ? 'доменная ошибка' : 'данные';
  лог(`  ${признак.padEnd(14)} HTTP ${р.status}  ${имя}`);
  return { р, текст, маршрутаНет, домен };
}

const вердикты = [];
const прими = (пункт, есть) => { вердикты.push(есть); лог(`  ${есть ? 'СДЕЛАНО' : 'НЕ СДЕЛАНО'}  ${пункт}`); };

лог('=== 1. Шахматы Шаха — ставки золотом в таверне ===');
{
  const состояние = await опрос('GET /api/chess/state/проба', `/api/chess/state/проба?characterId=${cid}`);
  прими('маршруты шахмат отвечают', !состояние.маршрутаНет);
}

лог('');
лог('=== 2. Вербовка караула — найм NPC-солдат ===');
{
  const r = await опрос('GET /api/soldiers', `/api/soldiers?characterId=${cid}`);
  let каталог = 0;
  try { каталог = (JSON.parse(r.текст)?.tiers ?? []).length; } catch { /* не JSON */ }
  лог(`    каталог караула: ${каталог} ступеней`);
  прими('каталог солдат отдаётся и непуст', !r.маршрутаНет && каталог > 0);
}

лог('');
лог('=== 3. Стихи Хафиза — поэтическая мини-игра ===');
{
  const r = await опрос('GET /api/poetry/challenges', '/api/poetry/challenges');
  let заданий = 0;
  try {
    const j = JSON.parse(r.текст);
    заданий = (j.challenges ?? j.data ?? (Array.isArray(j) ? j : [])).length;
  } catch { /* не JSON */ }
  лог(`    заданий: ${заданий}`);
  прими('задания стихов отдаются', !r.маршрутаНет);
}

лог('');
лог('=== 4. Шёлковый путь — грабёж караванов игроками ===');
{
  const дорога = await опрос('GET /api/game/trade/road', `/api/game/trade/road?characterId=${cid}`);
  let караванов = -1;
  try { караванов = (JSON.parse(дорога.текст)?.caravans ?? []).length; } catch { /* не JSON */ }
  лог(`    караванов на дороге сейчас: ${караванов}`);
  const засада = await опрос('POST /api/game/trade/ambush', '/api/game/trade/ambush', {
    метод: 'POST',
    тело: { characterId: cid, ownerId: '00000000-0000-0000-0000-000000000000' },
  });
  // Засада обязана отвечать ошибкой ИЗ ДОМЕНА: «каравана в пути нет» или
  // «нет такого владельца». Ответ «не хватает золота» тоже годится — значит
  // механика дошла до проверки, а не отвалилась на входе.
  прими('дорога и засада работают', !дорога.маршрутаНет && !засада.маршрутаНет && засада.домен);
}

лог('');
лог('=== 5. Диван Шаха — недельный топ-10 ===');
{
  const r = await опрос('GET /api/hall-of-fame/bosses', '/api/hall-of-fame/bosses?limit=5');
  прими('топ боссов отдаётся', !r.маршрутаНет);
}

лог('');
лог('=== 6. Хроники Сефевидов — энциклопедия по мере прохождения ===');
{
  const r = await опрос('GET /api/chronicles', '/api/chronicles');
  let записей = 0;
  try {
    const j = JSON.parse(r.текст);
    записей = (j.chronicles ?? j.entries ?? j.data ?? (Array.isArray(j) ? j : [])).length;
  } catch { /* не JSON */ }
  лог(`    записей: ${записей}`);
  прими('хроники отдаются', !r.маршрутаНет);
}

await sleep(50);
лог('');
лог('=== ИТОГ ===');
вердикты.forEach((есть, i) => лог(`  ${i + 1}. ${есть ? 'работает' : 'НЕ РАБОТАЕТ'}`));
const все = вердикты.every(Boolean);
лог(все
  ? 'Все шесть пунктов очереди работают. Карта, помечавшая два как несделанные, врала.'
  : 'Есть пункты, которые не работают: карта права, разбираться надо с ними.');
process.exit(все ? 0 : 1);