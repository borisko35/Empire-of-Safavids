#!/usr/bin/env bash
# ============================================================
# Проверка перед выкаткой — Empire of Safavids
# ============================================================
# Скрипт ничего не меняет: он только смотрит и либо пропускает
# выкатку, либо останавливает её ДО пересборки контейнеров.
#
# ЗАЧЕМ. 27 сентября случилось три вещи подряд, и каждая прошла
# с нулевой диагностикой:
#
#   1. Секреты лежали в одном экземпляре — в deploy/.env на сервере.
#      Файл исчез, и следующая команда пересборки упала с
#      «Couldn't find env file». Пересборка — это перезапуск сервера
#      игры: если файл пропал, сервер не поднимется и сайт ляжет.
#
#   2. Файл был неполным. Даже если .env существует, может оказаться,
#      что в нём не все переменные — тогда контейнер стартует «на
#      пустоте»: вход через внешние сервисы молча отключится, и
#      заметят это только игроки.
#
#   3. Команда git смотрела не в папку игры, а на уровень выше.
#      Из-за этого `git reset --hard` выписал копию проекта в корень
#      сервера, и любая команда git била не туда.
#
# Проверка идёт ДО того, как что-либо пересобрано. Смысл в том, чтобы
# узнать о проблеме до перезапуска, а не после: поднявшийся сервер
# без секретов — это лежащий сайт, а не сообщение об ошибке в логе.
#
# ЗАПУСК
#   bash tools/deploy-preflight.sh
#   или через `./tools/deploy-preflight.sh`, если файл исполняемый
#
# ВЫХОД: 0 — можно выкатывать, 1 — нельзя, с объяснением в списке.

set -uo pipefail

# Каталог проекта определяем сами, а не берём из текущего: из-за пробела
# в имени и из-за того, что рабочая папка у консоли меняется, полагаться
# на приглашение оболочки нельзя. Ищем вверх от этого скрипта.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT" || { echo "НЕ НАШЛИ корневую папку проекта"; exit 1; }

problems=()
notes=()

# ── 1. Файл секретов на месте ─────────────────────────────────
ENV_FILE="deploy/.env"
if [ -f "$ENV_FILE" ]; then
  notes+=("найден $ENV_FILE")
else
  problems+=("НЕТ ФАЙЛА $ENV_FILE — сервер игры не поднимется, сайт ляжет.
    Восстановить его можно из резервной копии, а если её нет — из
    работающего контейнера командой:
    CID=\$(docker ps -q --filter name=server | head -1)
    docker inspect --format '{{range .Config.Env}}{{println .}}{{end}}' \$CID \\
      | grep -E '^(JWT_SECRET|CLIENT_ORIGIN|DB_NAME|DB_USER|DB_PASSWORD|GOOGLE_CLIENT_ID|GOOGLE_CLIENT_SECRET|FACEBOOK_CLIENT_ID|FACEBOOK_CLIENT_SECRET)=' \\
      | sed 's/^DB_PASSWORD=/POSTGRES_PASSWORD=/' > deploy/.env
    echo \"DOMAIN=\$(grep '^CLIENT_ORIGIN=' deploy/.env | cut -d= -f2- | sed 's#https\\?://##')\" >> deploy/.env
    chmod 600 deploy/.env")
fi

# ── 2. В файле все нужные переменные ─────────────────────────
# Пустое значение — не ошибка: так помечается выключенный вход.
# Значит проверяем, что переменная ПРИСУТСТВУЕТ, а не что она не пуста.
REQUIRED="POSTGRES_PASSWORD JWT_SECRET CLIENT_ORIGIN DOMAIN DB_NAME DB_USER"
OPTIONAL="GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET FACEBOOK_CLIENT_ID FACEBOOK_CLIENT_SECRET"

if [ -f "$ENV_FILE" ]; then
  missing=""
  for key in $REQUIRED; do
    # -z не годится: нужно различие «нет строки» и «есть, но пусто».
    # Ищем именно начало строки с именем переменной.
    grep -q "^${key}=" "$ENV_FILE" || missing="$missing $key"
  done
  if [ -n "$missing" ]; then
    problems+=("В $ENV_FILE НЕТ переменных:$missing — без них контейнер
      либо не стартует, либо поднимется с выключенным входом.")
  else
    notes+=("все обязательные переменные на месте")
  fi

  # Незаполненный секрет молча ломает вход — предупреждаем отдельно
  for key in $OPTIONAL; do
    if grep -q "^${key}=" "$ENV_FILE" && [ -z "$(grep -m1 "^${key}=" "$ENV_FILE" | cut -d= -f2-)" ]; then
      notes+=("$key пустой — вход через этого провайдера выключен")
    fi
  done

  # Права: секрет должен быть доступен только владельцу
  perms="$(stat -c '%a' "$ENV_FILE" 2>/dev/null || echo '?')"
  if [ "$perms" != "600" ] && [ "$perms" != "400" ]; then
    notes+=("права на $ENV_FILE — $perms. Рекомендуется 600: chmod 600 $ENV_FILE")
  fi
fi

# ── 3. Куда наведён git ───────────────────────────────────────
# Главная причина сегодняшней потери. Если репозиторий указывает не
# туда, любая команда git бьёт не по игре.
if command -v git >/dev/null 2>&1; then
  if [ -d .git ] || [ -f .git ]; then
    top="$(git rev-parse --show-toplevel 2>/dev/null || echo '?')"
    # Сравниваем по канонизированному пути: оболочка и git иногда
    # показывают одно и то же место по-разному.
    here="$(cd "$ROOT" && pwd -P)"
    if [ "$top" = "$here" ]; then
      notes+=("git наведён правильно: $top")
    else
      problems+=("git наведён на '$top', а папка игры — '$here'.
    Пока так, git pull и git reset бьют не по игре. НЕЛЬЗЯ выполнять
    их, пока это не исправлено. Проверить: git rev-parse --show-toplevel")
    fi
  fi
fi

# ── Итог ─────────────────────────────────────────────────────
if [ ${#notes[@]} -gt 0 ]; then
  echo "Проверено:"
  for n in "${notes[@]}"; do echo "  - $n"; done
fi

if [ ${#problems[@]} -gt 0 ]; then
  echo
  echo "ВЫКАТКУ ОСТАНОВЛЕНО. Неполомлено:"
  for p in "${problems[@]}"; do echo "  ! $p"; done
  echo
  echo "Пересборка не запускалась: сервер не был перезапущен."
  exit 1
fi

echo
echo "Можно выкатывать."
exit 0
