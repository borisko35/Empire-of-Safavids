#!/usr/bin/env bash
# ============================================================
# Проверка перед выкаткой — Empire of Safavids
# ============================================================
# Скрипт ничего не меняет: он только смотрит и либо пропускает
# выкатку, либо останавливает её ДО пересборки контейнеров.
#
# ЗАЧЕМ. 27 сентября случилось три вещи подряд, и каждая прошла
# с нулевой диагностикой:
#
#   1. Секреты лежали в одном экземпляре — в deploy/.env на сервере.
#      Файл исчез, и следующая команда пересборки упала с
#      «Couldn't find env file». Пересборка — это перезапуск сервера
#      игры: если файл пропал, сервер не поднимется и сайт ляжет.
#
#   2. Файл был неполным. Даже если .env существует, может оказаться,
#      что в нём не все переменные — тогда контейнер стартует «на
#      пустоте»: вход через внешние сервисы молча отключится, и
#      заметят это только игроки.
#
#   3. Команда git смотрела не в папку игры, а на уровень выше.
#      Из-за этого `git reset --hard` выписал копию проекта в корень
#      сервера, и любая команда git била не туда.
#
# Проверка идёт ДО того, как что-либо пересобрано. Смысл в том, чтобы
# узнать о проблеме до перезапуска, а не после: поднявшийся сервер
# без секретов — это лежащий сайт, а не сообщение об ошибке в логе.
#
# ЗАПУСК
#   bash tools/deploy-preflight.sh
#   или через `./tools/deploy-preflight.sh`, если файл исполняемый
#
# ВЫХОД: 0 — можно выкатывать, 1 — нельзя, с объяснением в списке.

set -uo pipefail

# Каталог проекта определяем сами, а не берём из текущего: из-за пробела
# в имени и из-за того, что рабочая папка у консоли меняется, полагаться
# на приглашение оболочки нельзя. Ищем вверх от этого скрипта.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT" || { echo "НЕ НАШЛИ корневую папку проекта"; exit 1; }

problems=()
notes=()

# ── 1. Файл секретов на месте ─────────────────────────────────
ENV_FILE="deploy/.env"
if [ -f "$ENV_FILE" ]; then
  notes+=("найден $ENV_FILE")
else
  problems+=("НЕТ ФАЙЛА $ENV_FILE — сервер игры не поднимется, сайт ляжет.
    Восстановить его можно из резервной копии, а если её нет — из
    работающего контейнера командой:
    CID=\$(docker ps -q --filter name=server | head -1)
    docker inspect --format '{{range .Config.Env}}{{println .}}{{end}}' \$CID \\
      | grep -E '^(JWT_SECRET|CLIENT_ORIGIN|DB_NAME|DB_USER|DB_PASSWORD|GOOGLE_CLIENT_ID|GOOGLE_CLIENT_SECRET|FACEBOOK_CLIENT_ID|FACEBOOK_CLIENT_SECRET)=' \\
      | sed 's/^DB_PASSWORD=/POSTGRES_PASSWORD=/' > deploy/.env
    echo \"DOMAIN=\$(grep '^CLIENT_ORIGIN=' deploy/.env | cut -d= -f2- | sed 's#https\\?://##')\" >> deploy/.env
    chmod 600 deploy/.env")
fi

# ── 2. В файле все нужные переменные ─────────────────────────
# Пустое значение — не ошибка: так помечается выключенный вход.
# Значит проверяем, что переменная ПРИСУТСТВУЕТ, а не что она не пуста.
#
# СПИСОК ОБЯЗАТЕЛЬНЫХ БЕРЁТСЯ ИЗ COMPOSE, А НЕ ПЕРЕЧИСЛЕН ЗДЕСЬ.
# Compose различает два вида подстановок:
#   ${VAR:?текст}  — без VAR контейнер НЕ СТАРТУЕТ, переменная обязательна;
#   ${VAR:-знач}   — есть значение по умолчанию, переменную можно не задавать.
# Список, выписанный руками, разошёлся с compose молча: требовались DB_NAME и
# DB_USER, у которых в compose значения по умолчанию
# (`${DB_NAME:-empire_of_safavids}`), и такую РАБОЧУЮ конфигурацию проверка
# объявляла неполной. Теперь обязательным считается ровно то, на что compose
# сам ставит `:?`.
COMPOSE="deploy/docker-compose.prod.yml"
REQUIRED=""
if [ -f "$COMPOSE" ]; then
  REQUIRED=$(grep -o '\${[A-Z_][A-Z0-9_]*:?' "$COMPOSE" | sed 's/^\${//; s/:?$//' | sort -u | tr '\n' ' ')
fi
if [ -z "${REQUIRED// /}" ]; then
  # Файл compose не найден или в нём нет ни одной обязательной подстановки.
  # Молча пропускать проверку нельзя: она стала бы проверкой пустоты.
  REQUIRED="POSTGRES_PASSWORD JWT_SECRET DOMAIN"
  notes+=("Список обязательных переменных не выведен из $COMPOSE — берётся запасной список")
fi
# Туннель проверяется отдельно и только когда он используется: его
# CLOUDFLARE_TUNNEL_TOKEN compose сам требует через `:?`, и подставлять его
# в общий список нельзя — на VPS без туннеля переменной нет и не нужно.
OPTIONAL="DB_NAME DB_USER CLIENT_ORIGIN TRUST_PROXY_HOPS GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET FACEBOOK_CLIENT_ID FACEBOOK_CLIENT_SECRET"

if [ -f "$ENV_FILE" ]; then
  missing=""
  for key in $REQUIRED; do
    # -z не годится: нужно различие «нет строки» и «есть, но пусто».
    # Ищем именно начало строки с именем переменной.
    grep -q "^${key}=" "$ENV_FILE" || missing="$missing $key"
  done
  if [ -n "$missing" ]; then
    problems+=("В $ENV_FILE НЕТ переменных:$missing — без них контейнер
      либо не стартует, либо поднимется с выключенным входом.")
  else
    notes+=("все обязательные переменные на месте")
  fi

  # Незаполненный секрет молча ломает вход — предупреждаем отдельно
  for key in $OPTIONAL; do
    if grep -q "^${key}=" "$ENV_FILE" && [ -z "$(grep -m1 "^${key}=" "$ENV_FILE" | cut -d= -f2-)" ]; then
      notes+=("$key пустой — вход через этого провайдера выключен")
    fi
  done

  # Права: секрет должен быть доступен только владельцу.
  #
  # СОВЕТ ПРО chmod 600 НА WINDOWS БЕСПОЛЕЗЕН. В Git Bash `stat -c %a` показывает
  # 644 для любого файла, потому что прав POSIX у NTFS нет, а `chmod` там
  # ничего не меняет. Советовать владельцу chmod на его же машине — значит
  # отправить его искать несуществующую проблему. Поэтому на Windows говорим
  # правду: секрет защищён учётной записью, отдельных прав у файла нет.
  uname_s="$(uname -s 2>/dev/null || echo '?')"
  case "$uname_s" in
    MINGW*|MSYS*|CYGWIN*|Windows_NT)
      notes+=("Windows: POSIX-прав у файла нет, deploy/.env защищён учётной записью. chmod здесь не нужен")
      ;;
    *)
      perms="$(stat -c '%a' "$ENV_FILE" 2>/dev/null || echo '?')"
      if [ "$perms" != "600" ] && [ "$perms" != "400" ]; then
        notes+=("права на $ENV_FILE — $perms. Рекомендуется 600: chmod 600 $ENV_FILE")
      fi
      ;;
  esac
fi

# ── 3. Куда наведён git ───────────────────────────────────────
# Главная причина сегодняшней потери. Если репозиторий указывает не
# туда, любая команда git бьёт не по игре.
#
# СРАВНИВАЕТСЯ ПО ПРИВЕДЁННОМУ ВИДУ. Оболочка и git показывают одно и то же
# место по-разному: в Git Bash `pwd -P` даёт `/d/My Projects/Empire of Sefevids`,
# а git (он windows-бинарник) отдаёт `D:/My Projects/Empire of Sefevids`. Это
# один и тот же путь, и проверка объявляла его РАЗНЫМИ — то есть останавливала
# выкатку на заведомо правильной папке.
canon() {
  local p="$1"
  # cygpath -m переводит путь MSYS в смешанный вид `D:/...`. На Linux его нет,
  # и путь остаётся как есть — там обе стороны и так в одном формате.
  if command -v cygpath >/dev/null 2>&1; then
    p="$(cygpath -m "$p" 2>/dev/null || echo "$p")"
  fi
  # Регистр не различаем: в Windows он не значим, и git иногда пишет букву
  # диска в другом регистре. Хвостовой слеш тоже: он не часть пути.
  printf '%s' "$p" | tr 'A-Z' 'a-z' | tr '\\' '/' | sed 's#/*$##'
}

if command -v git >/dev/null 2>&1; then
  if [ -d .git ] || [ -f .git ]; then
    top="$(git rev-parse --show-toplevel 2>/dev/null || echo '?')"
    here="$(cd "$ROOT" && pwd -P)"
    if [ "$(canon "$top")" = "$(canon "$here")" ]; then
      notes+=("git наведён правильно: $top")
    else
      problems+=("git наведён на '$top', а папка игры — '$here'.
    Пока так, git pull и git reset бьют не по игре. НЕЛЬЗЯ выполнять
    их, пока это не исправлено. Проверить: git rev-parse --show-toplevel")
    fi
  fi
fi

# ── 4. Docker вообще работает ─────────────────────────────────
# БЫЛ НЕДОЧЁТ, ИЗ-ЗА КОТОРОГО ОШИБКА ВЫГЛЯДЕЛА НЕ ТАК, КАКАЯ ОНА БЫЛА.
# 10 октября 2026 переезд на AWS остановился здесь:
#   permission denied while trying to connect to the docker API
#   at unix:///var/run/docker.sock
# и deploy.sh обернул это в «контейнеры не перебрались». Настоящая причина —
# пользователь не в группе `docker`: на новой машине установщик добавляет его
# в группу, но права группы действуют только в НОВОЙ сессии, а переезд идёт по
# уже открытой. Лечится перезаходом по ssh.
#
# Проверяется `docker info`, а не `docker --version`: версия читает файл и
# отвечает всегда, а info идёт к сокету по-настоящему.
if ! command -v docker >/dev/null 2>&1; then
  problems+=("docker не найден в PATH — пересобирать нечем. На новой машине
    сначала запустите: bash tools/bootstrap-machine.sh")
elif ! docker info >/dev/null 2>&1; then
  problems+=("docker есть, но не отвечает: permission denied ... /var/run/docker.sock
    Пользователь не в группе docker, а права группы действуют только в НОВОЙ
    сессии. Выйдите из ssh и зайдите снова, либо выполните:
      sudo usermod -aG docker \$(id -un) && newgrp docker
    Если выкатка идёт через tools/bootstrap-machine.sh, он поправит это сам.")
fi

# ── Итог ─────────────────────────────────────────────────────
if [ ${#notes[@]} -gt 0 ]; then
  echo "Проверено:"
  for n in "${notes[@]}"; do echo "  - $n"; done
fi

if [ ${#problems[@]} -gt 0 ]; then
  echo
  echo "ВЫКАТКУ ОСТАНОВЛЕНО. Неполомлено:"
  for p in "${problems[@]}"; do echo "  ! $p"; done
  echo
  echo "Пересборка не запускалась: сервер не был перезапущен."
  exit 1
fi

echo
echo "Можно выкатывать."
exit 0
