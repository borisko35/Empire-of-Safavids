// Дополняет раздел items в словарях перевода.
//
// ЗАЧЕМ СКРИПТ, А НЕ РУКАМИ. Русские и английские названия не переводятся:
// они копируются дословно из server/src/data/items.ts, где их уже написали
// авторы проекта. Вводить их вручную означало бы перепечатывать 58 названий
// дважды с риском опечатки, и опечатка в названии предмета — это не «сломался
// переводчик», это предмет, который в игре называется не тем, чем он является.
//
// Файл правит ТОЛЬКО блок items, оставляя остальной JSON байт в байт:
// пересборка всего словаря через JSON.stringify переставила бы ключи и
// породила diff в тысячи строк, который невозможно прочитать.
const fs = require('fs');
const path = require('path');
const { items } = require('./list-items.cjs');

const корень = path.join(__dirname, '..');
const файл = (код) => path.join(корень, 'shared', 'locales', `${код}.json`);

/** Экранирование для JSON-строки. */
function строка(значение) {
  return JSON.stringify(значение);
}

/**
 * Заменяет блок items в словаре, сохраняя всё остальное.
 *
 * Файл в репозитории с окончаниями строк CRLF, и искать по '  "items": {\n'
 * на таком файле бессмысленно — совпадения не будет. Поэтому границы ищутся
 * по самой строке без учёта перевода строки, а тело блока собирается заново
 * с тем же переводом, какой был в файле.
 */
function границы(текст) {
  const открытие = /^ {2}"items": \{[^\S\n]*\n/m.exec(текст);
  if (!открытие) throw new Error('блок items не найден');
  const начало = открытие.index;
  const переводСтроки = открытие[0].endsWith('\r\n') ? '\r\n' : '\n';
  // Поиск ведётся по срезу от открытия, а НЕ через lastIndex. Регулярка
  // без флага g lastIndex игнорирует полностью: поиск закрытия уходил с
  // начала файла и попадал в первый блок верхнего уровня (debuffs), откуда
  // скрипт тащил ключи stun/slow/bleed/poison/fear. При этом он их не терял,
  // а наоборот затирал переписанным блоком - то есть молча ломал словарь
  // и выглядел при этом так, будто отработал.
  const дальше = текст.slice(начало + открытие[0].length);
  const закрытие = /^ {2}\},?$/m.exec(дальше);
  if (!закрытие) throw new Error('конец блока items не найден');
  const конец = начало + открытие[0].length + закрытие.index;
  return { начало, конец, длинаКонца: закрытие[0].length, переводСтроки };
}

function заменитьБлок(текст, строки) {
  const { начало, конец, длинаКонца, переводСтроки } = границы(текст);
  const хвост = текст.slice(конец, конец + длинаКонца);
  const разделитель = `,${переводСтроки}`;
  const тело = `  "items": {${переводСтроки}${строки.join(разделитель)}${переводСтроки}  }${хвост.endsWith(',') ? ',' : ''}`;
  return текст.slice(0, начало) + тело + текст.slice(конец + длинаКонца);
}

/**
 * Читает текущий блок items в объект.
 *
 * Ключи возвращаются в порядке появления вместе с признаком «это предмет».
 * Ключи не предметы (stun, slow, bleed, poison, fear, stunned_hint) —
 * названия эффектов, попавшие в этот блок исторически. Их нельзя ни
 * выбросить, ни переписать из данных: предмета с таким идентификатором
 * не существует.
 */
function прочитатьБлок(код) {
  const текст = fs.readFileSync(файл(код), 'utf8');
  const { начало, конец, длинаКонца } = границы(текст);
  const тело = текст.slice(начало, конец).split('\n').slice(1);
  const порядок = [];
  const значения = {};
  for (const стр of тело) {
    const m = /^\s*"([^"]+)":\s*(".*?")\s*,?\s*$/.exec(стр);
    if (!m) continue;
    порядок.push(m[1]);
    значения[m[1]] = JSON.parse(m[2]);
  }
  return { значения, порядок };
}

const режим = process.argv[2] ?? 'сводка';

if (режим === 'сводка') {
  const ru = прочитатьБлок('ru').значения;
  const нужны = items.filter((i) => !(i.id in ru));
  console.log('всего предметов:', items.length);
  console.log('уже переведено:', items.length - нужны.length);
  console.log('добавить:', нужны.length);
  console.log('\nid | ru (из данных) | en (из данных)');
  for (const i of нужны) console.log([i.id, i.ru, i.en].join(' | '));
}

if (режим === 'az-таблица') {
  // Читает переводы из файла, который заполняет переводчик, и печатает
  // готовый блок строк для вставки в az.json.
  const пары = JSON.parse(fs.readFileSync(path.join(__dirname, 'az-items.json'), 'utf8'));
  const строки = [];
  for (const i of items) {
    const az = пары[i.id];
    if (typeof az !== 'string' || az.trim() === '') throw new Error(`нет перевода для ${i.id}`);
    строки.push(`    ${строка(i.id)}: ${строка(az)},`);
  }
  fs.writeFileSync(path.join(__dirname, 'az-items.block.txt'), строки.join('\n'), 'utf8');
  console.log('готов блок на', строки.length, 'предметов -> tools/az-items.block.txt');
}

/**
 * Собирает строки блока: сначала предметы из данных, затем — с сохранением —
 * ключи блока, предметом не являющиеся.
 *
 * Между строками ставится запятая, у последней - нет: JSON без неё не
 * разбирается. Раньше здесь запятая терялась, файл получался невалидным,
 * и это было видно только при попытке его прочитать.
 */
function собратьСтроки(код, значения) {
  const { значения: текущие, порядок } = прочитатьБлок(код);
  const неПредметы = порядок.filter((k) => !items.some((i) => i.id === k));
  const строки = [];
  for (const i of items) {
    const v = значения[i.id];
    if (typeof v !== 'string' || v.trim() === '') throw new Error(`${код}: нет значения для ${i.id}`);
    строки.push(`    ${строка(i.id)}: ${строка(v)}`);
  }
  for (const k of неПредметы) {
    if (!(k in текущие)) continue;
    строки.push(`    ${строка(k)}: ${строка(текущие[k])}`);
  }
  if (неПредметы.length) console.log(`${код}: сохранено ключей, не являющихся предметами: ${неПредметы.join(', ')}`);
  if (строки.length === 0) throw new Error(`${код}: блок оказался пустым`);
  // Возвращаются СТРОКИ БЕЗ ЗАПЯТЫХ. Запятую между ними ставит
  // заменитьБлок: иначе строка склеивается в одну, и словарь перестаёт
  // разбираться - а это видно только при чтении файла, то есть позже.
  return строки;
}

if (режим === 'диффы') {
  // Расхождения собираются ВСЕ разом, а не падают на первом. Раньше скрипт
  // останавливался на первом несовпадении, и правки приходилось делать по
  // одной: запустил, упал, поправил, запустил, снова упал. Списком видно
  // сразу, о скольких местах речь, и решать их можно за один присест.
  let всего = 0;
  for (const [код, поле] of [['ru', 'ru'], ['en', 'en']]) {
    const d = прочитатьБлок(код).значения;
    console.log(`\n=== ${код} ===`);
    for (const i of items) {
      if (d[i.id] !== undefined && d[i.id] !== i[поле]) {
        console.log(`${i.id}\n  в словаре: ${d[i.id]}\n  в данных:   ${i[поле]}`);
        всего++;
      }
    }
  }
  console.log(`\nвсего расхождений: ${всего}`);
}

if (режим === 'заполнить') {
  // Второй аргумент — «принять-данные»: в расхождениях побеждают данные.
  // Без него скрипт останавливается, чтобы расхождение пришлось увидеть
  // глазами. Каноническим источником названий назначены данные
  // (server/src/data/items.ts): словарь заполняется из них, а не наоборот.
  const принятьДанные = process.argv[3] === 'принять-данные';
  for (const [код, поле] of [['ru', 'ru'], ['en', 'en']]) {
    const путь = файл(код);
    const текст = fs.readFileSync(путь, 'utf8');
    const текущие = прочитатьБлок(код).значения;
    const значения = {};
    let добавлено = 0;
    const переписано = [];
    for (const i of items) {
      const значение = i[поле];
      if (typeof значение !== 'string' || значение === '') throw new Error(`${код}: нет ${поле} у ${i.id}`);
      if (текущие[i.id] !== undefined && текущие[i.id] !== значение) {
        if (!принятьДанные) {
          throw new Error(`${код}: ${i.id} в словаре «${текущие[i.id]}», в данных «${значение}» — расхождение`);
        }
        переписано.push(`${i.id}: «${текущие[i.id]}» -> «${значение}»`);
      }
      if (текущие[i.id] === undefined) добавлено++;
      значения[i.id] = значение;
    }
    fs.writeFileSync(путь, заменитьБлок(текст, собратьСтроки(код, значения)), 'utf8');
    console.log(`${код}: записей ${items.length}, добавлено ${добавлено}, переписано ${переписано.length}`);
    for (const стр of переписано) console.log(`   ${стр}`);
  }
}

if (режим === 'применить-az') {
  // Файл с переводами содержит только недостающие названия. Уже переведённые
  // берутся из самого словаря и не переписываются: требовать от автора
  // переписать то, что уже написано и годно, — значит заставлять его
  // второй раз придумать то же самое и рисковать расхождением с собой.
  const новые = JSON.parse(fs.readFileSync(path.join(__dirname, 'az-items.json'), 'utf8'));
  const путь = файл('az');
  const текст = fs.readFileSync(путь, 'utf8');
  const { значения: текущие } = прочитатьБлок('az');
  const значения = {};
  let взятоСтарых = 0;
  for (const i of items) {
    if (typeof новые[i.id] === 'string' && новые[i.id].trim() !== '') {
      значения[i.id] = новые[i.id];
    } else if (typeof текущие[i.id] === 'string' && текущие[i.id].trim() !== '') {
      значения[i.id] = текущие[i.id];
      взятоСтарых++;
    }
  }
  fs.writeFileSync(путь, заменитьБлок(текст, собратьСтроки('az', значения)), 'utf8');
  console.log(`az: блок items пересобран, новых переводов ${items.length - взятоСтарых}, взято из словаря ${взятоСтарых}`);
}

if (режим === 'проверка') {
  let плохо = 0;
  for (const код of ['ru', 'en', 'az']) {
    const { значения: d } = прочитатьБлок(код);
    const нет = items.filter((i) => !(i.id in d));
    console.log(`${код}: предметов в словаре ${Object.keys(d).length}, без перевода ${нет.length}${нет.length ? ': ' + нет.map((i) => i.id).join(', ') : ''}`);
    if (нет.length) плохо++;
    for (const i of items) {
      const v = d[i.id];
      if (typeof v !== 'string' || v.trim() === '') { console.log(`${код}: ${i.id} — пустое значение`); плохо++; }
    }
    if (код === 'ru') {
      for (const i of items) {
        if (d[i.id] !== i.ru) { console.log(`ru: ${i.id} расходится с данными`); плохо++; }
      }
    }
    if (код === 'en') {
      for (const i of items) {
        if (d[i.id] !== i.en) { console.log(`en: ${i.id} расходится с данными`); плохо++; }
      }
    }
  }
  process.exit(плохо ? 1 : 0);
}
