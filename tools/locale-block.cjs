// Работа с одним блоком словаря перевода: найти его границы, прочитать,
// заменить, не тронув остальной JSON.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ДУБЛЬ В КАЖДОМ СКРИПТЕ. Границы блока —
// штука с тремя подводными камнями, и каждый из них однажды стоил
// поломанного словаря:
//
// 1. Файл в репозитории с окончаниями строк CRLF. Искать по '"items": {\n'
//    на таком файле бессмысленно — совпадения не будет.
// 2. Регулярка без флага g полностью игнорирует lastIndex. Поиск закрытия
//    уходил с начала файла и попадал в первый блок верхнего уровня
//    (debuffs), откуда скрипт тащил ключи stun/slow/bleed/poison/fear. При
//    этом он их не терял, а наоборот затирал переписанным блоком — то есть
//    молча ломал словарь и выглядел при этом так, будто отработал.
// 3. Пересборка всего словаря через JSON.stringify переставила бы ключи и
//    породила diff в тысячи строк, который невозможно прочитать.
//
// Модуль меняет ТОЛЬКО указанный блок, остальное остаётся байт в байт.
const fs = require('fs');
const path = require('path');

const корень = path.join(__dirname, '..');

/** Путь к словарю языка. */
function файлСловаря(код) {
  return path.join(корень, 'shared', 'locales', `${код}.json`);
}

/** Экранирование значения в JSON-строку. */
function строкаJSON(значение) {
  return JSON.stringify(значение);
}

/**
 * Границы блока с указанным именем.
 *
 * СМЫСЛОЛ ПОЛЕЙ ОДИН ДЛЯ ОБЕИХ ФОРМ, и это важно: конец указывает НА
 * закрывающий токен, а не за него, поэтому блок занимает диапазон
 * [начало, конец + длинаКонца). Раньше однострочная форма возвращала конец
 * уже за блоком, а многострочная — на скобке. Из-за этого конец +
 * длинаКонца уезжал далеко за границу, раздел закрывался не там, где
 * стоял, и следующий ключ приклеивался к скобке: «  },    "wpn_iron_sword"».
 */
function границы(текст, имяБлока) {
  // Открывающая строка бывает двух видов:
  //   "recipes": {        — содержимое на следующих строках;
  //   "recipes": {},      — раздел только что создан и ещё пуст.
  // Второй вид нельзя пропустить: без него невозможно создать новый
  // раздел словаря — инструмент не находит то, чего ещё нет.
  const одноСтрочный = new RegExp(`^ {2}"${имяБлока}": \\{\\}`, 'm').exec(текст);
  if (одноСтрочный) {
    const начало = одноСтрочный.index;
    // Закрывающий токен — последний символ совпадения, то есть «}».
    const конец = начало + одноСтрочный[0].length - 1;
    return {
      начало,
      конец,
      длинаКонца: 1,
      // Запятая после «{}» лежит СНАРУЖИ токена, поэтому её надо найти
      // отдельно — в многострочной форме она часть самого токена «},».
      запятая: текст[конец + 1] === ',',
      переводСтроки: текст.includes('\r\n') ? '\r\n' : '\n',
      одноСтрочный: true,
    };
  }
  const открытие = new RegExp(`^ {2}"${имяБлока}": \\{[^\\S\\n]*\\n`, 'm').exec(текст);
  if (!открытие) throw new Error(`блок ${имяБлока} не найден`);
  const начало = открытие.index;
  const переводСтроки = открытие[0].endsWith('\r\n') ? '\r\n' : '\n';
  const дальше = текст.slice(начало + открытие[0].length);
  const закрытие = /^ {2}\},?$/m.exec(дальше);
  if (!закрытие) throw new Error(`конец блока ${имяБлока} не найден`);
  const конец = начало + открытие[0].length + закрытие.index;
  return {
    начало,
    конец,
    длинаКонца: закрытие[0].length,
    // Регулярка захватывает запятую в токен, когда она есть. Искать её
    // ПОСЛЕ токена нельзя: там уже следующий раздел, и запятая терялась —
    // словарь переставал разбираться, и это было видно только при чтении.
    запятая: закрытие[0].endsWith(','),
    переводСтроки,
    одноСтрочный: false,
  };
}

/**
 * Читает блок словаря: значения и порядок ключей.
 *
 * Порядок нужен, чтобы сохранить ключи, предметом не являющиеся: в блоке
 * items исторически живут названия эффектов и маунтов. Выбросить их —
 * значит сломать подсказки дебаффов, а молча это сделать нельзя.
 */
function прочитатьБлок(код, имяБлока) {
  const текст = fs.readFileSync(файлСловаря(код), 'utf8');
  const { начало, конец } = границы(текст, имяБлока);
  const тело = текст.slice(начало, конец).split('\n').slice(1);
  const порядок = [];
  const значения = {};
  for (const стр of тело) {
    const m = /^\s*"([^"]+)":\s*(".*?")\s*,?\s*$/.exec(стр);
    if (!m) continue;
    порядок.push(m[1]);
    значения[m[1]] = JSON.parse(m[2]);
  }
  return { значения, порядок };
}

/**
 * Заменяет блок словаря пересобранным содержимым.
 *
 * строки — массив строк БЕЗ запятых между ними: запятую ставит эта
 * функция. Раньше запятая терялась по дороге, файл получался невалидным,
 * и это было видно только при попытке его прочитать.
 */
function заменитьБлок(код, имяБлока, строки) {
  if (!Array.isArray(строки) || строки.length === 0) {
    throw new Error(`${код}.${имяБлока}: блок оказался пустым — запись отменена`);
  }
  const путь = файлСловаря(код);
  const текст = fs.readFileSync(путь, 'utf8');
  const { начало, конец, длинаКонца, запятая, переводСтроки } = границы(текст, имяБлока);

  // В форме «},» запятая входит в длинаКонца, в форме «{}» — нет. Значение
  // приходит из границ, где оно берётся из самого закрывающего токена.
  const конецСЗапятой = конец + длинаКонца + (запятая && текст[конец + длинаКонца] === ',' ? 1 : 0);

  const разделитель = `,${переводСтроки}`;
  const тело =
    `  "${имяБлока}": {${переводСтроки}`
    + `${строки.join(разделитель)}${переводСтроки}`
    + `  }${запятая ? ',' : ''}`;
  fs.writeFileSync(путь, текст.slice(0, начало) + тело + текст.slice(конецСЗапятой), 'utf8');
}

module.exports = {
  корень,
  файлСловаря,
  строкаJSON,
  границы,
  прочитатьБлок,
  заменитьБлок,
};