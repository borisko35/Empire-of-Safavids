// Живая проверка публикации на Game Jolt.
//
// ЧТО ПРОВЕРЯЕТ. Игра находится в ПУБЛИЧНОМ поиске площадки, и её числовой id
// совпадает с тем, что вписан в инструкцию публикации.
//
// ПОЧЕМУ ЧЕРЕЗ ПОИСК, А НЕ ПО АДРЕСУ СТРАНИЦЫ. Заявление «снаружи проверить
// нельзя» было верно про АДРЕС СТРАНИЦЫ и неверно про площадку целиком:
// страница отдаёт одностраничную оболочку и на существующую игру, и на
// несуществующую — ответ тот же (HTTP 200, та же длина, §196/§200). А
// поисковый индекс отдаёт настоящие данные анонимно.
//
// ЧТО ЭТО ДОКАЗЫВАЕТ, А ЧТО НЕТ.
//   ДОКАЗЫВАЕТ: игра видна постороннему посетителю по названию, и id из
//     инструкции соответствует реальному. Оба id не совпали бы, если бы игра
//     исчезла из индекса или в инструкции лежал бы чужой.
//   НЕ ДОКАЗЫВАЕТ: снята ли метка Unlisted. Поле `status` у всех игр в выдаче
//     одинаково, и что именно оно значит, снаружи не выяснить. Поэтому вывод
//     здесь один — «игра найдена», без утверждений про метку.
//
// ЗАПУСК: node tools/check-gamejolt-live.mjs
import { readFileSync } from 'node:fs';

const ИГРА = 'Empire of Safavids';
const лог = (...a) => console.log(...a);

const документ = readFileSync(
  'D:/My Projects/Empire of Sefevids/tools/gamejolt-instructions.md', 'utf-8');
const адрес = /https:\/\/gamejolt\.com\/games\/[\w-]+\/(\d+)/.exec(документ)?.[1];
if (!адрес) {
  лог('ПРОВАЛ: в инструкции нет адреса страницы Game Jolt — пересоберите документ с настоящим адресом.');
  process.exit(2);
}

лог(`ищем «${ИГРА}» без сессии, без кук, без токена`);
const р = await fetch(
  'https://gamejolt.com/site-api/web/search/games?q=' + encodeURIComponent(ИГРА),
  { headers: { Accept: 'application/json' } },
);
if (р.status !== 200) {
  лог(`ПРОВАЛ: поиск площадки ответил ${р.status}. Публикацию проверить нечем — это поломка инструмента, а не площадки.`);
  process.exit(2);
}
const игры = (await р.json())?.payload?.games ?? [];
лог(`найдено игр в выдаче: ${игры.length}`);

const наша = игры.find((и) => String(и.id) === адрес);
лог('');
лог('--- ЗАКЛЮЧЕНИЯ ---');
лог(`  ${наша ? 'ДА' : 'НЕТ'}  игра найдена в публичном поиске`);

if (наша) {
  лог(`  ${наша.title === ИГРА ? 'ДА' : 'НЕТ'}  название совпадает: «${наша.title}»`);
  лог(`  ${String(наша.id) === адрес ? 'ДА' : 'НЕТ'}  id из инструкции (${адрес}) совпадает с найденным (${наша.id})`);
  лог(`      автор: ${наша.developer?.display_name ?? '?'}, статус: ${наша.status}, опубликована: ${наша.published_on ?? '?'}`);
} else {
  // Полезно сказать, ЧТО нашлось: пустая выдача и выдача без нашей игры — это
  // разные поломки, и без этого различия они неразличимы.
  const похожие = игры.filter((и) => /safavid/i.test(и.title ?? ''));
  лог(`  найдено похожих по слову «Safavid»: ${похожие.length}`);
  if (игры.length === 0) {
    лог('  выдача пуста: площадка не ищет по этому названию вовсе — проверьте, не сломан ли запрос.');
  } else {
    лог('  выдача непуста, но нашей игры в ней нет: она не опубликована или лежит под другим id.');
  }
  лог(`  первые: ${игры.slice(0, 3).map((и) => `${и.title} (${и.id})`).join('; ')}`);
}

лог('');
const всеОк = Boolean(наша);
лог(всеОк ? 'ИТОГ: игра опубликована и видна постороннему' : 'ИТОГ: проверить не удалось, см. строки НЕТ');
process.exit(всеОк ? 0 : 1);