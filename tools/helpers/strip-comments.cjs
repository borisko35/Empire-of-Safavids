// Вырезает комментарии из исходника TypeScript, оставляя исполняемый код.
//
// ЗАЧЕМ ИНСТРУМЕНТАМ ПЕРЕВОДА. Разбор данных в tools/ идёт регулярками по
// исходнику. Если между двумя полями объекта стоит комментарий, регулярка,
// требующая их соседства, перестаёт совпадать — и запись молча выпадает из
// результата. Дальше инструмент заполнения, который доверяет этому
// результату, переписывает словарь уже без выпавшего ключа. Выглядит при
// этом как успешная работа.
//
// Логика та же, что в server/src/tests/helpers/stripCode.ts: один проход с
// явным состоянием. Две фазы нельзя разнести — чтобы знать, где кончается
// строка, нужно знать, что перед ней не было комментария, и наоборот.
// Апостроф в комментарии открывает фантомную строку, которая в этом
// проекте однажды выросла до 29 689 символов и съела 6885 строк из 6963.
function stripComments(source) {
  let out = '';
  let состояние = 'код';
  let переносВБлоке = false;

  for (let i = 0; i < source.length; i++) {
    const c = source[i];
    const d = source[i + 1];

    switch (состояние) {
      case 'код':
        if (c === '/' && d === '/') { состояние = 'line'; i++; continue; }
        if (c === '/' && d === '*') { состояние = 'block'; переносВБлоке = false; i++; continue; }
        if (c === "'") { состояние = 'sq'; out += c; continue; }
        if (c === '"') { состояние = 'dq'; out += c; continue; }
        if (c === '`') { состояние = 'bt'; out += c; continue; }
        out += c;
        continue;

      case 'line':
        if (c === '\n') { состояние = 'код'; out += c; }
        continue;

      case 'block':
        if (c === '*' && d === '/') { состояние = 'код'; i++; continue; }
        if (c === '\n') { out += '\n'; переносВБлоке = true; }
        continue;

      case 'sq':
      case 'dq':
      case 'bt': {
        const закрывающая = состояние === 'sq' ? "'" : состояние === 'dq' ? '"' : '`';
        if (c === '\\') { out += c + (d ?? ''); i++; continue; }
        if (c === закрывающая) { состояние = 'код'; out += c; continue; }
        out += c;
        continue;
      }
    }
  }

  void переносВБлоке;
  return out;
}

module.exports = { stripComments };