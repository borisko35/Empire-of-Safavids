// ============================================================
// Удар сверху — уязвимое место из высоты (§376)
// ============================================================
// Третий кусок точного удара: спина (§355) — уязвимость сзади, ломающаяся
// броня (§374) — от самого боя, голова сверху — от превышения. В бою с
// кликом прицеливания по частям тела нет: место удара следует из взаимного
// положения, и поднявшийся выше цели бьёт ей в голову.
//
// ПОЧЕМУ ЭТО ЗАРАБОТАЛО ТОЛЬКО ТЕПЕРЬ. Высоту земли знал только клиент:
// монстры жили на сервере с y=0, y игрока приходил пакетом. Превышение по
// высоте нельзя было поверить ни с той, ни с другой стороны. Цепочка высоты
// переехала в shared/terrainHeight.ts (§376) - монстры стоят на настоящем
// рельефе, и разница высот стала серверным фактом.
//
// ПОЧЕМУ ФАЙЛ В shared/, как backStrike.ts. Правило обязано считаться
// одинаково на обеих сторонах: сервер применяет множитель и входит с ним в
// античит-базу, клиент рисует пометку удара. Две копии одной геометрии
// однажды разъехались бы.
//
// ПРО ЧЕСТНОСТЬ ВЫСОТЫ ИГРОКА. y монстра теперь серверный; y игрока по-прежнему
// приходит пакетом движения - на том же доверии, на котором уже стоят x, z и
// проверка досягаемости. Заявить себе лишние десять метров высоты - значит
// умножить свой урон на 1.35; множитель входит в античит-базу, а повторная
// подделка позиции ловится тем же слоем, что и подделка x/z. Настоящая
// серверная проверка y игрока против рельефа - отдельная работа: она обязана
// разбираться с лестницами, мезонинами, конём и плаванием, и молча врезать
// её в проверку позиции значило бы выкидывать игроков с лестниц.
//
// ЧИСЛА - ВЫБОР, НЕ ИЗМЕРЕНИЕ, как у спины.

/**
 * Сколько метров превышения делают удар ударом по голове.
 *
 * ВЫБОР. Мезонин интерьеров (§324) даёт перепад одного этажа - около 3 м;
 * 1.6 м отсекает «чуть выше на кочке» (подписи биомной геометрии дают
 * холмы 1-2.5 м, но на длину шага разница высот у соседних ног - десятки
 * сантиметров), и ловится с лестницы, уступа и конного скакуна.
 */
export const OVERHEAD_ADVANTAGE_M = 1.6;

/**
 * Множитель урона.
 *
 * Меньше спины (1.5): спина мимолётна - цель повернулась, и окна нет, а
 * высоту можно удерживать. 1.5 за удерживаемое положение сделало бы любой
 * уступ королём боя. Больше локального бонуса: удар по голове бьёт мимо
 * заслона, которым плечо защищает шею.
 */
export const OVERHEAD_MULT = 1.35;

/**
 * Стоит ли атакующий достаточно выше цели.
 *
 * Сравниваются только y: горизонтальная дистанция - дело досягаемости,
 * она проверена раньше и своим правилом. Мусор в координатах - «не стоит»:
 * сомнение против бонуса, как и везде в точном ударе.
 */
export function isAboveTarget(
  attacker: { y: number } | null | undefined,
  target: { y: number } | null | undefined,
): boolean {
  if (!attacker || !target) return false;
  const разница = Number(attacker.y) - Number(target.y);
  if (!Number.isFinite(разница)) return false;
  return разница >= OVERHEAD_ADVANTAGE_M;
}
