// ЗАЧЕМ УГЛУБИТЬСЯ В ПРАВИЛО, А НЕ В КРАЖУ. Первая попытка провалилась и была
// откачена. Причина измерена, а не заподозрена:
//
//   дальность рук                 6
//   обзор стража стоя            20
//   обзор стража приседши        10   (20 * 0.5)
//
// Дальность рук меньше приседного обзора, значит в любой точке досягаемости
// торговец видел вора. С КРУГОВЫМ наблюдателем «дотянуться и не быть замеченным»
// невозможно физически. Угол обзора - не украшение, а условие существования
// механики.
//
// ВЫБОР, НЕ ИЗМЕРЕНИЕ: ДАЛЬНОСТЬ РУК. THEFT_REACH = 6. В коде нет числа
// «на каком расстоянии можно что-то сделать с NPC»: в 3D игрок кликает по NPC
// мышью, дистанции взаимодействия не существует. Шесть единиц взяты из самого
// правила: присевший прячется за 10 единиц, значит дотянуться надо ближе
// половины этого. Отсюда вся механика:
//
//   дальше 6            - не дотянуться
//   сзади, стоя         - дотянуться, но приседание обязательно
//   сзади, присев       - дотянуться и не заметят (конус 120 градусов)
//   спереди, присев     - всё равно заметят: конус смотрит туда же
//
// ПОЧЕМУ НАПРАВЛЕНИЕ ТОРГОВЦА РАВНО ЕГО СМЕЩЕНИЮ (15, 2). Это измерено, а не
// выбрано. Клиент разворачивает NPC так:
//   client/src/app/game3d/npc.ts:198
//   rig.group.rotation.y = Math.atan2(origin.x - x, origin.z - z) + Math.PI
// Направление взгляда группы в мире равно (sin(yaw), cos(yaw)) - подтверждено
// дважды: fauna.ts:346 двигает существо по (sin(yaw), cos(yaw)), и
// navigator.ts:147 так же целится в следующую точку маршрута. Сложение с
// Math.PI разворачивает взгляд ОТ центра поселения, то есть наружу, а
// наружу для NPC группы - ровно его собственное смещение dx/dz. Значит
// facing = (15, 2) и сверяется с NPC_GROUPS напрямую, без угла и без atan2.

/** На каком расстоянии можно дотянуться до кошелька. Выбор, обоснован выше. */
export const THEFT_REACH = 6;

/** Золото за удачную кражу. Выбор: цена одного акта должна быть заметной,
 *  но несопоставимой с заработком честным - иначе кража становится быстрее
 *  торговли, а это ломает игру. */
export const THEFT_GOLD = 25;

/**
 * У кого можно украсть кошелёк.
 *
 * Форма записи та же, что у стража, потому что проверка обзора общая - canSee.
 * Отличие одно: у торговца задан взгляд, поэтому за его спиной можно пройти.
 * Стражи в GUARD_POSTS направления не имеют и видят кругом - как в шагах 1 и 2.
 */
export const PICKPOCKET_TARGETS: readonly GuardPost[] = [
  {
    id: 'npc_bazaar_merchant',
    nameRu: 'Торговец Джафар',
    x: 49,
    z: 28,
    sight: GUARD_SIGHT,
    // Взгляд наружу от центра города = собственное смещение NPC в NPC_GROUPS.
    facingX: 15,
    facingZ: 2,
  },
];

/**
 * Можно ли сейчас обокрасть цель.
 *
 * ТРИ условия, и все три нужны:
 *   1. дотянуться руками (не дальше THEFT_REACH);
 *   2. цель не видит вора (конус взгляда);
 *   3. вор присел.
 *
 * ПОЧЕМУ ПРИСЕДАНИЕ ОБЯЗАТЕЛЬНО, А НЕ ВЫГОДНО. Когда требовали только пункты 1
 * и 2, конус делал «стою за спиной» полностью безопасным: направление
 * отсекалось независимо от стойки, и обзор в 20 единиц не играл никакой
 * роли. Тогда кража переставала быть стелс-механикой - ровно то, чего владелец
 * просил не делать, только наоборот: не спрятаться совсем, а прятаться слишком
 * легко. Проверка поймала это, и решение принято в пользу явного условия.
 *
 * Порядок проверок выбран для порядка чтения, а не для скорости: сначала
 * «хватило ли рук», потом «тихо ли», потом «не заметил ли».
 */
export function canPickpocket(thief: Point, target: GuardPost, ctx: SightContext = {}): boolean {
  const достал = distanceSq(thief, target) <= THEFT_REACH * THEFT_REACH;
  if (!достал) return false;
  if (!ctx.crouch) return false;
  return !canSee(thief, target, ctx);
}
