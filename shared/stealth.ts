// Обнаружение игрока стражем — Empire of Safevids
// ============================================================
// ШАГ 1 СТЕЛСА: ОБНАРУЖЕНИЕ.
//
// ЧТО БЫЛО ИЗМЕРЕНО ДО ЭТОГО ФАЙЛА. У NPC на сервере нет обнаружения вообще:
// ноль совпадений по пяти признакам (дистанция до игрока, aggro у NPC,
// преследование, npcTarget, серверный поток действий NPC). У NPC есть только
// диалоги: NpcIntelligenceService и NpcMemoryService работают с репликами и
// памятью о взаимодействиях, координат в них нет. Клиент вообще ни о чём
// серверу не сообщает, кроме позиции.
//
// ПОЧЕМУ ФАЙЛ В shared/, А НЕ В СЕРВЕРЕ. Правило "виден ли игрок стражу"
// обязано считаться одинаково с обеих сторон. Если правило живёт только на
// сервере, клиент о нём не узнает и не сможет ни показать, ни скрыть знак
// обнаружения. Разделение таких копий уже стоило нам бага с дверями:
// координаты комнат были в двух списках, они разъехались, и кнопка перехода
// existed, а ничего не происходило.
//
// ПОЧЕМУ РАДИУС 20, А НЕ КАКОЕ-ТО ДРУГОЕ ЧИСЛО. Измерено по базе: у 40
// монстров aggroRange от 8 до 60, среднее 20.3, чаще всего встречаются 20
// (семь монстров) и 18 (семь). Двадцатка - самая частая дальность обнаружения
// в игре. Взяв её, мы не вводим свой баланс, а попадаем в уже существующий:
// игрок, которого монстр замечает за 20 единиц, и страж, который замечает за
// 20 единиц, ведут себя одинаково предсказуемо.
//
// ГРАНИЦА ВКЛЮЧЕНА. Ровно 20 - заметил. Ровно 20.0001 - не заметил. Это
// выбрано осознанно: правило "строго меньше" отодвигало бы границу на
// бесконечно малые значения у соседа, а включённое сравнение даёт ровно
// одну проверяемую точку на каждой стороне (19 и 21 - как в проверке).
//
// ЧТО ЗДЕСЬ НЕТ И ПОЧЕМУ. Нет приседания, нет света и нет ночи: это шаг 2.
// Правило скрытности отменяет обнаружение, и вводить его раньше самого
// обнаружения бессмысленно - отменять было бы нечего.

/** Сторожевой пост: где стоит страж и на каком расстоянии он замечает. */
export interface GuardPost {
  /** id NPC из реестра клиента — по нему страж узнаётся в интерфейсе */
  id: string;
  /** Имя для проверки и для отладки; игроку показывается переводом */
  nameRu: string;
  /** Мировая координата X */
  x: number;
  /** Мировая координата Z */
  z: number;
  /** Радиус обнаружения. Задан явно у каждого поста, а не общим числом:
   *  разные стражи должны видеть по-разному, иначе это одна длинная полоса. */
  sight: number;
  /**
   * Направление взгляда. Если не задано — наблюдатель видит КРУГОМ (шаги 1
   * и 2), если задано — конусом.
   *
   * ПОЧЕМУ ПОЛЕ НЕОБЯЗАТЕЛЬНОЕ. Стражи остаются круговыми: у них нет
   * направления в коде, и выдумывать его значило бы менять уже работающую
   * механику. Конус нужен только там, где наблюдатель — обычный человек с
   * спиной: к нему надо подойти сзади.
   */
  facingX?: number;
  facingZ?: number;
  /** Полная ширина конуса в градусах. По умолчанию WATCHER_FOV_DEG. */
  fov?: number;
  /**
   * Маршрут патруля. Если задан — пост ходит между своей точкой и конечной.
   *
   * ПОЧЕМУ ПАТРУЛЬ СЧИТАЕТСЯ ИЗ ВРЕМЕНИ, А НЕ ПЕРЕДАЁТСЯ С СЕРВЕРА. Если бы
   * сервер слал координаты стража, клиент рисовал бы его отдельно, и рано или
   * поздно они разошлись бы - ровно как разошлись двери интерьеров: сервер
   * считал бы по своим числам, а игрок видел бы чужие. Здесь позиция выводится
   * из мировых часов по формуле, одинаковой на обеих сторонах, поэтому и
   * рисунок, и правило берут одно и то же число.
   */
  patrol?: {
    /** Куда идёт от своей точки */
    toX: number;
    toZ: number;
    /** Полный цикл туда-обратно в миллисекундах */
    periodMs: number;
  };
}

/**
 * Где находится пост в данный момент.
 *
 * Стоящий пост стоит на месте. Патрулирующий идёт по треугольной волне: из
 * своей точки к конечной и обратно, без рывка на краях.
 *
 * Время передаётся в миллисекундах Date.now() у обеих сторон. Расхождение
 * часов в пределах секунды сдвигает стража на единицы единиц - на глаз
 * незаметно, а для правила безразлично.
 */
export function postPosition(post: GuardPost, worldMs = 0): { x: number; z: number } {
  const p = post.patrol;
  if (!p || p.periodMs <= 0) return { x: post.x, z: post.z };

  const cycle = ((worldMs % p.periodMs) + p.periodMs) % p.periodMs / p.periodMs;
  const t = cycle < 0.5 ? cycle * 2 : 2 - cycle * 2;
  return { x: post.x + (p.toX - post.x) * t, z: post.z + (p.toZ - post.z) * t };
}

