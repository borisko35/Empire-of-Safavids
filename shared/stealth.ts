// Правило таможенного досмотра.
//
// ЧЕСТНОЕ ИМЯ. Это НЕ «поиск контрабанды» в том виде, в каком его просил
// владелец. Поиск контрабанды означает случайность: караул либо находит, либо
// не находит. Детерминированного генератора в проекте нет вообще — ноль
// seededRandom, mulberry32 и xorshift, ноль Math.random в shared/. А правило
// обязано считаться одинаково на клиенте и сервере, иначе клиент покажет
// «пропущено», пока сервер считает «задержан». Это тот же класс расхождения,
