// ШАГ 4 СТЕЛСА: УДАР СТРАЖА
// ============================================================
// ЧТО БЫЛО ЗАМЕРЕНО ДО ЭТОГО БЛОКА. Поле guardAttack было объявлено в таблице
// последствий кармы (server/src/systems/KarmaSystem.ts) у рангов «красный» и
// «изгой» — и не читалось НИГДЕ: поиск по всему серверу давал только само
// объявление поля. Стражи в шагах 1-3 умели только замечать игрока. То есть
// город обещал тёмному игроку последствие, а наказывать было некому: тот же
// класс, что с сундуками и потерей золота — данные написаны, игры за ними нет.
//
// ЧТО ТЕПЕРЬ. Тёмного игрока, которого страж видит и до которого достаёт,
// страж бьёт. Решение владельца: удар и минус карма за него.
//
// ПОЧЕМУ ОДНО УСЛОВИЕ, А НЕ ДВА. Радиус удара и радиус обзора были бы двумя
// копиями одного правила, а такие копии в проекте уже расходились: сначала
// координаты дверей интерьеров, потом радиус обзора. Если бы страж бил с 8, а
// видел с 20, игрок в 12 единицах получал бы урон от того, кто его не видит,
// и это выглядело бы как ошибка. Здесь обзор остаётся единственным условием,
// и приседание, ночь и буря работают как задумано: ночью в бураю обзор
// 20 * 0.5 * 0.3 = 3, и до GUARD_STRIKE_REACH страж не дотягивается вовсе.
//
// ПОЧЕМУ ОДИН УДАР НА ЦИКЛ, А НО ПО ОДНОМУ ОТ КАЖДОГО ПОСТА. Измерено: два
// поста у ворот стоят в 7 единицах друг от друга, а третий отстоит от
// соседнего на 11.7. При радиусе 8 игрок между ними получил бы два удара за
// раз, то есть вдвое больше договорённого с владельцем. Поэтому функция
// возвращает ОДИН пост — первый по порядку в списке, — и решение об одном
// ударе за кулдаун принимает сервер, а не список постов.

/**
 * Числа удара стража. Решение владельца, а не измерение.
 *
 * Урон 60 и кулдаун 2 секунды взяты владельцем. Карма -100 - между убийством
 * монстра (-50) и злым квестом (-150) из KARMA_EVENTS, то есть по порядку
 * величины той же таблицы, а не число с потолка.
 *
 * Считано на настоящих порогах рангов, а не на глаз. Полоса красного по
 * getKarmaStatus: от -5000 до -2001. Хуже всего тому, кто только что в неё
 * попал: с -2001 до изгоя (-5001 и ниже) нужно 30 ударов по 100, то есть ровно
 * минута у поста. Тому, кто уже на дне полосы, хватает одного удара. Выход из
 * ямы есть: убийство красного даёт +100 (pk_kill_red), то есть выкупает себя
 * одиннадцатью такими убийствами с самого верха полосы.
 *
 * ЧТО ВЛАДЕЛЕЦ ДОЛЖЕН ЗНАТЬ ПРО ЭТО ЧИСЛО. Минута у ворот - это короткое
 * наказание. Кто хочет более долгую лестницу, меняет KARMA минус на плюс в
 * этом объекте и в таблице кармы (проверка guardStrike требует, чтобы числа
 * совпадали) - обе цифры специально не спрятаны в трёх местах, а связаны.
 *
 * Радиус 8 - ВЫБОР, и он не измерен из клинка. Дальность оружия игрока в
 * server/src/data/items.ts: 2.4-2.7. Восемь - это не длина руки, а радиус
 * власти поста: страж не подходит и не преследует, он стоит на месте. Восемь
 * выбрано так, чтобы зона поста накрывала базар: привратник патрулирует между
// (60,32) и (52,26), а торговец стоит в (49,28) - с радиусом 8 кражу у лотка
// делает риском, и это ровно то, для чего шаги 1-3 и писались.
 */
export const GUARD_STRIKE = {
  /** Урон за удар до вычета защиты цели (вычет такой же, как у монстров) */
  DAMAGE: 60,
  /** Пауза между ударами одного игрока */
  COOLDOWN_MS: 2000,
  /** Изменение кармы за удар. Минус: город загоняет тёмного глубже */
  KARMA: -100,
  /** Радиус удара от поста */
  REACH: 8,
} as const;

/**
 * Кто из стражей ударит игрока прямо сейчас.
 *
 * Возвращает ОДИН пост - тот, кто и видит игрока, и достаёт до него. null -
 * не бьёт никто: слишком далеко, или страж не видит (присел, ночь, буря).
 *
 * Правило обзора то же, что в шагах 1 и 2 (canSee), поэтому «видит» и
 «бьёт» не могут разойтись: игрока нельзя показать невидимым и тут же дать
 ему удар от того же стража.
 *
 * worldMs - то же мировое время, что и при обнаружении, иначе патрульный
 привратник в GameLoop и в клиенте стоял бы в разных местах.
 */
export function strikingGuard(
  player: Point,
  posts: readonly GuardPost[] = GUARD_POSTS,
  ctx: SightContext = {},
  worldMs = 0
): GuardPost | null {
  for (const post of posts) {
    if (!canSee(player, post, ctx, worldMs)) continue;
    const здесь = postPosition(post, worldMs);
    if (distanceSq(player, здесь) > GUARD_STRIKE.REACH * GUARD_STRIKE.REACH) continue;
    return post;
  }
  return null;
}

