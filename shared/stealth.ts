// existed, а ничего не происходило.
//
// ПОЧЕМУ РАДИУС 20, А НЕ КАКОЕ-ТО ДРУГОЕ ЧИСЛО. Измерено по базе: у 40
// монстров aggroRange от 8 до 60, среднее 20.3, чаще всего встречаются 20
// (семь монстров) и 18 (семь). Двадцатка - самая частая дальность обнаружения
// в игре. Взяв её, мы не вводим свой баланс, а попадаем в уже существующий:
// игрок, которого монстр замечает за 20 единиц, и страж, который замечает за
// 20 единиц, ведут себя одинаково предсказуемо.
//
// ГРАНИЦА ВКЛЮЧЕНА. Ровно 20 - заметил. Ровно 20.0001 - не заметил. Это
// выбрано осознанно: правило "строго меньше" отодвигало бы границу на
// бесконечно малые значения у соседа, а включённое сравнение даёт ровно
// одну проверяемую точку на каждой стороне (19 и 21 - как в проверке).
//
// ЧТО ЗДЕСЬ НЕТ И ПОЧЕМУ. Нет приседания, нет света и нет ночи: это шаг 2.
// Правило скрытности отменяет обнаружение, и вводить его раньше самого
// обнаружения бессмысленно - отменять было бы нечего.

/** Сторожевой пост: где стоит страж и на каком расстоянии он замечает. */
export interface GuardPost {
  /** id NPC из реестра клиента — по нему страж узнаётся в интерфейсе */
  id: string;
  /** Имя для проверки и для отладки; игроку показывается переводом */
  nameRu: string;
  /** Мировая координата X */
  x: number;
  /** Мировая координата Z */
  z: number;
  /** Радиус обнаружения. Задан явно у каждого поста, а не общим числом:
   *  разные стражи должны видеть по-разному, иначе это одна длинная полоса. */
  sight: number;
}

/**
 * Радиус обнаружения по умолчанию.
 *
 * Взят из базы монстров: 20 - самая частая дальность обнаружения в игре
 * (из 40 монстров: 20 встречается 7 раз, 18 - 7 раз, среднее 20.3).
 */
export const GUARD_SIGHT = 20;

/**
 * Сторожевые посты.
 *
 * Координаты не выдуманы, а сложены из измеренного: origin поселения из
 * client/src/app/game3d/terrain.ts плюс смещение dx/dz из NPC_GROUPS в
 * client/src/app/game3d/npc.ts. Сами NPC на сервере не существуют - там нет
 * ни координат, ни потока действий, - поэтому посты живут здесь.
 *
 * Чтобы эти две копии не разъехались, сверку держит проверка
 * server/src/tests/guardDetection.test.ts: она читает NPC_GROUPS и terrain.ts
 * и требует, чтобы числа здесь равнялись им.
 */
export const GUARD_POSTS: readonly GuardPost[] = [
  // Стражник каравана: караван-сарай (505,55) + (10,-6)
  { id: 'npc_desert_guard', nameRu: 'Стражник каравана', x: 515, z: 49, sight: GUARD_SIGHT },
  // Дозорный моря: порт (-225,-150) + (-9,-4)
  { id: 'npc_port_guard', nameRu: 'Дозорный моря', x: -234, z: -154, sight: GUARD_SIGHT },
  // Горный стрелок: форт (-320,-705) + (8,5)
  { id: 'npc_fort_guard', nameRu: 'Горный стрелок', x: -312, z: -700, sight: GUARD_SIGHT },
];

/** Точка на плоскости. Общий тип для игрока и стража. */
export interface Point {
  x: number;
  z: number;
}

/** Квадрат расстояния между двумя точками. Без корня - радиус сравнивается
 *  квадратом, и это дешевле: sqrt на каждом пакете движения не нужен. */
export function distanceSq(a: Point, b: Point): number {
  const dx = a.x - b.x;
  const dz = a.z - b.z;
  return dx * dx + dz * dz;
}

/**
 * Видит ли страж игрока.
 *
 * Граница включена: на расстоянии ровно sight - ещё видит.
 */
export function canSee(player: Point, post: GuardPost): boolean {
  return distanceSq(player, post) <= post.sight * post.sight;
}

/**
 * Кто из стражей видит игрока.
 *
 * Возвращает пост, который заметил игрока первым по списку, либо null.
 * Список стражей — константа, поэтому порядок в GUARD_POSTS и есть
 * приоритет: когда рядом оказались двое, считается тот, кто стоит выше в
 * списке. Это правило нужно, чтобы результат не зависел от порядка обхода
 * в вызывающем коде.
 */
export function spottedBy(player: Point, posts: readonly GuardPost[] = GUARD_POSTS): GuardPost | null {
  for (const post of posts) {
    if (canSee(player, post)) return post;
  }
  return null;
}