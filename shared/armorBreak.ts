// ============================================================
// Ломающаяся броня — Empire of Safavids
// ============================================================
// Уязвимые места (§355 спина, §374 броня). Броня ломается не от положения
// удара, а от самого боя: тяжёлая цель, которую бьют и бьют, теряет крепость
// ступенями. Это противовес застреванию: у вычитающей формулы урона цель с
// высокой защитой держит удары «по единице» сколько угодно долго, и бой без
// навыков не кончается никогда. Износ отвечает на вопрос «что делать с
// панцирем», который не пробивается, - бей, и он выломается.
//
// ПОЧЕМУ ФАЙЛ В shared/, как backStrike.ts и stealth.ts. Правило обязано
// считаться одинаково на обеих сторонах: сервер снижает защиту в бою,
// клиент называет ступень игроку. Две копии одной арифметики однажды
// разъехались бы.
//
// ПОЧЕМУ СЧЁТ ЖИВЁТ НА МОНСТРЕ, А НЕ В БАЗЕ. Износ - свойство ДРАКИ с этой
// целью, а не свойство мира: монстр умер - труп исчез вместе со счётчиком,
// новый экземпляр приходит с целой бронёй. Сброс при смерти и респавне
// получается бесплатно, отдельного кода «обнулить износ» не существует -
// и потому не может разойтись со смертью.
//
// ЧИСЛА - ВЫБОР, НЕ ИЗМЕРЕНИЕ. Шесть попаданий на ступень: рядовой бой с
// рядовым монстром кончается раньше первой ступени, бой с панцирем -
// успевает сломать две. Ступень - четверть базовой защиты: под вычитающей
// формулой это превращает «единицу урона» в настоящий размен уже к третьей
// ступени. Потолок три ступени: броня не исчезает вовсе, ниже четверти
// крепости панцирь не падает никогда.

/** Попаданий на одну ступень износа. Каждое применённое попадание. */
export const ARMOR_BREAK_HITS_PER_STEP = 6;

/** Доля базовой защиты, которую снимает одна ступень. */
export const ARMOR_BREAK_STEP = 0.25;

/** Ступеней не больше: ниже четверти крепости броня не падает. */
export const ARMOR_BREAK_MAX_STEPS = 3;

/** Ступеней износа по числу попаданий. Мусор и отрицательное - ноль ступеней. */
export function armorSteps(hits: number): number {
  if (!Number.isFinite(hits) || hits <= 0) return 0;
  return Math.min(ARMOR_BREAK_MAX_STEPS, Math.floor(hits / ARMOR_BREAK_HITS_PER_STEP));
}

/**
 * Защита цели с учётом износа.
 *
 * База берётся из справочника монстров, ступени - из счётчика попаданий.
 * Нулевая и отрицательная база (а также мусор) возвращаются как есть:
 * ломать нечего - и множитель не должен превратить «защиты нет» в
 * «защита ушла в минус», то есть в прибавку к урону.
 */
export function effectiveDefense(baseDefense: number, hits: number): number {
  const base = Number(baseDefense);
  if (!Number.isFinite(base) || base <= 0) return baseDefense;
  return base * (1 - ARMOR_BREAK_STEP * armorSteps(hits));
}
