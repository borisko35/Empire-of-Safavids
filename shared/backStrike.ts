// ============================================================
// Точный удар по уязвимому месту — Empire of Safavids
// ============================================================
// Пункт владельца «уровень механика»: уязвимые зоны (§355). Первый кусок —
// удар в спину: цель, которая тебя не видит, уязвима сзади.
//
// ПОЧЕМУ ФАЙЛ В shared/. Правило обязано считаться одинаково на обеих
// сторонах, как stealth.ts: сервер применяет множитель и проверяет
// античитом, клиент рисует пометку удара. Две копии одной геометрии
// однажды разъехались бы — как разъезжались двери и справочники.
//
// ПОЧЕМУ ЭТО «УЯЗВИМОЕ МЕСТО», А НЕ ОТДЕЛЬНАЯ КНОПКА. В бою с кликом нет
// прицеливания по частям тела — место удара определяется взаимным
// положением. Спина — первое уязвимое место, которое из положения
// следует: у цели, смотрящей на тебя, спины нет, у отвернувшейся — есть.
// Ломающаяся броня и короткое обездвиживание из списка владельца —
// следующие куски, не этот.
//
// ПРАВИЛО ОДНО ДЛЯ ВСЕХ, как и обзор стражей: удары игрока (сокет-путь)
// и удары монстров (тик GameLoop, §356) читают одну и ту же геометрию.

/** Множитель урона за удар в спину. ВЫБОР, не измерение: крит даёт 1.5 —
 *  тайминговая награда боя. Точный удар — награда за положение, та же цена. */
export const BACK_STRIKE_MULT = 1.5;

/**
 * Косинус границы дуги спины.
 *
 * ВЫБОР, не измерение. Строго за спиной — 180° (cos −1), строго сбоку —
 * 90° (cos 0). Граница на 110° (cos ≈ −0.34) отсекает «в бок»: бить по
 * касающейся цели сбоку — не точный удар. Дуга спины получается ±70°.
 */
export const BACK_STRIKE_COS = -0.34;

/**
 * Стоит ли атакующий за спиной цели.
 *
 * targetFacing — взгляд цели в мировых координатах (куда смотрит). null
 * означает «направления нет»: стражи без направления видят кругом
 * (shared/stealth.ts), монстр, вставший столбом, и игрок, чей пакет
 * движения ещё не дошёл, спины не открывают. Нет данных — нет бонуса:
 * выгодное сомнение всегда трактуется против атакующего.
 */
export function isBehindTarget(
  targetPos: { x: number; z: number },
  targetFacing: { x: number; z: number } | null,
  attackerPos: { x: number; z: number },
): boolean {
  if (!targetFacing) return false;
  const lenF = Math.hypot(targetFacing.x, targetFacing.z);
  if (!Number.isFinite(lenF) || lenF < 1e-6) return false;
  const ax = attackerPos.x - targetPos.x;
  const az = attackerPos.z - targetPos.z;
  const lenA = Math.hypot(ax, az);
  // Вплотную «куда ударил — там и спина» не бывает: нулевой вектор не
  // смотрит никуда.
  if (lenA < 1e-6) return false;
  const cos = (targetFacing.x * ax + targetFacing.z * az) / (lenF * lenA);
  return cos < BACK_STRIKE_COS;
}
