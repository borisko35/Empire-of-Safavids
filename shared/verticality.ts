// ============================================================
// Вертикальность: прыжок и серверный конверт высоты (§377)
// ============================================================
// ЗАЧЕМ ФАЙЛ. Прыжок и вертикальная физика жили в клиенте с давних пор
// (прыжок, гравитация, лестницы §324, мосты, плавание), но сервер высоту
// игрока не проверял вовсе: validateMovement смотрел только 3D-скорость,
// и медленный полёт проходил как «скорость в норме». Константы переехали
// сюда, чтобы обе стороны считали одним и тем же числом: клиент прыгает
// ровно на столько, на сколько разрешает сервер.
//
// ПРО ПРЫЖОК И УДАР СВЕРХУ (§376). Апекс прыжка - 1.444 м, порог удара
// сверху - 1.6 м. Прыжок НЕ доводит голову до зоны «удар сверху»: награда
// за высоту достаётся тому, кто нашёл настоящее возвышение, а не тому,
// кто подпрыгнул. Это свойство сторожится проверкой, не совпадением.

/** Ускорение свободного падения, м/с². Перенесено из world3d.ts без правки. */
export const GRAVITY = 20;

/** Начальная скорость прыжка, м/с. Перенесено из world3d.ts без правки. */
export const JUMP_V = 7.6;

/** Высота прыжка: vy²/(2g) ≈ 1.444 м. Меньше порога удара сверху (1.6). */
export const JUMP_APEX_M = (JUMP_V * JUMP_V) / (2 * GRAVITY);

/** Допуск НИЖЕ опоры: ступени, пороги и рельеф между соседними пакетами. */
export const FALL_TOLERANCE_M = 1.0;

/** Допуск НАД апексом: пакетный срез вершины дуги. */
export const AIR_TOLERANCE_M = 0.25;

/**
 * Полоса плавания относительно поверхности воды.
 *
 * Клиент держит тело в [поверхность − 1.9, поверхность − 0.7]
 * (голова над водой, ноги под ней). Полоса сервера шире на допуск
 * с каждой стороны: борт качки и пакетный срез не должны выкидывать
 * пловца. Прыжок в воде (всплытие) поднимает до поверхности.
 */
export const SWIM_BAND_LOW_M = 2.2;
export const SWIM_BAND_HIGH_M = 0.4;

/**
 * Голова над водой на лодке: палуба с подъёмом плюс прыжок с неё.
 * Применяется к позиции игрока, которого сервер видит в лодке.
 */
export const BOAT_HEADROOM_M = 1.5;

/**
 * Потолок внутри кармана интерьеров.
 *
 * Сервер не знает мезонинов (§324) - они живут в клиентской раскладке
 * комнат. Верхняя плата мезонина - 2.6 м над полом, прыжок с неё даёт
 * ещё 1.44: потолок 4.3 м пропускает всё легальное внутри комнаты и
 * всё равно не даёт летать. Знание платформ сервером - отдельная работа,
 * когда интерьеры синхронизируются.
 */
export const INTERIOR_CEILING_M = 4.3;

/**
 * Конверт высоты: легален ли y на этой опоре.
 *
 * y обязан лежать в [опора − допуск падения, опора + потолок + допуск
 * воздуха]. Мусор в числах возвращает true: наказание обязано стоять на
 * ясном факте, а не на сломанном пакете - сомнение против наказания.
 */
export function verticalEnvelopeOk(
  y: number,
  supportY: number,
  потолокМ: number = JUMP_APEX_M,
): boolean {
  if (!Number.isFinite(y) || !Number.isFinite(supportY)) return true;
  return y >= supportY - FALL_TOLERANCE_M && y <= supportY + потолокМ + AIR_TOLERANCE_M;
}

/**
 * Наказание за устойчивый полёт (§389).
 *
 * Единичный отказ конверта - обкатка допусков: ложный кик честного игрока
 * дороже медленного читера, поэтому месяц конверт только ломал полёт.
 * Обкатка прошла (две выкатки без нареканий), и порог назван: игрок шлёт
 * позиции ~10 раз в секунду, значит 30 отказов за минуту - это ТРИ СЕКУНДЫ
 * непрерывного полёта, и такое уже не допуск, а чит. Один отказ punished
 * не бывает никогда.
 */
export const FLIGHT_PUNISH_WINDOW_MS = 60_000;
export const FLIGHT_PUNISH_THRESHOLD = 30;

/**
 * Предел подъёма вертикальной скорости между пакетами.
 *
 * Клиент задаёт vy = JUMP_V в момент прыжка и дальше только гасит её
 * гравитацией. Рост выше JUMP_V × 1.35 (+ запас на пакет) - это не прыжок.
 * Вниз ограничение не ставится: падение со стены - легитимное движение,
 * и старая проверка 3D-скорости наказывала его как speed hack.
 */
export const MAX_RISE_SPEED_MS = JUMP_V * 1.35 + 0.5;
